static constexpr int ARABIC_CHAR_COUNT = sizeof(arabic_char_map) / sizeof(arabic_char_map[0]);

void FreestandingRenderer::loadBuiltinFont() {
    auto font = std::make_unique<BitmapFont>();
    font->name = "builtin_8x16";
    font->charWidth = 8;
    font->charHeight = 16;
    font->lineHeight = 18;
    font->monospace = true;

    // ─── ASCII glyphs (U+0020 - U+007E) ───
    for (int i = 0; i < ASCII_COUNT; ++i) {
        BitmapGlyph g;
        g.codepoint = ASCII_FIRST + i;
        g.width = 8;
        g.height = 16;
        g.xOffset = 0;
        g.yOffset = 0;
        g.advance = 8;
        g.bitmap = ascii_font_8x16[i];
        font->glyphs.push_back(g);
    }

    // ─── Arabic glyphs (U+0621 - U+064A) ───
    for (int i = 0; i < ARABIC_CHAR_COUNT; ++i) {
        BitmapGlyph g;
        g.codepoint = arabic_char_map[i].codepoint;
        g.width = 10;
        g.height = 16;
        g.xOffset = 0;
        g.yOffset = 0;
        g.advance = 10;
        g.bitmap = arabic_font_10x16[arabic_char_map[i].arrayIndex];
        font->glyphs.push_back(g);
    }

    currentFont_ = std::move(font);
}

