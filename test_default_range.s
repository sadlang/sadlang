# اختبار معاملات افتراضية مع أضف

دالة مصفوفة نطاق_اختبار(رقم نهاية_نطاق = 10، رقم بداية = 0، رقم خطوة = 1)
    اطبع("نهاية_نطاق =", نهاية_نطاق, "، بداية =", بداية, "، خطوة =", خطوة)
    مصفوفة نتيجة = []
    رقم ع = بداية
    بينما (ع < نهاية_نطاق)
        أضف(نتيجة، ع)
        ع = ع + خطوة
    نهاية
    إرجاع نتيجة
نهاية

اطبع("=== اختبار 1: بدون معاملات ===")
مصفوفة ن1 = نطاق_اختبار()
اطبع("النتيجة:", ن1)

اطبع("\n=== اختبار 2: معامل واحد ===")
مصفوفة ن2 = نطاق_اختبار(5)
اطبع("النتيجة:", ن2)

اطبع("\n=== اختبار 3: ثلاث معاملات ===")
مصفوفة ن3 = نطاق_اختبار(20، 0، 2)
اطبع("النتيجة:", ن3)
