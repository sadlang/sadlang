// اختبار المعاملات الافتراضية

// دالة مع معامل افتراضي واحد
دالة قوة(عدد رقم أساس، عدد رقم أس = 2) -> عدد رقم {
    نتيجة عدد رقم = أساس ^ أس؛
    راجع نتيجة؛
}

// دالة مع معاملات افتراضية متعددة
دالة تحية(نص اسم، نص رسالة = "مرحبا"، نص نهاية = "!") {
    اطبع(رسالة + " " + اسم + نهاية)؛
}

اطبع("=== اختبار معامل افتراضي واحد ===")؛
اطبع("قوة(5) =")؛
اطبع(قوة(5))؛
اطبع("قوة(5، 3) =")؛
اطبع(قوة(5، 3))؛

اطبع("\n=== اختبار معاملات افتراضية متعددة ===")؛
