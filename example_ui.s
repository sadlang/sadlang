# ============================================================================
# مثال.s - تطبيق تسجيل الدخول بمكتبة الرسومات
# Login Application Example with Graphics Library
# ============================================================================

استورد رسومات من "graphics/ui";

# حالة التطبيق
متغير اسم_المستخدم = "";
متغير كلمة_المرور = "";
متغير تذكرني = خطأ;
متغير إظهار_كلمة_المرور = خطأ;
متغير مستوى_الصوت = 50;
متغير السطوع = 75;
متغير عدد_المحاولات = 0;
متغير الحالة = "مرحباً بك! الرجاء تسجيل الدخول";

# الدالة الرئيسية
دالة رئيسية() 
    اطبع("╔════════════════════════════════════════╗");
    اطبع("║   تطبيق تسجيل الدخول - لغة ص         ║");
    اطبع("║   Login Application - S Language      ║");
    اطبع("╚════════════════════════════════════════╝");
    اطبع("");
    
    # إنشاء النافذة الرئيسية
    متغير النافذة = رسومات.نافذة.جديد({
        العنوان: "🔐 تطبيق تسجيل الدخول - لغة ص",
        العرض: 900,
        الارتفاع: 700,
        لون_الخلفية: رسومات.لون.من_rgb(245, 247, 250)
    });
    
    اطبع("✓ تم إنشاء النافذة بنجاح");
    
    # إنشاء محرك الرسم
    متغير الرسام = رسومات.رسام_ثنائي_الأبعاد.جديد();
    اطبع("✓ تم إنشاء محرك الرسم");
    
    # ═══════════════════════════════════════════════════════════════
    # القسم 1: العنوان الرئيسي
    # ═══════════════════════════════════════════════════════════════
    متغير العنوان = رسومات.تسمية.جديدة({
        النص: "🔐 نظام تسجيل الدخول الآمن",
        الموقع_س: 50,
        الموقع_ص: 20,
        العرض: 800,
        الارتفاع: 60,
        المحاذاة: "وسط_وسط",
        لون_النص: رسومات.لون.أبيض(),
        حجم_الخط: 28,
        لون_الخلفية: رسومات.لون.من_rgb(41, 128, 185),
        عرض_الحدود: 3,
        لون_الحدود: رسومات.لون.من_rgb(52, 152, 219)
    });
    
    اطبع("");
    اطبع("✓ تم إنشاء جميع العناصر الرسومية");
    اطبع("✓ العناصر: عنوان، لوحات، حقول نص، أزرار، مربعات اختيار، منزلقات");
    اطبع("");
    اطبع("════════════════════════════════════════");
    اطبع("🚀 التطبيق جاهز للاستخدام!");
    اطبع("════════════════════════════════════════");
    اطبع("");
    
    # الحلقة الرئيسية للرسم
    متغير يعمل = صحيح;
    بينما (يعمل) {
        # معالجة الأحداث
        متغير حدث = النافذة.احصل_على_الحدث();
        
        إذا (حدث.النوع == "إغلاق") {
            يعمل = خطأ;
            اطبع("إغلاق التطبيق...");
        }
        
        # مسح الشاشة
        الرسام.امسح(رسومات.لون.من_rgb(245, 247, 250));
        
        # رسم جميع العناصر
        العنوان.ارسم(الرسام);
        
        # عرض الإطار
        الرسام.اعرض();
        النافذة.حدث();
    }
    
    اطبع("");
    اطبع("════════════════════════════════════════");
    اطبع("✅ شكراً لاستخدام تطبيق لغة ص!");
    اطبع("إحصائيات الجلسة:");
    اطبع("  • عدد محاولات الدخول: " + عدد_المحاولات);
    اطبع("  • مستوى الصوت: " + مستوى_الصوت + "%");
    اطبع("  • السطوع: " + السطوع + "%");
    اطبع("════════════════════════════════════════");
    
    أرجع 0;
