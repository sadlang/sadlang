# اختبار نطاق كامل

دالة مصفوفة نطاق(رقم نهاية_نطاق = 10، رقم بداية = 0، رقم خطوة = 1)
    اطبع("نطاق: بداية =", بداية، "نهاية =", نهاية_نطاق، "خطوة =", خطوة)
    مصفوفة نتيجة = []
    اطبع("قبل الحلقة: نتيجة =", نتيجة)
    رقم ع = بداية
    بينما (ع < نهاية_نطاق)
        اطبع("  في الحلقة: ع =", ع، "نتيجة =", نتيجة)
        أضف(نتيجة، ع)
        ع = ع + خطوة
    نهاية
    اطبع("بعد الحلقة: نتيجة =", نتيجة)
    إرجاع نتيجة
نهاية

