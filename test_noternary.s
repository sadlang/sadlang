اطبع("=== التعابير الحسابية (Arithmetic Expressions) ===\n")

# تعابير حسابية بسيطة
رقم أ = 10 + 5
رقم ب = 20 - 7
رقم ج = 6 * 4
رقم د = 15 / 3
رقم ه = 17 % 5

اطبع("10 + 5 =", أ, "\n")
اطبع("20 - 7 =", ب, "\n")
اطبع("6 * 4 =", ج, "\n")
اطبع("15 / 3 =", د, "\n")
اطبع("17 % 5 =", ه, "\n")

# تعابير معقدة
رقم تعبير1 = 2 + 3 * 4
رقم تعبير2 = (2 + 3) * 4
رقم تعبير3 = 10 + 5 * 2 - 3

اطبع("\n2 + 3 * 4 =", تعبير1, " (الضرب أولاً)\n")
اطبع("(2 + 3) * 4 =", تعبير2, " (الأقواس أولاً)\n")
اطبع("10 + 5 * 2 - 3 =", تعبير3, "\n")

# أسس (Powers)
رقم أس1 = 2 ** 3
رقم أس2 = 5 ** 2
رقم أس3 = 10 ** 0

اطبع("\n2^3 =", أس1, "\n")
اطبع("5^2 =", أس2, "\n")
اطبع("10^0 =", أس3, "\n")

اطبع("\n=== تعابير المقارنة (Comparison Expressions) ===\n")

# مقارنات
منطقي مقارنة1 = 10 > 5
منطقي مقارنة2 = 3 < 7
منطقي مقارنة3 = 15 == 15
منطقي مقارنة4 = 8 != 9
منطقي مقارنة5 = 12 >= 10
منطقي مقارنة6 = 6 <= 6

اطبع("10 > 5 هو", مقارنة1, "\n")
اطبع("3 < 7 هو", مقارنة2, "\n")
اطبع("15 == 15 هو", مقارنة3, "\n")
اطبع("8 != 9 هو", مقارنة4, "\n")
اطبع("12 >= 10 هو", مقارنة5, "\n")
اطبع("6 <= 6 هو", مقارنة6, "\n")

اطبع("\n=== التعابير المنطقية (Logical Expressions) ===\n")

# عمليات منطقية
منطقي منطق1 = صحيح و صحيح
منطقي منطق2 = صحيح و خطأ
منطقي منطق3 = صحيح أو خطأ
منطقي منطق4 = خطأ أو خطأ
منطقي منطق5 = ليس صحيح
منطقي منطق6 = ليس خطأ

اطبع("صحيح و صحيح =", منطق1, "\n")
اطبع("صحيح و خطأ =", منطق2, "\n")
اطبع("صحيح أو خطأ =", منطق3, "\n")
اطبع("خطأ أو خطأ =", منطق4, "\n")
اطبع("ليس صحيح =", منطق5, "\n")
اطبع("ليس خطأ =", منطق6, "\n")

# تعابير منطقية معقدة
منطقي معقد1 = (10 > 5) و (3 < 7)
منطقي معقد2 = (15 == 15) أو (8 != 8)
منطقي معقد3 = ليس (10 < 5)

اطبع("\n(10 > 5) و (3 < 7) =", معقد1, "\n")
اطبع("(15 == 15) أو (8 != 8) =", معقد2, "\n")
اطبع("ليس (10 < 5) =", معقد3, "\n")

اطبع("\n=== التعابير الثلاثية (Ternary Expressions) ===\n")

# تعابير ثلاثية
رقم عمر = 18
اطبع("العمر:", عمر, "- الحالة:", حالة, "\n")

رقم درجة = 85
اطبع("الدرجة:", درجة, "- التقييم:", تقييم, "\n")

# تعابير ثلاثية في عمليات حسابية
رقم س = 10
اطبع("س =", س, ", النتيجة =", ص, "\n")

اطبع("\n=== الأولوية والأقواس (Precedence & Parentheses) ===\n")

# اختبار الأولوية
رقم أولوية1 = 2 + 3 * 4            # 2 + 12 = 14
رقم أولوية2 = (2 + 3) * 4          # 5 * 4 = 20
رقم أولوية3 = 10 - 5 + 3           # 5 + 3 = 8
رقم أولوية4 = 10 - (5 + 3)         # 10 - 8 = 2

اطبع("2 + 3 * 4 =", أولوية1, "\n")
اطبع("(2 + 3) * 4 =", أولوية2, "\n")
اطبع("10 - 5 + 3 =", أولوية3, "\n")
اطبع("10 - (5 + 3) =", أولوية4, "\n")

# أولوية مع مقارنات
منطقي أولوية_منطق1 = 5 + 3 > 7
منطقي أولوية_منطق2 = 5 + (3 > 7)  # خطأ منطقي
اطبع("\n5 + 3 > 7 =", أولوية_منطق1, "\n")

# أولوية المشغلات المنطقية
منطقي أولوية_منطق3 = صحيح أو خطأ و خطأ  # و قبل أو
منطقي أولوية_منطق4 = (صحيح أو خطأ) و خطأ
اطبع("صحيح أو خطأ و خطأ =", أولوية_منطق3, "\n")
اطبع("(صحيح أو خطأ) و خطأ =", أولوية_منطق4, "\n")

اطبع("\n=== تعابير النصوص (String Expressions) ===\n")

# عمليات النصوص
نص نص1 = "مرحبا" + " " + "عالم"
نص نص2 = "مكرر " * 3
اطبع("دمج النصوص:", نص1, "\n")
اطبع("تكرار النص:", نص2, "\n")

اطبع("\n=== تعابير المصفوفات (Array Expressions) ===\n")

# عمليات المصفوفات
مصفوفة مصفوفة1 = [1, 2, 3] + [4, 5]
مصفوفة مصفوفة2 = [0] * 5
اطبع("دمج المصفوفات:", مصفوفة1, "\n")
اطبع("تكرار المصفوفة:", مصفوفة2, "\n")

# الوصول للعناصر
رقم عنصر1 = [10, 20, 30][1]
رقم عنصر2 = [1, 2, 3, 4, 5][-1]
اطبع("العنصر بمؤشر 1:", عنصر1, "\n")
اطبع("العنصر الأخير:", عنصر2, "\n")

اطبع("\n=== تعابير الخرائط (Map Expressions) ===\n")

# الوصول لعناصر الخريطة
خريطة شخص = {"الاسم": "أحمد", "العمر": 25}
نص الاسم = شخص["الاسم"]
رقم العمر = شخص["العمر"]
اطبع("الاسم:", الاسم, "\n")
اطبع("العمر:", العمر, "\n")

اطبع("\n=== تعابير معقدة متداخلة ===\n")

# تعبير معقد يجمع كل شيء
رقم نتيجة_معقدة = ((10 + 5) * 2 - 3) ** 2 / 5 + 10
اطبع("تعبير معقد: ((10 + 5) * 2 - 3)^2 / 5 + 10 =", نتيجة_معقدة, "\n")

# تعبير منطقي معقد
منطقي شرط_معقد = ((10 > 5) و (20 < 30)) أو (ليس (5 == 6))
اطبع("شرط معقد: ((10 > 5) و (20 < 30)) أو (ليس (5 == 6)) =", شرط_معقد, "\n")

