        /// تحويل نوع العنصر إلى اسمه العربي (مثل: UINodeType::Text → "نص")
        std::string nodeTypeToArabicName(UINodeType type);

        /// تحويل الاسم العربي إلى نوع العنصر (مثل: "نص" → UINodeType::Text)
        std::optional<UINodeType> arabicNameToNodeType(const std::string &name);

        /// تحويل نوع المعدّل إلى اسمه العربي (مثل: ModifierType::FontSize → "حجم_خط")
        std::string modifierTypeToArabicName(ModifierType type);

        /// تحويل الاسم العربي إلى نوع المعدّل (مثل: "حجم_خط" → ModifierType::FontSize)
        std::optional<ModifierType> arabicNameToModifierType(const std::string &name);

        /// تحويل اللون المسمّى إلى قيمة RGBA (مثل: NamedColor::Red → 0xFF0000FF)
        uint32_t namedColorToRGBA(NamedColor color);

        /// تحويل الاسم العربي إلى لون مسمّى (مثل: "أحمر" → NamedColor::Red)
        std::optional<NamedColor> arabicNameToColor(const std::string &name);

