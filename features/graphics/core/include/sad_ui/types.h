        // ═══════════════════════════════════════════════════════════════════════════════
        // طور انتشار الحدث (Event Propagation Phase)
        // ═══════════════════════════════════════════════════════════════════════════════
        //
        // (AR) يُحدّد كيف ينتشر الحدث عبر شجرة العناصر:
        //   None    — لا انتشار (الحدث يُعالج فقط على العنصر المُستهدف)
        //   Bubble  — ينتشر من العنصر صعوداً إلى الجذر
        //   Capture — ينتشر من الجذر نزولاً إلى العنصر
        //   Both    — يمر بمرحلتي Capture ثم Bubble
        //
        // (EN) Determines how events propagate through the node tree:
        //   None    — no propagation (event handled only on target)
        //   Bubble  — propagates from target up to root
        //   Capture — propagates from root down to target
        //   Both    — capture phase then bubble phase
        // ═══════════════════════════════════════════════════════════════════════════════
        enum class EventPropagation : uint8_t
        {
            None,    ///< لا انتشار — الحدث على العنصر المُستهدف فقط
            Bubble,  ///< فقاعات — صعوداً من العنصر إلى الجذر
            Capture, ///< التقاط — نزولاً من الجذر إلى العنصر
            Both     ///< كلاهما — التقاط ثم فقاعات
        };

        // ═══════════════════════════════════════════════════════════════════════════════
        // بيانات الحدث (EventData) — المعلومات المُرفقة مع كل حدث
        // ═══════════════════════════════════════════════════════════════════════════════
        //
        // (AR) يحمل كل المعلومات عن الحدث: الموقع، المفتاح، أزرار التعديل،
        //      القيمة الجديدة (للإدخال)، بيانات مخصصة، وعلامة إيقاف الانتشار.
        //      ليس كل الحقول تُملأ لكل حدث — فقط ما يناسب نوعه.
        //
        // (EN) Carries all event info: position, key, modifier keys, new value
        //      (for input), custom data, and stop propagation flag.
        //      Not all fields are filled for every event — only what's relevant.
        // ═══════════════════════════════════════════════════════════════════════════════
        struct EventData
        {
            // ─── الموقع (Position) ─────────────────────
            float x = 0.0f; ///< إحداثي X (الفأرة/اللمس)
            float y = 0.0f; ///< إحداثي Y (الفأرة/اللمس)

            // ─── مقدار التغيير (Delta) ─────────────────
            float deltaX = 0.0f; ///< التغيير الأفقي (scroll, drag)
            float deltaY = 0.0f; ///< التغيير الرأسي (scroll, drag)

            // ─── لوحة المفاتيح (Keyboard) ─────────────
            int keyCode = 0;     ///< رمز المفتاح (SDL_Scancode)
            std::string keyName; ///< اسم المفتاح (مثال: "Enter", "Space")

            // ─── مفاتيح التعديل (Modifier Keys) ───────
            bool shiftKey = false; ///< هل Shift مضغوط؟
            bool ctrlKey = false;  ///< هل Ctrl مضغوط؟
            bool altKey = false;   ///< هل Alt مضغوط؟

            // ─── زر الفأرة (Mouse Button) ─────────────
            int button = 0; ///< زر الفأرة (0=أيسر, 1=أوسط, 2=أيمن)

            // ─── بيانات اللمس (Touch Data) ─────────────
            int64_t touchId = 0;   ///< معرّف جهاز اللمس (SDL_TouchID)
            int64_t fingerId = 0;  ///< معرّف الإصبع (SDL_FingerID)
            float pressure = 1.0f; ///< ضغط اللمس (0.0 → 1.0)
            int touchCount = 0;    ///< عدد الأصابع الملامسة حالياً
            bool isTouch = false;  ///< هل الحدث من شاشة لمس (وليس فأرة)

            // ─── زاوية الدوران (Rotation) ─────────────
            float angle = 0.0f; ///< زاوية الدوران (للإيماءات)

            // ─── القيمة الجديدة (New Value) ───────────
            std::string value; ///< القيمة الجديدة (حقل إدخال، slider، ...)

            // ─── بيانات مخصصة (Custom Payload) ────────
            /// (AR) بيانات حرّة يُحدّدها المبرمج لكلّ **معالِج**؛ يملؤها المُرسِل
            ///      قبل كلّ نداء من IREvent::userData — ولذلك هي mutable كعلامة
            ///      إيقاف الانتشار (بيانات الحدث تُمرَّر مرجعًا ثابتًا مشتركًا).
            mutable std::string customData;

            // ─── التحكم بالانتشار ─────────────────────
            mutable bool propagationStopped = false; ///< هل تم إيقاف الانتشار؟

            /// إيقاف انتشار الحدث — لا يصعد/ينزل بعد هذا العنصر
            void stopPropagation() const { propagationStopped = true; }
        };

        /// تحويل اسم حدث (عربي أو إنجليزي) إلى IREventType
        /// إذا لم يُعرف الاسم، يُرجع IREventType::Custom
        IREventType stringToIREventType(const std::string &name);

        /// تحويل IREventType إلى الاسم العربي الأساسي (للتصحيح والطباعة)
        const std::string &irEventTypeToString(IREventType type);

        /// هل هذا الاسم يمثل حدث معروف؟ (أي: ليس Custom)
        bool isKnownEventName(const std::string &name);

        /// (AR) اسم طورٍ عربيّ قانونيّ (SoT: ui_propagation.yaml) → EventPropagation.
        ///      يُرجع None لأيّ اسمٍ غير معروف (فشل-آمن: لا انتشار غير مقصود).
        EventPropagation stringToEventPropagation(const std::string &name);

        /// (AR) EventPropagation → اسمه العربيّ القانونيّ.
        const std::string &eventPropagationToString(EventPropagation phase);

        /// تحويل ModifierType (للأحداث فقط) إلى IREventType
        IREventType modifierTypeToIREventType(ModifierType mod);

        // ═══════════════════════════════════════════════════════════════════════════════
        // القسم الثالث: أنواع ربط الحالة (State Binding Types)
        // ═══════════════════════════════════════════════════════════════════════════════
        //
        // نظام الحالة هو قلب الواجهات التفاعلية. عندما تتغير حالة ما، يُعاد
        // رسم العناصر المرتبطة بها تلقائياً. مستوحى من SwiftUI @State و
        // Compose remember { mutableStateOf() }.
        //
        // مثال في كود ص:
        //   واجهة عدّاد {
        //       @حالة عدد: رقم = 0      ← StateBinding::State
        //       @ربط اسم: نص             ← StateBinding::Binding (من الأب)
        //       @بيئة لغة: نص            ← StateBinding::Environment (عالمي)
        //
        //       عرض() {
        //           نص("العدد: \(عدد)")
        //           زر("+1") { عدد += 1 }   ← التغيير يُعيد بناء الشجرة
        //       }
        //   }
        //
        // ═══════════════════════════════════════════════════════════════════════════════

        enum class StateBindingType : uint8_t
        {
            State,       ///< @حالة — حالة محلية يملكها العنصر نفسه
            Binding,     ///< @ربط — مرجع لحالة يملكها عنصر أب
            Observable,  ///< @مراقب — كائن مراقب يُنبّه عند التغيير
            Environment, ///< @بيئة — قيمة عالمية مشتركة (مثل السمة، اللغة)
            Computed,    ///< @محسوب — قيمة مشتقة من حالات أخرى
            Published,   ///< @منشور — تنشر التغييرات لكل المشتركين
        };

        // ═══════════════════════════════════════════════════════════════════════════════
        // القسم الرابع: أنواع القيم (Value Types)
        // ═══════════════════════════════════════════════════════════════════════════════
        //
        // قيم الخصائص يمكن أن تكون من عدة أنواع. هذا التعداد يُحدد نوع
        // القيمة المخزنة في كل معدّل — مما يسمح بالتحقق من الأنواع
        // والتحويل الصحيح لكل منصة.
        //
        // ═══════════════════════════════════════════════════════════════════════════════

        enum class ValueType : uint8_t
        {
            Number,     ///< رقم — قيمة عددية (int أو float)
            String,     ///< نص — سلسلة نصية
            Boolean,    ///< منطقي — صح أو خطأ
            Color,      ///< لون — قيمة لونية (RGBA)
            Dimension,  ///< بُعد — قيمة بُعدية مع وحدة (px, dp, %, em)
            EdgeInsets, ///< حواف — أربع قيم (أعلى، يمين، أسفل، يسار)
            Alignment,  ///< محاذاة — قيمة محاذاة (وسط، بداية، نهاية...)
            Callback,   ///< دالة — مرجع لدالة استدعاء
            Expression, ///< تعبير — تعبير حسابي أو نصي
            Enum,       ///< تعداد — قيمة من مجموعة خيارات
        };

        // ═══════════════════════════════════════════════════════════════════════════════
        // القسم الخامس: وحدات الأبعاد (Dimension Units)
        // ═══════════════════════════════════════════════════════════════════════════════

        enum class DimensionUnit : uint8_t
        {
            Px,      ///< بكسل — وحدة بكسل مطلقة
            Dp,      ///< dp — بكسل مستقل عن الكثافة (density-independent)
            Sp,      ///< sp — بكسل قابل للتحجيم مع إعدادات الخط
            Percent, ///< % — نسبة من العنصر الأب
            Em,      ///< em — نسبة من حجم الخط الحالي
            Vw,      ///< vw — نسبة من عرض الشاشة
            Vh,      ///< vh — نسبة من ارتفاع الشاشة
            Auto,    ///< تلقائي — يُحسب تلقائياً حسب المحتوى
        };

        // ═══════════════════════════════════════════════════════════════════════════════
        // القسم السادس: أنواع المحاذاة (Alignment Types)
        // ═══════════════════════════════════════════════════════════════════════════════

        enum class AlignmentType : uint8_t
        {
            Start,        ///< بداية — بداية النص (يمين في العربية RTL)
            End,          ///< نهاية — نهاية النص (يسار في العربية RTL)
            Center,       ///< وسط — توسيط
            Top,          ///< أعلى — محاذاة للأعلى
            Bottom,       ///< أسفل — محاذاة للأسفل
            TopStart,     ///< أعلى_بداية — الزاوية العليا من جهة البداية
            TopEnd,       ///< أعلى_نهاية — الزاوية العليا من جهة النهاية
            BottomStart,  ///< أسفل_بداية — الزاوية السفلى من جهة البداية
            BottomEnd,    ///< أسفل_نهاية — الزاوية السفلى من جهة النهاية
            Stretch,      ///< تمديد — يمتد ليملأ المساحة المتاحة
            SpaceBetween, ///< توزيع_بين — توزيع متساوٍ مع فراغات بين العناصر
            SpaceAround,  ///< توزيع_حول — توزيع متساوٍ مع فراغات حول العناصر
            SpaceEvenly,  ///< توزيع_متساوٍ — فراغات متساوية تماماً
        };

        // ═══════════════════════════════════════════════════════════════════════════════
        // القسم السابع: ألوان مسمّاة (Named Colors)
        // ═══════════════════════════════════════════════════════════════════════════════
        //
        // ألوان مُعرّفة مسبقاً يمكن استخدامها مباشرة في كود ص:
        //   نص("أهلاً").لون(.أحمر)
        //
        // ═══════════════════════════════════════════════════════════════════════════════

        enum class NamedColor : uint8_t
        {
            Black,       ///< أسود
            White,       ///< أبيض
            Red,         ///< أحمر
            Green,       ///< أخضر
            Blue,        ///< أزرق
            Yellow,      ///< أصفر
            Orange,      ///< برتقالي
            Purple,      ///< بنفسجي
            Pink,        ///< وردي
            Brown,       ///< بني
            Gray,        ///< رمادي
            LightGray,   ///< رمادي_فاتح
            DarkGray,    ///< رمادي_غامق
            Cyan,        ///< سماوي
            Teal,        ///< أزرق_مخضر
            Transparent, ///< شفاف
            // ألوان Material Design
            Primary,      ///< أساسي — لون السمة الأساسي
            Secondary,    ///< ثانوي — لون السمة الثانوي
            Surface,      ///< سطح — لون خلفية الأسطح
            OnPrimary,    ///< على_أساسي — لون النص على الخلفية الأساسية
            OnSecondary,  ///< على_ثانوي — لون النص على الخلفية الثانوية
            OnSurface,    ///< على_سطح — لون النص على الأسطح
            Error,        ///< خطأ — لون أحمر للأخطاء
            Grey,         ///< رمادي (بديل إنجليزي)
            Background,   ///< خلفية — لون الخلفية العامة
            OnBackground, ///< على_خلفية — لون النص على الخلفية
            OnError,      ///< على_خطأ — لون النص على خلفية الخطأ
            // (AR) درجات إضافيّة (من ui_colors.yaml) — تُرسَم أصلاً على سطح المكتب
            //      (كانت تسقط إلى اللون الافتراضيّ حين كانت خارج NamedColor).
            LightBlue,    ///< أزرق_فاتح
            DarkBlue,     ///< أزرق_داكن
            LightGreen,   ///< أخضر_فاتح
            DarkGreen,    ///< أخضر_داكن
            Success,      ///< تأكيد — لون النجاح
            Warning,      ///< تحذير — لون التحذير
            Info,         ///< معلومات — لون المعلومات
        };

        // ═══════════════════════════════════════════════════════════════════════════════
        // القسم الثامن: المنصات المستهدفة (Target Platforms)
        // ═══════════════════════════════════════════════════════════════════════════════

        enum class TargetPlatform : uint8_t
        {
            Desktop, ///< سطح_المكتب — Windows, Linux (SDL2+OpenGL)
            Android, ///< أندرويد — Jetpack Compose
            IOS,     ///< آي_أو_إس — SwiftUI
            Web,     ///< ويب — HTML5/CSS3/Canvas
            WASM,    ///< واسم — WebAssembly (SDL2+OpenGL)
            MacOS,   ///< ماك — macOS (AppKit/Cocoa)
            All,     ///< الكل — جميع المنصات
        };

