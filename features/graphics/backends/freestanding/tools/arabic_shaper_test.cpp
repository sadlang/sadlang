        // «يّة» = ي + شدّة(0651) + ة: قبل التحسين كانت الشدّة تكسر الاتّصال
        //   فتخرج ي وة منفصلتين [FE93 0651 FEF1]. بعده تُسقَط الشدّة ويتّصل
