    struct Case
    {
        const char *name;                // اسم الحالة (بيانات اختبار)
        std::vector<uint32_t> input;     // النقاط المنطقيّة
        std::vector<uint32_t> expected;  // النقاط العرضيّة المتوقَّعة
    };

    // ─────────────────────────────────────────────────────────────────────────
    // الاشتقاقات اليدويّة (من جدول arabic_normalization.cpp المعكوس):
    //
    // «سلام» = س ل ا م:
    //   س (ثنائيّ، لا سابق، يليه ل) ⇒ ابتدائيّ FEB3 (سطر FEB1..FEB4 ⇒ س).
    //   ل+ا ⇒ ليغاتورة لام-ألف؛ السابق س يتّصل يسارًا ⇒ نهائيّة FEFC (سطر FEFB/FEFC ⇒ ل ا).
    //   م (سابقه الألف اليمينيّة لا تتّصل يسارًا، لا لاحق) ⇒ منفصل FEE1.
    //   منطقيًّا [FEB3 FEFC FEE1] ⇒ عكس المدى ⇒ [FEE1 FEFC FEB3].
    //
    // «لا» = ل ا: ليغاتورة بلا سابق ⇒ منفصلة FEFB؛ مدًى مفرد ⇒ [FEFB].
    //
    // «ص» وحدها: لا سابق ولا لاحق ⇒ منفصل FEB9 (سطر FEB9..FEBC ⇒ ص).
    //
    // «إسلام» (لام-ألف غير بادئة بعد حرف لا يتّصل يسارًا):
    //   إ (يمينيّ، لا سابق) ⇒ منفصل FE87 (سطر FE87/FE88 ⇒ إ).
    //   س (سابقه إ لا يتّصل يسارًا؛ يليه ل) ⇒ ابتدائيّ FEB3.
    //   ل+ا (السابق س يتّصل) ⇒ ليغاتورة نهائيّة FEFC.
    //   م ⇒ منفصل FEE1.
    //   منطقيًّا [FE87 FEB3 FEFC FEE1] ⇒ عكس ⇒ [FEE1 FEFC FEB3 FE87].
    //
    // «نص FB» (مزيج عربيّ/ASCII):
    //   ن (يليه ص) ⇒ ابتدائيّ FEE7 (سطر FEE5..FEE8 ⇒ ن).
    //   ص (سابقه ن يتّصل، لا لاحق عربيّ) ⇒ نهائيّ FEBA (سطر FEB9..FEBC ⇒ ص:
    //   منفصل/نهائيّ/ابتدائيّ/وسطيّ — النهائيّ ثاني الأربعة).
    //   المدى العربيّ [FEE7 FEBA] يُعكس وحده ⇒ [FEBA FEE7]، والمسافة
    //   الحافّيّة و«FB» تبقى بترتيبها: [FEBA FEE7 0020 0046 0042].
    //   (ملاحظة تاريخيّة تثبت قدرة البوّابة على الفشل: أوّل صياغة لهذين الزوجين
    //   توقّعت خطأً FEBC — الوسطيّة — ففشل الاختبار باسمه الحقيقيّ وصُحّح المتوقَّع
    //   بعد مقابلة الجدول المرجعيّ، لا الكود.)
    //
    // «لا نص» (مدًى عربيّ بمسافة داخليّة):
    //   لا ⇒ FEFB (كما فوق)؛ نص ⇒ FEE7 FEBA (كما فوق).
    //   المدى كلّه بمسافته الداخليّة يُعكس: [FEFB 0020 FEE7 FEBA] ⇒
    //   [FEBA FEE7 0020 FEFB].
    //
    // «سلام لغة ص» (عنوان الديمو الحيّ — 7 غليفات عرض):
    //   سلام ⇒ FEB3 FEFC FEE1 (كما فوق).
    //   لغة = ل غ ة: ل (لا سابق متّصل، يليه غ) ⇒ ابتدائيّ FEDF (سطر FEDD..FEE0 ⇒ ل)؛
    //     غ (سابقه ل، يليه ة) ⇒ وسطيّ FED0 (سطر FECD..FED0 ⇒ غ)؛
    //     ة (سابقه غ يتّصل) ⇒ نهائيّة FE94 (سطر FE93/FE94 ⇒ ة).
    //   ص ⇒ منفصل FEB9.
    //   منطقيًّا [FEB3 FEFC FEE1 0020 FEDF FED0 FE94 0020 FEB9] — مدًى واحد
    //   بمسافتيه الداخليّتين ⇒ عكس كامل ⇒
    //   [FEB9 0020 FE94 FED0 FEDF 0020 FEE1 FEFC FEB3].
    // ─────────────────────────────────────────────────────────────────────────
