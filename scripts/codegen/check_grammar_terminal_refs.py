def عايِر_القرّاء() -> list:
    """(AR) يردُّ أسماءَ القرّاءِ الذين أخفقوا في عيارِ أنفسِهم."""
    قرّاء = {"نمط_الإحالة": نمط_الإحالة, "نمط_الفاصل": نمط_الفاصل}
    عُميان = []
    for اسم, موجبة, سالبة in عيّنات_القرّاء:
        نمط = قرّاء[اسم]
        if not نمط.search(موجبة):
            عُميان.append("%s لا يرى عيّنتَه الموجبة" % اسم)
        elif نمط.search(سالبة):
            عُميان.append("%s يرى عيّنتَه السالبة (وُسِّعَ حتّى طابقَ كلَّ شيء)"
                          % اسم)
    return عُميان


def امسح_الإحالات() -> tuple:
    """(AR) يردُّ (الإحالات، عددُ الملفّات، عددُ الفواصل) — والإحالةُ
    (ملفٌّ، سطرٌ، اسمٌ). والفواصلُ تُعَدُّ على حدةٍ لأنّ أرضيّتَها على حدة."""
    ملفّات = sorted(مجلد_القواعد.glob("*.yaml"))
    إحالات = []
    فواصل = 0
    for ملفّ in ملفّات:
        for رقم, خام in enumerate(ملفّ.read_text(encoding="utf-8").splitlines(), 1):
            سطر = انزع_التعليق(خام)
            من_الفواصل = نمط_الفاصل.findall(سطر)
            فواصل += len(من_الفواصل)
            for إحالة in نمط_الإحالة.findall(سطر) + من_الفواصل:
                إحالات.append((ملفّ.name, رقم, إحالة))
    return إحالات, len(ملفّات), فواصل


def افحص() -> int:
    try:
        معروفة, تقرير = اجمع_المعروفة()
        إحالات, عدد_الملفّات, عدد_الفواصل = امسح_الإحالات()
    except عطب_آلة as علّة:
        return أخفق_آلةً(str(علّة))

    print("حارس «إحالةُ رمزٍ في القواعدِ لها وجودٌ في الكتالوج»:")
    for سطر in تقرير:
        print(سطر)
    print("  مصادرُ أسماءٍ: %d · أسماءٌ معروفة: %d" % (len(تقرير), len(معروفة)))
    عُميان = عايِر_القرّاء()
    print("  ملفّاتُ قواعدَ مُسِحَت: %d (الأرضيّة %d) · إحالاتٌ قِيسَت: %d"
          " (الأرضيّة %d) · منها فواصلُ: %d · عيارُ القرّاء: %d/%d"
          % (عدد_الملفّات, أرضيّة_الملفّات, len(إحالات), أرضيّة_الإحالات,
             عدد_الفواصل, len(عيّنات_القرّاء) - len(عُميان),
             len(عيّنات_القرّاء)))

    # (AR) 🔑 **والعمى يُقالُ قبلَ الحكم.** صفرُ إحالةٍ كان يُقرأُ ✅ ورمزَ صفر.
    if عدد_الملفّات < أرضيّة_الملفّات:
        return أخفق_آلةً("ملفّاتُ القواعدِ %d دونَ الأرضيّةِ %d — لم يُمسَحْ شيء"
                        % (عدد_الملفّات, أرضيّة_الملفّات))
    if len(إحالات) < أرضيّة_الإحالات:
        return أخفق_آلةً("إحالاتٌ %d دونَ الأرضيّةِ %d — قارئُ الإحالاتِ أعمى"
                        % (len(إحالات), أرضيّة_الإحالات))
    if عُميان:
        return أخفق_آلةً("قارئٌ لا يُبصِر — %s" % "، ".join(عُميان))

    مخالفات = [بند for بند in إحالات if بند[2] not in معروفة]
    if مخالفات:
        print("[حارس] ✗ إحالاتُ رموزٍ شبحيّة في قواعد النحو: %d"
              % len(مخالفات), file=sys.stderr)
        for اسم, رقم, إحالة in مخالفات:
            print("  language-truth/grammar/%s:%d ⇐ %s" % (اسم, رقم, إحالة),
                  file=sys.stderr)
        print("  ⇐ الإحالةُ يجب أن تكون اسمَ رمزٍ في shared/lexer/include/token.h"
              " أو معرّفًا في keywords.yaml/operators.yaml"
              " (المصادرُ في _notation.yaml:terminal_ref_sources).",
              file=sys.stderr)
        return 1
    print("  ✓ كلُّ إحالاتِ الرموزِ في قواعدِ النحوِ موجودةٌ في الكتالوج.")
    return 0


if __name__ == "__main__":
    sys.exit(رمز_الخروج(افحص))
