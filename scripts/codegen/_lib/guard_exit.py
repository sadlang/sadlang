#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
============================================================================
(AR) **شبكةُ رمزِ الخروجِ العليا — قلبٌ واحدٌ لا نسخةٌ في كلِّ حارس.**

     عقدُ `x.py`: الرمزُ ٢ عطبُ **آلةٍ** («لم أنظرْ فلا حكمَ لي») والرمزُ ١
     حكمٌ على **المحتوى**. والانهيارُ غيرُ المتوقَّعِ يخرجُ في بايثون برمزِ ١،
     فيُقرأُ في البوّابةِ «وجدَ انجرافًا» — والعلاجانِ مختلفانِ تمامًا: إصلاحُ
     قارئٍ مقابلَ إصلاحِ مصدرِ حقيقة.

     وقِيسَ حيًّا: مخطَّطُ YAML يتبدّلُ (صفٌّ مكانَ خريطة) فينهارُ قارئُ الحارسِ
     بـ`AttributeError` ويخرجُ بـ١.

     ⚠️ **ولا تبتلعُ الشبكةُ `SystemExit`**: `argparse` يستعملُه لوسيطٍ خاطئٍ
        (٢) وللمساعدةِ (٠)، وابتلاعُه يقلبُ سلوكَ سطرِ الأمرِ رأسًا على عقب.

     🔑 **وهي ههنا لا في كلِّ حارس.** كُتِبَت أوّلَ مرّةٍ منسوخةً أربعَ مرّاتٍ
        في إيداعٍ أطروحتُه «قلبٌ واحدٌ لا ستُّ نسخٍ منجرفة» — وهي عينُ الحالةِ
        التي وُصِفَت قبلَ أن تنجرف. فرُفِعَت، ويُعلِنُها كلُّ سجلِّ عيارٍ في
        `depends` فتُبصَمُ مع الأهداف.

(EN) Shared top-level exit-code net: an unexpected crash is a TOOL fault
     (exit 2), never a content verdict (exit 1). SystemExit passes through so
     argparse keeps its own codes.
============================================================================
"""
from __future__ import annotations

import sys
import traceback


def رمز_الخروج(دالّة) -> int:
    """(AR) يُشغِّلُ جسمَ الحارسِ ويردُّ رمزَه — والانهيارُ غيرُ المتوقَّعِ ٢."""
    try:
        return دالّة()
    except SystemExit:
        raise
    except BaseException as علّة:          # noqa: BLE001 — الشبكةُ تعمُّ عمدًا
        traceback.print_exc()
        print("[حارس] ✗ عطبُ آلة: انهيارٌ غيرُ متوقَّعٍ (%s) — لم يُقَسْ شيء"
              % علّة.__class__.__name__, file=sys.stderr)
        return 2
