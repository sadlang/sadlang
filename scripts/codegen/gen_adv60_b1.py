HEADER = "# @rule: {rule}\n# @description: {desc}\n"

def main():
    written = 0
    for rule, cat, seq, desc, req, exp, body in T:
        d = BASE / rule / cat
        d.mkdir(parents=True, exist_ok=True)
        name = f"{seq}_{rule.split('.')[-1]}_{cat}.ص"
        # اسم مميّز لكلّ قاعدة+فئة+تسلسل
        name = f"{seq}_{cat}_{rule.split('.')[-1]}.ص"
        lines = [f"# @rule: {rule}", f"# @description: {desc}"]
        if req:
            lines.append(f"# @requires: {req}")
        if exp is None:
            lines.append("# @expect_error")
        else:
            lines.append(f"# @expected: {exp}")
        lines.append("")
        lines.append(body)
        (d / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
        written += 1
    print(f"كُتب {written} اختبارًا في {BASE}")

if __name__ == "__main__":
    main()
