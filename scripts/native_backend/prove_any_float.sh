#      و`known` يقيس ويطبع ولا يُفشِل (عيبٌ مفتوحٌ مُبلَّغٌ لا مسكوتٌ عنه).
#      الرأسُ ثابتٌ في كلّ الحالات: العنصرُ ٠ صحيحٌ (٧) والعنصرُ ١ عشريٌّ (٢٫٥)
#      ⇒ الوسمان مختلفان فيُميّز البرهانُ الفكَّ بالوسمِ عن الفكِّ الأعمى.
#      والاستيرادُ في الرأس لأنّ «جذر» تلزمها «رياضيات» في المفسّر (والخلفيّةُ
#      الأصليّةُ تقبلها بدونها — تباعُدُ إنفاذٍ منفصلٌ خارجَ نطاقِ هذا البرهان)؛
#      واستيرادٌ غيرُ مستعمَلٍ في بقيّةِ الحالات لا أثرَ له.
#      الأجسامُ تُكتَب بـ%b ⇒ تقبل «\n» لأجسامٍ متعدّدةِ الأسطر (شكلُ الفرع).
HEAD='استورد رياضيات\nمتغير خليط = [7، 2.5]'
