#!/bin/bash
# ============================================================================
# (AR) برهانُ «معامِلُ Any في عمليّةٍ عشريّة» حيًّا على المعماريّتين.
#      معامِلُ Any مؤشّرُ خانةٍ معلَّبة {وسم@0، حمولة@8}، والحمولةُ لا تكون بتّاتِ
#      double إلّا إذا كان الوسمُ Float. فالفكُّ الصحيحُ فرعٌ على الوسمِ **زمنَ
#      التشغيل** (نظيرُ dynToDouble في مسار LLVM) لا قراءةٌ عمياء.
#      ما يُبرهَن هنا (يُفشِل السكربتَ عند الردّ):
#        • النفيُ الأحاديّ: «‑[٧، ٢٫٥][٠]» ⇒ ‑7 و«‑[٧، ٢٫٥][١]» ⇒ ‑2.5 (كان يقع على
#          **مؤشّرِ العلبة** ثمّ يُقرأ خانةَ dyn ⇒ إشارة ١١ في الهدفَين؛ والعشريُّ
#          يُقلَب ببتِّ الإشارةِ وحدَه لأنّ المتمّمَ الثنائيَّ على بتّاتِ double قيمةٌ شاذّة)
#        • والنفيُ على عشريٍّ **ساكنٍ** (غيرِ معلَّب): «‑٢٫٥» ⇒ ‑2.5 (كان «‑1.75» —
#          جوابٌ خاطئٌ صامتٌ بنفسِ العلّة، غيرُ مقيسٍ حتّى كشفتْه المراجعة)
#        • ووسمٌ غيرُ عدديّ (منطقيّ/عدم/نصّ) ⇒ **إجهاضٌ برمزِ ١٣٣** لا جوابٌ ولا سقوط:
#          المفسّرُ يرمي RUN053، وقبلَ الإصلاح كانت الثلاثةُ تسقط بإشارة ١١؛ ولو فُكَّت
#          بلا فحصِ وسمٍ لصارت «‑صحيح = صحيح» و«‑لاشيء = لاشيء» بخروجِ صفر — أي
#          استبدالَ سقوطٍ مرئيٍّ بجوابٍ خاطئٍ صامت، وهو أسوأ.
#        • الحساب:   «[١، ٢٫٥][١] + ١٫٥» ⇒ 4.0   (كان x86 «1.5»: قرأ المؤشّرَ نفسَه)
#        • الوسم:    «[٧، ٢٫٥][٠] + ١٫٥» ⇒ 8.5   (كان الهدفان «1.5»: فكٌّ أعمى)
#        • المقارنةُ قيمةً بالشكلين (Any يمينًا ويسارًا) والمساواة
#        • المقارنةُ **فرعًا** («إذا»): كانت تقارن مؤشّرَ العلبة في الهدفَين،
#          والجوابُ يتبدّل بترتيبِ المعامِلَين في x86 (نصفُ فكّ) — حتّى
#          «إذا (س == س)» كان كاذبًا في AArch64.
#        • التحويلات: «عشري(Any)» و«رقم(Any)» و«جذر(Any)»  (كانت تُحوِّل العنوان)
#        • **الإرسالُ بالوسمِ زمنَ التشغيل**: أوپكودٌ صحيحٌ (ADD_I64/المقارنة) بمعامِلٍ
#          معلَّبٍ نوعُه الحقيقيُّ غيرُ معلومٍ ساكنًا ⇒ فرعٌ على الوسمِ في الشيفرةِ
#          المولَّدة. المقيسُ قبلَه: «خليط[٠]+خليط[١]» = ٤٦١٢٨١١٩١٨٣٣٤٢٣٠٥٣٥ والصوابُ
#          «٩٫٥»؛ و«خليط[٠] > خليط[١]» كاذبةٌ والصوابُ صادقة؛ و«خليط[١] > ٣» صادقةٌ
#          والصوابُ كاذبة — ثلاثتُها جوابٌ خاطئٌ صامتٌ بخروجِ صفر.
#          وثلاثةُ أشكالٍ لا يكفي فيها قياسُ الوسمِ وحدَه، وكلٌّ منها كشفَه البرهانُ:
#            - **ثابتٌ صحيحٌ ساكنٌ** في المسارِ العشريّ («خليط[١] > ٣») يمرّ نمطَ
#              بتّاتِه فيُقرأ double ⇒ يلزمه cvtsi2sd/scvtf (loadFloatOperandPromoting).
#            - **المقارنةُ فرعًا** («إذا (خليط[١] > ٣)») تُدمَج في المُنهي خارجَ
#              driveComparison ⇒ استُثنيت من الإدماج كمقارنةِ العوائم.
#            - **صحيحان معلَّبان** («خليط[٠]+خليط[٠]» = ١٤ لا ١٤٫٠) ⇒ المسارُ الصحيحُ
#              يبقى صحيحًا ووسمُ المُخرَجِ يتبع المسارَ المسلوك.
#      🐞 وما يبقى مفتوحًا — يُقاس ويُطبَع ولا يُفشِل:
#        • **وسمُ Float يُعلَّب من نفيٍ ساكنٍ** («خ[٠] = ‑س» حيث س عشريٌّ ساكن) ⇒ ARRAY_SET
#          يُثبّت وسمَ Int على بتّاتِ double (عيبُ تعليبٍ لا عيبُ نفي).
#        • **معاملاتُ «أي» المكتوبةُ في تصريحِ دالّة** — عيبٌ سابقٌ لهذه الدفعة (قِيس
#          على HEAD بالنتيجةِ عينِها) لا يبلغه الإرسالُ بالوسم، بوجهَين:
#            - «س + ع» ⇒ الأماميّةُ تُصدِر ADD_I64 بمعامِلَي Any ونتيجةِ **Integer**،
#              فيسقط شرطُ الإرسالِ ويعود المسارُ الأعمى (٤٦١٢٨١١٩١٨٣٣٤٢٣٠٥٣٥ لا ٩٫٥).
#            - «س > ع» **داخلَ فرعٍ شرطيّ** ⇒ جوابٌ ثابتٌ لا يتبع الوسيطَين ويختلف
#              بالمعماريّة: ندَاءان بترتيبَين متعاكسَين ⇒ المفسّرُ «نل» وx86 «نن»
#              وAArch64 «لل» — انجرافُ هدفَين فوق الجوابِ الخاطئ. (والشكلُ نفسُه
#              بلا فرعٍ يخرج صوابًا ⇒ العلّةُ في الفرعِ داخلَ دالّةٍ بمعاملاتِ «أي».)
#        • **قسمةُ صحيحَين تُنتج عشريًّا**: «س / ص» تُصدِر DIV_F64 بمعامِلَي Int ونتيجةِ
#          Any بلا خانةِ dyn ⇒ سقوطٌ بإشارة ١١ في الهدفَين والمفسّرُ «٢٫٥». موضعُه
#          الأماميّةُ ومسحُ التعليب لا مُحمِّلَ المعامِلات. والشكلُ المعلَّبُ يسقط كذلك
#          («خليط[٠] / خليط[١]» ⇒ إشارة ١١ والمفسّرُ «٢٫٨») ⇒ العيبُ أوسعُ من
#          معامِلَي Int الساكنَين.
#        • وسمُ Str في عمليّةٍ عشريّة ⇒ المفسّرُ يضمّ، والأماميّةُ لا تمسكه، والهدفان
#          يطبعان عنوانَ الواصفِ عددًا (والعنوانُ يختلف بالمعماريّة). والإرسالُ بالوسمِ
#          لا يُغلقه عمدًا: شرطُه «الوسم == Float» لا «ليس Int»، لأنّ توسيعَه إلى هلعٍ
#          يُجهِض مقارنةَ نصَّين معلَّبَين وهي عمليّةٌ مشروعةٌ في المفسّر. ⚠️ أمّا الوسمُ
#          غيرُ العدديِّ **مقرونًا بـFloat** فيُجهَض بالرمزِ ١٣٣ كنظيرِه الأحاديّ: بلا
#          ذلك يجرّه الإرسالُ إلى المسارِ العشريِّ فيُنتج «٣٫٥» (١٫٠+٢٫٥) بخروجِ صفر —
#          جوابٌ معقولُ المظهرِ خاطئ، أسوأُ من القمامةِ المرئيّةِ التي كانت.
#          ⚠️ و«==»/«!=» **مستثناةٌ من الهلع**: الهلعُ عقدُ عمليّةٍ لا جوابَ لها، وهاتان
#          جوابُهما محدَّدٌ في المفسّر حين يختلف الوسمان («غيرُ متساويين») لا خطأُ نوع ⇒
#          يُحسَبان ولا يُجهَضان. أمّا الترتيبيّاتُ فيرفضها المفسّرُ (SEM017) فتبقى هلعًا.
#          🐞 ويبقى الضمُّ عيبًا مفتوحًا لا مُغلَقًا: «نصّ + عدد» مشروعٌ في المفسّر
#          («نص2.5») والخلفيّةُ تُجهِض بـ١٣٣ — إجهاضٌ مقصودٌ لميزةٍ غيرِ منفَّذةٍ في
#          الخلفيّة (شكلُها الساكنُ يُخفِق زمنَ التصريف) لا ادّعاءُ مطابقةٍ للمفسّر.
#      ✅ والمتوقَّعُ للمقارنةِ «صحيح»/«خطأ» كالمفسّر: طباعةُ المنطقيِّ الساكنِ
#         كانت تطبع العددَ والمعلَّبةُ تطبع الكلمةَ — تناقضٌ داخلَ المخفّضِ الواحد،
#         أُغلق بـ`emitPrintBool` في الهدفَين. والجدولُ كان يوثّقُ الانحرافَ لا يكشفُه.
# (EN) Live proof: an Any operand in a float op must be unboxed **by its tag**.
#   الوسيط ١: مسارُ sad-build. الوسيط ٢ (اختياريّ): مجلّدُ العمل.
# ============================================================================
set -u
BUILD="${1:?usage: prove_any_float.sh <sad-build-path> [workdir]}"
WORK="${2:-$(mktemp -d)}"
FAIL=0
RAN=0
BUILT=0

# (AR) مجلّدٌ نظيفٌ لكلّ تشغيلة: الوسيطُ ٢ يُعاد استعمالُه عمدًا، وثنائيُّ تشغيلةٍ
#      ماضيةٍ باقٍ يجعل البرهانَ يخضرّ بمترجمٍ **لم يعمل قطّ**. البقايا أخطرُ من
#      الغياب: الغيابُ يُرى، والبقيّةُ تُقرأ نجاحًا.
#      ⚠️ ولا يُمحى إلّا ما يحمل بصمةَ هذا السكربت أو كان فارغًا: الوسيطُ ٢ مسارٌ
#         حرٌّ يكتبه إنسان، وخطأٌ مطبعيٌّ واحدٌ مع `rm -rf` أعمى يبتلع مجلّدًا حقيقيًّا.
STAMP_NAME=".prove_any_float"
# (AR) ما ليس مجلّدًا يُرفَض أوّلًا: شرطُ البصمةِ وحدَه يسقط على مسارِ **ملفّ**
#      فيمرّ `rm -rf` أعمى ويبتلعه. الحارسُ الذي يفوته نوعُ المقصدِ ليس حارسًا.
if [ -e "$WORK" ] && [ ! -d "$WORK" ]; then
  echo "FAIL: «$WORK» موجودٌ وليس مجلّدًا — لن يُمحى"
  exit 1
fi
if [ -d "$WORK" ] && [ ! -e "$WORK/$STAMP_NAME" ] && [ -n "$(ls -A "$WORK" 2>/dev/null)" ]; then
  echo "FAIL: «$WORK» ليس مجلّدَ عملٍ لهذا السكربت (لا بصمة) وليس فارغًا — لن يُمحى"
  exit 1
fi
rm -rf "$WORK"
mkdir -p "$WORK"
: > "$WORK/$STAMP_NAME"

# (AR) على ويندوز (Git Bash) يُترجَم بـsad-build.exe محلّيًّا ويُنفَّذ ثنائيُّ لينكس عبر WSL.
#      المسارُ يُترجَم C:/x ⇒ /mnt/c/x. وعلى لينكس لا وسيطَ ولا ترجمة.
WSLRUN=""
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) WSLRUN="1";; esac
to_linux_path() {
  if [ -n "$WSLRUN" ]; then
    printf '/mnt/%s' "$(cd "$(dirname "$1")" && pwd -W 2>/dev/null | tr 'A-Z' 'a-z' | tr -d ':')/$(basename "$1")"
  else printf '%s' "$1"; fi
}
run_bin() { # <ثنائيّ> [مُشغِّل]
  local bin="$1" runner="${2:-}"
  if [ -n "$WSLRUN" ]; then
    # (AR) مقصدٌ متفرّدٌ لكلّ ثنائيّ: مسارٌ ثابتٌ مشترَكٌ يعني أنّ إخفاقَ النسخِ
    #      يُنفّذ ثنائيَّ الحالةِ السابقة فيُقاس غيرُ المقصود.
    local tgt="/tmp/_pv_$(basename "$bin")"
    wsl.exe -e bash -c "rm -f '$tgt' && cp '$(to_linux_path "$bin")' '$tgt' && chmod +x '$tgt' && ${runner:+$runner }'$tgt'" 2>/dev/null
  elif [ -n "$runner" ]; then "$runner" "$bin" 2>/dev/null
  else "$bin" 2>/dev/null; fi
}

# (AR) qemu قد يكون داخل WSL لا على ويندوز ⇒ ابحث عنه حيث سيُنفَّذ الثنائيّ.
if [ -n "$WSLRUN" ]; then
  QEMU="$(wsl.exe -e bash -c 'command -v qemu-aarch64-static || command -v qemu-aarch64' 2>/dev/null | tr -d '\r')"
else
  QEMU="$(command -v qemu-aarch64-static || command -v qemu-aarch64 || true)"
fi

