#!/bin/bash
# ============================================================================
# (AR) برهانُ «معامِلُ Any في عمليّةٍ عشريّة» حيًّا على المعماريّتين.
#      معامِلُ Any مؤشّرُ خانةٍ معلَّبة {وسم@0، حمولة@8}، والحمولةُ لا تكون بتّاتِ
#      double إلّا إذا كان الوسمُ Float. فالفكُّ الصحيحُ فرعٌ على الوسمِ **زمنَ
#      التشغيل** (نظيرُ dynToDouble في مسار LLVM) لا قراءةٌ عمياء.
#      ما يُبرهَن هنا (يُفشِل السكربتَ عند الردّ):
#        • النفيُ الأحاديّ: «‑[٧، ٢٫٥][٠]» ⇒ ‑7 و«‑[٧، ٢٫٥][١]» ⇒ ‑2.5 (كان يقع على
#          **مؤشّرِ العلبة** ثمّ يُقرأ خانةَ dyn ⇒ إشارة ١١ في الهدفَين؛ والعشريُّ
#          يُقلَب ببتِّ الإشارةِ وحدَه لأنّ المتمّمَ الثنائيَّ على بتّاتِ double قيمةٌ شاذّة)
#        • والنفيُ على عشريٍّ **ساكنٍ** (غيرِ معلَّب): «‑٢٫٥» ⇒ ‑2.5 (كان «‑1.75» —
#          جوابٌ خاطئٌ صامتٌ بنفسِ العلّة، غيرُ مقيسٍ حتّى كشفتْه المراجعة)
#        • ووسمٌ غيرُ عدديّ (منطقيّ/عدم/نصّ) ⇒ **إجهاضٌ برمزِ ١٣٣** لا جوابٌ ولا سقوط:
#          المفسّرُ يرمي RUN053، وقبلَ الإصلاح كانت الثلاثةُ تسقط بإشارة ١١؛ ولو فُكَّت
#          بلا فحصِ وسمٍ لصارت «‑صحيح = صحيح» و«‑لاشيء = لاشيء» بخروجِ صفر — أي
#          استبدالَ سقوطٍ مرئيٍّ بجوابٍ خاطئٍ صامت، وهو أسوأ.
#        • الحساب:   «[١، ٢٫٥][١] + ١٫٥» ⇒ 4.0   (كان x86 «1.5»: قرأ المؤشّرَ نفسَه)
#        • الوسم:    «[٧، ٢٫٥][٠] + ١٫٥» ⇒ 8.5   (كان الهدفان «1.5»: فكٌّ أعمى)
#        • المقارنةُ قيمةً بالشكلين (Any يمينًا ويسارًا) والمساواة
#        • المقارنةُ **فرعًا** («إذا»): كانت تقارن مؤشّرَ العلبة في الهدفَين،
#          والجوابُ يتبدّل بترتيبِ المعامِلَين في x86 (نصفُ فكّ) — حتّى
#          «إذا (س == س)» كان كاذبًا في AArch64.
#        • التحويلات: «عشري(Any)» و«رقم(Any)» و«جذر(Any)»  (كانت تُحوِّل العنوان)
#      🐞 وما يبقى مفتوحًا — يُقاس ويُطبَع ولا يُفشِل:
#        • **معامِلا Any معًا** ⇒ الأماميّةُ تُبقي النتيجةَ Any فلا تُصدِر صيغةً عشريّةً
#          أصلًا، فتُعامَل الحمولتان صحيحَين أعميَين — جمعًا («+») ومقارنةً («>»).
#        • **المقارنةُ الصحيحةُ تفكّ بلا وسم** ⇒ حمولةُ وسمِ Float تُقارَن بتّاتِ double
#          كعددٍ صحيحٍ ضخم. إغلاقُه يلزمه فرعٌ رباعيٌّ على الوسمَين (ترقيةُ
#          صحيحٍ↔عشريٍّ زمنَ التشغيل) لا فكًّا بالوسمِ فحسب.
#        • **قسمةُ صحيحَين تُنتج عشريًّا**: «س / ص» تُصدِر DIV_F64 بمعامِلَي Int ونتيجةِ
#          Any بلا خانةِ dyn ⇒ سقوطٌ بإشارة ١١ في الهدفَين والمفسّرُ «٢٫٥». موضعُه
#          الأماميّةُ ومسحُ التعليب لا مُحمِّلَ المعامِلات.
#        • وسمُ Str في عمليّةٍ عشريّة ⇒ المفسّرُ يضمّ، والأماميّةُ لا تمسكه، والهدفان
#          يطبعان عنوانَ الواصفِ عددًا (والعنوانُ يختلف بالمعماريّة).
#      ⚠️ المتوقَّعُ للمقارنةِ قيمةً «1»/«0» لا «صحيح»/«خطأ»: الخلفيّةُ الأصليّةُ تطبع
#         المنطقيَّ عددًا بينما المفسّرُ يطبع «صحيح» — تباعُدُ عرضٍ قائمٌ سابقٌ لهذا
#         الإصلاح وخارجَ نطاقِه، يُثبَّت هنا كما هو لا يُجمَّل.
# (EN) Live proof: an Any operand in a float op must be unboxed **by its tag**.
#   الوسيط ١: مسارُ sad-build. الوسيط ٢ (اختياريّ): مجلّدُ العمل.
# ============================================================================
set -u
BUILD="${1:?usage: prove_any_float.sh <sad-build-path> [workdir]}"
WORK="${2:-$(mktemp -d)}"
FAIL=0
RAN=0
BUILT=0

# (AR) مجلّدٌ نظيفٌ لكلّ تشغيلة: الوسيطُ ٢ يُعاد استعمالُه عمدًا، وثنائيُّ تشغيلةٍ
#      ماضيةٍ باقٍ يجعل البرهانَ يخضرّ بمترجمٍ **لم يعمل قطّ**. البقايا أخطرُ من
#      الغياب: الغيابُ يُرى، والبقيّةُ تُقرأ نجاحًا.
#      ⚠️ ولا يُمحى إلّا ما يحمل بصمةَ هذا السكربت أو كان فارغًا: الوسيطُ ٢ مسارٌ
#         حرٌّ يكتبه إنسان، وخطأٌ مطبعيٌّ واحدٌ مع `rm -rf` أعمى يبتلع مجلّدًا حقيقيًّا.
STAMP_NAME=".prove_any_float"
# (AR) ما ليس مجلّدًا يُرفَض أوّلًا: شرطُ البصمةِ وحدَه يسقط على مسارِ **ملفّ**
#      فيمرّ `rm -rf` أعمى ويبتلعه. الحارسُ الذي يفوته نوعُ المقصدِ ليس حارسًا.
if [ -e "$WORK" ] && [ ! -d "$WORK" ]; then
  echo "FAIL: «$WORK» موجودٌ وليس مجلّدًا — لن يُمحى"
  exit 1
fi
if [ -d "$WORK" ] && [ ! -e "$WORK/$STAMP_NAME" ] && [ -n "$(ls -A "$WORK" 2>/dev/null)" ]; then
  echo "FAIL: «$WORK» ليس مجلّدَ عملٍ لهذا السكربت (لا بصمة) وليس فارغًا — لن يُمحى"
  exit 1
fi
rm -rf "$WORK"
mkdir -p "$WORK"
: > "$WORK/$STAMP_NAME"

# (AR) على ويندوز (Git Bash) يُترجَم بـsad-build.exe محلّيًّا ويُنفَّذ ثنائيُّ لينكس عبر WSL.
#      المسارُ يُترجَم C:/x ⇒ /mnt/c/x. وعلى لينكس لا وسيطَ ولا ترجمة.
WSLRUN=""
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) WSLRUN="1";; esac
to_linux_path() {
  if [ -n "$WSLRUN" ]; then
    printf '/mnt/%s' "$(cd "$(dirname "$1")" && pwd -W 2>/dev/null | tr 'A-Z' 'a-z' | tr -d ':')/$(basename "$1")"
  else printf '%s' "$1"; fi
}
run_bin() { # <ثنائيّ> [مُشغِّل]
  local bin="$1" runner="${2:-}"
  if [ -n "$WSLRUN" ]; then
    # (AR) مقصدٌ متفرّدٌ لكلّ ثنائيّ: مسارٌ ثابتٌ مشترَكٌ يعني أنّ إخفاقَ النسخِ
    #      يُنفّذ ثنائيَّ الحالةِ السابقة فيُقاس غيرُ المقصود.
    local tgt="/tmp/_pv_$(basename "$bin")"
    wsl.exe -e bash -c "rm -f '$tgt' && cp '$(to_linux_path "$bin")' '$tgt' && chmod +x '$tgt' && ${runner:+$runner }'$tgt'" 2>/dev/null
  elif [ -n "$runner" ]; then "$runner" "$bin" 2>/dev/null
  else "$bin" 2>/dev/null; fi
}

# (AR) qemu قد يكون داخل WSL لا على ويندوز ⇒ ابحث عنه حيث سيُنفَّذ الثنائيّ.
if [ -n "$WSLRUN" ]; then
  QEMU="$(wsl.exe -e bash -c 'command -v qemu-aarch64-static || command -v qemu-aarch64' 2>/dev/null | tr -d '\r')"
else
  QEMU="$(command -v qemu-aarch64-static || command -v qemu-aarch64 || true)"
fi

# (AR) الحالات: «اسم|نوع|المتوقَّع|جسمُ البرنامج». النوعُ `prove` يُفشِل عند الاختلاف،
#      و`known` يقيس ويطبع ولا يُفشِل (عيبٌ مفتوحٌ مُبلَّغٌ لا مسكوتٌ عنه).
#      الرأسُ ثابتٌ في كلّ الحالات: العنصرُ ٠ صحيحٌ (٧) والعنصرُ ١ عشريٌّ (٢٫٥)
#      ⇒ الوسمان مختلفان فيُميّز البرهانُ الفكَّ بالوسمِ عن الفكِّ الأعمى.
#      والاستيرادُ في الرأس لأنّ «جذر» تلزمها «رياضيات» في المفسّر (والخلفيّةُ
#      الأصليّةُ تقبلها بدونها — تباعُدُ إنفاذٍ منفصلٌ خارجَ نطاقِ هذا البرهان)؛
#      واستيرادٌ غيرُ مستعمَلٍ في بقيّةِ الحالات لا أثرَ له.
#      الأجسامُ تُكتَب بـ%b ⇒ تقبل «\n» لأجسامٍ متعدّدةِ الأسطر (شكلُ الفرع).
HEAD='استورد رياضيات\nمتغير خليط = [7، 2.5]'
# (AR) يُخرِج «\\n» **حرفيًّا** لا سطرًا فعليًّا: الحالةُ سطرٌ واحدٌ يفصله «|»،
#      وسطرٌ فعليٌّ داخلَها يقطع `read` فيضيع جسمُ البرنامجِ ويُقاس فراغ.
if_eq() { printf 'إذا (%s)\\n    اطبع_سطر("نعم")\\nوإلا\\n    اطبع_سطر("لا")\\nنهاية' "$1"; }
CASES=(
  "add_float|prove|4.0|اطبع_سطر(خليط[1] + 1.5)"
  "add_int|prove|8.5|اطبع_سطر(خليط[0] + 1.5)"
  "cmp_left|prove|1|اطبع_سطر(خليط[0] > 1.5)"
  "cmp_right|prove|1|اطبع_سطر(1.5 < خليط[0])"
  "cmp_eq|prove|1|اطبع_سطر(خليط[0] == 7.0)"
  "conv_float|prove|7.0|اطبع_سطر(عشري(خليط[0]))"
  "conv_int|prove|2|اطبع_سطر(رقم(خليط[1]))"
  "sqrt_any|prove|2.645751|اطبع_سطر(جذر(خليط[0]))"
  "br_eq|prove|نعم|$(if_eq 'خليط[0] == 7')"
  "br_eq_rev|prove|نعم|$(if_eq '7 == خليط[0]')"
  "br_self|prove|نعم|$(if_eq 'خليط[0] == خليط[0]')"
  "neg_any|prove|-7|اطبع_سطر(-خليط[0])"
  "neg_any_float|prove|-2.5|اطبع_سطر(-خليط[1])"
  "neg_static_float|prove|-2.5|متغير س = 2.5\nاطبع_سطر(-س)"
  "neg_static_float_boxed|known|-2.5|متغير س = 2.5\nمتغير خ = [1، 2]\nخ[0] = -س\nاطبع_سطر(خ[0])"
  "neg_bool|panic|133|متغير م = [صحيح، 2.5]\nاطبع_سطر(-م[0])"
  "neg_null|panic|133|متغير م = [لاشيء، 2.5]\nاطبع_سطر(-م[0])"
  "neg_str|panic|133|متغير م = [\"نص\"، 2.5]\nاطبع_سطر(-م[0])"
  "any_any|known|9.5|اطبع_سطر(خليط[0] + خليط[1])"
  "any_cmp_any|known|1|اطبع_سطر(خليط[0] > خليط[1])"
  "cmp_float_payload|known|0|اطبع_سطر(خليط[1] > 3)"
  "int_div_float|known|2.5|متغير س = 10\nمتغير ص = 4\nاطبع_سطر(س / ص)"
)

EXPECTED=0
for c in "${CASES[@]}"; do
  IFS='|' read -r name kind want body <<< "$c"
  printf '%b\n%b\n' "$HEAD" "$body" > "$WORK/$name.ص"
  if "$BUILD" "$WORK/$name.ص" --خلفية-أصلية --هدف=x86_64-unknown-linux-gnu  -o "$WORK/$name.x86" >/dev/null 2>&1
  then BUILT=$((BUILT+1)); fi
  if "$BUILD" "$WORK/$name.ص" --خلفية-أصلية --هدف=aarch64-unknown-linux-gnu -o "$WORK/$name.arm" >/dev/null 2>&1
  then BUILT=$((BUILT+1)); fi
  { [ "$kind" = "prove" ] || [ "$kind" = "panic" ]; } && EXPECTED=$((EXPECTED+2))
done

# (AR) صفرُ ترجمةٍ ناجحةٍ ⇒ لا مترجمَ أصلًا: أَبْلِغ قبل أن تُقرأ الـSKIPات نجاحًا.
if [ "$BUILT" -eq 0 ]; then
  echo "FAIL: لم تنجح أيُّ ترجمة — تحقّق من مسار sad-build («$BUILD»)"; exit 1
fi

check() { # <اسم> <لاحقة> <نوع> <متوقَّع> [مُشغِّل]
  local bin="$WORK/$1.$2" kind="$3" want="$4" runner="${5:-}" got rc
  if [ ! -f "$bin" ]; then echo "SKIP: $1.$2 لم يُترجَم"; return; fi
  chmod +x "$bin" 2>/dev/null || true
  got="$(run_bin "$bin" "$runner")"
  rc=$?
  # (AR) `panic` يقيس **رمزَ الخروج** لا المخرَج: النفيُ على وسمٍ غيرِ عدديٍّ إجهاضٌ
  #      متعمَّدٌ (١٣٣)، والبديلُ عنه جوابٌ خاطئٌ صامتٌ («‑صحيح = صحيح») أو سقوطٌ بإشارة ١١.
  if [ "$kind" = "panic" ]; then
    RAN=$((RAN+1))
    if [ "$rc" -eq "$want" ]; then echo "PASS(هلع): $1.$2 ⇒ رمز $rc"
    else echo "FAIL(هلع): $1.$2 ⇒ رمز $rc ومخرَج «$got» (متوقَّع رمز $want)"; FAIL=1; fi
    return
  fi
  if [ "$kind" = "known" ]; then
    if [ "$got" = "$want" ]; then echo "GREEN(عيبٌ أُصلِح): $1.$2 ⇒ «$got»"
    else echo "KNOWN-BUG: $1.$2 ⇒ «$got» (الصحيحُ «$want»)"; fi
    return
  fi
  RAN=$((RAN+1))
  # (AR) المخرَجُ وحدَه لا يكفي: ثنائيٌّ يطبع الجوابَ الصحيحَ ثمّ يسقط يُقرأ PASS.
  #      فرمزُ الخروجِ جزءٌ من الأوراكل — والحالاتُ هنا كلُّها تطبع ثمّ تخرج بـ٠.
  if [ "$rc" -ne 0 ]; then echo "FAIL: $1.$2 ⇒ «$got» ورمزُ الخروجِ $rc (متوقَّع ٠)"; FAIL=1; return; fi
  if [ "$got" = "$want" ]; then echo "PASS: $1.$2 ⇒ «$got»"
  else echo "FAIL: $1.$2 ⇒ «$got» (متوقَّع «$want»)"; FAIL=1; fi
}

echo "=== x86-64 (نيتيف) ==="
for c in "${CASES[@]}"; do
  IFS='|' read -r name kind want body <<< "$c"
  check "$name" x86 "$kind" "$want"
done

echo "=== AArch64 (qemu) ==="
if [ -z "$QEMU" ]; then
  echo "SKIP: qemu-aarch64 غير متوفّر"
else
  for c in "${CASES[@]}"; do
    IFS='|' read -r name kind want body <<< "$c"
    check "$name" arm "$kind" "$want" "$QEMU"
  done
fi

# (AR) الحدُّ = كلُّ حالةٍ حاسمةٍ × معماريّتين، لا صفرٌ ولا واحد: السكربتُ يدّعي
#      برهانًا **على المعماريّتين**، فنجاحٌ بنصفِ الحالاتِ المنفَّذة (qemu غائبٌ
#      مثلًا، وهو الحالُ الشائع) يعلن ما لم يُقَس. وأخضرُ بلا قياسٍ هو ما يُخفي
#      العيبَ لا ما يكشفه. (حالاتُ `known` لا تُعَدّ: تقيس ولا تُبرهن.)
if [ "$RAN" -lt "$EXPECTED" ]; then
  echo "FAIL: نُفِّذ $RAN من $EXPECTED — لا برهانَ كاملًا (تحقّق من المترجم/WSL/qemu)"
  exit 1
fi
N=$((EXPECTED/2))
# (AR) تمييزُ العددِ عربيًّا: ٣–١٠ جمعُ قلّةٍ («حالاتٍ»)، وما عداه مفردٌ منصوب.
if [ "$N" -ge 3 ] && [ "$N" -le 10 ]; then UNIT="حالاتٍ"; else UNIT="حالةً"; fi
[ "$FAIL" -eq 0 ] && { echo "PASS: معامِلُ Any يُفكُّ بوسمِه حسابًا ومقارنةً وفرعًا وتحويلًا ($RAN تنفيذًا = $N $UNIT × معماريّتين)"; exit 0; } \
                  || { echo "FAIL: معامِلُ Any يُقرأ قراءةً عمياء في عمليّةٍ عشريّة"; exit 1; }
