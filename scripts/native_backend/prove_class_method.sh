#!/bin/bash
# ============================================================================
# (AR) برهانُ نداءِ الطريقةِ الحيِّ بعدَ إدخالِ حارسِ المُستقبِلِ العدميّ (ISSUE-161):
#      «متغير ن = نقطة(42)» ثمّ «ارجع ن.احصل()» ⇒ رمزُ خروجٍ ٤٢ — على x86-64
#      نيتيفيًّا وAArch64 تحت qemu.
#
# (AR) 🔑 ولمَ هذا البرهانُ لازمٌ رغمَ وجودِ تأكيدٍ بايتيٍّ في gtest: التأكيدُ البايتيُّ
#      يُثبِتُ أنّ كتلةَ الهلعِ **صدرت**، ولا يُثبِتُ أنّ النداءَ ما يزال **يعمل**.
#      والحارسُ يُقحِمُ مقارنةً وفرعًا في منتصفِ مسارِ الإرسال — فلو أخطأ الفرعُ إزاحتَه
#      أو دهس المُستقبِلَ لَبقيت البايتاتُ في مواضعِها وسقط البرنامجُ عند التشغيل.
#      فالبايتاتُ تقيسُ الإصدار، وهذا يقيسُ الأثر.
#
# (AR) ⚠️ وما لا يقيسه هذا البرهان: **إطلاقَ** الحارسِ على مُستقبِلٍ عدميٍّ فعلًا
#      (خروجٌ ١٣٢). إنشاءُ مُستقبِلٍ عدميٍّ يبلغُ التخفيضَ الأصليَّ يصطدمُ بحرّاسِ
#      العدمِ الساكنةِ في الواجهةِ الأماميّة، فلا مُنتِجَ لهذه الحالةِ اليوم — وهي
#      مُدوَّنةٌ في ISSUE-161 دَينًا مفتوحًا لا فجوةً مسكوتًا عنها.
#
#   الوسيط ١: مجلّدُ الثنائيّات (حيث كُتبت sad_sir_class42 / sad_arm64_class42).
# ============================================================================
set -u
DIR="${1:?usage: prove_class_method.sh <binary-dir>}"
QEMU="$(command -v qemu-aarch64-static || command -v qemu-aarch64 || true)"
FAIL=0

# (AR) يشغّل ثنائيًّا ويؤكّد رمزَ الخروج المتوقَّع. المعاملات: <ملف> <متوقَّع> [مُشغِّل].
run_expect() {
  local bin="$1" want="$2" runner="${3:-}"
  if [ ! -f "$bin" ]; then echo "SKIP: $bin غير موجود"; return; fi
  chmod +x "$bin" 2>/dev/null || true
  if [ -n "$runner" ]; then "$runner" "$bin"; else "$bin"; fi
  local code=$?
  if [ "$code" -eq "$want" ]; then
    echo "PASS: $(basename "$bin") ⇒ $code (متوقَّع $want)"
  else
    echo "FAIL: $(basename "$bin") ⇒ $code (متوقَّع $want)"; FAIL=1
  fi
}

echo "=== x86-64 (نيتيف) ==="
run_expect "$DIR/sad_sir_class42" 42

echo "=== AArch64 (qemu) ==="
if [ -z "$QEMU" ]; then
  echo "SKIP: qemu-aarch64 غير متوفّر — البوّابة التفاضليّة (llvm-mc) هي برهان الصحّة"
else
  run_expect "$DIR/sad_arm64_class42" 42 "$QEMU"
fi

[ "$FAIL" -eq 0 ] && { echo "PASS: نداءُ الطريقةِ يعمل حيًّا بعدَ الحارس (⇒٤٢) على المعماريّتين"; exit 0; } \
                  || { echo "FAIL: خلَلٌ في برهان نداءِ الطريقة"; exit 1; }
