#!/bin/bash
# ============================================================================
# (AR) برهانُ «النصُّ يُسنَد ويُطبَع، والخريطةُ تُنشَأ» حيًّا على المعماريّتين.
#
#      قبلَ هذه الدفعةِ كانت الخلفيّةُ الأصليّةُ تطبع النصَّ **الحرفيَّ** ولا تقبل
#      إسنادَه لمتغيّر: `متغير أ = "مرحبا"` وحدَه يُسقِط الترجمةَ بـ`const-type=4`
#      لأنّ STORE يمرّ بـ`loadInto` الذي يرفض ثوابتَ النصّ، بينما `materializeString`
#      قائمٌ ولم يُستدعَ. وبعدَ فتحِ الإسنادِ ظهر الحاجزُ التالي فورًا: الطباعةُ
#      كانت تعرف الحرفيّةَ (طولُها معلومٌ زمنَ الترجمة) ولا تعرف مؤشّرًا محسوبًا
#      ⇒ `print-str-computed`. فالبرهانُ يقيس الاثنين معًا لأنّ أحدَهما بلا الآخرِ
#      لا أثرَ له في مخرَجِ برنامج.
#
#      والخريطةُ: `متغير خ = {}` كان يُصنَّف «خطأً مترجمًا داخليًّا يُرجى الإبلاغ»
#      (عن ميزةٍ غيرِ منفَّذة) ثمّ صار «غيرَ مدعومٍ بعد» باسمِ المُساعِد، ثمّ صار
#      **منفَّذًا**: إنشاءً وحجمًا، ثمّ إسنادًا مفهرَسًا وقراءةً واحتواءً في هذه
#      الدفعة. تخطيطُ الخريطةِ من مصدرِ الحقيقةِ عينِه الذي يقرؤه مخفّضُ LLVM
#      (`value_repr.yaml`) ⇒ لا يتباعد المُخفِّضان.
#      🔑 وأوّلُ صياغةٍ لحالتَي الخريطةِ لم تكن تُبرهن ما تدّعيه: `mmap` مجهولٌ
#         يُصفّر الكتلةَ، فحقلُ العددِ صفرٌ قبل أيِّ كتابة ⇒ كانتا تخضرّان حتّى لو
#         حُذفت كتاباتُ الترويسةِ كلُّها. أمّا الآن فالكتاباتُ لها **مستهلِكٌ في
#         مخرَجِ برنامج**: قراءةُ `خ["أ"]` تمرّ بمؤشّرَي المفاتيحِ والقيمِ معًا،
#         والحجمُ بعد الإسنادِ يقرأ عدّادًا كُتِب فعلًا ⇒ صار البرهانُ يقيس ما يدّعيه.
#      ⚠️ والسعةُ ساكنةٌ لا تنمو: تُحسَب زمنَ الترجمةِ من عددِ أزواجِ الحرفيّةِ
#         زائدًا عددَ الإسناداتِ المفهرَسةِ في الدالّة. فإسنادٌ في لولبٍ (أو في
#         دالّةٍ أخرى) يتجاوزها ⇒ **إجهاضٌ صريحٌ** برمز ١٣٥ لا إسقاطُ زوجٍ صامت.
#         وحالةُ `map_nine_keys` تحرس الحسابَ الساكنَ عند تجاوزِ أدنى سعة (٨).
#      ⚠️ وما لم يُنفَّذ بعدُ (الحذفُ/المفاتيحُ/القيمُ/الدمجُ) يبقى على تشخيصِه
#         المُسمّى، ولذلك لا حالةَ هنا تدّعيه.
# (EN) Live proof on both targets: a string can be assigned to a variable and
#      printed from it (both halves are needed for any observable effect), and a
#      map can be created and its size read natively. Map layout comes from the
#      same SoT the LLVM lowerer reads. Unimplemented map helpers keep their named
#      diagnostic and are deliberately not asserted here.
#   الوسيط ١: مسارُ sad-build. الوسيط ٢ (اختياريّ): مجلّدُ العمل.
# ============================================================================
set -u
BUILD="${1:?usage: prove_map_and_strings.sh <sad-build-path> [workdir]}"
WORK="${2:-$(mktemp -d)}"
FAIL=0
RAN=0
BUILT=0

# (AR) مجلّدٌ نظيفٌ لكلّ تشغيلة: الوسيطُ ٢ يُعاد استعمالُه عمدًا، وثنائيُّ تشغيلةٍ
#      ماضيةٍ باقٍ يجعل البرهانَ يخضرّ بمترجمٍ **لم يعمل قطّ**. البقايا أخطرُ من
#      الغياب: الغيابُ يُرى، والبقيّةُ تُقرأ نجاحًا.
#      ⚠️ ولا يُمحى إلّا ما يحمل بصمةَ هذا السكربت أو كان فارغًا: الوسيطُ ٢ مسارٌ
#         حرٌّ يكتبه إنسان، وخطأٌ مطبعيٌّ واحدٌ مع `rm -rf` أعمى يبتلع مجلّدًا حقيقيًّا.
STAMP_NAME=".prove_map_and_strings"
# (AR) ما ليس مجلّدًا يُرفَض أوّلًا: شرطُ البصمةِ وحدَه يسقط على مسارِ **ملفّ**
#      فيمرّ `rm -rf` أعمى ويبتلعه. الحارسُ الذي يفوته نوعُ المقصدِ ليس حارسًا.
if [ -e "$WORK" ] && [ ! -d "$WORK" ]; then
  echo "FAIL: «$WORK» موجودٌ وليس مجلّدًا — لن يُمحى"
  exit 1
fi
if [ -d "$WORK" ] && [ ! -e "$WORK/$STAMP_NAME" ] && [ -n "$(ls -A "$WORK" 2>/dev/null)" ]; then
  echo "FAIL: «$WORK» ليس مجلّدَ عملٍ لهذا السكربت (لا بصمة) وليس فارغًا — لن يُمحى"
  exit 1
fi
rm -rf "$WORK"
mkdir -p "$WORK"
: > "$WORK/$STAMP_NAME"

# (AR) على ويندوز (Git Bash) يُترجَم بـsad-build.exe محلّيًّا ويُنفَّذ ثنائيُّ لينكس عبر WSL.
#      المسارُ يُترجَم C:/x ⇒ /mnt/c/x. وعلى لينكس لا وسيطَ ولا ترجمة.
WSLRUN=""
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) WSLRUN="1";; esac
to_linux_path() {
  if [ -n "$WSLRUN" ]; then
    printf '/mnt/%s' "$(cd "$(dirname "$1")" && pwd -W 2>/dev/null | tr 'A-Z' 'a-z' | tr -d ':')/$(basename "$1")"
  else printf '%s' "$1"; fi
}
run_bin() { # <ثنائيّ> [مُشغِّل]
  local bin="$1" runner="${2:-}"
  if [ -n "$WSLRUN" ]; then
    # (AR) مقصدٌ متفرّدٌ لكلّ ثنائيّ: مسارٌ ثابتٌ مشترَكٌ يعني أنّ إخفاقَ النسخِ
    #      يُنفّذ ثنائيَّ الحالةِ السابقة فيُقاس غيرُ المقصود.
    local tgt="/tmp/_pv_$(basename "$bin")"
    wsl.exe -e bash -c "rm -f '$tgt' && cp '$(to_linux_path "$bin")' '$tgt' && chmod +x '$tgt' && ${runner:+$runner }'$tgt'" 2>/dev/null
  elif [ -n "$runner" ]; then "$runner" "$bin" 2>/dev/null
  else "$bin" 2>/dev/null; fi
}

# (AR) qemu قد يكون داخل WSL لا على ويندوز ⇒ ابحث عنه حيث سيُنفَّذ الثنائيّ.
if [ -n "$WSLRUN" ]; then
  QEMU="$(wsl.exe -e bash -c 'command -v qemu-aarch64-static || command -v qemu-aarch64' 2>/dev/null | tr -d '\r')"
else
  QEMU="$(command -v qemu-aarch64-static || command -v qemu-aarch64 || true)"
fi

# (AR) الحالات: «اسم|نوع|المتوقَّع|جسمُ البرنامج». النوعُ `prove` يُفشِل عند الاختلاف،
#      و`known` يقيس ويطبع ولا يُفشِل (عيبٌ مفتوحٌ مُبلَّغٌ لا مسكوتٌ عنه).
#      الرأسُ ثابتٌ في كلّ الحالات: العنصرُ ٠ صحيحٌ (٧) والعنصرُ ١ عشريٌّ (٢٫٥)
#      ⇒ الوسمان مختلفان فيُميّز البرهانُ الفكَّ بالوسمِ عن الفكِّ الأعمى.
#      والاستيرادُ في الرأس لأنّ «جذر» تلزمها «رياضيات» في المفسّر (والخلفيّةُ
#      الأصليّةُ تقبلها بدونها — تباعُدُ إنفاذٍ منفصلٌ خارجَ نطاقِ هذا البرهان)؛
#      واستيرادٌ غيرُ مستعمَلٍ في بقيّةِ الحالات لا أثرَ له.
#      الأجسامُ تُكتَب بـ%b ⇒ تقبل «\n» لأجسامٍ متعدّدةِ الأسطر (شكلُ الفرع).
# (AR) لا رأسَ مشترَكًا: كلُّ حالةٍ مكتفيةٌ بذاتها (الخريطةُ والنصُّ لا يشتركان في حالة).
# (AR) لا رأسَ مشترَكًا: كلُّ حالةٍ مكتفيةٌ بذاتها.
#      «\n» هنا حرفيّةٌ عمدًا: الحالةُ سطرٌ واحدٌ يقرؤه `read`، وسطرٌ فعليٌّ داخلها
#      يقطعه فيضيع بقيّةُ البرنامجِ ويُقاس فراغٌ — وهو ما حدث في أوّلِ صياغة.
HEAD=''
CASES=(
  "str_literal|prove|مرحبا|اطبع_سطر(\"مرحبا\")"
  "str_var|prove|مرحبا|متغير أ = \"مرحبا\"\nاطبع_سطر(أ)"
  "str_var_two|prove|مرحبايا عالم|متغير أ = \"مرحبا\"\nمتغير ب = \"يا عالم\"\nاطبع(أ)\nاطبع_سطر(ب)"
  "str_concat|prove|مرحبا يا عالم|متغير أ = \"مرحبا\"\nمتغير ب = \"يا عالم\"\nاطبع_سطر(أ + \" \" + ب)"
  "str_reassign|prove|ثان|متغير أ = \"أوّل\"\nأ = \"ثان\"\nاطبع_سطر(أ)"
  "str_in_func|prove|مرحبا|دالة رئيسية()\n    متغير أ = \"مرحبا\"\n    اطبع_سطر(أ)\nنهاية"
  "map_empty_size|prove|0|متغير خ = {}\nاطبع_سطر(خ.حجم())"
  "map_empty_size_func|prove|0|دالة رئيسية()\n    متغير خ = {}\n    اطبع_سطر(خ.حجم())\nنهاية"
  "map_set_get|prove|10|دالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 10\n    خ[\"ب\"] = 20\n    اطبع_سطر(خ[\"أ\"])\nنهاية"
  "map_set_get_second|prove|20|دالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 10\n    خ[\"ب\"] = 20\n    اطبع_سطر(خ[\"ب\"])\nنهاية"
  "map_overwrite|prove|99|دالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 10\n    خ[\"أ\"] = 99\n    اطبع_سطر(خ[\"أ\"])\nنهاية"
  # (AR) المفتاحُ الغائب: القناةُ الموسومةُ (__sad_map_get_dyn) تُعيد {فراغ، ٠} فتُطبَع
  #      «لاشيء» — مطابقةً للمفسّرِ وLLVM (اختبار السلوك 104). التوقّعُ القديمُ «0» كان
  #      يقيس قمامةَ القناةِ الخام (تصفيرَ mmap) لا الدلالةَ — بذرةٌ كانت تنطبق ولا تحمرّ.
  "map_missing_key|prove|لاشيء|دالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 10\n    اطبع_سطر(خ[\"ز\"])\nنهاية"
  "map_size_after_set|prove|2|استورد خرائط\nدالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 1\n    خ[\"ب\"] = 2\n    اطبع_سطر(خريطة_حجم(خ))\nنهاية"
  "map_has_hit|prove|صحيح|استورد خرائط\nدالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 1\n    اطبع_سطر(خريطة_تحتوي(خ، \"أ\"))\nنهاية"
  "map_has_miss|prove|خطأ|استورد خرائط\nدالة رئيسية()\n    متغير خ = {}\n    خ[\"أ\"] = 1\n    اطبع_سطر(خريطة_تحتوي(خ، \"ز\"))\nنهاية"
  "map_nine_keys|prove|9|استورد خرائط\nدالة رئيسية()\n    متغير خ = {}\n    خ[\"ا\"] = 1\n    خ[\"ب\"] = 2\n    خ[\"ت\"] = 3\n    خ[\"ث\"] = 4\n    خ[\"ج\"] = 5\n    خ[\"ح\"] = 6\n    خ[\"خ\"] = 7\n    خ[\"د\"] = 8\n    خ[\"ذ\"] = 9\n    اطبع_سطر(خريطة_حجم(خ))\nنهاية"
)

EXPECTED=0
for c in "${CASES[@]}"; do
  IFS='|' read -r name kind want body <<< "$c"
  printf '%b\n%b\n' "$HEAD" "$body" > "$WORK/$name.ص"
  if "$BUILD" "$WORK/$name.ص" --خلفية-أصلية --هدف=x86_64-unknown-linux-gnu  -o "$WORK/$name.x86" >/dev/null 2>&1
  then BUILT=$((BUILT+1)); fi
  if "$BUILD" "$WORK/$name.ص" --خلفية-أصلية --هدف=aarch64-unknown-linux-gnu -o "$WORK/$name.arm" >/dev/null 2>&1
  then BUILT=$((BUILT+1)); fi
  { [ "$kind" = "prove" ] || [ "$kind" = "panic" ]; } && EXPECTED=$((EXPECTED+2))
done

# (AR) صفرُ ترجمةٍ ناجحةٍ ⇒ لا مترجمَ أصلًا: أَبْلِغ قبل أن تُقرأ الـSKIPات نجاحًا.
if [ "$BUILT" -eq 0 ]; then
  echo "FAIL: لم تنجح أيُّ ترجمة — تحقّق من مسار sad-build («$BUILD»)"; exit 1
fi

check() { # <اسم> <لاحقة> <نوع> <متوقَّع> [مُشغِّل]
  local bin="$WORK/$1.$2" kind="$3" want="$4" runner="${5:-}" got rc
  if [ ! -f "$bin" ]; then echo "SKIP: $1.$2 لم يُترجَم"; return; fi
  chmod +x "$bin" 2>/dev/null || true
  got="$(run_bin "$bin" "$runner")"
  rc=$?
  # (AR) `panic` يقيس **رمزَ الخروج** لا المخرَج: النفيُ على وسمٍ غيرِ عدديٍّ إجهاضٌ
  #      متعمَّدٌ (١٣٣)، والبديلُ عنه جوابٌ خاطئٌ صامتٌ («‑صحيح = صحيح») أو سقوطٌ بإشارة ١١.
  if [ "$kind" = "panic" ]; then
    RAN=$((RAN+1))
    if [ "$rc" -eq "$want" ]; then echo "PASS(هلع): $1.$2 ⇒ رمز $rc"
    else echo "FAIL(هلع): $1.$2 ⇒ رمز $rc ومخرَج «$got» (متوقَّع رمز $want)"; FAIL=1; fi
    return
  fi
  if [ "$kind" = "known" ]; then
    if [ "$got" = "$want" ]; then echo "GREEN(عيبٌ أُصلِح): $1.$2 ⇒ «$got»"
    else echo "KNOWN-BUG: $1.$2 ⇒ «$got» (الصحيحُ «$want»)"; fi
    return
  fi
  RAN=$((RAN+1))
  # (AR) المخرَجُ وحدَه لا يكفي: ثنائيٌّ يطبع الجوابَ الصحيحَ ثمّ يسقط يُقرأ PASS.
  #      فرمزُ الخروجِ جزءٌ من الأوراكل — والحالاتُ هنا كلُّها تطبع ثمّ تخرج بـ٠.
  if [ "$rc" -ne 0 ]; then echo "FAIL: $1.$2 ⇒ «$got» ورمزُ الخروجِ $rc (متوقَّع ٠)"; FAIL=1; return; fi
  if [ "$got" = "$want" ]; then echo "PASS: $1.$2 ⇒ «$got»"
  else echo "FAIL: $1.$2 ⇒ «$got» (متوقَّع «$want»)"; FAIL=1; fi
}

echo "=== x86-64 (نيتيف) ==="
for c in "${CASES[@]}"; do
  IFS='|' read -r name kind want body <<< "$c"
  check "$name" x86 "$kind" "$want"
done

echo "=== AArch64 (qemu) ==="
if [ -z "$QEMU" ]; then
  echo "SKIP: qemu-aarch64 غير متوفّر"
else
  for c in "${CASES[@]}"; do
    IFS='|' read -r name kind want body <<< "$c"
    check "$name" arm "$kind" "$want" "$QEMU"
  done
fi

# (AR) الحدُّ = كلُّ حالةٍ حاسمةٍ × معماريّتين، لا صفرٌ ولا واحد: السكربتُ يدّعي
#      برهانًا **على المعماريّتين**، فنجاحٌ بنصفِ الحالاتِ المنفَّذة (qemu غائبٌ
#      مثلًا، وهو الحالُ الشائع) يعلن ما لم يُقَس. وأخضرُ بلا قياسٍ هو ما يُخفي
#      العيبَ لا ما يكشفه. (حالاتُ `known` لا تُعَدّ: تقيس ولا تُبرهن.)
if [ "$RAN" -lt "$EXPECTED" ]; then
  echo "FAIL: نُفِّذ $RAN من $EXPECTED — لا برهانَ كاملًا (تحقّق من المترجم/WSL/qemu)"
  exit 1
fi
N=$((EXPECTED/2))
# (AR) تمييزُ العددِ عربيًّا: ٣–١٠ جمعُ قلّةٍ («حالاتٍ»)، وما عداه مفردٌ منصوب.
if [ "$N" -ge 3 ] && [ "$N" -le 10 ]; then UNIT="حالاتٍ"; else UNIT="حالةً"; fi
[ "$FAIL" -eq 0 ] && { echo "PASS: النصُّ يُسنَد ويُطبَع من متغيّرٍ، وحجمُ الخريطةِ الفارغةِ يُقرَأ ($RAN تنفيذًا = $N $UNIT × معماريّتين)"; exit 0; } \
                  || { echo "FAIL: تباعُدٌ في إسنادِ النصّ أو طباعتِه أو في الخريطةِ الأصليّة"; exit 1; }
