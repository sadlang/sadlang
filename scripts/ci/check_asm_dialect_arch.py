#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""(AR) حارسُ بوّابةِ المعماريّة للهجةِ التجميع — الوسمُ يُقاس على مصدرِ الحقيقة.

ما الذي يحرسه ولماذا (العلّةُ مقيسةٌ في ١٩ آب ٢٠٢٦):
    لهجةُ «تجميع» كانت تُعلن `architectures: [i686]` بينما المترجّمُ يخفض كتلَها
    إلى منمناتِ i686 **لأيِّ هدف**، بلا ذكرٍ واحدٍ للمعماريّةِ في خافضِ الكتلة.
    فعلى macos-14-arm64 ماتت ثمانيةُ اختباراتٍ موجبةٍ في المُجمِّعِ نفسِه، ومرّ
    اثنا عشرَ اختبارًا سالبًا **بحقّ** — مرساةُ كلٍّ منها رمزُ خطأٍ دلاليٍّ يسبق
    التوليد. أي أنّ الأخضرَ كان يقيس الطبقةَ الدلاليّةَ وحدَها، والأحمرَ يأتي من
    طبقةٍ لم يحرسها أحد.

العقدُ المحروس — وهو على **الوسمِ مقابلَ المعجم** لا على النيّة:
    ١) قائمةُ `architectures` في assembly.yaml تطابق ملفّاتِ assembly_mnemonics/
       في الاتّجاهين: معماريّةٌ مُعلَنةٌ بلا معجمٍ دعوى بلا سند، ومعجمٌ غيرُ مُعلَنٍ
       ميزةٌ لا يعرف بها أحد.
    ٢) كلُّ ملفٍّ في القائمةِ مذكورٌ في وسائطِ المولّدِ في x.py — وإلّا صار المعجمُ
       مكتوبًا وغيرَ مُولَّد.
    ٣) لكلِّ اختبارٍ **موجب**: مجموعةُ `@arch` تساوي بالضبطِ المعماريّاتِ التي
       تقبلها كلُّ سطورِه. أضيقُ من ذلك يُخفي تغطيةً (اختبارٌ محمولٌ لا يُقاسُ إلّا
       على منصّةٍ واحدة)، وأوسعُ يُحمِّر على منصّةٍ لا يصلح لها.
    ٤) ولكلِّ اختبارٍ **سالب**: إن استعمل اسمًا معجميًّا غيرَ محمولٍ على المعماريّاتِ
       كلِّها فلا بدّ من وسمٍ صريح — لأنّ الاسمَ غيرَ المحمولِ يُبدِّل **رمزَ الخطأِ
       المقيس** من معماريّةٍ إلى أخرى (SEM034 هنا وSEM025 هناك)، فيبقى الاختبارُ
       أخضرَ وهو يقيس شيئًا آخر.

🔑 والحكمُ **بعددِ المعاملاتِ لا بوجودِ الاسم**: مسحًا أوّلَ كان الحارسُ يقيس وجودَ
    الاسمِ وحدَه، فقال عن «اضرب {ناتج}، {ب}» إنّها محمولةٌ على المعماريّاتِ الثلاث —
    والاسمُ موجودٌ فيها فعلًا، لكنّه أحاديُّ المعاملِ على x86 (بكتاباتٍ ضمنيّة)
    وثلاثيٌّ على AArch64. فوجودُ الاسمِ ليس صلاحيّةَ الاستعمال، والعقدُ الحقيقيُّ
    هو **الشكل**.

⚠️ لماذا لا تُفرَض المساواةُ على السالب:
    السالبُ قد يستعمل اسمًا **عمدًا** لأنّه غائبٌ عن معماريّةِ الهدفِ (062: منمنمةُ
    x86 تُرفَض على AArch64). فمساواةُ المجموعتَين هناك تقلب القصدَ رأسًا على عقب.

(EN) Architecture-gate guard for the assembly dialect: the @arch tag is measured
     against the SoT lexicons — by operand SHAPE, not merely by name existence —
     in both directions, so a tag can neither hide coverage nor promise an
     architecture the lexicon cannot serve.
"""
import io
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    print("::error::pyyaml غيرُ مثبَّت — لا يمكن قراءةُ مصدرِ الحقيقة")
    sys.exit(1)

جذر_اللهجة = Path("language-truth/dialects")
جذر_المعاجم = جذر_اللهجة / "assembly_mnemonics"
جذر_الاختبارات = Path("tests/behavior/rules_matrix/60_advanced/gr.adv.asm_dialect")
# ⚠️ (AR) واختباراتُ التداخلِ خارجَ مجلّدِ القاعدة: تُنسَب إليها بوسمِ @rule لا
#      بموضعِها. ومجلّدُ القاعدةِ وحدَه كان سيترك بابًا مفتوحًا — كتلةُ «تجميع»
#      داخلَ حلقةٍ في `_interactions/` تسكن مكانًا آخر ويحكمها العقدُ نفسُه.
# (EN) Interaction tests live outside the rule directory and are bound to it by
#      the @rule tag, not by location — scanning only the directory left a hole.
جذر_التداخلات = Path("tests/behavior/rules_matrix/_interactions")
معرّف_القاعدة = "gr.adv.asm_dialect"
نمط_القاعدة = re.compile(r"^#\s*@rule:?\s+(.+)$", re.M)
ملف_البناء = Path("x.py")

# (AR) أسماءٌ عائليّةٌ يقبلها الوسمُ اختصارًا — تُفكّ قبل المقارنة.
عائلات = {"x86": ("i686", "x86_64")}

نمط_الوسم = re.compile(r"^#\s*@arch:?\s+([^#\n]+)", re.M)
نمط_سالب = re.compile(r"^#\s*@expect_error\b|^#\s*@expect_compile_error\b"
                      r"|^#\s*@expect_error_compiled\b", re.M)
نمط_معرّف = re.compile(r"[^\s،,\{\}\(\)\[\]\+\*:]+")
أسطر_الرأس = 25


def جرّد_التشكيل(نصّ: str) -> str:
    """(AR) يحذف U+064B..U+065F — المفتاحُ القانونيُّ مجرَّدٌ كما يُصدره المُشكِّل."""
    return "".join(ح for ح in نصّ if not (0x064B <= ord(ح) <= 0x065F))


def افتح(مسار: Path) -> str:
    return io.open(مسار, encoding="utf-8", errors="replace").read()


def اقرأ_المعاجم() -> dict:
    """(AR) معرّفُ المعماريّة ⇒ {منمنمة ⇒ عددُ معاملاتِها} و{أسماءُ سجلّاتِها}."""
    جداول = {}
    for ملف in sorted(جذر_المعاجم.glob("*.yaml")):
        بيانات = yaml.safe_load(افتح(ملف))
        منمنمات = {}
        for قائمة in بيانات["instructions"].values():
            for تعليمة in قائمة:
                منمنمات[جرّد_التشكيل(تعليمة["ar"])] = len(تعليمة["operands"])
        سجلات = {جرّد_التشكيل(س["ar"])
                 for قائمة in بيانات["registers"].values() for س in قائمة}
        جداول[بيانات["architecture"]] = (منمنمات, سجلات)
    return جداول


def حلّل_الكتل(نصّ: str):
    """(AR) يُخرج (منمنمةٌ، عددُ معاملاتِها) وأسماءَ المعاملاتِ المجرَّدةَ من كتلِ اللهجة.

    ⚠️ لا محلّلَ نحويًّا هنا ولا حاجةَ إليه: كلُّ اسمٍ لا وجودَ له في أيِّ معجمٍ
       يُهمَل لاحقًا (لصائقُ القفزِ، وأسماءُ ص المربوطة، والأسماءُ الخطأُ في السوالب).
    """
    تعليمات = []
    أسماء = set()
    داخل = False
    for سطر in نصّ.split("\n"):
        نظيف = سطر.split("#")[0].strip()
        if not نظيف:
            continue
        if not داخل:
            if نظيف == "تجميع" or نظيف.startswith("تجميع "):
                داخل = True
            continue
        if نظيف == "نهاية":
            داخل = False
            continue
        # (AR) لصيقةٌ «اسم:» قد تسبق تعليمةً في السطر نفسِه — تُنزَع أوّلًا.
        قطع = نظيف.split(":", 1)
        if len(قطع) == 2 and قطع[0].strip() and " " not in قطع[0].strip():
            نظيف = قطع[1].strip()
            if not نظيف:
                continue
        # (AR) بندُ «يلوّث(…)»: أهدافُه أسماءٌ لا تعليمةٌ ذاتُ معاملات.
        if نظيف.startswith("يلوث") or نظيف.startswith("يلوّث"):
            أسماء.update(جرّد_التشكيل(م) for م in نمط_معرّف.findall(نظيف)[1:])
            continue
        أجزاء = نظيف.split(None, 1)
        منمنمة = جرّد_التشكيل(أجزاء[0])
        بقيّة = أجزاء[1] if len(أجزاء) > 1 else ""
        معاملات = [ج for ج in re.split(r"[،,]", بقيّة) if ج.strip()]
        تعليمات.append((منمنمة, len(معاملات)))
        for معامل in معاملات:
            أسماء.update(جرّد_التشكيل(م) for م in نمط_معرّف.findall(معامل))
    return تعليمات, أسماء


def فكّ_الوسم(خام: str) -> list:
    خرج = []
    for قطعة in خام.replace(",", " ").split():
        مفتاح = قطعة.strip().lower()
        خرج.extend(عائلات.get(مفتاح, (مفتاح,)))
    return sorted(set(خرج))


def افحص_مصدر_الحقيقة(جداول: dict) -> list:
    مخالفات = []
    لهجة = yaml.safe_load(افتح(جذر_اللهجة / "assembly.yaml"))
    مُعلَنة = sorted(لهجة.get("architectures", []))
    مُلَفَّة = sorted(جداول)
    if مُعلَنة != مُلَفَّة:
        مخالفات.append(
            ((جذر_اللهجة / "assembly.yaml").as_posix(),
             "architectures " + str(مُعلَنة) + " لا تطابق ملفّاتِ المعجم " + str(مُلَفَّة)))
    بناء = افتح(ملف_البناء)
    for معماريّة in مُلَفَّة:
        مسار = "assembly_mnemonics/" + معماريّة + ".yaml"
        if مسار not in بناء:
            مخالفات.append((ملف_البناء.as_posix(),
                            "معجمُ «" + معماريّة + "» غيرُ ممرَّرٍ إلى المولّد — مكتوبٌ ولا يُولَّد"))
    return مخالفات


def افحص_الاختبارات(جداول: dict) -> list:
    مخالفات = []
    كلّ_المعماريّات = set(جداول)
    كلّ_الأسماء = set()
    for منمنمات, سجلات in جداول.values():
        كلّ_الأسماء |= set(منمنمات) | سجلات

    ملفّات = list(جذر_الاختبارات.rglob("*.ص"))
    for مرشّح in جذر_التداخلات.rglob("*.ص"):
        رأس_مرشّح = افتح(مرشّح)
        وسم_قاعدة = نمط_القاعدة.search(رأس_مرشّح)
        if وسم_قاعدة and معرّف_القاعدة in وسم_قاعدة.group(1):
            ملفّات.append(مرشّح)

    for ملف in sorted(ملفّات):
        نصّ = افتح(ملف)
        رأس = "\n".join(نصّ.split("\n")[:أسطر_الرأس])
        وسم = نمط_الوسم.search(رأس)
        موسومة = فكّ_الوسم(وسم.group(1)) if وسم else []
        مجهولة = [أ for أ in موسومة if أ not in كلّ_المعماريّات]
        if مجهولة:
            مخالفات.append((ملف.as_posix(),
                            "@arch يذكر معماريّةً لا معجمَ لها: " + "، ".join(مجهولة)))
            continue

        تعليمات, أسماء = حلّل_الكتل(نصّ)
        معروفة = {اسم for اسم in أسماء if اسم in كلّ_الأسماء}
        مقيَّدة = [(م, ع) for م, ع in تعليمات if م in كلّ_الأسماء]
        if not معروفة and not مقيَّدة:
            continue

        صالحة = set()
        for معماريّة, (منمنمات, سجلات) in جداول.items():
            محلّيّ = set(منمنمات) | سجلات
            if all(اسم in محلّيّ for اسم in معروفة) and \
               all(منمنمات.get(م) == ع for م, ع in مقيَّدة):
                صالحة.add(معماريّة)

        سالب = bool(نمط_سالب.search(نصّ))
        if سالب:
            # (AR) السالبُ يكفيه وسمٌ صريحٌ متى كان اسمٌ غيرَ محمول — لا مساواة.
            if صالحة != كلّ_المعماريّات and not موسومة:
                غير_محمولة = sorted(
                    اسم for اسم in معروفة
                    if any(اسم not in (set(م) | س) for م, س in جداول.values()))
                مخالفات.append(
                    (ملف.as_posix(),
                     "اختبارٌ سالبٌ يستعمل اسمًا غيرَ محمول (" + "، ".join(غير_محمولة) +
                     ") بلا @arch — رمزُ الخطأِ المقيسُ يتبدّل بين المعماريّات صامتًا"))
            continue

        متوقَّعة = sorted(صالحة)
        محمول = متوقَّعة == sorted(كلّ_المعماريّات)
        # (AR) المحمولُ يبقى **بلا وسم** فيُقاس على المنصّاتِ كلِّها؛ ووسمٌ عليه
        #      يُخفي تغطيةً بلا أن يُحمِّر شيئًا — وهو الصنفُ الذي لا يكشفه إلّا حارس.
        # (EN) A portable test must stay untagged; tagging it hides coverage silently.
        مخالف = (موسومة != []) if محمول else (موسومة != متوقَّعة)
        if مخالف:
            سبب = ("بلا @arch" if not موسومة else "@arch " + " ".join(موسومة))
            مخالفات.append(
                (ملف.as_posix(),
                 سبب + " — والمقيسُ من المعجم: " +
                 (" ".join(متوقَّعة) if متوقَّعة else "لا معماريّةَ تصلح") +
                 (" (محمولٌ فلا وسمَ له)" if محمول else "")))
    return مخالفات


def main() -> int:
    if not جذر_المعاجم.is_dir():
        print("::error::" + جذر_المعاجم.as_posix() + " غيرُ موجود")
        return 1
    جداول = اقرأ_المعاجم()
    if not جداول:
        print("::error::صفرُ معجمٍ قُرِئ — الحارسُ نفسُه أعمى")
        return 1

    مخالفات = افحص_مصدر_الحقيقة(جداول) + افحص_الاختبارات(جداول)
    if not مخالفات:
        print("✅ حارسُ بوّابةِ المعماريّة: " + str(len(جداول)) + " معجمًا (" +
              "، ".join(sorted(جداول)) + ") ووسومُ الاختباراتِ مطابقةٌ لها")
        return 0

    print("❌ حارسُ بوّابةِ المعماريّة — " + str(len(مخالفات)) + " مخالفة:")
    for مسار, سبب in مخالفات:
        print("   " + مسار)
        print("      " + سبب)
        print("::error file=" + مسار + "::" + سبب)
    return 1


if __name__ == "__main__":
    sys.exit(main())
