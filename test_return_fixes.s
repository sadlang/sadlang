# اختبار إصلاحات return
# 1. الفاصلة المنقوطة اختيارية بعد ارجع
# 2. التحقق من نوع الإرجاع
# =====================================================

اطبع("=== اختبار 1: ارجع مع فاصلة منقوطة ===")
دالة رقم test1()
    ارجع 5;
نهاية
رقم نتيجة1 = test1()
اطبع("النتيجة = ")
اطبع(نتيجة1)

اطبع("\n=== اختبار 2: ارجع بدون فاصلة منقوطة ===")
دالة رقم test2()
    ارجع 10
نهاية
رقم نتيجة2 = test2()
اطبع("النتيجة = ")
اطبع(نتيجة2)

اطبع("\n=== اختبار 3: عدة return في دالة واحدة ===")
دالة رقم test3(رقم x)
    إذا (x > 0)
        ارجع 1
    نهاية
    ارجع 0
نهاية
رقم نتيجة3 = test3(5)
اطبع("النتيجة للقيمة الموجبة = ")
اطبع(نتيجة3)
رقم نتيجة4 = test3(-3)
اطبع("النتيجة للقيمة السالبة = ")
اطبع(نتيجة4)

اطبع("\n=== اختبار 4: دالة بدون نوع إرجاع ترجع قيمة (يجب أن تعطي خطأ) ===")
دالة مرحبا()
    اطبع("السلام عليكم")
    ارجع 10
نهاية

رقم ص = مرحبا()
اطبع(ص)
