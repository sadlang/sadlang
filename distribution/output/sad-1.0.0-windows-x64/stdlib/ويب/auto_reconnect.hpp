/**
 * استراتيجية الانتظار
 */
enum class استراتيجية_انتظار {
    ثابت,              // نفس الوقت دائماً
    خطي,               // زيادة ثابتة
    أسي,               // مضاعفة (Exponential)
    أسي_مع_عشوائية     // مضاعفة + عشوائية (الأفضل!)
};

/**
 * إعدادات إعادة الاتصال
 */
struct إعدادات_إعادة_اتصال {
    // الانتظار الأولي (1 ثانية افتراضياً)
    std::chrono::milliseconds انتظار_أولي{1000};
    
    // أقصى انتظار (30 ثانية افتراضياً)
    std::chrono::milliseconds أقصى_انتظار{30000};
    
    // أقصى عدد محاولات (0 = لا نهائي)
    int أقصى_محاولات = 0;
    
    // المضاعف للـ Exponential (2.0 = مضاعفة)
    double مضاعف = 2.0;
    
    // نسبة العشوائية (0.1 = ±10%)
    double نسبة_عشوائية = 0.1;
    
    // الاستراتيجية
    استراتيجية_انتظار الاستراتيجية = استراتيجية_انتظار::أسي_مع_عشوائية;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              حاسب الانتظار
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حاسب وقت الانتظار
 * 
 * يحسب كم ثانية ننتظر قبل المحاولة التالية
 */
class حاسب_انتظار {
public:
    explicit حاسب_انتظار(const إعدادات_إعادة_اتصال& إعدادات)
        : الإعدادات_(إعدادات), المحاولة_الحالية_(0) {
        
        // مولد أرقام عشوائية
        std::random_device rd;
        المولد_ = std::mt19937(rd());
        التوزيع_ = std::uniform_real_distribution<double>(
            1.0 - إعدادات.نسبة_عشوائية,
            1.0 + إعدادات.نسبة_عشوائية
        );
    }
    
    /**
     * احصل على وقت الانتظار التالي
     */
    std::chrono::milliseconds الانتظار_التالي() {
        المحاولة_الحالية_++;
        
        double انتظار_ms = 0;
        
        switch (الإعدادات_.الاستراتيجية) {
            case استراتيجية_انتظار::ثابت:
                // دائماً نفس الوقت
                انتظار_ms = الإعدادات_.انتظار_أولي.count();
                break;
                
            case استراتيجية_انتظار::خطي:
                // زيادة خطية: 1, 2, 3, 4...
                انتظار_ms = الإعدادات_.انتظار_أولي.count() * المحاولة_الحالية_;
                break;
                
            case استراتيجية_انتظار::أسي:
                // مضاعفة: 1, 2, 4, 8, 16...
                انتظار_ms = الإعدادات_.انتظار_أولي.count() * 
                           std::pow(الإعدادات_.مضاعف, المحاولة_الحالية_ - 1);
                break;
                
            case استراتيجية_انتظار::أسي_مع_عشوائية:
                // مضاعفة + عشوائية
                انتظار_ms = الإعدادات_.انتظار_أولي.count() * 
                           std::pow(الإعدادات_.مضاعف, المحاولة_الحالية_ - 1);
                انتظار_ms *= التوزيع_(المولد_);  // ±10%
                break;
        }
        
        // لا تتجاوز الحد الأقصى
        انتظار_ms = std::min(انتظار_ms, (double)الإعدادات_.أقصى_انتظار.count());
        
        return std::chrono::milliseconds(static_cast<long long>(انتظار_ms));
    }
    
    /**
     * هل يمكننا المحاولة مرة أخرى؟
     */
    bool يمكن_المحاولة() const {
        if (الإعدادات_.أقصى_محاولات == 0) {
            return true;  // لا نهائي
        }
        return المحاولة_الحالية_ < الإعدادات_.أقصى_محاولات;
    }
    
    /**
     * إعادة التعيين (بعد اتصال ناجح)
     */
    void أعد_التعيين() {
        المحاولة_الحالية_ = 0;
    }
    
    /**
     * رقم المحاولة الحالية
     */
    int المحاولة_الحالية() const {
        return المحاولة_الحالية_;
    }
    
private:
    إعدادات_إعادة_اتصال الإعدادات_;
    int المحاولة_الحالية_;
    
    std::mt19937 المولد_;
    std::uniform_real_distribution<double> التوزيع_;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مدير إعادة الاتصال
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حالة الاتصال
 */
enum class حالة_اتصال {
    متصل,              // الاتصال يعمل
    غير_متصل,          // لا يوجد اتصال
    يحاول_الاتصال,     // جاري المحاولة
    متوقف              // توقف يدوياً
};

/**
 * مدير إعادة الاتصال التلقائية
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │              مدير إعادة الاتصال                        │
 *     │                                                        │
 *     │   الحالة الحالية: متصل ✓                               │
 *     │                                                        │
 *     │   ┌──────────────────────────────────────────────┐    │
 *     │   │ الأحداث:                                     │    │
 *     │   │                                              │    │
 *     │   │   عند_انقطاع ────→ ابدأ إعادة الاتصال       │    │
 *     │   │   عند_محاولة ────→ سجل المحاولة            │    │
 *     │   │   عند_نجاح ──────→ استأنف العمل             │    │
 *     │   │   عند_فشل_نهائي ─→ أبلغ المستخدم           │    │
 *     │   │                                              │    │
 *     │   └──────────────────────────────────────────────┘    │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
class مدير_إعادة_اتصال {
public:
    // أنواع المعالجات
    using دالة_اتصال = std::function<bool()>;
    using معالج_حدث = std::function<void()>;
    using معالج_محاولة = std::function<void(int محاولة, std::chrono::milliseconds انتظار)>;
    
    explicit مدير_إعادة_اتصال(
        const إعدادات_إعادة_اتصال& إعدادات = إعدادات_إعادة_اتصال{}
    ) : الإعدادات_(إعدادات), الحاسب_(إعدادات), الحالة_(حالة_اتصال::غير_متصل) {}
    
    /**
     * تعيين دالة الاتصال
     */
    void عند_محاولة_اتصال(دالة_اتصال دالة) {
        دالة_الاتصال_ = دالة;
    }
    
    /**
     * معالج حدث الاتصال
     */
    void عند_الاتصال(معالج_حدث معالج) {
        معالج_اتصال_ = معالج;
    }
    
    /**
     * معالج حدث الانقطاع
     */
    void عند_الانقطاع(معالج_حدث معالج) {
        معالج_انقطاع_ = معالج;
    }
    
    /**
     * معالج المحاولة
     */
    void عند_المحاولة(معالج_محاولة معالج) {
        معالج_محاولة_ = معالج;
    }
    
    /**
     * معالج الفشل النهائي
     */
    void عند_فشل_نهائي(معالج_حدث معالج) {
        معالج_فشل_نهائي_ = معالج;
    }
    
    /**
     * الإبلاغ عن انقطاع الاتصال
     */
    void انقطع_الاتصال() {
        الحالة_ = حالة_اتصال::غير_متصل;
        
        if (معالج_انقطاع_) {
            معالج_انقطاع_();
        }
        
        // ابدأ إعادة الاتصال
        ابدأ_إعادة_الاتصال();
    }
    
    /**
     * بدء إعادة الاتصال
     */
    void ابدأ_إعادة_الاتصال() {
        if (!دالة_الاتصال_) {
            return;
        }
        
        الحالة_ = حالة_اتصال::يحاول_الاتصال;
        يجب_إيقاف_ = false;
        
        while (!يجب_إيقاف_ && الحاسب_.يمكن_المحاولة()) {
            auto انتظار = الحاسب_.الانتظار_التالي();
            
            // إبلاغ عن المحاولة
            if (معالج_محاولة_) {
                معالج_محاولة_(الحاسب_.المحاولة_الحالية(), انتظار);
            }
            
            // انتظر
            std::this_thread::sleep_for(انتظار);
            
            // حاول الاتصال
            if (دالة_الاتصال_()) {
                // نجح!
                الحالة_ = حالة_اتصال::متصل;
                الحاسب_.أعد_التعيين();
                
                if (معالج_اتصال_) {
                    معالج_اتصال_();
                }
                
                return;
            }
        }
        
        // فشل نهائي
        الحالة_ = حالة_اتصال::غير_متصل;
        
        if (معالج_فشل_نهائي_) {
            معالج_فشل_نهائي_();
        }
    }
    
    /**
     * إيقاف المحاولات
     */
    void أوقف() {
        يجب_إيقاف_ = true;
        الحالة_ = حالة_اتصال::متوقف;
    }
    
    /**
     * الحالة الحالية
     */
    حالة_اتصال الحالة() const {
        return الحالة_;
    }
    
    /**
     * هل متصل؟
     */
    bool متصل() const {
        return الحالة_ == حالة_اتصال::متصل;
    }
    
private:
    إعدادات_إعادة_اتصال الإعدادات_;
    حاسب_انتظار الحاسب_;
    std::atomic<حالة_اتصال> الحالة_;
    std::atomic<bool> يجب_إيقاف_{false};
    
    دالة_اتصال دالة_الاتصال_;
    معالج_حدث معالج_اتصال_;
    معالج_حدث معالج_انقطاع_;
    معالج_محاولة معالج_محاولة_;
    معالج_حدث معالج_فشل_نهائي_;
};

