/**
 * اتصال WebSocket مع إعادة اتصال تلقائية
 */
class اتصال_مستمر {
public:
    using معالج_رسالة = std::function<void(const std::string&)>;
    using دالة_اتصال = std::function<bool(const std::string&)>;
    using دالة_إرسال = std::function<bool(const std::string&)>;
    
    explicit اتصال_مستمر(
        const std::string& عنوان,
        const إعدادات_إعادة_اتصال& إعدادات = إعدادات_إعادة_اتصال{}
    ) : العنوان_(عنوان), المدير_(إعدادات) {
        
        المدير_.عند_محاولة_اتصال([this]() {
            return حاول_الاتصال_داخلي();
        });
        
        المدير_.عند_الاتصال([this]() {
            // أعد إرسال الرسائل المُعلَّقة
            أرسل_المُعلَّقة();
        });
    }
    
    /**
     * تعيين دالة الاتصال
     */
    void حدد_دالة_اتصال(دالة_اتصال دالة) {
        دالة_الاتصال_ = دالة;
    }
    
    /**
     * تعيين دالة الإرسال
     */
    void حدد_دالة_إرسال(دالة_إرسال دالة) {
        دالة_الإرسال_ = دالة;
    }
    
    /**
     * الاتصال
     */
    bool اتصل() {
        if (حاول_الاتصال_داخلي()) {
            return true;
        }
        
        المدير_.ابدأ_إعادة_الاتصال();
        return المدير_.متصل();
    }
    
    /**
     * إرسال رسالة (مع تخزين إذا غير متصل)
     */
    bool أرسل(const std::string& رسالة) {
        if (المدير_.متصل() && دالة_الإرسال_) {
            return دالة_الإرسال_(رسالة);
        }
        
        // خزّن للإرسال لاحقاً
        رسائل_مُعلَّقة_.push_back(رسالة);
        return false;
    }
    
    /**
     * الإبلاغ عن انقطاع
     */
    void انقطع() {
        المدير_.انقطع_الاتصال();
    }
    
    /**
     * الوصول للمدير
     */
    مدير_إعادة_اتصال& المدير() { return المدير_; }
    
private:
    bool حاول_الاتصال_داخلي() {
        if (دالة_الاتصال_) {
            return دالة_الاتصال_(العنوان_);
        }
        return false;
    }
    
    void أرسل_المُعلَّقة() {
        if (!دالة_الإرسال_) return;
        
        for (const auto& رسالة : رسائل_مُعلَّقة_) {
            دالة_الإرسال_(رسالة);
        }
        رسائل_مُعلَّقة_.clear();
    }
    
    std::string العنوان_;
    مدير_إعادة_اتصال المدير_;
    
    دالة_اتصال دالة_الاتصال_;
    دالة_إرسال دالة_الإرسال_;
    
    std::vector<std::string> رسائل_مُعلَّقة_;
};

