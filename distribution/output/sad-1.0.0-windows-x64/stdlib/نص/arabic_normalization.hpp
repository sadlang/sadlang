/**
 * مُقارن للنصوص العربية مع دعم التطبيع
 */
class مُقارن_عربي {
public:
    /**
     * مقارنة أساسية (بدون تطبيع)
     */
    static int قارن(const std::string& أ, const std::string& ب) {
        return أ.compare(ب);
    }
    
    /**
     * مقارنة مُطبَّعة
     */
    static int قارن_مُطبَّع(
        const std::string& أ, 
        const std::string& ب,
        const خيارات_تطبيع& خيارات = خيارات_تطبيع::للبحث()
    ) {
        مُطبِّع م(خيارات);
        return م.طبّع(أ).compare(م.طبّع(ب));
    }
    
    /**
     * فرز قائمة نصوص عربية
     */
    static void رتّب(
        std::vector<std::string>& قائمة,
        bool تطبيع = true
    ) {
        if (تطبيع) {
            مُطبِّع م(خيارات_تطبيع::للبحث());
            std::sort(قائمة.begin(), قائمة.end(),
                [&م](const std::string& أ, const std::string& ب) {
                    return م.طبّع(أ) < م.طبّع(ب);
                });
        }
        else {
            std::sort(قائمة.begin(), قائمة.end());
        }
    }
    
    /**
     * تشابه النصين (0.0 - 1.0)
     */
    static double تشابه(
        const std::string& أ,
        const std::string& ب,
        bool تطبيع = true
    ) {
        std::string نص_أ = أ;
        std::string نص_ب = ب;
        
        if (تطبيع) {
            مُطبِّع م(خيارات_تطبيع::للبحث());
            نص_أ = م.طبّع(أ);
            نص_ب = م.طبّع(ب);
        }
        
        if (نص_أ == نص_ب) return 1.0;
        if (نص_أ.empty() || نص_ب.empty()) return 0.0;
        
        // حساب مسافة Levenshtein مبسطة
        size_t الأطول = std::max(نص_أ.size(), نص_ب.size());
        size_t المسافة = مسافة_levenshtein(نص_أ, نص_ب);
        
        return 1.0 - (static_cast<double>(المسافة) / الأطول);
    }
    
private:
    static size_t مسافة_levenshtein(
        const std::string& أ,
        const std::string& ب
    ) {
        std::vector<std::vector<size_t>> م(
            أ.size() + 1,
            std::vector<size_t>(ب.size() + 1)
        );
        
        for (size_t i = 0; i <= أ.size(); i++) م[i][0] = i;
        for (size_t j = 0; j <= ب.size(); j++) م[0][j] = j;
        
        for (size_t i = 1; i <= أ.size(); i++) {
            for (size_t j = 1; j <= ب.size(); j++) {
                size_t تكلفة = (أ[i-1] == ب[j-1]) ? 0 : 1;
                م[i][j] = std::min({
                    م[i-1][j] + 1,      // حذف
                    م[i][j-1] + 1,      // إدراج
                    م[i-1][j-1] + تكلفة // استبدال
                });
            }
        }
        
        return م[أ.size()][ب.size()];
    }
};

