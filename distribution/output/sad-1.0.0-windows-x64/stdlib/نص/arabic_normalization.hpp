/**
 * خيارات التطبيع
 */
struct خيارات_تطبيع {
    bool إزالة_التشكيل = true;      // إزالة الحركات
    bool توحيد_الألفات = true;      // إأآ → ا
    bool توحيد_الياء = true;        // ى → ي
    bool توحيد_الهاء = false;       // ة → ه (قد يغير المعنى)
    bool إزالة_التطويل = true;      // إزالة ـ
    bool إزالة_الفراغات_الزائدة = true;
    bool حذف_أرقام_عربية = false;   // تحويل ٠١٢ → 012
    bool صغير_للكبير = false;       // لا يؤثر على العربية
    
    // إعدادات مسبقة
    static خيارات_تطبيع للبحث() {
        خيارات_تطبيع خ;
        خ.إزالة_التشكيل = true;
        خ.توحيد_الألفات = true;
        خ.توحيد_الياء = true;
        خ.توحيد_الهاء = true;
        خ.إزالة_التطويل = true;
        return خ;
    }
    
    static خيارات_تطبيع للعرض() {
        خيارات_تطبيع خ;
        خ.إزالة_التشكيل = false;
        خ.توحيد_الألفات = false;
        خ.توحيد_الياء = false;
        خ.توحيد_الهاء = false;
        خ.إزالة_التطويل = true;
        return خ;
    }
    
    static خيارات_تطبيع للتخزين() {
        خيارات_تطبيع خ;
        خ.إزالة_التشكيل = true;
        خ.توحيد_الألفات = true;
        خ.توحيد_الياء = true;
        خ.توحيد_الهاء = false;
        خ.إزالة_التطويل = true;
        خ.إزالة_الفراغات_الزائدة = true;
        return خ;
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُطبِّع النصوص العربية
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مُطبِّع النصوص العربية
 */
class مُطبِّع {
public:
    مُطبِّع(const خيارات_تطبيع& خيارات = خيارات_تطبيع())
        : الخيارات_(خيارات) {}
    
    /**
     * تطبيع نص
     */
    std::string طبّع(const std::string& نص) const {
        std::string نتيجة;
        size_t موقع = 0;
        bool فراغ_سابق = true;  // لمنع الفراغات في البداية
        
        while (موقع < نص.size()) {
            char32_t حرف = اقرأ_حرف_utf8(نص, موقع);
            
            // إزالة التشكيل
            if (الخيارات_.إزالة_التشكيل && تشكيل(حرف)) {
                continue;
            }
            
            // إزالة التطويل
            if (الخيارات_.إزالة_التطويل && حرف == 0x0640) {
                continue;
            }
            
            // توحيد الألفات
            if (الخيارات_.توحيد_الألفات) {
                حرف = وحّد_ألف(حرف);
            }
            
            // توحيد الياء
            if (الخيارات_.توحيد_الياء && حرف == 0x0649) {
                حرف = 0x064A;  // ى → ي
            }
            
            // توحيد الهاء
            if (الخيارات_.توحيد_الهاء && حرف == 0x0629) {
                حرف = 0x0647;  // ة → ه
            }
            
            // تحويل الأرقام العربية
            if (الخيارات_.حذف_أرقام_عربية) {
                حرف = وحّد_رقم(حرف);
            }
            
            // معالجة الفراغات
            if (حرف == ' ' || حرف == '\t' || حرف == '\n') {
                if (الخيارات_.إزالة_الفراغات_الزائدة) {
                    if (فراغ_سابق) continue;
                    فراغ_سابق = true;
                    نتيجة += ' ';
                }
                else {
                    نتيجة += حرف_إلى_utf8(حرف);
                }
                continue;
            }
            
            فراغ_سابق = false;
            نتيجة += حرف_إلى_utf8(حرف);
        }
        
        // إزالة الفراغ في النهاية
        if (الخيارات_.إزالة_الفراغات_الزائدة && 
            !نتيجة.empty() && نتيجة.back() == ' ') {
            نتيجة.pop_back();
        }
        
        return نتيجة;
    }
    
    /**
     * مقارنة مُطبَّعة
     */
    bool متساويان(const std::string& أ, const std::string& ب) const {
        return طبّع(أ) == طبّع(ب);
    }
    
    /**
     * البحث بتطبيع
     */
    bool يحتوي(const std::string& نص, const std::string& بحث) const {
        return طبّع(نص).find(طبّع(بحث)) != std::string::npos;
    }
    
private:
    char32_t اقرأ_حرف_utf8(const std::string& نص, size_t& موقع) const {
        unsigned char أول = نص[موقع++];
        
        if ((أول & 0x80) == 0) return أول;
        else if ((أول & 0xE0) == 0xC0) {
            char32_t رمز = (أول & 0x1F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else if ((أول & 0xF0) == 0xE0) {
            char32_t رمز = (أول & 0x0F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else {
            char32_t رمز = (أول & 0x07) << 18;
            رمز |= (نص[موقع++] & 0x3F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
    }
    
    std::string حرف_إلى_utf8(char32_t رمز) const {
        std::string نتيجة;
        if (رمز < 0x80) {
            نتيجة += static_cast<char>(رمز);
        }
        else if (رمز < 0x800) {
            نتيجة += static_cast<char>(0xC0 | (رمز >> 6));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        else if (رمز < 0x10000) {
            نتيجة += static_cast<char>(0xE0 | (رمز >> 12));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 6) & 0x3F));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        else {
            نتيجة += static_cast<char>(0xF0 | (رمز >> 18));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 12) & 0x3F));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 6) & 0x3F));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        return نتيجة;
    }
    
    bool تشكيل(char32_t حرف) const {
        return (حرف >= 0x064B && حرف <= 0x0652) ||  // تشكيل أساسي
               (حرف >= 0x0653 && حرف <= 0x0655) ||  // همزة وصل ومدة
               حرف == 0x0670;                        // ألف خنجرية
    }
    
    char32_t وحّد_ألف(char32_t حرف) const {
        // جميع أشكال الألف تصبح ألف عادية
        switch (حرف) {
            case 0x0622:  // آ - ألف مد
            case 0x0623:  // أ - ألف همزة فوق
            case 0x0625:  // إ - ألف همزة تحت
            case 0x0671:  // ٱ - ألف وصل
                return 0x0627;  // ا
            default:
                return حرف;
        }
    }
    
    char32_t وحّد_رقم(char32_t حرف) const {
        // تحويل الأرقام العربية-الهندية إلى أرقام غربية
        if (حرف >= 0x0660 && حرف <= 0x0669) {
            return '0' + (حرف - 0x0660);
        }
        // الأرقام الفارسية
        if (حرف >= 0x06F0 && حرف <= 0x06F9) {
            return '0' + (حرف - 0x06F0);
        }
        return حرف;
    }
    
    خيارات_تطبيع الخيارات_;
};

