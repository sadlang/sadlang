/**
 * نص مُدار بواسطة Pool
 * 
 * يبدو مثل std::string لكنه يستخدم Pool داخلياً
 */
class نص_مُدار {
public:
    نص_مُدار() = default;
    
    نص_مُدار(const std::string& نص)
        : المعرف_(string_pool::العام().أضف(نص)) {}
    
    نص_مُدار(const char* نص)
        : المعرف_(string_pool::العام().أضف(نص)) {}
    
    // الحصول على النص
    const std::string& إلى_نص() const {
        return string_pool::العام().احصل(المعرف_);
    }
    
    // المعرف
    معرف_نص المعرف() const { return المعرف_; }
    
    // تحويل ضمني
    operator const std::string&() const {
        return إلى_نص();
    }
    
    // الطول
    size_t الطول() const { return إلى_نص().size(); }
    
    // فارغ؟
    bool فارغ() const { return المعرف_.فارغ(); }
    
    // مقارنات
    bool operator==(const نص_مُدار& آخر) const {
        return المعرف_ == آخر.المعرف_;
    }
    
    bool operator!=(const نص_مُدار& آخر) const {
        return المعرف_ != آخر.المعرف_;
    }
    
    bool operator<(const نص_مُدار& آخر) const {
        return المعرف_ < آخر.المعرف_;
    }
    
    // للاستخدام في خرائط التجزئة
    struct تجزئة {
        size_t operator()(const نص_مُدار& ن) const {
            return معرف_نص::تجزئة{}(ن.المعرف_);
        }
    };
    
private:
    معرف_نص المعرف_;
};

