/**
 * معرف نص مُخزَّن في Pool
 * 
 * بدلاً من تخزين النص كاملاً، نخزن رقمه فقط!
 */
class معرف_نص {
public:
    معرف_نص() : القيمة_(0) {}
    explicit معرف_نص(uint32_t قيمة) : القيمة_(قيمة) {}
    
    // الوصول للقيمة
    uint32_t القيمة() const { return القيمة_; }
    
    // فارغ؟
    bool فارغ() const { return القيمة_ == 0; }
    
    // مقارنة
    bool operator==(const معرف_نص& آخر) const {
        return القيمة_ == آخر.القيمة_;
    }
    
    bool operator!=(const معرف_نص& آخر) const {
        return القيمة_ != آخر.القيمة_;
    }
    
    bool operator<(const معرف_نص& آخر) const {
        return القيمة_ < آخر.القيمة_;
    }
    
    // للاستخدام في خرائط التجزئة
    struct تجزئة {
        size_t operator()(const معرف_نص& م) const {
            return std::hash<uint32_t>{}(م.القيمة_);
        }
    };
    
private:
    uint32_t القيمة_;
};

