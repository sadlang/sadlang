/**
 * Pool للنصوص العربية
 * 
 * يخزن كل نص مرة واحدة فقط ويُعيد معرفاً صغيراً
 */
class string_pool {
public:
    /**
     * الحصول على المثيل العام
     */
    static string_pool& العام() {
        static string_pool مثيل;
        return مثيل;
    }
    
    /**
     * إضافة نص وإرجاع معرفه
     * 
     * إذا كان النص موجوداً، يُرجع معرفه الحالي
     * إذا لم يكن موجوداً، يُضيفه ويُرجع معرفاً جديداً
     */
    معرف_نص أضف(const std::string& نص) {
        std::lock_guard<std::mutex> قفل(المُزامن_);
        
        // هل النص موجود؟
        auto it = خريطة_المعرفات_.find(نص);
        if (it != خريطة_المعرفات_.end()) {
            return it->second;
        }
        
        // أضف النص
        uint32_t معرف = العداد_++;
        النصوص_.push_back(نص);
        خريطة_المعرفات_[نص] = معرف_نص(معرف);
        
        return معرف_نص(معرف);
    }
    
    /**
     * الحصول على النص من معرفه
     */
    const std::string& احصل(معرف_نص معرف) const {
        static const std::string فارغ;
        
        if (معرف.القيمة() == 0 || معرف.القيمة() > النصوص_.size()) {
            return فارغ;
        }
        
        return النصوص_[معرف.القيمة() - 1];
    }
    
    /**
     * البحث عن معرف نص
     */
    معرف_نص ابحث(const std::string& نص) const {
        std::lock_guard<std::mutex> قفل(المُزامن_);
        
        auto it = خريطة_المعرفات_.find(نص);
        if (it != خريطة_المعرفات_.end()) {
            return it->second;
        }
        
        return معرف_نص();  // فارغ
    }
    
    /**
     * عدد النصوص المخزنة
     */
    size_t الحجم() const {
        return النصوص_.size();
    }
    
    /**
     * حجم الذاكرة المستخدمة
     */
    size_t حجم_الذاكرة() const {
        size_t حجم = 0;
        for (const auto& نص : النصوص_) {
            حجم += نص.capacity();
        }
        حجم += خريطة_المعرفات_.size() * 
               (sizeof(std::string) + sizeof(معرف_نص));
        return حجم;
    }
    
    /**
     * مسح كل النصوص
     */
    void امسح() {
        std::lock_guard<std::mutex> قفل(المُزامن_);
        النصوص_.clear();
        خريطة_المعرفات_.clear();
        العداد_ = 1;
    }
    
    /**
     * إحصائيات
     */
    struct إحصائيات {
        size_t عدد_النصوص;
        size_t حجم_الذاكرة;
        size_t متوسط_طول_النص;
        size_t أطول_نص;
    };
    
    إحصائيات الإحصائيات() const {
        إحصائيات إ;
        إ.عدد_النصوص = النصوص_.size();
        إ.حجم_الذاكرة = حجم_الذاكرة();
        
        size_t مجموع_الأطوال = 0;
        إ.أطول_نص = 0;
        
        for (const auto& نص : النصوص_) {
            مجموع_الأطوال += نص.size();
            if (نص.size() > إ.أطول_نص) {
                إ.أطول_نص = نص.size();
            }
        }
        
        إ.متوسط_طول_النص = النصوص_.empty() ? 0 : 
                          مجموع_الأطوال / النصوص_.size();
        
        return إ;
    }
    
private:
    string_pool() : العداد_(1) {}
    
    mutable std::mutex المُزامن_;
    std::vector<std::string> النصوص_;
    std::unordered_map<std::string, معرف_نص> خريطة_المعرفات_;
    std::atomic<uint32_t> العداد_;
};

