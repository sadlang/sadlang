/**
 * جذر عربي
 */
struct جذر {
    std::vector<char32_t> الحروف;  // حروف الجذر
    
    جذر() = default;
    
    جذر(const std::string& نص) {
        // تحليل الجذر من نص مثل "ك-ت-ب" أو "كتب"
        for (size_t i = 0; i < نص.size();) {
            if (نص[i] == '-' || نص[i] == ' ') {
                i++;
                continue;
            }
            
            // قراءة حرف UTF-8
            char32_t حرف = اقرأ_حرف_utf8(نص, i);
            if (حرف_عربي(حرف)) {
                الحروف.push_back(حرف);
            }
        }
    }
    
    // تحويل إلى نص
    std::string إلى_نص() const {
        std::string نتيجة;
        for (size_t i = 0; i < الحروف.size(); i++) {
            if (i > 0) نتيجة += "-";
            نتيجة += حرف_إلى_utf8(الحروف[i]);
        }
        return نتيجة;
    }
    
    // عدد الحروف
    size_t الطول() const { return الحروف.size(); }
    
    // مقارنة
    bool operator==(const جذر& آخر) const {
        return الحروف == آخر.الحروف;
    }
    
    bool operator<(const جذر& آخر) const {
        return الحروف < آخر.الحروف;
    }
    
private:
    static char32_t اقرأ_حرف_utf8(const std::string& نص, size_t& موقع) {
        unsigned char أول = نص[موقع++];
        
        if ((أول & 0x80) == 0) {
            return أول;
        }
        else if ((أول & 0xE0) == 0xC0) {
            char32_t رمز = (أول & 0x1F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else if ((أول & 0xF0) == 0xE0) {
            char32_t رمز = (أول & 0x0F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else {
            char32_t رمز = (أول & 0x07) << 18;
            رمز |= (نص[موقع++] & 0x3F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
    }
    
    static bool حرف_عربي(char32_t حرف) {
        return (حرف >= 0x0621 && حرف <= 0x064A) ||
               (حرف >= 0x0660 && حرف <= 0x0669);  // أرقام عربية
    }
    
    static std::string حرف_إلى_utf8(char32_t رمز) {
        std::string نتيجة;
        if (رمز < 0x80) {
            نتيجة += static_cast<char>(رمز);
        }
        else if (رمز < 0x800) {
            نتيجة += static_cast<char>(0xC0 | (رمز >> 6));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        else if (رمز < 0x10000) {
            نتيجة += static_cast<char>(0xE0 | (رمز >> 12));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 6) & 0x3F));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        return نتيجة;
    }
};

