/**
 * مستخرج الجذور من الكلمات
 */
class مُستخرج_جذور {
public:
    /**
     * استخراج الجذر من كلمة
     */
    std::optional<جذر> استخرج(const std::string& كلمة) const {
        // تحويل الكلمة إلى حروف
        std::vector<char32_t> حروف = حلل_حروف(كلمة);
        
        // إزالة الزوائد
        حروف = أزل_الزوائد(حروف);
        
        // يجب أن يبقى 3 حروف على الأقل
        if (حروف.size() < 3) {
            return std::nullopt;
        }
        
        // إنشاء الجذر
        جذر ج;
        // أخذ الحروف الثلاثة الأولى (تبسيط)
        for (size_t i = 0; i < 3 && i < حروف.size(); i++) {
            ج.الحروف.push_back(حروف[i]);
        }
        
        return ج;
    }
    
private:
    std::vector<char32_t> حلل_حروف(const std::string& نص) const {
        std::vector<char32_t> حروف;
        size_t i = 0;
        
        while (i < نص.size()) {
            char32_t حرف = اقرأ_حرف_utf8(نص, i);
            
            // تجاهل التشكيل
            if (!تشكيل(حرف) && حرف_عربي_أساسي(حرف)) {
                حروف.push_back(حرف_أساسي(حرف));
            }
        }
        
        return حروف;
    }
    
    std::vector<char32_t> أزل_الزوائد(std::vector<char32_t> حروف) const {
        // الزوائد الشائعة في البداية
        static const std::set<char32_t> زوائد_بداية = {
            0x0627,  // ا
            0x0648,  // و
            0x064A,  // ي
            0x062A,  // ت
            0x0646,  // ن
            0x0645,  // م
            0x0633,  // س
        };
        
        // الزوائد الشائعة في النهاية
        static const std::set<char32_t> زوائد_نهاية = {
            0x0627,  // ا
            0x0648,  // و
            0x064A,  // ي
            0x0646,  // ن
            0x0629,  // ة
            0x062A,  // ت
        };
        
        // إزالة الزوائد من البداية
        while (حروف.size() > 3 && 
               زوائد_بداية.count(حروف.front())) {
            حروف.erase(حروف.begin());
        }
        
        // إزالة الزوائد من النهاية
        while (حروف.size() > 3 && 
               زوائد_نهاية.count(حروف.back())) {
            حروف.pop_back();
        }
        
        return حروف;
    }
    
    char32_t اقرأ_حرف_utf8(const std::string& نص, size_t& موقع) const {
        unsigned char أول = نص[موقع++];
        
        if ((أول & 0x80) == 0) return أول;
        else if ((أول & 0xE0) == 0xC0) {
            char32_t رمز = (أول & 0x1F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else if ((أول & 0xF0) == 0xE0) {
            char32_t رمز = (أول & 0x0F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else {
            char32_t رمز = (أول & 0x07) << 18;
            رمز |= (نص[موقع++] & 0x3F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
    }
    
    bool تشكيل(char32_t حرف) const {
        return حرف >= 0x064B && حرف <= 0x0652;
    }
    
    bool حرف_عربي_أساسي(char32_t حرف) const {
        return (حرف >= 0x0621 && حرف <= 0x064A);
    }
    
    char32_t حرف_أساسي(char32_t حرف) const {
        // تحويل أشكال الألف إلى ألف أساسي
        if (حرف == 0x0622 || حرف == 0x0623 || 
            حرف == 0x0625 || حرف == 0x0671) {
            return 0x0627;  // ا
        }
        // ى → ي
        if (حرف == 0x0649) {
            return 0x064A;  // ي
        }
        // ة → ت
        if (حرف == 0x0629) {
            return 0x062A;  // ت
        }
        return حرف;
    }
};

