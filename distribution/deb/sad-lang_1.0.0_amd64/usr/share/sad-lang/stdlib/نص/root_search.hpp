/**
 * فهرس للبحث بالجذور
 */
class فهرس_جذور {
public:
    /**
     * إضافة كلمة للفهرس
     */
    void أضف(const std::string& كلمة) {
        auto ج = المُستخرج_.استخرج(كلمة);
        if (ج) {
            الفهرس_[*ج].insert(كلمة);
        }
    }
    
    /**
     * إضافة نص كامل
     */
    void فهرس_نص(const std::string& نص) {
        std::string كلمة;
        
        for (size_t i = 0; i < نص.size();) {
            char32_t حرف = اقرأ_حرف_utf8(نص, i);
            
            if (حرف_عربي(حرف) || تشكيل(حرف)) {
                كلمة += حرف_إلى_utf8(حرف);
            }
            else {
                if (!كلمة.empty()) {
                    أضف(كلمة);
                    كلمة.clear();
                }
            }
        }
        
        if (!كلمة.empty()) {
            أضف(كلمة);
        }
    }
    
    /**
     * البحث بالجذر
     */
    std::vector<std::string> ابحث(const جذر& ج) const {
        std::vector<std::string> نتائج;
        
        auto it = الفهرس_.find(ج);
        if (it != الفهرس_.end()) {
            for (const auto& كلمة : it->second) {
                نتائج.push_back(كلمة);
            }
        }
        
        return نتائج;
    }
    
    /**
     * البحث بنص الجذر
     */
    std::vector<std::string> ابحث(const std::string& نص_جذر) const {
        return ابحث(جذر(نص_جذر));
    }
    
    /**
     * عدد الجذور في الفهرس
     */
    size_t عدد_الجذور() const { return الفهرس_.size(); }
    
    /**
     * جميع الجذور
     */
    std::vector<جذر> كل_الجذور() const {
        std::vector<جذر> نتائج;
        for (const auto& [ج, _] : الفهرس_) {
            نتائج.push_back(ج);
        }
        return نتائج;
    }
    
private:
    char32_t اقرأ_حرف_utf8(const std::string& نص, size_t& موقع) const {
        unsigned char أول = نص[موقع++];
        if ((أول & 0x80) == 0) return أول;
        else if ((أول & 0xE0) == 0xC0) {
            char32_t رمز = (أول & 0x1F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else if ((أول & 0xF0) == 0xE0) {
            char32_t رمز = (أول & 0x0F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        char32_t رمز = (أول & 0x07) << 18;
        رمز |= (نص[موقع++] & 0x3F) << 12;
        رمز |= (نص[موقع++] & 0x3F) << 6;
        رمز |= (نص[موقع++] & 0x3F);
        return رمز;
    }
    
    std::string حرف_إلى_utf8(char32_t رمز) const {
        std::string نتيجة;
        if (رمز < 0x80) نتيجة += static_cast<char>(رمز);
        else if (رمز < 0x800) {
            نتيجة += static_cast<char>(0xC0 | (رمز >> 6));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        else if (رمز < 0x10000) {
            نتيجة += static_cast<char>(0xE0 | (رمز >> 12));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 6) & 0x3F));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        return نتيجة;
    }
    
    bool حرف_عربي(char32_t حرف) const {
        return (حرف >= 0x0621 && حرف <= 0x064A);
    }
    
    bool تشكيل(char32_t حرف) const {
        return حرف >= 0x064B && حرف <= 0x0652;
    }
    
    مُستخرج_جذور المُستخرج_;
    std::map<جذر, std::set<std::string>> الفهرس_;
};

