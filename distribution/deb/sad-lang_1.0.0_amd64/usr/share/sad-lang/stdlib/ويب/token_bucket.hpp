/**
 * خوارزمية Token Bucket
 */
class دلو_عملات {
public:
    /**
     * إنشاء دلو عملات
     * 
     * @param السعة: الحد الأقصى من العملات
     * @param معدل_الإضافة: عدد العملات المضافة في الثانية
     */
    دلو_عملات(double السعة, double معدل_الإضافة)
        : m_السعة(السعة),
          m_معدل_الإضافة(معدل_الإضافة),
          m_العملات(السعة),  // نبدأ ممتلئين
          m_آخر_تحديث(std::chrono::steady_clock::now()) {}
    
    /**
     * محاولة استهلاك عملات
     * 
     * @param عدد: عدد العملات المطلوبة
     * @return true إذا نجح، false إذا لا توجد عملات كافية
     */
    bool استهلك(double عدد = 1.0) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        أعد_الملء();
        
        if (m_العملات >= عدد) {
            m_العملات -= عدد;
            return true;
        }
        
        return false;
    }
    
    /**
     * محاولة استهلاك مع انتظار
     * 
     * @param عدد: عدد العملات المطلوبة
     * @param أقصى_انتظار: أقصى وقت للانتظار
     * @return true إذا نجح، false إذا انتهى الوقت
     */
    bool استهلك_مع_انتظار(double عدد, std::chrono::milliseconds أقصى_انتظار) {
        auto البداية = std::chrono::steady_clock::now();
        
        while (true) {
            if (استهلك(عدد)) {
                return true;
            }
            
            // تحقق من انتهاء الوقت
            auto الآن = std::chrono::steady_clock::now();
            auto مضى = std::chrono::duration_cast<std::chrono::milliseconds>(الآن - البداية);
            
            if (مضى >= أقصى_انتظار) {
                return false;
            }
            
            // انتظر قليلاً قبل المحاولة مرة أخرى
            std::this_thread::sleep_for(std::chrono::milliseconds(10));
        }
    }
    
    /**
     * الحصول على عدد العملات الحالي
     */
    double العملات_المتاحة() {
        std::lock_guard<std::mutex> قفل(m_قفل);
        أعد_الملء();
        return m_العملات;
    }
    
    /**
     * الحصول على السعة القصوى
     */
    double السعة() const {
        return m_السعة;
    }
    
    /**
     * الوقت حتى تتوفر عملة واحدة
     */
    std::chrono::milliseconds وقت_الانتظار() {
        std::lock_guard<std::mutex> قفل(m_قفل);
        أعد_الملء();
        
        if (m_العملات >= 1.0) {
            return std::chrono::milliseconds(0);
        }
        
        double مطلوب = 1.0 - m_العملات;
        double ثواني = مطلوب / m_معدل_الإضافة;
        
        return std::chrono::milliseconds(static_cast<int>(ثواني * 1000));
    }
    
private:
    double m_السعة;
    double m_معدل_الإضافة;
    double m_العملات;
    std::chrono::steady_clock::time_point m_آخر_تحديث;
    std::mutex m_قفل;
    
    /**
     * إعادة ملء الدلو بناءً على الوقت المنقضي
     */
    void أعد_الملء() {
        auto الآن = std::chrono::steady_clock::now();
        auto مضى = std::chrono::duration<double>(الآن - m_آخر_تحديث).count();
        
        m_العملات = std::min(m_السعة, m_العملات + مضى * m_معدل_الإضافة);
        m_آخر_تحديث = الآن;
    }
};

