# Example 3: Multiple Type Guards

دالة تحقق_وعالج(س)
    # فحص null أولاً
    إذا (س == فارغ)
        عرض("القيمة فارغة")
        إرجاع "فارغ"
    نهاية
    
    # الآن نعرف أن س ليست فارغة
    # فلنتحقق من نوعها
    نوع_س = نوع(س)
    
    إذا (نوع_س == "رقم")
        عرض("رقم: ")
        عرض(س)
        نتيجة = "رقم: " + نص(س)
        إرجاع نتيجة
    وإلا
        عرض("نص: ")
        عرض(س)
        نتيجة = "نص: " + نص(س)
        إرجاع نتيجة
    نهاية
نهاية

