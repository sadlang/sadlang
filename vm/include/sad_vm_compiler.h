// ============================================================================
// sad_vm_compiler.h - مُترجم AST إلى بايت كود
// AST to Bytecode Compiler for Sad Language VM (لغة ص)
// ============================================================================
//
// الوصف:
//   هذا هو الجسر بين الواجهة الأمامية المشتركة (Lexer → Parser → AST)
//   والآلة الافتراضية. يأخذ شجرة AST ويُنتج وحدة بايت كود.
//
// كيف يعمل:
//   1. يتلقى قائمة الجمل (statements) من الـ Parser
//   2. يجتاز كل عقدة AST باستخدام نمط الزائر (Visitor Pattern)
//   3. لكل عقدة، يُصدر تعليمات البايت كود المقابلة
//   4. يُدير جدول المتغيرات والنطاقات (scopes)
//   5. يُنتج وحدة بايت كود جاهزة للتنفيذ
//
// مثال على سير العمل:
//   كود ص:        متغير س = 5 + 3
//   AST:          VarDeclStmt("س", BinaryExpr(Lit(5), +, Lit(3)))
//   بايت كود:     CONST 0 (5)    → دفع 5
//                  CONST 1 (3)    → دفع 3
//                  ADD            → جمع: 8
//                  STORE_LOCAL 0  → تخزين في "س"
//
// ============================================================================

#pragma once

#include "sad_vm_chunk.h"
#include "sad_vm_opcodes.h"
#include "sad_vm_value.h"

// تضمين ملفات AST المشتركة
#include "ast_node.h"
#include "ast_visitor.h"
#include "expressions.h"
#include "statements.h"
#include "declarations.h"
#include "class_nodes.h"

#include <string>
#include <vector>
#include <unordered_map>
#include <stack>
#include <memory>

namespace sad {
namespace vm {

// ============================================================================
// معلومات المتغير المحلي
// ============================================================================
// المتغيرات المحلية تُخزّن في مصفوفة مفهرسة داخل إطار الاستدعاء.
// نحتاج لتتبع اسمها وعمق نطاقها لحل التبديل الصحيح.
// ============================================================================

struct متغير_محلي {
    std::string الاسم;       ///< اسم المتغير كما ظهر في الكود
    int العمق;               ///< عمق النطاق (0 = الأعلى في الدالة الحالية)
    bool ثابت;               ///< هل هو ثابت (const)؟
    bool محتجز;              ///< هل يُحتجز بواسطة إغلاق (closure)؟

    متغير_محلي(const std::string& اسم, int عمق, bool ثابت = false)
        : الاسم(اسم), العمق(عمق), ثابت(ثابت), محتجز(false) {}
};

// ============================================================================
// معلومات القيمة العلوية (Upvalue) - للإغلاقات
// ============================================================================

struct معلومات_علوية {
    uint8_t الفهرس;          ///< فهرس المتغير (محلي أو علوي في الدالة المحيطة)
    bool محلي;               ///< هل هو متغير محلي في الدالة المحيطة مباشرة؟
};

// ============================================================================
// نطاق الحلقة - لدعم "توقف" (break) و"استمر" (continue)
// ============================================================================

struct نطاق_حلقة {
    uint32_t بداية;                          ///< عنوان بداية الحلقة (لـ "استمر")
    std::vector<uint32_t> قفزات_التوقف;     ///< قفزات "توقف" تحتاج تصحيح
};

// ============================================================================
// سياق الترجمة - يُغلّف حالة ترجمة دالة واحدة
// ============================================================================
// كل دالة لها سياقها الخاص: متغيراتها المحلية، عمق النطاق، إلخ.
// عند دخول دالة متداخلة، نُنشئ سياقاً جديداً ونعود للسابق عند الخروج.
// ============================================================================

struct سياق_الترجمة {
    std::string اسم_الدالة;                              ///< اسم الدالة الحالية
    std::vector<متغير_محلي> المحليات;                    ///< المتغيرات المحلية
    std::vector<معلومات_علوية> العلويات;                  ///< القيم العلوية
    std::vector<نطاق_حلقة> الحلقات;                      ///< مكدس الحلقات النشطة
    int عمق_النطاق;                                      ///< عمق النطاق الحالي
    int عدد_المحليات_القصوى;                              ///< أقصى عدد محليات (لتخصيص الإطار)

    سياق_الترجمة* الأب;                                  ///< السياق المحيط (للإغلاقات)

    سياق_الترجمة()
        : عمق_النطاق(0), عدد_المحليات_القصوى(0), الأب(nullptr) {}
};

// ============================================================================
// مُترجم البايت كود الرئيسي
// ============================================================================
//
// يُنفّذ نمط الزائر (Visitor) على شجرة AST ويُصدر البايت كود.
// يتعامل مع:
//   - التعابير: حسابية، منطقية، نصية، استدعاء دوال
//   - الجمل: تصريحات متغيرات، إذا/وإلا، بينما، لكل
//   - التصريحات: دوال، أصناف، وراثة
//   - النطاقات: متغيرات محلية وعامة، إغلاقات
//
// ============================================================================

class مُترجم_بايت_كود {
public:
    مُترجم_بايت_كود();
    ~مُترجم_بايت_كود();

    // ========================================================================
    // الواجهة الرئيسية
    // ========================================================================

    /// ترجمة قائمة جمل (برنامج كامل) إلى وحدة بايت كود
    /// هذه هي نقطة الدخول الرئيسية.
    /// @param الجمل قائمة الجمل من الـ Parser
    /// @param اسم_الوحدة اسم ملف المصدر (للتصحيح)
    /// @return وحدة البايت كود المُترجمة
    وحدة_بايت_كود ترجم(
        const std::vector<std::unique_ptr<Sad::AST::Statement>>& الجمل,
        const std::string& اسم_الوحدة = "<رئيسي>"
    );

    /// هل حدثت أخطاء أثناء الترجمة؟
    bool يوجد_أخطاء() const { return !الأخطاء_.empty(); }

    /// الحصول على قائمة الأخطاء
    const std::vector<std::string>& الأخطاء() const { return الأخطاء_; }

private:
    وحدة_بايت_كود* الوحدة_;                              ///< الوحدة الحالية
    سياق_الترجمة* السياق_;                                ///< سياق الترجمة الحالي
    std::vector<std::string> الأخطاء_;                     ///< أخطاء الترجمة

    // ========================================================================
    // ترجمة الجمل (Statements)
    // ========================================================================

    /// ترجمة جملة واحدة (النقطة المركزية لتوزيع الجمل)
    void ترجم_جملة(Sad::AST::Statement* جملة);

    /// ترجمة كتلة جمل (block)
    void ترجم_كتلة(Sad::AST::BlockStmt* كتلة);

    /// ترجمة جملة تصريح متغير: "متغير س = تعبير" أو "ثابت ص = تعبير"
    void ترجم_تصريح_متغير(Sad::AST::VarDeclStmt* تصريح);

    /// ترجمة جملة تعبير: "اطبع(...)" أو "دالة() "
    void ترجم_جملة_تعبير(Sad::AST::ExprStmt* جملة);

    /// ترجمة جملة "إذا" / "وإلا"
    void ترجم_إذا(Sad::AST::IfStmt* جملة);

    /// ترجمة جملة "بينما"
    void ترجم_بينما(Sad::AST::WhileStmt* جملة);

    /// ترجمة جملة "لكل" (for)
    void ترجم_لكل(Sad::AST::ForStmt* جملة);

    /// ترجمة جملة "لكل في" (for-range)
    void ترجم_لكل_في(Sad::AST::ForRangeStmt* جملة);

    /// ترجمة جملة "ارجع"
    void ترجم_إرجاع(Sad::AST::ReturnStmt* جملة);

    /// ترجمة جملة "توقف" (break)
    void ترجم_توقف(Sad::AST::BreakStmt* جملة);

    /// ترجمة جملة "استمر" (continue)
    void ترجم_استمر(Sad::AST::ContinueStmt* جملة);

    /// ترجمة تصريح دالة
    void ترجم_تصريح_دالة(Sad::AST::FunctionDecl* تصريح);

    /// ترجمة تصريح صنف
    void ترجم_تصريح_صنف(Sad::AST::ClassDecl* تصريح);

    /// ترجمة جملة "حاول/امسك" (try/catch)
    void ترجم_حاول(Sad::AST::TryStmt* جملة);

    // ========================================================================
    // ترجمة التعابير (Expressions)
    // ========================================================================
    // كل تعبير يترك نتيجته على قمة المكدس.
    // ========================================================================

    /// ترجمة تعبير واحد (النقطة المركزية لتوزيع التعابير)
    void ترجم_تعبير(Sad::AST::Expression* تعبير);

    /// ترجمة تعبير ثنائي: أ + ب، أ > ب، أ و ب
    void ترجم_ثنائي(Sad::AST::BinaryExpr* تعبير);

    /// ترجمة تعبير أحادي: -أ، !أ
    void ترجم_أحادي(Sad::AST::UnaryExpr* تعبير);

    /// ترجمة قيمة حرفية: 42، "نص"، صحيح
    void ترجم_حرفي(Sad::AST::LiteralExpr* تعبير);

    /// ترجمة مرجع متغير: س (تحميل قيمة المتغير)
    void ترجم_متغير(Sad::AST::VariableExpr* تعبير);

    /// ترجمة إسناد: س = تعبير
    void ترجم_إسناد(Sad::AST::AssignExpr* تعبير);

    /// ترجمة استدعاء دالة: دالة(مع1، مع2)
    void ترجم_استدعاء(Sad::AST::CallExpr* تعبير);

    /// ترجمة تعبير مصفوفة حرفية: [1، 2، 3]
    void ترجم_مصفوفة(Sad::AST::ArrayExpr* تعبير);

    /// ترجمة فهرسة مصفوفة: م[ف]
    void ترجم_فهرسة(Sad::AST::IndexExpr* تعبير);

    /// ترجمة الوصول لعضو: كائن.حقل
    void ترجم_عضو(Sad::AST::MemberExpr* تعبير);

    /// ترجمة إسناد لعضو: كائن.حقل = قيمة
    void ترجم_إسناد_عضو(Sad::AST::MemberAssignExpr* تعبير);

    /// ترجمة إنشاء كائن جديد: جديد صنف(...)
    void ترجم_جديد(Sad::AST::NewExpr* تعبير);

    /// ترجمة "هذا" (this)
    void ترجم_هذا(Sad::AST::ThisExpr* تعبير);

    /// ترجمة لامدا (دالة مجهولة)
    void ترجم_لامدا(Sad::AST::LambdaExpr* تعبير);

    // ========================================================================
    // إدارة المتغيرات والنطاقات
    // ========================================================================

    /// بدء نطاق جديد (عند دخول كتلة {})
    void ادخل_نطاق();

    /// إنهاء النطاق الحالي (عند خروج من كتلة {})
    /// يُصدر تعليمات سحب للمتغيرات المحلية في هذا النطاق
    void اخرج_من_نطاق();

    /// تعريف متغير محلي جديد
    /// @return فهرس المتغير في مصفوفة المحليات
    int عرّف_محلي(const std::string& اسم, bool ثابت = false);

    /// حل مرجع متغير: محلي أولاً، ثم علوي، ثم عام
    /// @return فهرس المتغير أو -1 إذا لم يُوجد محلياً
    int ابحث_محلي(const std::string& اسم) const;

    /// حل قيمة علوية (للإغلاقات)
    /// @return فهرس القيمة العلوية أو -1
    int ابحث_علوي(const std::string& اسم);

    // ========================================================================
    // مساعدات الإصدار
    // ========================================================================

    /// إصدار عملية بسيطة (بدون معاملات)
    void أصدر(رمز_عملية عملية, uint32_t سطر);

    /// إصدار عملية مع معامل 8 بت
    void أصدر_مع8(رمز_عملية عملية, uint8_t معامل, uint32_t سطر);

    /// إصدار عملية مع معامل 16 بت
    void أصدر_مع16(رمز_عملية عملية, uint16_t معامل, uint32_t سطر);

    /// إصدار تعليمة تحميل ثابت
    void أصدر_ثابت(const قيمة& ق, uint32_t سطر);

    /// إصدار قفزة مؤقتة (يُصحَّح لاحقاً)
    uint32_t أصدر_قفزة(رمز_عملية عملية_قفز, uint32_t سطر);

    /// تصحيح قفزة مؤقتة
    void صحّح_قفزة(uint32_t إزاحة);

    /// الحصول على الإزاحة الحالية في البايت كود
    uint32_t الإزاحة_الحالية() const;

    /// الحصول على رقم السطر من عقدة AST
    uint32_t سطر(Sad::AST::ASTNode* عقدة) const;

    // ========================================================================
    // الإبلاغ عن الأخطاء
    // ========================================================================

    /// تسجيل خطأ ترجمة
    void خطأ(const std::string& رسالة, uint32_t سطر = 0);

    /// تسجيل خطأ مع سياق عقدة AST
    void خطأ_في(Sad::AST::ASTNode* عقدة, const std::string& رسالة);
};

} // namespace vm
} // namespace sad
