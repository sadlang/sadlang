// ============================================================================
// sad_vm_executor.h - الآلة الافتراضية - المُنفّذ
// Bytecode VM Executor for Sad Language (لغة ص)
// ============================================================================
//
// الوصف:
//   هذا هو قلب الآلة الافتراضية - المحرك الذي يُنفّذ البايت كود.
//   يقرأ التعليمات واحدة تلو الأخرى وينفذها على المكدس.
//
// المعمارية:
//   ┌─────────────────────────────────────────────────┐
//   │                  المكدس (Stack)                  │
//   │  [قيمة] [قيمة] [قيمة] ... ← قمة المكدس          │
//   ├─────────────────────────────────────────────────┤
//   │            إطارات الاستدعاء (Call Frames)        │
//   │  [إطار 0: رئيسي] [إطار 1: دالة_أ] ...           │
//   ├─────────────────────────────────────────────────┤
//   │             المتغيرات العامة (Globals)            │
//   │  {"س" → 42, "اسم" → "أحمد", ...}               │
//   ├─────────────────────────────────────────────────┤
//   │           الدوال الأصلية (Native Functions)      │
//   │  {"اطبع" → ..., "ادخل" → ..., ...}             │
//   └─────────────────────────────────────────────────┘
//
// دورة التنفيذ:
//   1. اقرأ رمز العملية من البايت كود
//   2. فكّ رموز المعاملات (إن وُجدت)
//   3. نفّذ العملية على المكدس
//   4. تقدّم مؤشر التعليمة
//   5. كرر حتى HALT أو نهاية البايت كود
//
// ============================================================================

#pragma once

#include "sad_vm_chunk.h"
#include "sad_vm_opcodes.h"
