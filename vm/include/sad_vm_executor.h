#include <iostream>

namespace sad {
namespace vm {

// ============================================================================
// حجم المكدس الأقصى
// ============================================================================

/// الحجم الأقصى للمكدس (عدد القيم) - يمنع الفيض (stack overflow)
constexpr size_t حجم_المكدس_الأقصى = 65536;

/// العدد الأقصى لإطارات الاستدعاء - يمنع التكرار اللانهائي
constexpr size_t عدد_الإطارات_الأقصى = 1024;

// ============================================================================
// إطار الاستدعاء (Call Frame)
// ============================================================================
// كل استدعاء دالة يُنشئ إطاراً جديداً يحتوي على:
//   - مؤشر التعليمة (IP): أين نحن في البايت كود
//   - قاعدة المكدس: أين تبدأ المتغيرات المحلية لهذه الدالة
//   - معلومات الدالة: الاسم، عدد المعاملات، إلخ
// ============================================================================

struct إطار_استدعاء {
    std::shared_ptr<كائن_دالة> الدالة;       ///< الدالة المُستدعاة
    std::shared_ptr<كائن_إغلاق> الإغلاق;    ///< الإغلاق (nullptr إذا ليست إغلاقاً)
    uint32_t مؤشر_التعليمة;                  ///< الموقع الحالي في البايت كود (IP)
    size_t قاعدة_المكدس;                     ///< بداية المتغيرات المحلية في المكدس

    إطار_استدعاء()
        : مؤشر_التعليمة(0), قاعدة_المكدس(0) {}

    إطار_استدعاء(std::shared_ptr<كائن_دالة> دالة, uint32_t ip, size_t قاعدة)
        : الدالة(std::move(دالة)), مؤشر_التعليمة(ip), قاعدة_المكدس(قاعدة) {}
};

// ============================================================================
// نتيجة التنفيذ
// ============================================================================

/// حالة إنهاء التنفيذ
enum class حالة_التنفيذ {
    نجاح,               ///< انتهى البرنامج بنجاح
    خطأ_تشغيل,          ///< حدث خطأ أثناء التنفيذ
    خطأ_مكدس,           ///< فيض المكدس (stack overflow)
    خطأ_تعليمة,         ///< تعليمة غير معروفة
};

/// نتيجة تنفيذ البرنامج مع معلومات إضافية
struct نتيجة_التنفيذ {
    حالة_التنفيذ الحالة;                     ///< هل نجح أم فشل؟
    قيمة القيمة_النهائية;                    ///< آخر قيمة على المكدس
    std::string رسالة_الخطأ;                 ///< وصف الخطأ (إن حدث)
    uint32_t سطر_الخطأ;                      ///< رقم السطر الذي حدث فيه الخطأ
    uint64_t عدد_التعليمات;                  ///< عدد التعليمات المُنفّذة
    double زمن_التنفيذ_مللي;                 ///< زمن التنفيذ بالمللي ثانية

    نتيجة_التنفيذ()
        : الحالة(حالة_التنفيذ::نجاح), القيمة_النهائية(قيمة::لا_شيء()),
          سطر_الخطأ(0), عدد_التعليمات(0), زمن_التنفيذ_مللي(0) {}
};

// ============================================================================
// معلومات معالج الخطأ (try/catch)
// ============================================================================

struct معالج_خطأ {
    uint32_t عنوان_المعالج;                  ///< عنوان كتلة "امسك"
    size_t عمق_المكدس;                       ///< عمق المكدس عند "حاول"
    size_t عمق_الإطارات;                     ///< عدد الإطارات عند "حاول"
};

// ============================================================================
// الآلة الافتراضية الرئيسية
// ============================================================================

class آلة_افتراضية {
public:
    آلة_افتراضية();
    ~آلة_افتراضية();

    // ========================================================================
    // التنفيذ
    // ========================================================================

    /// تنفيذ وحدة بايت كود كاملة
    /// نقطة الدخول الرئيسية لتشغيل البرامج.
    /// @param وحدة وحدة البايت كود المُترجمة
    /// @return نتيجة التنفيذ (نجاح/فشل + بيانات)
    نتيجة_التنفيذ نفّذ(وحدة_بايت_كود& وحدة);

    /// إعادة تهيئة الآلة الافتراضية
    void أعد_التهيئة();

    // ========================================================================
    // تسجيل الدوال الأصلية (المدمجة)
    // ========================================================================

    /// تسجيل دالة أصلية C++ ليتم استدعاؤها من كود ص
    /// @param اسم اسم الدالة بالعربية (مثل "اطبع")
    /// @param دالة الدالة C++ المقابلة
    void سجّل_دالة_أصلية(const std::string& اسم, دالة_أصلية دالة);

    /// تسجيل الدوال الأصلية المدمجة الأساسية
    /// يُسجّل: اطبع، اطبع_سطر، ادخل، طول، نوع، إلخ
    void سجّل_الدوال_المدمجة();

    // ========================================================================
    // المتغيرات العامة
    // ========================================================================

    /// تعيين متغير عام
    void عيّن_عام(const std::string& اسم, const قيمة& ق);

    /// الحصول على متغير عام
    قيمة اقرأ_عام(const std::string& اسم) const;

    /// هل يوجد متغير عام بهذا الاسم؟
    bool يوجد_عام(const std::string& اسم) const;

    // ========================================================================
    // التصحيح والمراقبة
    // ========================================================================

    /// تفعيل/تعطيل وضع التتبع (يطبع كل تعليمة أثناء التنفيذ)
    void عيّن_وضع_التتبع(bool تفعيل) { وضع_التتبع_ = تفعيل; }

    /// الحصول على محتويات المكدس الحالية (للتصحيح)
    const std::vector<قيمة>& المكدس() const { return المكدس_; }

    /// رقم السطر المصدري الحالي
    uint32_t السطر_الحالي() const;

private:
    // ========================================================================
    // حالة الآلة الافتراضية
    // ========================================================================

    وحدة_بايت_كود* الوحدة_;                              ///< الوحدة المُنفّذة حالياً
    std::vector<قيمة> المكدس_;                            ///< مكدس القيم
    std::vector<إطار_استدعاء> الإطارات_;                  ///< مكدس إطارات الاستدعاء
    std::unordered_map<std::string, قيمة> العامة_;        ///< المتغيرات العامة
    std::vector<معالج_خطأ> معالجات_الأخطاء_;              ///< مكدس معالجات try/catch
    std::vector<std::shared_ptr<قيمة_علوية>> العلويات_المفتوحة_; ///< القيم العلوية المفتوحة

    bool وضع_التتبع_;                                     ///< هل نطبع كل تعليمة؟
    bool قيد_التشغيل_;                                    ///< هل الآلة تعمل؟

    // إحصائيات
    uint64_t عدّاد_التعليمات_;
    std::chrono::high_resolution_clock::time_point وقت_البداية_;

    // ========================================================================
    // حلقة التنفيذ الرئيسية
    // ========================================================================

    /// حلقة قراءة-فك-تنفيذ الرئيسية
    /// هذه هي الدالة الأكثر حساسية للأداء في كل الآلة الافتراضية.
    نتيجة_التنفيذ حلقة_التنفيذ();

    // ========================================================================
    // عمليات المكدس
    // ========================================================================

    /// دفع قيمة على المكدس
    inline void ادفع(const قيمة& ق) {
        if (المكدس_.size() >= حجم_المكدس_الأقصى) {
            throw std::runtime_error("فيض المكدس! (Stack Overflow)");
        }
        المكدس_.push_back(ق);
    }

    /// دفع قيمة بنقل (move) لتحسين الأداء
    inline void ادفع(قيمة&& ق) {
        if (المكدس_.size() >= حجم_المكدس_الأقصى) {
            throw std::runtime_error("فيض المكدس! (Stack Overflow)");
        }
        المكدس_.push_back(std::move(ق));
    }

    /// سحب القيمة العليا من المكدس
    inline قيمة اسحب() {
        if (المكدس_.empty()) {
            throw std::runtime_error("المكدس فارغ! (Stack Underflow)");
        }
        قيمة ق = std::move(المكدس_.back());
        المكدس_.pop_back();
        return ق;
    }

    /// الاطلاع على القيمة العليا بدون سحبها
    inline قيمة& القمة() {
        if (المكدس_.empty()) {
            throw std::runtime_error("المكدس فارغ!");
        }
        return المكدس_.back();
    }

    /// الاطلاع على قيمة بعمق معين من القمة
    inline قيمة& اطّلع(size_t عمق) {
        return المكدس_[المكدس_.size() - 1 - عمق];
    }

    // ========================================================================
    // قراءة البيانات من البايت كود
    // ========================================================================

    /// قراءة البايت التالي وتقدّم مؤشر التعليمة
    inline بايت اقرأ_بايت(إطار_استدعاء& إطار) {
        return الوحدة_->اقرأ(إطار.مؤشر_التعليمة++);
    }

    /// قراءة معامل 16 بت (بايتين) وتقدّم مؤشر التعليمة
    inline uint16_t اقرأ_معامل16(إطار_استدعاء& إطار) {
        uint16_t ق = الوحدة_->اقرأ_معامل16(إطار.مؤشر_التعليمة);
        إطار.مؤشر_التعليمة += 2;
        return ق;
    }

    /// قراءة ثابت من مجمع الثوابت
    inline const قيمة& اقرأ_ثابت(إطار_استدعاء& إطار) {
        uint16_t فهرس = اقرأ_معامل16(إطار);
        return الوحدة_->اقرأ_ثابت(فهرس);
    }

    // ========================================================================
    // تنفيذ العمليات
    // ========================================================================

    /// تنفيذ عملية حسابية ثنائية (+، -، ×، ÷)
    bool نفّذ_حسابية(رمز_عملية عملية);

    /// تنفيذ عملية مقارنة (==، !=، <، >، <=، >=)
    bool نفّذ_مقارنة(رمز_عملية عملية);

    /// تنفيذ استدعاء دالة
    bool استدعِ(int عدد_المعاملات);

    /// تنفيذ استدعاء دالة أصلية
    bool استدعِ_أصلية(const دالة_أصلية& د, int عدد_المعاملات);

    /// تنفيذ استدعاء إغلاق
    bool استدعِ_إغلاق(كائن_إغلاق& غ, int عدد_المعاملات);

    /// تنفيذ إنشاء كائن جديد
    bool أنشئ_كائن(كائن_صنف& ص, int عدد_المعاملات);

    // ========================================================================
    // معالجة الأخطاء في وقت التشغيل
    // ========================================================================

    /// الإبلاغ عن خطأ تشغيل مع تتبع المكدس
    نتيجة_التنفيذ خطأ_تشغيل(const std::string& رسالة);

    /// طباعة تتبع المكدس (stack trace) - لتصحيح الأخطاء
    void اطبع_تتبع_المكدس() const;

    // ========================================================================
    // تتبع التنفيذ (للتصحيح)
    // ========================================================================

    /// طباعة معلومات التعليمة الحالية (إذا كان وضع التتبع مفعلاً)
    void تتبّع_تعليمة(uint32_t إزاحة, رمز_عملية عملية) const;
};

} // namespace vm
} // namespace sad
