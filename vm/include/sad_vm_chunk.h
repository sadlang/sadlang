// ============================================================================
// sad_vm_chunk.h - وحدة البايت كود (Chunk)
// Bytecode Chunk for Sad Language VM (لغة ص)
// ============================================================================
//
// الوصف:
//   "الوحدة" (Chunk) هي الحاوية الأساسية للبايت كود المُترجم.
//   تحتوي على:
//     1. مصفوفة البايت كود (التعليمات المُترجمة)
//     2. مجمع الثوابت (الأعداد والنصوص المستخدمة في البرنامج)
//     3. معلومات الأسطر (لربط البايت كود بالكود المصدري)
//     4. معلومات الدوال المُعرّفة
//
//   يمكن لوحدة واحدة أن تمثل برنامجاً كاملاً أو وحدة (module)
//   واحدة مستوردة.
//
// المصطلحات:
//   - الإزاحة (offset): موقع بايت في مصفوفة البايت كود
//   - المعامل (operand): بيانات إضافية بعد رمز العملية
//   - مجمع الثوابت (constant pool): مصفوفة القيم الثابتة
//   - معلومات السطر (line info): ربط كل إزاحة برقم سطر مصدري
//
// ============================================================================

#pragma once

#include "sad_vm_opcodes.h"
#include "sad_vm_value.h"
#include <vector>
#include <string>
#include <unordered_map>
#include <cassert>

namespace sad {
namespace vm {

// ============================================================================
// معلومات السطر المصدري
// ============================================================================
// نستخدم ترميز RLE (Run-Length Encoding) لتوفير الذاكرة:
// بدل تخزين رقم سطر لكل بايت، نُخزّن (عدد البايتات، رقم السطر).
// ============================================================================

/// سجل واحد يربط مجموعة بايتات متتالية برقم سطر مصدري واحد
struct سجل_سطر {
    uint32_t عدد_البايتات;   ///< عدد البايتات التي تنتمي لهذا السطر
    uint32_t رقم_السطر;      ///< رقم السطر في الملف المصدري

    سجل_سطر(uint32_t عدد, uint32_t سطر)
        : عدد_البايتات(عدد), رقم_السطر(سطر) {}
};

// ============================================================================
// وحدة البايت كود الرئيسية
// ============================================================================

class وحدة_بايت_كود {
public:
    // ========================================================================
    // البناء
    // ========================================================================

    وحدة_بايت_كود() : السطر_الحالي_(0) {}
    explicit وحدة_بايت_كود(const std::string& اسم) : الاسم_(اسم), السطر_الحالي_(0) {}

    // ========================================================================
    // كتابة البايت كود
    // ========================================================================

    /// كتابة بايت واحد (رمز عملية أو معامل)
    /// يُسجّل أيضاً رقم السطر المصدري الحالي
    void اكتب(بايت ب, uint32_t سطر) {
        الكود_.push_back(ب);
        سجّل_سطر(سطر);
    }

    /// كتابة بايت بدون تحديث السطر (يستخدم آخر سطر)
    void اكتب(بايت ب) {
        الكود_.push_back(ب);
        سجّل_سطر(السطر_الحالي_);
    }

    /// كتابة رمز عملية مع معامل 8 بت
    void اكتب_عملية_ومعامل8(رمز_عملية عملية, uint8_t معامل, uint32_t سطر) {
        اكتب(عملية, سطر);
        اكتب(معامل, سطر);
    }

    /// كتابة رمز عملية مع معامل 16 بت (يُقسم إلى بايتين: العلوي ثم السفلي)
    void اكتب_عملية_ومعامل16(رمز_عملية عملية, uint16_t معامل, uint32_t سطر) {
        اكتب(عملية, سطر);
        اكتب(static_cast<بايت>((معامل >> 8) & 0xFF), سطر);  // البايت العلوي
        اكتب(static_cast<بايت>(معامل & 0xFF), سطر);          // البايت السفلي
    }

    /// كتابة معامل 16 بت فقط (بدون رمز العملية)
    void اكتب_معامل16(uint16_t معامل, uint32_t سطر) {
        اكتب(static_cast<بايت>((معامل >> 8) & 0xFF), سطر);
        اكتب(static_cast<بايت>(معامل & 0xFF), سطر);
    }

    // ========================================================================
    // مجمع الثوابت
    // ========================================================================
    // كل قيمة ثابتة في البرنامج (أعداد، نصوص) تُخزّن هنا مرة واحدة.
    // التعليمات تُشير إلى الثوابت بالفهرس فقط.
    // نستخدم خرائط للتأكد من عدم تكرار الثوابت (deduplication).
    // ========================================================================

    /// إضافة ثابت وإرجاع فهرسه.
    /// إذا كان الثابت موجوداً مسبقاً، يُرجع فهرسه القديم.
    uint16_t أضف_ثابت(const قيمة& ق) {
        // البحث عن تكرار لتوفير الذاكرة
        if (ق.هل_صحيح()) {
            auto بحث = خريطة_الأعداد_.find(ق.كـ_صحيح());
            if (بحث != خريطة_الأعداد_.end()) return بحث->second;
        } else if (ق.هل_عشري()) {
            auto بحث = خريطة_العشريات_.find(ق.كـ_عشري());
            if (بحث != خريطة_العشريات_.end()) return بحث->second;
        } else if (ق.هل_نص()) {
            auto بحث = خريطة_النصوص_.find(ق.كـ_نص());
            if (بحث != خريطة_النصوص_.end()) return بحث->second;
        }

        // إضافة ثابت جديد
        uint16_t فهرس = static_cast<uint16_t>(الثوابت_.size());
        الثوابت_.push_back(ق);

        // تحديث خرائط التكرار
        if (ق.هل_صحيح()) {
            خريطة_الأعداد_[ق.كـ_صحيح()] = فهرس;
        } else if (ق.هل_عشري()) {
            خريطة_العشريات_[ق.كـ_عشري()] = فهرس;
        } else if (ق.هل_نص()) {
            خريطة_النصوص_[ق.كـ_نص()] = فهرس;
        }

        return فهرس;
    }

    /// الحصول على ثابت بفهرسه
    const قيمة& اقرأ_ثابت(uint16_t فهرس) const {
        assert(فهرس < الثوابت_.size() && "فهرس ثابت خارج النطاق");
        return الثوابت_[فهرس];
    }

    /// عدد الثوابت
    size_t عدد_الثوابت() const { return الثوابت_.size(); }

    // ========================================================================
    // تسجيل معلومات الدوال
    // ========================================================================

    /// تسجيل دالة مع موقعها في البايت كود
    void سجّل_دالة(const std::string& اسم, int معاملات, int محليات, uint32_t بداية) {
        الدوال_[اسم] = std::make_shared<كائن_دالة>(اسم, معاملات, محليات, بداية);
    }

    /// البحث عن دالة بالاسم
    std::shared_ptr<كائن_دالة> ابحث_عن_دالة(const std::string& اسم) const {
        auto بحث = الدوال_.find(اسم);
        if (بحث != الدوال_.end()) return بحث->second;
        return nullptr;
    }

    /// الحصول على كل الدوال
    const std::unordered_map<std::string, std::shared_ptr<كائن_دالة>>& الدوال() const {
        return الدوال_;
    }

    // ========================================================================
    // القراءة والوصول
    // ========================================================================

    /// قراءة بايت من إزاحة معينة
    بايت اقرأ(uint32_t إزاحة) const {
        assert(إزاحة < الكود_.size() && "إزاحة خارج نطاق البايت كود");
        return الكود_[إزاحة];
    }

    /// قراءة معامل 16 بت من إزاحة معينة
    uint16_t اقرأ_معامل16(uint32_t إزاحة) const {
        return (static_cast<uint16_t>(اقرأ(إزاحة)) << 8)
             | static_cast<uint16_t>(اقرأ(إزاحة + 1));
    }

    /// الحصول على الحجم الكلي للبايت كود
    uint32_t الحجم() const { return static_cast<uint32_t>(الكود_.size()); }

    /// الحصول على مؤشر للبايت كود (للقراءة المباشرة عالية الأداء)
    const بايت* البيانات() const { return الكود_.data(); }

    /// مصفوفة البايت كود كاملة
    const std::vector<بايت>& الكود() const { return الكود_; }

    /// مصفوفة الثوابت كاملة
    const std::vector<قيمة>& الثوابت() const { return الثوابت_; }

    // ========================================================================
    // تصحيح القفزات (Backpatching)
    // ========================================================================
    // عند ترجمة "إذا" أو "بينما"، لا نعرف عنوان القفز مسبقاً.
    // نكتب عنواناً مؤقتاً (placeholder) ثم نُصححه لاحقاً.
    // ========================================================================

    /// كتابة تعليمة قفز مع عنوان مؤقت (يُصحَّح لاحقاً)
    /// تُرجع إزاحة المعامل (لاستخدامها في التصحيح)
    uint32_t اكتب_قفزة_مؤقتة(رمز_عملية عملية_قفز, uint32_t سطر) {
        اكتب(عملية_قفز, سطر);
        uint32_t إزاحة_المعامل = الحجم();
        اكتب(0xFF, سطر);  // بايت علوي مؤقت
        اكتب(0xFF, سطر);  // بايت سفلي مؤقت
        return إزاحة_المعامل;
    }

    /// تصحيح عنوان قفزة مؤقتة إلى العنوان الحالي
    void صحّح_قفزة(uint32_t إزاحة_المعامل) {
        uint16_t هدف = static_cast<uint16_t>(الحجم());
        الكود_[إزاحة_المعامل] = static_cast<بايت>((هدف >> 8) & 0xFF);
        الكود_[إزاحة_المعامل + 1] = static_cast<بايت>(هدف & 0xFF);
    }

    /// تصحيح قفزة إلى عنوان محدد
    void صحّح_قفزة_إلى(uint32_t إزاحة_المعامل, uint16_t هدف) {
        الكود_[إزاحة_المعامل] = static_cast<بايت>((هدف >> 8) & 0xFF);
        الكود_[إزاحة_المعامل + 1] = static_cast<بايت>(هدف & 0xFF);
    }

    // ========================================================================
    // معلومات السطر المصدري
    // ========================================================================

    /// الحصول على رقم السطر المصدري لإزاحة معينة
    uint32_t رقم_السطر(uint32_t إزاحة) const {
        uint32_t تراكمي = 0;
        for (const auto& سجل : سجلات_الأسطر_) {
            تراكمي += سجل.عدد_البايتات;
            if (إزاحة < تراكمي) return سجل.رقم_السطر;
        }
        // إزاحة خارج النطاق، نرجع آخر سطر معروف
        if (!سجلات_الأسطر_.empty()) {
            return سجلات_الأسطر_.back().رقم_السطر;
        }
        return 0;
    }

    // ========================================================================
    // البيانات الوصفية
    // ========================================================================

    /// اسم الوحدة (اسم الملف عادة)
    const std::string& الاسم() const { return الاسم_; }
    void عيّن_الاسم(const std::string& اسم) { الاسم_ = اسم; }

    /// تعيين نقطة الدخول (بداية تنفيذ البرنامج)
    void عيّن_نقطة_الدخول(uint32_t إزاحة) { نقطة_الدخول_ = إزاحة; }
    uint32_t نقطة_الدخول() const { return نقطة_الدخول_; }

    /// مسح كل شيء وإعادة التهيئة
    void امسح() {
        الكود_.clear();
        الثوابت_.clear();
        سجلات_الأسطر_.clear();
        خريطة_الأعداد_.clear();
        خريطة_العشريات_.clear();
        خريطة_النصوص_.clear();
        الدوال_.clear();
        السطر_الحالي_ = 0;
        نقطة_الدخول_ = 0;
    }

private:
    std::string الاسم_;                                          ///< اسم الوحدة
    std::vector<بايت> الكود_;                                    ///< مصفوفة البايت كود
    std::vector<قيمة> الثوابت_;                                  ///< مجمع الثوابت
    std::vector<سجل_سطر> سجلات_الأسطر_;                         ///< معلومات الأسطر (RLE)
    uint32_t السطر_الحالي_;                                      ///< آخر سطر مصدري مُسجّل
    uint32_t نقطة_الدخول_ = 0;                                   ///< إزاحة بداية التنفيذ

    /// خرائط لمنع تكرار الثوابت
    std::unordered_map<int64_t, uint16_t> خريطة_الأعداد_;
    std::unordered_map<double, uint16_t> خريطة_العشريات_;
    std::unordered_map<std::string, uint16_t> خريطة_النصوص_;

    /// خريطة الدوال المُعرّفة
    std::unordered_map<std::string, std::shared_ptr<كائن_دالة>> الدوال_;

    /// تسجيل رقم سطر مصدري للبايت الحالي (ترميز RLE)
    void سجّل_سطر(uint32_t سطر) {
        السطر_الحالي_ = سطر;
        if (!سجلات_الأسطر_.empty() && سجلات_الأسطر_.back().رقم_السطر == سطر) {
            // نفس السطر السابق: نزيد العداد فقط
            سجلات_الأسطر_.back().عدد_البايتات++;
        } else {
            // سطر جديد: نضيف سجلاً جديداً
            سجلات_الأسطر_.emplace_back(1, سطر);
        }
    }
};

} // namespace vm
} // namespace sad
