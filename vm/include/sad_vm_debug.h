#include <string>
#include <sstream>
#include <iostream>
#include <iomanip>

namespace sad {
namespace vm {

// ============================================================================
// مُفكّك البايت كود (Disassembler)
// ============================================================================
// يقرأ البايت كود المُترجم ويُنتج تمثيلاً نصياً مقروءاً.
// مفيد جداً لتصحيح الأخطاء وفهم ما أنتجه المُترجم.
//
// مثال الخرج:
//   ═══ وحدة: <رئيسي> ═══
//   ═══ الثوابت ═══
//     0: [صحيح] 5
//     1: [صحيح] 3
//     2: [نص] "النتيجة"
//   ═══ البايت كود ═══
//   0000  1 | ثابت          0  (5)
//   0003  1 | ثابت          1  (3)
//   0006  1 | جمع
//   0007  1 | تخزين_محلي    0
//   0009  2 | اطبع_سطر
// ============================================================================

class مفكك_البايت_كود {
public:
    // ========================================================================
    // تفكيك وحدة كاملة
    // ========================================================================

    /// تفكيك وطباعة وحدة بايت كود كاملة
    /// يطبع: اسم الوحدة، الثوابت، الدوال، ثم كل التعليمات
    void فكّك_وحدة(const وحدة_بايت_كود& وحدة) const {
        std::cout << "\n";
        اطبع_خط_عريض();
        std::cout << "  وحدة: " << (وحدة.الاسم().empty() ? "<رئيسي>" : وحدة.الاسم()) << "\n";
        اطبع_خط_عريض();

        // طباعة الثوابت
        فكّك_الثوابت(وحدة);

        // طباعة الدوال المُعرّفة
        فكّك_الدوال(وحدة);

        // طباعة البايت كود
        std::cout << "\n  ─── البايت كود (" << وحدة.الحجم() << " بايت) ───\n";
        uint32_t إزاحة = 0;
        while (إزاحة < وحدة.الحجم()) {
            إزاحة = فكّك_تعليمة(وحدة, إزاحة);
        }

        اطبع_خط_عريض();
        std::cout << "\n";
    }

    /// تفكيك ثوابت الوحدة
    void فكّك_الثوابت(const وحدة_بايت_كود& وحدة) const {
        if (وحدة.عدد_الثوابت() == 0) return;

        std::cout << "\n  ─── الثوابت (" << وحدة.عدد_الثوابت() << ") ───\n";
        for (size_t ف = 0; ف < وحدة.عدد_الثوابت(); ف++) {
            const auto& ق = وحدة.الثوابت()[ف];
            std::cout << "    " << std::setw(4) << ف << ": ["
                      << ق.اسم_النوع() << "] " << ق.إلى_نص() << "\n";
        }
    }

    /// تفكيك قائمة الدوال
    void فكّك_الدوال(const وحدة_بايت_كود& وحدة) const {
        const auto& دوال = وحدة.الدوال();
        if (دوال.empty()) return;

        std::cout << "\n  ─── الدوال (" << دوال.size() << ") ───\n";
        for (const auto& [اسم, دالة] : دوال) {
            std::cout << "    " << اسم
                      << " (معاملات: " << دالة->عدد_المعاملات
                      << ", محليات: " << دالة->عدد_المحليات
                      << ", بداية: @" << دالة->بداية_الكود << ")\n";
        }
    }

    // ========================================================================
    // تفكيك تعليمة واحدة
    // ========================================================================

    /// تفكيك تعليمة واحدة عند إزاحة معينة
    /// @return إزاحة التعليمة التالية
    uint32_t فكّك_تعليمة(const وحدة_بايت_كود& وحدة, uint32_t إزاحة) const {
        // طباعة الإزاحة
        std::cout << "  " << std::setfill('0') << std::setw(4) << إزاحة;
        std::cout << std::setfill(' ');

        // طباعة رقم السطر
        uint32_t سطر = وحدة.رقم_السطر(إزاحة);
        std::cout << "  " << std::setw(4) << سطر << " | ";

        // قراءة رمز العملية
        رمز_عملية عملية = وحدة.اقرأ(إزاحة);
        إزاحة++;

        // طباعة حسب نوع التعليمة
        switch (عملية) {
            // تعليمات بدون معاملات
            case عملية_لا_شيء:
            case عملية_لا_شيء_قيمة:
            case عملية_صحيح:
            case عملية_خطأ:
            case عملية_سحب:
            case عملية_نسخ:
            case عملية_تبديل:
            case عملية_جمع:
            case عملية_طرح:
            case عملية_ضرب:
            case عملية_قسمة:
            case عملية_باقي:
            case عملية_سالب:
            case عملية_أس:
            case عملية_زيادة:
            case عملية_نقصان:
            case عملية_ليس:
            case عملية_و:
            case عملية_أو:
            case عملية_و_بتية:
            case عملية_أو_بتية:
            case عملية_أو_حصرية:
            case عملية_نفي_بتي:
            case عملية_إزاحة_يسار:
            case عملية_إزاحة_يمين:
            case عملية_يساوي:
            case عملية_لا_يساوي:
            case عملية_أصغر:
            case عملية_أصغر_يساوي:
            case عملية_أكبر:
            case عملية_أكبر_يساوي:
            case عملية_عودة:
            case عملية_عودة_بقيمة:
            case عملية_ربط_نص:
            case عملية_إلى_نص:
            case عملية_إلى_رقم:
            case عملية_إلى_عشري:
            case عملية_إلى_منطقي:
            case عملية_طول:
            case عملية_مصفوفة_قراءة:
            case عملية_مصفوفة_كتابة:
            case عملية_مصفوفة_إضافة:
            case عملية_مصفوفة_طول:
            case عملية_قاموس_قراءة:
            case عملية_قاموس_كتابة:
            case عملية_وراثة:
            case عملية_هذا:
            case عملية_اطبع:
            case عملية_اطبع_سطر:
            case عملية_ادخل:
            case عملية_نوع:
            case عملية_نهاية_حاول:
            case عملية_ارمِ:
            case عملية_إيقاف:
            case عملية_تأكيد:
            case عملية_نقطة_توقف:
            case عملية_جمع_قمامة:
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية) << "\n";
                return إزاحة;

            // تعليمات مع معامل 8 بت
            case عملية_رقم_صغير:
            case عملية_سحب_متعدد:
            case عملية_تحميل_محلي:
            case عملية_تخزين_محلي:
            case عملية_استدعاء:
            case عملية_تحميل_علوية:
            case عملية_تخزين_علوية:
            case عملية_إغلاق_علوية: {
                uint8_t معامل = وحدة.اقرأ(إزاحة++);
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية)
                          << " " << static_cast<int>(معامل) << "\n";
                return إزاحة;
            }

            // تعليمات مع معامل 16 بت
            case عملية_ثابت: {
                uint16_t فهرس = وحدة.اقرأ_معامل16(إزاحة);
                إزاحة += 2;
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية)
                          << " " << فهرس;
                if (فهرس < وحدة.عدد_الثوابت()) {
                    std::cout << "  (" << وحدة.اقرأ_ثابت(فهرس).إلى_نص() << ")";
                }
                std::cout << "\n";
                return إزاحة;
            }

            // تعليمات القفز (معامل 16 بت = عنوان)
            case عملية_قفز:
            case عملية_قفز_إذا_صحيح:
            case عملية_قفز_إذا_خطأ:
            case عملية_حلقة: {
                uint16_t هدف = وحدة.اقرأ_معامل16(إزاحة);
                إزاحة += 2;
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية)
                          << " → @" << هدف << "\n";
                return إزاحة;
            }

            // تعليمات المتغيرات العامة والأصناف (فهرس 16 بت في مجمع الثوابت)
            case عملية_تحميل_عام:
            case عملية_تخزين_عام:
            case عملية_تعريف_عام:
            case عملية_كائن_جديد:
            case عملية_حقل_قراءة:
            case عملية_حقل_كتابة:
            case عملية_تعريف_صنف:
            case عملية_الأساس:
            case عملية_استورد:
            case عملية_إغلاق:
            case عملية_حاول:
            case عملية_استدعاء_أصلي: {
                uint16_t فهرس = وحدة.اقرأ_معامل16(إزاحة);
                إزاحة += 2;
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية)
                          << " " << فهرس;
                if (فهرس < وحدة.عدد_الثوابت()) {
                    std::cout << "  (" << وحدة.اقرأ_ثابت(فهرس).إلى_نص() << ")";
                }
                std::cout << "\n";
                return إزاحة;
            }

            // تعليمة استدعاء طريقة: معامل 16 بت + معامل 8 بت
            case عملية_استدعاء_طريقة: {
                uint16_t فهرس = وحدة.اقرأ_معامل16(إزاحة);
                إزاحة += 2;
                uint8_t عدد = وحدة.اقرأ(إزاحة++);
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية)
                          << " " << فهرس << " (" << static_cast<int>(عدد) << " معامل)";
                if (فهرس < وحدة.عدد_الثوابت()) {
                    std::cout << "  [" << وحدة.اقرأ_ثابت(فهرس).إلى_نص() << "]";
                }
                std::cout << "\n";
                return إزاحة;
            }

            // إنشاء مصفوفة/قاموس: معامل 16 بت = عدد العناصر
            case عملية_مصفوفة_جديدة:
            case عملية_قاموس_جديد: {
                uint16_t عدد = وحدة.اقرأ_معامل16(إزاحة);
                إزاحة += 2;
                std::cout << std::left << std::setw(20) << اسم_العملية(عملية)
                          << " " << عدد << " عنصر\n";
                return إزاحة;
            }

            default:
                std::cout << "تعليمة_مجهولة (0x"
                          << std::hex << static_cast<int>(عملية) << std::dec << ")\n";
                return إزاحة;
        }
    }

    // ========================================================================
    // أدوات مساعدة للطباعة
    // ========================================================================

    /// طباعة محتويات المكدس
    void اطبع_المكدس(const std::vector<قيمة>& مكدس) const {
        std::cout << "  المكدس: [";
        for (size_t ف = 0; ف < مكدس.size(); ف++) {
            if (ف > 0) std::cout << " | ";
            std::cout << مكدس[ف].إلى_نص();
        }
        std::cout << "]\n";
    }

    /// تفكيك وحدة وإرجاع النتيجة كنص (بدل الطباعة)
    std::string فكّك_إلى_نص(const وحدة_بايت_كود& وحدة) const {
        std::ostringstream خرج;
        // يمكن إعادة تنفيذ التفكيك هنا للكتابة في الـ stream
        // حالياً نطبع للشاشة فقط
        خرج << "[وحدة: " << وحدة.الاسم()
             << ", " << وحدة.الحجم() << " بايت"
             << ", " << وحدة.عدد_الثوابت() << " ثابت]\n";
        return خرج.str();
    }

private:
    void اطبع_خط_عريض() const {
        std::cout << "  ═══════════════════════════════════════════════\n";
    }
};

} // namespace vm
} // namespace sad
