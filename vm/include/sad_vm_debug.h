//     1. المُفكّك (Disassembler): يُحوّل البايت كود إلى نص مقروء
//     2. مُراقب المكدس: يعرض محتويات المكدس في أي لحظة
//     3. معلومات الأداء: يعرض إحصائيات التنفيذ
//
// الاستخدام:
//   مفكك_البايت_كود مفكك;
//   مفكك.فكّك_وحدة(وحدة);           // طباعة كل التعليمات
//   مفكك.فكّك_تعليمة(وحدة, 42);     // طباعة تعليمة واحدة
//
// ============================================================================

#pragma once

#include "sad_vm_chunk.h"
#include "sad_vm_opcodes.h"
