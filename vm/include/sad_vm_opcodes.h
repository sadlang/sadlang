/// الحصول على اسم رمز العملية بالعربية (للتصحيح والتفكيك)
/// مثال: اسم_العملية(عملية_جمع) → "جمع"
const char* اسم_العملية(رمز_عملية رمز);

/// الحصول على اسم رمز العملية بالإنجليزية (للتوافق)
/// مثال: opcode_name(عملية_جمع) → "ADD"
const char* opcode_name(رمز_عملية op);

/// حجم المعاملات بالبايت لرمز عملية معين
/// مثال: حجم_المعاملات(عملية_ثابت) → 2 (لأن الفهرس يحتاج 2 بايت)
int حجم_المعاملات(رمز_عملية رمز);

/// الطول الكامل للتعليمة (1 + حجم المعاملات)
inline int طول_التعليمة(رمز_عملية رمز) {
    return 1 + حجم_المعاملات(رمز);
}

