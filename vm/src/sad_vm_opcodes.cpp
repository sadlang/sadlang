        case عملية_قسمة:
        case عملية_باقي:
        case عملية_سالب:
        case عملية_أس:
        case عملية_زيادة:
        case عملية_نقصان:
        case عملية_ليس:
        case عملية_و:
        case عملية_أو:
        case عملية_و_بتية:
        case عملية_أو_بتية:
        case عملية_أو_حصرية:
        case عملية_نفي_بتي:
        case عملية_إزاحة_يسار:
        case عملية_إزاحة_يمين:
        case عملية_يساوي:
        case عملية_لا_يساوي:
        case عملية_أصغر:
        case عملية_أصغر_يساوي:
        case عملية_أكبر:
        case عملية_أكبر_يساوي:
        case عملية_عودة:
        case عملية_عودة_بقيمة:
        case عملية_ربط_نص:
        case عملية_إلى_نص:
        case عملية_إلى_رقم:
        case عملية_إلى_عشري:
        case عملية_إلى_منطقي:
        case عملية_طول:
        case عملية_مصفوفة_قراءة:
        case عملية_مصفوفة_كتابة:
        case عملية_مصفوفة_إضافة:
        case عملية_مصفوفة_طول:
        case عملية_قاموس_قراءة:
        case عملية_قاموس_كتابة:
        case عملية_وراثة:
        case عملية_هذا:
        case عملية_اندماج_صفري:
        case عملية_اطبع:
        case عملية_اطبع_سطر:
        case عملية_ادخل:
        case عملية_نوع:
        case عملية_نهاية_حاول:
        case عملية_ارمِ:
        case عملية_إيقاف:
