// ============================================================================
// البناء والهدم
// ============================================================================

مُترجم_بايت_كود::مُترجم_بايت_كود()
    : الوحدة_(nullptr), السياق_(nullptr) {}

مُترجم_بايت_كود::~مُترجم_بايت_كود() = default;

// ============================================================================
// الواجهة الرئيسية: ترجمة برنامج كامل
// ============================================================================
// هذه هي نقطة الدخول. تُنشئ وحدة بايت كود جديدة وسياق ترجمة،
// ثم تترجم كل جملة بالتسلسل، وتُضيف تعليمة إيقاف في النهاية.
// ============================================================================

وحدة_بايت_كود مُترجم_بايت_كود::ترجم(
    const std::vector<std::unique_ptr<Sad::AST::Statement>>& الجمل,
    const std::string& اسم_الوحدة
) {
    // تهيئة الوحدة والسياق
    وحدة_بايت_كود وحدة(اسم_الوحدة);
    الوحدة_ = &وحدة;
    الأخطاء_.clear();

    سياق_الترجمة سياق_رئيسي;
    سياق_رئيسي.اسم_الدالة = "<رئيسي>";
    السياق_ = &سياق_رئيسي;

    // ترجمة كل الجمل واحدة تلو الأخرى
    for (const auto& جملة : الجمل) {
        if (جملة) {
            ترجم_جملة(جملة.get());
        }
    }

    // إضافة تعليمة الإيقاف في نهاية البرنامج
    أصدر(عملية_إيقاف, 0);

    // تسجيل عدد المحليات القصوى في الوحدة
    // (يُستخدم لتخصيص مساحة إطار الاستدعاء الرئيسي)

    الوحدة_ = nullptr;
    السياق_ = nullptr;

    return وحدة;
}

// ============================================================================
// ترجمة الجمل (Statements)
// ============================================================================
// الموزّع المركزي: يفحص نوع كل جملة ويُوجّهها للمُترجم المناسب.
// نستخدم dynamic_cast لتحديد النوع الفعلي لعقدة AST.
// ============================================================================

void مُترجم_بايت_كود::ترجم_جملة(Sad::AST::Statement* جملة) {
    if (!جملة) return;

    // التعرف على نوع الجملة وتوجيهها
    if (auto* تعبير = dynamic_cast<Sad::AST::ExprStmt*>(جملة)) {
        ترجم_جملة_تعبير(تعبير);
    }
    else if (auto* تصريح = dynamic_cast<Sad::AST::VarDeclStmt*>(جملة)) {
        ترجم_تصريح_متغير(تصريح);
    }
    else if (auto* إذا = dynamic_cast<Sad::AST::IfStmt*>(جملة)) {
        ترجم_إذا(إذا);
    }
    else if (auto* بينما = dynamic_cast<Sad::AST::WhileStmt*>(جملة)) {
        ترجم_بينما(بينما);
    }
    else if (auto* لكل = dynamic_cast<Sad::AST::ForStmt*>(جملة)) {
        ترجم_لكل(لكل);
    }
    else if (auto* لكل_في = dynamic_cast<Sad::AST::ForRangeStmt*>(جملة)) {
        ترجم_لكل_في(لكل_في);
    }
    else if (auto* إرجاع = dynamic_cast<Sad::AST::ReturnStmt*>(جملة)) {
        ترجم_إرجاع(إرجاع);
    }
    else if (auto* توقف = dynamic_cast<Sad::AST::BreakStmt*>(جملة)) {
        ترجم_توقف(توقف);
    }
    else if (auto* استمر = dynamic_cast<Sad::AST::ContinueStmt*>(جملة)) {
        ترجم_استمر(استمر);
    }
    else if (auto* كتلة = dynamic_cast<Sad::AST::BlockStmt*>(جملة)) {
        ترجم_كتلة(كتلة);
    }
    else if (auto* دالة = dynamic_cast<Sad::AST::FunctionDecl*>(جملة)) {
        ترجم_تصريح_دالة(دالة);
    }
    else if (auto* صنف = dynamic_cast<Sad::AST::ClassDecl*>(جملة)) {
        ترجم_تصريح_صنف(صنف);
    }
    else if (auto* حاول = dynamic_cast<Sad::AST::TryStmt*>(جملة)) {
        ترجم_حاول(حاول);
    }
    else if (auto* ارفع = dynamic_cast<Sad::AST::RaiseStmt*>(جملة)) {
        // ارمِ: ترجم التعبير ثم أصدر عملية الرمي
        ترجم_تعبير(ارفع->exception.get());
        أصدر(عملية_ارمِ, سطر(ارفع));
    }
    else if (auto* حالة = dynamic_cast<Sad::AST::SwitchStmt*>(جملة)) {
        // ترجمة حالة/عندما كسلسلة من إذا/وإلا
        ترجم_تعبير(حالة->expression.get());
        std::vector<uint32_t> قفزات_نهاية;

        for (auto& فرع : حالة->cases) {
            // نسخ تعبير الحالة (هو على المكدس بالفعل)
            أصدر(عملية_نسخ, سطر(حالة));
            // ترجم قيمة الفرع
            ترجم_تعبير(فرع.value.get());
            // مقارنة
            أصدر(عملية_يساوي, سطر(حالة));
            // إذا لم يتطابق، اقفز للفرع التالي
            uint32_t قفزة_تالي = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(حالة));
            // تطابق: أزل القيمة المنسوخة
            أصدر(عملية_سحب, سطر(حالة));
            // نفّذ جسم الفرع
            ترجم_جملة(فرع.body.get());
            // اقفز لنهاية الـ switch
            قفزات_نهاية.push_back(أصدر_قفزة(عملية_قفز, سطر(حالة)));
            // نقطة: الفرع التالي
            صحّح_قفزة(قفزة_تالي);
        }

        // الحالة الافتراضية
        if (حالة->defaultCase) {
            أصدر(عملية_سحب, سطر(حالة)); // أزل القيمة المتبقية
            ترجم_جملة(حالة->defaultCase.get());
        } else {
            أصدر(عملية_سحب, سطر(حالة)); // أزل القيمة
        }

        // تصحيح قفزات النهاية
        for (auto إزاحة : قفزات_نهاية) {
            صحّح_قفزة(إزاحة);
        }
    }
    else {
        // نوع جملة غير مدعوم حالياً - نتجاهلها بتحذير
        خطأ("نوع جملة غير مدعوم في مُترجم البايت كود", سطر(جملة));
    }
}

// ============================================================================
// ترجمة كتلة جمل (BlockStmt)
// ============================================================================
// الكتلة تُنشئ نطاقاً جديداً، وعند الخروج منه تُحرّر المتغيرات المحلية.
// ============================================================================

void مُترجم_بايت_كود::ترجم_كتلة(Sad::AST::BlockStmt* كتلة) {
    ادخل_نطاق();
    for (const auto& جملة : كتلة->statements) {
        ترجم_جملة(جملة.get());
    }
    اخرج_من_نطاق();
}

// ============================================================================
// ترجمة تصريح متغير: "متغير س = 5 + 3"
// ============================================================================
// 1. ترجم التعبير الأولي (إن وُجد) → القيمة على المكدس
// 2. إذا لا يوجد تعبير أولي → ادفع "لا_شيء"
// 3. سجّل المتغير المحلي أو العام
// ============================================================================

void مُترجم_بايت_كود::ترجم_تصريح_متغير(Sad::AST::VarDeclStmt* تصريح) {
    // ترجمة القيمة الأولية
    if (تصريح->initializer) {
        ترجم_تعبير(تصريح->initializer.get());
    } else {
        // لا قيمة أولية: ادفع لا_شيء
        أصدر(عملية_لا_شيء_قيمة, سطر(تصريح));
    }

    // هل نحن في النطاق العام (عمق 0) أم محلي؟
    if (السياق_->عمق_النطاق == 0 && السياق_->الأب == nullptr) {
        // متغير عام: خزّنه في جدول المتغيرات العامة
        uint16_t فهرس_الاسم = الوحدة_->أضف_ثابت(قيمة::نص(تصريح->name));
        أصدر_مع16(عملية_تعريف_عام, فهرس_الاسم, سطر(تصريح));
    } else {
        // متغير محلي: سجّله في السياق الحالي
        عرّف_محلي(تصريح->name, تصريح->isConst);
    }
}

// ============================================================================
// ترجمة جملة تعبير: "اطبع(...)" أو "دالة()"
// ============================================================================
// نترجم التعبير ثم نسحب النتيجة (لأنها جملة وليست جزءاً من تعبير أكبر).
// ============================================================================

void مُترجم_بايت_كود::ترجم_جملة_تعبير(Sad::AST::ExprStmt* جملة) {
    ترجم_تعبير(جملة->expression.get());
    // نتيجة التعبير لا نحتاجها (هذه جملة)، فنسحبها من المكدس
    أصدر(عملية_سحب, سطر(جملة));
}

// ============================================================================
// ترجمة جملة "إذا" (if / else)
// ============================================================================
// البنية المُنتجة:
//   [ترجمة الشرط]
//   قفز_إذا_خطأ → @وإلا (أو @نهاية)
//   [ترجمة فرع إذا]
//   قفز → @نهاية              (فقط إذا وُجد فرع "وإلا")
//   @وإلا:
//   [ترجمة فرع وإلا]
//   @نهاية:
// ============================================================================

void مُترجم_بايت_كود::ترجم_إذا(Sad::AST::IfStmt* جملة) {
    // ترجمة الشرط → نتيجة منطقية على المكدس
    ترجم_تعبير(جملة->condition.get());

    // قفز إذا الشرط خطأ (تخطي فرع "إذا")
    uint32_t قفزة_وإلا = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(جملة));

    // ترجمة فرع "إذا"
    ترجم_جملة(جملة->thenBranch.get());

    if (جملة->elseBranch) {
        // يوجد فرع "وإلا": نحتاج قفزة لتخطيه
        uint32_t قفزة_نهاية = أصدر_قفزة(عملية_قفز, سطر(جملة));

        // تصحيح قفزة "وإلا" لتشير للموقع الحالي
        صحّح_قفزة(قفزة_وإلا);

        // ترجمة فرع "وإلا"
        ترجم_جملة(جملة->elseBranch.get());

        // تصحيح قفزة النهاية
        صحّح_قفزة(قفزة_نهاية);
    } else {
        // لا يوجد فرع "وإلا"
        صحّح_قفزة(قفزة_وإلا);
    }
}

// ============================================================================
// ترجمة جملة "بينما" (while)
// ============================================================================
// البنية المُنتجة:
//   @بداية:
//   [ترجمة الشرط]
//   قفز_إذا_خطأ → @نهاية
//   [ترجمة الجسم]
//   حلقة → @بداية
//   @نهاية:
// ============================================================================

void مُترجم_بايت_كود::ترجم_بينما(Sad::AST::WhileStmt* جملة) {
    // تسجيل بداية الحلقة (لدعم "استمر" و"توقف")
    uint32_t بداية_الحلقة = الإزاحة_الحالية();
    نطاق_حلقة حلقة;
    حلقة.بداية = بداية_الحلقة;
    السياق_->الحلقات.push_back(حلقة);

    // ترجمة الشرط
    ترجم_تعبير(جملة->condition.get());

    // قفز للنهاية إذا الشرط خطأ
    uint32_t قفزة_نهاية = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(جملة));

    // ترجمة جسم الحلقة
    ترجم_جملة(جملة->body.get());

    // العودة لبداية الحلقة
    أصدر_مع16(عملية_حلقة, static_cast<uint16_t>(بداية_الحلقة), سطر(جملة));

    // تصحيح قفزة النهاية
    صحّح_قفزة(قفزة_نهاية);

    // تصحيح قفزات "توقف" المُعلّقة
    auto& حلقة_حالية = السياق_->الحلقات.back();
    for (auto إزاحة : حلقة_حالية.قفزات_التوقف) {
        صحّح_قفزة(إزاحة);
    }
    السياق_->الحلقات.pop_back();
}

// ============================================================================
// ترجمة جملة "لكل" (for) - بأسلوب C
// ============================================================================
// lكل (تهيئة; شرط; زيادة) { جسم }
// البنية المُنتجة:
//   [ترجمة التهيئة]
//   @بداية:
//   [ترجمة الشرط]
//   قفز_إذا_خطأ → @نهاية
//   [ترجمة الجسم]
//   [ترجمة الزيادة]
//   سحب (نتيجة الزيادة)
//   حلقة → @بداية
//   @نهاية:
// ============================================================================

void مُترجم_بايت_كود::ترجم_لكل(Sad::AST::ForStmt* جملة) {
    // نطاق جديد للمتغير المبدئي (مثل "متغير ف = 0")
    ادخل_نطاق();

    // ترجمة التهيئة (إن وُجدت)
    if (جملة->initializer) {
        ترجم_جملة(جملة->initializer.get());
    }

    uint32_t بداية_الحلقة = الإزاحة_الحالية();
    نطاق_حلقة حلقة;
    حلقة.بداية = بداية_الحلقة;
    السياق_->الحلقات.push_back(حلقة);

    // ترجمة الشرط (إن وُجد)
    uint32_t قفزة_نهاية = 0;
    bool يوجد_شرط = false;
    if (جملة->condition) {
        يوجد_شرط = true;
        ترجم_تعبير(جملة->condition.get());
        قفزة_نهاية = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(جملة));
    }

    // ترجمة الجسم
    ترجم_جملة(جملة->body.get());

    // ترجمة تعبير الزيادة (إن وُجد)
    if (جملة->increment) {
        ترجم_تعبير(جملة->increment.get());
        أصدر(عملية_سحب, سطر(جملة)); // نتجاهل نتيجة الزيادة
    }

    // العودة لبداية الحلقة
    أصدر_مع16(عملية_حلقة, static_cast<uint16_t>(بداية_الحلقة), سطر(جملة));

    // تصحيح قفزة النهاية
    if (يوجد_شرط) {
        صحّح_قفزة(قفزة_نهاية);
    }

    // تصحيح قفزات "توقف"
    auto& حلقة_حالية = السياق_->الحلقات.back();
    for (auto إزاحة : حلقة_حالية.قفزات_التوقف) {
        صحّح_قفزة(إزاحة);
    }
    السياق_->الحلقات.pop_back();

    اخرج_من_نطاق();
}

// ============================================================================
// ترجمة جملة "لكل في" (for-range / for-each)
// ============================================================================
// لكل (عنصر في مجموعة) { جسم }
// - نحوّلها لحلقة عادية باستخدام فهرس مؤقت
// البنية المُنتجة:
//   [ترجمة المجموعة] → المصفوفة على المكدس
//   فهرس = 0
//   @بداية:
//   فهرس < طول(المصفوفة) ؟
//   قفز_إذا_خطأ → @نهاية
//   عنصر = مصفوفة[فهرس]
//   [ترجمة الجسم]
//   فهرس++
//   حلقة → @بداية
//   @نهاية:
// ============================================================================

void مُترجم_بايت_كود::ترجم_لكل_في(Sad::AST::ForRangeStmt* جملة) {
    ادخل_نطاق();

    // ترجمة المجموعة القابلة للتكرار
    ترجم_تعبير(جملة->iterable.get());
    int فهرس_المجموعة = عرّف_محلي("__مجموعة__");

    // متغير الفهرس المؤقت
    أصدر(عملية_رقم_صغير, سطر(جملة));
    الوحدة_->اكتب(0); // البدء من الصفر
    int فهرس_العداد = عرّف_محلي("__عداد__");

    // متغير الحلقة (العنصر الحالي)
    أصدر(عملية_لا_شيء_قيمة, سطر(جملة));
    int فهرس_العنصر = عرّف_محلي(جملة->variable);

    uint32_t بداية_الحلقة = الإزاحة_الحالية();
    نطاق_حلقة حلقة;
    حلقة.بداية = بداية_الحلقة;
    السياق_->الحلقات.push_back(حلقة);

    // الشرط: عداد < طول(المجموعة)
    أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس_العداد), سطر(جملة));
    أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس_المجموعة), سطر(جملة));
    أصدر(عملية_مصفوفة_طول, سطر(جملة));
    أصدر(عملية_أصغر, سطر(جملة));

    uint32_t قفزة_نهاية = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(جملة));

    // تحميل العنصر الحالي: عنصر = مجموعة[عداد]
    أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس_المجموعة), سطر(جملة));
    أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس_العداد), سطر(جملة));
    أصدر(عملية_مصفوفة_قراءة, سطر(جملة));
    أصدر_مع8(عملية_تخزين_محلي, static_cast<uint8_t>(فهرس_العنصر), سطر(جملة));

    // ترجمة الجسم
    ترجم_جملة(جملة->body.get());

    // زيادة العداد
    أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس_العداد), سطر(جملة));
    أصدر(عملية_زيادة, سطر(جملة));
    أصدر_مع8(عملية_تخزين_محلي, static_cast<uint8_t>(فهرس_العداد), سطر(جملة));

    // العودة للبداية
    أصدر_مع16(عملية_حلقة, static_cast<uint16_t>(بداية_الحلقة), سطر(جملة));

    // تصحيح قفزة النهاية
    صحّح_قفزة(قفزة_نهاية);

    // تصحيح قفزات "توقف"
    auto& حلقة_حالية = السياق_->الحلقات.back();
    for (auto إزاحة : حلقة_حالية.قفزات_التوقف) {
        صحّح_قفزة(إزاحة);
    }
    السياق_->الحلقات.pop_back();

    اخرج_من_نطاق();
}

// ============================================================================
// ترجمة جملة "ارجع" (return)
// ============================================================================

void مُترجم_بايت_كود::ترجم_إرجاع(Sad::AST::ReturnStmt* جملة) {
    if (جملة->value) {
        // إرجاع بقيمة
        ترجم_تعبير(جملة->value.get());
        أصدر(عملية_عودة_بقيمة, سطر(جملة));
    } else {
        // إرجاع بدون قيمة
        أصدر(عملية_عودة, سطر(جملة));
    }
}

// ============================================================================
// ترجمة "توقف" (break) و"استمر" (continue)
// ============================================================================

void مُترجم_بايت_كود::ترجم_توقف(Sad::AST::BreakStmt* جملة) {
    if (السياق_->الحلقات.empty()) {
        خطأ_في(جملة, "لا يمكن استخدام 'توقف' خارج حلقة");
        return;
    }

    // قفزة مؤقتة ستُصحَّح عند نهاية الحلقة
    uint32_t إزاحة = أصدر_قفزة(عملية_قفز, سطر(جملة));
    السياق_->الحلقات.back().قفزات_التوقف.push_back(إزاحة);
}

void مُترجم_بايت_كود::ترجم_استمر(Sad::AST::ContinueStmt* جملة) {
    if (السياق_->الحلقات.empty()) {
        خطأ_في(جملة, "لا يمكن استخدام 'استمر' خارج حلقة");
        return;
    }

    // قفز لبداية الحلقة
    uint32_t بداية = السياق_->الحلقات.back().بداية;
    أصدر_مع16(عملية_حلقة, static_cast<uint16_t>(بداية), سطر(جملة));
}

// ============================================================================
// ترجمة تصريح دالة
// ============================================================================
// 1. نُسجّل اسم الدالة كمتغير عام (أو محلي)
// 2. نُنشئ سياق ترجمة جديد للدالة
// 3. نُترجم جسم الدالة في السياق الجديد
// 4. نُسجّل الدالة في الوحدة بمعلوماتها
// ============================================================================

void مُترجم_بايت_كود::ترجم_تصريح_دالة(Sad::AST::FunctionDecl* تصريح) {
    // حفظ السياق الحالي
    سياق_الترجمة سياق_الدالة;
    سياق_الدالة.اسم_الدالة = تصريح->name;
    سياق_الدالة.الأب = السياق_;
    سياق_الترجمة* السياق_السابق = السياق_;
    السياق_ = &سياق_الدالة;

    // تسجيل المعاملات كمتغيرات محلية
    for (const auto& معامل : تصريح->parameters) {
        عرّف_محلي(معامل.name);
    }

    // قفزة لتخطي جسم الدالة (سيُنفّذ عند الاستدعاء فقط)
    uint32_t قفزة_تخطي = أصدر_قفزة(عملية_قفز, سطر(تصريح));

    // تسجيل بداية الدالة
    uint32_t بداية_الدالة = الإزاحة_الحالية();

    // ترجمة جسم الدالة
    if (تصريح->body) {
        ترجم_جملة(تصريح->body.get());
    }

    // إضافة عودة ضمنية (إذا لم يكن هناك return صريح)
    أصدر(عملية_عودة, سطر(تصريح));

    // تسجيل الدالة في الوحدة
    الوحدة_->سجّل_دالة(
        تصريح->name,
        Sad::Security::SafeArithmetic::assertSafeCast<int>(تصريح->parameters.size(), "function_arity"),
        سياق_الدالة.عدد_المحليات_القصوى,
        بداية_الدالة
    );

    // العودة للسياق السابق
    السياق_ = السياق_السابق;

    // تصحيح القفزة لتخطي جسم الدالة
    صحّح_قفزة(قفزة_تخطي);

    // تسجيل الدالة كمتغير (لتمكين الاستدعاء)
    uint16_t فهرس_الاسم = الوحدة_->أضف_ثابت(قيمة::نص(تصريح->name));
    auto كائن_د = std::make_shared<كائن_دالة>(
        تصريح->name,
        Sad::Security::SafeArithmetic::assertSafeCast<int>(تصريح->parameters.size(), "function_arity"),
        سياق_الدالة.عدد_المحليات_القصوى,
        بداية_الدالة
    );
    uint16_t فهرس_الدالة = الوحدة_->أضف_ثابت(قيمة::دالة(كائن_د));
    أصدر_مع16(عملية_ثابت, فهرس_الدالة, سطر(تصريح));
    أصدر_مع16(عملية_تعريف_عام, فهرس_الاسم, سطر(تصريح));
}

// ============================================================================
// ترجمة تصريح صنف
// ============================================================================
// 1. أصدر تعريف الصنف بالاسم
// 2. لكل أب في الوراثة، أصدر عملية الوراثة
// 3. لكل طريقة/حقل في الأعضاء، سجّلهم
// ============================================================================

void مُترجم_بايت_كود::ترجم_تصريح_صنف(Sad::AST::ClassDecl* تصريح) {
    // إنشاء كائن الصنف
    uint16_t فهرس_الاسم = الوحدة_->أضف_ثابت(قيمة::نص(تصريح->name));
    أصدر_مع16(عملية_تعريف_صنف, فهرس_الاسم, سطر(تصريح));

    // الوراثة: لكل صنف أب
    for (const auto& أب : تصريح->superclasses) {
        uint16_t فهرس_أب = الوحدة_->أضف_ثابت(قيمة::نص(أب));
        أصدر_مع16(عملية_تحميل_عام, فهرس_أب, سطر(تصريح));
        أصدر(عملية_وراثة, سطر(تصريح));
    }

    // ترجمة الأعضاء (الطرق والحقول)
    for (const auto& عضو : تصريح->members) {
        if (auto* طريقة = dynamic_cast<Sad::AST::FunctionDecl*>(عضو.get())) {
            // ترجمة الطريقة كدالة
            ترجم_تصريح_دالة(طريقة);
        } else if (auto* طريقة_م = dynamic_cast<Sad::AST::MethodDecl*>(عضو.get())) {
            // ترجمة MethodDecl: ننشئ سياقاً جديداً
            سياق_الترجمة سياق_طريقة;
            سياق_طريقة.اسم_الدالة = طريقة_م->name;
            سياق_طريقة.الأب = السياق_;
            سياق_الترجمة* السياق_السابق = السياق_;
            السياق_ = &سياق_طريقة;

            // "هذا" هو المعامل الأول الضمني
            عرّف_محلي("هذا");
            for (const auto& معامل : طريقة_م->parameters) {
                عرّف_محلي(معامل.name);
            }

            uint32_t قفزة_تخطي = أصدر_قفزة(عملية_قفز, سطر(تصريح));
            uint32_t بداية = الإزاحة_الحالية();

            if (طريقة_م->body) {
                ترجم_جملة(طريقة_م->body.get());
            }
            أصدر(عملية_عودة, سطر(تصريح));

            الوحدة_->سجّل_دالة(
                تصريح->name + "." + طريقة_م->name,
                Sad::Security::SafeArithmetic::assertSafeCast<int>(طريقة_م->parameters.size(), "method_arity") + 1, // +1 لـ "هذا"
                سياق_طريقة.عدد_المحليات_القصوى,
                بداية
            );

            السياق_ = السياق_السابق;
            صحّح_قفزة(قفزة_تخطي);
        } else if (auto* حقل = dynamic_cast<Sad::AST::FieldDecl*>(عضو.get())) {
            // تجاهل الحقول حالياً (سيتم التعامل معها عند إنشاء الكائن)
            (void)حقل;
        }
    }

    // تسجيل الصنف كمتغير عام
    أصدر_مع16(عملية_تعريف_عام, فهرس_الاسم, سطر(تصريح));
}

// ============================================================================
// ترجمة جملة "حاول/امسك" (try/catch)
// ============================================================================

void مُترجم_بايت_كود::ترجم_حاول(Sad::AST::TryStmt* جملة) {
    // بداية كتلة حاول: سجّل عنوان المعالج
    uint32_t قفزة_معالج = أصدر_قفزة(عملية_حاول, سطر(جملة));

    // ترجمة كتلة المحاولة
    ترجم_جملة(جملة->tryBlock.get());

    // نهاية المحاولة بنجاح
    أصدر(عملية_نهاية_حاول, سطر(جملة));
    uint32_t قفزة_ما_بعد = أصدر_قفزة(عملية_قفز, سطر(جملة));

    // تصحيح عنوان المعالج ليشير هنا
    صحّح_قفزة(قفزة_معالج);

    // ترجمة كتل الالتقاط
    for (auto& التقاط : جملة->catchClauses) {
        ادخل_نطاق();
        // متغير الاستثناء: القيمة المرمية موجودة على المكدس
        if (!التقاط.exceptionVar.empty()) {
            عرّف_محلي(التقاط.exceptionVar);
        } else {
            أصدر(عملية_سحب, سطر(جملة)); // تجاهل الاستثناء
        }
        // ترجمة جسم الالتقاط
        ترجم_جملة(التقاط.body.get());
        اخرج_من_نطاق();
    }

    // تصحيح قفزة ما بعد المحاولة
    صحّح_قفزة(قفزة_ما_بعد);

    // ترجمة كتلة "أخيراً" (finally) إن وُجدت
    if (جملة->finallyBlock) {
        ترجم_جملة(جملة->finallyBlock.get());
    }
}

// ============================================================================
// ترجمة التعابير (Expressions)
// ============================================================================
// كل تعبير يترك نتيجة واحدة على قمة المكدس.
// هذا هو الموزّع المركزي للتعابير.
// ============================================================================

void مُترجم_بايت_كود::ترجم_تعبير(Sad::AST::Expression* تعبير) {
    if (!تعبير) return;

    if (auto* ثنائي = dynamic_cast<Sad::AST::BinaryExpr*>(تعبير)) {
        ترجم_ثنائي(ثنائي);
    }
    else if (auto* أحادي = dynamic_cast<Sad::AST::UnaryExpr*>(تعبير)) {
        ترجم_أحادي(أحادي);
    }
    else if (auto* حرفي = dynamic_cast<Sad::AST::LiteralExpr*>(تعبير)) {
        ترجم_حرفي(حرفي);
    }
    else if (auto* متغير = dynamic_cast<Sad::AST::VariableExpr*>(تعبير)) {
        ترجم_متغير(متغير);
    }
    else if (auto* إسناد = dynamic_cast<Sad::AST::AssignExpr*>(تعبير)) {
        ترجم_إسناد(إسناد);
    }
    else if (auto* استدعاء = dynamic_cast<Sad::AST::CallExpr*>(تعبير)) {
        ترجم_استدعاء(استدعاء);
    }
    else if (auto* مصفوفة = dynamic_cast<Sad::AST::ArrayExpr*>(تعبير)) {
        ترجم_مصفوفة(مصفوفة);
    }
    else if (auto* فهرسة = dynamic_cast<Sad::AST::IndexExpr*>(تعبير)) {
        ترجم_فهرسة(فهرسة);
    }
    else if (auto* عضو = dynamic_cast<Sad::AST::MemberExpr*>(تعبير)) {
        ترجم_عضو(عضو);
    }
    else if (auto* إسناد_عضو = dynamic_cast<Sad::AST::MemberAssignExpr*>(تعبير)) {
        ترجم_إسناد_عضو(إسناد_عضو);
    }
    else if (auto* جديد = dynamic_cast<Sad::AST::NewExpr*>(تعبير)) {
        ترجم_جديد(جديد);
    }
    else if (auto* هذا = dynamic_cast<Sad::AST::ThisExpr*>(تعبير)) {
        ترجم_هذا(هذا);
    }
    else if (auto* لامدا = dynamic_cast<Sad::AST::LambdaExpr*>(تعبير)) {
        ترجم_لامدا(لامدا);
    }
    else if (auto* ثلاثي = dynamic_cast<Sad::AST::TernaryExpr*>(تعبير)) {
        // التعبير الثلاثي: شرط ? صحيح : خطأ
        ترجم_تعبير(ثلاثي->condition.get());
        uint32_t قفزة_خطأ = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(تعبير));
        ترجم_تعبير(ثلاثي->trueExpr.get());
        uint32_t قفزة_نهاية = أصدر_قفزة(عملية_قفز, سطر(تعبير));
        صحّح_قفزة(قفزة_خطأ);
        ترجم_تعبير(ثلاثي->falseExpr.get());
        صحّح_قفزة(قفزة_نهاية);
    }
    else if (auto* قاموس = dynamic_cast<Sad::AST::MapExpr*>(تعبير)) {
        // ترجمة قاموس حرفي: { م1: ق1, م2: ق2 }
        for (auto& زوج : قاموس->pairs) {
            ترجم_تعبير(زوج.key.get());
            ترجم_تعبير(زوج.value.get());
        }
        أصدر_مع16(عملية_قاموس_جديد,
                   static_cast<uint16_t>(قاموس->pairs.size()), سطر(تعبير));
    }
    else if (auto* وصول_آمن = dynamic_cast<Sad::AST::OptionalChainExpr*>(تعبير)) {
        // (AR) وصول اختياري ?. — ترجم الكائن ثم استخدم عملية_وصول_اختياري
        // (EN) Optional chain ?. — compile object then emit OPTIONAL_CHAIN opcode
        ترجم_تعبير(وصول_آمن->object.get());
        uint16_t فهرس = الوحدة_->أضف_ثابت(قيمة::نص(وصول_آمن->member));
        أصدر_مع16(عملية_وصول_اختياري, فهرس, سطر(تعبير));
    }
    else if (auto* اندماج = dynamic_cast<Sad::AST::NullCoalesceExpr*>(تعبير)) {
        // (AR) اندماج صفري ?? — ترجم اليسار، فحص null، ثم اليمين
        // (EN) Null coalesce ?? — compile left, null check, then right
        ترجم_تعبير(اندماج->left.get());
        أصدر(عملية_نسخ, سطر(تعبير)); // (AR) نسخ اليسار لفحصه
        uint32_t قفزة_غير_null = أصدر_قفزة(عملية_قفز_إذا_صحيح, سطر(تعبير));
        أصدر(عملية_سحب, سطر(تعبير)); // (AR) سحب اليسار (null)
        ترجم_تعبير(اندماج->right.get()); // (AR) القيمة البديلة
        uint32_t قفزة_نهاية = أصدر_قفزة(عملية_قفز, سطر(تعبير));
        صحّح_قفزة(قفزة_غير_null); // (AR) إذا كان اليسار غير null، نستخدمه
        صحّح_قفزة(قفزة_نهاية);
    }
    else {
        // تعبير غير مدعوم حالياً
        خطأ("نوع تعبير غير مدعوم في مُترجم البايت كود", سطر(تعبير));
        // ادفع لا_شيء كقيمة بديلة
        أصدر(عملية_لا_شيء_قيمة, سطر(تعبير));
    }
}

// ============================================================================
// ترجمة تعبير ثنائي: أ + ب، أ > ب، أ و ب ...
// ============================================================================
// نترجم الطرف الأيسر أولاً، ثم الأيمن، ثم نصدر العملية المناسبة.
// النتيجة تبقى على قمة المكدس.
// ============================================================================

void مُترجم_بايت_كود::ترجم_ثنائي(Sad::AST::BinaryExpr* تعبير) {
    // حالة خاصة: "و" المنطقية - استدعاء اختصاري (short-circuit)
    if (تعبير->op == Sad::Lexer::TokenType::OP_AND) {
        ترجم_تعبير(تعبير->left.get());
        uint32_t قفزة = أصدر_قفزة(عملية_قفز_إذا_خطأ, سطر(تعبير));
        ترجم_تعبير(تعبير->right.get());
        أصدر(عملية_و, سطر(تعبير));
        صحّح_قفزة(قفزة);
        return;
    }

    // حالة خاصة: "أو" المنطقية - استدعاء اختصاري
    if (تعبير->op == Sad::Lexer::TokenType::OP_OR) {
        ترجم_تعبير(تعبير->left.get());
        uint32_t قفزة = أصدر_قفزة(عملية_قفز_إذا_صحيح, سطر(تعبير));
        ترجم_تعبير(تعبير->right.get());
        أصدر(عملية_أو, سطر(تعبير));
        صحّح_قفزة(قفزة);
        return;
    }

    // الحالة العادية: ترجم الطرفين ثم العملية
    ترجم_تعبير(تعبير->left.get());
    ترجم_تعبير(تعبير->right.get());

    // تحويل نوع العامل إلى رمز العملية المناسب
    switch (تعبير->op) {
        // العمليات الحسابية
        case Sad::Lexer::TokenType::OP_PLUS:
            أصدر(عملية_جمع, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_MINUS:
            أصدر(عملية_طرح, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_MULTIPLY:
            أصدر(عملية_ضرب, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_DIVIDE:
            أصدر(عملية_قسمة, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_MODULO:
            أصدر(عملية_باقي, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_POWER:
            أصدر(عملية_أس, سطر(تعبير));
            break;

        // عمليات المقارنة
        case Sad::Lexer::TokenType::OP_EQUAL:
            أصدر(عملية_يساوي, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_NOT_EQUAL:
            أصدر(عملية_لا_يساوي, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_LESS:
            أصدر(عملية_أصغر, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_LESS_EQUAL:
            أصدر(عملية_أصغر_يساوي, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_GREATER:
            أصدر(عملية_أكبر, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_GREATER_EQUAL:
            أصدر(عملية_أكبر_يساوي, سطر(تعبير));
            break;

        default:
            خطأ("عامل ثنائي غير مدعوم", سطر(تعبير));
            break;
    }
}

// ============================================================================
// ترجمة تعبير أحادي: -أ، !أ
// ============================================================================

void مُترجم_بايت_كود::ترجم_أحادي(Sad::AST::UnaryExpr* تعبير) {
    ترجم_تعبير(تعبير->operand.get());

    switch (تعبير->op) {
        case Sad::Lexer::TokenType::OP_MINUS:
            أصدر(عملية_سالب, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_NOT:
            أصدر(عملية_ليس, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_INCREMENT:
            أصدر(عملية_زيادة, سطر(تعبير));
            break;
        case Sad::Lexer::TokenType::OP_DECREMENT:
            أصدر(عملية_نقصان, سطر(تعبير));
            break;
        default:
            خطأ("عامل أحادي غير مدعوم", سطر(تعبير));
            break;
    }
}

// ============================================================================
// ترجمة قيمة حرفية: 42، 3.14، "نص"، صحيح، خطأ، لا_شيء
// ============================================================================
// نفحص نوع الرمز (token) لتحديد نوع القيمة ونُصدر التعليمة المناسبة.
// الأعداد الصغيرة (0-255) تستخدم عملية_رقم_صغير لتوفير المساحة.
// ============================================================================

void مُترجم_بايت_كود::ترجم_حرفي(Sad::AST::LiteralExpr* تعبير) {
    const auto& رمز = تعبير->token;

    switch (رمز.getType()) {
        case Sad::Lexer::TokenType::NUMBER_INTEGER: {
            // عدد صحيح
            int64_t ع = std::stoll(رمز.getValue());
            if (ع >= 0 && ع <= 255) {
                // تحسين: استخدام رقم صغير مباشر (بدون مجمع الثوابت)
                أصدر_مع8(عملية_رقم_صغير, static_cast<uint8_t>(ع), سطر(تعبير));
            } else {
                أصدر_ثابت(قيمة::صحيح(ع), سطر(تعبير));
            }
            break;
        }

        case Sad::Lexer::TokenType::NUMBER_DOUBLE: {
            // عدد عشري
            double ع = std::stod(رمز.getValue());
            أصدر_ثابت(قيمة::عشري(ع), سطر(تعبير));
            break;
        }

        case Sad::Lexer::TokenType::STRING_LITERAL: {
            // نص حرفي
            أصدر_ثابت(قيمة::نص(رمز.getValue()), سطر(تعبير));
            break;
        }

        case Sad::Lexer::TokenType::LITERAL_TRUE: {
            أصدر(عملية_صحيح, سطر(تعبير));
            break;
        }

        case Sad::Lexer::TokenType::LITERAL_FALSE: {
            أصدر(عملية_خطأ, سطر(تعبير));
            break;
        }

        case Sad::Lexer::TokenType::LITERAL_NULL: {
            أصدر(عملية_لا_شيء_قيمة, سطر(تعبير));
            break;
        }

        default:
            خطأ("نوع حرفي غير مدعوم: " + رمز.getValue(), سطر(تعبير));
            أصدر(عملية_لا_شيء_قيمة, سطر(تعبير));
            break;
    }
}

// ============================================================================
// ترجمة مرجع متغير: تحميل قيمة المتغير
// ============================================================================
// ترتيب البحث: محلي أولاً → علوي → عام
// ============================================================================

void مُترجم_بايت_كود::ترجم_متغير(Sad::AST::VariableExpr* تعبير) {
    // أولاً: البحث في المتغيرات المحلية
    int فهرس = ابحث_محلي(تعبير->name);
    if (فهرس >= 0) {
        أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس), سطر(تعبير));
        return;
    }

    // ثانياً: البحث في القيم العلوية (للإغلاقات)
    int فهرس_علوي = ابحث_علوي(تعبير->name);
    if (فهرس_علوي >= 0) {
        أصدر_مع8(عملية_تحميل_علوية, static_cast<uint8_t>(فهرس_علوي), سطر(تعبير));
        return;
    }

    // ثالثاً: متغير عام
    uint16_t فهرس_الاسم = الوحدة_->أضف_ثابت(قيمة::نص(تعبير->name));
    أصدر_مع16(عملية_تحميل_عام, فهرس_الاسم, سطر(تعبير));
}

// ============================================================================
// ترجمة إسناد: س = تعبير
// ============================================================================

void مُترجم_بايت_كود::ترجم_إسناد(Sad::AST::AssignExpr* تعبير) {
    // ترجمة القيمة الجديدة
    ترجم_تعبير(تعبير->value.get());

    // البحث عن المتغير
    int فهرس = ابحث_محلي(تعبير->name);
    if (فهرس >= 0) {
        // فحص الثبات
        if (السياق_->المحليات[فهرس].ثابت) {
            خطأ("لا يمكن تغيير الثابت '" + تعبير->name + "'", سطر(تعبير));
            return;
        }
        أصدر_مع8(عملية_تخزين_محلي, static_cast<uint8_t>(فهرس), سطر(تعبير));
        // الإسناد أيضاً تعبير يُرجع القيمة المُسندة
        أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس), سطر(تعبير));
        return;
    }

    int فهرس_علوي = ابحث_علوي(تعبير->name);
    if (فهرس_علوي >= 0) {
        أصدر_مع8(عملية_تخزين_علوية, static_cast<uint8_t>(فهرس_علوي), سطر(تعبير));
        أصدر_مع8(عملية_تحميل_علوية, static_cast<uint8_t>(فهرس_علوي), سطر(تعبير));
        return;
    }

    // متغير عام
    uint16_t فهرس_الاسم = الوحدة_->أضف_ثابت(قيمة::نص(تعبير->name));
    أصدر_مع16(عملية_تخزين_عام, فهرس_الاسم, سطر(تعبير));
    // لإرجاع القيمة من الإسناد
    أصدر_مع16(عملية_تحميل_عام, فهرس_الاسم, سطر(تعبير));
}

// ============================================================================
// ترجمة استدعاء دالة: دالة(مع1، مع2)
// ============================================================================
// 1. ترجم الدالة (قد تكون متغير أو تعبير عضو)
// 2. ترجم كل المعاملات على المكدس
// 3. أصدر عملية الاستدعاء مع عدد المعاملات
// ============================================================================

void مُترجم_بايت_كود::ترجم_استدعاء(Sad::AST::CallExpr* تعبير) {
    // هل هو استدعاء طريقة على كائن؟ مثل: كائن.طريقة(...)
    if (auto* عضو = dynamic_cast<Sad::AST::MemberExpr*>(تعبير->callee.get())) {
        // استدعاء طريقة
        ترجم_تعبير(عضو->object.get()); // الكائن

        // ترجمة المعاملات
        for (const auto& معامل : تعبير->arguments) {
            ترجم_تعبير(معامل.get());
        }

        // أصدر استدعاء طريقة
        uint16_t فهرس_اسم = الوحدة_->أضف_ثابت(قيمة::نص(عضو->member));
        أصدر_مع16(عملية_استدعاء_طريقة, فهرس_اسم, سطر(تعبير));
        الوحدة_->اكتب(static_cast<بايت>(تعبير->arguments.size()), سطر(تعبير));
        return;
    }

    // استدعاء عادي
    ترجم_تعبير(تعبير->callee.get());

    // ترجمة المعاملات
    for (const auto& معامل : تعبير->arguments) {
        ترجم_تعبير(معامل.get());
    }

    // أصدر عملية الاستدعاء
    أصدر_مع8(عملية_استدعاء,
              static_cast<uint8_t>(تعبير->arguments.size()), سطر(تعبير));
}

// ============================================================================
// ترجمة مصفوفة حرفية: [1، 2، 3]
// ============================================================================

void مُترجم_بايت_كود::ترجم_مصفوفة(Sad::AST::ArrayExpr* تعبير) {
    // ترجمة كل العناصر على المكدس
    for (const auto& عنصر : تعبير->elements) {
        ترجم_تعبير(عنصر.get());
    }
    // إنشاء المصفوفة من العناصر على المكدس
    أصدر_مع16(عملية_مصفوفة_جديدة,
              static_cast<uint16_t>(تعبير->elements.size()), سطر(تعبير));
}

// ============================================================================
// ترجمة فهرسة: م[ف]
// ============================================================================

void مُترجم_بايت_كود::ترجم_فهرسة(Sad::AST::IndexExpr* تعبير) {
    ترجم_تعبير(تعبير->object.get());  // المصفوفة/القاموس
    ترجم_تعبير(تعبير->index.get());   // الفهرس/المفتاح
    أصدر(عملية_مصفوفة_قراءة, سطر(تعبير));
}

// ============================================================================
// ترجمة الوصول لعضو: كائن.حقل
// ============================================================================

void مُترجم_بايت_كود::ترجم_عضو(Sad::AST::MemberExpr* تعبير) {
    ترجم_تعبير(تعبير->object.get());
    uint16_t فهرس = الوحدة_->أضف_ثابت(قيمة::نص(تعبير->member));
    أصدر_مع16(عملية_حقل_قراءة, فهرس, سطر(تعبير));
}

// ============================================================================
// ترجمة إسناد لعضو: كائن.حقل = قيمة
// ============================================================================

void مُترجم_بايت_كود::ترجم_إسناد_عضو(Sad::AST::MemberAssignExpr* تعبير) {
    ترجم_تعبير(تعبير->object.get());   // الكائن
    ترجم_تعبير(تعبير->value.get());    // القيمة الجديدة
    uint16_t فهرس = الوحدة_->أضف_ثابت(قيمة::نص(تعبير->member));
    أصدر_مع16(عملية_حقل_كتابة, فهرس, سطر(تعبير));
}

// ============================================================================
// ترجمة "جديد": جديد صنف(...)
// ============================================================================

void مُترجم_بايت_كود::ترجم_جديد(Sad::AST::NewExpr* تعبير) {
    // className هو اسم الصنف
    // نُحمّل الصنف ونُنشئ كائناً جديداً

    // تحميل الصنف باسمه من المتغيرات العامة
    أصدر_ثابت(قيمة::نص(تعبير->className), سطر(تعبير));
    أصدر(عملية_تحميل_عام, سطر(تعبير));

    for (const auto& معامل : تعبير->arguments) {
        ترجم_تعبير(معامل.get());
    }

    أصدر_مع8(عملية_استدعاء,
              static_cast<uint8_t>(تعبير->arguments.size()), سطر(تعبير));
}

// ============================================================================
// ترجمة "هذا" (this)
// ============================================================================

void مُترجم_بايت_كود::ترجم_هذا(Sad::AST::ThisExpr* تعبير) {
    // "هذا" هو دائماً المتغير المحلي الأول في الطرق
    int فهرس = ابحث_محلي("هذا");
    if (فهرس >= 0) {
        أصدر_مع8(عملية_تحميل_محلي, static_cast<uint8_t>(فهرس), سطر(تعبير));
    } else {
        أصدر(عملية_هذا, سطر(تعبير));
    }
}

// ============================================================================
// ترجمة لامدا (دالة مجهولة)
// ============================================================================

void مُترجم_بايت_كود::ترجم_لامدا(Sad::AST::LambdaExpr* تعبير) {
    // إنشاء سياق جديد للامدا
    سياق_الترجمة سياق_لامدا;
    سياق_لامدا.اسم_الدالة = "<لامدا>";
    سياق_لامدا.الأب = السياق_;
    سياق_الترجمة* السياق_السابق = السياق_;
    السياق_ = &سياق_لامدا;

    // تسجيل المعاملات
    for (const auto& معامل : تعبير->parameters) {
        عرّف_محلي(معامل.name);
    }

    // قفزة لتخطي جسم اللامدا
    uint32_t قفزة_تخطي = أصدر_قفزة(عملية_قفز, سطر(تعبير));
    uint32_t بداية = الإزاحة_الحالية();

    // ترجمة جسم اللامدا (تعبير واحد يُرجع قيمته)
    ترجم_تعبير(تعبير->body.get());
    أصدر(عملية_عودة_بقيمة, سطر(تعبير));

    // تسجيل الدالة
    static int عداد_لامدا = 0;
    std::string اسم_لامدا = "<لامدا_" + std::to_string(عداد_لامدا++) + ">";
    الوحدة_->سجّل_دالة(
        اسم_لامدا,
        Sad::Security::SafeArithmetic::assertSafeCast<int>(تعبير->parameters.size(), "lambda_arity"),
        سياق_لامدا.عدد_المحليات_القصوى,
        بداية
    );

    السياق_ = السياق_السابق;
    صحّح_قفزة(قفزة_تخطي);

    // إنشاء كائن الدالة ودفعه على المكدس
    auto كائن_د = std::make_shared<كائن_دالة>(
        اسم_لامدا,
        Sad::Security::SafeArithmetic::assertSafeCast<int>(تعبير->parameters.size(), "lambda_arity"),
        سياق_لامدا.عدد_المحليات_القصوى,
        بداية
    );

    // هل هناك قيم علوية؟ (إغلاق)
    if (!سياق_لامدا.العلويات.empty()) {
        uint16_t فهرس = الوحدة_->أضف_ثابت(قيمة::دالة(كائن_د));
        أصدر_مع16(عملية_إغلاق, فهرس, سطر(تعبير));
        // إصدار معلومات القيم العلوية
        for (const auto& علوية : سياق_لامدا.العلويات) {
            الوحدة_->اكتب(علوية.محلي ? 1 : 0);
            الوحدة_->اكتب(علوية.الفهرس);
        }
    } else {
        uint16_t فهرس = الوحدة_->أضف_ثابت(قيمة::دالة(كائن_د));
        أصدر_مع16(عملية_ثابت, فهرس, سطر(تعبير));
    }
}

// ============================================================================
// إدارة المتغيرات والنطاقات
// ============================================================================

void مُترجم_بايت_كود::ادخل_نطاق() {
    السياق_->عمق_النطاق++;
}

void مُترجم_بايت_كود::اخرج_من_نطاق() {
    السياق_->عمق_النطاق--;

    // سحب المتغيرات المحلية التي أصبحت خارج النطاق
    while (!السياق_->المحليات.empty() &&
           السياق_->المحليات.back().العمق > السياق_->عمق_النطاق) {

        if (السياق_->المحليات.back().محتجز) {
            // إغلاق القيمة العلوية (نقلها للكومة)
            أصدر(عملية_إغلاق_علوية, 0);
        } else {
            // مجرد سحب من المكدس
            أصدر(عملية_سحب, 0);
        }
        السياق_->المحليات.pop_back();
    }
}

int مُترجم_بايت_كود::عرّف_محلي(const std::string& اسم, bool ثابت) {
    // التأكد من عدم تكرار الاسم في نفس النطاق
    for (int ف = Sad::Security::SafeArithmetic::assertSafeCast<int>(السياق_->المحليات.size(), "locals_index") - 1; ف >= 0; ف--) {
        if (السياق_->المحليات[ف].العمق < السياق_->عمق_النطاق) break;
        if (السياق_->المحليات[ف].الاسم == اسم) {
            خطأ("المتغير '" + اسم + "' مُعرّف مسبقاً في هذا النطاق");
            return ف;
        }
    }

    السياق_->المحليات.emplace_back(اسم, السياق_->عمق_النطاق, ثابت);
    int فهرس = Sad::Security::SafeArithmetic::assertSafeCast<int>(السياق_->المحليات.size(), "locals_index") - 1;

    // تحديث العدد الأقصى للمحليات
    if (فهرس + 1 > السياق_->عدد_المحليات_القصوى) {
        السياق_->عدد_المحليات_القصوى = فهرس + 1;
    }

    return فهرس;
}

int مُترجم_بايت_كود::ابحث_محلي(const std::string& اسم) const {
    // البحث من الأعلى (النطاق الأعمق) إلى الأسفل
    for (int ف = Sad::Security::SafeArithmetic::assertSafeCast<int>(السياق_->المحليات.size(), "locals_index") - 1; ف >= 0; ف--) {
        if (السياق_->المحليات[ف].الاسم == اسم) {
            return ف;
        }
    }
    return -1;
}

int مُترجم_بايت_كود::ابحث_علوي(const std::string& اسم) {
    // البحث في السياقات المحيطة (للإغلاقات)
    if (!السياق_->الأب) return -1;

    // البحث في المحليات المحيطة
    سياق_الترجمة* السياق_المحيط = السياق_->الأب;
    for (int ف = Sad::Security::SafeArithmetic::assertSafeCast<int>(السياق_المحيط->المحليات.size(), "enclosing_locals_index") - 1; ف >= 0; ف--) {
        if (السياق_المحيط->المحليات[ف].الاسم == اسم) {
            // وجدناه! أنشئ قيمة علوية
            السياق_المحيط->المحليات[ف].محتجز = true;
            معلومات_علوية علوية;
            علوية.الفهرس = static_cast<uint8_t>(ف);
            علوية.محلي = true;
            السياق_->العلويات.push_back(علوية);
            return Sad::Security::SafeArithmetic::assertSafeCast<int>(السياق_->العلويات.size(), "upvalues_index") - 1;
        }
    }

    return -1;
}

