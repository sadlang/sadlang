// الإبلاغ عن الأخطاء
// ============================================================================

void مُترجم_بايت_كود::خطأ(const std::string& رسالة, uint32_t سطر) {
    std::string نص_الخطأ = "[خطأ ترجمة بايت كود]";
    if (سطر > 0) {
        نص_الخطأ += " سطر " + std::to_string(سطر) + ":";
    }
    نص_الخطأ += " " + رسالة;
    الأخطاء_.push_back(نص_الخطأ);
    std::cerr << نص_الخطأ << std::endl;
}

void مُترجم_بايت_كود::خطأ_في(Sad::AST::ASTNode* عقدة, const std::string& رسالة) {
    خطأ(رسالة, سطر(عقدة));
}

