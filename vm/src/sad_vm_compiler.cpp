// مساعدات إصدار البايت كود
// ============================================================================

void مُترجم_بايت_كود::أصدر(رمز_عملية عملية, uint32_t سطر) {
    الوحدة_->اكتب(عملية, سطر);
}

void مُترجم_بايت_كود::أصدر_مع8(رمز_عملية عملية, uint8_t معامل, uint32_t سطر) {
    الوحدة_->اكتب_عملية_ومعامل8(عملية, معامل, سطر);
}

void مُترجم_بايت_كود::أصدر_مع16(رمز_عملية عملية, uint16_t معامل, uint32_t سطر) {
    الوحدة_->اكتب_عملية_ومعامل16(عملية, معامل, سطر);
}

void مُترجم_بايت_كود::أصدر_ثابت(const قيمة& ق, uint32_t سطر) {
    uint16_t فهرس = الوحدة_->أضف_ثابت(ق);
    أصدر_مع16(عملية_ثابت, فهرس, سطر);
}

uint32_t مُترجم_بايت_كود::أصدر_قفزة(رمز_عملية عملية_قفز, uint32_t سطر) {
    return الوحدة_->اكتب_قفزة_مؤقتة(عملية_قفز, سطر);
}

