// ============================================================================
// sad_vm_compiler.cpp - مُترجم شجرة AST إلى بايت كود
// AST to Bytecode Compiler Implementation for Sad Language VM
// ============================================================================
//
// هذا الملف هو الجسر الأهم بين الواجهة الأمامية (المُحلل) والآلة الافتراضية.
// يأخذ شجرة AST المُنتجة من المُحلل ويُولّد بايت كود قابل للتنفيذ.
//
// سير العمل:
//   1. يستقبل قائمة الجمل (statements) من المُحلل
//   2. يمشي على كل عقدة بنمط الزائر (visitor pattern)
//   3. يُصدر تعليمات البايت كود المناسبة لكل عقدة
//   4. يُدير جدول المتغيرات المحلية والعامة
//   5. يُنتج وحدة_بايت_كود جاهزة للتنفيذ
//
// مثال تفصيلي:
//   كود ص:           إذا (س > 5) { اطبع_سطر("كبير") }
//   البايت كود المُنتج:
//     تحميل_محلي 0       ← تحميل قيمة "س"
//     ثابت 0 (5)         ← دفع الرقم 5
//     أكبر               ← المقارنة: س > 5
//     قفز_إذا_خطأ @XX    ← تخطي الكتلة إذا الشرط خطأ
//     ثابت 1 ("كبير")    ← دفع النص
//     اطبع_سطر           ← طباعة
//     @XX:               ← نقطة ما بعد الكتلة
//
// ============================================================================

#include "sad_vm_compiler.h"

#include <iostream>
#include <algorithm>
#include <cstdlib>
#include <cassert>

// (AR) تحويل عددي آمن (size_t → int) لتسجيل arity الدوال وفهارس المحليات/العلويات.
// (EN) Bounds-checked size_t → int for function arity registration and local/upvalue indexing.
#include "safe_arithmetic.h"

