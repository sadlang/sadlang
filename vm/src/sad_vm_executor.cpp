void آلة_افتراضية::عيّن_عام(const std::string& اسم, const قيمة& ق) {
    العامة_[اسم] = ق;
}

قيمة آلة_افتراضية::اقرأ_عام(const std::string& اسم) const {
    auto بحث = العامة_.find(اسم);
    if (بحث != العامة_.end()) return بحث->second;
    return قيمة::لا_شيء();
}

bool آلة_افتراضية::يوجد_عام(const std::string& اسم) const {
    return العامة_.find(اسم) != العامة_.end();
}

