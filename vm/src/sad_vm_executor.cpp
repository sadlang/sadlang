uint32_t آلة_افتراضية::السطر_الحالي() const {
    if (الوحدة_ && !الإطارات_.empty()) {
        return الوحدة_->رقم_السطر(الإطارات_.back().مؤشر_التعليمة);
    }
    return 0;
}

نتيجة_التنفيذ آلة_افتراضية::خطأ_تشغيل(const std::string& رسالة) {
    نتيجة_التنفيذ نتيجة;
    نتيجة.الحالة = حالة_التنفيذ::خطأ_تشغيل;
    نتيجة.رسالة_الخطأ = رسالة;
    نتيجة.سطر_الخطأ = السطر_الحالي();
    نتيجة.عدد_التعليمات = عدّاد_التعليمات_;

    // طباعة تتبع المكدس
    std::cerr << "\n╔══ خطأ تشغيل ═══════════════════════════════════╗\n";
    std::cerr << "║ " << رسالة << "\n";
    if (نتيجة.سطر_الخطأ > 0) {
        std::cerr << "║ في السطر: " << نتيجة.سطر_الخطأ << "\n";
    }
    اطبع_تتبع_المكدس();
    std::cerr << "╚═══════════════════════════════════════════════════╝\n";

    قيد_التشغيل_ = false;
    return نتيجة;
}

void آلة_افتراضية::اطبع_تتبع_المكدس() const {
    std::cerr << "║\n║ تتبع الاستدعاءات:\n";
    for (int ف = static_cast<int>(الإطارات_.size()) - 1; ف >= 0; ف--) {
        const auto& إطار = الإطارات_[ف];
        std::cerr << "║   [" << ف << "] ";
        if (إطار.الدالة) {
            std::cerr << إطار.الدالة->الاسم;
        } else {
            std::cerr << "<مجهول>";
        }
        if (الوحدة_) {
            std::cerr << " (سطر " << الوحدة_->رقم_السطر(إطار.مؤشر_التعليمة) << ")";
        }
        std::cerr << "\n";
    }
}

