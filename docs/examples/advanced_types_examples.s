# 2. الأنواع العامة (Generic Types)
# =============================================================================

# مصفوفة من الأرقام
# Array of numbers
متغير أرقام: مصفوفة<رقم> = [1، 2، 3، 4، 5]

# مصفوفة من النصوص
# Array of strings
متغير أسماء: مصفوفة<نص> = ["أحمد"، "محمد"، "فاطمة"]

# قاموس من نص إلى رقم
# Dictionary from string to number
متغير أعمار: قاموس<نص، رقم> = {
    "أحمد": 25،
    "محمد": 30،
    "فاطمة": 28
}

# قاموس متداخل
# Nested dictionary
متغير بيانات_الموظفين: قاموس<نص، قاموس<نص، رقم>> = {
    "أحمد": {
        "العمر": 25،
        "الراتب": 5000
    }،
    "محمد": {
        "العمر": 30،
        "الراتب": 6000
    }
}

# مصفوفة من المصفوفات (مصفوفة ثنائية الأبعاد)
# Array of arrays (2D array)
متغير مصفوفة_ثنائية: مصفوفة<مصفوفة<رقم>> = [
    [1، 2، 3]،
    [4، 5، 6]،
    [7، 8، 9]
]

# =============================================================================
# 3. أنواع الاتحاد (Union Types)
# =============================================================================

# متغير يمكن أن يكون رقماً أو نصاً
# Variable that can be number or string
متغير قيمة: رقم | نص = 42
قيمة = "نص الآن"  # يمكن تغيير النوع

# دالة تقبل رقم أو نص
# Function that accepts number or string
دالة طباعة_القيمة(ق: رقم | نص) {
    اطبع("القيمة: " + ق)
}

طباعة_القيمة(100)
طباعة_القيمة("مرحبا")

# نوع اتحاد متعدد
# Multiple union type
متغير نتيجة: رقم | نص | منطقي = صحيح
نتيجة = 42
نتيجة = "نجح"

# دالة تُرجع نوع اتحاد
# Function returning union type
دالة رقم | نص احصل_على_قيمة(استخدم_رقم: منطقي) {
    إذا (استخدم_رقم) {
        إرجاع 42
    } وإلا {
        إرجاع "قيمة نصية"
    }
}

متغير النتيجة1 = احصل_على_قيمة(صحيح)   # رقم
متغير النتيجة2 = احصل_على_قيمة(خطأ)     # نص

# =============================================================================
# 4. الأنواع الاختيارية (Optional Types)
# =============================================================================

# متغير اختياري (يمكن أن يكون null)
# Optional variable (can be null)
متغير عمر_اختياري: رقم? = 25
عمر_اختياري = لاشيء  # null

# دالة تُرجع قيمة اختيارية
# Function returning optional value
دالة رقم? ابحث_عن_عمر(الاسم: نص) {
    إذا (الاسم == "أحمد") {
        إرجاع 25
    } وإلا {
        إرجاع لاشيء  # لم يُعثر على الشخص
    }
}

متغير عمر1 = ابحث_عن_عمر("أحمد")    # رقم? = 25
متغير عمر2 = ابحث_عن_عمر("غير_موجود") # رقم? = لاشيء

# استخدام القيمة الاختيارية بأمان
# Safely using optional value
إذا (عمر1 != لاشيء) {
    اطبع("العمر: " + عمر1)
} وإلا {
    اطبع("لم يُعثر على العمر")
}

# مصفوفة من قيم اختيارية
# Array of optional values
متغير أعمار_اختيارية: مصفوفة<رقم?> = [25، لاشيء، 30، لاشيء، 28]

# قاموس بقيم اختيارية
# Dictionary with optional values
متغير معلومات: قاموس<نص، نص?> = {
    "الاسم": "أحمد"،
    "العنوان": لاشيء،
    "الهاتف": "1234567890"
}

# =============================================================================
# 5. أنواع الدوال (Function Types)
# =============================================================================

# متغير من نوع دالة
# Variable of function type
متغير عملية: (رقم، رقم) -> رقم

# تعيين دالة جمع
# Assign addition function
دالة رقم جمع(أ: رقم، ب: رقم) {
    إرجاع أ + ب
}
عملية = جمع

# تعيين دالة ضرب
# Assign multiplication function
دالة رقم ضرب(أ: رقم، ب: رقم) {
    إرجاع أ * ب
}
عملية = ضرب

# استخدام الدالة
# Using the function
متغير نتيجة = عملية(5، 3)  # 15 (ضرب)

# دالة تقبل دالة كمعامل (Higher-Order Function)
# Function that accepts a function as parameter
دالة رقم تطبيق_العملية(أ: رقم، ب: رقم، عملية: (رقم، رقم) -> رقم) {
    إرجاع عملية(أ، ب)
}

متغير مجموع = تطبيق_العملية(10، 5، جمع)   # 15
متغير حاصل_الضرب = تطبيق_العملية(10، 5، ضرب) # 50

# دالة Lambda بنوع دالة
# Lambda function with function type
متغير طرح: (رقم، رقم) -> رقم = دالة(أ، ب) { إرجاع أ - ب }
متغير فرق = طرح(10، 3)  # 7

# دالة تُرجع دالة
# Function that returns a function
دالة (رقم) -> رقم انشئ_مضاعف(عامل: رقم) {
    إرجاع دالة(س) { إرجاع س * عامل }
}

متغير ضعف = انشئ_مضاعف(2)
متغير ثلاثة_أضعاف = انشئ_مضاعف(3)

اطبع(ضعف(5))         # 10
اطبع(ثلاثة_أضعاف(5)) # 15

# مصفوفة من الدوال
# Array of functions
متغير عمليات: مصفوفة<(رقم، رقم) -> رقم> = [جمع، طرح، ضرب]

لكل عملية في عمليات {
    اطبع(عملية(10، 5))
}

