# مجموعة بسيطة (زوج)
# Simple tuple (pair)
متغير نقطة: (رقم، رقم) = (10، 20)

# مجموعة مع أنواع مختلفة
# Tuple with different types
متغير معلومات_الشخص: (نص، رقم، منطقي) = ("أحمد"، 25، صحيح)

# دالة تُرجع مجموعة
# Function returning tuple
دالة (رقم، رقم) احصل_على_احداثيات() {
