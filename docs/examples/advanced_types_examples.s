# 1. الأنواع البسيطة (Simple Types)
# =============================================================================

# تصريح متغيرات بأنواع بسيطة
# Simple type variable declarations
متغير عمر: رقم = 25
متغير الاسم: نص = "أحمد"
متغير نشط: منطقي = صحيح
متغير الراتب: عشري = 5000.50

# يمكن استخدام الأسماء الإنجليزية أيضاً
# English names are also supported
var age: integer = 25
var name: string = "Ahmed"
var active: boolean = true
var salary: float = 5000.50

