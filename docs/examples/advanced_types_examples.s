# 9. أمثلة معقدة ومتداخلة (Complex and Nested Examples)
# =============================================================================

# نوع معقد: قاموس من نص إلى مصفوفة من أنواع اتحاد اختيارية
# Complex type: dictionary from string to array of optional union types
متغير بيانات_معقدة: قاموس<نص، مصفوفة<(رقم | نص)?>> = {
    "مجموعة1": [42، "نص"، لاشيء، 100]،
    "مجموعة2": ["أ"، "ب"، لاشيء، 50]
}

# دالة معقدة تقبل دالة وتُرجع دالة
# Complex function that accepts a function and returns a function
دالة ((رقم) -> رقم) -> ((رقم) -> رقم) دمج_الدوال(
    دالة1: (رقم) -> رقم،
    دالة2: (رقم) -> رقم
) {
    إرجاع دالة(س) {
        إرجاع دالة2(دالة1(س))
    }
}

متغير مربع = دالة(س) { إرجاع س * س }
متغير ضعف_المربع = دمج_الدوال(مربع، دالة(س) { إرجاع س * 2 })
اطبع(ضعف_المربع(5))  # (5^2) * 2 = 50

# مصفوفة من دوال تُرجع قيم اختيارية
# Array of functions that return optional values
متغير محولات: مصفوفة<(نص) -> رقم?> = [
    دالة(س) {
        إذا (س == "واحد") { إرجاع 1 }
        إرجاع لاشيء
    }،
    دالة(س) {
        إذا (س == "اثنان") { إرجاع 2 }
        إرجاع لاشيء
    }
]

