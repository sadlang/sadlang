# --- مثال 1: نظام إدارة المستخدمين ---
# --- Example 1: User Management System ---

صنف مستخدم {
    عام الاسم: نص
    عام العمر: رقم?
    عام البريد_الإلكتروني: نص?
    عام الصلاحيات: مصفوفة<نص>
    
    دالة بناء(اسم: نص) {
        هذا.الاسم = اسم
        هذا.العمر = لاشيء
        هذا.البريد_الإلكتروني = لاشيء
        هذا.الصلاحيات = []
    }
}

# قاموس المستخدمين
# Users dictionary
متغير المستخدمون: قاموس<نص، مستخدم> = {}

# دالة إضافة مستخدم
# Add user function
دالة منطقي اضف_مستخدم(معرف: نص، مستخدم: مستخدم) {
    المستخدمون[معرف] = مستخدم
    إرجاع صحيح
}

# دالة البحث عن مستخدم
# Find user function
دالة مستخدم? ابحث_عن_مستخدم(معرف: نص) {
    إذا (معرف في المستخدمون) {
        إرجاع المستخدمون[معرف]
    }
    إرجاع لاشيء
}

# --- مثال 2: معالج البيانات مع دوال Callback ---
# --- Example 2: Data Processor with Callback Functions ---

# نوع دالة المعالجة
# Processing function type
متغير معالج_بيانات: ((رقم | نص) -> (رقم | نص))?

# دالة معالجة البيانات
# Process data function
دالة مصفوفة<رقم | نص> عالج_البيانات(
    البيانات: مصفوفة<رقم | نص>،
    المعالج: ((رقم | نص) -> (رقم | نص))?
) {
    إذا (المعالج == لاشيء) {
        إرجاع البيانات  # لا معالجة
    }
    
    متغير النتيجة: مصفوفة<رقم | نص> = []
    لكل عنصر في البيانات {
        النتيجة.اضف(المعالج(عنصر))
    }
    إرجاع النتيجة
}

# استخدام
# Usage
متغير بيانات: مصفوفة<رقم | نص> = [1، "2"، 3، "4"، 5]
متغير النتيجة = عالج_البيانات(بيانات، دالة(س) {
    إذا (نوع(س) == "رقم") {
        إرجاع س * 2
    } وإلا {
        إرجاع س + س
    }
})

# --- مثال 3: نظام التحقق من البيانات ---
# --- Example 3: Data Validation System ---

# نوع قاعدة التحقق
# Validation rule type
متغير قاعدة_تحقق: (أي) -> منطقي

# دالة التحقق من البيانات
# Validate data function
دالة منطقي تحقق_من_البيانات(
    القيمة: أي،
    القواعد: مصفوفة<(أي) -> منطقي>
) {
    لكل قاعدة في القواعد {
        إذا (!قاعدة(القيمة)) {
            إرجاع خطأ
        }
    }
    إرجاع صحيح
}

# قواعد التحقق
# Validation rules
متغير قواعد_العمر: مصفوفة<(أي) -> منطقي> = [
    دالة(ق) { إرجاع نوع(ق) == "رقم" }،
    دالة(ق) { إرجاع ق >= 0 }،
    دالة(ق) { إرجاع ق <= 120 }
]

متغير عمر = 25
إذا (تحقق_من_البيانات(عمر، قواعد_العمر)) {
    اطبع("العمر صحيح")
} وإلا {
    اطبع("العمر غير صحيح")
}

