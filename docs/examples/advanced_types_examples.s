}

متغير (س، ص) = احصل_على_احداثيات()
اطبع("س = " + س + "، ص = " + ص)

# مصفوفة من المجموعات
# Array of tuples
متغير نقاط: مصفوفة<(رقم، رقم)> = [
    (0، 0)،
    (10، 10)،
    (20، 20)
]

# أو بشكل مختصر
# Or in shorthand
متغير نقاط2: (رقم، رقم)[] = [
    (0، 0)،
    (10، 10)،
    (20، 20)
]

# مجموعة متداخلة
# Nested tuple
متغير بيانات_معقدة: (نص، (رقم، رقم)، منطقي) = (
    "نقطة أ"،
    (100، 200)،
    صحيح
)

