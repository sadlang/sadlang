# دالة عامة للبحث في مصفوفة
# Generic function to search in array
دالة رقم? ابحث_في_المصفوفة<T>(
    المصفوفة: مصفوفة<T>،
    العنصر: T
) {
    متغير الفهرس = 0
    لكل عنصر_حالي في المصفوفة {
        إذا (عنصر_حالي == العنصر) {
            إرجاع الفهرس
        }
        الفهرس = الفهرس + 1
    }
    إرجاع لاشيء
}

