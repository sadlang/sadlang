# 6. Transactions - المعاملات
# ============================================================================

اطبع("6. المعاملات / Transactions")
اطبع("----------------------------------------\n")

# Begin transaction / بدء معاملة
ابدأ_معاملة()
اطبع("✓ بدأت المعاملة / Transaction started")

حاول {
    # Insert multiple records in transaction / إدراج سجلات متعددة
    نفذ_استعلام("INSERT INTO users (name, email, age) VALUES ('محمد', 'mohamed@example.com', 30)")
    اطبع("  - تم إدراج محمد")
    
    نفذ_استعلام("INSERT INTO users (name, email, age) VALUES ('عائشة', 'aisha@example.com', 27)")
    اطبع("  - تم إدراج عائشة")
    
    # Commit transaction / تأكيد المعاملة
    أكد_معاملة()
    اطبع("✓ تم تأكيد المعاملة / Transaction committed\n")
    
} catch (خطأ) {
    # Rollback on error / التراجع عند الخطأ
    تراجع_عن_معاملة()
    اطبع("✗ تم التراجع عن المعاملة / Transaction rolled back\n")
