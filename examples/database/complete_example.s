نفذ_استعلام("DROP TABLE IF EXISTS users")
نفذ_استعلام("
    CREATE TABLE users (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        email TEXT UNIQUE NOT NULL,
        age INTEGER,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
")
اطبع("✓ تم إنشاء جدول users")

# Create posts table / إنشاء جدول المنشورات
نفذ_استعلام("DROP TABLE IF EXISTS posts")
نفذ_استعلام("
    CREATE TABLE posts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id INTEGER NOT NULL,
        title TEXT NOT NULL,
        content TEXT,
        views INTEGER DEFAULT 0,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (user_id) REFERENCES users(id)
    )
")
اطبع("✓ تم إنشاء جدول posts\n")

