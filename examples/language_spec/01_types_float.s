# القواعد النحوية المستخدمة / EBNF Rules Used:
# ═══════════════════════════════════════════════════════════
# float_literal ::= decimal_part ['.' fractional_part] [exponent_part]
# decimal_part ::= ['+' | '-'] digit+
# fractional_part ::= digit+
# exponent_part ::= ('e' | 'E') ['+' | '-'] digit+
# ═══════════════════════════════════════════════════════════

