# 1. أرقام عشرية بسيطة / Simple Floats
اطبع("\n1. الأرقام العشرية البسيطة:")
عشري الطول = 5.5
عشري الوزن = 72.3
عشري درجة_الحرارة = 36.6
عشري سالب = -12.5

اطبع("الطول = " + الطول + " متر")
اطبع("الوزن = " + الوزن + " كجم")
اطبع("درجة الحرارة = " + درجة_الحرارة + " درجة")
اطبع("رقم سالب = " + سالب )

# 2. الكسور العشرية / Decimal Fractions
اطبع("\n2. الكسور العشرية:")
عشري ربع = 0.25
عشري نصف = 0.5
عشري ثلاثة_أرباع = 0.75
عشري ثلث = 0.333333

اطبع("الربع = " + ربع)
اطبع("النصف = " + نصف)
اطبع("ثلاثة أرباع = " + ثلاثة_أرباع)
اطبع("الثلث (تقريباً) = " + ثلث)

# 3. الصيغة العلمية / Scientific Notation
اطبع("\n3. الصيغة العلمية:")
عشري كبير = 1.5e10
عشري صغير = 3.2e-5

اطبع("1.5e10 = " + كبير)
اطبع("3.2e-5 = " + صغير)

# 4. العمليات الحسابية / Arithmetic Operations
اطبع("\n4. العمليات الحسابية:")
عشري س = 10.5
عشري ص = 3.2

عشري مجموع = س + ص
عشري فرق = س - ص
عشري ضرب = س * ص
عشري قسمة = س / ص

اطبع(س + " + " + ص + " = " + مجموع)
اطبع(س + " - " + ص + " = " + فرق)
اطبع(س + " * " + ص + " = " + ضرب)
اطبع(س + " / " + ص + " = " + قسمة)

# 5. الثوابت الرياضية الشهيرة / Famous Math Constants
اطبع("\n5. الثوابت الرياضية:")
عشري باي = 3.14159265359
عشري إيلر = 2.71828182846
عشري الذهبي = 1.61803398875

اطبع("باي (π) = " + باي)
اطبع("عدد إيلر (e) = " + إيلر)
اطبع("النسبة الذهبية (φ) = " + الذهبي)

# 6. حسابات المساحات / Area Calculations
اطبع("\n6. حسابات المساحات:")
عشري نصف_قطر_الدائرة = 5.0
عشري مساحة_الدائرة = باي * نصف_قطر_الدائرة * نصف_قطر_الدائرة

اطبع("نصف قطر الدائرة: " + نصف_قطر_الدائرة + " متر")
اطبع("مساحة الدائرة: " + مساحة_الدائرة + " متر مربع")

عشري طول_المستطيل = 10.5
عشري عرض_المستطيل = 5.3
عشري مساحة_المستطيل = طول_المستطيل * عرض_المستطيل

اطبع("\nطول المستطيل: " + طول_المستطيل + " متر")
اطبع("عرض المستطيل: " + عرض_المستطيل + " متر")
اطبع("مساحة المستطيل: " + مساحة_المستطيل + " متر مربع")

# 7. حسابات السرعة / Speed Calculations
اطبع("\n7. حسابات السرعة:")
