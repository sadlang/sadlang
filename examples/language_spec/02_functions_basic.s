# ═══════════════════════════════════════════════════════════
# function_decl ::= 'دالة' [type] IDENTIFIER '(' [param_list] ')' block
# param_list ::= param (',' param)*
# param ::= IDENTIFIER [':' type] ['=' expression]
# block ::= statement* 'نهاية'
# return_stmt ::= 'إرجاع' [expression]
# call_expr ::= IDENTIFIER '(' [arg_list] ')'
# ═══════════════════════════════════════════════════════════

