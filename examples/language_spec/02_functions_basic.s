# 1. دالة بسيطة بدون معاملات / Simple Function Without Parameters
اطبع("\n1. دالة بسيطة بدون معاملات:")

دالة قل_السلام()
    اطبع("السلام عليكم ورحمة الله وبركاته")
نهاية

قل_السلام()

# 2. دالة مع معامل واحد / Function With One Parameter
اطبع("\n2. دالة مع معامل واحد:")

دالة رقم مربع(رقم العدد)
    إرجاع العدد * العدد
نهاية

رقم نتيجة_المربع = مربع(7)
اطبع("مربع 7 = " + نص(نتيجة_المربع))

# 3. دالة مع عدة معاملات / Function With Multiple Parameters
اطبع("\n3. دالة مع عدة معاملات:")

دالة رقم جمع_ثلاثة(رقم الأول، رقم الثاني، رقم الثالث)
    إرجاع الأول + الثاني + الثالث
نهاية

رقم المجموع = جمع_ثلاثة(10، 20، 30)
اطبع("10 + 20 + 30 = " + نص(المجموع))

# 4. دالة مع نوع إرجاع صريح / Function With Explicit Return Type
اطبع("\n4. دالة مع نوع إرجاع صريح:")

دالة عشري حساب_المعدل(رقم المجموع، رقم العدد)
    إرجاع المجموع / العدد
نهاية

عشري المعدل = حساب_المعدل(285، 3)
اطبع("المعدل = " + نص(المعدل))

# 5. دالة تطبع ولا ترجع قيمة / Function That Prints (No Return)
اطبع("\n5. دالة تطبع ولا ترجع قيمة:")

دالة اطبع_معلومات_الطالب(نص الاسم، رقم العمر، نص التخصص)
    اطبع("=== معلومات الطالب ===")
    اطبع("الاسم: " + الاسم)
    اطبع("العمر: " + نص(العمر))
    اطبع("التخصص: " + التخصص)
    اطبع("=======================")
نهاية

اطبع_معلومات_الطالب("أحمد محمد"، 22، "هندسة البرمجيات")

# 6. دالة مع شروط / Function With Conditions
اطبع("\n6. دالة مع شروط:")

دالة نص تقييم_الدرجة(رقم الدرجة)
    إذا الدرجة >= 90 أعمل
        إرجاع "ممتاز"
    نهاية
    
    إذا الدرجة >= 80 أعمل
        إرجاع "جيد جداً"
    نهاية
    
    إذا الدرجة >= 70 أعمل
        إرجاع "جيد"
    نهاية
    
    إذا الدرجة >= 60 أعمل
        إرجاع "مقبول"
    نهاية
    
    إرجاع "راسب"
نهاية

نص التقييم_واحد = تقييم_الدرجة(95)
نص التقييم_اثنان = تقييم_الدرجة(75)
نص التقييم_ثلاثة = تقييم_الدرجة(55)

اطبع("التقييم لدرجة 95: " + التقييم_واحد)
اطبع("التقييم لدرجة 75: " + التقييم_اثنان)
اطبع("التقييم لدرجة 55: " + التقييم_ثلاثة)

# 7. دالة حسابية معقدة / Complex Mathematical Function
اطبع("\n7. دالة حسابية معقدة:")

دالة رقم حساب_المساحة_الدائرة(عشري نصف_القطر)
    عشري باي = 3.14159
    إرجاع باي * نصف_القطر * نصف_القطر
نهاية

عشري مساحة = حساب_المساحة_الدائرة(5.0)
اطبع("مساحة دائرة نصف قطرها 5 = " + نص(مساحة))

# 8. دالة تستدعي دالة أخرى / Function Calling Another Function
اطبع("\n8. دالة تستدعي دالة أخرى:")

دالة رقم ضعف(رقم العدد)
    إرجاع العدد * 2
نهاية

دالة رقم ربع(رقم العدد)
    إرجاع ضعف(ضعف(العدد))
نهاية

رقم نتيجة_الربع = ربع(10)
اطبع("ربع أضعاف 10 = " + نص(نتيجة_الربع))

# 9. دالة تحقق من شرط / Validation Function
اطبع("\n9. دالة تحقق من شرط:")

دالة منطقي هل_بالغ(رقم العمر)
    إرجاع العمر >= 18
نهاية

منطقي شخص_واحد = هل_بالغ(25)
منطقي شخص_اثنان = هل_بالغ(15)

اطبع("هل عمر 25 بالغ؟ " + نص(شخص_واحد))
اطبع("هل عمر 15 بالغ؟ " + نص(شخص_اثنان))

# 10. دالة لحساب الفاتورة / Invoice Calculation Function
اطبع("\n10. دالة لحساب الفاتورة:")

دالة عشري حساب_الفاتورة(رقم السعر، رقم الكمية، عشري الضريبة)
    عشري المجموع_الفرعي = السعر * الكمية
    عشري قيمة_الضريبة = المجموع_الفرعي * الضريبة
    إرجاع المجموع_الفرعي + قيمة_الضريبة
نهاية

عشري الفاتورة = حساب_الفاتورة(50، 3، 0.15)
اطبع("إجمالي الفاتورة: " + نص(الفاتورة) + " ريال")

# 11. دالة تحويل وحدات / Unit Conversion Function
اطبع("\n11. دالة تحويل وحدات:")

دالة عشري من_سنتيمتر_الى_متر(عشري السنتيمتر)
    إرجاع السنتيمتر / 100.0
نهاية

دالة عشري من_متر_الى_كيلومتر(عشري المتر)
    إرجاع المتر / 1000.0
نهاية

عشري الطول_بالسنتيمتر = 15000.0
عشري الطول_بالمتر = من_سنتيمتر_الى_متر(الطول_بالسنتيمتر)
عشري الطول_بالكيلومتر = من_متر_الى_كيلومتر(الطول_بالمتر)

اطبع("الطول: " + نص(الطول_بالسنتيمتر) + " سم")
اطبع("الطول: " + نص(الطول_بالمتر) + " م")
اطبع("الطول: " + نص(الطول_بالكيلومتر) + " كم")

