# 5. العمليات الحسابية / Arithmetic Operations
اطبع("\n5. العمليات الحسابية:")
رقم أ = 50
رقم ب = 10

رقم مجموع = أ + ب
رقم فرق = أ - ب
رقم ضرب = أ * ب
رقم قسمة = أ / ب
رقم باقي_القسمة = أ % 3
رقم قوة = 2 ** 8

اطبع(نص(أ) + " + " + نص(ب) + " = " + نص(مجموع))
اطبع(نص(أ) + " - " + نص(ب) + " = " + نص(فرق))
اطبع(نص(أ) + " * " + نص(ب) + " = " + نص(ضرب))
اطبع(نص(أ) + " / " + نص(ب) + " = " + نص(قسمة))
اطبع(نص(أ) + " % 3 = " + نص(باقي_القسمة))
اطبع("2 ** 8 = " + نص(قوة))

# 6. عمليات المقارنة / Comparison Operations
اطبع("\n6. عمليات المقارنة:")
