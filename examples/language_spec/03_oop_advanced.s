صنف مستطيل_محسوب:
    """مستطيل مع خصائص محسوبة"""
    
    بناء(الطول، العرض):
        هذا._طول = الطول
        هذا._عرض = العرض
    
    @خاصية
    دالة طول():
        """Getter للطول"""
        إرجاع هذا._طول
    
    @طول.عين
    دالة طول(القيمة):
        """Setter للطول"""
        إذا القيمة > 0:
            هذا._طول = القيمة
        وإلا:
            اطبع("⚠️  الطول يجب أن يكون موجباً!")
    
    @خاصية
    دالة مساحة():
        """خاصية محسوبة - المساحة"""
        إرجاع هذا._طول * هذا._عرض
    
    @خاصية
    دالة محيط():
        """خاصية محسوبة - المحيط"""
        إرجاع 2 * (هذا._طول + هذا._عرض)
    
    @خاصية
    دالة قطر():
        """خاصية محسوبة - القطر"""
        إرجاع (هذا._طول ** 2 + هذا._عرض ** 2) ** 0.5

