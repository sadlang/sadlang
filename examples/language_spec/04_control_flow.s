# while_stmt ::= 'بينما' expression 'أعمل' block 'نهاية'
# for_stmt ::= 'لكل' IDENTIFIER 'في' expression 'أعمل' block 'نهاية'
# break_stmt ::= 'اخرج'
# continue_stmt ::= 'واصل'
