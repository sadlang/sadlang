# 1. شرط بسيط / Simple If Statement
اطبع("\n1. شرط بسيط:")

رقم العمر = 20

إذا العمر >= 18 أعمل
    اطبع("أنت بالغ")
نهاية

# 2. شرط مع وإلا / If-Else Statement
اطبع("\n2. شرط مع وإلا:")

رقم الدرجة = 75

إذا الدرجة >= 60 أعمل
    اطبع("ناجح!")
وإلا أعمل
    اطبع("راسب!")
نهاية

# 3. شروط متداخلة / Nested If Statements
اطبع("\n3. شروط متداخلة:")

رقم النقاط = 85

إذا النقاط >= 90 أعمل
    اطبع("التقدير: ممتاز")
وإلا أعمل
    إذا النقاط >= 80 أعمل
        اطبع("التقدير: جيد جداً")
    وإلا أعمل
        إذا النقاط >= 70 أعمل
            اطبع("التقدير: جيد")
        وإلا أعمل
            اطبع("التقدير: مقبول")
        نهاية
    نهاية
نهاية

# 4. شروط متعددة مع و / Multiple Conditions With AND
اطبع("\n4. شروط متعددة مع و:")

رقم عمر_الطالب = 22
رقم معدل_الطالب = 3.5

إذا (عمر_الطالب >= 18) و (معدل_الطالب >= 3.0) أعمل
    اطبع("مؤهل للمنحة")
وإلا أعمل
    اطبع("غير مؤهل للمنحة")
نهاية

# 5. شروط متعددة مع أو / Multiple Conditions With OR
اطبع("\n5. شروط متعددة مع أو:")

منطقي لديه_تذكرة = صحيح
منطقي لديه_دعوة = خطأ

إذا لديه_تذكرة أو لديه_دعوة أعمل
    اطبع("يمكنه الدخول")
وإلا أعمل
    اطبع("لا يمكنه الدخول")
نهاية

# 6. حلقة بينما / While Loop
اطبع("\n6. حلقة بينما:")

رقم عداد = 1

اطبع("العد من 1 إلى 5:")
بينما عداد <= 5 أعمل
    اطبع("العدد: " + نص(عداد))
    عداد = عداد + 1
نهاية

# 7. حلقة بينما مع شرط معقد / While Loop With Complex Condition
اطبع("\n7. حلقة بينما مع شرط معقد:")

رقم المجموع = 0
رقم رقم_حالي = 1

بينما (المجموع < 100) و (رقم_حالي <= 20) أعمل
    المجموع = المجموع + رقم_حالي
    رقم_حالي = رقم_حالي + 1
نهاية

اطبع("المجموع النهائي: " + نص(المجموع))
اطبع("آخر رقم: " + نص(رقم_حالي - 1))

# 8. حلقة تنازلية / Countdown Loop
اطبع("\n8. العد التنازلي:")

رقم الوقت = 5

بينما الوقت > 0 أعمل
    اطبع(نص(الوقت) + "...")
    الوقت = الوقت - 1
نهاية

اطبع("انطلق!")

# 9. جدول الضرب / Multiplication Table
اطبع("\n9. جدول الضرب للرقم 5:")

رقم الرقم_الأساسي = 5
رقم المضروب = 1

بينما المضروب <= 10 أعمل
    رقم الناتج = الرقم_الأساسي * المضروب
    اطبع(نص(الرقم_الأساسي) + " × " + نص(المضروب) + " = " + نص(الناتج))
    المضروب = المضروب + 1
نهاية

# 10. حساب المتوسط / Calculate Average
اطبع("\n10. حساب المتوسط:")

رقم مجموع_الدرجات = 0
رقم عدد_المواد = 5
رقم مادة_حالية = 1

بينما مادة_حالية <= عدد_المواد أعمل
    رقم درجة = 80 + مادة_حالية * 2
    اطبع("درجة المادة " + نص(مادة_حالية) + ": " + نص(درجة))
    مجموع_الدرجات = مجموع_الدرجات + درجة
    مادة_حالية = مادة_حالية + 1
نهاية

عشري المتوسط = مجموع_الدرجات / عدد_المواد
اطبع("المتوسط النهائي: " + نص(المتوسط))

# 11. البحث عن رقم / Number Search
اطبع("\n11. البحث عن رقم:")

رقم الرقم_المستهدف = 7
رقم رقم_بحث = 1
منطقي وجد = خطأ

بينما (رقم_بحث <= 10) و (ليس وجد) أعمل
    إذا رقم_بحث == الرقم_المستهدف أعمل
        اطبع("وجدنا الرقم " + نص(الرقم_المستهدف) + "!")
        وجد = صحيح
    نهاية
    رقم_بحث = رقم_بحث + 1
نهاية

# 12. حساب المضروب (Factorial)
اطبع("\n12. حساب المضروب:")

رقم العدد_للمضروب = 5
رقم النتيجة_المضروب = 1
رقم عامل = 1

بينما عامل <= العدد_للمضروب أعمل
    النتيجة_المضروب = النتيجة_المضروب * عامل
    عامل = عامل + 1
نهاية

اطبع("مضروب " + نص(العدد_للمضروب) + " = " + نص(النتيجة_المضروب))

