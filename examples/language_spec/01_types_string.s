# ═══════════════════════════════════════════════════════════
# string_literal ::= '"' string_char* '"' | "'" string_char* "'"
# string_char ::= escape_sequence | unicode_char | [^"\\\n]
# escape_sequence ::= '\' ('n' | 't' | 'r' | '\' | '"' | "'")
# f_string ::= 'ن' string_literal    # Format string
# ═══════════════════════════════════════════════════════════

