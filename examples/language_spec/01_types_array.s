# 11. البحث في المصفوفة / Search in Array
اطبع("\n11. البحث في المصفوفة:")

مصفوفة أرقام_الهاتف = ["0501234567"، "0561234567"، "0551234567"]
نص رقم_مستهدف = "0561234567"
منطقي موجود = خطأ
رقم موضع = -1
رقم عداد_بحث = 0

