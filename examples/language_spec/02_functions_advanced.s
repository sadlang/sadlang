دالة مُحفظ(الدالة):
    """مُزين يحفظ نتائج الدالة في ذاكرة مؤقتة"""
    الذاكرة = {}
    
    دالة الدالة_المحفوظة(*الحجج):
        المفتاح = نص(الحجج)
        إذا المفتاح في الذاكرة:
            اطبع("💾 من الذاكرة: " + المفتاح)
            إرجاع الذاكرة[المفتاح]
        
        النتيجة = الدالة(*الحجج)
        الذاكرة[المفتاح] = النتيجة
        اطبع("🔢 حساب جديد: " + المفتاح)
        إرجاع النتيجة
    
    إرجاع الدالة_المحفوظة

@مُحفظ
دالة فيبوناتشي_محفوظ(ع):
    """فيبوناتشي مع تخزين مؤقت"""
    إذا ع <= 1:
        إرجاع ع
    إرجاع فيبوناتشي_محفوظ(ع - 1) + فيبوناتشي_محفوظ(ع - 2)

اطبع("✅ فيبوناتشي مع Memoization:")
