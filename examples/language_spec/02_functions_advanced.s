دالة قوة(الأساس، الأس):
    """حساب القوة بطريقة عودية"""
    إذا الأس == 0:
        إرجاع 1
    إذا الأس == 1:
        إرجاع الأساس
    إرجاع الأساس * قوة(الأساس، الأس - 1)

اطبع("✅ 2 أس 10 = " + نص(قوة(2، 10)))      # 1024

