دالة مضروب(ع):
    """حساب المضروب بطريقة عودية"""
    إذا ع <= 1:
        إرجاع 1
    إرجاع ع * مضروب(ع - 1)

اطبع("✅ مضروب 5: " + نص(مضروب(5)))         # 120
اطبع("✅ مضروب 7: " + نص(مضروب(7)))         # 5040

دالة فيبوناتشي(ع):
    """حساب رقم فيبوناتشي"""
    إذا ع <= 1:
        إرجاع ع
    إرجاع فيبوناتشي(ع - 1) + فيبوناتشي(ع - 2)

اطبع("✅ متتالية فيبوناتشي:")
لكل ر في نطاق(10):
