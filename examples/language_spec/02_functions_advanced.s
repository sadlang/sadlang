دالة مولد_الأرقام(البداية، النهاية):
    """مولد يرجع أرقام من البداية للنهاية"""
    رقم الحالي = البداية
    بينما الحالي <= النهاية:
        ينتج الحالي
        الحالي = الحالي + 1

