دالة مُزين_المؤقت(الدالة):
    """مُزين يقيس وقت تنفيذ الدالة"""
    دالة الدالة_الملفوفة(*الحجج، **الكلمات):
        رقم الوقت_البداية = الوقت_الحالي()
        النتيجة = الدالة(*الحجج، **الكلمات)
        رقم الوقت_النهاية = الوقت_الحالي()
        رقم المدة = الوقت_النهاية - الوقت_البداية
        اطبع("⏱️  وقت التنفيذ: " + نص(المدة) + " ثانية")
        إرجاع النتيجة
    إرجاع الدالة_الملفوفة

@مُزين_المؤقت
دالة عملية_طويلة():
