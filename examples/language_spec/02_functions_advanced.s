دالة مولد_فيبوناتشي(العدد):
    """مولد لمتتالية فيبوناتشي"""
    رقم أ = 0
    رقم ب = 1
    رقم عداد = 0
    
    بينما عداد < العدد:
        ينتج أ
        رقم التالي = أ + ب
        أ = ب
        ب = التالي
        عداد = عداد + 1

اطبع("✅ أول 10 أرقام فيبوناتشي:")
