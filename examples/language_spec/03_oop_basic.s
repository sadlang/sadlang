# 3. صنف طالب / Student Class
اطبع("\n3. صنف طالب:")

صنف طالب
    خاصية نص الاسم
    خاصية نص الرقم_الجامعي
    خاصية عشري المعدل
    خاصية نص التخصص
    
    بناء(نص اسم، نص رقم، نص تخصص)
        هذا.الاسم = اسم
        هذا.الرقم_الجامعي = رقم
        هذا.التخصص = تخصص
        هذا.المعدل = 0.0
    نهاية
    
    دالة تعيين_المعدل(عشري معدل_جديد)
        إذا (معدل_جديد >= 0.0) و (معدل_جديد <= 4.0) أعمل
            هذا.المعدل = معدل_جديد
            اطبع("تم تحديث المعدل")
        وإلا أعمل
            اطبع("خطأ: المعدل يجب أن يكون بين 0 و 4")
        نهاية
    نهاية
    
    دالة نص احصل_على_التقدير()
        إذا هذا.المعدل >= 3.75 أعمل
            إرجاع "ممتاز"
        نهاية
        إذا هذا.المعدل >= 3.25 أعمل
            إرجاع "جيد جداً"
        نهاية
        إذا هذا.المعدل >= 2.75 أعمل
            إرجاع "جيد"
        نهاية
        إذا هذا.المعدل >= 2.0 أعمل
            إرجاع "مقبول"
        نهاية
        إرجاع "راسب"
    نهاية
    
    دالة اطبع_البطاقة()
        اطبع("=== بطاقة الطالب ===")
        اطبع("الاسم: " + هذا.الاسم)
        اطبع("الرقم الجامعي: " + هذا.الرقم_الجامعي)
        اطبع("التخصص: " + هذا.التخصص)
        اطبع("المعدل: " + نص(هذا.المعدل))
        اطبع("التقدير: " + هذا.احصل_على_التقدير())
        اطبع("=====================")
    نهاية
نهاية

