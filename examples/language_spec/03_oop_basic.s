# 2. صنف مع عدة دوال / Class With Multiple Methods
اطبع("\n2. صنف مع عدة دوال:")

صنف حساب_بنكي
    خاصية نص رقم_الحساب
    خاصية عشري الرصيد
    
    بناء(نص رقم، عشري رصيد_أولي)
        هذا.رقم_الحساب = رقم
        هذا.الرصيد = رصيد_أولي
    نهاية
    
    دالة إيداع(عشري المبلغ)
        هذا.الرصيد = هذا.الرصيد + المبلغ
        اطبع("تم إيداع: " + نص(المبلغ))
        اطبع("الرصيد الجديد: " + نص(هذا.الرصيد))
    نهاية
    
    دالة سحب(عشري المبلغ)
        إذا المبلغ <= هذا.الرصيد أعمل
            هذا.الرصيد = هذا.الرصيد - المبلغ
            اطبع("تم السحب: " + نص(المبلغ))
            اطبع("الرصيد المتبقي: " + نص(هذا.الرصيد))
        وإلا أعمل
            اطبع("رصيد غير كافٍ!")
        نهاية
    نهاية
    
    دالة عشري احصل_على_الرصيد()
        إرجاع هذا.الرصيد
    نهاية
نهاية

