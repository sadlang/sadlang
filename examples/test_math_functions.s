// Example: Quadratic equation roots
// --------------------------------------------
اطبع_سطر("13. معادلة تربيعية / Quadratic")
اطبع_سطر("   ax² + bx + c = 0")
اطبع_سطر("")

رقم_حقيقي أ = 1.0
رقم_حقيقي ب = -5.0
رقم_حقيقي ج = 6.0

اطبع("a = ")
اطبع(أ)
اطبع(", b = ")
اطبع(ب)
اطبع(", c = ")
اطبع_سطر(ج)

// المميز = b² - 4ac
رقم_حقيقي المميز = مربع(ب) - 4 * أ * ج
اطبع("المميز / Discriminant: ")
اطبع_سطر(المميز)

إذا المميز >= 0 {
    // الجذر الأول = (-b + √Δ) / 2a
    رقم_حقيقي جذر1 = (-ب + جذر(المميز)) / (2 * أ)
    
    // الجذر الثاني = (-b - √Δ) / 2a
    رقم_حقيقي جذر2 = (-ب - جذر(المميز)) / (2 * أ)
    
    اطبع("الجذر الأول / Root 1: ")
    اطبع_سطر(جذر1)
    اطبع("الجذر الثاني / Root 2: ")
    اطبع_سطر(جذر2)
} وإلا {
    اطبع_سطر("لا توجد جذور حقيقية / No real roots")
}
