دالة حلل_الطلب(نص الطلب) -> (نص، نص)
    # استخراج الطريقة والمسار من السطر الأول
    مصفوفة أسطر = قسّم(الطلب، "\r\n")
    إذا (طول(أسطر) == 0)
        ارجع ("GET"، "/")
    نهاية
    
    مصفوفة أجزاء = قسّم(أسطر[0]، " ")
    إذا (طول(أجزاء) < 2)
        ارجع ("GET"، "/")
    نهاية
    
    ارجع (أجزاء[0]، أجزاء[1])
نهاية

