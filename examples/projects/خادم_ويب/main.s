دالة عالج_الطلب(نص المسار، نص الطريقة) -> (نص، نص، رقم)
    # (المحتوى، نوع_المحتوى، رمز_الحالة)
    
    طابق المسار
        حالة "/":
            ارجع (صفحة_رئيسية()، "text/html; charset=utf-8"، 200)
        
        حالة "/api/معلومات":
            ارجع (معلومات_الخادم()، "application/json; charset=utf-8"، 200)
        
        حالة "/api/وقت":
            ارجع (الوقت_الحالي()، "application/json; charset=utf-8"، 200)
        
        حالة _:
            ارجع (صفحة_غير_موجودة()، "text/html; charset=utf-8"، 404)
    نهاية
نهاية

# ═══════════════════════════════════════════════════════
# إنشاء استجابة HTTP / Create HTTP Response
# ═══════════════════════════════════════════════════════

دالة أنشئ_استجابة(نص المحتوى، نص نوع_المحتوى، رقم رمز_الحالة) -> نص
    نص حالة = "OK"
    طابق رمز_الحالة
        حالة 200: حالة = "OK"
        حالة 201: حالة = "Created"
        حالة 404: حالة = "Not Found"
        حالة 500: حالة = "Internal Server Error"
        حالة _: حالة = "Unknown"
    نهاية
    
    نص استجابة = "HTTP/1.1 " + لنص(رمز_الحالة) + " " + حالة + "\r\n"
    استجابة = استجابة + "Content-Type: " + نوع_المحتوى + "\r\n"
    استجابة = استجابة + "Content-Length: " + لنص(طول(المحتوى)) + "\r\n"
    استجابة = استجابة + "Server: " + اسم_الخادم + "/" + الإصدار + "\r\n"
    استجابة = استجابة + "Connection: close\r\n"
    استجابة = استجابة + "\r\n"
    استجابة = استجابة + المحتوى
    
    ارجع استجابة
نهاية

# ═══════════════════════════════════════════════════════
