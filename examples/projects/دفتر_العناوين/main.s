فئة دفتر_عناوين
    مصفوفة جهات = []
    رقم المعرف_التالي = 1
    نص مسار_الملف = "contacts.json"
    
    دالة أضف(نص اسم، نص لقب) -> جهة_اتصال
        متغير جهة = جهة_اتصال(هذا.المعرف_التالي، اسم، لقب)
        هذا.جهات.أضف(جهة)
        هذا.المعرف_التالي = هذا.المعرف_التالي + 1
        ارجع جهة
    نهاية
    
    دالة أضف_كاملة(نص اسم، نص لقب، نص هاتف، نص بريد) -> جهة_اتصال
        متغير جهة = هذا.أضف(اسم، لقب)
        جهة.الهاتف = هاتف
        جهة.البريد = بريد
        ارجع جهة
    نهاية
    
    دالة احذف(رقم معرف) -> منطقي
        لكل ي في مدى(0، طول(هذا.جهات))
            إذا (هذا.جهات[ي].المعرف == معرف)
                هذا.جهات.احذف(ي)
                ارجع صحيح
            نهاية
        نهاية
        ارجع خطأ
    نهاية
    
    دالة ابحث_بالمعرف(رقم معرف) -> جهة_اتصال؟
        لكل جهة في هذا.جهات
            إذا (جهة.المعرف == معرف)
                ارجع جهة
            نهاية
        نهاية
        ارجع فارغ
    نهاية
    
    دالة ابحث_بالاسم(نص بحث) -> مصفوفة
        مصفوفة نتائج = []
        نص بحث_صغير = صغير(بحث)
        
        لكل جهة في هذا.جهات
            نص الاسم_الكامل = صغير(جهة.الاسم_الكامل())
            إذا (يحتوي(الاسم_الكامل، بحث_صغير))
                نتائج.أضف(جهة)
            نهاية
        نهاية
        ارجع نتائج
    نهاية
    
    دالة ابحث_بالهاتف(نص رقم) -> مصفوفة
        مصفوفة نتائج = []
        لكل جهة في هذا.جهات
            إذا (يحتوي(جهة.الهاتف، رقم))
                نتائج.أضف(جهة)
            نهاية
        نهاية
        ارجع نتائج
    نهاية
    
    دالة المفضلون() -> مصفوفة
        مصفوفة نتائج = []
        لكل جهة في هذا.جهات
            إذا (جهة.مفضل)
                نتائج.أضف(جهة)
            نهاية
        نهاية
        ارجع نتائج
    نهاية
    
    دالة بالوسم(نص وسم) -> مصفوفة
        مصفوفة نتائج = []
        لكل جهة في هذا.جهات
            لكل و في جهة.الوسوم
                إذا (و == وسم)
                    نتائج.أضف(جهة)
                    توقف
                نهاية
            نهاية
        نهاية
        ارجع نتائج
    نهاية
    
    دالة رتّب_أبجدياً() -> مصفوفة
        # نسخة مرتبة من الجهات
        مصفوفة مرتب = []
        لكل جهة في هذا.جهات
            مرتب.أضف(جهة)
        نهاية
        # خوارزمية الترتيب الفقاعي للتبسيط
        لكل ي في مدى(0، طول(مرتب) - 1)
            لكل ج في مدى(0، طول(مرتب) - ي - 1)
                إذا (مرتب[ج].الاسم > مرتب[ج + 1].الاسم)
                    متغير مؤقت = مرتب[ج]
                    مرتب[ج] = مرتب[ج + 1]
                    مرتب[ج + 1] = مؤقت
                نهاية
            نهاية
        نهاية
        ارجع مرتب
    نهاية
    
    دالة العدد() -> رقم
        ارجع طول(هذا.جهات)
    نهاية
    
    دالة صدّر_json() -> نص
        نص نتيجة = "[\n"
        لكل ي في مدى(0، طول(هذا.جهات))
            إذا (ي > 0)
                نتيجة = نتيجة + "،\n"
            نهاية
            نتيجة = نتيجة + هذا.جهات[ي].إلى_json()
        نهاية
        نتيجة = نتيجة + "\n]"
        ارجع نتيجة
    نهاية
نهاية

