فئة جهة_اتصال
    رقم المعرف
    نص الاسم
    نص اللقب
    نص الهاتف
    نص البريد
    نص العنوان
    نص الشركة
    نص الملاحظات
    مصفوفة الوسوم = []
    منطقي مفضل = خطأ
    
    دالة بناء(رقم معرف، نص اسم، نص لقب)
        هذا.المعرف = معرف
        هذا.الاسم = اسم
        هذا.اللقب = لقب
        هذا.الهاتف = ""
        هذا.البريد = ""
        هذا.العنوان = ""
        هذا.الشركة = ""
        هذا.الملاحظات = ""
    نهاية
    
    دالة الاسم_الكامل() -> نص
        ارجع هذا.الاسم + " " + هذا.اللقب
    نهاية
    
    دالة أضف_وسم(نص وسم)
        هذا.الوسوم.أضف(وسم)
    نهاية
    
    دالة رمز_المفضل() -> نص
        إذا (هذا.مفضل)
            ارجع "⭐"
        وإلا
            ارجع "  "
        نهاية
    نهاية
    
    دالة اعرض_مختصر()
        اطبع(هذا.رمز_المفضل())
        اطبع(" [")
        اطبع(هذا.المعرف)
        اطبع("] ")
        اطبع(هذا.الاسم_الكامل())
        إذا (هذا.الهاتف != "")
            اطبع(" 📱 ")
            اطبع(هذا.الهاتف)
        نهاية
        اطبع("\n")
    نهاية
    
    دالة اعرض_كامل()
        اطبع("\n")
        اطبع("╔═══════════════════════════════════════════╗\n")
        اطبع("║ ")
        اطبع(هذا.رمز_المفضل())
        اطبع(" ")
        اطبع(هذا.الاسم_الكامل())
        اطبع("\n")
        اطبع("╠═══════════════════════════════════════════╣\n")
        
        إذا (هذا.الهاتف != "")
            اطبع("║ 📱 الهاتف: ")
            اطبع(هذا.الهاتف)
            اطبع("\n")
        نهاية
        
        إذا (هذا.البريد != "")
            اطبع("║ 📧 البريد: ")
            اطبع(هذا.البريد)
            اطبع("\n")
        نهاية
        
        إذا (هذا.العنوان != "")
            اطبع("║ 🏠 العنوان: ")
            اطبع(هذا.العنوان)
            اطبع("\n")
        نهاية
        
        إذا (هذا.الشركة != "")
            اطبع("║ 🏢 الشركة: ")
            اطبع(هذا.الشركة)
            اطبع("\n")
        نهاية
        
        إذا (طول(هذا.الوسوم) > 0)
            اطبع("║ 🏷️ الوسوم: ")
            لكل ي في مدى(0، طول(هذا.الوسوم))
                إذا (ي > 0)
                    اطبع("، ")
                نهاية
                اطبع(هذا.الوسوم[ي])
            نهاية
            اطبع("\n")
        نهاية
        
        إذا (هذا.الملاحظات != "")
            اطبع("║ 📝 ملاحظات: ")
            اطبع(هذا.الملاحظات)
            اطبع("\n")
        نهاية
        
        اطبع("╚═══════════════════════════════════════════╝\n")
    نهاية
    
    دالة إلى_json() -> نص
        ارجع """{
    "معرف": """ + لنص(هذا.المعرف) + """,
    "اسم": """" + هذا.الاسم + """",
    "لقب": """" + هذا.اللقب + """",
    "هاتف": """" + هذا.الهاتف + """",
    "بريد": """" + هذا.البريد + """",
    "مفضل": """ + لنص(هذا.مفضل) + """
}"""
    نهاية
نهاية

