دالة احصل_على_تلميح(رقم تخمين، رقم الهدف) -> نص
    رقم الفرق = الهدف - تخمين
    إذا (الفرق < 0)
        الفرق = -الفرق
    نهاية
    
    إذا (الفرق <= 5)
        ارجع "🔥 حار جداً! قريب جداً!"
    وإلا_إذا (الفرق <= 10)
        ارجع "😊 حار! أنت قريب!"
    وإلا_إذا (الفرق <= 25)
        ارجع "😐 دافئ..."
    وإلا_إذا (الفرق <= 50)
        ارجع "❄️ بارد..."
    وإلا
        ارجع "🥶 بارد جداً!"
    نهاية
نهاية

دالة قيّم_الأداء(رقم المحاولات) -> نص
    إذا (المحاولات == 1)
        ارجع "🏆 مذهل! تخمين من أول محاولة! أنت عبقري!"
    وإلا_إذا (المحاولات <= 3)
        ارجع "🥇 ممتاز! أداء رائع!"
    وإلا_إذا (المحاولات <= 5)
        ارجع "🥈 جيد جداً! أحسنت!"
    وإلا_إذا (المحاولات <= 7)
        ارجع "🥉 جيد! يمكنك التحسن!"
    وإلا
        ارجع "👍 أكملت اللعبة! حاول أن تكون أسرع في المرة القادمة!"
    نهاية
نهاية

