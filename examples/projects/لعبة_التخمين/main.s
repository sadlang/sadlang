دالة العب_جولة() -> منطقي
    # توليد رقم عشوائي
    رقم الهدف = عشوائي.رقم_عشوائي(الحد_الأدنى، الحد_الأقصى)
    رقم المحاولات = 0
    منطقي فاز = خطأ
    
    اطبع("🎲 اخترت رقماً... هيا خمّن!\n\n")
    
    بينما (المحاولات < أقصى_محاولات)
        المحاولات = المحاولات + 1
        
        اطبع("المحاولة ")
        اطبع(المحاولات)
        اطبع("/")
        اطبع(أقصى_محاولات)
        اطبع(": ")
        
        # في التنفيذ الحقيقي، نقرأ من المستخدم
        # رقم تخمين = مدخلات.اقرأ_رقم()
        
        # للعرض التوضيحي، نستخدم تخمينات ثابتة
        رقم تخمين = 50
        إذا (المحاولات == 2)
            تخمين = 75
        وإلا_إذا (المحاولات == 3)
            تخمين = 63
        وإلا_إذا (المحاولات == 4)
            تخمين = الهدف  # نفترض أنه خمّن صحيحاً
        نهاية
        
        اطبع("تخمينك: ")
        اطبع(تخمين)
        اطبع("\n")
        
        إذا (تخمين == الهدف)
            فاز = صحيح
            اطبع("\n")
            اطبع("🎉 تهانينا! لقد خمّنت الرقم الصحيح!\n")
            اطبع("الرقم كان: ")
            اطبع(الهدف)
            اطبع("\n")
            اطبع("عدد المحاولات: ")
            اطبع(المحاولات)
            اطبع("\n")
            اطبع(قيّم_الأداء(المحاولات))
            اطبع("\n")
            توقف
        وإلا_إذا (تخمين < الهدف)
            اطبع("⬆️  أعلى! الرقم أكبر من ")
            اطبع(تخمين)
            اطبع("\n")
            اطبع(احصل_على_تلميح(تخمين، الهدف))
            اطبع("\n\n")
        وإلا
            اطبع("⬇️  أقل! الرقم أصغر من ")
            اطبع(تخمين)
            اطبع("\n")
            اطبع(احصل_على_تلميح(تخمين، الهدف))
            اطبع("\n\n")
        نهاية
    نهاية
    
    إذا (! فاز)
        اطبع("\n")
        اطبع("😢 للأسف! نفدت المحاولات!\n")
        اطبع("الرقم الصحيح كان: ")
        اطبع(الهدف)
        اطبع("\n")
        اطبع("حاول مرة أخرى!\n")
    نهاية
    
    ارجع فاز
نهاية

