# دالة طباعة الإطار
دالة اطبع_إطار(نص النص، رقم العرض)
    # الخط العلوي
    اطبع("┌")
    رقم ع = 0
    بينما (ع < العرض)
        اطبع("─")
        ع = ع + 1
    نهاية
    اطبع("┐\n")
    
    # السطر مع النص
    اطبع("│ ")
    اطبع(النص)
    
    # ملء المسافات
    رقم المسافات = العرض - طول(النص) - 2
    رقم م = 0
    بينما (م < المسافات)
        اطبع(" ")
        م = م + 1
    نهاية
    اطبع(" │\n")
    
    # الخط السفلي
    اطبع("└")
    ع = 0
    بينما (ع < العرض)
        اطبع("─")
        ع = ع + 1
    نهاية
    اطبع("┘\n")
نهاية

# دالة طباعة مع تأخير (محاكاة الكتابة)
دالة اكتب_ببطء(نص النص)
    رقم ع = 0
    بينما (ع < طول(النص))
        اطبع(النص[ع])
        # في الواقع نحتاج تأخير هنا
        ع = ع + 1
    نهاية
