دالة اطبع_عنوان()
    اطبع("\n")
    اطبع("╔═══════════════════════════════════════════════╗\n")
    اطبع("║                                               ║\n")
    اطبع("║      📝 قائمة المهام - Todo List             ║\n")
    اطبع("║                                               ║\n")
    اطبع("╚═══════════════════════════════════════════════╝\n")
نهاية

دالة اطبع_فاصل()
    اطبع("─────────────────────────────────────────────────\n")
نهاية

دالة اطبع_القائمة(مصفوفة مهام، نص عنوان)
    اطبع("\n")
    اطبع("📋 ")
    اطبع(عنوان)
    اطبع(" (")
    اطبع(طول(مهام))
    اطبع(")\n")
    اطبع_فاصل()
    
    إذا (طول(مهام) == 0)
        اطبع("  لا توجد مهام\n")
    وإلا
        لكل م في مهام
            اطبع("  ")
            م.اعرض()
        نهاية
    نهاية
    اطبع_فاصل()
نهاية

دالة اطبع_الإحصائيات(قاموس إحصاء)
    اطبع("\n")
    اطبع("📊 الإحصائيات:\n")
    اطبع_فاصل()
    اطبع("  📌 إجمالي المهام: ")
    اطبع(إحصاء["إجمالي"])
    اطبع("\n")
    اطبع("  ✅ المكتملة: ")
    اطبع(إحصاء["مكتملة"])
    اطبع("\n")
    اطبع("  ⏳ النشطة: ")
    اطبع(إحصاء["نشطة"])
    اطبع("\n")
    اطبع("  🔴 عالية الأولوية: ")
    اطبع(إحصاء["عالية_الأولوية"])
    اطبع("\n")
    
    إذا (إحصاء["إجمالي"] > 0)
        رقم نسبة = (إحصاء["مكتملة"] * 100) / إحصاء["إجمالي"]
        اطبع("  📈 نسبة الإنجاز: ")
        اطبع(نسبة)
        اطبع("%\n")
    نهاية
    اطبع_فاصل()
نهاية

