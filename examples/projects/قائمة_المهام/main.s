دالة رئيسية()
    اطبع_عنوان()
    
    # إنشاء مدير المهام
    متغير مدير = مدير_المهام()
    
    # إضافة بعض المهام للعرض
    اطبع("\n✨ إضافة مهام تجريبية...\n")
    
    متغير م1 = مدير.أضف_مهمة_كاملة(
        "إكمال مشروع البرمجة"،
        "إنهاء الواجهة الرسومية للتطبيق"،
        "عالية"،
        "2024-01-20"
    )
    
    متغير م2 = مدير.أضف_مهمة_كاملة(
        "قراءة كتاب الخوارزميات"،
        "الفصول من 5 إلى 8"،
        "متوسطة"،
        "2024-01-25"
    )
    
    متغير م3 = مدير.أضف_مهمة_كاملة(
        "التسوق"،
        "شراء مستلزمات المكتب"،
        "منخفضة"،
        "2024-01-18"
    )
    
    متغير م4 = مدير.أضف_مهمة_كاملة(
        "الرياضة"،
        "تمارين صباحية"،
        "متوسطة"،
        ""
    )
    
    متغير م5 = مدير.أضف_مهمة_كاملة(
        "تعلم لغة ص"،
        "إكمال الدروس التعليمية"،
        "عالية"،
        "2024-01-22"
    )
    
    # عرض جميع المهام
    اطبع_القائمة(مدير.مهام، "جميع المهام")
    
    # إكمال بعض المهام
    اطبع("\n✅ إكمال بعض المهام...\n")
    مدير.أكمل_مهمة(3)  # التسوق
    مدير.أكمل_مهمة(4)  # الرياضة
    
    # عرض المهام بعد التحديث
    اطبع_القائمة(مدير.المهام_النشطة()، "المهام النشطة")
    اطبع_القائمة(مدير.المهام_المكتملة()، "المهام المكتملة")
    
    # عرض المهام العالية الأولوية
    اطبع_القائمة(مدير.المهام_بالأولوية("عالية")، "مهام عالية الأولوية 🔴")
    
    # عرض الإحصائيات
    اطبع_الإحصائيات(مدير.الإحصائيات())
    
    # عرض الأوامر المتاحة
    اطبع("\n")
    اطبع("💡 الأوامر المتاحة:\n")
    اطبع_فاصل()
    اطبع("  أضف \"عنوان المهمة\"     - إضافة مهمة جديدة\n")
    اطبع("  أكمل <معرف>             - تحديد مهمة كمكتملة\n")
    اطبع("  احذف <معرف>             - حذف مهمة\n")
    اطبع("  قائمة                   - عرض جميع المهام\n")
    اطبع("  نشطة                    - عرض المهام النشطة\n")
    اطبع("  مكتملة                  - عرض المهام المكتملة\n")
    اطبع("  إحصائيات                - عرض الإحصائيات\n")
    اطبع("  خروج                    - الخروج من البرنامج\n")
    اطبع_فاصل()
    
    اطبع("\n🎉 تم تنفيذ البرنامج بنجاح!\n")
    
    ارجع 0
نهاية
