# مدير المهام / Task Manager
# ═══════════════════════════════════════════════════════

فئة مدير_المهام
    مصفوفة مهام = []
    رقم المعرف_التالي = 1
    
    دالة أضف_مهمة(نص عنوان) -> مهمة
        متغير م = مهمة(هذا.المعرف_التالي، عنوان)
        هذا.مهام.أضف(م)
        هذا.المعرف_التالي = هذا.المعرف_التالي + 1
        ارجع م
    نهاية
    
    دالة أضف_مهمة_كاملة(نص عنوان، نص وصف، نص أولوية، نص استحقاق) -> مهمة
        متغير م = هذا.أضف_مهمة(عنوان)
        م.الوصف = وصف
        م.الأولوية = أولوية
        م.تاريخ_الاستحقاق = استحقاق
        ارجع م
    نهاية
    
    دالة احذف_مهمة(رقم معرف) -> منطقي
        لكل ي في مدى(0، طول(هذا.مهام))
            إذا (هذا.مهام[ي].المعرف == معرف)
                هذا.مهام.احذف(ي)
                ارجع صحيح
            نهاية
        نهاية
        ارجع خطأ
    نهاية
    
    دالة أكمل_مهمة(رقم معرف) -> منطقي
        متغير م = هذا.ابحث(معرف)
        إذا (م != فارغ)
            م.أكمل()
            ارجع صحيح
        نهاية
        ارجع خطأ
    نهاية
    
    دالة ابحث(رقم معرف) -> مهمة؟
        لكل م في هذا.مهام
            إذا (م.المعرف == معرف)
                ارجع م
            نهاية
        نهاية
        ارجع فارغ
    نهاية
    
    دالة المهام_النشطة() -> مصفوفة
        مصفوفة نتيجة = []
        لكل م في هذا.مهام
            إذا (! م.مكتملة)
                نتيجة.أضف(م)
            نهاية
        نهاية
        ارجع نتيجة
    نهاية
    
    دالة المهام_المكتملة() -> مصفوفة
        مصفوفة نتيجة = []
        لكل م في هذا.مهام
            إذا (م.مكتملة)
                نتيجة.أضف(م)
            نهاية
        نهاية
        ارجع نتيجة
    نهاية
    
    دالة المهام_بالأولوية(نص أولوية) -> مصفوفة
        مصفوفة نتيجة = []
        لكل م في هذا.مهام
            إذا (م.الأولوية == أولوية && ! م.مكتملة)
                نتيجة.أضف(م)
            نهاية
        نهاية
        ارجع نتيجة
    نهاية
    
    دالة الإحصائيات() -> قاموس
        رقم إجمالي = طول(هذا.مهام)
        رقم مكتملة = طول(هذا.المهام_المكتملة())
        رقم نشطة = طول(هذا.المهام_النشطة())
        رقم عالية = طول(هذا.المهام_بالأولوية("عالية"))
        
        ارجع {
            "إجمالي": إجمالي،
            "مكتملة": مكتملة،
            "نشطة": نشطة،
            "عالية_الأولوية": عالية
        }
    نهاية
نهاية

