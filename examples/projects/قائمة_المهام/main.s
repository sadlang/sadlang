فئة مهمة
    رقم المعرف
    نص العنوان
    نص الوصف
    نص الأولوية  # عالية، متوسطة، منخفضة
    نص الحالة    # جديدة، قيد_التنفيذ، مكتملة
    نص تاريخ_الإنشاء
    نص تاريخ_الاستحقاق
    منطقي مكتملة = خطأ
    
    دالة بناء(رقم معرف، نص عنوان)
        هذا.المعرف = معرف
        هذا.العنوان = عنوان
        هذا.الوصف = ""
        هذا.الأولوية = "متوسطة"
        هذا.الحالة = "جديدة"
        هذا.تاريخ_الإنشاء = وقت.الآن()
        هذا.تاريخ_الاستحقاق = ""
    نهاية
    
    دالة أكمل()
        هذا.مكتملة = صحيح
        هذا.الحالة = "مكتملة"
    نهاية
    
    دالة رمز_الأولوية() -> نص
        طابق هذا.الأولوية
            حالة "عالية": ارجع "🔴"
            حالة "متوسطة": ارجع "🟡"
            حالة "منخفضة": ارجع "🟢"
            حالة _: ارجع "⚪"
        نهاية
    نهاية
    
    دالة رمز_الحالة() -> نص
        إذا (هذا.مكتملة)
            ارجع "✅"
        وإلا
            ارجع "⬜"
        نهاية
    نهاية
    
    دالة اعرض()
        اطبع(هذا.رمز_الحالة())
        اطبع(" ")
        اطبع(هذا.رمز_الأولوية())
        اطبع(" [")
        اطبع(هذا.المعرف)
        اطبع("] ")
        اطبع(هذا.العنوان)
        إذا (هذا.تاريخ_الاستحقاق != "")
            اطبع(" 📅 ")
            اطبع(هذا.تاريخ_الاستحقاق)
        نهاية
        اطبع("\n")
    نهاية
نهاية

