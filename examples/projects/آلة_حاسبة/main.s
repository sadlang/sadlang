دالة قوة(عشري الأساس، رقم الأس) -> عشري
    إذا (الأس == 0)
        ارجع 1.0
    نهاية
    
    عشري نتيجة = 1.0
    رقم ع = 0
    منطقي سالب = الأس < 0
    رقم أس_مطلق = الأس
    
    إذا (سالب)
        أس_مطلق = 0 - الأس
    نهاية
    
    بينما (ع < أس_مطلق)
        نتيجة = نتيجة * الأساس
        ع = ع + 1
    نهاية
    
    إذا (سالب)
        ارجع 1.0 / نتيجة
    نهاية
    
    ارجع نتيجة
نهاية

دالة جذر_تربيعي(عشري س) -> عشري
    إذا (س < 0)
        اطبع("❌ خطأ: لا يمكن حساب الجذر التربيعي لرقم سالب!\n")
        ارجع 0
    نهاية
    
    إذا (س == 0)
        ارجع 0
    نهاية
    
    # خوارزمية نيوتن-رافسون
    عشري تخمين = س / 2.0
    عشري فرق = 1.0
    
    بينما (فرق > 0.00001)
        عشري تخمين_جديد = (تخمين + س / تخمين) / 2.0
        فرق = تخمين - تخمين_جديد
        إذا (فرق < 0)
            فرق = 0 - فرق
        نهاية
        تخمين = تخمين_جديد
    نهاية
    
    ارجع تخمين
نهاية

دالة نسبة_مئوية(عشري القيمة، عشري النسبة) -> عشري
    ارجع القيمة * النسبة / 100.0
نهاية

دالة عاملي(رقم ن) -> رقم
    إذا (ن < 0)
        اطبع("❌ خطأ: لا يمكن حساب العاملي لرقم سالب!\n")
        ارجع 0
    نهاية
    
    إذا (ن <= 1)
        ارجع 1
    نهاية
    
    رقم نتيجة = 1
    رقم ع = 2
    
    بينما (ع <= ن)
        نتيجة = نتيجة * ع
        ع = ع + 1
    نهاية
    
    ارجع نتيجة
نهاية

دالة القيمة_المطلقة(عشري س) -> عشري
    إذا (س < 0)
        ارجع 0 - س
    نهاية
    ارجع س
نهاية

