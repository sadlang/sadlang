    متغير س = 10؛
    متغير ص = 20؛
    
    // استدعاء القالب مع نوع رقم (i64)
    متغير النتيجة = أكبر(س، ص)؛
    
    اطبع("الأكبر: ")؛
    اطبع(النتيجة)؛
