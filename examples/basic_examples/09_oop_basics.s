# صنف الموظف (يرث من شخص)
صنف موظف يرث شخص
    نص الوظيفة ;
    رقم الراتب ;
    رقم سنوات_الخبرة ;
    
    دالة موظف( نص اسم ، رقم عمر ، نص جنسية ، نص وظيفة ، رقم راتب )
        # استدعاء البانى الأساسي
        عام(اسم, عمر, جنسية) ;
        
        # تهيئة خصائص الموظف
        الوظيفة = وظيفة ;
        الراتب = راتب ;
        سنوات_الخبرة = 0 ;
        
        اطبع("تم تعيين موظف جديد:", اسم) ;
    نهاية
    
    دالة زد_الخبرة( رقم سنوات )
        سنوات_الخبرة = سنوات_الخبرة + سنوات ;
        اطبع("تم تحديث خبرة", الاسم, "إلى", سنوات_الخبرة, "سنة") ;
    نهاية
    
    دالة زد_الراتب( رقم زيادة )
        الراتب = الراتب + زيادة ;
        اطبع("تم زيادة راتب", الاسم, "بمقدار", زيادة) ;
        اطبع("الراتب الجديد:", الراتب) ;
    نهاية
    
    دالة اطبع_معلومات_الموظف()
        اطبع("======= معلومات الموظف =======") ;
        اطبع_المعلومات_الأساسية() ;  # من الصنف الأساسي
        اطبع("الوظيفة:", الوظيفة) ;
        اطبع("الراتب:", الراتب) ;
        اطبع("سنوات الخبرة:", سنوات_الخبرة) ;
        اطبع("===============================") ;
    نهاية
نهاية

