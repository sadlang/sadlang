# صنف الطالب
صنف طالب
    # الخصائص (Properties)
    نص الاسم ;
    رقم العمر ;
    نص التخصص ;
    رقم المعدل ;
    
    # البانى (Constructor)
    دالة طالب( نص اسم ، رقم عمر ، نص تخصص )
        الاسم = اسم ;
        العمر = عمر ;
        التخصص = تخصص ;
        المعدل = 0.0 ;  # معدل ابتدائي
        اطبع("تم إنشاء طالب جديد:", الاسم) ;
    نهاية
    
    # دالة للحصول على الاسم
    دالة احصل_على_الاسم()
        أرجع الاسم ;
    نهاية
    
    # دالة لتحديد المعدل
    دالة حدد_المعدل( رقم معدل_جديد )
        إذا ( معدل_جديد >= 0 && معدل_جديد <= 4.0 )
            المعدل = معدل_جديد ;
            اطبع("تم تحديث معدل", الاسم, "إلى", المعدل) ;
        وإلا
            اطبع("خطأ: المعدل يجب أن يكون بين 0 و 4.0") ;
        نهاية
    نهاية
    
    # دالة لطباعة معلومات الطالب
    دالة اطبع_المعلومات()
        اطبع("--- معلومات الطالب ---") ;
        اطبع("الاسم:", الاسم) ;
        اطبع("العمر:", العمر, "سنة") ;
        اطبع("التخصص:", التخصص) ;
        اطبع("المعدل:", المعدل) ;
        اطبع("------------------------") ;
    نهاية
    
    # دالة للتحقق من التفوق
    دالة متفوق()
        أرجع المعدل >= 3.5 ;
    نهاية
نهاية

