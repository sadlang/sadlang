# صنف أكثر تطوراً - حساب بنكي
# More Advanced Class - Bank Account
# ======================

اطبع("\n=== صنف الحساب البنكي ===") ;

صنف حساب_بنكي
    # خصائص خاصة
    خاص رقم الرصيد ;
    خاص نص رقم_الحساب ;
    
    # خصائص عامة
    نص اسم_صاحب_الحساب ;
    نص نوع_الحساب ;
    
    # البانى
    دالة حساب_بنكي( نص اسم_صاحب ، نص رقم ، نص نوع )
        اسم_صاحب_الحساب = اسم_صاحب ;
        رقم_الحساب = رقم ;
        نوع_الحساب = نوع ;
        الرصيد = 0.0 ;
        اطبع("تم فتح حساب جديد لـ", اسم_صاحب_الحساب) ;
        اطبع("رقم الحساب:", رقم_الحساب) ;
    نهاية
    
    # دالة للإيداع
    دالة ايداع( رقم المبلغ )
        إذا ( المبلغ > 0 )
            الرصيد = الرصيد + المبلغ ;
            اطبع("تم إيداع", المبلغ, "الرصيد الحالي:", الرصيد) ;
        وإلا
            اطبع("خطأ: مبلغ الإيداع يجب أن يكون موجب") ;
        نهاية
    نهاية
    
    # دالة للسحب
    دالة سحب( رقم المبلغ )
        إذا ( المبلغ > 0 )
            إذا ( المبلغ <= الرصيد )
                الرصيد = الرصيد - المبلغ ;
                اطبع("تم سحب", المبلغ, "الرصيد المتبقي:", الرصيد) ;
            وإلا
                اطبع("خطأ: الرصيد غير كافي") ;
                اطبع("المبلغ المطلوب:", المبلغ, "الرصيد المتوفر:", الرصيد) ;
            نهاية
        وإلا
            اطبع("خطأ: مبلغ السحب يجب أن يكون موجب") ;
        نهاية
    نهاية
    
    # دالة للحصول على الرصيد
    دالة احصل_على_الرصيد()
        أرجع الرصيد ;
    نهاية
    
    # دالة طباعة كشف الحساب
    دالة اطبع_كشف_الحساب()
        اطبع("========== كشف الحساب ==========") ;
        اطبع("اسم صاحب الحساب:", اسم_صاحب_الحساب) ;
        اطبع("رقم الحساب:", رقم_الحساب) ;
        اطبع("نوع الحساب:", نوع_الحساب) ;
        اطبع("الرصيد الحالي:", الرصيد) ;
        اطبع("==================================") ;
    نهاية
    
    # دالة التحويل إلى حساب آخر
    دالة حول_إلى( حساب_بنكي الحساب_الهدف ، رقم المبلغ )
        إذا ( المبلغ > 0 && المبلغ <= الرصيد )
            الرصيد = الرصيد - المبلغ ;
            الحساب_الهدف.ايداع(المبلغ) ;
            اطبع("تم تحويل", المبلغ, "من", اسم_صاحب_الحساب, "إلى", الحساب_الهدف.اسم_صاحب_الحساب) ;
        وإلا
            اطبع("فشل التحويل: تحقق من المبلغ والرصيد") ;
        نهاية
    نهاية
نهاية

