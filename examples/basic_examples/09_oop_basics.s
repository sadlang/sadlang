# صنف الكتاب
صنف كتاب
    نص العنوان ;
    نص المؤلف ;
    رقم سنة_النشر ;
    منطق متوفر ;
    
    دالة كتاب( نص عنوان ، نص مؤلف ، رقم سنة )
        العنوان = عنوان ;
        المؤلف = مؤلف ;
        سنة_النشر = سنة ;
        متوفر = صحيح ;
    نهاية
    
    دالة استعر()
        إذا ( متوفر )
            متوفر = خطأ ;
            اطبع("تم استعارة كتاب:", العنوان) ;
            أرجع صحيح ;
        وإلا
            اطبع("الكتاب غير متوفر:", العنوان) ;
            أرجع خطأ ;
        نهاية
    نهاية
    
    دالة أرجع_الكتاب()
        إذا ( !متوفر )
            متوفر = صحيح ;
            اطبع("تم إرجاع كتاب:", العنوان) ;
        وإلا
            اطبع("الكتاب موجود أصلاً:", العنوان) ;
        نهاية
    نهاية
    
    دالة اطبع_معلومات_الكتاب()
        اطبع("--- معلومات الكتاب ---") ;
        اطبع("العنوان:", العنوان) ;
        اطبع("المؤلف:", المؤلف) ;
        اطبع("سنة النشر:", سنة_النشر) ;
        اطبع("الحالة:", إذا( متوفر , "متوفر" , "مُستعار" )) ;
        اطبع("---------------------") ;
    نهاية
نهاية

