# خوارزمية Bubble Sort
دالة ترتيب_فقاعي( مصفوفة مصفوفة )
    رقم الطول = طول(مصفوفة) ;
    رقم تم_تبديل = صحيح ;
    
    بينما ( تم_تبديل )
        تم_تبديل = خطأ ;
        رقم مؤشر = 0 ;
        
        بينما ( مؤشر < الطول - 1 )
            إذا ( مصفوفة[مؤشر] > مصفوفة[مؤشر + 1] )
                # تبديل العنصرين
                رقم مؤقت = مصفوفة[مؤشر] ;
                مصفوفة[مؤشر] = مصفوفة[مؤشر + 1] ;
                مصفوفة[مؤشر + 1] = مؤقت ;
                تم_تبديل = صحيح ;
            نهاية
            مؤشر = مؤشر + 1 ;
        نهاية
    نهاية
    
    أرجع مصفوفة ;
نهاية

# خوارزمية Selection Sort  
دالة ترتيب_انتقائي( مصفوفة مصفوفة )
    رقم الطول = طول(مصفوفة) ;
    
    رقم ي = 0 ;
    بينما ( ي < الطول - 1 )
        رقم فهرس_الأصغر = ي ;
        رقم ج = ي + 1 ;
        
        # البحث عن أصغر عنصر
        بينما ( ج < الطول )
            إذا ( مصفوفة[ج] < مصفوفة[فهرس_الأصغر] )
                فهرس_الأصغر = ج ;
            نهاية
            ج = ج + 1 ;
        نهاية
        
        # تبديل العنصر الأصغر مع العنصر الحالي
        إذا ( فهرس_الأصغر != ي )
            رقم مؤقت = مصفوفة[ي] ;
            مصفوفة[ي] = مصفوفة[فهرس_الأصغر] ;
            مصفوفة[فهرس_الأصغر] = مؤقت ;
        نهاية
        
        ي = ي + 1 ;
    نهاية
    
    أرجع مصفوفة ;
نهاية

