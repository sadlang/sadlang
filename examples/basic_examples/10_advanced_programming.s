    دالة اطلع()
        إذا ( القمة >= 0 )
            أرجع العناصر[القمة] ;
        وإلا
            أرجع -1 ;
        نهاية
    نهاية
    
    # فحص إذا كان المكدس فارغ
    دالة فارغ()
        أرجع القمة == -1 ;
    نهاية
    
    # حجم المكدس
    دالة الحجم()
        أرجع القمة + 1 ;
    نهاية
    
    # طباعة محتوى المكدس
    دالة اطبع_المحتوى()
        إذا ( فارغ() )
            اطبع("المكدس فارغ") ;
        وإلا
            اطبع("محتوى المكدس (من الأسفل للأعلى):", العناصر) ;
            اطبع("العنصر العلوي:", العناصر[القمة]) ;
        نهاية
    نهاية
