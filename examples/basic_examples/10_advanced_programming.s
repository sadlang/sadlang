دالة بحث_خطي( مصفوفة مصفوفة ، رقم القيمة )
    رقم مؤشر = 0 ;
    
    بينما ( مؤشر < طول(مصفوفة) )
        إذا ( مصفوفة[مؤشر] == القيمة )
            أرجع مؤشر ;
        نهاية
        مؤشر = مؤشر + 1 ;
    نهاية
    
    أرجع -1 ;  # لم يوجد
نهاية

# البحث الثنائي (للمصفوفات المرتبة)
دالة بحث_ثنائي( مصفوفة مصفوفة_مرتبة ، رقم القيمة )
    رقم البداية = 0 ;
    رقم النهاية = طول(مصفوفة_مرتبة) - 1 ;
    
    بينما ( البداية <= النهاية )
        رقم الوسط = (البداية + النهاية) / 2 ;
        
        إذا ( مصفوفة_مرتبة[الوسط] == القيمة )
            أرجع الوسط ;
        وإلا إذا ( مصفوفة_مرتبة[الوسط] < القيمة )
            البداية = الوسط + 1 ;
        وإلا
            النهاية = الوسط - 1 ;
        نهاية
    نهاية
    
    أرجع -1 ;  # لم يوجد
نهاية

