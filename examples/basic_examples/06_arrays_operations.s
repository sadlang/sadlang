# ======================
# إيجاد أكبر وأصغر رقم
# Finding Maximum and Minimum
# ======================

اطبع("\n=== إيجاد أكبر وأصغر رقم ===") ;

مصفوفة درجات_متنوعة = [85, 92, 67, 98, 73, 88, 91] ;
اطبع("الدرجات:", درجات_متنوعة) ;

# تهيئة القيم بأول عنصر
رقم أكبر_درجة = درجات_متنوعة[0] ;
رقم أصغر_درجة = درجات_متنوعة[0] ;
رقم فهرس_الأكبر = 0 ;
رقم فهرس_الأصغر = 0 ;

رقم فهرس_المقارنة = 1 ;  # نبدأ من العنصر الثاني

بينما ( فهرس_المقارنة < طول(درجات_متنوعة) )
    رقم الدرجة_الحالية = درجات_متنوعة[فهرس_المقارنة] ;
    
    إذا ( الدرجة_الحالية > أكبر_درجة )
        أكبر_درجة = الدرجة_الحالية ;
        فهرس_الأكبر = فهرس_المقارنة ;
    نهاية
    
    إذا ( الدرجة_الحالية < أصغر_درجة )
        أصغر_درجة = الدرجة_الحالية ;
        فهرس_الأصغر = فهرس_المقارنة ;
    نهاية
    
    فهرس_المقارنة = فهرس_المقارنة + 1 ;
نهاية

اطبع("أكبر درجة:", أكبر_درجة, "في الموضع", فهرس_الأكبر) ;
اطبع("أصغر درجة:", أصغر_درجة, "في الموضع", فهرس_الأصغر) ;

