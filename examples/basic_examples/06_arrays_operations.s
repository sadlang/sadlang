# ======================
# ترتيب المصفوفة (Bubble Sort بسيط)
# Array Sorting (Simple Bubble Sort)
# ======================

اطبع("\n=== ترتيب المصفوفة ===") ;

مصفوفة أرقام_للترتيب = [64, 34, 25, 12, 22, 11, 90] ;
اطبع("قبل الترتيب:", أرقام_للترتيب) ;

# Bubble Sort
رقم ن = طول(أرقام_للترتيب) ;
رقم ي = 0 ;

بينما ( ي < ن - 1 )
    رقم ج = 0 ;
    بينما ( ج < ن - ي - 1 )
        إذا ( أرقام_للترتيب[ج] > أرقام_للترتيب[ج + 1] )
            # تبديل العنصرين
            رقم مؤقت = أرقام_للترتيب[ج] ;
            أرقام_للترتيب[ج] = أرقام_للترتيب[ج + 1] ;
            أرقام_للترتيب[ج + 1] = مؤقت ;
        نهاية
        ج = ج + 1 ;
    نهاية
    ي = ي + 1 ;
نهاية

اطبع("بعد الترتيب:", أرقام_للترتيب) ;

