# ======================
# دوال للمصفوفات
# Array Functions
# ======================

# دالة حساب متوسط مصفوفة
دالة احسب_المتوسط( مصفوفة الأرقام )
    رقم المجموع = 0 ;
    رقم العدد = 0 ;
    
    بينما ( العدد < طول(الأرقام) )
        المجموع = المجموع + الأرقام[العدد] ;
        العدد = العدد + 1 ;
    نهاية
    
    رقم المتوسط = المجموع / طول(الأرقام) ;
    أرجع المتوسط ;
نهاية

# دالة إيجاد أكبر رقم في مصفوفة
دالة اجد_الأكبر( مصفوفة الأرقام )
    رقم الأكبر = الأرقام[0] ;
    رقم الفهرس = 1 ;
    
    بينما ( الفهرس < طول(الأرقام) )
        إذا ( الأرقام[الفهرس] > الأكبر )
            الأكبر = الأرقام[الفهرس] ;
        نهاية
        الفهرس = الفهرس + 1 ;
    نهاية
    
    أرجع الأكبر ;
نهاية

# دالة عد الأرقام الموجبة
دالة عد_الموجبة( مصفوفة الأرقام )
    رقم العدد = 0 ;
    رقم المؤشر = 0 ;
    
    بينما ( المؤشر < طول(الأرقام) )
        إذا ( الأرقام[المؤشر] > 0 )
            العدد = العدد + 1 ;
        نهاية
        المؤشر = المؤشر + 1 ;
    نهاية
    
    أرجع العدد ;
نهاية

اطبع("\n=== دوال المصفوفات ===") ;

