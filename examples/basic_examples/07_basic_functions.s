# ======================
# دالة حاسبة شاملة
# Complete Calculator Function
# ======================

دالة حاسبة( رقم أ ، رقم ب ، نص العملية )
    إذا ( العملية == "+" )
        أرجع أ + ب ;
    وإلا إذا ( العملية == "-" )
        أرجع أ - ب ;
    وإلا إذا ( العملية == "*" )
        أرجع أ * ب ;
    وإلا إذا ( العملية == "/" )
        إذا ( ب != 0 )
            أرجع أ / ب ;
        وإلا
            اطبع("خطأ: لا يمكن القسمة على صفر") ;
            أرجع 0 ;
        نهاية
    وإلا
        اطبع("عملية غير معروفة:", العملية) ;
        أرجع 0 ;
    نهاية
نهاية

اطبع("\n=== آلة حاسبة ===") ;

