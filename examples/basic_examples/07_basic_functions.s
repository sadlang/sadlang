# دالة مع قيمة إرجاع
# Function with Return Value
# ======================

# دالة جمع رقمين
دالة اجمع( رقم أ ، رقم ب )
    رقم النتيجة = أ + ب ;
    أرجع النتيجة ;
نهاية

