# دالة فحص الدرجة
دالة فحص_الدرجة( رقم الدرجة )
    إذا ( الدرجة >= 95 )
        أرجع "ممتاز+" ;
    وإلا إذا ( الدرجة >= 90 )
        أرجع "ممتاز" ;
    وإلا إذا ( الدرجة >= 85 )
        أرجع "جيد جداً+" ;
    وإلا إذا ( الدرجة >= 80 )
        أرجع "جيد جداً" ;
    وإلا إذا ( الدرجة >= 70 )
        أرجع "جيد" ;
    وإلا إذا ( الدرجة >= 60 )
        أرجع "مقبول" ;
    وإلا
        أرجع "راسب" ;
    نهاية
نهاية

# دالة تحديد فئة العمر
دالة فئة_العمر( رقم العمر )
    إذا ( العمر < 13 )
        أرجع "طفل" ;
    وإلا إذا ( العمر < 20 )
        أرجع "مراهق" ;
    وإلا إذا ( العمر < 60 )
        أرجع "بالغ" ;
    وإلا
        أرجع "كبير السن" ;
    نهاية
نهاية

اطبع("\n=== دوال التحقق ===") ;

مصفوفة درجات_للفحص = [96, 87, 72, 58, 91] ;
