# مثال 2: المتغيرات وأنواع البيانات
# Example 2: Variables and Data Types

# ======================
# أنواع البيانات الأساسية
# Basic Data Types
# ======================

اطبع("=== أنواع البيانات الأساسية ===") ;
اطبع("=== Basic Data Types ===") ;

# الأرقام (Numbers)
رقم العمر = 25 ;
رقم الراتب = 5000.50 ;
رقم درجة_الحرارة = -10 ;

اطبع("العمر:", العمر) ;
اطبع("الراتب:", الراتب) ;
اطبع("درجة الحرارة:", درجة_الحرارة) ;

# النصوص (Strings)
نص الاسم_الأول = "أحمد" ;
نص الاسم_الأخير = "محمد" ;
نص الرسالة = "مرحباً بكم في لغة ص" ;

اطبع("الاسم الأول:", الاسم_الأول) ;
اطبع("الاسم الأخير:", الاسم_الأخير) ;
اطبع("الرسالة:", الرسالة) ;

# القيم المنطقية (Booleans)
منطق متزوج = صحيح ;
منطق طالب = خطأ ;
منطق يعمل = صحيح ;

اطبع("متزوج:", متزوج) ;
اطبع("طالب:", طالب) ;
اطبع("يعمل:", يعمل) ;

# ======================
# عمليات على المتغيرات
# Variable Operations
# ======================

اطبع("\n=== عمليات على المتغيرات ===") ;

# تغيير قيم المتغيرات
العمر = العمر + 1 ;
اطبع("العمر بعد سنة:", العمر) ;

# دمج النصوص
نص الاسم_الكامل = الاسم_الأول + " " + الاسم_الأخير ;
اطبع("الاسم الكامل:", الاسم_الكامل) ;

# عمليات منطقية
منطق يستطيع_التصويت = العمر >= 18 ;
اطبع("يستطيع التصويت:", يستطيع_التصويت) ;

# ======================
# المصفوفات (Arrays)
# ======================

اطبع("\n=== المصفوفات ===") ;

# مصفوفة أرقام
مصفوفة درجات = [95, 87, 92, 78, 88] ;
اطبع("الدرجات:", درجات) ;
اطبع("أول درجة:", درجات[0]) ;
اطبع("آخر درجة:", درجات[4]) ;

# مصفوفة نصوص
مصفوفة أسماء = ["أحمد", "فاطمة", "محمد", "عائشة"] ;
اطبع("الأسماء:", أسماء) ;
اطبع("أول اسم:", أسماء[0]) ;

# مصفوفة مختلطة
مصفوفة بيانات = ["أحمد", 25, صحيح, 5000.50] ;
اطبع("البيانات المختلطة:", بيانات) ;

# ======================
# أمثلة عملية
# Practical Examples
# ======================

اطبع("\n=== أمثلة عملية ===") ;

# حساب معدل الدرجات
رقم مجموع_الدرجات = 95 + 87 + 92 + 78 + 88 ;
رقم عدد_المواد = 5 ;
رقم المعدل = مجموع_الدرجات / عدد_المواد ;
اطبع("المعدل:", المعدل) ;

# معلومات شخصية
نص اسم = "سارة" ;
رقم عمر = 22 ;
نص مهنة = "مطورة برمجيات" ;
منطق خريجة = صحيح ;

اطبع("الاسم:", اسم) ;
اطبع("العمر:", عمر) ;
اطبع("المهنة:", مهنة) ;
اطبع("خريجة جامعية:", خريجة) ;

# حساب السن بالأيام (تقريبي)
رقم عدد_الأيام = عمر * 365 ;
اطبع("تقريباً", عدد_الأيام, "يوم منذ الولادة") ;

اطبع("\n==================") ;
اطبع("انتهى مثال المتغيرات") ;