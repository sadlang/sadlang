# ======================
# حلقة while الأساسية
# Basic while Loop
# ======================

اطبع("=== حلقة while الأساسية ===") ;

# طباعة الأرقام من 1 إلى 5
رقم عداد = 1 ;
اطبع("الأرقام من 1 إلى 5:") ;

بينما ( عداد <= 5 )
    اطبع("الرقم:", عداد) ;
    عداد = عداد + 1 ;
نهاية

# ======================
# العد التنازلي
# Countdown
# ======================

اطبع("\n=== العد التنازلي ===") ;

رقم عد_تنازلي = 5 ;
اطبع("بدء العد التنازلي من", عد_تنازلي) ;

بينما ( عد_تنازلي > 0 )
    اطبع(عد_تنازلي) ;
    عد_تنازلي = عد_تنازلي - 1 ;
نهاية

اطبع("انطلاق! 🚀") ;

# ======================
# جمع الأرقام
# Sum Numbers
# ======================

اطبع("\n=== جمع الأرقام من 1 إلى 10 ===") ;

رقم العدد = 1 ;
رقم المجموع = 0 ;

بينما ( العدد <= 10 )
    المجموع = المجموع + العدد ;
    اطبع("إضافة", العدد, "المجموع الحالي:", المجموع) ;
    العدد = العدد + 1 ;
نهاية

اطبع("المجموع النهائي من 1 إلى 10 =", المجموع) ;

# ======================
# حساب المضروب (Factorial)
# ======================

اطبع("\n=== حساب المضروب ===") ;

رقم الرقم_للمضروب = 5 ;
رقم المضروب = 1 ;
رقم مؤشر = 1 ;

اطبع("حساب مضروب", الرقم_للمضروب) ;

بينما ( مؤشر <= الرقم_للمضروب )
    المضروب = المضروب * مؤشر ;
    اطبع(مؤشر, "! =", المضروب) ;
    مؤشر = مؤشر + 1 ;
نهاية

اطبع("النتيجة النهائية:", الرقم_للمضروب, "! =", المضروب) ;

# ======================
# جدول الضرب
# Multiplication Table
# ======================

اطبع("\n=== جدول الضرب ===") ;

رقم الرقم_الأساسي = 7 ;
رقم المضاعف = 1 ;

اطبع("جدول ضرب العدد", الرقم_الأساسي, ":") ;

بينما ( المضاعف <= 10 )
    رقم النتيجة = الرقم_الأساسي * المضاعف ;
    اطبع(الرقم_الأساسي, "×", المضاعف, "=", النتيجة) ;
    المضاعف = المضاعف + 1 ;
نهاية

# ======================
# البحث عن الأرقام الزوجية والفردية
# Finding Even and Odd Numbers
# ======================

اطبع("\n=== الأرقام الزوجية والفردية من 1 إلى 15 ===") ;

رقم الرقم_الحالي = 1 ;

بينما ( الرقم_الحالي <= 15 )
    إذا ( الرقم_الحالي % 2 == 0 )
        اطبع(الرقم_الحالي, "زوجي") ;
    وإلا
        اطبع(الرقم_الحالي, "فردي") ;
    نهاية
    الرقم_الحالي = الرقم_الحالي + 1 ;
نهاية

# ======================
# حلقة للتحقق من شرط معين
# Loop with Condition Check
# ======================

اطبع("\n=== البحث عن رقم معين ===") ;

رقم الهدف = 13 ;
رقم البحث = 1 ;
منطق وُجد = خطأ ;

اطبع("البحث عن الرقم", الهدف, "في المجال من 1 إلى 20") ;

بينما ( البحث <= 20 && !وُجد )
    إذا ( البحث == الهدف )
        اطبع("وُجد الرقم", الهدف, "في الموضع", البحث) ;
        وُجد = صحيح ;
    نهاية
    البحث = البحث + 1 ;
نهاية

إذا ( !وُجد )
    اطبع("لم يوجد الرقم", الهدف) ;
نهاية

# ======================
# حساب المتوسط
# Calculate Average
# ======================

اطبع("\n=== حساب متوسط مجموعة أرقام ===") ;

رقم عدد_الأرقام = 5 ;
رقم مجموع_الأرقام = 0 ;
رقم الترقيم = 1 ;

# أرقام للمثال: 85, 92, 78, 96, 89
مصفوفة الدرجات = [85, 92, 78, 96, 89] ;

اطبع("الدرجات:", الدرجات) ;
اطبع("حساب المتوسط...") ;

بينما ( الترقيم <= عدد_الأرقام )
    رقم الدرجة_الحالية = الدرجات[الترقيم - 1] ;  # المصفوفة تبدأ من 0
    مجموع_الأرقام = مجموع_الأرقام + الدرجة_الحالية ;
    اطبع("إضافة درجة", الترقيم, ":", الدرجة_الحالية, "المجموع:", مجموع_الأرقام) ;
    الترقيم = الترقيم + 1 ;
نهاية

رقم المتوسط = مجموع_الأرقام / عدد_الأرقام ;
اطبع("المتوسط النهائي:", المتوسط) ;

# ======================
# إيجاد أكبر رقم في مجموعة
# Find Maximum Number
# ======================

اطبع("\n=== إيجاد أكبر رقم ===") ;

مصفوفة أرقام_مختلفة = [23, 67, 12, 89, 45, 56, 34] ;
رقم أكبر_رقم = أرقام_مختلفة[0] ;  # افتراض أول رقم هو الأكبر
رقم فهرس = 1 ;  # نبدأ من الرقم الثاني

اطبع("الأرقام:", أرقام_مختلفة) ;

بينما ( فهرس < طول(أرقام_مختلفة) )
    رقم الرقم_الحالي = أرقام_مختلفة[فهرس] ;
    اطبع("مقارنة", الرقم_الحالي, "مع", أكبر_رقم) ;
    
    إذا ( الرقم_الحالي > أكبر_رقم )
        أكبر_رقم = الرقم_الحالي ;
        اطبع("رقم جديد أكبر:", أكبر_رقم) ;
    نهاية
    
    فهرس = فهرس + 1 ;
نهاية

اطبع("أكبر رقم في المجموعة:", أكبر_رقم) ;

# ======================
# محاكاة حساب بنكي
# Bank Account Simulation
# ======================

اطبع("\n=== محاكاة حساب بنكي ===") ;

رقم الرصيد = 1000 ;
رقم يوم = 1 ;

اطبع("الرصيد الابتدائي:", الرصيد) ;

بينما ( يوم <= 7 && الرصيد > 0 )
    اطبع("--- اليوم", يوم, "---") ;
    
    # محاكاة مصروف يومي عشوائي (للمثال نستخدم قيم ثابتة)
    رقم المصروف_اليومي ;
    
    إذا ( يوم == 1 )
        المصروف_اليومي = 50 ;  # طعام
    وإلا إذا ( يوم == 2 )
        المصروف_اليومي = 200 ; # تسوق
    وإلا إذا ( يوم == 3 )
        المصروف_اليومي = 30 ;  # نقل
    وإلا إذا ( يوم == 4 )
        المصروف_اليومي = 100 ; # فواتير
    وإلا إذا ( يوم == 5 )
        المصروف_اليومي = 75 ;  # ترفيه
    وإلا إذا ( يوم == 6 )
        المصروف_اليومي = 40 ;  # طعام
    وإلا
        المصروف_اليومي = 60 ;  # متنوعة
    نهاية
    
    إذا ( المصروف_اليومي <= الرصيد )
        الرصيد = الرصيد - المصروف_اليومي ;
        اطبع("مصروف:", المصروف_اليومي, "الرصيد المتبقي:", الرصيد) ;
    وإلا
        اطبع("رصيد غير كافي! مطلوب:", المصروف_اليومي, "متوفر:", الرصيد) ;
    نهاية
    
    يوم = يوم + 1 ;
نهاية

إذا ( الرصيد <= 0 )
    اطبع("تحذير: نفد الرصيد!") ;
وإلا
    اطبع("الرصيد النهائي بعد 7 أيام:", الرصيد) ;
نهاية

اطبع("\n==================") ;
