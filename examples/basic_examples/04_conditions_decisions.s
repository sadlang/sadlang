# مثال 4: الشروط والقرارات (if-else)
# Example 4: Conditions and Decisions (if-else)

# ======================
# الشروط الأساسية
# Basic Conditions
# ======================

اطبع("=== الشروط الأساسية ===") ;

رقم العمر = 20 ;

اطبع("العمر:", العمر) ;

# شرط بسيط
إذا ( العمر >= 18 )
    اطبع("أنت بالغ") ;
نهاية

# شرط مع else
إذا ( العمر >= 65 )
    اطبع("أنت من كبار السن") ;
وإلا
    اطبع("أنت لست من كبار السن") ;
نهاية

# ======================
# شروط متعددة المستويات
# Multi-level Conditions
# ======================

اطبع("\n=== تصنيف العمر ===") ;

رقم عمر_الشخص = 25 ;
اطبع("عمر الشخص:", عمر_الشخص) ;

إذا ( عمر_الشخص < 13 )
    اطبع("طفل") ;
وإلا إذا ( عمر_الشخص < 20 )
    اطبع("مراهق") ;
وإلا إذا ( عمر_الشخص < 60 )
    اطبع("بالغ") ;
وإلا
    اطبع("كبير السن") ;
نهاية

