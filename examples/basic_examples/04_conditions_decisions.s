# ======================
# صرف الراتب
# Salary Management
# ======================

اطبع("\n=== إدارة الراتب ===") ;

رقم الراتب = 4500 ;
رقم الإيجار = 1200 ;
رقم الطعام = 800 ;
رقم النقل = 300 ;
رقم فواتير = 400 ;

رقم إجمالي_المصروفات = الإيجار + الطعام + النقل + فواتير ;
رقم الباقي = الراتب - إجمالي_المصروفات ;

اطبع("الراتب:", الراتب) ;
اطبع("المصروفات:", إجمالي_المصروفات) ;
اطبع("المبلغ الباقي:", الباقي) ;

إذا ( الباقي > 1000 )
    اطبع("وضع مالي ممتاز! يمكنك الادخار") ;
    رقم الادخار_المقترح = الباقي * 0.3 ;
    اطبع("اقتراح للادخار:", الادخار_المقترح) ;
وإلا إذا ( الباقي > 500 )
    اطبع("وضع مالي جيد") ;
وإلا إذا ( الباقي > 0 )
    اطبع("احذر! لديك مال قليل متبقي") ;
وإلا
    اطبع("تحذير! مصروفاتك أكبر من راتبك!") ;
    رقم العجز = إجمالي_المصروفات - الراتب ;
    اطبع("مقدار العجز:", العجز) ;
نهاية

# ======================
# تحديد نوع المثلث
# Triangle Type Detection
# ======================

اطبع("\n=== تحديد نوع المثلث ===") ;

رقم ضلع1 = 5 ;
رقم ضلع2 = 5 ;
رقم ضلع3 = 8 ;

اطبع("أطوال الأضلاع:", ضلع1, "،", ضلع2, "،", ضلع3) ;

# التحقق من صحة المثلث
إذا ( ضلع1 + ضلع2 > ضلع3 && ضلع1 + ضلع3 > ضلع2 && ضلع2 + ضلع3 > ضلع1 )
    إذا ( ضلع1 == ضلع2 && ضلع2 == ضلع3 )
        اطبع("مثلث متساوي الأضلاع") ;
    وإلا إذا ( ضلع1 == ضلع2 || ضلع2 == ضلع3 || ضلع1 == ضلع3 )
        اطبع("مثلث متساوي الساقين") ;
    وإلا
        اطبع("مثلث مختلف الأضلاع") ;
    نهاية
وإلا
    اطبع("هذه الأطوال لا تشكل مثلثاً صحيحاً!") ;
نهاية

