# ======================
# شروط مركبة (AND, OR)
# Compound Conditions
# ======================

اطبع("\n=== شروط القبول في الجامعة ===") ;

رقم درجة_الثانوية = 92 ;
رقم درجة_الرياضيات = 85 ;
رقم درجة_الإنجليزية = 78 ;
منطق حضر_اختبار_القدرات = صحيح ;

اطبع("درجة الثانوية:", درجة_الثانوية) ;
اطبع("درجة الرياضيات:", درجة_الرياضيات) ;
اطبع("درجة الإنجليزية:", درجة_الإنجليزية) ;
اطبع("حضر اختبار القدرات:", حضر_اختبار_القدرات) ;

# شروط مختلفة للتخصصات
إذا ( درجة_الثانوية >= 95 && درجة_الرياضيات >= 90 && حضر_اختبار_القدرات )
    اطبع("مقبول في الطب أو الهندسة") ;
وإلا إذا ( درجة_الثانوية >= 85 && درجة_الرياضيات >= 80 )
    اطبع("مقبول في العلوم أو الحاسوب") ;
وإلا إذا ( درجة_الثانوية >= 75 && درجة_الإنجليزية >= 75 )
    اطبع("مقبول في الأدب أو الإدارة") ;
وإلا إذا ( درجة_الثانوية >= 70 )
    اطبع("مقبول في التخصصات العامة") ;
وإلا
    اطبع("غير مقبول - يرجى إعادة التقديم") ;
نهاية

