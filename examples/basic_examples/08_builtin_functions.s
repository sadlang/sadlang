اطبع("\n=== مثال تطبيقي شامل ===") ;

# إنشاء تقرير إحصائي لمصفوفة درجات
مصفوفة درجات_الطلاب = [85, 92, 78, 96, 73, 88, 91, 82, 95, 79] ;

اطبع("=== تقرير إحصائي للدرجات ===") ;
اطبع("الدرجات:", درجات_الطلاب) ;

# الإحصائيات الأساسية
رقم عدد_الطلاب = طول(درجات_الطلاب) ;
رقم مجموع_الدرجات = 0 ;
رقم أعلى_درجة = أكبر_في_مصفوفة(درجات_الطلاب) ;
رقم أقل_درجة = أصغر_في_مصفوفة(درجات_الطلاب) ;

# حساب المجموع
رقم مؤشر_المجموع = 0 ;
بينما ( مؤشر_المجموع < عدد_الطلاب )
    مجموع_الدرجات = مجموع_الدرجات + درجات_الطلاب[مؤشر_المجموع] ;
    مؤشر_المجموع = مؤشر_المجموع + 1 ;
نهاية

رقم المتوسط = قرب(مجموع_الدرجات / عدد_الطلاب) ;

# عد حسب الفئات
رقم عدد_ممتاز = 0 ;    # >= 90
رقم عدد_جيد_جدا = 0 ;  # 80-89
رقم عدد_جيد = 0 ;      # 70-79
رقم عدد_مقبول = 0 ;    # 60-69
رقم عدد_راسب = 0 ;     # < 60

رقم مؤشر_التصنيف = 0 ;
بينما ( مؤشر_التصنيف < عدد_الطلاب )
    رقم الدرجة = درجات_الطلاب[مؤشر_التصنيف] ;
    
    إذا ( الدرجة >= 90 )
        عدد_ممتاز = عدد_ممتاز + 1 ;
    وإلا إذا ( الدرجة >= 80 )
        عدد_جيد_جدا = عدد_جيد_جدا + 1 ;
    وإلا إذا ( الدرجة >= 70 )
        عدد_جيد = عدد_جيد + 1 ;
    وإلا إذا ( الدرجة >= 60 )
        عدد_مقبول = عدد_مقبول + 1 ;
    وإلا
        عدد_راسب = عدد_راسب + 1 ;
    نهاية
    
    مؤشر_التصنيف = مؤشر_التصنيف + 1 ;
نهاية

# طباعة التقرير
اطبع("عدد الطلاب:", عدد_الطلاب) ;
اطبع("المجموع الكلي:", مجموع_الدرجات) ;
اطبع("المتوسط:", المتوسط) ;
اطبع("أعلى درجة:", أعلى_درجة) ;
اطبع("أقل درجة:", أقل_درجة) ;
