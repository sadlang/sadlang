# مثال 3: العمليات الحسابية والمقارنات
# Example 3: Arithmetic Operations and Comparisons

# ======================
# العمليات الحسابية الأساسية
# Basic Arithmetic Operations
# ======================

اطبع("=== العمليات الحسابية الأساسية ===") ;

رقم أ = 15 ;
رقم ب = 4 ;

اطبع("الرقم أ:", أ) ;
اطبع("الرقم ب:", ب) ;
اطبع("") ;

# العمليات الأساسية
رقم الجمع = أ + ب ;
رقم الطرح = أ - ب ;
رقم الضرب = أ * ب ;
رقم القسمة = أ / ب ;
رقم الباقي = أ % ب ;

اطبع("الجمع (أ + ب):", الجمع) ;
اطبع("الطرح (أ - ب):", الطرح) ;
اطبع("الضرب (أ * ب):", الضرب) ;
اطبع("القسمة (أ / ب):", القسمة) ;
اطبع("الباقي (أ % ب):", الباقي) ;

# ======================
# أمثلة حسابية متقدمة
# Advanced Arithmetic Examples
# ======================

اطبع("\n=== أمثلة حسابية متقدمة ===") ;

# حساب مساحة المستطيل
رقم الطول = 12 ;
رقم العرض = 8 ;
رقم المساحة = الطول * العرض ;
اطبع("مساحة المستطيل:", الطول, "×", العرض, "=", المساحة) ;

# حساب محيط الدائرة (π ≈ 3.14159)
رقم نصف_القطر = 5 ;
رقم ط = 3.14159 ;
رقم المحيط = 2 * ط * نصف_القطر ;
اطبع("محيط الدائرة بنصف قطر", نصف_القطر, "=", المحيط) ;

# تحويل درجة حرارة من مئوية إلى فهرنهايت
رقم مئوية = 25 ;
رقم فهرنهايت = (مئوية * 9 / 5) + 32 ;
اطبع(مئوية, "درجة مئوية =", فهرنهايت, "درجة فهرنهايت") ;

# ======================
# العمليات المقارنة
# Comparison Operations
# ======================

اطبع("\n=== عمليات المقارنة ===") ;

رقم س = 10 ;
رقم ص = 15 ;

اطبع("س =", س, "، ص =", ص) ;
اطبع("") ;

# مقارنات رقمية
اطبع("س == ص:", س == ص) ;  # يساوي
اطبع("س != ص:", س != ص) ;  # لا يساوي
اطبع("س < ص:", س < ص) ;    # أصغر من
اطبع("س > ص:", س > ص) ;    # أكبر من
اطبع("س <= ص:", س <= ص) ;  # أصغر من أو يساوي
اطبع("س >= ص:", س >= ص) ;  # أكبر من أو يساوي

# مقارنات نصية
نص كلمة1 = "أحمد" ;
نص كلمة2 = "محمد" ;
نص كلمة3 = "أحمد" ;

اطبع("\n=== مقارنة النصوص ===") ;
اطبع("كلمة1:", كلمة1) ;
اطبع("كلمة2:", كلمة2) ;
اطبع("كلمة3:", كلمة3) ;
اطبع("") ;

اطبع("كلمة1 == كلمة2:", كلمة1 == كلمة2) ;
اطبع("كلمة1 == كلمة3:", كلمة1 == كلمة3) ;
اطبع("كلمة1 != كلمة2:", كلمة1 != كلمة2) ;

# ======================
# العمليات المنطقية
# Logical Operations
# ======================

اطبع("\n=== العمليات المنطقية ===") ;

منطق حالة1 = صحيح ;
منطق حالة2 = خطأ ;

اطبع("حالة1:", حالة1) ;
اطبع("حالة2:", حالة2) ;
اطبع("") ;

# العمليات المنطقية الأساسية
اطبع("حالة1 && حالة2:", حالة1 && حالة2) ;  # AND
اطبع("حالة1 || حالة2:", حالة1 || حالة2) ;  # OR
اطبع("!حالة1:", !حالة1) ;                   # NOT
اطبع("!حالة2:", !حالة2) ;                   # NOT

# مثال عملي: شروط القبول في الجامعة
رقم درجة_الثانوية = 85 ;
رقم درجة_اللغة = 70 ;
رقم الحد_الأدنى_الثانوية = 80 ;
رقم الحد_الأدنى_اللغة = 65 ;

منطق مؤهل_الثانوية = درجة_الثانوية >= الحد_الأدنى_الثانوية ;
منطق مؤهل_اللغة = درجة_اللغة >= الحد_الأدنى_اللغة ;
منطق مقبول = مؤهل_الثانوية && مؤهل_اللغة ;

اطبع("\n=== مثال عملي: شروط القبول ===") ;
اطبع("درجة الثانوية:", درجة_الثانوية) ;
اطبع("درجة اللغة:", درجة_اللغة) ;
اطبع("مؤهل في الثانوية:", مؤهل_الثانوية) ;
اطبع("مؤهل في اللغة:", مؤهل_اللغة) ;
اطبع("مقبول في الجامعة:", مقبول) ;

# ======================
# أمثلة رياضية متنوعة
# Various Mathematical Examples
# ======================

اطبع("\n=== أمثلة رياضية متنوعة ===") ;

# حساب المتوسط الحسابي
رقم درجة1 = 85 ;
رقم درجة2 = 92 ;
رقم درجة3 = 78 ;
رقم درجة4 = 96 ;
رقم المتوسط = (درجة1 + درجة2 + درجة3 + درجة4) / 4 ;
اطبع("المتوسط الحسابي:", المتوسط) ;

# حساب سعر بعد الخصم
رقم السعر_الأصلي = 100 ;
رقم نسبة_الخصم = 15 ;  # 15%
رقم مقدار_الخصم = السعر_الأصلي * نسبة_الخصم / 100 ;
رقم السعر_النهائي = السعر_الأصلي - مقدار_الخصم ;

اطبع("السعر الأصلي:", السعر_الأصلي) ;
اطبع("نسبة الخصم:", نسبة_الخصم, "%") ;
اطبع("مقدار الخصم:", مقدار_الخصم) ;
اطبع("السعر النهائي:", السعر_النهائي) ;

# حساب الفائدة البسيطة
رقم رأس_المال = 1000 ;
رقم معدل_الفائدة = 5 ;  # 5% سنوياً
رقم المدة = 3 ;         # 3 سنوات
رقم الفائدة = رأس_المال * معدل_الفائدة * المدة / 100 ;
رقم المبلغ_الكلي = رأس_المال + الفائدة ;

اطبع("\n--- حساب الفائدة البسيطة ---") ;
اطبع("رأس المال:", رأس_المال) ;
اطبع("معدل الفائدة:", معدل_الفائدة, "% سنوياً") ;
اطبع("المدة:", المدة, "سنوات") ;
اطبع("الفائدة:", الفائدة) ;
اطبع("المبلغ الكلي:", المبلغ_الكلي) ;

اطبع("\n==================") ;
اطبع("انتهى مثال العمليات الحسابية") ;