# بسم الله الرحمن الرحيم
"""
مثال شامل: عمليات نظام الملفات في لغة ص
Comprehensive Example: Filesystem Operations in Sad Language

هذا المثال يوضح استخدام جميع دوال نظام الملفات المتاحة
This example demonstrates using all available filesystem functions

الحمد لله رب العالمين
"""

# ============================================================================
# قراءة وكتابة الملفات / File I/O
# ============================================================================

اطبع("=== قراءة وكتابة الملفات ===")

# كتابة ملف نصي / Write text file
اكتب_ملف("مثال.txt"، "مرحباً بالعالم!\nهذا ملف تجريبي.")

# قراءة الملف / Read file
محتوى = اقرأ_ملف("مثال.txt")
اطبع("المحتوى:", محتوى)

# كتابة أسطر / Write lines
مصفوفة أسطر = ["السطر الأول", "السطر الثاني", "السطر الثالث"]
اكتب_أسطر("أسطر.txt"، أسطر)

# قراءة أسطر / Read lines
أسطر_مقروءة = اقرأ_أسطر("أسطر.txt")
لكل سطر في أسطر_مقروءة:
    اطبع("سطر:", سطر)

# إضافة إلى ملف / Append to file
أضف_إلى_ملف("مثال.txt"، "\nسطر إضافي!")

# نسخ ملف / Copy file
انسخ_ملف("مثال.txt"، "نسخة.txt")

# نقل ملف / Move file
انقل_ملف("نسخة.txt"، "نسخة_منقولة.txt")

# ============================================================================
# عمليات المجلدات / Directory Operations
# ============================================================================

اطبع("\n=== عمليات المجلدات ===")

# إنشاء مجلد / Create directory
أنشئ_مجلد("بيانات")
أنشئ_مجلد("بيانات/فرعي/متداخل"، صحيح)  # تكراري / recursive

# الحصول على مجلد العمل / Get current directory
مجلد_العمل = احصل_على_مجلد_العمل()
اطبع("مجلد العمل:", مجلد_العمل)

# سرد محتويات مجلد / List directory
محتويات = اسرد_مجلد("بيانات")
اطبع("محتويات المجلد:")
لكل عنصر في محتويات:
    اطبع("  -", عنصر)

# سرد تكراري / Recursive listing
اكتب_ملف("بيانات/ملف1.txt"، "محتوى 1")
اكتب_ملف("بيانات/فرعي/ملف2.txt"، "محتوى 2")

جميع_الملفات = اسرد_مجلد_تكراري("بيانات")
اطبع("جميع الملفات (تكراري):")
لكل ملف في جميع_الملفات:
    اطبع("  -", ملف)

# ============================================================================
# معالجة المسارات / Path Manipulation
# ============================================================================

اطبع("\n=== معالجة المسارات ===")

# جمع مسارات / Join paths
مسار = اجمع_مسار(["بيانات", "فرعي", "ملف.txt"])
اطبع("المسار المجموع:", مسار)

# الحصول على مسار مطلق / Get absolute path
مسار_مطلق = احصل_على_مسار_مطلق("مثال.txt")
اطبع("المسار المطلق:", مسار_مطلق)

# استخراج معلومات المسار / Extract path info
اسم_الملف = احصل_على_اسم_ملف(مسار_مطلق)
اطبع("اسم الملف:", اسم_الملف)

امتداد = احصل_على_امتداد(مسار_مطلق)
اطبع("الامتداد:", امتداد)

مجلد_أب = احصل_على_مجلد_أب(مسار_مطلق)
اطبع("المجلد الأب:", مجلد_أب)

# ============================================================================
# معلومات الملف / File Information
# ============================================================================

اطبع("\n=== معلومات الملف ===")

# فحص الوجود / Check existence
إذا هل_موجود("مثال.txt"):
    اطبع("✓ الملف موجود")

# فحص النوع / Check type
إذا هل_ملف("مثال.txt"):
    اطبع("✓ هذا ملف")

إذا هل_مجلد("بيانات"):
    اطبع("✓ هذا مجلد")

# الحصول على حجم الملف / Get file size
حجم = احصل_على_حجم_ملف("مثال.txt")
اطبع("حجم الملف:", حجم, "بايت")

# فحص الصلاحيات / Check permissions
إذا هل_قابل_للقراءة("مثال.txt"):
    اطبع("✓ الملف قابل للقراءة")

إذا هل_قابل_للكتابة("مثال.txt"):
    اطبع("✓ الملف قابل للكتابة")

# ============================================================================
# مطابقة الأنماط (Glob) / Pattern Matching
# ============================================================================

اطبع("\n=== مطابقة الأنماط ===")

# إنشاء ملفات اختبار / Create test files
اكتب_ملف("ملف1.txt"، "محتوى 1")
اكتب_ملف("ملف2.txt"، "محتوى 2")
اكتب_ملف("بيانات.dat"، "بيانات")
اكتب_ملف("وثيقة.doc"، "وثيقة")

# البحث عن ملفات .txt / Find .txt files
ملفات_txt = طابق_نمط("*.txt", ".")
اطبع("ملفات TXT:")
لكل ملف في ملفات_txt:
    اطبع("  -", ملف)

# البحث عن أي ملف يبدأ بـ "ملف" / Find files starting with "ملف"
ملفات = طابق_نمط("ملف*.*", ".")
اطبع("ملفات تبدأ بـ 'ملف':")
لكل ملف في ملفات:
    اطبع("  -", ملف)

# ============================================================================
# قراءة وكتابة بيانات ثنائية / Binary I/O
# ============================================================================

اطبع("\n=== بيانات ثنائية ===")

# كتابة بايتات / Write bytes
بايتات = [0x48، 0x65، 0x6C، 0x6C، 0x6F]  # "Hello" in ASCII
اكتب_بايتات("ثنائي.bin"، بايتات)

# قراءة بايتات / Read bytes
بايتات_مقروءة = اقرأ_بايتات("ثنائي.bin")
اطبع("البايتات المقروءة:", بايتات_مقروءة)

# ============================================================================
# سير عمل متقدم / Advanced Workflow
# ============================================================================

اطبع("\n=== سير عمل متقدم ===")

دالة معالج_ملفات(مجلد_مصدر، مجلد_هدف):
    """
    معالج ملفات متقدم يقوم بـ:
    1. قراءة جميع ملفات .txt من المصدر
    2. معالجة المحتوى
    3. حفظ النتائج في المجلد الهدف
    """
    
    # إنشاء مجلد الهدف إذا لم يكن موجوداً
    إذا لا هل_موجود(مجلد_هدف):
        أنشئ_مجلد(مجلد_هدف)
    
    # البحث عن ملفات .txt
    ملفات = طابق_نمط("*.txt"، مجلد_مصدر)
    
    لكل مسار_ملف في ملفات:
        # قراءة المحتوى
        محتوى = اقرأ_ملف(مسار_ملف)
        
        # معالجة المحتوى (إضافة تاريخ)
        محتوى_معالج = "=== تمت المعالجة ===\n" + محتوى
        
        # استخراج اسم الملف
        اسم = احصل_على_اسم_ملف(مسار_ملف)
        
        # حفظ في المجلد الهدف
        مسار_هدف = اجمع_مسار([مجلد_هدف، اسم])
        اكتب_ملف(مسار_هدف، محتوى_معالج)
        
        اطبع("✓ تمت معالجة:", اسم)

# تنفيذ المعالج / Execute processor
معالج_ملفات("بيانات"، "معالج")

# ============================================================================
# إحصائيات نهائية / Final Statistics
# ============================================================================

اطبع("\n=== إحصائيات نهائية ===")

دالة احسب_حجم_مجلد(مجلد):
    """حساب الحجم الإجمالي لجميع الملفات في المجلد"""
    حجم_إجمالي = 0
    ملفات = اسرد_مجلد_تكراري(مجلد)
    
    لكل ملف في ملفات:
        إذا هل_ملف(ملف):
            حجم_إجمالي = حجم_إجمالي + احصل_على_حجم_ملف(ملف)
    
    أرجع حجم_إجمالي

حجم_بيانات = احسب_حجم_مجلد("بيانات")
اطبع("حجم مجلد البيانات:", حجم_بيانات, "بايت")

حجم_معالج = احسب_حجم_مجلد("معالج")
اطبع("حجم مجلد المعالج:", حجم_معالج, "بايت")

# ============================================================================
# تنظيف (اختياري) / Cleanup (Optional)
# ============================================================================

اطبع("\n=== تنظيف ===")

# حذف ملف / Delete file
احذف_ملف("نسخة_منقولة.txt")
اطبع("✓ تم حذف الملف")

# حذف مجلد (تكراري) / Delete directory (recursive)
احذف_مجلد("بيانات"، صحيح)
احذف_مجلد("معالج"، صحيح)
اطبع("✓ تم حذف المجلدات")

اطبع("\n=== اكتمل المثال بنجاح! ===")
اطبع("الحمد لله رب العالمين")

