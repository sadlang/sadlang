اطبع("=== اختبار الدوال الرياضية ===\n")

// 1. اختبار الجذر التربيعي - sqrt test
متغير جذر١ = جذر(16)
متغير جذر٢ = sqrt(25)
اطبع("جذر(16) = " + جذر١)
اطبع("sqrt(25) = " + جذر٢)

// 2. اختبار الأس - power test
متغير أس١ = أس(2، 3)
متغير أس٢ = power(5، 2)
اطبع("أس(2، 3) = " + أس١)
اطبع("power(5، 2) = " + أس٢)

// 3. اختبار القيمة المطلقة - absolute test
متغير مطلق١ = مطلق(-15)
متغير مطلق٢ = abs(-42.7)
اطبع("مطلق(-15) = " + مطلق١)
اطبع("abs(-42.7) = " + مطلق٢)

// 4. اختبار الأكبر - max test
متغير أكبر١ = أكبر(10، 20)
متغير أكبر٢ = max(5، 3، 8، 12، 1)
اطبع("أكبر(10، 20) = " + أكبر١)
اطبع("max(5، 3، 8، 12، 1) = " + أكبر٢)

// 5. اختبار الأصغر - min test
متغير أصغر١ = أصغر(10، 20)
متغير أصغر٢ = min(5، 3، 8، 12، 1)
اطبع("أصغر(10، 20) = " + أصغر١)
اطبع("min(5، 3، 8، 12، 1) = " + أصغر٢)

// 6. اختبار التقريب - round test
متغير تقريب١ = تقريب(3.7)
متغير تقريب٢ = round(3.2)
اطبع("تقريب(3.7) = " + تقريب١)
اطبع("round(3.2) = " + تقريب٢)

// 7. اختبار الأرضية - floor test
متغير أرضية١ = أرضية(3.9)
متغير أرضية٢ = floor(-2.1)
اطبع("أرضية(3.9) = " + أرضية١)
اطبع("floor(-2.1) = " + أرضية٢)

// 8. اختبار السقف - ceil test
متغير سقف١ = سقف(3.1)
متغير سقف٢ = ceil(-2.9)
اطبع("سقف(3.1) = " + سقف١)
اطبع("ceil(-2.9) = " + سقف٢)

// 9. اختبار المربع - square test
متغير مربع١ = مربع(5)
متغير مربع٢ = square(12)
اطبع("مربع(5) = " + مربع١)
اطبع("square(12) = " + مربع٢)

// 10. اختبار الجيب - sine test
متغير جيب١ = جيب(0)
متغير جيب٢ = sin(1.5708)  // π/2 ≈ 1.5708
اطبع("جيب(0) = " + جيب١)
اطبع("sin(1.5708) ≈ " + جيب٢)

// 11. اختبار جيب التمام - cosine test
متغير جيب_تمام١ = جيب_تمام(0)
متغير جيب_تمام٢ = cos(3.14159)  // π
اطبع("جيب_تمام(0) = " + جيب_تمام١)
اطبع("cos(3.14159) ≈ " + جيب_تمام٢)

// 12. اختبار الظل - tangent test
متغير ظل١ = ظل(0)
متغير ظل٢ = tan(0.7854)  // π/4 ≈ 0.7854
اطبع("ظل(0) = " + ظل١)
اطبع("tan(0.7854) ≈ " + ظل٢)

// اختبار مركب - Combined test
اطبع("\n=== اختبار مركب ===")
متغير نتيجة = جذر(أس(3، 2) + أس(4، 2))
اطبع("جذر(أس(3، 2) + أس(4، 2)) = " + نتيجة + " (يجب أن تكون 5)")

متغير متوسط = (أكبر(1، 2، 3، 4، 5) + أصغر(1، 2، 3، 4، 5)) / 2
اطبع("(أكبر + أصغر) / 2 = " + متوسط + " (متوسط الحدود)")

اطبع("\n✅ اكتمل اختبار جميع الدوال الرياضية!")
