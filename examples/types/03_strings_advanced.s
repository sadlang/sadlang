# نصوص بسيطة / Simple strings
نص اسم = "أحمد"
نص مدينة = "الرياض"
نص بلد = "السعودية"

اطبع("=== نصوص بسيطة ===")
اطبع("الاسم:", اسم)
اطبع("المدينة:", مدينة)
اطبع("البلد:", بلد)

# دمج النصوص / String concatenation
نص معلومات_بسيطة = "الاسم: " + اسم
نص معلومات_كاملة = اسم + " من " + مدينة + "، " + بلد

اطبع("\n=== دمج النصوص ===")
اطبع(معلومات_بسيطة)
اطبع(معلومات_كاملة)

# نصوص مع رموز escape / Strings with escape sequences
نص مع_سطر_جديد = "السطر الأول\nالسطر الثاني\nالسطر الثالث"
نص مع_tab = "العمود1\tالعمود2\tالعمود3"
نص مع_علامات = "قال: \"مرحبا بكم\""

اطبع("\n=== رموز Escape ===")
اطبع(مع_سطر_جديد)
اطبع(مع_tab)
اطبع(مع_علامات)

# تكرار النصوص / String repetition
نص خط_فاصل = "=" * 30
نص نجوم = "* " * 10

اطبع("\n=== تكرار النصوص ===")
اطبع(خط_فاصل)
اطبع(نجوم)

# نصوص متعددة الأسطر / Multiline strings
نص قصيدة = "
الشمس تشرق في الصباح
والطيور تغني بفرح
والحياة تبدأ من جديد
"

اطبع("\n=== نص متعدد الأسطر ===")
اطبع(قصيدة)

# Unicode والرموز التعبيرية / Unicode and emojis
نص مع_emoji = "مرحباً 👋 أهلاً بك 😊"
نص رموز_متنوعة = "النجوم: ⭐⭐⭐ القلوب: ❤️💙💚"
نص رياضيات = "الجذر التربيعي √ باي π الدلتا Δ"

اطبع("\n=== Unicode والرموز ===")
اطبع(مع_emoji)
اطبع(رموز_متنوعة)
اطبع(رياضيات)

# عمليات على النصوص / String operations
رقم طول_النص = 10  # سيُحسب فعلياً بدالة
نص جزء = "مرحبا بالعالم"
منطقي يحتوي = صحيح  # "مرحبا" في جزء

اطبع("\n=== عمليات النصوص ===")
اطبع("النص:", جزء)
اطبع("يحتوي على 'مرحبا':", يحتوي)

# نصوص مع أرقام / Strings with numbers
رقم عمر = 25
رقم سنة = 2025
نص معلومات_رقمية = "العمر: " + "25" + " سنة"

اطبع("\n=== نصوص مع أرقام ===")
اطبع(معلومات_رقمية)

# مقارنة النصوص / String comparison
منطقي متساوية = "أحمد" == "أحمد"
منطقي مختلفة = "أحمد" != "محمد"
منطقي ترتيب = "أ" < "ب"

اطبع("\n=== مقارنة النصوص ===")
اطبع("'أحمد' == 'أحمد':", متساوية)
اطبع("'أحمد' != 'محمد':", مختلفة)
اطبع("'أ' < 'ب' (ترتيب أبجدي):", ترتيب)

# نصوص خاصة / Special strings
نص فارغ = ""
نص مسافات = "   "
نص مختلط = "Arabic العربية 123 !@#"

اطبع("\n=== نصوص خاصة ===")
اطبع("نص فارغ: '" + فارغ + "'")
اطبع("نص مسافات: '" + مسافات + "'")
اطبع("نص مختلط:", مختلط)

# نصوص طويلة / Long strings
نص رسالة_طويلة = "هذا مثال على نص طويل يحتوي على عدة كلمات ومعلومات مختلفة " +
                   "يمكن أن يمتد على عدة أسطر في الكود ولكنه سيكون سطراً واحداً " +
                   "عند التشغيل ما لم نستخدم رمز السطر الجديد \\n بشكل صريح"

اطبع("\n=== نص طويل ===")
اطبع(رسالة_طويلة)

