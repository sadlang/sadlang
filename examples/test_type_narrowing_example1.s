# Example 1: Null Check with Type Narrowing

دالة معالجة_نص(قيمة)
    إذا (قيمة != لاشيء)
        # هنا القيمة ليست فارغة - يمكن استخدامها بأمان
        # Value is not null - safe to use
        اطبع("النص: ")
        اطبع(قيمة)
        اطبع("\n")
        إرجاع قيمة
    وإلا
        # هنا القيمة فارغة
        # Value is null
        اطبع("القيمة فارغة\n")
        إرجاع "افتراضي"
    نهاية
