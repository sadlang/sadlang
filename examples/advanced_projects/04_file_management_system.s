صنف مجلد
    # خصائص المجلد
    نص اسم_المجلد ;
    نص المسار_الكامل ;
    نص تاريخ_الإنشاء ;
    نص تاريخ_آخر_تعديل ;
    
    # محتويات المجلد
    مصفوفة قائمة_الملفات ;
    مصفوفة قائمة_المجلدات_الفرعية ;
    رقم عدد_الملفات ;
    رقم عدد_المجلدات_الفرعية ;
    
    # إحصائيات
    رقم الحجم_الكلي ;
    منطق فارغ ;
    
    دالة مجلد( نص اسم ، نص مسار_أساسي )
        اسم_المجلد = اسم ;
        المسار_الكامل = مسار_أساسي + "/" + اسم ;
        تاريخ_الإنشاء = "2024-11-28 09:00" ;
        تاريخ_آخر_تعديل = تاريخ_الإنشاء ;
        
        قائمة_الملفات = [] ;
        قائمة_المجلدات_الفرعية = [] ;
        عدد_الملفات = 0 ;
        عدد_المجلدات_الفرعية = 0 ;
        الحجم_الكلي = 0 ;
        فارغ = صحيح ;
        
        اطبع("📁 تم إنشاء مجلد جديد:", المسار_الكامل) ;
    نهاية
    
    # إضافة ملف للمجلد
    دالة اضف_ملف( ملف ملف_جديد )
        قائمة_الملفات = أضف_عنصر(قائمة_الملفات, ملف_جديد) ;
        عدد_الملفات = عدد_الملفات + 1 ;
        الحجم_الكلي = الحجم_الكلي + ملف_جديد.احصل_على_الحجم() ;
        فارغ = خطأ ;
        تاريخ_آخر_تعديل = "2024-11-28 12:00" ;
        
        اطبع("📄 تم إضافة ملف للمجلد:", ملف_جديد.احصل_على_الاسم()) ;
        اطبع("   في المجلد:", اسم_المجلد) ;
    نهاية
    
    # إضافة مجلد فرعي
    دالة اضف_مجلد_فرعي( مجلد مجلد_فرعي )
        قائمة_المجلدات_الفرعية = أضف_عنصر(قائمة_المجلدات_الفرعية, مجلد_فرعي) ;
        عدد_المجلدات_الفرعية = عدد_المجلدات_الفرعية + 1 ;
        فارغ = خطأ ;
        تاريخ_آخر_تعديل = "2024-11-28 13:00" ;
        
        اطبع("📁 تم إضافة مجلد فرعي:", مجلد_فرعي.اسم_المجلد) ;
        اطبع("   في المجلد الأساسي:", اسم_المجلد) ;
    نهاية
    
    # عرض محتويات المجلد
    دالة اظهر_محتويات()
        اطبع("📂 محتويات المجلد:", اسم_المجلد) ;
        اطبع("════════════════════════════════════") ;
        
        إذا ( فارغ )
            اطبع("المجلد فارغ") ;
        وإلا
            إذا ( عدد_المجلدات_الفرعية > 0 )
                اطبع("📁 المجلدات الفرعية:") ;
                رقم مؤشر_مجلد = 0 ;
                بينما ( مؤشر_مجلد < عدد_المجلدات_الفرعية )
                    مجلد مجلد_فرعي = قائمة_المجلدات_الفرعية[مؤشر_مجلد] ;
                    اطبع("  ", (مؤشر_مجلد + 1), ".", مجلد_فرعي.اسم_المجلد, "/") ;
                    مؤشر_مجلد = مؤشر_مجلد + 1 ;
                نهاية
                اطبع("") ;
            نهاية
            
            إذا ( عدد_الملفات > 0 )
                اطبع("📄 الملفات:") ;
                رقم مؤشر_ملف = 0 ;
                بينما ( مؤشر_ملف < عدد_الملفات )
                    ملف ملف_حالي = قائمة_الملفات[مؤشر_ملف] ;
                    إذا ( !ملف_حالي.هل_مخفي() )
                        اطبع("  ", (مؤشر_ملف + 1), ".", ملف_حالي.احصل_على_الاسم(), 
                              "(", ملف_حالي.احصل_على_الحجم(), "KB)") ;
                    نهاية
                    مؤشر_ملف = مؤشر_ملف + 1 ;
                نهاية
            نهاية
        نهاية
        
        اطبع("") ;
        اطبع("إجمالي الملفات:", عدد_الملفات) ;
        اطبع("إجمالي المجلدات الفرعية:", عدد_المجلدات_الفرعية) ;
        اطبع("الحجم الكلي:", الحجم_الكلي, "KB") ;
        اطبع("════════════════════════════════════") ;
    نهاية
    
    # البحث عن ملف
    دالة ابحث_عن_ملف( نص اسم_الملف_المطلوب )
        رقم مؤشر = 0 ;
        بينما ( مؤشر < عدد_الملفات )
            ملف ملف_حالي = قائمة_الملفات[مؤشر] ;
            إذا ( بحث(ملف_حالي.احصل_على_الاسم(), اسم_الملف_المطلوب) >= 0 )
                اطبع("✅ تم العثور على الملف:", ملف_حالي.احصل_على_الاسم()) ;
                اطبع("   في المجلد:", اسم_المجلد) ;
                أرجع مؤشر ;
            نهاية
            مؤشر = مؤشر + 1 ;
        نهاية
        
        اطبع("❌ لم يتم العثور على الملف:", اسم_الملف_المطلوب) ;
        أرجع -1 ;
    نهاية
    
    # حذف ملف
    دالة احذف_ملف( نص اسم_الملف_للحذف )
        رقم فهرس = ابحث_عن_ملف(اسم_الملف_للحذف) ;
        إذا ( فهرس >= 0 )
            ملف ملف_محذوف = قائمة_الملفات[فهرس] ;
            الحجم_الكلي = الحجم_الكلي - ملف_محذوف.احصل_على_الحجم() ;
            قائمة_الملفات = احذف_عنصر(قائمة_الملفات, فهرس) ;
            عدد_الملفات = عدد_الملفات - 1 ;
            
            إذا ( عدد_الملفات == 0 && عدد_المجلدات_الفرعية == 0 )
                فارغ = صحيح ;
            نهاية
            
            اطبع("🗑️ تم حذف الملف:", اسم_الملف_للحذف) ;
            أرجع صحيح ;
        نهاية
        أرجع خطأ ;
    نهاية
    
    # إحصائيات المجلد
    دالة اعرض_إحصائيات()
        اطبع("📊 إحصائيات المجلد:", اسم_المجلد) ;
        اطبع("════════════════════════════════") ;
        اطبع("المسار الكامل:", المسار_الكامل) ;
        اطبع("تاريخ الإنشاء:", تاريخ_الإنشاء) ;
        اطبع("آخر تعديل:", تاريخ_آخر_تعديل) ;
        اطبع("عدد الملفات:", عدد_الملفات) ;
        اطبع("عدد المجلدات الفرعية:", عدد_المجلدات_الفرعية) ;
        اطبع("الحجم الكلي:", الحجم_الكلي, "KB") ;
        اطبع("المجلد فارغ:", إذا( فارغ , "نعم" , "لا" )) ;
        
        # تصنيف الملفات حسب النوع
        إذا ( عدد_الملفات > 0 )
            رقم عدد_النصوص = 0 ;
            رقم عدد_الصور = 0 ;
            رقم عدد_المستندات = 0 ;
            رقم عدد_أخرى = 0 ;
            
            رقم مؤشر = 0 ;
            بينما ( مؤشر < عدد_الملفات )
                ملف ملف_حالي = قائمة_الملفات[مؤشر] ;
                نص نوع = ملف_حالي.احصل_على_النوع() ;
                
                إذا ( نوع == "نص" )
                    عدد_النصوص = عدد_النصوص + 1 ;
                وإلا إذا ( نوع == "صورة" )
                    عدد_الصور = عدد_الصور + 1 ;
                وإلا إذا ( نوع == "مستند" )
                    عدد_المستندات = عدد_المستندات + 1 ;
                وإلا
                    عدد_أخرى = عدد_أخرى + 1 ;
                نهاية
                
                مؤشر = مؤشر + 1 ;
            نهاية
            
            اطبع("\nتوزيع الملفات حسب النوع:") ;
            اطبع("ملفات نصية:", عدد_النصوص) ;
            اطبع("ملفات الصور:", عدد_الصور) ;
            اطبع("المستندات:", عدد_المستندات) ;
            اطبع("ملفات أخرى:", عدد_أخرى) ;
        نهاية
        
        اطبع("════════════════════════════════") ;
    نهاية
نهاية

