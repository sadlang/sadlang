        تاريخ_آخر_تعديل = "2024-11-28 " + نص(10 + عدد_مرات_الفتح) + ":00" ;
        اطبع("📂 تم فتح الملف:", اسم_الملف + "." + امتداد_الملف) ;
        اطبع("   عدد مرات الفتح:", عدد_مرات_الفتح) ;
    نهاية
    
    # تعديل حجم الملف
    دالة غير_الحجم( رقم حجم_جديد )
        إذا ( !للقراءة_فقط )
            حجم_الملف = حجم_جديد ;
            تاريخ_آخر_تعديل = "2024-11-28 " + نص(15 + عدد_مرات_الفتح) + ":00" ;
            اطبع("💾 تم تعديل حجم الملف:", اسم_الملف + "." + امتداد_الملف) ;
            اطبع("   الحجم الجديد:", حجم_جديد, "KB") ;
        وإلا
            اطبع("❌ لا يمكن تعديل الملف - للقراءة فقط") ;
        نهاية
    نهاية
    
    # تغيير خصائص الملف
    دالة اجعل_للقراءة_فقط()
        للقراءة_فقط = صحيح ;
        اطبع("🔒 تم تعديل الملف ليكون للقراءة فقط:", اسم_الملف + "." + امتداد_الملف) ;
    نهاية
    
    دالة اجعل_قابل_للتعديل()
