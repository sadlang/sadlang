صنف نظام_إدارة_الملفات
    # الجذر الرئيسي
    مجلد المجلد_الجذر ;
    
    # إحصائيات النظام
    رقم إجمالي_الملفات ;
    رقم إجمالي_المجلدات ;
    رقم إجمالي_الحجم ;
    
    دالة نظام_إدارة_الملفات()
        المجلد_الجذر = جديد مجلد("Root", "/") ;
        إجمالي_الملفات = 0 ;
        إجمالي_المجلدات = 1 ;  # المجلد الجذر
        إجمالي_الحجم = 0 ;
        
        اطبع("💾 تم تهيئة نظام إدارة الملفات") ;
        اطبع("🌳 المجلد الجذر: /Root") ;
    نهاية
    
    # إنشاء ملف جديد
    دالة انشئ_ملف( نص اسم ، نص امتداد ، رقم حجم ، نص مسار ، نص نوع ، مجلد مجلد_الهدف )
        ملف ملف_جديد = جديد ملف(اسم, امتداد, حجم, مسار, نوع) ;
        مجلد_الهدف.اضف_ملف(ملف_جديد) ;
        
        إجمالي_الملفات = إجمالي_الملفات + 1 ;
        إجمالي_الحجم = إجمالي_الحجم + حجم ;
        
        اطبع("✅ تم إنشاء الملف بنجاح في النظام") ;
        أرجع ملف_جديد ;
    نهاية
    
    # إنشاء مجلد جديد
    دالة انشئ_مجلد( نص اسم ، نص مسار_أساسي ، مجلد مجلد_أساسي )
        مجلد مجلد_جديد = جديد مجلد(اسم, مسار_أساسي) ;
        مجلد_أساسي.اضف_مجلد_فرعي(مجلد_جديد) ;
        
        إجمالي_المجلدات = إجمالي_المجلدات + 1 ;
        
        اطبع("✅ تم إنشاء المجلد بنجاح في النظام") ;
        أرجع مجلد_جديد ;
    نهاية
    
    # نسخ ملف
    دالة انسخ_ملف( ملف ملف_أصلي ، مجلد مجلد_الهدف )
        نص اسم_النسخة = ملف_أصلي.اسم_الملف + "_copy" ;
        
        ملف نسخة_الملف = جديد ملف(اسم_النسخة, ملف_أصلي.امتداد_الملف, 
                                       ملف_أصلي.احصل_على_الحجم(), 
                                       مجلد_الهدف.المسار_الكامل, 
                                       ملف_أصلي.احصل_على_النوع()) ;
        
        مجلد_الهدف.اضف_ملف(نسخة_الملف) ;
        إجمالي_الملفات = إجمالي_الملفات + 1 ;
        إجمالي_الحجم = إجمالي_الحجم + ملف_أصلي.احصل_على_الحجم() ;
        
        اطبع("📋 تم نسخ الملف بنجاح") ;
        أرجع نسخة_الملف ;
    نهاية
    
    # عرض بنية النظام
    دالة اظهر_بنية_النظام()
        اطبع("🌳 بنية نظام الملفات") ;
        اطبع("═══════════════════════════") ;
        المجلد_الجذر.اظهر_محتويات() ;
    نهاية
    
    # إحصائيات شاملة للنظام
    دالة اعرض_إحصائيات_النظام()
        اطبع("📊 إحصائيات نظام إدارة الملفات") ;
        اطبع("═══════════════════════════════════════") ;
        اطبع("إجمالي الملفات:", إجمالي_الملفات) ;
        اطبع("إجمالي المجلدات:", إجمالي_المجلدات) ;
        اطبع("إجمالي الحجم:", إجمالي_الحجم, "KB") ;
        
        # تحويل الحجم لوحدات أكبر
        إذا ( إجمالي_الحجم >= 1024 )
            رقم الحجم_بالميجا = إجمالي_الحجم / 1024 ;
            اطبع("إجمالي الحجم:", الحجم_بالميجا, "MB") ;
        نهاية
        
        # الذاكرة المستخدمة تقديرياً
        رقم الذاكرة_المقدرة = (إجمالي_الملفات * 50) + (إجمالي_المجلدات * 100) ;  # بايت
        اطبع("الذاكرة المستخدمة (تقديري):", الذاكرة_المقدرة, "bytes") ;
        
        اطبع("═══════════════════════════════════════") ;
    نهاية
نهاية

