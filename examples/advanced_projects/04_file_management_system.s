    منطق مخفي ;
    رقم عدد_مرات_الفتح ;
    
    دالة ملف( نص اسم ، نص امتداد ، رقم حجم ، نص مسار ، نص نوع )
        اسم_الملف = اسم ;
        امتداد_الملف = امتداد ;
