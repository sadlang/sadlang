        تاريخ_آخر_تعديل = تاريخ_الإنشاء ;
        المسار_الكامل = مسار + "/" + اسم + "." + امتداد ;
        نوع_الملف = نوع ;
        
        للقراءة_فقط = خطأ ;
        مخفي = خطأ ;
        عدد_مرات_الفتح = 0 ;
        
        اطبع("📄 تم إنشاء ملف جديد:", المسار_الكامل) ;
    نهاية
    
    # فتح الملف
    دالة افتح_الملف()
