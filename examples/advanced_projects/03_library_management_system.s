صنف عضو_مكتبة
    # المعلومات الشخصية
    خاص نص رقم_العضوية ;
    نص الاسم_الكامل ;
    رقم العمر ;
    نص رقم_الهاتف ;
    نص البريد_الإلكتروني ;
    نص نوع_العضوية ;  # طالب، موظف، زائر
    
    # سجل الاستعارة
    خاص مصفوفة الكتب_المستعارة ;
    خاص رقم عدد_الكتب_المستعارة_حالياً ;
    خاص رقم إجمالي_الكتب_المستعارة ;
    خاص رقم الحد_الأقصى_للاستعارة ;
    
    دالة عضو_مكتبة( نص رقم ، نص اسم ، رقم عمر ، نص هاتف ، نص إيميل ، نص نوع )
        رقم_العضوية = رقم ;
        الاسم_الكامل = اسم ;
        العمر = عمر ;
        رقم_الهاتف = هاتف ;
        البريد_الإلكتروني = إيميل ;
        نوع_العضوية = نوع ;
        
        الكتب_المستعارة = [] ;
        عدد_الكتب_المستعارة_حالياً = 0 ;
        إجمالي_الكتب_المستعارة = 0 ;
        
        # تحديد الحد الأقصى حسب نوع العضوية
        إذا ( نوع == "طالب" )
            الحد_الأقصى_للاستعارة = 5 ;
        وإلا إذا ( نوع == "موظف" )
            الحد_الأقصى_للاستعارة = 10 ;
        وإلا
            الحد_الأقصى_للاستعارة = 3 ;  # زائر
        نهاية
        
        اطبع("👤 تم تسجيل عضو جديد:", الاسم_الكامل, "- رقم العضوية:", رقم_العضوية) ;
    نهاية
    
    # استعارة كتاب
    دالة استعر_كتاب( نص رقم_كتاب )
        إذا ( عدد_الكتب_المستعارة_حالياً < الحد_الأقصى_للاستعارة )
            الكتب_المستعارة = أضف_عنصر(الكتب_المستعارة, رقم_كتاب) ;
            عدد_الكتب_المستعارة_حالياً = عدد_الكتب_المستعارة_حالياً + 1 ;
            إجمالي_الكتب_المستعارة = إجمالي_الكتب_المستعارة + 1 ;
            أرجع صحيح ;
        وإلا
            اطبع("❌ تجاوز الحد الأقصى للاستعارة (", الحد_الأقصى_للاستعارة, "كتب)") ;
            أرجع خطأ ;
        نهاية
    نهاية
    
    # إرجاع كتاب
    دالة أرجع_كتاب( نص رقم_كتاب )
        رقم فهرس = 0 ;
        منطق وُجد = خطأ ;
        
        بينما ( فهرس < طول(الكتب_المستعارة) )
            إذا ( الكتب_المستعارة[فهرس] == رقم_كتاب )
                الكتب_المستعارة = احذف_عنصر(الكتب_المستعارة, فهرس) ;
                عدد_الكتب_المستعارة_حالياً = عدد_الكتب_المستعارة_حالياً - 1 ;
                وُجد = صحيح ;
                أرجع صحيح ;
            نهاية
            فهرس = فهرس + 1 ;
        نهاية
        
        إذا ( !وُجد )
            اطبع("❌ الكتاب غير مستعار من قبل هذا العضو") ;
            أرجع خطأ ;
        نهاية
    نهاية
    
    # عرض معلومات العضو
    دالة اظهر_معلومات_العضو()
        اطبع("═════════════════ معلومات العضو ═════════════════") ;
        اطبع("رقم العضوية:", رقم_العضوية) ;
        اطبع("الاسم الكامل:", الاسم_الكامل) ;
        اطبع("العمر:", العمر) ;
        اطبع("رقم الهاتف:", رقم_الهاتف) ;
        اطبع("البريد الإلكتروني:", البريد_الإلكتروني) ;
        اطبع("نوع العضوية:", نوع_العضوية) ;
        اطبع("الحد الأقصى للاستعارة:", الحد_الأقصى_للاستعارة, "كتب") ;
        اطبع("الكتب المستعارة حالياً:", عدد_الكتب_المستعارة_حالياً) ;
        اطبع("إجمالي الكتب المستعارة:", إجمالي_الكتب_المستعارة) ;
        
        إذا ( عدد_الكتب_المستعارة_حالياً > 0 )
            اطبع("أرقام الكتب المستعارة:", الكتب_المستعارة) ;
        نهاية
        
        اطبع("══════════════════════════════════════════════════") ;
    نهاية
    
    # دوال الحصول على المعلومات
    دالة احصل_على_الرقم()
        أرجع رقم_العضوية ;
    نهاية
    
    دالة احصل_على_عدد_المستعار()
        أرجع عدد_الكتب_المستعارة_حالياً ;
    نهاية
    
    دالة يمكن_الاستعارة()
        أرجع عدد_الكتب_المستعارة_حالياً < الحد_الأقصى_للاستعارة ;
    نهاية
نهاية

# ======================
# صنف نظام إدارة المكتبة
# Library Management System Class
# ======================

صنف نظام_المكتبة
    # مجموعات البيانات الرئيسية
    خاص مصفوفة مجموعة_الكتب ;
    خاص مصفوفة مجموعة_الأعضاء ;
    
    # إحصائيات عامة
    خاص رقم إجمالي_الكتب ;
    خاص رقم الكتب_المتوفرة ;
    خاص رقم الكتب_المستعارة ;
    خاص رقم إجمالي_الأعضاء ;
    
    دالة نظام_المكتبة()
        مجموعة_الكتب = [] ;
        مجموعة_الأعضاء = [] ;
        إجمالي_الكتب = 0 ;
        الكتب_المتوفرة = 0 ;
        الكتب_المستعارة = 0 ;
        إجمالي_الأعضاء = 0 ;
        
        اطبع("🏛️ تم تهيئة نظام إدارة المكتبة بنجاح") ;
    نهاية
    
    # إضافة كتاب جديد
    دالة اضف_كتاب( كتاب كتاب_جديد )
        مجموعة_الكتب = أضف_عنصر(مجموعة_الكتب, كتاب_جديد) ;
        إجمالي_الكتب = إجمالي_الكتب + 1 ;
        الكتب_المتوفرة = الكتب_المتوفرة + 1 ;
        اطبع("📚 تم إضافة الكتاب للمجموعة. إجمالي الكتب:", إجمالي_الكتب) ;
    نهاية
    
    # تسجيل عضو جديد
    دالة اضف_عضو( عضو_مكتبة عضو_جديد )
        مجموعة_الأعضاء = أضف_عنصر(مجموعة_الأعضاء, عضو_جديد) ;
        إجمالي_الأعضاء = إجمالي_الأعضاء + 1 ;
        اطبع("👥 تم تسجيل العضو. إجمالي الأعضاء:", إجمالي_الأعضاء) ;
    نهاية
    
    # البحث عن كتاب بالرقم
    دالة ابحث_عن_كتاب( نص رقم_كتاب )
        رقم مؤشر = 0 ;
        بينما ( مؤشر < طول(مجموعة_الكتب) )
            إذا ( مجموعة_الكتب[مؤشر].احصل_على_الرقم() == رقم_كتاب )
                أرجع مؤشر ;
            نهاية
            مؤشر = مؤشر + 1 ;
        نهاية
        أرجع -1 ;
    نهاية
    
    # البحث عن عضو بالرقم
    دالة ابحث_عن_عضو( نص رقم_عضو )
        رقم مؤشر = 0 ;
        بينما ( مؤشر < طول(مجموعة_الأعضاء) )
            إذا ( مجموعة_الأعضاء[مؤشر].احصل_على_الرقم() == رقم_عضو )
                أرجع مؤشر ;
            نهاية
            مؤشر = مؤشر + 1 ;
        نهاية
        أرجع -1 ;
    نهاية
    
    # عملية استعارة كتاب
    دالة استعر_كتاب( نص رقم_كتاب ، نص رقم_عضو ، رقم مدة_استعارة )
        رقم فهرس_كتاب = ابحث_عن_كتاب(رقم_كتاب) ;
        رقم فهرس_عضو = ابحث_عن_عضو(رقم_عضو) ;
        
        إذا ( فهرس_كتاب < 0 )
            اطبع("❌ الكتاب غير موجود في النظام") ;
            أرجع خطأ ;
        نهاية
        
        إذا ( فهرس_عضو < 0 )
            اطبع("❌ العضو غير مسجل في النظام") ;
            أرجع خطأ ;
        نهاية
        
        كتاب الكتاب_المطلوب = مجموعة_الكتب[فهرس_كتاب] ;
        عضو_مكتبة العضو_المطلوب = مجموعة_الأعضاء[فهرس_عضو] ;
        
        إذا ( !العضو_المطلوب.يمكن_الاستعارة() )
            اطبع("❌ العضو تجاوز الحد الأقصى للاستعارة") ;
            أرجع خطأ ;
        نهاية
        
        منطق تم_الاستعارة = الكتاب_المطلوب.استعر(رقم_عضو, مدة_استعارة) ;
        إذا ( تم_الاستعارة )
            العضو_المطلوب.استعر_كتاب(رقم_كتاب) ;
            الكتب_المتوفرة = الكتب_المتوفرة - 1 ;
            الكتب_المستعارة = الكتب_المستعارة + 1 ;
            أرجع صحيح ;
        نهاية
        
        أرجع خطأ ;
    نهاية
    
    # عملية إرجاع كتاب
    دالة أرجع_كتاب( نص رقم_كتاب ، نص رقم_عضو )
        رقم فهرس_كتاب = ابحث_عن_كتاب(رقم_كتاب) ;
        رقم فهرس_عضو = ابحث_عن_عضو(رقم_عضو) ;
        
        إذا ( فهرس_كتاب >= 0 && فهرس_عضو >= 0 )
            كتاب الكتاب_المطلوب = مجموعة_الكتب[فهرس_كتاب] ;
            عضو_مكتبة العضو_المطلوب = مجموعة_الأعضاء[فهرس_عضو] ;
            
            منطق تم_الإرجاع = الكتاب_المطلوب.أرجع_الكتاب() ;
            إذا ( تم_الإرجاع )
                العضو_المطلوب.أرجع_كتاب(رقم_كتاب) ;
                الكتب_المتوفرة = الكتب_المتوفرة + 1 ;
                الكتب_المستعارة = الكتب_المستعارة - 1 ;
                أرجع صحيح ;
            نهاية
        وإلا
            اطبع("❌ لم يتم العثور على الكتاب أو العضو") ;
        نهاية
        
        أرجع خطأ ;
    نهاية
    
    # البحث بالعنوان أو المؤلف
    دالة ابحث_بالنص( نص نص_البحث )
        اطبع("🔍 نتائج البحث عن:", نص_البحث) ;
        اطبع("═══════════════════════════════") ;
        
        رقم عدد_النتائج = 0 ;
        رقم مؤشر = 0 ;
        
        بينما ( مؤشر < طول(مجموعة_الكتب) )
            كتاب كتاب_حالي = مجموعة_الكتب[مؤشر] ;
            
            إذا ( بحث(كتاب_حالي.العنوان, نص_البحث) >= 0 || 
                  بحث(كتاب_حالي.المؤلف, نص_البحث) >= 0 )
                عدد_النتائج = عدد_النتائج + 1 ;
                اطبع(عدد_النتائج, ".", كتاب_حالي.العنوان, "- بواسطة:", كتاب_حالي.المؤلف) ;
                اطبع("   رقم الكتاب:", كتاب_حالي.احصل_على_الرقم()) ;
                اطبع("   الحالة:", إذا( كتاب_حالي.هل_متوفر() , "متوفر 🟢" , "مُستعار 🔴" )) ;
                اطبع("   ──────────────────────────") ;
            نهاية
            
            مؤشر = مؤشر + 1 ;
        نهاية
        
        إذا ( عدد_النتائج == 0 )
            اطبع("لا توجد نتائج للبحث") ;
        وإلا
            اطبع("إجمالي النتائج:", عدد_النتائج) ;
        نهاية
        
        اطبع("═══════════════════════════════") ;
    نهاية
    
    # عرض الكتب حسب الفئة
    دالة اعرض_كتب_الفئة( نص الفئة )
        اطبع("📚 كتب فئة:", الفئة) ;
        اطبع("═══════════════════════════════") ;
        
        رقم عدد_الكتب_في_الفئة = 0 ;
        رقم مؤشر = 0 ;
        
        بينما ( مؤشر < طول(مجموعة_الكتب) )
            كتاب كتاب_حالي = مجموعة_الكتب[مؤشر] ;
            
            إذا ( كتاب_حالي.احصل_على_الفئة() == الفئة )
                عدد_الكتب_في_الفئة = عدد_الكتب_في_الفئة + 1 ;
                اطبع(عدد_الكتب_في_الفئة, ".", كتاب_حالي.العنوان, "- بواسطة:", كتاب_حالي.المؤلف) ;
                اطبع("   الحالة:", إذا( كتاب_حالي.هل_متوفر() , "متوفر 🟢" , "مُستعار 🔴" )) ;
                اطبع("   عدد الاستعارات:", كتاب_حالي.احصل_على_عدد_الاستعارات()) ;
            نهاية
            
            مؤشر = مؤشر + 1 ;
        نهاية
        
        إذا ( عدد_الكتب_في_الفئة == 0 )
            اطبع("لا توجد كتب في هذه الفئة") ;
        نهاية
        
        اطبع("═══════════════════════════════") ;
    نهاية
    
