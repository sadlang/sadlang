صنف مستوى_الصعوبة
    نص اسم_المستوى ;
    رقم الحد_الأدنى ;
    رقم الحد_الأقصى ;
    رقم عدد_المحاولات_المسموحة ;
    رقم النقاط_الأساسية ;
    نص الوصف ;
    نص الرمز ;
    
    دالة مستوى_الصعوبة( نص اسم ، رقم أدنى ، رقم أقصى ، رقم محاولات ، رقم نقاط ، نص وصف ، نص رمز )
        اسم_المستوى = اسم ;
        الحد_الأدنى = أدنى ;
        الحد_الأقصى = أقصى ;
        عدد_المحاولات_المسموحة = محاولات ;
        النقاط_الأساسية = نقاط ;
        الوصف = وصف ;
        الرمز = رمز ;
    نهاية
    
    دالة اعرض_معلومات_المستوى()
        اطبع("══════════════════════════════════") ;
        اطبع(الرمز, "مستوى:", اسم_المستوى) ;
        اطبع("══════════════════════════════════") ;
        اطبع("الوصف:", الوصف) ;
        اطبع("نطاق الأرقام:", الحد_الأدنى, "-", الحد_الأقصى) ;
        اطبع("المحاولات المسموحة:", عدد_المحاولات_المسموحة) ;
        اطبع("النقاط الأساسية:", النقاط_الأساسية) ;
        اطبع("══════════════════════════════════") ;
    نهاية
    
    # حساب النقاط بناء على المحاولات
    دالة احسب_النقاط( رقم محاولات_مستخدمة )
        إذا ( محاولات_مستخدمة <= عدد_المحاولات_المسموحة )
            # مكافأة للفوز السريع
            رقم نقاط_مكافأة = النقاط_الأساسية * (عدد_المحاولات_المسموحة - محاولات_مستخدمة) ;
            أرجع النقاط_الأساسية + نقاط_مكافأة ;
        وإلا
            أرجع 0 ;  # لا نقاط إذا تجاوز المحاولات المسموحة
        نهاية
    نهاية
    
    # توليد رقم عشوائي في النطاق
    دالة ولد_رقم_عشوائي()
        رقم نطاق = الحد_الأقصى - الحد_الأدنى + 1 ;
        رقم رقم_عشوائي = (إجمالي_الألعاب * 13 + 7) % نطاق ;  # محاكاة الرقم العشوائي
        أرجع الحد_الأدنى + رقم_عشوائي ;
    نهاية
نهاية

