صنف إدارة_نظام_الطلاب
    خاص مصفوفة قائمة_الطلاب ;
    خاص رقم عدد_الطلاب_الكلي ;
    
    دالة إدارة_نظام_الطلاب()
        قائمة_الطلاب = [] ;
        عدد_الطلاب_الكلي = 0 ;
        اطبع("🏫 تم تهيئة نظام إدارة الطلاب بنجاح") ;
    نهاية
    
    # إضافة طالب جديد
    دالة اضف_طالب( طالب طالب_جديد )
        قائمة_الطلاب = أضف_عنصر(قائمة_الطلاب, طالب_جديد) ;
        عدد_الطلاب_الكلي = عدد_الطلاب_الكلي + 1 ;
        اطبع("📝 تم إضافة الطالب للنظام. إجمالي الطلاب:", عدد_الطلاب_الكلي) ;
    نهاية
    
    # البحث عن طالب بالرقم
    دالة ابحث_عن_طالب( نص رقم_الطالب )
        رقم مؤشر = 0 ;
        بينما ( مؤشر < طول(قائمة_الطلاب) )
            إذا ( قائمة_الطلاب[مؤشر].احصل_على_الرقم() == رقم_الطالب )
                أرجع مؤشر ;
            نهاية
            مؤشر = مؤشر + 1 ;
        نهاية
        أرجع -1 ;  # لم يوجد
    نهاية
    
    # عرض جميع الطلاب
    دالة اعرض_جميع_الطلاب()
        إذا ( عدد_الطلاب_الكلي == 0 )
            اطبع("📋 لا يوجد طلاب مسجلون في النظام") ;
        وإلا
            اطبع("📋 قائمة جميع الطلاب (", عدد_الطلاب_الكلي, "طالب):") ;
            اطبع("══════════════════════════════════════════════════") ;
            
            رقم مؤشر = 0 ;
            بينما ( مؤشر < طول(قائمة_الطلاب) )
                طالب الطالب_الحالي = قائمة_الطلاب[مؤشر] ;
                اطبع((مؤشر + 1), ".", الطالب_الحالي.الاسم_الكامل, 
                      "- رقم:", الطالب_الحالي.احصل_على_الرقم(),
                      "- معدل:", الطالب_الحالي.احصل_على_المعدل(),
                      "- مواد:", الطالب_الحالي.احصل_على_عدد_المواد()) ;
                مؤشر = مؤشر + 1 ;
            نهاية
            اطبع("══════════════════════════════════════════════════") ;
        نهاية
    نهاية
    
    # إحصائيات النظام
    دالة اعرض_إحصائيات_النظام()
        إذا ( عدد_الطلاب_الكلي == 0 )
            اطبع("📊 لا توجد بيانات لعرض الإحصائيات") ;
            أرجع ;
        نهاية
        
        اطبع("📊 إحصائيات النظام التفصيلية") ;
        اطبع("═════════════════════════════════") ;
        
        # إحصائيات عامة
        اطبع("إجمالي الطلاب المسجلين:", عدد_الطلاب_الكلي) ;
        
        # حساب المعدل العام
        رقم مجموع_المعدلات = 0 ;
        رقم عدد_الطلاب_بمعدل = 0 ;
        
        # إحصائيات التقديرات
        رقم عدد_ممتاز = 0 ;
        رقم عدد_جيد_جدا = 0 ;
        رقم عدد_جيد = 0 ;
        رقم عدد_مقبول = 0 ;
        رقم عدد_راسب = 0 ;
        
        # إحصائيات التخصصات
        رقم عدد_هندسة = 0 ;
        رقم عدد_طب = 0 ;
        رقم عدد_علوم = 0 ;
        رقم عدد_أدب = 0 ;
        رقم عدد_إدارة = 0 ;
        رقم عدد_تخصصات_أخرى = 0 ;
        
        رقم أعلى_معدل = 0 ;
        رقم أقل_معدل = 100 ;
        نص اسم_أعلى_معدل = "" ;
        نص اسم_أقل_معدل = "" ;
        
        رقم مؤشر = 0 ;
        بينما ( مؤشر < طول(قائمة_الطلاب) )
            طالب الطالب_الحالي = قائمة_الطلاب[مؤشر] ;
            
            # حساب المعدل العام
            إذا ( الطالب_الحالي.احصل_على_عدد_المواد() > 0 )
                مجموع_المعدلات = مجموع_المعدلات + الطالب_الحالي.احصل_على_المعدل() ;
                عدد_الطلاب_بمعدل = عدد_الطلاب_بمعدل + 1 ;
                
                # أعلى وأقل معدل
                إذا ( الطالب_الحالي.احصل_على_المعدل() > أعلى_معدل )
                    أعلى_معدل = الطالب_الحالي.احصل_على_المعدل() ;
                    اسم_أعلى_معدل = الطالب_الحالي.الاسم_الكامل ;
                نهاية
                
                إذا ( الطالب_الحالي.احصل_على_المعدل() < أقل_معدل )
                    أقل_معدل = الطالب_الحالي.احصل_على_المعدل() ;
                    اسم_أقل_معدل = الطالب_الحالي.الاسم_الكامل ;
                نهاية
            نهاية
            
            # تصنيف التقديرات
            رقم معدل = الطالب_الحالي.احصل_على_المعدل() ;
            إذا ( معدل >= 90 )
                عدد_ممتاز = عدد_ممتاز + 1 ;
            وإلا إذا ( معدل >= 80 )
                عدد_جيد_جدا = عدد_جيد_جدا + 1 ;
            وإلا إذا ( معدل >= 70 )
                عدد_جيد = عدد_جيد + 1 ;
            وإلا إذا ( معدل >= 60 )
                عدد_مقبول = عدد_مقبول + 1 ;
            وإلا
                عدد_راسب = عدد_راسب + 1 ;
            نهاية
            
            # تصنيف التخصصات
            نص تخصص = الطالب_الحالي.التخصص ;
            إذا ( بحث(تخصص, "هندسة") >= 0 )
                عدد_هندسة = عدد_هندسة + 1 ;
            وإلا إذا ( بحث(تخصص, "طب") >= 0 )
                عدد_طب = عدد_طب + 1 ;
            وإلا إذا ( بحث(تخصص, "علوم") >= 0 )
                عدد_علوم = عدد_علوم + 1 ;
            وإلا إذا ( بحث(تخصص, "أدب") >= 0 )
                عدد_أدب = عدد_أدب + 1 ;
            وإلا إذا ( بحث(تخصص, "إدارة") >= 0 )
                عدد_إدارة = عدد_إدارة + 1 ;
            وإلا
                عدد_تخصصات_أخرى = عدد_تخصصات_أخرى + 1 ;
            نهاية
            
            مؤشر = مؤشر + 1 ;
        نهاية
        
        # عرض الإحصائيات
        إذا ( عدد_الطلاب_بمعدل > 0 )
            رقم المعدل_العام = مجموع_المعدلات / عدد_الطلاب_بمعدل ;
            اطبع("المعدل العام لجميع الطلاب:", المعدل_العام) ;
        نهاية
        
        اطبع("أعلى معدل:", أعلى_معدل, "-", اسم_أعلى_معدل) ;
        اطبع("أقل معدل:", أقل_معدل, "-", اسم_أقل_معدل) ;
        
        اطبع("\nتوزيع التقديرات:") ;
        اطبع("ممتاز (90-100):", عدد_ممتاز, "طلاب") ;
        اطبع("جيد جداً (80-89):", عدد_جيد_جدا, "طلاب") ;
        اطبع("جيد (70-79):", عدد_جيد, "طلاب") ;
        اطبع("مقبول (60-69):", عدد_مقبول, "طلاب") ;
        اطبع("راسب (أقل من 60):", عدد_راسب, "طلاب") ;
        
        اطبع("\nتوزيع التخصصات:") ;
        اطبع("الهندسة:", عدد_هندسة, "طلاب") ;
        اطبع("الطب:", عدد_طب, "طلاب") ;
        اطبع("العلوم:", عدد_علوم, "طلاب") ;
        اطبع("الأدب:", عدد_أدب, "طلاب") ;
        اطبع("إدارة الأعمال:", عدد_إدارة, "طلاب") ;
        اطبع("تخصصات أخرى:", عدد_تخصصات_أخرى, "طلاب") ;
        
        اطبع("═════════════════════════════════") ;
    نهاية
    
    # البحث عن الطلاب المتفوقين
    دالة اعرض_المتفوقين( رقم حد_المعدل )
        اطبع("🏆 الطلاب المتفوقين (معدل >=", حد_المعدل, "):") ;
        اطبع("═══════════════════════════════════════") ;
        
        رقم عدد_المتفوقين = 0 ;
        رقم مؤشر = 0 ;
        
        بينما ( مؤشر < طول(قائمة_الطلاب) )
            طالب الطالب_الحالي = قائمة_الطلاب[مؤشر] ;
            
            إذا ( الطالب_الحالي.احصل_على_المعدل() >= حد_المعدل )
                عدد_المتفوقين = عدد_المتفوقين + 1 ;
                اطبع(عدد_المتفوقين, ".", الطالب_الحالي.الاسم_الكامل,
                      "- معدل:", الطالب_الحالي.احصل_على_المعدل(),
                      "- تخصص:", الطالب_الحالي.التخصص) ;
            نهاية
            
            مؤشر = مؤشر + 1 ;
        نهاية
        
        إذا ( عدد_المتفوقين == 0 )
            اطبع("لا يوجد طلاب متفوقين بالمعدل المطلوب") ;
        وإلا
            اطبع("إجمالي المتفوقين:", عدد_المتفوقين, "طالب") ;
        نهاية
        
        اطبع("═══════════════════════════════════════") ;
    نهاية
نهاية

