صنف طالب
    # الخصائص الأساسية
    خاص نص رقم_الطالب ;
    نص الاسم_الكامل ;
    رقم العمر ;
    نص التخصص ;
    نص مستوى_الدراسة ;  # بكالوريوس، ماجستير، دكتوراه
    
    # الدرجات والأداء
    خاص مصفوفة درجات_المواد ;
    خاص مصفوفة أسماء_المواد ;
    خاص رقم المعدل_التراكمي ;
    خاص رقم عدد_الساعات_المكتملة ;
    خاص منطق حالة_تخرج ;
    
    # البانى
    دالة طالب( نص رقم ، نص اسم ، رقم عمر ، نص تخصص ، نص مستوى )
        رقم_الطالب = رقم ;
        الاسم_الكامل = اسم ;
        العمر = عمر ;
        التخصص = تخصص ;
        مستوى_الدراسة = مستوى ;
        
        درجات_المواد = [] ;
        أسماء_المواد = [] ;
        المعدل_التراكمي = 0.0 ;
        عدد_الساعات_المكتملة = 0 ;
        حالة_تخرج = خطأ ;
        
        اطبع("✅ تم تسجيل طالب جديد:", الاسم_الكامل, "- رقم الطالب:", رقم_الطالب) ;
    نهاية
    
    # إضافة درجة مادة
    دالة اضف_درجة( نص اسم_المادة ، رقم الدرجة ، رقم ساعات_المادة )
        إذا ( الدرجة >= 0 && الدرجة <= 100 )
            أسماء_المواد = أضف_عنصر(أسماء_المواد, اسم_المادة) ;
            درجات_المواد = أضف_عنصر(درجات_المواد, الدرجة) ;
            عدد_الساعات_المكتملة = عدد_الساعات_المكتملة + ساعات_المادة ;
            
            احسب_المعدل_التراكمي() ;
            اطبع("📚 تم إضافة درجة مادة:", اسم_المادة, "- الدرجة:", الدرجة) ;
        وإلا
            اطبع("❌ خطأ: الدرجة يجب أن تكون بين 0 و 100") ;
        نهاية
    نهاية
    
    # حساب المعدل التراكمي
    دالة احسب_المعدل_التراكمي()
        إذا ( طول(درجات_المواد) > 0 )
            رقم مجموع_الدرجات = 0 ;
            رقم مؤشر = 0 ;
            
            بينما ( مؤشر < طول(درجات_المواد) )
                مجموع_الدرجات = مجموع_الدرجات + درجات_المواد[مؤشر] ;
                مؤشر = مؤشر + 1 ;
            نهاية
            
            المعدل_التراكمي = مجموع_الدرجات / طول(درجات_المواد) ;
        نهاية
    نهاية
    
    # تحديث حالة التخرج
    دالة فحص_التخرج( رقم الحد_الأدنى_للساعات )
        إذا ( عدد_الساعات_المكتملة >= الحد_الأدنى_للساعات && المعدل_التراكمي >= 60 )
            حالة_تخرج = صحيح ;
        وإلا
            حالة_تخرج = خطأ ;
        نهاية
        أرجع حالة_تخرج ;
    نهاية
    
    # تقييم الأداء الأكاديمي
    دالة احصل_على_التقدير()
        إذا ( المعدل_التراكمي >= 95 )
            أرجع "ممتاز مع مرتبة الشرف الأولى" ;
        وإلا إذا ( المعدل_التراكمي >= 90 )
            أرجع "ممتاز" ;
        وإلا إذا ( المعدل_التراكمي >= 85 )
            أرجع "جيد جداً مع مرتبة الشرف" ;
        وإلا إذا ( المعدل_التراكمي >= 80 )
            أرجع "جيد جداً" ;
        وإلا إذا ( المعدل_التراكمي >= 75 )
            أرجع "جيد مع مرتبة الشرف" ;
        وإلا إذا ( المعدل_التراكمي >= 70 )
            أرجع "جيد" ;
        وإلا إذا ( المعدل_التراكمي >= 65 )
            أرجع "مقبول مع مرتبة الشرف" ;
        وإلا إذا ( المعدل_التراكمي >= 60 )
            أرجع "مقبول" ;
        وإلا
            أرجع "راسب" ;
        نهاية
    نهاية
    
    # طباعة كشف الدرجات
    دالة اطبع_كشف_الدرجات()
        اطبع("========================= كشف الدرجات =========================") ;
        اطبع("الطالب:", الاسم_الكامل, "- رقم الطالب:", رقم_الطالب) ;
        اطبع("التخصص:", التخصص, "- المستوى:", مستوى_الدراسة) ;
        اطبع("─────────────────────────────────────────────────────────────") ;
        
        إذا ( طول(أسماء_المواد) > 0 )
            اطبع("المواد والدرجات:") ;
            رقم مؤشر = 0 ;
            بينما ( مؤشر < طول(أسماء_المواد) )
                نص تقدير_المادة = تقدير_الدرجة(درجات_المواد[مؤشر]) ;
                اطبع((مؤشر + 1), ".", أسماء_المواد[مؤشر], ":", درجات_المواد[مؤشر], "(", تقدير_المادة, ")") ;
                مؤشر = مؤشر + 1 ;
            نهاية
            
            اطبع("─────────────────────────────────────────────────────────────") ;
            اطبع("عدد المواد:", طول(أسماء_المواد)) ;
            اطبع("المعدل التراكمي:", المعدل_التراكمي) ;
            اطبع("التقدير العام:", احصل_على_التقدير()) ;
            اطبع("الساعات المكتملة:", عدد_الساعات_المكتملة) ;
            اطبع("حالة التخرج:", إذا( حالة_تخرج , "مؤهل للتخرج" , "غير مؤهل للتخرج" )) ;
        وإلا
            اطبع("لا توجد درجات مسجلة") ;
        نهاية
        
        اطبع("===============================================================") ;
    نهاية
    
    # دالة مساعدة لتقدير الدرجة الفردية
    دالة تقدير_الدرجة( رقم درجة )
        إذا ( درجة >= 95 )
            أرجع "A+" ;
        وإلا إذا ( درجة >= 90 )
            أرجع "A" ;
        وإلا إذا ( درجة >= 85 )
            أرجع "B+" ;
        وإلا إذا ( درجة >= 80 )
            أرجع "B" ;
        وإلا إذا ( درجة >= 75 )
            أرجع "C+" ;
        وإلا إذا ( درجة >= 70 )
            أرجع "C" ;
        وإلا إذا ( درجة >= 65 )
            أرجع "D+" ;
        وإلا إذا ( درجة >= 60 )
            أرجع "D" ;
        وإلا
            أرجع "F" ;
        نهاية
    نهاية
    
    # الحصول على معلومات أساسية
    دالة احصل_على_الرقم()
        أرجع رقم_الطالب ;
    نهاية
    
    دالة احصل_على_المعدل()
        أرجع المعدل_التراكمي ;
    نهاية
    
    دالة احصل_على_عدد_المواد()
        أرجع طول(أسماء_المواد) ;
    نهاية
نهاية

