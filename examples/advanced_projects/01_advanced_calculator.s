صنف آلة_حاسبة
    خاص مصفوفة تاريخ_العمليات ;
    خاص رقم عدد_العمليات ;
    
    دالة آلة_حاسبة()
        تاريخ_العمليات = [] ;
        عدد_العمليات = 0 ;
        اطبع("تم تهيئة الآلة الحاسبة بنجاح!") ;
    نهاية
    
    # العمليات الأساسية
    دالة جمع( رقم أ , رقم ب )
        رقم النتيجة = أ + ب ;
        اضف_لتاريخ(أ, "+", ب, النتيجة) ;
        أرجع النتيجة ;
    نهاية
    
    دالة طرح( رقم أ , رقم ب )
        رقم النتيجة = أ - ب ;
        اضف_لتاريخ(أ, "-", ب, النتيجة) ;
        أرجع النتيجة ;
    نهاية
    
    دالة ضرب( رقم أ , رقم ب )
        رقم النتيجة = أ * ب ;
        اضف_لتاريخ(أ, "*", ب, النتيجة) ;
        أرجع النتيجة ;
    نهاية
    
    دالة قسمة( رقم أ , رقم ب )
        إذا ( ب != 0 )
            رقم النتيجة = أ / ب ;
            اضف_لتاريخ(أ, "/", ب, النتيجة) ;
            أرجع النتيجة ;
        وإلا
            اطبع("❌ خطأ: لا يمكن القسمة على صفر!") ;
            أرجع 0 ;
        نهاية
    نهاية
    
    دالة باقي_القسمة( رقم أ , رقم ب )
        إذا ( ب != 0 )
            رقم النتيجة = أ % ب ;
            اضف_لتاريخ(أ, "%", ب, النتيجة) ;
            أرجع النتيجة ;
        وإلا
            اطبع("❌ خطأ: لا يمكن حساب باقي القسمة على صفر!") ;
            أرجع 0 ;
        نهاية
    نهاية
    
    # العمليات المتقدمة
    دالة أس( رقم الأساس , رقم الأس )
        رقم النتيجة = قوة(الأساس, الأس) ;
        اضف_لتاريخ(الأساس, "^", الأس, النتيجة) ;
        أرجع النتيجة ;
    نهاية
    
    دالة جذر_تربيعي( رقم العدد )
        إذا ( العدد >= 0 )
            رقم النتيجة = جذر(العدد) ;
            اضف_لتاريخ_واحد("√", العدد, النتيجة) ;
            أرجع النتيجة ;
        وإلا
            اطبع("❌ خطأ: لا يمكن حساب الجذر التربيعي لرقم سالب!") ;
            أرجع 0 ;
        نهاية
    نهاية
    
    دالة قيمة_مطلقة( رقم العدد )
        رقم النتيجة = مطلق(العدد) ;
        اضف_لتاريخ_واحد("|", العدد, النتيجة) ;
        أرجع النتيجة ;
    نهاية
    
    دالة مضروب( رقم العدد )
        إذا ( العدد >= 0 && العدد <= 20 )
            رقم النتيجة = حساب_مضروب(العدد) ;
            اضف_لتاريخ_واحد("!", العدد, النتيجة) ;
            أرجع النتيجة ;
        وإلا
            اطبع("❌ خطأ: المضروب محدود من 0 إلى 20!") ;
            أرجع 0 ;
        نهاية
    نهاية
    
    # دالة مساعدة لحساب المضروب
    دالة حساب_مضروب( رقم ن )
        إذا ( ن <= 1 )
            أرجع 1 ;
        وإلا
            أرجع ن * حساب_مضروب(ن - 1) ;
        نهاية
    نهاية
    
    # إدارة التاريخ
    دالة اضف_لتاريخ( رقم أ , نص عملية , رقم ب , رقم نتيجة )
        نص العملية_النصية = نص(أ) + " " + عملية + " " + نص(ب) + " = " + نص(نتيجة) ;
        تاريخ_العمليات = أضف_عنصر(تاريخ_العمليات, العملية_النصية) ;
        عدد_العمليات = عدد_العمليات + 1 ;
    نهاية
    
    دالة اضف_لتاريخ_واحد( نص رمز , رقم عدد , رقم نتيجة )
        نص العملية_النصية ;
        إذا ( رمز == "√" )
            العملية_النصية = "√" + نص(عدد) + " = " + نص(نتيجة) ;
        وإلا إذا ( رمز == "|" )
            العملية_النصية = "|" + نص(عدد) + "| = " + نص(نتيجة) ;
        وإلا إذا ( رمز == "!" )
            العملية_النصية = نص(عدد) + "! = " + نص(نتيجة) ;
        نهاية
        
        تاريخ_العمليات = أضف_عنصر(تاريخ_العمليات, العملية_النصية) ;
        عدد_العمليات = عدد_العمليات + 1 ;
    نهاية
    
    دالة اظهر_التاريخ()
        إذا ( عدد_العمليات == 0 )
            اطبع("📋 لا توجد عمليات محفوظة") ;
        وإلا
            اطبع("📋 تاريخ العمليات (", عدد_العمليات, "عملية):") ;
            اطبع("========================") ;
            رقم مؤشر = 0 ;
            بينما ( مؤشر < طول(تاريخ_العمليات) )
                اطبع((مؤشر + 1), ".", تاريخ_العمليات[مؤشر]) ;
                مؤشر = مؤشر + 1 ;
            نهاية
            اطبع("========================") ;
        نهاية
    نهاية
    
    دالة امسح_التاريخ()
        تاريخ_العمليات = [] ;
        عدد_العمليات = 0 ;
        اطبع("🗑️ تم مسح التاريخ بنجاح") ;
    نهاية
    
    # إحصائيات الاستخدام
    دالة اظهر_الإحصائيات()
        اطبع("📊 إحصائيات الاستخدام:") ;
        اطبع("عدد العمليات الكلي:", عدد_العمليات) ;
        
        إذا ( عدد_العمليات > 0 )
            # حساب متوسط تقديري للاستخدام
            اطبع("آخر عملية:", تاريخ_العمليات[طول(تاريخ_العمليات) - 1]) ;
        نهاية
    نهاية
نهاية

