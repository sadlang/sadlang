    """صنف لإدارة العمليات على الملفات"""
    
    دالة أنشئ_ملف_سجل(اسم_الملف، المحتوى):
        """إنشاء ملف سجل مع الوقت والتاريخ"""
        محاولة:
            التاريخ = filesystem.احصل_على_التاريخ()
            الرأس = "=" * 50 + "\n"
            الرأس = الرأس + "سجل النظام - " + التاريخ + "\n"
            الرأس = الرأس + "=" * 50 + "\n\n"
            
            filesystem.اكتب_نص(اسم_الملف، الرأس + المحتوى)
            إرجاع صحيح
        خطأ:
            إرجاع خطأ
    
    دالة احصل_على_حجم_المجلد(مسار_المجلد):
        """حساب حجم جميع الملفات في المجلد"""
        محاولة:
            الحجم_الكلي = 0
            المحتويات = filesystem.اعرض_المجلد(مسار_المجلد)
            
            لكل عنصر في المحتويات:
                المسار_الكامل = filesystem.دمج_مسار(مسار_المجلد، عنصر)
                إذا filesystem.ملف؟(المسار_الكامل):
                    المعلومات = filesystem.معلومات(المسار_الكامل)
                    الحجم_الكلي = الحجم_الكلي + المعلومات["حجم"]
            
            إرجاع الحجم_الكلي
        خطأ:
            إرجاع 0
    
    دالة نسخ_احتياطي(المصدر، الوجهة):
        """إنشاء نسخة احتياطية من مجلد"""
        محاولة:
            filesystem.أنشئ_مجلد(الوجهة)
            الملفات = filesystem.اعرض_المجلد(المصدر)
            
            لكل ملف في الملفات:
                مسار_المصدر = filesystem.دمج_مسار(المصدر، ملف)
                مسار_الوجهة = filesystem.دمج_مسار(الوجهة، ملف)
                
                إذا filesystem.ملف؟(مسار_المصدر):
                    filesystem.انسخ(مسار_المصدر، مسار_الوجهة)
            
            إرجاع صحيح
        خطأ:
            إرجاع خطأ

