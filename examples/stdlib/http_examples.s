# 8. فحص رموز الحالة HTTP / Check HTTP Status Codes
# ═══════════════════════════════════════════════════════════════════
اطبع("\n8️⃣  فحص رموز الحالة HTTP:")
اطبع("-" * 50)

قائمة_الروابط = [
    "https://httpbin.org/status/200",  # OK
    "https://httpbin.org/status/404",  # Not Found
    "https://httpbin.org/status/500"   # Internal Server Error
]

لكل رابط في قائمة_الروابط:
    محاولة:
        استجابة = http.احصل(رابط)
        حالة = استجابة.حالة
        
        إذا حالة == 200:
            اطبع("✅ " + رابط + " → حالة: " + نص(حالة) + " (OK)")
        وإلا إذا حالة == 404:
            اطبع("⚠️  " + رابط + " → حالة: " + نص(حالة) + " (Not Found)")
        وإلا إذا حالة >= 500:
            اطبع("❌ " + رابط + " → حالة: " + نص(حالة) + " (Server Error)")
        وإلا:
            اطبع("ℹ️  " + رابط + " → حالة: " + نص(حالة))
    خطأ كـ خطأ:
        اطبع("❌ خطأ في فحص الرابط: " + رابط)

