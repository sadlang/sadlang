// بسم الله الرحمن الرحيم
// مثال خادم HTTP بسيط
// Simple HTTP Server Example

استيراد "http"

// إنشاء خادم HTTP
دالة رئيسية() {
    // خادم على المنفذ 8080
    خادم = خادم_http_جديد(8080)
    
    // مسار الصفحة الرئيسية
    خادم_http_get(خادم, "/", دالة(طلب, رد) {
        رد_html(رد, "<h1>مرحباً بك في خادم HTTP!</h1>")
    })
    
    // مسار API
    خادم_http_get(خادم, "/api/data", دالة(طلب, رد) {
        بيانات = {
            "اسم": "أحمد",
            "عمر": 25,
            "مدينة": "القاهرة"
        }
        رد_json(رد, بيانات)
    })
    
    // مسار POST
    خادم_http_post(خادم, "/api/users", دالة(طلب, رد) {
        بيانات_المستخدم = طلب_body_json(طلب)
        
        // معالجة البيانات
        جواب = {
            "رسالة": "تم إنشاء المستخدم بنجاح",
            "بيانات": بيانات_المستخدم
        }
        
        رد_json(رد, جواب, 201)
    })
    
    // تشغيل الخادم
    اطبع("🌐 الخادم يعمل على http://localhost:8080")
    خادم_http_listen(خادم)
}
