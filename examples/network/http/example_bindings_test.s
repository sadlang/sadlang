دالة رئيسية() {
    اطبع("🌐 اختبار مكتبة HTTP")
    اطبع("==================")
    اطبع("")
    
    # اختبار 1: إنشاء عميل HTTP
    اطبع("✓ اختبار 1: إنشاء عميل HTTP")
    عميل = عميل_http_جديد()
    إذا (عميل == باطل) {
        اطبع("✗ فشل إنشاء العميل!")
        عودة 1
    }
    اطبع("  → نجح إنشاء العميل")
    اطبع("")
    
    # اختبار 2: تعيين إعدادات العميل
    اطبع("✓ اختبار 2: تعيين إعدادات العميل")
    عميل_http_set_timeout(عميل, 5000)
    عميل_http_set_header(عميل, "User-Agent", "Sad-HTTP/1.0")
    اطبع("  → نجح تعيين المهلة الزمنية والرؤوس")
    اطبع("")
    
    # اختبار 3: طلب GET (سيفشل لأن الخادم غير موجود، لكن يجب ألا يتعطل)
    اطبع("✓ اختبار 3: طلب GET")
    رد = عميل_http_get(عميل, "http://localhost:9999/test")
    إذا (رد == باطل) {
        اطبع("  → لم يتم الاتصال (متوقع - لا يوجد خادم)")
        خطأ = عميل_http_last_error(عميل)
        اطبع("  → الخطأ: " + خطأ)
    } وإلا {
        حالة = رد_http_status(رد)
        اطبع("  → الحالة: " + حالة)
        
        إذا (رد_http_is_success(رد)) {
            جسم = رد_http_body(رد)
            اطبع("  → الجسم: " + جسم)
        }
    }
    اطبع("")
    
    # اختبار 4: الدالة المختصرة
    اطبع("✓ اختبار 4: الدالة المختصرة http_get")
    رد2 = http_get("http://localhost:9999/api")
    إذا (رد2 == باطل) {
        اطبع("  → لم يتم الاتصال (متوقع - لا يوجد خادم)")
    }
    اطبع("")
    
    # اختبار 5: الثوابت
    اطبع("✓ اختبار 5: ثوابت HTTP")
    اطبع("  → HTTP_OK = " + HTTP_OK)
    اطبع("  → HTTP_NOT_FOUND = " + HTTP_NOT_FOUND)
    اطبع("  → HTTP_INTERNAL_ERROR = " + HTTP_INTERNAL_ERROR)
    اطبع("")
    
    # اختبار 6: إنشاء خادم (لن نشغله)
    اطبع("✓ اختبار 6: إنشاء خادم HTTP")
    خادم = خادم_http_جديد(8080)
    إذا (خادم == باطل) {
        اطبع("✗ فشل إنشاء الخادم!")
        عودة 1
    }
    اطبع("  → نجح إنشاء الخادم على المنفذ 8080")
    
    # تسجيل مسارات (حتى لو لم نشغل الخادم)
    خادم_http_get(خادم, "/", باطل)
    خادم_http_post(خادم, "/api/data", باطل)
    اطبع("  → نجح تسجيل المسارات")
    اطبع("")
    
    اطبع("✓ جميع الاختبارات نجحت!")
    اطبع("🎉 مكتبة HTTP تعمل بشكل صحيح")
    
    عودة 0
}
