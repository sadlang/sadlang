// بسم الله الرحمن الرحيم
// مثال عميل HTTP بسيط
// Simple HTTP Client Example

استيراد "http"

دالة رئيسية() {
    // إنشاء عميل HTTP
    عميل = عميل_http_جديد()
    
    // ═══════════════════════════════════
    // طلب GET بسيط
    // ═══════════════════════════════════
    اطبع("📡 إرسال طلب GET...")
    رد = عميل_http_get(عميل, "http://httpbin.org/get")
    
    إذا رد_ok(رد) {
        اطبع("✅ نجح الطلب!")
        اطبع("الحالة: " + رد_status(رد))
        اطبع("الجسم: " + رد_body(رد))
    } وإلا {
        اطبع("❌ فشل الطلب: " + رد_error(رد))
    }
    
    // ═══════════════════════════════════
    // طلب POST مع JSON
    // ═══════════════════════════════════
    اطبع("\n📡 إرسال طلب POST...")
    بيانات = {
        "اسم": "أحمد",
        "بريد": "ahmed@example.com"
    }
    
    رد = عميل_http_post(عميل, "http://httpbin.org/post", json_encode(بيانات))
    
    إذا رد_ok(رد) {
        اطبع("✅ نجح الطلب!")
        محتوى = json_decode(رد_body(رد))
        اطبع("البيانات المرسلة: " + محتوى["data"])
    }
    
    // ═══════════════════════════════════
    // طلب مع Headers مخصصة
    // ═══════════════════════════════════
    اطبع("\n📡 طلب مع Headers...")
    عميل_http_set_header(عميل, "User-Agent", "Sad/1.0")
    عميل_http_set_header(عميل, "Accept", "application/json")
    
    رد = عميل_http_get(عميل, "http://httpbin.org/headers")
    
    إذا رد_ok(رد) {
        اطبع("✅ تم إرسال Headers بنجاح!")
        اطبع(رد_body(رد))
    }
    
    // ═══════════════════════════════════
    // Authentication
    // ═══════════════════════════════════
    اطبع("\n📡 طلب مع Authentication...")
    عميل_http_set_basic_auth(عميل, "user", "pass")
    
    رد = عميل_http_get(عميل, "http://httpbin.org/basic-auth/user/pass")
    
    إذا رد_ok(رد) {
        اطبع("✅ تم التحقق بنجاح!")
    } وإلا {
        اطبع("❌ فشل التحقق")
    }
    
    اطبع("\n✨ تم الانتهاء من جميع الطلبات!")
}
