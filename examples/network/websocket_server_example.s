/**
 * @example مثال خادم WebSocket بسيط
 * 
 * هذا المثال يوضح كيفية إنشاء خادم WebSocket
 * وإدارة الاتصالات والبث.
 */

استورد شبكة.websocket

دالة main() {
    اطبع("=== مثال خادم WebSocket ===")
    اطبع("")
    
    // إنشاء خادم جديد
    متغير خادم = websocket.خادم_جديد()
    
    // عداد الاتصالات
    متغير عدد_المستخدمين = 0
    
    // تعيين دوال الاستجابة
    خادم.عند_اتصال((عميل) => {
        عدد_المستخدمين++
        اطبع("→ مستخدم جديد انضم: #" + عميل.المعرف())
        اطبع("  العنوان: " + عميل.العنوان() + ":" + عميل.المنفذ())
        اطبع("  المستخدمون الحاليون: " + عدد_المستخدمين)
        
        // إرسال رسالة ترحيب
        عميل.ارسل("مرحباً بك! أنت المستخدم رقم " + عميل.المعرف())
        
        // إعلام الآخرين
        خادم.بث_ما_عدا("انضم مستخدم جديد #" + عميل.المعرف(), عميل.المعرف())
    })
    
    خادم.عند_رسالة((عميل, رسالة) => {
        اطبع("← رسالة من #" + عميل.المعرف() + ": " + رسالة.كنص())
        
        // التحقق من الأوامر الخاصة
        متغير نص = رسالة.كنص()
        
        اذا (نص.يبدأ_بـ("/اسم ")) {
            // تغيير الاسم
            متغير اسم_جديد = نص.استبدل("/اسم ", "")
            خادم.بث("#" + عميل.المعرف() + " غيّر اسمه إلى: " + اسم_جديد)
            
        } واذا (نص == "/عدد") {
            // عرض عدد المتصلين
            عميل.ارسل("عدد المتصلين: " + خادم.عدد_الاتصالات())
            
        } واذا (نص.يبدأ_بـ("/انضم ")) {
            // الانضمام لغرفة
            متغير غرفة = نص.استبدل("/انضم ", "")
            عميل.انضم(غرفة)
            عميل.ارسل("✓ انضممت لغرفة: " + غرفة)
            خادم.بث_لغرفة(غرفة, "انضم مستخدم جديد للغرفة: #" + عميل.المعرف())
            
        } واذا (نص.يبدأ_بـ("/غادر ")) {
            // مغادرة غرفة
            متغير غرفة = نص.استبدل("/غادر ", "")
            عميل.غادر(غرفة)
            عميل.ارسل("✗ غادرت غرفة: " + غرفة)
            
        } واذا (نص == "/غرف") {
            // عرض الغرف
            متغير غرف = عميل.الغرف()
            عميل.ارسل("غرفك: " + غرف.اتصل(", "))
            
        } والا {
            // بث الرسالة للجميع
            خادم.بث("#" + عميل.المعرف() + ": " + نص)
        }
    })
    
    خادم.عند_قطع((عميل, رمز, سبب) => {
        عدد_المستخدمين--
        اطبع("← غادر المستخدم #" + عميل.المعرف())
        اطبع("  المستخدمون المتبقون: " + عدد_المستخدمين)
        
        // إعلام الآخرين
        خادم.بث("غادر المستخدم #" + عميل.المعرف())
    })
    
    خادم.عند_خطأ((عميل, خطأ) => {
        اطبع("✗ خطأ مع المستخدم #" + عميل.المعرف() + ": " + خطأ)
    })
    
    // تكوين الخادم
    خادم.عين_اقصى_اتصالات(100)
    خادم.عين_فترة_نبض(30000)  // نبض كل 30 ثانية
    
    // بدء الخادم
    اطبع("جاري بدء الخادم على المنفذ 8080...")
    
    اذا (خادم.ابدأ(8080)) {
        اطبع("✓ الخادم يعمل على ws://localhost:8080")
        اطبع("")
        اطبع("الأوامر المتاحة للعملاء:")
        اطبع("  /اسم <الاسم> - تغيير الاسم")
        اطبع("  /عدد - عرض عدد المتصلين")
        اطبع("  /انضم <غرفة> - الانضمام لغرفة")
        اطبع("  /غادر <غرفة> - مغادرة غرفة")
        اطبع("  /غرف - عرض غرفك")
        اطبع("")
        اطبع("اضغط Ctrl+C للإيقاف...")
        
        // الانتظار (في التطبيق الحقيقي سيكون هناك حلقة أحداث)
        بينما (خادم.يعمل()) {
            انتظر(1000)
        }
        
    } والا {
        اطبع("✗ فشل بدء الخادم!")
        اطبع("  تأكد من أن المنفذ 8080 غير مستخدم")
    }
    
    اطبع("")
    اطبع("=== انتهى الخادم ===")
}
