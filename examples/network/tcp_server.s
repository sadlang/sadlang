# Example: Simple TCP Server (Echo Server)

استورد شبكة من "stdlib/network/socket"

دالة main() 
    اطبع("🚀 بدء خادم TCP Echo...")
    اطبع("=" * 50)
    
    # إنشاء مقبس الخادم
    متغير خادم = شبكة.مقبس_tcp()
    
    # تعيين إعادة استخدام العنوان
    خادم.عين_اعادة_استخدام_عنوان(صحيح)
    
    # ربط المقبس بالمنفذ 8080
    متغير منفذ = 8080
    حاول 
        خادم.اربط(منفذ)
        اطبع("✅ تم ربط الخادم بالمنفذ: " + منفذ)
     اصطاد (خطأ) 
        اطبع("❌ خطأ: " + خطأ)
        ارجع 1
    نهاية
    
    # الاستماع للاتصالات (عدد الانتظار: 10)
    خادم.استمع(10)
    اطبع("👂 الخادم يستمع للاتصالات...")
    اطبع("📡 يمكنك الاتصال باستخدام: telnet 127.0.0.1 " + منفذ)
    اطبع("=" نكرر 50)
    
    متغير عدد_العملاء = 0
    
    # حلقة قبول الاتصالات
    بينما (صحيح) 
        حاول 
            اطبع("\n⏳ في انتظار اتصال جديد...")
            
            # قبول عميل جديد
            متغير عميل = خادم.اقبل()
            عدد_العملاء = عدد_العملاء + 1
            
            متغير عنوان_عميل = عميل.احصل_على_عنوان_الطرف_الآخر()
            اطبع("✨ عميل جديد #" + عدد_العملاء + " من " + عنوان_عميل.الى_نص())
            
            # إرسال رسالة ترحيب
            متغير ترحيب = "مرحباً بك في خادم Echo! (العميل #" + عدد_العملاء + ")\n"
            عميل.ارسل_الكل(ترحيب)
            
            # حلقة التعامل مع العميل
            بينما (صحيح) 
                # استقبال بيانات من العميل
                متغير بيانات = عميل.استقبل(1024)
                
                # اذا لم نستقبل شيء، العميل أغلق الاتصال
                اذا (طول(بيانات) == 0) 
                    اطبع("👋 العميل #" + عدد_العملاء + " أغلق الاتصال")
                    اكسر
                نهاية
                
                # طباعة ما استقبلناه
                اطبع("📨 استقبل من العميل #" + عدد_العملاء + ": " + نظف(بيانات))
                
                # إرجاع نفس البيانات (Echo)
                متغير رد = "Echo: " + بيانات
                عميل.ارسل_الكل(رد)
                اطبع("📤 تم إرسال الرد")
                
                # اذا كانت الرسالة "quit" أو "exit"، أغلق الاتصال
                اذا (نظف(بيانات) == "quit" او نظف(بيانات) == "exit") 
                    اطبع("🚪 العميل طلب الإغلاق")
                    عميل.ارسل_الكل("وداعاً! شكراً لاستخدامك خادم Echo.\n")
                    اكسر
                نهاية
            نهاية
            
            # إغلاق اتصال العميل
            عميل.اغلق()
            اطبع("✅ تم إغلاق اتصال العميل #" + عدد_العملاء)
            
        نهاية اصطاد (خطأ) 
            اطبع("⚠️  خطأ في التعامل مع العميل: " + خطأ)
            متغير معلومات_خطأ = شبكة.احصل_على_خطأ()
            اطبع("   الخطأ بالعربية: " + معلومات_خطأ.عربي)
        نهاية
    نهاية
    
    # إغلاق الخادم (لن نصل هنا في هذا المثال)
    خادم.اغلق()
    اطبع("\n🛑 تم إغلاق الخادم")
    
    ارجع 0
نهاية

# دالة مساعدة لتنظيف النص من الأسطر الجديدة
دالة نظف(نص: نص) -> نص 
    ارجع استبدل(استبدل(نص، "\n"، "")، "\r"، "")
نهاية

# تشغيل البرنامج
main()
