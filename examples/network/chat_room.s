/**
 * @example تطبيق غرفة دردشة كامل
 * 
 * هذا المثال يوضح تطبيق دردشة متكامل باستخدام WebSocket
 * مع دعم الغرف والرسائل الخاصة.
 */

استورد شبكة.websocket

// ============================================================================
// هيكل بيانات المستخدم
// ============================================================================

صنف مستخدم {
    متغير المعرف: رقم
    متغير الاسم: نص
    متغير الاتصال: websocket.اتصال
    
    دالة انشئ(معرف: رقم, اسم: نص, اتصال: websocket.اتصال) {
        المعرف = معرف
        الاسم = اسم
        الاتصال = اتصال
    }
}

// ============================================================================
// مدير الدردشة
// ============================================================================

صنف مدير_الدردشة {
    خاص:
        متغير _خادم: websocket.خادم
        متغير _مستخدمون: قاموس<رقم, مستخدم>
        متغير _اسماء: قاموس<نص, رقم>
    
    عام:
        دالة انشئ() {
            _خادم = websocket.خادم_جديد()
            _مستخدمون = {}
            _اسماء = {}
            _هيئ_احداث()
        }
        
        دالة ابدأ(منفذ: رقم) -> منطقي {
            ارجع _خادم.ابدأ(منفذ)
        }
        
        دالة اوقف() {
            _خادم.اوقف()
        }
    
    خاص:
        دالة _هيئ_احداث() {
            _خادم.عند_اتصال((اتصال) => _عند_اتصال(اتصال))
            _خادم.عند_رسالة((اتصال, رسالة) => _عند_رسالة(اتصال, رسالة))
            _خادم.عند_قطع((اتصال, رمز, سبب) => _عند_قطع(اتصال))
        }
        
        دالة _عند_اتصال(اتصال: websocket.اتصال) {
            // إنشاء اسم افتراضي
            متغير اسم_افتراضي = "ضيف_" + اتصال.المعرف()
            
            // إنشاء مستخدم جديد
            متغير مستخدم_جديد = مستخدم(اتصال.المعرف(), اسم_افتراضي, اتصال)
            _مستخدمون[اتصال.المعرف()] = مستخدم_جديد
            _اسماء[اسم_افتراضي] = اتصال.المعرف()
            
            // إرسال رسالة ترحيب
            _ارسل_نظام(اتصال, "مرحباً بك في غرفة الدردشة!")
            _ارسل_نظام(اتصال, "اسمك الحالي: " + اسم_افتراضي)
            _ارسل_نظام(اتصال, "اكتب /مساعدة لعرض الأوامر")
            
            // إعلام الآخرين
            _بث_نظام(اسم_افتراضي + " انضم للدردشة", اتصال.المعرف())
        }
        
        دالة _عند_رسالة(اتصال: websocket.اتصال, رسالة: websocket.رسالة) {
            متغير نص = رسالة.كنص().تقليم()
            متغير مستخدم = _مستخدمون[اتصال.المعرف()]
            
            اذا (نص.يبدأ_بـ("/")) {
                _معالجة_امر(مستخدم, نص)
            } والا {
                _بث_رسالة(مستخدم, نص)
            }
        }
        
        دالة _عند_قطع(اتصال: websocket.اتصال) {
            متغير مستخدم = _مستخدمون[اتصال.المعرف()]
            اذا (مستخدم != فارغ) {
                _بث_نظام(مستخدم.الاسم + " غادر الدردشة")
                _اسماء.احذف(مستخدم.الاسم)
                _مستخدمون.احذف(اتصال.المعرف())
            }
        }
        
        دالة _معالجة_امر(مستخدم: مستخدم, امر: نص) {
            متغير اجزاء = امر.قسم(" ")
            متغير الامر = اجزاء[0].حروف_صغيرة()
            
            تطابق (الامر) {
                حالة "/مساعدة":
                    _عرض_مساعدة(مستخدم)
                
                حالة "/اسم":
                    اذا (اجزاء.الطول() > 1) {
                        _تغيير_اسم(مستخدم, اجزاء[1])
                    } والا {
                        _ارسل_خطأ(مستخدم, "استخدام: /اسم <الاسم الجديد>")
                    }
                
                حالة "/خاص":
                    اذا (اجزاء.الطول() > 2) {
                        متغير هدف = اجزاء[1]
                        متغير رسالة = اجزاء.من(2).اتصل(" ")
                        _رسالة_خاصة(مستخدم, هدف, رسالة)
                    } والا {
                        _ارسل_خطأ(مستخدم, "استخدام: /خاص <اسم> <رسالة>")
                    }
                
                حالة "/قائمة":
                    _عرض_قائمة(مستخدم)
                
                حالة "/انضم":
                    اذا (اجزاء.الطول() > 1) {
                        _انضم_غرفة(مستخدم, اجزاء[1])
                    } والا {
                        _ارسل_خطأ(مستخدم, "استخدام: /انضم <اسم الغرفة>")
                    }
                
                حالة "/غادر":
                    اذا (اجزاء.الطول() > 1) {
                        _غادر_غرفة(مستخدم, اجزاء[1])
                    } والا {
                        _ارسل_خطأ(مستخدم, "استخدام: /غادر <اسم الغرفة>")
                    }
                
                حالة "/غرف":
                    _عرض_غرف(مستخدم)
                
                افتراضي:
                    _ارسل_خطأ(مستخدم, "أمر غير معروف: " + الامر)
            }
        }
        
        دالة _عرض_مساعدة(مستخدم: مستخدم) {
            متغير مساعدة = [
                "═══ أوامر الدردشة ═══",
                "/مساعدة - عرض هذه القائمة",
                "/اسم <اسم> - تغيير اسمك",
                "/خاص <اسم> <رسالة> - رسالة خاصة",
                "/قائمة - قائمة المتصلين",
                "/انضم <غرفة> - الانضمام لغرفة",
                "/غادر <غرفة> - مغادرة غرفة",
                "/غرف - عرض غرفك",
                "═════════════════════"
            ]
            
            لكل (سطر في مساعدة) {
                _ارسل_نظام(مستخدم.الاتصال, سطر)
            }
        }
        
        دالة _تغيير_اسم(مستخدم: مستخدم, اسم_جديد: نص) {
            // التحقق من عدم استخدام الاسم
            اذا (_اسماء.يحتوي(اسم_جديد)) {
                _ارسل_خطأ(مستخدم, "هذا الاسم مستخدم بالفعل!")
                ارجع
            }
            
            متغير اسم_قديم = مستخدم.الاسم
            _اسماء.احذف(اسم_قديم)
            _اسماء[اسم_جديد] = مستخدم.الاتصال.المعرف()
            مستخدم.الاسم = اسم_جديد
            
            _ارسل_نظام(مستخدم.الاتصال, "تم تغيير اسمك إلى: " + اسم_جديد)
            _بث_نظام(اسم_قديم + " غيّر اسمه إلى " + اسم_جديد)
        }
        
        دالة _رسالة_خاصة(مرسل: مستخدم, هدف: نص, رسالة: نص) {
            اذا (!_اسماء.يحتوي(هدف)) {
                _ارسل_خطأ(مرسل, "المستخدم '" + هدف + "' غير موجود")
                ارجع
            }
            
            متغير معرف_هدف = _اسماء[هدف]
            متغير مستخدم_هدف = _مستخدمون[معرف_هدف]
            
            // إرسال للهدف
            مستخدم_هدف.الاتصال.ارسل("[خاص من " + مرسل.الاسم + "]: " + رسالة)
            
            // تأكيد للمرسل
            مرسل.الاتصال.ارسل("[خاص إلى " + هدف + "]: " + رسالة)
        }
        
        دالة _عرض_قائمة(مستخدم: مستخدم) {
            _ارسل_نظام(مستخدم.الاتصال, "═══ المتصلون (" + _مستخدمون.الطول() + ") ═══")
            
            لكل (م في _مستخدمون.القيم()) {
                متغير علامة = اذا (م.المعرف == مستخدم.المعرف) " (أنت)" والا ""
                _ارسل_نظام(مستخدم.الاتصال, "• " + م.الاسم + علامة)
            }
        }
        
        دالة _انضم_غرفة(مستخدم: مستخدم, غرفة: نص) {
            مستخدم.الاتصال.انضم(غرفة)
            _ارسل_نظام(مستخدم.الاتصال, "✓ انضممت لغرفة: " + غرفة)
            _خادم.بث_لغرفة(غرفة, "[" + غرفة + "] " + مستخدم.الاسم + " انضم للغرفة")
        }
        
        دالة _غادر_غرفة(مستخدم: مستخدم, غرفة: نص) {
            _خادم.بث_لغرفة(غرفة, "[" + غرفة + "] " + مستخدم.الاسم + " غادر الغرفة")
            مستخدم.الاتصال.غادر(غرفة)
            _ارسل_نظام(مستخدم.الاتصال, "✗ غادرت غرفة: " + غرفة)
        }
        
        دالة _عرض_غرف(مستخدم: مستخدم) {
            متغير غرف = مستخدم.الاتصال.الغرف()
            اذا (غرف.فارغة()) {
                _ارسل_نظام(مستخدم.الاتصال, "أنت لست في أي غرفة")
            } والا {
                _ارسل_نظام(مستخدم.الاتصال, "غرفك: " + غرف.اتصل(", "))
            }
        }
        
        // دوال المساعدة للإرسال
        دالة _ارسل_نظام(اتصال: websocket.اتصال, رسالة: نص) {
            اتصال.ارسل("[النظام] " + رسالة)
        }
        
        دالة _ارسل_خطأ(مستخدم: مستخدم, رسالة: نص) {
            مستخدم.الاتصال.ارسل("[خطأ] " + رسالة)
        }
        
        دالة _بث_رسالة(مرسل: مستخدم, رسالة: نص) {
            _خادم.بث(مرسل.الاسم + ": " + رسالة)
        }
        
        دالة _بث_نظام(رسالة: نص, استثناء: رقم = -1) {
            اذا (استثناء >= 0) {
                _خادم.بث_ما_عدا("[النظام] " + رسالة, استثناء)
            } والا {
                _خادم.بث("[النظام] " + رسالة)
            }
        }
}

