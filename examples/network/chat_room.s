دالة main() {
    اطبع("╔════════════════════════════════════╗")
    اطبع("║     غرفة دردشة لغة ص             ║")
    اطبع("║     Sad Language Chat Room        ║")
    اطبع("╚════════════════════════════════════╝")
    اطبع("")
    
    متغير مدير = مدير_الدردشة()
    
    اذا (مدير.ابدأ(8080)) {
        اطبع("✓ خادم الدردشة يعمل على ws://localhost:8080")
        اطبع("")
        اطبع("اضغط Ctrl+C للإيقاف...")
        
        // حلقة انتظار لا نهائية
        بينما (صحيح) {
            انتظر(1000)
        }
        
    } والا {
        اطبع("✗ فشل بدء خادم الدردشة!")
    }
}
