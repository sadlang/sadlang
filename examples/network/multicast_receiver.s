    اطبع("📡 المجموعة: " + مجموعة_بث + ":" + منفذ)
    اطبع("=" نكرر 50)
    
    متغير عدد_رسائل = 0
    
    // حلقة استقبال الرسائل
    بينما (صحيح) {
        حاول {
            // استقبال رسالة
            متغير نتيجة = مستقبل.استقبل_من(4096)
            عدد_رسائل = عدد_رسائل + 1
            
            متغير بيانات = نتيجة.بيانات
            متغير عنوان = نتيجة.عنوان
            متغير منفذ_مرسل = نتيجة.منفذ
            
            // طباعة المعلومات
            متغير وقت = احصل_على_وقت()
            اطبع("\n[" + وقت + "] 📨 رسالة #" + عدد_رسائل)
            اطبع("   من: " + عنوان + ":" + منفذ_مرسل)
            اطبع("   المحتوى: " + بيانات)
            اطبع("   الحجم: " + طول(بيانات) + " بايت")
            
        } اصطاد (خطأ) {
            اطبع("⚠️  خطأ: " + خطأ)
        }
    }
    
    // إغلاق المقبس
    حاول {
        مستقبل.غادر_مجموعة(مجموعة_بث)
        اطبع("\n👋 تم مغادرة مجموعة البث")
    } اصطاد (خطأ) {
        اطبع("⚠️  خطأ في المغادرة: " + خطأ)
    }
    
    مستقبل.اغلق()
    اطبع("🛑 تم إغلاق المستقبل")
    
    ارجع 0
}

