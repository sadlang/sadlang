// WebSocket Client Example

/**
 * @example مثال عميل WebSocket بسيط
 * 
 * هذا المثال يوضح كيفية الاتصال بخادم WebSocket
 * وإرسال واستقبال الرسائل.
 */

استورد شبكة.websocket

دالة main() {
    اطبع("=== مثال عميل WebSocket ===")
    اطبع("")
    
    // إنشاء عميل جديد
    متغير عميل = websocket.عميل_جديد()
    
    // تعيين دوال الاستجابة
    عميل.عند_فتح(() => {
        اطبع("✓ تم الاتصال بالخادم!")
        
        // إرسال رسالة ترحيب
        عميل.ارسل("مرحباً من لغة ص!")
    })
    
    عميل.عند_رسالة((رسالة) => {
        اطبع("← استلم: " + رسالة.كنص())
    })
    
    عميل.عند_خطأ((خطأ) => {
        اطبع("✗ خطأ: " + خطأ)
    })
    
    عميل.عند_اغلاق((رمز, سبب) => {
        اطبع("⊘ انقطع الاتصال")
        اطبع("  الرمز: " + رمز)
        اذا (سبب != "") {
            اطبع("  السبب: " + سبب)
        }
    })
    
    // محاولة الاتصال
    اطبع("جاري الاتصال بـ ws://localhost:8080...")
    
    اذا (عميل.اتصل("ws://localhost:8080")) {
        اطبع("✓ الاتصال نجح!")
        
        // إرسال بعض الرسائل
        كرر (متغير i = 1; i <= 5; i++) {
            عميل.ارسل("رسالة رقم " + i)
            انتظر(1000)  // انتظر ثانية
        }
        
        // إغلاق الاتصال
        عميل.اغلق(websocket.رمز_الاغلاق.عادي, "انتهى المثال")
        
    } والا {
        اطبع("✗ فشل الاتصال!")
        اطبع("  تأكد من أن الخادم يعمل على المنفذ 8080")
    }
    
    اطبع("")
    اطبع("=== انتهى المثال ===")
}
