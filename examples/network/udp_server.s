// بسم الله الرحمن الرحيم
// مثال: خادم UDP Echo
// Example: UDP Echo Server

استورد شبكة من "stdlib/network/socket"

دالة main() {
    اطبع("🚀 بدء خادم UDP Echo...")
    اطبع("=" نكرر 50)
    
    // إنشاء مقبس UDP
    متغير خادم = شبكة.مقبس_udp()
    
    // ربط المقبس بالمنفذ 9090
    متغير منفذ = 9090
    
    حاول {
        خادم.اربط(منفذ)
        اطبع("✅ تم ربط خادم UDP بالمنفذ: " + منفذ)
    } اصطاد (خطأ) {
        اطبع("❌ خطأ في الربط: " + خطأ)
        ارجع 1
    }
    
    اطبع("👂 خادم UDP يستمع...")
    اطبع("📡 يمكنك إرسال رسائل UDP إلى: 127.0.0.1:" + منفذ)
    اطبع("=" نكرر 50)
    
    متغير عدد_رسائل = 0
    
    // حلقة استقبال الرسائل
    بينما (صحيح) {
        حاول {
            // استقبال رسالة
            متغير نتيجة = خادم.استقبل_من(4096)
            عدد_رسائل = عدد_رسائل + 1
            
            متغير بيانات = نتيجة.بيانات
            متغير عنوان = نتيجة.عنوان
            متغير منفذ_مرسل = نتيجة.منفذ
            
            // طباعة المعلومات
            اطبع("\n📨 رسالة #" + عدد_رسائل + " من " + عنوان + ":" + منفذ_مرسل)
            اطبع("   المحتوى: " + بيانات)
            اطبع("   الحجم: " + طول(بيانات) + " بايت")
            
            // إرجاع نفس البيانات (Echo)
            متغير رد = "Echo: " + بيانات
            متغير مرسل = خادم.ارسل_الى(رد، عنوان، منفذ_مرسل)
            اطبع("📤 تم إرسال " + مرسل + " بايت")
            
        } اصطاد (خطأ) {
            اطبع("⚠️  خطأ: " + خطأ)
            متغير معلومات_خطأ = شبكة.احصل_على_خطأ()
            اطبع("   الخطأ بالعربية: " + معلومات_خطأ.عربي)
        }
    }
    
    // إغلاق الخادم (لن نصل هنا)
    خادم.اغلق()
    اطبع("\n🛑 تم إغلاق الخادم")
    
    ارجع 0
}

// تشغيل البرنامج
main()
