            انتظر(2000)
            
        } اصطاد (خطأ) {
            اطبع("⚠️  خطأ في الإرسال: " + خطأ)
        }
    }
    
    // إرسال رسالة نهائية
    حاول {
        متغير رسالة_نهائية = "📢 انتهى البث!"
