// بسم الله الرحمن الرحيم
// مثال: عميل TCP بسيط
// Example: Simple TCP Client

استورد شبكة من "stdlib/network/socket"

دالة main() {
    اطبع("🚀 بدء عميل TCP...")
    اطبع("=" نكرر 50)
    
    // إنشاء مقبس العميل
    متغير عميل = شبكة.مقبس_tcp()
    
    // تعيين مهلة الاستقبال (5 ثواني)
    عميل.عين_مهلة_استقبال(5000)
    
    // الاتصال بالخادم
    متغير عنوان = "127.0.0.1"
    متغير منفذ = 8080
    
    حاول {
        اطبع("🔌 الاتصال بـ " + عنوان + ":" + منفذ + "...")
        عميل.اتصل(عنوان، منفذ)
        اطبع("✅ تم الاتصال بنجاح!")
    } اصطاد (خطأ) {
        اطبع("❌ فشل الاتصال: " + خطأ)
        متغير معلومات_خطأ = شبكة.احصل_على_خطأ()
        اطبع("   الخطأ بالعربية: " + معلومات_خطأ.عربي)
        ارجع 1
    }
    
    اطبع("=" نكرر 50)
    
    // استقبال رسالة الترحيب
    حاول {
        متغير ترحيب = عميل.استقبل(1024)
        اطبع("📨 " + ترحيب)
    } اصطاد (خطأ) {
        اطبع("⚠️  خطأ في استقبال الترحيب: " + خطأ)
    }
    
    // إرسال رسائل
    متغير رسائل = [
        "مرحباً، أنا عميل لغة ص!",
        "كيف حالك؟",
        "هذا اختبار للشبكات",
        "السلام عليكم",
        "quit"
    ]
    
    لكل (رسالة في رسائل) {
        حاول {
            // إرسال الرسالة
            اطبع("\n📤 إرسال: " + رسالة)
            عميل.ارسل_الكل(رسالة + "\n")
            
            // استقبال الرد
            متغير رد = عميل.استقبل(1024)
            اطبع("📨 استقبل: " + نظف(رد))
            
            // انتظر قليلاً بين الرسائل
            انتظر(500) // 500ms
            
        } اصطاد (خطأ) {
            اطبع("⚠️  خطأ: " + خطأ)
            اكسر
        }
    }
    
    // إغلاق الاتصال
    عميل.اغلق()
    اطبع("\n🛑 تم إغلاق الاتصال")
    
    ارجع 0
}

// دالة مساعدة لتنظيف النص
دالة نظف(نص: نص) -> نص {
    ارجع استبدل(استبدل(نص، "\n"، "")، "\r"، "")
}

// دالة انتظار بالملي ثانية
دالة انتظر(ملي_ثانية: رقم) {
    // TODO: تنفيذ دالة sleep
    // لحين ذلك، نستخدم حلقة فارغة
    متغير نهاية = الوقت_الحالي() + ملي_ثانية
    بينما (الوقت_الحالي() < نهاية) {
        // انتظار
    }
}

// تشغيل البرنامج
main()
