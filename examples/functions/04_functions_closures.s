# إغلاق يعيد عدة دوال / Closure returning multiple functions
دالة خريطة أنشئ_آلة_حاسبة()
    رقم ذاكرة = 0
    
    خريطة عمليات = {
        "اجمع": (رقم ع) => {
            ذاكرة = ذاكرة + ع
            إرجاع ذاكرة
        },
        "اطرح": (رقم ع) => {
            ذاكرة = ذاكرة - ع
            إرجاع ذاكرة
        },
        "احصل": () => ذاكرة,
        "امسح": () => { ذاكرة = 0 }
    }
    
    إرجاع عمليات
نهاية

