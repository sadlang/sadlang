# إغلاق لإنشاء عداد تنازلي / Countdown closure
دالة دالة أنشئ_عداد_تنازلي(رقم بداية)
    رقم قيمة = بداية
    
    إرجاع () => {
        إذا (قيمة > 0)
            رقم حالي = قيمة
            قيمة = قيمة - 1
            إرجاع حالي
        نهاية
        إرجاع 0
    }
نهاية

