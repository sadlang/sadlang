# إغلاق مع عمليات خاصة / Closure with private operations
دالة دالة أنشئ_حساب_بنكي(عشري رصيد_ابتدائي)
    عشري رصيد = رصيد_ابتدائي
    
    خريطة حساب = {
        "إيداع": (عشري مبلغ) => {
            رصيد = رصيد + مبلغ
            إرجاع رصيد
        },
        "سحب": (عشري مبلغ) => {
            إذا (مبلغ <= رصيد)
                رصيد = رصيد - مبلغ
                إرجاع رصيد
            نهاية
            إرجاع -1.0
        },
        "الرصيد": () => رصيد
    }
    
    إرجاع حساب
نهاية

اطبع("\n=== حساب بنكي ===\n")
خريطة حسابي = أنشئ_حساب_بنكي(1000.0)
اطبع("الرصيد الابتدائي:", حسابي["الرصيد"](), "\n")
اطبع("إيداع 500:", حسابي["إيداع"](500.0), "\n")
اطبع("سحب 200:", حسابي["سحب"](200.0), "\n")
اطبع("الرصيد النهائي:", حسابي["الرصيد"](), "\n")

# إغلاق لإنشاء مولد أرقام / Number generator closure
