# دالة رسم خط / Draw line
دالة رسم_خط(رقم طول = 50، نص حرف = "-")
    نص خط = ""
    رقم ع = 0
    بينما (ع < طول)
        خط = خط + حرف
        ع = ع + 1
    نهاية
    اطبع(خط)
نهاية

