# دالة حساب المسافة / Distance calculation
دالة عشري مسافة(عشري س1، عشري ص1، عشري س2 = 0.0، عشري ص2 = 0.0)
    عشري فرق_س = س2 - س1
    عشري فرق_ص = ص2 - ص1
    عشري مربع_مجموع = فرق_س ** 2.0 + فرق_ص ** 2.0
    إرجاع مربع_مجموع ** 0.5
نهاية

