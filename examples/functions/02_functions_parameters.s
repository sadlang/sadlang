# دالة لإنشاء قائمة بقيمة افتراضية / Create list with default value
دالة مصفوفة أنشئ_قائمة(رقم حجم، رقم قيمة = 0)
    مصفوفة نتيجة = []
    رقم ع = 0
    بينما (ع < حجم)
        نتيجة = نتيجة + [قيمة]
        ع = ع + 1
    نهاية
    إرجاع نتيجة
نهاية

اطبع("\n=== إنشاء قوائم ===")
