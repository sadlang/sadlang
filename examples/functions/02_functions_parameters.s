# دالة إنشاء نطاق / Range creation
دالة مصفوفة نطاق(رقم بداية = 0، رقم نهاية = 10، رقم خطوة = 1)
    مصفوفة نتيجة = []
    رقم ع = بداية
    بينما (ع < نهاية)
        نتيجة = نتيجة + [ع]
        ع = ع + خطوة
    نهاية
    إرجاع نتيجة
نهاية

