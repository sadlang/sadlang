# دالة حساب الخصم / Discount calculation
دالة عشري سعر_بعد_الخصم(عشري سعر_أصلي، عشري نسبة_خصم = 10.0)
    عشري خصم = سعر_أصلي * (نسبة_خصم / 100.0)
    إرجاع سعر_أصلي - خصم
