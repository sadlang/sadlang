# دالة curry - تحويل دالة ثنائية لمتسلسلة / Curry function
دالة دالة curry(دالة ف)
    إرجاع (رقم أ) => (رقم ب) => ف(أ، ب)
نهاية

اطبع("\n=== Currying ===\n")
أي جمع_ثنائي = (رقم أ، رقم ب) => أ + ب
أي جمع_curry = curry(جمع_ثنائي)
أي جمع_5 = جمع_curry(5)

اطبع("Curry: 5 + 10 =", جمع_5(10), "\n")
اطبع("Curry: 5 + 20 =", جمع_5(20), "\n")

# دالة تطبيق جزئي / Partial application
