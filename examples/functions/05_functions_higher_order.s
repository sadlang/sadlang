# دالة pipe - تمرير متسلسل / Pipe function
دالة أي pipe(أي قيمة، دالة ف1، دالة ف2، دالة ف3)
    أي نتيجة = ف1(قيمة)
    نتيجة = ف2(نتيجة)
    نتيجة = ف3(نتيجة)
    إرجاع نتيجة
نهاية

اطبع("\n=== pipe - تمرير متسلسل ===\n")
