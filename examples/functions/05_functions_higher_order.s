# دالة تقبل دالة كمعامل / Function accepting function as parameter
دالة رقم طبق(دالة ف، رقم ع)
    إرجاع ف(ع)
نهاية

اطبع("=== دالة تقبل دالة ===\n")
أي مربع = (رقم ع) => ع * ع
أي مكعب = (رقم ع) => ع * ع * ع

اطبع("تطبيق مربع على 5:", طبق(مربع، 5), "\n")
اطبع("تطبيق مكعب على 3:", طبق(مكعب، 3), "\n")

# دالة تعيد دالة / Function returning function
دالة دالة مؤلف(دالة ف، دالة ج)
    إرجاع (أي ع) => ف(ج(ع))
نهاية

اطبع("\n=== دالة تعيد دالة ===\n")
أي ضعف = (رقم ع) => ع * 2
أي زائد_واحد = (رقم ع) => ع + 1

أي ضعف_ثم_زائد = مؤلف(زائد_واحد، ضعف)
اطبع("ضعف 5 ثم إضافة 1:", ضعف_ثم_زائد(5), "\n")

# تطبيق map - تطبيق دالة على كل عنصر / map implementation
دالة مصفوفة map(مصفوفة قائمة، دالة ف)
    مصفوفة نتيجة = []
    رقم ع = 0
    رقم طول = 5  # سيُحسب فعلياً
    
    بينما (ع < طول)
        نتيجة = نتيجة + [ف(قائمة[ع])]
        ع = ع + 1
    نهاية
    
    إرجاع نتيجة
نهاية

اطبع("\n=== تطبيق map ===\n")
مصفوفة أرقام = [1، 2، 3، 4، 5]
مصفوفة مربعات = map(أرقام، (ع) => ع * ع)
مصفوفة مضاعف = map(أرقام، (ع) => ع * 2)

اطبع("الأرقام:", أرقام, "\n")
اطبع("المربعات:", مربعات, "\n")
اطبع("المضاعف:", مضاعف, "\n")

# تطبيق filter - تصفية العناصر / filter implementation
دالة مصفوفة filter(مصفوفة قائمة، دالة شرط)
    مصفوفة نتيجة = []
    رقم ع = 0
    رقم طول = 5
    
    بينما (ع < طول)
        إذا (شرط(قائمة[ع]))
            نتيجة = نتيجة + [قائمة[ع]]
        نهاية
        ع = ع + 1
    نهاية
    
    إرجاع نتيجة
نهاية

اطبع("\n=== تطبيق filter ===\n")
مصفوفة زوجية = filter(أرقام، (ع) => ع % 2 == 0)
مصفوفة أكبر_من_2 = filter(أرقام، (ع) => ع > 2)

اطبع("الأعداد الزوجية:", زوجية, "\n")
اطبع("الأعداد الأكبر من 2:", أكبر_من_2, "\n")

# تطبيق reduce - طي المصفوفة / reduce implementation
دالة أي reduce(مصفوفة قائمة، دالة ف، أي قيمة_أولية)
    أي مجمع = قيمة_أولية
    رقم ع = 0
    رقم طول = 5
    
    بينما (ع < طول)
        مجمع = ف(مجمع، قائمة[ع])
        ع = ع + 1
    نهاية
    
    إرجاع مجمع
نهاية

اطبع("\n=== تطبيق reduce ===\n")
رقم مجموع = reduce(أرقام، (مجمع، ع) => مجمع + ع، 0)
رقم حاصل_ضرب = reduce(أرقام، (مجمع، ع) => مجمع * ع، 1)

اطبع("مجموع الأرقام:", مجموع, "\n")
اطبع("حاصل ضرب الأرقام:", حاصل_ضرب, "\n")

# دالة تطبق دالة عدة مرات / Function applying function multiple times
دالة أي طبق_عدة_مرات(دالة ف، أي قيمة، رقم عدد)
    أي نتيجة = قيمة
    رقم ع = 0
    
    بينما (ع < عدد)
        نتيجة = ف(نتيجة)
        ع = ع + 1
    نهاية
    
    إرجاع نتيجة
نهاية

اطبع("\n=== تطبيق متكرر ===\n")
رقم نتيجة_ضعف = طبق_عدة_مرات((ع) => ع * 2، 1، 5)
اطبع("ضعف 1 خمس مرات:", نتيجة_ضعف, "\n")

# دالة تركيب / Compose function
دالة دالة compose(دالة ف، دالة ج، دالة ه)
    إرجاع (أي ع) => ف(ج(ه(ع)))
نهاية

اطبع("\n=== تركيب ثلاث دوال ===\n")
أي زائد_1 = (رقم ع) => ع + 1
أي ضرب_2 = (رقم ع) => ع * 2
أي تربيع = (رقم ع) => ع * ع

أي معقد = compose(زائد_1، ضرب_2، تربيع)
اطبع("((3^2) * 2) + 1 =", معقد(3), "\n")

# دالة تنفيذ شرطي / Conditional execution
دالة أي تنفيذ_إذا(منطقي شرط، دالة إذا_صحيح، دالة إذا_خطأ، أي قيمة)
    إذا (شرط)
        إرجاع إذا_صحيح(قيمة)
    نهاية
    إرجاع إذا_خطأ(قيمة)
نهاية

اطبع("\n=== تنفيذ شرطي ===\n")
رقم نتيجة1 = تنفيذ_إذا(صحيح، (ع) => ع * 2، (ع) => ع / 2، 10)
رقم نتيجة2 = تنفيذ_إذا(خطأ، (ع) => ع * 2، (ع) => ع / 2، 10)

اطبع("إذا صحيح (ضعف 10):", نتيجة1, "\n")
اطبع("إذا خطأ (نصف 10):", نتيجة2, "\n")

# دالة تطبيق على زوج / Apply to pair
دالة أي طبق_على_زوج(دالة ف، رقم أ، رقم ب)
