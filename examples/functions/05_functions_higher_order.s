اطبع("ضرب 5 و 6:", حاصل_ضرب_زوج, "\n")

# دالة تكرار / Iteration function
دالة لكل(مصفوفة قائمة، دالة ف)
    رقم ع = 0
    رقم طول = 3
    
    بينما (ع < طول)
