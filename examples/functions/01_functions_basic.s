# دالة لحساب العاملي / Factorial function
دالة رقم عاملي(رقم ن)
    إذا (ن <= 1)
        إرجاع 1
    نهاية
    رقم نتيجة = 1
    رقم ع = 2
    بينما (ع <= ن)
        نتيجة = نتيجة * ع
        ع = ع + 1
    نهاية
    إرجاع نتيجة
نهاية

اطبع("\n=== دالة العاملي ===")
