# لامدا بسيطة بمعامل واحد / Simple lambda with one parameter
أي مربع = (رقم ع) => ع * ع

اطبع("=== لامدا بسيطة ===")
اطبع("مربع 5 =", مربع(5))
اطبع("مربع 10 =", مربع(10))

# لامدا بمعاملين / Lambda with two parameters
أي جمع = (رقم أ، رقم ب) => أ + ب
أي ضرب = (رقم أ، رقم ب) => أ * ب

اطبع("\n=== لامدا بمعاملين ===")
اطبع("3 + 7 =", جمع(3، 7))
اطبع("4 × 5 =", ضرب(4، 5))

# لامدا بدون معاملات / Lambda without parameters
أي احصل_على_42 = () => 42
أي احصل_على_باي = () => 3.14159

اطبع("\n=== لامدا بدون معاملات ===")
اطبع("الإجابة:", احصل_على_42())
اطبع("باي:", احصل_على_باي())

# لامدا مع عمليات معقدة / Lambda with complex operations
أي متوسط = (رقم أ، رقم ب) => (أ + ب) / 2.0
أي فرق_مطلق = (رقم أ، رقم ب) => ((أ - ب) >= 0) ? (أ - ب) : (ب - أ)

اطبع("\n=== لامدا معقدة ===")
اطبع("متوسط 10 و 20 =", متوسط(10، 20))
اطبع("الفرق المطلق بين 5 و 15 =", فرق_مطلق(5، 15))

# لامدا لفحص الشروط / Lambda for conditions
أي هل_زوجي = (رقم ع) => ع % 2 == 0
أي هل_موجب = (رقم ع) => ع > 0
أي في_النطاق = (رقم ع، رقم min، رقم max) => ع >= min && ع <= max

اطبع("\n=== لامدا للفحص ===")
اطبع("4 زوجي؟", هل_زوجي(4))
اطبع("7 زوجي؟", هل_زوجي(7))
اطبع("-5 موجب؟", هل_موجب(-5))
اطبع("15 موجب؟", هل_موجب(15))
اطبع("5 بين 1 و 10؟", في_النطاق(5، 1، 10))
اطبع("15 بين 1 و 10؟", في_النطاق(15، 1، 10))

# لامدا مع نصوص / Lambda with strings
أي دمج = (نص أ، نص ب) => أ + " " + ب
أي طول_نص = (نص س) => 10  # سيُحسب فعلياً

اطبع("\n=== لامدا مع النصوص ===")
اطبع(دمج("مرحبا"، "بالعالم"))
اطبع(دمج("لغة"، "ص"))

# لامدا متداخلة / Nested lambda
أي أضف = (رقم س) => (رقم ص) => س + ص
أي أضف_5 = أضف(5)
أي أضف_10 = أضف(10)

اطبع("\n=== لامدا متداخلة ===")
اطبع("أضف 5 إلى 3 =", أضف_5(3))
اطبع("أضف 10 إلى 7 =", أضف_10(7))

# لامدا مع عمليات حسابية متعددة / Lambda with multiple operations
أي حساب_معقد = (رقم س) => س ** 2 + 2 * س + 1
أي عملية_مركبة = (رقم أ، رقم ب، رقم ج) => أ * ب + ج

اطبع("\n=== لامدا بحسابات معقدة ===")
اطبع("(س^2 + 2س + 1) عندما س=3:", حساب_معقد(3))
اطبع("أ×ب+ج عندما أ=2، ب=3، ج=4:", عملية_مركبة(2، 3، 4))

# لامدا للمقارنة / Lambda for comparison
أي الأكبر = (رقم أ، رقم ب) => (أ > ب) ? أ : ب
أي الأصغر = (رقم أ، رقم ب) => (أ < ب) ? أ : ب

اطبع("\n=== لامدا للمقارنة ===")
اطبع("الأكبر بين 15 و 8:", الأكبر(15، 8))
اطبع("الأصغر بين 15 و 8:", الأصغر(15، 8))

# لامدا مع أنواع مختلطة / Lambda with mixed types
أي تنسيق = (نص بادئة، رقم رقم) => بادئة + ": " + "؟"  # سيُحول الرقم
أي إنشاء_رسالة = (نص اسم، رقم عمر) => "مرحبا " + اسم

اطبع("\n=== لامدا بأنواع مختلطة ===")
اطبع(تنسيق("العدد"، 42))
اطبع(إنشاء_رسالة("أحمد"، 25))

# استخدام لامدا مع مصفوفات / Using lambda with arrays
مصفوفة أرقام = [1، 2، 3، 4، 5]

اطبع("\n=== لامدا مع المصفوفات ===")
اطبع("الأرقام الأصلية:", أرقام)

