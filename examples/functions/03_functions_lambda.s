# لامدا للعمليات المنطقية / Lambda for logical operations
أي and = (منطقي أ، منطقي ب) => أ && ب
أي or = (منطقي أ، منطقي ب) => أ || ب
أي not = (منطقي أ) => !أ

اطبع("\n=== لامدا للعمليات المنطقية ===")
اطبع("صحيح AND خطأ =", and(صحيح، خطأ))
اطبع("صحيح OR خطأ =", or(صحيح، خطأ))
اطبع("NOT صحيح =", not(صحيح))

# لامدا لحساب القوة / Lambda for power calculation
أي تربيع = (رقم ع) => ع ** 2
أي تكعيب = (رقم ع) => ع ** 3
أي قوة_4 = (رقم ع) => ع ** 4

اطبع("\n=== لامدا للقوى ===")
اطبع("3^2 =", تربيع(3))
اطبع("3^3 =", تكعيب(3))
اطبع("2^4 =", قوة_4(2))

# لامدا مع تعبيرات شرطية متداخلة / Lambda with nested conditions
أي تصنيف_عمر = (رقم عمر) => 
    (عمر < 13) ? "طفل" : 
    (عمر < 20) ? "مراهق" : 
    (عمر < 60) ? "بالغ" : "كبير"

اطبع("\n=== لامدا بشروط متداخلة ===")
اطبع("تصنيف عمر 10:", تصنيف_عمر(10))
اطبع("تصنيف عمر 16:", تصنيف_عمر(16))
اطبع("تصنيف عمر 35:", تصنيف_عمر(35))
اطبع("تصنيف عمر 70:", تصنيف_عمر(70))

# لامدا لحسابات هندسية / Lambda for geometric calculations
أي مساحة_مربع = (عشري ضلع) => ضلع ** 2.0
أي مساحة_مستطيل = (عشري طول، عشري عرض) => طول * عرض
أي محيط_دائرة = (عشري نصف_قطر) => 2.0 * 3.14159 * نصف_قطر

اطبع("\n=== لامدا للهندسة ===")
اطبع("مساحة مربع ضلعه 5:", مساحة_مربع(5.0))
اطبع("مساحة مستطيل 4×7:", مساحة_مستطيل(4.0، 7.0))
اطبع("محيط دائرة نصف قطرها 3:", محيط_دائرة(3.0))

