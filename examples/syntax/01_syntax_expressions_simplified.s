# اختبار تعابير مبسط

اطبع("=== التعابير الحسابية ===\n")

رقم أ = 10 + 5
رقم ب = 20 - 7
رقم ج = 6 * 4
رقم د = 15 / 3
رقم ه = 17 % 5

اطبع("10 + 5 =", أ, "\n")
اطبع("20 - 7 =", ب, "\n")
اطبع("6 * 4 =", ج, "\n")
اطبع("15 / 3 =", د, "\n")
اطبع("17 % 5 =", ه, "\n")

رقم تعبير1 = 2 + 3 * 4
رقم تعبير2 = (2 + 3) * 4
رقم تعبير3 = 10 + 5 * 2 - 3

اطبع("\n2 + 3 * 4 =", تعبير1, "\n")
اطبع("(2 + 3) * 4 =", تعبير2, "\n")
اطبع("10 + 5 * 2 - 3 =", تعبير3, "\n")

رقم أس1 = 2 ** 3
رقم أس2 = 5 ** 2
رقم أس3 = 10 ** 0

اطبع("\n2^3 =", أس1, "\n")
اطبع("5^2 =", أس2, "\n")
اطبع("10^0 =", أس3, "\n")

اطبع("\n=== تعابير المقارنة ===\n")

منطقي مقارنة1 = 10 > 5
منطقي مقارنة2 = 3 < 7
منطقي مقارنة3 = 15 == 15
منطقي مقارنة4 = 8 != 9
منطقي مقارنة5 = 12 >= 10
منطقي مقارنة6 = 6 <= 6

اطبع("10 > 5 هو", مقارنة1, "\n")
اطبع("3 < 7 هو", مقارنة2, "\n")
اطبع("15 == 15 هو", مقارنة3, "\n")
اطبع("8 != 9 هو", مقارنة4, "\n")
اطبع("12 >= 10 هو", مقارنة5, "\n")
اطبع("6 <= 6 هو", مقارنة6, "\n")

اطبع("\n=== التعابير المنطقية ===\n")

منطقي منطق1 = صحيح و صحيح
منطقي منطق2 = صحيح و خطأ
منطقي منطق3 = صحيح أو خطأ
منطقي منطق4 = خطأ أو خطأ
منطقي منطق5 = ليس صحيح
منطقي منطق6 = ليس خطأ

اطبع("صحيح و صحيح =", منطق1, "\n")
اطبع("صحيح و خطأ =", منطق2, "\n")
اطبع("صحيح أو خطأ =", منطق3, "\n")
اطبع("خطأ أو خطأ =", منطق4, "\n")
اطبع("ليس صحيح =", منطق5, "\n")
اطبع("ليس خطأ =", منطق6, "\n")

منطقي معقد1 = (10 > 5) و (3 < 7)
منطقي معقد2 = (15 == 15) أو (8 != 8)
منطقي معقد3 = ليس (10 < 5)

اطبع("\n(10 > 5) و (3 < 7) =", معقد1, "\n")
اطبع("(15 == 15) أو (8 != 8) =", معقد2, "\n")
اطبع("ليس (10 < 5) =", معقد3, "\n")

اطبع("\n=== الأولوية والأقواس ===\n")

رقم أولوية1 = 2 + 3 * 4
رقم أولوية2 = (2 + 3) * 4
رقم أولوية3 = 10 - 5 + 3
رقم أولوية4 = 10 - (5 + 3)

اطبع("2 + 3 * 4 =", أولوية1, "\n")
اطبع("(2 + 3) * 4 =", أولوية2, "\n")
اطبع("10 - 5 + 3 =", أولوية3, "\n")
اطبع("10 - (5 + 3) =", أولوية4, "\n")

منطقي أولوية_منطق1 = 5 + 3 > 7

اطبع("\n5 + 3 > 7 =", أولوية_منطق1, "\n")

منطقي أولوية_منطق3 = صحيح أو خطأ و خطأ
منطقي أولوية_منطق4 = (صحيح أو خطأ) و خطأ
اطبع("صحيح أو خطأ و خطأ =", أولوية_منطق3, "\n")
اطبع("(صحيح أو خطأ) و خطأ =", أولوية_منطق4, "\n")

اطبع("\n=== تعابير النصوص ===\n")

نص نص1 = "مرحبا" + " " + "عالم"
نص نص2 = "مكرر " * 3
اطبع("دمج النصوص:", نص1, "\n")
اطبع("تكرار النص:", نص2, "\n")

اطبع("\n=== تعابير المصفوفات ===\n")

مصفوفة مصفوفة1 = [1, 2, 3] + [4, 5]
مصفوفة مصفوفة2 = [0] * 5
اطبع("دمج المصفوفات:", مصفوفة1, "\n")
اطبع("تكرار المصفوفة:", مصفوفة2, "\n")

رقم عنصر1 = [10, 20, 30][1]
اطبع("العنصر بمؤشر 1:", عنصر1, "\n")

اطبع("\n=== تعابير الخرائط ===\n")

خريطة شخص = {"الاسم": "أحمد", "العمر": 25}
نص الاسم = شخص["الاسم"]
رقم العمر = شخص["العمر"]
اطبع("الاسم:", الاسم, "\n")
اطبع("العمر:", العمر, "\n")

اطبع("\n=== تعابير معقدة متداخلة ===\n")

رقم نتيجة_معقدة = ((10 + 5) * 2 - 3) ** 2 / 5 + 10
اطبع("تعبير معقد: ((10 + 5) * 2 - 3)^2 / 5 + 10 =", نتيجة_معقدة, "\n")

منطقي شرط_معقد = ((10 > 5) و (20 < 30)) أو (ليس (5 == 6))
اطبع("شرط معقد: ((10 > 5) و (20 < 30)) أو (ليس (5 == 6)) =", شرط_معقد, "\n")

