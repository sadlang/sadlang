اطبع("=== المشغلات الحسابية (Arithmetic Operators) ===\n")

# الجمع (+)
رقم جمع = 10 + 5
اطبع("10 + 5 =", جمع, "\n")

# الطرح (-)
رقم طرح = 20 - 7
اطبع("20 - 7 =", طرح, "\n")

# الضرب (*)
رقم ضرب = 6 * 4
اطبع("6 × 4 =", ضرب, "\n")

# القسمة (/)
رقم قسمة = 15 / 3
اطبع("15 ÷ 3 =", قسمة, "\n")

# باقي القسمة (%)
رقم باقي = 17 % 5
اطبع("17 % 5 =", باقي, "\n")

# الأس (**)
رقم أس = 2 ** 8
اطبع("2^8 =", أس, "\n")

# السالب الأحادي (-)
رقم موجب = 42
رقم سالب = -موجب
اطبع("سالب 42 =", سالب, "\n")

اطبع("\n=== المشغلات الحسابية على أنواع مختلفة ===\n")

# عمليات على الأعداد العشرية
عشري ع1 = 10.5 + 5.3
عشري ع2 = 20.8 - 7.2
عشري ع3 = 3.5 * 2.0
عشري ع4 = 10.0 / 4.0

اطبع("10.5 + 5.3 =", ع1, "\n")
اطبع("20.8 - 7.2 =", ع2, "\n")
اطبع("3.5 × 2.0 =", ع3, "\n")
اطبع("10.0 ÷ 4.0 =", ع4, "\n")

# عمليات مختلطة (int + float)
عشري مختلط1 = 10 + 5.5
عشري مختلط2 = 20.5 - 5
اطبع("10 + 5.5 =", مختلط1, "\n")
اطبع("20.5 - 5 =", مختلط2, "\n")

اطبع("\n=== مشغلات المقارنة (Comparison Operators) ===\n")

# أكبر من (>)
منطقي أكبر = 10 > 5
اطبع("10 > 5 هو", أكبر, "\n")

# أصغر من (<)
منطقي أصغر = 3 < 7
اطبع("3 < 7 هو", أصغر, "\n")

# يساوي (==)
منطقي يساوي = 15 == 15
اطبع("15 == 15 هو", يساوي, "\n")

# لا يساوي (!=)
منطقي لا_يساوي = 8 != 9
اطبع("8 != 9 هو", لا_يساوي, "\n")

# أكبر من أو يساوي (>=)
منطقي أكبر_يساوي1 = 12 >= 10
منطقي أكبر_يساوي2 = 10 >= 10
اطبع("12 >= 10 هو", أكبر_يساوي1, "\n")
اطبع("10 >= 10 هو", أكبر_يساوي2, "\n")

# أصغر من أو يساوي (<=)
منطقي أصغر_يساوي1 = 6 <= 10
منطقي أصغر_يساوي2 = 10 <= 10
اطبع("6 <= 10 هو", أصغر_يساوي1, "\n")
اطبع("10 <= 10 هو", أصغر_يساوي2, "\n")

اطبع("\n=== مقارنات على أنواع مختلفة ===\n")

# مقارنة نصوص
منطقي نص1 = "أحمد" == "أحمد"
منطقي نص2 = "أحمد" != "محمد"
اطبع("'أحمد' == 'أحمد' هو", نص1, "\n")
اطبع("'أحمد' != 'محمد' هو", نص2, "\n")

# مقارنة منطقية
منطقي منطق1 = صحيح == صحيح
منطقي منطق2 = صحيح != خطأ
اطبع("صحيح == صحيح هو", منطق1, "\n")
اطبع("صحيح != خطأ هو", منطق2, "\n")

اطبع("\n=== المشغلات المنطقية (Logical Operators) ===\n")

# و (and)
منطقي و1 = صحيح و صحيح
منطقي و2 = صحيح و خطأ
منطقي و3 = خطأ و خطأ
اطبع("صحيح و صحيح =", و1, "\n")
اطبع("صحيح و خطأ =", و2, "\n")
اطبع("خطأ و خطأ =", و3, "\n")

# أو (or)
منطقي أو1 = صحيح أو صحيح
منطقي أو2 = صحيح أو خطأ
منطقي أو3 = خطأ أو خطأ
اطبع("صحيح أو صحيح =", أو1, "\n")
اطبع("صحيح أو خطأ =", أو2, "\n")
اطبع("خطأ أو خطأ =", أو3, "\n")

# ليس (not)
منطقي ليس1 = ليس صحيح
منطقي ليس2 = ليس خطأ
اطبع("ليس صحيح =", ليس1, "\n")
اطبع("ليس خطأ =", ليس2, "\n")

# تركيب معقد
منطقي معقد1 = (صحيح و خطأ) أو (ليس خطأ)
منطقي معقد2 = صحيح و (خطأ أو صحيح)
اطبع("(صحيح و خطأ) أو (ليس خطأ) =", معقد1, "\n")
اطبع("صحيح و (خطأ أو صحيح) =", معقد2, "\n")

اطبع("\n=== مشغلات على النصوص (String Operators) ===\n")

# دمج النصوص (+)
نص دمج = "مرحبا" + " " + "عالم"
اطبع("دمج:", دمج, "\n")

# تكرار النص (*)
نص تكرار = "هلا " * 3
اطبع("تكرار:", تكرار, "\n")

اطبع("\n=== مشغلات على المصفوفات (Array Operators) ===\n")

# دمج المصفوفات (+)
مصفوفة مصفوفة1 = [1، 2، 3]
مصفوفة مصفوفة2 = [4، 5، 6]
مصفوفة دمج_مصفوفات = مصفوفة1 + مصفوفة2
اطبع("دمج المصفوفات:", دمج_مصفوفات, "\n")

# تكرار المصفوفة (*)
مصفوفة تكرار_مصفوفة = [0] * 5
اطبع("تكرار المصفوفة:", تكرار_مصفوفة, "\n")

# الوصول للعنصر ([])
مصفوفة أرقام = [10، 20، 30، 40، 50]
رقم عنصر = أرقام[2]
اطبع("العنصر بمؤشر 2:", عنصر, "\n")

# مؤشر سالب
رقم آخر_عنصر = أرقام[-1]
اطبع("العنصر الأخير:", آخر_عنصر, "\n")

# التقطيع (Slicing)
مصفوفة شريحة1 = أرقام[1:4]
مصفوفة شريحة2 = أرقام[:3]
مصفوفة شريحة3 = أرقام[2:]
اطبع("أرقام[1:4] =", شريحة1, "\n")
اطبع("أرقام[:3] =", شريحة2, "\n")
اطبع("أرقام[2:] =", شريحة3, "\n")

اطبع("\n=== مشغلات على الخرائط (Map Operators) ===\n")

# الوصول للقيمة ([])
خريطة شخص = {"الاسم": "أحمد"، "العمر": 25، "المدينة": "القاهرة"}
نص الاسم = شخص["الاسم"]
رقم العمر = شخص["العمر"]
اطبع("الاسم:", الاسم, "\n")
اطبع("العمر:", العمر, "\n")

اطبع("\n=== المشغل الثلاثي (Ternary Operator) ===\n")

# ثلاثي بسيط
رقم عمر = 20
نص حالة = عمر >= 18 ? "بالغ" : "قاصر"
اطبع("الحالة:", حالة, "\n")

# ثلاثي متداخل
رقم درجة = 85
نص تقييم = درجة >= 90 ? "ممتاز" : درجة >= 70 ? "جيد" : "مقبول"
اطبع("التقييم:", تقييم, "\n")

# ثلاثي في عملية حسابية
رقم س = -5
رقم قيمة_مطلقة = س >= 0 ? س : -س
اطبع("القيمة المطلقة لـ", س, "هي", قيمة_مطلقة, "\n")

اطبع("\n=== أولوية المشغلات (Operator Precedence) ===\n")

# الضرب قبل الجمع
رقم أولوية1 = 2 + 3 * 4
اطبع("2 + 3 × 4 =", أولوية1, " (الضرب أولاً)\n")

# الأقواس تغير الأولوية
رقم أولوية2 = (2 + 3) * 4
اطبع("(2 + 3) × 4 =", أولوية2, " (الأقواس أولاً)\n")

# المقارنات قبل العمليات المنطقية
منطقي أولوية3 = 10 > 5 و 3 < 7
اطبع("10 > 5 و 3 < 7 =", أولوية3, "\n")

# و قبل أو
منطقي أولوية4 = صحيح أو خطأ و خطأ
منطقي أولوية5 = (صحيح أو خطأ) و خطأ
اطبع("صحيح أو خطأ و خطأ =", أولوية4, "\n")
اطبع("(صحيح أو خطأ) و خطأ =", أولوية5, "\n")

اطبع("\n=== أمثلة عملية على المشغلات ===\n")

# حساب المتوسط
رقم عدد1 = 10
رقم عدد2 = 20
رقم عدد3 = 30
رقم متوسط = (عدد1 + عدد2 + عدد3) / 3
