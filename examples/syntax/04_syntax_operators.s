# فحص النطاق
رقم قيمة = 15
منطقي في_النطاق = قيمة >= 10 و قيمة <= 20
اطبع("هل 15 بين 10 و 20؟", في_النطاق, "\n")

# فحص زوجي أم فردي
رقم عدد_اختبار = 17
نص نوع = عدد_اختبار % 2 == 0 ? "زوجي" : "فردي"
اطبع(عدد_اختبار, "هو", نوع, "\n")

# حساب القوة
رقم قاعدة = 2
رقم أس_قوة = 10
رقم نتيجة = قاعدة ** أس_قوة
اطبع(قاعدة, "^", أس_قوة, "=", نتيجة, "\n")

# منطق معقد
منطقي ص1 = 10 > 5
منطقي ص2 = 20 < 30
منطقي ص3 = 15 == 15
منطقي نتيجة_معقدة = (ص1 و ص2) أو ص3
اطبع("((10>5) و (20<30)) أو (15==15) =", نتيجة_معقدة, "\n")

