دالة رئيسية() {
    # إنشاء نافذة
    متغير نافذة = نافذة_جديد("مرحباً بك في لغة ص", 800, 600)
    
    # إنشاء رسام
    متغير رسام = رسام_ثنائي_جديد(نافذة)
    
    # حلقة الرسم الرئيسية
    متغير يعمل = صحيح
    
    بينما (يعمل) {
        # معالجة الأحداث
        نافذة_معالجة_احداث(نافذة)
        
        # فحص إغلاق النافذة
        اذا (نافذة_يجب_الاغلاق(نافذة)) {
            يعمل = خطأ
        }
        
        # بدء إطار جديد
        رسام_ابدأ_اطار(رسام)
        
        # مسح الشاشة بلون أزرق فاتح
        رسام_مسح(رسام, 135, 206, 235, 255)
        
        # رسم مستطيل أحمر
        رسام_رسم_مستطيل(رسام, 100, 100, 200, 150, 255, 0, 0, 255, صحيح)
        
        # رسم دائرة خضراء
        رسام_رسم_دائرة(رسام, 500, 300, 80, 0, 255, 0, 255, صحيح)
        
        # رسم خط أصفر
        رسام_رسم_خط(رسام, 100, 400, 700, 400, 255, 255, 0, 255)
        
        # رسم مستطيل فارغ أزرق
        رسام_رسم_مستطيل(رسام, 400, 100, 300, 200, 0, 0, 255, 255, خطأ)
        
        # إنهاء الإطار
        رسام_انهي_اطار(رسام)
        
        # تبديل المخازن
        نافذة_بدل_المخازن(نافذة)
    }
    
    # إغلاق النافذة
    نافذة_اغلق(نافذة)
    
    اطبع("تم إغلاق التطبيق بنجاح")
}
