/**
 * أوامر البيان في سطر الأوامر
 * 
 * ص إضافة هيِّئ        - إنشاء بيان جديد
 * ص إضافة تحقق        - التحقق من البيان
 * ص إضافة اعرض        - عرض محتوى البيان
 */
class أوامر_بيان {
public:
    /**
     * إنشاء بيان جديد تفاعلياً
     */
    static بيان_إضافة هيِّئ_تفاعلي() {
        بيان_إضافة بيان;
        
        // في التنفيذ الكامل، اسأل المستخدم
        بيان.الاسم = "إضافتي";
        بيان.الإصدار = "0.1.0";
        بيان.الوصف = "وصف الإضافة";
        بيان.الترخيص = "MIT";
        بيان.المنصات = {"windows", "linux", "macos"};
        بيان.الحد_الأدنى_لغة_ص = "1.0.0";
        
        return بيان;
    }
    
    /**
     * طباعة ملخص البيان
     */
    static void اطبع_ملخص(const بيان_إضافة& بيان) {
        std::cout << "\n📦 " << بيان.الاسم << " v" << بيان.الإصدار << "\n";
        std::cout << "   " << بيان.الوصف << "\n";
        
        if (!بيان.المؤلفون.empty()) {
            std::cout << "   👤 " << بيان.المؤلفون[0].إلى_نص() << "\n";
        }
        
        std::cout << "   📜 " << بيان.الترخيص << "\n";
        
        // الأذونات
        std::cout << "   🔐 الأذونات:\n";
        if (!بيان.الأذونات.الملفات.empty()) {
            std::cout << "      - ملفات: ";
            for (const auto& إ : بيان.الأذونات.الملفات) {
                std::cout << إ << " ";
            }
            std::cout << "\n";
        }
        if (!بيان.الأذونات.الشبكة.empty()) {
            std::cout << "      - شبكة: ";
            for (const auto& إ : بيان.الأذونات.الشبكة) {
                std::cout << إ << " ";
            }
            std::cout << "\n";
        }
        
        std::cout << "\n";
    }
};

