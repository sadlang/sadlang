/**
 * نوع الإضافة
 */
enum class نوع_إضافة {
    مكتبة,           // توفر دوال للاستخدام
    أداة,            // أداة سطر أوامر
    محلل_لغة,        // دعم لغة جديدة
    سمة,             // سمة للمحرر
    أخرى
};

/**
 * معلومات المؤلف
 */
struct مؤلف {
    std::string الاسم;
    std::string البريد;
    std::string الموقع;
    
    std::string إلى_نص() const {
        std::string نتيجة = الاسم;
        if (!البريد.empty()) {
            نتيجة += " <" + البريد + ">";
        }
        return نتيجة;
    }
};

/**
 * معلومات المستودع
 */
struct مستودع {
    std::string النوع;          // git, hg, svn
    std::string الرابط;
    std::string الفرع;
};

/**
 * تبعية إضافة
 */
struct تبعية_إضافة {
    std::string الاسم;
    std::string نطاق_الإصدار;    // مثل: ">=1.0.0 <2.0.0"
    bool اختيارية = false;
};

/**
 * أذونات الإضافة
 */
struct أذونات_بيان {
    // نظام الملفات
    std::vector<std::string> الملفات;     // قراءة، كتابة، حذف
    std::vector<std::string> المسارات;    // مسارات محددة مسموحة
    
    // الشبكة
    std::vector<std::string> الشبكة;      // http, socket, listen
    std::vector<std::string> النطاقات;    // نطاقات محددة
    
    // النظام
    std::vector<std::string> النظام;      // env, exec
    
    // الموارد
    size_t حد_الذاكرة_ميغابايت = 64;
    int حد_الخيوط = 4;
};

/**
 * دالة مُصدَّرة
 */
struct دالة_مُصدَّرة {
    std::string الاسم;
    std::string الوصف;
    std::vector<std::pair<std::string, std::string>> المعاملات;  // اسم، نوع
    std::string نوع_الإرجاع;
};

/**
 * نقطة الدخول
 */
struct نقطة_دخول {
    std::string الملف;           // الملف الرئيسي
    std::string الدالة;          // دالة البدء
    std::string نوع_التحميل;    // فوري، كسول، عند_الطلب
};

