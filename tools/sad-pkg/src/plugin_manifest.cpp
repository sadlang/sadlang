/**
 * بيان الإضافة الكامل
 * 
 * يحتوي كل المعلومات عن الإضافة
 */
class بيان_إضافة {
public:
    // ═══════════════════════════════════════
    // المعلومات الأساسية
    // ═══════════════════════════════════════
    
    std::string الاسم;
    std::string الإصدار;
    std::string الوصف;
    std::string الوصف_الطويل;
    نوع_إضافة النوع = نوع_إضافة::مكتبة;
    std::vector<std::string> الكلمات_المفتاحية;
    std::string الترخيص;
    
    // ═══════════════════════════════════════
    // المؤلف والمستودع
    // ═══════════════════════════════════════
    
    std::vector<مؤلف> المؤلفون;
    std::optional<مستودع> المستودع;
    std::string الصفحة_الرئيسية;
    std::string التوثيق;
    
    // ═══════════════════════════════════════
    // التوافق
    // ═══════════════════════════════════════
    
    std::string الحد_الأدنى_لغة_ص;    // مثل: "1.0.0"
    std::string الحد_الأقصى_لغة_ص;    // مثل: "2.0.0"
    std::vector<std::string> المنصات;  // windows, linux, macos, wasm
    
    // ═══════════════════════════════════════
    // التبعيات
    // ═══════════════════════════════════════
    
    std::vector<تبعية_إضافة> التبعيات;
    std::vector<تبعية_إضافة> تبعيات_التطوير;
    
    // ═══════════════════════════════════════
    // الأذونات
    // ═══════════════════════════════════════
    
    أذونات_بيان الأذونات;
    
    // ═══════════════════════════════════════
    // التصدير
    // ═══════════════════════════════════════
    
    std::vector<دالة_مُصدَّرة> الدوال_المُصدَّرة;
    نقطة_دخول نقطة_الدخول;
    
    // ═══════════════════════════════════════
    // التحقق
    // ═══════════════════════════════════════
    
    /**
     * التحقق من صحة البيان
     */
    struct نتيجة_تحقق {
        bool صالح;
        std::vector<std::string> أخطاء;
        std::vector<std::string> تحذيرات;
    };
    
    نتيجة_تحقق تحقق() const {
        نتيجة_تحقق نتيجة;
        نتيجة.صالح = true;
        
        // الحقول المطلوبة
        if (الاسم.empty()) {
            نتيجة.أخطاء.push_back("الاسم مطلوب");
            نتيجة.صالح = false;
        }
        
        if (الإصدار.empty()) {
            نتيجة.أخطاء.push_back("الإصدار مطلوب");
            نتيجة.صالح = false;
        } else if (!إصدار_صالح(الإصدار)) {
            نتيجة.أخطاء.push_back("صيغة الإصدار غير صالحة (استخدم: X.Y.Z)");
            نتيجة.صالح = false;
        }
        
        if (الوصف.empty()) {
            نتيجة.تحذيرات.push_back("يُنصح بإضافة وصف");
        }
        
        if (المؤلفون.empty()) {
            نتيجة.تحذيرات.push_back("يُنصح بذكر المؤلف");
        }
        
        if (الترخيص.empty()) {
            نتيجة.تحذيرات.push_back("يُنصح بتحديد الترخيص");
        }
        
        // تحقق من الأذونات
        if (الأذونات.النظام.size() > 0) {
            bool يتضمن_exec = false;
            for (const auto& إذن : الأذونات.النظام) {
                if (إذن == "exec") يتضمن_exec = true;
            }
            if (يتضمن_exec) {
                نتيجة.تحذيرات.push_back("إذن تنفيذ أوامر النظام خطير!");
            }
        }
        
        return نتيجة;
    }
    
    // ═══════════════════════════════════════
    // التسلسل
    // ═══════════════════════════════════════
    
    /**
     * تحويل إلى صيغة TOML
     */
    std::string إلى_toml() const {
        std::stringstream س;
        
        س << "# بيان إضافة لغة ص\n";
        س << "# تم توليده تلقائياً\n\n";
        
        // القسم الرئيسي
        س << "[إضافة]\n";
        س << "الاسم = \"" << الاسم << "\"\n";
        س << "الإصدار = \"" << الإصدار << "\"\n";
        
        if (!الوصف.empty()) {
            س << "الوصف = \"" << الوصف << "\"\n";
        }
        
        if (!الترخيص.empty()) {
            س << "الترخيص = \"" << الترخيص << "\"\n";
        }
        
        if (!الكلمات_المفتاحية.empty()) {
            س << "كلمات_مفتاحية = [";
            for (size_t i = 0; i < الكلمات_المفتاحية.size(); i++) {
                if (i > 0) س << ", ";
                س << "\"" << الكلمات_المفتاحية[i] << "\"";
            }
            س << "]\n";
        }
        
        // المؤلفون
        if (!المؤلفون.empty()) {
            س << "\n[مؤلفون]\n";
            for (const auto& م : المؤلفون) {
                س << "[[مؤلف]]\n";
                س << "الاسم = \"" << م.الاسم << "\"\n";
                if (!م.البريد.empty()) {
                    س << "البريد = \"" << م.البريد << "\"\n";
                }
            }
        }
        
        // التوافق
        س << "\n[توافق]\n";
        if (!الحد_الأدنى_لغة_ص.empty()) {
            س << "لغة_ص = \">=" << الحد_الأدنى_لغة_ص << "\"\n";
        }
        if (!المنصات.empty()) {
            س << "منصات = [";
            for (size_t i = 0; i < المنصات.size(); i++) {
                if (i > 0) س << ", ";
                س << "\"" << المنصات[i] << "\"";
            }
            س << "]\n";
        }
        
        // التبعيات
        if (!التبعيات.empty()) {
            س << "\n[تبعيات]\n";
            for (const auto& ت : التبعيات) {
                س << ت.الاسم << " = \"" << ت.نطاق_الإصدار << "\"\n";
            }
        }
        
        // الأذونات
        س << "\n[أذونات]\n";
        if (!الأذونات.الملفات.empty()) {
            س << "ملفات = [";
            for (size_t i = 0; i < الأذونات.الملفات.size(); i++) {
                if (i > 0) س << ", ";
                س << "\"" << الأذونات.الملفات[i] << "\"";
            }
            س << "]\n";
        }
        if (!الأذونات.الشبكة.empty()) {
            س << "شبكة = [";
            for (size_t i = 0; i < الأذونات.الشبكة.size(); i++) {
                if (i > 0) س << ", ";
                س << "\"" << الأذونات.الشبكة[i] << "\"";
            }
            س << "]\n";
        }
        س << "حد_الذاكرة_ميغابايت = " << الأذونات.حد_الذاكرة_ميغابايت << "\n";
        
        // التصدير
        if (!الدوال_المُصدَّرة.empty()) {
            س << "\n[تصدير]\n";
            س << "دوال = [";
            for (size_t i = 0; i < الدوال_المُصدَّرة.size(); i++) {
                if (i > 0) س << ", ";
                س << "\"" << الدوال_المُصدَّرة[i].الاسم << "\"";
            }
            س << "]\n";
        }
        
        // نقطة الدخول
        if (!نقطة_الدخول.الملف.empty()) {
            س << "\n[دخول]\n";
            س << "الملف = \"" << نقطة_الدخول.الملف << "\"\n";
            if (!نقطة_الدخول.الدالة.empty()) {
                س << "الدالة = \"" << نقطة_الدخول.الدالة << "\"\n";
            }
        }
        
        return س.str();
    }

private:
    bool إصدار_صالح(const std::string& إصدار) const {
        // صيغة بسيطة: X.Y.Z
        int نقاط = 0;
        for (char c : إصدار) {
            if (c == '.') نقاط++;
            else if (!std::isdigit(c)) return false;
        }
        return نقاط == 2;
    }
};

