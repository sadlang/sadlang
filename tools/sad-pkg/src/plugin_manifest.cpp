/**
 * محلل ملفات البيان
 */
class محلل_بيان {
public:
    /**
     * قراءة بيان من ملف
     */
    static std::optional<بيان_إضافة> من_ملف(const std::string& مسار) {
        std::ifstream ملف(مسار);
        if (!ملف.is_open()) {
            return std::nullopt;
        }
        
        std::stringstream محتوى;
        محتوى << ملف.rdbuf();
        
        return من_toml(محتوى.str());
    }
    
    /**
     * تحليل نص TOML
     */
    static std::optional<بيان_إضافة> من_toml(const std::string& نص) {
        // محلل TOML مُبسَّط
        // في التنفيذ الكامل، استخدم مكتبة TOML حقيقية
        
        بيان_إضافة بيان;
        
        std::string قسم_حالي;
        std::istringstream سطور(نص);
        std::string سطر;
        
        while (std::getline(سطور, سطر)) {
            // تجاهل التعليقات والأسطر الفارغة
            if (سطر.empty() || سطر[0] == '#') continue;
            
            // اكتشاف القسم
            if (سطر[0] == '[') {
                size_t نهاية = سطر.find(']');
                if (نهاية != std::string::npos) {
                    قسم_حالي = سطر.substr(1, نهاية - 1);
                }
                continue;
            }
            
            // تحليل القيمة
            size_t يساوي = سطر.find('=');
            if (يساوي == std::string::npos) continue;
            
            std::string مفتاح = قص_مسافات(سطر.substr(0, يساوي));
            std::string قيمة = قص_مسافات(سطر.substr(يساوي + 1));
            
            // إزالة علامات الاقتباس
            if (قيمة.size() >= 2 && قيمة.front() == '"' && قيمة.back() == '"') {
                قيمة = قيمة.substr(1, قيمة.size() - 2);
            }
            
            // تعيين القيم
            if (قسم_حالي == "إضافة") {
                if (مفتاح == "الاسم") بيان.الاسم = قيمة;
                else if (مفتاح == "الإصدار") بيان.الإصدار = قيمة;
                else if (مفتاح == "الوصف") بيان.الوصف = قيمة;
                else if (مفتاح == "الترخيص") بيان.الترخيص = قيمة;
            }
            else if (قسم_حالي == "توافق") {
                if (مفتاح == "لغة_ص") {
                    // تحليل نطاق الإصدار
                    بيان.الحد_الأدنى_لغة_ص = قيمة;
                }
            }
            else if (قسم_حالي == "أذونات") {
                if (مفتاح == "حد_الذاكرة_ميغابايت") {
                    بيان.الأذونات.حد_الذاكرة_ميغابايت = std::stoul(قيمة);
                }
            }
            else if (قسم_حالي == "دخول") {
                if (مفتاح == "الملف") بيان.نقطة_الدخول.الملف = قيمة;
                else if (مفتاح == "الدالة") بيان.نقطة_الدخول.الدالة = قيمة;
            }
        }
        
        return بيان;
    }
    
    /**
     * حفظ بيان إلى ملف
     */
    static bool إلى_ملف(const بيان_إضافة& بيان, const std::string& مسار) {
        std::ofstream ملف(مسار);
        if (!ملف.is_open()) {
            return false;
        }
        
        ملف << بيان.إلى_toml();
        return true;
    }

private:
    static std::string قص_مسافات(const std::string& نص) {
        size_t بداية = نص.find_first_not_of(" \t");
        size_t نهاية = نص.find_last_not_of(" \t");
        
        if (بداية == std::string::npos) return "";
        return نص.substr(بداية, نهاية - بداية + 1);
    }
};

