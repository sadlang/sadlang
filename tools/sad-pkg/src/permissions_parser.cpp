/**
 * بيان أذونات البرنامج الكامل
 */
class بيان_أذونات {
public:
    /**
     * إنشاء بيان فارغ (لا أذونات)
     */
    بيان_أذونات() = default;
    
    /**
     * إضافة مجموعة أذونات
     */
    void أضف_مجموعة(مجموعة_أذونات مجموعة) {
        m_مجموعات[مجموعة.الفئة] = std::move(مجموعة);
    }
    
    /**
     * الحصول على مجموعة
     */
    const مجموعة_أذونات* احصل_على_مجموعة(فئة_إذن فئة) const {
        auto it = m_مجموعات.find(فئة);
        if (it == m_مجموعات.end()) return nullptr;
        return &it->second;
    }
    
    /**
     * التحقق من إذن
     */
    bool مسموح(فئة_إذن فئة, const std::string& هدف, نوع_عملية عملية) const {
        auto* مجموعة = احصل_على_مجموعة(فئة);
        if (!مجموعة) return false;
        return مجموعة->مسموح(هدف, عملية);
    }
    
    /**
     * التحقق من إذن ملف
     */
    bool يسمح_ملف(const std::string& مسار, نوع_عملية عملية) const {
        return مسموح(فئة_إذن::ملفات, مسار, عملية);
    }
    
    /**
     * التحقق من إذن شبكة
     */
    bool يسمح_شبكة(const std::string& url) const {
        return مسموح(فئة_إذن::شبكة, url, نوع_عملية::الكل);
    }
    
    /**
     * التحقق من إذن بسيط (بدون هدف)
     */
    bool فعَّال(فئة_إذن فئة) const {
        auto* مجموعة = احصل_على_مجموعة(فئة);
        return مجموعة && مجموعة->مفعَّلة;
    }
    
    /**
     * قائمة الأذونات المطلوبة
     */
    std::vector<فئة_إذن> الأذونات_المطلوبة() const {
        std::vector<فئة_إذن> نتيجة;
        for (const auto& [فئة, مجموعة] : m_مجموعات) {
            if (مجموعة.مفعَّلة) {
                نتيجة.push_back(فئة);
            }
        }
        return نتيجة;
    }
    
    /**
     * ملخص نصي
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "╔════════════════════════════════════════════╗\n"
           << "║           بيان الأذونات                    ║\n"
           << "╠════════════════════════════════════════════╣\n";
        
        for (const auto& [فئة, مجموعة] : m_مجموعات) {
            ss << "║ " << فئة_إلى_نص(فئة) << ": ";
            if (مجموعة.مفعَّلة) {
                ss << "✅ مفعَّل";
                if (!مجموعة.القواعد.empty()) {
                    ss << " (" << مجموعة.القواعد.size() << " قاعدة)";
                }
            } else {
                ss << "❌ معطَّل";
            }
            ss << "\n";
            
            for (const auto& قاعدة : مجموعة.القواعد) {
                ss << "║   └─ " << قاعدة.إلى_نص() << "\n";
            }
        }
        
        ss << "╚════════════════════════════════════════════╝";
        return ss.str();
    }
    
private:
    std::unordered_map<فئة_إذن, مجموعة_أذونات> m_مجموعات;
};

