/**
 * محلل TOML بسيط للأذونات
 * 
 * للمبتدئ: هذا يقرأ ملف ص.toml ويستخرج الأذونات
 */
class محلل_أذونات {
public:
    /**
     * نتيجة التحليل
     */
    struct نتيجة_تحليل {
        bool نجح = false;
        بيان_أذونات البيان;
        std::vector<std::string> أخطاء;
        std::vector<std::string> تحذيرات;
    };
    
    /**
     * تحليل ملف ص.toml
     */
    نتيجة_تحليل حلل_ملف(const std::string& مسار) {
        نتيجة_تحليل نتيجة;
        
        // قراءة الملف
        std::ifstream ملف(مسار);
        if (!ملف) {
            نتيجة.أخطاء.push_back("تعذر فتح الملف: " + مسار);
            return نتيجة;
        }
        
        std::string محتوى((std::istreambuf_iterator<char>(ملف)),
                          std::istreambuf_iterator<char>());
        
        return حلل_نص(محتوى);
    }
    
    /**
     * تحليل نص TOML
     */
    نتيجة_تحليل حلل_نص(const std::string& محتوى) {
        نتيجة_تحليل نتيجة;
        m_سطر_حالي = 0;
        m_قسم_حالي = "";
        
        // تقسيم إلى أسطر
        std::istringstream stream(محتوى);
        std::string سطر;
        
        bool في_قسم_أذونات = false;
        
        while (std::getline(stream, سطر)) {
            m_سطر_حالي++;
            
            // تجاهل الأسطر الفارغة والتعليقات
            سطر = احذف_المسافات(سطر);
            if (سطر.empty() || سطر[0] == '#') continue;
            
            // فحص بداية قسم
            if (سطر[0] == '[') {
                auto قسم = استخرج_اسم_القسم(سطر);
                m_قسم_حالي = قسم;
                في_قسم_أذونات = (قسم == "أذونات" || قسم == "permissions");
                continue;
            }
            
            // تحليل الأذونات
            if (في_قسم_أذونات) {
                auto خطأ = حلل_سطر_إذن(سطر, نتيجة.البيان);
                if (!خطأ.empty()) {
                    نتيجة.أخطاء.push_back("سطر " + std::to_string(m_سطر_حالي) + ": " + خطأ);
                }
            }
        }
        
        نتيجة.نجح = نتيجة.أخطاء.empty();
        return نتيجة;
    }
    
private:
    int m_سطر_حالي = 0;
    std::string m_قسم_حالي;
    
    /**
     * إزالة المسافات البادئة والنهائية
     */
    std::string احذف_المسافات(const std::string& نص) {
        size_t بداية = نص.find_first_not_of(" \t\r\n");
        if (بداية == std::string::npos) return "";
        size_t نهاية = نص.find_last_not_of(" \t\r\n");
        return نص.substr(بداية, نهاية - بداية + 1);
    }
    
    /**
     * استخراج اسم القسم من [اسم]
     */
    std::string استخرج_اسم_القسم(const std::string& سطر) {
        size_t بداية = سطر.find('[');
        size_t نهاية = سطر.find(']');
        if (بداية == std::string::npos || نهاية == std::string::npos) return "";
        return احذف_المسافات(سطر.substr(بداية + 1, نهاية - بداية - 1));
    }
    
    /**
     * تحليل سطر إذن
     */
    std::string حلل_سطر_إذن(const std::string& سطر, بيان_أذونات& بيان) {
        // البحث عن =
        size_t موقع_يساوي = سطر.find('=');
        if (موقع_يساوي == std::string::npos) {
            return "صيغة غير صحيحة (مطلوب =)";
        }
        
        std::string مفتاح = احذف_المسافات(سطر.substr(0, موقع_يساوي));
        std::string قيمة = احذف_المسافات(سطر.substr(موقع_يساوي + 1));
        
        // تحديد الفئة
        auto فئة_opt = نص_إلى_فئة(مفتاح);
        if (!فئة_opt) {
            return "فئة إذن غير معروفة: " + مفتاح;
        }
        
        فئة_إذن الفئة = *فئة_opt;
        مجموعة_أذونات مجموعة;
        مجموعة.الفئة = الفئة;
        
        // تحليل القيمة
        if (قيمة == "صحيح" || قيمة == "true") {
            // إذن كامل
            مجموعة.مفعَّلة = true;
            قاعدة_إذن قاعدة;
            قاعدة.الفئة = الفئة;
            قاعدة.العملية = نوع_عملية::الكل;
            قاعدة.النمط = "*";
            مجموعة.أضف_قاعدة(قاعدة);
        } else if (قيمة == "خطأ" || قيمة == "false") {
            // إذن معطَّل
            مجموعة.مفعَّلة = false;
        } else if (قيمة[0] == '[') {
            // مصفوفة قواعد
            auto قواعد = حلل_مصفوفة(قيمة);
            for (const auto& نص_قاعدة : قواعد) {
                قاعدة_إذن قاعدة = حلل_قاعدة(الفئة, نص_قاعدة);
                مجموعة.أضف_قاعدة(قاعدة);
            }
        } else {
            // قاعدة مفردة
            قاعدة_إذن قاعدة = حلل_قاعدة(الفئة, قيمة);
            مجموعة.أضف_قاعدة(قاعدة);
        }
        
        بيان.أضف_مجموعة(مجموعة);
        return "";  // نجاح
    }
    
    /**
     * تحليل مصفوفة TOML
     */
    std::vector<std::string> حلل_مصفوفة(const std::string& نص) {
        std::vector<std::string> نتيجة;
        
        // إزالة [ و ]
        std::string محتوى = نص.substr(1, نص.length() - 2);
        
        // تقسيم بالفواصل
        std::stringstream ss(محتوى);
        std::string عنصر;
        
        while (std::getline(ss, عنصر, ',')) {
            عنصر = احذف_المسافات(عنصر);
            
            // إزالة علامات الاقتباس
            if (عنصر.size() >= 2 && عنصر[0] == '"' && عنصر.back() == '"') {
                عنصر = عنصر.substr(1, عنصر.size() - 2);
            }
            
            if (!عنصر.empty()) {
                نتيجة.push_back(عنصر);
            }
        }
        
        return نتيجة;
    }
    
    /**
     * تحليل قاعدة إذن من نص
     * 
     * صيغ مدعومة:
     * - "قراءة:./data/*"
     * - "كتابة:./output/*"
     * - "https://api.example.com/*"
     * - "./files/*"
     */
    قاعدة_إذن حلل_قاعدة(فئة_إذن فئة, const std::string& نص) {
        قاعدة_إذن قاعدة;
        قاعدة.الفئة = فئة;
        
        // البحث عن :
        size_t موقع_نقطتين = نص.find(':');
        
        if (موقع_نقطتين != std::string::npos && موقع_نقطتين < 10) {
            // لدينا عملية:نمط
            std::string عملية_نص = نص.substr(0, موقع_نقطتين);
            قاعدة.النمط = نص.substr(موقع_نقطتين + 1);
            
            // تحديد العملية
            if (عملية_نص == "قراءة" || عملية_نص == "read") {
                قاعدة.العملية = نوع_عملية::قراءة;
            } else if (عملية_نص == "كتابة" || عملية_نص == "write") {
                قاعدة.العملية = نوع_عملية::كتابة;
            } else if (عملية_نص == "تنفيذ" || عملية_نص == "execute") {
                قاعدة.العملية = نوع_عملية::تنفيذ;
            } else if (عملية_نص == "إنشاء" || عملية_نص == "create") {
                قاعدة.العملية = نوع_عملية::إنشاء;
            } else if (عملية_نص == "حذف" || عملية_نص == "delete") {
                قاعدة.العملية = نوع_عملية::حذف;
            } else {
                // ليست عملية، ربما URL
                قاعدة.العملية = نوع_عملية::الكل;
                قاعدة.النمط = نص;
            }
        } else {
            // نمط فقط
            قاعدة.العملية = نوع_عملية::الكل;
            قاعدة.النمط = نص;
        }
        
        return قاعدة;
    }
};

