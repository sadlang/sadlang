/**
 * قاعدة إذن واحدة
 * 
 * مثال: "قراءة:./data/*"
 *   - العملية: قراءة
 *   - النمط: ./data/*
 */
struct قاعدة_إذن {
    فئة_إذن الفئة;
    نوع_عملية العملية = نوع_عملية::الكل;
    std::string النمط;        // glob pattern
    bool مفعَّل = true;
    std::string تعليق;
    
    /**
     * التحقق من تطابق
     */
    bool يطابق(const std::string& هدف) const {
        if (!مفعَّل) return false;
        if (النمط.empty() || النمط == "*") return true;
        
        // تحويل glob إلى regex
        std::string regex_pattern;
        for (char c : النمط) {
            switch (c) {
                case '*':
                    if (regex_pattern.back() == '*') {
                        regex_pattern.pop_back();
                        regex_pattern += ".*";  // ** = أي شيء
                    } else {
                        regex_pattern += "[^/]*";  // * = أي شيء باستثناء /
                    }
                    break;
                case '?':
                    regex_pattern += ".";
                    break;
                case '.':
                case '(':
                case ')':
                case '[':
                case ']':
                case '{':
                case '}':
                case '+':
                case '^':
                case '$':
                case '|':
                case '\\':
                    regex_pattern += '\\';
                    regex_pattern += c;
                    break;
                default:
                    regex_pattern += c;
            }
        }
        
        try {
            std::regex re(regex_pattern);
            return std::regex_match(هدف, re);
        } catch (...) {
            return هدف == النمط;  // fallback للمطابقة المباشرة
        }
    }
    
    /**
     * تحويل إلى نص
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << نوع_عملية_إلى_نص(العملية) << ":" << النمط;
        return ss.str();
    }
};

