/**
 * مجموعة أذونات لفئة معينة
 */
struct مجموعة_أذونات {
    فئة_إذن الفئة;
    bool مفعَّلة = false;       // هل الفئة كلها مفعَّلة؟
    std::vector<قاعدة_إذن> القواعد;
    
    /**
     * إضافة قاعدة
     */
    void أضف_قاعدة(قاعدة_إذن قاعدة) {
        قاعدة.الفئة = الفئة;
        القواعد.push_back(std::move(قاعدة));
        مفعَّلة = true;
    }
    
    /**
     * التحقق من إذن
     */
    bool مسموح(const std::string& هدف, نوع_عملية عملية) const {
        if (!مفعَّلة) return false;
        
        for (const auto& قاعدة : القواعد) {
            if (قاعدة.العملية == نوع_عملية::الكل || قاعدة.العملية == عملية) {
                if (قاعدة.يطابق(هدف)) {
                    return true;
                }
            }
        }
        
        return false;
    }
};

