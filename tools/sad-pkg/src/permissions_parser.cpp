/**
 * فئة الإذن
 */
enum class فئة_إذن {
    ملفات,       // الوصول للملفات
    شبكة,        // الاتصال بالإنترنت
    نظام,        // أوامر النظام
    كاميرا,      // الكاميرا
    ميكروفون,    // الميكروفون
    موقع,        // GPS / الموقع الجغرافي
    إشعارات,     // الإشعارات
    حافظة,       // الـ Clipboard
    بيئة,        // متغيرات البيئة
    عملية,       // العمليات الفرعية
};

/**
 * تحويل فئة إلى نص
 */
