/**
 * إنشاء بيان أذونات افتراضي للتطوير
 */
inline بيان_أذونات أذونات_تطوير() {
    بيان_أذونات بيان;
    
    // ملفات: قراءة وكتابة محلية
    مجموعة_أذونات ملفات;
    ملفات.الفئة = فئة_إذن::ملفات;
    ملفات.مفعَّلة = true;
    
    قاعدة_إذن قراءة_محلية;
    قراءة_محلية.الفئة = فئة_إذن::ملفات;
    قراءة_محلية.العملية = نوع_عملية::قراءة;
    قراءة_محلية.النمط = "./**";
    ملفات.القواعد.push_back(قراءة_محلية);
    
    قاعدة_إذن كتابة_محلية;
    كتابة_محلية.الفئة = فئة_إذن::ملفات;
    كتابة_محلية.العملية = نوع_عملية::كتابة;
    كتابة_محلية.النمط = "./**";
    ملفات.القواعد.push_back(كتابة_محلية);
    
    بيان.أضف_مجموعة(ملفات);
    
    // شبكة: localhost فقط
    مجموعة_أذونات شبكة;
    شبكة.الفئة = فئة_إذن::شبكة;
    شبكة.مفعَّلة = true;
    
    قاعدة_إذن محلي;
    محلي.الفئة = فئة_إذن::شبكة;
    محلي.النمط = "http://localhost:*";
    شبكة.القواعد.push_back(محلي);
    
    بيان.أضف_مجموعة(شبكة);
    
    return بيان;
}

