extern "C" {

int sad_contract_command_main(int argc, const char* argv[]) {
    using namespace sad::tools;
    
    محلل_أوامر_العقود محلل;
    auto خيارات = محلل.حلل(argc, argv);
    
    منفذ_أوامر_العقود منفذ(خيارات);
    return منفذ.نفّذ();
}

} // extern "C"
