/**
 * محلل أوامر CLI للصوت
 */
class محلل_أوامر_الصوت {
public:
    خيارات_الصوت حلّل(int argc, char* argv[]) {
        خيارات_الصوت خيارات;
        
        for (int i = 1; i < argc; ++i) {
            std::string arg = argv[i];
            
            if (arg == "--مساعدة" || arg == "-م" || arg == "--help" || arg == "-h") {
                خيارات.مساعدة = true;
            }
            else if (arg == "--ملف" || arg == "-ف" || arg == "--file" || arg == "-f") {
                if (i + 1 < argc) {
                    خيارات.ملف = argv[++i];
                }
            }
            else if (arg == "--لهجة" || arg == "-ل" || arg == "--dialect" || arg == "-d") {
                if (i + 1 < argc) {
                    خيارات.لهجة = argv[++i];
                }
            }
            else if (arg == "--وضع" || arg == "-و" || arg == "--mode" || arg == "-m") {
                if (i + 1 < argc) {
                    خيارات.وضع = argv[++i];
                }
            }
            else if (arg == "--غير-تفاعلي" || arg == "--non-interactive") {
                خيارات.تفاعلي = false;
            }
            else if (arg == "--مفصّل" || arg == "-v" || arg == "--verbose") {
                خيارات.مفصّل = true;
            }
            else if (arg == "--مهلة" || arg == "-ت" || arg == "--timeout" || arg == "-t") {
                if (i + 1 < argc) {
                    خيارات.مهلة = std::stoi(argv[++i]);
                }
            }
            else if (arg == "--جهاز" || arg == "--device") {
                if (i + 1 < argc) {
                    خيارات.جهاز = argv[++i];
                }
            }
            else if (arg == "--معدل" || arg == "--rate") {
                if (i + 1 < argc) {
                    خيارات.معدل = std::stoi(argv[++i]);
                }
            }
            else if (!arg.empty() && arg[0] != '-') {
                // ملف بدون علم
                if (خيارات.ملف.empty()) {
                    خيارات.ملف = arg;
                }
            }
        }
        
        return خيارات;
    }
};

