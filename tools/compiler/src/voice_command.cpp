/**
 * محاكاة محرك STT
 */
class محرك_STT_CLI {
private:
    std::string لهجة_;
    std::atomic<bool> يستمع_{false};
    std::vector<std::function<void(const std::string&, bool)>> مستمعون_;
    
public:
    محرك_STT_CLI(const std::string& لهجة = "فصحى") : لهجة_(لهجة) {}
    
    bool ابدأ() {
        يستمع_ = true;
        return true;
    }
    
    void أوقف() {
        يستمع_ = false;
    }
    
    bool يستمع() const { return يستمع_; }
    
    void أضف_مستمع(std::function<void(const std::string&, bool)> مستمع) {
        مستمعون_.push_back(std::move(مستمع));
    }
    
    // محاكاة: في التطبيق الحقيقي، هذا يتصل بنظام STT
    void محاكاة_إدخال(const std::string& نص) {
        if (!يستمع_) return;
        
        for (const auto& مستمع : مستمعون_) {
            مستمع(نص, false);  // false = مؤكد
        }
    }
};

/**
 * معالج الأوامر الصوتية
 */
class معالج_الأوامر {
public:
    std::string عالج(const std::string& نص) {
        std::string كود;
        
        // أنشئ دالة
        if (نص.find("أنشئ دالة") != std::string::npos ||
            نص.find("اعمل دالة") != std::string::npos) {
            std::string اسم = استخرج_اسم(نص, "اسمها");
            if (اسم.empty()) اسم = استخرج_اسم(نص, "دالة");
            كود = "دالة " + اسم + "()\n";
        }
        // أنشئ متغير
        else if (نص.find("أنشئ متغير") != std::string::npos ||
                 نص.find("أضف متغير") != std::string::npos) {
            std::string اسم = استخرج_اسم(نص, "اسمه");
            if (اسم.empty()) اسم = استخرج_اسم(نص, "متغير");
            كود = "متغير " + اسم + "\n";
        }
        // لو
        else if (نص.find("لو ") == 0 || نص.find("إذا ") == 0) {
            كود = نص + "\n";
        }
        // وإلا
        else if (نص.find("وإلا") != std::string::npos) {
            كود = "وإلا\n";
        }
        // نهاية
        else if (نص.find("نهاية") != std::string::npos ||
                 نص.find("أغلق") != std::string::npos) {
            كود = "نهاية\n";
        }
        // أرجع
        else if (نص.find("أرجع") != std::string::npos) {
            std::string قيمة = استخرج_بعد(نص, "أرجع");
            كود = "أرجع " + قيمة + "\n";
        }
        // تعليق
        else if (نص.find("تعليق") != std::string::npos) {
            std::string محتوى = استخرج_بعد(نص, "تعليق");
            كود = "// " + محتوى + "\n";
        }
        // سطر جديد
        else if (نص.find("سطر جديد") != std::string::npos) {
            كود = "\n";
        }
        else {
            // نص عادي
            كود = نص + "\n";
        }
        
        return كود;
    }
    
private:
    std::string استخرج_اسم(const std::string& نص, const std::string& كلمة) {
        size_t pos = نص.find(كلمة);
        if (pos == std::string::npos) return "";
        
        pos += كلمة.length();
        while (pos < نص.length() && نص[pos] == ' ') pos++;
        
        std::string اسم;
        while (pos < نص.length() && نص[pos] != ' ' && نص[pos] != '\n') {
            اسم += نص[pos++];
        }
        
        return اسم;
    }
    
    std::string استخرج_بعد(const std::string& نص, const std::string& كلمة) {
        size_t pos = نص.find(كلمة);
        if (pos == std::string::npos) return "";
        
        pos += كلمة.length();
        while (pos < نص.length() && نص[pos] == ' ') pos++;
        
        return نص.substr(pos);
    }
};

