int voice_command_main(int argc, char* argv[]) {
    محلل_أوامر_الصوت محلل;
    خيارات_الصوت خيارات = محلل.حلّل(argc, argv);
    
    if (خيارات.مساعدة) {
        اعرض_المساعدة();
        return 0;
    }
    
    جلسة_تفاعلية جلسة(خيارات);
    return جلسة.شغّل();
}

