/**
 * جلسة صوت تفاعلية
 */
class جلسة_تفاعلية {
private:
    خيارات_الصوت خيارات_;
    محرك_STT_CLI محرك_;
    معالج_الأوامر معالج_;
    std::string كود_متراكم_;
    std::ofstream ملف_إخراج_;
    
public:
    جلسة_تفاعلية(const خيارات_الصوت& خيارات) 
        : خيارات_(خيارات), محرك_(خيارات.لهجة) {
        
        if (!خيارات_.ملف.empty()) {
            ملف_إخراج_.open(خيارات_.ملف);
        }
    }
    
    ~جلسة_تفاعلية() {
        if (ملف_إخراج_.is_open()) {
            ملف_إخراج_.close();
        }
    }
    
    int شغّل() {
        عرض_ترحيب();
        
        // بدء المحرك
        if (!محرك_.ابدأ()) {
            std::cerr << "❌ فشل في بدء محرك الصوت\n";
            return 1;
        }
        
        std::cout << "🎤 جاهز للاستماع... (اكتب 'أوقف' للإنهاء)\n\n";
        
        // حلقة الإدخال
        std::string إدخال;
        while (true) {
            std::cout << "🎤 ";
            std::getline(std::cin, إدخال);
            
            if (إدخال == "أوقف" || إدخال == "stop" || إدخال == "exit") {
                break;
            }
            
            if (إدخال == "احفظ" || إدخال == "save") {
                احفظ();
                continue;
            }
            
            if (إدخال == "أظهر" || إدخال == "show") {
                أظهر_الكود();
                continue;
            }
            
            if (إدخال == "امسح" || إدخال == "clear") {
                امسح();
                continue;
            }
            
            if (إدخال == "تراجع" || إدخال == "undo") {
                تراجع();
                continue;
            }
            
            // معالجة الأمر
            std::string كود = معالج_.عالج(إدخال);
            
            if (!كود.empty()) {
                كود_متراكم_ += كود;
                
                if (خيارات_.مفصّل) {
                    std::cout << "📝 " << كود;
                }
                
                // كتابة للملف إذا كان مفتوحاً
                if (ملف_إخراج_.is_open()) {
                    ملف_إخراج_ << كود;
                    ملف_إخراج_.flush();
                }
            }
        }
        
        محرك_.أوقف();
        
        // عرض الكود النهائي
        if (!كود_متراكم_.empty()) {
            std::cout << "\n📄 الكود النهائي:\n";
            std::cout << "═══════════════════════════════════════\n";
            std::cout << كود_متراكم_;
            std::cout << "═══════════════════════════════════════\n";
        }
        
        return 0;
    }
    
private:
    void عرض_ترحيب() {
        std::cout << "\n";
        std::cout << "╔═══════════════════════════════════════════════════════╗\n";
        std::cout << "║              🎤 ص صوت - البرمجة الصوتية              ║\n";
        std::cout << "╚═══════════════════════════════════════════════════════╝\n\n";
        
        std::cout << "📌 اللهجة: " << خيارات_.لهجة << "\n";
        std::cout << "📌 الوضع: " << خيارات_.وضع << "\n";
        
        if (!خيارات_.ملف.empty()) {
            std::cout << "📌 الملف: " << خيارات_.ملف << "\n";
        }
        
        std::cout << "\n";
        std::cout << "💡 أوامر خاصة:\n";
        std::cout << "   أوقف  - إنهاء الجلسة\n";
        std::cout << "   احفظ  - حفظ الكود\n";
        std::cout << "   أظهر  - عرض الكود الحالي\n";
        std::cout << "   امسح  - مسح الكود\n";
        std::cout << "   تراجع - التراجع عن آخر أمر\n\n";
    }
    
    void احفظ() {
        if (خيارات_.ملف.empty()) {
            std::cout << "⚠️ لم يُحدد ملف للحفظ\n";
            return;
        }
        
        std::ofstream ملف(خيارات_.ملف);
        if (ملف.is_open()) {
            ملف << كود_متراكم_;
            ملف.close();
            std::cout << "✅ تم الحفظ في " << خيارات_.ملف << "\n";
        } else {
            std::cout << "❌ فشل في الحفظ\n";
        }
    }
    
    void أظهر_الكود() {
        std::cout << "\n📄 الكود الحالي:\n";
        std::cout << "───────────────────────────────────────\n";
        std::cout << كود_متراكم_;
        std::cout << "───────────────────────────────────────\n\n";
    }
    
    void امسح() {
        كود_متراكم_.clear();
        std::cout << "🗑️ تم مسح الكود\n";
    }
    
    void تراجع() {
        // إزالة آخر سطر
        size_t pos = كود_متراكم_.rfind('\n', كود_متراكم_.length() - 2);
        if (pos != std::string::npos) {
            كود_متراكم_ = كود_متراكم_.substr(0, pos + 1);
            std::cout << "↩️ تم التراجع\n";
        } else {
            كود_متراكم_.clear();
            std::cout << "↩️ تم مسح الكل\n";
        }
    }
};

