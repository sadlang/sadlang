    // ============== أمر التشغيل ==============
    
    int أمر_تشغيل(const std::vector<std::string>& معاملات) {
        std::cout << ألوان::أخضر << "⟳ تشغيل تطبيق XR...\n" << ألوان::إعادة;
        
        std::string ملف;
        std::string جهاز = "simulator";
        
        for (size_t i = 0; i < معاملات.size(); i++) {
            const auto& م = معاملات[i];
            if ((م == "-d" || م == "--جهاز") && i + 1 < معاملات.size()) {
                جهاز = معاملات[++i];
            } else if (!م.empty() && م[0] != '-') {
                ملف = م;
            }
        }
        
        if (ملف.empty()) {
            // البحث عن ملف البداية الافتراضي
            ملف = "main.ص";
        }
        
        std::cout << "  📁 الملف: " << ملف << "\n";
        std::cout << "  🎮 الجهاز: " << جهاز << "\n\n";
        
        // شريط تقدم التحميل
        std::cout << "  جاري التحميل: [";
        for (int i = 0; i < 30; i++) {
            std::cout << ألوان::أخضر << "█" << ألوان::إعادة;
        }
        std::cout << "] 100%\n\n";
        
        std::cout << ألوان::أخضر << "✓ " << ألوان::إعادة 
                  << "التطبيق يعمل. اضغط Ctrl+C للإيقاف.\n";
        
        return 0;
    }
    
