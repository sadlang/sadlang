    // ============== أمر الأجهزة ==============
    
    int أمر_أجهزة(const std::vector<std::string>& معاملات) {
        std::cout << ألوان::عريض << "\n╔════════════════════════════════════════════════════════════════════════╗\n";
        std::cout << "║                        أجهزة XR المتاحة                                 ║\n";
        std::cout << "╠════════════════════════════════════════════════════════════════════════╣\n" << ألوان::إعادة;
        
        const auto& أجهزة = مدير_أجهزة_.قائمة_الأجهزة();
        
        for (const auto& ج : أجهزة) {
            std::string حالة = ج.متصل ? 
                (std::string(ألوان::أخضر) + "● متصل" + ألوان::إعادة) :
                (std::string(ألوان::أصفر) + "○ غير متصل" + ألوان::إعادة);
            
            std::string نوع;
            switch (ج.النوع) {
                case نوع_جهاز_XR::VR_متصل: نوع = "VR (PC)"; break;
                case نوع_جهاز_XR::VR_مستقل: نوع = "VR (مستقل)"; break;
                case نوع_جهاز_XR::AR_هاتف: نوع = "AR (هاتف)"; break;
                case نوع_جهاز_XR::AR_نظارات: نوع = "AR (نظارات)"; break;
                case نوع_جهاز_XR::MR_مختلط: نوع = "MR"; break;
            }
            
            std::cout << "║ " << حالة << "  ";
            std::cout << std::left;
            printf("%-20s │ %-10s │ %s\n", 
                   ج.الاسم.c_str(), نوع.c_str(), ج.الشركة.c_str());
            
            if (وضع_مطول_) {
                std::cout << "║         الدقة: " << ج.عرض_العين << "x" << ج.ارتفاع_العين;
                std::cout << " │ " << ج.معدل_التحديث << "Hz";
                std::cout << " │ FOV: " << ج.مجال_الرؤية << "°\n";
                
                std::cout << "║         الميزات: ";
                if (ج.تتبع_اليد) std::cout << "✓يد ";
                if (ج.تتبع_العين) std::cout << "✓عين ";
                if (ج.نفاذية) std::cout << "✓نفاذية";
                std::cout << "\n";
            }
        }
        
        std::cout << "╚════════════════════════════════════════════════════════════════════════╝\n\n";
        
        return 0;
    }
    
