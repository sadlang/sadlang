int sad_xr_cli(const char* أمر) {
    // تحليل الأمر كسطر واحد
    std::vector<std::string> أجزاء;
    std::string جزء;
    
    for (char c : std::string(أمر)) {
        if (c == ' ') {
            if (!جزء.empty()) {
                أجزاء.push_back(جزء);
                جزء.clear();
            }
        } else {
            جزء += c;
        }
    }
    if (!جزء.empty()) {
        أجزاء.push_back(جزء);
    }
    
    std::vector<char*> argv;
    argv.push_back(const_cast<char*>("xr"));
    for (auto& ج : أجزاء) {
        argv.push_back(const_cast<char*>(ج.c_str()));
    }
    
    return sad_xr_main(static_cast<int>(argv.size()), argv.data());
}

