extern "C" {

int sad_distributed_command_main(int argc, const char* argv[]) {
    using namespace sad::tools;
    
    محلل_أوامر_موزع محلل;
    auto خيارات = محلل.حلل(argc, argv);
    
    منفذ_أوامر_موزع منفذ(خيارات);
    return منفذ.نفّذ();
}

} // extern "C"
