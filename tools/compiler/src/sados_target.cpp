struct إعدادات_بناء_صOS {
    جهاز_صOS الجهاز;
    std::string مسار_الإخراج;
    std::string اسم_المشروع;
    bool وضع_التصحيح;
    bool تضمين_WiFi;
    bool تضمين_Bluetooth;
    bool تضمين_الرسومات;
    uint32_t حجم_المكدس;        // بالبايت
    uint32_t حجم_الكومة;        // بالبايت
    std::vector<std::string> ملفات_المصدر;
    std::vector<std::string> مكتبات_إضافية;
    
    إعدادات_بناء_صOS() :
        الجهاز(جهاز_صOS::ESP32),
        مسار_الإخراج("./build"),
        اسم_المشروع("مشروع_صOS"),
        وضع_التصحيح(true),
        تضمين_WiFi(false),
        تضمين_Bluetooth(false),
        تضمين_الرسومات(false),
        حجم_المكدس(8192),
        حجم_الكومة(32768) {}
};

// ==========================================================
// 📌 مولّد البناء
// ==========================================================

class مولّد_بناء_صOS {
private:
    إعدادات_بناء_صOS الإعدادات_;
    const إعدادات_جهاز* معلومات_الجهاز_;

public:
    مولّد_بناء_صOS() : معلومات_الجهاز_(nullptr) {}
    
    bool هيّئ(const إعدادات_بناء_صOS& الإعدادات) {
        الإعدادات_ = الإعدادات;
        معلومات_الجهاز_ = قاعدة_الأجهزة::أحضر().أحضر_جهاز(الإعدادات.الجهاز);
        
        if (معلومات_الجهاز_ == nullptr) {
            std::cerr << "خطأ: جهاز غير معروف" << std::endl;
            return false;
        }
        
        return true;
    }
    
    // =======================================================
    // 📌 توليد CMakeLists.txt
    // =======================================================
    
    std::string ولّد_CMakeLists() {
        std::string محتوى;
        
        محتوى += "# مشروع صOS - توليد تلقائي\n";
        محتوى += "cmake_minimum_required(VERSION 3.16)\n\n";
        
        // إعدادات خاصة بالجهاز
        if (معلومات_الجهاز_->SDK == "ESP-IDF") {
            محتوى += "include($ENV{IDF_PATH}/tools/cmake/project.cmake)\n";
        } else if (معلومات_الجهاز_->SDK == "Pico SDK") {
            محتوى += "include($ENV{PICO_SDK_PATH}/pico_sdk_init.cmake)\n";
        }
        
        محتوى += "project(" + الإعدادات_.اسم_المشروع + " C CXX ASM)\n\n";
        
        // الملفات المصدرية
        محتوى += "set(SOURCES\n";
        for (const auto& ملف : الإعدادات_.ملفات_المصدر) {
            محتوى += "    " + ملف + "\n";
        }
        محتوى += ")\n\n";
        
        // إعدادات المترجم
        محتوى += "add_compile_options(\n";
        for (const auto& علم : معلومات_الجهاز_->أعلام_إضافية) {
            محتوى += "    " + علم + "\n";
        }
        if (الإعدادات_.وضع_التصحيح) {
            محتوى += "    -g\n    -O0\n";
        } else {
            محتوى += "    -Os\n";  // تحسين للحجم
        }
        محتوى += ")\n\n";
        
        // التعريفات
        محتوى += "add_definitions(\n";
        محتوى += "    -DSAD_OS=1\n";
        محتوى += "    -DSAD_DEVICE=\"" + معلومات_الجهاز_->الاسم + "\"\n";
        محتوى += "    -DSAD_STACK_SIZE=" + std::to_string(الإعدادات_.حجم_المكدس) + "\n";
        محتوى += "    -DSAD_HEAP_SIZE=" + std::to_string(الإعدادات_.حجم_الكومة) + "\n";
        if (الإعدادات_.تضمين_WiFi && معلومات_الجهاز_->يدعم_WiFi) {
            محتوى += "    -DSAD_WIFI_ENABLED=1\n";
        }
        if (الإعدادات_.تضمين_Bluetooth && معلومات_الجهاز_->يدعم_Bluetooth) {
            محتوى += "    -DSAD_BT_ENABLED=1\n";
        }
        محتوى += ")\n\n";
        
        // الهدف
        if (معلومات_الجهاز_->SDK == "ESP-IDF") {
            محتوى += "idf_component_register(SRCS ${SOURCES})\n";
        } else {
            محتوى += "add_executable(${PROJECT_NAME} ${SOURCES})\n";
        }
        
        return محتوى;
    }
    
    // =======================================================
    // 📌 توليد ملف الربط (Linker Script)
    // =======================================================
    
    std::string ولّد_ملف_الربط() {
        std::string محتوى;
        
        محتوى += "/* ملف ربط صOS - توليد تلقائي */\n\n";
        
        محتوى += "MEMORY {\n";
        محتوى += "    FLASH (rx)  : ORIGIN = 0x00000000, LENGTH = " + 
                 std::to_string(معلومات_الجهاز_->ذاكرة_Flash) + "K\n";
        محتوى += "    RAM   (rwx) : ORIGIN = 0x20000000, LENGTH = " +
                 std::to_string(معلومات_الجهاز_->ذاكرة_RAM) + "K\n";
        محتوى += "}\n\n";
        
        محتوى += "_stack_size = " + std::to_string(الإعدادات_.حجم_المكدس) + ";\n";
        محتوى += "_heap_size = " + std::to_string(الإعدادات_.حجم_الكومة) + ";\n\n";
        
        محتوى += "SECTIONS {\n";
        محتوى += "    .text : { *(.text*) } > FLASH\n";
        محتوى += "    .rodata : { *(.rodata*) } > FLASH\n";
        محتوى += "    .data : { *(.data*) } > RAM AT > FLASH\n";
        محتوى += "    .bss : { *(.bss*) } > RAM\n";
        محتوى += "}\n";
        
        return محتوى;
    }
    
    // =======================================================
    // 📌 توليد ملف البدء (Startup)
    // =======================================================
    
    std::string ولّد_ملف_البدء() {
        std::string محتوى;
        
        محتوى += "// ملف بدء صOS - توليد تلقائي\n\n";
        
        محتوى += "#include <stdint.h>\n\n";
        
        محتوى += "extern int main(void);\n";
        محتوى += "extern void sad_os_init(void);\n\n";
        
        محتوى += "void Reset_Handler(void) {\n";
        محتوى += "    // تهيئة النواة\n";
        محتوى += "    sad_os_init();\n";
        محتوى += "    \n";
        محتوى += "    // استدعاء البرنامج الرئيسي\n";
        محتوى += "    main();\n";
        محتوى += "    \n";
        محتوى += "    // حلقة لا نهائية في حال العودة\n";
        محتوى += "    while (1) {}\n";
        محتوى += "}\n";
        
        return محتوى;
    }
    
    // =======================================================
    // 📌 التحقق من الموارد
    // =======================================================
    
    bool تحقق_من_الموارد() {
        if (معلومات_الجهاز_ == nullptr) return false;
        
        // تحقق من الذاكرة
        uint32_t الذاكرة_المطلوبة = الإعدادات_.حجم_المكدس + الإعدادات_.حجم_الكومة;
        uint32_t الذاكرة_المتاحة = معلومات_الجهاز_->ذاكرة_RAM * 1024;
        
        if (الذاكرة_المطلوبة > الذاكرة_المتاحة * 0.8) {
            std::cerr << "تحذير: الذاكرة المطلوبة (" << الذاكرة_المطلوبة 
                      << " بايت) قريبة من الحد الأقصى" << std::endl;
        }
        
        // تحقق من الميزات
        if (الإعدادات_.تضمين_WiFi && !معلومات_الجهاز_->يدعم_WiFi) {
            std::cerr << "خطأ: الجهاز لا يدعم WiFi" << std::endl;
            return false;
        }
        
        if (الإعدادات_.تضمين_Bluetooth && !معلومات_الجهاز_->يدعم_Bluetooth) {
            std::cerr << "خطأ: الجهاز لا يدعم Bluetooth" << std::endl;
            return false;
        }
        
        return true;
    }
    
    // =======================================================
    // 📌 عرض المعلومات
    // =======================================================
    
    void اعرض_معلومات_الجهاز() {
        if (معلومات_الجهاز_ == nullptr) return;
        
        std::cout << "═══════════════════════════════════════\n";
        std::cout << "  معلومات الجهاز: " << معلومات_الجهاز_->الاسم << "\n";
        std::cout << "═══════════════════════════════════════\n";
        std::cout << "  المعالج:     " << معلومات_الجهاز_->المعالج << "\n";
        std::cout << "  البنية:      " << معلومات_الجهاز_->البنية << "\n";
        std::cout << "  الذاكرة:     " << معلومات_الجهاز_->ذاكرة_RAM << " KB RAM, "
                  << معلومات_الجهاز_->ذاكرة_Flash << " KB Flash\n";
        std::cout << "  التردد:      " << معلومات_الجهاز_->التردد << " MHz\n";
        std::cout << "  WiFi:        " << (معلومات_الجهاز_->يدعم_WiFi ? "نعم" : "لا") << "\n";
        std::cout << "  Bluetooth:   " << (معلومات_الجهاز_->يدعم_Bluetooth ? "نعم" : "لا") << "\n";
        std::cout << "  SDK:         " << معلومات_الجهاز_->SDK << "\n";
        std::cout << "\n";
    }
};

