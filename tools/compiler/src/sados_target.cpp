// 📌 محلل سطر الأوامر
// ==========================================================

class محلل_أوامر_صOS {
public:
    static إعدادات_بناء_صOS حلل(int argc, char** argv) {
        إعدادات_بناء_صOS إعدادات;
        
        for (int i = 1; i < argc; ++i) {
            std::string الوسيط = argv[i];
            
            if (الوسيط == "--جهاز" && i + 1 < argc) {
                إعدادات.الجهاز = حوّل_اسم_الجهاز(argv[++i]);
            }
            else if (الوسيط == "--إخراج" && i + 1 < argc) {
                إعدادات.مسار_الإخراج = argv[++i];
            }
            else if (الوسيط == "--اسم" && i + 1 < argc) {
                إعدادات.اسم_المشروع = argv[++i];
            }
            else if (الوسيط == "--wifi") {
                إعدادات.تضمين_WiFi = true;
            }
            else if (الوسيط == "--bluetooth") {
                إعدادات.تضمين_Bluetooth = true;
            }
            else if (الوسيط == "--إنتاج") {
                إعدادات.وضع_التصحيح = false;
            }
            else if (الوسيط.substr(0, 2) != "--") {
                إعدادات.ملفات_المصدر.push_back(الوسيط);
            }
        }
        
        return إعدادات;
    }
    
    static void اعرض_المساعدة() {
        std::cout << "استخدام: ص بناء --صOS [خيارات] <ملفات>\n\n";
        std::cout << "الخيارات:\n";
        std::cout << "  --جهاز <اسم>    الجهاز المستهدف (esp32, stm32f4, rp2040, محاكي)\n";
        std::cout << "  --إخراج <مسار>  مجلد الإخراج\n";
        std::cout << "  --اسم <اسم>     اسم المشروع\n";
        std::cout << "  --wifi          تضمين دعم WiFi\n";
        std::cout << "  --bluetooth     تضمين دعم Bluetooth\n";
        std::cout << "  --إنتاج         بناء للإنتاج (بدون تصحيح)\n";
        std::cout << "\nالأجهزة المدعومة:\n";
        for (const auto& اسم : قاعدة_الأجهزة::أحضر().قائمة_الأجهزة()) {
            std::cout << "  - " << اسم << "\n";
        }
    }

private:
    static جهاز_صOS حوّل_اسم_الجهاز(const std::string& الاسم) {
        if (الاسم == "esp32") return جهاز_صOS::ESP32;
        if (الاسم == "esp32-s3") return جهاز_صOS::ESP32_S3;
        if (الاسم == "esp32-c3") return جهاز_صOS::ESP32_C3;
        if (الاسم == "stm32f4") return جهاز_صOS::STM32F4;
        if (الاسم == "rp2040") return جهاز_صOS::RP2040;
        if (الاسم == "محاكي") return جهاز_صOS::محاكي;
        return جهاز_صOS::ESP32; // افتراضي
    }
};

