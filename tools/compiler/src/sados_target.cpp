/**
 * 📚 للمبتدئين:
 * صOS يدعم عدة أنواع من الأجهزة المدمجة.
 * كل جهاز له معالج ومواصفات مختلفة.
 */

enum class جهاز_صOS {
    ESP32,          // ESP32 الشهير - WiFi + Bluetooth
    ESP32_S2,       // نسخة أرخص بدون Bluetooth
    ESP32_S3,       // أقوى - مع AI acceleration
    ESP32_C3,       // RISC-V
    
    STM32F4,        // ARM Cortex-M4
    STM32F7,        // ARM Cortex-M7
    STM32H7,        // أقوى STM32
    
    RP2040,         // Raspberry Pi Pico
    
    WASM,           // للمحاكاة في المتصفح
    محاكي           // للتطوير على الكمبيوتر
};

// ==========================================================
// 📌 إعدادات الجهاز
// ==========================================================

struct إعدادات_جهاز {
    std::string الاسم;
    std::string المعالج;           // نوع المعالج
    std::string البنية;            // arm, xtensa, riscv
    uint32_t ذاكرة_RAM;            // بالكيلوبايت
    uint32_t ذاكرة_Flash;          // بالكيلوبايت
    uint32_t التردد;              // بالميغاهرتز
    bool يدعم_WiFi;
    bool يدعم_Bluetooth;
    std::string SDK;               // ESP-IDF, STM32Cube, etc.
    std::vector<std::string> أعلام_إضافية;
};

// ==========================================================
// 📌 قاعدة بيانات الأجهزة
// ==========================================================

class قاعدة_الأجهزة {
private:
    std::map<جهاز_صOS, إعدادات_جهاز> الأجهزة_;
    
    static قاعدة_الأجهزة* النسخة_;
    
    قاعدة_الأجهزة() {
        تهيئة_الأجهزة();
    }
    
    void تهيئة_الأجهزة() {
        // ESP32
        الأجهزة_[جهاز_صOS::ESP32] = {
            "ESP32",
            "Xtensa LX6",
            "xtensa",
            520,      // 520 KB SRAM
            4096,     // 4 MB Flash
            240,      // 240 MHz
            true,
            true,
            "ESP-IDF",
            {"-mlongcalls", "-mtext-section-literals"}
        };
        
        // ESP32-S3
        الأجهزة_[جهاز_صOS::ESP32_S3] = {
            "ESP32-S3",
            "Xtensa LX7",
            "xtensa",
            512,
            8192,
            240,
            true,
            true,
            "ESP-IDF",
            {"-mlongcalls", "-mtext-section-literals"}
        };
        
        // ESP32-C3 (RISC-V)
        الأجهزة_[جهاز_صOS::ESP32_C3] = {
            "ESP32-C3",
            "RISC-V",
            "riscv32",
            400,
            4096,
            160,
            true,
            true,
            "ESP-IDF",
            {"-march=rv32imc", "-mabi=ilp32"}
        };
        
        // STM32F4
        الأجهزة_[جهاز_صOS::STM32F4] = {
            "STM32F4",
            "ARM Cortex-M4",
            "arm",
            192,
            1024,
            168,
            false,
            false,
            "STM32Cube",
            {"-mthumb", "-mcpu=cortex-m4", "-mfpu=fpv4-sp-d16"}
        };
        
        // RP2040
        الأجهزة_[جهاز_صOS::RP2040] = {
            "RP2040",
            "ARM Cortex-M0+",
            "arm",
            264,
            2048,
            133,
            false,
            false,
            "Pico SDK",
            {"-mthumb", "-mcpu=cortex-m0plus"}
        };
        
        // محاكي
        الأجهزة_[جهاز_صOS::محاكي] = {
            "محاكي",
            "Native",
            "native",
            65536,    // 64 MB
            65536,
            0,        // سرعة الكمبيوتر
            true,
            true,
            "Native",
            {}
        };
    }

public:
    static قاعدة_الأجهزة& أحضر() {
        if (النسخة_ == nullptr) {
            static قاعدة_الأجهزة نسخة;
            النسخة_ = &نسخة;
        }
        return *النسخة_;
    }
    
    const إعدادات_جهاز* أحضر_جهاز(جهاز_صOS الجهاز) const {
        auto it = الأجهزة_.find(الجهاز);
        if (it != الأجهزة_.end()) {
            return &it->second;
        }
        return nullptr;
    }
    
    std::vector<std::string> قائمة_الأجهزة() const {
        std::vector<std::string> القائمة;
        for (const auto& زوج : الأجهزة_) {
            القائمة.push_back(زوج.second.الاسم);
        }
        return القائمة;
    }
};

قاعدة_الأجهزة* قاعدة_الأجهزة::النسخة_ = nullptr;

