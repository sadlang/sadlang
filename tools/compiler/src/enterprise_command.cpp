    // ============== أدوات العرض ==============
    
    void عرض_رأس(const std::string& العنوان) {
        الخرج_ << "\n";
        الخرج_ << عريض << بنفسجي;
        الخرج_ << "╔══════════════════════════════════════════════════════════╗\n";
        الخرج_ << "║  " << std::left << std::setw(56) << العنوان << "║\n";
        الخرج_ << "╚══════════════════════════════════════════════════════════╝\n";
        الخرج_ << إعادة;
    }
    
    void عرض_شريط_تقدم(const std::string& التسمية, int القيمة, int الحد_الأقصى) {
        int نسبة = (القيمة * 100) / الحد_الأقصى;
        int عرض_الشريط = 30;
        int ممتلئ = (نسبة * عرض_الشريط) / 100;
        
        الخرج_ << "  " << التسمية << ": ";
        الخرج_ << "[";
        
        for (int i = 0; i < عرض_الشريط; i++) {
            if (i < ممتلئ) {
                الخرج_ << أخضر << "█" << إعادة;
            } else {
                الخرج_ << "░";
            }
        }
        
        الخرج_ << "] " << القيمة << "/" << الحد_الأقصى;
        الخرج_ << " (" << نسبة << "%)\n";
    }
