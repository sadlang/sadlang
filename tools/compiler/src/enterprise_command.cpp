// ============== أنواع الأوامر ==============

/**
 * أمر الشراكة
 */
enum class أمر_شراكة {
    ترخيص,
    دعم,
    تدريب,
    امتثال,
    تحليلات,
    سجل,
    SLA,
    تقارير,
    إعدادات,
    مساعدة
};

// ============== معالج الأوامر ==============

