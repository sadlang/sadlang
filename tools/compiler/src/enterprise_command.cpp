    // ============== المعالجة الرئيسية ==============
    
    int معالجة(const std::vector<std::string>& المدخلات) {
        if (المدخلات.empty()) {
            عرض_المساعدة();
            return 0;
        }
        
        أمر_شراكة الأمر = تحليل_الأمر(المدخلات[0]);
        std::vector<std::string> المعاملات(المدخلات.begin() + 1, المدخلات.end());
        
        switch (الأمر) {
            case أمر_شراكة::ترخيص:
                return معالجة_ترخيص(المعاملات);
            case أمر_شراكة::دعم:
                return معالجة_دعم(المعاملات);
            case أمر_شراكة::تدريب:
                return معالجة_تدريب(المعاملات);
            case أمر_شراكة::امتثال:
                return معالجة_امتثال(المعاملات);
            case أمر_شراكة::تحليلات:
                return معالجة_تحليلات(المعاملات);
            case أمر_شراكة::سجل:
                return معالجة_سجل(المعاملات);
            case أمر_شراكة::SLA:
                return معالجة_SLA(المعاملات);
            case أمر_شراكة::تقارير:
                return معالجة_تقارير(المعاملات);
            case أمر_شراكة::إعدادات:
                return معالجة_إعدادات(المعاملات);
            case أمر_شراكة::مساعدة:
            default:
                عرض_المساعدة();
                return 0;
        }
    }
    
private:
    // ============== تحليل الأمر ==============
    
    أمر_شراكة تحليل_الأمر(const std::string& أمر) {
        static const std::map<std::string, أمر_شراكة> الأوامر = {
            {"ترخيص", أمر_شراكة::ترخيص},
            {"license", أمر_شراكة::ترخيص},
            {"دعم", أمر_شراكة::دعم},
            {"support", أمر_شراكة::دعم},
            {"تدريب", أمر_شراكة::تدريب},
            {"training", أمر_شراكة::تدريب},
            {"امتثال", أمر_شراكة::امتثال},
            {"compliance", أمر_شراكة::امتثال},
            {"تحليلات", أمر_شراكة::تحليلات},
            {"analytics", أمر_شراكة::تحليلات},
            {"سجل", أمر_شراكة::سجل},
            {"registry", أمر_شراكة::سجل},
            {"sla", أمر_شراكة::SLA},
            {"تقارير", أمر_شراكة::تقارير},
            {"reports", أمر_شراكة::تقارير},
            {"إعدادات", أمر_شراكة::إعدادات},
            {"settings", أمر_شراكة::إعدادات},
            {"مساعدة", أمر_شراكة::مساعدة},
            {"help", أمر_شراكة::مساعدة},
            {"-h", أمر_شراكة::مساعدة},
            {"--help", أمر_شراكة::مساعدة}
        };
        
        auto it = الأوامر.find(أمر);
        return it != الأوامر.end() ? it->second : أمر_شراكة::مساعدة;
    }
    
