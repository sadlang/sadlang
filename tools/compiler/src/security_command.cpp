/**
 * نوع الأمر الفرعي
 */
enum class أمر_أمان {
    فحص,          // scan
    تبعيات,       // audit
    وقّع,         // sign
    تحقق,         // verify
    تقرير,        // report
    مساعدة        // help
};

/**
 * خيارات سطر الأوامر
 */
struct خيارات_الأمان {
    أمر_أمان أمر = أمر_أمان::مساعدة;
    std::vector<std::string> ملفات;
    std::string مفتاح;
    std::string خوارزمية = "Ed25519";
    bool مفصّل = false;
    bool JSON = false;
    std::string مخرج;
    
    // خيارات الفحص
    bool فحص_SQL = true;
    bool فحص_XSS = true;
    bool فحص_تلوث = true;
    bool فحص_تبعيات = true;
};

// ==========================================================
// 📌 محلل الأوامر
// ==========================================================

/**
 * محلل أوامر الأمان
 */
class محلل_أوامر_الأمان {
public:
    /**
     * تحليل الأوامر
     */
    خيارات_الأمان حلل(int argc, const char* argv[]) {
        خيارات_الأمان خيارات;
        
        if (argc < 2) {
            خيارات.أمر = أمر_أمان::مساعدة;
            return خيارات;
        }
        
        std::string أمر = argv[1];
        
        // تحديد الأمر الفرعي
        if (أمر == "فحص" || أمر == "scan") {
            خيارات.أمر = أمر_أمان::فحص;
        } else if (أمر == "تبعيات" || أمر == "audit") {
            خيارات.أمر = أمر_أمان::تبعيات;
        } else if (أمر == "وقّع" || أمر == "sign") {
            خيارات.أمر = أمر_أمان::وقّع;
        } else if (أمر == "تحقق" || أمر == "verify") {
            خيارات.أمر = أمر_أمان::تحقق;
        } else if (أمر == "تقرير" || أمر == "report") {
            خيارات.أمر = أمر_أمان::تقرير;
        } else if (أمر == "--مساعدة" || أمر == "-م" || أمر == "--help" || أمر == "-h") {
            خيارات.أمر = أمر_أمان::مساعدة;
        } else {
            // افتراض أنه ملف للفحص
            خيارات.أمر = أمر_أمان::فحص;
            خيارات.ملفات.push_back(أمر);
        }
        
        // تحليل الخيارات
        for (int i = 2; i < argc; i++) {
            std::string arg = argv[i];
            
            if (arg == "--مفصّل" || arg == "-v" || arg == "--verbose") {
                خيارات.مفصّل = true;
            } else if (arg == "--json") {
                خيارات.JSON = true;
            } else if ((arg == "--مفتاح" || arg == "-k" || arg == "--key") && i + 1 < argc) {
                خيارات.مفتاح = argv[++i];
            } else if ((arg == "--خوارزمية" || arg == "-a" || arg == "--algo") && i + 1 < argc) {
                خيارات.خوارزمية = argv[++i];
            } else if ((arg == "--مخرج" || arg == "-o" || arg == "--output") && i + 1 < argc) {
                خيارات.مخرج = argv[++i];
            } else if (arg == "--لا-SQL" || arg == "--no-sql") {
                خيارات.فحص_SQL = false;
            } else if (arg == "--لا-XSS" || arg == "--no-xss") {
                خيارات.فحص_XSS = false;
            } else if (arg[0] != '-') {
                خيارات.ملفات.push_back(arg);
            }
        }
        
        return خيارات;
    }
};

