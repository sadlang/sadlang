// ============== أنواع الأوامر ==============

/**
 * أمر الذاكرة الموزعة
 */
enum class أمر_موزع {
    بدء,          // Start node
    انضمام,       // Join cluster
    مغادرة,       // Leave cluster
    حالة,         // Cluster status
    عقد,          // List nodes
    بيانات,       // Data overview
    نسخ,          // Replication status
    توازن,        // Rebalance data
    مراقبة,       // Monitor dashboard
    إعدادات,      // Configuration
    مساعدة        // Help
};

/**
 * حالة العقدة للعرض
 */
struct حالة_عقدة_عرض {
    std::string المعرف;
    std::string العنوان;
    std::string الحالة;     // نشط، متوقف، مشتبه
    int المنفذ = 0;
    uint64_t البيانات_المخزنة = 0;
    double استخدام_الذاكرة = 0;
    uint64_t آخر_نبضة = 0;
    bool هو_قائد = false;
};

