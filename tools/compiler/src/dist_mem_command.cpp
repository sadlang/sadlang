public:
    int معالجة(int argc, char* argv[]) {
        if (argc < 2) {
            عرض_المساعدة();
            return 0;
        }
        
        std::string الأمر = argv[1];
        أمر_موزع نوع = تحليل_أمر(الأمر);
        
        std::vector<std::string> المعاملات;
        for (int i = 2; i < argc; i++) {
            المعاملات.push_back(argv[i]);
        }
        
        switch (نوع) {
            case أمر_موزع::بدء:
                return معالجة_بدء(المعاملات);
                
            case أمر_موزع::انضمام:
                return معالجة_انضمام(المعاملات);
                
            case أمر_موزع::مغادرة:
                return معالجة_مغادرة(المعاملات);
                
            case أمر_موزع::حالة:
                return معالجة_حالة(المعاملات);
                
            case أمر_موزع::عقد:
                return معالجة_عقد(المعاملات);
                
            case أمر_موزع::بيانات:
                return معالجة_بيانات(المعاملات);
                
            case أمر_موزع::نسخ:
                return معالجة_نسخ(المعاملات);
                
            case أمر_موزع::توازن:
                return معالجة_توازن(المعاملات);
                
            case أمر_موزع::مراقبة:
                return معالجة_مراقبة(المعاملات);
                
            case أمر_موزع::إعدادات:
                return معالجة_إعدادات(المعاملات);
                
            case أمر_موزع::مساعدة:
            default:
                عرض_المساعدة();
                return 0;
        }
    }
    
private:
    // ============== تحليل الأمر ==============
    
    أمر_موزع تحليل_أمر(const std::string& أمر) {
        // أوامر عربية
        if (أمر == "بدء" || أمر == "start") return أمر_موزع::بدء;
        if (أمر == "انضمام" || أمر == "join") return أمر_موزع::انضمام;
        if (أمر == "مغادرة" || أمر == "leave") return أمر_موزع::مغادرة;
        if (أمر == "حالة" || أمر == "status") return أمر_موزع::حالة;
        if (أمر == "عقد" || أمر == "nodes") return أمر_موزع::عقد;
        if (أمر == "بيانات" || أمر == "data") return أمر_موزع::بيانات;
        if (أمر == "نسخ" || أمر == "replication") return أمر_موزع::نسخ;
        if (أمر == "توازن" || أمر == "rebalance") return أمر_موزع::توازن;
        if (أمر == "مراقبة" || أمر == "monitor") return أمر_موزع::مراقبة;
        if (أمر == "إعدادات" || أمر == "config") return أمر_موزع::إعدادات;
        
        return أمر_موزع::مساعدة;
    }
    
