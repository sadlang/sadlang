/**
 * محلل سطر الأوامر
 */
class محلل_الأوامر {
public:
    خيارات_البرهان حلل(int argc, char* argv[]) {
        خيارات_البرهان خيارات;
        
        for (int i = 1; i < argc; ++i) {
            std::string arg = argv[i];
            
            if (arg == "--مهلة" || arg == "--timeout" || arg == "-t") {
                if (i + 1 < argc) {
                    خيارات.مهلة_بالثواني = std::stoi(argv[++i]);
                }
            }
            else if (arg == "--مفصل" || arg == "--verbose" || arg == "-v") {
                خيارات.وضع_مفصل = true;
            }
            else if (arg == "--توقف" || arg == "--fail-fast") {
                خيارات.توقف_عند_الفشل = true;
            }
            else if (arg == "--تقرير" || arg == "--report" || arg == "-o") {
                if (i + 1 < argc) {
                    خيارات.ملف_التقرير = argv[++i];
                }
            }
            else if (arg == "--json") {
                خيارات.تنسيق_JSON = true;
            }
            else if (arg == "--بدون-ألوان" || arg == "--no-color") {
                خيارات.ألوان = false;
            }
            else if (arg == "--محقق" || arg == "--solver") {
                if (i + 1 < argc) {
                    خيارات.المحقق = argv[++i];
                }
            }
            else if (arg == "--دالة" || arg == "--function" || arg == "-f") {
                if (i + 1 < argc) {
                    خيارات.تصفية_الدوال.push_back(argv[++i]);
                }
            }
            else if (arg == "--مع-موثوق" || arg == "--include-unsafe") {
                خيارات.تخطي_موثوق = false;
            }
            else if (arg == "--مساعدة" || arg == "--help" || arg == "-h") {
                اطبع_المساعدة();
                std::exit(0);
            }
            else if (arg == ".") {
                خيارات.كل_الملفات = true;
            }
            else if (!arg.empty() && arg[0] != '-') {
                خيارات.الملفات.push_back(arg);
            }
        }
        
        return خيارات;
    }
    
    void اطبع_المساعدة() {
        std::cout << R"(
╔═══════════════════════════════════════════════════════════════╗
║                    ص برهن - التحقق الرسمي                     ║
╚═══════════════════════════════════════════════════════════════╝

الاستخدام:
  ص برهن [خيارات] <ملفات>

الخيارات:
  --مهلة, -t <ثواني>     مهلة التحقق لكل برهان (افتراضي: 30)
  --مفصل, -v              عرض مفصل للعمليات
  --توقف                  توقف عند أول فشل
  --تقرير, -o <ملف>      حفظ التقرير في ملف
  --json                  إخراج بتنسيق JSON
  --بدون-ألوان           تعطيل الألوان
  --محقق <اسم>           اختيار المحقق (z3, cvc5)
  --دالة, -f <اسم>       التحقق من دالة محددة فقط
  --مع-موثوق             شمل الدوال الموثوقة
  --مساعدة, -h           عرض هذه الرسالة

أمثلة:
  ص برهن ملف.ص                    # تحقق من ملف واحد
  ص برهن .                        # تحقق من كل الملفات
  ص برهن --مهلة 60 --مفصل .      # مهلة 60 ثانية مع تفاصيل
  ص برهن --دالة مجموع ملف.ص      # تحقق من دالة واحدة

)" << std::endl;
    }
};

