/**
 * محرك التحقق
 */
class محرك_التحقق_CLI {
private:
    خيارات_البرهان الخيارات;
    
    /**
     * طباعة ملونة
     */
    std::string لون(const std::string& نص, const std::string& كود) {
        if (!الخيارات.ألوان) return نص;
        return "\033[" + كود + "m" + نص + "\033[0m";
    }
    
    std::string أخضر(const std::string& نص) { return لون(نص, "32"); }
    std::string أحمر(const std::string& نص) { return لون(نص, "31"); }
    std::string أصفر(const std::string& نص) { return لون(نص, "33"); }
    std::string أزرق(const std::string& نص) { return لون(نص, "34"); }
    std::string رمادي(const std::string& نص) { return لون(نص, "90"); }
    
    /**
     * طباعة نتيجة برهان
     */
    void اطبع_نتيجة(const نتيجة_برهان_CLI& نتيجة) {
        std::string رمز;
        std::string لون_حالة;
        
        switch (نتيجة.الحالة) {
            case حالة_البرهان::مثبت:
                std::cout << أخضر("  ✅ ") << نتيجة.اسم_الدالة << أخضر(" مثبت");
                break;
            case حالة_البرهان::مدحوض:
                std::cout << أحمر("  ❌ ") << نتيجة.اسم_الدالة << أحمر(" مدحوض");
                break;
            case حالة_البرهان::غير_محدد:
                std::cout << أصفر("  ❓ ") << نتيجة.اسم_الدالة << أصفر(" غير محدد");
                break;
            case حالة_البرهان::مهلة:
                std::cout << أصفر("  ⏱️ ") << نتيجة.اسم_الدالة << أصفر(" مهلة");
                break;
            case حالة_البرهان::تخطي:
                std::cout << رمادي("  ⏭️ ") << نتيجة.اسم_الدالة << رمادي(" تخطي");
                break;
            case حالة_البرهان::خطأ:
                std::cout << أحمر("  ⚠️ ") << نتيجة.اسم_الدالة << أحمر(" خطأ");
                break;
        }
        
        std::cout << رمادي(" (" + std::to_string(نتيجة.الوقت_بالثواني) + "ث)") << "\n";
        
        // طباعة المثال المضاد إن وجد
        if (نتيجة.الحالة == حالة_البرهان::مدحوض && !نتيجة.مثال_مضاد.empty()) {
            std::cout << أحمر("     مثال مضاد:\n");
            for (const auto& [اسم, قيمة] : نتيجة.مثال_مضاد) {
                std::cout << "       " << اسم << " = " << قيمة << "\n";
            }
        }
        
        // طباعة رسالة الخطأ إن وجدت
        if (!نتيجة.الرسالة.empty() && 
            (نتيجة.الحالة == حالة_البرهان::خطأ || الخيارات.وضع_مفصل)) {
            std::cout << رمادي("     " + نتيجة.الرسالة) << "\n";
        }
    }
    
    /**
     * طباعة الملخص
     */
    void اطبع_ملخص(const ملخص_CLI& ملخص) {
        std::cout << "\n";
        std::cout << "═══════════════════════════════════════════════════════\n";
        std::cout << "                      ملخص التحقق\n";
        std::cout << "═══════════════════════════════════════════════════════\n\n";
        
        std::cout << "  📊 الإحصائيات:\n";
        std::cout << "     إجمالي البراهين: " << ملخص.إجمالي << "\n";
        std::cout << "     " << أخضر("✅ مثبت: " + std::to_string(ملخص.مثبت)) << "\n";
        
        if (ملخص.مدحوض > 0) {
            std::cout << "     " << أحمر("❌ مدحوض: " + std::to_string(ملخص.مدحوض)) << "\n";
        }
        if (ملخص.غير_محدد > 0) {
            std::cout << "     " << أصفر("❓ غير محدد: " + std::to_string(ملخص.غير_محدد)) << "\n";
        }
        if (ملخص.تخطي > 0) {
            std::cout << "     " << رمادي("⏭️ تخطي: " + std::to_string(ملخص.تخطي)) << "\n";
        }
        if (ملخص.أخطاء > 0) {
            std::cout << "     " << أحمر("⚠️ أخطاء: " + std::to_string(ملخص.أخطاء)) << "\n";
        }
        
        std::cout << "     ⏱️ الوقت: " << ملخص.الوقت_الإجمالي << " ثانية\n\n";
        
        if (ملخص.نجح()) {
            std::cout << أخضر("  🎉 جميع البراهين مثبتة!") << "\n\n";
        } else if (ملخص.مدحوض > 0) {
            std::cout << أحمر("  ⚠️ بعض البراهين مدحوضة - راجع الأمثلة المضادة") << "\n\n";
        } else {
            std::cout << أصفر("  ⚠️ بعض البراهين لم تُحل") << "\n\n";
        }
    }
    
    /**
     * تحقق من ملف واحد (محاكاة)
     */
    std::vector<نتيجة_برهان_CLI> تحقق_من_ملف(const std::string& مسار) {
        std::vector<نتيجة_برهان_CLI> النتائج;
        
        if (الخيارات.وضع_مفصل) {
            std::cout << أزرق("📄 فحص: ") << مسار << "\n";
        }
        
        // TODO: تحليل الملف الحقيقي واستخراج الدوال المعلّمة بـ #[برهان]
        // هنا محاكاة بسيطة
        
        نتيجة_برهان_CLI نتيجة;
        نتيجة.اسم_الدالة = "مثال";
        نتيجة.الملف = مسار;
        نتيجة.السطر = 1;
        نتيجة.الحالة = حالة_البرهان::غير_محدد;
        نتيجة.الرسالة = "لم يتم التنفيذ الكامل بعد";
        نتيجة.الوقت_بالثواني = 0.01;
        
        النتائج.push_back(نتيجة);
        
        return النتائج;
    }
    
public:
    محرك_التحقق_CLI(const خيارات_البرهان& خيارات) : الخيارات(خيارات) {}
    
    /**
     * تشغيل التحقق
     */
    int شغّل() {
        auto بداية = std::chrono::high_resolution_clock::now();
        
        // طباعة الترويسة
        if (!الخيارات.تنسيق_JSON) {
            std::cout << "\n";
            std::cout << "╔═══════════════════════════════════════════════════════╗\n";
            std::cout << "║                 ص برهن - التحقق الرسمي                ║\n";
            std::cout << "╚═══════════════════════════════════════════════════════╝\n\n";
        }
        
        ملخص_CLI ملخص;
        
        // جمع الملفات
        std::vector<std::string> الملفات = الخيارات.الملفات;
        
        if (الخيارات.كل_الملفات) {
            // البحث عن كل ملفات .ص
            for (const auto& entry : fs::recursive_directory_iterator(".")) {
                if (entry.path().extension() == ".ص") {
                    الملفات.push_back(entry.path().string());
                }
            }
        }
        
        if (الملفات.empty()) {
            std::cerr << أحمر("خطأ: لم يتم تحديد ملفات للتحقق") << "\n";
            std::cerr << "استخدم: ص برهن --مساعدة\n";
            return 1;
        }
        
        // التحقق من كل ملف
        for (const auto& ملف : الملفات) {
            if (!fs::exists(ملف)) {
                std::cerr << أحمر("خطأ: الملف غير موجود: ") << ملف << "\n";
                continue;
            }
            
            auto النتائج = تحقق_من_ملف(ملف);
            
            for (const auto& نتيجة : النتائج) {
                ملخص.إجمالي++;
                
                switch (نتيجة.الحالة) {
                    case حالة_البرهان::مثبت: ملخص.مثبت++; break;
                    case حالة_البرهان::مدحوض: ملخص.مدحوض++; break;
                    case حالة_البرهان::غير_محدد: 
                    case حالة_البرهان::مهلة: 
                        ملخص.غير_محدد++; break;
                    case حالة_البرهان::تخطي: ملخص.تخطي++; break;
                    case حالة_البرهان::خطأ: ملخص.أخطاء++; break;
                }
                
                ملخص.الوقت_الإجمالي += نتيجة.الوقت_بالثواني;
                ملخص.النتائج.push_back(نتيجة);
                
                if (!الخيارات.تنسيق_JSON) {
                    اطبع_نتيجة(نتيجة);
                }
                
                // توقف إذا طُلب
                if (الخيارات.توقف_عند_الفشل && 
                    (نتيجة.الحالة == حالة_البرهان::مدحوض || 
                     نتيجة.الحالة == حالة_البرهان::خطأ)) {
                    break;
                }
            }
        }
        
        auto نهاية = std::chrono::high_resolution_clock::now();
        ملخص.الوقت_الإجمالي = std::chrono::duration<double>(نهاية - بداية).count();
        
        // طباعة الملخص
        if (الخيارات.تنسيق_JSON) {
            اطبع_JSON(ملخص);
        } else {
            اطبع_ملخص(ملخص);
        }
        
        // حفظ التقرير إذا طُلب
        if (!الخيارات.ملف_التقرير.empty()) {
            احفظ_التقرير(ملخص);
        }
        
        return ملخص.نجح() ? 0 : 1;
    }
    
    /**
     * طباعة JSON
     */
    void اطبع_JSON(const ملخص_CLI& ملخص) {
        std::cout << "{\n";
        std::cout << "  \"total\": " << ملخص.إجمالي << ",\n";
        std::cout << "  \"proven\": " << ملخص.مثبت << ",\n";
        std::cout << "  \"refuted\": " << ملخص.مدحوض << ",\n";
        std::cout << "  \"unknown\": " << ملخص.غير_محدد << ",\n";
        std::cout << "  \"skipped\": " << ملخص.تخطي << ",\n";
        std::cout << "  \"errors\": " << ملخص.أخطاء << ",\n";
        std::cout << "  \"time\": " << ملخص.الوقت_الإجمالي << ",\n";
        std::cout << "  \"success\": " << (ملخص.نجح() ? "true" : "false") << ",\n";
        std::cout << "  \"results\": [\n";
        
        for (size_t i = 0; i < ملخص.النتائج.size(); ++i) {
            const auto& ن = ملخص.النتائج[i];
            std::cout << "    {\n";
            std::cout << "      \"function\": \"" << ن.اسم_الدالة << "\",\n";
            std::cout << "      \"file\": \"" << ن.الملف << "\",\n";
            std::cout << "      \"line\": " << ن.السطر << ",\n";
            std::cout << "      \"status\": \"";
            switch (ن.الحالة) {
                case حالة_البرهان::مثبت: std::cout << "proven"; break;
                case حالة_البرهان::مدحوض: std::cout << "refuted"; break;
                case حالة_البرهان::غير_محدد: std::cout << "unknown"; break;
                case حالة_البرهان::مهلة: std::cout << "timeout"; break;
                case حالة_البرهان::تخطي: std::cout << "skipped"; break;
                case حالة_البرهان::خطأ: std::cout << "error"; break;
            }
            std::cout << "\",\n";
            std::cout << "      \"time\": " << ن.الوقت_بالثواني << "\n";
            std::cout << "    }" << (i + 1 < ملخص.النتائج.size() ? "," : "") << "\n";
        }
        
        std::cout << "  ]\n";
        std::cout << "}\n";
    }
    
    /**
     * حفظ التقرير
     */
    void احفظ_التقرير(const ملخص_CLI& ملخص) {
        std::ofstream ملف(الخيارات.ملف_التقرير);
        if (!ملف) {
            std::cerr << "خطأ: لا يمكن حفظ التقرير في " << الخيارات.ملف_التقرير << "\n";
            return;
        }
        
        ملف << "تقرير التحقق الرسمي\n";
        ملف << "===================\n\n";
        ملف << "التاريخ: " << __DATE__ << " " << __TIME__ << "\n\n";
        ملف << "إجمالي: " << ملخص.إجمالي << "\n";
        ملف << "مثبت: " << ملخص.مثبت << "\n";
        ملف << "مدحوض: " << ملخص.مدحوض << "\n";
        ملف << "غير محدد: " << ملخص.غير_محدد << "\n";
        ملف << "الوقت: " << ملخص.الوقت_الإجمالي << " ثانية\n";
        
        ملف.close();
        std::cout << "تم حفظ التقرير في: " << الخيارات.ملف_التقرير << "\n";
    }
};

