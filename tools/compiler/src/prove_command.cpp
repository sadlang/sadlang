/**
 * حالة البرهان
 */
enum class حالة_البرهان {
    مثبت,       // ✅ Proven
    مدحوض,      // ❌ Refuted
    غير_محدد,   // ❓ Unknown
    مهلة,       // ⏱️ Timeout
    تخطي,       // ⏭️ Skipped
    خطأ         // ⚠️ Error
};

/**
 * نتيجة برهان واحد
 */
struct نتيجة_برهان_CLI {
    std::string اسم_الدالة;
    std::string الملف;
    int السطر = 0;
    
    حالة_البرهان الحالة;
    std::string الرسالة;
    
    // للبراهين المدحوضة
    std::vector<std::pair<std::string, std::string>> مثال_مضاد;
    
    double الوقت_بالثواني = 0.0;
};

/**
 * ملخص التحقق
 */
struct ملخص_CLI {
    int إجمالي = 0;
    int مثبت = 0;
    int مدحوض = 0;
    int غير_محدد = 0;
    int تخطي = 0;
    int أخطاء = 0;
    
    double الوقت_الإجمالي = 0.0;
    
    std::vector<نتيجة_برهان_CLI> النتائج;
    
    bool نجح() const {
        return مدحوض == 0 && أخطاء == 0;
    }
};

