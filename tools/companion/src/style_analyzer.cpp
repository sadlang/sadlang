#include <iostream>
#include <string>
#include <vector>
#include <memory>
#include <map>
#include <regex>

namespace sad {
namespace companion {

// ==========================================================
// 📌 أنماط الأسلوب
// ==========================================================

/**
 * لغة التسمية
 */
enum class لغة_التسمية {
    عربية_فقط,      // عداد، مجموع
    إنجليزية_فقط,  // counter, sum
    مختلطة          // مزيج
};

/**
 * نمط التسمية
 */
enum class نمط_التسمية {
    شرطة_سفلية,    // عداد_الطلبات
    جملية,          // عدادالطلبات
    مختلط          // متنوع
};

/**
 * نمط الإزاحة
 */
struct نمط_الإزاحة {
    int عدد_المسافات = 4;
    bool يستخدم_تاب = false;
};

/**
 * نمط التعليقات
 */
struct نمط_التعليقات {
    bool يعلق_الدوال = true;
    bool يعلق_الأصناف = true;
    bool يعلق_المعقد = true;
    double نسبة_التعليقات = 0.1;  // سطور التعليقات / إجمالي السطور
};

/**
 * ملف أسلوب البرمجة
 */
struct ملف_الأسلوب {
    لغة_التسمية لغة = لغة_التسمية::عربية_فقط;
    نمط_التسمية نمط_تسمية = نمط_التسمية::شرطة_سفلية;
    نمط_الإزاحة إزاحة;
    نمط_التعليقات تعليقات;
    
    // تفضيلات إضافية
    int طول_سطر_مفضل = 80;
    bool يفضل_دوال_صغيرة = true;
    int عدد_أسطر_الدالة_المفضل = 20;
    
    // الأنماط المتكررة
    std::vector<std::string> تراكيب_مفضلة;
    std::map<std::string, int> كلمات_متكررة;
};

// ==========================================================
// 📌 محلل الأسلوب
// ==========================================================

/**
 * محلل أسلوب البرمجة
 */
class محلل_الأسلوب {
private:
    ملف_الأسلوب ملف_;
    int إجمالي_الملفات_ = 0;
    int إجمالي_السطور_ = 0;
    
public:
    /**
     * تحليل ملف
     */
    void حلل_ملف(const std::string& محتوى) {
        إجمالي_الملفات_++;
        
        std::vector<std::string> سطور = قسّم_سطور(محتوى);
        إجمالي_السطور_ += سطور.size();
        
        // تحليل الإزاحة
        حلل_الإزاحة(سطور);
        
        // تحليل التسمية
        حلل_التسمية(محتوى);
        
        // تحليل التعليقات
        حلل_التعليقات(سطور);
        
        // تحليل طول السطور
        حلل_طول_السطور(سطور);
        
        // تحليل الأنماط
        حلل_الأنماط(محتوى);
    }
    
    /**
     * الحصول على ملف الأسلوب
     */
    const ملف_الأسلوب& الأسلوب() const {
        return ملف_;
    }
    
    /**
     * تقرير الأسلوب
     */
    std::string تقرير() const {
        std::string ت;
        
        ت += "═══════════════════════════════════════════════════\n";
        ت += "📊 تقرير أسلوب البرمجة\n";
        ت += "═══════════════════════════════════════════════════\n\n";
        
        ت += "📁 الملفات المحللة: " + std::to_string(إجمالي_الملفات_) + "\n";
        ت += "📝 إجمالي السطور: " + std::to_string(إجمالي_السطور_) + "\n\n";
        
        // لغة التسمية
        ت += "🔤 لغة التسمية: ";
        switch (ملف_.لغة) {
            case لغة_التسمية::عربية_فقط: ت += "عربية فقط\n"; break;
            case لغة_التسمية::إنجليزية_فقط: ت += "إنجليزية فقط\n"; break;
            case لغة_التسمية::مختلطة: ت += "مختلطة\n"; break;
        }
        
        // نمط التسمية
        ت += "📌 نمط التسمية: ";
        switch (ملف_.نمط_تسمية) {
            case نمط_التسمية::شرطة_سفلية: ت += "شرطة_سفلية\n"; break;
            case نمط_التسمية::جملية: ت += "جُملية\n"; break;
            case نمط_التسمية::مختلط: ت += "مختلط\n"; break;
        }
        
        // الإزاحة
        if (ملف_.إزاحة.يستخدم_تاب) {
            ت += "↔️ الإزاحة: تاب\n";
        } else {
            ت += "↔️ الإزاحة: " + std::to_string(ملف_.إزاحة.عدد_المسافات) + " مسافات\n";
        }
        
        // التعليقات
        ت += "💬 نسبة التعليقات: " + 
             std::to_string((int)(ملف_.تعليقات.نسبة_التعليقات * 100)) + "%\n";
        
        // طول السطر
        ت += "📏 طول السطر المفضل: " + std::to_string(ملف_.طول_سطر_مفضل) + " حرف\n";
        
        return ت;
    }
    
private:
    /**
     * تقسيم النص إلى سطور
     */
    std::vector<std::string> قسّم_سطور(const std::string& نص) {
        std::vector<std::string> سطور;
        std::string سطر;
        
        for (char c : نص) {
            if (c == '\n') {
                سطور.push_back(سطر);
                سطر.clear();
            } else {
                سطر += c;
            }
        }
        if (!سطر.empty()) {
            سطور.push_back(سطر);
        }
        
        return سطور;
    }
    
    /**
     * تحليل نمط الإزاحة
     */
    void حلل_الإزاحة(const std::vector<std::string>& سطور) {
        std::map<int, int> مسافات;
        int تاب = 0;
        
        for (const auto& سطر : سطور) {
            if (سطر.empty()) continue;
            
            int عدد = 0;
            for (char c : سطر) {
                if (c == ' ') عدد++;
                else if (c == '\t') { تاب++; break; }
                else break;
            }
            
            if (عدد > 0 && عدد <= 8) {
                مسافات[عدد]++;
            }
        }
        
        // تحديد النمط الأكثر شيوعاً
        if (تاب > 0) {
            ملف_.إزاحة.يستخدم_تاب = true;
        } else {
            // البحث عن أصغر إزاحة متكررة
            for (int i = 2; i <= 4; i++) {
                if (مسافات[i] > 5) {
                    ملف_.إزاحة.عدد_المسافات = i;
                    break;
                }
            }
        }
    }
    
    /**
     * تحليل أسلوب التسمية
     */
    void حلل_التسمية(const std::string& محتوى) {
        // عد الأسماء العربية والإنجليزية
        int عربية = 0;
        int إنجليزية = 0;
        int شرطة = 0;
        int جملية = 0;
        
        // regex للأسماء
        std::regex نمط_عربي(u8"[\\u0600-\\u06FF]+");
        std::regex نمط_إنجليزي("[a-zA-Z]+");
        std::regex نمط_شرطة("_");
        
        // تحليل بسيط
        bool في_كلمة = false;
        std::string كلمة;
        
        for (char c : محتوى) {
            if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' ||
                (unsigned char)c > 127) {
                كلمة += c;
            } else {
                if (!كلمة.empty()) {
                    // تحليل الكلمة
                    if (كلمة.find('_') != std::string::npos) شرطة++;
                    
                    // تحقق من وجود أحرف عربية
                    bool عربي = false;
                    for (unsigned char ch : كلمة) {
                        if (ch > 127) { عربي = true; break; }
                    }
                    if (عربي) عربية++;
                    else إنجليزية++;
                    
                    كلمة.clear();
                }
            }
        }
        
        // تحديد اللغة
        if (عربية > إنجليزية * 2) {
            ملف_.لغة = لغة_التسمية::عربية_فقط;
        } else if (إنجليزية > عربية * 2) {
            ملف_.لغة = لغة_التسمية::إنجليزية_فقط;
        } else {
            ملف_.لغة = لغة_التسمية::مختلطة;
        }
        
        // تحديد نمط التسمية
        if (شرطة > 10) {
            ملف_.نمط_تسمية = نمط_التسمية::شرطة_سفلية;
        } else {
            ملف_.نمط_تسمية = نمط_التسمية::جملية;
        }
    }
    
    /**
     * تحليل التعليقات
     */
    void حلل_التعليقات(const std::vector<std::string>& سطور) {
        int تعليقات = 0;
        
        for (const auto& سطر : سطور) {
            // البحث عن //
            if (سطر.find("//") != std::string::npos) {
                تعليقات++;
            }
        }
        
        if (!سطور.empty()) {
            ملف_.تعليقات.نسبة_التعليقات = (double)تعليقات / سطور.size();
        }
    }
    
    /**
     * تحليل طول السطور
     */
    void حلل_طول_السطور(const std::vector<std::string>& سطور) {
        if (سطور.empty()) return;
        
        int مجموع = 0;
        for (const auto& سطر : سطور) {
            مجموع += سطر.length();
        }
        
        // المتوسط كمؤشر للطول المفضل
        int متوسط = مجموع / سطور.size();
        
        // تقريب لأقرب 10
        ملف_.طول_سطر_مفضل = ((متوسط + 5) / 10) * 10;
        if (ملف_.طول_سطر_مفضل < 60) ملف_.طول_سطر_مفضل = 60;
        if (ملف_.طول_سطر_مفضل > 120) ملف_.طول_سطر_مفضل = 120;
    }
    
    /**
     * تحليل الأنماط المتكررة
     */
    void حلل_الأنماط(const std::string& محتوى) {
        // عد الكلمات المتكررة
        std::string كلمة;
        
        for (char c : محتوى) {
            if (c == ' ' || c == '\n' || c == '\t') {
                if (!كلمة.empty() && كلمة.length() > 3) {
                    ملف_.كلمات_متكررة[كلمة]++;
                }
                كلمة.clear();
            } else {
                كلمة += c;
            }
        }
    }
};

} // namespace companion
} // namespace sad

// ==========================================================
