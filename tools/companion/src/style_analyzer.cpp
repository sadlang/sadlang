extern "C" {

using namespace sad::companion;

void* sad_style_analyzer_create() {
    return new محلل_الأسلوب();
}

void sad_style_analyzer_destroy(void* analyzer) {
    delete static_cast<محلل_الأسلوب*>(analyzer);
}

void sad_style_analyzer_analyze(void* analyzer, const char* content) {
    static_cast<محلل_الأسلوب*>(analyzer)->حلل_ملف(content);
}

const char* sad_style_analyzer_report(void* analyzer) {
    static std::string تقرير;
    تقرير = static_cast<محلل_الأسلوب*>(analyzer)->تقرير();
    return تقرير.c_str();
}

} // extern "C"
