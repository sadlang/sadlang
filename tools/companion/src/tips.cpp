#include <iostream>
#include <string>
#include <vector>
#include <map>
#include <random>

namespace sad {
namespace companion {

/**
 * فئة النصيحة
 */
enum class فئة_نصيحة {
    جودة_الكود,
    أداء,
    أمان,
    قراءة,
    أسلوب,
    أفضل_ممارسات
};

/**
 * مستوى النصيحة
 */
enum class مستوى_نصيحة {
    مبتدئ,
    متوسط,
    متقدم
};

/**
 * نصيحة تحسين
 */
struct نصيحة {
    std::string عنوان;
    std::string محتوى;
    std::string مثال;
    فئة_نصيحة فئة;
    مستوى_نصيحة مستوى;
};

/**
 * مولد النصائح
 */
class مولّد_النصائح {
private:
    std::vector<نصيحة> نصائح_;
    std::map<std::string, int> نصائح_معروضة_;
    
public:
    مولّد_النصائح() {
        حمّل_النصائح();
    }
    
    /**
     * نصيحة اليوم
     */
    نصيحة نصيحة_اليوم() {
        if (نصائح_.empty()) return نصيحة{};
        
        std::random_device rd;
        std::mt19937 gen(rd());
        std::uniform_int_distribution<> dis(0, نصائح_.size() - 1);
        
        return نصائح_[dis(gen)];
    }
    
    /**
     * نصيحة حسب السياق
     */
    نصيحة نصيحة_سياقية(const std::string& كود) {
        // تحليل الكود وإعطاء نصيحة مناسبة
        
        if (كود.find("// TODO") != std::string::npos) {
            return نصيحة{
                .عنوان = "تتبع المهام",
                .محتوى = "لديك مهام TODO في الكود. حاول إكمالها قبل الانتقال.",
                .مثال = "// استخدم نظام إدارة المهام بدلاً من TODO",
                .فئة = فئة_نصيحة::أفضل_ممارسات,
                .مستوى = مستوى_نصيحة::مبتدئ
            };
        }
        
        if (كود.find("متغير") != std::string::npos && كود.length() < 10) {
            return نصيحة{
                .عنوان = "أسماء وصفية",
                .محتوى = "استخدم أسماء وصفية للمتغيرات بدلاً من أسماء عامة.",
                .مثال = "// بدلاً من 'متغير' استخدم 'عدد_الطلاب'",
                .فئة = فئة_نصيحة::قراءة,
                .مستوى = مستوى_نصيحة::مبتدئ
            };
        }
        
        return نصيحة_اليوم();
    }
    
    /**
     * نصائح حسب الفئة
     */
    std::vector<نصيحة> نصائح_الفئة(فئة_نصيحة ف) {
        std::vector<نصيحة> نتيجة;
        for (const auto& ن : نصائح_) {
            if (ن.فئة == ف) {
                نتيجة.push_back(ن);
            }
        }
        return نتيجة;
    }
    
    /**
     * نصائح حسب المستوى
     */
    std::vector<نصيحة> نصائح_المستوى(مستوى_نصيحة م) {
        std::vector<نصيحة> نتيجة;
        for (const auto& ن : نصائح_) {
            if (ن.مستوى == م) {
                نتيجة.push_back(ن);
            }
        }
        return نتيجة;
    }
    
    /**
     * عرض النصيحة
     */
    std::string اعرض(const نصيحة& ن) {
        std::string ت;
        ت += "💡 " + ن.عنوان + "\n";
        ت += "───────────────────\n";
        ت += ن.محتوى + "\n\n";
        ت += "📝 مثال:\n" + ن.مثال + "\n";
        return ت;
    }
    
private:
    void حمّل_النصائح() {
        نصائح_ = {
            // نصائح جودة الكود
            {
                .عنوان = "التعليقات التوضيحية",
                .محتوى = "اكتب تعليقات توضح 'لماذا' وليس 'ماذا'. الكود يشرح نفسه.",
                .مثال = "// نستخدم التأخير لتجنب الضغط على الخادم\nانتظر(100)",
                .فئة = فئة_نصيحة::قراءة,
                .مستوى = مستوى_نصيحة::مبتدئ
            },
            {
                .عنوان = "الدوال الصغيرة",
                .محتوى = "اجعل الدوال صغيرة ومركزة على مهمة واحدة.",
                .مثال = "دالة احسب_المجموع(أرقام) -> صحيح نهاية",
                .فئة = فئة_نصيحة::جودة_الكود,
                .مستوى = مستوى_نصيحة::مبتدئ
            },
            {
                .عنوان = "معالجة الأخطاء",
                .محتوى = "تعامل مع الأخطاء بوضوح. لا تتجاهلها.",
                .مثال = "حاول\n    افتح(ملف)\nالتقط خطأ\n    اطبع(خطأ.رسالة)\nنهاية",
                .فئة = فئة_نصيحة::أفضل_ممارسات,
                .مستوى = مستوى_نصيحة::متوسط
            },
            // نصائح الأداء
            {
                .عنوان = "تجنب الحسابات المتكررة",
                .محتوى = "احفظ نتائج الحسابات المكلفة في متغيرات.",
                .مثال = "متغير الطول = قائمة.طول()\nلكل ع من 0 إلى الطول",
                .فئة = فئة_نصيحة::أداء,
                .مستوى = مستوى_نصيحة::متوسط
            },
            // نصائح الأمان
            {
                .عنوان = "تحقق من المدخلات",
                .محتوى = "دائماً تحقق من مدخلات المستخدم قبل استخدامها.",
                .مثال = "إذا اسم.طول() > 0 و اسم.طول() < 100 ثم\n    استخدم(اسم)\nنهاية",
                .فئة = فئة_نصيحة::أمان,
                .مستوى = مستوى_نصيحة::متوسط
            }
        };
    }
};

} // namespace companion
} // namespace sad

extern "C" {
using namespace sad::companion;

void* sad_tips_create() {
    return new مولّد_النصائح();
}

void sad_tips_destroy(void* tips) {
    delete static_cast<مولّد_النصائح*>(tips);
}

const char* sad_tips_today(void* tips) {
    static std::string تقرير;
    auto مولّد = static_cast<مولّد_النصائح*>(tips);
    auto ن = مولّد->نصيحة_اليوم();
    تقرير = مولّد->اعرض(ن);
    return تقرير.c_str();
}

const char* sad_tips_contextual(void* tips, const char* code) {
    static std::string تقرير;
    auto مولّد = static_cast<مولّد_النصائح*>(tips);
    auto ن = مولّد->نصيحة_سياقية(code);
    تقرير = مولّد->اعرض(ن);
    return تقرير.c_str();
}
}
