// صنف مزود معلومات التمرير - Hover Provider Class
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * @class HoverProvider
 * @brief يوفر معلومات التمرير
 */
class HoverProvider {
public:
    /**
     * @brief الحصول على معلومات التمرير
     * @param doc المستند
     * @param pos الموقع
     * @return معلومات التمرير
     */
    std::optional<Hover> get_hover(const DocumentInfo& doc, const Position& pos) {
        // الحصول على الكلمة تحت المؤشر
        std::string word = get_word_at_position(doc, pos);
        
        if (word.empty()) {
            return std::nullopt;
        }
        
        // البحث في الدوال المدمجة
        auto builtin_it = BUILTIN_DOCS.find(word);
        if (builtin_it != BUILTIN_DOCS.end()) {
            return create_builtin_hover(builtin_it->second);
        }
        
        // البحث في الكلمات المفتاحية
        auto keyword_it = KEYWORD_DOCS.find(word);
        if (keyword_it != KEYWORD_DOCS.end()) {
            return create_keyword_hover(keyword_it->second);
        }
        
        // البحث في الأنواع
        auto type_it = TYPE_DOCS.find(word);
        if (type_it != TYPE_DOCS.end()) {
            return create_type_hover(type_it->second);
        }
        
        // البحث في عناصر الواجهة
        auto widget_it = UI_WIDGET_DOCS.find(word);
        if (widget_it != UI_WIDGET_DOCS.end()) {
            return create_widget_hover(widget_it->second);
        }
        
        // البحث في رموز المستند
        for (const auto& sym : doc.symbols) {
            if (sym.name == word) {
                return create_symbol_hover(sym);
            }
        }
        
        return std::nullopt;
    }

private:
    /**
     * @brief الحصول على الكلمة في موقع محدد
     */
    std::string get_word_at_position(const DocumentInfo& doc, const Position& pos) {
        if (pos.line < 0 || pos.line >= static_cast<int>(doc.lines.size())) {
            return "";
        }
        
        const std::string& line = doc.lines[pos.line];
        
        if (pos.character < 0 || pos.character >= static_cast<int>(line.length())) {
            return "";
        }
        
        // إيجاد بداية الكلمة
        int start = pos.character;
        while (start > 0 && is_word_char(line[start - 1])) {
            start--;
        }
        
        // إيجاد نهاية الكلمة
        int end = pos.character;
        while (end < static_cast<int>(line.length()) && is_word_char(line[end])) {
            end++;
        }
        
        if (start == end) {
            return "";
        }
        
        return line.substr(start, end - start);
    }
    
    /**
     * @brief التحقق من حرف الكلمة
     */
    bool is_word_char(char c) {
        return (c >= 'a' && c <= 'z') ||
               (c >= 'A' && c <= 'Z') ||
               (c >= '0' && c <= '9') ||
               c == '_' ||
               (static_cast<unsigned char>(c) >= 0x80); // UTF-8 للعربية
    }
    
    /**
     * @brief إنشاء hover للدالة المدمجة
     */
    Hover create_builtin_hover(const BuiltinInfo& info) {
        Hover hover;
        
        std::ostringstream content;
        content << "```ص\n" << info.signature << "\n```\n\n";
        content << info.description << "\n\n";
        
        if (!info.parameters.empty()) {
            content << "**المعلمات:**\n" << info.parameters << "\n\n";
        }
        
        if (!info.returns.empty()) {
            content << "**الإرجاع:** " << info.returns << "\n\n";
        }
        
        if (!info.example.empty()) {
            content << "**مثال:**\n```ص\n" << info.example << "\n```";
        }
        
        hover.contents.kind = MarkupKind::MARKDOWN;
        hover.contents.value = content.str();
        
        return hover;
    }
    
    /**
     * @brief إنشاء hover لعنصر واجهة
     */
    Hover create_widget_hover(const BuiltinInfo& info) {
        Hover hover;
        
        std::ostringstream content;
        content << "```ص\n" << info.signature << "\n```\n\n";
        content << "🧩 " << info.description << "\n\n";
        
        if (!info.parameters.empty()) {
            content << "**المعاملات:**\n" << info.parameters << "\n\n";
        }
        
        if (!info.example.empty()) {
            content << "**مثال:**\n```ص\n" << info.example << "\n```\n\n";
        }
        
        content << "*من مكتبة `ui.واجهات`*";
        
        hover.contents.kind = MarkupKind::MARKDOWN;
        hover.contents.value = content.str();
        
        return hover;
    }
    
    /**
     * @brief إنشاء hover للكلمة المفتاحية
     */
    Hover create_keyword_hover(const std::string& doc) {
        Hover hover;
        hover.contents.kind = MarkupKind::MARKDOWN;
        hover.contents.value = doc;
        return hover;
    }
    
    /**
     * @brief إنشاء hover للنوع
     */
    Hover create_type_hover(const std::string& doc) {
        Hover hover;
        hover.contents.kind = MarkupKind::MARKDOWN;
        hover.contents.value = doc;
        return hover;
    }
    
    /**
     * @brief إنشاء hover لرمز من المستند
     */
    Hover create_symbol_hover(const SymbolInfo& sym) {
        Hover hover;
        
        std::ostringstream content;
        
        // النوع
        switch (sym.kind) {
            case SymbolKind::FUNCTION:
                content << "```ص\nدالة " << sym.name << "(...)\n```\n\n";
                break;
            case SymbolKind::VARIABLE:
                content << "```ص\n" << sym.detail << " " << sym.name << "\n```\n\n";
                break;
            case SymbolKind::CLASS:
                content << "```ص\nصنف " << sym.name << "\n```\n\n";
                break;
            case SymbolKind::CONSTANT:
                content << "```ص\nثابت " << sym.name << "\n```\n\n";
                break;
            default:
                content << "```ص\n" << sym.name << "\n```\n\n";
        }
        
        // التوثيق إن وجد
        if (!sym.documentation.empty()) {
            content << sym.documentation;
        } else {
            content << "*لا يوجد توثيق*";
        }
        
        hover.contents.kind = MarkupKind::MARKDOWN;
        hover.contents.value = content.str();
        
        return hover;
    }
};

