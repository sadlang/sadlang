/**
 * @brief مستوى خطورة مشكلة النمط
 * 
 * يحدد هذا التعداد مدى خطورة المشكلة المكتشفة في الكود:
 * - معلومة: نصيحة عامة لتحسين الكود
 * - تلميح: اقتراح لتحسين طفيف
 * - تحذير: مشكلة يجب معالجتها
 * - خطأ: انتهاك صريح لقواعد النمط
 */
enum class StyleSeverity {
    معلومة,         // Information - نصائح عامة
    تلميح,          // Hint - اقتراحات
    تحذير,          // Warning - تحذيرات
    خطأ             // Error - أخطاء النمط
};

/**
 * @brief فئة قاعدة النمط
 * 
 * تصنيف القواعد حسب نوعها لتسهيل الفلترة والتكوين
 */
enum class StyleCategory {
    تسمية,          // Naming - قواعد التسمية
    تنسيق,          // Formatting - قواعد التنسيق
    توثيق,          // Documentation - قواعد التوثيق
    تعقيد,          // Complexity - قواعد التعقيد
    ممارسات,        // Best Practices - الممارسات الأفضل
    أداء,           // Performance - قواعد الأداء
    أمان,           // Security - قواعد الأمان
    نظافة           // Clean Code - نظافة الكود
};

/**
 * @brief موقع في الكود
 * 
 * يحدد موقع مشكلة النمط بدقة في الملف
 */
struct StyleLocation {
    int سطر_البداية = 0;      // رقم السطر (يبدأ من 0)
    int عمود_البداية = 0;     // رقم العمود (يبدأ من 0)
    int سطر_النهاية = 0;      // سطر نهاية المشكلة
    int عمود_النهاية = 0;     // عمود نهاية المشكلة
    
    /**
     * @brief تحويل الموقع إلى نص للعرض
     */
    std::string إلى_نص() const {
        return "سطر " + std::to_string(سطر_البداية + 1) + 
               "، عمود " + std::to_string(عمود_البداية + 1);
    }
};

/**
 * @brief إصلاح مقترح لمشكلة النمط
 * 
 * يحتوي على تعديل يمكن تطبيقه تلقائياً لإصلاح المشكلة
 */
struct StyleFix {
    std::string وصف;              // وصف الإصلاح
    std::string النص_القديم;       // النص المراد استبداله
    std::string النص_الجديد;       // النص البديل
    StyleLocation الموقع;          // موقع التعديل
    bool آمن = true;              // هل الإصلاح آمن للتطبيق التلقائي؟
    
    /**
     * @brief إنشاء إصلاح بسيط
     */
    static StyleFix استبدال(const std::string& قديم, const std::string& جديد,
                           const StyleLocation& موقع, const std::string& وصف = "") {
        StyleFix fix;
        fix.النص_القديم = قديم;
        fix.النص_الجديد = جديد;
        fix.الموقع = موقع;
        fix.وصف = وصف.empty() ? "استبدال '" + قديم + "' بـ '" + جديد + "'" : وصف;
        return fix;
    }
};

/**
 * @brief مشكلة نمط مكتشفة
 * 
 * تمثل انتهاكاً واحداً لقواعد النمط مع كل التفاصيل اللازمة
 */
struct StyleIssue {
    std::string معرف_القاعدة;              // معرف فريد للقاعدة (مثل: "تسمية-001")
    std::string الرسالة;                   // رسالة الخطأ للمستخدم
    std::string الشرح;                     // شرح مفصل للمشكلة
    StyleSeverity الخطورة;                 // مستوى الخطورة
    StyleCategory الفئة;                   // فئة القاعدة
    StyleLocation الموقع;                  // موقع المشكلة
    std::vector<StyleFix> الإصلاحات;       // إصلاحات مقترحة
    std::string رابط_التوثيق;               // رابط لمزيد من المعلومات
    
    /**
     * @brief إنشاء مشكلة نمط جديدة
     */
    static StyleIssue إنشاء(
        const std::string& معرف,
        const std::string& رسالة,
        StyleSeverity خطورة,
        StyleCategory فئة,
        const StyleLocation& موقع
    ) {
        StyleIssue issue;
        issue.معرف_القاعدة = معرف;
        issue.الرسالة = رسالة;
        issue.الخطورة = خطورة;
        issue.الفئة = فئة;
        issue.الموقع = موقع;
        return issue;
    }
};

/**
 * @brief قاعدة نمط قابلة للتكوين
 * 
 * تعريف قاعدة نمط واحدة مع إمكانية التخصيص
 */
struct StyleRule {
    std::string المعرف;                    // معرف فريد
    std::string الاسم;                     // اسم القاعدة
    std::string الوصف;                     // وصف القاعدة
    StyleSeverity الخطورة_الافتراضية;       // الخطورة الافتراضية
    StyleCategory الفئة;                   // فئة القاعدة
    bool مفعلة = true;                     // هل القاعدة مفعلة؟
    std::map<std::string, std::string> خيارات;  // خيارات إضافية
    
    // دالة الفحص - تأخذ الكود وترجع قائمة المشاكل
    std::function<std::vector<StyleIssue>(const std::string&)> فحص;
};

