/**
 * @brief موقع في الكود المصدري
 */
struct CodeLocation {
    int سطر = 0;           ///< رقم السطر (يبدأ من 0)
    int عمود = 0;          ///< رقم العمود (يبدأ من 0)
    
    bool operator<(const CodeLocation& other) const {
        if (سطر != other.سطر) return سطر < other.سطر;
        return عمود < other.عمود;
    }
    
    bool operator==(const CodeLocation& other) const {
        return سطر == other.سطر && عمود == other.عمود;
    }
    
    std::string إلى_نص() const {
        return "سطر " + std::to_string(سطر + 1) + "، عمود " + std::to_string(عمود + 1);
    }
};

/**
 * @brief نطاق في الكود المصدري
 */
struct CodeRange {
    CodeLocation البداية;
    CodeLocation النهاية;
    
    bool فارغ() const {
        return البداية == النهاية;
    }
    
    bool يحتوي(const CodeLocation& موقع) const {
        if (موقع.سطر < البداية.سطر || موقع.سطر > النهاية.سطر) return false;
        if (موقع.سطر == البداية.سطر && موقع.عمود < البداية.عمود) return false;
        if (موقع.سطر == النهاية.سطر && موقع.عمود > النهاية.عمود) return false;
        return true;
    }
    
    std::string إلى_نص() const {
        return البداية.إلى_نص() + " إلى " + النهاية.إلى_نص();
    }
};

/**
 * @brief تعديل واحد في الكود
 * 
 * يمثل تغييراً واحداً سيتم تطبيقه على الكود.
 * كل عملية إعادة هيكلة تنتج قائمة من التعديلات.
 */
struct TextEdit {
    CodeRange النطاق;          ///< الجزء الذي سيتم استبداله
    std::string النص_الجديد;   ///< النص الذي سيحل محل النطاق
    std::string الوصف;         ///< شرح التعديل (للعرض على المستخدم)
    
    /**
     * @brief تطبيق التعديل على الكود
     * 
     * ملاحظة: هذه الدالة تفترض أن النطاق صحيح
     */
    std::string تطبيق(const std::string& الكود) const;
};

/**
 * @brief تعديلات على ملف واحد
 */
struct FileEdit {
    std::string مسار_الملف;
    std::vector<TextEdit> التعديلات;
    
    /**
     * @brief تطبيق جميع التعديلات على محتوى الملف
     * 
     * التعديلات تُطبق من النهاية للبداية لتجنب تعارض المواقع
     */
    std::string تطبيق(const std::string& المحتوى) const;
};

/**
 * @brief نتيجة عملية إعادة الهيكلة
 */
struct RefactoringResult {
    RefactoringStatus الحالة = RefactoringStatus::جاهز;
    std::string الرسالة;                    ///< رسالة للمستخدم
    std::vector<FileEdit> التعديلات;        ///< التعديلات على الملفات
    std::vector<std::string> التحذيرات;     ///< تحذيرات (لا تمنع التنفيذ)
    std::vector<std::string> الأخطاء;       ///< أخطاء (تمنع التنفيذ)
    
    /**
     * @brief هل العملية ناجحة؟
     */
    bool نجاح() const {
        return الحالة == RefactoringStatus::جاهز || 
               الحالة == RefactoringStatus::تحذير;
    }
    
    /**
     * @brief معاينة نصية للتعديلات
     */
    std::string معاينة() const;
};

/**
 * @brief معلومات رمز (متغير، دالة، الخ)
 */
struct Symbol {
    std::string الاسم;
    std::string النوع;              ///< "متغير"، "دالة"، "ثابت"، الخ
    CodeRange نطاق_التعريف;
    std::vector<CodeRange> المراجع; ///< أماكن الاستخدام
    std::string الملف;
    
    bool مُعرَّف() const { return !نطاق_التعريف.فارغ(); }
};

/**
 * @brief معلومات دالة مستخرجة
 */
struct ExtractedFunction {
    std::string الاسم;
    std::vector<std::string> المعاملات;     ///< المتغيرات الداخلة
    std::vector<std::string> المُرجعات;     ///< المتغيرات الخارجة
    std::string الجسم;                       ///< محتوى الدالة
    std::string توقيع_الدالة;                ///< التوقيع الكامل
    std::string استدعاء_الدالة;              ///< كود الاستدعاء
};

