/**
 * @brief خيارات إعادة التسمية
 */
struct RenameOptions {
    bool تضمين_التعليقات = true;        ///< تحديث الأسماء في التعليقات أيضاً
    bool تضمين_النصوص = false;          ///< تحديث الأسماء في النصوص (خطر!)
    bool معاينة_أولاً = true;           ///< طلب معاينة قبل التطبيق
    bool تحقق_من_التعارضات = true;      ///< التحقق من عدم وجود اسم مشابه
};

/**
 * @brief خيارات استخراج الدالة
 */
struct ExtractFunctionOptions {
    std::string اسم_الدالة = "";           ///< اسم الدالة الجديدة
    bool إنشاء_توثيق = true;               ///< إضافة توثيق للدالة
    bool استنتاج_المعاملات = true;         ///< تحليل المتغيرات المطلوبة تلقائياً
    bool استخدام_مرجع = false;             ///< استخدام المراجع للمعاملات الكبيرة
};

/**
 * @brief خيارات استخراج المتغير
 */
struct ExtractVariableOptions {
    std::string اسم_المتغير = "";
    bool استبدال_جميع_التكرارات = true;    ///< استبدال جميع التكرارات المطابقة
    bool جعله_ثابتاً = false;               ///< إنشاء ثابت بدلاً من متغير
};

