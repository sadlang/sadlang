/**
 * @class RefactoringProvider
 * @brief المزود الرئيسي لعمليات إعادة الهيكلة
 * 
 * ─────────────────────────────────────────────────────────────────────────────
 * الوصف المفصل:
 * ─────────────────────────────────────────────────────────────────────────────
 * 
 * هذا الصنف يوفر واجهة شاملة لجميع عمليات إعادة الهيكلة.
 * يعمل بذكاء على تحليل الكود وضمان سلامة التغييرات.
 * 
 * ─────────────────────────────────────────────────────────────────────────────
 * المبادئ الأساسية:
 * ─────────────────────────────────────────────────────────────────────────────
 * 
 * 1. السلامة أولاً:
 *    - كل عملية تُفحص للتأكد من عدم كسر الكود
 *    - التحذير من التغييرات الخطرة
 *    - إمكانية المعاينة قبل التطبيق
 * 
 * 2. الذكاء:
 *    - تحليل سياق الكود لاقتراح أفضل الخيارات
 *    - اقتراح أسماء مناسبة
 *    - الكشف عن المشاكل المحتملة
 * 
 * 3. الشمولية:
 *    - تحديث جميع المراجع تلقائياً
 *    - التعامل مع ملفات متعددة
 *    - دعم اللغة العربية الكامل
 * 
 * ─────────────────────────────────────────────────────────────────────────────
 * أمثلة الاستخدام:
 * ─────────────────────────────────────────────────────────────────────────────
 * 
 * // مثال 1: إعادة تسمية متغير
 * RefactoringProvider مساعد;
 * auto نتيجة = مساعد.إعادة_تسمية(الكود, موقع_المتغير, "الاسم_الجديد");
 * if (نتيجة.نجاح()) {
 *     auto الكود_الجديد = نتيجة.التعديلات[0].تطبيق(الكود);
 * }
 * 
 * // مثال 2: استخراج دالة
 * ExtractFunctionOptions خيارات;
 * خيارات.اسم_الدالة = "حساب_المجموع";
 * auto نتيجة = مساعد.استخراج_دالة(الكود, البداية, النهاية, خيارات);
 * 
 * ─────────────────────────────────────────────────────────────────────────────
 */
class RefactoringProvider {
public:
    // ═════════════════════════════════════════════════════════════════════════
    //                              المُنشئات
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief المُنشئ الافتراضي
     */
    RefactoringProvider();
    
    /**
     * @brief المُدمر
     */
    ~RefactoringProvider() = default;
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              إعادة التسمية
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief إعادة تسمية رمز
     * 
     * تبحث عن تعريف الرمز في الموقع المحدد وتغير اسمه
     * في جميع الأماكن (التعريف والاستخدامات).
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع الرمز المراد تغيير اسمه
     * @param الاسم_الجديد الاسم الجديد
     * @param خيارات خيارات إضافية
     * @return نتيجة العملية مع التعديلات
     */
    RefactoringResult إعادة_تسمية(
        const std::string& الكود,
        const CodeLocation& الموقع,
        const std::string& الاسم_الجديد,
        const RenameOptions& خيارات = RenameOptions{});
    
    /**
     * @brief معاينة إعادة التسمية
     * 
     * تعرض جميع الأماكن التي سيتم تغييرها دون تطبيق التغيير.
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع الرمز
     * @return قائمة بجميع المواقع التي ستتغير
     */
    std::vector<CodeRange> معاينة_إعادة_التسمية(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    /**
     * @brief التحقق من صلاحية الاسم الجديد
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع الرمز الأصلي
     * @param الاسم_الجديد الاسم المقترح
     * @return رسالة خطأ إذا كان الاسم غير صالح، أو نص فارغ إذا كان صالحاً
     */
    std::string التحقق_من_اسم(
        const std::string& الكود,
        const CodeLocation& الموقع,
        const std::string& الاسم_الجديد);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              استخراج الدوال
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief استخراج نطاق من الكود إلى دالة جديدة
     * 
     * هذه العملية تأخذ جزءاً من الكود وتحوله إلى دالة منفصلة،
     * ثم تستبدل الجزء الأصلي باستدعاء للدالة الجديدة.
     * 
     * ─────────────────────────────────────────────────────────────────────
     * مثال:
     * ─────────────────────────────────────────────────────────────────────
     * قبل:
     *   دالة الرئيسية() {
     *       // كود طويل للحساب
     *       متغير س = 10
     *       متغير ص = 20
     *       متغير النتيجة = س + ص * 2
     *       اطبع(النتيجة)
     *   }
     * 
     * بعد استخراج السطور 3-5:
     *   دالة حساب_النتيجة(س، ص) {
     *       متغير النتيجة = س + ص * 2
     *       أرجع النتيجة
     *   }
     *   
     *   دالة الرئيسية() {
     *       // كود طويل للحساب
     *       متغير س = 10
     *       متغير ص = 20
     *       متغير النتيجة = حساب_النتيجة(س، ص)
     *       اطبع(النتيجة)
     *   }
     * ─────────────────────────────────────────────────────────────────────
     * 
     * @param الكود الكود المصدري
     * @param النطاق نطاق الكود المراد استخراجه
     * @param خيارات خيارات الاستخراج
     * @return نتيجة العملية مع الدالة الجديدة والتعديلات
     */
    RefactoringResult استخراج_دالة(
        const std::string& الكود,
        const CodeRange& النطاق,
        const ExtractFunctionOptions& خيارات = ExtractFunctionOptions{});
    
    /**
     * @brief تحليل النطاق لمعرفة إمكانية الاستخراج
     * 
     * تحلل الكود المحدد لمعرفة:
     * - المتغيرات المطلوبة (الداخلة)
     * - المتغيرات المُنتجة (الخارجة)
     * - هل الاستخراج ممكن؟
     * 
     * @param الكود الكود المصدري
     * @param النطاق نطاق الكود
     * @return معلومات عن الدالة المحتملة
     */
    ExtractedFunction تحليل_للاستخراج(
        const std::string& الكود,
        const CodeRange& النطاق);
    
    /**
     * @brief اقتراح اسم للدالة المُستخرجة
     * 
     * تحلل محتوى الكود وتقترح اسماً مناسباً للدالة.
     * 
     * @param الكود الكود المستخرج
     * @return اسم مقترح
     */
    std::string اقتراح_اسم_دالة(const std::string& الكود);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              استخراج المتغيرات
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief استخراج تعبير إلى متغير
     * 
     * تأخذ تعبيراً وتنشئ له متغيراً منفصلاً، ثم تستبدل
     * التعبير باسم المتغير.
     * 
     * ─────────────────────────────────────────────────────────────────────
     * مثال:
     * ─────────────────────────────────────────────────────────────────────
     * قبل:
     *   اطبع(س * 2 + ص * 3)
     * 
     * بعد استخراج "س * 2 + ص * 3":
     *   متغير النتيجة = س * 2 + ص * 3
     *   اطبع(النتيجة)
     * ─────────────────────────────────────────────────────────────────────
     * 
     * @param الكود الكود المصدري
     * @param النطاق نطاق التعبير
     * @param خيارات خيارات الاستخراج
     * @return نتيجة العملية
     */
    RefactoringResult استخراج_متغير(
        const std::string& الكود,
        const CodeRange& النطاق,
        const ExtractVariableOptions& خيارات = ExtractVariableOptions{});
    
    /**
     * @brief استخراج قيمة إلى ثابت
     * 
     * مشابه لاستخراج متغير لكن ينشئ ثابتاً.
     * مفيد للقيم السحرية (magic numbers).
     * 
     * @param الكود الكود المصدري
     * @param النطاق نطاق القيمة
     * @param اسم_الثابت اسم الثابت الجديد
     * @return نتيجة العملية
     */
    RefactoringResult استخراج_ثابت(
        const std::string& الكود,
        const CodeRange& النطاق,
        const std::string& اسم_الثابت);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              دمج (Inline) العناصر
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief دمج دالة (استبدال الاستدعاء بالمحتوى)
     * 
     * تأخذ استدعاء دالة وتستبدله بمحتوى الدالة الفعلي.
     * مفيد للدوال الصغيرة جداً.
     * 
     * ─────────────────────────────────────────────────────────────────────
     * مثال:
     * ─────────────────────────────────────────────────────────────────────
     * قبل:
     *   دالة مربع(س) { أرجع س * س }
     *   متغير النتيجة = مربع(5)
     * 
     * بعد دمج "مربع(5)":
     *   متغير النتيجة = 5 * 5
     * ─────────────────────────────────────────────────────────────────────
     * 
     * @param الكود الكود المصدري
     * @param موقع_الاستدعاء موقع استدعاء الدالة
     * @return نتيجة العملية
     */
    RefactoringResult دمج_دالة(
        const std::string& الكود,
        const CodeLocation& موقع_الاستدعاء);
    
    /**
     * @brief دمج متغير (استبدال الاسم بالقيمة)
     * 
     * تستبدل جميع استخدامات المتغير بقيمته مباشرة.
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع المتغير
     * @return نتيجة العملية
     */
    RefactoringResult دمج_متغير(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              تحويلات الكود
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief تحويل if متعدد إلى switch
     * 
     * تحول سلسلة من if-else إلى بنية switch أكثر وضوحاً.
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع أول if
     * @return نتيجة العملية
     */
    RefactoringResult تحويل_إلى_switch(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    /**
     * @brief تحويل switch إلى if
     * 
     * تحول بنية switch إلى سلسلة if-else.
     * مفيد عندما تكون الشروط معقدة.
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع switch
     * @return نتيجة العملية
     */
    RefactoringResult تحويل_إلى_if(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    /**
     * @brief تبسيط شرط معقد
     * 
     * تحلل شرطاً معقداً وتحاول تبسيطه.
     * مثال: !(أ || ب) → !أ && !ب (قانون دي مورغان)
     * 
     * @param الكود الكود المصدري
     * @param الموقع موقع الشرط
     * @return نتيجة العملية
     */
    RefactoringResult تبسيط_شرط(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              تنظيم الكود
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief تنظيم الاستيرادات
     * 
     * - ترتيب أبجدي
     * - تجميع حسب المصدر
     * - إزالة غير المستخدمة
     * - إضافة المفقودة
     * 
     * @param الكود الكود المصدري
     * @return نتيجة العملية
     */
    RefactoringResult تنظيم_الاستيرادات(const std::string& الكود);
    
    /**
     * @brief إزالة الكود الميت
     * 
     * تبحث عن متغيرات ودوال غير مستخدمة وتقترح إزالتها.
     * 
     * @param الكود الكود المصدري
     * @return نتيجة العملية
     */
    RefactoringResult إزالة_كود_ميت(const std::string& الكود);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              الاقتراحات الذكية
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief الحصول على عمليات إعادة الهيكلة المتاحة
     * 
     * تحلل الموقع الحالي وتقترح عمليات إعادة الهيكلة المناسبة.
     * 
     * @param الكود الكود المصدري
     * @param الموقع الموقع الحالي للمؤشر
     * @return قائمة بالعمليات المتاحة
     */
    std::vector<std::pair<RefactoringKind, std::string>> 
    الحصول_على_العمليات_المتاحة(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    /**
     * @brief الحصول على عمليات إعادة الهيكلة للنطاق
     * 
     * @param الكود الكود المصدري  
     * @param النطاق النطاق المحدد
     * @return قائمة بالعمليات المتاحة
     */
    std::vector<std::pair<RefactoringKind, std::string>>
    الحصول_على_عمليات_النطاق(
        const std::string& الكود,
        const CodeRange& النطاق);
    
private:
    // ═════════════════════════════════════════════════════════════════════════
    //                              دوال مساعدة خاصة
    // ═════════════════════════════════════════════════════════════════════════
    
    /**
     * @brief إيجاد الرمز في الموقع المحدد
     */
    std::optional<Symbol> إيجاد_الرمز_(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    /**
     * @brief إيجاد جميع مراجع الرمز
     */
    std::vector<CodeRange> إيجاد_المراجع_(
        const std::string& الكود,
        const std::string& اسم_الرمز);
    
    /**
     * @brief تحليل المتغيرات في نطاق
     */
    void تحليل_المتغيرات_(
        const std::string& الكود,
        const CodeRange& النطاق,
        std::set<std::string>& المُستخدمة,
        std::set<std::string>& المُعرَّفة);
    
    /**
     * @brief التحقق من صحة المعرف
     */
    bool معرف_صالح_(const std::string& الاسم);
    
    /**
     * @brief استخراج نص من نطاق
     */
    std::string استخراج_نص_(
        const std::string& الكود,
        const CodeRange& النطاق);
    
    /**
     * @brief تقسيم الكود إلى أسطر
     */
    std::vector<std::string> تقسيم_أسطر_(const std::string& الكود);
    
    /**
     * @brief حساب الإزاحة من الموقع
     */
    size_t موقع_إلى_إزاحة_(
        const std::string& الكود,
        const CodeLocation& الموقع);
    
    /**
     * @brief حساب الموقع من الإزاحة
     */
    CodeLocation إزاحة_إلى_موقع_(
        const std::string& الكود,
        size_t الإزاحة);
    
    // ═════════════════════════════════════════════════════════════════════════
    //                              البيانات الخاصة
    // ═════════════════════════════════════════════════════════════════════════
    
    /// ذاكرة مؤقتة للرموز المُحللة
    mutable std::map<std::string, std::vector<Symbol>> ذاكرة_الرموز_;
    
    /// الكلمات المحجوزة في اللغة
    std::set<std::string> الكلمات_المحجوزة_;
};

