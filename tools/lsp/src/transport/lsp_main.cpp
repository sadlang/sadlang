#include "lsp_engine.h"
#include "json_rpc_transport.h"
#include "utf8_args.h"

#include <iostream>
#include <cstring>

#ifdef _WIN32
#include <windows.h>
#endif

using namespace sad::lsp;
using namespace sad::lsp::transport;

/// طباعة معلومات الإصدار
static void print_version()
{
    std::cerr << "خادم لغة ص الثوري (SAD LSP Server) v2.0.0" << std::endl;
    std::cerr << "بروتوكول LSP 3.17" << std::endl;
    std::cerr << "الحمد لله رب العالمين" << std::endl;
}

/// طباعة المساعدة
static void print_help()
{
    std::cerr << R"(
╔═══════════════════════════════════════════════════════════════════╗
║            خادم بروتوكول اللغة الثوري للغة ص                     ║
║         SAD Language Server Protocol (LSP) Server                ║
╚═══════════════════════════════════════════════════════════════════╝

الاستخدام:
  sad-lsp [خيارات]

الخيارات:
  --stdio     استخدام stdin/stdout للتواصل (افتراضي)
  --version   عرض معلومات الإصدار
  --help      عرض هذه المساعدة

متغيرات البيئة:
  SAD_LSP_LOG=<مسار>   تمكين السجل في ملف

أمثلة:
  sad-lsp --stdio                    # تشغيل الخادم
  SAD_LSP_LOG=lsp.log sad-lsp       # تشغيل مع سجل

للاستخدام مع VS Code:
  قم بتثبيت إضافة لغة ص التي تدعم LSP
  الإضافة ستشغل الخادم تلقائياً

)" << std::endl;
}

int main(int argc, char *argv[])
{
#ifdef _WIN32
    // تعيين صفحة الترميز إلى UTF-8
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);
#endif
    // (AR) ربط argv بـUTF-8 لدعم الأسماء العربية على ويندوز
    Sad::Utils::Utf8ArgvHolder _argvHolder(argc, argv);

    // معالجة وسائط سطر الأوامر
    for (int i = 1; i < argc; ++i)
    {
        if (std::strcmp(argv[i], "--version") == 0 || std::strcmp(argv[i], "-v") == 0)
        {
            print_version();
            return 0;
        }
        if (std::strcmp(argv[i], "--help") == 0 || std::strcmp(argv[i], "-h") == 0)
        {
            print_help();
            return 0;
        }
        if (std::strcmp(argv[i], "--stdio") == 0)
        {
            // الوضع الافتراضي - لا شيء مطلوب
            continue;
        }
        // وسيط غير معروف
        std::cerr << "وسيط غير معروف: " << argv[i] << std::endl;
        std::cerr << "استخدم --help للمساعدة" << std::endl;
        return 1;
    }

    // إنشاء المحرك الأساسي
    LspEngine engine;

    // إنشاء طبقة النقل وربطها بالمحرك
    JsonRpcTransport transport(engine);

    // تشغيل حلقة الخادم الرئيسية
    // ستعمل حتى يتم إغلاق stdin أو استقبال طلب exit
    transport.run();

    return 0;
}
