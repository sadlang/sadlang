/**
 * نوع أمر التنقل
 */
enum class نوع_التنقل {
    // موضع
    سطر,
    عمود,
    موضع,
    
    // رمز
    دالة,
    صنف,
    متغير,
    تعريف,
    استخدام,
    
    // ملف
    ملف,
    مجلد,
    
    // نسبي
    أعلى,
    أسفل,
    يمين,
    يسار,
    بداية_سطر,
    نهاية_سطر,
    بداية_ملف,
    نهاية_ملف,
    
    // كتلة
    بداية_كتلة,
    نهاية_كتلة,
    كتلة_تالية,
    كتلة_سابقة,
    
    // بحث
    بحث_تالي,
    بحث_سابق,
    
    // سجل
    موضع_سابق,
    موضع_تالي
};

// ==========================================================
// 📌 أمر التنقل
// ==========================================================

/**
 * أمر تنقل مُحلل
 */
struct أمر_تنقل {
    نوع_التنقل نوع;
    std::string هدف;        // اسم الدالة/الصنف/الملف
    int رقم = 0;            // رقم السطر/العمود
    int كمية = 1;           // عدد مرات التكرار
    bool تحديد = false;     // هل مع تحديد؟
    
    bool صالح() const {
        return نوع != نوع_التنقل::سطر || رقم > 0 || !هدف.empty();
    }
};

/**
 * موضع في الكود
 */
struct موضع {
    std::string ملف;
    int سطر = 1;
    int عمود = 1;
    
    bool operator==(const موضع& آخر) const {
        return ملف == آخر.ملف && سطر == آخر.سطر && عمود == آخر.عمود;
    }
};

