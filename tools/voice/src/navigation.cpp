/**
 * واجهة المحرر
 */
class واجهة_المحرر {
public:
    virtual ~واجهة_المحرر() = default;
    
    virtual موضع الموضع_الحالي() = 0;
    virtual void انتقل_إلى(const موضع& م) = 0;
    virtual void افتح_ملف(const std::string& مسار) = 0;
    virtual int عدد_الأسطر() = 0;
    virtual int طول_السطر(int سطر) = 0;
    virtual std::string محتوى_السطر(int سطر) = 0;
};

/**
 * منفذ أوامر التنقل
 */
class منفذ_التنقل {
private:
    واجهة_المحرر* محرر_ = nullptr;
    std::vector<موضع> سجل_المواضع_;
    size_t مؤشر_السجل_ = 0;
    
public:
    void عيّن_المحرر(واجهة_المحرر* محرر) {
        محرر_ = محرر;
    }
    
    /**
     * تنفيذ أمر تنقل
     */
    bool نفّذ(const أمر_تنقل& أمر) {
        if (!محرر_) return false;
        
        // حفظ الموضع الحالي في السجل
        سجل_الموضع_الحالي();
        
        switch (أمر.نوع) {
            case نوع_التنقل::سطر:
                return انتقل_سطر(أمر.رقم);
                
            case نوع_التنقل::دالة:
                return انتقل_دالة(أمر.هدف);
                
            case نوع_التنقل::صنف:
                return انتقل_صنف(أمر.هدف);
                
            case نوع_التنقل::ملف:
                return افتح_ملف(أمر.هدف);
                
            case نوع_التنقل::أعلى:
                return تحرك_نسبي(-أمر.كمية, 0);
                
            case نوع_التنقل::أسفل:
                return تحرك_نسبي(أمر.كمية, 0);
                
            case نوع_التنقل::يمين:
                return تحرك_نسبي(0, أمر.كمية);
                
            case نوع_التنقل::يسار:
                return تحرك_نسبي(0, -أمر.كمية);
                
            case نوع_التنقل::بداية_سطر:
                return انتقل_بداية_سطر();
                
            case نوع_التنقل::نهاية_سطر:
                return انتقل_نهاية_سطر();
                
            case نوع_التنقل::بداية_ملف:
                return انتقل_بداية_ملف();
                
            case نوع_التنقل::نهاية_ملف:
                return انتقل_نهاية_ملف();
                
            case نوع_التنقل::موضع_سابق:
                return انتقل_موضع_سابق();
                
            case نوع_التنقل::موضع_تالي:
                return انتقل_موضع_تالي();
                
            default:
                return false;
        }
    }
    
private:
    void سجل_الموضع_الحالي() {
        موضع حالي = محرر_->الموضع_الحالي();
        
        // تجنب التكرار
        if (سجل_المواضع_.empty() || !(سجل_المواضع_.back() == حالي)) {
            // إزالة المواضع بعد المؤشر الحالي
            while (سجل_المواضع_.size() > مؤشر_السجل_ + 1) {
                سجل_المواضع_.pop_back();
            }
            
            سجل_المواضع_.push_back(حالي);
            مؤشر_السجل_ = سجل_المواضع_.size() - 1;
        }
    }
    
    bool انتقل_سطر(int سطر) {
        if (سطر < 1 || سطر > محرر_->عدد_الأسطر()) {
            return false;
        }
        
        موضع م = محرر_->الموضع_الحالي();
        م.سطر = سطر;
        م.عمود = 1;
        محرر_->انتقل_إلى(م);
        return true;
    }
    
    bool انتقل_دالة(const std::string& اسم) {
        // بحث عن الدالة في الملف
        for (int ل = 1; ل <= محرر_->عدد_الأسطر(); ++ل) {
            std::string سطر = محرر_->محتوى_السطر(ل);
            if (سطر.find("دالة " + اسم) != std::string::npos ||
                سطر.find("دالة  " + اسم) != std::string::npos) {
                return انتقل_سطر(ل);
            }
        }
        return false;
    }
    
    bool انتقل_صنف(const std::string& اسم) {
        for (int ل = 1; ل <= محرر_->عدد_الأسطر(); ++ل) {
            std::string سطر = محرر_->محتوى_السطر(ل);
            if (سطر.find("صنف " + اسم) != std::string::npos) {
                return انتقل_سطر(ل);
            }
        }
        return false;
    }
    
    bool افتح_ملف(const std::string& مسار) {
        محرر_->افتح_ملف(مسار);
        return true;
    }
    
    bool تحرك_نسبي(int أسطر, int أعمدة) {
        موضع م = محرر_->الموضع_الحالي();
        م.سطر += أسطر;
        م.عمود += أعمدة;
        
        // التحقق من الحدود
        م.سطر = std::max(1, std::min(م.سطر, محرر_->عدد_الأسطر()));
        م.عمود = std::max(1, م.عمود);
        
        محرر_->انتقل_إلى(م);
        return true;
    }
    
    bool انتقل_بداية_سطر() {
        موضع م = محرر_->الموضع_الحالي();
        م.عمود = 1;
        محرر_->انتقل_إلى(م);
        return true;
    }
    
    bool انتقل_نهاية_سطر() {
        موضع م = محرر_->الموضع_الحالي();
        م.عمود = محرر_->طول_السطر(م.سطر);
        محرر_->انتقل_إلى(م);
        return true;
    }
    
    bool انتقل_بداية_ملف() {
        موضع م;
        م.ملف = محرر_->الموضع_الحالي().ملف;
        م.سطر = 1;
        م.عمود = 1;
        محرر_->انتقل_إلى(م);
        return true;
    }
    
    bool انتقل_نهاية_ملف() {
        موضع م = محرر_->الموضع_الحالي();
        م.سطر = محرر_->عدد_الأسطر();
        م.عمود = محرر_->طول_السطر(م.سطر);
        محرر_->انتقل_إلى(م);
        return true;
    }
    
    bool انتقل_موضع_سابق() {
        if (مؤشر_السجل_ > 0) {
            مؤشر_السجل_--;
            محرر_->انتقل_إلى(سجل_المواضع_[مؤشر_السجل_]);
            return true;
        }
        return false;
    }
    
    bool انتقل_موضع_تالي() {
        if (مؤشر_السجل_ < سجل_المواضع_.size() - 1) {
            مؤشر_السجل_++;
            محرر_->انتقل_إلى(سجل_المواضع_[مؤشر_السجل_]);
            return true;
        }
        return false;
    }
};

