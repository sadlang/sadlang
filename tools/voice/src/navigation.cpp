/**
 * محلل أوامر التنقل الصوتية
 */
class محلل_التنقل {
private:
    // قاموس الأرقام
    std::unordered_map<std::string, int> أرقام_;
    
public:
    محلل_التنقل() {
        تهيئة_الأرقام();
    }
    
    /**
     * تحليل نص إلى أمر تنقل
     */
    أمر_تنقل حلّل(const std::string& نص) {
        أمر_تنقل أمر;
        
        // أنماط التنقل
        if (تطابق_سطر(نص, أمر)) return أمر;
        if (تطابق_دالة(نص, أمر)) return أمر;
        if (تطابق_صنف(نص, أمر)) return أمر;
        if (تطابق_ملف(نص, أمر)) return أمر;
        if (تطابق_نسبي(نص, أمر)) return أمر;
        if (تطابق_كتلة(نص, أمر)) return أمر;
        
        return أمر;
    }
    
private:
    void تهيئة_الأرقام() {
        أرقام_["صفر"] = 0;
        أرقام_["واحد"] = 1;
        أرقام_["اثنين"] = 2;
        أرقام_["اثنان"] = 2;
        أرقام_["ثلاثة"] = 3;
        أرقام_["أربعة"] = 4;
        أرقام_["خمسة"] = 5;
        أرقام_["ستة"] = 6;
        أرقام_["سبعة"] = 7;
        أرقام_["ثمانية"] = 8;
        أرقام_["تسعة"] = 9;
        أرقام_["عشرة"] = 10;
        أرقام_["عشرين"] = 20;
        أرقام_["ثلاثين"] = 30;
        أرقام_["أربعين"] = 40;
        أرقام_["خمسين"] = 50;
        أرقام_["مئة"] = 100;
    }
    
    int حوّل_رقم(const std::string& نص) {
        auto it = أرقام_.find(نص);
        if (it != أرقام_.end()) {
            return it->second;
        }
        
        try {
            return std::stoi(نص);
        } catch (...) {
            return 0;
        }
    }
    
    bool تطابق_سطر(const std::string& نص, أمر_تنقل& أمر) {
        std::regex نمط("(?:اذهب\\s+)?(?:إلى\\s+)?(?:ال)?سطر\\s+(\\S+)", std::regex::icase);
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            أمر.نوع = نوع_التنقل::سطر;
            أمر.رقم = حوّل_رقم(مطابقات[1].str());
            return true;
        }
        
        return false;
    }
    
    bool تطابق_دالة(const std::string& نص, أمر_تنقل& أمر) {
        std::regex نمط("(?:اذهب\\s+)?(?:إلى\\s+)?(?:ال)?دالة\\s+(\\S+)", std::regex::icase);
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            أمر.نوع = نوع_التنقل::دالة;
            أمر.هدف = مطابقات[1].str();
            return true;
        }
        
        return false;
    }
    
    bool تطابق_صنف(const std::string& نص, أمر_تنقل& أمر) {
        std::regex نمط("(?:اذهب\\s+)?(?:إلى\\s+)?(?:ال)?صنف\\s+(\\S+)", std::regex::icase);
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            أمر.نوع = نوع_التنقل::صنف;
            أمر.هدف = مطابقات[1].str();
            return true;
        }
        
        return false;
    }
    
    bool تطابق_ملف(const std::string& نص, أمر_تنقل& أمر) {
        std::regex نمط("(?:افتح\\s+)?(?:ال)?ملف\\s+(\\S+)", std::regex::icase);
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            أمر.نوع = نوع_التنقل::ملف;
            أمر.هدف = مطابقات[1].str();
            return true;
        }
        
        return false;
    }
    
    bool تطابق_نسبي(const std::string& نص, أمر_تنقل& أمر) {
        // أعلى/أسفل/يمين/يسار
        if (نص.find("أعلى") != std::string::npos || نص.find("فوق") != std::string::npos) {
            أمر.نوع = نوع_التنقل::أعلى;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("أسفل") != std::string::npos || نص.find("تحت") != std::string::npos) {
            أمر.نوع = نوع_التنقل::أسفل;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("يمين") != std::string::npos) {
            أمر.نوع = نوع_التنقل::يمين;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("يسار") != std::string::npos || نص.find("شمال") != std::string::npos) {
            أمر.نوع = نوع_التنقل::يسار;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        // بداية/نهاية
        if (نص.find("بداية السطر") != std::string::npos || نص.find("أول السطر") != std::string::npos) {
            أمر.نوع = نوع_التنقل::بداية_سطر;
            return true;
        }
        
        if (نص.find("نهاية السطر") != std::string::npos || نص.find("آخر السطر") != std::string::npos) {
            أمر.نوع = نوع_التنقل::نهاية_سطر;
            return true;
        }
        
        if (نص.find("بداية الملف") != std::string::npos || نص.find("أول الملف") != std::string::npos) {
            أمر.نوع = نوع_التنقل::بداية_ملف;
            return true;
        }
        
        if (نص.find("نهاية الملف") != std::string::npos || نص.find("آخر الملف") != std::string::npos) {
            أمر.نوع = نوع_التنقل::نهاية_ملف;
            return true;
        }
        
        return false;
    }
    
    bool تطابق_كتلة(const std::string& نص, أمر_تنقل& أمر) {
        if (نص.find("بداية الكتلة") != std::string::npos) {
            أمر.نوع = نوع_التنقل::بداية_كتلة;
            return true;
        }
        
        if (نص.find("نهاية الكتلة") != std::string::npos) {
            أمر.نوع = نوع_التنقل::نهاية_كتلة;
            return true;
        }
        
        if (نص.find("الكتلة التالية") != std::string::npos) {
            أمر.نوع = نوع_التنقل::كتلة_تالية;
            return true;
        }
        
        if (نص.find("الكتلة السابقة") != std::string::npos) {
            أمر.نوع = نوع_التنقل::كتلة_سابقة;
            return true;
        }
        
        return false;
    }
    
    int استخرج_كمية(const std::string& نص) {
        // بحث عن رقم في النص
        std::regex نمط("(\\d+)");
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            return std::stoi(مطابقات[1].str());
        }
        
        // بحث عن رقم بالعربي
        for (const auto& [كلمة, قيمة] : أرقام_) {
            if (نص.find(كلمة) != std::string::npos) {
                return قيمة;
            }
        }
        
        return 1;  // القيمة الافتراضية
    }
};

