/**
 * نظام التنقل الصوتي الكامل
 */
class نظام_التنقل {
private:
    محلل_التنقل محلل_;
    منفذ_التنقل منفذ_;
    
public:
    نظام_التنقل() = default;
    
    /**
     * تعيين المحرر
     */
    void عيّن_المحرر(واجهة_المحرر* محرر) {
        منفذ_.عيّن_المحرر(محرر);
    }
    
    /**
     * معالجة أمر صوتي
     */
    bool عالج(const std::string& نص) {
        أمر_تنقل أمر = محلل_.حلّل(نص);
        
        if (!أمر.صالح()) {
            return false;
        }
        
        return منفذ_.نفّذ(أمر);
    }
};

