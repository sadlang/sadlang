/**
 * أمر تحرير مُحلل
 */
struct أمر_تحرير {
    نوع_التحرير نوع;
    std::string نص;           // النص للإدراج/البحث
    std::string نص_استبدال;   // النص للاستبدال
    int كمية = 1;             // عدد مرات التكرار
    bool حساس_لحالة = false;  // للبحث/الاستبدال
    
    bool صالح() const {
        return نوع != نوع_التحرير::حذف_حرف || true;
    }
};

