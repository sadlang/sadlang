/**
 * محلل أوامر التحرير الصوتية
 */
class محلل_التحرير {
private:
    std::unordered_map<std::string, int> أرقام_;
    
public:
    محلل_التحرير() {
        تهيئة_الأرقام();
    }
    
    /**
     * تحليل نص إلى أمر تحرير
     */
    أمر_تحرير حلّل(const std::string& نص) {
        أمر_تحرير أمر;
        
        // أوامر الحذف
        if (تطابق_حذف(نص, أمر)) return أمر;
        
        // أوامر النسخ
        if (تطابق_نسخ(نص, أمر)) return أمر;
        
        // أوامر القص
        if (تطابق_قص(نص, أمر)) return أمر;
        
        // أوامر اللصق
        if (تطابق_لصق(نص, أمر)) return أمر;
        
        // أوامر التراجع/الإعادة
        if (تطابق_تراجع_إعادة(نص, أمر)) return أمر;
        
        // أوامر التحديد
        if (تطابق_تحديد(نص, أمر)) return أمر;
        
        // أوامر الاستبدال
        if (تطابق_استبدال(نص, أمر)) return أمر;
        
        // أوامر الأسطر
        if (تطابق_أسطر(نص, أمر)) return أمر;
        
        // أوامر التعليقات
        if (تطابق_تعليق(نص, أمر)) return أمر;
        
        // أوامر الإدراج
        if (تطابق_إدراج(نص, أمر)) return أمر;
        
        // أوامر الحفظ
        if (تطابق_حفظ(نص, أمر)) return أمر;
        
        return أمر;
    }
    
private:
    void تهيئة_الأرقام() {
        أرقام_["واحد"] = 1;
        أرقام_["اثنين"] = 2;
        أرقام_["ثلاثة"] = 3;
        أرقام_["أربعة"] = 4;
        أرقام_["خمسة"] = 5;
        أرقام_["عشرة"] = 10;
    }
    
    int استخرج_كمية(const std::string& نص) {
        std::regex نمط("(\\d+)");
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            return std::stoi(مطابقات[1].str());
        }
        
        for (const auto& [كلمة, قيمة] : أرقام_) {
            if (نص.find(كلمة) != std::string::npos) {
                return قيمة;
            }
        }
        
        return 1;
    }
    
    bool تطابق_حذف(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("احذف") == std::string::npos && 
            نص.find("امسح") == std::string::npos) {
            return false;
        }
        
        if (نص.find("السطر") != std::string::npos) {
            أمر.نوع = نوع_التحرير::حذف_سطر;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("الكلمة") != std::string::npos) {
            أمر.نوع = نوع_التحرير::حذف_كلمة;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("الحرف") != std::string::npos) {
            أمر.نوع = نوع_التحرير::حذف_حرف;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("التحديد") != std::string::npos || نص.find("المحدد") != std::string::npos) {
            أمر.نوع = نوع_التحرير::حذف_تحديد;
            return true;
        }
        
        if (نص.find("حتى نهاية") != std::string::npos || نص.find("للآخر") != std::string::npos) {
            أمر.نوع = نوع_التحرير::حذف_حتى_نهاية_سطر;
            return true;
        }
        
        // افتراضي: حذف سطر
        أمر.نوع = نوع_التحرير::حذف_سطر;
        return true;
    }
    
    bool تطابق_نسخ(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("انسخ") == std::string::npos && نص.find("نسخ") == std::string::npos) {
            return false;
        }
        
        if (نص.find("السطر") != std::string::npos) {
            أمر.نوع = نوع_التحرير::نسخ_سطر;
            return true;
        }
        
        if (نص.find("الكلمة") != std::string::npos) {
            أمر.نوع = نوع_التحرير::نسخ_كلمة;
            return true;
        }
        
        if (نص.find("الكل") != std::string::npos) {
            أمر.نوع = نوع_التحرير::نسخ_كل;
            return true;
        }
        
        // افتراضي: نسخ تحديد
        أمر.نوع = نوع_التحرير::نسخ_تحديد;
        return true;
    }
    
    bool تطابق_قص(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("قص") == std::string::npos) {
            return false;
        }
        
        if (نص.find("السطر") != std::string::npos) {
            أمر.نوع = نوع_التحرير::قص_سطر;
            return true;
        }
        
        if (نص.find("الكلمة") != std::string::npos) {
            أمر.نوع = نوع_التحرير::قص_كلمة;
            return true;
        }
        
        أمر.نوع = نوع_التحرير::قص_تحديد;
        return true;
    }
    
    bool تطابق_لصق(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("الصق") != std::string::npos || نص.find("لصق") != std::string::npos) {
            أمر.نوع = نوع_التحرير::لصق;
            return true;
        }
        return false;
    }
    
    bool تطابق_تراجع_إعادة(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("تراجع") != std::string::npos || نص.find("ألغِ") != std::string::npos) {
            أمر.نوع = نوع_التحرير::تراجع;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        if (نص.find("أعد") != std::string::npos || نص.find("إعادة") != std::string::npos) {
            أمر.نوع = نوع_التحرير::إعادة;
            أمر.كمية = استخرج_كمية(نص);
            return true;
        }
        
        return false;
    }
    
    bool تطابق_تحديد(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("حدد") == std::string::npos && 
            نص.find("اختر") == std::string::npos) {
            return false;
        }
        
        if (نص.find("السطر") != std::string::npos) {
            أمر.نوع = نوع_التحرير::تحديد_سطر;
            return true;
        }
        
        if (نص.find("الكلمة") != std::string::npos) {
            أمر.نوع = نوع_التحرير::تحديد_كلمة;
            return true;
        }
        
        if (نص.find("الكل") != std::string::npos) {
            أمر.نوع = نوع_التحرير::تحديد_كل;
            return true;
        }
        
        if (نص.find("الكتلة") != std::string::npos) {
            أمر.نوع = نوع_التحرير::تحديد_كتلة;
            return true;
        }
        
        return false;
    }
    
    bool تطابق_استبدال(const std::string& نص, أمر_تحرير& أمر) {
        std::regex نمط("استبدل\\s+(.+?)\\s+بـ?\\s+(.+)", std::regex::icase);
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            أمر.نوع = نوع_التحرير::استبدال;
            أمر.نص = مطابقات[1].str();
            أمر.نص_استبدال = مطابقات[2].str();
            
            if (نص.find("الكل") != std::string::npos) {
                أمر.نوع = نوع_التحرير::استبدال_كل;
            }
            
            return true;
        }
        
        return false;
    }
    
    bool تطابق_أسطر(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("سطر جديد") != std::string::npos) {
            if (نص.find("فوق") != std::string::npos || نص.find("أعلى") != std::string::npos) {
                أمر.نوع = نوع_التحرير::سطر_جديد_أعلى;
            } else {
                أمر.نوع = نوع_التحرير::سطر_جديد_أسفل;
            }
            return true;
        }
        
        if (نص.find("انقل السطر") != std::string::npos) {
            if (نص.find("أعلى") != std::string::npos || نص.find("فوق") != std::string::npos) {
                أمر.نوع = نوع_التحرير::نقل_سطر_أعلى;
            } else {
                أمر.نوع = نوع_التحرير::نقل_سطر_أسفل;
            }
            return true;
        }
        
        if (نص.find("كرر السطر") != std::string::npos || نص.find("ضاعف السطر") != std::string::npos) {
            if (نص.find("أعلى") != std::string::npos || نص.find("فوق") != std::string::npos) {
                أمر.نوع = نوع_التحرير::نسخ_سطر_أعلى;
            } else {
                أمر.نوع = نوع_التحرير::نسخ_سطر_أسفل;
            }
            return true;
        }
        
        if (نص.find("ادمج") != std::string::npos && نص.find("سطر") != std::string::npos) {
            أمر.نوع = نوع_التحرير::دمج_أسطر;
            return true;
        }
        
        return false;
    }
    
    bool تطابق_تعليق(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("علّق") != std::string::npos || نص.find("تعليق") != std::string::npos) {
            if (نص.find("إلغاء") != std::string::npos || نص.find("أزل") != std::string::npos) {
                أمر.نوع = نوع_التحرير::إلغاء_تعليق_سطر;
            } else if (نص.find("كتلة") != std::string::npos) {
                أمر.نوع = نوع_التحرير::تعليق_كتلة;
            } else {
                أمر.نوع = نوع_التحرير::تعليق_سطر;
            }
            return true;
        }
        
        return false;
    }
    
    bool تطابق_إدراج(const std::string& نص, أمر_تحرير& أمر) {
        std::regex نمط("أدرج\\s+(.+)", std::regex::icase);
        std::smatch مطابقات;
        
        if (std::regex_search(نص, مطابقات, نمط)) {
            أمر.نوع = نوع_التحرير::إدراج_نص;
            أمر.نص = مطابقات[1].str();
            return true;
        }
        
        std::regex نمط2("اكتب\\s+(.+)", std::regex::icase);
        if (std::regex_search(نص, مطابقات, نمط2)) {
            أمر.نوع = نوع_التحرير::إدراج_نص;
            أمر.نص = مطابقات[1].str();
            return true;
        }
        
        return false;
    }
    
    bool تطابق_حفظ(const std::string& نص, أمر_تحرير& أمر) {
        if (نص.find("احفظ") != std::string::npos || نص.find("حفظ") != std::string::npos) {
            if (نص.find("باسم") != std::string::npos) {
                أمر.نوع = نوع_التحرير::حفظ_باسم;
            } else {
                أمر.نوع = نوع_التحرير::حفظ;
            }
            return true;
        }
        return false;
    }
};

