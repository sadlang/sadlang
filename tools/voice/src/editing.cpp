    void عيّن_المحرر(واجهة_التحرير* محرر) {
        منفذ_.عيّن_المحرر(محرر);
    }
    
    bool عالج(const std::string& نص) {
        أمر_تحرير أمر = محلل_.حلّل(نص);
        
        if (!أمر.صالح()) {
            return false;
        }
        
        return منفذ_.نفّذ(أمر);
    }
