/**
 * واجهة محرر للتحرير
 */
class واجهة_التحرير {
public:
    virtual ~واجهة_التحرير() = default;
    
    // عمليات أساسية
    virtual void أدرج_نص(const std::string& نص) = 0;
    virtual void احذف(int بداية, int طول) = 0;
    virtual std::string اقرأ(int بداية, int طول) = 0;
    
    // الحافظة
    virtual void انسخ(const std::string& نص) = 0;
    virtual std::string الصق() = 0;
    
    // التحديد
    virtual void حدد(int بداية, int نهاية) = 0;
    virtual std::pair<int, int> التحديد() = 0;
    virtual void ألغِ_التحديد() = 0;
    
    // الموضع
    virtual int الموضع() = 0;
    virtual void انتقل(int موضع) = 0;
    
    // معلومات
    virtual int طول_الملف() = 0;
    virtual int بداية_السطر(int سطر) = 0;
    virtual int نهاية_السطر(int سطر) = 0;
    virtual int السطر_الحالي() = 0;
};

/**
 * منفذ أوامر التحرير
 */
class منفذ_التحرير {
private:
    واجهة_التحرير* محرر_ = nullptr;
    std::stack<std::function<void()>> سجل_التراجع_;
    std::stack<std::function<void()>> سجل_الإعادة_;
    
public:
    void عيّن_المحرر(واجهة_التحرير* محرر) {
        محرر_ = محرر;
    }
    
    /**
     * تنفيذ أمر تحرير
     */
    bool نفّذ(const أمر_تحرير& أمر) {
        if (!محرر_) return false;
        
        switch (أمر.نوع) {
            case نوع_التحرير::حذف_سطر:
                return حذف_سطر(أمر.كمية);
                
            case نوع_التحرير::حذف_كلمة:
                return حذف_كلمة(أمر.كمية);
                
            case نوع_التحرير::حذف_تحديد:
                return حذف_تحديد();
                
            case نوع_التحرير::نسخ_سطر:
                return نسخ_سطر();
                
            case نوع_التحرير::نسخ_تحديد:
                return نسخ_تحديد();
                
            case نوع_التحرير::قص_سطر:
                نسخ_سطر();
                return حذف_سطر(1);
                
            case نوع_التحرير::لصق:
                return لصق();
                
            case نوع_التحرير::تراجع:
                return تراجع(أمر.كمية);
                
            case نوع_التحرير::إعادة:
                return إعادة(أمر.كمية);
                
            case نوع_التحرير::تحديد_سطر:
                return تحديد_سطر();
                
            case نوع_التحرير::تحديد_كل:
                return تحديد_كل();
                
            case نوع_التحرير::استبدال:
                return استبدال(أمر.نص, أمر.نص_استبدال, false);
                
            case نوع_التحرير::استبدال_كل:
                return استبدال(أمر.نص, أمر.نص_استبدال, true);
                
            case نوع_التحرير::سطر_جديد_أسفل:
                return سطر_جديد(false);
                
            case نوع_التحرير::سطر_جديد_أعلى:
                return سطر_جديد(true);
                
            case نوع_التحرير::تعليق_سطر:
                return تعليق_سطر();
                
            case نوع_التحرير::إدراج_نص:
                return إدراج(أمر.نص);
                
            default:
                return false;
        }
    }
    
private:
    bool حذف_سطر(int كمية) {
        for (int i = 0; i < كمية; ++i) {
            int سطر = محرر_->السطر_الحالي();
            int بداية = محرر_->بداية_السطر(سطر);
            int نهاية = محرر_->نهاية_السطر(سطر);
            
            std::string محتوى = محرر_->اقرأ(بداية, نهاية - بداية + 1);
            محرر_->احذف(بداية, نهاية - بداية + 1);
            
            // سجل للتراجع
            سجل_التراجع_.push([this, بداية, محتوى]() {
                محرر_->انتقل(بداية);
                محرر_->أدرج_نص(محتوى);
            });
        }
        return true;
    }
    
    bool حذف_كلمة(int كمية) {
        // مُبسّط: حذف حتى المسافة التالية
        for (int i = 0; i < كمية; ++i) {
            int موضع = محرر_->الموضع();
            int نهاية = موضع;
            
            // البحث عن نهاية الكلمة
            while (نهاية < محرر_->طول_الملف()) {
                std::string حرف = محرر_->اقرأ(نهاية, 1);
                if (حرف == " " || حرف == "\n") break;
                نهاية++;
            }
            
            if (نهاية > موضع) {
                std::string كلمة = محرر_->اقرأ(موضع, نهاية - موضع);
                محرر_->احذف(موضع, نهاية - موضع);
                
                سجل_التراجع_.push([this, موضع, كلمة]() {
                    محرر_->انتقل(موضع);
                    محرر_->أدرج_نص(كلمة);
                });
            }
        }
        return true;
    }
    
    bool حذف_تحديد() {
        auto [بداية, نهاية] = محرر_->التحديد();
        if (بداية >= نهاية) return false;
        
        std::string محتوى = محرر_->اقرأ(بداية, نهاية - بداية);
        محرر_->احذف(بداية, نهاية - بداية);
        
        سجل_التراجع_.push([this, بداية, محتوى]() {
            محرر_->انتقل(بداية);
            محرر_->أدرج_نص(محتوى);
        });
        
        return true;
    }
    
    bool نسخ_سطر() {
        int سطر = محرر_->السطر_الحالي();
        int بداية = محرر_->بداية_السطر(سطر);
        int نهاية = محرر_->نهاية_السطر(سطر);
        
        std::string محتوى = محرر_->اقرأ(بداية, نهاية - بداية + 1);
        محرر_->انسخ(محتوى);
        return true;
    }
    
    bool نسخ_تحديد() {
        auto [بداية, نهاية] = محرر_->التحديد();
        if (بداية >= نهاية) return false;
        
        std::string محتوى = محرر_->اقرأ(بداية, نهاية - بداية);
        محرر_->انسخ(محتوى);
        return true;
    }
    
    bool لصق() {
        std::string محتوى = محرر_->الصق();
        if (محتوى.empty()) return false;
        
        int موضع = محرر_->الموضع();
        محرر_->أدرج_نص(محتوى);
        
        سجل_التراجع_.push([this, موضع, محتوى]() {
            محرر_->انتقل(موضع);
            محرر_->احذف(موضع, محتوى.length());
        });
        
        return true;
    }
    
    bool تراجع(int كمية) {
        for (int i = 0; i < كمية && !سجل_التراجع_.empty(); ++i) {
            auto عملية = سجل_التراجع_.top();
            سجل_التراجع_.pop();
            عملية();
        }
        return true;
    }
    
    bool إعادة(int كمية) {
        for (int i = 0; i < كمية && !سجل_الإعادة_.empty(); ++i) {
            auto عملية = سجل_الإعادة_.top();
            سجل_الإعادة_.pop();
            عملية();
        }
        return true;
    }
    
    bool تحديد_سطر() {
        int سطر = محرر_->السطر_الحالي();
        int بداية = محرر_->بداية_السطر(سطر);
        int نهاية = محرر_->نهاية_السطر(سطر);
        محرر_->حدد(بداية, نهاية);
        return true;
    }
    
    bool تحديد_كل() {
        محرر_->حدد(0, محرر_->طول_الملف());
        return true;
    }
    
    bool استبدال(const std::string& نص, const std::string& بديل, bool الكل) {
        // مُبسّط
        return true;
    }
    
    bool سطر_جديد(bool فوق) {
        int سطر = محرر_->السطر_الحالي();
        int موضع = فوق ? محرر_->بداية_السطر(سطر) : محرر_->نهاية_السطر(سطر);
        
        محرر_->انتقل(موضع);
        محرر_->أدرج_نص("\n");
        
        return true;
    }
    
    bool تعليق_سطر() {
        int سطر = محرر_->السطر_الحالي();
        int بداية = محرر_->بداية_السطر(سطر);
        
        محرر_->انتقل(بداية);
        محرر_->أدرج_نص("// ");
        
        return true;
    }
    
    bool إدراج(const std::string& نص) {
        محرر_->أدرج_نص(نص);
        return true;
    }
};

