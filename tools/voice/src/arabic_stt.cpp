/**
 * أحداث الصوت
 */
using مستمع_الصوت = std::function<void(const نتيجة_التعرف&)>;
using مستمع_مؤقت = std::function<void(const std::string&)>;

/**
 * محرك التعرف على الكلام العربي
 */
class محرك_STT {
private:
    إعدادات_الصوت إعدادات_;
    std::unique_ptr<معالج_الإشارة> معالج_;
    std::unique_ptr<نموذج_عربي> نموذج_;
    
    std::vector<مستمع_الصوت> مستمعون_;
    std::vector<مستمع_مؤقت> مستمعون_مؤقتون_;
    
    bool يستمع_ = false;
    std::vector<float> مخزن_صوتي_;
    std::vector<std::vector<float>> خصائص_متراكمة_;
    
public:
    محرك_STT() : محرك_STT(إعدادات_الصوت{}) {}
    
    explicit محرك_STT(const إعدادات_الصوت& إعدادات) 
        : إعدادات_(إعدادات) {
        معالج_ = std::make_unique<معالج_الإشارة>(إعدادات_);
        نموذج_ = std::make_unique<نموذج_عربي>();
    }
    
    /**
     * بدء الاستماع
     */
    bool ابدأ_الاستماع() {
        if (يستمع_) return false;
        
        يستمع_ = true;
        مخزن_صوتي_.clear();
        خصائص_متراكمة_.clear();
        
        std::cout << "🎤 بدأ الاستماع..." << std::endl;
        return true;
    }
    
    /**
     * إيقاف الاستماع
     */
    نتيجة_التعرف أوقف_الاستماع() {
        يستمع_ = false;
        
        // معالجة الصوت المتراكم
        نتيجة_التعرف نتيجة;
        if (!خصائص_متراكمة_.empty()) {
            نتيجة = نموذج_->فك_ترميز(خصائص_متراكمة_);
        }
        
        std::cout << "🎤 توقف الاستماع" << std::endl;
        return نتيجة;
    }
    
    /**
     * تغذية بعينات صوتية
     */
    void غذِّ(const std::vector<float>& عينات) {
        if (!يستمع_) return;
        
        // إضافة للمخزن
        مخزن_صوتي_.insert(مخزن_صوتي_.end(), عينات.begin(), عينات.end());
        
        // معالجة الإطارات الكاملة
        int حجم_الإطار = (إعدادات_.معدل_العينات * إعدادات_.حجم_الإطار_ms) / 1000;
        int خطوة = (إعدادات_.معدل_العينات * إعدادات_.خطوة_الإطار_ms) / 1000;
        
        while (مخزن_صوتي_.size() >= static_cast<size_t>(حجم_الإطار)) {
            // استخراج إطار
            std::vector<float> إطار(مخزن_صوتي_.begin(), مخزن_صوتي_.begin() + حجم_الإطار);
            
            // التحقق من الصمت
            if (!معالج_->هو_صمت(إطار)) {
                // استخراج MFCC
                auto mfcc = معالج_->استخراج_MFCC(إطار);
                خصائص_متراكمة_.push_back(mfcc);
            }
            
            // تحريك النافذة
            مخزن_صوتي_.erase(مخزن_صوتي_.begin(), مخزن_صوتي_.begin() + خطوة);
        }
    }
    
    /**
     * إضافة مستمع للنتائج النهائية
     */
    void أضف_مستمع(مستمع_الصوت مستمع) {
        مستمعون_.push_back(std::move(مستمع));
    }
    
    /**
     * إضافة مستمع للنتائج المؤقتة
     */
    void أضف_مستمع_مؤقت(مستمع_مؤقت مستمع) {
        مستمعون_مؤقتون_.push_back(std::move(مستمع));
    }
    
    /**
     * تغيير اللهجة
     */
    void اختر_لهجة(اللهجة لهجة) {
        نموذج_ = std::make_unique<نموذج_عربي>(لهجة);
    }
    
    /**
     * الحصول على الإعدادات
     */
    const إعدادات_الصوت& إعدادات() const { return إعدادات_; }
    
    /**
     * تحديث الإعدادات
     */
    void حدّث_إعدادات(const إعدادات_الصوت& إعدادات) {
        إعدادات_ = إعدادات;
        معالج_ = std::make_unique<معالج_الإشارة>(إعدادات_);
    }
    
    /**
     * هل يستمع حالياً؟
     */
    bool يستمع() const { return يستمع_; }
    
private:
    void إرسال_نتيجة(const نتيجة_التعرف& نتيجة) {
        for (const auto& مستمع : مستمعون_) {
            مستمع(نتيجة);
        }
    }
    
    void إرسال_نتيجة_مؤقتة(const std::string& نص) {
        for (const auto& مستمع : مستمعون_مؤقتون_) {
            مستمع(نص);
        }
    }
};

