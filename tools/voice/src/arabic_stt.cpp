extern "C" {

using namespace sad::voice;

typedef struct SadSTTEngine SadSTTEngine;

SadSTTEngine* sad_stt_create(void) {
    return reinterpret_cast<SadSTTEngine*>(new محرك_STT());
}

void sad_stt_destroy(SadSTTEngine* engine) {
    delete reinterpret_cast<محرك_STT*>(engine);
}

int sad_stt_start(SadSTTEngine* engine) {
    if (!engine) return 0;
    return reinterpret_cast<محرك_STT*>(engine)->ابدأ_الاستماع() ? 1 : 0;
}

void sad_stt_stop(SadSTTEngine* engine) {
    if (engine) {
        reinterpret_cast<محرك_STT*>(engine)->أوقف_الاستماع();
    }
}

void sad_stt_feed(SadSTTEngine* engine, const float* samples, int count) {
    if (engine && samples && count > 0) {
        std::vector<float> عينات(samples, samples + count);
        reinterpret_cast<محرك_STT*>(engine)->غذِّ(عينات);
    }
}

int sad_stt_is_listening(SadSTTEngine* engine) {
    if (!engine) return 0;
    return reinterpret_cast<محرك_STT*>(engine)->يستمع() ? 1 : 0;
}

void sad_stt_set_dialect(SadSTTEngine* engine, int dialect) {
    if (engine) {
        reinterpret_cast<محرك_STT*>(engine)->اختر_لهجة(static_cast<اللهجة>(dialect));
    }
}

// محرك برمجي
typedef struct SadCodeSTT SadCodeSTT;

SadCodeSTT* sad_code_stt_create(void) {
    return reinterpret_cast<SadCodeSTT*>(new محرك_STT_برمجي());
}

void sad_code_stt_destroy(SadCodeSTT* engine) {
    delete reinterpret_cast<محرك_STT_برمجي*>(engine);
}

int sad_code_stt_start(SadCodeSTT* engine) {
    if (!engine) return 0;
    return reinterpret_cast<محرك_STT_برمجي*>(engine)->ابدأ() ? 1 : 0;
}

void sad_code_stt_set_context(SadCodeSTT* engine, int context) {
    if (engine) {
        reinterpret_cast<محرك_STT_برمجي*>(engine)->عيّن_السياق(
            static_cast<سياق_برمجي>(context)
        );
    }
}

} // extern "C"
