/**
 * إطار صوتي
 */
struct إطار_صوتي {
    std::vector<float> عينات;
    double طاقة;
    bool صمت;
    double طابع_زمني;
};

/**
 * معالج الإشارة الصوتية
 * 
 * يقوم بـ:
 * - تطبيق نافذة Hamming
 * - استخراج MFCC
 * - إزالة الضوضاء
 */
class معالج_الإشارة {
private:
    إعدادات_الصوت إعدادات_;
    std::vector<float> نافذة_هامينغ_;
    int حجم_الإطار_;
    int حجم_FFT_;
    
    // مصفوفة Mel filterbank
    std::vector<std::vector<float>> مرشحات_ميل_;
    int عدد_المرشحات_ = 26;
    int عدد_MFCC_ = 13;
    
public:
    معالج_الإشارة(const إعدادات_الصوت& إعدادات) 
        : إعدادات_(إعدادات) {
        
        // حساب حجم الإطار
        حجم_الإطار_ = (إعدادات_.معدل_العينات * إعدادات_.حجم_الإطار_ms) / 1000;
        
        // حجم FFT (قوة 2)
        حجم_FFT_ = 1;
        while (حجم_FFT_ < حجم_الإطار_) {
            حجم_FFT_ *= 2;
        }
        
        // تهيئة نافذة Hamming
        نافذة_هامينغ_.resize(حجم_الإطار_);
        for (int i = 0; i < حجم_الإطار_; ++i) {
            نافذة_هامينغ_[i] = 0.54f - 0.46f * std::cos(2 * M_PI * i / (حجم_الإطار_ - 1));
        }
        
        // تهيئة مرشحات Mel
        تهيئة_مرشحات_ميل();
    }
    
    /**
     * استخراج خصائص MFCC
     */
    std::vector<float> استخراج_MFCC(const std::vector<float>& إطار) {
        std::vector<float> mfcc(عدد_MFCC_, 0.0f);
        
        if (إطار.size() < static_cast<size_t>(حجم_الإطار_)) {
            return mfcc;
        }
        
        // 1. تطبيق نافذة Hamming
        std::vector<float> إطار_منوفذ(حجم_الإطار_);
        for (int i = 0; i < حجم_الإطار_; ++i) {
            إطار_منوفذ[i] = إطار[i] * نافذة_هامينغ_[i];
        }
        
        // 2. حساب FFT (مُبسّط)
        std::vector<float> طيف = حساب_طيف_القدرة(إطار_منوفذ);
        
        // 3. تطبيق مرشحات Mel
        std::vector<float> طاقات_ميل(عدد_المرشحات_, 0.0f);
        for (int i = 0; i < عدد_المرشحات_; ++i) {
            for (size_t j = 0; j < طيف.size() && j < مرشحات_ميل_[i].size(); ++j) {
                طاقات_ميل[i] += طيف[j] * مرشحات_ميل_[i][j];
            }
            // Log compression
            طاقات_ميل[i] = std::log(طاقات_ميل[i] + 1e-10f);
        }
        
        // 4. DCT للحصول على MFCC
        for (int i = 0; i < عدد_MFCC_; ++i) {
            for (int j = 0; j < عدد_المرشحات_; ++j) {
                mfcc[i] += طاقات_ميل[j] * std::cos(M_PI * i * (j + 0.5) / عدد_المرشحات_);
            }
        }
        
        return mfcc;
    }
    
    /**
     * حساب طاقة الإطار
     */
    double حساب_الطاقة(const std::vector<float>& إطار) {
        double طاقة = 0.0;
        for (float عينة : إطار) {
            طاقة += عينة * عينة;
        }
        return std::sqrt(طاقة / إطار.size());
    }
    
    /**
     * كشف الصمت
     */
    bool هو_صمت(const std::vector<float>& إطار) {
        return حساب_الطاقة(إطار) < إعدادات_.عتبة_الصمت;
    }
    
private:
    void تهيئة_مرشحات_ميل() {
        مرشحات_ميل_.resize(عدد_المرشحات_);
        
        float mel_min = 0;
        float mel_max = 2595 * std::log10(1 + (إعدادات_.معدل_العينات / 2.0f) / 700);
        
        std::vector<float> mel_points(عدد_المرشحات_ + 2);
        for (int i = 0; i < عدد_المرشحات_ + 2; ++i) {
            mel_points[i] = mel_min + (mel_max - mel_min) * i / (عدد_المرشحات_ + 1);
        }
        
        // تحويل من Mel إلى Hz
        std::vector<int> bin_points(عدد_المرشحات_ + 2);
        for (int i = 0; i < عدد_المرشحات_ + 2; ++i) {
            float hz = 700 * (std::pow(10, mel_points[i] / 2595) - 1);
            bin_points[i] = static_cast<int>((حجم_FFT_ + 1) * hz / إعدادات_.معدل_العينات);
        }
        
        // إنشاء المرشحات
        int fft_bins = حجم_FFT_ / 2 + 1;
        for (int i = 0; i < عدد_المرشحات_; ++i) {
            مرشحات_ميل_[i].resize(fft_bins, 0.0f);
            
            for (int j = bin_points[i]; j < bin_points[i+1]; ++j) {
                if (j < fft_bins) {
                    مرشحات_ميل_[i][j] = static_cast<float>(j - bin_points[i]) / 
                                        (bin_points[i+1] - bin_points[i]);
                }
            }
            for (int j = bin_points[i+1]; j < bin_points[i+2]; ++j) {
                if (j < fft_bins) {
                    مرشحات_ميل_[i][j] = static_cast<float>(bin_points[i+2] - j) / 
                                        (bin_points[i+2] - bin_points[i+1]);
                }
            }
        }
    }
    
    std::vector<float> حساب_طيف_القدرة(const std::vector<float>& إطار) {
        // تطبيق مُبسّط للـ FFT
        int n = حجم_FFT_ / 2 + 1;
        std::vector<float> طيف(n, 0.0f);
        
        for (int k = 0; k < n; ++k) {
            float real = 0, imag = 0;
            for (size_t j = 0; j < إطار.size(); ++j) {
                float angle = -2 * M_PI * k * j / حجم_FFT_;
                real += إطار[j] * std::cos(angle);
                imag += إطار[j] * std::sin(angle);
            }
            طيف[k] = (real * real + imag * imag) / حجم_FFT_;
        }
        
        return طيف;
    }
};

