/**
 * إعدادات محرك الصوت
 */
struct إعدادات_الصوت {
    int معدل_العينات = 16000;      // 16 kHz
    int عمق_البت = 16;             // 16-bit
    int عدد_القنوات = 1;           // Mono
    int حجم_الإطار_ms = 25;        // 25ms frames
    int خطوة_الإطار_ms = 10;       // 10ms hop
    bool إزالة_الضوضاء = true;
    float عتبة_الصمت = 0.01f;
    int مهلة_الصمت_ms = 1000;      // 1 second silence = end
    std::string لغة = "ar";        // Arabic
    std::string لهجة = "msa";      // Modern Standard Arabic
};

/**
 * اللهجات المدعومة
 */
enum class اللهجة {
    فصحى,          // Modern Standard Arabic
    مصرية,         // Egyptian
    خليجية,        // Gulf
    شامية,         // Levantine
    مغربية,        // Maghrebi
    عراقية         // Iraqi
};

