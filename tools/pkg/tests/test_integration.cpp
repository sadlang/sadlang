#include "../package.h"
#include "../dependency_resolver.h"
#include <cassert>
#include <iostream>
#include <filesystem>
#include <fstream>

using namespace sad::pkg;
namespace fs = std::filesystem;

// Test directory for integration tests
const std::string TEST_DIR = "test_integration_tmp";

// Setup test environment - إعداد بيئة الاختبار
void setup_test_env() {
    fs::create_directories(TEST_DIR);
    fs::create_directories(TEST_DIR + "/src");
}

// Cleanup test environment - تنظيف بيئة الاختبار
void cleanup_test_env() {
    if (fs::exists(TEST_DIR)) {
        fs::remove_all(TEST_DIR);
    }
}

// Test: sad-pkg init workflow - اختبار سير عمل sad-pkg init
void test_init_workflow() {
    std::cout << "Testing init workflow...\n";
    
    fs::current_path(TEST_DIR);
    
    // Create a package programmatically (simulating sad-pkg init)
    Package pkg;
    pkg.name = "test_project";
    pkg.version = Version::parse("0.1.0");
    pkg.description = "Test integration project";
    pkg.authors.push_back("Test Author");
    pkg.main_file = "src/main.ص";
    pkg.source_dirs.push_back("src");
    
    pkg.save_to_file("sad.toml");
    
    // Create main.ص file
    std::ofstream main_file("src/main.ص");
    main_file << "// بسم الله الرحمن الرحيم\n";
    main_file << "دالة رئيسية() {\n";
    main_file << "    اطبع(\"مرحباً!\");\n";
    main_file << "    أرجع 0;\n";
    main_file << "}\n";
    main_file.close();
    
    // Verify files were created
    assert(fs::exists("sad.toml"));
    assert(fs::exists("src/main.ص"));
    
    // Load and verify package
    Package loaded = Package::load_from_file("sad.toml");
    assert(loaded.name == "test_project");
    assert(loaded.version == Version::parse("0.1.0"));
    
    fs::current_path("..");
    
    std::cout << "  ✓ Init workflow test passed\n";
}

// Test: sad-pkg add workflow - اختبار سير عمل sad-pkg add
void test_add_dependency_workflow() {
    std::cout << "Testing add dependency workflow...\n";
    
    fs::current_path(TEST_DIR);
    
    // Load existing package
    Package pkg = Package::load_from_file("sad.toml");
    
    // Add dependencies (simulating sad-pkg add)
    pkg.dependencies["http"] = "^1.0.0";
    pkg.dependencies["json"] = "~2.3.0";
    
    // Save
    pkg.save_to_file("sad.toml");
    
    // Reload and verify
    Package reloaded = Package::load_from_file("sad.toml");
    assert(reloaded.dependencies.size() == 2);
    assert(reloaded.dependencies["http"] == "^1.0.0");
    assert(reloaded.dependencies["json"] == "~2.3.0");
    
    fs::current_path("..");
    
    std::cout << "  ✓ Add dependency workflow test passed\n";
}

// Test: sad-pkg install workflow - اختبار سير عمل sad-pkg install
void test_install_workflow() {
    std::cout << "Testing install workflow...\n";
    
    fs::current_path(TEST_DIR);
    
    // Load package
    Package pkg = Package::load_from_file("sad.toml");
    
    // Resolve dependencies (simulating sad-pkg install)
    DependencyResolver resolver;
    
    try {
        auto resolved = resolver.resolve(pkg.dependencies);
        
        // Create sad_modules directory
        fs::create_directories("sad_modules");
        
        // In real scenario, would download and install each package
        // Here we just verify resolution worked
        std::cout << "  Resolved " << resolved.size() << " dependencies\n";
        
        // Create a lock file (sad.lock)
        std::ofstream lock_file("sad.lock");
        lock_file << "# Lock file generated by sad-pkg\n";
        for (const auto& [name, pkg] : resolved) {
            lock_file << name << " = \"" << pkg.version.to_string() << "\"\n";
        }
        lock_file.close();
        
        assert(fs::exists("sad.lock"));
        
    } catch (const std::exception& e) {
        std::cout << "  Note: Install workflow test needs mock registry\n";
    }
    
    fs::current_path("..");
    
    std::cout << "  ✓ Install workflow test passed (partial)\n";
}

// Test: sad-pkg remove workflow - اختبار سير عمل sad-pkg remove
void test_remove_dependency_workflow() {
    std::cout << "Testing remove dependency workflow...\n";
    
    fs::current_path(TEST_DIR);
    
    // Load package
    Package pkg = Package::load_from_file("sad.toml");
    
    // Remove a dependency (simulating sad-pkg remove)
    pkg.dependencies.erase("http");
    
    // Save
    pkg.save_to_file("sad.toml");
    
    // Reload and verify
    Package reloaded = Package::load_from_file("sad.toml");
    assert(reloaded.dependencies.find("http") == reloaded.dependencies.end());
    assert(reloaded.dependencies.find("json") != reloaded.dependencies.end());
    
    fs::current_path("..");
    
    std::cout << "  ✓ Remove dependency workflow test passed\n";
}

