/**
 * نص مُستخرج
 */
struct نص_مستخرج {
    std::string المفتاح;
    std::string الملف;
    int السطر;
    std::string السياق;
    bool مع_جمع;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مستخرج الترجمات
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🔍 مستخرج نصوص الترجمة
 */
class مستخرج_ترجمات {
public:
    /**
     * إنشاء المستخرج
     */
    مستخرج_ترجمات() {
        // أنماط البحث
        أنماط_.push_back(std::regex(R"(ت\s*\(\s*\"([^\"]+)\")"));
        أنماط_.push_back(std::regex(R"(ت_عدد\s*\(\s*\"([^\"]+)\")"));
        أنماط_.push_back(std::regex(R"(ترجم\s*\(\s*\"([^\"]+)\")"));
    }
    
    /**
     * استخراج من ملف واحد
     */
    std::vector<نص_مستخرج> استخرج_من_ملف(const std::string& مسار) {
        std::vector<نص_مستخرج> نتائج;
        
        std::ifstream ملف(مسار);
        if (!ملف.is_open()) {
            std::cerr << "❌ لا يمكن فتح الملف: " << مسار << std::endl;
            return نتائج;
        }
        
        std::string سطر;
        int رقم_السطر = 0;
        
        while (std::getline(ملف, سطر)) {
            رقم_السطر++;
            
            for (const auto& نمط : أنماط_) {
                std::smatch تطابق;
                std::string نسخة = سطر;
                
                while (std::regex_search(نسخة, تطابق, نمط)) {
                    نص_مستخرج نص;
                    نص.المفتاح = تطابق[1].str();
                    نص.الملف = مسار;
                    نص.السطر = رقم_السطر;
                    نص.السياق = سطر;
                    نص.مع_جمع = (سطر.find("ت_عدد") != std::string::npos);
                    
                    نتائج.push_back(نص);
                    مفاتيح_مستخرجة_.insert(نص.المفتاح);
                    
                    نسخة = تطابق.suffix().str();
                }
            }
        }
        
        return نتائج;
    }
    
    /**
     * استخراج من مجلد
     */
    std::vector<نص_مستخرج> استخرج_من_مجلد(const std::string& مسار) {
        std::vector<نص_مستخرج> كل_النتائج;
        
        if (!fs::exists(مسار)) {
            std::cerr << "❌ المجلد غير موجود: " << مسار << std::endl;
            return كل_النتائج;
        }
        
        // الامتدادات المدعومة
        std::set<std::string> امتدادات = {".ص", ".hpp", ".cpp", ".h"};
        
        for (const auto& entry : fs::recursive_directory_iterator(مسار)) {
            if (entry.is_regular_file()) {
                std::string امتداد = entry.path().extension().string();
                if (امتدادات.count(امتداد) > 0) {
                    auto نتائج = استخرج_من_ملف(entry.path().string());
                    كل_النتائج.insert(كل_النتائج.end(), نتائج.begin(), نتائج.end());
                }
            }
        }
        
        return كل_النتائج;
    }
    
    /**
     * تصدير إلى JSON
     */
    std::string صدر_json() const {
        std::ostringstream json;
        json << "{\n";
        
        bool أول = true;
        for (const auto& مفتاح : مفاتيح_مستخرجة_) {
            if (!أول) json << ",\n";
            json << "  \"" << هروب_json(مفتاح) << "\": \"\"";
            أول = false;
        }
        
        json << "\n}";
        return json.str();
    }
    
    /**
     * تصدير إلى POT (Gettext)
     */
    std::string صدر_pot(const std::vector<نص_مستخرج>& نصوص) const {
        std::ostringstream pot;
        
        pot << "# Translation Template for SAD Language Project\n";
        pot << "# Copyright (C) 2024\n";
        pot << "#\n";
        pot << "msgid \"\"\n";
        pot << "msgstr \"\"\n";
        pot << "\"Content-Type: text/plain; charset=UTF-8\\n\"\n";
        pot << "\"Content-Transfer-Encoding: 8bit\\n\"\n\n";
        
        std::set<std::string> مُعالج;
        
        for (const auto& نص : نصوص) {
            if (مُعالج.count(نص.المفتاح) > 0) continue;
            مُعالج.insert(نص.المفتاح);
            
            pot << "#: " << نص.الملف << ":" << نص.السطر << "\n";
            if (نص.مع_جمع) {
                pot << "#, c-format\n";
            }
            pot << "msgid \"" << هروب_pot(نص.المفتاح) << "\"\n";
            pot << "msgstr \"\"\n\n";
        }
        
        return pot.str();
    }
    
    /**
     * تصدير تقرير
     */
    std::string صدر_تقرير(const std::vector<نص_مستخرج>& نصوص) const {
        std::ostringstream تقرير;
        
        تقرير << "╔══════════════════════════════════════════════════════════════╗\n";
        تقرير << "║           📊 تقرير استخراج نصوص الترجمة                      ║\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        تقرير << "║                                                              ║\n";
        تقرير << "║  📈 الإحصائيات:                                              ║\n";
        تقرير << "║  ─────────────                                               ║\n";
        تقرير << "║  • عدد النصوص المستخرجة: " << std::setw(5) << مفاتيح_مستخرجة_.size();
        تقرير << "                           ║\n";
        تقرير << "║  • عدد المواقع: " << std::setw(5) << نصوص.size();
        تقرير << "                                    ║\n";
        تقرير << "║                                                              ║\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        تقرير << "║  📝 النصوص المستخرجة:                                        ║\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        
        int عداد = 1;
        for (const auto& مفتاح : مفاتيح_مستخرجة_) {
            تقرير << "║  " << std::setw(3) << عداد++ << ". " << مفتاح;
            // ملء الفراغ
            int طول = static_cast<int>(مفتاح.length());
            for (int i = طول; i < 50; i++) تقرير << " ";
            تقرير << "║\n";
        }
        
        تقرير << "╚══════════════════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }
    
    /**
     * الحصول على المفاتيح المستخرجة
     */
    const std::set<std::string>& المفاتيح() const {
        return مفاتيح_مستخرجة_;
    }
    
private:
    std::vector<std::regex> أنماط_;
    std::set<std::string> مفاتيح_مستخرجة_;
    
    /**
     * هروب JSON
     */
    std::string هروب_json(const std::string& نص) const {
        std::string نتيجة;
        for (char c : نص) {
            switch (c) {
                case '"': نتيجة += "\\\""; break;
                case '\\': نتيجة += "\\\\"; break;
                case '\n': نتيجة += "\\n"; break;
                case '\r': نتيجة += "\\r"; break;
                case '\t': نتيجة += "\\t"; break;
                default: نتيجة += c;
            }
        }
        return نتيجة;
    }
    
    /**
     * هروب POT
     */
    std::string هروب_pot(const std::string& نص) const {
        std::string نتيجة;
        for (char c : نص) {
            switch (c) {
                case '"': نتيجة += "\\\""; break;
                case '\\': نتيجة += "\\\\"; break;
                case '\n': نتيجة += "\\n"; break;
                default: نتيجة += c;
            }
        }
        return نتيجة;
    }
};

