/**
 * الدالة الرئيسية
 */
int main(int argc, char* argv[]) {
    if (argc < 3) {
        اطبع_المساعدة();
        return 1;
    }
    
    std::string أمر = argv[1];
    std::string مسار = argv[2];
    
    // خيارات افتراضية
    std::string ملف_إخراج = "translations.json";
    std::string تنسيق = "json";
    bool مُفصّل = false;
    
    // معالجة الخيارات
    for (int i = 3; i < argc; i++) {
        std::string خيار = argv[i];
        
        if (خيار == "-o" || خيار == "--output") {
            if (i + 1 < argc) {
                ملف_إخراج = argv[++i];
            }
        } else if (خيار == "-f" || خيار == "--format") {
            if (i + 1 < argc) {
                تنسيق = argv[++i];
            }
        } else if (خيار == "-v" || خيار == "--verbose") {
            مُفصّل = true;
        } else if (خيار == "-h" || خيار == "--help") {
            اطبع_المساعدة();
            return 0;
        }
    }
    
    if (أمر == "استخرج" || أمر == "extract") {
        std::cout << "🔍 جاري استخراج النصوص من: " << مسار << std::endl;
        
        مستخرج_ترجمات مستخرج;
        auto نصوص = مستخرج.استخرج_من_مجلد(مسار);
        
        std::cout << "✅ تم استخراج " << مستخرج.المفاتيح().size() 
                  << " نص فريد من " << نصوص.size() << " موقع" << std::endl;
        
        // تصدير النتائج
        std::string محتوى;
        if (تنسيق == "json") {
            محتوى = مستخرج.صدر_json();
        } else if (تنسيق == "pot") {
            محتوى = مستخرج.صدر_pot(نصوص);
        } else if (تنسيق == "report") {
            محتوى = مستخرج.صدر_تقرير(نصوص);
            std::cout << محتوى;
            return 0;
        }
        
        // حفظ الملف
        std::ofstream ملف(ملف_إخراج);
        if (ملف.is_open()) {
            ملف << محتوى;
            std::cout << "💾 تم الحفظ في: " << ملف_إخراج << std::endl;
        } else {
            std::cerr << "❌ فشل في حفظ الملف: " << ملف_إخراج << std::endl;
            return 1;
        }
        
        if (مُفصّل) {
            std::cout << "\n📝 النصوص المستخرجة:\n";
            for (const auto& مفتاح : مستخرج.المفاتيح()) {
                std::cout << "  • " << مفتاح << std::endl;
            }
        }
        
    } else if (أمر == "تحقق" || أمر == "check") {
        std::cout << "🔍 جاري التحقق من الترجمات..." << std::endl;
        // TODO: تنفيذ التحقق
        
    } else if (أمر == "دمج" || أمر == "merge") {
        std::cout << "🔀 جاري دمج الترجمات..." << std::endl;
        // TODO: تنفيذ الدمج
        
    } else {
        std::cerr << "❌ أمر غير معروف: " << أمر << std::endl;
        اطبع_المساعدة();
        return 1;
    }
    
    return 0;
}
