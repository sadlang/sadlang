/**
 * نتيجة اختبار
 */
enum class نتيجة_اختبار {
    نجاح,
    فشل,
    تخطي,
    خطأ
};

/**
 * تقرير اختبار
 */
struct تقرير_اختبار_واحد {
    std::string اسم;
    نتيجة_اختبار نتيجة;
    std::string رسالة;
    double مدة_ms;
    uint64_t gas_مستخدم;
};

/**
 * حالة اختبار
 */
class حالة_اختبار {
private:
    std::string اسم_;
    std::function<void(بيئة_الاختبار&)> دالة_;
    bool يتخطى_ = false;
    
public:
    حالة_اختبار(const std::string& اسم, 
                std::function<void(بيئة_الاختبار&)> دالة)
        : اسم_(اسم), دالة_(دالة) {}
    
    /**
     * تشغيل الاختبار
     */
    تقرير_اختبار_واحد شغّل() {
        تقرير_اختبار_واحد تقرير;
        تقرير.اسم = اسم_;
        
        if (يتخطى_) {
            تقرير.نتيجة = نتيجة_اختبار::تخطي;
            تقرير.رسالة = "تم التخطي";
            return تقرير;
        }
        
        بيئة_الاختبار بيئة;
        auto بداية = std::chrono::high_resolution_clock::now();
        
        try {
            دالة_(بيئة);
            تقرير.نتيجة = نتيجة_اختبار::نجاح;
            تقرير.رسالة = "نجح";
        } catch (const std::exception& e) {
            تقرير.نتيجة = نتيجة_اختبار::فشل;
            تقرير.رسالة = e.what();
        } catch (...) {
            تقرير.نتيجة = نتيجة_اختبار::خطأ;
            تقرير.رسالة = "خطأ غير معروف";
        }
        
        auto نهاية = std::chrono::high_resolution_clock::now();
        تقرير.مدة_ms = std::chrono::duration<double, std::milli>(نهاية - بداية).count();
        تقرير.gas_مستخدم = بيئة.gas_مستخدم();
        
        return تقرير;
    }
    
    void تخطى() { يتخطى_ = true; }
    const std::string& اسم() const { return اسم_; }
};

