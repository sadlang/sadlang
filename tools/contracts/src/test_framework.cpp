/**
 * مجموعة اختبارات العقود
 */
class مجموعة_اختبارات {
private:
    std::string اسم_;
    std::vector<حالة_اختبار> اختبارات_;
    std::function<void(بيئة_الاختبار&)> قبل_الكل_;
    std::function<void(بيئة_الاختبار&)> بعد_الكل_;
    std::function<void(بيئة_الاختبار&)> قبل_كل_;
    std::function<void(بيئة_الاختبار&)> بعد_كل_;
    
public:
    explicit مجموعة_اختبارات(const std::string& اسم = "")
        : اسم_(اسم) {}
    
    /**
     * إضافة اختبار
     */
    void أضف_اختبار(const std::string& اسم,
                    std::function<void(بيئة_الاختبار&)> دالة) {
        اختبارات_.emplace_back(اسم, دالة);
    }
    
    /**
     * إعداد قبل جميع الاختبارات
     */
    void قبل_الكل(std::function<void(بيئة_الاختبار&)> دالة) {
        قبل_الكل_ = دالة;
    }
    
    /**
     * إعداد قبل كل اختبار
     */
    void قبل_كل(std::function<void(بيئة_الاختبار&)> دالة) {
        قبل_كل_ = دالة;
    }
    
    /**
     * تشغيل جميع الاختبارات
     */
    std::vector<تقرير_اختبار_واحد> شغّل_الكل() {
        std::vector<تقرير_اختبار_واحد> نتائج;
        
        for (auto& اختبار : اختبارات_) {
            auto تقرير = اختبار.شغّل();
            نتائج.push_back(تقرير);
        }
        
        return نتائج;
    }
    
    const std::string& اسم() const { return اسم_; }
    size_t عدد() const { return اختبارات_.size(); }
};

