/**
 * حساب اختبار
 */
struct حساب_اختبار {
    std::string عنوان;
    uint64_t رصيد;
    std::string اسم;
    
    حساب_اختبار(const std::string& ع = "", uint64_t ر = 0)
        : عنوان(ع), رصيد(ر), اسم("") {}
};

/**
 * بلوك وهمي
 */
struct بلوك_اختبار {
    uint64_t رقم;
    uint64_t timestamp;
    std::string hash;
};

