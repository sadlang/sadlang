/**
 * استثناء التأكيد
 */
class فشل_تأكيد : public std::exception {
private:
    std::string رسالة_;
    
public:
    explicit فشل_تأكيد(const std::string& رسالة) : رسالة_(رسالة) {}
    const char* what() const noexcept override { return رسالة_.c_str(); }
};

/**
 * تأكيدات الاختبار
 */
class تأكيد {
public:
    /**
     * تأكيد المساواة
     */
    template<typename T>
    static void يساوي(const T& متوقع, const T& فعلي, 
                      const std::string& رسالة = "") {
        if (متوقع != فعلي) {
            throw فشل_تأكيد(رسالة.empty() ? 
                "فشل التأكيد: القيم غير متساوية" : رسالة);
        }
    }
    
    /**
     * تأكيد عدم المساواة
     */
    template<typename T>
    static void لا_يساوي(const T& غير_متوقع, const T& فعلي,
                         const std::string& رسالة = "") {
        if (غير_متوقع == فعلي) {
            throw فشل_تأكيد(رسالة.empty() ?
                "فشل التأكيد: القيم متساوية" : رسالة);
        }
    }
    
    /**
     * تأكيد صحيح
     */
    static void صحيح(bool شرط, const std::string& رسالة = "") {
        if (!شرط) {
            throw فشل_تأكيد(رسالة.empty() ?
                "فشل التأكيد: الشرط غير صحيح" : رسالة);
        }
    }
    
    /**
     * تأكيد خاطئ
     */
    static void خاطئ(bool شرط, const std::string& رسالة = "") {
        if (شرط) {
            throw فشل_تأكيد(رسالة.empty() ?
                "فشل التأكيد: الشرط صحيح" : رسالة);
        }
    }
    
    /**
     * تأكيد أكبر من
     */
    template<typename T>
    static void أكبر_من(const T& حد, const T& فعلي,
                         const std::string& رسالة = "") {
        if (فعلي <= حد) {
            throw فشل_تأكيد(رسالة.empty() ?
                "فشل التأكيد: القيمة ليست أكبر" : رسالة);
        }
    }
    
    /**
     * تأكيد أصغر من
     */
    template<typename T>
    static void أصغر_من(const T& حد, const T& فعلي,
                         const std::string& رسالة = "") {
        if (فعلي >= حد) {
            throw فشل_تأكيد(رسالة.empty() ?
                "فشل التأكيد: القيمة ليست أصغر" : رسالة);
        }
    }
    
    /**
     * تأكيد حدوث استثناء
     */
    template<typename E, typename F>
    static void يرمي(F دالة, const std::string& رسالة = "") {
        try {
            دالة();
            throw فشل_تأكيد(رسالة.empty() ?
                "فشل التأكيد: لم يُرمى استثناء" : رسالة);
        } catch (const E&) {
            // متوقع
        }
    }
    
    /**
     * تأكيد revert
     */
    static void يُرجع(std::function<void()> دالة, 
                      const std::string& رسالة_متوقعة = "") {
        // التحقق من revert في العقد
    }
};

