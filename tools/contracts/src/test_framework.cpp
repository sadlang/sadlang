/**
 * مشغل اختبارات العقود
 */
class مشغّل_الاختبارات {
private:
    std::vector<مجموعة_اختبارات> مجموعات_;
    bool مفصّل_ = false;
    
public:
    /**
     * إضافة مجموعة
     */
    void أضف_مجموعة(مجموعة_اختبارات& مجموعة) {
        مجموعات_.push_back(مجموعة);
    }
    
    /**
     * تشغيل جميع الاختبارات
     */
    int شغّل_الكل() {
        int إجمالي = 0;
        int نجح = 0;
        int فشل = 0;
        int تخطي = 0;
        
        std::cout << "═══════════════════════════════════════════════════\n";
        std::cout << "🧪 تشغيل اختبارات العقود الذكية\n";
        std::cout << "═══════════════════════════════════════════════════\n\n";
        
        for (auto& مجموعة : مجموعات_) {
            std::cout << "📦 " << مجموعة.اسم() << "\n";
            
            auto نتائج = مجموعة.شغّل_الكل();
            
            for (const auto& تقرير : نتائج) {
                إجمالي++;
                
                switch (تقرير.نتيجة) {
                    case نتيجة_اختبار::نجاح:
                        نجح++;
                        std::cout << "   ✅ " << تقرير.اسم;
                        break;
                    case نتيجة_اختبار::فشل:
                        فشل++;
                        std::cout << "   ❌ " << تقرير.اسم;
                        break;
                    case نتيجة_اختبار::تخطي:
                        تخطي++;
                        std::cout << "   ⏭️ " << تقرير.اسم;
                        break;
                    case نتيجة_اختبار::خطأ:
                        فشل++;
                        std::cout << "   💥 " << تقرير.اسم;
                        break;
                }
                
                if (مفصّل_) {
                    std::cout << " (" << تقرير.مدة_ms << "ms, "
                              << تقرير.gas_مستخدم << " gas)";
                }
                std::cout << "\n";
                
                if (تقرير.نتيجة == نتيجة_اختبار::فشل ||
                    تقرير.نتيجة == نتيجة_اختبار::خطأ) {
                    std::cout << "      💬 " << تقرير.رسالة << "\n";
                }
            }
            
            std::cout << "\n";
        }
        
        // الملخص
        std::cout << "═══════════════════════════════════════════════════\n";
        std::cout << "📊 الملخص: " << نجح << "/" << إجمالي << " نجح";
        if (فشل > 0) std::cout << ", " << فشل << " فشل";
        if (تخطي > 0) std::cout << ", " << تخطي << " تخطي";
        std::cout << "\n═══════════════════════════════════════════════════\n";
        
        return فشل;
    }
    
    void فعّل_التفصيل() { مفصّل_ = true; }
};

