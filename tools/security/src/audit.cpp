// ============== التقرير الشامل ==============

class مولد_التقرير {
    std::vector<نتيجة_فحص> جميع_النتائج_;
    
public:
    void أضف_نتائج(const std::vector<نتيجة_فحص>& نتائج) {
        for (const auto& ن : نتائج) {
            جميع_النتائج_.push_back(ن);
        }
    }
    
    void اطبع_تقرير() {
        std::cout << "\n";
        std::cout << "╔════════════════════════════════════════════════════════════════════╗\n";
        std::cout << "║            🔒 تقرير تدقيق الأمان للغة ص v5.0 🔒                   ║\n";
        std::cout << "╚════════════════════════════════════════════════════════════════════╝\n\n";
        
        // إحصائيات
        int حرجة = 0, عالية = 0, متوسطة = 0, منخفضة = 0, معلومات = 0;
        int معالج = 0;
        
        for (const auto& ن : جميع_النتائج_) {
            switch (ن.الخطورة) {
                case نوع_الثغرة::حرجة: حرجة++; break;
                case نوع_الثغرة::عالية: عالية++; break;
                case نوع_الثغرة::متوسطة: متوسطة++; break;
                case نوع_الثغرة::منخفضة: منخفضة++; break;
                case نوع_الثغرة::معلوماتية: معلومات++; break;
            }
            if (ن.مُعالَج) معالج++;
        }
        
        std::cout << "📊 ملخص النتائج:\n";
        std::cout << "─────────────────────────────────\n";
        std::cout << "  🔴 حرجة:      " << حرجة << "\n";
        std::cout << "  🟠 عالية:      " << عالية << "\n";
        std::cout << "  🟡 متوسطة:    " << متوسطة << "\n";
        std::cout << "  🟢 منخفضة:    " << منخفضة << "\n";
        std::cout << "  ⚪ معلوماتية: " << معلومات << "\n";
        std::cout << "─────────────────────────────────\n";
        std::cout << "  ✅ معالج: " << معالج << "/" << جميع_النتائج_.size() << "\n";
        std::cout << "  📈 نسبة المعالجة: " 
                  << (int)(100.0 * معالج / جميع_النتائج_.size()) << "%\n\n";
        
        // التفاصيل
        std::cout << "📋 تفاصيل النتائج:\n";
        std::cout << "═════════════════════════════════════════════════════════════════════\n";
        
        int رقم = 1;
        for (const auto& ن : جميع_النتائج_) {
            std::cout << "\n[" << رقم++ << "] " << ن.خطورة_نص() << " - " << ن.المكون << "\n";
            std::cout << "    الوصف: " << ن.الوصف << "\n";
            std::cout << "    التوصية: " << ن.التوصية << "\n";
            std::cout << "    الحالة: " << (ن.مُعالَج ? "✅ معالج" : "⚠️ يحتاج معالجة") << "\n";
        }
        
        std::cout << "\n═════════════════════════════════════════════════════════════════════\n";
        std::cout << "🏆 التقييم الأمني الإجمالي: ";
        
        if (حرجة == 0 && عالية == 0) {
            std::cout << "ممتاز ⭐⭐⭐⭐⭐\n";
        } else if (حرجة == 0) {
            std::cout << "جيد جداً ⭐⭐⭐⭐\n";
        } else {
            std::cout << "يحتاج تحسين ⭐⭐⭐\n";
        }
        
        std::cout << "═════════════════════════════════════════════════════════════════════\n";
    }
};

