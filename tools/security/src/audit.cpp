// ============== أنواع الثغرات ==============

enum class نوع_الثغرة {
    حرجة,      // Critical
    عالية,      // High
    متوسطة,    // Medium
    منخفضة,    // Low
    معلوماتية  // Informational
};

// ============== نتيجة الفحص ==============

struct نتيجة_فحص {
    std::string المكون;
    std::string الوصف;
    نوع_الثغرة الخطورة;
    std::string التوصية;
    bool مُعالَج;
    
    std::string خطورة_نص() const {
        switch (الخطورة) {
            case نوع_الثغرة::حرجة: return "🔴 حرجة";
            case نوع_الثغرة::عالية: return "🟠 عالية";
            case نوع_الثغرة::متوسطة: return "🟡 متوسطة";
            case نوع_الثغرة::منخفضة: return "🟢 منخفضة";
            case نوع_الثغرة::معلوماتية: return "⚪ معلوماتية";
        }
        return "غير معروف";
    }
};

// ============== مدقق العقود الذكية ==============

class مدقق_العقود {
public:
    std::vector<نتيجة_فحص> افحص(const std::string& كود) {
        std::vector<نتيجة_فحص> نتائج;
        
        // 1. فحص إعادة الدخول (Reentrancy)
        if (كود.find("أرسل_أموال") != std::string::npos ||
            كود.find("استدعِ") != std::string::npos) {
            if (كود.find("@منع_إعادة_الدخول") == std::string::npos) {
                نتائج.push_back({
                    "العقود الذكية",
                    "احتمال هجوم إعادة الدخول (Reentrancy Attack)",
                    نوع_الثغرة::حرجة,
                    "استخدم مُعدِّل @منع_إعادة_الدخول أو نمط checks-effects-interactions",
                    false
                });
            }
        }
        
        // 2. فحص تجاوز الأعداد
        if (كود.find("+=") != std::string::npos || 
            كود.find("-=") != std::string::npos) {
            if (كود.find("@آمن_حسابياً") == std::string::npos &&
                كود.find("تحقق") == std::string::npos) {
                نتائج.push_back({
                    "العقود الذكية",
                    "احتمال تجاوز حسابي (Integer Overflow/Underflow)",
                    نوع_الثغرة::عالية,
                    "استخدم SafeMath أو @آمن_حسابياً",
                    false
                });
            }
        }
        
        // 3. فحص التحكم في الوصول
        if (كود.find("@عام") != std::string::npos) {
            if (كود.find("تحقق") == std::string::npos) {
                نتائج.push_back({
                    "العقود الذكية",
                    "دالة عامة بدون تحقق من الصلاحيات",
                    نوع_الثغرة::عالية,
                    "أضف تحقق من المرسل أو استخدم @فقط_المالك",
                    false
                });
            }
        }
        
        // 4. فحص استخدام tx.origin
        if (كود.find("الرسالة.الأصل") != std::string::npos) {
            نتائج.push_back({
                "العقود الذكية",
                "استخدام tx.origin للمصادقة (خطير)",
                نوع_الثغرة::حرجة,
                "استخدم msg.sender بدلاً من tx.origin",
                false
            });
        }
        
        // 5. فحص الغاز
        if (كود.find("طالما") != std::string::npos ||
            كود.find("لكل") != std::string::npos) {
            نتائج.push_back({
                "العقود الذكية",
                "حلقة قد تستهلك غاز غير محدود",
                نوع_الثغرة::متوسطة,
                "حدد أقصى عدد للتكرارات أو استخدم pagination",
                false
            });
        }
        
        return نتائج;
    }
};

