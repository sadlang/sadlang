/**
 * محرك حساب التجزئة
 */
class محرك_التجزئة {
public:
    /**
     * حساب تجزئة لبيانات
     */
    std::string احسب(const std::string& بيانات, 
                      خوارزمية_التجزئة خوارزمية = خوارزمية_التجزئة::SHA256) {
        switch (خوارزمية) {
            case خوارزمية_التجزئة::SHA256:
                return sha256(بيانات);
            case خوارزمية_التجزئة::SHA512:
                return sha512(بيانات);
            case خوارزمية_التجزئة::BLAKE3:
                return blake3(بيانات);
            default:
                return sha256(بيانات);
        }
    }
    
    /**
     * حساب تجزئة ملف
     */
    std::string احسب_ملف(const std::string& مسار,
                          خوارزمية_التجزئة خوارزمية = خوارزمية_التجزئة::SHA256) {
        std::ifstream ملف(مسار, std::ios::binary);
        if (!ملف.is_open()) return "";
        
        std::ostringstream ss;
        ss << ملف.rdbuf();
        return احسب(ss.str(), خوارزمية);
    }
    
private:
    // محاكاة SHA-256
    std::string sha256(const std::string& بيانات) {
        // في التطبيق الحقيقي: استخدام OpenSSL أو libsodium
        std::ostringstream ss;
        ss << "SHA256:" << std::hex;
        for (size_t i = 0; i < 32 && i < بيانات.length(); ++i) {
            ss << std::setw(2) << std::setfill('0') 
               << (static_cast<int>(بيانات[i]) & 0xFF);
        }
        return ss.str();
    }
    
    std::string sha512(const std::string& بيانات) {
        std::ostringstream ss;
        ss << "SHA512:" << std::hex;
        for (size_t i = 0; i < 64 && i < بيانات.length(); ++i) {
            ss << std::setw(2) << std::setfill('0') 
               << (static_cast<int>(بيانات[i]) & 0xFF);
        }
        return ss.str();
    }
    
    std::string blake3(const std::string& بيانات) {
        std::ostringstream ss;
        ss << "BLAKE3:" << std::hex;
        for (size_t i = 0; i < 32 && i < بيانات.length(); ++i) {
            ss << std::setw(2) << std::setfill('0') 
               << (static_cast<int>(بيانات[i]) & 0xFF);
        }
        return ss.str();
    }
};

