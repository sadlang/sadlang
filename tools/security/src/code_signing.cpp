/**
 * شهادة توقيع
 */
struct شهادة {
    std::string معرّف;
    مفتاح_عام مفتاح;
    std::string الاسم_الشائع;
    std::string المنظمة;
    std::string البلد;
    time_t تاريخ_الإصدار;
    time_t تاريخ_الانتهاء;
    std::string الجهة_المصدرة;
    std::string توقيع_الجهة;
    bool ملغاة = false;
};

/**
 * مدير الشهادات
 */
class مدير_الشهادات {
private:
    std::vector<شهادة> شهادات_;
    std::vector<شهادة> شهادات_جذر_;
    std::vector<std::string> قائمة_الإلغاء_;
    
public:
    /**
     * إضافة شهادة جذر
     */
    void أضف_شهادة_جذر(const شهادة& ش) {
        شهادات_جذر_.push_back(ش);
    }
    
    /**
     * التحقق من سلسلة الشهادات
     */
    bool تحقق_من_السلسلة(const شهادة& ش) {
        // التحقق من الإلغاء
        if (std::find(قائمة_الإلغاء_.begin(), قائمة_الإلغاء_.end(), 
                      ش.معرّف) != قائمة_الإلغاء_.end()) {
            return false;
        }
        
        // التحقق من الصلاحية
        time_t الآن = std::time(nullptr);
        if (الآن < ش.تاريخ_الإصدار || الآن > ش.تاريخ_الانتهاء) {
            return false;
        }
        
        // التحقق من الجهة المصدرة
        for (const auto& جذر : شهادات_جذر_) {
            if (ش.الجهة_المصدرة == جذر.الاسم_الشائع) {
                return true;
            }
        }
        
        return false;
    }
    
    /**
     * إلغاء شهادة
     */
    void ألغِ(const std::string& معرّف) {
        قائمة_الإلغاء_.push_back(معرّف);
    }
};

