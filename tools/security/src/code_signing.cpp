/**
 * موقّع الكود
 */
class موقّع_الكود {
private:
    مفتاح_خاص مفتاح_;
    محرك_التجزئة تجزئة_;
    std::string اسم_الموقّع_;
    std::string بريد_الموقّع_;
    
public:
    موقّع_الكود(const مفتاح_خاص& مفتاح,
                 const std::string& اسم = "",
                 const std::string& بريد = "")
        : مفتاح_(مفتاح), اسم_الموقّع_(اسم), بريد_الموقّع_(بريد) {}
    
    /**
     * توقيع محتوى
     */
    توقيع وقّع(const std::string& محتوى) {
        توقيع ت;
        
        // حساب التجزئة
        ت.تجزئة_المحتوى = تجزئة_.احسب(محتوى, خوارزمية_التجزئة::SHA256);
        ت.خوارزمية_التجزئة = خوارزمية_التجزئة::SHA256;
        
        // التوقيع
        ت.قيمة = توقيع_رقمي(ت.تجزئة_المحتوى);
        ت.خوارزمية = مفتاح_.خوارزمية;
        ت.معرّف_المفتاح = مفتاح_.معرّف;
        
        // الطابع الزمني
        ت.الطابع_الزمني = std::time(nullptr);
        
        // معلومات الموقّع
        ت.اسم_الموقّع = اسم_الموقّع_;
        ت.بريد_الموقّع = بريد_الموقّع_;
        
        return ت;
    }
    
    /**
     * توقيع ملف
     */
    توقيع وقّع_ملف(const std::string& مسار) {
        std::string تجزئة = تجزئة_.احسب_ملف(مسار);
        
        توقيع ت;
        ت.تجزئة_المحتوى = تجزئة;
        ت.خوارزمية_التجزئة = خوارزمية_التجزئة::SHA256;
        ت.قيمة = توقيع_رقمي(تجزئة);
        ت.خوارزمية = مفتاح_.خوارزمية;
        ت.معرّف_المفتاح = مفتاح_.معرّف;
        ت.الطابع_الزمني = std::time(nullptr);
        ت.اسم_الموقّع = اسم_الموقّع_;
        ت.بريد_الموقّع = بريد_الموقّع_;
        
        return ت;
    }
    
private:
    std::string توقيع_رقمي(const std::string& تجزئة) {
        // محاكاة التوقيع الرقمي
        return "SIG:" + تجزئة.substr(0, 16) + "...";
    }
};

