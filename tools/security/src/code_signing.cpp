/**
 * محقق التوقيع
 */
class محقق_التوقيع {
private:
    std::unordered_map<std::string, مفتاح_عام> مفاتيح_موثوقة_;
    محرك_التجزئة تجزئة_;
    
public:
    /**
     * إضافة مفتاح موثوق
     */
    void أضف_مفتاح_موثوق(const مفتاح_عام& مفتاح) {
        مفاتيح_موثوقة_[مفتاح.معرّف] = مفتاح;
    }
    
    /**
     * التحقق من توقيع محتوى
     */
    نتيجة_التحقق تحقق(const std::string& محتوى, const توقيع& ت) {
        نتيجة_التحقق نتيجة;
        نتيجة.معرّف_المفتاح = ت.معرّف_المفتاح;
        نتيجة.اسم_الموقّع = ت.اسم_الموقّع;
        نتيجة.طابع_التوقيع = ت.الطابع_الزمني;
        
        // التحقق من وجود المفتاح
        auto it = مفاتيح_موثوقة_.find(ت.معرّف_المفتاح);
        if (it == مفاتيح_موثوقة_.end()) {
            نتيجة.صالح = false;
            نتيجة.رسالة = "المفتاح غير موثوق";
            نتيجة.أسباب_الرفض.push_back("مفتاح غير معروف: " + ت.معرّف_المفتاح);
            return نتيجة;
        }
        
        const مفتاح_عام& مفتاح = it->second;
        
        // التحقق من صلاحية المفتاح
        if (مفتاح.منتهي()) {
            نتيجة.صالح = false;
            نتيجة.رسالة = "المفتاح منتهي الصلاحية";
            نتيجة.أسباب_الرفض.push_back("انتهت صلاحية المفتاح");
            return نتيجة;
        }
        
        // التحقق من التجزئة
        std::string تجزئة_محسوبة = تجزئة_.احسب(محتوى, ت.خوارزمية_التجزئة);
        if (تجزئة_محسوبة != ت.تجزئة_المحتوى) {
            نتيجة.صالح = false;
            نتيجة.رسالة = "التجزئة غير متطابقة - المحتوى معدّل";
            نتيجة.أسباب_الرفض.push_back("التجزئة لا تتطابق");
            return نتيجة;
        }
        
        // التحقق من التوقيع (محاكاة)
        if (!تحقق_من_التوقيع(ت.تجزئة_المحتوى, ت.قيمة, مفتاح)) {
            نتيجة.صالح = false;
            نتيجة.رسالة = "التوقيع غير صالح";
            نتيجة.أسباب_الرفض.push_back("فشل التحقق من التوقيع");
            return نتيجة;
        }
        
        نتيجة.صالح = true;
        نتيجة.رسالة = "التوقيع صالح";
        return نتيجة;
    }
    
    /**
     * التحقق من ملف
     */
    نتيجة_التحقق تحقق_ملف(const std::string& مسار, const توقيع& ت) {
        std::ifstream ملف(مسار, std::ios::binary);
        if (!ملف.is_open()) {
            نتيجة_التحقق نتيجة;
            نتيجة.صالح = false;
            نتيجة.رسالة = "تعذر فتح الملف";
            return نتيجة;
        }
        
        std::ostringstream ss;
        ss << ملف.rdbuf();
        return تحقق(ss.str(), ت);
    }
    
private:
    bool تحقق_من_التوقيع(const std::string& تجزئة, 
                          const std::string& توقيع,
                          const مفتاح_عام& مفتاح) {
        // محاكاة التحقق
        return توقيع.find(تجزئة.substr(7, 16)) != std::string::npos;
    }
};

