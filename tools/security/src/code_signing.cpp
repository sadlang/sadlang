/**
 * مولّد المفاتيح
 */
class مولّد_المفاتيح {
public:
    /**
     * توليد زوج مفاتيح جديد
     */
    زوج_مفاتيح ولّد(خوارزمية_التوقيع خوارزمية, 
                     int صلاحية_بالأيام = 365) {
        زوج_مفاتيح زوج;
        
        // توليد معرّف فريد
        std::string معرّف = ولّد_معرّف();
        
        // توليد المفاتيح حسب الخوارزمية
        switch (خوارزمية) {
            case خوارزمية_التوقيع::Ed25519:
                ولّد_Ed25519(زوج);
                break;
            case خوارزمية_التوقيع::ECDSA_P256:
                ولّد_ECDSA(زوج, 256);
                break;
            case خوارزمية_التوقيع::RSA_SHA256:
            default:
                ولّد_RSA(زوج, 2048);
                break;
        }
        
        // تعيين المعرّف والتواريخ
        زوج.عام.معرّف = معرّف;
        زوج.عام.خوارزمية = خوارزمية;
        زوج.عام.تاريخ_الإنشاء = std::time(nullptr);
        زوج.عام.تاريخ_الانتهاء = زوج.عام.تاريخ_الإنشاء + 
                                 (صلاحية_بالأيام * 24 * 60 * 60);
        
        زوج.خاص.معرّف = معرّف;
        زوج.خاص.خوارزمية = خوارزمية;
        
        return زوج;
    }
    
private:
    std::string ولّد_معرّف() {
        // محاكاة توليد معرّف فريد
        std::ostringstream ss;
        ss << "KEY-" << std::hex << std::time(nullptr) 
           << "-" << rand() % 10000;
        return ss.str();
    }
    
    void ولّد_RSA(زوج_مفاتيح& زوج, int حجم) {
        // محاكاة توليد RSA
        زوج.عام.قيمة = "RSA_PUBLIC_KEY_" + std::to_string(حجم);
        زوج.خاص.قيمة_مشفرة = "RSA_PRIVATE_KEY_ENCRYPTED";
    }
    
    void ولّد_ECDSA(زوج_مفاتيح& زوج, int منحنى) {
        // محاكاة توليد ECDSA
        زوج.عام.قيمة = "ECDSA_PUBLIC_KEY_P" + std::to_string(منحنى);
        زوج.خاص.قيمة_مشفرة = "ECDSA_PRIVATE_KEY_ENCRYPTED";
    }
    
    void ولّد_Ed25519(زوج_مفاتيح& زوج) {
        // محاكاة توليد Ed25519
        زوج.عام.قيمة = "ED25519_PUBLIC_KEY";
        زوج.خاص.قيمة_مشفرة = "ED25519_PRIVATE_KEY_ENCRYPTED";
    }
};

