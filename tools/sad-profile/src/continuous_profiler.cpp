/**
 * Profiler مستمر مع تحديثات حية
 */
class profiler_مستمر {
public:
    using مستمع_تحديث = std::function<void(
        const std::unordered_map<std::string, إحصائيات_دالة>&
    )>;
    
    /**
     * إعدادات الـ Profiler
     */
    struct إعدادات {
        int فترة_العينة_us = 1000;
        int فترة_التحديث_ms = 1000;  // كل ثانية
        int حجم_النافذة = 10000;     // عدد العينات في النافذة
        bool تلقائي = true;
    };
    
    /**
     * إنشاء Profiler
     */
    explicit profiler_مستمر(إعدادات إعدادات = إعدادات{})
        : الإعدادات_(إعدادات),
          الجامع_(جامع_عينات::إعدادات{
              .فترة_العينة_us = إعدادات.فترة_العينة_us,
              .أقصى_عينات = إعدادات.حجم_النافذة
          }) {}
    
    /**
     * بدء الـ Profiling
     */
    void ابدأ() {
        الجامع_.ابدأ();
        
        if (الإعدادات_.تلقائي) {
            يحلل_ = true;
            خيط_التحليل_ = std::thread([this]() {
                while (يحلل_) {
                    حدِّث();
                    std::this_thread::sleep_for(
                        std::chrono::milliseconds(الإعدادات_.فترة_التحديث_ms)
                    );
                }
            });
        }
    }
    
    /**
     * إيقاف الـ Profiling
     */
    void أوقف() {
        يحلل_ = false;
        if (خيط_التحليل_.joinable()) {
            خيط_التحليل_.join();
        }
        الجامع_.أوقف();
    }
    
    /**
     * تحديث يدوي
     */
    void حدِّث() {
        auto العينات = الجامع_.العينات();
        آخر_إحصائيات_ = المحلل_.حلل(العينات);
        
        // إبلاغ المستمعين
        for (auto& مستمع : المستمعون_) {
            مستمع(آخر_إحصائيات_);
        }
    }
    
    /**
     * الحصول على آخر إحصائيات
     */
    const std::unordered_map<std::string, إحصائيات_دالة>& الإحصائيات() const {
        return آخر_إحصائيات_;
    }
    
    /**
     * أعلى الدوال استهلاكاً
     */
    std::vector<إحصائيات_دالة> أعلى_الدوال(int عدد = 10) {
        return المحلل_.أعلى_الدوال(آخر_إحصائيات_, عدد);
    }
    
    /**
     * تسجيل مستمع
     */
    void عند_تحديث(مستمع_تحديث مستمع) {
        المستمعون_.push_back(مستمع);
    }

private:
    إعدادات الإعدادات_;
    جامع_عينات الجامع_;
    محلل_أداء المحلل_;
    
    std::atomic<bool> يحلل_{false};
    std::thread خيط_التحليل_;
    
    std::unordered_map<std::string, إحصائيات_دالة> آخر_إحصائيات_;
    std::vector<مستمع_تحديث> المستمعون_;
};

