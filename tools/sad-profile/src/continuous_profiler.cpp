/**
 * محلل بيانات الأداء
 */
class محلل_أداء {
public:
    /**
     * تحليل العينات وإنتاج إحصائيات
     */
    std::unordered_map<std::string, إحصائيات_دالة> حلل(
        const std::vector<عينة_stack>& العينات
    ) {
        std::unordered_map<std::string, إحصائيات_دالة> إحصائيات;
        
        // عدّ ظهور كل دالة
        std::unordered_map<std::string, uint64_t> عدّاد;
        
        for (const auto& عينة : العينات) {
            if (عينة.الإطارات.empty()) continue;
            
            // الدالة في قمة الـ Stack
            const std::string& قمة = عينة.الإطارات[0];
            عدّاد[قمة]++;
            
            // تأكد من وجود الإحصائية
            if (إحصائيات.find(قمة) == إحصائيات.end()) {
                إحصائيات_دالة إحصائية;
                إحصائية.الاسم = قمة;
                إحصائيات[قمة] = إحصائية;
            }
        }
        
        // حساب النسب
        double مجموع = العينات.size();
        for (auto& [اسم, عدد] : عدّاد) {
            إحصائيات[اسم].عدد_الاستدعاءات = عدد;
            إحصائيات[اسم].نسبة_الوقت = (عدد / مجموع) * 100.0;
        }
        
        return إحصائيات;
    }
    
    /**
     * إيجاد الدوال الأكثر استهلاكاً للوقت
     */
    std::vector<إحصائيات_دالة> أعلى_الدوال(
        const std::unordered_map<std::string, إحصائيات_دالة>& إحصائيات,
        int عدد = 10
    ) {
        std::vector<إحصائيات_دالة> قائمة;
        for (const auto& [_, إحصائية] : إحصائيات) {
            قائمة.push_back(إحصائية);
        }
        
        std::sort(قائمة.begin(), قائمة.end(),
            [](const إحصائيات_دالة& أ, const إحصائيات_دالة& ب) {
                return أ.نسبة_الوقت > ب.نسبة_الوقت;
            });
        
        if (قائمة.size() > عدد) {
            قائمة.resize(عدد);
        }
        
        return قائمة;
    }
};

