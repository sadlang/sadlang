/**
 * إحصائيات دالة
 */
struct إحصائيات_دالة {
    std::string الاسم;
    std::string الملف;
    int السطر = 0;
    
    // التوقيت
    uint64_t عدد_الاستدعاءات = 0;
    double الوقت_الكلي_ms = 0;
    double الوقت_الذاتي_ms = 0;  // بدون الدوال الفرعية
    double أقصى_وقت_ms = 0;
    double أدنى_وقت_ms = std::numeric_limits<double>::max();
    double متوسط_الوقت_ms = 0;
    
    // الذاكرة
    size_t الذاكرة_المخصصة = 0;
    size_t الذاكرة_المحررة = 0;
    size_t ذروة_الذاكرة = 0;
    
    // النسبة
    double نسبة_الوقت = 0;
};

/**
 * عينة Stack
 */
struct عينة_stack {
    std::vector<std::string> الإطارات;  // من الأعلى للأسفل
    std::chrono::system_clock::time_point الوقت;
    std::thread::id معرف_الخيط;
};

