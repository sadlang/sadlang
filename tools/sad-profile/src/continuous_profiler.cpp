/**
 * مُولِّد تقارير الأداء
 */
class مولد_تقارير_أداء {
public:
    /**
     * توليد تقرير نصي
     */
    static std::string ولِّد_تقرير(
        const std::vector<إحصائيات_دالة>& إحصائيات
    ) {
        std::stringstream تقرير;
        
        تقرير << "╔════════════════════════════════════════════════════════════════╗\n";
        تقرير << "║                    تقرير الأداء                                ║\n";
        تقرير << "╠════════════════════════════════════════════════════════════════╣\n";
        تقرير << "║ الدالة                              الوقت        %            ║\n";
        تقرير << "╠════════════════════════════════════════════════════════════════╣\n";
        
        for (const auto& إحصائية : إحصائيات) {
            // شريط بصري
            int طول_الشريط = int(إحصائية.نسبة_الوقت / 2);
            std::string شريط(طول_الشريط, '█');
            شريط.resize(50, ' ');
            
            تقرير << "║ ";
            تقرير << std::setw(35) << std::left << إحصائية.الاسم;
            تقرير << std::setw(10) << std::right << std::fixed 
                  << std::setprecision(1) << إحصائية.الوقت_الكلي_ms << "ms ";
            تقرير << std::setw(5) << std::right << std::fixed 
                  << std::setprecision(1) << إحصائية.نسبة_الوقت << "%\n";
            تقرير << "║   " << شريط << "\n";
        }
        
        تقرير << "╚════════════════════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }
    
    /**
     * توليد JSON
     */
    static std::string ولِّد_json(
        const std::vector<إحصائيات_دالة>& إحصائيات
    ) {
        std::stringstream json;
        
        json << "{\n  \"functions\": [\n";
        
        for (size_t i = 0; i < إحصائيات.size(); i++) {
            const auto& إحصائية = إحصائيات[i];
            
            json << "    {\n";
            json << "      \"name\": \"" << إحصائية.الاسم << "\",\n";
            json << "      \"calls\": " << إحصائية.عدد_الاستدعاءات << ",\n";
            json << "      \"total_time_ms\": " << إحصائية.الوقت_الكلي_ms << ",\n";
            json << "      \"self_time_ms\": " << إحصائية.الوقت_الذاتي_ms << ",\n";
            json << "      \"percentage\": " << إحصائية.نسبة_الوقت << "\n";
            json << "    }";
            
            if (i < إحصائيات.size() - 1) json << ",";
            json << "\n";
        }
        
        json << "  ]\n}\n";
        
        return json.str();
    }
};

