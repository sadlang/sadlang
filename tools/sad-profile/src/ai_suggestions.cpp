/**
 * اقتراح تحسين
 */
struct اقتراح_تحسين {
    std::string المعرف;
    std::string العنوان;
    std::string الوصف;
    
    // الموقع
    std::string الملف;
    std::string الدالة;
    int السطر = 0;
    
    // التصنيف
    فئة_مشكلة الفئة;
    خطورة الخطورة;
    
    // الكود
    std::string الكود_الحالي;
    std::string الكود_المُقترح;
    std::string شرح_التغيير;
    
    // التأثير المتوقع
    double تحسين_الوقت_نسبة;  // كم % أسرع
    double تحسين_الذاكرة_نسبة;
    double الثقة;  // ثقة الـ AI في الاقتراح (0-1)
    
    // قابلية التطبيق التلقائي
    bool قابل_للتطبيق_تلقائياً;
    std::string سبب_عدم_الإمكانية;
};

// ═══════════════════════════════════════════════════════════════════════════════
