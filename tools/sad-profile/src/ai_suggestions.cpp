/**
 * فئة المشكلة
 */
enum class فئة_مشكلة {
    تعقيد_خوارزمي,      // O(n²) يمكن أن يكون O(n)
    تخصيص_ذاكرة,        // تخصيصات كثيرة
    حلقة_غير_فعالة,     // حلقة يمكن تحسينها
    استدعاء_متكرر,       // دالة تُستدعى كثيراً
    io_بطيء,            // قراءة/كتابة بطيئة
    قفل_مُعيق,          // انتظار على mutex
    تجميد_سلسلة,        // concatenation غير فعال
    فرز_غير_فعال,       // خوارزمية فرز بطيئة
    بحث_غير_فعال,       // بحث خطي يمكن أن يكون ثنائي
    أخرى
};

/**
 * خطورة المشكلة
 */
enum class خطورة {
    منخفضة,   // تحسين بسيط
    متوسطة,  // يستحق الإصلاح
    عالية,   // مؤثر على الأداء
    حرجة     // يجب إصلاحه
};

