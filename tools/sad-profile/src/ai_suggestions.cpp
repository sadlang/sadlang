/**
 * مُولِّد تقارير الاقتراحات
 */
class مولد_تقارير_اقتراحات {
public:
    /**
     * توليد تقرير نصي
     */
    static std::string ولِّد_تقرير(
        const std::vector<اقتراح_تحسين>& الاقتراحات
    ) {
        std::stringstream تقرير;
        
        تقرير << "╔════════════════════════════════════════════════════════════════╗\n";
        تقرير << "║              اقتراحات تحسين الأداء - AI                        ║\n";
        تقرير << "╠════════════════════════════════════════════════════════════════╣\n";
        
        int رقم = 1;
        for (const auto& اقتراح : الاقتراحات) {
            تقرير << "║                                                                ║\n";
            تقرير << "║ ⚡ اقتراح #" << رقم++ << ": " << اقتراح.العنوان << "\n";
            تقرير << "║ ────────────────────────────────────────────────────────────  ║\n";
            تقرير << "║ الدالة: " << اقتراح.الدالة << "\n";
            تقرير << "║ الخطورة: " << اسم_الخطورة(اقتراح.الخطورة) << "\n";
            تقرير << "║ الثقة: " << int(اقتراح.الثقة * 100) << "%\n";
            تقرير << "║ التحسين المتوقع: " << اقتراح.تحسين_الوقت_نسبة << "%\n";
            تقرير << "║ الوصف: " << اقتراح.الوصف << "\n";
            
            if (اقتراح.قابل_للتطبيق_تلقائياً) {
                تقرير << "║ ✓ يمكن تطبيقه تلقائياً\n";
            }
            
            تقرير << "║                                                                ║\n";
        }
        
        تقرير << "╚════════════════════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }

private:
    static std::string اسم_الخطورة(خطورة خ) {
        switch (خ) {
            case خطورة::منخفضة: return "🟢 منخفضة";
            case خطورة::متوسطة: return "🟡 متوسطة";
            case خطورة::عالية: return "🟠 عالية";
            case خطورة::حرجة: return "🔴 حرجة";
            default: return "غير معروفة";
        }
    }
};

