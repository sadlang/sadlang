/**
 * بيانات أداء دالة
 */
struct بيانات_أداء_دالة {
    std::string الاسم;
    uint64_t عدد_الاستدعاءات;
    double الوقت_الكلي_ms;
    double الوقت_المتوسط_ms;
    double نسبة_الوقت;
    
    // الكود
    std::string كود_الدالة;
};

/**
 * محلل الأداء بالذكاء الاصطناعي
 */
class محلل_أداء_ذكي {
public:
    /**
     * تحليل الأداء وإنتاج اقتراحات
     */
    std::vector<اقتراح_تحسين> حلل(
        const std::vector<بيانات_أداء_دالة>& بيانات
    ) {
        std::vector<اقتراح_تحسين> كل_الاقتراحات;
        
        for (const auto& دالة : بيانات) {
            // 1. كشف الأنماط في الكود
            auto اقتراحات_كود = الكاشف_.اكشف(دالة.كود_الدالة);
            
            for (auto& اقتراح : اقتراحات_كود) {
                اقتراح.الدالة = دالة.الاسم;
                
                // تعديل الخطورة حسب بيانات الأداء
                if (دالة.نسبة_الوقت > 20) {
                    اقتراح.الخطورة = خطورة::حرجة;
                } else if (دالة.نسبة_الوقت > 10) {
                    اقتراح.الخطورة = خطورة::عالية;
                }
                
                // حساب الثقة
                اقتراح.الثقة = احسب_الثقة(دالة, اقتراح);
                
                كل_الاقتراحات.push_back(اقتراح);
            }
            
            // 2. اقتراحات مبنية على البيانات
            if (دالة.عدد_الاستدعاءات > 10000 && دالة.الوقت_المتوسط_ms > 1) {
                اقتراح_تحسين اقتراح;
                اقتراح.العنوان = "دالة ساخنة";
                اقتراح.الوصف = "هذه الدالة تُستدعى " + 
                              std::to_string(دالة.عدد_الاستدعاءات) + 
                              " مرة. تحسينها سيُحدث فرقاً كبيراً.";
                اقتراح.الدالة = دالة.الاسم;
                اقتراح.الفئة = فئة_مشكلة::استدعاء_متكرر;
                اقتراح.الخطورة = خطورة::عالية;
                اقتراح.تحسين_الوقت_نسبة = دالة.نسبة_الوقت;
                اقتراح.الثقة = 0.9;
                
                كل_الاقتراحات.push_back(اقتراح);
            }
        }
        
        // ترتيب حسب الخطورة والثقة
        std::sort(كل_الاقتراحات.begin(), كل_الاقتراحات.end(),
            [](const اقتراح_تحسين& أ, const اقتراح_تحسين& ب) {
                if (أ.الخطورة != ب.الخطورة) {
                    return int(أ.الخطورة) > int(ب.الخطورة);
                }
                return أ.الثقة > ب.الثقة;
            });
        
        return كل_الاقتراحات;
    }

private:
    كاشف_أنماط الكاشف_;
    
    double احسب_الثقة(
        const بيانات_أداء_دالة& دالة,
        const اقتراح_تحسين& اقتراح
    ) {
        double ثقة = 0.5;  // قاعدة
        
        // زيادة الثقة إذا الدالة بطيئة فعلاً
        if (دالة.نسبة_الوقت > 10) ثقة += 0.2;
        if (دالة.عدد_الاستدعاءات > 1000) ثقة += 0.1;
        
        // زيادة إذا النمط واضح
        if (اقتراح.قابل_للتطبيق_تلقائياً) ثقة += 0.1;
        
        return std::min(ثقة, 0.95);
    }
};

