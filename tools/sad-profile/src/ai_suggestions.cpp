/**
 * نمط مشكلة معروف
 */
struct نمط_مشكلة {
    std::string الاسم;
    فئة_مشكلة الفئة;
    خطورة الخطورة_الافتراضية;
    
    // كاشف
    std::function<bool(const std::string& كود)> اكتشف;
    
    // مُصلح
    std::function<std::string(const std::string& كود)> أصلح;
    
    // معلومات
    std::string الشرح;
    double التحسين_المتوقع;
};

/**
 * كاشف الأنماط البطيئة
 */
class كاشف_أنماط {
public:
    /**
     * إنشاء الكاشف مع الأنماط المدمجة
     */
    كاشف_أنماط() {
        سجّل_أنماط_مدمجة();
    }
    
    /**
     * كشف المشاكل في الكود
     */
    std::vector<اقتراح_تحسين> اكشف(const std::string& الكود) {
        std::vector<اقتراح_تحسين> اقتراحات;
        
        for (const auto& نمط : الأنماط_) {
            if (نمط.اكتشف(الكود)) {
                اقتراح_تحسين اقتراح;
                اقتراح.العنوان = نمط.الاسم;
                اقتراح.الوصف = نمط.الشرح;
                اقتراح.الفئة = نمط.الفئة;
                اقتراح.الخطورة = نمط.الخطورة_الافتراضية;
                اقتراح.الكود_الحالي = الكود;
                اقتراح.تحسين_الوقت_نسبة = نمط.التحسين_المتوقع;
                
                if (نمط.أصلح) {
                    اقتراح.الكود_المُقترح = نمط.أصلح(الكود);
                    اقتراح.قابل_للتطبيق_تلقائياً = true;
                }
                
                اقتراحات.push_back(اقتراح);
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * إضافة نمط جديد
     */
    void أضف_نمط(const نمط_مشكلة& نمط) {
        الأنماط_.push_back(نمط);
    }

private:
    std::vector<نمط_مشكلة> الأنماط_;
    
    void سجّل_أنماط_مدمجة() {
        // نمط 1: حلقة متداخلة O(n²)
        أضف_نمط({
            .الاسم = "حلقة متداخلة O(n²)",
            .الفئة = فئة_مشكلة::تعقيد_خوارزمي,
            .الخطورة_الافتراضية = خطورة::عالية,
            .اكتشف = [](const std::string& كود) {
                // كشف مُبسَّط - في الإنتاج نستخدم AST
                return كود.find("لكل") != std::string::npos &&
                       std::count(كود.begin(), كود.end(), '\n') > 2 &&
                       كود.rfind("لكل") != كود.find("لكل");  // حلقتان
            },
            .أصلح = nullptr,  // يحتاج تحليل أعمق
            .الشرح = "حلقة متداخلة قد تكون O(n²). فكر في استخدام HashMap.",
            .التحسين_المتوقع = 80.0
        });
        
        // نمط 2: تجميع سلاسل في حلقة
        أضف_نمط({
            .الاسم = "تجميع سلاسل غير فعال",
            .الفئة = فئة_مشكلة::تجميد_سلسلة,
            .الخطورة_الافتراضية = خطورة::متوسطة,
            .اكتشف = [](const std::string& كود) {
                return (كود.find("لكل") != std::string::npos ||
                        كود.find("طالما") != std::string::npos) &&
                       كود.find("+= \"") != std::string::npos;
            },
            .أصلح = [](const std::string& كود) {
                // تحويل إلى StringBuilder
                std::string مُعدَّل = "// استخدم بنّاء_نص بدلاً من التجميع\n";
                مُعدَّل += "متغير بنّاء = بنّاء_نص()\n";
                مُعدَّل += كود;  // في الإنتاج: تحويل حقيقي
                return مُعدَّل;
            },
            .الشرح = "تجميع السلاسل في حلقة يُنشئ نسخاً كثيرة. استخدم بنّاء_نص.",
            .التحسين_المتوقع = 50.0
        });
        
        // نمط 3: بحث خطي في قائمة كبيرة
        أضف_نمط({
            .الاسم = "بحث خطي يمكن تحسينه",
            .الفئة = فئة_مشكلة::بحث_غير_فعال,
            .الخطورة_الافتراضية = خطورة::متوسطة,
            .اكتشف = [](const std::string& كود) {
                return كود.find(".يحتوي(") != std::string::npos ||
                       كود.find(".ابحث(") != std::string::npos;
            },
            .أصلح = nullptr,
            .الشرح = "البحث الخطي O(n). إذا كان متكرراً، استخدم مجموعة أو قاموس.",
            .التحسين_المتوقع = 70.0
        });
        
        // نمط 4: قراءة ملف سطر بسطر
        أضف_نمط({
            .الاسم = "قراءة ملف بطيئة",
            .الفئة = فئة_مشكلة::io_بطيء,
            .الخطورة_الافتراضية = خطورة::متوسطة,
            .اكتشف = [](const std::string& كود) {
                return كود.find("اقرأ_سطر") != std::string::npos &&
                       كود.find("طالما") != std::string::npos;
            },
            .أصلح = nullptr,
            .الشرح = "قراءة سطر بسطر بطيئة. فكر في قراءة الملف كله أو استخدام buffer.",
            .التحسين_المتوقع = 40.0
        });
    }
};

