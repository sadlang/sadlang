/**
 * إعدادات الرسم
 */
struct إعدادات_رسم {
    int العرض = 1200;
    int ارتفاع_الإطار = 20;
    int هامش = 10;
    
    std::string لون_خلفية = "#f8f8f8";
    std::string لون_نص = "#000000";
    std::string خط = "Tahoma, Arial";
    int حجم_خط = 12;
    
    // الألوان (يُختار عشوائياً من هذه)
    std::vector<std::string> ألوان = {
        "#f8a51a", "#f85a3e", "#f7347a", "#5d3ef7",
        "#3e9cf7", "#3ef7a4", "#a4f73e", "#f7e43e"
    };
};

/**
 * مُولِّد Flame Graph بصيغة SVG
 */
class مولد_flame_svg {
public:
    /**
     * إنشاء المولد
     */
    explicit مولد_flame_svg(إعدادات_رسم إعدادات = إعدادات_رسم{})
        : الإعدادات_(إعدادات) {}
    
    /**
     * توليد SVG
     */
    std::string ولِّد(std::shared_ptr<عقدة_flame> الجذر) {
        // حساب الأبعاد
        int أقصى_عمق = احسب_أقصى_عمق(الجذر);
        int الارتفاع = الإعدادات_.هامش * 2 + 
                       (أقصى_عمق + 1) * الإعدادات_.ارتفاع_الإطار;
        
        // حساب العرض لكل عقدة
        double المقياس = (الإعدادات_.العرض - 2 * الإعدادات_.هامش) / 
                        double(الجذر->القيمة);
        احسب_الأبعاد(الجذر, الإعدادات_.هامش, المقياس);
        
        // بناء SVG
        std::stringstream svg;
        
        svg << "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
        svg << "<svg xmlns=\"http://www.w3.org/2000/svg\" "
            << "width=\"" << الإعدادات_.العرض << "\" "
            << "height=\"" << الارتفاع << "\">\n";
        
        // الخلفية
        svg << "<rect width=\"100%\" height=\"100%\" "
            << "fill=\"" << الإعدادات_.لون_خلفية << "\"/>\n";
        
        // العنوان
        svg << "<text x=\"" << الإعدادات_.العرض / 2 << "\" y=\"15\" "
            << "text-anchor=\"middle\" "
            << "font-family=\"" << الإعدادات_.خط << "\" "
            << "font-size=\"16\" fill=\"" << الإعدادات_.لون_نص << "\">"
            << "Flame Graph - لغة ص"
            << "</text>\n";
        
        // الإطارات
        ارسم_عقدة(svg, الجذر, الارتفاع - الإعدادات_.هامش);
        
        // JavaScript للتفاعل
        svg << "<script type=\"text/ecmascript\"><![CDATA[\n"
            << "  function show(e) {\n"
            << "    var info = document.getElementById('info');\n"
            << "    info.textContent = e.getAttribute('data-info');\n"
            << "  }\n"
            << "]]></script>\n";
        
        // منطقة المعلومات
        svg << "<text id=\"info\" x=\"10\" y=\"" << الارتفاع - 5 << "\" "
            << "font-family=\"" << الإعدادات_.خط << "\" "
            << "font-size=\"" << الإعدادات_.حجم_خط << "\"></text>\n";
        
        svg << "</svg>\n";
        
        return svg.str();
    }

private:
    إعدادات_رسم الإعدادات_;
    std::mt19937 rng_{std::random_device{}()};
    
    int احسب_أقصى_عمق(std::shared_ptr<عقدة_flame> عقدة) {
        int أقصى = عقدة->depth;
        for (const auto& [_, طفل] : عقدة->الأطفال) {
            أقصى = std::max(أقصى, احسب_أقصى_عمق(طفل));
        }
        return أقصى;
    }
    
    void احسب_الأبعاد(
        std::shared_ptr<عقدة_flame> عقدة,
        double x,
        double المقياس
    ) {
        عقدة->x = x;
        عقدة->width = عقدة->القيمة * المقياس;
        
        double x_طفل = x;
        for (auto& [_, طفل] : عقدة->الأطفال) {
            احسب_الأبعاد(طفل, x_طفل, المقياس);
            x_طفل += طفل->width;
        }
    }
    
    void ارسم_عقدة(
        std::stringstream& svg,
        std::shared_ptr<عقدة_flame> عقدة,
        int y_قاعدة
    ) {
        if (عقدة->depth >= 0 && عقدة->width > 1) {  // لا ترسم الصغيرة جداً
            int y = y_قاعدة - (عقدة->depth + 1) * الإعدادات_.ارتفاع_الإطار;
            
            // اختيار لون
            std::uniform_int_distribution<size_t> dist(0, الإعدادات_.ألوان.size() - 1);
            std::string لون = الإعدادات_.ألوان[dist(rng_)];
            
            // معلومات
            std::stringstream معلومات;
            معلومات << عقدة->الاسم << " (" << عقدة->القيمة << " عينة";
            if (عقدة->القيمة_الذاتية > 0) {
                معلومات << ", " << عقدة->القيمة_الذاتية << " ذاتية";
            }
            معلومات << ")";
            
            // المستطيل
            svg << "<g class=\"frame\" onmouseover=\"show(this)\" "
                << "data-info=\"" << معلومات.str() << "\">\n";
            
            svg << "  <rect x=\"" << عقدة->x << "\" y=\"" << y << "\" "
                << "width=\"" << عقدة->width << "\" "
                << "height=\"" << الإعدادات_.ارتفاع_الإطار - 1 << "\" "
                << "fill=\"" << لون << "\" "
                << "rx=\"2\" ry=\"2\"/>\n";
            
            // النص (إذا كان هناك مساحة)
            if (عقدة->width > 30) {
                svg << "  <text x=\"" << عقدة->x + 3 << "\" "
                    << "y=\"" << y + الإعدادات_.ارتفاع_الإطار - 5 << "\" "
                    << "font-family=\"" << الإعدادات_.خط << "\" "
                    << "font-size=\"" << الإعدادات_.حجم_خط << "\" "
                    << "fill=\"" << الإعدادات_.لون_نص << "\">"
                    << اقطع_نص(عقدة->الاسم, عقدة->width)
                    << "</text>\n";
            }
            
            svg << "</g>\n";
        }
        
        // الأطفال
        for (const auto& [_, طفل] : عقدة->الأطفال) {
            ارسم_عقدة(svg, طفل, y_قاعدة);
        }
    }
    
    std::string اقطع_نص(const std::string& نص, double العرض) {
        int أقصى_حروف = int(العرض / 7);  // تقريبي
        if (نص.size() <= أقصى_حروف) return نص;
        if (أقصى_حروف < 4) return "";
        return نص.substr(0, أقصى_حروف - 3) + "...";
    }
};

