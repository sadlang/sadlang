/**
 * إطار في الـ Stack
 */
struct إطار_stack {
    std::string الدالة;
    std::string الملف;
    int السطر = 0;
    
    // للتوليد
    std::string المفتاح() const {
        return الدالة + ":" + الملف + ":" + std::to_string(السطر);
    }
};

/**
 * مسار Stack كامل (من القاعدة للقمة)
 */
struct مسار_stack {
    std::vector<إطار_stack> الإطارات;
    uint64_t العدد = 1;  // كم مرة ظهر هذا المسار
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              عقدة الشجرة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * عقدة في شجرة الـ Flame
 */
struct عقدة_flame {
    std::string الاسم;
    uint64_t القيمة = 0;     // العينات
    uint64_t القيمة_الذاتية = 0;  // العينات في هذه الدالة فقط
    
    // الأطفال
    std::unordered_map<std::string, std::shared_ptr<عقدة_flame>> الأطفال;
    
    // للرسم
    double x = 0;
    double width = 0;
    int depth = 0;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              بناء الشجرة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * بنّاء شجرة الـ Flame
 */
class بناء_شجرة_flame {
public:
    /**
     * بناء الشجرة من مسارات Stack
     */
    std::shared_ptr<عقدة_flame> ابنِ(const std::vector<مسار_stack>& المسارات) {
        auto جذر = std::make_shared<عقدة_flame>();
        جذر->الاسم = "root";
        جذر->depth = -1;
        
        for (const auto& مسار : المسارات) {
            أضف_مسار(جذر, مسار);
        }
        
        return جذر;
    }

private:
    void أضف_مسار(
        std::shared_ptr<عقدة_flame> عقدة,
        const مسار_stack& مسار
    ) {
        عقدة->القيمة += مسار.العدد;
        
        std::shared_ptr<عقدة_flame> حالية = عقدة;
        
        // من القاعدة (أول إطار) إلى القمة
        for (size_t i = 0; i < مسار.الإطارات.size(); i++) {
            const auto& إطار = مسار.الإطارات[i];
            const std::string& اسم = إطار.الدالة;
            
            auto it = حالية->الأطفال.find(اسم);
            if (it == حالية->الأطفال.end()) {
                auto طفل = std::make_shared<عقدة_flame>();
                طفل->الاسم = اسم;
                طفل->depth = حالية->depth + 1;
                حالية->الأطفال[اسم] = طفل;
                it = حالية->الأطفال.find(اسم);
            }
            
            it->second->القيمة += مسار.العدد;
            
            // إذا كان هذا آخر إطار، القيمة ذاتية
            if (i == مسار.الإطارات.size() - 1) {
                it->second->القيمة_الذاتية += مسار.العدد;
            }
            
            حالية = it->second;
        }
    }
};

