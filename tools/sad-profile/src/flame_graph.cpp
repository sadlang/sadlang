/**
 * واجهة مُولِّد Flame Graph
 */
class مولد_flame_graph {
public:
    /**
     * توليد Flame Graph من مسارات Stack
     */
    std::string ولِّد_svg(const std::vector<مسار_stack>& المسارات) {
        // بناء الشجرة
        بناء_شجرة_flame بناء;
        auto شجرة = بناء.ابنِ(المسارات);
        
        // توليد SVG
        مولد_flame_svg مولد;
        return مولد.ولِّد(شجرة);
    }
    
    /**
     * حفظ إلى ملف
     */
    bool احفظ(const std::string& المسار, const std::vector<مسار_stack>& المسارات) {
        std::string svg = ولِّد_svg(المسارات);
        
        std::ofstream ملف(المسار);
        if (!ملف) return false;
        
        ملف << svg;
        return true;
    }
    
    /**
     * توليد HTML تفاعلي
     */
    std::string ولِّد_html(const std::vector<مسار_stack>& المسارات) {
        std::string svg = ولِّد_svg(المسارات);
        
        std::stringstream html;
        
        html << "<!DOCTYPE html>\n"
             << "<html dir=\"rtl\" lang=\"ar\">\n"
             << "<head>\n"
             << "  <meta charset=\"UTF-8\">\n"
             << "  <title>Flame Graph - لغة ص</title>\n"
             << "  <style>\n"
             << "    body { font-family: Tahoma, Arial; margin: 20px; }\n"
             << "    h1 { text-align: center; }\n"
             << "    .frame:hover rect { stroke: #000; stroke-width: 1; }\n"
             << "  </style>\n"
             << "</head>\n"
             << "<body>\n"
             << "  <h1>رسم اللهب - تحليل الأداء</h1>\n"
             << svg
             << "</body>\n"
             << "</html>\n";
        
        return html.str();
    }
};

