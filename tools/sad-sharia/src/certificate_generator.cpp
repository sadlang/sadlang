/**
 * ملخص فحص شرعي
 */
struct ملخص_فحص {
    std::string الفئة;      // "الربا" / "الغرر" / "الميسر"
    bool ناجح;
    int مشاكل_صريحة;
    int مشاكل_محتملة;
    int مشاكل_مُشتبهة;
    std::vector<std::string> التفاصيل;
    std::vector<std::string> التوصيات;
};

/**
 * نتيجة الفحص الشامل
 */
struct نتيجة_فحص_شامل {
    bool ممتثل;
    مستوى_امتثال المستوى;
    std::vector<ملخص_فحص> الملخصات;
    std::string ملاحظات_عامة;
    
    int إجمالي_صريح() const {
        int مجموع = 0;
        for (const auto& م : الملخصات) مجموع += م.مشاكل_صريحة;
        return مجموع;
    }
    
    int إجمالي_محتمل() const {
        int مجموع = 0;
        for (const auto& م : الملخصات) مجموع += م.مشاكل_محتملة;
        return مجموع;
    }
};

