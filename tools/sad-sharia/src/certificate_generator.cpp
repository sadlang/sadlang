/**
 * مستوى الامتثال الشرعي
 */
enum class مستوى_امتثال {
    ذهبي,      // امتثال كامل
    فضي,       // امتثال جيد
    برونزي,    // امتثال مقبول
    مرفوض      // غير ممتثل
};

/**
 * تحويل المستوى لنص عربي
 */
inline std::string نص_المستوى(مستوى_امتثال المستوى) {
    switch (المستوى) {
        case مستوى_امتثال::ذهبي: return "🥇 ذهبي - امتثال كامل";
        case مستوى_امتثال::فضي: return "🥈 فضي - امتثال جيد";
        case مستوى_امتثال::برونزي: return "🥉 برونزي - امتثال مقبول";
        case مستوى_امتثال::مرفوض: return "❌ مرفوض - غير ممتثل";
    }
    return "غير معروف";
}

// ═══════════════════════════════════════════════════════════════════════════════
