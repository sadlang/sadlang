// ============== أنواع المعايير ==============

/**
 * المعيار
 */
enum class معيار_امتثال {
    ISO_27001,      // أمن المعلومات
    ISO_27017,      // أمن السحابة
    ISO_27018,      // حماية البيانات الشخصية
    SOC2_Type1,     // ضوابط الخدمة
    SOC2_Type2,     // ضوابط الخدمة (مستمر)
    GDPR,           // حماية البيانات الأوروبية
    HIPAA,          // الرعاية الصحية
    PCI_DSS,        // بطاقات الدفع
    CCPA,           // خصوصية كاليفورنيا
    مخصص            // معيار مخصص
};

/**
 * فئة الضابط
 */
enum class فئة_ضابط {
    وصول,           // Access Control
    تشفير,          // Encryption
    سجلات,         // Logging/Audit
    نسخ_احتياطي,   // Backup
    استجابة_حوادث, // Incident Response
    إدارة_أصول,    // Asset Management
    موارد_بشرية,   // HR Security
    فيزيائي,        // Physical Security
    شبكات,          // Network Security
    تطوير          // Secure Development
};

/**
 * حالة الامتثال
 */
enum class حالة_امتثال {
    ممتثل,          // Compliant
    جزئي,           // Partially compliant
    غير_ممتثل,     // Non-compliant
    غير_قابل_للتطبيق,  // N/A
    قيد_التقييم    // Under review
};

/**
 * خطورة الانتهاك
 */
enum class خطورة_انتهاك {
    معلوماتي,
    منخفض,
    متوسط,
    عالي,
    حرج
};

// ============== الضابط ==============

/**
 * ضابط امتثال
 */
struct ضابط_امتثال {
    std::string معرف;
    std::string الكود;        // مثل "AC-1"
    std::string العنوان;
    std::string الوصف;
    
    معيار_امتثال المعيار;
    فئة_ضابط الفئة;
    
    // المتطلبات
    std::vector<std::string> المتطلبات;
    
    // الأدلة المطلوبة
    std::vector<std::string> الأدلة_المطلوبة;
    
    // الحالة
    حالة_امتثال الحالة = حالة_امتثال::قيد_التقييم;
    
    // التاريخ
    std::string آخر_تقييم;
    std::string التقييم_القادم;
    
    // الملاحظات
    std::string ملاحظات;
};

// ============== الدليل ==============

/**
 * دليل امتثال
 */
struct دليل_امتثال {
    std::string معرف;
    std::string معرف_ضابط;
    
    std::string العنوان;
    std::string الوصف;
    
    std::string نوع_الدليل;   // مستند، لقطة، سجل، إلخ
    std::string المسار;       // رابط أو مسار ملف
    
    std::string جمعه;
    std::string تاريخ_الجمع;
    
    bool صالح = true;
    std::string تاريخ_الانتهاء;
};

// ============== السياسة ==============

/**
 * سياسة امتثال
 */
struct سياسة_امتثال {
    std::string معرف;
    std::string العنوان;
    std::string الوصف;
    
    // المحتوى
    std::string المحتوى;
    std::string الإصدار;
    
    // المعايير المرتبطة
    std::vector<معيار_امتثال> المعايير;
    
    // الحالة
    bool نشطة = true;
    std::string تاريخ_السريان;
    std::string تاريخ_المراجعة_القادمة;
    
    // الموافقات
    std::string معتمد_من;
    std::string تاريخ_الاعتماد;
};

// ============== الانتهاك ==============

/**
 * انتهاك امتثال
 */
struct انتهاك_امتثال {
    std::string معرف;
    std::string معرف_ضابط;
    
    std::string العنوان;
    std::string الوصف;
    
    خطورة_انتهاك الخطورة;
    
    // التواريخ
    std::string تاريخ_الاكتشاف;
    std::string تاريخ_الإصلاح_المتوقع;
    std::string تاريخ_الإصلاح_الفعلي;
    
    // المعالجة
    std::string خطة_الإصلاح;
    std::string المسؤول;
    bool معالج = false;
    
    // الأثر
    std::string الأثر_المحتمل;
};

// ============== التقييم ==============

