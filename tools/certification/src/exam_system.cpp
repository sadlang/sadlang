extern "C" {

using namespace ص::شهادات;

static مدير_امتحانات* المدير_العام = nullptr;

void sad_exam_init() {
    if (!المدير_العام) {
        المدير_العام = new مدير_امتحانات();
    }
}

void sad_exam_cleanup() {
    delete المدير_العام;
    المدير_العام = nullptr;
}

const char* sad_exam_start_session(const char* معرف_امتحان, 
                                    const char* معرف_طالب) {
    if (!المدير_العام) return nullptr;
    
    static std::string نتيجة;
    نتيجة = المدير_العام->بدء_جلسة(معرف_امتحان, معرف_طالب);
    
    return نتيجة.empty() ? nullptr : نتيجة.c_str();
}

int sad_exam_get_remaining_time(const char* معرف_جلسة) {
    if (!المدير_العام) return 0;
    
    auto* جلسة = المدير_العام->الحصول_على_جلسة(معرف_جلسة);
    return جلسة ? جلسة->الوقت_المتبقي() : 0;
}

double sad_exam_get_score(const char* معرف_جلسة) {
    if (!المدير_العام) return 0;
    
    auto* جلسة = المدير_العام->الحصول_على_جلسة(معرف_جلسة);
    return جلسة ? جلسة->النسبة_المئوية() : 0;
}

int sad_exam_has_passed(const char* معرف_جلسة) {
    if (!المدير_العام) return 0;
    
    auto* جلسة = المدير_العام->الحصول_على_جلسة(معرف_جلسة);
    return جلسة ? (جلسة->نجح() ? 1 : 0) : 0;
}

}  // extern "C"
