/**
 * مولد شهادات ص
 */
class مولد_شهادات {
private:
    إعدادات_قالب الإعدادات_;
    
public:
    explicit مولد_شهادات(const إعدادات_قالب& إعدادات = إعدادات_قالب{})
        : الإعدادات_(إعدادات) {}
    
    // ============== توليد الشهادة ==============
    
    bool توليد_شهادة(const معلومات_شهادة& معلومات,
                    const std::string& مسار_الملف) {
        مولد_PDF pdf(الإعدادات_);
        
        double مركز = الإعدادات_.عرض / 2;
        
        // ============== الخلفية ==============
        if (الإعدادات_.يتضمن_خلفية_زخرفية) {
            // إطار ذهبي
            pdf.إضافة_مستطيل(20, 20, الإعدادات_.عرض - 40, 
                            الإعدادات_.ارتفاع - 40, 
                            الإعدادات_.لون_ثانوي);
        }
        
        // ============== العنوان ==============
        double y = 80;
        
        pdf.إضافة_نص(مركز, y, "شهادة", الإعدادات_.خط_عنوان, 48,
                     الإعدادات_.لون_رئيسي);
        y += 50;
        
        pdf.إضافة_نص(مركز, y, "CERTIFICATE", الإعدادات_.خط_إنجليزي, 24,
                     الإعدادات_.لون_رئيسي);
        y += 40;
        
        // خط فاصل
        pdf.إضافة_خط(100, y, الإعدادات_.عرض - 100, y,
                     الإعدادات_.لون_ثانوي, 2);
        y += 40;
        
        // ============== المحتوى ==============
        
        pdf.إضافة_نص(مركز, y, "تشهد مؤسسة ص للبرمجة أن", "", 14);
        y += 30;
        
        // اسم المستلم
        pdf.إضافة_نص(مركز, y, معلومات.اسم_المستلم, 
                     الإعدادات_.خط_عنوان, 36, الإعدادات_.لون_رئيسي);
        y += 40;
        
        if (!معلومات.اسم_إنجليزي.empty()) {
            pdf.إضافة_نص(مركز, y, معلومات.اسم_إنجليزي,
                        الإعدادات_.خط_إنجليزي, 18);
            y += 30;
        }
        
        pdf.إضافة_نص(مركز, y, "قد أتم بنجاح", "", 14);
        y += 30;
        
        // عنوان الشهادة
        pdf.إضافة_نص(مركز, y, معلومات.عنوان, الإعدادات_.خط_عنوان, 28,
                     الإعدادات_.لون_رئيسي);
        y += 35;
        
        // المستوى
        pdf.إضافة_نص(مركز, y, "مستوى: " + معلومات.مستوى, "", 16);
        y += 30;
        
        // النتيجة
        std::ostringstream نتيجة;
        نتيجة << "بنسبة " << std::fixed << std::setprecision(1) 
              << معلومات.النسبة << "% - " << معلومات.التقدير;
        pdf.إضافة_نص(مركز, y, نتيجة.str(), "", 16);
        y += 50;
        
        // ============== التوقيع ==============
        
        // خط التوقيع
        pdf.إضافة_خط(مركز - 100, y, مركز + 100, y, "#000000", 1);
        y += 20;
        
        pdf.إضافة_نص(مركز, y, معلومات.اسم_المُصدر, "", 14);
        y += 20;
        
        pdf.إضافة_نص(مركز, y, معلومات.منصب_المُصدر, "", 12,
                     الإعدادات_.لون_نص);
        y += 40;
        
        // ============== التاريخ والرقم ==============
        
        pdf.إضافة_نص(100, y, "تاريخ الإصدار: " + معلومات.تاريخ_إصدار,
                     "", 10, الإعدادات_.لون_نص, "left");
        pdf.إضافة_نص(الإعدادات_.عرض - 100, y, 
                     "رقم الشهادة: " + معلومات.رقم_شهادة,
                     "", 10, الإعدادات_.لون_نص, "right");
        y += 20;
        
        if (!معلومات.تاريخ_انتهاء.empty()) {
            pdf.إضافة_نص(100, y, "صالحة حتى: " + معلومات.تاريخ_انتهاء,
                        "", 10, الإعدادات_.لون_نص, "left");
        }
        
        // ============== رابط التحقق ==============
        
        y = الإعدادات_.ارتفاع - 60;
        pdf.إضافة_نص(مركز, y, "للتحقق من صحة الشهادة:", "", 10,
                     الإعدادات_.لون_نص);
        y += 15;
        pdf.إضافة_نص(مركز, y, معلومات.رابط_التحقق, "", 10,
                     الإعدادات_.لون_رئيسي);
        
        // ============== حفظ ==============
        
        return pdf.حفظ(مسار_الملف);
    }
    
    // ============== القوالب ==============
    
    void تطبيق_قالب(نوع_قالب قالب) {
        switch (قالب) {
            case نوع_قالب::كلاسيكي:
                الإعدادات_.لون_رئيسي = "#8B4513";  // بني
                الإعدادات_.لون_ثانوي = "#DAA520";  // ذهبي
                break;
                
            case نوع_قالب::حديث:
                الإعدادات_.لون_رئيسي = "#1E3A5F";  // أزرق
                الإعدادات_.لون_ثانوي = "#4ECDC4";  // تركوازي
                break;
                
            case نوع_قالب::أكاديمي:
                الإعدادات_.لون_رئيسي = "#2C3E50";  // كحلي
                الإعدادات_.لون_ثانوي = "#E74C3C";  // أحمر
                break;
                
            case نوع_قالب::تقني:
                الإعدادات_.لون_رئيسي = "#00D4AA";  // أخضر فاتح
                الإعدادات_.لون_ثانوي = "#1A1A2E";  // كحلي غامق
                break;
                
            case نوع_قالب::رسمي:
                الإعدادات_.لون_رئيسي = "#006400";  // أخضر داكن
                الإعدادات_.لون_ثانوي = "#FFD700";  // ذهبي
                break;
                
            default:
                break;
        }
    }
    
    إعدادات_قالب& الإعدادات() { return الإعدادات_; }
};

