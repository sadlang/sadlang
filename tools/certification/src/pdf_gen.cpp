// ============== C API ==============

extern "C" {

using namespace ص::شهادات;

typedef struct {
    char* اسم_المستلم;
    char* اسم_إنجليزي;
    char* رقم_شهادة;
    char* عنوان;
    char* مستوى;
    char* تاريخ_إصدار;
    char* تاريخ_انتهاء;
    double النسبة;
    char* التقدير;
    char* اسم_المُصدر;
    char* منصب_المُصدر;
    char* رابط_التحقق;
} sad_cert_info;

int sad_cert_generate(const sad_cert_info* info, const char* مسار, int قالب) {
    if (!info || !مسار) return 0;
    
    مولد_شهادات مولد;
    مولد.تطبيق_قالب(static_cast<نوع_قالب>(قالب));
    
    معلومات_شهادة معلومات;
    معلومات.اسم_المستلم = info->اسم_المستلم ? info->اسم_المستلم : "";
    معلومات.اسم_إنجليزي = info->اسم_إنجليزي ? info->اسم_إنجليزي : "";
    معلومات.رقم_شهادة = info->رقم_شهادة ? info->رقم_شهادة : "";
    معلومات.عنوان = info->عنوان ? info->عنوان : "";
    معلومات.مستوى = info->مستوى ? info->مستوى : "";
    معلومات.تاريخ_إصدار = info->تاريخ_إصدار ? info->تاريخ_إصدار : "";
    معلومات.تاريخ_انتهاء = info->تاريخ_انتهاء ? info->تاريخ_انتهاء : "";
    معلومات.النسبة = info->النسبة;
    معلومات.التقدير = info->التقدير ? info->التقدير : "";
    معلومات.اسم_المُصدر = info->اسم_المُصدر ? info->اسم_المُصدر : "";
    معلومات.منصب_المُصدر = info->منصب_المُصدر ? info->منصب_المُصدر : "";
    معلومات.رابط_التحقق = info->رابط_التحقق ? info->رابط_التحقق : "";
    
    return مولد.توليد_شهادة(معلومات, مسار) ? 1 : 0;
}

}  // extern "C"
