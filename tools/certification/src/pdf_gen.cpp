    // الخطوط
    std::string خط_عنوان = "Arabic Typesetting";
    std::string خط_نص = "Arabic Typesetting";
    std::string خط_إنجليزي = "Georgia";
    
    // الأبعاد (بالنقاط)
    double عرض = 595;   // A4 عرض
    double ارتفاع = 842; // A4 طول
    
    // هوامش
