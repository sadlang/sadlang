/**
 * عنصر PDF
 */
struct عنصر_PDF {
    enum نوع { نص, صورة, خط, مستطيل, دائرة };
    نوع النوع;
    
    // موقع
    double x, y;
    double عرض = 0, ارتفاع = 0;
    
    // للنص
    std::string محتوى;
    std::string خط;
    double حجم_خط = 12;
    std::string لون = "#000000";
    std::string محاذاة = "center";  // left, center, right
    
    // للأشكال
    std::string لون_حدود;
    std::string لون_تعبئة;
    double سمك_حدود = 1;
    
    // للصورة
    std::string مسار_صورة;
};

/**
 * مولد PDF (يولد محتوى PDF بسيط)
 */
class مولد_PDF {
private:
    std::vector<عنصر_PDF> العناصر_;
    إعدادات_قالب الإعدادات_;
    
    std::ostringstream المحتوى_;
    std::vector<int> مواقع_الكائنات_;
    
public:
    explicit مولد_PDF(const إعدادات_قالب& إعدادات)
        : الإعدادات_(إعدادات) {}
    
    // ============== إضافة العناصر ==============
    
    void إضافة_نص(double x, double y, const std::string& نص,
                  const std::string& خط = "", double حجم = 12,
                  const std::string& لون = "#000000",
                  const std::string& محاذاة = "center") {
        عنصر_PDF عنصر;
        عنصر.النوع = عنصر_PDF::نص;
        عنصر.x = x;
        عنصر.y = y;
        عنصر.محتوى = نص;
        عنصر.خط = خط.empty() ? الإعدادات_.خط_نص : خط;
        عنصر.حجم_خط = حجم;
        عنصر.لون = لون;
        عنصر.محاذاة = محاذاة;
        
        العناصر_.push_back(عنصر);
    }
    
    void إضافة_خط(double x1, double y1, double x2, double y2,
                  const std::string& لون = "#000000", double سمك = 1) {
        عنصر_PDF عنصر;
        عنصر.النوع = عنصر_PDF::خط;
        عنصر.x = x1;
        عنصر.y = y1;
        عنصر.عرض = x2 - x1;
        عنصر.ارتفاع = y2 - y1;
        عنصر.لون = لون;
        عنصر.سمك_حدود = سمك;
        
        العناصر_.push_back(عنصر);
    }
    
    void إضافة_مستطيل(double x, double y, double عرض, double ارتفاع,
                       const std::string& لون_حدود = "",
                       const std::string& لون_تعبئة = "") {
        عنصر_PDF عنصر;
        عنصر.النوع = عنصر_PDF::مستطيل;
        عنصر.x = x;
        عنصر.y = y;
        عنصر.عرض = عرض;
        عنصر.ارتفاع = ارتفاع;
        عنصر.لون_حدود = لون_حدود;
        عنصر.لون_تعبئة = لون_تعبئة;
        
        العناصر_.push_back(عنصر);
    }
    
    // ============== توليد PDF ==============
    
    std::string توليد() {
        المحتوى_.str("");
        المحتوى_.clear();
        مواقع_الكائنات_.clear();
        
        // رأس PDF
        المحتوى_ << "%PDF-1.4\n";
        
        // كائن 1: الكتالوج
        كتابة_كائن(1);
        المحتوى_ << "<< /Type /Catalog /Pages 2 0 R >>\n";
        المحتوى_ << "endobj\n\n";
        
        // كائن 2: الصفحات
        كتابة_كائن(2);
        المحتوى_ << "<< /Type /Pages /Kids [3 0 R] /Count 1 >>\n";
        المحتوى_ << "endobj\n\n";
        
        // كائن 3: الصفحة
        كتابة_كائن(3);
        المحتوى_ << "<< /Type /Page /Parent 2 0 R\n";
        المحتوى_ << "/MediaBox [0 0 " << الإعدادات_.عرض << " " 
                 << الإعدادات_.ارتفاع << "]\n";
        المحتوى_ << "/Contents 4 0 R\n";
        المحتوى_ << "/Resources << /Font << /F1 5 0 R >> >> >>\n";
        المحتوى_ << "endobj\n\n";
        
        // كائن 4: المحتوى
        std::ostringstream محتوى_صفحة;
        توليد_محتوى_صفحة(محتوى_صفحة);
        std::string محتوى_نهائي = محتوى_صفحة.str();
        
        كتابة_كائن(4);
        المحتوى_ << "<< /Length " << محتوى_نهائي.size() << " >>\n";
        المحتوى_ << "stream\n";
        المحتوى_ << محتوى_نهائي;
        المحتوى_ << "\nendstream\n";
        المحتوى_ << "endobj\n\n";
        
        // كائن 5: الخط
        كتابة_كائن(5);
        المحتوى_ << "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\n";
        المحتوى_ << "endobj\n\n";
        
        // جدول المراجع
        int موقع_xref = المحتوى_.str().size();
        المحتوى_ << "xref\n";
        المحتوى_ << "0 6\n";
        المحتوى_ << "0000000000 65535 f \n";
        for (int موقع : مواقع_الكائنات_) {
            المحتوى_ << std::setw(10) << std::setfill('0') << موقع << " 00000 n \n";
        }
        
        // التذييل
        المحتوى_ << "trailer\n";
        المحتوى_ << "<< /Size 6 /Root 1 0 R >>\n";
        المحتوى_ << "startxref\n";
        المحتوى_ << موقع_xref << "\n";
        المحتوى_ << "%%EOF\n";
        
        return المحتوى_.str();
    }
    
    bool حفظ(const std::string& مسار) {
        std::ofstream ملف(مسار, std::ios::binary);
        if (!ملف) return false;
        
        std::string محتوى = توليد();
        ملف.write(محتوى.c_str(), محتوى.size());
        
        return ملف.good();
    }
    
private:
    void كتابة_كائن(int رقم) {
        مواقع_الكائنات_.push_back(المحتوى_.str().size());
        المحتوى_ << رقم << " 0 obj\n";
    }
    
    void توليد_محتوى_صفحة(std::ostringstream& s) {
        for (const auto& عنصر : العناصر_) {
            switch (عنصر.النوع) {
                case عنصر_PDF::نص:
                    s << "BT\n";
                    s << "/F1 " << عنصر.حجم_خط << " Tf\n";
                    s << عنصر.x << " " << (الإعدادات_.ارتفاع - عنصر.y) << " Td\n";
                    s << "(" << تحويل_نص(عنصر.محتوى) << ") Tj\n";
                    s << "ET\n";
                    break;
                    
                case عنصر_PDF::خط:
                    s << عنصر.سمك_حدود << " w\n";
                    s << عنصر.x << " " << (الإعدادات_.ارتفاع - عنصر.y) << " m\n";
                    s << (عنصر.x + عنصر.عرض) << " " 
                      << (الإعدادات_.ارتفاع - عنصر.y - عنصر.ارتفاع) << " l\n";
                    s << "S\n";
                    break;
                    
                case عنصر_PDF::مستطيل:
                    if (!عنصر.لون_تعبئة.empty()) {
                        s << عنصر.x << " " << (الإعدادات_.ارتفاع - عنصر.y - عنصر.ارتفاع);
                        s << " " << عنصر.عرض << " " << عنصر.ارتفاع << " re\n";
                        s << "f\n";
                    }
                    break;
                    
                default:
                    break;
            }
        }
    }
    
    std::string تحويل_نص(const std::string& نص) {
        std::string نتيجة;
        for (char c : نص) {
            if (c == '(' || c == ')' || c == '\\') {
                نتيجة += '\\';
            }
            نتيجة += c;
        }
        return نتيجة;
    }
};

