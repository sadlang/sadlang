// ============== أنواع المهارات ==============

/**
 * فئة المهارة
 */
enum class فئة_مهارة {
    أساسيات,        // المتغيرات، الأنواع، العمليات
    تحكم,           // الشروط، الحلقات
    دوال,           // تعريف واستخدام الدوال
    هياكل_بيانات,   // القوائم، القواميس، المجموعات
    كائنية,         // البرمجة الكائنية
    ملفات,          // التعامل مع الملفات
    شبكات,          // البرمجة الشبكية
    قواعد_بيانات,   // SQL و NoSQL
    خوارزميات,      // الخوارزميات وهياكل البيانات
    اختبار,         // كتابة الاختبارات
    أمان,           // الأمان السيبراني
    أداء,           // تحسين الأداء
    تزامن,          // البرمجة المتزامنة
    ذاكرة,          // إدارة الذاكرة
    تصميم           // أنماط التصميم
};

/**
 * مستوى المهارة (0-100)
 */
struct مستوى_مهارة {
    فئة_مهارة الفئة;
    double المستوى = 0;       // 0-100
    double الثقة = 0;         // مدى الثقة في التقييم 0-100
    int عدد_التقييمات = 0;   // عدد مرات التقييم
    
    std::string وصف_المستوى() const {
        if (المستوى < 20) return "مبتدئ";
        if (المستوى < 40) return "أساسي";
        if (المستوى < 60) return "متوسط";
        if (المستوى < 80) return "متقدم";
        return "خبير";
    }
};

// ============== نتيجة التقييم ==============

/**
 * نتيجة سؤال واحد
 */
struct نتيجة_سؤال {
    std::string معرف_سؤال;
    فئة_مهارة المهارة;
    double الصعوبة;  // 0-100
    
    bool صحيح;
    int الوقت_المستغرق;  // بالثواني
    
    // تأثير على تقدير المهارة
    double تعديل_مستوى() const {
        if (صحيح) {
            // الإجابة الصحيحة ترفع المستوى (أكثر للأسئلة الصعبة)
            return (الصعوبة / 100.0) * 10.0;
        } else {
            // الإجابة الخاطئة تخفض المستوى (أكثر للأسئلة السهلة)
            return -((100 - الصعوبة) / 100.0) * 8.0;
        }
    }
};

// ============== ملف المهارات ==============

/**
 * ملف مهارات الطالب
 */
class ملف_مهارات {
private:
    std::string معرف_طالب_;
    std::map<فئة_مهارة, مستوى_مهارة> المهارات_;
    std::vector<نتيجة_سؤال> السجل_;
    
    // إعدادات التقييم التكيفي
    double معامل_التعلم_ = 0.1;  // سرعة تعديل المستوى
    
public:
    explicit ملف_مهارات(const std::string& معرف) : معرف_طالب_(معرف) {
        // تهيئة جميع المهارات بمستوى 50 (متوسط افتراضي)
        for (int i = static_cast<int>(فئة_مهارة::أساسيات);
             i <= static_cast<int>(فئة_مهارة::تصميم); ++i) {
            فئة_مهارة ف = static_cast<فئة_مهارة>(i);
            المهارات_[ف] = {ف, 50.0, 0.0, 0};
        }
    }
    
    // ============== التحديث ==============
    
    void تسجيل_نتيجة(const نتيجة_سؤال& نتيجة) {
        السجل_.push_back(نتيجة);
        
        auto& مهارة = المهارات_[نتيجة.المهارة];
        
        // تحديث المستوى باستخدام ELO-like algorithm
        double تعديل = نتيجة.تعديل_مستوى() * معامل_التعلم_;
        مهارة.المستوى = std::clamp(مهارة.المستوى + تعديل, 0.0, 100.0);
        
        // تحديث الثقة (تزداد مع كل تقييم)
        مهارة.عدد_التقييمات++;
        مهارة.الثقة = std::min(100.0, مهارة.عدد_التقييمات * 5.0);
    }
    
    // ============== الاستعلام ==============
    
    مستوى_مهارة الحصول_على_مهارة(فئة_مهارة فئة) const {
        auto it = المهارات_.find(فئة);
        return it != المهارات_.end() ? it->second : مستوى_مهارة{فئة};
    }
    
    double المستوى_العام() const {
        double مجموع = 0;
        double أوزان = 0;
        
        for (const auto& [_, م] : المهارات_) {
            double وزن = م.الثقة / 100.0;
            مجموع += م.المستوى * وزن;
            أوزان += وزن;
        }
        
        return أوزان > 0 ? مجموع / أوزان : 50.0;
    }
    
    std::vector<فئة_مهارة> نقاط_القوة() const {
        std::vector<فئة_مهارة> نتيجة;
        for (const auto& [ف, م] : المهارات_) {
            if (م.المستوى >= 70 && م.الثقة >= 50) {
                نتيجة.push_back(ف);
            }
        }
        return نتيجة;
    }
    
    std::vector<فئة_مهارة> نقاط_الضعف() const {
        std::vector<فئة_مهارة> نتيجة;
        for (const auto& [ف, م] : المهارات_) {
            if (م.المستوى < 40 && م.الثقة >= 30) {
                نتيجة.push_back(ف);
            }
        }
        return نتيجة;
    }
    
    // ============== التقييم التكيفي ==============
    
    double صعوبة_السؤال_التالي(فئة_مهارة فئة) const {
        auto مهارة = الحصول_على_مهارة(فئة);
        
        // إذا الثقة منخفضة، نختار صعوبة متوسطة
        if (مهارة.الثقة < 30) {
            return 50.0;
        }
        
        // وإلا نختار صعوبة قريبة من مستوى الطالب
        // مع بعض العشوائية (+/- 20)
        return std::clamp(مهارة.المستوى + (rand() % 41 - 20), 10.0, 90.0);
    }
    
    // ============== التصدير ==============
    
    std::map<std::string, double> إلى_قاموس() const {
        std::map<std::string, double> نتيجة;
        
        for (const auto& [ف, م] : المهارات_) {
            نتيجة[اسم_فئة(ف)] = م.المستوى;
        }
        
        return نتيجة;
    }
    
private:
    std::string اسم_فئة(فئة_مهارة ف) const {
        switch (ف) {
            case فئة_مهارة::أساسيات: return "أساسيات";
            case فئة_مهارة::تحكم: return "تحكم";
            case فئة_مهارة::دوال: return "دوال";
            case فئة_مهارة::هياكل_بيانات: return "هياكل_بيانات";
            case فئة_مهارة::كائنية: return "كائنية";
            case فئة_مهارة::ملفات: return "ملفات";
            case فئة_مهارة::شبكات: return "شبكات";
            case فئة_مهارة::قواعد_بيانات: return "قواعد_بيانات";
            case فئة_مهارة::خوارزميات: return "خوارزميات";
            case فئة_مهارة::اختبار: return "اختبار";
            case فئة_مهارة::أمان: return "أمان";
            case فئة_مهارة::أداء: return "أداء";
            case فئة_مهارة::تزامن: return "تزامن";
            case فئة_مهارة::ذاكرة: return "ذاكرة";
            case فئة_مهارة::تصميم: return "تصميم";
        }
        return "غير معروف";
    }
};

// ============== خطة التعلم ==============

/**
 * توصية تعلم
 */
struct توصية_تعلم {
    فئة_مهارة المهارة;
    int الأولوية;  // 1-5 (5 أعلى)
    std::string الوصف;
    std::vector<std::string> الموارد;  // روابط أو معرفات دروس
};

/**
 * خطة تعلم مخصصة
 */
class خطة_تعلم {
private:
    std::string معرف_طالب_;
    std::vector<توصية_تعلم> التوصيات_;
    
public:
    explicit خطة_تعلم(const ملف_مهارات& ملف) {
        // تحليل نقاط الضعف
        auto ضعف = ملف.نقاط_الضعف();
        
        for (const auto& ف : ضعف) {
            auto م = ملف.الحصول_على_مهارة(ف);
            
            توصية_تعلم توصية;
            توصية.المهارة = ف;
            توصية.الأولوية = 5 - static_cast<int>(م.المستوى / 20);
            توصية.الوصف = "تحسين " + وصف_مهارة(ف);
            توصية.الموارد = اقتراح_موارد(ف);
            
            التوصيات_.push_back(توصية);
        }
        
        // ترتيب حسب الأولوية
        std::sort(التوصيات_.begin(), التوصيات_.end(),
            [](const auto& a, const auto& b) {
                return a.الأولوية > b.الأولوية;
            });
    }
    
    const std::vector<توصية_تعلم>& التوصيات() const {
        return التوصيات_;
    }
    
private:
    std::string وصف_مهارة(فئة_مهارة ف) {
        switch (ف) {
            case فئة_مهارة::أساسيات: return "أساسيات البرمجة";
            case فئة_مهارة::تحكم: return "هياكل التحكم";
            case فئة_مهارة::دوال: return "الدوال";
            case فئة_مهارة::هياكل_بيانات: return "هياكل البيانات";
            case فئة_مهارة::كائنية: return "البرمجة الكائنية";
            case فئة_مهارة::ملفات: return "التعامل مع الملفات";
            case فئة_مهارة::شبكات: return "البرمجة الشبكية";
            case فئة_مهارة::قواعد_بيانات: return "قواعد البيانات";
            case فئة_مهارة::خوارزميات: return "الخوارزميات";
            case فئة_مهارة::اختبار: return "الاختبارات";
            case فئة_مهارة::أمان: return "الأمان";
            case فئة_مهارة::أداء: return "تحسين الأداء";
            case فئة_مهارة::تزامن: return "البرمجة المتزامنة";
            case فئة_مهارة::ذاكرة: return "إدارة الذاكرة";
            case فئة_مهارة::تصميم: return "أنماط التصميم";
        }
        return "مهارة";
    }
    
    std::vector<std::string> اقتراح_موارد(فئة_مهارة ف) {
        // في التطبيق الفعلي، سيتم ربطها بقاعدة بيانات الدروس
        return {"درس_" + std::to_string(static_cast<int>(ف)) + "_1",
                "درس_" + std::to_string(static_cast<int>(ف)) + "_2",
                "تمرين_" + std::to_string(static_cast<int>(ف)) + "_1"};
    }
};

