    int عداد_ = 0;
    
public:
    نظام_مستويات() {
        إنشاء_مستويات_افتراضية();
        إنشاء_مسارات_افتراضية();
    }
    
    // ============== المستويات ==============
    
    std::string إضافة_مستوى(تعريف_مستوى& مستوى) {
        مستوى.معرف = "level_" + std::to_string(++عداد_);
        المستويات_[مستوى.معرف] = مستوى;
        return مستوى.معرف;
    }
    
    تعريف_مستوى* الحصول_على_مستوى(const std::string& معرف) {
        auto it = المستويات_.find(معرف);
        return it != المستويات_.end() ? &it->second : nullptr;
    }
    
    std::vector<تعريف_مستوى> مستويات_بالتخصص(تخصص_شهادة تخصص) const {
        std::vector<تعريف_مستوى> نتيجة;
        for (const auto& [_, م] : المستويات_) {
            if (م.التخصص == تخصص || م.التخصص == تخصص_شهادة::عام) {
                نتيجة.push_back(م);
            }
        }
        return نتيجة;
    }
    
    std::vector<تعريف_مستوى> كل_المستويات() const {
        std::vector<تعريف_مستوى> نتيجة;
        for (const auto& [_, م] : المستويات_) {
            نتيجة.push_back(م);
        }
        return نتيجة;
    }
    
    // ============== المسارات ==============
    
    مسار_تعلم* الحصول_على_مسار(const std::string& معرف) {
        auto it = المسارات_.find(معرف);
        return it != المسارات_.end() ? &it->second : nullptr;
    }
    
    std::vector<مسار_تعلم> كل_المسارات() const {
        std::vector<مسار_تعلم> نتيجة;
        for (const auto& [_, م] : المسارات_) {
            نتيجة.push_back(م);
        }
        return نتيجة;
    }
    
    // ============== التحقق من الأهلية ==============
    
    struct نتيجة_أهلية {
        bool مؤهل = false;
        std::vector<std::string> متطلبات_ناقصة;
        std::vector<std::string> متطلبات_مكتملة;
    };
    
    نتيجة_أهلية التحقق_من_أهلية(const std::string& معرف_مستوى,
                                const std::map<std::string, bool>& الإنجازات) {
        نتيجة_أهلية نتيجة;
        
        auto* مستوى = الحصول_على_مستوى(معرف_مستوى);
        if (!مستوى) return نتيجة;
        
        for (const auto& متطلب : مستوى->المتطلبات) {
            auto it = الإنجازات.find(متطلب.معرف);
            if (it != الإنجازات.end() && it->second) {
                نتيجة.متطلبات_مكتملة.push_back(متطلب.وصف);
            } else {
                نتيجة.متطلبات_ناقصة.push_back(متطلب.وصف);
            }
        }
        
        نتيجة.مؤهل = نتيجة.متطلبات_ناقصة.empty();
        return نتيجة;
    }
    
    // ============== المستوى التالي ==============
    
    std::string المستوى_التالي(const std::string& معرف_حالي) const {
        auto it = المستويات_.find(معرف_حالي);
        if (it == المستويات_.end()) return "";
        
        مستوى_شهادة الحالي = it->second.المستوى;
        تخصص_شهادة التخصص = it->second.التخصص;
        
        // البحث عن المستوى التالي
        مستوى_شهادة التالي;
        switch (الحالي) {
            case مستوى_شهادة::مبتدئ: التالي = مستوى_شهادة::متوسط; break;
            case مستوى_شهادة::متوسط: التالي = مستوى_شهادة::متقدم; break;
            case مستوى_شهادة::متقدم: التالي = مستوى_شهادة::خبير; break;
            case مستوى_شهادة::خبير: return "";  // أعلى مستوى
        }
        
        for (const auto& [معرف, م] : المستويات_) {
            if (م.المستوى == التالي && م.التخصص == التخصص) {
                return معرف;
            }
        }
        
        return "";
    }
    
