// ============== C API ==============

extern "C" {

using namespace ص::شهادات;

static نظام_مستويات* النظام_العام = nullptr;

void sad_levels_init() {
    if (!النظام_العام) {
        النظام_العام = new نظام_مستويات();
    }
}

void sad_levels_cleanup() {
    delete النظام_العام;
    النظام_العام = nullptr;
}

int sad_levels_count() {
    if (!النظام_العام) return 0;
    return النظام_العام->كل_المستويات().size();
}

const char* sad_levels_get_name(const char* معرف) {
    if (!النظام_العام) return "";
    
    auto* مستوى = النظام_العام->الحصول_على_مستوى(معرف);
    if (!مستوى) return "";
    
    static std::string نتيجة;
    نتيجة = مستوى->اسم_عربي;
    
    return نتيجة.c_str();
}

const char* sad_levels_next(const char* معرف_حالي) {
    if (!النظام_العام) return "";
    
    static std::string نتيجة;
    نتيجة = النظام_العام->المستوى_التالي(معرف_حالي);
    
    return نتيجة.c_str();
}

}  // extern "C"
