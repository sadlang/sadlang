/**
 * عقدة في رسم الاستدعاءات
 */
struct عقدة_استدعاء {
    std::string الاسم;
    std::string الملف;
    
    // من يستدعيها
    std::unordered_set<std::string> المستدعون;
    
    // من تستدعي
    std::unordered_set<std::string> تستدعي;
    
    // Hash للمقارنة السريعة
    std::string hash_الجسم;
    std::string hash_التوقيع;
};

/**
 * رسم الاستدعاءات للمشروع
 */
class رسم_استدعاءات {
public:
    /**
     * إضافة دالة
     */
    void أضف_دالة(const عقدة_استدعاء& عقدة) {
        العقد_[عقدة.الاسم] = عقدة;
    }
    
    /**
     * إضافة علاقة استدعاء
     */
    void أضف_استدعاء(
        const std::string& المستدعي,
        const std::string& المستدعى
    ) {
        العقد_[المستدعي].تستدعي.insert(المستدعى);
        العقد_[المستدعى].المستدعون.insert(المستدعي);
    }
    
    /**
     * الحصول على كل المتأثرين بتغيير دالة
     */
    std::vector<std::string> احصل_على_المتأثرين(
        const std::string& الدالة,
        int عمق_أقصى = -1
    ) {
        std::vector<std::string> متأثرون;
        std::unordered_set<std::string> زُرت;
        
        ابحث_عن_متأثرين(الدالة, زُرت, متأثرون, 0, عمق_أقصى);
        
        return متأثرون;
    }
    
    /**
     * الحصول على عقدة
     */
    عقدة_استدعاء* احصل(const std::string& اسم) {
        auto it = العقد_.find(اسم);
        return it != العقد_.end() ? &it->second : nullptr;
    }

private:
    std::unordered_map<std::string, عقدة_استدعاء> العقد_;
    
    void ابحث_عن_متأثرين(
        const std::string& الدالة,
        std::unordered_set<std::string>& زُرت,
        std::vector<std::string>& متأثرون,
        int العمق,
        int العمق_الأقصى
    ) {
        if (زُرت.find(الدالة) != زُرت.end()) return;
        if (العمق_الأقصى >= 0 && العمق > العمق_الأقصى) return;
        
        زُرت.insert(الدالة);
        
        auto it = العقد_.find(الدالة);
        if (it == العقد_.end()) return;
        
        // كل من يستدعي هذه الدالة متأثر
        for (const auto& مستدعي : it->second.المستدعون) {
            متأثرون.push_back(مستدعي);
            ابحث_عن_متأثرين(مستدعي, زُرت, متأثرون, العمق + 1, العمق_الأقصى);
        }
    }
};

