/**
 * نوع التغيير المكتشف
 */
enum class نوع_تغيير {
    تغيير_جسم,           // تغيير في جسم الدالة فقط
    تغيير_توقيع,         // تغيير في التوقيع (معاملات، نوع الإرجاع)
    إضافة_دالة,          // دالة جديدة
    حذف_دالة,            // دالة محذوفة
    تغيير_متغير_عام,     // تغيير متغير عام
    تغيير_نوع,           // تغيير تعريف نوع (بنية، صنف)
    تغيير_استيراد,       // تغيير الاستيرادات
    تغيير_تعليق,         // تعليق فقط - لا يحتاج إعادة ترجمة
    تغيير_غير_محدد       // تغيير لم نستطع تصنيفه
};

/**
 * مستوى تأثير التغيير
 */
enum class مستوى_تأثير {
    بدون_تأثير,          // تعليق فقط
    محلي,               // يؤثر على الدالة فقط
    مباشر,              // يؤثر على المستدعين المباشرين
    متوسط,              // يؤثر على شجرة الاستدعاءات
    شامل                // يحتاج إعادة ترجمة كاملة
};

