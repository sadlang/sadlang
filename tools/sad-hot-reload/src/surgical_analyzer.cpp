/**
 * المحلل الجراحي للتغييرات
 */
class محلل_جراحي {
public:
    /**
     * نتيجة التحليل
     */
    struct نتيجة_تحليل {
        std::vector<تغيير_مكتشف> التغييرات;
        
        // ملخص
        int تغييرات_جسم = 0;
        int تغييرات_توقيع = 0;
        int إضافات = 0;
        int حذوفات = 0;
        
        // التوصية
        bool يمكن_hot_reload;
        std::string سبب_عدم_الإمكانية;
        
        // التأثير
        std::vector<std::string> الملفات_المتأثرة;
        std::vector<std::string> الدوال_المتأثرة;
        
        // الوقت المتوقع
        double زمن_التحديث_المتوقع_ms;
    };
    
    /**
     * تحليل التغييرات بين نسختين
     */
    نتيجة_تحليل حلل(
        const std::string& المحتوى_القديم,
        const std::string& المحتوى_الجديد,
        const std::string& اسم_الملف
    ) {
        نتيجة_تحليل نتيجة;
        نتيجة.يمكن_hot_reload = true;
        
        // 1. تقسيم إلى وحدات (دوال، أنواع)
        auto وحدات_قديمة = قسّم_إلى_وحدات(المحتوى_القديم);
        auto وحدات_جديدة = قسّم_إلى_وحدات(المحتوى_الجديد);
        
        // 2. مقارنة الوحدات
        for (const auto& [اسم, وحدة_جديدة] : وحدات_جديدة) {
            auto it = وحدات_قديمة.find(اسم);
            
            if (it == وحدات_قديمة.end()) {
                // وحدة جديدة
                تغيير_مكتشف تغيير;
                تغيير.المعرف = اسم;
                تغيير.النوع = نوع_تغيير::إضافة_دالة;
                تغيير.التأثير = مستوى_تأثير::مباشر;
                تغيير.الكود_الجديد = وحدة_جديدة.المحتوى;
                تغيير.وصف_التغيير = "إضافة " + اسم;
                نتيجة.التغييرات.push_back(تغيير);
                نتيجة.إضافات++;
            } else {
                // مقارنة المحتوى
                auto تغيير = قارن_وحدة(it->second, وحدة_جديدة);
                if (تغيير.النوع != نوع_تغيير::تغيير_تعليق) {
                    نتيجة.التغييرات.push_back(تغيير);
                    
                    if (تغيير.النوع == نوع_تغيير::تغيير_جسم) {
                        نتيجة.تغييرات_جسم++;
                    } else if (تغيير.النوع == نوع_تغيير::تغيير_توقيع) {
                        نتيجة.تغييرات_توقيع++;
                    }
                }
            }
        }
        
        // 3. اكتشاف المحذوفات
        for (const auto& [اسم, _] : وحدات_قديمة) {
            if (وحدات_جديدة.find(اسم) == وحدات_جديدة.end()) {
                تغيير_مكتشف تغيير;
                تغيير.المعرف = اسم;
                تغيير.النوع = نوع_تغيير::حذف_دالة;
                تغيير.التأثير = مستوى_تأثير::شامل;  // الحذف خطير
                تغيير.وصف_التغيير = "حذف " + اسم;
                نتيجة.التغييرات.push_back(تغيير);
                نتيجة.حذوفات++;
                
                // الحذف يمنع Hot Reload عادةً
                نتيجة.يمكن_hot_reload = false;
                نتيجة.سبب_عدم_الإمكانية = "حذف دالة يحتاج إعادة تشغيل";
            }
        }
        
        // 4. تحديد التأثير الشامل
        for (const auto& تغيير : نتيجة.التغييرات) {
            if (تغيير.التأثير == مستوى_تأثير::شامل) {
                نتيجة.يمكن_hot_reload = false;
                نتيجة.سبب_عدم_الإمكانية = "تغيير يؤثر على البنية العامة";
                break;
            }
        }
        
        // 5. تقدير الوقت
        نتيجة.زمن_التحديث_المتوقع_ms = 
            نتيجة.تغييرات_جسم * 10 +
            نتيجة.تغييرات_توقيع * 50 +
            نتيجة.إضافات * 30;
        
        return نتيجة;
    }
    
    /**
     * تعيين رسم الاستدعاءات
     */
    void حدد_رسم_استدعاءات(std::shared_ptr<رسم_استدعاءات> رسم) {
        الرسم_ = رسم;
    }

private:
    std::shared_ptr<رسم_استدعاءات> الرسم_;
    
    /**
     * وحدة كود (دالة، نوع)
     */
    struct وحدة_كود {
        std::string الاسم;
        std::string النوع;  // "دالة", "بنية", "صنف"
        std::string المحتوى;
        std::string التوقيع;
        std::string الجسم;
    };
    
    /**
     * تقسيم المحتوى إلى وحدات
     */
    std::unordered_map<std::string, وحدة_كود> قسّم_إلى_وحدات(
        const std::string& محتوى
    ) {
        std::unordered_map<std::string, وحدة_كود> وحدات;
        
        // تحليل مُبسَّط - في الإنتاج نستخدم المُحلل اللغوي
        size_t pos = 0;
        while (pos < محتوى.size()) {
            // ابحث عن تعريف دالة: دالة اسم(...)
            size_t دالة_pos = محتوى.find("دالة", pos);
            if (دالة_pos == std::string::npos) break;
            
            // استخراج الاسم
            size_t اسم_بداية = دالة_pos + 8;  // تجاوز "دالة "
            while (اسم_بداية < محتوى.size() && 
                   (محتوى[اسم_بداية] == ' ' || محتوى[اسم_بداية] == '\t')) {
                اسم_بداية++;
            }
            
            size_t اسم_نهاية = اسم_بداية;
            while (اسم_نهاية < محتوى.size() && 
                   محتوى[اسم_نهاية] != '(' && 
                   محتوى[اسم_نهاية] != ':' &&
                   محتوى[اسم_نهاية] != ' ') {
                اسم_نهاية++;
            }
            
            std::string اسم = محتوى.substr(اسم_بداية, اسم_نهاية - اسم_بداية);
            
            // ابحث عن نهاية الدالة
            size_t نهاية = محتوى.find("نهاية", اسم_نهاية);
            if (نهاية == std::string::npos) {
                pos = اسم_نهاية;
                continue;
            }
            
            وحدة_كود وحدة;
            وحدة.الاسم = اسم;
            وحدة.النوع = "دالة";
            وحدة.المحتوى = محتوى.substr(دالة_pos, نهاية - دالة_pos + 10);
            
            وحدات[اسم] = وحدة;
            pos = نهاية + 10;
        }
        
        return وحدات;
    }
    
    /**
     * مقارنة وحدتين
     */
    تغيير_مكتشف قارن_وحدة(
        const وحدة_كود& قديمة,
        const وحدة_كود& جديدة
    ) {
        تغيير_مكتشف تغيير;
        تغيير.المعرف = جديدة.الاسم;
        تغيير.الكود_القديم = قديمة.المحتوى;
        تغيير.الكود_الجديد = جديدة.المحتوى;
        
        if (قديمة.المحتوى == جديدة.المحتوى) {
            تغيير.النوع = نوع_تغيير::تغيير_تعليق;
            تغيير.التأثير = مستوى_تأثير::بدون_تأثير;
        } else if (قديمة.التوقيع != جديدة.التوقيع) {
            تغيير.النوع = نوع_تغيير::تغيير_توقيع;
            تغيير.التأثير = مستوى_تأثير::مباشر;
            تغيير.وصف_التغيير = "تغيير توقيع " + جديدة.الاسم;
        } else {
            تغيير.النوع = نوع_تغيير::تغيير_جسم;
            تغيير.التأثير = مستوى_تأثير::محلي;
            تغيير.وصف_التغيير = "تغيير جسم " + جديدة.الاسم;
        }
        
        // اكتشاف المتأثرين
        if (الرسم_ && تغيير.التأثير != مستوى_تأثير::بدون_تأثير) {
            تغيير.المتأثرون = الرسم_->احصل_على_المتأثرين(جديدة.الاسم);
        }
        
        return تغيير;
    }
};

