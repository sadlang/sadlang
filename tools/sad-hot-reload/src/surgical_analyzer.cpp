/**
 * مراقب تغييرات الملفات
 */
class مراقب_تغييرات {
public:
    using مستمع = std::function<void(const std::string& ملف)>;
    
    /**
     * بدء المراقبة
     */
    void ابدأ(const std::string& مجلد) {
        المجلد_ = مجلد;
        يعمل_ = true;
        // في الإنتاج: استخدم inotify (Linux) أو ReadDirectoryChangesW (Windows)
    }
    
    /**
     * إيقاف المراقبة
     */
    void أوقف() {
        يعمل_ = false;
    }
    
    /**
     * تسجيل مستمع
     */
    void عند_تغيير(مستمع م) {
        المستمعون_.push_back(م);
    }

private:
    std::string المجلد_;
    bool يعمل_ = false;
    std::vector<مستمع> المستمعون_;
};

