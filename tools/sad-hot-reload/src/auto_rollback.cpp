/**
 * كاشف المشاكل بعد التحديث
 */
class كاشف_مشاكل {
public:
    /**
     * إعدادات الكشف
     */
    struct إعدادات {
        int مهلة_مراقبة_ms = 2000;      // مدة المراقبة بعد التحديث
        int فترة_فحص_ms = 100;         // كل كم نفحص
        bool كشف_exceptions = true;
        bool كشف_timeout = true;
        bool كشف_memory_leak = true;
    };
    
    /**
     * إنشاء كاشف
     */
    explicit كاشف_مشاكل(إعدادات إعدادات = إعدادات{})
        : الإعدادات_(إعدادات) {}
    
    /**
     * بدء المراقبة لدالة مُحدَّثة
     */
    void ابدأ_مراقبة(const std::string& دالة) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        دوال_تحت_المراقبة_[دالة] = {
            .بداية = std::chrono::steady_clock::now(),
            .مشكلة_مكتشفة = false,
            .السبب = سبب_تراجع::خطأ_تشغيل,
            .الرسالة = ""
        };
    }
    
    /**
     * إنهاء المراقبة (نجاح)
     */
    void أنهِ_مراقبة(const std::string& دالة) {
        std::lock_guard<std::mutex> قفل(القفل_);
        دوال_تحت_المراقبة_.erase(دالة);
    }
    
    /**
     * إبلاغ عن مشكلة
     */
    void أبلغ_عن_مشكلة(
        const std::string& دالة,
        سبب_تراجع السبب,
        const std::string& رسالة
    ) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        auto it = دوال_تحت_المراقبة_.find(دالة);
        if (it != دوال_تحت_المراقبة_.end()) {
            it->second.مشكلة_مكتشفة = true;
            it->second.السبب = السبب;
            it->second.الرسالة = رسالة;
        }
    }
    
    /**
     * فحص كل الدوال تحت المراقبة
     * @return قائمة الدوال التي اكتُشفت بها مشاكل
     */
    std::vector<std::pair<std::string, سبب_تراجع>> افحص() {
        std::lock_guard<std::mutex> قفل(القفل_);
        std::vector<std::pair<std::string, سبب_تراجع>> مشاكل;
        
        auto الآن = std::chrono::steady_clock::now();
        
        for (auto it = دوال_تحت_المراقبة_.begin(); 
             it != دوال_تحت_المراقبة_.end(); ) {
            
            auto& [دالة, حالة] = *it;
            
            // تحقق من مشكلة مُبلَّغة
            if (حالة.مشكلة_مكتشفة) {
                مشاكل.push_back({دالة, حالة.السبب});
                it = دوال_تحت_المراقبة_.erase(it);
                continue;
            }
            
            // تحقق من المهلة
            auto مضى = std::chrono::duration_cast<std::chrono::milliseconds>(
                الآن - حالة.بداية
            ).count();
            
            if (مضى > الإعدادات_.مهلة_مراقبة_ms) {
                // انتهت المراقبة بدون مشاكل
                it = دوال_تحت_المراقبة_.erase(it);
            } else {
                ++it;
            }
        }
        
        return مشاكل;
    }

private:
    إعدادات الإعدادات_;
    std::mutex القفل_;
    
    struct حالة_مراقبة {
        std::chrono::steady_clock::time_point بداية;
        bool مشكلة_مكتشفة;
        سبب_تراجع السبب;
        std::string الرسالة;
    };
    
    std::unordered_map<std::string, حالة_مراقبة> دوال_تحت_المراقبة_;
};

