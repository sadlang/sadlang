/**
 * مراقب صحة الدالة بعد التحديث
 */
class مراقب_صحة {
public:
    /**
     * فحص صحة
     */
    using فحص_صحة = std::function<bool()>;
    
    /**
     * تسجيل فحص لدالة
     */
    void سجّل_فحص(const std::string& دالة, فحص_صحة فحص) {
        الفحوصات_[دالة].push_back(فحص);
    }
    
    /**
     * تشغيل كل الفحوصات لدالة
     */
    bool افحص(const std::string& دالة) {
        auto it = الفحوصات_.find(دالة);
        if (it == الفحوصات_.end()) {
            return true;  // لا فحوصات = صحي
        }
        
        for (const auto& فحص : it->second) {
            try {
                if (!فحص()) {
                    return false;
                }
            } catch (...) {
                return false;
            }
        }
        
        return true;
    }
    
    /**
     * إزالة كل فحوصات دالة
     */
    void أزل_فحوصات(const std::string& دالة) {
        الفحوصات_.erase(دالة);
    }

private:
    std::unordered_map<std::string, std::vector<فحص_صحة>> الفحوصات_;
};

