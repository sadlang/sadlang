/**
 * سبب التراجع
 */
enum class سبب_تراجع {
    خطأ_تشغيل,           // Exception/Crash
    مهلة_منتهية,         // لم يستجب البرنامج
    فشل_اختبار,          // اختبار فشل بعد التحديث
    طلب_مستخدم,          // المستخدم طلب التراجع
    سلوك_غير_متوقع      // سلوك مختلف عن المتوقع
};

/**
 * تفاصيل التراجع
 */
struct تفاصيل_تراجع {
    std::string اسم_الدالة;
    سبب_تراجع السبب;
    std::string رسالة;
    
    int رقم_النسخة_الفاشلة;
    int رقم_النسخة_المستعادة;
    
    std::chrono::system_clock::time_point وقت_التحديث;
    std::chrono::system_clock::time_point وقت_الاكتشاف;
    std::chrono::system_clock::time_point وقت_التراجع;
    
    double زمن_الاكتشاف_ms;
    double زمن_التراجع_ms;
};

