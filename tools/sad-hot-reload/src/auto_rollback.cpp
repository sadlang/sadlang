/**
 * واجهة التراجع
 */
class واجهة_تراجع {
public:
    virtual ~واجهة_تراجع() = default;
    virtual bool تراجع(const std::string& دالة) = 0;
};

/**
 * مدير التراجع التلقائي
 */
class مدير_تراجع_تلقائي {
public:
    using مستمع_تراجع = std::function<void(const تفاصيل_تراجع&)>;
    
    /**
     * إعدادات المدير
     */
    struct إعدادات {
        int مهلة_مراقبة_ms = 2000;
        int فترة_فحص_ms = 50;
        bool تراجع_تلقائي = true;
        int محاولات_قصوى = 3;  // أقصى عدد من التحديثات الفاشلة قبل الإيقاف
    };
    
    /**
     * إنشاء المدير
     */
    explicit مدير_تراجع_تلقائي(
        std::shared_ptr<واجهة_تراجع> نظام_تراجع,
        إعدادات إعدادات = إعدادات{}
    ) : نظام_التراجع_(نظام_تراجع),
        الإعدادات_(إعدادات),
        الكاشف_(كاشف_مشاكل::إعدادات{
            .مهلة_مراقبة_ms = إعدادات.مهلة_مراقبة_ms,
            .فترة_فحص_ms = إعدادات.فترة_فحص_ms
        }) {}
    
    /**
     * بدء المراقبة التلقائية
     */
    void ابدأ() {
        يعمل_ = true;
        خيط_المراقبة_ = std::thread([this]() {
            while (يعمل_) {
                // فحص المشاكل
                auto مشاكل = الكاشف_.افحص();
                
                for (const auto& [دالة, سبب] : مشاكل) {
                    if (الإعدادات_.تراجع_تلقائي) {
                        نفذ_تراجع(دالة, سبب);
                    }
                }
                
                std::this_thread::sleep_for(
                    std::chrono::milliseconds(الإعدادات_.فترة_فحص_ms)
                );
            }
        });
    }
    
    /**
     * إيقاف المراقبة
     */
    void أوقف() {
        يعمل_ = false;
        if (خيط_المراقبة_.joinable()) {
            خيط_المراقبة_.join();
        }
    }
    
    /**
     * إبلاغ عن تحديث دالة (لبدء المراقبة)
     */
    void دالة_تم_تحديثها(const std::string& دالة) {
        الكاشف_.ابدأ_مراقبة(دالة);
        
        // إضافة للسجل
        std::lock_guard<std::mutex> قفل(القفل_);
        سجل_التحديثات_[دالة]++;
        
        // تحقق من المحاولات الكثيرة
        if (سجل_التحديثات_[دالة] > الإعدادات_.محاولات_قصوى) {
            // تحذير: كثير من المحاولات الفاشلة
        }
    }
    
    /**
     * إبلاغ عن خطأ في دالة
     */
    void أبلغ_عن_خطأ(
        const std::string& دالة,
        sسبب_تراجع السبب,
        const std::string& رسالة
    ) {
        الكاشف_.أبلغ_عن_مشكلة(دالة, السبب, رسالة);
    }
    
    /**
     * تسجيل مستمع للتراجع
     */
    void عند_تراجع(مستمع_تراجع مستمع) {
        المستمعون_.push_back(مستمع);
    }
    
    /**
     * تراجع يدوي
     */
    bool تراجع_يدوي(const std::string& دالة) {
        return نفذ_تراجع(دالة, سبب_تراجع::طلب_مستخدم);
    }
    
    /**
     * إحصائيات
     */
    int عدد_التراجعات() const { return عدد_التراجعات_; }

private:
    std::shared_ptr<واجهة_تراجع> نظام_التراجع_;
    إعدادات الإعدادات_;
    كاشف_مشاكل الكاشف_;
    
    std::atomic<bool> يعمل_{false};
    std::thread خيط_المراقبة_;
    
    std::mutex القفل_;
    std::unordered_map<std::string, int> سجل_التحديثات_;
    std::vector<مستمع_تراجع> المستمعون_;
    std::atomic<int> عدد_التراجعات_{0};
    
    /**
     * تنفيذ التراجع
     */
    bool نفذ_تراجع(const std::string& دالة, سبب_تراجع السبب) {
        auto بداية = std::chrono::high_resolution_clock::now();
        
        // تنفيذ التراجع
        bool نجح = نظام_التراجع_->تراجع(دالة);
        
        auto نهاية = std::chrono::high_resolution_clock::now();
        
        if (نجح) {
            عدد_التراجعات_++;
            
            // إنشاء تفاصيل
            تفاصيل_تراجع تفاصيل;
            تفاصيل.اسم_الدالة = دالة;
            تفاصيل.السبب = السبب;
            تفاصيل.وقت_التراجع = std::chrono::system_clock::now();
            تفاصيل.زمن_التراجع_ms = 
                std::chrono::duration<double, std::milli>(نهاية - بداية).count();
            
            // إبلاغ المستمعين
            for (auto& مستمع : المستمعون_) {
                مستمع(تفاصيل);
            }
            
            // إعادة ضبط عداد المحاولات
            std::lock_guard<std::mutex> قفل(القفل_);
            سجل_التحديثات_.erase(دالة);
        }
        
        return نجح;
    }
};

