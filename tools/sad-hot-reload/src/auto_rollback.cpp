/**
 * مُولِّد تقارير التراجع
 */
class مولد_تقارير_تراجع {
public:
    /**
     * توليد تقرير لتراجع
     */
    static std::string ولِّد_تقرير(const تفاصيل_تراجع& تفاصيل) {
        std::stringstream تقرير;
        
        تقرير << "╔════════════════════════════════════════════════╗\n";
        تقرير << "║            تقرير التراجع التلقائي              ║\n";
        تقرير << "╠════════════════════════════════════════════════╣\n";
        
        تقرير << "║ الدالة: " << تفاصيل.اسم_الدالة << "\n";
        تقرير << "║ السبب: " << اسم_السبب(تفاصيل.السبب) << "\n";
        
        if (!تفاصيل.رسالة.empty()) {
            تقرير << "║ الرسالة: " << تفاصيل.رسالة << "\n";
        }
        
        تقرير << "╠════════════════════════════════════════════════╣\n";
        تقرير << "║ النسخة الفاشلة: " << تفاصيل.رقم_النسخة_الفاشلة << "\n";
        تقرير << "║ النسخة المستعادة: " << تفاصيل.رقم_النسخة_المستعادة << "\n";
        تقرير << "║ زمن التراجع: " << تفاصيل.زمن_التراجع_ms << " ms\n";
        تقرير << "╚════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }

private:
    static std::string اسم_السبب(سبب_تراجع السبب) {
        switch (السبب) {
            case سبب_تراجع::خطأ_تشغيل: return "خطأ في التشغيل";
            case سبب_تراجع::مهلة_منتهية: return "انتهت المهلة";
            case سبب_تراجع::فشل_اختبار: return "فشل اختبار";
            case سبب_تراجع::طلب_مستخدم: return "طلب المستخدم";
            case سبب_تراجع::سلوك_غير_متوقع: return "سلوك غير متوقع";
            default: return "غير معروف";
        }
    }
};

