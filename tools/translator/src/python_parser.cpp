#include <iostream>
#include <string>
#include <vector>
#include <map>
#include <regex>

namespace sad {
namespace translator {

/**
 * نوع عقدة Python
 */
enum class نوع_عقدة_بايثون {
    وحدة,        // Module
    دالة,        // FunctionDef
    صنف,         // ClassDef
    إذا,         // If
    لكل,         // For
    طالما,       // While
    إرجاع,       // Return
    تعيين,       // Assign
    تعبير,       // Expr
    استدعاء,     // Call
    اسم,         // Name
    رقم,         // Num
    نص,          // Str
    قائمة,       // List
    قاموس,       // Dict
    استيراد,     // Import
    حاول         // Try
};

/**
 * عقدة Python AST
 */
struct عقدة_بايثون {
    نوع_عقدة_بايثون نوع;
    std::string قيمة;
    int سطر;
    int عمود;
    std::vector<عقدة_بايثون> أبناء;
    std::map<std::string, std::string> سمات;
};

/**
 * محلل Python
 */
class محلل_بايثون {
private:
    std::string كود_;
    size_t موقع_ = 0;
    int سطر_ = 1;
    int عمود_ = 1;
    
public:
    /**
     * تحليل كود Python
     */
    عقدة_بايثون حلل(const std::string& كود) {
        كود_ = كود;
        موقع_ = 0;
        سطر_ = 1;
        عمود_ = 1;
        
        عقدة_بايثون وحدة;
        وحدة.نوع = نوع_عقدة_بايثون::وحدة;
        
        // تحليل الأسطر
        while (موقع_ < كود_.length()) {
            تخطى_فراغات();
            if (موقع_ >= كود_.length()) break;
            
            auto عقدة = حلل_عبارة();
            if (عقدة.نوع != نوع_عقدة_بايثون::تعبير || !عقدة.قيمة.empty()) {
                وحدة.أبناء.push_back(عقدة);
            }
        }
        
        return وحدة;
    }
    
    /**
     * الحصول على الأخطاء
     */
    std::vector<std::string> أخطاء() const {
        return أخطاء_;
    }
    
private:
    std::vector<std::string> أخطاء_;
    
    void تخطى_فراغات() {
        while (موقع_ < كود_.length() && 
               (كود_[موقع_] == ' ' || كود_[موقع_] == '\t' || كود_[موقع_] == '\n')) {
            if (كود_[موقع_] == '\n') {
                سطر_++;
                عمود_ = 1;
            } else {
                عمود_++;
            }
            موقع_++;
        }
        
        // تخطي التعليقات
        if (موقع_ < كود_.length() && كود_[موقع_] == '#') {
            while (موقع_ < كود_.length() && كود_[موقع_] != '\n') {
                موقع_++;
            }
            تخطى_فراغات();
        }
    }
    
    عقدة_بايثون حلل_عبارة() {
        تخطى_فراغات();
        
        // تحقق من الكلمات المفتاحية
        if (يبدأ_بـ("def ")) {
            return حلل_دالة();
        }
        if (يبدأ_بـ("class ")) {
            return حلل_صنف();
        }
        if (يبدأ_بـ("if ")) {
            return حلل_إذا();
        }
        if (يبدأ_بـ("for ")) {
            return حلل_لكل();
        }
        if (يبدأ_بـ("while ")) {
            return حلل_طالما();
        }
        if (يبدأ_بـ("return ")) {
            return حلل_إرجاع();
        }
        if (يبدأ_بـ("import ") || يبدأ_بـ("from ")) {
            return حلل_استيراد();
        }
        if (يبدأ_بـ("try:")) {
            return حلل_حاول();
        }
        
        // تعيين أو تعبير
        return حلل_تعيين_أو_تعبير();
    }
    
    bool يبدأ_بـ(const std::string& نص) {
        return كود_.substr(موقع_, نص.length()) == نص;
    }
    
    عقدة_بايثون حلل_دالة() {
        عقدة_بايثون دالة;
        دالة.نوع = نوع_عقدة_بايثون::دالة;
        دالة.سطر = سطر_;
        
        موقع_ += 4;  // تخطي "def "
        
        // اسم الدالة
        std::string اسم;
        while (موقع_ < كود_.length() && كود_[موقع_] != '(') {
            اسم += كود_[موقع_++];
        }
        دالة.قيمة = اسم;
        
        // المعاملات
        if (موقع_ < كود_.length() && كود_[موقع_] == '(') {
            موقع_++;
            std::string معاملات;
            while (موقع_ < كود_.length() && كود_[موقع_] != ')') {
                معاملات += كود_[موقع_++];
            }
            دالة.سمات["معاملات"] = معاملات;
            موقع_++;  // تخطي ')'
        }
        
        // البحث عن :
        while (موقع_ < كود_.length() && كود_[موقع_] != ':') {
            موقع_++;
        }
        موقع_++;  // تخطي ':'
        
        return دالة;
    }
    
    عقدة_بايثون حلل_صنف() {
        عقدة_بايثون صنف;
        صنف.نوع = نوع_عقدة_بايثون::صنف;
        صنف.سطر = سطر_;
        
        موقع_ += 6;  // تخطي "class "
        
        std::string اسم;
        while (موقع_ < كود_.length() && كود_[موقع_] != ':' && كود_[موقع_] != '(') {
            اسم += كود_[موقع_++];
        }
        صنف.قيمة = اسم;
        
        return صنف;
    }
    
    عقدة_بايثون حلل_إذا() {
        عقدة_بايثون إذا;
        إذا.نوع = نوع_عقدة_بايثون::إذا;
        إذا.سطر = سطر_;
        
        موقع_ += 3;  // تخطي "if "
        
        std::string شرط;
        while (موقع_ < كود_.length() && كود_[موقع_] != ':') {
            شرط += كود_[موقع_++];
        }
        إذا.قيمة = شرط;
        
        return إذا;
    }
    
    عقدة_بايثون حلل_لكل() {
        عقدة_بايثون لكل;
        لكل.نوع = نوع_عقدة_بايثون::لكل;
        لكل.سطر = سطر_;
        
        موقع_ += 4;  // تخطي "for "
        
        std::string تعريف;
        while (موقع_ < كود_.length() && كود_[موقع_] != ':') {
            تعريف += كود_[موقع_++];
        }
        لكل.قيمة = تعريف;
        
        return لكل;
    }
    
    عقدة_بايثون حلل_طالما() {
        عقدة_بايثون طالما;
        طالما.نوع = نوع_عقدة_بايثون::طالما;
        طالما.سطر = سطر_;
        
        موقع_ += 6;  // تخطي "while "
        
        std::string شرط;
        while (موقع_ < كود_.length() && كود_[موقع_] != ':') {
            شرط += كود_[موقع_++];
        }
        طالما.قيمة = شرط;
        
        return طالما;
    }
    
    عقدة_بايثون حلل_إرجاع() {
        عقدة_بايثون إرجاع;
        إرجاع.نوع = نوع_عقدة_بايثون::إرجاع;
        إرجاع.سطر = سطر_;
        
        موقع_ += 7;  // تخطي "return "
        
        std::string قيمة;
        while (موقع_ < كود_.length() && كود_[موقع_] != '\n') {
            قيمة += كود_[موقع_++];
        }
        إرجاع.قيمة = قيمة;
        
        return إرجاع;
    }
    
    عقدة_بايثون حلل_استيراد() {
        عقدة_بايثون استيراد;
        استيراد.نوع = نوع_عقدة_بايثون::استيراد;
        استيراد.سطر = سطر_;
        
        std::string سطر;
        while (موقع_ < كود_.length() && كود_[موقع_] != '\n') {
            سطر += كود_[موقع_++];
        }
        استيراد.قيمة = سطر;
        
        return استيراد;
    }
    
    عقدة_بايثون حلل_حاول() {
        عقدة_بايثون حاول;
        حاول.نوع = نوع_عقدة_بايثون::حاول;
        حاول.سطر = سطر_;
        
        return حاول;
    }
    
    عقدة_بايثون حلل_تعيين_أو_تعبير() {
        عقدة_بايثون عقدة;
        عقدة.سطر = سطر_;
        
        std::string سطر;
        while (موقع_ < كود_.length() && كود_[موقع_] != '\n') {
            سطر += كود_[موقع_++];
        }
        
        if (سطر.find('=') != std::string::npos && سطر.find("==") == std::string::npos) {
            عقدة.نوع = نوع_عقدة_بايثون::تعيين;
        } else {
            عقدة.نوع = نوع_عقدة_بايثون::تعبير;
        }
        عقدة.قيمة = سطر;
        
        return عقدة;
    }
};

} // namespace translator
} // namespace sad

extern "C" {
using namespace sad::translator;

void* sad_python_parser_create() {
    return new محلل_بايثون();
}

void sad_python_parser_destroy(void* parser) {
    delete static_cast<محلل_بايثون*>(parser);
}

int sad_python_parse(void* parser, const char* code) {
    auto محلل = static_cast<محلل_بايثون*>(parser);
    auto ast = محلل->حلل(code);
    return محلل->أخطاء().empty() ? 0 : 1;
}
}
