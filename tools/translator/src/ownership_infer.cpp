#include <iostream>
#include <string>
#include <vector>
#include <map>
#include <set>

namespace sad {
namespace translator {

/**
 * نوع الملكية
 */
enum class نوع_ملكية {
    مملوك,      // Owned - القيمة مملوكة بالكامل
    مستعار,     // Borrowed - مرجع للقراءة فقط
    متحول,      // Mutable - مرجع قابل للتعديل
    مشترك      // Shared - ملكية مشتركة (Rc/Arc)
};

/**
 * معلومات متغير
 */
struct معلومات_متغير {
    std::string اسم;
    نوع_ملكية ملكية;
    bool قابل_للتعديل;
    std::set<std::string> يستخدمه;  // المتغيرات التي تستخدم هذا المتغير
    int عدد_القراءات;
    int عدد_الكتابات;
};

/**
 * مستنتج الملكية
 */
class مستنتج_الملكية {
private:
    std::map<std::string, معلومات_متغير> متغيرات_;
    
public:
    /**
     * تحليل الكود واستنتاج الملكية
     */
    std::map<std::string, نوع_ملكية> حلل(const std::string& كود) {
        متغيرات_.clear();
        
        // 1. اكتشاف المتغيرات
        اكتشف_المتغيرات(كود);
        
        // 2. تحليل الاستخدام
        حلل_الاستخدام(كود);
        
        // 3. استنتاج الملكية
        return استنتج_الملكية();
    }
    
    /**
     * الحصول على تعليقات الملكية
     */
    std::string أنتج_تعليقات() {
        std::string نتيجة;
        نتيجة += "// === تحليل الملكية ===\n";
        
        for (const auto& [اسم, معلومات] : متغيرات_) {
            نتيجة += "// " + اسم + ": ";
            
            switch (معلومات.ملكية) {
                case نوع_ملكية::مملوك:
                    نتيجة += "مملوك (يُنقل عند الإسناد)\n";
                    break;
                case نوع_ملكية::مستعار:
                    نتيجة += "مستعار (للقراءة فقط)\n";
                    break;
                case نوع_ملكية::متحول:
                    نتيجة += "مستعار_متحول (قابل للتعديل)\n";
                    break;
                case نوع_ملكية::مشترك:
                    نتيجة += "مشترك (ملكية مشتركة)\n";
                    break;
            }
        }
        
        return نتيجة;
    }
    
    /**
     * اقتراحات السلامة
     */
    std::vector<std::string> اقتراحات() {
        std::vector<std::string> نتيجة;
        
        for (const auto& [اسم, معلومات] : متغيرات_) {
            // متغير يُكتب ولا يُقرأ
            if (معلومات.عدد_الكتابات > 0 && معلومات.عدد_القراءات == 0) {
                نتيجة.push_back("⚠️ المتغير '" + اسم + "' يُعيَّن لكن لا يُستخدم");
            }
            
            // متغير مشترك بين عدة أماكن
            if (معلومات.يستخدمه.size() > 2) {
                نتيجة.push_back("💡 المتغير '" + اسم + "' مشترك في " + 
                              std::to_string(معلومات.يستخدمه.size()) + 
                              " أماكن - فكر في استخدام Arc");
            }
            
            // متغير يُعدّل من عدة أماكن
            if (معلومات.قابل_للتعديل && معلومات.يستخدمه.size() > 1) {
                نتيجة.push_back("🔒 المتغير '" + اسم + "' يُعدّل من أماكن متعددة - تأكد من السلامة");
            }
        }
        
        return نتيجة;
    }
    
private:
    void اكتشف_المتغيرات(const std::string& كود) {
        // البحث عن تعريفات المتغيرات
        std::vector<std::string> أنماط = {
            "متغير ", "ثابت ", "let ", "const ", "var "
        };
        
        size_t موقع = 0;
        while (موقع < كود.length()) {
            // تخطي المسافات
            while (موقع < كود.length() && (كود[موقع] == ' ' || كود[موقع] == '\n')) {
                موقع++;
            }
            
            for (const auto& نمط : أنماط) {
                if (كود.substr(موقع, نمط.length()) == نمط) {
                    موقع += نمط.length();
                    
                    // استخراج اسم المتغير
                    std::string اسم;
                    while (موقع < كود.length() && كود[موقع] != ' ' && 
                           كود[موقع] != '=' && كود[موقع] != ':' && كود[موقع] != '\n') {
                        اسم += كود[موقع++];
                    }
                    
                    if (!اسم.empty()) {
                        معلومات_متغير معلومات;
                        معلومات.اسم = اسم;
                        معلومات.ملكية = نوع_ملكية::مملوك;
                        معلومات.قابل_للتعديل = (نمط == "متغير " || نمط == "let " || نمط == "var ");
                        معلومات.عدد_القراءات = 0;
                        معلومات.عدد_الكتابات = 1;
                        متغيرات_[اسم] = معلومات;
                    }
                    break;
                }
            }
            
            موقع++;
        }
    }
    
    void حلل_الاستخدام(const std::string& كود) {
        // تحليل استخدام كل متغير
        for (auto& [اسم, معلومات] : متغيرات_) {
            size_t موقع = 0;
            while ((موقع = كود.find(اسم, موقع)) != std::string::npos) {
                // تحقق أنه ليس جزء من كلمة أخرى
                bool بداية_صحيحة = (موقع == 0 || !isalnum(كود[موقع - 1]));
                bool نهاية_صحيحة = (موقع + اسم.length() >= كود.length() || 
                                   !isalnum(كود[موقع + اسم.length()]));
                
                if (بداية_صحيحة && نهاية_صحيحة) {
                    // تحقق من نوع الاستخدام
                    bool كتابة = false;
                    size_t بعد = موقع + اسم.length();
                    while (بعد < كود.length() && كود[بعد] == ' ') بعد++;
                    
                    if (بعد < كود.length() && كود[بعد] == '=') {
                        كتابة = true;
                        معلومات.عدد_الكتابات++;
                    } else {
                        معلومات.عدد_القراءات++;
                    }
                    
                    // تحديد السياق (الدالة الحالية)
                    std::string سياق = "عام";
                    // (يمكن تحسينه لاكتشاف الدالة الحالية)
                    معلومات.يستخدمه.insert(سياق);
                }
                
                موقع++;
            }
        }
    }
    
    std::map<std::string, نوع_ملكية> استنتج_الملكية() {
        std::map<std::string, نوع_ملكية> نتيجة;
        
        for (auto& [اسم, معلومات] : متغيرات_) {
            // قواعد الاستنتاج:
            
            // 1. إذا كان المتغير يُستخدم في مكان واحد فقط -> مملوك
            if (معلومات.يستخدمه.size() <= 1) {
                معلومات.ملكية = نوع_ملكية::مملوك;
            }
            // 2. إذا كان يُقرأ فقط من أماكن متعددة -> مستعار
            else if (معلومات.عدد_الكتابات <= 1) {
                معلومات.ملكية = نوع_ملكية::مستعار;
            }
            // 3. إذا كان يُعدّل من أماكن متعددة -> مشترك مع Mutex
            else if (معلومات.يستخدمه.size() > 2) {
                معلومات.ملكية = نوع_ملكية::مشترك;
            }
            // 4. إذا كان يُعدّل من مكان واحد -> متحول
            else {
                معلومات.ملكية = نوع_ملكية::متحول;
            }
            
            نتيجة[اسم] = معلومات.ملكية;
        }
        
        return نتيجة;
    }
};

} // namespace translator
} // namespace sad

extern "C" {
using namespace sad::translator;

void* sad_ownership_infer_create() {
    return new مستنتج_الملكية();
}

void sad_ownership_infer_destroy(void* infer) {
    delete static_cast<مستنتج_الملكية*>(infer);
}

const char* sad_ownership_analyze(void* infer, const char* code) {
    static std::string نتيجة;
    auto مستنتج = static_cast<مستنتج_الملكية*>(infer);
    مستنتج->حلل(code);
    نتيجة = مستنتج->أنتج_تعليقات();
    return نتيجة.c_str();
}
}
