/**
 * تعريف ماكرو للعرض
 */
struct ماكرو_بسيط {
    std::string الاسم;
    std::vector<std::string> المعاملات;
    std::string الجسم;
};

/**
 * مخزن الماكرو المُعرَّفة
 */
class مخزن_ماكرو {
public:
    مخزن_ماكرو() {
        // ماكرو افتراضية للتجربة
        أضف_افتراضية();
    }
    
    void أضف(const ماكرو_بسيط& م) {
        m_الماكروات[م.الاسم] = م;
    }
    
    std::optional<ماكرو_بسيط> ابحث(const std::string& اسم) const {
        auto it = m_الماكروات.find(اسم);
        if (it != m_الماكروات.end()) {
            return it->second;
        }
        return std::nullopt;
    }
    
    std::vector<std::string> القائمة() const {
        std::vector<std::string> نتيجة;
        for (const auto& [اسم, _] : m_الماكروات) {
            نتيجة.push_back(اسم);
        }
        return نتيجة;
    }
    
private:
    std::unordered_map<std::string, ماكرو_بسيط> m_الماكروات;
    
    void أضف_افتراضية() {
        // ماكرو مربع
        أضف({"مربع", {"س"}, "$س * $س"});
        
        // ماكرو حد_أدنى
        أضف({"حد_أدنى", {"أ", "ب"}, "إذا $أ < $ب فـ $أ وإلا $ب"});
        
        // ماكرو سجِّل
        أضف({"سجِّل", {"مستوى", "رسالة"}, "اطبع(\"[$مستوى] \" + $رسالة)"});
        
        // ماكرو كرر
        أضف({"كرر", {"عدد", "كود"}, "لكل ي في 0..$عدد: $كود"});
        
        // ماكرو تأكد
        أضف({"تأكد", {"شرط"}, "إذا ليس ($شرط) فـ ذعر!(\"فشل التأكيد: $شرط\")"});
    }
};

