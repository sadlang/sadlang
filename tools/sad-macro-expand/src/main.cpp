/**
 * توسيع ماكرو في ملف
 */
class موسع_ملف {
public:
    void وسِّع_ملف(const std::string& مسار) {
        طابعة ط(true);
        
        std::ifstream ملف(مسار);
        if (!ملف) {
            ط.خطأ("لا يمكن فتح الملف: " + مسار);
            return;
        }
        
        ط.عنوان("توسيع الماكرو في " + مسار);
        
        std::stringstream محتوى;
        محتوى << ملف.rdbuf();
        
        std::string كود = محتوى.str();
        
        // ابحث عن كل استدعاءات الماكرو
        مخزن_ماكرو مخزن;
        موسع_عرض موسع(مخزن);
        
        size_t موضع = 0;
        while ((موضع = كود.find("!(", موضع)) != std::string::npos) {
            // ابحث عن بداية الاسم
            size_t بداية = موضع;
            while (بداية > 0 && (isalnum(كود[بداية - 1]) || (unsigned char)كود[بداية - 1] > 127)) {
                بداية--;
            }
            
            // ابحث عن نهاية الاستدعاء
            int عمق = 1;
            size_t نهاية = موضع + 2;
            while (نهاية < كود.length() && عمق > 0) {
                if (كود[نهاية] == '(') عمق++;
                else if (كود[نهاية] == ')') عمق--;
                نهاية++;
            }
            
            std::string استدعاء = كود.substr(بداية, نهاية - بداية);
            std::cout << "\n─────────────────────────────────\n";
            موسع.وسِّع_وأظهر(استدعاء);
            
            موضع = نهاية;
        }
    }
};

