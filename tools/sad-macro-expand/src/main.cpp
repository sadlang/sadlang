/**
 * موسع ماكرو مع عرض تفصيلي
 */
class موسع_عرض {
public:
    موسع_عرض(مخزن_ماكرو& مخزن) : m_مخزن(مخزن), m_طابعة(true) {}
    
    /**
     * توسيع مع عرض المراحل
     */
    void وسِّع_وأظهر(const std::string& استدعاء) {
        m_طابعة.عنوان("توسيع الماكرو");
        
        std::cout << "\nالأصل: ";
        m_طابعة.كود(استدعاء);
        
        // استخرج اسم الماكرو والمعاملات
        auto [الاسم, المعاملات_فعلية] = حلِّل_استدعاء(استدعاء);
        
        if (الاسم.empty()) {
            m_طابعة.خطأ("صيغة غير صالحة - استخدم: اسم!(معامل1, معامل2)");
            return;
        }
        
        // ابحث عن التعريف
        auto تعريف = m_مخزن.ابحث(الاسم);
        if (!تعريف.has_value()) {
            m_طابعة.خطأ("ماكرو غير معرَّفة: " + الاسم + "!");
            std::cout << "\nالماكرو المتاحة:\n";
            for (const auto& م : m_مخزن.القائمة()) {
                std::cout << "  - " << م << "!\n";
            }
            return;
        }
        
        // تحقق من عدد المعاملات
        if (المعاملات_فعلية.size() != تعريف->المعاملات.size()) {
            m_طابعة.خطأ("عدد المعاملات غير متطابق");
            std::cout << "  متوقع: " << تعريف->المعاملات.size() << "\n";
            std::cout << "  وُجد: " << المعاملات_فعلية.size() << "\n";
            return;
        }
        
        // المرحلة 1: عرض الاستبدالات
        m_طابعة.عنوان_فرعي("المرحلة 1: استبدال المعاملات");
        
        for (size_t i = 0; i < تعريف->المعاملات.size(); i++) {
            m_طابعة.استبدال("$" + تعريف->المعاملات[i], المعاملات_فعلية[i]);
        }
        
        // المرحلة 2: التوسيع
        m_طابعة.عنوان_فرعي("المرحلة 2: التوسيع");
        
        std::cout << تعريف->الجسم << "\n";
        m_طابعة.سهم();
        
        // نفِّذ الاستبدال
        std::string نتيجة = تعريف->الجسم;
        for (size_t i = 0; i < تعريف->المعاملات.size(); i++) {
            std::string ما_نبحث = "$" + تعريف->المعاملات[i];
            std::string ما_نستبدل = "(" + المعاملات_فعلية[i] + ")";
            
            // استبدل كل الظهورات
            size_t موضع = 0;
            while ((موضع = نتيجة.find(ما_نبحث, موضع)) != std::string::npos) {
                نتيجة.replace(موضع, ما_نبحث.length(), ما_نستبدل);
                موضع += ما_نستبدل.length();
            }
        }
        
        m_طابعة.كود(نتيجة);
        
        // النتيجة النهائية
        m_طابعة.عنوان_فرعي("النتيجة النهائية");
        m_طابعة.كود(نتيجة);
        m_طابعة.نجاح("تم التوسيع بنجاح");
    }
    
private:
    مخزن_ماكرو& m_مخزن;
    طابعة m_طابعة;
    
    /**
     * تحليل استدعاء ماكرو
     */
    std::pair<std::string, std::vector<std::string>> 
    حلِّل_استدعاء(const std::string& استدعاء) {
        // ابحث عن !(
        size_t موضع_علامة = استدعاء.find("!(");
        if (موضع_علامة == std::string::npos) {
            return {"", {}};
        }
        
        std::string الاسم = استدعاء.substr(0, موضع_علامة);
        
        // ابحث عن القوس المغلق
        size_t قوس_فتح = موضع_علامة + 1;
        int عمق = 1;
        size_t i = قوس_فتح + 1;
        
        while (i < استدعاء.length() && عمق > 0) {
            if (استدعاء[i] == '(') عمق++;
            else if (استدعاء[i] == ')') عمق--;
            i++;
        }
        
        if (عمق != 0) {
            return {"", {}};
        }
        
        // استخرج المعاملات
        std::string محتوى = استدعاء.substr(قوس_فتح + 1, i - قوس_فتح - 2);
        
        // قسِّم بالفواصل
        std::vector<std::string> المعاملات;
        std::string حالي;
        int عمق_داخلي = 0;
        
        for (char c : محتوى) {
            if (c == '(' || c == '[') {
                عمق_داخلي++;
                حالي += c;
            } else if (c == ')' || c == ']') {
                عمق_داخلي--;
                حالي += c;
            } else if (c == ',' && عمق_داخلي == 0) {
                // قص المسافات
                size_t بداية = حالي.find_first_not_of(" \t");
                size_t نهاية = حالي.find_last_not_of(" \t");
                if (بداية != std::string::npos) {
                    المعاملات.push_back(حالي.substr(بداية, نهاية - بداية + 1));
                }
                حالي.clear();
            } else {
                حالي += c;
            }
        }
        
        // آخر معامل
        size_t بداية = حالي.find_first_not_of(" \t");
        size_t نهاية = حالي.find_last_not_of(" \t");
        if (بداية != std::string::npos) {
            المعاملات.push_back(حالي.substr(بداية, نهاية - بداية + 1));
        }
        
        return {الاسم, المعاملات};
    }
};

