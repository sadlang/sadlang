class وضع_تفاعلي {
public:
    void ابدأ() {
        طابعة ط(true);
        مخزن_ماكرو مخزن;
        موسع_عرض موسع(مخزن);
        
        ط.عنوان("ص توسيع-ماكرو - الوضع التفاعلي");
        std::cout << "\nاكتب استدعاء ماكرو لرؤية التوسيع.\n";
        std::cout << "الأوامر:\n";
        std::cout << "  قائمة    - عرض الماكرو المتاحة\n";
        std::cout << "  مساعدة  - عرض المساعدة\n";
        std::cout << "  خروج    - إنهاء البرنامج\n\n";
        
        std::string سطر;
        while (true) {
            std::cout << "ماكرو> ";
            if (!std::getline(std::cin, سطر)) break;
            
            // قص المسافات
            size_t بداية = سطر.find_first_not_of(" \t");
            if (بداية == std::string::npos) continue;
            سطر = سطر.substr(بداية);
            size_t نهاية = سطر.find_last_not_of(" \t");
            سطر = سطر.substr(0, نهاية + 1);
            
            if (سطر.empty()) continue;
            
            if (سطر == "خروج" || سطر == "exit" || سطر == "q") {
                std::cout << "وداعاً!\n";
                break;
            }
            
            if (سطر == "قائمة" || سطر == "list") {
                std::cout << "\nالماكرو المتاحة:\n";
                for (const auto& اسم : مخزن.القائمة()) {
                    auto م = مخزن.ابحث(اسم);
                    if (م) {
                        std::cout << "  " << اسم << "!(";
                        for (size_t i = 0; i < م->المعاملات.size(); i++) {
                            if (i > 0) std::cout << ", ";
                            std::cout << "$" << م->المعاملات[i];
                        }
                        std::cout << ")\n";
                        std::cout << "    → " << م->الجسم << "\n\n";
                    }
                }
                continue;
            }
            
            if (سطر == "مساعدة" || سطر == "help" || سطر == "?") {
                std::cout << "\n═══ المساعدة ═══\n\n";
                std::cout << "هذه أداة لعرض كيفية توسيع الماكرو.\n\n";
                std::cout << "الاستخدام:\n";
                std::cout << "  اكتب استدعاء ماكرو مثل: مربع!(5)\n";
                std::cout << "  ستُظهر الأداة خطوات التوسيع.\n\n";
                std::cout << "مثال:\n";
                std::cout << "  مربع!(س + 1)  →  (س + 1) * (س + 1)\n\n";
                continue;
            }
            
            // وسِّع الماكرو
            موسع.وسِّع_وأظهر(سطر);
            std::cout << "\n";
        }
    }
};

