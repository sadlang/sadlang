/**
 * شرط تحقق
 */
struct شرط_تحقق {
    نوع_البرهان النوع;
    std::string الوصف;
    std::string الشرط_SMT;  // بصيغة SMT-LIB
    int السطر = 0;
};

/**
 * مولّد شروط التحقق
 */
class مولّد_شروط_التحقق {
private:
    int عداد_المتغيرات = 0;
    std::vector<شرط_تحقق> الشروط;
    
    std::string متغير_جديد(const std::string& بادئة) {
        return بادئة + "_" + std::to_string(عداد_المتغيرات++);
    }
    
    /**
     * تحويل تعبير إلى SMT
     */
    std::string تعبير_إلى_SMT(const مؤشر_تعبير& ت) {
        if (!ت) return "true";
        
        switch (ت->النوع_) {
            case تعبير::نوع::ثابت:
                return std::to_string(ت->قيمة_ثابت);
            
            case تعبير::نوع::متغير:
                return ت->اسم_متغير;
            
            case تعبير::نوع::ثنائي: {
                std::string يسار = تعبير_إلى_SMT(ت->اليسار);
                std::string يمين = تعبير_إلى_SMT(ت->اليمين);
                
                if (ت->العامل == "==") return "(= " + يسار + " " + يمين + ")";
                if (ت->العامل == "!=") return "(not (= " + يسار + " " + يمين + "))";
                if (ت->العامل == "<") return "(< " + يسار + " " + يمين + ")";
                if (ت->العامل == "<=") return "(<= " + يسار + " " + يمين + ")";
                if (ت->العامل == ">") return "(> " + يسار + " " + يمين + ")";
                if (ت->العامل == ">=") return "(>= " + يسار + " " + يمين + ")";
                if (ت->العامل == "+") return "(+ " + يسار + " " + يمين + ")";
                if (ت->العامل == "-") return "(- " + يسار + " " + يمين + ")";
                if (ت->العامل == "*") return "(* " + يسار + " " + يمين + ")";
                if (ت->العامل == "/") return "(div " + يسار + " " + يمين + ")";
                if (ت->العامل == "&&" || ت->العامل == "و") 
                    return "(and " + يسار + " " + يمين + ")";
                if (ت->العامل == "||" || ت->العامل == "أو") 
                    return "(or " + يسار + " " + يمين + ")";
                
                return "unknown";
            }
            
            default:
                return "true";
        }
    }
    
    /**
     * معالجة تعليمة
     */
    void عالج_تعليمة(const مؤشر_تعليمة& تعليمة,
                      std::unordered_map<std::string, std::string>& حالة,
                      const std::string& شروط_المسار) {
        if (!تعليمة) return;
        
        switch (تعليمة->النوع) {
            case نوع_التعليمة::تعيين: {
                // تحديث الحالة
                std::string نسخة = متغير_جديد(تعليمة->متغير_الهدف);
                حالة[تعليمة->متغير_الهدف] = نسخة;
                break;
            }
            
            case نوع_التعليمة::شرط: {
                std::string شرط_SMT = تعبير_إلى_SMT(تعليمة->الشرط);
                
                // فرع صحيح
                auto حالة_صحيح = حالة;
                std::string مسار_صحيح = "(and " + شروط_المسار + " " + شرط_SMT + ")";
                for (const auto& ت : تعليمة->فرع_صحيح) {
                    عالج_تعليمة(ت, حالة_صحيح, مسار_صحيح);
                }
                
                // فرع خطأ
                auto حالة_خطأ = حالة;
                std::string مسار_خطأ = "(and " + شروط_المسار + " (not " + شرط_SMT + "))";
                for (const auto& ت : تعليمة->فرع_خطأ) {
                    عالج_تعليمة(ت, حالة_خطأ, مسار_خطأ);
                }
                break;
            }
            
            case نوع_التعليمة::حلقة: {
                // إضافة شروط ثبات الحلقة
                for (const auto& ثابت : تعليمة->ثوابت_الحلقة) {
                    std::string ثابت_SMT = تعبير_إلى_SMT(ثابت);
                    
                    // الثابت صحيح عند الدخول
                    شرط_تحقق شرط1;
                    شرط1.النوع = نوع_البرهان::ثابت_حلقة;
                    شرط1.الوصف = "ثابت الحلقة صحيح عند الدخول";
                    شرط1.الشرط_SMT = "(=> " + شروط_المسار + " " + ثابت_SMT + ")";
                    شرط1.السطر = تعليمة->السطر;
                    الشروط.push_back(شرط1);
                    
                    // الثابت يُحفظ بعد تكرار
                    شرط_تحقق شرط2;
                    شرط2.النوع = نوع_البرهان::ثابت_حلقة;
                    شرط2.الوصف = "ثابت الحلقة يُحفظ";
                    شرط2.الشرط_SMT = "(=> (and " + شروط_المسار + " " + 
                                      تعبير_إلى_SMT(تعليمة->الشرط) + " " + 
                                      ثابت_SMT + ") " + ثابت_SMT + ")";
                    شرط2.السطر = تعليمة->السطر;
                    الشروط.push_back(شرط2);
                }
                
                // المتغير التناقصي
                if (تعليمة->متغير_تناقصي) {
                    شرط_تحقق شرط;
                    شرط.النوع = نوع_البرهان::متغير_تناقصي;
                    شرط.الوصف = "المتغير يتناقص";
                    شرط.الشرط_SMT = "(> " + تعبير_إلى_SMT(تعليمة->متغير_تناقصي) + " 0)";
                    شرط.السطر = تعليمة->السطر;
                    الشروط.push_back(شرط);
                }
                break;
            }
            
            case نوع_التعليمة::تأكيد: {
                شرط_تحقق شرط;
                شرط.النوع = نوع_البرهان::تأكيد;
                شرط.الوصف = تعليمة->رسالة_التأكيد.empty() ? 
                            "تأكيد" : تعليمة->رسالة_التأكيد;
                شرط.الشرط_SMT = "(=> " + شروط_المسار + " " + 
                                تعبير_إلى_SMT(تعليمة->التأكيد) + ")";
                شرط.السطر = تعليمة->السطر;
                الشروط.push_back(شرط);
                break;
            }
            
            default:
                break;
        }
    }
    
public:
    /**
     * توليد شروط التحقق لدالة
     */
    std::vector<شرط_تحقق> ولّد(const دالة_موثقة& دالة) {
        الشروط.clear();
        عداد_المتغيرات = 0;
        
        std::unordered_map<std::string, std::string> حالة;
        
        // إضافة المعاملات للحالة
        for (const auto& [اسم, نوع] : دالة.المعاملات) {
            حالة[اسم] = اسم;
        }
        
        // الشروط المسبقة كافتراضات
        std::string افتراضات = "true";
        for (const auto& شرط : دالة.الشروط_المسبقة) {
            افتراضات = "(and " + افتراضات + " " + تعبير_إلى_SMT(شرط) + ")";
        }
        
        // معالجة التعليمات
        for (const auto& ت : دالة.التعليمات) {
            عالج_تعليمة(ت, حالة, افتراضات);
        }
        
        // الشروط اللاحقة
        for (const auto& شرط : دالة.الشروط_اللاحقة) {
            شرط_تحقق ش;
            ش.النوع = نوع_البرهان::شرط_لاحق;
            ش.الوصف = "شرط لاحق";
            ش.الشرط_SMT = "(=> " + افتراضات + " " + تعبير_إلى_SMT(شرط) + ")";
            الشروط.push_back(ش);
        }
        
        return الشروط;
    }
};

