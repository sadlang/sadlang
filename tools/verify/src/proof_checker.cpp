/**
 * نوع البرهان
 */
enum class نوع_البرهان {
    شرط_مسبق,          // Precondition
    شرط_لاحق,           // Postcondition
    ثابت_حلقة,          // Loop invariant
    متغير_تناقصي,       // Decreasing variant (for termination)
    تأكيد,              // Assertion
    افتراض,             // Assumption
    خاصية_أمان,         // Safety property
    خاصية_حياة          // Liveness property
};

/**
 * حالة التحقق
 */
enum class حالة_التحقق {
    مثبت,       // Proven
    مدحوض,      // Refuted (counter-example found)
    غير_محدد,   // Unknown
    مهلة,       // Timeout
    خطأ         // Error
};

/**
 * نتيجة التحقق من برهان واحد
 */
struct نتيجة_برهان {
    نوع_البرهان النوع;
    حالة_التحقق الحالة;
    std::string الوصف;
    
    // للبراهين المدحوضة
    std::vector<std::pair<std::string, std::string>> مثال_مضاد;
    
    // معلومات إضافية
    int السطر = 0;
    std::string الملف;
    double الوقت_بالثواني = 0.0;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        
        switch (الحالة) {
            case حالة_التحقق::مثبت:
                ss << "✅ مثبت";
                break;
            case حالة_التحقق::مدحوض:
                ss << "❌ مدحوض";
                break;
            case حالة_التحقق::غير_محدد:
                ss << "❓ غير محدد";
                break;
            case حالة_التحقق::مهلة:
                ss << "⏱️ مهلة";
                break;
            case حالة_التحقق::خطأ:
                ss << "⚠️ خطأ";
                break;
        }
        
        ss << ": " << الوصف;
        
        if (الحالة == حالة_التحقق::مدحوض && !مثال_مضاد.empty()) {
            ss << "\n   مثال مضاد:\n";
            for (const auto& [اسم, قيمة] : مثال_مضاد) {
                ss << "     " << اسم << " = " << قيمة << "\n";
            }
        }
        
        return ss.str();
    }
};

/**
 * ملخص التحقق
 */
struct ملخص_التحقق {
    int إجمالي = 0;
    int مثبت = 0;
    int مدحوض = 0;
    int غير_محدد = 0;
    int أخطاء = 0;
    double الوقت_الإجمالي = 0.0;
    
    std::vector<نتيجة_برهان> النتائج;
    
    bool كل_شيء_مثبت() const {
        return إجمالي > 0 && مثبت == إجمالي;
    }
    
    std::string إلى_نص() const {
        std::stringstream ss;
        
        ss << "═══════════════════════════════════════════════════════\n";
        ss << "              ملخص التحقق من البراهين\n";
        ss << "═══════════════════════════════════════════════════════\n\n";
        
        ss << "📊 الإحصائيات:\n";
        ss << "   إجمالي البراهين: " << إجمالي << "\n";
        ss << "   ✅ مثبت: " << مثبت << "\n";
        ss << "   ❌ مدحوض: " << مدحوض << "\n";
        ss << "   ❓ غير محدد: " << غير_محدد << "\n";
        ss << "   ⚠️ أخطاء: " << أخطاء << "\n";
        ss << "   ⏱️ الوقت: " << الوقت_الإجمالي << " ثانية\n\n";
        
        if (كل_شيء_مثبت()) {
            ss << "🎉 جميع البراهين مثبتة!\n";
        } else if (مدحوض > 0) {
            ss << "⚠️ بعض البراهين مدحوضة - راجع الأمثلة المضادة\n";
        }
        
        return ss.str();
    }
};

