/**
 * خطر محتمل
 */
struct خطر_محتمل {
    نوع_الخطر النوع;
    int السطر;
    std::string الوصف;
    std::string الشرط_الآمن;  // الشرط الذي يضمن الأمان
};

/**
 * فاحص الأمان
 */
class فاحص_الأمان {
private:
    std::vector<خطر_محتمل> الأخطار;
    
public:
    /**
     * تحليل دالة للأخطار المحتملة
     */
    std::vector<خطر_محتمل> حلل(const دالة_موثقة& دالة) {
        الأخطار.clear();
        
        for (const auto& تعليمة : دالة.التعليمات) {
            حلل_تعليمة(تعليمة);
        }
        
        return الأخطار;
    }
    
private:
    void حلل_تعليمة(const مؤشر_تعليمة& تعليمة) {
        if (!تعليمة) return;
        
        if (تعليمة->النوع == نوع_التعليمة::تعيين && تعليمة->التعبير) {
            حلل_تعبير(تعليمة->التعبير, تعليمة->السطر);
        }
        
        // تحليل الفروع
        for (const auto& ت : تعليمة->فرع_صحيح) {
            حلل_تعليمة(ت);
        }
        for (const auto& ت : تعليمة->فرع_خطأ) {
            حلل_تعليمة(ت);
        }
        for (const auto& ت : تعليمة->جسم_الحلقة) {
            حلل_تعليمة(ت);
        }
    }
    
    void حلل_تعبير(const مؤشر_تعبير& تعبير, int السطر) {
        if (!تعبير) return;
        
        if (تعبير->النوع_ == تعبير::نوع::ثنائي) {
            // القسمة على صفر
            if (تعبير->العامل == "/" || تعبير->العامل == "%") {
                خطر_محتمل خطر;
                خطر.النوع = نوع_الخطر::قسمة_على_صفر;
                خطر.السطر = السطر;
                خطر.الوصف = "قسمة محتملة على صفر";
                خطر.الشرط_الآمن = "المقسوم_عليه != 0";
                الأخطار.push_back(خطر);
            }
            
            // تحليل المعاملات
            حلل_تعبير(تعبير->اليسار, السطر);
            حلل_تعبير(تعبير->اليمين, السطر);
        }
    }
};

