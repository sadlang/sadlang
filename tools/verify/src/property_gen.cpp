/**
 * نوع الخاصية
 */
enum class نوع_الخاصية {
    لكل,            // forAll - يجب أن تكون صحيحة لكل القيم
    يوجد,           // exists - يجب أن تكون صحيحة لقيمة واحدة على الأقل
    عندما,          // implies - إذا كان أ صحيحاً، فيجب أن يكون ب صحيحاً
    مكافئ           // equivalent - أ صحيح إذا وفقط إذا ب صحيح
};

/**
 * نوع المولّد
 */
enum class نوع_المولّد {
    عدد_صحيح,
    عدد_حقيقي,
    منطقي,
    نص,
    قائمة,
    قاموس,
    مخصص
};

/**
 * حالة النتيجة
 */
enum class حالة_الاختبار {
    نجح,
    فشل,
    تخطي,
    خطأ
};

