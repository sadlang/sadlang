/**
 * نتيجة اختبار خاصية
 */
struct نتيجة_خاصية {
    حالة_الاختبار الحالة;
    int عدد_الاختبارات = 0;
    int عدد_النجاحات = 0;
    int عدد_الفشل = 0;
    
    // في حالة الفشل
    std::vector<قيمة_مولّدة> مثال_مضاد;      // القيم التي فشلت
    std::vector<قيمة_مولّدة> مثال_مقلّص;      // أصغر مثال مضاد
    std::string رسالة_الخطأ;
    
    // إحصائيات
    double الوقت_بالثواني = 0.0;
};

/**
 * تعريف خاصية
 */
class خاصية {
public:
    std::string الاسم;
    std::string الوصف;
    نوع_الخاصية النوع = نوع_الخاصية::لكل;
    
    // تعريف المعاملات
    struct معامل {
        std::string الاسم;
        نوع_المولّد النوع;
        // قيود اختيارية
        int64_t حد_أدنى = INT64_MIN;
        int64_t حد_أقصى = INT64_MAX;
    };
    std::vector<معامل> المعاملات;
    
    // دالة التحقق
    using دالة_تحقق = std::function<bool(const std::vector<قيمة_مولّدة>&)>;
    دالة_تحقق الدالة;
    
    // إعدادات
    int عدد_المحاولات = 100;
    bool تقليص_ممكّن = true;
    int حد_التقليص = 50;
};

