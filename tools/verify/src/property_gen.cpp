/**
 * محرك اختبار الخصائص
 */
class محرك_الخصائص {
private:
    مولّد_القيم المولّد;
    bool وضع_تفصيلي = false;
    
    /**
     * توليد قيم للمعاملات
     */
    std::vector<قيمة_مولّدة> ولّد_قيم(const std::vector<خاصية::معامل>& المعاملات) {
        std::vector<قيمة_مولّدة> قيم;
        
        for (const auto& معامل : المعاملات) {
            switch (معامل.النوع) {
                case نوع_المولّد::عدد_صحيح:
                    قيم.push_back(المولّد.ولّد_عدد_صحيح(معامل.حد_أدنى, معامل.حد_أقصى));
                    break;
                case نوع_المولّد::عدد_حقيقي:
                    قيم.push_back(المولّد.ولّد_عدد_حقيقي());
                    break;
                case نوع_المولّد::منطقي:
                    قيم.push_back(المولّد.ولّد_منطقي());
                    break;
                case نوع_المولّد::نص:
                    قيم.push_back(المولّد.ولّد_نص());
                    break;
                case نوع_المولّد::قائمة:
                    قيم.push_back(المولّد.ولّد_قائمة(نوع_المولّد::عدد_صحيح));
                    break;
                default:
                    قيم.push_back(المولّد.ولّد_عدد_صحيح());
                    break;
            }
        }
        
        return قيم;
    }
    
    /**
     * تقليص المثال المضاد
     */
    std::vector<قيمة_مولّدة> قلّص_المثال(const خاصية& خ,
                                           std::vector<قيمة_مولّدة> مثال) {
        if (!خ.تقليص_ممكّن) return مثال;
        
        std::vector<قيمة_مولّدة> أصغر = مثال;
        
        for (int تكرار = 0; تكرار < خ.حد_التقليص; ++تكرار) {
            bool تحسّن = false;
            
            // محاولة تقليص كل قيمة
            for (size_t i = 0; i < أصغر.size(); ++i) {
                auto بدائل = المولّد.قلّص(أصغر[i]);
                
                for (const auto& بديل : بدائل) {
                    auto نسخة = أصغر;
                    نسخة[i] = بديل;
                    
                    // هل مازال المثال يفشل؟
                    try {
                        if (!خ.الدالة(نسخة)) {
                            أصغر = نسخة;
                            تحسّن = true;
                            break;
                        }
                    } catch (...) {
                        أصغر = نسخة;
                        تحسّن = true;
                        break;
                    }
                }
                
                if (تحسّن) break;
            }
            
            if (!تحسّن) break;
        }
        
        return أصغر;
    }
    
public:
    محرك_الخصائص(uint64_t بذرة = 0) : المولّد(بذرة) {}
    
    void وضع_تفصيلي_مفعّل(bool مفعّل) { وضع_تفصيلي = مفعّل; }
    
    /**
     * اختبار خاصية واحدة
     */
    نتيجة_خاصية اختبر(const خاصية& خ) {
        نتيجة_خاصية نتيجة;
        نتيجة.الحالة = حالة_الاختبار::نجح;
        
        auto بداية = std::chrono::high_resolution_clock::now();
        
        // أولاً: اختبار القيم الحدودية
        // (مبسط هنا)
        
        // ثانياً: اختبار عشوائي
        for (int i = 0; i < خ.عدد_المحاولات; ++i) {
            نتيجة.عدد_الاختبارات++;
            
            auto قيم = ولّد_قيم(خ.المعاملات);
            
            try {
                bool نجح = خ.الدالة(قيم);
                
                if (نجح) {
                    نتيجة.عدد_النجاحات++;
                } else {
                    نتيجة.عدد_الفشل++;
                    نتيجة.الحالة = حالة_الاختبار::فشل;
                    نتيجة.مثال_مضاد = قيم;
                    نتيجة.مثال_مقلّص = قلّص_المثال(خ, قيم);
                    
                    // تكوين رسالة الخطأ
                    std::stringstream ss;
                    ss << "فشلت الخاصية '" << خ.الاسم << "' عند:\n";
                    for (size_t j = 0; j < قيم.size(); ++j) {
                        ss << "  " << خ.المعاملات[j].الاسم << " = " 
                           << قيم[j].إلى_نص() << "\n";
                    }
                    if (نتيجة.مثال_مقلّص != نتيجة.مثال_مضاد) {
                        ss << "\nأصغر مثال مضاد:\n";
                        for (size_t j = 0; j < نتيجة.مثال_مقلّص.size(); ++j) {
                            ss << "  " << خ.المعاملات[j].الاسم << " = " 
                               << نتيجة.مثال_مقلّص[j].إلى_نص() << "\n";
                        }
                    }
                    نتيجة.رسالة_الخطأ = ss.str();
                    
                    break; // توقف عند أول فشل
                }
            }
            catch (const std::exception& e) {
                نتيجة.عدد_الفشل++;
                نتيجة.الحالة = حالة_الاختبار::خطأ;
                نتيجة.مثال_مضاد = قيم;
                نتيجة.رسالة_الخطأ = std::string("استثناء: ") + e.what();
                break;
            }
        }
        
        auto نهاية = std::chrono::high_resolution_clock::now();
        نتيجة.الوقت_بالثواني = std::chrono::duration<double>(نهاية - بداية).count();
        
        return نتيجة;
    }
    
    /**
     * اختبار مجموعة خصائص
     */
    std::vector<نتيجة_خاصية> اختبر_الكل(const std::vector<خاصية>& الخصائص) {
        std::vector<نتيجة_خاصية> النتائج;
        
        for (const auto& خ : الخصائص) {
            if (وضع_تفصيلي) {
                std::cout << "🔍 اختبار: " << خ.الاسم << "...\n";
            }
            
            auto نتيجة = اختبر(خ);
            النتائج.push_back(نتيجة);
            
            if (وضع_تفصيلي) {
                if (نتيجة.الحالة == حالة_الاختبار::نجح) {
                    std::cout << "   ✅ نجح (" << نتيجة.عدد_الاختبارات << " اختبار)\n";
                } else {
                    std::cout << "   ❌ فشل\n";
                    std::cout << "   " << نتيجة.رسالة_الخطأ << "\n";
                }
            }
        }
        
        return النتائج;
    }
};

