int sad_property_test_integer(sad_property_engine_t engine,
                              const char* name,
                              int (*check_fn)(int64_t),
                              int num_tests) {
    auto* محرك = reinterpret_cast<محرك_الخصائص*>(engine);
    
    خاصية خ;
    خ.الاسم = name;
    خ.عدد_المحاولات = num_tests;
    خ.المعاملات.push_back({"ن", نوع_المولّد::عدد_صحيح, -1000, 1000});
    خ.الدالة = [check_fn](const std::vector<قيمة_مولّدة>& قيم) {
        return check_fn(قيم[0].عدد_صحيح) != 0;
    };
    
    auto نتيجة = محرك->اختبر(خ);
    return نتيجة.الحالة == حالة_الاختبار::نجح ? 0 : -1;
}

