/**
 * مولّد كود اختبارات الخصائص
 */
class مولّد_كود_الخصائص {
public:
    /**
     * توليد كود C++ للخاصية
     */
    std::string ولّد_كود(const خاصية& خ) {
        std::stringstream كود;
        
        كود << "// خاصية: " << خ.الاسم << "\n";
        كود << "// " << خ.الوصف << "\n";
        كود << "خاصية " << خ.الاسم << ";\n";
        كود << خ.الاسم << ".الاسم = \"" << خ.الاسم << "\";\n";
        كود << خ.الاسم << ".عدد_المحاولات = " << خ.عدد_المحاولات << ";\n\n";
        
        // المعاملات
        for (const auto& م : خ.المعاملات) {
            كود << خ.الاسم << ".المعاملات.push_back({\"" << م.الاسم << "\", ";
            switch (م.النوع) {
                case نوع_المولّد::عدد_صحيح: كود << "نوع_المولّد::عدد_صحيح"; break;
                case نوع_المولّد::عدد_حقيقي: كود << "نوع_المولّد::عدد_حقيقي"; break;
                case نوع_المولّد::منطقي: كود << "نوع_المولّد::منطقي"; break;
                case نوع_المولّد::نص: كود << "نوع_المولّد::نص"; break;
                case نوع_المولّد::قائمة: كود << "نوع_المولّد::قائمة"; break;
                default: كود << "نوع_المولّد::عدد_صحيح"; break;
            }
            كود << "});\n";
        }
        
        return كود.str();
    }
    
    /**
     * توليد تقرير النتائج
     */
    std::string ولّد_تقرير(const std::vector<خاصية>& الخصائص,
                           const std::vector<نتيجة_خاصية>& النتائج) {
        std::stringstream تقرير;
        
        int نجح = 0, فشل = 0;
        double إجمالي_الوقت = 0;
        int إجمالي_الاختبارات = 0;
        
        for (const auto& ن : النتائج) {
            if (ن.الحالة == حالة_الاختبار::نجح) نجح++;
            else فشل++;
            إجمالي_الوقت += ن.الوقت_بالثواني;
            إجمالي_الاختبارات += ن.عدد_الاختبارات;
        }
        
        تقرير << "╔═══════════════════════════════════════════════════════╗\n";
        تقرير << "║           تقرير اختبارات الخصائص                      ║\n";
        تقرير << "╚═══════════════════════════════════════════════════════╝\n\n";
        
        تقرير << "📊 ملخص:\n";
        تقرير << "   الخصائص: " << الخصائص.size() << "\n";
        تقرير << "   ✅ نجح: " << نجح << "\n";
        تقرير << "   ❌ فشل: " << فشل << "\n";
        تقرير << "   📝 إجمالي الاختبارات: " << إجمالي_الاختبارات << "\n";
        تقرير << "   ⏱️ الوقت: " << إجمالي_الوقت << " ثانية\n\n";
        
        if (فشل > 0) {
            تقرير << "❌ الإخفاقات:\n";
            for (size_t i = 0; i < النتائج.size(); ++i) {
                if (النتائج[i].الحالة != حالة_الاختبار::نجح) {
                    تقرير << "   " << الخصائص[i].الاسم << ":\n";
                    تقرير << "   " << النتائج[i].رسالة_الخطأ << "\n";
                }
            }
        }
        
        return تقرير.str();
    }
};

