/**
 * قيمة مولّدة
 */
struct قيمة_مولّدة {
    std::string النوع;
    
    // القيم المختلفة
    int64_t عدد_صحيح = 0;
    double عدد_حقيقي = 0.0;
    bool منطقي = false;
    std::string نص;
    std::vector<قيمة_مولّدة> قائمة;
    
    std::string إلى_نص() const {
        if (النوع == "عدد_صحيح") return std::to_string(عدد_صحيح);
        if (النوع == "عدد_حقيقي") return std::to_string(عدد_حقيقي);
        if (النوع == "منطقي") return منطقي ? "صحيح" : "خطأ";
        if (النوع == "نص") return "\"" + نص + "\"";
        if (النوع == "قائمة") {
            std::string s = "[";
            for (size_t i = 0; i < قائمة.size(); ++i) {
                if (i > 0) s += ", ";
                s += قائمة[i].إلى_نص();
            }
            return s + "]";
        }
        return "غير_معروف";
    }
};

/**
 * مولّد القيم العشوائية
 */
class مولّد_القيم {
private:
    std::mt19937_64 مولّد_عشوائي;
    
public:
    مولّد_القيم(uint64_t بذرة = 0) {
        if (بذرة == 0) {
            بذرة = std::chrono::system_clock::now().time_since_epoch().count();
        }
        مولّد_عشوائي.seed(بذرة);
    }
    
    /**
     * توليد عدد صحيح
     */
    قيمة_مولّدة ولّد_عدد_صحيح(int64_t الحد_الأدنى = -1000000,
                                int64_t الحد_الأقصى = 1000000) {
        std::uniform_int_distribution<int64_t> توزيع(الحد_الأدنى, الحد_الأقصى);
        
        قيمة_مولّدة قيمة;
        قيمة.النوع = "عدد_صحيح";
        قيمة.عدد_صحيح = توزيع(مولّد_عشوائي);
        return قيمة;
    }
    
    /**
     * توليد عدد حقيقي
     */
    قيمة_مولّدة ولّد_عدد_حقيقي(double الحد_الأدنى = -1000000.0,
                                 double الحد_الأقصى = 1000000.0) {
        std::uniform_real_distribution<double> توزيع(الحد_الأدنى, الحد_الأقصى);
        
        قيمة_مولّدة قيمة;
        قيمة.النوع = "عدد_حقيقي";
        قيمة.عدد_حقيقي = توزيع(مولّد_عشوائي);
        return قيمة;
    }
    
    /**
     * توليد قيمة منطقية
     */
    قيمة_مولّدة ولّد_منطقي() {
        std::uniform_int_distribution<int> توزيع(0, 1);
        
        قيمة_مولّدة قيمة;
        قيمة.النوع = "منطقي";
        قيمة.منطقي = توزيع(مولّد_عشوائي) == 1;
        return قيمة;
    }
    
    /**
     * توليد نص عشوائي
     */
    قيمة_مولّدة ولّد_نص(size_t الحد_الأدنى = 0, size_t الحد_الأقصى = 100) {
        std::uniform_int_distribution<size_t> توزيع_طول(الحد_الأدنى, الحد_الأقصى);
        std::uniform_int_distribution<int> توزيع_حرف(32, 126); // ASCII قابل للطباعة
        
        size_t الطول = توزيع_طول(مولّد_عشوائي);
        std::string نتيجة;
        نتيجة.reserve(الطول);
        
        for (size_t i = 0; i < الطول; ++i) {
            نتيجة += static_cast<char>(توزيع_حرف(مولّد_عشوائي));
        }
        
        قيمة_مولّدة قيمة;
        قيمة.النوع = "نص";
        قيمة.نص = نتيجة;
        return قيمة;
    }
    
    /**
     * توليد قائمة عشوائية
     */
    قيمة_مولّدة ولّد_قائمة(نوع_المولّد نوع_العناصر,
                            size_t الحد_الأدنى = 0,
                            size_t الحد_الأقصى = 50) {
        std::uniform_int_distribution<size_t> توزيع_طول(الحد_الأدنى, الحد_الأقصى);
        size_t الطول = توزيع_طول(مولّد_عشوائي);
        
        قيمة_مولّدة قيمة;
        قيمة.النوع = "قائمة";
        قيمة.قائمة.reserve(الطول);
        
        for (size_t i = 0; i < الطول; ++i) {
            switch (نوع_العناصر) {
                case نوع_المولّد::عدد_صحيح:
                    قيمة.قائمة.push_back(ولّد_عدد_صحيح(-100, 100));
                    break;
                case نوع_المولّد::عدد_حقيقي:
                    قيمة.قائمة.push_back(ولّد_عدد_حقيقي(-100.0, 100.0));
                    break;
                case نوع_المولّد::منطقي:
                    قيمة.قائمة.push_back(ولّد_منطقي());
                    break;
                case نوع_المولّد::نص:
                    قيمة.قائمة.push_back(ولّد_نص(0, 20));
                    break;
                default:
                    قيمة.قائمة.push_back(ولّد_عدد_صحيح());
                    break;
            }
        }
        
        return قيمة;
    }
    
    /**
     * توليد قيم حدودية (للتغطية الأفضل)
     */
    std::vector<قيمة_مولّدة> ولّد_قيم_حدودية(نوع_المولّد النوع) {
        std::vector<قيمة_مولّدة> قيم;
        
        switch (النوع) {
            case نوع_المولّد::عدد_صحيح: {
                // قيم حدودية للأعداد الصحيحة
                قيمة_مولّدة q1; q1.النوع = "عدد_صحيح"; q1.عدد_صحيح = 0; قيم.push_back(q1);
                قيمة_مولّدة q2; q2.النوع = "عدد_صحيح"; q2.عدد_صحيح = 1; قيم.push_back(q2);
                قيمة_مولّدة q3; q3.النوع = "عدد_صحيح"; q3.عدد_صحيح = -1; قيم.push_back(q3);
                قيمة_مولّدة q4; q4.النوع = "عدد_صحيح"; q4.عدد_صحيح = INT32_MAX; قيم.push_back(q4);
                قيمة_مولّدة q5; q5.النوع = "عدد_صحيح"; q5.عدد_صحيح = INT32_MIN; قيم.push_back(q5);
                break;
            }
            
            case نوع_المولّد::عدد_حقيقي: {
                قيمة_مولّدة q1; q1.النوع = "عدد_حقيقي"; q1.عدد_حقيقي = 0.0; قيم.push_back(q1);
                قيمة_مولّدة q2; q2.النوع = "عدد_حقيقي"; q2.عدد_حقيقي = 1.0; قيم.push_back(q2);
                قيمة_مولّدة q3; q3.النوع = "عدد_حقيقي"; q3.عدد_حقيقي = -1.0; قيم.push_back(q3);
                قيمة_مولّدة q4; q4.النوع = "عدد_حقيقي"; q4.عدد_حقيقي = 0.0001; قيم.push_back(q4);
                قيمة_مولّدة q5; q5.النوع = "عدد_حقيقي"; q5.عدد_حقيقي = 1e10; قيم.push_back(q5);
                break;
            }
            
            case نوع_المولّد::قائمة: {
                // قائمة فارغة
                قيمة_مولّدة q1; q1.النوع = "قائمة"; قيم.push_back(q1);
                // قائمة بعنصر واحد
                قيمة_مولّدة q2; q2.النوع = "قائمة";
                قيمة_مولّدة عنصر; عنصر.النوع = "عدد_صحيح"; عنصر.عدد_صحيح = 42;
                q2.قائمة.push_back(عنصر);
                قيم.push_back(q2);
                break;
            }
            
            default:
                break;
        }
        
        return قيم;
    }
    
    /**
     * تقليص القيمة (Shrinking)
     */
    std::vector<قيمة_مولّدة> قلّص(const قيمة_مولّدة& قيمة) {
        std::vector<قيمة_مولّدة> نتائج;
        
        if (قيمة.النوع == "عدد_صحيح") {
            // تقليص نحو الصفر
            int64_t ع = قيمة.عدد_صحيح;
            if (ع > 0) {
                قيمة_مولّدة q; q.النوع = "عدد_صحيح"; q.عدد_صحيح = ع / 2; نتائج.push_back(q);
                قيمة_مولّدة q2; q2.النوع = "عدد_صحيح"; q2.عدد_صحيح = ع - 1; نتائج.push_back(q2);
            } else if (ع < 0) {
                قيمة_مولّدة q; q.النوع = "عدد_صحيح"; q.عدد_صحيح = ع / 2; نتائج.push_back(q);
                قيمة_مولّدة q2; q2.النوع = "عدد_صحيح"; q2.عدد_صحيح = ع + 1; نتائج.push_back(q2);
            }
            قيمة_مولّدة صفر; صفر.النوع = "عدد_صحيح"; صفر.عدد_صحيح = 0;
            نتائج.push_back(صفر);
        }
        else if (قيمة.النوع == "قائمة") {
            // تقليص بإزالة عناصر
            for (size_t i = 0; i < قيمة.قائمة.size(); ++i) {
                قيمة_مولّدة أقصر;
                أقصر.النوع = "قائمة";
                for (size_t j = 0; j < قيمة.قائمة.size(); ++j) {
                    if (i != j) أقصر.قائمة.push_back(قيمة.قائمة[j]);
                }
                نتائج.push_back(أقصر);
            }
            // قائمة فارغة
            قيمة_مولّدة فارغة; فارغة.النوع = "قائمة";
            نتائج.push_back(فارغة);
        }
        else if (قيمة.النوع == "نص") {
            // تقليص بإزالة أحرف
            if (!قيمة.نص.empty()) {
                قيمة_مولّدة نصف; نصف.النوع = "نص";
                نصف.نص = قيمة.نص.substr(0, قيمة.نص.size() / 2);
                نتائج.push_back(نصف);
                
                قيمة_مولّدة فارغ; فارغ.النوع = "نص"; فارغ.نص = "";
                نتائج.push_back(فارغ);
            }
        }
        
        return نتائج;
    }
};

