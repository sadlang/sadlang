/**
 * نوع الاقتراح
 */
enum class نوع_اقتراح {
    جودة,
    أداء,
    أمان,
    قراءة,
    تصميم
};

/**
 * اقتراح من AI
 */
struct اقتراح_ai {
    نوع_اقتراح النوع;
    std::string الملف;
    int السطر_البداية;
    int السطر_النهاية;
    std::string العنوان;
    std::string التفاصيل;
    std::string الكود_المقترح;
    double الثقة;           // 0.0 - 1.0
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مراجع AI
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🤖 مراجع AI للكود
 */
class مراجع_ai {
public:
    /**
     * مراجعة ملف
     */
    std::vector<اقتراح_ai> راجع_ملف(const std::string& مسار) {
        std::vector<اقتراح_ai> اقتراحات;
        
        std::ifstream ملف(مسار);
        if (!ملف.is_open()) {
            return اقتراحات;
        }
        
        std::vector<std::string> أسطر;
        std::string سطر;
        while (std::getline(ملف, سطر)) {
            أسطر.push_back(سطر);
        }
        
        // قواعد المراجعة
        اقتراحات = راجع_الأمان(مسار, أسطر);
        
        auto جودة = راجع_الجودة(مسار, أسطر);
        اقتراحات.insert(اقتراحات.end(), جودة.begin(), جودة.end());
        
        auto أداء = راجع_الأداء(مسار, أسطر);
        اقتراحات.insert(اقتراحات.end(), أداء.begin(), أداء.end());
        
        auto قراءة = راجع_القراءة(مسار, أسطر);
        اقتراحات.insert(اقتراحات.end(), قراءة.begin(), قراءة.end());
        
        return اقتراحات;
    }
    
    /**
     * توليد تعليق المراجعة
     */
    std::string ولد_تعليق(const std::vector<اقتراح_ai>& اقتراحات) const {
        if (اقتراحات.empty()) {
            return "✅ **مراجعة AI:** لا توجد ملاحظات. الكود جيد!";
        }
        
        std::ostringstream تعليق;
        تعليق << "## 🤖 مراجعة AI\n\n";
        
        // تجميع حسب النوع
        std::map<نوع_اقتراح, std::vector<const اقتراح_ai*>> حسب_النوع;
        for (const auto& اقتراح : اقتراحات) {
            حسب_النوع[اقتراح.النوع].push_back(&اقتراح);
        }
        
        // عرض حسب الأولوية
        std::vector<std::pair<نوع_اقتراح, std::string>> أنواع = {
            {نوع_اقتراح::أمان, "🔒 الأمان"},
            {نوع_اقتراح::أداء, "⚡ الأداء"},
            {نوع_اقتراح::جودة, "📊 الجودة"},
            {نوع_اقتراح::قراءة, "📖 القراءة"},
            {نوع_اقتراح::تصميم, "🏗️ التصميم"}
        };
        
        for (const auto& [نوع, عنوان] : أنواع) {
            auto it = حسب_النوع.find(نوع);
            if (it == حسب_النوع.end()) continue;
            
            تعليق << "### " << عنوان << "\n\n";
            
            for (const auto* اقتراح : it->second) {
                تعليق << "- **" << اقتراح->العنوان << "**";
                if (اقتراح->السطر_البداية > 0) {
                    تعليق << " (سطر " << اقتراح->السطر_البداية << ")";
                }
                تعليق << "\n";
                تعليق << "  " << اقتراح->التفاصيل << "\n";
                
                if (!اقتراح->الكود_المقترح.empty()) {
                    تعليق << "  ```ص\n";
                    تعليق << "  " << اقتراح->الكود_المقترح << "\n";
                    تعليق << "  ```\n";
                }
                تعليق << "\n";
            }
        }
        
        // ملخص
        تعليق << "---\n";
        تعليق << "📊 **ملخص:** " << اقتراحات.size() << " ملاحظة\n";
        
        return تعليق.str();
    }
    
private:
    /**
     * مراجعة الأمان
     */
    std::vector<اقتراح_ai> راجع_الأمان(const std::string& مسار,
                                         const std::vector<std::string>& أسطر) {
        std::vector<اقتراح_ai> اقتراحات;
        
        // أنماط خطيرة
        std::vector<std::pair<std::regex, std::string>> أنماط_أمان = {
            {std::regex(R"(sql.*\+.*user|user.*\+.*sql)", std::regex::icase), "SQL Injection محتمل"},
            {std::regex(R"(eval\s*\()"), "استخدام eval خطير"},
            {std::regex(R"(innerHTML\s*=)"), "XSS محتمل"},
            {std::regex(R"(password.*=.*['\"].*['\"])"), "كلمة سر مكشوفة في الكود"},
            {std::regex(R"(api_key.*=.*['\"].*['\"])"), "مفتاح API مكشوف"},
            {std::regex(R"(exec\s*\()"), "استخدام exec خطير"}
        };
        
        for (size_t i = 0; i < أسطر.size(); i++) {
            for (const auto& [نمط, رسالة] : أنماط_أمان) {
                if (std::regex_search(أسطر[i], نمط)) {
                    اقتراح_ai اقتراح;
                    اقتراح.النوع = نوع_اقتراح::أمان;
                    اقتراح.الملف = مسار;
                    اقتراح.السطر_البداية = static_cast<int>(i) + 1;
                    اقتراح.العنوان = رسالة;
                    اقتراح.التفاصيل = "راجع هذا السطر للتأكد من عدم وجود ثغرات أمنية";
                    اقتراح.الثقة = 0.8;
                    اقتراحات.push_back(اقتراح);
                }
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * مراجعة الجودة
     */
    std::vector<اقتراح_ai> راجع_الجودة(const std::string& مسار,
                                         const std::vector<std::string>& أسطر) {
        std::vector<اقتراح_ai> اقتراحات;
        
        // دوال طويلة
        int بداية_دالة = -1;
        for (size_t i = 0; i < أسطر.size(); i++) {
            if (أسطر[i].find("دالة ") != std::string::npos ||
                أسطر[i].find("function ") != std::string::npos) {
                بداية_دالة = static_cast<int>(i);
            }
            
            if (بداية_دالة >= 0 && أسطر[i].find("}") != std::string::npos) {
                int طول = static_cast<int>(i) - بداية_دالة + 1;
                if (طول > 50) {
                    اقتراح_ai اقتراح;
                    اقتراح.النوع = نوع_اقتراح::جودة;
                    اقتراح.الملف = مسار;
                    اقتراح.السطر_البداية = بداية_دالة + 1;
                    اقتراح.السطر_النهاية = static_cast<int>(i) + 1;
                    اقتراح.العنوان = "دالة طويلة جداً";
                    اقتراح.التفاصيل = "الدالة " + std::to_string(طول) + 
                                       " سطر. يُفضل أقل من 50 سطر.";
                    اقتراح.الثقة = 0.9;
                    اقتراحات.push_back(اقتراح);
                }
                بداية_دالة = -1;
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * مراجعة الأداء
     */
    std::vector<اقتراح_ai> راجع_الأداء(const std::string& مسار,
                                         const std::vector<std::string>& أسطر) {
        std::vector<اقتراح_ai> اقتراحات;
        
        // أنماط أداء سيء
        std::vector<std::pair<std::regex, std::pair<std::string, std::string>>> أنماط = {
            {std::regex(R"(لكل.*لكل|for.*for)"), 
             {"حلقة متداخلة", "تعقيد O(n²) - راجع إمكانية تحسينها"}},
            {std::regex(R"(\+.*في.*حلقة|\+.*in.*loop)"), 
             {"سلسلة نصية في حلقة", "استخدم StringBuilder بدلاً من +"}},
        };
        
        for (size_t i = 0; i < أسطر.size(); i++) {
            for (const auto& [نمط, رسائل] : أنماط) {
                if (std::regex_search(أسطر[i], نمط)) {
                    اقتراح_ai اقتراح;
                    اقتراح.النوع = نوع_اقتراح::أداء;
                    اقتراح.الملف = مسار;
                    اقتراح.السطر_البداية = static_cast<int>(i) + 1;
                    اقتراح.العنوان = رسائل.first;
                    اقتراح.التفاصيل = رسائل.second;
                    اقتراح.الثقة = 0.7;
                    اقتراحات.push_back(اقتراح);
                }
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * مراجعة القراءة
     */
    std::vector<اقتراح_ai> راجع_القراءة(const std::string& مسار,
                                          const std::vector<std::string>& أسطر) {
        std::vector<اقتراح_ai> اقتراحات;
        
        // أسطر طويلة جداً
        for (size_t i = 0; i < أسطر.size(); i++) {
            if (أسطر[i].length() > 120) {
                اقتراح_ai اقتراح;
                اقتراح.النوع = نوع_اقتراح::قراءة;
                اقتراح.الملف = مسار;
                اقتراح.السطر_البداية = static_cast<int>(i) + 1;
                اقتراح.العنوان = "سطر طويل جداً";
                اقتراح.التفاصيل = "طول السطر " + std::to_string(أسطر[i].length()) +
                                   " حرف. يُفضل أقل من 120.";
                اقتراح.الثقة = 0.95;
                اقتراحات.push_back(اقتراح);
            }
        }
        
        return اقتراحات;
    }
};

