/**
 * خطورة المشكلة
 */
enum class خطورة {
    ملاحظة,
    تحذير,
    خطأ,
    حرج
};

/**
 * مشكلة في الكود
 */
struct مشكلة_كود {
    std::string الملف;
    int السطر;
    int العمود;
    خطورة الخطورة;
    std::string الرمز;      // مثال: "SA001"
    std::string الرسالة;
    std::string الاقتراح;   // إصلاح مقترح
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مقاييس الكود
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مقاييس دالة
 */
struct مقاييس_دالة {
    std::string الاسم;
    int عدد_الأسطر;
    int التعقيد_الدوري;
    int عمق_التداخل;
    int عدد_المعاملات;
    int عدد_المتغيرات;
    bool طويلة_جداً;
    bool معقدة_جداً;
};

/**
 * مقاييس ملف
 */
struct مقاييس_ملف {
    std::string المسار;
    int عدد_الأسطر;
    int أسطر_الكود;
    int أسطر_التعليقات;
    int عدد_الدوال;
    int عدد_الأصناف;
    double نسبة_التعليقات;
    std::vector<مقاييس_دالة> الدوال;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              المُحلل الثابت
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🔍 المُحلل الثابت المتقدم
 */
class محلل_ثابت {
public:
    /**
     * الإعدادات
     */
    struct إعدادات {
        int حد_التعقيد = 10;
        int حد_طول_الدالة = 50;
        int حد_عمق_التداخل = 4;
        int حد_المعاملات = 5;
        bool فحص_متغيرات_غير_مستخدمة = true;
        bool فحص_كود_متكرر = true;
        bool فحص_أمان = true;
    };
    
    /**
     * إنشاء المحلل
     */
    محلل_ثابت(const إعدادات& إعدادات = إعدادات()) 
        : الإعدادات_(إعدادات) {}
    
    /**
     * تحليل ملف
     */
    std::pair<مقاييس_ملف, std::vector<مشكلة_كود>> حلل_ملف(const std::string& مسار) {
        مقاييس_ملف مقاييس;
        مقاييس.المسار = مسار;
        
        std::vector<مشكلة_كود> مشاكل;
        
        std::ifstream ملف(مسار);
        if (!ملف.is_open()) {
            مشكلة_كود م;
            م.الملف = مسار;
            م.السطر = 0;
            م.الخطورة = خطورة::خطأ;
            م.الرمز = "SA000";
            م.الرسالة = "لا يمكن فتح الملف";
            مشاكل.push_back(م);
            return {مقاييس, مشاكل};
        }
        
        std::vector<std::string> أسطر;
        std::string سطر;
        while (std::getline(ملف, سطر)) {
            أسطر.push_back(سطر);
        }
        
        مقاييس.عدد_الأسطر = static_cast<int>(أسطر.size());
        
        // تحليل الأسطر
        int عداد_كود = 0;
        int عداد_تعليقات = 0;
        int عمق_حالي = 0;
        int أقصى_عمق = 0;
        bool في_دالة = false;
        std::string اسم_الدالة_الحالية;
        int بداية_الدالة = 0;
        int تعقيد_حالي = 1;
        
        for (size_t i = 0; i < أسطر.size(); i++) {
            const auto& س = أسطر[i];
            std::string مقلم = قلم(س);
            
            if (مقلم.empty()) continue;
            
            // تعليق
            if (مقلم.find("//") == 0 || مقلم.find("/*") == 0) {
                عداد_تعليقات++;
                continue;
            }
            
            عداد_كود++;
            
            // بداية دالة
            if (مقلم.find("دالة ") != std::string::npos ||
                مقلم.find("function ") != std::string::npos) {
                في_دالة = true;
                بداية_الدالة = static_cast<int>(i) + 1;
                تعقيد_حالي = 1;
                عمق_حالي = 0;
                مقاييس.عدد_الدوال++;
                
                // استخراج اسم الدالة
                std::regex نمط(R"((?:دالة|function)\s+(\w+))");
                std::smatch تطابق;
                if (std::regex_search(س, تطابق, نمط)) {
                    اسم_الدالة_الحالية = تطابق[1].str();
                }
            }
            
            // صنف
            if (مقلم.find("صنف ") != std::string::npos ||
                مقلم.find("class ") != std::string::npos) {
                مقاييس.عدد_الأصناف++;
            }
            
            // تتبع العمق
            for (char c : س) {
                if (c == '{') عمق_حالي++;
                if (c == '}') عمق_حالي--;
            }
            أقصى_عمق = std::max(أقصى_عمق, عمق_حالي);
            
            // حساب التعقيد
            if (مقلم.find("إذا ") != std::string::npos ||
                مقلم.find("if ") != std::string::npos ||
                مقلم.find("طالما ") != std::string::npos ||
                مقلم.find("while ") != std::string::npos ||
                مقلم.find("لكل ") != std::string::npos ||
                مقلم.find("for ") != std::string::npos ||
                مقلم.find("&&") != std::string::npos ||
                مقلم.find("||") != std::string::npos) {
                تعقيد_حالي++;
            }
            
            // نهاية دالة (مبسط)
            if (في_دالة && عمق_حالي == 0 && مقلم.find("}") != std::string::npos) {
                في_دالة = false;
                int طول = static_cast<int>(i) - بداية_الدالة + 1;
                
                مقاييس_دالة مقياس;
                مقياس.الاسم = اسم_الدالة_الحالية;
                مقياس.عدد_الأسطر = طول;
                مقياس.التعقيد_الدوري = تعقيد_حالي;
                مقياس.عمق_التداخل = أقصى_عمق;
                
                // فحص المشاكل
                if (طول > الإعدادات_.حد_طول_الدالة) {
                    مقياس.طويلة_جداً = true;
                    مشكلة_كود م;
                    م.الملف = مسار;
                    م.السطر = بداية_الدالة;
                    م.الخطورة = خطورة::تحذير;
                    م.الرمز = "SA001";
                    م.الرسالة = "الدالة طويلة جداً (" + std::to_string(طول) + " سطر)";
                    م.الاقتراح = "قسّم الدالة إلى دوال أصغر";
                    مشاكل.push_back(م);
                }
                
                if (تعقيد_حالي > الإعدادات_.حد_التعقيد) {
                    مقياس.معقدة_جداً = true;
                    مشكلة_كود م;
                    م.الملف = مسار;
                    م.السطر = بداية_الدالة;
                    م.الخطورة = خطورة::تحذير;
                    م.الرمز = "SA002";
                    م.الرسالة = "الدالة معقدة جداً (تعقيد = " + std::to_string(تعقيد_حالي) + ")";
                    م.الاقتراح = "بسّط المنطق أو قسّم الدالة";
                    مشاكل.push_back(م);
                }
                
                مقاييس.الدوال.push_back(مقياس);
                أقصى_عمق = 0;
            }
        }
        
        مقاييس.أسطر_الكود = عداد_كود;
        مقاييس.أسطر_التعليقات = عداد_تعليقات;
        مقاييس.نسبة_التعليقات = عداد_كود > 0 
            ? static_cast<double>(عداد_تعليقات) / عداد_كود * 100 : 0;
        
        // تحذير عند قلة التعليقات
        if (مقاييس.نسبة_التعليقات < 10 && مقاييس.أسطر_الكود > 50) {
            مشكلة_كود م;
            م.الملف = مسار;
            م.السطر = 0;
            م.الخطورة = خطورة::ملاحظة;
            م.الرمز = "SA003";
            م.الرسالة = "نسبة التعليقات منخفضة (" + 
                        std::to_string(static_cast<int>(مقاييس.نسبة_التعليقات)) + "%)";
            م.الاقتراح = "أضف تعليقات لتوضيح المنطق المعقد";
            مشاكل.push_back(م);
        }
        
        return {مقاييس, مشاكل};
    }
    
    /**
     * توليد تقرير
     */
    std::string ولد_تقرير(const مقاييس_ملف& مقاييس,
                           const std::vector<مشكلة_كود>& مشاكل) const {
        std::ostringstream تقرير;
        
        تقرير << "╔══════════════════════════════════════════════════════════════╗\n";
        تقرير << "║           📊 تقرير التحليل الثابت                           ║\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        تقرير << "║ الملف: " << مقاييس.المسار << "\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        تقرير << "║ 📈 المقاييس:                                                 ║\n";
        تقرير << "║   • أسطر الكود: " << مقاييس.أسطر_الكود << "\n";
        تقرير << "║   • أسطر التعليقات: " << مقاييس.أسطر_التعليقات << "\n";
        تقرير << "║   • عدد الدوال: " << مقاييس.عدد_الدوال << "\n";
        تقرير << "║   • عدد الأصناف: " << مقاييس.عدد_الأصناف << "\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        
        if (!مشاكل.empty()) {
            تقرير << "║ ⚠️ المشاكل (" << مشاكل.size() << "):                           \n";
            for (const auto& م : مشاكل) {
                std::string رمز;
                switch (م.الخطورة) {
                    case خطورة::ملاحظة: رمز = "ℹ️"; break;
                    case خطورة::تحذير: رمز = "⚠️"; break;
                    case خطورة::خطأ: رمز = "❌"; break;
                    case خطورة::حرج: رمز = "🚨"; break;
                }
                تقرير << "║   " << رمز << " [" << م.الرمز << "] السطر " 
                       << م.السطر << ": " << م.الرسالة << "\n";
                if (!م.الاقتراح.empty()) {
                    تقرير << "║      💡 " << م.الاقتراح << "\n";
                }
            }
        } else {
            تقرير << "║ ✅ لا توجد مشاكل!                                           \n";
        }
        
        تقرير << "╚══════════════════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }
    
private:
    إعدادات الإعدادات_;
    
    /**
     * إزالة المسافات
     */
    std::string قلم(const std::string& نص) const {
        size_t بداية = نص.find_first_not_of(" \t\r\n");
        size_t نهاية = نص.find_last_not_of(" \t\r\n");
        if (بداية == std::string::npos) return "";
        return نص.substr(بداية, نهاية - بداية + 1);
    }
};

