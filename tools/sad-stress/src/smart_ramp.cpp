#include <string>
#include <vector>
#include <chrono>
#include <thread>
#include <atomic>
#include <iostream>
#include <cmath>

namespace sad {
namespace tools {

/**
 * ⬆️ مُصعِّد الحمل الذكي
 */
class مصعد_حمل {
public:
    enum استراتيجية {
        خطي,           // تصعيد ثابت
        تدريجي,        // بطيء ثم سريع
        موجات,         // تصعيد وتخفيض
        ذروة           // وصول سريع للذروة
    };
    
    /**
     * إنشاء المُصعِّد
     */
    مصعد_حمل(int حمل_أقصى, int مدة_ثواني, استراتيجية نوع = خطي)
        : الحمل_الأقصى_(حمل_أقصى)
        , المدة_(مدة_ثواني)
        , الاستراتيجية_(نوع) {}
    
    /**
     * الحصول على الحمل الحالي
     */
    int الحمل_الحالي(double الوقت_المنقضي) const {
        double نسبة = الوقت_المنقضي / المدة_;
        if (نسبة > 1.0) نسبة = 1.0;
        
        switch (الاستراتيجية_) {
            case خطي:
                return static_cast<int>(الحمل_الأقصى_ * نسبة);
                
            case تدريجي:
                // منحنى أسي
                return static_cast<int>(الحمل_الأقصى_ * (1 - std::exp(-3 * نسبة)));
                
            case موجات:
                // موجة جيبية
                return static_cast<int>(الحمل_الأقصى_ * 0.5 * (1 + std::sin(نسبة * 3.14159 * 4)));
                
            case ذروة:
                // وصول سريع للذروة
                if (نسبة < 0.2) {
                    return static_cast<int>(الحمل_الأقصى_ * نسبة * 5);
                }
                return الحمل_الأقصى_;
        }
        
        return 0;
    }
    
    /**
     * طباعة رسم بياني للتصعيد
     */
    void اطبع_رسم() const {
        std::cout << "\n📈 مخطط التصعيد:\n";
        std::cout << "────────────────────────────────────────────────\n";
        
        const int عرض = 50;
        for (int t = 0; t <= 10; t++) {
            double نسبة_وقت = t / 10.0;
            int حمل = الحمل_الحالي(نسبة_وقت * المدة_);
            int أعمدة = static_cast<int>((حمل * عرض) / الحمل_الأقصى_);
            
            std::cout << (t * 10) << "% |";
            for (int i = 0; i < أعمدة; i++) std::cout << "█";
            for (int i = أعمدة; i < عرض; i++) std::cout << " ";
            std::cout << "| " << حمل << " مستخدم\n";
        }
        
        std::cout << "────────────────────────────────────────────────\n";
    }
    
private:
    int الحمل_الأقصى_;
    int المدة_;
    استراتيجية الاستراتيجية_;
};

} // namespace tools
} // namespace sad

int main() {
    std::cout << "⬆️ استراتيجيات التصعيد:\n\n";
    
    std::cout << "1. خطي:\n";
    sad::tools::مصعد_حمل خطي(100, 60, sad::tools::مصعد_حمل::خطي);
    خطي.اطبع_رسم();
    
    std::cout << "\n2. تدريجي:\n";
    sad::tools::مصعد_حمل تدريجي(100, 60, sad::tools::مصعد_حمل::تدريجي);
    تدريجي.اطبع_رسم();
    
    std::cout << "\n3. موجات:\n";
    sad::tools::مصعد_حمل موجات(100, 60, sad::tools::مصعد_حمل::موجات);
    موجات.اطبع_رسم();
    
    return 0;
}
