#include <string>
#include <vector>
#include <map>
#include <algorithm>
#include <iostream>
#include <iomanip>
#include <cmath>

namespace sad {
namespace tools {

/**
 * نقطة اختناق
 */
struct نقطة_اختناق {
    std::string الموقع;        // URL أو الدالة
    double متوسط_الوقت_ms;
    double أقصى_وقت_ms;
    double نسبة_الأخطاء;
    int عدد_الطلبات;
    std::string التوصية;
};

/**
 * 🔍 كاشف نقاط الاختناق
 */
class كاشف_اختناق {
public:
    /**
     * تسجيل طلب
     */
    void سجل(const std::string& موقع, double وقت_ms, bool نجاح) {
        auto& بيانات = البيانات_[موقع];
        بيانات.أوقات.push_back(وقت_ms);
        بيانات.عدد_الكلي++;
        if (!نجاح) بيانات.عدد_الأخطاء++;
    }
    
    /**
     * تحليل وكشف الاختناقات
     */
    std::vector<نقطة_اختناق> حلل() const {
        std::vector<نقطة_اختناق> نتائج;
        
        for (const auto& [موقع, بيانات] : البيانات_) {
            if (بيانات.أوقات.empty()) continue;
            
            نقطة_اختناق نقطة;
            نقطة.الموقع = موقع;
            نقطة.عدد_الطلبات = بيانات.عدد_الكلي;
            
            // حساب الإحصائيات
            double مجموع = 0;
            double أقصى = 0;
            for (double و : بيانات.أوقات) {
                مجموع += و;
                if (و > أقصى) أقصى = و;
            }
            
            نقطة.متوسط_الوقت_ms = مجموع / بيانات.أوقات.size();
            نقطة.أقصى_وقت_ms = أقصى;
            نقطة.نسبة_الأخطاء = بيانات.عدد_الكلي > 0 
                ? static_cast<double>(بيانات.عدد_الأخطاء) / بيانات.عدد_الكلي * 100 : 0;
            
            // تحديد التوصية
            if (نقطة.متوسط_الوقت_ms > 1000) {
                نقطة.التوصية = "⚠️ بطيء جداً - راجع قاعدة البيانات أو الكاش";
            } else if (نقطة.نسبة_الأخطاء > 5) {
                نقطة.التوصية = "❌ معدل أخطاء مرتفع - راجع المنطق";
            } else if (نقطة.أقصى_وقت_ms > 5000) {
                نقطة.التوصية = "⏱️ تباين كبير - راجع الموارد الخارجية";
            } else {
                نقطة.التوصية = "✅ جيد";
            }
            
            نتائج.push_back(نقطة);
        }
        
        // ترتيب حسب الأبطأ
        std::sort(نتائج.begin(), نتائج.end(),
            [](const نقطة_اختناق& أ, const نقطة_اختناق& ب) {
                return أ.متوسط_الوقت_ms > ب.متوسط_الوقت_ms;
            });
        
        return نتائج;
    }
    
    /**
     * طباعة التقرير
     */
    void اطبع_تقرير() const {
        auto نتائج = حلل();
        
        std::cout << "\n╔══════════════════════════════════════════════════════════════════════════════╗\n";
        std::cout << "║                    🔍 تقرير نقاط الاختناق                                    ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════════════════════╣\n";
        std::cout << "║ الموقع                          │ متوسط │ أقصى  │ أخطاء │ التوصية          ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════════════════════╣\n";
        
        for (const auto& ن : نتائج) {
            std::cout << "║ " << std::setw(30) << std::left << ن.الموقع.substr(0, 30)
                      << " │ " << std::setw(5) << static_cast<int>(ن.متوسط_الوقت_ms) << "ms"
                      << " │ " << std::setw(5) << static_cast<int>(ن.أقصى_وقت_ms) << "ms"
                      << " │ " << std::setw(4) << std::fixed << std::setprecision(1) << ن.نسبة_الأخطاء << "%"
                      << " │ " << ن.التوصية << "\n";
        }
        
        std::cout << "╚══════════════════════════════════════════════════════════════════════════════╝\n";
    }
    
private:
    struct بيانات_موقع {
        std::vector<double> أوقات;
        int عدد_الكلي = 0;
        int عدد_الأخطاء = 0;
    };
    
    std::map<std::string, بيانات_موقع> البيانات_;
};

} // namespace tools
} // namespace sad

int main() {
    sad::tools::كاشف_اختناق كاشف;
    
    // بيانات تجريبية
    for (int i = 0; i < 100; i++) {
        كاشف.سجل("/api/users", 50 + (i % 30), true);
        كاشف.سجل("/api/products", 200 + (i % 100), true);
        كاشف.سجل("/api/orders", 1500 + (i % 500), i % 10 == 0 ? false : true);
        كاشف.سجل("/api/search", 800 + (i % 2000), true);
    }
    
    كاشف.اطبع_تقرير();
    
    return 0;
}
