/**
 * نوع الخطوة
 */
enum class نوع_خطوة {
    طلب_HTTP,
    انتظار,
    فكر,
    تأكيد,
    سجل
};

/**
 * خطوة في السيناريو
 */
struct خطوة_سيناريو {
    نوع_خطوة النوع;
    std::string الطريقة;      // GET, POST, etc.
    std::string المسار;
    std::map<std::string, std::string> الرؤوس;
    std::string الجسم;
    int انتظار_أدنى_ms;
    int انتظار_أقصى_ms;
    std::string تأكيد_حالة;
    std::string تأكيد_محتوى;
};

/**
 * سيناريو كامل
 */
struct سيناريو {
    std::string الاسم;
    std::string الوصف;
    int الوزن = 1;           // للاختيار العشوائي
    std::vector<خطوة_سيناريو> الخطوات;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل DSL
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 📋 محلل DSL السيناريوهات
 */
class محلل_سيناريو {
public:
    /**
     * تحليل ملف سيناريو
     */
    std::vector<سيناريو> حلل_ملف(const std::string& مسار) {
        std::vector<سيناريو> سيناريوهات;
        
        std::ifstream ملف(مسار);
        if (!ملف.is_open()) {
            std::cerr << "❌ لا يمكن فتح الملف: " << مسار << std::endl;
            return سيناريوهات;
        }
        
        سيناريو* حالي = nullptr;
        std::string سطر;
        
        while (std::getline(ملف, سطر)) {
            سطر = قلم(سطر);
            if (سطر.empty() || سطر[0] == '#') continue;
            
            // سيناريو جديد
            if (سطر.find("@سيناريو") != std::string::npos ||
                سطر.find("@scenario") != std::string::npos) {
                سيناريوهات.push_back(سيناريو());
                حالي = &سيناريوهات.back();
                
                // استخراج الاسم
                std::regex نمط(R"(\(\"([^\"]+)\"\))");
                std::smatch تطابق;
                if (std::regex_search(سطر, تطابق, نمط)) {
                    حالي->الاسم = تطابق[1].str();
                }
                continue;
            }
            
            if (!حالي) continue;
            
            // طلب HTTP
            if (سطر.find("افتح(") != std::string::npos ||
                سطر.find("open(") != std::string::npos) {
                خطوة_سيناريو خطوة;
                خطوة.النوع = نوع_خطوة::طلب_HTTP;
                خطوة.الطريقة = "GET";
                
                std::regex نمط(R"(\(\"([^\"]+)\"\))");
                std::smatch تطابق;
                if (std::regex_search(سطر, تطابق, نمط)) {
                    خطوة.المسار = تطابق[1].str();
                }
                
                حالي->الخطوات.push_back(خطوة);
            }
            
            // طلب POST
            if (سطر.find("أرسل(") != std::string::npos ||
                سطر.find("post(") != std::string::npos) {
                خطوة_سيناريو خطوة;
                خطوة.النوع = نوع_خطوة::طلب_HTTP;
                خطوة.الطريقة = "POST";
                
                std::regex نمط(R"(\(\"([^\"]+)\")");
                std::smatch تطابق;
                if (std::regex_search(سطر, تطابق, نمط)) {
                    خطوة.المسار = تطابق[1].str();
                }
                
                حالي->الخطوات.push_back(خطوة);
            }
            
            // وقت التفكير
            if (سطر.find("فكر(") != std::string::npos ||
                سطر.find("think(") != std::string::npos) {
                خطوة_سيناريو خطوة;
                خطوة.النوع = نوع_خطوة::فكر;
                
                // استخراج النطاق
                std::regex نمط(R"((\d+)\s*[-,]\s*(\d+))");
                std::smatch تطابق;
                if (std::regex_search(سطر, تطابق, نمط)) {
                    خطوة.انتظار_أدنى_ms = std::stoi(تطابق[1].str()) * 1000;
                    خطوة.انتظار_أقصى_ms = std::stoi(تطابق[2].str()) * 1000;
                }
                
                حالي->الخطوات.push_back(خطوة);
            }
            
            // انتظار ثابت
            if (سطر.find("انتظر(") != std::string::npos ||
                سطر.find("wait(") != std::string::npos) {
                خطوة_سيناريو خطوة;
                خطوة.النوع = نوع_خطوة::انتظار;
                
                std::regex نمط(R"((\d+))");
                std::smatch تطابق;
                if (std::regex_search(سطر, تطابق, نمط)) {
                    خطوة.انتظار_أدنى_ms = std::stoi(تطابق[1].str()) * 1000;
                    خطوة.انتظار_أقصى_ms = خطوة.انتظار_أدنى_ms;
                }
                
                حالي->الخطوات.push_back(خطوة);
            }
            
            // تأكيد
            if (سطر.find("تأكد(") != std::string::npos ||
                سطر.find("assert(") != std::string::npos) {
                خطوة_سيناريو خطوة;
                خطوة.النوع = نوع_خطوة::تأكيد;
                
                std::regex نمط(R"(\(\"([^\"]+)\"\))");
                std::smatch تطابق;
                if (std::regex_search(سطر, تطابق, نمط)) {
                    خطوة.تأكيد_محتوى = تطابق[1].str();
                }
                
                حالي->الخطوات.push_back(خطوة);
            }
        }
        
        return سيناريوهات;
    }
    
    /**
     * توليد تقرير السيناريوهات
     */
    std::string ولد_تقرير(const std::vector<سيناريو>& سيناريوهات) const {
        std::ostringstream تقرير;
        
        تقرير << "╔══════════════════════════════════════════════════════════════╗\n";
        تقرير << "║           📋 السيناريوهات المُحمَّلة                          ║\n";
        تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        
        for (const auto& س : سيناريوهات) {
            تقرير << "║ 📌 " << س.الاسم << "\n";
            تقرير << "║    خطوات: " << س.الخطوات.size() << "\n";
            for (const auto& خ : س.الخطوات) {
                switch (خ.النوع) {
                    case نوع_خطوة::طلب_HTTP:
                        تقرير << "║      → " << خ.الطريقة << " " << خ.المسار << "\n";
                        break;
                    case نوع_خطوة::فكر:
                        تقرير << "║      ⏳ فكر " << خ.انتظار_أدنى_ms/1000 
                               << "-" << خ.انتظار_أقصى_ms/1000 << " ثانية\n";
                        break;
                    case نوع_خطوة::تأكيد:
                        تقرير << "║      ✓ تأكد: " << خ.تأكيد_محتوى << "\n";
                        break;
                    default:
                        break;
                }
            }
            تقرير << "╠══════════════════════════════════════════════════════════════╣\n";
        }
        
        تقرير << "╚══════════════════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }
    
private:
    /**
     * إزالة المسافات
     */
    std::string قلم(const std::string& نص) const {
        size_t بداية = نص.find_first_not_of(" \t\r\n");
        size_t نهاية = نص.find_last_not_of(" \t\r\n");
        if (بداية == std::string::npos) return "";
        return نص.substr(بداية, نهاية - بداية + 1);
    }
};

