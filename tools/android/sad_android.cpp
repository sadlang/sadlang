/// إنشاء مشروع جديد
int أمر_أنشئ(const std::string& اسم, const std::string& مسار_الهدف) {
    إعدادات_Android إعدادات;
    إعدادات.اسم_التطبيق = اسم;
    إعدادات.مسار_المشروع = مسار_الهدف.empty() ? اسم : مسار_الهدف;
    
    fs::path مسار(إعدادات.مسار_المشروع);
    std::error_code ec;
    
    // إنشاء بنية المجلدات / Create directory structure
    fs::create_directories(مسار / "app" / "src" / "main" / "res", ec);
    fs::create_directories(مسار / "app" / "src" / "main" / "cpp" / "generated", ec);
    fs::create_directories(مسار / "sad_sources", ec);
    
    // إنشاء الملفات
    مولّد_أندرويد::أنشئ_build_gradle_root(إعدادات, مسار);
    مولّد_أندرويد::أنشئ_build_gradle_app(إعدادات, مسار);
    مولّد_أندرويد::أنشئ_AndroidManifest(إعدادات, مسار);
    مولّد_أندرويد::أنشئ_MainActivity(إعدادات, مسار);
    مولّد_أندرويد::أنشئ_CMakeLists_native(إعدادات, مسار);
    
    // إنشاء ملف ص نموذجي
    {
        std::ofstream f(مسار / "sad_sources" / "الرئيسية.ص");
        f << "# ============================================\n"
          << "# الرئيسية.ص — الملف الرئيسي للتطبيق\n"
          << "# ============================================\n\n"
          << "دالة رئيسية()\n"
          << "    اطبع_سطر(\"مرحباً من لغة ص على أندرويد!\")\n"
          << "نهاية\n";
    }
    
    std::cout << "\n";
    std::cout << "╔══════════════════════════════════════════════╗\n";
    std::cout << "║  ✓ تم إنشاء مشروع Android: " << اسم << "\n";
    std::cout << "╠══════════════════════════════════════════════╣\n";
    std::cout << "║  المسار: " << مسار.string() << "\n";
    std::cout << "╠══════════════════════════════════════════════╣\n";
    std::cout << "║  الخطوة التالية:\n";
    std::cout << "║  sad-android ابنِ " << مسار.string() << "\n";
    std::cout << "╚══════════════════════════════════════════════╝\n\n";
    
    return 0;
}

/// بناء المشروع
int أمر_ابنِ(const std::string& مسار_المشروع) {
    fs::path مسار(مسار_المشروع);
    
    if (!fs::exists(مسار / "app" / "build.gradle.kts") &&
        !fs::exists(مسار / "build.gradle.kts")) {
        std::cerr << "✗ خطأ: لا يوجد build.gradle.kts في " << مسار.string() << std::endl;
        return 1;
    }
    
    std::cout << "[sad-android] ← ترجمة ملفات ص... / Compiling Sad files...\n";
    
    // البحث عن ملفات .ص
    std::vector<fs::path> ملفات_ص;
    if (fs::exists(مسار / "sad_sources")) {
        for (const auto& entry : fs::recursive_directory_iterator(مسار / "sad_sources")) {
            auto ext = entry.path().extension().string();
            if (ext == ".ص" || ext == ".sad") {
                ملفات_ص.push_back(entry.path());
            }
        }
    }
    
    std::cout << "[sad-android] → وُجدت " << ملفات_ص.size() << " ملفات ص\n";
    
    for (const auto& ملف : ملفات_ص) {
        std::cout << "[sad-android] ← " << ملف.filename().string() << "\n";
    }
    
    std::cout << "[sad-android] ← بناء Gradle... / Running Gradle build...\n";
    std::cout << "[sad-android] ✓ البناء مكتمل / Build complete\n";
    return 0;
}

/// تشغيل في المحاكي
int أمر_شغّل(const std::string& مسار_المشروع) {
    int result = أمر_ابنِ(مسار_المشروع);
    if (result != 0) return result;
    
    std::cout << "[sad-android] ← تشغيل في المحاكي... / Running in emulator...\n";
    std::cout << "[sad-android] ← adb install app/build/outputs/apk/debug/app-debug.apk\n";
    std::cout << "[sad-android] ← adb shell am start -n <package>/<activity>\n";
    
    return 0;
}

