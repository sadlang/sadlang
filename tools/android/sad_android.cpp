int main(int argc, char* argv[]) {
    if (argc < 2) {
        اطبع_المساعدة();
        return 1;
    }
    
    std::string أمر = argv[1];
    
    if (أمر == "أنشئ" || أمر == "create") {
        if (argc < 3) {
            std::cerr << "✗ يجب تحديد اسم المشروع\n";
            return 1;
        }
        std::string هدف = (argc >= 4) ? argv[3] : "";
        return أمر_أنشئ(argv[2], هدف);
    }
    else if (أمر == "ابنِ" || أمر == "build") {
        if (argc < 3) {
            std::cerr << "✗ يجب تحديد مسار المشروع\n";
            return 1;
        }
        return أمر_ابنِ(argv[2]);
    }
    else if (أمر == "شغّل" || أمر == "run") {
        if (argc < 3) {
            std::cerr << "✗ يجب تحديد مسار المشروع\n";
            return 1;
        }
        return أمر_شغّل(argv[2]);
    }
    else if (أمر == "وقّع" || أمر == "sign") {
        if (argc < 3) {
            std::cerr << "✗ يجب تحديد مسار المشروع\n";
            return 1;
        }
        std::string keystore = (argc >= 4) ? argv[3] : "";
        std::string alias = (argc >= 5) ? argv[4] : "";
        return أمر_وقّع(argv[2], keystore, alias);
    }
    else if (أمر == "--مساعدة" || أمر == "--help" || أمر == "-h") {
        اطبع_المساعدة();
        return 0;
    }
    else {
        std::cerr << "✗ أمر غير معروف: " << أمر << "\n";
        اطبع_المساعدة();
        return 1;
    }
}
