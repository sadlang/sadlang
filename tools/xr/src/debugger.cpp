// ============== إحصائيات الأداء ==============

struct إحصائيات_إطار {
    double وقت_الإطار_ms = 0;
    double وقت_CPU_ms = 0;
    double وقت_GPU_ms = 0;
    double وقت_العرض_ms = 0;
    
    uint32_t استدعاءات_الرسم = 0;
    uint32_t المثلثات = 0;
    uint32_t الرؤوس = 0;
    
    uint64_t ذاكرة_GPU_مستخدمة = 0;
    uint64_t ذاكرة_CPU_مستخدمة = 0;
    
    // معلومات XR
    double وقت_التتبع_ms = 0;
    double كمون_العرض_ms = 0;
    uint32_t إطارات_مسقطة = 0;
};

class مراقب_الأداء {
private:
    std::deque<إحصائيات_إطار> تاريخ_الإطارات_;
    static constexpr size_t حجم_التاريخ_ = 300;  // 5 ثواني @ 60fps
    
    std::chrono::high_resolution_clock::time_point بداية_الإطار_;
    إحصائيات_إطار إطار_حالي_;
    
    // عتبات التحذير
    double عتبة_وقت_الإطار_ = 11.1;  // 90fps
    uint32_t عتبة_استدعاءات_ = 500;
    uint32_t عتبة_مثلثات_ = 1000000;
    
public:
    void بدء_إطار() {
        بداية_الإطار_ = std::chrono::high_resolution_clock::now();
        إطار_حالي_ = {};
    }
    
    void إنهاء_إطار() {
        auto الآن = std::chrono::high_resolution_clock::now();
        إطار_حالي_.وقت_الإطار_ms = 
            std::chrono::duration<double, std::milli>(الآن - بداية_الإطار_).count();
        
        تاريخ_الإطارات_.push_back(إطار_حالي_);
        if (تاريخ_الإطارات_.size() > حجم_التاريخ_) {
            تاريخ_الإطارات_.pop_front();
        }
    }
    
    void تسجيل_استدعاء_رسم(uint32_t مثلثات, uint32_t رؤوس) {
        إطار_حالي_.استدعاءات_الرسم++;
        إطار_حالي_.المثلثات += مثلثات;
        إطار_حالي_.الرؤوس += رؤوس;
    }
    
    void تعيين_وقت_CPU(double ms) { إطار_حالي_.وقت_CPU_ms = ms; }
    void تعيين_وقت_GPU(double ms) { إطار_حالي_.وقت_GPU_ms = ms; }
    void تعيين_وقت_العرض(double ms) { إطار_حالي_.وقت_العرض_ms = ms; }
    void تعيين_كمون_العرض(double ms) { إطار_حالي_.كمون_العرض_ms = ms; }
    
    // ============== التحليل ==============
    
    double متوسط_وقت_الإطار() const {
        if (تاريخ_الإطارات_.empty()) return 0;
        double مجموع = 0;
        for (const auto& إ : تاريخ_الإطارات_) {
            مجموع += إ.وقت_الإطار_ms;
        }
        return مجموع / تاريخ_الإطارات_.size();
    }
    
    double معدل_الإطارات() const {
        double متوسط = متوسط_وقت_الإطار();
        return متوسط > 0 ? 1000.0 / متوسط : 0;
    }
    
    double أقصى_وقت_إطار() const {
        double أقصى = 0;
        for (const auto& إ : تاريخ_الإطارات_) {
            if (إ.وقت_الإطار_ms > أقصى) أقصى = إ.وقت_الإطار_ms;
        }
        return أقصى;
    }
    
    uint32_t إطارات_بطيئة() const {
        uint32_t عدد = 0;
        for (const auto& إ : تاريخ_الإطارات_) {
            if (إ.وقت_الإطار_ms > عتبة_وقت_الإطار_) عدد++;
        }
        return عدد;
    }
    
    const إحصائيات_إطار& إطار_أخير() const {
        static إحصائيات_إطار فارغ;
        return تاريخ_الإطارات_.empty() ? فارغ : تاريخ_الإطارات_.back();
    }
    
    // ============== التحذيرات ==============
    
    std::vector<std::string> التحذيرات() const {
        std::vector<std::string> تحذيرات;
        const auto& إ = إطار_أخير();
        
        if (إ.وقت_الإطار_ms > عتبة_وقت_الإطار_) {
            std::ostringstream ss;
            ss << "⚠ وقت الإطار مرتفع: " << std::fixed << std::setprecision(1) 
               << إ.وقت_الإطار_ms << "ms";
            تحذيرات.push_back(ss.str());
        }
        
        if (إ.استدعاءات_الرسم > عتبة_استدعاءات_) {
            std::ostringstream ss;
            ss << "⚠ استدعاءات رسم كثيرة: " << إ.استدعاءات_الرسم;
            تحذيرات.push_back(ss.str());
        }
        
        if (إ.المثلثات > عتبة_مثلثات_) {
            std::ostringstream ss;
            ss << "⚠ مثلثات كثيرة: " << إ.المثلثات / 1000 << "K";
            تحذيرات.push_back(ss.str());
        }
        
        return تحذيرات;
    }
    
    // ============== توليد التقرير ==============
    
    std::string تقرير_نصي() const {
        std::ostringstream ss;
        const auto& إ = إطار_أخير();
        
        ss << "╔══════════════════════════════════════╗\n";
        ss << "║        معلومات الأداء                ║\n";
        ss << "╠══════════════════════════════════════╣\n";
        ss << "║ FPS: " << std::fixed << std::setprecision(1) << std::setw(8) 
           << معدل_الإطارات() << "                    ║\n";
        ss << "║ وقت الإطار: " << std::setw(6) << إ.وقت_الإطار_ms << " ms          ║\n";
        ss << "╠══════════════════════════════════════╣\n";
        ss << "║ CPU: " << std::setw(6) << إ.وقت_CPU_ms << " ms                   ║\n";
        ss << "║ GPU: " << std::setw(6) << إ.وقت_GPU_ms << " ms                   ║\n";
        ss << "║ العرض: " << std::setw(6) << إ.وقت_العرض_ms << " ms               ║\n";
        ss << "╠══════════════════════════════════════╣\n";
        ss << "║ استدعاءات: " << std::setw(6) << إ.استدعاءات_الرسم << "                ║\n";
        ss << "║ مثلثات: " << std::setw(8) << إ.المثلثات << "              ║\n";
        ss << "╚══════════════════════════════════════╝\n";
        
        return ss.str();
    }
    
    // مخطط ASCII للأداء
    std::string مخطط_الأداء() const {
        std::ostringstream ss;
        
        ss << "\n معدل الإطارات (آخر 60 إطار):\n";
        ss << " 90|";
        
        size_t عينات = std::min<size_t>(60, تاريخ_الإطارات_.size());
        size_t بداية = تاريخ_الإطارات_.size() - عينات;
        
        for (size_t i = 0; i < عينات; i++) {
            double fps = 1000.0 / تاريخ_الإطارات_[بداية + i].وقت_الإطار_ms;
            int ارتفاع = static_cast<int>((fps / 90.0) * 10);
            ارتفاع = std::min(10, std::max(0, ارتفاع));
            
            if (fps >= 85) ss << "█";
            else if (fps >= 72) ss << "▄";
            else if (fps >= 60) ss << "▂";
            else ss << "_";
        }
        
        ss << "\n 45|";
        for (size_t i = 0; i < عينات; i++) ss << "-";
        ss << "\n  0|" << std::string(عينات, '_') << "\n";
        
        return ss.str();
    }
};

// ============== مصحح التتبع ==============

struct سجل_تتبع {
    uint64_t الطابع_الزمني;
    متجه3 موضع_الرأس;
    رباعي توجه_الرأس;
    متجه3 موضع_يد_يسرى;
    متجه3 موضع_يد_يمنى;
    float قوة_قرصة_يسرى;
    float قوة_قرصة_يمنى;
};

class مصحح_التتبع {
private:
    std::deque<سجل_تتبع> تاريخ_التتبع_;
    static constexpr size_t حجم_التاريخ_ = 600;  // 10 ثواني
    
    bool تسجيل_نشط_ = false;
    
public:
    void تسجيل(const سجل_تتبع& سجل) {
        if (!تسجيل_نشط_) return;
        
        تاريخ_التتبع_.push_back(سجل);
        if (تاريخ_التتبع_.size() > حجم_التاريخ_) {
            تاريخ_التتبع_.pop_front();
        }
    }
    
    void بدء_التسجيل() { 
        تسجيل_نشط_ = true;
        تاريخ_التتبع_.clear();
    }
    
    void إيقاف_التسجيل() { 
        تسجيل_نشط_ = false; 
    }
    
    bool تسجيل_نشط() const { return تسجيل_نشط_; }
    
    // تصدير البيانات
    std::string تصدير_CSV() const {
        std::ostringstream ss;
        ss << "الطابع,موضع_س,موضع_ص,موضع_ع,يسرى_س,يسرى_ص,يسرى_ع,يمنى_س,يمنى_ص,يمنى_ع,قرصة_يسرى,قرصة_يمنى\n";
        
        for (const auto& س : تاريخ_التتبع_) {
            ss << س.الطابع_الزمني << ","
               << س.موضع_الرأس.x << "," << س.موضع_الرأس.y << "," << س.موضع_الرأس.z << ","
               << س.موضع_يد_يسرى.x << "," << س.موضع_يد_يسرى.y << "," << س.موضع_يد_يسرى.z << ","
               << س.موضع_يد_يمنى.x << "," << س.موضع_يد_يمنى.y << "," << س.موضع_يد_يمنى.z << ","
               << س.قوة_قرصة_يسرى << "," << س.قوة_قرصة_يمنى << "\n";
        }
        
        return ss.str();
    }
    
    // تحليل الحركة
    float متوسط_سرعة_الرأس() const {
        if (تاريخ_التتبع_.size() < 2) return 0;
        
        float مجموع_سرعة = 0;
        for (size_t i = 1; i < تاريخ_التتبع_.size(); i++) {
            const auto& سابق = تاريخ_التتبع_[i-1].موضع_الرأس;
            const auto& حالي = تاريخ_التتبع_[i].موضع_الرأس;
            
            float dx = حالي.x - سابق.x;
            float dy = حالي.y - سابق.y;
            float dz = حالي.z - سابق.z;
            
            مجموع_سرعة += std::sqrt(dx*dx + dy*dy + dz*dz);
        }
        
        return مجموع_سرعة / (تاريخ_التتبع_.size() - 1);
    }
};

// ============== مصحح الاصطدام ==============

enum class شكل_اصطدام {
    صندوق,
    كرة,
    كبسولة,
    شعاع
};

struct حد_اصطدام {
    شكل_اصطدام الشكل;
    متجه3 الموضع;
    متجه3 الأبعاد;  // نصف الأبعاد للصندوق، نصف القطر للكرة
    bool نشط = true;
    uint32_t لون = 0x00FF00;  // أخضر افتراضي
};

class مصحح_الاصطدام {
private:
    std::vector<حد_اصطدام> الحدود_;
    bool عرض_نشط_ = true;
    
public:
    void إضافة_صندوق(const متجه3& موضع, const متجه3& نصف_أبعاد, uint32_t لون = 0x00FF00) {
        الحدود_.push_back({شكل_اصطدام::صندوق, موضع, نصف_أبعاد, true, لون});
    }
    
    void إضافة_كرة(const متجه3& موضع, float نصف_قطر, uint32_t لون = 0x00FF00) {
        الحدود_.push_back({شكل_اصطدام::كرة, موضع, {نصف_قطر, 0, 0}, true, لون});
    }
    
    void إضافة_شعاع(const متجه3& أصل, const متجه3& اتجاه, uint32_t لون = 0xFF0000) {
        الحدود_.push_back({شكل_اصطدام::شعاع, أصل, اتجاه, true, لون});
    }
    
    void مسح() { الحدود_.clear(); }
    
    void تبديل_العرض() { عرض_نشط_ = !عرض_نشط_; }
    bool عرض_نشط() const { return عرض_نشط_; }
    
    const std::vector<حد_اصطدام>& الحدود() const { return الحدود_; }
    
    // توليد أوامر رسم (للتكامل مع محرك الرسم)
    struct أمر_رسم_خط {
        متجه3 بداية;
        متجه3 نهاية;
        uint32_t لون;
    };
    
    std::vector<أمر_رسم_خط> توليد_أوامر_رسم() const {
        std::vector<أمر_رسم_خط> أوامر;
        
        if (!عرض_نشط_) return أوامر;
        
        for (const auto& ح : الحدود_) {
            if (!ح.نشط) continue;
            
            if (ح.الشكل == شكل_اصطدام::صندوق) {
                // رسم 12 خط للصندوق
                float x = ح.الأبعاد.x;
                float y = ح.الأبعاد.y;
                float z = ح.الأبعاد.z;
                
                // الوجه الأمامي
                أوامر.push_back({{ح.الموضع.x-x, ح.الموضع.y-y, ح.الموضع.z-z},
                                 {ح.الموضع.x+x, ح.الموضع.y-y, ح.الموضع.z-z}, ح.لون});
                أوامر.push_back({{ح.الموضع.x+x, ح.الموضع.y-y, ح.الموضع.z-z},
                                 {ح.الموضع.x+x, ح.الموضع.y+y, ح.الموضع.z-z}, ح.لون});
                أوامر.push_back({{ح.الموضع.x+x, ح.الموضع.y+y, ح.الموضع.z-z},
                                 {ح.الموضع.x-x, ح.الموضع.y+y, ح.الموضع.z-z}, ح.لون});
                أوامر.push_back({{ح.الموضع.x-x, ح.الموضع.y+y, ح.الموضع.z-z},
                                 {ح.الموضع.x-x, ح.الموضع.y-y, ح.الموضع.z-z}, ح.لون});
                
                // ... خطوط إضافية للوجوه الأخرى
            }
            else if (ح.الشكل == شكل_اصطدام::شعاع) {
                أوامر.push_back({ح.الموضع, 
                                 {ح.الموضع.x + ح.الأبعاد.x * 10,
                                  ح.الموضع.y + ح.الأبعاد.y * 10,
                                  ح.الموضع.z + ح.الأبعاد.z * 10},
                                 ح.لون});
            }
        }
        
        return أوامر;
    }
};

// ============== سجل الأحداث ==============

enum class نوع_حدث_تصحيح {
    معلومات,
    تحذير,
    خطأ,
    أداء,
    تتبع,
    إدخال
};

struct حدث_تصحيح {
    uint64_t الطابع_الزمني;
    نوع_حدث_تصحيح النوع;
    std::string الرسالة;
    std::string المصدر;
};

class سجل_الأحداث {
private:
    std::deque<حدث_تصحيح> الأحداث_;
    static constexpr size_t حجم_أقصى_ = 1000;
    
    std::map<نوع_حدث_تصحيح, bool> فلاتر_;
    
public:
    سجل_الأحداث() {
        // تفعيل جميع الفلاتر افتراضياً
        فلاتر_[نوع_حدث_تصحيح::معلومات] = true;
        فلاتر_[نوع_حدث_تصحيح::تحذير] = true;
        فلاتر_[نوع_حدث_تصحيح::خطأ] = true;
        فلاتر_[نوع_حدث_تصحيح::أداء] = true;
        فلاتر_[نوع_حدث_تصحيح::تتبع] = false;  // معطل افتراضياً (كثير)
        فلاتر_[نوع_حدث_تصحيح::إدخال] = false;
    }
    
    void إضافة(نوع_حدث_تصحيح نوع, const std::string& رسالة, const std::string& مصدر = "") {
        if (!فلاتر_[نوع]) return;
        
        حدث_تصحيح حدث;
        حدث.الطابع_الزمني = std::chrono::duration_cast<std::chrono::milliseconds>(
            std::chrono::system_clock::now().time_since_epoch()
        ).count();
        حدث.النوع = نوع;
        حدث.الرسالة = رسالة;
        حدث.المصدر = مصدر;
        
        الأحداث_.push_back(حدث);
        if (الأحداث_.size() > حجم_أقصى_) {
            الأحداث_.pop_front();
        }
    }
    
    void تعيين_فلتر(نوع_حدث_تصحيح نوع, bool مفعل) {
        فلاتر_[نوع] = مفعل;
    }
    
    void مسح() { الأحداث_.clear(); }
    
    std::string تنسيق() const {
        std::ostringstream ss;
        
        for (const auto& ح : الأحداث_) {
            // تنسيق الطابع الزمني
            uint64_t ثوان = ح.الطابع_الزمني / 1000;
            uint64_t ms = ح.الطابع_الزمني % 1000;
            
            ss << "[" << std::setw(6) << ثوان << "." << std::setfill('0') 
               << std::setw(3) << ms << std::setfill(' ') << "] ";
            
            // رمز النوع
            switch (ح.النوع) {
                case نوع_حدث_تصحيح::معلومات: ss << "ℹ "; break;
                case نوع_حدث_تصحيح::تحذير: ss << "⚠ "; break;
                case نوع_حدث_تصحيح::خطأ: ss << "✗ "; break;
                case نوع_حدث_تصحيح::أداء: ss << "⚡"; break;
                case نوع_حدث_تصحيح::تتبع: ss << "👁 "; break;
                case نوع_حدث_تصحيح::إدخال: ss << "🎮"; break;
            }
            
            if (!ح.المصدر.empty()) {
                ss << "[" << ح.المصدر << "] ";
            }
            
            ss << ح.الرسالة << "\n";
        }
        
        return ss.str();
    }
};

