extern "C" {

using namespace ص::أدوات::تصحيح_XR;

static مصحح_XR* مصحح_عام = nullptr;

int sad_xr_debug_init() {
    if (!مصحح_عام) {
        مصحح_عام = new مصحح_XR();
    }
    مصحح_عام->تفعيل();
    return 1;
}

void sad_xr_debug_shutdown() {
    if (مصحح_عام) {
        delete مصحح_عام;
        مصحح_عام = nullptr;
    }
}

void sad_xr_debug_frame_begin() {
    if (مصحح_عام) مصحح_عام->بدء_إطار();
}

void sad_xr_debug_frame_end() {
    if (مصحح_عام) مصحح_عام->إنهاء_إطار();
}

void sad_xr_debug_log(int نوع, const char* رسالة, const char* مصدر) {
    if (مصحح_عام) {
        مصحح_عام->سجل().إضافة(
            static_cast<نوع_حدث_تصحيح>(نوع),
            رسالة,
            مصدر ? مصدر : ""
        );
    }
}

void sad_xr_debug_draw_call(uint32_t مثلثات, uint32_t رؤوس) {
    if (مصحح_عام) {
        مصحح_عام->أداء().تسجيل_استدعاء_رسم(مثلثات, رؤوس);
    }
}

double sad_xr_debug_get_fps() {
    if (مصحح_عام) {
        return مصحح_عام->أداء().معدل_الإطارات();
    }
    return 0;
}

void sad_xr_debug_toggle_hud() {
    if (مصحح_عام) مصحح_عام->تبديل_HUD();
}

void sad_xr_debug_toggle_collision() {
    if (مصحح_عام) مصحح_عام->اصطدام().تبديل_العرض();
}

}  // extern "C"
