/// إنشاء ملف مشروع CMake للترجمة المتقاطعة
void أنشئ_CMakeLists(const إعدادات_iOS& إعدادات, const fs::path& مسار) {
    std::ofstream f(مسار / "CMakeLists.txt");
    f << "# ============================================\n"
      << "# CMakeLists.txt — " << إعدادات.اسم_التطبيق << "\n"
      << "# مُولَّد بواسطة sad-ios / Generated by sad-ios\n"
      << "# ============================================\n\n"
      << "cmake_minimum_required(VERSION 3.20)\n"
      << "project(" << إعدادات.اسم_التطبيق << " LANGUAGES CXX Swift)\n\n"
      << "set(CMAKE_OSX_DEPLOYMENT_TARGET \"" << إعدادات.أقل_إصدار_iOS << "\")\n"
      << "set(CMAKE_XCODE_ATTRIBUTE_PRODUCT_BUNDLE_IDENTIFIER "
      << "\"" << إعدادات.معرّف_الحزمة << "\")\n\n"
      << "# ملفات ص المُترجمة / Compiled Sad files\n"
      << "file(GLOB SAD_GENERATED_SOURCES \"generated/*.swift\")\n\n"
      << "add_executable(" << إعدادات.اسم_التطبيق << "\n"
      << "    " << إعدادات.اسم_التطبيق << "App.swift\n"
      << "    ContentView.swift\n"
      << "    ${SAD_GENERATED_SOURCES}\n"
      << ")\n\n"
      << "set_target_properties(" << إعدادات.اسم_التطبيق << " PROPERTIES\n"
      << "    MACOSX_BUNDLE TRUE\n"
      << "    MACOSX_BUNDLE_INFO_PLIST ${CMAKE_CURRENT_SOURCE_DIR}/Info.plist\n"
      << ")\n";
}

/// إنشاء ترويسة الجسر C/Swift / Generate C-Swift bridging header
void أنشئ_Bridging_Header(const إعدادات_iOS& إعدادات, const fs::path& مسار) {
    // (AR) ترويسة C للتوافق مع Swift
    std::ofstream h(مسار / (إعدادات.اسم_التطبيق + "-Bridging-Header.h"));
    h << "// ============================================\n"
      << "// " << إعدادات.اسم_التطبيق << "-Bridging-Header.h\n"
      << "// جسر C ↔ Swift — مُولَّد بواسطة sad-ios\n"
      << "// ============================================\n\n"
      << "#ifndef " << إعدادات.اسم_التطبيق << "_Bridging_Header_h\n"
      << "#define " << إعدادات.اسم_التطبيق << "_Bridging_Header_h\n\n"
      << "#include <stdbool.h>\n"
      << "#include <stdint.h>\n\n"
      << "// ===== واجهة لغة ص الأصلية / Sad Language Native Interface =====\n\n"
      << "/// تهيئة محرك لغة ص / Initialize Sad engine\n"
      << "bool sad_init(void);\n\n"
      << "/// تنفيذ كود لغة ص / Execute Sad code\n"
      << "/// @param code كود ص بترميز UTF-8 / UTF-8 encoded Sad code\n"
      << "/// @return نتيجة التنفيذ / Execution result (caller frees)\n"
      << "const char* sad_execute(const char* code);\n\n"
      << "/// تحرير نص مخصص / Free allocated string\n"
      << "void sad_free_string(const char* str);\n\n"
      << "// ===== دورة الحياة / Lifecycle =====\n\n"
      << "/// إيقاف مؤقت / Pause\n"
      << "void sad_on_pause(void);\n\n"
      << "/// استئناف / Resume\n"
      << "void sad_on_resume(void);\n\n"
      << "/// تدمير / Destroy\n"
      << "void sad_on_destroy(void);\n\n"
      << "/// حفظ الحالة / Save state\n"
      << "const char* sad_save_state(void);\n\n"
      << "/// استعادة الحالة / Restore state\n"
      << "void sad_restore_state(const char* state);\n\n"
      << "#endif\n";
    
    // (AR) تنفيذ C++ للجسر
    std::ofstream cpp(مسار / "SadBridge.cpp");
    cpp << "// ============================================\n"
        << "// SadBridge.cpp — تنفيذ جسر C ↔ Swift\n"
        << "// مُولَّد بواسطة sad-ios / Generated by sad-ios\n"
        << "// ============================================\n\n"
        << "#include \"" << إعدادات.اسم_التطبيق << "-Bridging-Header.h\"\n"
        << "#include <string>\n"
        << "#include <cstring>\n\n"
        << "static bool g_initialized = false;\n"
        << "static std::string g_savedState;\n\n"
        << "extern \"C\" {\n\n"
        << "bool sad_init(void) {\n"
        << "    g_initialized = true;\n"
        << "    return true;\n"
        << "}\n\n"
        << "const char* sad_execute(const char* code) {\n"
        << "    if (!code) return strdup(\"خطأ: كود فارغ\");\n"
        << "    try {\n"
        << "        std::string result = std::string(\"[sad] \") + code;\n"
        << "        return strdup(result.c_str());\n"
        << "    } catch (...) {\n"
        << "        return strdup(\"خطأ في التنفيذ\");\n"
        << "    }\n"
        << "}\n\n"
        << "void sad_free_string(const char* str) {\n"
        << "    free(const_cast<char*>(str));\n"
        << "}\n\n"
        << "void sad_on_pause(void) {\n"
        << "    // حفظ الموارد / Save resources\n"
        << "}\n\n"
        << "void sad_on_resume(void) {\n"
        << "    // استئناف الموارد / Resume resources\n"
        << "}\n\n"
        << "void sad_on_destroy(void) {\n"
        << "    g_initialized = false;\n"
        << "    g_savedState.clear();\n"
        << "}\n\n"
        << "const char* sad_save_state(void) {\n"
        << "    return strdup(\"{\\\"version\\\":\\\"1.0\\\"}\");\n"
        << "}\n\n"
        << "void sad_restore_state(const char* state) {\n"
        << "    if (state) g_savedState = state;\n"
        << "}\n\n"
        << "} // extern \"C\"\n";
    
    // (AR) غلاف Swift للجسر
    std::ofstream swift(مسار / "SadEngine.swift");
    swift << "// ============================================\n"
          << "// SadEngine.swift — واجهة Swift لمحرك لغة ص\n"
          << "// مُولَّد بواسطة sad-ios / Generated by sad-ios\n"
          << "// ============================================\n\n"
          << "import Foundation\n\n"
          << "/// محرك لغة ص — غلاف Swift للكود الأصلي\n"
          << "/// Sad Language Engine — Swift wrapper for native code\n"
          << "class SadEngine: ObservableObject {\n"
          << "    @Published var isInitialized = false\n"
          << "    @Published var lastResult: String = \"\"\n\n"
          << "    static let shared = SadEngine()\n\n"
          << "    private init() {\n"
          << "        isInitialized = sad_init()\n"
          << "    }\n\n"
          << "    /// تنفيذ كود لغة ص / Execute Sad code\n"
          << "    func execute(_ code: String) -> String {\n"
          << "        guard let result = sad_execute(code) else { return \"\" }\n"
          << "        let str = String(cString: result)\n"
          << "        sad_free_string(result)\n"
          << "        lastResult = str\n"
          << "        return str\n"
          << "    }\n\n"
          << "    // ===== دورة الحياة / Lifecycle =====\n\n"
          << "    func pause() { sad_on_pause() }\n"
          << "    func resume() { sad_on_resume() }\n\n"
          << "    func saveState() -> String {\n"
          << "        guard let state = sad_save_state() else { return \"\" }\n"
          << "        let str = String(cString: state)\n"
          << "        sad_free_string(state)\n"
          << "        return str\n"
          << "    }\n\n"
          << "    func restoreState(_ state: String) {\n"
          << "        sad_restore_state(state)\n"
          << "    }\n\n"
          << "    deinit {\n"
          << "        sad_on_destroy()\n"
          << "    }\n"
          << "}\n";
}

