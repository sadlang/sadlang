استورد "../src/lib.s" كـ مكتبة;
استورد "test_framework" كـ Test;

دالة اختبار_جمع() {
    نتيجة = مكتبة.جمع(2, 3);
    Test.assert_equal(نتيجة, 5, "جمع 2 + 3 يجب أن يساوي 5");
}

دالة اختبار_طرح() {
    نتيجة = مكتبة.طرح(5, 3);
    Test.assert_equal(نتيجة, 2, "طرح 5 - 3 يجب أن يساوي 2");
}

دالة اختبار_ضرب() {
    نتيجة = مكتبة.ضرب(4, 5);
    Test.assert_equal(نتيجة, 20, "ضرب 4 * 5 يجب أن يساوي 20");
}

دالة اختبار_قسمة() {
    نتيجة = مكتبة.قسمة(10, 2);
    Test.assert_equal(نتيجة, 5, "قسمة 10 / 2 يجب أن يساوي 5");
}

دالة اختبار_آلة_حاسبة() {
    آلة = مكتبة.آلة_حاسبة.جديد();
    نتيجة = آلة.جمع(5).طرح(2).احصل_النتيجة();
    Test.assert_equal(نتيجة, 3, "5 + (-2) يجب أن يساوي 3");
}

دالة تشغيل_الاختبارات() {
    Test.run("اختبار الجمع", اختبار_جمع);
    Test.run("اختبار الطرح", اختبار_طرح);
    Test.run("اختبار الضرب", اختبار_ضرب);
    Test.run("اختبار القسمة", اختبار_قسمة);
    Test.run("اختبار آلة حاسبة", اختبار_آلة_حاسبة);
}
