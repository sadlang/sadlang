استورد "gui" كـ واجهة;
استورد "file_system" كـ ملفات;

/**
 * Main application class
 */
صنف تطبيق {
    نافذة: واجهة.نافذة;
    محتوى: نص;
    
    دالة __إنشاء__() {
        // Create window
        هذا.نافذة = واجهة.نافذة({
            "title": "{{PROJECT_NAME}}",
            "width": 800,
            "height": 600,
            "resizable": true
        });
        
        هذا.محتوى = "";
        هذا.إعداد_القوائم();
        هذا.إعداد_الواجهة();
    }
    
    /**
     * Setup menus
     */
    دالة إعداد_القوائم() {
        // File menu
        قائمة_ملف = هذا.نافذة.إضافة_قائمة("ملف");
        قائمة_ملف.إضافة_عنصر("جديد", هذا.ملف_جديد);
        قائمة_ملف.إضافة_عنصر("فتح", هذا.فتح_ملف);
        قائمة_ملف.إضافة_عنصر("حفظ", هذا.حفظ_ملف);
        قائمة_ملف.إضافة_فاصل();
        قائمة_ملف.إضافة_عنصر("خروج", هذا.خروج);
        
        // Help menu
        قائمة_مساعدة = هذا.نافذة.إضافة_قائمة("مساعدة");
        قائمة_مساعدة.إضافة_عنصر("حول", هذا.عرض_حول);
    }
    
    /**
     * Setup UI
     */
    دالة إعداد_الواجهة() {
        // Main text area
        هذا.منطقة_نص = واجهة.منطقة_نص({
            "font_size": 14,
            "wrap": true
        });
        
        هذا.نافذة.إضافة_مكون(هذا.منطقة_نص);
        
        // Status bar
        هذا.شريط_حالة = واجهة.شريط_حالة();
        هذا.شريط_حالة.نص = "جاهز";
        هذا.نافذة.إضافة_شريط_حالة(هذا.شريط_حالة);
    }
    
    /**
     * New file
     */
    دالة ملف_جديد() {
        هذا.محتوى = "";
        هذا.منطقة_نص.نص = "";
        هذا.شريط_حالة.نص = "ملف جديد";
    }
    
    /**
     * Open file
     */
    دالة فتح_ملف() {
        مسار = واجهة.حوار_فتح_ملف();
        إذا (مسار) {
            هذا.محتوى = ملفات.اقرأ(مسار);
            هذا.منطقة_نص.نص = هذا.محتوى;
            هذا.شريط_حالة.نص = "تم فتح: " + مسار;
        }
    }
    
    /**
     * Save file
     */
    دالة حفظ_ملف() {
        مسار = واجهة.حوار_حفظ_ملف();
        إذا (مسار) {
            ملفات.اكتب(مسار, هذا.منطقة_نص.نص);
            هذا.شريط_حالة.نص = "تم الحفظ: " + مسار;
        }
    }
    
    /**
     * Show about dialog
     */
    دالة عرض_حول() {
        واجهة.حوار_معلومات(
            "حول {{PROJECT_NAME}}",
            "{{PROJECT_NAME}} v0.1.0\nتطبيق مكتبي مبني بلغة ص"
        );
    }
    
    /**
     * Exit application
     */
    دالة خروج() {
        هذا.نافذة.أغلق();
    }
    
    /**
     * Run application
     */
    دالة تشغيل() {
        هذا.نافذة.اعرض();
    }
}

/**
 * Main entry point
 */
دالة رئيسية() {
    تطبيق = تطبيق.جديد();
    تطبيق.تشغيل();
    أرجع 0;
}
