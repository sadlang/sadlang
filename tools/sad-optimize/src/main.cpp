/**
 * نقطة الدخول
 */
int main(int argc, char* argv[]) {
    // تحليل الأوامر
    محلل_أوامر محلل;
    auto خيارات = محلل.حلل(argc, argv);
    
    // معالجة الأوامر الخاصة
    if (خيارات.مساعدة) {
        اعرض_مساعدة();
        return 0;
    }
    
    if (خيارات.إصدار) {
        اعرض_إصدار();
        return 0;
    }
    
    // تحقق من وجود ملفات
    if (خيارات.الملفات.empty()) {
        std::cerr << "خطأ: لم تُحدد أي ملفات" << std::endl;
        std::cerr << "استخدم 'ص حسّن --مساعدة' لعرض المساعدة" << std::endl;
        return 1;
    }
    
    // المحرك
    محرك_تحسين محرك;
    
    // معالجة الملفات
    int إجمالي_اقتراحات = 0;
    int إجمالي_مُطبَّقة = 0;
    double إجمالي_تحسين = 0;
    
    for (const auto& ملف : خيارات.الملفات) {
        // تحقق من الملف/المجلد
        std::filesystem::path مسار(ملف);
        
        std::vector<std::string> ملفات_للمعالجة;
        
        if (std::filesystem::is_directory(مسار)) {
            // جمع كل ملفات .ص
            for (const auto& entry : std::filesystem::recursive_directory_iterator(مسار)) {
                if (entry.path().extension() == ".ص" || 
                    entry.path().extension() == ".sad") {
                    ملفات_للمعالجة.push_back(entry.path().string());
                }
            }
        } else if (std::filesystem::exists(مسار)) {
            ملفات_للمعالجة.push_back(ملف);
        } else {
            std::cerr << "تحذير: الملف غير موجود: " << ملف << std::endl;
            continue;
        }
        
        // معالجة كل ملف
        for (const auto& ملف_حالي : ملفات_للمعالجة) {
            auto نتيجة = محرك.حلل_ملف(ملف_حالي, خيارات);
            
            إجمالي_اقتراحات += نتيجة.عدد_الاقتراحات;
            إجمالي_تحسين = std::max(إجمالي_تحسين, نتيجة.التحسين_المتوقع);
            
            if (خيارات.تطبيق) {
                if (محرك.طبّق(ملف_حالي, خيارات)) {
                    إجمالي_مُطبَّقة += نتيجة.عدد_الاقتراحات;
                }
            }
        }
    }
    
    // عرض الملخص
    if (!خيارات.صامت) {
        std::cout << "\n";
        std::cout << "╔════════════════════════════════════════╗" << std::endl;
        std::cout << "║              ملخص التحسين              ║" << std::endl;
        std::cout << "╠════════════════════════════════════════╣" << std::endl;
        std::cout << "║ الاقتراحات: " << إجمالي_اقتراحات << std::endl;
        
        if (خيارات.تطبيق) {
            std::cout << "║ المُطبَّقة: " << إجمالي_مُطبَّقة << std::endl;
        }
        
        std::cout << "║ التحسين المتوقع: " << إجمالي_تحسين << "%" << std::endl;
        std::cout << "╚════════════════════════════════════════╝" << std::endl;
    }
    
    // حفظ التقرير
    if (!خيارات.ملف_تقرير.empty()) {
        std::ofstream تقرير(خيارات.ملف_تقرير);
        if (تقرير) {
            // في الإنتاج: كتابة التقرير الكامل
            تقرير << "تقرير تحسين الأداء" << std::endl;
            std::cout << "✓ تم حفظ التقرير: " << خيارات.ملف_تقرير << std::endl;
        }
    }
    
    return 0;
}

