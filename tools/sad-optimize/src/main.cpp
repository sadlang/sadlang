/**
 * خيارات سطر الأوامر
 */
struct خيارات_أمر {
    std::vector<std::string> الملفات;
    
    // الأوضاع
    bool تحليل = true;
    bool تطبيق = false;
    bool تلقائي = false;
    bool تفاعلي = false;
    
    // الإخراج
    std::string ملف_تقرير;
    std::string تنسيق = "نص";  // نص، json، html
    
    // الخيارات
    bool صامت = false;
    bool مُفصَّل = false;
    int أقصى_اقتراحات = 10;
    double حد_ثقة = 0.5;
    
    // المساعدة
    bool مساعدة = false;
    bool إصدار = false;
};

/**
 * محلل سطر الأوامر
 */
class محلل_أوامر {
public:
    خيارات_أمر حلل(int argc, char* argv[]) {
        خيارات_أمر خيارات;
        
        for (int i = 1; i < argc; i++) {
            std::string arg = argv[i];
            
            if (arg == "--مساعدة" || arg == "-م" || arg == "--help" || arg == "-h") {
                خيارات.مساعدة = true;
            }
            else if (arg == "--إصدار" || arg == "-ن" || arg == "--version" || arg == "-v") {
                خيارات.إصدار = true;
            }
            else if (arg == "--تلقائي" || arg == "--auto") {
                خيارات.تلقائي = true;
            }
            else if (arg == "--طبّق" || arg == "--apply") {
                خيارات.تطبيق = true;
            }
            else if (arg == "--تفاعلي" || arg == "--interactive" || arg == "-i") {
                خيارات.تفاعلي = true;
            }
            else if (arg == "--صامت" || arg == "--quiet" || arg == "-q") {
                خيارات.صامت = true;
            }
            else if (arg == "--مُفصَّل" || arg == "--verbose") {
                خيارات.مُفصَّل = true;
            }
            else if (arg == "--تقرير" || arg == "--report" || arg == "-o") {
                if (i + 1 < argc) {
                    خيارات.ملف_تقرير = argv[++i];
                }
            }
            else if (arg == "--تنسيق" || arg == "--format" || arg == "-f") {
                if (i + 1 < argc) {
                    خيارات.تنسيق = argv[++i];
                }
            }
            else if (arg == "--حد-ثقة") {
                if (i + 1 < argc) {
                    خيارات.حد_ثقة = std::stod(argv[++i]);
                }
            }
            else if (arg == "--أقصى") {
                if (i + 1 < argc) {
                    خيارات.أقصى_اقتراحات = std::stoi(argv[++i]);
                }
            }
            else if (arg[0] != '-') {
                خيارات.الملفات.push_back(arg);
            }
        }
        
        return خيارات;
    }
};

