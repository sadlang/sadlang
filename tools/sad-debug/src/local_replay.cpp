/**
 * نقطة في التسجيلة
 */
struct نقطة_تسجيل {
    std::string الخدمة;
    std::string العملية;
    std::string المدخلات_json;
    std::string المخرجات_json;
    double المدة_ms;
    std::string الحالة;
    std::string رسالة_الخطأ;
};

/**
 * تسجيلة طلب كاملة
 */
struct تسجيلة_طلب {
    std::string معرف_البصمة;
    std::string تاريخ_التسجيل;
    std::string البيئة;        // إنتاج، تجريبي
    std::vector<نقطة_تسجيل> النقاط;
    std::map<std::string, std::string> المتغيرات_البيئية;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُعيد التشغيل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🔄 مُعيد التشغيل المحلي
 */
class معيد_تشغيل {
public:
    using معالج_خدمة = std::function<std::string(const std::string&)>;
    
    /**
     * تسجيل معالج خدمة
     */
    void سجل_خدمة(const std::string& اسم, معالج_خدمة معالج) {
        المعالجات_[اسم] = معالج;
    }
    
    /**
     * تحميل تسجيلة من ملف
     */
    bool حمل(const std::string& مسار_ملف) {
        std::ifstream ملف(مسار_ملف);
        if (!ملف.is_open()) {
            std::cerr << "❌ لا يمكن فتح الملف: " << مسار_ملف << std::endl;
            return false;
        }
        
        // قراءة JSON (مبسط)
        std::stringstream buffer;
        buffer << ملف.rdbuf();
        
        // TODO: تحليل JSON الحقيقي
        التسجيلة_.معرف_البصمة = "loaded-trace";
        
        std::cout << "✅ تم تحميل التسجيلة: " << مسار_ملف << std::endl;
        return true;
    }
    
    /**
     * إعادة التشغيل
     */
    void أعد_التشغيل(bool خطوة_خطوة = false) {
        std::cout << "\n🔄 بدء إعادة التشغيل...\n" << std::endl;
        std::cout << "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n";
        
        int رقم_النقطة = 1;
        
        for (const auto& نقطة : التسجيلة_.النقاط) {
            std::cout << "\n📍 نقطة " << رقم_النقطة++ << ": " 
                      << نقطة.الخدمة << "::" << نقطة.العملية << std::endl;
            std::cout << "   المدخلات: " << نقطة.المدخلات_json << std::endl;
            
            // تنفيذ محلي
            auto it = المعالجات_.find(نقطة.الخدمة);
            if (it != المعالجات_.end()) {
                try {
                    std::string نتيجة_محلية = it->second(نقطة.المدخلات_json);
                    
                    std::cout << "   ─────────────────────────────────────────────\n";
                    std::cout << "   النتيجة الأصلية: " << نقطة.المخرجات_json << std::endl;
                    std::cout << "   النتيجة المحلية: " << نتيجة_محلية << std::endl;
                    
                    if (نقطة.المخرجات_json == نتيجة_محلية) {
                        std::cout << "   ✅ متطابق!\n";
                    } else {
                        std::cout << "   ⚠️  مختلف - قد يكون هذا مصدر المشكلة\n";
                    }
                } catch (const std::exception& e) {
                    std::cout << "   ❌ خطأ في التنفيذ المحلي: " << e.what() << std::endl;
                }
            } else {
                std::cout << "   ⏭️  لا يوجد معالج محلي - تخطي\n";
            }
            
            if (خطوة_خطوة) {
                std::cout << "\n   اضغط Enter للمتابعة...";
                std::cin.get();
            }
        }
        
        std::cout << "\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n";
        std::cout << "✅ انتهت إعادة التشغيل\n" << std::endl;
    }
    
    /**
     * مقارنة النتائج
     */
    void قارن() const {
        std::cout << "\n📊 تقرير المقارنة\n";
        std::cout << "════════════════════════════════════════════════════\n\n";
        
        int متطابقة = 0;
        int مختلفة = 0;
        int أخطاء = 0;
        
        for (const auto& نقطة : التسجيلة_.النقاط) {
            if (نقطة.الحالة == "نجاح") {
                متطابقة++;
            } else if (نقطة.الحالة == "فشل") {
                أخطاء++;
            } else {
                مختلفة++;
            }
        }
        
        std::cout << "  ✅ نقاط متطابقة: " << متطابقة << std::endl;
        std::cout << "  ⚠️  نقاط مختلفة: " << مختلفة << std::endl;
        std::cout << "  ❌ نقاط فاشلة: " << أخطاء << std::endl;
        std::cout << "\n════════════════════════════════════════════════════\n";
    }
    
private:
    تسجيلة_طلب التسجيلة_;
    std::map<std::string, معالج_خدمة> المعالجات_;
};

