int main(int argc, char* argv[]) {
    if (argc < 2) {
        اطبع_المساعدة();
        return 1;
    }
    
    std::string أمر = argv[1];
    معيد_تشغيل معيد;
    
    if (أمر == "تحميل" || أمر == "load") {
        if (argc < 3) {
            std::cerr << "❌ يجب تحديد معرف البصمة" << std::endl;
            return 1;
        }
        
        std::string معرف = argv[2];
        std::string مسار = "traces/" + معرف + ".json";
        
        if (!معيد.حمل(مسار)) {
            return 1;
        }
        
    } else if (أمر == "أعد" || أمر == "replay") {
        bool خطوة_خطوة = false;
        
        for (int i = 2; i < argc; i++) {
            std::string خيار = argv[i];
            if (خيار == "--خطوة-خطوة" || خيار == "--step") {
                خطوة_خطوة = true;
            }
        }
        
        معيد.أعد_التشغيل(خطوة_خطوة);
        
    } else if (أمر == "قارن" || أمر == "compare") {
        معيد.قارن();
        
    } else if (أمر == "-h" || أمر == "--help" || أمر == "مساعدة") {
        اطبع_المساعدة();
        
    } else {
        std::cerr << "❌ أمر غير معروف: " << أمر << std::endl;
        اطبع_المساعدة();
        return 1;
    }
    
    return 0;
}
