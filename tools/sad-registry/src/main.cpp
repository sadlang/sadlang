/**
 * @brief نقطة البدء الرئيسية لخادم مستودع الحزم
 *
 * تسلسل التشغيل:
 *   ١. إعداد وحدة التحكم (UTF-8 + ألوان)
 *   ٢. عرض الشعار
 *   ٣. تحليل خيارات سطر الأوامر
 *   ٤. إنشاء مجلدات البيانات
 *   ٥. تهيئة قاعدة البيانات
 *   ٦. تهيئة مخزن الكائنات
 *   ٧. تهيئة محرك البحث العربي
 *   ٨. تهيئة نظام المصادقة
 *   ٩. إعداد نقاط API
 *   ١٠. تشغيل الخادم والبدء بالاستماع
 */
int main(int argc, char* argv[]) {
    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ١: إعداد وحدة التحكم
    // ─────────────────────────────────────────────────────────────────────
    setup_console();

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٢: عرض الشعار
    // ─────────────────────────────────────────────────────────────────────
    print_banner();

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٣: تحليل خيارات سطر الأوامر
    // ─────────────────────────────────────────────────────────────────────
    ServerConfig config = parse_args(argc, argv);

    std::cout << "  ⚙  إعدادات التشغيل:\n";
    std::cout << "     المنفذ: " << config.port << "\n";
    std::cout << "     العنوان: " << config.host << "\n";
    std::cout << "     قاعدة البيانات: " << config.db_path << "\n";
    std::cout << "     مجلد البيانات: " << config.data_dir << "\n";
    std::cout << "\n";

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٤: إنشاء مجلدات البيانات
    // ─────────────────────────────────────────────────────────────────────
    // نتأكد من وجود المجلدات اللازمة قبل البدء
    try {
        fs::create_directories(config.data_dir);
        fs::create_directories(config.data_dir + "/blobs");
        fs::create_directories(config.data_dir + "/temp");
        std::cout << "  ✓ مجلدات البيانات جاهزة\n";
    } catch (const std::exception& e) {
        std::cerr << "  ✗ فشل إنشاء مجلدات البيانات: " << e.what() << "\n";
        return 1;
    }

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٥: تهيئة قاعدة البيانات
    // ─────────────────────────────────────────────────────────────────────
    // نفتح اتصالاً بقاعدة البيانات ونُنفّذ مخطط الجداول إذا لم يكن موجوداً
    std::cout << "  ⏳ تهيئة قاعدة البيانات...\n";

    auto database = std::make_shared<sad::registry::Database>(config.db_path);
    if (!database->initialize()) {
        std::cerr << "  ✗ فشل تهيئة قاعدة البيانات!\n";
        std::cerr << "    تأكد من صلاحيات الكتابة على المسار: " << config.db_path << "\n";
        return 1;
    }
    std::cout << "  ✓ قاعدة البيانات جاهزة\n";

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٦: تهيئة مخزن الكائنات
    // ─────────────────────────────────────────────────────────────────────
    // مخزن الكائنات يُدير ملفات الحزم المضغوطة (ZIP/tar.gz)
    // يستخدم تخزين محتوى-موجّه (Content-Addressable Storage)
    std::string blobs_dir = config.data_dir + "/blobs";
    auto blob_store = std::make_shared<sad::registry::BlobStore>(blobs_dir);
    if (!blob_store->initialize()) {
        std::cerr << "  ✗ فشل تهيئة مخزن الكائنات!\n";
        return 1;
    }
    std::cout << "  ✓ مخزن الكائنات جاهز\n";

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٧: تهيئة محرك البحث العربي
    // ─────────────────────────────────────────────────────────────────────
    // محرك البحث يفهم الجذور العربية والتشكيل والمترادفات
    auto arabic_search = std::make_shared<sad::registry::ArabicSearchEngine>(database);
    arabic_search->initialize();
    std::cout << "  ✓ محرك البحث العربي جاهز\n";

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٨: تهيئة نظام المصادقة
    // ─────────────────────────────────────────────────────────────────────
    auto auth = std::make_shared<sad::registry::AuthManager>(database);
    std::cout << "  ✓ نظام المصادقة جاهز\n";

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ٩: إعداد خادم HTTP ونقاط API
    // ─────────────────────────────────────────────────────────────────────
    // نُنشئ الخادم ونسجّل جميع نقاط الوصول (API endpoints)
    sad::registry::HttpServer server(config.host, config.port);
    g_server = &server;

    // تسجيل مجلد الملفات الثابتة (واجهة الويب)
    server.set_static_dir(config.web_dir);

    // إعداد نقاط API
    sad::registry::ApiRoutes api(database, blob_store, arabic_search, auth);
    api.register_routes(server);

    std::cout << "  ✓ نقاط API مسجلة\n";

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ١٠: تسجيل معالج الإيقاف الآمن
    // ─────────────────────────────────────────────────────────────────────
    std::signal(SIGINT, signal_handler);
    std::signal(SIGTERM, signal_handler);

    // ─────────────────────────────────────────────────────────────────────
    // الخطوة ١١: تشغيل الخادم!
    // ─────────────────────────────────────────────────────────────────────
    std::cout << "\n";
    std::cout << "╔═══════════════════════════════════════════════════════════╗\n";
    std::cout << "║  ▶  الخادم يعمل على: http://" << config.host << ":" << config.port << "              ║\n";
    std::cout << "║  📦 واجهة الويب: http://localhost:" << config.port << "                  ║\n";
    std::cout << "║  📡 API: http://localhost:" << config.port << "/api/v1/              ║\n";
    std::cout << "║                                                           ║\n";
    std::cout << "║  اضغط Ctrl+C للإيقاف                                     ║\n";
    std::cout << "╚═══════════════════════════════════════════════════════════╝\n";
    std::cout << "\n";

    // بدء الاستماع - هذا الاستدعاء يحجب (blocking) حتى يتم إيقاف الخادم
    if (!server.start()) {
        std::cerr << "  ✗ فشل تشغيل الخادم على المنفذ " << config.port << "\n";
        std::cerr << "    تأكد من أن المنفذ غير مستخدم من قبل برنامج آخر.\n";
        return 1;
    }

    // ─────────────────────────────────────────────────────────────────────
    // التنظيف والإغلاق
    // ─────────────────────────────────────────────────────────────────────
    std::cout << "\n  ⏹  تم إيقاف الخادم بأمان.\n";
    std::cout << "  الحمد لله رب العالمين.\n\n";

    database->close();
    g_server = nullptr;

    return 0;
}
