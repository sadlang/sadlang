/**
 * @brief إعداد وحدة التحكم لدعم UTF-8 والألوان على ويندوز
 *
 * على ويندوز، وحدة التحكم الافتراضية لا تدعم UTF-8 بشكل صحيح.
 * هذه الدالة:
 *   ١. تحوّل صفحة الترميز إلى UTF-8 (65001)
 *   ٢. تفعّل معالجة تسلسلات ANSI للألوان
 *   ٣. تضبط الخط على خط يدعم العربية (إن أمكن)
 */
static void setup_console() {
#ifdef _WIN32
    // تفعيل UTF-8 في وحدة التحكم
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // تفعيل ألوان ANSI
    HANDLE hOut = GetStdHandle(STD_OUTPUT_HANDLE);
    if (hOut != INVALID_HANDLE_VALUE) {
        DWORD dwMode = 0;
        if (GetConsoleMode(hOut, &dwMode)) {
            dwMode |= ENABLE_VIRTUAL_TERMINAL_PROCESSING;
            SetConsoleMode(hOut, dwMode);
        }
    }
#endif
}

/**
 * @brief عرض شعار الخادم عند بدء التشغيل
 *
 * يعرض شعار فني مع معلومات الإصدار واسم المشروع.
 * الشعار يظهر بالعربية والإنجليزية.
 */
static void print_banner() {
    // ألوان ANSI
    const char* CYAN    = "\033[36m";
    const char* GREEN   = "\033[32m";
    const char* YELLOW  = "\033[33m";
    const char* BOLD    = "\033[1m";
    const char* RESET   = "\033[0m";

    std::cout << BOLD << CYAN;
    std::cout << R"(
  ╔═══════════════════════════════════════════════════════════╗
  ║                                                           ║
  ║     ███████╗    ╔══════════════════════════════════╗      ║
  ║     ██╔════╝    ║  مستودع حزم لغة ص               ║      ║
  ║     ███████╗    ║  Sad Language Package Registry    ║      ║
  ║     ╚════██║    ╚══════════════════════════════════╝      ║
  ║     ███████║                                              ║
  ║     ╚══════╝                                              ║
  ║                                                           ║
  ╚═══════════════════════════════════════════════════════════╝
)" << RESET;

    std::cout << "  " << GREEN << "الإصدار: " << SERVER_VERSION << RESET;
    std::cout << "  │  ";
    std::cout << YELLOW << "بسم الله الرحمن الرحيم" << RESET;
    std::cout << "\n\n";
}

/**
 * @brief عرض رسالة المساعدة
 *
 * تعرض جميع خيارات سطر الأوامر المتاحة مع شرح لكل منها.
 */
static void print_help() {
    std::cout << "الاستخدام: sad-registry [خيارات]\n\n";
    std::cout << "الخيارات:\n";
    std::cout << "  --port <رقم>      منفذ الاستماع (افتراضي: " << DEFAULT_PORT << ")\n";
    std::cout << "  --host <عنوان>    عنوان الاستماع (افتراضي: " << DEFAULT_HOST << ")\n";
    std::cout << "  --db <مسار>       مسار قاعدة البيانات (افتراضي: " << DEFAULT_DB_PATH << ")\n";
    std::cout << "  --data <مجلد>     مجلد البيانات (افتراضي: " << DEFAULT_DATA_DIR << ")\n";
    std::cout << "  --web <مجلد>      مجلد واجهة الويب (افتراضي: " << DEFAULT_WEB_DIR << ")\n";
    std::cout << "  --verbose          وضع الإسهاب\n";
    std::cout << "  --help             عرض هذه المساعدة\n";
    std::cout << "\nأمثلة:\n";
    std::cout << "  sad-registry                              # تشغيل بالإعدادات الافتراضية\n";
    std::cout << "  sad-registry --port 3000                  # تشغيل على المنفذ ٣٠٠٠\n";
    std::cout << "  sad-registry --db ./mydata/pkgs.db        # مسار قاعدة بيانات مخصص\n";
}

/**
 * @brief تحليل خيارات سطر الأوامر
 * @param argc عدد المعاملات
 * @param argv مصفوفة المعاملات
 * @return إعدادات الخادم المُملأة من خيارات سطر الأوامر
 *
 * يمر على جميع المعاملات ويملأ هيكل الإعدادات.
 * الخيارات غير المعروفة تُتَجاهل مع طباعة تحذير.
 */
static ServerConfig parse_args(int argc, char* argv[]) {
    ServerConfig config;

    for (int i = 1; i < argc; i++) {
        std::string arg = argv[i];

        if (arg == "--help" || arg == "-h" || arg == "--مساعدة") {
            print_help();
            std::exit(0);
        }
        else if ((arg == "--port" || arg == "--منفذ") && i + 1 < argc) {
            config.port = std::atoi(argv[++i]);
        }
        else if ((arg == "--host" || arg == "--عنوان") && i + 1 < argc) {
            config.host = argv[++i];
        }
        else if ((arg == "--db" || arg == "--قاعدة") && i + 1 < argc) {
            config.db_path = argv[++i];
        }
        else if ((arg == "--data" || arg == "--بيانات") && i + 1 < argc) {
            config.data_dir = argv[++i];
        }
        else if ((arg == "--web" || arg == "--ويب") && i + 1 < argc) {
            config.web_dir = argv[++i];
        }
        else if (arg == "--verbose" || arg == "--تفصيل") {
            config.verbose = true;
        }
        else {
            std::cerr << "⚠ خيار غير معروف: " << arg << "\n";
        }
    }

    return config;
}

// ═══════════════════════════════════════════════════════════════════════════════
