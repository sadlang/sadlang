/// المنفذ الافتراضي للخادم
static constexpr int DEFAULT_PORT = 8080;

/// عنوان الاستماع الافتراضي (جميع العناوين)
static const std::string DEFAULT_HOST = "0.0.0.0";

/// مسار قاعدة البيانات الافتراضي
static const std::string DEFAULT_DB_PATH = "./data/packages.db";

/// مسار مجلد البيانات الافتراضي
static const std::string DEFAULT_DATA_DIR = "./data";

/// مسار مجلد واجهة الويب الافتراضي
static const std::string DEFAULT_WEB_DIR = "./web";

/// إصدار الخادم
static const std::string SERVER_VERSION = "1.0.0";

// ═══════════════════════════════════════════════════════════════════════════════
// هيكل إعدادات الخادم
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * @struct إعدادات_الخادم
 * @brief يحتوي على جميع إعدادات التشغيل التي يمكن تخصيصها عبر سطر الأوامر
 *
 * عند بدء التشغيل، يتم ملء هذا الهيكل من:
 *   ١. القيم الافتراضية
 *   ٢. ملف الإعدادات (إن وُجد)
 *   ٣. خيارات سطر الأوامر (الأولوية الأعلى)
 */
struct ServerConfig {
    int port = DEFAULT_PORT;                 // منفذ الاستماع
    std::string host = DEFAULT_HOST;         // عنوان الاستماع
    std::string db_path = DEFAULT_DB_PATH;   // مسار قاعدة البيانات
    std::string data_dir = DEFAULT_DATA_DIR; // مجلد البيانات
    std::string web_dir = DEFAULT_WEB_DIR;   // مجلد الويب
    bool verbose = false;                    // وضع الإسهاب (طباعة تفاصيل أكثر)
};

// ═══════════════════════════════════════════════════════════════════════════════
// متغيرات عامة
// ═══════════════════════════════════════════════════════════════════════════════

/// مؤشر الخادم العام (للإيقاف الآمن عند Ctrl+C)
static sad::registry::HttpServer* g_server = nullptr;

/// علم الإيقاف - يتحول إلى true عند طلب الإيقاف
static volatile bool g_shutdown_requested = false;

// ═══════════════════════════════════════════════════════════════════════════════
// معالج إشارة الإيقاف
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * @brief معالج إشارة SIGINT (Ctrl+C) و SIGTERM
 *
 * عند ضغط المستخدم Ctrl+C أو إرسال إشارة إيقاف:
 *   ١. يطبع رسالة الإيقاف
 *   ٢. يرفع علم الإيقاف
 *   ٣. يطلب من الخادم التوقف عن قبول طلبات جديدة
 *   ٤. ينتظر انتهاء الطلبات الحالية قبل الإغلاق
 */
static void signal_handler(int signum) {
    (void)signum;
    if (!g_shutdown_requested) {
        g_shutdown_requested = true;
        std::cout << "\n\n";
        std::cout << "╔═══════════════════════════════════════════╗\n";
        std::cout << "║  ⏹  جارٍ إيقاف الخادم بأمان...           ║\n";
        std::cout << "╚═══════════════════════════════════════════╝\n";

        if (g_server) {
            g_server->stop();
        }
    }
}

