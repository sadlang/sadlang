/**
 * محلل خيارات الأمر
 */
class محلل_خيارات_codegen {
public:
    إعدادات_توليد حلل(int argc, char* argv[]) {
        إعدادات_توليد إعدادات;
        
        for (int i = 1; i < argc; i++) {
            std::string arg = argv[i];
            
            if (arg.rfind("--من=", 0) == 0 || arg.rfind("--from=", 0) == 0) {
                إعدادات.مسار_الإدخال = arg.substr(arg.find('=') + 1);
            }
            else if (arg.rfind("--إلى=", 0) == 0 || arg.rfind("--to=", 0) == 0) {
                إعدادات.مسار_الإخراج = arg.substr(arg.find('=') + 1);
            }
            else if (arg.rfind("--نوع=", 0) == 0 || arg.rfind("--type=", 0) == 0) {
                std::string نوع = arg.substr(arg.find('=') + 1);
                if (نوع == "openapi" || نوع == "rest") {
                    إعدادات.المصدر = نوع_مصدر::openapi;
                }
                else if (نوع == "graphql" || نوع == "gql") {
                    إعدادات.المصدر = نوع_مصدر::graphql;
                }
                else if (نوع == "protobuf" || نوع == "proto") {
                    إعدادات.المصدر = نوع_مصدر::protobuf;
                }
            }
            else if (arg == "--عميل" || arg == "--client") {
                إعدادات.النمط = نمط_توليد::عميل;
            }
            else if (arg == "--خادم" || arg == "--server") {
                إعدادات.النمط = نمط_توليد::خادم;
            }
            else if (arg == "--بلا-توثيق" || arg == "--no-docs") {
                إعدادات.توثيق = false;
            }
            else if (arg == "--متزامن" || arg == "--sync") {
                إعدادات.غير_متزامن = false;
            }
        }
        
        return إعدادات;
    }
};

