/**
 * مولد كود ص من النموذج الموحد
 */
class مولد_كود_ص {
public:
    مولد_كود_ص(const إعدادات_توليد& إعدادات)
        : الإعدادات_(إعدادات) {}
    
    /**
     * توليد الكود
     */
    std::string ولّد(const نموذج_موحد& نموذج) {
        std::string كود;
        
        // ترويسة الملف
        كود += ولّد_ترويسة(نموذج);
        
        // الأنواع
        كود += "// ══════════════════════════════════════════════════\n";
        كود += "//                      الأنواع\n";
        كود += "// ══════════════════════════════════════════════════\n\n";
        
        for (const auto& نوع : نموذج.الأنواع) {
            كود += ولّد_نوع(نوع);
        }
        
        // الخدمات
        كود += "// ══════════════════════════════════════════════════\n";
        كود += "//                      الخدمات\n";
        كود += "// ══════════════════════════════════════════════════\n\n";
        
        for (const auto& خدمة : نموذج.الخدمات) {
            if (الإعدادات_.النمط == نمط_توليد::عميل ||
                الإعدادات_.النمط == نمط_توليد::كلاهما) {
                كود += ولّد_عميل(خدمة);
            }
            
            if (الإعدادات_.النمط == نمط_توليد::خادم ||
                الإعدادات_.النمط == نمط_توليد::كلاهما) {
                كود += ولّد_خادم(خدمة);
            }
        }
        
        return كود;
    }
    
private:
    std::string ولّد_ترويسة(const نموذج_موحد& نموذج) {
        std::string كود;
        
        كود += "/**\n";
        كود += " * ═══════════════════════════════════════════════════════════\n";
        كود += " * " + نموذج.العنوان + "\n";
        كود += " * الإصدار: " + نموذج.الإصدار + "\n";
        if (!نموذج.الوصف.empty()) {
            كود += " * " + نموذج.الوصف + "\n";
        }
        كود += " * \n";
        كود += " * ⚠️ هذا الملف مُولَّد تلقائياً - لا تعدله يدوياً!\n";
        كود += " * ═══════════════════════════════════════════════════════════\n";
        كود += " */\n\n";
        
        // الاستيرادات
        كود += "استورد \"شبكة/http\"\n";
        if (الإعدادات_.غير_متزامن) {
            كود += "استورد \"تزامن/مهام\"\n";
        }
        كود += "\n";
        
        return كود;
    }
    
    std::string ولّد_نوع(const نوع_مُعرَّف& نوع) {
        std::string كود;
        
        // تعليق توثيقي
        if (الإعدادات_.توثيق && !نوع.الوصف.empty()) {
            كود += "/**\n";
            كود += " * " + نوع.الوصف + "\n";
            كود += " */\n";
        }
        
        // تعداد
        if (!نوع.قيم_التعداد.empty()) {
            كود += "تعداد " + تطبيق_اسم(نوع.الاسم_عربي.empty() ? نوع.الاسم : نوع.الاسم_عربي) + ":\n";
            for (const auto& قيمة : نوع.قيم_التعداد) {
                كود += "    " + قيمة + "\n";
            }
            كود += "\n";
            return كود;
        }
        
        // بنية
        كود += "بنية " + تطبيق_اسم(نوع.الاسم_عربي.empty() ? نوع.الاسم : نوع.الاسم_عربي) + ":\n";
        
        for (const auto& حقل : نوع.الحقول) {
            // تعليق للحقل
            if (الإعدادات_.توثيق && !حقل.الوصف.empty()) {
                كود += "    // " + حقل.الوصف + "\n";
            }
            
            std::string اسم_حقل = حقل.الاسم_عربي.empty() ? 
                قاموس_ترجمة::المثيل().ترجم(حقل.الاسم) : حقل.الاسم_عربي;
            
            كود += "    " + اسم_حقل + ": " + ترجم_نوع(حقل);
            
            if (!حقل.القيمة_الافتراضية.empty()) {
                كود += " = " + حقل.القيمة_الافتراضية;
            }
            
            كود += "\n";
        }
        
        كود += "\n";
        return كود;
    }
    
    std::string ولّد_عميل(const خدمة_موحدة& خدمة) {
        std::string كود;
        
        std::string اسم = خدمة.الاسم_عربي.empty() ?
            قاموس_ترجمة::المثيل().ترجم(خدمة.الاسم) : خدمة.الاسم_عربي;
        
        if (الإعدادات_.توثيق && !خدمة.الوصف.empty()) {
            كود += "/**\n";
            كود += " * " + خدمة.الوصف + "\n";
            كود += " */\n";
        }
        
        كود += "صنف عميل_" + تطبيق_اسم(اسم) + ":\n";
        كود += "    // العنوان الأساسي للخدمة\n";
        كود += "    _عنوان: نص\n\n";
        
        // المُنشئ
        كود += "    دالة جديد(عنوان: نص = \"" + خدمة.العنوان_الأساسي + "\"):\n";
        كود += "        _عنوان = عنوان\n\n";
        
        // العمليات
        for (const auto& عملية : خدمة.العمليات) {
            كود += ولّد_عملية_عميل(عملية);
        }
        
        كود += "\n";
        return كود;
    }
    
    std::string ولّد_عملية_عميل(const عملية_موحدة& عملية) {
        std::string كود;
        
        std::string اسم = عملية.الاسم_عربي.empty() ?
            قاموس_ترجمة::المثيل().ترجم(عملية.المعرف) : عملية.الاسم_عربي;
        
        if (الإعدادات_.توثيق && !عملية.الوصف.empty()) {
            كود += "    /**\n";
            كود += "     * " + عملية.الوصف + "\n";
            كود += "     */\n";
        }
        
        // توقيع الدالة
        if (الإعدادات_.غير_متزامن) {
            كود += "    غير_متزامن دالة " + اسم + "(";
        }
        else {
            كود += "    دالة " + اسم + "(";
        }
        
        // المعاملات
        bool أول = true;
        for (const auto& معامل : عملية.المعاملات) {
            if (!أول) كود += ", ";
            
            std::string اسم_معامل = معامل.الاسم_عربي.empty() ?
                قاموس_ترجمة::المثيل().ترجم(معامل.الاسم) : معامل.الاسم_عربي;
            
            كود += اسم_معامل + ": " + ترجم_نوع_موحد(معامل.النوع, معامل.اسم_النوع);
            
            if (!معامل.مطلوب) {
                كود += "?";
            }
            
            أول = false;
        }
        
        كود += ")";
        
        // نوع الإرجاع
        std::string نوع_إرجاع = عملية.نوع_الإرجاع_عربي.empty() ?
            قاموس_ترجمة::المثيل().ترجم(عملية.نوع_الإرجاع) : عملية.نوع_الإرجاع_عربي;
        
        if (!نوع_إرجاع.empty()) {
            كود += " -> " + نوع_إرجاع;
        }
        
        كود += ":\n";
        
        // جسم الدالة
        كود += "        // بناء المسار\n";
        كود += "        متغير مسار = \"" + عملية.المسار + "\"\n";
        
        // استبدال معاملات المسار
        for (const auto& معامل : عملية.المعاملات) {
            if (معامل.الموقع == "path") {
                كود += "        مسار = مسار.استبدل(\"{" + معامل.الاسم + "}\", ";
                std::string اسم_معامل = معامل.الاسم_عربي.empty() ?
                    قاموس_ترجمة::المثيل().ترجم(معامل.الاسم) : معامل.الاسم_عربي;
                كود += اسم_معامل + ".إلى_نص())\n";
            }
        }
        
        // إرسال الطلب
        كود += "\n        // إرسال الطلب\n";
        if (الإعدادات_.غير_متزامن) {
            كود += "        متغير استجابة = انتظر http." + عملية.الطريقة.substr(0, 1);
            كود += عملية.الطريقة.substr(1) + "(_عنوان + مسار)\n";
        }
        else {
            كود += "        متغير استجابة = http." + عملية.الطريقة.substr(0, 1);
            كود += عملية.الطريقة.substr(1) + "(_عنوان + مسار)\n";
        }
        
        كود += "        أرجع استجابة.json()\n\n";
        
        return كود;
    }
    
    std::string ولّد_خادم(const خدمة_موحدة& خدمة) {
        std::string كود;
        
        std::string اسم = خدمة.الاسم_عربي.empty() ?
            قاموس_ترجمة::المثيل().ترجم(خدمة.الاسم) : خدمة.الاسم_عربي;
        
        كود += "/**\n";
        كود += " * واجهة الخادم - يجب تنفيذها\n";
        كود += " */\n";
        كود += "واجهة " + تطبيق_اسم(اسم) + "_واجهة:\n";
        
        for (const auto& عملية : خدمة.العمليات) {
            std::string اسم_عملية = عملية.الاسم_عربي.empty() ?
                قاموس_ترجمة::المثيل().ترجم(عملية.المعرف) : عملية.الاسم_عربي;
            
            if (الإعدادات_.غير_متزامن) {
                كود += "    غير_متزامن دالة " + اسم_عملية + "(";
            }
            else {
                كود += "    دالة " + اسم_عملية + "(";
            }
            
            bool أول = true;
            for (const auto& معامل : عملية.المعاملات) {
                if (!أول) كود += ", ";
                
                std::string اسم_معامل = معامل.الاسم_عربي.empty() ?
                    قاموس_ترجمة::المثيل().ترجم(معامل.الاسم) : معامل.الاسم_عربي;
                
                كود += اسم_معامل + ": " + ترجم_نوع_موحد(معامل.النوع, معامل.اسم_النوع);
                أول = false;
            }
            
            كود += ") -> " + عملية.نوع_الإرجاع + "\n";
        }
        
        كود += "\n";
        return كود;
    }
    
    std::string ترجم_نوع(const حقل_موحد& حقل) {
        std::string نوع = ترجم_نوع_موحد(حقل.النوع, حقل.اسم_النوع);
        
        if (!حقل.مطلوب) {
            نوع += "?";
        }
        
        return نوع;
    }
    
    std::string ترجم_نوع_موحد(نوع_موحد نوع, const std::string& اسم_نوع) {
        switch (نوع) {
            case نوع_موحد::نص:
                return "نص";
            case نوع_موحد::عدد:
                return "عدد";
            case نوع_موحد::عشري:
                return "عشري";
            case نوع_موحد::منطقي:
                return "منطقي";
            case نوع_موحد::مصفوفة:
                return "[" + قاموس_ترجمة::المثيل().ترجم(اسم_نوع) + "]";
            case نوع_موحد::كائن:
                return قاموس_ترجمة::المثيل().ترجم(اسم_نوع);
            case نوع_موحد::تعداد:
                return قاموس_ترجمة::المثيل().ترجم(اسم_نوع);
            case نوع_موحد::اختياري:
                return قاموس_ترجمة::المثيل().ترجم(اسم_نوع) + "?";
            case نوع_موحد::خريطة:
                return "{نص: " + قاموس_ترجمة::المثيل().ترجم(اسم_نوع) + "}";
            case نوع_موحد::تاريخ:
                return "تاريخ";
            case نوع_موحد::وقت:
                return "وقت";
            case نوع_موحد::uuid:
                return "معرف_فريد";
            case نوع_موحد::بايتات:
                return "[بايت]";
            case نوع_موحد::فارغ:
            default:
                return "لا_شيء";
        }
    }
    
    std::string تطبيق_اسم(const std::string& اسم) {
        return الإعدادات_.بادئة_صنف + اسم + الإعدادات_.لاحقة_صنف;
    }
    
    الإعدادات_توليد الإعدادات_;
};

