/**
 * مولد كود ص من Protobuf
 */
class مولد_كود_ص_protobuf {
public:
    std::string ولّد(const ملف_proto& ملف) {
        std::string كود;
        
        كود += "// كود مُولَّد تلقائياً من Protobuf\n";
        if (!ملف.الحزمة.empty()) {
            كود += "// الحزمة: " + ملف.الحزمة + "\n";
        }
        كود += "\n";
        
        // التعدادات
        for (const auto& تعداد : ملف.التعدادات) {
            كود += ولّد_تعداد(تعداد);
        }
        
        // الرسائل
        for (const auto& رسالة : ملف.الرسائل) {
            كود += ولّد_رسالة(رسالة);
        }
        
        // الخدمات
        for (const auto& خدمة : ملف.الخدمات) {
            كود += ولّد_خدمة(خدمة);
        }
        
        return كود;
    }
    
private:
    std::string ولّد_تعداد(const تعداد_proto& تعداد) {
        std::string كود;
        
        كود += "تعداد " + ترجم_اسم(تعداد.الاسم) + ":\n";
        for (const auto& قيمة : تعداد.القيم) {
            كود += "    " + ترجم_اسم(قيمة.الاسم) + " = " + 
                   std::to_string(قيمة.الرقم) + "\n";
        }
        كود += "\n";
        
        return كود;
    }
    
    std::string ولّد_رسالة(const رسالة_proto& رسالة) {
        std::string كود;
        
        كود += "@protobuf\n";
        كود += "بنية " + ترجم_اسم(رسالة.الاسم) + ":\n";
        
        for (const auto& حقل : رسالة.الحقول) {
            كود += "    @رقم(" + std::to_string(حقل.الرقم) + ")\n";
            كود += "    " + ترجم_اسم(حقل.الاسم) + ": ";
            كود += ترجم_نوع(حقل);
            كود += "\n";
        }
        
        كود += "\n";
        
        return كود;
    }
    
    std::string ولّد_خدمة(const خدمة_proto& خدمة) {
        std::string كود;
        
        كود += "صنف " + ترجم_اسم(خدمة.الاسم) + ":\n";
        
        for (const auto& طريقة : خدمة.الطرق) {
            كود += "    غير_متزامن دالة " + ترجم_اسم(طريقة.الاسم) + "(";
            كود += "طلب: " + ترجم_اسم(طريقة.الإدخال);
            كود += ") -> " + ترجم_اسم(طريقة.الإخراج) + ":\n";
            كود += "        // TODO: تنفيذ\n";
            كود += "        مر\n\n";
        }
        
        return كود;
    }
    
    std::string ترجم_اسم(const std::string& اسم) {
        // يمكن إضافة قاموس ترجمة هنا
        return اسم;
    }
    
    std::string ترجم_نوع(const حقل_proto& حقل) {
        std::string نوع;
        
        switch (حقل.النوع) {
            case نوع_protobuf::int32:
            case نوع_protobuf::int64:
            case نوع_protobuf::uint32:
            case نوع_protobuf::uint64:
            case نوع_protobuf::sint32:
            case نوع_protobuf::sint64:
            case نوع_protobuf::fixed32:
            case نوع_protobuf::fixed64:
            case نوع_protobuf::sfixed32:
            case نوع_protobuf::sfixed64:
                نوع = "عدد";
                break;
            case نوع_protobuf::double_:
            case نوع_protobuf::float_:
                نوع = "عشري";
                break;
            case نوع_protobuf::bool_:
                نوع = "منطقي";
                break;
            case نوع_protobuf::string_:
                نوع = "نص";
                break;
            case نوع_protobuf::bytes_:
                نوع = "[بايت]";
                break;
            case نوع_protobuf::map_:
                نوع = "{" + حقل.نوع_المفتاح + ": " + حقل.نوع_القيمة + "}";
                break;
            case نوع_protobuf::message:
            case نوع_protobuf::enum_:
                نوع = ترجم_اسم(حقل.اسم_النوع);
                break;
        }
        
        if (حقل.القاعدة == قاعدة_حقل::repeated) {
            نوع = "[" + نوع + "]";
        }
        else if (حقل.القاعدة == قاعدة_حقل::optional) {
            نوع += "?";
        }
        
        return نوع;
    }
};

