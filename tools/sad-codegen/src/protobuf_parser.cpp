/**
 * نوع الحقل في Protobuf
 */
enum class نوع_protobuf {
    // أنواع عددية
    double_,
    float_,
    int32,
    int64,
    uint32,
    uint64,
    sint32,
    sint64,
    fixed32,
    fixed64,
    sfixed32,
    sfixed64,
    bool_,
    string_,
    bytes_,
    
    // أنواع مُركَّبة
    message,
    enum_,
    
    // map
    map_
};

/**
 * قاعدة الحقل
 */
enum class قاعدة_حقل {
    singular,      // حقل عادي (افتراضي في proto3)
    optional,      // اختياري
    repeated,      // مصفوفة
    map            // خريطة
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              تعريفات Protobuf
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * قيمة تعداد
 */
struct قيمة_تعداد_proto {
    std::string الاسم;
    int الرقم;
    std::string التعليق;
};

/**
 * تعريف تعداد
 */
struct تعداد_proto {
    std::string الاسم;
    std::vector<قيمة_تعداد_proto> القيم;
    std::string التعليق;
};

/**
 * حقل رسالة
 */
struct حقل_proto {
    std::string الاسم;
    نوع_protobuf النوع;
    std::string اسم_النوع;  // للأنواع المُعرَّفة
    int الرقم;             // field number
    قاعدة_حقل القاعدة = قاعدة_حقل::singular;
    std::string التعليق;
    
    // للـ map
    std::string نوع_المفتاح;
    std::string نوع_القيمة;
};

/**
 * رسالة (Message)
 */
struct رسالة_proto {
    std::string الاسم;
    std::vector<حقل_proto> الحقول;
    std::vector<تعداد_proto> التعدادات;  // nested enums
    std::vector<رسالة_proto> الرسائل;   // nested messages
    std::string التعليق;
};

/**
 * خدمة RPC
 */
struct طريقة_rpc {
    std::string الاسم;
    std::string الإدخال;
    std::string الإخراج;
    bool stream_إدخال = false;
    bool stream_إخراج = false;
    std::string التعليق;
};

struct خدمة_proto {
    std::string الاسم;
    std::vector<طريقة_rpc> الطرق;
    std::string التعليق;
};

/**
 * ملف Proto كامل
 */
struct ملف_proto {
    std::string الإصدار;  // "proto2" أو "proto3"
    std::string الحزمة;   // package
    std::vector<std::string> الاستيرادات;
    std::vector<تعداد_proto> التعدادات;
    std::vector<رسالة_proto> الرسائل;
    std::vector<خدمة_proto> الخدمات;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل Protobuf
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * محلل ملفات .proto
 */
class محلل_protobuf {
public:
    /**
     * تحليل ملف
     */
    std::optional<ملف_proto> حلل_ملف(const std::string& مسار) {
        std::ifstream ملف(مسار);
        if (!ملف) {
            خطأ_ = "تعذر فتح الملف: " + مسار;
            return std::nullopt;
        }
        
        std::stringstream buffer;
        buffer << ملف.rdbuf();
        
        return حلل_نص(buffer.str());
    }
    
    /**
     * تحليل نص
     */
    std::optional<ملف_proto> حلل_نص(const std::string& محتوى) {
        ملف_proto ملف;
        ملف.الإصدار = "proto3";
        
        size_t موقع = 0;
        while (موقع < محتوى.length()) {
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (موقع >= محتوى.length()) break;
            
            auto كلمة = اقرأ_كلمة(محتوى, موقع);
            
            if (كلمة == "syntax") {
                ملف.الإصدار = حلل_syntax(محتوى, موقع);
            }
            else if (كلمة == "package") {
                ملف.الحزمة = حلل_package(محتوى, موقع);
            }
            else if (كلمة == "import") {
                ملف.الاستيرادات.push_back(حلل_import(محتوى, موقع));
            }
            else if (كلمة == "message") {
                auto رسالة = حلل_message(محتوى, موقع);
                if (رسالة) {
                    ملف.الرسائل.push_back(*رسالة);
                }
            }
            else if (كلمة == "enum") {
                auto تعداد = حلل_enum(محتوى, موقع);
                if (تعداد) {
                    ملف.التعدادات.push_back(*تعداد);
                }
            }
            else if (كلمة == "service") {
                auto خدمة = حلل_service(محتوى, موقع);
                if (خدمة) {
                    ملف.الخدمات.push_back(*خدمة);
                }
            }
            else {
                // تخطي غير معروف
                while (موقع < محتوى.length() && محتوى[موقع] != '\n') {
                    موقع++;
                }
            }
        }
        
        return ملف;
    }
    
    const std::string& الخطأ() const { return خطأ_; }
    
private:
    std::string حلل_syntax(const std::string& محتوى, size_t& موقع) {
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] == '=') موقع++;
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        
        std::string قيمة;
        if (محتوى[موقع] == '"') {
            موقع++;
            while (موقع < محتوى.length() && محتوى[موقع] != '"') {
                قيمة += محتوى[موقع++];
            }
            if (موقع < محتوى.length()) موقع++;
        }
        
        // ;
        while (موقع < محتوى.length() && محتوى[موقع] != ';') موقع++;
        if (موقع < محتوى.length()) موقع++;
        
        return قيمة;
    }
    
    std::string حلل_package(const std::string& محتوى, size_t& موقع) {
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        
        std::string حزمة;
        while (موقع < محتوى.length() && محتوى[موقع] != ';') {
            if (!std::isspace(محتوى[موقع])) {
                حزمة += محتوى[موقع];
            }
            موقع++;
        }
        if (موقع < محتوى.length()) موقع++;
        
        return حزمة;
    }
    
    std::string حلل_import(const std::string& محتوى, size_t& موقع) {
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        
        std::string استيراد;
        if (محتوى[موقع] == '"') {
            موقع++;
            while (موقع < محتوى.length() && محتوى[موقع] != '"') {
                استيراد += محتوى[موقع++];
            }
            if (موقع < محتوى.length()) موقع++;
        }
        
        while (موقع < محتوى.length() && محتوى[موقع] != ';') موقع++;
        if (موقع < محتوى.length()) موقع++;
        
        return استيراد;
    }
    
    std::optional<رسالة_proto> حلل_message(const std::string& محتوى, size_t& موقع) {
        رسالة_proto رسالة;
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        رسالة.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] != '{') return std::nullopt;
        موقع++;
        
        while (موقع < محتوى.length() && محتوى[موقع] != '}') {
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == '}') break;
            
            auto كلمة = اقرأ_كلمة(محتوى, موقع);
            
            if (كلمة == "message") {
                auto رسالة_فرعية = حلل_message(محتوى, موقع);
                if (رسالة_فرعية) {
                    رسالة.الرسائل.push_back(*رسالة_فرعية);
                }
            }
            else if (كلمة == "enum") {
                auto تعداد = حلل_enum(محتوى, موقع);
                if (تعداد) {
                    رسالة.التعدادات.push_back(*تعداد);
                }
            }
            else if (كلمة == "reserved") {
                // تخطي reserved
                while (موقع < محتوى.length() && محتوى[موقع] != ';') موقع++;
                if (موقع < محتوى.length()) موقع++;
            }
            else {
                // حقل
                auto حقل = حلل_field(محتوى, موقع, كلمة);
                if (حقل) {
                    رسالة.الحقول.push_back(*حقل);
                }
            }
        }
        
        if (موقع < محتوى.length()) موقع++;  // }
        
        return رسالة;
    }
    
    std::optional<حقل_proto> حلل_field(
        const std::string& محتوى,
        size_t& موقع,
        const std::string& كلمة_أولى
    ) {
        حقل_proto حقل;
        std::string نوع;
        
        // تحقق من القاعدة
        if (كلمة_أولى == "repeated") {
            حقل.القاعدة = قاعدة_حقل::repeated;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            نوع = اقرأ_كلمة(محتوى, موقع);
        }
        else if (كلمة_أولى == "optional") {
            حقل.القاعدة = قاعدة_حقل::optional;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            نوع = اقرأ_كلمة(محتوى, موقع);
        }
        else if (كلمة_أولى == "map") {
            حقل.القاعدة = قاعدة_حقل::map;
            // map<key, value>
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == '<') موقع++;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            حقل.نوع_المفتاح = اقرأ_كلمة(محتوى, موقع);
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == ',') موقع++;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            حقل.نوع_القيمة = اقرأ_كلمة(محتوى, موقع);
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == '>') موقع++;
            نوع = "map";
        }
        else {
            نوع = كلمة_أولى;
        }
        
        حقل.النوع = ترجم_نوع(نوع);
        حقل.اسم_النوع = نوع;
        
        // الاسم
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        حقل.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        // =
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] == '=') موقع++;
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        
        // الرقم
        std::string رقم;
        while (موقع < محتوى.length() && std::isdigit(محتوى[موقع])) {
            رقم += محتوى[موقع++];
        }
        حقل.الرقم = رقم.empty() ? 0 : std::stoi(رقم);
        
        // ;
        while (موقع < محتوى.length() && محتوى[موقع] != ';' && محتوى[موقع] != '}') {
            موقع++;
        }
        if (موقع < محتوى.length() && محتوى[موقع] == ';') موقع++;
        
        return حقل;
    }
    
    std::optional<تعداد_proto> حلل_enum(const std::string& محتوى, size_t& موقع) {
        تعداد_proto تعداد;
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        تعداد.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] != '{') return std::nullopt;
        موقع++;
        
        while (موقع < محتوى.length() && محتوى[موقع] != '}') {
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == '}') break;
            
            قيمة_تعداد_proto قيمة;
            قيمة.الاسم = اقرأ_كلمة(محتوى, موقع);
            
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == '=') موقع++;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            
            std::string رقم;
            while (موقع < محتوى.length() && 
                   (std::isdigit(محتوى[موقع]) || محتوى[موقع] == '-')) {
                رقم += محتوى[موقع++];
            }
            قيمة.الرقم = رقم.empty() ? 0 : std::stoi(رقم);
            
            تعداد.القيم.push_back(قيمة);
            
            while (موقع < محتوى.length() && محتوى[موقع] != ';' && محتوى[موقع] != '}') {
                موقع++;
            }
            if (موقع < محتوى.length() && محتوى[موقع] == ';') موقع++;
        }
        
        if (موقع < محتوى.length()) موقع++;  // }
        
        return تعداد;
    }
    
    std::optional<خدمة_proto> حلل_service(const std::string& محتوى, size_t& موقع) {
        خدمة_proto خدمة;
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        خدمة.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] != '{') return std::nullopt;
        موقع++;
        
        while (موقع < محتوى.length() && محتوى[موقع] != '}') {
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            if (محتوى[موقع] == '}') break;
            
            auto كلمة = اقرأ_كلمة(محتوى, موقع);
            if (كلمة == "rpc") {
                auto طريقة = حلل_rpc(محتوى, موقع);
                if (طريقة) {
                    خدمة.الطرق.push_back(*طريقة);
                }
            }
        }
        
        if (موقع < محتوى.length()) موقع++;  // }
        
        return خدمة;
    }
    
    std::optional<طريقة_rpc> حلل_rpc(const std::string& محتوى, size_t& موقع) {
        طريقة_rpc طريقة;
        
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        طريقة.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        // (
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] == '(') موقع++;
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        
        // stream?
        auto كلمة = اقرأ_كلمة(محتوى, موقع);
        if (كلمة == "stream") {
            طريقة.stream_إدخال = true;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            طريقة.الإدخال = اقرأ_كلمة(محتوى, موقع);
        }
        else {
            طريقة.الإدخال = كلمة;
        }
        
        // )
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] == ')') موقع++;
        
        // returns
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        اقرأ_كلمة(محتوى, موقع);  // "returns"
        
        // (
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] == '(') موقع++;
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        
        // stream?
        كلمة = اقرأ_كلمة(محتوى, موقع);
        if (كلمة == "stream") {
            طريقة.stream_إخراج = true;
            موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
            طريقة.الإخراج = اقرأ_كلمة(محتوى, موقع);
        }
        else {
            طريقة.الإخراج = كلمة;
        }
        
        // )
        while (موقع < محتوى.length() && محتوى[موقع] != ')') موقع++;
        if (موقع < محتوى.length()) موقع++;
        
        // ; أو {}
        موقع = تخطي_فراغات_وتعليقات(محتوى, موقع);
        if (محتوى[موقع] == ';') {
            موقع++;
        }
        else if (محتوى[موقع] == '{') {
            int عمق = 1;
            موقع++;
            while (موقع < محتوى.length() && عمق > 0) {
                if (محتوى[موقع] == '{') عمق++;
                else if (محتوى[موقع] == '}') عمق--;
                موقع++;
            }
        }
        
        return طريقة;
    }
    
    نوع_protobuf ترجم_نوع(const std::string& نوع) {
        static std::map<std::string, نوع_protobuf> خريطة = {
            {"double", نوع_protobuf::double_},
            {"float", نوع_protobuf::float_},
            {"int32", نوع_protobuf::int32},
            {"int64", نوع_protobuf::int64},
            {"uint32", نوع_protobuf::uint32},
            {"uint64", نوع_protobuf::uint64},
            {"sint32", نوع_protobuf::sint32},
            {"sint64", نوع_protobuf::sint64},
            {"fixed32", نوع_protobuf::fixed32},
            {"fixed64", نوع_protobuf::fixed64},
            {"sfixed32", نوع_protobuf::sfixed32},
            {"sfixed64", نوع_protobuf::sfixed64},
            {"bool", نوع_protobuf::bool_},
            {"string", نوع_protobuf::string_},
            {"bytes", نوع_protobuf::bytes_},
            {"map", نوع_protobuf::map_}
        };
        
        if (خريطة.count(نوع)) {
            return خريطة[نوع];
        }
        
        return نوع_protobuf::message;
    }
    
    size_t تخطي_فراغات_وتعليقات(const std::string& محتوى, size_t موقع) {
        while (موقع < محتوى.length()) {
            if (std::isspace(محتوى[موقع])) {
                موقع++;
            }
            else if (محتوى.substr(موقع, 2) == "//") {
                while (موقع < محتوى.length() && محتوى[موقع] != '\n') {
                    موقع++;
                }
            }
            else if (محتوى.substr(موقع, 2) == "/*") {
                موقع += 2;
                while (موقع < محتوى.length() - 1 && 
                       محتوى.substr(موقع, 2) != "*/") {
                    موقع++;
                }
                موقع += 2;
            }
            else {
                break;
            }
        }
        return موقع;
    }
    
    std::string اقرأ_كلمة(const std::string& محتوى, size_t& موقع) {
        std::string كلمة;
        while (موقع < محتوى.length() && 
               (std::isalnum(محتوى[موقع]) || محتوى[موقع] == '_' || محتوى[موقع] == '.')) {
            كلمة += محتوى[موقع++];
        }
        return كلمة;
    }
    
    std::string خطأ_;
};

