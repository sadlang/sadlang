/**
 * نوع البيانات في OpenAPI
 */
enum class نوع_مخطط {
    نص,                // string
    عدد_صحيح,          // integer
    عدد_عشري,          // number
    منطقي,             // boolean
    مصفوفة,            // array
    كائن,              // object
    أي                 // any
};

/**
 * تنسيق البيانات
 */
enum class تنسيق_بيانات {
    بدون,
    تاريخ,             // date
    تاريخ_وقت,         // date-time
    بريد,              // email
    uuid,
    uri
};

/**
 * طريقة HTTP
 */
enum class طريقة_http {
    GET,
    POST,
    PUT,
    DELETE,
    PATCH,
    OPTIONS,
    HEAD
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              المخطط (Schema)
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * خاصية المخطط
 */
struct خاصية_مخطط {
    std::string الاسم;
    نوع_مخطط النوع = نوع_مخطط::نص;
    تنسيق_بيانات التنسيق = تنسيق_بيانات::بدون;
    std::string الوصف;
    bool مطلوب = false;
    std::optional<std::string> قيمة_افتراضية;
    
    // للمصفوفات
    std::string نوع_العناصر;
    
    // للكائنات المُشار إليها
    std::string مرجع;  // $ref
};

/**
 * مخطط OpenAPI
 */
struct مخطط_openapi {
    std::string الاسم;
    std::string الوصف;
    نوع_مخطط النوع = نوع_مخطط::كائن;
    
    std::vector<خاصية_مخطط> الخصائص;
    std::vector<std::string> المطلوبة;
    
    // للتعداد
    std::vector<std::string> قيم_التعداد;
    
    // للوراثة
    std::string يرث_من;  // allOf
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              المعاملات (Parameters)
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * موقع المعامل
 */
enum class موقع_معامل {
    مسار,              // path: /users/{id}
    استعلام,           // query: ?page=1
    رأس,               // header: Authorization
    كوكي              // cookie
};

/**
 * معامل الطلب
 */
struct معامل_طلب {
    std::string الاسم;
    موقع_معامل الموقع;
    std::string الوصف;
    bool مطلوب = false;
    
    نوع_مخطط النوع = نوع_مخطط::نص;
    تنسيق_بيانات التنسيق = تنسيق_بيانات::بدون;
    std::optional<std::string> قيمة_افتراضية;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              الاستجابات (Responses)
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * استجابة الطلب
 */
struct استجابة_طلب {
    int الكود;          // 200, 404, etc.
    std::string الوصف;
    std::string نوع_المحتوى;  // application/json
    std::string مرجع_المخطط;  // #/components/schemas/...
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              العملية (Operation)
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * عملية API
 */
struct عملية_api {
    std::string المعرف;      // operationId
    std::string الملخص;
    std::string الوصف;
    طريقة_http الطريقة;
    std::string المسار;      // /users/{id}
    
    std::vector<std::string> الوسوم;  // tags
    
    std::vector<معامل_طلب> المعاملات;
    std::optional<std::string> جسم_الطلب;  // requestBody schema
    std::map<int, استجابة_طلب> الاستجابات;
    
    bool مُهمَل = false;
    std::vector<std::map<std::string, std::vector<std::string>>> الأمان;  // security
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مستند OpenAPI
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات API
 */
struct معلومات_api {
    std::string العنوان;
    std::string الوصف;
    std::string الإصدار;
    std::string رخصة;
    std::string تواصل;
};

/**
 * خادم API
 */
struct خادم_api {
    std::string العنوان;
    std::string الوصف;
};

/**
 * مستند OpenAPI الكامل
 */
struct مستند_openapi {
    std::string الإصدار;  // openapi version (3.0.0)
    معلومات_api المعلومات;
    std::vector<خادم_api> الخوادم;
    std::map<std::string, مخطط_openapi> المخططات;
    std::vector<عملية_api> العمليات;
};

