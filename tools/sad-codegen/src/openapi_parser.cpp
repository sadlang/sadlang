/**
 * مولد كود ص
 */
class مولد_كود_ص {
public:
    /**
     * توليد عميل API كامل
     */
    std::string ولّد_عميل(const مستند_openapi& مستند) {
        std::string كود;
        
        كود += "/**\n";
        كود += " * عميل " + مستند.المعلومات.العنوان + "\n";
        كود += " * الإصدار: " + مستند.المعلومات.الإصدار + "\n";
        كود += " * تم توليده تلقائياً من OpenAPI\n";
        كود += " */\n\n";
        
        // استيراد المكتبات
        كود += "استخدم ص.شبكة\n";
        كود += "استخدم ص.json\n\n";
        
        // توليد البُنى
        for (const auto& [اسم, مخطط] : مستند.المخططات) {
            كود += ولّد_بنية(اسم, مخطط);
        }
        
        // توليد صنف العميل
        كود += ولّد_صنف_عميل(مستند);
        
        return كود;
    }
    
    /**
     * توليد بنية من مخطط
     */
    std::string ولّد_بنية(const std::string& اسم, const مخطط_openapi& مخطط) {
        std::string كود;
        
        if (!مخطط.الوصف.empty()) {
            كود += "// " + مخطط.الوصف + "\n";
        }
        
        كود += "بنية " + ترجم_اسم(اسم) + ":\n";
        
        for (const auto& خاصية : مخطط.الخصائص) {
            كود += "    " + ترجم_اسم(خاصية.الاسم) + ": ";
            كود += ترجم_نوع(خاصية.النوع, خاصية.مرجع);
            
            if (!خاصية.مطلوب) {
                كود += "?";  // اختياري
            }
            
            كود += "\n";
        }
        
        كود += "\n";
        return كود;
    }
    
    /**
     * توليد صنف العميل
     */
    std::string ولّد_صنف_عميل(const مستند_openapi& مستند) {
        std::string كود;
        
        كود += "صنف عميل_" + ترجم_اسم(مستند.المعلومات.العنوان) + ":\n";
        كود += "    خاص العنوان: نص\n";
        كود += "    خاص http_عميل: شبكة.عميل_http\n\n";
        
        // المُنشئ
        كود += "    دالة أنشئ(عنوان: نص = \"";
        if (!مستند.الخوادم.empty()) {
            كود += مستند.الخوادم[0].العنوان;
        }
        كود += "\"):\n";
        كود += "        العنوان = عنوان\n";
        كود += "        http_عميل = شبكة.عميل_http.جديد()\n\n";
        
        // توليد دالة لكل عملية
        for (const auto& عملية : مستند.العمليات) {
            كود += ولّد_دالة_عملية(عملية);
        }
        
        return كود;
    }
    
    /**
     * توليد دالة لعملية API
     */
    std::string ولّد_دالة_عملية(const عملية_api& عملية) {
        std::string كود;
        
        // تعليق
        if (!عملية.الملخص.empty()) {
            كود += "    // " + عملية.الملخص + "\n";
        }
        
        // توقيع الدالة
        كود += "    غير_متزامن دالة " + ترجم_اسم(عملية.المعرف) + "(";
        
        // المعاملات
        bool أول = true;
        for (const auto& معامل : عملية.المعاملات) {
            if (!أول) كود += ", ";
            أول = false;
            
            كود += ترجم_اسم(معامل.الاسم) + ": ";
            كود += ترجم_نوع(معامل.النوع, "");
            
            if (!معامل.مطلوب) {
                كود += "?";
            }
        }
        
        كود += ")";
        
        // نوع الإرجاع
        if (!عملية.الاستجابات.empty()) {
            auto& استجابة = عملية.الاستجابات.begin()->second;
            if (!استجابة.مرجع_المخطط.empty()) {
                كود += " -> " + استخرج_اسم_مرجع(استجابة.مرجع_المخطط);
            }
        }
        
        كود += ":\n";
        
        // جسم الدالة
        كود += "        مسار = \"" + عملية.المسار + "\"\n";
        
        // استبدال معاملات المسار
        for (const auto& معامل : عملية.المعاملات) {
            if (معامل.الموقع == موقع_معامل::مسار) {
                كود += "        مسار = مسار.استبدل(\"{" + معامل.الاسم + "}\", ";
                كود += ترجم_اسم(معامل.الاسم) + ")\n";
            }
        }
        
        // الطلب
        كود += "        جواب = انتظر http_عميل.";
        switch (عملية.الطريقة) {
            case طريقة_http::GET: كود += "جلب"; break;
            case طريقة_http::POST: كود += "أرسل"; break;
            case طريقة_http::PUT: كود += "حدّث"; break;
            case طريقة_http::DELETE: كود += "احذف"; break;
            default: كود += "جلب"; break;
        }
        كود += "(العنوان + مسار)\n";
        
        كود += "        أرجع جواب.json()\n\n";
        
        return كود;
    }
    
private:
    /**
     * ترجمة اسم للعربية
     */
    std::string ترجم_اسم(const std::string& اسم) {
        // قاموس ترجمة بسيط
        static std::map<std::string, std::string> قاموس = {
            {"user", "مستخدم"},
            {"users", "مستخدمين"},
            {"product", "منتج"},
            {"products", "منتجات"},
            {"order", "طلب"},
            {"orders", "طلبات"},
            {"id", "معرف"},
            {"name", "اسم"},
            {"email", "بريد"},
            {"get", "جلب"},
            {"create", "أنشئ"},
            {"update", "حدّث"},
            {"delete", "احذف"},
            {"list", "قائمة"}
        };
        
        // تحويل للحروف الصغيرة
        std::string صغير = اسم;
        for (char& c : صغير) {
            if (c >= 'A' && c <= 'Z') c += 32;
        }
        
        if (قاموس.count(صغير)) {
            return قاموس[صغير];
        }
        
        return اسم;
    }
    
    /**
     * ترجمة نوع للغة ص
     */
    std::string ترجم_نوع(نوع_مخطط نوع, const std::string& مرجع) {
        if (!مرجع.empty()) {
            return استخرج_اسم_مرجع(مرجع);
        }
        
        switch (نوع) {
            case نوع_مخطط::نص: return "نص";
            case نوع_مخطط::عدد_صحيح: return "عدد";
            case نوع_مخطط::عدد_عشري: return "عشري";
            case نوع_مخطط::منطقي: return "منطقي";
            case نوع_مخطط::مصفوفة: return "[]";
            case نوع_مخطط::كائن: return "{}";
            default: return "أي";
        }
    }
    
    /**
     * استخراج اسم من مرجع
     */
    std::string استخرج_اسم_مرجع(const std::string& مرجع) {
        // #/components/schemas/User → User
        auto pos = مرجع.rfind('/');
        if (pos != std::string::npos) {
            return ترجم_اسم(مرجع.substr(pos + 1));
        }
        return مرجع;
    }
};

