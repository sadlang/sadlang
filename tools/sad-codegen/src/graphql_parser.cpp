/**
 * نوع GraphQL الأساسي
 */
enum class نوع_graphql {
    عددي,              // ID, String, Int, Float, Boolean
    كائن,              // type
    واجهة,             // interface
    اتحاد,             // union
    تعداد,             // enum
    إدخال              // input
};

/**
 * نوع عددي
 */
enum class عددي_graphql {
    ID,
    String,
    Int,
    Float,
    Boolean,
    مُخصص
};

