/**
 * مرجع نوع (مع معدلات)
 */
struct مرجع_نوع_graphql {
    std::string الاسم;
    bool مطلوب = false;         // !
    bool قائمة = false;         // []
    bool عناصر_مطلوبة = false;  // [!]
    
    /**
     * كنص
     */
    std::string كنص() const {
        std::string نص;
        if (قائمة) نص += "[";
        نص += الاسم;
        if (عناصر_مطلوبة) نص += "!";
        if (قائمة) نص += "]";
        if (مطلوب) نص += "!";
        return نص;
    }
};

/**
 * حقل GraphQL
 */
struct حقل_graphql {
    std::string الاسم;
    std::string الوصف;
    مرجع_نوع_graphql النوع;
    
    // الوسائط
    struct وسيطة {
        std::string الاسم;
        مرجع_نوع_graphql النوع;
        std::optional<std::string> قيمة_افتراضية;
    };
    std::vector<وسيطة> الوسائط;
    
    // التوجيهات
    std::vector<std::string> التوجيهات;  // @deprecated, etc.
    bool مُهمَل = false;
    std::string سبب_الإهمال;
};

/**
 * تعريف نوع GraphQL
 */
struct تعريف_نوع_graphql {
    std::string الاسم;
    std::string الوصف;
    نوع_graphql النوع;
    
    // للكائنات والواجهات
    std::vector<حقل_graphql> الحقول;
    std::vector<std::string> الواجهات;  // implements
    
    // للتعداد
    std::vector<std::string> قيم_التعداد;
    
    // للاتحاد
    std::vector<std::string> أنواع_الاتحاد;
};

/**
 * مخطط GraphQL الكامل
 */
struct مخطط_graphql {
    std::map<std::string, تعريف_نوع_graphql> الأنواع;
    std::optional<std::string> نوع_الاستعلام;     // Query
    std::optional<std::string> نوع_التغيير;       // Mutation
    std::optional<std::string> نوع_الاشتراك;      // Subscription
};

