/**
 * محلل GraphQL Schema
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │               محلل GraphQL Schema                      │
 *     │                                                        │
 *     │   المدخل:                                              │
 *     │   ────────                                             │
 *     │   type User { id: ID!, name: String! }                │
 *     │                                                        │
 *     │   المخرج:                                              │
 *     │   ────────                                             │
 *     │   تعريف_نوع_graphql {                                  │
 *     │     الاسم: "User",                                     │
 *     │     الحقول: [                                          │
 *     │       { الاسم: "id", النوع: ID! },                     │
 *     │       { الاسم: "name", النوع: String! }                │
 *     │     ]                                                  │
 *     │   }                                                    │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
class محلل_graphql {
public:
    /**
     * تحليل مخطط GraphQL
     */
    std::optional<مخطط_graphql> حلل(const std::string& محتوى) {
        مخطط_graphql مخطط;
        
        // تحليل التعريفات
        size_t موقع = 0;
        while (موقع < محتوى.length()) {
            // تخطي المسافات والتعليقات
            موقع = تخطي_فراغات(محتوى, موقع);
            if (موقع >= محتوى.length()) break;
            
            // تعليق
            if (محتوى[موقع] == '#') {
                موقع = ابحث_عن_سطر_جديد(محتوى, موقع);
                continue;
            }
            
            // وصف (""")
            std::string وصف;
            if (محتوى.substr(موقع, 3) == "\"\"\"") {
                auto نهاية = محتوى.find("\"\"\"", موقع + 3);
                if (نهاية != std::string::npos) {
                    وصف = محتوى.substr(موقع + 3, نهاية - موقع - 3);
                    موقع = نهاية + 3;
                    موقع = تخطي_فراغات(محتوى, موقع);
                }
            }
            
            // نوع التعريف
            auto كلمة = اقرأ_كلمة(محتوى, موقع);
            
            if (كلمة == "type") {
                auto نوع = حلل_نوع_كائن(محتوى, موقع, وصف);
                if (نوع) {
                    مخطط.الأنواع[نوع->الاسم] = *نوع;
                }
            }
            else if (كلمة == "interface") {
                auto واجهة = حلل_واجهة(محتوى, موقع, وصف);
                if (واجهة) {
                    مخطط.الأنواع[واجهة->الاسم] = *واجهة;
                }
            }
            else if (كلمة == "enum") {
                auto تعداد = حلل_تعداد(محتوى, موقع, وصف);
                if (تعداد) {
                    مخطط.الأنواع[تعداد->الاسم] = *تعداد;
                }
            }
            else if (كلمة == "union") {
                auto اتحاد = حلل_اتحاد(محتوى, موقع, وصف);
                if (اتحاد) {
                    مخطط.الأنواع[اتحاد->الاسم] = *اتحاد;
                }
            }
            else if (كلمة == "input") {
                auto إدخال = حلل_إدخال(محتوى, موقع, وصف);
                if (إدخال) {
                    مخطط.الأنواع[إدخال->الاسم] = *إدخال;
                }
            }
            else if (كلمة == "schema") {
                حلل_مخطط_رئيسي(محتوى, موقع, مخطط);
            }
            else {
                // تخطي سطر غير معروف
                موقع = ابحث_عن_سطر_جديد(محتوى, موقع);
            }
        }
        
        // افتراضيات
        if (!مخطط.نوع_الاستعلام && مخطط.الأنواع.count("Query")) {
            مخطط.نوع_الاستعلام = "Query";
        }
        if (!مخطط.نوع_التغيير && مخطط.الأنواع.count("Mutation")) {
            مخطط.نوع_التغيير = "Mutation";
        }
        
        return مخطط;
    }
    
private:
    std::optional<تعريف_نوع_graphql> حلل_نوع_كائن(
        const std::string& محتوى,
        size_t& موقع,
        const std::string& وصف
    ) {
        تعريف_نوع_graphql نوع;
        نوع.النوع = نوع_graphql::كائن;
        نوع.الوصف = وصف;
        
        // الاسم
        موقع = تخطي_فراغات(محتوى, موقع);
        نوع.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        // implements
        موقع = تخطي_فراغات(محتوى, موقع);
        if (محتوى.substr(موقع, 10) == "implements") {
            موقع += 10;
            موقع = تخطي_فراغات(محتوى, موقع);
            
            while (موقع < محتوى.length() && محتوى[موقع] != '{') {
                auto واجهة = اقرأ_كلمة(محتوى, موقع);
                if (!واجهة.empty()) {
                    نوع.الواجهات.push_back(واجهة);
                }
                موقع = تخطي_فراغات(محتوى, موقع);
                if (محتوى[موقع] == '&') {
                    موقع++;
                    موقع = تخطي_فراغات(محتوى, موقع);
                }
            }
        }
        
        // الحقول
        نوع.الحقول = حلل_حقول(محتوى, موقع);
        
        return نوع;
    }
    
    std::optional<تعريف_نوع_graphql> حلل_واجهة(
        const std::string& محتوى,
        size_t& موقع,
        const std::string& وصف
    ) {
        auto نوع = حلل_نوع_كائن(محتوى, موقع, وصف);
        if (نوع) {
            نوع->النوع = نوع_graphql::واجهة;
        }
        return نوع;
    }
    
    std::optional<تعريف_نوع_graphql> حلل_تعداد(
        const std::string& محتوى,
        size_t& موقع,
        const std::string& وصف
    ) {
        تعريف_نوع_graphql نوع;
        نوع.النوع = نوع_graphql::تعداد;
        نوع.الوصف = وصف;
        
        موقع = تخطي_فراغات(محتوى, موقع);
        نوع.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        // قيم التعداد
        موقع = تخطي_فراغات(محتوى, موقع);
        if (محتوى[موقع] == '{') {
            موقع++;
            
            while (موقع < محتوى.length() && محتوى[موقع] != '}') {
                موقع = تخطي_فراغات(محتوى, موقع);
                if (محتوى[موقع] == '}') break;
                
                auto قيمة = اقرأ_كلمة(محتوى, موقع);
                if (!قيمة.empty()) {
                    نوع.قيم_التعداد.push_back(قيمة);
                }
                
                موقع = تخطي_فراغات(محتوى, موقع);
            }
            
            if (موقع < محتوى.length()) موقع++;  // }
        }
        
        return نوع;
    }
    
    std::optional<تعريف_نوع_graphql> حلل_اتحاد(
        const std::string& محتوى,
        size_t& موقع,
        const std::string& وصف
    ) {
        تعريف_نوع_graphql نوع;
        نوع.النوع = نوع_graphql::اتحاد;
        نوع.الوصف = وصف;
        
        موقع = تخطي_فراغات(محتوى, موقع);
        نوع.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        // =
        موقع = تخطي_فراغات(محتوى, موقع);
        if (محتوى[موقع] == '=') موقع++;
        
        // الأنواع
        موقع = تخطي_فراغات(محتوى, موقع);
        while (موقع < محتوى.length()) {
            auto نوع_فرعي = اقرأ_كلمة(محتوى, موقع);
            if (نوع_فرعي.empty()) break;
            
            نوع.أنواع_الاتحاد.push_back(نوع_فرعي);
            
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == '|') {
                موقع++;
                موقع = تخطي_فراغات(محتوى, موقع);
            }
            else {
                break;
            }
        }
        
        return نوع;
    }
    
    std::optional<تعريف_نوع_graphql> حلل_إدخال(
        const std::string& محتوى,
        size_t& موقع,
        const std::string& وصف
    ) {
        auto نوع = حلل_نوع_كائن(محتوى, موقع, وصف);
        if (نوع) {
            نوع->النوع = نوع_graphql::إدخال;
        }
        return نوع;
    }
    
    void حلل_مخطط_رئيسي(
        const std::string& محتوى,
        size_t& موقع,
        مخطط_graphql& مخطط
    ) {
        موقع = تخطي_فراغات(محتوى, موقع);
        if (محتوى[موقع] == '{') {
            موقع++;
            
            while (موقع < محتوى.length() && محتوى[موقع] != '}') {
                موقع = تخطي_فراغات(محتوى, موقع);
                auto حقل = اقرأ_كلمة(محتوى, موقع);
                
                موقع = تخطي_فراغات(محتوى, موقع);
                if (محتوى[موقع] == ':') موقع++;
                موقع = تخطي_فراغات(محتوى, موقع);
                
                auto قيمة = اقرأ_كلمة(محتوى, موقع);
                
                if (حقل == "query") مخطط.نوع_الاستعلام = قيمة;
                else if (حقل == "mutation") مخطط.نوع_التغيير = قيمة;
                else if (حقل == "subscription") مخطط.نوع_الاشتراك = قيمة;
            }
            
            if (موقع < محتوى.length()) موقع++;
        }
    }
    
    std::vector<حقل_graphql> حلل_حقول(
        const std::string& محتوى,
        size_t& موقع
    ) {
        std::vector<حقل_graphql> حقول;
        
        موقع = تخطي_فراغات(محتوى, موقع);
        if (محتوى[موقع] != '{') return حقول;
        موقع++;  // {
        
        while (موقع < محتوى.length() && محتوى[موقع] != '}') {
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == '}') break;
            
            حقل_graphql حقل;
            
            // الاسم
            حقل.الاسم = اقرأ_كلمة(محتوى, موقع);
            if (حقل.الاسم.empty()) {
                موقع++;
                continue;
            }
            
            موقع = تخطي_فراغات(محتوى, موقع);
            
            // الوسائط
            if (محتوى[موقع] == '(') {
                موقع++;
                حقل.الوسائط = حلل_وسائط(محتوى, موقع);
            }
            
            // :
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == ':') موقع++;
            موقع = تخطي_فراغات(محتوى, موقع);
            
            // النوع
            حقل.النوع = حلل_مرجع_نوع(محتوى, موقع);
            
            حقول.push_back(حقل);
        }
        
        if (موقع < محتوى.length()) موقع++;  // }
        
        return حقول;
    }
    
    std::vector<حقل_graphql::وسيطة> حلل_وسائط(
        const std::string& محتوى,
        size_t& موقع
    ) {
        std::vector<حقل_graphql::وسيطة> وسائط;
        
        while (موقع < محتوى.length() && محتوى[موقع] != ')') {
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == ')') break;
            
            حقل_graphql::وسيطة وسيطة;
            وسيطة.الاسم = اقرأ_كلمة(محتوى, موقع);
            
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == ':') موقع++;
            موقع = تخطي_فراغات(محتوى, موقع);
            
            وسيطة.النوع = حلل_مرجع_نوع(محتوى, موقع);
            
            وسائط.push_back(وسيطة);
            
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == ',') موقع++;
        }
        
        if (موقع < محتوى.length()) موقع++;  // )
        
        return وسائط;
    }
    
    مرجع_نوع_graphql حلل_مرجع_نوع(
        const std::string& محتوى,
        size_t& موقع
    ) {
        مرجع_نوع_graphql مرجع;
        
        موقع = تخطي_فراغات(محتوى, موقع);
        
        // قائمة؟
        if (محتوى[موقع] == '[') {
            مرجع.قائمة = true;
            موقع++;
            موقع = تخطي_فراغات(محتوى, موقع);
        }
        
        // الاسم
        مرجع.الاسم = اقرأ_كلمة(محتوى, موقع);
        
        // عناصر مطلوبة؟
        if (مرجع.قائمة && موقع < محتوى.length() && محتوى[موقع] == '!') {
            مرجع.عناصر_مطلوبة = true;
            موقع++;
        }
        
        // إغلاق القائمة
        if (مرجع.قائمة) {
            موقع = تخطي_فراغات(محتوى, موقع);
            if (محتوى[موقع] == ']') موقع++;
        }
        
        // مطلوب؟
        if (موقع < محتوى.length() && محتوى[موقع] == '!') {
            مرجع.مطلوب = true;
            موقع++;
        }
        
        return مرجع;
    }
    
    // أدوات مساعدة
    size_t تخطي_فراغات(const std::string& محتوى, size_t موقع) {
        while (موقع < محتوى.length() && 
               (محتوى[موقع] == ' ' || محتوى[موقع] == '\t' || 
                محتوى[موقع] == '\n' || محتوى[موقع] == '\r')) {
            موقع++;
        }
        return موقع;
    }
    
    size_t ابحث_عن_سطر_جديد(const std::string& محتوى, size_t موقع) {
        while (موقع < محتوى.length() && محتوى[موقع] != '\n') {
            موقع++;
        }
        return موقع + 1;
    }
    
    std::string اقرأ_كلمة(const std::string& محتوى, size_t& موقع) {
        std::string كلمة;
        while (موقع < محتوى.length() && 
               (std::isalnum(محتوى[موقع]) || محتوى[موقع] == '_')) {
            كلمة += محتوى[موقع++];
        }
        return كلمة;
    }
};

