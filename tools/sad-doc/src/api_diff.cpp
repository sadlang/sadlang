/**
 * نوع بيانات حقل
 */
struct نوع_حقل_api {
    std::string الاسم;
    bool مصفوفة = false;
    bool اختياري = false;
    
    bool operator==(const نوع_حقل_api& آخر) const {
        return الاسم == آخر.الاسم && 
               مصفوفة == آخر.مصفوفة && 
               اختياري == آخر.اختياري;
    }
    
    bool operator!=(const نوع_حقل_api& آخر) const {
        return !(*this == آخر);
    }
    
    std::string إلى_نص() const {
        std::string نتيجة = الاسم;
        if (مصفوفة) نتيجة = "[" + نتيجة + "]";
        if (اختياري) نتيجة += "?";
        return نتيجة;
    }
};

/**
 * حقل في بنية
 */
struct حقل_api {
    std::string الاسم;
    نوع_حقل_api النوع;
    std::string الوصف;
    bool مطلوب = true;
    
    bool operator==(const حقل_api& آخر) const {
        return الاسم == آخر.الاسم && 
               النوع == آخر.النوع && 
               مطلوب == آخر.مطلوب;
    }
};

/**
 * بنية بيانات
 */
struct بنية_api {
    std::string الاسم;
    std::string الوصف;
    std::vector<حقل_api> الحقول;
};

/**
 * معامل دالة
 */
struct معامل_api {
    std::string الاسم;
    نوع_حقل_api النوع;
    std::string الموقع;  // path, query, header, body
    bool مطلوب = true;
    std::string الوصف;
    
    bool operator==(const معامل_api& آخر) const {
        return الاسم == آخر.الاسم && 
               النوع == آخر.النوع && 
               الموقع == آخر.الموقع &&
               مطلوب == آخر.مطلوب;
    }
};

/**
 * نقطة نهاية API
 */
struct نقطة_نهاية_api {
    std::string المعرف;
    std::string المسار;
    std::string الطريقة;  // GET, POST, etc.
    std::string الوصف;
    std::vector<معامل_api> المعاملات;
    نوع_حقل_api نوع_الإرجاع;
};

/**
 * تعريف API كامل
 */
struct تعريف_api {
    std::string الاسم;
    std::string الإصدار;
    std::string الوصف;
    std::vector<بنية_api> البنيات;
    std::vector<نقطة_نهاية_api> النقاط;
};

