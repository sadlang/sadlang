/**
 * مستوى خطورة التغيير
 */
enum class خطورة_تغيير {
    معلومات,    // تغيير في الوصف فقط
    تحسين,      // إضافة ميزات جديدة
    تحذير,      // تغيير قد يؤثر على بعض المستخدمين
    كسري        // تغيير يكسر التوافق
};

/**
 * نوع التغيير
 */
enum class نوع_تغيير {
    إضافة,
    حذف,
    تعديل,
    إعادة_تسمية,
    نقل
};

/**
 * تغيير واحد
 */
struct تغيير_api {
    نوع_تغيير النوع;
    خطورة_تغيير الخطورة;
    std::string الكيان;      // اسم النقطة أو البنية
    std::string الحقل;       // اسم الحقل (إن وُجد)
    std::string الوصف;
    
    // للتعديلات
    std::string القيمة_القديمة;
    std::string القيمة_الجديدة;
    
    // للإعادة تسمية
    std::string الاسم_القديم;
    std::string الاسم_الجديد;
};

