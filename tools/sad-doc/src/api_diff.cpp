/**
 * محلل الفروقات بين إصدارين
 */
class محلل_فروقات_api {
public:
    /**
     * مقارنة إصدارين
     */
    std::vector<تغيير_api> قارن(
        const تعريف_api& القديم,
        const تعريف_api& الجديد
    ) {
        std::vector<تغيير_api> تغييرات;
        
        // مقارنة البنيات
        قارن_البنيات(القديم.البنيات, الجديد.البنيات, تغييرات);
        
        // مقارنة النقاط
        قارن_النقاط(القديم.النقاط, الجديد.النقاط, تغييرات);
        
        return تغييرات;
    }
    
private:
    void قارن_البنيات(
        const std::vector<بنية_api>& قديم,
        const std::vector<بنية_api>& جديد,
        std::vector<تغيير_api>& تغييرات
    ) {
        std::map<std::string, const بنية_api*> خريطة_قديم;
        std::map<std::string, const بنية_api*> خريطة_جديد;
        
        for (const auto& بنية : قديم) {
            خريطة_قديم[بنية.الاسم] = &بنية;
        }
        for (const auto& بنية : جديد) {
            خريطة_جديد[بنية.الاسم] = &بنية;
        }
        
        // البنيات المحذوفة
        for (const auto& [اسم, بنية] : خريطة_قديم) {
            if (خريطة_جديد.find(اسم) == خريطة_جديد.end()) {
                تغيير_api تغيير;
                تغيير.النوع = نوع_تغيير::حذف;
                تغيير.الخطورة = خطورة_تغيير::كسري;
                تغيير.الكيان = اسم;
                تغيير.الوصف = "تم حذف البنية: " + اسم;
                تغييرات.push_back(تغيير);
            }
        }
        
        // البنيات الجديدة
        for (const auto& [اسم, بنية] : خريطة_جديد) {
            if (خريطة_قديم.find(اسم) == خريطة_قديم.end()) {
                تغيير_api تغيير;
                تغيير.النوع = نوع_تغيير::إضافة;
                تغيير.الخطورة = خطورة_تغيير::تحسين;
                تغيير.الكيان = اسم;
                تغيير.الوصف = "تمت إضافة بنية جديدة: " + اسم;
                تغييرات.push_back(تغيير);
            }
        }
        
        // مقارنة البنيات المشتركة
        for (const auto& [اسم, بنية_قديمة] : خريطة_قديم) {
            auto it = خريطة_جديد.find(اسم);
            if (it != خريطة_جديد.end()) {
                قارن_حقول_بنية(*بنية_قديمة, *it->second, تغييرات);
            }
        }
    }
    
    void قارن_حقول_بنية(
        const بنية_api& قديم,
        const بنية_api& جديد,
        std::vector<تغيير_api>& تغييرات
    ) {
        std::map<std::string, const حقل_api*> خريطة_قديم;
        std::map<std::string, const حقل_api*> خريطة_جديد;
        
        for (const auto& حقل : قديم.الحقول) {
            خريطة_قديم[حقل.الاسم] = &حقل;
        }
        for (const auto& حقل : جديد.الحقول) {
            خريطة_جديد[حقل.الاسم] = &حقل;
        }
        
        // الحقول المحذوفة
        for (const auto& [اسم, حقل] : خريطة_قديم) {
            if (خريطة_جديد.find(اسم) == خريطة_جديد.end()) {
                تغيير_api تغيير;
                تغيير.النوع = نوع_تغيير::حذف;
                تغيير.الخطورة = خطورة_تغيير::كسري;
                تغيير.الكيان = قديم.الاسم;
                تغيير.الحقل = اسم;
                تغيير.الوصف = "تم حذف الحقل: " + اسم;
                تغييرات.push_back(تغيير);
            }
        }
        
        // الحقول الجديدة
        for (const auto& [اسم, حقل] : خريطة_جديد) {
            if (خريطة_قديم.find(اسم) == خريطة_قديم.end()) {
                تغيير_api تغيير;
                تغيير.النوع = نوع_تغيير::إضافة;
                تغيير.الخطورة = حقل->مطلوب ? خطورة_تغيير::كسري : خطورة_تغيير::تحسين;
                تغيير.الكيان = قديم.الاسم;
                تغيير.الحقل = اسم;
                تغيير.الوصف = "تمت إضافة حقل " + 
                              (حقل->مطلوب ? "مطلوب" : "اختياري") + 
                              ": " + اسم;
                تغييرات.push_back(تغيير);
            }
        }
        
        // تغييرات في الحقول المشتركة
        for (const auto& [اسم, حقل_قديم] : خريطة_قديم) {
            auto it = خريطة_جديد.find(اسم);
            if (it != خريطة_جديد.end()) {
                if (!(*حقل_قديم == *it->second)) {
                    تغيير_api تغيير;
                    تغيير.النوع = نوع_تغيير::تعديل;
                    تغيير.الكيان = قديم.الاسم;
                    تغيير.الحقل = اسم;
                    
                    // تحديد الخطورة والوصف
                    if (حقل_قديم->النوع != it->second->النوع) {
                        تغيير.الخطورة = خطورة_تغيير::كسري;
                        تغيير.الوصف = "تغيير نوع الحقل";
                        تغيير.القيمة_القديمة = حقل_قديم->النوع.إلى_نص();
                        تغيير.القيمة_الجديدة = it->second->النوع.إلى_نص();
                    }
                    else if (حقل_قديم->مطلوب && !it->second->مطلوب) {
                        تغيير.الخطورة = خطورة_تغيير::تحسين;
                        تغيير.الوصف = "الحقل أصبح اختيارياً";
                    }
                    else if (!حقل_قديم->مطلوب && it->second->مطلوب) {
                        تغيير.الخطورة = خطورة_تغيير::كسري;
                        تغيير.الوصف = "الحقل أصبح مطلوباً";
                    }
                    
                    تغييرات.push_back(تغيير);
                }
            }
        }
    }
    
    void قارن_النقاط(
        const std::vector<نقطة_نهاية_api>& قديم,
        const std::vector<نقطة_نهاية_api>& جديد,
        std::vector<تغيير_api>& تغييرات
    ) {
        std::map<std::string, const نقطة_نهاية_api*> خريطة_قديم;
        std::map<std::string, const نقطة_نهاية_api*> خريطة_جديد;
        
        for (const auto& نقطة : قديم) {
            خريطة_قديم[نقطة.المعرف] = &نقطة;
        }
        for (const auto& نقطة : جديد) {
            خريطة_جديد[نقطة.المعرف] = &نقطة;
        }
        
        // النقاط المحذوفة
        for (const auto& [معرف, نقطة] : خريطة_قديم) {
            if (خريطة_جديد.find(معرف) == خريطة_جديد.end()) {
                تغيير_api تغيير;
                تغيير.النوع = نوع_تغيير::حذف;
                تغيير.الخطورة = خطورة_تغيير::كسري;
                تغيير.الكيان = معرف;
                تغيير.الوصف = "تم حذف: " + نقطة->الطريقة + " " + نقطة->المسار;
                تغييرات.push_back(تغيير);
            }
        }
        
        // النقاط الجديدة
        for (const auto& [معرف, نقطة] : خريطة_جديد) {
            if (خريطة_قديم.find(معرف) == خريطة_قديم.end()) {
                تغيير_api تغيير;
                تغيير.النوع = نوع_تغيير::إضافة;
                تغيير.الخطورة = خطورة_تغيير::تحسين;
                تغيير.الكيان = معرف;
                تغيير.الوصف = "تمت إضافة: " + نقطة->الطريقة + " " + نقطة->المسار;
                تغييرات.push_back(تغيير);
            }
        }
    }
};

