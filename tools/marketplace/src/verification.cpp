// ============== C API ==============

extern "C" {

using namespace ص::سوق;

typedef struct نظام_تحقق_مقبض {
    std::unique_ptr<نظام_تحقق> نظام;
} نظام_تحقق_مقبض;

نظام_تحقق_مقبض* sad_verification_create() {
    auto مقبض = new نظام_تحقق_مقبض();
    مقبض->نظام = std::make_unique<نظام_تحقق>();
    return مقبض;
}

void sad_verification_destroy(نظام_تحقق_مقبض* مقبض) {
    delete مقبض;
}

int sad_verification_is_verified(نظام_تحقق_مقبض* مقبض, const char* developer_id) {
    if (مقبض && مقبض->نظام) {
        return مقبض->نظام->هل_موثق(developer_id ? developer_id : "") ? 1 : 0;
    }
    return 0;
}

int sad_verification_grant_badge(نظام_تحقق_مقبض* مقبض,
                                 const char* developer_id,
                                 int badge_type) {
    if (مقبض && مقبض->نظام) {
        return مقبض->نظام->منح_شارة(
            developer_id ? developer_id : "",
            static_cast<نوع_شارة>(badge_type)
        ) ? 1 : 0;
    }
    return 0;
}

}  // extern "C"
