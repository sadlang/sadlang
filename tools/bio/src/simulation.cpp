// ============== صندوق المحاكاة ==============

struct صندوق {
    متجه٣ الأبعاد;
    bool دوري_x, دوري_y, دوري_z;
    
    صندوق() : دوري_x(true), دوري_y(true), دوري_z(true) {}
    
    صندوق(double طول_x, double طول_y, double طول_z) 
        : الأبعاد(طول_x, طول_y, طول_z), 
          دوري_x(true), دوري_y(true), دوري_z(true) {}
    
    // تطبيق الشروط الحدودية الدورية
    متجه٣ تطبيق_PBC(const متجه٣& موقع) const {
        متجه٣ نتيجة = موقع;
        
        if (دوري_x) {
            while (نتيجة.x < 0) نتيجة.x += الأبعاد.x;
            while (نتيجة.x >= الأبعاد.x) نتيجة.x -= الأبعاد.x;
        }
        if (دوري_y) {
            while (نتيجة.y < 0) نتيجة.y += الأبعاد.y;
            while (نتيجة.y >= الأبعاد.y) نتيجة.y -= الأبعاد.y;
        }
        if (دوري_z) {
            while (نتيجة.z < 0) نتيجة.z += الأبعاد.z;
            while (نتيجة.z >= الأبعاد.z) نتيجة.z -= الأبعاد.z;
        }
        
        return نتيجة;
    }
    
    // حساب أقصر مسافة (صورة الحد الأدنى)
    متجه٣ أقصر_متجه(const متجه٣& من, const متجه٣& إلى) const {
        متجه٣ فرق = إلى - من;
        
        if (دوري_x) {
            while (فرق.x > الأبعاد.x / 2) فرق.x -= الأبعاد.x;
            while (فرق.x < -الأبعاد.x / 2) فرق.x += الأبعاد.x;
        }
        if (دوري_y) {
            while (فرق.y > الأبعاد.y / 2) فرق.y -= الأبعاد.y;
            while (فرق.y < -الأبعاد.y / 2) فرق.y += الأبعاد.y;
        }
        if (دوري_z) {
            while (فرق.z > الأبعاد.z / 2) فرق.z -= الأبعاد.z;
            while (فرق.z < -الأبعاد.z / 2) فرق.z += الأبعاد.z;
        }
        
        return فرق;
    }
    
    double حجم() const {
        return الأبعاد.x * الأبعاد.y * الأبعاد.z;
    }
};

// ============== حقل القوة ==============

class حقل_القوة {
protected:
    std::string الاسم_;
    
public:
    virtual ~حقل_القوة() = default;
    
    virtual std::string الاسم() const { return الاسم_; }
    
    // حساب طاقة الرابطة
    virtual double طاقة_رابطة(const ذرة& ذ١, const ذرة& ذ٢, 
                              const رابطة& ر, const صندوق& ص) const {
        متجه٣ فرق = ص.أقصر_متجه(ذ١.الموقع, ذ٢.الموقع);
        double مسافة = فرق.طول();
        double انحراف = مسافة - ر.طول_التوازن;
        return 0.5 * ر.ثابت_القوة * انحراف * انحراف;
    }
    
    // حساب قوة الرابطة
    virtual متجه٣ قوة_رابطة(const ذرة& ذ١, const ذرة& ذ٢, 
                            const رابطة& ر, const صندوق& ص) const {
        متجه٣ فرق = ص.أقصر_متجه(ذ١.الموقع, ذ٢.الموقع);
        double مسافة = فرق.طول();
        
        if (مسافة < 1e-10) return متجه٣();
        
        double انحراف = مسافة - ر.طول_التوازن;
        double مقدار = ر.ثابت_القوة * انحراف / مسافة;
        
        return فرق * مقدار;
    }
    
    // حساب طاقة الزاوية
    virtual double طاقة_زاوية(const ذرة& ذ١, const ذرة& ذ٢, const ذرة& ذ٣,
                              const زاوية& ز, const صندوق& ص) const {
        متجه٣ v1 = ص.أقصر_متجه(ذ٢.الموقع, ذ١.الموقع);
        متجه٣ v2 = ص.أقصر_متجه(ذ٢.الموقع, ذ٣.الموقع);
        
        double cos_theta = v1.نقطي(v2) / (v1.طول() * v2.طول());
        cos_theta = std::max(-1.0, std::min(1.0, cos_theta));
        double theta = std::acos(cos_theta);
        
        double انحراف = theta - ز.زاوية_التوازن;
        return 0.5 * ز.ثابت_القوة * انحراف * انحراف;
    }
    
    // حساب طاقة Lennard-Jones
    virtual double طاقة_LJ(const ذرة& ذ١, const ذرة& ذ٢, 
                           const صندوق& ص, double قطع) const {
        متجه٣ فرق = ص.أقصر_متجه(ذ١.الموقع, ذ٢.الموقع);
        double r = فرق.طول();
        
        if (r > قطع || r < 1e-10) return 0.0;
        
        // قواعد الخلط (Lorentz-Berthelot)
        double epsilon = std::sqrt(ذ١.إبسيلون * ذ٢.إبسيلون);
        double sigma = (ذ١.سيغما + ذ٢.سيغما) / 2.0;
        
        double s_r = sigma / r;
        double s_r6 = std::pow(s_r, 6);
        double s_r12 = s_r6 * s_r6;
        
        return 4.0 * epsilon * (s_r12 - s_r6);
    }
    
    // حساب قوة Lennard-Jones
    virtual متجه٣ قوة_LJ(const ذرة& ذ١, const ذرة& ذ٢, 
                         const صندوق& ص, double قطع) const {
        متجه٣ فرق = ص.أقصر_متجه(ذ١.الموقع, ذ٢.الموقع);
        double r = فرق.طول();
        
        if (r > قطع || r < 1e-10) return متجه٣();
        
        double epsilon = std::sqrt(ذ١.إبسيلون * ذ٢.إبسيلون);
        double sigma = (ذ١.سيغما + ذ٢.سيغما) / 2.0;
        
        double s_r = sigma / r;
        double s_r6 = std::pow(s_r, 6);
        double s_r12 = s_r6 * s_r6;
        
        double مقدار = 24.0 * epsilon * (2.0 * s_r12 - s_r6) / (r * r);
        
        return فرق * مقدار;
    }
    
    // حساب طاقة كولوم
    virtual double طاقة_كولوم(const ذرة& ذ١, const ذرة& ذ٢, 
                              const صندوق& ص, double قطع) const {
        متجه٣ فرق = ص.أقصر_متجه(ذ١.الموقع, ذ٢.الموقع);
        double r = فرق.طول();
        
        if (r > قطع || r < 1e-10) return 0.0;
        
        return كولوم * ذ١.الشحنة * ذ٢.الشحنة / r;
    }
    
    // حساب قوة كولوم
    virtual متجه٣ قوة_كولوم(const ذرة& ذ١, const ذرة& ذ٢, 
                            const صندوق& ص, double قطع) const {
        متجه٣ فرق = ص.أقصر_متجه(ذ١.الموقع, ذ٢.الموقع);
        double r = فرق.طول();
        
        if (r > قطع || r < 1e-10) return متجه٣();
        
        double مقدار = كولوم * ذ١.الشحنة * ذ٢.الشحنة / (r * r * r);
        
        return فرق * مقدار;
    }
};

