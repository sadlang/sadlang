// ============== المتجه ثلاثي الأبعاد ==============

struct متجه٣ {
    double x, y, z;
    
    متجه٣() : x(0), y(0), z(0) {}
    متجه٣(double _x, double _y, double _z) : x(_x), y(_y), z(_z) {}
    
    متجه٣ operator+(const متجه٣& أخر) const {
        return متجه٣(x + أخر.x, y + أخر.y, z + أخر.z);
    }
    
    متجه٣ operator-(const متجه٣& أخر) const {
        return متجه٣(x - أخر.x, y - أخر.y, z - أخر.z);
    }
    
    متجه٣ operator*(double معامل) const {
        return متجه٣(x * معامل, y * معامل, z * معامل);
    }
    
    متجه٣& operator+=(const متجه٣& أخر) {
        x += أخر.x; y += أخر.y; z += أخر.z;
        return *this;
    }
    
    متجه٣& operator-=(const متجه٣& أخر) {
        x -= أخر.x; y -= أخر.y; z -= أخر.z;
        return *this;
    }
    
    double طول() const {
        return std::sqrt(x*x + y*y + z*z);
    }
    
    double طول_مربع() const {
        return x*x + y*y + z*z;
    }
    
    متجه٣ طبيعي() const {
        double ط = طول();
        if (ط > 0) return متجه٣(x/ط, y/ط, z/ط);
        return متجه٣();
    }
    
    double نقطي(const متجه٣& أخر) const {
        return x * أخر.x + y * أخر.y + z * أخر.z;
    }
    
    متجه٣ تقاطعي(const متجه٣& أخر) const {
        return متجه٣(
            y * أخر.z - z * أخر.y,
            z * أخر.x - x * أخر.z,
            x * أخر.y - y * أخر.x
        );
    }
};

