    void تحديث_العنصر_الحالي(تقدم_مسار& تقدم, const مسار& م) {
        // إيجاد أول عنصر غير مكتمل يمكن البدء به
        for (const auto& ع : م.العناصر) {
            if (!تقدم.عناصر_مكتملة[ع.معرف]) {
                // التحقق من المتطلبات
                bool يمكن_البدء = true;
                for (const auto& متطلب : ع.متطلبات) {
                    if (!تقدم.عناصر_مكتملة[متطلب]) {
                        يمكن_البدء = false;
                        break;
                    }
                }
                
                if (يمكن_البدء) {
                    تقدم.العنصر_الحالي = ع.معرف;
                    return;
                }
            }
        }
    }
