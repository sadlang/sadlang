// ============== C API ==============

extern "C" {

using namespace ص::جامعة;

static نظام_مسارات* النظام_العام = nullptr;

void sad_paths_init() {
    if (!النظام_العام) {
        النظام_العام = new نظام_مسارات();
    }
}

void sad_paths_cleanup() {
    delete النظام_العام;
    النظام_العام = nullptr;
}

int sad_paths_count() {
    if (!النظام_العام) return 0;
    return النظام_العام->كل_المسارات().size();
}

int sad_paths_start(const char* معرف_طالب, const char* معرف_مسار) {
    if (!النظام_العام) return 0;
    return النظام_العام->بدء_مسار(معرف_طالب, معرف_مسار) ? 1 : 0;
}

int sad_paths_complete_item(const char* معرف_طالب,
                             const char* معرف_مسار,
                             const char* معرف_عنصر) {
    if (!النظام_العام) return 0;
    return النظام_العام->إكمال_عنصر(معرف_طالب, معرف_مسار, معرف_عنصر) ? 1 : 0;
}

double sad_paths_progress(const char* معرف_طالب, const char* معرف_مسار) {
    if (!النظام_العام) return 0.0;
    
    auto* تقدم = النظام_العام->الحصول_على_تقدم(معرف_طالب, معرف_مسار);
    return تقدم ? تقدم->النسبة : 0.0;
}

int sad_paths_is_complete(const char* معرف_طالب, const char* معرف_مسار) {
    if (!النظام_العام) return 0;
    
    auto* تقدم = النظام_العام->الحصول_على_تقدم(معرف_طالب, معرف_مسار);
    return (تقدم && تقدم->مكتمل) ? 1 : 0;
}

}  // extern "C"
