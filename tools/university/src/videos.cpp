namespace ص::جامعة {

// ============== أنواع الفيديو ==============

/**
 * مصدر الفيديو
 */
enum class مصدر_فيديو {
    محلي,           // ملف محلي
    يوتيوب,         // YouTube
    فيميو,          // Vimeo
    مخصص,          // رابط مخصص
    مباشر          // بث مباشر
};

/**
 * جودة الفيديو
 */
enum class جودة_فيديو {
    تلقائي,
    منخفضة_360,    // 360p
    متوسطة_480,    // 480p
    عالية_720,     // 720p
    عالية_جداً_1080 // 1080p
};

// ============== الفيديو ==============

/**
 * معلومات فيديو
 */
struct فيديو {
    std::string معرف;
    std::string عنوان;
    std::string عنوان_إنجليزي;
    std::string وصف;
    
    مصدر_فيديو المصدر;
    std::string الرابط;
    std::string معرف_خارجي;  // YouTube ID, Vimeo ID
    
    // المدة بالثواني
    int المدة = 0;
    
    // معلومات إضافية
    std::string الصورة_المصغرة;
    std::string المحاضر;
    std::string اللغة = "العربية";
    
    // ترجمات
    std::map<std::string, std::string> الترجمات;  // لغة -> رابط
    
    // معرف الدرس المرتبط
    std::string معرف_درس;
    std::string معرف_دورة;
    
    // الفصول/العلامات الزمنية
    std::vector<std::pair<int, std::string>> الفصول;  // ثانية -> عنوان
};

// ============== تقدم المشاهدة ==============

/**
 * تقدم مشاهدة فيديو
 */
struct تقدم_فيديو {
    std::string معرف_فيديو;
    std::string معرف_طالب;
    
    // الموقع الحالي (بالثواني)
    int الموقع_الحالي = 0;
    
    // المشاهدة
    int وقت_مشاهدة = 0;       // إجمالي الوقت المشاهد
    double نسبة_المشاهدة = 0.0;
    bool مكتمل = false;
    
    // الجودة
    جودة_فيديو الجودة = جودة_فيديو::تلقائي;
    
    // السرعة
    double السرعة = 1.0;  // 0.5x, 1x, 1.5x, 2x
    
    // التواريخ
    std::string أول_مشاهدة;
    std::string آخر_مشاهدة;
    
    // عدد المشاهدات
    int عدد_المشاهدات = 0;
};

// ============== ملاحظة على الفيديو ==============

/**
 * ملاحظة مرتبطة بوقت معين في الفيديو
 */
struct ملاحظة_فيديو {
    std::string معرف;
    std::string معرف_فيديو;
    std::string معرف_طالب;
    
    int الثانية;      // الوقت في الفيديو
    std::string النص;
    
    std::string التاريخ;
    bool مهمة = false;  // علامة للمراجعة
};

// ============== قائمة تشغيل ==============

/**
 * قائمة تشغيل فيديوهات
 */
struct قائمة_تشغيل {
    std::string معرف;
    std::string عنوان;
    std::string وصف;
    
    std::vector<std::string> فيديوهات;  // معرفات
    
    std::string معرف_دورة;
    
    // المدة الإجمالية
    int المدة_الإجمالية = 0;
};

// ============== نظام الفيديو ==============

/**
 * نظام إدارة فيديوهات التعلم
 */
class نظام_فيديو {
private:
    std::map<std::string, فيديو> الفيديوهات_;
    std::map<std::string, تقدم_فيديو> التقدم_;  // معرف_طالب_معرف_فيديو
    std::map<std::string, std::vector<ملاحظة_فيديو>> الملاحظات_;
    std::map<std::string, قائمة_تشغيل> القوائم_;
    
    int عداد_ = 0;
    
public:
    // ============== إدارة الفيديوهات ==============
    
    std::string إضافة_فيديو(فيديو& ف) {
        ف.معرف = "video_" + std::to_string(++عداد_);
        الفيديوهات_[ف.معرف] = ف;
        return ف.معرف;
    }
    
    فيديو* الحصول_على_فيديو(const std::string& معرف) {
        auto it = الفيديوهات_.find(معرف);
        return it != الفيديوهات_.end() ? &it->second : nullptr;
    }
    
    std::vector<فيديو> فيديوهات_الدرس(const std::string& معرف_درس) const {
        std::vector<فيديو> نتيجة;
        for (const auto& [_, ف] : الفيديوهات_) {
            if (ف.معرف_درس == معرف_درس) {
                نتيجة.push_back(ف);
            }
        }
        return نتيجة;
    }
    
    std::vector<فيديو> فيديوهات_الدورة(const std::string& معرف_دورة) const {
        std::vector<فيديو> نتيجة;
        for (const auto& [_, ف] : الفيديوهات_) {
            if (ف.معرف_دورة == معرف_دورة) {
                نتيجة.push_back(ف);
            }
        }
        return نتيجة;
    }
    
    // ============== التشغيل ==============
    
    std::string بناء_رابط_تضمين(const std::string& معرف) const {
        auto it = الفيديوهات_.find(معرف);
        if (it == الفيديوهات_.end()) return "";
        
        const auto& ف = it->second;
        
        switch (ف.المصدر) {
            case مصدر_فيديو::يوتيوب:
                return "https://www.youtube.com/embed/" + ف.معرف_خارجي;
                
            case مصدر_فيديو::فيميو:
                return "https://player.vimeo.com/video/" + ف.معرف_خارجي;
                
            case مصدر_فيديو::محلي:
            case مصدر_فيديو::مخصص:
                return ف.الرابط;
                
            case مصدر_فيديو::مباشر:
                return ف.الرابط + "?live=1";
        }
        
        return "";
    }
    
    // ============== تتبع المشاهدة ==============
    
    void تحديث_الموقع(const std::string& معرف_طالب,
                      const std::string& معرف_فيديو,
                      int الثانية) {
        std::string مفتاح = معرف_طالب + "_" + معرف_فيديو;
        
        auto& تقدم = التقدم_[مفتاح];
        تقدم.معرف_فيديو = معرف_فيديو;
        تقدم.معرف_طالب = معرف_طالب;
        
        // أول مشاهدة
        if (تقدم.أول_مشاهدة.empty()) {
            time_t now = time(nullptr);
            struct tm* tm_info = localtime(&now);
            char buffer[20];
            strftime(buffer, 20, "%Y-%m-%d %H:%M", tm_info);
            تقدم.أول_مشاهدة = buffer;
        }
        
        // تحديث الموقع
        if (الثانية > تقدم.الموقع_الحالي) {
            تقدم.وقت_مشاهدة += (الثانية - تقدم.الموقع_الحالي);
        }
        تقدم.الموقع_الحالي = الثانية;
        
        // تحديث النسبة
        auto* ف = الحصول_على_فيديو(معرف_فيديو);
        if (ف && ف->المدة > 0) {
            تقدم.نسبة_المشاهدة = 100.0 * تقدم.وقت_مشاهدة / ف->المدة;
            
            // اعتبار الفيديو مكتمل عند 90%
            if (تقدم.نسبة_المشاهدة >= 90.0) {
                تقدم.مكتمل = true;
            }
        }
        
        // آخر مشاهدة
        time_t now = time(nullptr);
        struct tm* tm_info = localtime(&now);
        char buffer[20];
        strftime(buffer, 20, "%Y-%m-%d %H:%M", tm_info);
        تقدم.آخر_مشاهدة = buffer;
    }
    
    تقدم_فيديو* الحصول_على_تقدم(const std::string& معرف_طالب,
                                const std::string& معرف_فيديو) {
        std::string مفتاح = معرف_طالب + "_" + معرف_فيديو;
        auto it = التقدم_.find(مفتاح);
        return it != التقدم_.end() ? &it->second : nullptr;
    }
    
    int موقع_الاستئناف(const std::string& معرف_طالب,
                       const std::string& معرف_فيديو) {
        auto* تقدم = الحصول_على_تقدم(معرف_طالب, معرف_فيديو);
        return تقدم ? تقدم->الموقع_الحالي : 0;
    }
    
    // ============== الملاحظات ==============
    
    std::string إضافة_ملاحظة(const std::string& معرف_طالب,
                             const std::string& معرف_فيديو,
                             int الثانية,
                             const std::string& النص) {
        ملاحظة_فيديو م;
        م.معرف = "note_" + std::to_string(++عداد_);
        م.معرف_فيديو = معرف_فيديو;
        م.معرف_طالب = معرف_طالب;
        م.الثانية = الثانية;
        م.النص = النص;
        
        time_t now = time(nullptr);
        struct tm* tm_info = localtime(&now);
        char buffer[20];
        strftime(buffer, 20, "%Y-%m-%d %H:%M", tm_info);
        م.التاريخ = buffer;
        
        std::string مفتاح = معرف_طالب + "_" + معرف_فيديو;
        الملاحظات_[مفتاح].push_back(م);
        
        return م.معرف;
    }
    
    std::vector<ملاحظة_فيديو> ملاحظات_الفيديو(const std::string& معرف_طالب,
                                               const std::string& معرف_فيديو) {
        std::string مفتاح = معرف_طالب + "_" + معرف_فيديو;
        auto it = الملاحظات_.find(مفتاح);
        return it != الملاحظات_.end() ? it->second : std::vector<ملاحظة_فيديو>();
    }
    
    // ============== قوائم التشغيل ==============
    
    std::string إنشاء_قائمة(const std::string& عنوان,
                            const std::vector<std::string>& فيديوهات) {
        قائمة_تشغيل ق;
        ق.معرف = "playlist_" + std::to_string(++عداد_);
        ق.عنوان = عنوان;
        ق.فيديوهات = فيديوهات;
        
        // حساب المدة الإجمالية
        for (const auto& معرف : فيديوهات) {
            auto* ف = الحصول_على_فيديو(معرف);
            if (ف) {
                ق.المدة_الإجمالية += ف->المدة;
            }
        }
        
        القوائم_[ق.معرف] = ق;
        return ق.معرف;
    }
    
    قائمة_تشغيل* الحصول_على_قائمة(const std::string& معرف) {
        auto it = القوائم_.find(معرف);
        return it != القوائم_.end() ? &it->second : nullptr;
    }
    
    // ============== تحويل الوقت ==============
    
    static std::string تنسيق_الوقت(int ثواني) {
        int ساعات = ثواني / 3600;
        int دقائق = (ثواني % 3600) / 60;
        int ث = ثواني % 60;
        
        char buffer[16];
        if (ساعات > 0) {
            snprintf(buffer, 16, "%d:%02d:%02d", ساعات, دقائق, ث);
        } else {
            snprintf(buffer, 16, "%d:%02d", دقائق, ث);
        }
        
        return buffer;
    }
    
    // ============== الإحصائيات ==============
    
    int إجمالي_وقت_المشاهدة(const std::string& معرف_طالب) const {
        int إجمالي = 0;
        
        for (const auto& [مفتاح, تقدم] : التقدم_) {
            if (تقدم.معرف_طالب == معرف_طالب) {
                إجمالي += تقدم.وقت_مشاهدة;
            }
        }
        
        return إجمالي;
    }
    
    int عدد_الفيديوهات_المكتملة(const std::string& معرف_طالب) const {
        int عدد = 0;
        
        for (const auto& [مفتاح, تقدم] : التقدم_) {
            if (تقدم.معرف_طالب == معرف_طالب && تقدم.مكتمل) {
                عدد++;
            }
        }
        
        return عدد;
    }
};

}  // namespace ص::جامعة

// ============== C API ==============

extern "C" {

using namespace ص::جامعة;

static نظام_فيديو* النظام_العام = nullptr;

void sad_videos_init() {
    if (!النظام_العام) {
        النظام_العام = new نظام_فيديو();
    }
}

void sad_videos_cleanup() {
    delete النظام_العام;
    النظام_العام = nullptr;
}

void sad_videos_update_position(const char* معرف_طالب,
                                 const char* معرف_فيديو,
                                 int الثانية) {
    if (!النظام_العام) return;
    النظام_العام->تحديث_الموقع(معرف_طالب, معرف_فيديو, الثانية);
}

int sad_videos_resume_position(const char* معرف_طالب, const char* معرف_فيديو) {
    if (!النظام_العام) return 0;
    return النظام_العام->موقع_الاستئناف(معرف_طالب, معرف_فيديو);
}

int sad_videos_total_watched(const char* معرف_طالب) {
    if (!النظام_العام) return 0;
    return النظام_العام->إجمالي_وقت_المشاهدة(معرف_طالب);
}

int sad_videos_completed_count(const char* معرف_طالب) {
    if (!النظام_العام) return 0;
    return النظام_العام->عدد_الفيديوهات_المكتملة(معرف_طالب);
}

const char* sad_videos_add_note(const char* معرف_طالب,
                                 const char* معرف_فيديو,
                                 int الثانية,
                                 const char* النص) {
    if (!النظام_العام) return "";
    
    static std::string نتيجة;
    نتيجة = النظام_العام->إضافة_ملاحظة(معرف_طالب, معرف_فيديو, الثانية, النص);
    
    return نتيجة.c_str();
}

}  // extern "C"
