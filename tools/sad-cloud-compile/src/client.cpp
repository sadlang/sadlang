/**
 * طابور مهام الترجمة
 */
class طابور_ترجمة {
public:
    /**
     * إضافة مهمة للطابور
     */
    void أضف(مهمة_ترجمة مهمة) {
        الطابور_.push(std::move(مهمة));
    }
    
    /**
     * الحصول على المهمة التالية
     */
    std::optional<مهمة_ترجمة> التالية() {
        if (الطابور_.empty()) {
            return std::nullopt;
        }
        
        مهمة_ترجمة مهمة = std::move(const_cast<مهمة_ترجمة&>(الطابور_.front()));
        الطابور_.pop();
        return مهمة;
    }
    
    /**
     * هل الطابور فارغ؟
     */
    bool فارغ() const {
        return الطابور_.empty();
    }
    
    /**
     * عدد المهام في الانتظار
     */
    size_t الحجم() const {
        return الطابور_.size();
    }

private:
    std::queue<مهمة_ترجمة> الطابور_;
};

