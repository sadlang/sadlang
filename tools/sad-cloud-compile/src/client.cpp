/**
 * واجهة الاتصال بالخادم
 */
class واجهة_نقل {
public:
    virtual ~واجهة_نقل() = default;
    
    virtual bool اتصل(const إعدادات_اتصال& إعدادات) = 0;
    virtual void افصل() = 0;
    virtual bool متصل() const = 0;
    
    virtual std::string أرسل_طلب(
        const std::string& المسار,
        const std::string& البيانات
    ) = 0;
    
    virtual std::string استلم_ملف(const std::string& معرف_الملف) = 0;
};

/**
 * نقل HTTP/HTTPS
 */
class نقل_https : public واجهة_نقل {
public:
    bool اتصل(const إعدادات_اتصال& إعدادات) override {
        الإعدادات_ = إعدادات;
        // في التنفيذ الحقيقي، نتصل بالخادم
        متصل_ = true;
        return true;
    }
    
    void افصل() override {
        متصل_ = false;
    }
    
    bool متصل() const override {
        return متصل_;
    }
    
    std::string أرسل_طلب(
        const std::string& المسار,
        const std::string& البيانات
    ) override {
        if (!متصل_) return "";
        
        // في التنفيذ الحقيقي، نرسل طلب HTTP
        // هنا نُرجع استجابة وهمية للتوضيح
        return "{\"status\": \"ok\", \"job_id\": \"job_123\"}";
    }
    
    std::string استلم_ملف(const std::string& معرف_الملف) override {
        if (!متصل_) return "";
        // استلام ملف من الخادم
        return "";
    }

private:
    إعدادات_اتصال الإعدادات_;
    bool متصل_ = false;
};

