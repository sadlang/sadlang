/**
 * حالة المهمة
 */
enum class حالة_مهمة {
    في_الانتظار,
    قيد_الإرسال,
    قيد_الترجمة,
    مكتملة,
    فاشلة
};

/**
 * ملف للترجمة
 */
struct ملف_ترجمة {
    std::string المسار;
    std::string المحتوى;
    std::string الـhash;
    size_t الحجم;
};

/**
 * نتيجة ترجمة ملف
 */
struct نتيجة_ملف {
    std::string المسار;
    bool نجحت;
    std::string الناتج_المُترجم;  // Object code
    std::vector<std::string> الأخطاء;
    std::vector<std::string> التحذيرات;
    double زمن_الترجمة;  // بالثواني
};

/**
 * مهمة ترجمة
 */
struct مهمة_ترجمة {
    std::string المعرف;
    std::vector<ملف_ترجمة> الملفات;
    حالة_مهمة الحالة = حالة_مهمة::في_الانتظار;
    
    // الإعدادات
    std::string إصدار_المترجم;
    std::vector<std::string> خيارات_الترجمة;
    std::string المنصة_الهدف;  // windows-x64, linux-x64, etc.
    
    // النتائج
    std::vector<نتيجة_ملف> النتائج;
    
    // التوقيت
    std::chrono::system_clock::time_point وقت_البدء;
    std::chrono::system_clock::time_point وقت_الانتهاء;
};

