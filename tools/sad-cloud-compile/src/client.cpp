/**
 * إعدادات الاتصال بالسحابة
 */
struct إعدادات_اتصال {
    std::string عنوان_الخادم = "compile.sad-lang.org";
    int المنفذ = 443;
    bool استخدم_tls = true;
    std::string مفتاح_api = "";
    
    // مهلات (بالثواني)
    int مهلة_الاتصال = 30;
    int مهلة_الترجمة = 3600;  // ساعة
    
    // إعادة المحاولة
    int محاولات_إعادة = 3;
    int تأخير_إعادة = 5;
};

