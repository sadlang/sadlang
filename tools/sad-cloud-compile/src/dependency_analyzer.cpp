/**
 * مجموعة الترجمة (ملفات يمكن ترجمتها بالتوازي)
 */
struct مجموعة_ترجمة {
    int المستوى;
    std::vector<std::string> الملفات;
    
    // التقدير
    size_t الحجم_الكلي = 0;
    int عدد_الملفات = 0;
};

/**
 * محلل مستويات الترجمة
 */
class محلل_مستويات {
public:
    /**
     * حساب مستويات الترجمة
     * 
     * يستخدم خوارزمية Kahn للترتيب الطوبولوجي
     */
    std::vector<مجموعة_ترجمة> حلل(رسم_تبعيات& رسم) {
        std::vector<مجموعة_ترجمة> مستويات;
        
        // حساب درجة الدخول لكل عقدة
        std::unordered_map<std::string, int> درجة_دخول;
        for (const auto& [مسار, عقدة] : رسم.العقد()) {
            درجة_دخول[مسار] = عقدة.يعتمد_على.size();
        }
        
        // ابدأ بالعقد بدون تبعيات (درجة دخول = 0)
        std::queue<std::string> جاهزة;
        for (const auto& [مسار, درجة] : درجة_دخول) {
            if (درجة == 0) {
                جاهزة.push(مسار);
            }
        }
        
        int مستوى_حالي = 0;
        
        while (!جاهزة.empty()) {
            مجموعة_ترجمة مجموعة;
            مجموعة.المستوى = مستوى_حالي;
            
            // أضف كل العقد الجاهزة لهذا المستوى
            std::queue<std::string> جاهزة_التالية;
            
            while (!جاهزة.empty()) {
                std::string مسار = جاهزة.front();
                جاهزة.pop();
                
                // تعيين المستوى
                auto* عقدة = رسم.احصل(مسار);
                if (عقدة) {
                    عقدة->مستوى = مستوى_حالي;
                }
                
                مجموعة.الملفات.push_back(مسار);
                مجموعة.عدد_الملفات++;
                
                // تحديث المعتمدين
                if (عقدة) {
                    for (const auto& معتمد : عقدة->معتمد_عليه_من) {
                        درجة_دخول[معتمد]--;
                        if (درجة_دخول[معتمد] == 0) {
                            جاهزة_التالية.push(معتمد);
                        }
                    }
                }
            }
            
            if (!مجموعة.الملفات.empty()) {
                مستويات.push_back(مجموعة);
            }
            
            جاهزة = جاهزة_التالية;
            مستوى_حالي++;
        }
        
        return مستويات;
    }
    
    /**
     * اكتشاف الدورات في التبعيات
     */
    std::vector<std::vector<std::string>> اكتشف_دورات(
        const رسم_تبعيات& رسم
    ) {
        std::vector<std::vector<std::string>> دورات;
        std::unordered_set<std::string> زُرت;
        std::unordered_set<std::string> في_المسار;
        std::vector<std::string> المسار_الحالي;
        
        for (const auto& [مسار, _] : رسم.العقد()) {
            if (زُرت.find(مسار) == زُرت.end()) {
                اكتشف_دورة_من(رسم, مسار, زُرت, في_المسار, 
                              المسار_الحالي, دورات);
            }
        }
        
        return دورات;
    }

private:
    void اكتشف_دورة_من(
        const رسم_تبعيات& رسم,
        const std::string& عقدة,
        std::unordered_set<std::string>& زُرت,
        std::unordered_set<std::string>& في_المسار,
        std::vector<std::string>& المسار_الحالي,
        std::vector<std::vector<std::string>>& دورات
    ) {
        زُرت.insert(عقدة);
        في_المسار.insert(عقدة);
        المسار_الحالي.push_back(عقدة);
        
        auto it = رسم.العقد().find(عقدة);
        if (it != رسم.العقد().end()) {
            for (const auto& تبعية : it->second.يعتمد_على) {
                if (في_المسار.find(تبعية) != في_المسار.end()) {
                    // وجدنا دورة!
                    std::vector<std::string> دورة;
                    bool بدأت = false;
                    for (const auto& ع : المسار_الحالي) {
                        if (ع == تبعية) بدأت = true;
                        if (بدأت) دورة.push_back(ع);
                    }
                    دورة.push_back(تبعية);
                    دورات.push_back(دورة);
                } else if (زُرت.find(تبعية) == زُرت.end()) {
                    اكتشف_دورة_من(رسم, تبعية, زُرت, في_المسار,
                                  المسار_الحالي, دورات);
                }
            }
        }
        
        في_المسار.erase(عقدة);
        المسار_الحالي.pop_back();
    }
};

