/**
 * محلل التبعيات من الكود المصدري
 */
class محلل_تبعيات {
public:
    /**
     * تحليل ملف واستخراج تبعياته
     */
    std::vector<std::string> حلل_ملف(
        const std::string& مسار,
        const std::string& محتوى
    ) {
        std::vector<std::string> تبعيات;
        
        // البحث عن عبارات الاستيراد
        // استورد "ملف.sad"
        // استورد حزمة.وحدة
        
        size_t pos = 0;
        while ((pos = محتوى.find("استورد", pos)) != std::string::npos) {
            pos += 12;  // تجاوز "استورد"
            
            // تجاوز المسافات
            while (pos < محتوى.size() && 
                   (محتوى[pos] == ' ' || محتوى[pos] == '\t')) {
                pos++;
            }
            
            if (pos >= محتوى.size()) break;
            
            // استخراج اسم الاستيراد
            std::string استيراد;
            
            if (محتوى[pos] == '"') {
                // استيراد مسار: استورد "ملف.sad"
                pos++;
                while (pos < محتوى.size() && محتوى[pos] != '"') {
                    استيراد += محتوى[pos++];
                }
            } else {
                // استيراد حزمة: استورد حزمة.وحدة
                while (pos < محتوى.size() && 
                       محتوى[pos] != '\n' && 
                       محتوى[pos] != ' ' &&
                       محتوى[pos] != '\r') {
                    استيراد += محتوى[pos++];
                }
            }
            
            if (!استيراد.empty()) {
                تبعيات.push_back(حوِّل_لمسار(استيراد, مسار));
            }
        }
        
        return تبعيات;
    }
    
    /**
     * بناء رسم التبعيات من مجموعة ملفات
     */
    رسم_تبعيات ابنِ_رسم(
        const std::unordered_map<std::string, std::string>& ملفات
    ) {
        رسم_تبعيات رسم;
        
        for (const auto& [مسار, محتوى] : ملفات) {
            رسم.أضف_ملف(مسار);
            
            auto تبعيات = حلل_ملف(مسار, محتوى);
            for (const auto& تبعية : تبعيات) {
                رسم.أضف_تبعية(مسار, تبعية);
            }
        }
        
        return رسم;
    }

private:
    /**
     * تحويل اسم الاستيراد لمسار ملف
     */
    std::string حوِّل_لمسار(
        const std::string& استيراد,
        const std::string& ملف_حالي
    ) {
        // إذا كان بالفعل مسار، أرجعه
        if (استيراد.find(".sad") != std::string::npos) {
            return استيراد;
        }
        
        // تحويل حزمة.وحدة إلى حزمة/وحدة.sad
        std::string مسار = استيراد;
        std::replace(مسار.begin(), مسار.end(), '.', '/');
        return مسار + ".sad";
    }
};

