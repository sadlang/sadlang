/**
 * رسم بياني للتبعيات
 */
class رسم_تبعيات {
public:
    /**
     * إضافة ملف
     */
    void أضف_ملف(const std::string& مسار, const std::string& hash = "") {
        if (العقد_.find(مسار) == العقد_.end()) {
            عقدة_تبعية عقدة;
            عقدة.المسار = مسار;
            عقدة.الـhash = hash;
            العقد_[مسار] = عقدة;
        }
    }
    
    /**
     * إضافة تبعية (أ يعتمد على ب)
     */
    void أضف_تبعية(const std::string& من, const std::string& إلى) {
        أضف_ملف(من);
        أضف_ملف(إلى);
        
        العقد_[من].يعتمد_على.insert(إلى);
        العقد_[إلى].معتمد_عليه_من.insert(من);
    }
    
    /**
     * الحصول على عقدة
     */
    عقدة_تبعية* احصل(const std::string& مسار) {
        auto it = العقد_.find(مسار);
        return it != العقد_.end() ? &it->second : nullptr;
    }
    
    /**
     * كل العقد
     */
    const std::unordered_map<std::string, عقدة_تبعية>& العقد() const {
        return العقد_;
    }
    
    /**
     * عدد الملفات
     */
    size_t الحجم() const {
        return العقد_.size();
    }

private:
    std::unordered_map<std::string, عقدة_تبعية> العقد_;
};

