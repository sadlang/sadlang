/**
 * خادم ترجمة
 */
struct خادم_ترجمة {
    std::string المعرف;
    std::string العنوان;
    int الحمل_الحالي;
    int السعة_القصوى;
    double سرعة_نسبية;  // 1.0 = متوسط
};

/**
 * موزع مهام الترجمة على الخوادم
 */
class موزع_مهام {
public:
    /**
     * إضافة خادم
     */
    void أضف_خادم(const خادم_ترجمة& خادم) {
        الخوادم_[خادم.المعرف] = خادم;
    }
    
    /**
     * توزيع مجموعة ملفات على الخوادم
     */
    std::unordered_map<std::string, std::vector<std::string>> وزِّع(
        const std::vector<std::string>& ملفات
    ) {
        std::unordered_map<std::string, std::vector<std::string>> توزيع;
        
        if (الخوادم_.empty() || ملفات.empty()) {
            return توزيع;
        }
        
        // ترتيب الخوادم حسب السعة المتاحة
        std::vector<خادم_ترجمة*> خوادم_مرتبة;
        for (auto& [_, خادم] : الخوادم_) {
            خوادم_مرتبة.push_back(&خادم);
        }
        
        std::sort(خوادم_مرتبة.begin(), خوادم_مرتبة.end(),
            [](const خادم_ترجمة* أ, const خادم_ترجمة* ب) {
                int سعة_أ = أ->السعة_القصوى - أ->الحمل_الحالي;
                int سعة_ب = ب->السعة_القصوى - ب->الحمل_الحالي;
                return سعة_أ * أ->سرعة_نسبية > سعة_ب * ب->سرعة_نسبية;
            });
        
        // توزيع الملفات بالتناوب
        size_t فهرس_خادم = 0;
        for (const auto& ملف : ملفات) {
            auto* خادم = خوادم_مرتبة[فهرس_خادم % خوادم_مرتبة.size()];
            
            // تحقق من السعة
            int سعة_متاحة = خادم->السعة_القصوى - خادم->الحمل_الحالي;
            if (سعة_متاحة > 0) {
                توزيع[خادم->المعرف].push_back(ملف);
                خادم->الحمل_الحالي++;
            }
            
            فهرس_خادم++;
        }
        
        return توزيع;
    }
    
    /**
     * توليد تقرير التوزيع
     */
    std::string ولِّد_تقرير(
        const std::vector<مجموعة_ترجمة>& مستويات
    ) {
        std::stringstream تقرير;
        
        تقرير << "╔════════════════════════════════════════════════╗\n";
        تقرير << "║            تقرير توزيع الترجمة                 ║\n";
        تقرير << "╠════════════════════════════════════════════════╣\n";
        
        int إجمالي_ملفات = 0;
        for (const auto& مستوى : مستويات) {
            إجمالي_ملفات += مستوى.عدد_الملفات;
        }
        
        تقرير << "║ إجمالي الملفات: " << إجمالي_ملفات << "\n";
        تقرير << "║ عدد المستويات: " << مستويات.size() << "\n";
        تقرير << "║ عدد الخوادم: " << الخوادم_.size() << "\n";
        تقرير << "╠════════════════════════════════════════════════╣\n";
        
        for (const auto& مستوى : مستويات) {
            تقرير << "║ المستوى " << مستوى.المستوى << ": ";
            تقرير << مستوى.عدد_الملفات << " ملف (متوازي)\n";
            
            for (const auto& ملف : مستوى.الملفات) {
                تقرير << "║   └─ " << ملف << "\n";
            }
        }
        
        تقرير << "╚════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }

private:
    std::unordered_map<std::string, خادم_ترجمة> الخوادم_;
};

