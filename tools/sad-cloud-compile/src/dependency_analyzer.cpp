/**
 * عقدة في رسم التبعيات
 */
struct عقدة_تبعية {
    std::string المسار;
    std::string الـhash;
    
    // التبعيات المباشرة (الملفات التي يستوردها)
    std::unordered_set<std::string> يعتمد_على;
    
    // المعتمدون (الملفات التي تستورده)
    std::unordered_set<std::string> معتمد_عليه_من;
    
    // مستوى الترجمة (0 = لا تبعيات)
    int مستوى = -1;
    
    // حالة الترجمة
    bool مُترجَم = false;
    bool قيد_الترجمة = false;
};

