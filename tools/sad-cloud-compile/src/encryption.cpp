/**
 * خوارزميات التشفير المدعومة
 */
enum class خوارزمية {
    AES_256_GCM,      // الافتراضي - آمن جداً
    ChaCha20_Poly1305 // بديل سريع
};

/**
 * نتيجة التشفير
 */
struct نتيجة_تشفير {
    std::vector<uint8_t> البيانات_المشفرة;
    std::array<uint8_t, حجم_iv> iv;
    std::array<uint8_t, 16> tag;  // للتحقق من السلامة
    bool نجح = false;
    std::string خطأ;
};

/**
 * نتيجة فك التشفير
 */
struct نتيجة_فك_تشفير {
    std::vector<uint8_t> البيانات;
    bool نجح = false;
    std::string خطأ;
};

