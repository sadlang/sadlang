/**
 * حساب Hash للتحقق من السلامة
 */
class حاسب_hash {
public:
    /**
     * حساب SHA-256 (مُبسَّط)
     */
    static std::array<uint8_t, 32> sha256(const std::vector<uint8_t>& البيانات) {
        // في الإنتاج: استخدم مكتبة تشفير حقيقية
        std::array<uint8_t, 32> hash;
        hash.fill(0);
        
        for (size_t i = 0; i < البيانات.size(); i++) {
            hash[i % 32] ^= البيانات[i];
            // محاكاة بسيطة للتشتيت
            hash[(i + 1) % 32] = (hash[(i + 1) % 32] + البيانات[i]) & 0xFF;
        }
        
        return hash;
    }
    
    /**
     * تحويل hash إلى سلسلة hex
     */
    static std::string إلى_hex(const std::array<uint8_t, 32>& hash) {
        static const char* hex = "0123456789abcdef";
        std::string نتيجة;
        نتيجة.reserve(64);
        
        for (uint8_t byte : hash) {
            نتيجة += hex[byte >> 4];
            نتيجة += hex[byte & 0x0F];
        }
        
        return نتيجة;
    }
};

