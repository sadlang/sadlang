/**
 * حجم المفتاح (256 بت = 32 بايت)
 */
constexpr size_t حجم_المفتاح = 32;

/**
 * حجم IV (128 بت = 16 بايت)
 */
constexpr size_t حجم_iv = 16;

/**
 * مفتاح تشفير
 */
struct مفتاح {
    std::array<uint8_t, حجم_المفتاح> البيانات;
    
    /**
     * توليد مفتاح عشوائي
     */
    static مفتاح عشوائي() {
        مفتاح م;
        std::random_device rd;
        std::mt19937_64 gen(rd());
        std::uniform_int_distribution<uint8_t> dist(0, 255);
        
        for (auto& byte : م.البيانات) {
            byte = dist(gen);
        }
        
        return م;
    }
    
    /**
     * من سلسلة Base64
     */
    static مفتاح من_base64(const std::string& b64);
    
    /**
     * تحويل إلى Base64
     */
    std::string إلى_base64() const;
    
    /**
     * مسح المفتاح من الذاكرة (أمان)
     */
    void امسح() {
        std::memset(البيانات.data(), 0, حجم_المفتاح);
    }
};

/**
 * زوج مفاتيح (للتشفير غير المتماثل)
 */
struct زوج_مفاتيح {
    مفتاح عام;
    مفتاح خاص;
    
    /**
     * توليد زوج مفاتيح
     */
    static زوج_مفاتيح ولِّد() {
        // في التنفيذ الحقيقي، نستخدم خوارزمية مثل X25519
        return زوج_مفاتيح{مفتاح::عشوائي(), مفتاح::عشوائي()};
    }
};

