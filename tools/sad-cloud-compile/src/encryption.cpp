/**
 * جلسة تشفير End-to-End
 */
class جلسة_e2e {
public:
    /**
     * إنشاء جلسة جديدة
     */
    جلسة_e2e() : المحرك_(خوارزمية::AES_256_GCM) {
        المفاتيح_ = زوج_مفاتيح::ولِّد();
        مفتاح_الجلسة_ = مفتاح::عشوائي();
    }
    
    /**
     * الحصول على المفتاح العام (لإرساله للخادم)
     */
    const مفتاح& المفتاح_العام() const {
        return المفاتيح_.عام;
    }
    
    /**
     * إعداد مفتاح الجلسة المشترك
     */
    bool أعدّ_مفتاح_مشترك(const مفتاح& مفتاح_الخادم_العام) {
        // في التنفيذ الحقيقي: Diffie-Hellman key exchange
        // هنا نُبسّط
        
        for (size_t i = 0; i < حجم_المفتاح; i++) {
            مفتاح_الجلسة_.البيانات[i] = 
                المفاتيح_.خاص.البيانات[i] ^ مفتاح_الخادم_العام.البيانات[i];
        }
        
        مُعدّ_ = true;
        return true;
    }
    
    /**
     * تشفير ملف للإرسال
     */
    نتيجة_تشفير شفِّر_ملف(const std::vector<uint8_t>& محتوى) {
        if (!مُعدّ_) {
            نتيجة_تشفير نتيجة;
            نتيجة.خطأ = "الجلسة غير مُعدَّة";
            return نتيجة;
        }
        
        return المحرك_.شفِّر(محتوى, مفتاح_الجلسة_);
    }
    
    /**
     * فك تشفير ملف مستلم
     */
    نتيجة_فك_تشفير فُك_تشفير_ملف(const نتيجة_تشفير& مشفر) {
        if (!مُعدّ_) {
            نتيجة_فك_تشفير نتيجة;
            نتيجة.خطأ = "الجلسة غير مُعدَّة";
            return نتيجة;
        }
        
        return المحرك_.فُك_تشفير(مشفر, مفتاح_الجلسة_);
    }
    
    /**
     * إنهاء الجلسة ومسح المفاتيح
     */
    void أنهِ() {
        المفاتيح_.عام.امسح();
        المفاتيح_.خاص.امسح();
        مفتاح_الجلسة_.امسح();
        مُعدّ_ = false;
    }
    
    /**
     * هل الجلسة مُعدَّة؟
     */
    bool مُعدَّة() const { return مُعدّ_; }

private:
    محرك_تشفير المحرك_;
    زوج_مفاتيح المفاتيح_;
    مفتاح مفتاح_الجلسة_;
    bool مُعدّ_ = false;
};

