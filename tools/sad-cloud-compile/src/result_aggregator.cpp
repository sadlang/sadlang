/**
 * مُولِّد تقارير الترجمة
 */
class مولد_تقارير {
public:
    /**
     * توليد تقرير نصي
     */
    std::string ولِّد_تقرير_نصي(const نتيجة_مجمعة& نتيجة) {
        std::stringstream تقرير;
        
        تقرير << "╔════════════════════════════════════════════════════════╗\n";
        تقرير << "║            تقرير الترجمة السحابية                      ║\n";
        تقرير << "╠════════════════════════════════════════════════════════╣\n";
        
        // الحالة العامة
        تقرير << "║ الحالة: " << (نتيجة.نجحت ? "✓ نجاح" : "✗ فشل") << "\n";
        تقرير << "║ الرسالة: " << نتيجة.رسالة << "\n";
        تقرير << "╠════════════════════════════════════════════════════════╣\n";
        
        // الإحصائيات
        تقرير << "║                     الإحصائيات                         ║\n";
        تقرير << "╠════════════════════════════════════════════════════════╣\n";
        
        int إجمالي = نتيجة.الإحصائيات.ملفات_ناجحة + 
                     نتيجة.الإحصائيات.ملفات_فاشلة;
        
        تقرير << "║ الملفات: " << نتيجة.الإحصائيات.ملفات_ناجحة 
              << "/" << إجمالي << " نجحت\n";
        تقرير << "║ الأخطاء: " << نتيجة.الإحصائيات.إجمالي_أخطاء << "\n";
        تقرير << "║ التحذيرات: " << نتيجة.الإحصائيات.إجمالي_تحذيرات << "\n";
        تقرير << "║ زمن الترجمة: " << نتيجة.الإحصائيات.زمن_ترجمة_كلي 
              << " ثانية\n";
        تقرير << "║ حجم المصدر: " << تنسيق_حجم(
            نتيجة.الإحصائيات.حجم_مصدر_كلي) << "\n";
        تقرير << "║ حجم الناتج: " << تنسيق_حجم(
            نتيجة.الإحصائيات.حجم_ناتج_كلي) << "\n";
        
        // أطول ملف
        if (!نتيجة.الإحصائيات.أطول_ملف_اسم.empty()) {
            تقرير << "║ أطول ملف: " << نتيجة.الإحصائيات.أطول_ملف_اسم;
            تقرير << " (" << نتيجة.الإحصائيات.أطول_ملف_ثواني << "ث)\n";
        }
        
        // الأخطاء
        if (!نتيجة.كل_الأخطاء.empty()) {
            تقرير << "╠════════════════════════════════════════════════════════╣\n";
            تقرير << "║                      الأخطاء                           ║\n";
            تقرير << "╠════════════════════════════════════════════════════════╣\n";
            
            for (const auto& خطأ : نتيجة.كل_الأخطاء) {
                تقرير << "║ ✗ " << خطأ << "\n";
            }
        }
        
        // التحذيرات
        if (!نتيجة.كل_التحذيرات.empty()) {
            تقرير << "╠════════════════════════════════════════════════════════╣\n";
            تقرير << "║                    التحذيرات                           ║\n";
            تقرير << "╠════════════════════════════════════════════════════════╣\n";
            
            for (const auto& تحذير : نتيجة.كل_التحذيرات) {
                تقرير << "║ ⚠ " << تحذير << "\n";
            }
        }
        
        تقرير << "╚════════════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }
    
    /**
     * توليد تقرير JSON
     */
    std::string ولِّد_تقرير_json(const نتيجة_مجمعة& نتيجة) {
        std::stringstream json;
        
        json << "{\n";
        json << "  \"success\": " << (نتيجة.نجحت ? "true" : "false") << ",\n";
        json << "  \"message\": \"" << نتيجة.رسالة << "\",\n";
        
        json << "  \"statistics\": {\n";
        json << "    \"files_succeeded\": " << نتيجة.الإحصائيات.ملفات_ناجحة << ",\n";
        json << "    \"files_failed\": " << نتيجة.الإحصائيات.ملفات_فاشلة << ",\n";
        json << "    \"total_errors\": " << نتيجة.الإحصائيات.إجمالي_أخطاء << ",\n";
        json << "    \"total_warnings\": " << نتيجة.الإحصائيات.إجمالي_تحذيرات << ",\n";
        json << "    \"compile_time_seconds\": " << نتيجة.الإحصائيات.زمن_ترجمة_كلي << ",\n";
        json << "    \"source_size_bytes\": " << نتيجة.الإحصائيات.حجم_مصدر_كلي << ",\n";
        json << "    \"output_size_bytes\": " << نتيجة.الإحصائيات.حجم_ناتج_كلي << "\n";
        json << "  },\n";
        
        json << "  \"errors\": [";
        for (size_t i = 0; i < نتيجة.كل_الأخطاء.size(); i++) {
            if (i > 0) json << ", ";
            json << "\"" << نتيجة.كل_الأخطاء[i] << "\"";
        }
        json << "],\n";
        
        json << "  \"warnings\": [";
        for (size_t i = 0; i < نتيجة.كل_التحذيرات.size(); i++) {
            if (i > 0) json << ", ";
            json << "\"" << نتيجة.كل_التحذيرات[i] << "\"";
        }
        json << "]\n";
        
        json << "}";
        
        return json.str();
    }

private:
    std::string تنسيق_حجم(size_t بايت) {
        const char* وحدات[] = {"B", "KB", "MB", "GB"};
        int وحدة = 0;
        double حجم = بايت;
        
        while (حجم >= 1024 && وحدة < 3) {
            حجم /= 1024;
            وحدة++;
        }
        
        std::stringstream نتيجة;
        نتيجة << std::fixed << std::setprecision(2) << حجم << " " << وحدات[وحدة];
        return نتيجة.str();
    }
};

