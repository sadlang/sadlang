/**
 * ملخص الإحصائيات
 */
struct ملخص_إحصائيات {
    int ملفات_ناجحة = 0;
    int ملفات_فاشلة = 0;
    int إجمالي_أخطاء = 0;
    int إجمالي_تحذيرات = 0;
    
    double زمن_ترجمة_كلي = 0;
    double أطول_ملف_ثواني = 0;
    std::string أطول_ملف_اسم;
    
    size_t حجم_مصدر_كلي = 0;
    size_t حجم_ناتج_كلي = 0;
    float نسبة_الضغط = 0;
};

/**
 * النتيجة النهائية المُجمَّعة
 */
struct نتيجة_مجمعة {
    bool نجحت = false;
    std::string رسالة;
    
    // كل النتائج الجزئية
    std::vector<نتيجة_جزئية> النتائج;
    
    // الملفات الناتجة
    std::vector<std::string> ملفات_الناتج;
    
    // الأخطاء المُجمَّعة
    std::vector<std::string> كل_الأخطاء;
    std::vector<std::string> كل_التحذيرات;
    
    // الإحصائيات
    ملخص_إحصائيات الإحصائيات;
    
    // التوقيت
    std::chrono::system_clock::time_point وقت_البدء;
    std::chrono::system_clock::time_point وقت_الانتهاء;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُجمِّع النتائج
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مُجمِّع نتائج الترجمة
 */
class مجمع_نتائج {
public:
    /**
     * بدء جلسة تجميع
     */
    void ابدأ_جلسة(const std::vector<std::string>& الملفات_المتوقعة) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        النتيجة_ = نتيجة_مجمعة{};
        النتيجة_.وقت_البدء = std::chrono::system_clock::now();
        
        // تهيئة نتائج في الانتظار
        for (const auto& ملف : الملفات_المتوقعة) {
            نتيجة_جزئية جزئية;
            جزئية.مسار_المصدر = ملف;
            جزئية.الحالة = حالة_نتيجة::في_الانتظار;
            النتائج_الجزئية_[ملف] = جزئية;
        }
        
        الملفات_المتوقعة_ = الملفات_المتوقعة.size();
        الملفات_المستلمة_ = 0;
    }
    
    /**
     * إضافة نتيجة جزئية
     */
    void أضف_نتيجة(const نتيجة_جزئية& نتيجة) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        النتائج_الجزئية_[نتيجة.مسار_المصدر] = نتيجة;
        
        if (نتيجة.الحالة == حالة_نتيجة::مكتملة ||
            نتيجة.الحالة == حالة_نتيجة::فاشلة) {
            الملفات_المستلمة_++;
        }
        
        // إبلاغ المستمعين
        for (auto& مستمع : مستمعو_التقدم_) {
            مستمع(الملفات_المستلمة_, الملفات_المتوقعة_);
        }
    }
    
    /**
     * هل اكتملت كل النتائج؟
     */
    bool اكتملت() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        return الملفات_المستلمة_ >= الملفات_المتوقعة_;
    }
    
    /**
     * نسبة الاكتمال
     */
    float نسبة_الاكتمال() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        return الملفات_المتوقعة_ > 0 ?
            float(الملفات_المستلمة_) / الملفات_المتوقعة_ * 100.0f :
            0.0f;
    }
    
    /**
     * تجميع النتائج النهائية
     */
    نتيجة_مجمعة جمِّع() {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        النتيجة_.وقت_الانتهاء = std::chrono::system_clock::now();
        
        // جمع كل النتائج
        for (const auto& [مسار, جزئية] : النتائج_الجزئية_) {
            النتيجة_.النتائج.push_back(جزئية);
            
            // الأخطاء والتحذيرات
            for (const auto& خطأ : جزئية.الأخطاء) {
                النتيجة_.كل_الأخطاء.push_back(مسار + ": " + خطأ);
            }
            for (const auto& تحذير : جزئية.التحذيرات) {
                النتيجة_.كل_التحذيرات.push_back(مسار + ": " + تحذير);
            }
            
            // الإحصائيات
            if (جزئية.الحالة == حالة_نتيجة::مكتملة) {
                النتيجة_.الإحصائيات.ملفات_ناجحة++;
                النتيجة_.ملفات_الناتج.push_back(جزئية.مسار_الناتج);
            } else if (جزئية.الحالة == حالة_نتيجة::فاشلة) {
                النتيجة_.الإحصائيات.ملفات_فاشلة++;
            }
            
            النتيجة_.الإحصائيات.إجمالي_أخطاء += جزئية.الأخطاء.size();
            النتيجة_.الإحصائيات.إجمالي_تحذيرات += جزئية.التحذيرات.size();
            النتيجة_.الإحصائيات.زمن_ترجمة_كلي += جزئية.زمن_الترجمة_ثواني;
            النتيجة_.الإحصائيات.حجم_مصدر_كلي += جزئية.حجم_المصدر;
            النتيجة_.الإحصائيات.حجم_ناتج_كلي += جزئية.حجم_الناتج;
            
            // أطول ملف
            if (جزئية.زمن_الترجمة_ثواني > 
                النتيجة_.الإحصائيات.أطول_ملف_ثواني) {
                النتيجة_.الإحصائيات.أطول_ملف_ثواني = جزئية.زمن_الترجمة_ثواني;
                النتيجة_.الإحصائيات.أطول_ملف_اسم = مسار;
            }
        }
        
        // نسبة الضغط
        if (النتيجة_.الإحصائيات.حجم_مصدر_كلي > 0) {
            النتيجة_.الإحصائيات.نسبة_الضغط = 
                float(النتيجة_.الإحصائيات.حجم_ناتج_كلي) /
                النتيجة_.الإحصائيات.حجم_مصدر_كلي;
        }
        
        // هل نجحت؟
        النتيجة_.نجحت = النتيجة_.الإحصائيات.ملفات_فاشلة == 0;
        
        if (النتيجة_.نجحت) {
            النتيجة_.رسالة = "الترجمة اكتملت بنجاح";
        } else {
            النتيجة_.رسالة = "فشلت الترجمة: " + 
                std::to_string(النتيجة_.الإحصائيات.ملفات_فاشلة) + " ملف";
        }
        
        return النتيجة_;
    }
    
    /**
     * تسجيل مستمع التقدم
     */
    using مستمع_تقدم = std::function<void(int مستلمة, int متوقعة)>;
    void عند_تقدم(مستمع_تقدم مستمع) {
        مستمعو_التقدم_.push_back(مستمع);
    }

private:
    mutable std::mutex القفل_;
    نتيجة_مجمعة النتيجة_;
    std::unordered_map<std::string, نتيجة_جزئية> النتائج_الجزئية_;
    size_t الملفات_المتوقعة_ = 0;
    size_t الملفات_المستلمة_ = 0;
    std::vector<مستمع_تقدم> مستمعو_التقدم_;
};

