/**
 * حالة النتيجة
 */
enum class حالة_نتيجة {
    في_الانتظار,
    مكتملة,
    فاشلة,
    مهلة_منتهية
};

/**
 * نتيجة ترجمة ملف واحد
 */
struct نتيجة_جزئية {
    std::string مسار_المصدر;
    std::string معرف_الخادم;
    حالة_نتيجة الحالة = حالة_نتيجة::في_الانتظار;
    
    // الناتج
    std::vector<uint8_t> الكود_المُترجم;  // Object code
    std::string مسار_الناتج;
    
    // الأخطاء والتحذيرات
    std::vector<std::string> الأخطاء;
    std::vector<std::string> التحذيرات;
    
    // الإحصائيات
    double زمن_الترجمة_ثواني;
    size_t حجم_المصدر;
    size_t حجم_الناتج;
    
    // البيانات الوصفية
    std::string hash_المصدر;
    std::string hash_الناتج;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              نتيجة مُجمَّعة
