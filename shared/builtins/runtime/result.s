    ارجع نتيجة<ن، خ>.نجاح(قيمة)
نهاية

# إنشاء نتيجة فاشلة (اختصار)
قالب<نوع ن، نوع خ> دالة فشل(خ خطأ) نتيجة<ن، خ>
    ارجع نتيجة<ن، خ>.فشل(خطأ)
نهاية

# ===================================================
#                    صنف خطأ عام
# ===================================================

# صنف لتمثيل الأخطاء العامة
صنف خطأ_عام
    نص رسالة
    رقم رمز
    
    دالة منشئ(نص رسالة_جديدة)
        رسالة = رسالة_جديدة
        رمز = 0
    نهاية
    
    دالة منشئ(نص رسالة_جديدة، رقم رمز_جديد)
        رسالة = رسالة_جديدة
        رمز = رمز_جديد
    نهاية
    
    دالة نص_الخطأ() نص
        إذا (رمز != 0)
            ارجع "[" + رمز + "] " + رسالة
        نهاية
        ارجع رسالة
    نهاية
نهاية

