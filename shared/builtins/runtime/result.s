#
#     النوع نتيجة يُمثِّل نتيجة عملية قد:
#     
#     • نجاح - تحتوي على قيمة النجاح
#     • فشل - تحتوي على معلومات الخطأ
#
#     هذا النوع يُغني عن الاستثناءات ويجعل معالجة
#     الأخطاء صريحة وآمنة.
#
# ===================================================
#                    أمثلة الاستخدام
# ===================================================
#
#     # دالة تُرجع نتيجة
#     دالة قسمة(رقم أ، رقم ب) نتيجة<رقم، نص>
#         إذا (ب == 0)
#             ارجع نتيجة.فشل("لا يمكن القسمة على صفر")
#         نهاية
#         ارجع نتيجة.نجاح(أ / ب)
#     نهاية
#     
#     # معالجة النتيجة
#     نتيجة<رقم، نص> ن = قسمة(10، 2)
#     إذا (ن.ناجح())
#         اطبع("الناتج: " + ن.قيمة())
#     وإلا
#         اطبع("خطأ: " + ن.خطأ())
#     نهاية
#
# ===================================================

# ===================================================
#                    تعريف النوع
# ===================================================

# صنف نتيجة - يُمثِّل نتيجة عملية قد تنجح أو تفشل
# ن: نوع قيمة النجاح
# خ: نوع معلومات الخطأ
قالب<نوع ن، نوع خ> صنف نتيجة
    # الحقول الخاصة
    ن _قيمة
    خ _خطأ
    منطقي _ناجح
    
    # =========================================
    #              البناء
    # =========================================
    
    # منشئ خاص - لا يُستخدم مباشرة
    دالة منشئ()
        _ناجح = خطأ
    نهاية
    
    # =========================================
    #           دوال الإنشاء الثابتة
    # =========================================
    
    # إنشاء نتيجة ناجحة
    # مثال: نتيجة<رقم، نص> ن = نتيجة.نجاح(42)
    ثابتة دالة نجاح(ن قيمة) نتيجة<ن، خ>
        نتيجة<ن، خ> نت = نتيجة<ن، خ>()
        نت._قيمة = قيمة
        نت._ناجح = صحيح
        ارجع نت
    نهاية
    
    # إنشاء نتيجة فاشلة
    # مثال: نتيجة<رقم، نص> ن = نتيجة.فشل("خطأ!")
    ثابتة دالة فشل(خ خطأ) نتيجة<ن، خ>
        نتيجة<ن، خ> نت = نتيجة<ن، خ>()
        نت._خطأ = خطأ
        نت._ناجح = خطأ
        ارجع نت
    نهاية
    
    # =========================================
    #              التحقق
    # =========================================
    
    # التحقق من نجاح العملية
    # مثال: إذا (ن.ناجح()) ...
    دالة ناجح() منطقي
        ارجع _ناجح
    نهاية
    
    # التحقق من فشل العملية
    # مثال: إذا (ن.فاشل()) ...
    دالة فاشل() منطقي
        ارجع !_ناجح
    نهاية
    
    # =========================================
    #           الوصول للقيمة
    # =========================================
    
    # الحصول على قيمة النجاح (يُذعر إذا فشل!)
    # تحذير: تأكد من النجاح أولاً!
    دالة قيمة() ن
        إذا (!_ناجح)
            ذعر("خطأ: محاولة الوصول لقيمة نتيجة فاشلة!")
        نهاية
        ارجع _قيمة
    نهاية
    
    # الحصول على معلومات الخطأ (يُذعر إذا نجح!)
    دالة خطأ() خ
        إذا (_ناجح)
            ذعر("خطأ: محاولة الوصول لخطأ نتيجة ناجحة!")
        نهاية
        ارجع _خطأ
    نهاية
    
    # الحصول على القيمة أو قيمة افتراضية
    # مثال: رقم ن = نتيجة.او_قيمة(0)
    دالة او_قيمة(ن افتراضي) ن
        إذا (_ناجح)
            ارجع _قيمة
        نهاية
        ارجع افتراضي
    نهاية
    
    # الحصول على القيمة أو تنفيذ دالة مع الخطأ
    دالة او_نفذ(دالة<ن، خ> معالج) ن
        إذا (_ناجح)
            ارجع _قيمة
        نهاية
        ارجع معالج(_خطأ)
    نهاية
    
    # =========================================
    #              التحويل
    # =========================================
    
    # تحويل قيمة النجاح باستخدام دالة
    # مثال: نتيجة<نص، خ> = ن.حول(دالة_تحويل)
    قالب<نوع م> دالة حول(دالة<م، ن> محول) نتيجة<م، خ>
        إذا (_ناجح)
            ارجع نتيجة<م، خ>.نجاح(محول(_قيمة))
        نهاية
        ارجع نتيجة<م، خ>.فشل(_خطأ)
    نهاية
    
    # تحويل قيمة الخطأ باستخدام دالة
    قالب<نوع خ2> دالة حول_خطأ(دالة<خ2، خ> محول) نتيجة<ن، خ2>
        إذا (_ناجح)
            ارجع نتيجة<ن، خ2>.نجاح(_قيمة)
        نهاية
        ارجع نتيجة<ن، خ2>.فشل(محول(_خطأ))
    نهاية
    
    # تسلسل العمليات (flatMap)
    # مثال: نتيجة<م، خ> = ن.ثم(دالة_أخرى)
    قالب<نوع م> دالة ثم(دالة<نتيجة<م، خ>، ن> عملية) نتيجة<م، خ>
        إذا (_ناجح)
            ارجع عملية(_قيمة)
        نهاية
        ارجع نتيجة<م، خ>.فشل(_خطأ)
    نهاية
    
    # =========================================
    #              التنفيذ
    # =========================================
    
    # تنفيذ دالة على القيمة إذا نجحت
    دالة لو_نجح(دالة<فراغ، ن> عملية)
        إذا (_ناجح)
            عملية(_قيمة)
        نهاية
    نهاية
    
    # تنفيذ دالة على الخطأ إذا فشلت
    دالة لو_فشل(دالة<فراغ، خ> عملية)
        إذا (!_ناجح)
            عملية(_خطأ)
        نهاية
    نهاية
    
    # معالجة كلتا الحالتين
    قالب<نوع م> دالة عالج(دالة<م، ن> عند_نجاح، دالة<م، خ> عند_فشل) م
        إذا (_ناجح)
            ارجع عند_نجاح(_قيمة)
        نهاية
        ارجع عند_فشل(_خطأ)
    نهاية
    
    # =========================================
    #              التحويل لاختياري
    # =========================================
    
    # تحويل النتيجة إلى اختياري (يتجاهل الخطأ)
    دالة الى_اختياري() اختياري<ن>
        إذا (_ناجح)
            ارجع اختياري<ن>.بعض(_قيمة)
        نهاية
        ارجع اختياري<ن>.لاشيء()
    نهاية
نهاية

