# صنف اختياري - يُغلِّف قيمة قد تكون موجودة أو غائبة
قالب<نوع ت> صنف اختياري
    # الحقول الخاصة
    ت _قيمة
    منطقي _موجود
    
    # =========================================
    #              البناء
    # =========================================
    
    # منشئ افتراضي - ينشئ اختياري فارغ
    دالة منشئ()
        _موجود = خطأ
    نهاية
    
    # منشئ بقيمة
    دالة منشئ(ت قيمة_جديدة)
        _قيمة = قيمة_جديدة
        _موجود = صحيح
    نهاية
    
    # =========================================
    #           دوال الإنشاء الثابتة
    # =========================================
    
    # إنشاء اختياري بقيمة موجودة
    # مثال: اختياري<رقم> س = اختياري.بعض(42)
    ثابتة دالة بعض(ت قيمة) اختياري<ت>
        اختياري<ت> نتيجة = اختياري<ت>(قيمة)
        ارجع نتيجة
    نهاية
    
    # إنشاء اختياري فارغ
    # مثال: اختياري<رقم> س = اختياري.لاشيء()
    ثابتة دالة لاشيء() اختياري<ت>
        اختياري<ت> نتيجة = اختياري<ت>()
        ارجع نتيجة
    نهاية
    
    # =========================================
    #              التحقق
    # =========================================
    
    # التحقق من وجود قيمة
    # مثال: إذا (س.موجود()) ...
    دالة موجود() منطقي
        ارجع _موجود
    نهاية
    
    # التحقق من غياب القيمة
    # مثال: إذا (س.غائب()) ...
    دالة غائب() منطقي
        ارجع !_موجود
    نهاية
    
    # =========================================
    #           الوصول للقيمة
    # =========================================
    
    # الحصول على القيمة (يُذعر إذا غائبة!)
    # تحذير: تأكد من وجود القيمة أولاً!
    دالة قيمة() ت
        إذا (!_موجود)
            ذعر("خطأ: محاولة الوصول لقيمة اختيارية غائبة!")
        نهاية
        ارجع _قيمة
    نهاية
    
    # الحصول على القيمة أو قيمة افتراضية
    # مثال: رقم ن = س.او_قيمة(0)
    دالة او_قيمة(ت افتراضي) ت
        إذا (_موجود)
            ارجع _قيمة
        نهاية
        ارجع افتراضي
    نهاية
    
    # الحصول على القيمة أو تنفيذ دالة
    # مثال: رقم ن = س.او_نفذ(دالة_حساب)
    دالة او_نفذ(دالة<ت> مولد) ت
        إذا (_موجود)
            ارجع _قيمة
        نهاية
        ارجع مولد()
    نهاية
    
    # =========================================
    #              التحويل
    # =========================================
    
    # تحويل القيمة باستخدام دالة (map)
    # مثال: اختياري<رقم> مضاعف = س.حول(دالة_مضاعفة)
    قالب<نوع م> دالة حول(دالة<م، ت> محول) اختياري<م>
        إذا (_موجود)
            ارجع اختياري<م>.بعض(محول(_قيمة))
        نهاية
        ارجع اختياري<م>.لاشيء()
    نهاية
    
    # تصفية القيمة بشرط
    # مثال: اختياري<رقم> موجب = س.صفي(دالة_موجب)
    دالة صفي(دالة<منطقي، ت> شرط) اختياري<ت>
        إذا (_موجود)
            إذا (شرط(_قيمة))
                ارجع اختياري<ت>.بعض(_قيمة)
            نهاية
        نهاية
        ارجع اختياري<ت>.لاشيء()
    نهاية
    
    # =========================================
    #              التنفيذ
    # =========================================
    
    # تنفيذ دالة على القيمة إذا موجودة
    # مثال: س.لو_موجود(دالة_طباعة)
    دالة لو_موجود(دالة<فراغ، ت> عملية)
        إذا (_موجود)
            عملية(_قيمة)
        نهاية
    نهاية
    
    # تنفيذ دالة إذا غائبة
    دالة لو_غائب(دالة<فراغ> عملية)
        إذا (!_موجود)
            عملية()
        نهاية
    نهاية
