/**
 * بند واحد في العقد
 */
struct بند_عقد {
    نوع_العقد النوع;
    مؤشر_تعبير التعبير;
    std::string الرسالة;  // رسالة خطأ مخصصة
    int السطر;
    int العمود;
};

/**
 * عقد الدالة الكامل
 */
class عقد_دالة {
public:
    std::string اسم_الدالة;
    std::vector<بند_عقد> الشروط_المسبقة;    // يتطلب
    std::vector<بند_عقد> الشروط_اللاحقة;    // يضمن
    std::vector<بند_عقد> الثوابت;            // ثابت
    
    // القيم القديمة للمتغيرات (للشروط اللاحقة)
    std::vector<std::string> القيم_القديمة;
    
    bool فارغ() const {
        return الشروط_المسبقة.empty() && 
               الشروط_اللاحقة.empty() && 
               الثوابت.empty();
    }
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "عقد دالة: " << اسم_الدالة << "\n";
        
        if (!الشروط_المسبقة.empty()) {
            ss << "  الشروط المسبقة:\n";
            for (const auto& شرط : الشروط_المسبقة) {
                ss << "    يتطلب " << شرط.التعبير->إلى_نص() << "\n";
            }
        }
        
        if (!الشروط_اللاحقة.empty()) {
            ss << "  الشروط اللاحقة:\n";
            for (const auto& شرط : الشروط_اللاحقة) {
                ss << "    يضمن " << شرط.التعبير->إلى_نص() << "\n";
            }
        }
        
        return ss.str();
    }
};

/**
 * ثابت الصنف
 */
class ثابت_صنف {
public:
    std::string اسم_الصنف;
    std::vector<بند_عقد> الثوابت;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "ثوابت صنف: " << اسم_الصنف << "\n";
        for (const auto& ثابت : الثوابت) {
            ss << "  ثابت " << ثابت.التعبير->إلى_نص() << "\n";
        }
        return ss.str();
    }
};

