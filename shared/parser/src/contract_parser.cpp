class تعبير_عقد;
using مؤشر_تعبير = std::shared_ptr<تعبير_عقد>;

/**
 * العقدة الأساسية للتعبير
 */
class تعبير_عقد {
public:
    نوع_التعبير النوع;
    int السطر = 0;
    int العمود = 0;
    
    تعبير_عقد(نوع_التعبير نوع) : النوع(نوع) {}
    virtual ~تعبير_عقد() = default;
    
    virtual std::string إلى_نص() const = 0;
};

/**
 * تعبير المقارنة
 */
class تعبير_مقارنة : public تعبير_عقد {
public:
    مؤشر_تعبير اليسار;
    مؤشر_تعبير اليمين;
    عامل_المقارنة العامل;
    
    تعبير_مقارنة() : تعبير_عقد(نوع_التعبير::مقارنة) {}
    
    std::string إلى_نص() const override {
        std::string op;
        switch (العامل) {
            case عامل_المقارنة::يساوي: op = " == "; break;
            case عامل_المقارنة::لا_يساوي: op = " != "; break;
            case عامل_المقارنة::أصغر: op = " < "; break;
            case عامل_المقارنة::أكبر: op = " > "; break;
            case عامل_المقارنة::أصغر_أو_يساوي: op = " <= "; break;
            case عامل_المقارنة::أكبر_أو_يساوي: op = " >= "; break;
        }
        return اليسار->إلى_نص() + op + اليمين->إلى_نص();
    }
};

/**
 * تعبير منطقي
 */
class تعبير_منطقي : public تعبير_عقد {
public:
    مؤشر_تعبير اليسار;
    مؤشر_تعبير اليمين;  // nullptr للعمليات الأحادية
    عامل_منطقي العامل;
    
    تعبير_منطقي() : تعبير_عقد(نوع_التعبير::منطقي) {}
    
    std::string إلى_نص() const override {
        std::string op;
        switch (العامل) {
            case عامل_منطقي::و: op = " و "; break;
            case عامل_منطقي::أو: op = " أو "; break;
            case عامل_منطقي::ليس: return "ليس " + اليسار->إلى_نص();
        }
        return "(" + اليسار->إلى_نص() + op + اليمين->إلى_نص() + ")";
    }
};

/**
 * تعبير كمي (لكل، يوجد)
 */
class تعبير_كمي : public تعبير_عقد {
public:
    محدد_كمي المحدد;
    std::string المتغير;
    std::string النوع;
    مؤشر_تعبير المدى;    // المدى الذي يتحرك فيه المتغير
    مؤشر_تعبير الشرط;
    
    تعبير_كمي() : تعبير_عقد(نوع_التعبير::كمي) {}
    
    std::string إلى_نص() const override {
        std::string q = (المحدد == محدد_كمي::لكل) ? "لكل" : "يوجد";
        return q + " " + المتغير + " في " + المدى->إلى_نص() + ": " + الشرط->إلى_نص();
    }
};

/**
 * تعبير متغير
 */
class تعبير_متغير : public تعبير_عقد {
public:
    std::string الاسم;
    
    تعبير_متغير(const std::string& اسم) 
        : تعبير_عقد(نوع_التعبير::متغير), الاسم(اسم) {}
    
    std::string إلى_نص() const override { return الاسم; }
};

/**
 * تعبير ثابت عددي
 */
class تعبير_ثابت_عددي : public تعبير_عقد {
public:
    double القيمة;
    
    تعبير_ثابت_عددي(double قيمة) 
        : تعبير_عقد(نوع_التعبير::ثابت_عددي), القيمة(قيمة) {}
    
    std::string إلى_نص() const override { 
        return std::to_string(static_cast<int64_t>(القيمة)); 
    }
};

/**
 * تعبير النتيجة (للشروط اللاحقة)
 */
class تعبير_النتيجة : public تعبير_عقد {
public:
    تعبير_النتيجة() : تعبير_عقد(نوع_التعبير::النتيجة) {}
    std::string إلى_نص() const override { return "النتيجة"; }
};

