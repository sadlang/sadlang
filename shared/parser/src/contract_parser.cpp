/**
 * نتيجة التحليل
 */
struct نتيجة_تحليل_عقد {
    bool نجح = false;
    عقد_دالة العقد;
    std::string رسالة_خطأ;
    int سطر_الخطأ = 0;
    int عمود_الخطأ = 0;
};

/**
 * محلل العقود
 */
class محلل_العقود {
private:
    معجم_العقود* المعجم;
    رمز الرمز_الحالي;
    std::vector<std::string> الأخطاء;
    
    void التالي() {
        الرمز_الحالي = المعجم->الرمز_التالي();
    }
    
    bool تطابق(رمز_عقد نوع) const {
        return الرمز_الحالي.النوع == نوع;
    }
    
    bool استهلك(رمز_عقد نوع) {
        if (تطابق(نوع)) {
            التالي();
            return true;
        }
        return false;
    }
    
    void خطأ(const std::string& رسالة) {
        std::stringstream ss;
        ss << "خطأ في السطر " << الرمز_الحالي.السطر 
           << " العمود " << الرمز_الحالي.العمود 
           << ": " << رسالة;
        الأخطاء.push_back(ss.str());
    }
    
    // تحليل التعبيرات
    مؤشر_تعبير تحليل_تعبير();
    مؤشر_تعبير تحليل_تعبير_منطقي();
    مؤشر_تعبير تحليل_تعبير_مقارنة();
    مؤشر_تعبير تحليل_تعبير_حسابي();
    مؤشر_تعبير تحليل_تعبير_أولي();
    مؤشر_تعبير تحليل_تعبير_كمي();
    
public:
    نتيجة_تحليل_عقد حلل(const std::string& مصدر, const std::string& اسم_الدالة) {
        معجم_العقود معجم(مصدر);
        المعجم = &معجم;
        التالي();
        
        نتيجة_تحليل_عقد نتيجة;
        نتيجة.العقد.اسم_الدالة = اسم_الدالة;
        
        while (!تطابق(رمز_عقد::نهاية_الملف)) {
            // تخطي أسطر فارغة
            if (تطابق(رمز_عقد::نهاية_السطر)) {
                التالي();
                continue;
            }
            
            // يتطلب
            if (تطابق(رمز_عقد::يتطلب)) {
                التالي();
                auto تعبير = تحليل_تعبير();
                if (تعبير) {
                    بند_عقد بند;
                    بند.النوع = نوع_العقد::يتطلب;
                    بند.التعبير = تعبير;
                    بند.السطر = الرمز_الحالي.السطر;
                    بند.العمود = الرمز_الحالي.العمود;
                    نتيجة.العقد.الشروط_المسبقة.push_back(بند);
                }
                continue;
            }
            
            // يضمن
            if (تطابق(رمز_عقد::يضمن)) {
                التالي();
                auto تعبير = تحليل_تعبير();
                if (تعبير) {
                    بند_عقد بند;
                    بند.النوع = نوع_العقد::يضمن;
                    بند.التعبير = تعبير;
                    بند.السطر = الرمز_الحالي.السطر;
                    بند.العمود = الرمز_الحالي.العمود;
                    نتيجة.العقد.الشروط_اللاحقة.push_back(بند);
                }
                continue;
            }
            
            // ثابت
            if (تطابق(رمز_عقد::ثابت)) {
                التالي();
                auto تعبير = تحليل_تعبير();
                if (تعبير) {
                    بند_عقد بند;
                    بند.النوع = نوع_العقد::ثابت;
                    بند.التعبير = تعبير;
                    بند.السطر = الرمز_الحالي.السطر;
                    بند.العمود = الرمز_الحالي.العمود;
                    نتيجة.العقد.الثوابت.push_back(بند);
                }
                continue;
            }
            
            // غير معروف - تخطي
            التالي();
        }
        
        نتيجة.نجح = الأخطاء.empty();
        if (!الأخطاء.empty()) {
            نتيجة.رسالة_خطأ = الأخطاء[0];
        }
        
        return نتيجة;
    }
};

// تحليل التعبير الكامل
مؤشر_تعبير محلل_العقود::تحليل_تعبير() {
    return تحليل_تعبير_منطقي();
}

// تحليل التعبيرات المنطقية (و، أو)
مؤشر_تعبير محلل_العقود::تحليل_تعبير_منطقي() {
    auto يسار = تحليل_تعبير_مقارنة();
    if (!يسار) return nullptr;
    
    while (تطابق(رمز_عقد::و) || تطابق(رمز_عقد::أو)) {
        عامل_منطقي عامل = تطابق(رمز_عقد::و) ? 
            عامل_منطقي::و : عامل_منطقي::أو;
        التالي();
        
        auto يمين = تحليل_تعبير_مقارنة();
        if (!يمين) return nullptr;
        
        auto تعبير = std::make_shared<تعبير_منطقي>();
        تعبير->اليسار = يسار;
        تعبير->اليمين = يمين;
        تعبير->العامل = عامل;
        يسار = تعبير;
    }
    
    return يسار;
}

// تحليل تعبيرات المقارنة
مؤشر_تعبير محلل_العقود::تحليل_تعبير_مقارنة() {
    auto يسار = تحليل_تعبير_حسابي();
    if (!يسار) return nullptr;
    
    if (تطابق(رمز_عقد::يساوي) || تطابق(رمز_عقد::لا_يساوي) ||
        تطابق(رمز_عقد::أصغر) || تطابق(رمز_عقد::أكبر) ||
        تطابق(رمز_عقد::أصغر_أو_يساوي) || تطابق(رمز_عقد::أكبر_أو_يساوي)) {
        
        عامل_المقارنة عامل;
        switch (الرمز_الحالي.النوع) {
            case رمز_عقد::يساوي: عامل = عامل_المقارنة::يساوي; break;
            case رمز_عقد::لا_يساوي: عامل = عامل_المقارنة::لا_يساوي; break;
            case رمز_عقد::أصغر: عامل = عامل_المقارنة::أصغر; break;
            case رمز_عقد::أكبر: عامل = عامل_المقارنة::أكبر; break;
            case رمز_عقد::أصغر_أو_يساوي: عامل = عامل_المقارنة::أصغر_أو_يساوي; break;
            case رمز_عقد::أكبر_أو_يساوي: عامل = عامل_المقارنة::أكبر_أو_يساوي; break;
            default: break;
        }
        التالي();
        
        auto يمين = تحليل_تعبير_حسابي();
        if (!يمين) return nullptr;
        
        auto تعبير = std::make_shared<تعبير_مقارنة>();
        تعبير->اليسار = يسار;
        تعبير->اليمين = يمين;
        تعبير->العامل = عامل;
        return تعبير;
    }
    
    return يسار;
}

// تحليل التعبيرات الحسابية
مؤشر_تعبير محلل_العقود::تحليل_تعبير_حسابي() {
    return تحليل_تعبير_أولي();
}

// تحليل التعبيرات الأولية
مؤشر_تعبير محلل_العقود::تحليل_تعبير_أولي() {
    // ليس
    if (تطابق(رمز_عقد::ليس)) {
        التالي();
        auto تعبير_داخلي = تحليل_تعبير_أولي();
        if (!تعبير_داخلي) return nullptr;
        
        auto تعبير = std::make_shared<تعبير_منطقي>();
        تعبير->اليسار = تعبير_داخلي;
        تعبير->العامل = عامل_منطقي::ليس;
        return تعبير;
    }
    
    // لكل / يوجد
    if (تطابق(رمز_عقد::لكل) || تطابق(رمز_عقد::يوجد)) {
        return تحليل_تعبير_كمي();
    }
    
    // قوس
    if (تطابق(رمز_عقد::قوس_فتح)) {
        التالي();
        auto تعبير = تحليل_تعبير();
        if (!استهلك(رمز_عقد::قوس_غلق)) {
            خطأ("متوقع ')'");
            return nullptr;
        }
        return تعبير;
    }
    
    // النتيجة
    if (تطابق(رمز_عقد::النتيجة)) {
        التالي();
        return std::make_shared<تعبير_النتيجة>();
    }
    
    // صحيح/خطأ
    if (تطابق(رمز_عقد::صحيح)) {
        التالي();
        return std::make_shared<تعبير_ثابت_عددي>(1);
    }
    if (تطابق(رمز_عقد::خطأ)) {
        التالي();
        return std::make_shared<تعبير_ثابت_عددي>(0);
    }
    
    // رقم
    if (تطابق(رمز_عقد::رقم)) {
        double قيمة = std::stod(الرمز_الحالي.القيمة);
        التالي();
        return std::make_shared<تعبير_ثابت_عددي>(قيمة);
    }
    
    // معرّف
    if (تطابق(رمز_عقد::معرّف)) {
        std::string اسم = الرمز_الحالي.القيمة;
        التالي();
        return std::make_shared<تعبير_متغير>(اسم);
    }
    
    خطأ("تعبير غير متوقع");
    return nullptr;
}

// تحليل تعبير كمي
مؤشر_تعبير محلل_العقود::تحليل_تعبير_كمي() {
    auto تعبير = std::make_shared<تعبير_كمي>();
    
    تعبير->المحدد = تطابق(رمز_عقد::لكل) ? 
        محدد_كمي::لكل : محدد_كمي::يوجد;
    التالي();
    
    // اسم المتغير
    if (!تطابق(رمز_عقد::معرّف)) {
        خطأ("متوقع اسم متغير بعد 'لكل' أو 'يوجد'");
        return nullptr;
    }
    تعبير->المتغير = الرمز_الحالي.القيمة;
    التالي();
    
    // في
    if (!استهلك(رمز_عقد::في)) {
        خطأ("متوقع 'في' بعد اسم المتغير");
        return nullptr;
    }
    
    // المدى
    تعبير->المدى = تحليل_تعبير_أولي();
    if (!تعبير->المدى) return nullptr;
    
    // نقطتان
    if (!استهلك(رمز_عقد::نقطتان)) {
        خطأ("متوقع ':' بعد المدى");
        return nullptr;
    }
    
    // الشرط
    تعبير->الشرط = تحليل_تعبير();
    if (!تعبير->الشرط) return nullptr;
    
    return تعبير;
}

