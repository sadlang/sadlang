/**
 * نوع العقد
 */
enum class نوع_العقد {
    يتطلب,      // Precondition (requires)
    يضمن,       // Postcondition (ensures)
    ثابت,       // Invariant (invariant)
    يفترض,      // Assumption (assumes)
    يؤكد        // Assertion (asserts)
};

/**
 * نوع التعبير في العقد
 */
enum class نوع_التعبير {
    مقارنة,      // Comparison (==, !=, <, >, <=, >=)
    منطقي,       // Logical (و, أو, ليس)
    حسابي,       // Arithmetic (+, -, *, /, %)
    كمي,         // Quantifier (لكل, يوجد)
    متغير,       // Variable reference
    ثابت_عددي,   // Numeric literal
    ثابت_منطقي,  // Boolean literal
    استدعاء,     // Function call
    وصول_حقل,    // Field access
    وصول_مصفوفة, // Array access
    النتيجة      // Result reference (للشروط اللاحقة)
};

/**
 * عامل المقارنة
 */
enum class عامل_المقارنة {
    يساوي,        // ==
    لا_يساوي,     // !=
    أصغر,         // <
    أكبر,         // >
    أصغر_أو_يساوي, // <=
    أكبر_أو_يساوي  // >=
};

/**
 * عامل منطقي
 */
enum class عامل_منطقي {
    و,      // &&
    أو,     // ||
    ليس     // !
};

/**
 * محدد كمي
 */
enum class محدد_كمي {
    لكل,    // forall
    يوجد    // exists
};

