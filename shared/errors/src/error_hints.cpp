        // (AR) تنسيق النصيحة للعرض في الطرفية
        // (EN) Format hint for terminal display
        // ═══════════════════════════════════════════════════════════════════════════════

        std::string ErrorHintEngine::formatHint(const ErrorHint &hint, bool colorize)
        {
            // (AR) ألوان ANSI
            const std::string CYAN = colorize ? "\033[36m" : "";
            const std::string GREEN = colorize ? "\033[32m" : "";
            const std::string YELLOW = colorize ? "\033[33m" : "";
            const std::string RED = colorize ? "\033[91m" : "";
            const std::string BOLD = colorize ? "\033[1m" : "";
            const std::string DIM = colorize ? "\033[2m" : "";
            const std::string RESET = colorize ? "\033[0m" : "";

            std::string result;

            // (AR) الشرح
            result += "\n" + CYAN + BOLD + "💡 ماذا حدث؟" + RESET + "\n";
            result += "   " + CYAN + hint.explanation + RESET + "\n";

            // (AR) الكود الخاطئ
            if (!hint.wrongExample.empty())
            {
                result += "\n" + RED + BOLD + "❌ مثال على الخطأ:" + RESET + "\n";
                // (AR) عرض كل سطر مع مسافة بادئة
                std::string line;
                std::istringstream wrongStream(hint.wrongExample);
                while (std::getline(wrongStream, line))
                {
                    result += "   " + DIM + line + RESET + "\n";
                }
            }

            // (AR) الكود الصحيح
            if (!hint.correctExample.empty())
            {
                result += "\n" + GREEN + BOLD + "✅ الحل:" + RESET + "\n";
                std::string line;
                std::istringstream correctStream(hint.correctExample);
                while (std::getline(correctStream, line))
                {
                    result += "   " + GREEN + line + RESET + "\n";
                }
            }

            // (AR) النصائح الإضافية
            if (!hint.tips.empty())
            {
                result += "\n" + YELLOW + BOLD + "📝 نصائح:" + RESET + "\n";
                for (const auto &tip : hint.tips)
                {
                    result += "   " + YELLOW + "• " + tip + RESET + "\n";
                }
            }

            return result;
        }

