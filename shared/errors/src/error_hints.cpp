        // (EN) Find hint for a specific error
        // ═══════════════════════════════════════════════════════════════════════════════

        const ErrorHint *ErrorHintEngine::findHint(const std::string &errorType,
                                                   const std::string &errorMessage) const
        {
            // (AR) أولاً: البحث بنوع الاستثناء مباشرة
            // (EN) First: search by exception type directly
            auto typeIt = typeHints_.find(errorType);
            if (typeIt != typeHints_.end())
            {
                return &typeIt->second;
            }

            // (AR) ثانياً: البحث بكلمات مفتاحية في رسالة الخطأ
            // (EN) Second: search by keywords in error message
            for (const auto &kh : keywordHints_)
            {
                if (errorMessage.find(kh.keyword) != std::string::npos)
                {
                    return &kh.hint;
                }
            }

            return nullptr;
        }

