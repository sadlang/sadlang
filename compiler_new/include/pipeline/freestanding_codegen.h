/**
 * @enum FreestandingError
 * @brief (AR) رموز أخطاء توليد الكود في وضع freestanding
 *        (EN) Error codes for freestanding code generation
 */
enum class FreestandingError {
    // لا خطأ
    لا_خطأ = 0,

    // ═══ أخطاء الأنواع ═══════════════════════════════════════════════════════
    /**
     * (AR) نوع غير مدعوم في وضع freestanding
     *      (مثلاً: std::string، std::vector، الاستثناءات)
     * (EN) Type not supported in freestanding mode
     */
    نوع_غير_مدعوم,

    /**
     * (AR) محاولة استخدام تخصيص ذاكرة ديناميكي بدون مُخصّص مُسجَّل
     * (EN) Heap allocation used without registered allocator
     */
    تخصيص_بدون_مُخصّص,

    // ═══ أخطاء الدوال ════════════════════════════════════════════════════════
    /**
     * (AR) دالة نقطة الدخول غير موجودة أو غير صحيحة
     * (EN) Entry point function missing or invalid
     */
    نقطة_دخول_مفقودة,

    /**
     * (AR) معالج الذعر غير مُسجَّل
     * (EN) Panic handler not registered
     */
    معالج_ذعر_مفقود,

    /**
     * (AR) دالة ذات [[noreturn]] ترجع قيمة
     * (EN) noreturn function has return value
     */
    لن_ترجع_لكنها_ترجع,

    // ═══ أخطاء المكتبة ═══════════════════════════════════════════════════════
    /**
     * (AR) استخدام رمز من المكتبة القياسية في وضع بلا_مكتبة_قياسية
     * (EN) Standard library symbol used in no_std mode
     */
    رمز_مكتبة_قياسية,

    // ═══ أخطاء التحكم ════════════════════════════════════════════════════════
    /**
     * (AR) أوقف/أكمل خارج حلقة
     * (EN) break/continue outside loop
     */
    توقف_خارج_حلقة,
};

/**
 * @struct نتيجة_توليد
 * @brief (AR) نتيجة عملية توليد كود
 *        (EN) Code generation operation result
 */
struct نتيجة_توليد {
    bool نجاح = false;
    FreestandingError رمز_الخطأ = FreestandingError::لا_خطأ;
    std::string رسالة_الخطأ_عربي;
    std::string رسالة_الخطأ_إنجليزي;
    std::string ملف_المصدر;
    int سطر_المصدر = 0;

    // بناء نتيجة ناجحة
    static نتيجة_توليد نجاح_() {
        نتيجة_توليد ن;
        ن.نجاح = true;
        return ن;
    }

    // بناء نتيجة فاشلة
    static نتيجة_توليد خطأ_(FreestandingError رمز,
                              const std::string& عربي,
                              const std::string& إنجليزي,
                              const std::string& ملف = "",
                              int سطر = 0)
    {
        نتيجة_توليد ن;
        ن.نجاح = false;
        ن.رمز_الخطأ = رمز;
        ن.رسالة_الخطأ_عربي = عربي;
        ن.رسالة_الخطأ_إنجليزي = إنجليزي;
        ن.ملف_المصدر = ملف;
        ن.سطر_المصدر = سطر;
        return ن;
    }
};

