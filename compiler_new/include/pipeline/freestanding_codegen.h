/**
 * @struct سياق_حلقة
 * @brief (AR) معلومات الحلقة الحالية للتتبع أثناء توليد الكود
 *        (EN) Current loop context for tracking during code generation
 *
 * يُخزَّن في مكدس للتعامل مع الحلقات المتداخلة بشكل صحيح.
 *
 * مثال للحلقات المتداخلة:
 *   لكل (ع32 ن = 0; ن < 10; ن++) {        ← حلقة خارجية
 *       طالما (شرط) {                      ← حلقة داخلية
 *           إذا (نهاية) أوقف;             ← يخرج من الداخلية فقط
 *           إذا (تخطي) أكمل;             ← ينتقل لتكرار الداخلية
 *       }
 *   }
 */
struct سياق_حلقة {
    // ─── نوع الحلقة ───────────────────────────────────────────────────────────
    enum class النوع {
        طالما_ن,    ///< حلقة while / طالما
        لكل_ن,      ///< حلقة for / لكل
        حلقة_ن,     ///< حلقة lا نهائية / حلقة
    } نوع_الحلقة;

    // ─── تسميات الكتل في LLVM IR ─────────────────────────────────────────────
    std::string تسمية_البداية;          ///< كتلة بداية الحلقة (header)
    std::string تسمية_الجسم;            ///< كتلة جسم الحلقة (body)
    std::string تسمية_التحديث;          ///< كتلة تحديث المتغير (في لكل فقط)
    std::string تسمية_النهاية;          ///< كتلة بعد الحلقة (exit/merge)

    // ─── للحلقات المُسمّاة (لدعم break/continue لحلقة محددة) ─────────────────
    std::string الاسم;                  ///< اسم اختياري (label)

    // ─── معلومات إضافية ──────────────────────────────────────────────────────
    bool له_تسمية = false;              ///< هل الحلقة مُسمّاة؟
};

/**
 * @struct سياق_شرط
 * @brief (AR) معلومات جملة إذا/وإلا الحالية
 *        (EN) Current if/else statement context
 *
 * يُخزَّن في مكدس للتعامل مع جمل الشرط المتداخلة.
 */
struct سياق_شرط {
    std::string تسمية_صحيح;    ///< كتلة الفرع الصحيح (then)
    std::string تسمية_خطأ;     ///< كتلة الفرع الخاطئ (else/elif)
    std::string تسمية_دمج;     ///< كتلة ما بعد الجملة (merge)
    bool له_وإلا = false;      ///< هل يوجد فرع وإلا؟
};

