/**
 * =============================================================================
 * ملف: freestanding_codegen.h
 * الوصف: مولّد الكود لوضع Freestanding (بدون مكتبة قياسية)
 * المهمة: م-ت01 — دعم شامل لتوليد كود وضع Freestanding في المترجم
 * =============================================================================
 *
 * هذا الملف يُعرِّف الصنف FreestandingCodeGen الذي يُضيف طبقة توليد
 * كود خاصة بوضع freestanding فوق مولّد LLVM الموجود.
 *
 * المسؤوليات الرئيسية:
 * ──────────────────────────────────────────────────────────────
 *   1. جمل التحكم:
 *      - توليد كود LLVM IR صحيح لجمل إذا/وإلا/وإلا_إذا
 *      - توليد حلقات طالما/لكل/حلقة بدون أي اعتماد على المكتبة
 *      - دعم أكمل/أوقف مع التتبع الصحيح للحلقات المتداخلة
 *
 *   2. الذعر والتأكد:
 *      - استبدال طرح استثناءات C++ بمعالج الذعر sad_panic
 *      - توليد كود sad_assert بدون #include <assert.h>
 *      - التعامل مع دوال [[noreturn]] بشكل صحيح
 *
 *   3. المتغيرات والأنواع:
 *      - التحقق من أن الأنواع المستخدمة متوافقة مع freestanding
 *      - رفض أي استخدام لأنواع من المكتبة القياسية
 *      - دعم أنواع لغة ص (ع8-ع64، ح8-ح64، حجم، منطق)
 *
 *   4. دوال النواة:
 *      - دعم #[نقطة_دخول]    → الحصول على رمز خاص (export + noreturn)
 *      - دعم #[معالج_ذعر]    → تسجيل دالة الذعر
 *      - دعم #[معالج_مقاطعة] → vector table entry
 *
 *   5. تحسين للـ bare-metal:
 *      - inline functions الصغيرة تلقائياً
 *      - حذف كود إعداد المكدس غير الضروري (stack frames)
 *      - توليد أسماء C للدوال الخارجية (extern "C")
 *
 * الاستخدام:
 * ──────────────────────────────────────────────────────────────
 *   // في خط الترجمة (Compilation Pipeline):
 *   NoStdConfig إعداد = ...;
 *   FreestandingCodeGen مولّد(سياق_LLVM, إعداد);
 *
 *   // مولّد إذا/وإلا في freestanding:
 *   مولّد.ولِّد_إذا(شرط, دالة_if, دالة_else);
 *
 *   // مولّد حلقة طالما:
 *   مولّد.ابدأ_طالما(شرط_بداية);
 *   مولّد.أنهِ_طالما();
 *
 *   // مولّد حلقة لكل:
 *   مولّد.ابدأ_لكل(تهيئة, شرط, خطوة);
 *   مولّد.أنهِ_لكل();
 * =============================================================================
 */

