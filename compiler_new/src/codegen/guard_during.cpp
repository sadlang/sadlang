/**
 * تحذير تدفق بيانات
 */
struct تحذير_تدفق {
    مصدر_بيانات المصدر;
    وجهة_بيانات الوجهة;
    std::string المتغير;
    std::string الرسالة;
    خطورة_ثغرة الخطورة;
};

/**
 * محلل تدفق البيانات
 * 
 * للمبتدئ: هذا المحلل يتتبع "رحلة" البيانات في البرنامج.
 * 
 * مثال:
 *     المستخدم يدخل اسمه → يُحفظ في متغير → يُرسل لقاعدة البيانات
 *     
 *     إذا وصلت بيانات المستخدم مباشرة لقاعدة البيانات بدون تنظيف،
 *     هذا خطير! (SQL Injection)
 */
class محلل_تدفق_البيانات {
public:
    /**
     * تسجيل أن متغيراً يأتي من مصدر معين
     */
    void سجِّل_مصدر(const std::string& متغير, مصدر_بيانات مصدر) {
        m_مصادر[متغير] = مصدر;
    }
    
    /**
     * تحقق إذا كان المتغير يصل لوجهة خطيرة
     * @return تحذير إذا كان هناك خطر
     */
    std::optional<تحذير_تدفق> تحقق_وجهة(
        const std::string& متغير,
        وجهة_بيانات وجهة) const {
        
        auto it = m_مصادر.find(متغير);
        if (it == m_مصادر.end()) {
            // متغير غير معروف المصدر - حذر
            return تحذير_تدفق{
                مصدر_بيانات::غير_معروف,
                وجهة,
                متغير,
                "متغير غير معروف المصدر يصل لوجهة حساسة",
                خطورة_ثغرة::متوسط
            };
        }
        
        مصدر_بيانات المصدر = it->second;
        
        // مصادر غير موثوقة
        bool مصدر_غير_موثوق = (المصدر == مصدر_بيانات::مستخدم ||
                               المصدر == مصدر_بيانات::شبكة);
        
        // وجهات خطيرة
        bool وجهة_خطيرة = (وجهة == وجهة_بيانات::SQL ||
                          وجهة == وجهة_بيانات::أمر_نظام ||
                          وجهة == وجهة_بيانات::عرض);
        
        if (مصدر_غير_موثوق && وجهة_خطيرة) {
            return تحذير_تدفق{
                المصدر,
                وجهة,
                متغير,
                "بيانات غير موثوقة تصل لوجهة خطيرة بدون تنظيف",
                خطورة_ثغرة::عالي
            };
        }
        
        return std::nullopt;
    }
    
    /**
     * مسح كل البيانات المُسجَّلة
     */
    void امسح() {
        m_مصادر.clear();
    }
    
private:
    std::unordered_map<std::string, مصدر_بيانات> m_مصادر;
};

