/**
 * الحارس أثناء التوليد
 * 
 * الفئة الرئيسية التي تفحص الكود أثناء توليده سطراً بسطر.
 * 
 * مثال الاستخدام:
 * ```cpp
 * حارس_أثناء_التوليد حارس;
 * 
 * std::string سطر;
 * size_t رقم = 1;
 * 
 * while (المُولِّد.لديه_المزيد()) {
 *     سطر = المُولِّد.السطر_التالي();
 *     
 *     auto نتيجة = حارس.افحص_سطر(سطر, رقم, "main.ص");
 *     
 *     if (نتيجة.يجب_الإيقاف()) {
 *         std::cerr << "⛔ تم اكتشاف ثغرات خطيرة!\n";
 *         for (const auto& ث : نتيجة.الثغرات) {
 *             std::cerr << ث.رسالة_مفصلة();
 *         }
 *         المُولِّد.أوقف();
 *         break;
 *     }
 *     
 *     رقم++;
 * }
 * ```
 */
class حارس_أثناء_التوليد {
public:
    /**
     * إعدادات الحارس
     */
    struct إعدادات {
        bool فعِّل_فحص_SQL = true;
        bool فعِّل_فحص_أوامر = true;
        bool فعِّل_فحص_ذاكرة = true;
        bool فعِّل_فحص_أسرار = true;
        bool فعِّل_فحص_مسارات = true;
        bool فعِّل_تحليل_تدفق = true;
        
        خطورة_ثغرة حد_الإيقاف = خطورة_ثغرة::حرج;
        
        std::function<void(const ثغرة_مكتشفة&)> معالج_الثغرات;
    };
    
    /**
     * مُنشئ مع الإعدادات الافتراضية
     */
    حارس_أثناء_التوليد() {
        // إضافة القواعد الافتراضية
        if (m_إعدادات.فعِّل_فحص_SQL) {
            أضف_قاعدة(std::make_unique<قاعدة_SQL_Injection>());
        }
        if (m_إعدادات.فعِّل_فحص_أوامر) {
            أضف_قاعدة(std::make_unique<قاعدة_حقن_أوامر>());
        }
        if (m_إعدادات.فعِّل_فحص_ذاكرة) {
            أضف_قاعدة(std::make_unique<قاعدة_تجاوز_مخزن>());
        }
        if (m_إعدادات.فعِّل_فحص_أسرار) {
            أضف_قاعدة(std::make_unique<قاعدة_أسرار_مكشوفة>());
        }
        if (m_إعدادات.فعِّل_فحص_مسارات) {
            أضف_قاعدة(std::make_unique<قاعدة_اختراق_مسارات>());
        }
    }
    
    /**
     * مُنشئ مع إعدادات مخصصة
     */
    explicit حارس_أثناء_التوليد(إعدادات إعدادات)
        : m_إعدادات(std::move(إعدادات)) {
        // إضافة القواعد حسب الإعدادات
        // (نفس المنطق أعلاه)
    }
    
    /**
     * إضافة قاعدة فحص مخصصة
     */
    void أضف_قاعدة(std::unique_ptr<قاعدة_فحص> قاعدة) {
        m_قواعد.push_back(std::move(قاعدة));
    }
    
    /**
     * فحص سطر واحد من الكود
     */
    نتيجة_فحص_كود افحص_سطر(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const {
        
        نتيجة_فحص_كود نتيجة;
        نتيجة.نظيف = true;
        نتيجة.عدد_الأسطر_المفحوصة = 1;
        
        // تطبيق كل قاعدة
        for (const auto& قاعدة : m_قواعد) {
            auto ثغرة = قاعدة->افحص(سطر, رقم_السطر, الملف);
            
            if (ثغرة) {
                نتيجة.الثغرات.push_back(*ثغرة);
                نتيجة.نظيف = false;
                
                if (m_إعدادات.معالج_الثغرات) {
                    m_إعدادات.معالج_الثغرات(*ثغرة);
                }
            }
        }
        
        return نتيجة;
    }
    
    /**
     * فحص ملف كامل
     */
    نتيجة_فحص_كود افحص_ملف(
        const std::string& محتوى,
        const std::string& الملف) const {
        
        نتيجة_فحص_كود نتيجة;
        نتيجة.نظيف = true;
        
        std::istringstream stream(محتوى);
        std::string سطر;
        size_t رقم = 1;
        
        while (std::getline(stream, سطر)) {
            auto نتيجة_سطر = افحص_سطر(سطر, رقم, الملف);
            
            for (auto& ث : نتيجة_سطر.الثغرات) {
                نتيجة.الثغرات.push_back(std::move(ث));
            }
            
            if (!نتيجة_سطر.نظيف) {
                نتيجة.نظيف = false;
            }
            
            رقم++;
        }
        
        نتيجة.عدد_الأسطر_المفحوصة = رقم - 1;
        return نتيجة;
    }
    
    /**
     * الحصول على محلل تدفق البيانات
     */
    محلل_تدفق_البيانات& محلل_التدفق() {
        return m_محلل_تدفق;
    }
    
private:
    إعدادات m_إعدادات;
    std::vector<std::unique_ptr<قاعدة_فحص>> m_قواعد;
    محلل_تدفق_البيانات m_محلل_تدفق;
};

