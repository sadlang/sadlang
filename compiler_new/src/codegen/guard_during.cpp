/**
 * قاعدة فحص SQL Injection
 */
class قاعدة_SQL_Injection : public قاعدة_فحص {
public:
    std::string الاسم() const override { return "SQL-INJECTION"; }
    
    std::string الوصف() const override {
        return "يكشف استعلامات SQL التي تُبنى بدمج نصوص مباشرة، "
               "مما يسمح للمهاجم بحقن أوامر SQL خبيثة";
    }
    
    نوع_ثغرة نوع_الثغرة() const override {
        return نوع_ثغرة::SQL_INJECTION;
    }
    
    std::optional<ثغرة_مكتشفة> افحص(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const override {
        
        // أنماط SQL Injection
        static std::vector<std::regex> أنماط = {
            // دمج متغيرات في استعلام SQL
            std::regex(R"(SELECT.*\+\s*\w+|SELECT.*\{\w+\})", std::regex::icase),
            // استعلام بدون معاملات
            std::regex(R"(execute\s*\(\s*[\"']SELECT.*\+)", std::regex::icase),
            // استخدام format مع SQL
            std::regex(R"(format\s*\(\s*[\"'].*SELECT)", std::regex::icase),
            // استعلام عربي غير آمن
            std::regex(R"(نفذ_استعلام\s*\(\s*[\"'].*\+)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            if (std::regex_search(سطر, نمط)) {
                return ثغرة_مكتشفة{
                    نوع_ثغرة::SQL_INJECTION,
                    خطورة_ثغرة::حرج,
                    "استعلام SQL يُبنى بدمج نصوص - خطر حقن SQL",
                    سطر,
                    {رقم_السطر, 0, سطر.length(), الملف},
                    "استخدم Prepared Statements أو معاملات مُسمَّاة",
                    "CWE-89: SQL Injection"
                };
            }
        }
        
        return std::nullopt;
    }
};

/**
 * قاعدة فحص حقن الأوامر
 */
class قاعدة_حقن_أوامر : public قاعدة_فحص {
public:
    std::string الاسم() const override { return "COMMAND-INJECTION"; }
    
    std::string الوصف() const override {
        return "يكشف تنفيذ أوامر نظام التشغيل مع مدخلات غير موثوقة";
    }
    
    نوع_ثغرة نوع_الثغرة() const override {
        return نوع_ثغرة::COMMAND_INJECTION;
    }
    
    std::optional<ثغرة_مكتشفة> افحص(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const override {
        
        static std::vector<std::regex> أنماط = {
            std::regex(R"(system\s*\(\s*\w+)", std::regex::icase),
            std::regex(R"(exec\s*\(\s*\w+)", std::regex::icase),
            std::regex(R"(popen\s*\(\s*\w+)", std::regex::icase),
            std::regex(R"(نفذ_أمر\s*\(\s*\w+)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            if (std::regex_search(سطر, نمط)) {
                return ثغرة_مكتشفة{
                    نوع_ثغرة::COMMAND_INJECTION,
                    خطورة_ثغرة::حرج,
                    "تنفيذ أوامر نظام مع متغير - خطر حقن أوامر",
                    سطر,
                    {رقم_السطر, 0, سطر.length(), الملف},
                    "استخدم قائمة بيضاء للأوامر المسموحة أو تجنب exec",
                    "CWE-78: OS Command Injection"
                };
            }
        }
        
        return std::nullopt;
    }
};

/**
 * قاعدة فحص تجاوز المخزن المؤقت
 */
class قاعدة_تجاوز_مخزن : public قاعدة_فحص {
public:
    std::string الاسم() const override { return "BUFFER-OVERFLOW"; }
    
    std::string الوصف() const override {
        return "يكشف استخدام دوال نسخ غير آمنة قد تؤدي لتجاوز المخزن";
    }
    
    نوع_ثغرة نوع_الثغرة() const override {
        return نوع_ثغرة::BUFFER_OVERFLOW;
    }
    
    std::optional<ثغرة_مكتشفة> افحص(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const override {
        
        // دوال C غير آمنة
        static std::vector<std::string> دوال_خطيرة = {
            "strcpy", "strcat", "sprintf", "gets", "scanf",
            "انسخ_نص", "ألحق_نص"  // الأسماء العربية
        };
        
        for (const auto& دالة : دوال_خطيرة) {
            if (سطر.find(دالة) != std::string::npos) {
                return ثغرة_مكتشفة{
                    نوع_ثغرة::BUFFER_OVERFLOW,
                    خطورة_ثغرة::عالي,
                    "استخدام دالة " + دالة + " غير آمنة",
                    سطر,
                    {رقم_السطر, 0, سطر.length(), الملف},
                    "استخدم البدائل الآمنة: strncpy, strncat, snprintf",
                    "CWE-120: Buffer Copy without Checking Size"
                };
            }
        }
        
        return std::nullopt;
    }
};

/**
 * قاعدة فحص الأسرار المكشوفة
 */
class قاعدة_أسرار_مكشوفة : public قاعدة_فحص {
public:
    std::string الاسم() const override { return "HARDCODED-SECRET"; }
    
    std::string الوصف() const override {
        return "يكشف كلمات السر ومفاتيح API المكتوبة مباشرة في الكود";
    }
    
    نوع_ثغرة نوع_الثغرة() const override {
        return نوع_ثغرة::HARDCODED_SECRET;
    }
    
    std::optional<ثغرة_مكتشفة> افحص(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const override {
        
        static std::vector<std::regex> أنماط = {
            // كلمات سر
            std::regex(R"((password|passwd|pwd)\s*=\s*[\"'][^\"']+[\"'])", std::regex::icase),
            // مفاتيح API
            std::regex(R"((api_key|apikey|api-key)\s*=\s*[\"'][^\"']+[\"'])", std::regex::icase),
            // أسرار
            std::regex(R"((secret|token|auth)\s*=\s*[\"'][^\"']+[\"'])", std::regex::icase),
            // أنماط عربية
            std::regex(R"((كلمة_سر|مفتاح|سر)\s*=\s*[\"'][^\"']+[\"'])", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            if (std::regex_search(سطر, نمط)) {
                return ثغرة_مكتشفة{
                    نوع_ثغرة::HARDCODED_SECRET,
                    خطورة_ثغرة::عالي,
                    "سر مكشوف في الكود المصدري",
                    "*** مخفي لأسباب أمنية ***",
                    {رقم_السطر, 0, 0, الملف},
                    "استخدم متغيرات البيئة أو مدير أسرار",
                    "CWE-798: Use of Hard-coded Credentials"
                };
            }
        }
        
        return std::nullopt;
    }
};

/**
 * قاعدة فحص Path Traversal
 */
class قاعدة_اختراق_مسارات : public قاعدة_فحص {
public:
    std::string الاسم() const override { return "PATH-TRAVERSAL"; }
    
    std::string الوصف() const override {
        return "يكشف مسارات ملفات قد تسمح بالوصول لملفات خارج المجلد المسموح";
    }
    
    نوع_ثغرة نوع_الثغرة() const override {
        return نوع_ثغرة::PATH_TRAVERSAL;
    }
    
    std::optional<ثغرة_مكتشفة> افحص(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const override {
        
        static std::vector<std::regex> أنماط = {
            std::regex(R"(\.\./)", std::regex::icase),
            std::regex(R"(\.\.\\)", std::regex::icase),
            std::regex(R"(/etc/passwd)", std::regex::icase),
            std::regex(R"(C:\\Windows)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            if (std::regex_search(سطر, نمط)) {
                return ثغرة_مكتشفة{
                    نوع_ثغرة::PATH_TRAVERSAL,
                    خطورة_ثغرة::عالي,
                    "مسار ملف قد يسمح بالوصول لملفات حساسة",
                    سطر,
                    {رقم_السطر, 0, سطر.length(), الملف},
                    "استخدم دالة تنظيف المسار وتحقق من المسار النهائي",
                    "CWE-22: Path Traversal"
                };
            }
        }
        
        return std::nullopt;
    }
};

