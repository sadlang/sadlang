/**
 * موقع في الكود المصدري
 */
struct موقع_كود {
    size_t سطر = 0;
    size_t عمود = 0;
    size_t طول = 0;          // طول النص المشبوه
    std::string الملف;
    
    std::string إلى_نص() const {
        return الملف + ":" + std::to_string(سطر) + ":" + std::to_string(عمود);
    }
};

/**
 * ثغرة مكتشفة
 */
struct ثغرة_مكتشفة {
    نوع_ثغرة النوع;
    خطورة_ثغرة الخطورة;
    std::string الوصف;
    std::string الكود_المشبوه;
    موقع_كود الموقع;
    std::string الإصلاح_المقترح;
    std::string المرجع;          // رابط CWE أو OWASP
    
    /**
     * إنشاء رسالة مفصلة
     */
    std::string رسالة_مفصلة() const {
        std::stringstream ss;
        ss << "⚠️ ثغرة: " << إلى_اسم(النوع) << "\n"
           << "   الموقع: " << الموقع.إلى_نص() << "\n"
           << "   الوصف: " << الوصف << "\n"
           << "   الكود: " << الكود_المشبوه << "\n"
           << "   الإصلاح: " << الإصلاح_المقترح << "\n";
        if (!المرجع.empty()) {
            ss << "   المرجع: " << المرجع << "\n";
        }
        return ss.str();
    }
};

/**
 * نتيجة الفحص الكاملة
 */
struct نتيجة_فحص_كود {
    bool نظيف;                              // هل الكود نظيف؟
    std::vector<ثغرة_مكتشفة> الثغرات;
    size_t عدد_الأسطر_المفحوصة = 0;
    double وقت_الفحص_ms = 0.0;
    
    /**
     * عدد الثغرات حسب الخطورة
     */
    size_t عدد(خطورة_ثغرة خ) const {
        size_t عدد = 0;
        for (const auto& ث : الثغرات) {
            if (ث.الخطورة == خ) عدد++;
        }
        return عدد;
    }
    
    /**
     * هل يجب إيقاف التوليد؟
     */
    bool يجب_الإيقاف() const {
        return عدد(خطورة_ثغرة::حرج) > 0 || عدد(خطورة_ثغرة::عالي) > 1;
    }
};

