/**
 * أنواع الثغرات الأمنية التي يبحث عنها الحارس
 * 
 * للمبتدئ: كل ثغرة هي "باب خلفي" يمكن للمخترقين استغلاله.
 * هنا قائمة بأشهر الثغرات:
 */
enum class نوع_ثغرة {
    // ثغرات الحقن (Injection)
    SQL_INJECTION,          // حقن SQL - خطير جداً
    COMMAND_INJECTION,      // حقن أوامر النظام
    XSS,                    // هجوم السكربت عبر المواقع
    
    // ثغرات الذاكرة
    BUFFER_OVERFLOW,        // تجاوز المخزن المؤقت
    USE_AFTER_FREE,         // استخدام ذاكرة محررة
    NULL_DEREFERENCE,       // إلغاء مرجعية NULL
    
    // ثغرات التشفير
    WEAK_CRYPTO,            // تشفير ضعيف
    HARDCODED_SECRET,       // سر مكتوب في الكود
    INSECURE_RANDOM,        // أرقام عشوائية غير آمنة
    
    // ثغرات المنطق
    RACE_CONDITION,         // حالة سباق
    INFINITE_LOOP,          // حلقة لانهائية
    RESOURCE_LEAK,          // تسريب موارد
    
    // ثغرات الوصول
    PATH_TRAVERSAL,         // اختراق المسارات
    INSECURE_DESERIALIZATION, // إلغاء تسلسل غير آمن
    
    // أخرى
    UNVALIDATED_INPUT,      // مدخلات غير محققة
    INFORMATION_DISCLOSURE, // كشف معلومات
};

/**
 * تحويل نوع الثغرة إلى اسم مقروء
 */
inline std::string إلى_اسم(نوع_ثغرة نوع) {
    switch (نوع) {
        case نوع_ثغرة::SQL_INJECTION: return "SQL Injection";
        case نوع_ثغرة::COMMAND_INJECTION: return "حقن أوامر";
        case نوع_ثغرة::XSS: return "XSS";
        case نوع_ثغرة::BUFFER_OVERFLOW: return "تجاوز المخزن";
        case نوع_ثغرة::USE_AFTER_FREE: return "Use-After-Free";
        case نوع_ثغرة::NULL_DEREFERENCE: return "Null Dereference";
        case نوع_ثغرة::WEAK_CRYPTO: return "تشفير ضعيف";
        case نوع_ثغرة::HARDCODED_SECRET: return "سر مكشوف";
        case نوع_ثغرة::INSECURE_RANDOM: return "عشوائية ضعيفة";
        case نوع_ثغرة::RACE_CONDITION: return "حالة سباق";
        case نوع_ثغرة::INFINITE_LOOP: return "حلقة لانهائية";
        case نوع_ثغرة::RESOURCE_LEAK: return "تسريب موارد";
        case نوع_ثغرة::PATH_TRAVERSAL: return "اختراق مسارات";
        case نوع_ثغرة::INSECURE_DESERIALIZATION: return "إلغاء تسلسل غير آمن";
        case نوع_ثغرة::UNVALIDATED_INPUT: return "مدخلات غير محققة";
        case نوع_ثغرة::INFORMATION_DISCLOSURE: return "كشف معلومات";
    }
    return "غير معروف";
}

/**
 * درجة خطورة الثغرة (CVSS-like)
 */
enum class خطورة_ثغرة {
    معلوماتي,    // 0.0 - معلومة فقط
    منخفض,       // 0.1-3.9
    متوسط,       // 4.0-6.9
    عالي,        // 7.0-8.9
    حرج,         // 9.0-10.0
};

