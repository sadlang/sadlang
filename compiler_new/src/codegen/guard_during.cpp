/**
 * قاعدة فحص واحدة
 * 
 * للمبتدئ: كل قاعدة تبحث عن نوع معين من المشاكل.
 * مثلاً: قاعدة SQL_INJECTION تبحث عن استعلامات SQL غير آمنة.
 */
class قاعدة_فحص {
public:
    virtual ~قاعدة_فحص() = default;
    
    /**
     * اسم القاعدة
     */
    virtual std::string الاسم() const = 0;
    
    /**
     * وصف ما تفحصه القاعدة
     */
    virtual std::string الوصف() const = 0;
    
    /**
     * نوع الثغرة التي تكتشفها
     */
    virtual نوع_ثغرة نوع_الثغرة() const = 0;
    
    /**
     * فحص سطر من الكود
     * @param سطر السطر المراد فحصه
     * @param رقم_السطر رقم السطر في الملف
     * @param الملف اسم الملف
     * @return ثغرة إذا وُجدت، أو std::nullopt
     */
    virtual std::optional<ثغرة_مكتشفة> افحص(
        const std::string& سطر,
        size_t رقم_السطر,
        const std::string& الملف) const = 0;
};

