/**
 * القائمة السوداء للأنماط الخطيرة
 * 
 * للمبتدئ: هذه قائمة بكل الأنماط التي نعتبرها خطيرة.
 * يتم فحص كل طلب مقابل هذه القائمة.
 */
class القائمة_السوداء {
public:
    /**
     * الحصول على النسخة الوحيدة (Singleton)
     */
    static القائمة_السوداء& المثال() {
        static القائمة_السوداء مثال;
        return مثال;
    }
    
    /**
     * إضافة نمط خطير
     */
    void أضف_نمط(نمط_خطير نمط) {
        m_أنماط.push_back(std::move(نمط));
    }
    
    /**
     * فحص نص مقابل كل الأنماط
     * @return قائمة الأنماط المطابقة
     */
    std::vector<const نمط_خطير*> افحص(const std::string& نص) const {
        std::vector<const نمط_خطير*> مطابقات;
        
        for (const auto& نمط : m_أنماط) {
            if (نمط.يطابق(نص)) {
                مطابقات.push_back(&نمط);
            }
        }
        
        return مطابقات;
    }
    
    /**
     * عدد الأنماط في القائمة
     */
    size_t الحجم() const {
        return m_أنماط.size();
    }
    
    /**
     * تحميل الأنماط الافتراضية
     */
    void حمِّل_الافتراضية();
    
private:
    القائمة_السوداء() {
        حمِّل_الافتراضية();
    }
    
    std::vector<نمط_خطير> m_أنماط;
};

