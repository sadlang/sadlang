/**
 * مستويات خطورة العمليات
 * 
 * للمبتدئ: كل عملية لها مستوى خطورة.
 * كلما زاد المستوى، زاد التدقيق المطلوب.
 */
enum class مستوى_خطورة {
    آمن,        // لا خطر - يُسمح دائماً
    منخفض,      // خطر قليل - يُسجَّل فقط
    متوسط,      // خطر متوسط - تحذير للمستخدم
    عالي,       // خطر عالي - يتطلب تأكيد
    حرج,        // خطر حرج - رفض فوري
};

/**
 * تحويل مستوى الخطورة إلى نص
 */
inline std::string إلى_نص(مستوى_خطورة مستوى) {
    switch (مستوى) {
        case مستوى_خطورة::آمن: return "آمن";
        case مستوى_خطورة::منخفض: return "منخفض";
        case مستوى_خطورة::متوسط: return "متوسط";
        case مستوى_خطورة::عالي: return "عالي";
        case مستوى_خطورة::حرج: return "حرج";
    }
    return "غير معروف";
}

/**
 * تحويل مستوى الخطورة إلى رمز
 */
inline std::string رمز_خطورة(مستوى_خطورة مستوى) {
    switch (مستوى) {
        case مستوى_خطورة::آمن: return "🟢";
        case مستوى_خطورة::منخفض: return "🟡";
        case مستوى_خطورة::متوسط: return "🟠";
        case مستوى_خطورة::عالي: return "🔴";
        case مستوى_خطورة::حرج: return "⛔";
    }
    return "❓";
}

