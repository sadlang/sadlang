/**
 * تعريف نمط خطير في القائمة السوداء
 * 
 * للمبتدئ: النمط الخطير هو تعبير نمطي (regex) يصف كوداً قد يكون خطيراً.
 * مثال: أي كود يحتوي "rm -rf /" هو خطير!
 */
struct نمط_خطير {
    std::string المعرف;              // معرف فريد للنمط
    std::string الاسم;               // اسم مقروء
    std::string الوصف;               // شرح للمستخدم
    std::regex التعبير_النمطي;       // التعبير المنتظم للبحث
    نوع_تهديد النوع;                 // نوع التهديد
    مستوى_خطورة الخطورة;             // مستوى الخطورة
    std::string الاقتراح;            // بديل آمن
    std::vector<std::string> أمثلة; // أمثلة على الكود الخطير
    
    /**
     * فحص إذا كان النص يطابق النمط
     */
    bool يطابق(const std::string& نص) const {
        return std::regex_search(نص, التعبير_النمطي);
    }
};

