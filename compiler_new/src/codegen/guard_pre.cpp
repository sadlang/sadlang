/**
 * تحذير أمني من التحليل
 */
struct تحذير_أمني {
    نوع_تهديد النوع;
    مستوى_خطورة الخطورة;
    std::string الرسالة;
    std::string الموقع;          // أين في الطلب
    std::string الاقتراح;
    std::string النمط_المطابق;   // أي نمط تم اكتشافه
};

/**
 * نتيجة تحليل الطلب
 */
struct نتيجة_تحليل {
    bool آمن;                               // هل الطلب آمن؟
    مستوى_خطورة أعلى_خطورة;                 // أعلى مستوى خطورة مكتشف
    std::vector<تحذير_أمني> التحذيرات;      // قائمة التحذيرات
    bool يتطلب_تأكيد;                       // هل يحتاج تأكيد المستخدم؟
    std::string ملخص;                       // ملخص للمستخدم
    
    /**
     * هل هناك تحذيرات؟
     */
    bool بها_تحذيرات() const {
        return !التحذيرات.empty();
    }
    
    /**
     * عدد التحذيرات حسب المستوى
     */
    size_t عدد_بمستوى(مستوى_خطورة مستوى) const {
        size_t عدد = 0;
        for (const auto& ت : التحذيرات) {
            if (ت.الخطورة == مستوى) عدد++;
        }
        return عدد;
    }
};

