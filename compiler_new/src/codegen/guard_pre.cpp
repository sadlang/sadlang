inline محلل_النية::نتيجة_نية محلل_النية::حلل(const std::string& طلب) const {
    نتيجة_نية نتيجة;
    نتيجة.النوع = نوع_نية::غير_محدد;
    نتيجة.الثقة = 0.5;
    نتيجة.آمنة = true;
    
    // تحويل إلى أحرف صغيرة للمقارنة
    std::string طلب_صغير = طلب;
    std::transform(طلب_صغير.begin(), طلب_صغير.end(), طلب_صغير.begin(), ::tolower);
    
    // البحث عن كلمات النية
    // كلمات القراءة (آمن)
    if (طلب_صغير.find("اقرأ") != std::string::npos ||
        طلب_صغير.find("قراءة") != std::string::npos ||
        طلب_صغير.find("احصل") != std::string::npos ||
        طلب_صغير.find("get") != std::string::npos ||
        طلب_صغير.find("read") != std::string::npos) {
        نتيجة.النوع = نوع_نية::قراءة_بيانات;
        نتيجة.الثقة = 0.8;
        نتيجة.آمنة = true;
        نتيجة.الشرح = "نية قراءة بيانات - عملية آمنة عادة";
        نتيجة.مؤشرات.push_back("كلمة قراءة");
    }
    
    // كلمات الكتابة (تحتاج تحقق)
    else if (طلب_صغير.find("اكتب") != std::string::npos ||
             طلب_صغير.find("احفظ") != std::string::npos ||
             طلب_صغير.find("write") != std::string::npos ||
             طلب_صغير.find("save") != std::string::npos) {
        نتيجة.النوع = نوع_نية::كتابة_بيانات;
        نتيجة.الثقة = 0.7;
        نتيجة.آمنة = true;  // آمن إذا كان في مكان مسموح
        نتيجة.الشرح = "نية كتابة بيانات - تأكد من الموقع";
        نتيجة.مؤشرات.push_back("كلمة كتابة");
    }
    
    // كلمات الحذف (خطير)
    else if (طلب_صغير.find("احذف") != std::string::npos ||
             طلب_صغير.find("امسح") != std::string::npos ||
             طلب_صغير.find("أزل") != std::string::npos ||
             طلب_صغير.find("delete") != std::string::npos ||
             طلب_صغير.find("remove") != std::string::npos) {
        نتيجة.النوع = نوع_نية::حذف_بيانات;
        نتيجة.الثقة = 0.85;
        نتيجة.آمنة = false;
        نتيجة.الشرح = "نية حذف بيانات - يتطلب تأكيد";
        نتيجة.مؤشرات.push_back("كلمة حذف");
    }
    
    // كلمات التنفيذ (خطير جداً)
    else if (طلب_صغير.find("نفذ") != std::string::npos ||
             طلب_صغير.find("شغل") != std::string::npos ||
             طلب_صغير.find("exec") != std::string::npos ||
             طلب_صغير.find("run") != std::string::npos ||
             طلب_صغير.find("system") != std::string::npos) {
        نتيجة.النوع = نوع_نية::تنفيذ_نظام;
        نتيجة.الثقة = 0.9;
        نتيجة.آمنة = false;
        نتيجة.الشرح = "نية تنفيذ أوامر نظام - خطير جداً";
        نتيجة.مؤشرات.push_back("كلمة تنفيذ");
    }
    
    // البحث عن كلمات تزيد الخطورة
    if (طلب_صغير.find("كل") != std::string::npos ||
        طلب_صغير.find("جميع") != std::string::npos ||
        طلب_صغير.find("all") != std::string::npos) {
        نتيجة.آمنة = false;
        نتيجة.الثقة += 0.1;
        نتيجة.مؤشرات.push_back("كلمة شاملة (كل/جميع)");
    }
    
    return نتيجة;
}

inline نتيجة_تحليل حارس_قبل_التوليد::افحص(const std::string& طلب) const {
    نتيجة_تحليل نتيجة;
    نتيجة.آمن = true;
    نتيجة.أعلى_خطورة = مستوى_خطورة::آمن;
    نتيجة.يتطلب_تأكيد = false;
    
    // 1. تحليل النية
    if (m_إعدادات.فعِّل_تحليل_النية) {
        auto نتيجة_النية = m_محلل_النية.حلل(طلب);
        
        if (!نتيجة_النية.آمنة) {
            تحذير_أمني تحذير;
            تحذير.النوع = نوع_تهديد::غير_محدد;
            تحذير.الخطورة = مستوى_خطورة::عالي;
            تحذير.الرسالة = "النية المكتشفة: " + نتيجة_النية.الشرح;
            تحذير.الاقتراح = "تأكد من أن هذا ما تريده فعلاً";
            
            نتيجة.التحذيرات.push_back(تحذير);
            
            if (نتيجة_النية.النوع == محلل_النية::نوع_نية::حذف_بيانات ||
                نتيجة_النية.النوع == محلل_النية::نوع_نية::تنفيذ_نظام) {
                نتيجة.يتطلب_تأكيد = true;
            }
        }
    }
    
    // 2. فحص القائمة السوداء
    if (m_إعدادات.فعِّل_القائمة_السوداء) {
        auto تحذيرات_القائمة = افحص_القائمة_السوداء(طلب);
        for (auto& ت : تحذيرات_القائمة) {
            نتيجة.التحذيرات.push_back(std::move(ت));
        }
    }
    
    // 3. تحديد أعلى خطورة
    for (const auto& ت : نتيجة.التحذيرات) {
        if (static_cast<int>(ت.الخطورة) > static_cast<int>(نتيجة.أعلى_خطورة)) {
            نتيجة.أعلى_خطورة = ت.الخطورة;
        }
        
        // استدعاء معالج التحذيرات إذا موجود
        if (m_إعدادات.معالج_التحذيرات) {
            m_إعدادات.معالج_التحذيرات(ت);
        }
    }
    
    // 4. تحديد إذا كان آمن ويتطلب تأكيد
    if (نتيجة.أعلى_خطورة >= m_إعدادات.الحد_للرفض) {
        نتيجة.آمن = false;
    }
    
    if (نتيجة.أعلى_خطورة >= m_إعدادات.الحد_للتأكيد) {
        نتيجة.يتطلب_تأكيد = true;
    }
    
    // 5. بناء الملخص
    نتيجة.ملخص = ابنِ_الملخص(نتيجة.التحذيرات);
    
    return نتيجة;
}

inline std::vector<تحذير_أمني> حارس_قبل_التوليد::افحص_القائمة_السوداء(
    const std::string& طلب) const {
    
    std::vector<تحذير_أمني> تحذيرات;
    
    auto مطابقات = القائمة_السوداء::المثال().افحص(طلب);
    
    for (const auto* نمط : مطابقات) {
        تحذير_أمني تحذير;
        تحذير.النوع = نمط->النوع;
        تحذير.الخطورة = نمط->الخطورة;
        تحذير.الرسالة = نمط->الوصف;
        تحذير.الاقتراح = نمط->الاقتراح;
        تحذير.النمط_المطابق = نمط->المعرف;
        
        تحذيرات.push_back(تحذير);
    }
    
    return تحذيرات;
}

inline std::string حارس_قبل_التوليد::ابنِ_الملخص(
    const std::vector<تحذير_أمني>& تحذيرات) const {
    
    if (تحذيرات.empty()) {
        return "✅ الطلب يبدو آمناً";
    }
    
    std::string ملخص;
    
    // عدّ التحذيرات حسب المستوى
    size_t حرج = 0, عالي = 0, متوسط = 0, منخفض = 0;
    
    for (const auto& ت : تحذيرات) {
        switch (ت.الخطورة) {
            case مستوى_خطورة::حرج: حرج++; break;
            case مستوى_خطورة::عالي: عالي++; break;
            case مستوى_خطورة::متوسط: متوسط++; break;
            case مستوى_خطورة::منخفض: منخفض++; break;
            default: break;
        }
    }
    
    ملخص = "⚠️ تم اكتشاف " + std::to_string(تحذيرات.size()) + " تحذير(ات):\n";
    
    if (حرج > 0) ملخص += "  ⛔ " + std::to_string(حرج) + " حرج\n";
    if (عالي > 0) ملخص += "  🔴 " + std::to_string(عالي) + " عالي\n";
    if (متوسط > 0) ملخص += "  🟠 " + std::to_string(متوسط) + " متوسط\n";
    if (منخفض > 0) ملخص += "  🟡 " + std::to_string(منخفض) + " منخفض\n";
    
    return ملخص;
}

