/**
 * الحارس قبل التوليد
 * 
 * الفئة الرئيسية التي تجمع كل آليات الفحص قبل توليد الكود.
 * 
 * مثال الاستخدام:
 * ```cpp
 * حارس_قبل_التوليد حارس;
 * 
 * std::string طلب = "اكتب دالة لحذف الملفات القديمة";
 * 
 * auto نتيجة = حارس.افحص(طلب);
 * 
 * if (!نتيجة.آمن) {
 *     std::cout << "⚠️ تحذير: " << نتيجة.ملخص << std::endl;
 *     
 *     if (نتيجة.يتطلب_تأكيد) {
 *         // اطلب تأكيد المستخدم
 *         if (!احصل_على_تأكيد()) {
 *             return; // ألغِ العملية
 *         }
 *     }
 * }
 * 
 * // تابع التوليد...
 * ```
 */
class حارس_قبل_التوليد {
public:
    /**
     * إعدادات الحارس
     */
    struct إعدادات {
        مستوى_خطورة الحد_للتأكيد = مستوى_خطورة::عالي;
        مستوى_خطورة الحد_للرفض = مستوى_خطورة::حرج;
        bool سجِّل_كل_الطلبات = false;
        bool فعِّل_تحليل_النية = true;
        bool فعِّل_القائمة_السوداء = true;
        std::function<void(const تحذير_أمني&)> معالج_التحذيرات;
    };
    
    /**
     * مُنشئ مع إعدادات افتراضية
     */
    حارس_قبل_التوليد() = default;
    
    /**
     * مُنشئ مع إعدادات مخصصة
     */
    explicit حارس_قبل_التوليد(إعدادات إعدادات)
        : m_إعدادات(std::move(إعدادات)) {}
    
    /**
     * فحص طلب المستخدم
     * @param طلب نص الطلب من المستخدم
     * @return نتيجة التحليل
     */
    نتيجة_تحليل افحص(const std::string& طلب) const;
    
    /**
     * تحديث الإعدادات
     */
    void عيِّن_الإعدادات(إعدادات إعدادات) {
        m_إعدادات = std::move(إعدادات);
    }
    
    /**
     * الحصول على الإعدادات الحالية
     */
    const إعدادات& احصل_على_الإعدادات() const {
        return m_إعدادات;
    }
    
    /**
     * إضافة نمط خطير مخصص
     */
    void أضف_نمط_خطير(نمط_خطير نمط) {
        القائمة_السوداء::المثال().أضف_نمط(std::move(نمط));
    }
    
private:
    إعدادات m_إعدادات;
    محلل_النية m_محلل_النية;
    
    /**
     * فحص بالقائمة السوداء
     */
    std::vector<تحذير_أمني> افحص_القائمة_السوداء(const std::string& طلب) const;
    
    /**
     * بناء الملخص
     */
    std::string ابنِ_الملخص(const std::vector<تحذير_أمني>& تحذيرات) const;
};

