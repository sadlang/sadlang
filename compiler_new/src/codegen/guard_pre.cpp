/**
 * محلل نية المستخدم
 * 
 * للمبتدئ: هذا المحلل يحاول فهم "ما يريد المستخدم فعله حقاً"
 * ويتحقق إذا كانت النية آمنة.
 * 
 * مثال:
 *     "اكتب دالة لقراءة ملف" → نية آمنة ✅
 *     "اكتب دالة لحذف كل الملفات" → نية خطيرة ⚠️
 */
class محلل_النية {
public:
    /**
     * أنواع النوايا المعروفة
     */
    enum class نوع_نية {
        قراءة_بيانات,      // قراءة فقط - آمن عادة
        كتابة_بيانات,      // كتابة - يحتاج تحقق
        حذف_بيانات,        // حذف - خطير
        اتصال_شبكة,        // شبكة - يحتاج مراجعة
        تنفيذ_نظام,        // تنفيذ أوامر - خطير جداً
        تشفير,            // تشفير - يحتاج مراجعة
        مصادقة,           // مصادقة - حساس
        غير_محدد,          // غير واضح
    };
    
    /**
     * نتيجة تحليل النية
     */
    struct نتيجة_نية {
        نوع_نية النوع;
        double الثقة;           // 0.0-1.0 مدى ثقتنا بالتحليل
        std::string الشرح;
        bool آمنة;
        std::vector<std::string> مؤشرات;  // الكلمات/الأنماط التي أدت للتحليل
    };
    
    /**
     * تحليل نية طلب المستخدم
     */
    نتيجة_نية حلل(const std::string& طلب) const;
    
private:
    /**
     * كلمات مفتاحية لكل نوع نية
     */
    static const std::unordered_map<std::string, نوع_نية> كلمات_النية;
    
    /**
     * كلمات تزيد الخطورة
     */
    static const std::unordered_set<std::string> كلمات_خطرة;
};

