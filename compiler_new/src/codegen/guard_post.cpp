/**
 * نوع الخطأ المكتشف
 */
enum class نوع_خطأ_Fuzzing {
    انهيار,           // Crash
    تجاوز_وقت,        // Timeout
    تسريب_ذاكرة,      // Memory leak
    سلوك_غير_متوقع,   // Unexpected behavior
    استثناء,          // Exception
    assertion_fail,   // Assertion failure
    لا_خطأ,
};

/**
 * حالة اختبار واحدة
 */
struct حالة_Fuzzing {
    std::string المدخل;
    نوع_خطأ_Fuzzing النتيجة;
    std::string رسالة_الخطأ;
    double الوقت_ms;
    size_t استخدام_الذاكرة;
};

/**
 * ملخص نتائج الـ Fuzzing
 */
struct ملخص_Fuzzing {
    size_t إجمالي_الاختبارات = 0;
    size_t الاختبارات_الناجحة = 0;
    size_t الانهيارات = 0;
    size_t التجاوزات = 0;
    size_t التسريبات = 0;
    
    std::vector<حالة_Fuzzing> الحالات_الفاشلة;
    
    double معدل_النجاح() const {
        if (إجمالي_الاختبارات == 0) return 0.0;
        return static_cast<double>(الاختبارات_الناجحة) / 
               إجمالي_الاختبارات * 100.0;
    }
    
    bool نجح_كلياً() const {
        return الانهيارات == 0 && التجاوزات == 0;
    }
};

