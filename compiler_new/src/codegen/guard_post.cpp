/**
 * مولد مدخلات للـ Fuzzing
 * 
 * للمبتدئ: هذا يولد مدخلات "غريبة" لاختبار البرنامج.
 * 
 * الهدف: إيجاد حالات تُكسر البرنامج.
 * إذا وجدنا حالة → نصلحها قبل أن يجدها المخترق!
 */
class مولد_مدخلات_Fuzzing {
public:
    /**
     * أنواع المدخلات للتوليد
     */
    enum class نوع_مدخل {
        نص_فارغ,           // ""
        نص_طويل_جداً,       // مليون حرف
        أرقام_حدية,        // INT_MAX, INT_MIN, 0
        أحرف_خاصة,         // 💀, \0, \n, etc
        Unicode_غريب,      // RTL, combining chars
        SQL_حقن,           // ' OR 1=1 --
        XSS_حقن,           // <script>alert(1)</script>
        مسارات,            // ../../../etc/passwd
        عشوائي,
    };
    
    /**
     * توليد مدخل من نوع معين
     */
    std::string ولِّد(نوع_مدخل نوع) {
        switch (نوع) {
            case نوع_مدخل::نص_فارغ:
                return "";
                
            case نوع_مدخل::نص_طويل_جداً:
                return std::string(1000000, 'A');
                
            case نوع_مدخل::أرقام_حدية:
                return ولِّد_رقم_حدي();
                
            case نوع_مدخل::أحرف_خاصة:
                return ولِّد_أحرف_خاصة();
                
            case نوع_مدخل::Unicode_غريب:
                return ولِّد_Unicode_غريب();
                
            case نوع_مدخل::SQL_حقن:
                return ولِّد_SQL_حقن();
                
            case نوع_مدخل::XSS_حقن:
                return ولِّد_XSS_حقن();
                
            case نوع_مدخل::مسارات:
                return ولِّد_مسار_خبيث();
                
            case نوع_مدخل::عشوائي:
                return ولِّد_عشوائي();
        }
        return "";
    }
    
    /**
     * توليد مجموعة كاملة من المدخلات
     */
    std::vector<std::string> ولِّد_مجموعة_كاملة() {
        std::vector<std::string> مدخلات;
        
        for (int i = 0; i <= static_cast<int>(نوع_مدخل::عشوائي); ++i) {
            مدخلات.push_back(ولِّد(static_cast<نوع_مدخل>(i)));
        }
        
        // إضافة مدخلات عشوائية إضافية
        for (int i = 0; i < 10; ++i) {
            مدخلات.push_back(ولِّد(نوع_مدخل::عشوائي));
        }
        
        return مدخلات;
    }
    
private:
    std::mt19937 m_مولد{std::random_device{}()};
    
    std::string ولِّد_رقم_حدي() {
        std::vector<std::string> قيم = {
            "0", "-1", "1",
            std::to_string(INT32_MAX),
            std::to_string(INT32_MIN),
            std::to_string(INT64_MAX),
            std::to_string(INT64_MIN),
            "NaN", "Infinity", "-Infinity",
            "0.0", "-0.0", "1e308", "1e-308"
        };
        
        std::uniform_int_distribution<> توزيع(0, قيم.size() - 1);
        return قيم[توزيع(m_مولد)];
    }
    
    std::string ولِّد_أحرف_خاصة() {
        std::vector<std::string> أحرف = {
            "\0", "\n", "\r", "\t",
            "\x1b", "\x7f",  // Control chars
            "\\", "/", "\"", "'",
            "<", ">", "&", "|",
            "$", "`", "!", "?",
            "💀", "🔥", "💣", "☠️",  // Emoji
        };
        
        std::string نتيجة;
        std::uniform_int_distribution<> توزيع(0, أحرف.size() - 1);
        
        for (int i = 0; i < 20; ++i) {
            نتيجة += أحرف[توزيع(m_مولد)];
        }
        
        return نتيجة;
    }
    
    std::string ولِّد_Unicode_غريب() {
        std::vector<std::string> unicode = {
            "\u202E",      // Right-to-Left Override
            "\u200B",      // Zero Width Space
            "\u200D",      // Zero Width Joiner
            "\uFEFF",      // BOM
            "\u0300\u0301\u0302",  // Combining chars
            "مرحبا",        // Arabic
            "שלום",         // Hebrew
            "中文",          // Chinese
            "🏳️‍🌈",         // Complex emoji
        };
        
        std::string نتيجة;
        std::uniform_int_distribution<> توزيع(0, unicode.size() - 1);
        
        for (int i = 0; i < 5; ++i) {
            نتيجة += unicode[توزيع(m_مولد)];
        }
        
        return نتيجة;
    }
    
    std::string ولِّد_SQL_حقن() {
        std::vector<std::string> حقن = {
            "' OR '1'='1",
            "'; DROP TABLE users; --",
            "1' AND 1=1 UNION SELECT * FROM passwords --",
            "admin'--",
            "1; DELETE FROM products",
            "' UNION SELECT username, password FROM users--",
        };
        
        std::uniform_int_distribution<> توزيع(0, حقن.size() - 1);
        return حقن[توزيع(m_مولد)];
    }
    
    std::string ولِّد_XSS_حقن() {
        std::vector<std::string> حقن = {
            "<script>alert('XSS')</script>",
            "<img src=x onerror=alert('XSS')>",
            "<svg onload=alert('XSS')>",
            "javascript:alert('XSS')",
            "<body onload=alert('XSS')>",
            "';alert('XSS');//",
        };
        
        std::uniform_int_distribution<> توزيع(0, حقن.size() - 1);
        return حقن[توزيع(m_مولد)];
    }
    
    std::string ولِّد_مسار_خبيث() {
        std::vector<std::string> مسارات = {
            "../../../etc/passwd",
            "..\\..\\..\\windows\\system32\\config\\sam",
            "/etc/shadow",
            "....//....//....//etc/passwd",
            "%2e%2e%2f%2e%2e%2f%2e%2e%2fetc/passwd",
            "..%c0%af..%c0%af..%c0%afetc/passwd",
        };
        
        std::uniform_int_distribution<> توزيع(0, مسارات.size() - 1);
        return مسارات[توزيع(m_مولد)];
    }
    
    std::string ولِّد_عشوائي() {
        std::string نتيجة;
        std::uniform_int_distribution<> توزيع_طول(1, 1000);
        std::uniform_int_distribution<> توزيع_حرف(0, 255);
        
        int طول = توزيع_طول(m_مولد);
        for (int i = 0; i < طول; ++i) {
            نتيجة += static_cast<char>(توزيع_حرف(m_مولد));
        }
        
        return نتيجة;
    }
};

