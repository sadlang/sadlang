/**
 * الحارس بعد التوليد
 * 
 * الفئة الرئيسية التي تجمع كل آليات الفحص بعد توليد الكود.
 * 
 * مثال الاستخدام:
 * ```cpp
 * حارس_بعد_التوليد حارس;
 * 
 * std::string كود_مُولَّد = المُولِّد.احصل_على_الكود();
 * 
 * // 1. Fuzzing
 * auto نتيجة_fuzz = حارس.نفِّذ_Fuzzing(كود_مُولَّد, دالة_اختبار);
 * if (!نتيجة_fuzz.نجح_كلياً()) {
 *     std::cerr << "⚠️ Fuzzing وجد مشاكل!\n";
 *     // عالج المشاكل
 * }
 * 
 * // 2. مراجعة AI (اختياري)
 * auto نتيجة_ai = حارس.راجع_بـAI(كود_مُولَّد, "دالة لقراءة ملفات");
 * if (!نتيجة_ai.آمن) {
 *     std::cerr << "⚠️ AI يرى مخاوف: " << نتيجة_ai.الملخص << "\n";
 * }
 * 
 * // 3. تشغيل في Sandbox
 * auto نتيجة_sandbox = حارس.شغِّل_في_Sandbox(كود_مُولَّد, أذونات);
 * if (نتيجة_sandbox.حاول_الهروب) {
 *     std::cerr << "⛔ الكود حاول الهروب من Sandbox!\n";
 *     // ارفض الكود
 * }
 * ```
 */
class حارس_بعد_التوليد {
public:
    /**
     * إعدادات الحارس
     */
    struct إعدادات {
        // Fuzzing
        bool فعِّل_Fuzzing = true;
        size_t عدد_اختبارات_Fuzzing = 100;
        size_t الحد_الأقصى_للوقت_ms = 1000;
        
        // مراجعة AI
        bool فعِّل_مراجعة_AI = false;
        std::shared_ptr<واجهة_مراجعة_AI> مراجع_AI;
        
        // Sandbox
        bool فعِّل_Sandbox = true;
        أذونات_Sandbox أذونات_افتراضية;
        
        // Callbacks
        std::function<void(const حالة_Fuzzing&)> معالج_Fuzzing;
        std::function<void(const نتيجة_مراجعة_AI&)> معالج_AI;
        std::function<void(const نتيجة_Sandbox&)> معالج_Sandbox;
    };
    
    /**
     * مُنشئ
     */
    حارس_بعد_التوليد() = default;
    
    explicit حارس_بعد_التوليد(إعدادات إعدادات)
        : m_إعدادات(std::move(إعدادات)) {}
    
    /**
     * تنفيذ Fuzzing على دالة
     * 
     * @param دالة_الاختبار دالة تأخذ std::string وترجع bool (true = نجاح)
     * @return ملخص نتائج الـ Fuzzing
     */
    template<typename دالة>
    ملخص_Fuzzing نفِّذ_Fuzzing(دالة&& دالة_الاختبار) {
        ملخص_Fuzzing ملخص;
        
        مولد_مدخلات_Fuzzing مولد;
        auto مدخلات = مولد.ولِّد_مجموعة_كاملة();
        
        // إضافة مدخلات عشوائية إضافية
        for (size_t i = مدخلات.size(); 
             i < m_إعدادات.عدد_اختبارات_Fuzzing; ++i) {
            مدخلات.push_back(
                مولد.ولِّد(مولد_مدخلات_Fuzzing::نوع_مدخل::عشوائي)
            );
        }
        
        for (const auto& مدخل : مدخلات) {
            ملخص.إجمالي_الاختبارات++;
            
            حالة_Fuzzing حالة;
            حالة.المدخل = مدخل;
            
            auto بداية = std::chrono::high_resolution_clock::now();
            
            try {
                // تشغيل مع timeout
                std::future<bool> future = std::async(
                    std::launch::async,
                    [&]() { return دالة_الاختبار(مدخل); }
                );
                
                if (future.wait_for(
                        std::chrono::milliseconds(m_إعدادات.الحد_الأقصى_للوقت_ms)) 
                    == std::future_status::timeout) {
                    
                    حالة.النتيجة = نوع_خطأ_Fuzzing::تجاوز_وقت;
                    حالة.رسالة_الخطأ = "تجاوز الحد الأقصى للوقت";
                    ملخص.التجاوزات++;
                    ملخص.الحالات_الفاشلة.push_back(حالة);
                    
                } else {
                    bool نجح = future.get();
                    
                    if (نجح) {
                        حالة.النتيجة = نوع_خطأ_Fuzzing::لا_خطأ;
                        ملخص.الاختبارات_الناجحة++;
                    } else {
                        حالة.النتيجة = نوع_خطأ_Fuzzing::سلوك_غير_متوقع;
                        حالة.رسالة_الخطأ = "الدالة أرجعت false";
                        ملخص.الحالات_الفاشلة.push_back(حالة);
                    }
                }
                
            } catch (const std::exception& e) {
                حالة.النتيجة = نوع_خطأ_Fuzzing::استثناء;
                حالة.رسالة_الخطأ = e.what();
                ملخص.الانهيارات++;
                ملخص.الحالات_الفاشلة.push_back(حالة);
                
            } catch (...) {
                حالة.النتيجة = نوع_خطأ_Fuzzing::انهيار;
                حالة.رسالة_الخطأ = "استثناء غير معروف";
                ملخص.الانهيارات++;
                ملخص.الحالات_الفاشلة.push_back(حالة);
            }
            
            auto نهاية = std::chrono::high_resolution_clock::now();
            حالة.الوقت_ms = std::chrono::duration<double, std::milli>(
                نهاية - بداية).count();
            
            // استدعاء المعالج إذا موجود
            if (m_إعدادات.معالج_Fuzzing) {
                m_إعدادات.معالج_Fuzzing(حالة);
            }
        }
        
        return ملخص;
    }
    
    /**
     * مراجعة الكود باستخدام AI
     */
    نتيجة_مراجعة_AI راجع_بـAI(
        const std::string& الكود,
        const std::string& السياق = "") {
        
        if (!m_إعدادات.مراجع_AI) {
            // استخدم المراجع الوهمي كافتراضي
            m_إعدادات.مراجع_AI = std::make_shared<مراجع_AI_وهمي>();
        }
        
        auto نتيجة = m_إعدادات.مراجع_AI->راجع(الكود, السياق);
        
        if (m_إعدادات.معالج_AI) {
            m_إعدادات.معالج_AI(نتيجة);
        }
        
        return نتيجة;
    }
    
    /**
     * تشغيل كود في Sandbox
     * 
     * ملاحظة: التنفيذ الفعلي للـ Sandbox يعتمد على المنصة.
     * هذا تنفيذ محاكاة للتوضيح.
     */
    نتيجة_Sandbox شغِّل_في_Sandbox(
        const std::string& الكود,
        const أذونات_Sandbox& أذونات = أذونات_Sandbox{}) {
        
        نتيجة_Sandbox نتيجة;
        نتيجة.نجح = true;
        نتيجة.كود_الخروج = 0;
        نتيجة.حاول_الهروب = false;
        
        // محاكاة فحص الكود للعمليات غير المسموحة
        
        // فحص محاولات الوصول للملفات
        if (!أذونات.قراءة_ملفات) {
            if (الكود.find("افتح(") != std::string::npos ||
                الكود.find("open(") != std::string::npos ||
                الكود.find("fopen(") != std::string::npos) {
                نتيجة.محاولات_مرفوضة.push_back("محاولة فتح ملف");
            }
        }
        
        // فحص محاولات الشبكة
        if (!أذونات.اتصال_شبكة) {
            if (الكود.find("socket(") != std::string::npos ||
                الكود.find("connect(") != std::string::npos ||
                الكود.find("اتصل(") != std::string::npos) {
                نتيجة.محاولات_مرفوضة.push_back("محاولة اتصال شبكة");
            }
        }
        
        // فحص محاولات تنفيذ أوامر
        if (!أذونات.تنفيذ_أوامر) {
            if (الكود.find("system(") != std::string::npos ||
                الكود.find("exec(") != std::string::npos ||
                الكود.find("نفذ(") != std::string::npos) {
                نتيجة.محاولات_مرفوضة.push_back("محاولة تنفيذ أمر نظام");
                نتيجة.حاول_الهروب = true;
            }
        }
        
        // فحص محاولات الهروب من Sandbox
        std::vector<std::string> أنماط_هروب = {
            "/proc/", "/dev/", "../../../",
            "\\\\", "C:\\Windows", "cmd.exe",
            "ptrace", "prctl"
        };
        
        for (const auto& نمط : أنماط_هروب) {
            if (الكود.find(نمط) != std::string::npos) {
                نتيجة.حاول_الهروب = true;
                نتيجة.محاولات_مرفوضة.push_back(
                    "محاولة هروب محتملة: " + نمط
                );
            }
        }
        
        if (!نتيجة.محاولات_مرفوضة.empty()) {
            نتيجة.نجح = false;
            نتيجة.مخرجات_الأخطاء = "تم رفض " + 
                std::to_string(نتيجة.محاولات_مرفوضة.size()) + 
                " عملية(عمليات)";
        }
        
        if (m_إعدادات.معالج_Sandbox) {
            m_إعدادات.معالج_Sandbox(نتيجة);
        }
        
        return نتيجة;
    }
    
    /**
     * تنفيذ كل الفحوصات
     */
    struct نتيجة_فحص_كامل {
        bool نجح;
        std::optional<ملخص_Fuzzing> Fuzzing;
        std::optional<نتيجة_مراجعة_AI> AI;
        std::optional<نتيجة_Sandbox> Sandbox;
        std::string الملخص;
    };
    
    template<typename دالة>
    نتيجة_فحص_كامل افحص_كامل(
        const std::string& الكود,
        دالة&& دالة_اختبار,
        const std::string& السياق = "") {
        
        نتيجة_فحص_كامل نتيجة;
        نتيجة.نجح = true;
        std::stringstream ملخص;
        
        // 1. Fuzzing
        if (m_إعدادات.فعِّل_Fuzzing) {
            نتيجة.Fuzzing = نفِّذ_Fuzzing(std::forward<دالة>(دالة_اختبار));
            
            if (!نتيجة.Fuzzing->نجح_كلياً()) {
                نتيجة.نجح = false;
                ملخص << "⚠️ Fuzzing: " 
                      << نتيجة.Fuzzing->الانهيارات << " انهيار، "
                      << نتيجة.Fuzzing->التجاوزات << " تجاوز وقت\n";
            } else {
                ملخص << "✅ Fuzzing: نجح (" 
                      << نتيجة.Fuzzing->معدل_النجاح() << "%)\n";
            }
        }
        
        // 2. مراجعة AI
        if (m_إعدادات.فعِّل_مراجعة_AI) {
            نتيجة.AI = راجع_بـAI(الكود, السياق);
            
            if (!نتيجة.AI->آمن) {
                نتيجة.نجح = false;
                ملخص << "⚠️ AI: " << نتيجة.AI->الملخص << "\n";
            } else {
                ملخص << "✅ AI: " << نتيجة.AI->الملخص << "\n";
            }
        }
        
        // 3. Sandbox
        if (m_إعدادات.فعِّل_Sandbox) {
            نتيجة.Sandbox = شغِّل_في_Sandbox(الكود);
            
            if (نتيجة.Sandbox->حاول_الهروب) {
                نتيجة.نجح = false;
                ملخص << "⛔ Sandbox: محاولة هروب!\n";
            } else if (!نتيجة.Sandbox->محاولات_مرفوضة.empty()) {
                ملخص << "⚠️ Sandbox: " 
                      << نتيجة.Sandbox->محاولات_مرفوضة.size() 
                      << " عملية مرفوضة\n";
            } else {
                ملخص << "✅ Sandbox: آمن\n";
            }
        }
        
        نتيجة.الملخص = ملخص.str();
        return نتيجة;
    }
    
    /**
     * تعيين الإعدادات
     */
    void عيِّن_الإعدادات(إعدادات إعدادات) {
        m_إعدادات = std::move(إعدادات);
    }
    
private:
    إعدادات m_إعدادات;
};

