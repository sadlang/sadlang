/**
 * أنماط البحث في الكود
 */
struct أنماط_كود {
    // نمط تعريف متغير: دع اسم = قيمة
    static inline std::string تعريف_متغير = R"(دع\s+([أ-ي\w]+)\s*=)";
    
    // نمط استخدام متغير
    static inline std::string استخدام_متغير = R"(\$([أ-ي\w]+)|([أ-ي][أ-ي\w]*))";
};

/**
 * مُنظِّف الماكرو الرئيسي
 * 
 * يحول كود الماكرو إلى كود "نظيف" بأسماء فريدة
 */
class منظف_ماكرو {
public:
    /**
     * تنظيف جسم الماكرو
     * 
     * مثال:
     *     قبل: دع نتيجة = $س * 2; نتيجة
     *     بعد: دع __ماكرو_ضاعف_نتيجة_1 = $س * 2; __ماكرو_ضاعف_نتيجة_1
     */
    std::string نظِّف(
        const std::string& اسم_الماكرو,
        const std::string& الجسم,
        const std::vector<std::string>& أسماء_المعاملات
    ) {
        نطاق_ماكرو نطاق(اسم_الماكرو);
        
        // سجِّل المعاملات
        for (const auto& معامل : أسماء_المعاملات) {
            نطاق.سجِّل_معامل(معامل);
        }
        
        std::string نتيجة = الجسم;
        
        // المرحلة 1: ابحث عن كل تعريفات المتغيرات واستبدلها
        نتيجة = استبدل_تعريفات(نتيجة, نطاق);
        
        // المرحلة 2: استبدل كل استخدامات المتغيرات
        نتيجة = استبدل_استخدامات(نتيجة, نطاق);
        
        return نتيجة;
    }
    
private:
    /**
     * استبدال تعريفات المتغيرات
     */
    std::string استبدل_تعريفات(const std::string& كود, نطاق_ماكرو& نطاق) {
        std::string نتيجة = كود;
        
        // ابحث عن "دع X ="
        std::regex نمط("دع\\s+([أ-ي][أ-ي\\w]*)\\s*=");
        std::smatch match;
        
        std::string::const_iterator بداية = نتيجة.cbegin();
        std::vector<std::pair<size_t, std::pair<std::string, std::string>>> استبدالات;
        
        while (std::regex_search(بداية, نتيجة.cend(), match, نمط)) {
            std::string اسم_المتغير = match[1].str();
            
            // تجاهل المعاملات
            if (!نطاق.معامل(اسم_المتغير)) {
                std::string اسم_جديد = نطاق.عرِّف_محلي(اسم_المتغير);
                size_t موضع = match.position(1) + (بداية - نتيجة.cbegin());
                استبدالات.push_back({موضع, {اسم_المتغير, اسم_جديد}});
            }
            
            بداية = match.suffix().first;
        }
        
        // طبِّق الاستبدالات من الآخر للأول
        for (auto it = استبدالات.rbegin(); it != استبدالات.rend(); ++it) {
            نتيجة.replace(it->first, it->second.first.length(), it->second.second);
        }
        
        return نتيجة;
    }
    
    /**
     * استبدال استخدامات المتغيرات
     */
    std::string استبدل_استخدامات(const std::string& كود, const نطاق_ماكرو& نطاق) {
        std::string نتيجة = كود;
        
        // ابحث عن كل المعرفات (ليست بعد دع)
        // هذا تبسيط - في الواقع نحتاج محلل كامل
        
        std::regex نمط("([أ-ي][أ-ي\\w]*)");
        std::smatch match;
        
        std::vector<std::pair<size_t, std::pair<std::string, std::string>>> استبدالات;
        std::string::const_iterator بداية = نتيجة.cbegin();
        
        while (std::regex_search(بداية, نتيجة.cend(), match, نمط)) {
            std::string الاسم = match[1].str();
            std::string محلول = نطاق.حُل(الاسم);
            
            if (محلول != الاسم) {
                size_t موضع = match.position(1) + (بداية - نتيجة.cbegin());
                استبدالات.push_back({موضع, {الاسم, محلول}});
            }
            
            بداية = match.suffix().first;
        }
        
        // طبِّق الاستبدالات
        for (auto it = استبدالات.rbegin(); it != استبدالات.rend(); ++it) {
            نتيجة.replace(it->first, it->second.first.length(), it->second.second);
        }
        
        return نتيجة;
    }
};

