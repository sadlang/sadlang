/**
 * أحياناً نريد الماكرو أن تُعرِّف متغيرات في نطاق المستدعي!
 * 
 * مثال:
 *     ماكرو! أنشئ_عداد!():
 *         @صدِّر(عداد)
 *         دع عداد = 0
 * 
 *     // الاستخدام
 *     أنشئ_عداد!()
 *     اطبع(عداد)   // ✓ يعمل لأن عداد مُصدَّر
 */
class مصدِّر_نطاق {
public:
    /**
     * تسجيل متغير للتصدير
     */
    void صدِّر(const std::string& الاسم) {
        m_المُصدَّرة.insert(الاسم);
    }
    
    /**
     * هل المتغير مُصدَّر؟
     */
    bool مُصدَّر(const std::string& الاسم) const {
        return m_المُصدَّرة.count(الاسم) > 0;
    }
    
    /**
     * قائمة المتغيرات المُصدَّرة
     */
    const std::unordered_set<std::string>& المُصدَّرة() const {
        return m_المُصدَّرة;
    }
    
private:
    std::unordered_set<std::string> m_المُصدَّرة;
};

