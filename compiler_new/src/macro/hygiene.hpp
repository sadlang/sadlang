/**
 * مولد أسماء فريدة للمتغيرات
 * 
 * مثال:
 *     مولد_أسماء مولد("ضاعف");
 *     مولد.اسم_فريد("نتيجة");  // → "__ماكرو_ضاعف_نتيجة_1"
 *     مولد.اسم_فريد("مؤقت");   // → "__ماكرو_ضاعف_مؤقت_2"
 */
class مولد_أسماء {
public:
    مولد_أسماء(const std::string& اسم_الماكرو) : m_اسم_الماكرو(اسم_الماكرو) {}
    
    /**
     * توليد اسم فريد لمتغير
     */
    std::string اسم_فريد(const std::string& الاسم_الأصلي) {
        int رقم = m_العداد++;
        std::stringstream ss;
        ss << "__ماكرو_" << m_اسم_الماكرو << "_" << الاسم_الأصلي << "_" << رقم;
        
        std::string اسم_جديد = ss.str();
        m_الربط[الاسم_الأصلي] = اسم_جديد;
        m_المتغيرات_المُولَّدة.insert(اسم_جديد);
        
        return اسم_جديد;
    }
    
    /**
     * الحصول على الاسم المُرتبط (إن وُجد)
     */
    std::string الاسم_المُرتبط(const std::string& الاسم_الأصلي) const {
        auto it = m_الربط.find(الاسم_الأصلي);
        return it != m_الربط.end() ? it->second : الاسم_الأصلي;
    }
    
    /**
     * هل الاسم مُولَّد من الماكرو؟
     */
    bool مُولَّد(const std::string& الاسم) const {
        return m_المتغيرات_المُولَّدة.count(الاسم) > 0;
    }
    
private:
    std::string m_اسم_الماكرو;
    int m_العداد = 0;
    std::unordered_map<std::string, std::string> m_الربط;
    std::unordered_set<std::string> m_المتغيرات_المُولَّدة;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              نطاق الماكرو
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * نطاق ماكرو واحد
 * 
 * يتتبع:
 * - المتغيرات المُعرَّفة داخل الماكرو
 * - المعاملات المُمررة للماكرو
 * - المتغيرات من النطاق الخارجي
 */
class نطاق_ماكرو {
public:
    نطاق_ماكرو(const std::string& اسم_الماكرو, نطاق_ماكرو* الأب = nullptr)
        : m_اسم_الماكرو(اسم_الماكرو), m_الأب(الأب), m_المولد(اسم_الماكرو) {}
    
    /**
     * تسجيل معامل ماكرو
     * المعاملات لا تُغيَّر أسماؤها
     */
    void سجِّل_معامل(const std::string& الاسم) {
        m_المعاملات.insert(الاسم);
    }
    
    /**
     * تعريف متغير محلي
     * يحصل على اسم فريد
     */
    std::string عرِّف_محلي(const std::string& الاسم) {
        // إذا كان معامل، لا تُغيِّره
        if (m_المعاملات.count(الاسم) > 0) {
            return الاسم;
        }
        
        std::string اسم_فريد = m_المولد.اسم_فريد(الاسم);
        m_المحليات[الاسم] = اسم_فريد;
        return اسم_فريد;
    }
    
    /**
     * حل اسم متغير
     * يُرجع الاسم المناسب حسب السياق
     */
    std::string حُل(const std::string& الاسم) const {
        // 1. هل هو معامل؟
        if (m_المعاملات.count(الاسم) > 0) {
            return الاسم;  // المعاملات تبقى كما هي
        }
        
        // 2. هل هو متغير محلي؟
        auto it = m_المحليات.find(الاسم);
        if (it != m_المحليات.end()) {
            return it->second;
        }
        
        // 3. ابحث في النطاق الأب
        if (m_الأب != nullptr) {
            return m_الأب->حُل(الاسم);
        }
        
        // 4. متغير خارجي - أبقِه كما هو
        return الاسم;
    }
    
    /**
     * هل الاسم معامل؟
     */
    bool معامل(const std::string& الاسم) const {
        return m_المعاملات.count(الاسم) > 0;
    }
    
    /**
     * هل الاسم متغير محلي؟
     */
    bool محلي(const std::string& الاسم) const {
        return m_المحليات.count(الاسم) > 0;
    }
    
    /**
     * اسم الماكرو
     */
    const std::string& الاسم() const {
        return m_اسم_الماكرو;
    }
    
private:
    std::string m_اسم_الماكرو;
    نطاق_ماكرو* m_الأب;
    مولد_أسماء m_المولد;
    std::unordered_set<std::string> m_المعاملات;
    std::unordered_map<std::string, std::string> m_المحليات;
};

