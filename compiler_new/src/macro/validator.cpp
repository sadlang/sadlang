/**
 * نوع الخطأ
 */
enum class نوع_خطأ_ماكرو {
    نوع_غير_مطابق,        // $س ليس عدداً
    قيمة_غير_مسموحة,      // $مستوى ليس من القيم المحددة
    نطاق_خارج_الحدود,     // $س أكبر من الحد الأقصى
    معامل_ناقص,           // لم تُمرر قيمة للمعامل
    معامل_زائد,           // معاملات أكثر من المتوقع
    آثار_جانبية,          // استدعاء دالة IO في ماكرو @لا_آثار_جانبية
    تقييم_متعدد,          // $س يُقيَّم عدة مرات
    تعريف_مكرر,           // ماكرو بنفس الاسم موجودة
    قاعدة_غير_صالحة,      // قاعدة @... غير معروفة
};

/**
 * خطأ في استخدام الماكرو
 */
struct خطأ_ماكرو {
    نوع_خطأ_ماكرو النوع;
    std::string الماكرو;           // اسم الماكرو
    std::string التفاصيل;
    std::string الملف;
    int السطر = 0;
    int العمود = 0;
    
    // اقتراح الإصلاح
    std::optional<std::string> اقتراح;
    
    /**
     * رسالة الخطأ
     */
    std::string الرسالة() const {
        std::stringstream ss;
        
        ss << "❌ خطأ ماكرو: ";
        
        switch (النوع) {
            case نوع_خطأ_ماكرو::نوع_غير_مطابق:
                ss << "نوع غير متوافق - " << التفاصيل;
                break;
            case نوع_خطأ_ماكرو::قيمة_غير_مسموحة:
                ss << "قيمة غير مسموحة - " << التفاصيل;
                break;
            case نوع_خطأ_ماكرو::نطاق_خارج_الحدود:
                ss << "قيمة خارج النطاق - " << التفاصيل;
                break;
            case نوع_خطأ_ماكرو::معامل_ناقص:
                ss << "معامل مفقود - " << التفاصيل;
                break;
            case نوع_خطأ_ماكرو::آثار_جانبية:
                ss << "آثار جانبية في ماكرو نقية - " << التفاصيل;
                break;
            case نوع_خطأ_ماكرو::تقييم_متعدد:
                ss << "المعامل يُقيَّم عدة مرات - " << التفاصيل;
                break;
            default:
                ss << التفاصيل;
        }
        
        ss << "\n   في " << الملف << ":" << السطر;
        
        if (اقتراح.has_value()) {
            ss << "\n   💡 اقتراح: " << *اقتراح;
        }
        
        return ss.str();
    }
};

