/**
 * مُدقق الماكرو الرئيسي
 */
class مدقق_ماكرو {
public:
    /**
     * تسجيل تعريف ماكرو
     */
    void سجِّل(const تعريف_ماكرو& تعريف) {
        m_الماكروات[تعريف.الاسم] = تعريف;
    }
    
    /**
     * التحقق من استدعاء ماكرو
     */
    std::vector<خطأ_ماكرو> تحقق_استدعاء(
        const std::string& اسم_الماكرو,
        const std::vector<std::string>& المعاملات_الفعلية,
        const std::string& الملف,
        int السطر
    ) {
        std::vector<خطأ_ماكرو> الأخطاء;
        
        // ابحث عن الماكرو
        auto it = m_الماكروات.find(اسم_الماكرو);
        if (it == m_الماكروات.end()) {
            خطأ_ماكرو خطأ;
            خطأ.النوع = نوع_خطأ_ماكرو::تعريف_مكرر;  // استخدام نوع مؤقت
            خطأ.الماكرو = اسم_الماكرو;
            خطأ.التفاصيل = "الماكرو '" + اسم_الماكرو + "' غير معرَّفة";
            خطأ.الملف = الملف;
            خطأ.السطر = السطر;
            الأخطاء.push_back(خطأ);
            return الأخطاء;
        }
        
        const auto& تعريف = it->second;
        
        // تحقق من عدد المعاملات
        int معاملات_مطلوبة = 0;
        for (const auto& م : تعريف.المعاملات) {
            if (!م.اختياري) معاملات_مطلوبة++;
        }
        
        if (static_cast<int>(المعاملات_الفعلية.size()) < معاملات_مطلوبة) {
            خطأ_ماكرو خطأ;
            خطأ.النوع = نوع_خطأ_ماكرو::معامل_ناقص;
            خطأ.الماكرو = اسم_الماكرو;
            خطأ.التفاصيل = "مطلوب " + std::to_string(معاملات_مطلوبة) + 
                          " معاملات، وُجد " + std::to_string(المعاملات_الفعلية.size());
            خطأ.الملف = الملف;
            خطأ.السطر = السطر;
            الأخطاء.push_back(خطأ);
        }
        
        if (المعاملات_الفعلية.size() > تعريف.المعاملات.size()) {
            خطأ_ماكرو خطأ;
            خطأ.النوع = نوع_خطأ_ماكرو::معامل_زائد;
            خطأ.الماكرو = اسم_الماكرو;
            خطأ.التفاصيل = "معاملات زائدة";
            خطأ.الملف = الملف;
            خطأ.السطر = السطر;
            الأخطاء.push_back(خطأ);
        }
        
        // تحقق من القواعد
        for (const auto& قاعدة : تعريف.القواعد) {
            auto أخطاء_قاعدة = تحقق_قاعدة(تعريف, قاعدة, المعاملات_الفعلية, الملف, السطر);
            الأخطاء.insert(الأخطاء.end(), أخطاء_قاعدة.begin(), أخطاء_قاعدة.end());
        }
        
        return الأخطاء;
    }
    
    /**
     * التحقق من تعريف ماكرو جديد
     */
    std::vector<خطأ_ماكرو> تحقق_تعريف(const تعريف_ماكرو& تعريف) {
        std::vector<خطأ_ماكرو> الأخطاء;
        
        // تحقق من التكرار
        if (m_الماكروات.count(تعريف.الاسم) > 0) {
            خطأ_ماكرو خطأ;
            خطأ.النوع = نوع_خطأ_ماكرو::تعريف_مكرر;
            خطأ.الماكرو = تعريف.الاسم;
            خطأ.التفاصيل = "ماكرو بنفس الاسم موجودة مسبقاً";
            خطأ.الملف = تعريف.الملف;
            خطأ.السطر = تعريف.السطر;
            الأخطاء.push_back(خطأ);
        }
        
        // تحقق من صحة القواعد
        for (const auto& قاعدة : تعريف.القواعد) {
            // تحقق أن المعامل موجود
            bool موجود = false;
            for (const auto& م : تعريف.المعاملات) {
                if (م.الاسم == قاعدة.المعامل) {
                    موجود = true;
                    break;
                }
            }
            
            if (!قاعدة.المعامل.empty() && !موجود) {
                خطأ_ماكرو خطأ;
                خطأ.النوع = نوع_خطأ_ماكرو::قاعدة_غير_صالحة;
                خطأ.الماكرو = تعريف.الاسم;
                خطأ.التفاصيل = "القاعدة تشير لمعامل غير موجود: $" + قاعدة.المعامل;
                خطأ.الملف = تعريف.الملف;
                خطأ.السطر = تعريف.السطر;
                الأخطاء.push_back(خطأ);
            }
        }
        
        // تحقق من التقييم المتعدد
        auto تعدد = ابحث_عن_تقييم_متعدد(تعريف);
        for (const auto& معامل : تعدد) {
            // تحقق إذا لم يكن هناك @تقييم_مرة
            bool محمي = false;
            for (const auto& قاعدة : تعريف.القواعد) {
                if (قاعدة.النوع == نوع_قاعدة::تقييم_مرة && قاعدة.المعامل == معامل) {
                    محمي = true;
                    break;
                }
            }
            
            if (!محمي) {
                خطأ_ماكرو خطأ;
                خطأ.النوع = نوع_خطأ_ماكرو::تقييم_متعدد;
                خطأ.الماكرو = تعريف.الاسم;
                خطأ.التفاصيل = "المعامل $" + معامل + " يُستخدم عدة مرات";
                خطأ.الملف = تعريف.الملف;
                خطأ.السطر = تعريف.السطر;
                خطأ.اقتراح = "أضف @تقييم_مرة($" + معامل + ") أو استخدم متغير مؤقت";
                الأخطاء.push_back(خطأ);
            }
        }
        
        return الأخطاء;
    }
    
    /**
     * قائمة الماكروات المسجلة
     */
    std::vector<std::string> الماكروات_المسجلة() const {
        std::vector<std::string> قائمة;
        for (const auto& [اسم, _] : m_الماكروات) {
            قائمة.push_back(اسم);
        }
        return قائمة;
    }
    
private:
    std::unordered_map<std::string, تعريف_ماكرو> m_الماكروات;
    
    /**
     * التحقق من قاعدة واحدة
     */
    std::vector<خطأ_ماكرو> تحقق_قاعدة(
        const تعريف_ماكرو& تعريف,
        const قاعدة_تحقق& قاعدة,
        const std::vector<std::string>& المعاملات,
        const std::string& الملف,
        int السطر
    ) {
        std::vector<خطأ_ماكرو> أخطاء;
        
        // ابحث عن موضع المعامل
        int موضع = -1;
        for (size_t i = 0; i < تعريف.المعاملات.size(); i++) {
            if (تعريف.المعاملات[i].الاسم == قاعدة.المعامل) {
                موضع = static_cast<int>(i);
                break;
            }
        }
        
        if (موضع < 0 || موضع >= static_cast<int>(المعاملات.size())) {
            return أخطاء;  // معامل غير موجود - خطأ آخر سيُكتشف
        }
        
        const std::string& قيمة = المعاملات[موضع];
        
        switch (قاعدة.النوع) {
            case نوع_قاعدة::قيم_محددة: {
                bool موجود = false;
                for (const auto& ق : قاعدة.القيم) {
                    if (قيمة == ق || قيمة == "\"" + ق + "\"") {
                        موجود = true;
                        break;
                    }
                }
                
                if (!موجود) {
                    خطأ_ماكرو خطأ;
                    خطأ.النوع = نوع_خطأ_ماكرو::قيمة_غير_مسموحة;
                    خطأ.الماكرو = تعريف.الاسم;
                    
                    std::stringstream ss;
                    ss << "القيمة '" << قيمة << "' غير مسموحة للمعامل $" << قاعدة.المعامل;
                    ss << ". القيم المسموحة: [";
                    for (size_t i = 0; i < قاعدة.القيم.size(); i++) {
                        if (i > 0) ss << ", ";
                        ss << "\"" << قاعدة.القيم[i] << "\"";
                    }
                    ss << "]";
                    
                    خطأ.التفاصيل = ss.str();
                    خطأ.الملف = الملف;
                    خطأ.السطر = السطر;
                    أخطاء.push_back(خطأ);
                }
                break;
            }
            
            default:
                break;
        }
        
        return أخطاء;
    }
    
    /**
     * البحث عن معاملات تُقيَّم عدة مرات
     */
    std::vector<std::string> ابحث_عن_تقييم_متعدد(const تعريف_ماكرو& تعريف) {
        std::vector<std::string> نتيجة;
        
        for (const auto& معامل : تعريف.المعاملات) {
            std::string بحث = "$" + معامل.الاسم;
            
            // احسب عدد الظهورات في الجسم
            int عدد = 0;
            size_t pos = 0;
            while ((pos = تعريف.الجسم.find(بحث, pos)) != std::string::npos) {
                عدد++;
                pos += بحث.length();
            }
            
            if (عدد > 1) {
                نتيجة.push_back(معامل.الاسم);
            }
        }
        
        return نتيجة;
    }
};

