/**
 * تعريف ماكرو كامل
 */
struct تعريف_ماكرو {
    std::string الاسم;
    std::vector<معامل_ماكرو> المعاملات;
    std::vector<قاعدة_تحقق> القواعد;
    std::string الجسم;             // القالب
    
    // معلومات المصدر
    std::string الملف;
    int السطر = 0;
    
    // خصائص
    bool عامة = false;             // قابلة للتصدير
    bool موروثة = false;           // من مكتبة أخرى
    
    /**
     * هل الماكرو آمنة؟
     */
    bool آمنة() const {
        for (const auto& قاعدة : القواعد) {
            if (قاعدة.النوع == نوع_قاعدة::لا_آثار_جانبية) {
                return true;
            }
        }
        return false;
    }
};

