/**
 * نوع معامل الماكرو
 */
enum class نوع_معامل_ماكرو {
    تعبير,       // $س - أي تعبير
    معرف,        // $اسم - معرف فقط (اسم متغير)
    نوع,         // $ن - نوع بيانات
    كتلة,        // $كود - كتلة كود
    قائمة,       // $..عناصر - صفر أو أكثر
    حرفي,        // "نص" أو 42
};

/**
 * معامل ماكرو واحد
 */
struct معامل_ماكرو {
    std::string الاسم;           // مثل "س" في $س
    نوع_معامل_ماكرو النوع;
    std::string نوع_مُقيَّد;     // إذا @تحقق(نوع: عدد)
    bool اختياري = false;
    std::string قيمة_افتراضية;
};

