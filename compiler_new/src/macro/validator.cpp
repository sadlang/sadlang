/**
 * نوع القاعدة
 */
enum class نوع_قاعدة {
    تحقق_نوع,           // @تحقق(نوع: $س عدد)
    لا_آثار_جانبية,     // @لا_آثار_جانبية
    تقييم_مرة,          // @تقييم_مرة($س)
    نطاق_مقيد,          // @نطاق($س، 0..100)
    قيم_محددة,          // @قيم($مستوى في ["معلومة", "تحذير", "خطأ"])
    ليس_فارغ,           // @ليس_فارغ($قائمة)
    طول_أقصى,           // @طول_أقصى($نص، 255)
    مخصص,               // @مخصص(...)
};

/**
 * قاعدة تحقق واحدة
 */
struct قاعدة_تحقق {
    نوع_قاعدة النوع;
    std::string المعامل;          // اسم المعامل المُراد التحقق منه
    std::vector<std::string> القيم; // القيم المسموحة أو الحدود
    std::string رسالة_خطأ;         // رسالة مخصصة عند الفشل
    
    /**
     * تحويل القاعدة لنص مقروء
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        
        switch (النوع) {
            case نوع_قاعدة::تحقق_نوع:
                ss << "@تحقق(نوع: $" << المعامل << " " << القيم[0] << ")";
                break;
            case نوع_قاعدة::لا_آثار_جانبية:
                ss << "@لا_آثار_جانبية";
                break;
            case نوع_قاعدة::تقييم_مرة:
                ss << "@تقييم_مرة($" << المعامل << ")";
                break;
            case نوع_قاعدة::نطاق_مقيد:
                ss << "@نطاق($" << المعامل << "، " << القيم[0] << ".." << القيم[1] << ")";
                break;
            case نوع_قاعدة::قيم_محددة:
                ss << "@قيم($" << المعامل << " في [";
                for (size_t i = 0; i < القيم.size(); i++) {
                    if (i > 0) ss << ", ";
                    ss << "\"" << القيم[i] << "\"";
                }
                ss << "])";
                break;
            default:
                ss << "@قاعدة_مخصصة";
        }
        
        return ss.str();
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
