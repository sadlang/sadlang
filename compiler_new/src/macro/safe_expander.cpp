/**
 * نوع التوسيع
 */
enum class نوع_توسيع {
    مباشر,        // استبدال بسيط
    مع_تقييم,     // تقييم المعاملات أولاً
    آمن,          // مع كل الحمايات
    تكراري,       // يحتوي ماكرو أخرى
};

/**
 * نتيجة التوسيع
 */
struct نتيجة_توسيع {
    bool نجح = true;
    std::string الكود;                    // الكود الموسَّع
    std::vector<std::string> التحذيرات;
    std::string الخطأ;
    
    // معلومات إضافية
    int عدد_الاستبدالات = 0;
    bool يحتاج_توسيع_إضافي = false;       // هل يحتوي ماكرو أخرى
    
    /**
     * إنشاء نتيجة ناجحة
     */
    static نتيجة_توسيع ناجحة(const std::string& كود, int استبدالات = 0) {
        نتيجة_توسيع ن;
        ن.نجح = true;
        ن.الكود = كود;
        ن.عدد_الاستبدالات = استبدالات;
        return ن;
    }
    
    /**
     * إنشاء نتيجة فاشلة
     */
    static نتيجة_توسيع فاشلة(const std::string& خطأ) {
        نتيجة_توسيع ن;
        ن.نجح = false;
        ن.الخطأ = خطأ;
        return ن;
    }
};

