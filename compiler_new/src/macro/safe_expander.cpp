/**
 * موسع يدعم الماكرو المتداخلة
 * 
 * مثال:
 *     ماكرو! أ!($س): ب!($س, $س)
 *     ماكرو! ب!($س, $ص): $س + $ص
 *     
 *     أ!(5)
 *     → ب!(5, 5)    ← توسيع أول
 *     → 5 + 5       ← توسيع ثاني
 */
class موسع_تكراري {
public:
    using مزوِّد_ماكرو = std::function<std::optional<std::pair<std::string, std::vector<std::string>>>(const std::string&)>;
    
    /**
     * ضبط مزوِّد تعريفات الماكرو
     */
    void اضبط_مزوِّد(مزوِّد_ماكرو مزوِّد) {
        m_مزوِّد = مزوِّد;
    }
    
    /**
     * توسيع كامل حتى لا يبقى ماكرو
     */
    نتيجة_توسيع وسِّع_كامل(const std::string& كود, int حد_التكرار = 100) {
        std::string حالي = كود;
        موسع_آمن موسع;
        
        for (int i = 0; i < حد_التكرار; i++) {
            if (!موسع.يحتاج_توسيع_إضافي(حالي)) {
                return نتيجة_توسيع::ناجحة(حالي);
            }
            
            // ابحث عن أول ماكرو ووسِّعها
            auto استدعاء = ابحث_عن_استدعاء(حالي);
            if (!استدعاء.has_value()) {
                break;
            }
            
            auto [الاسم, المعاملات, البداية, النهاية] = *استدعاء;
            
            // احصل على تعريف الماكرو
            if (!m_مزوِّد) {
                return نتيجة_توسيع::فاشلة("لا يوجد مزوِّد ماكرو");
            }
            
            auto تعريف = m_مزوِّد(الاسم);
            if (!تعريف.has_value()) {
                return نتيجة_توسيع::فاشلة("ماكرو غير معرَّفة: " + الاسم);
            }
            
            auto [الجسم, أسماء_المعاملات] = *تعريف;
            
            // أنشئ خريطة المعاملات
            std::unordered_map<std::string, std::string> خريطة;
            for (size_t j = 0; j < أسماء_المعاملات.size() && j < المعاملات.size(); j++) {
                خريطة[أسماء_المعاملات[j]] = المعاملات[j];
            }
            
            // وسِّع
            auto نتيجة = موسع.وسِّع(الاسم, الجسم, خريطة);
            if (!نتيجة.نجح) {
                return نتيجة;
            }
            
            // استبدل في الكود
            حالي = حالي.substr(0, البداية) + نتيجة.الكود + حالي.substr(النهاية);
        }
        
        return نتيجة_توسيع::فاشلة("تجاوز حد التكرار - ربما تكرار لانهائي");
    }
    
private:
    مزوِّد_ماكرو m_مزوِّد;
    
    /**
     * البحث عن أول استدعاء ماكرو
     * يُرجع: (الاسم، المعاملات، موضع_البداية، موضع_النهاية)
     */
    std::optional<std::tuple<std::string, std::vector<std::string>, size_t, size_t>>
    ابحث_عن_استدعاء(const std::string& كود) {
        size_t موضع = كود.find("!(");
        if (موضع == std::string::npos) return std::nullopt;
        
        // ابحث عن بداية الاسم
        size_t بداية_اسم = موضع;
        while (بداية_اسم > 0 && (isalnum(كود[بداية_اسم - 1]) || كود[بداية_اسم - 1] > 127)) {
            بداية_اسم--;
        }
        
        std::string الاسم = كود.substr(بداية_اسم, موضع - بداية_اسم);
        
        // ابحث عن القوس المغلق
        size_t قوس_فتح = موضع + 1;
        int عمق = 1;
        size_t i = قوس_فتح + 1;
        
        while (i < كود.length() && عمق > 0) {
            if (كود[i] == '(') عمق++;
            else if (كود[i] == ')') عمق--;
            i++;
        }
        
        if (عمق != 0) return std::nullopt;
        
        // استخرج المعاملات
        std::string محتوى_أقواس = كود.substr(قوس_فتح + 1, i - قوس_فتح - 2);
        std::vector<std::string> المعاملات = قسِّم_معاملات(محتوى_أقواس);
        
        return std::make_tuple(الاسم, المعاملات, بداية_اسم, i);
    }
    
    /**
     * تقسيم سلسلة المعاملات
     */
    std::vector<std::string> قسِّم_معاملات(const std::string& نص) {
        std::vector<std::string> نتيجة;
        std::string حالي;
        int عمق = 0;
        
        for (char c : نص) {
            if (c == '(' || c == '[' || c == '{') {
                عمق++;
                حالي += c;
            } else if (c == ')' || c == ']' || c == '}') {
                عمق--;
                حالي += c;
            } else if (c == ',' && عمق == 0) {
                // قص المسافات
                size_t بداية = حالي.find_first_not_of(" \t\n");
                size_t نهاية = حالي.find_last_not_of(" \t\n");
                if (بداية != std::string::npos) {
                    نتيجة.push_back(حالي.substr(بداية, نهاية - بداية + 1));
                }
                حالي.clear();
            } else {
                حالي += c;
            }
        }
        
        // آخر معامل
        size_t بداية = حالي.find_first_not_of(" \t\n");
        size_t نهاية = حالي.find_last_not_of(" \t\n");
        if (بداية != std::string::npos) {
            نتيجة.push_back(حالي.substr(بداية, نهاية - بداية + 1));
        }
        
        return نتيجة;
    }
};

