/**
 * معلومات معامل واحد
 */
struct معلومات_معامل {
    std::string الاسم;             // اسم المعامل في التعريف
    std::string القيمة;           // القيمة المُمررة
    bool بسيط = true;             // هل هو قيمة بسيطة (عدد، متغير)
    bool له_آثار_جانبية = false;  // هل قد يُغيِّر شيئاً (++، --)
    int عدد_الاستخدامات = 0;      // كم مرة يُستخدم في الجسم
};

/**
 * محلل المعاملات
 */
class محلل_معاملات {
public:
    /**
     * تحليل معامل واحد
     */
    معلومات_معامل حلِّل(const std::string& الاسم, const std::string& القيمة) {
        معلومات_معامل م;
        م.الاسم = الاسم;
        م.القيمة = القيمة;
        
        // تحقق إذا كانت قيمة بسيطة
        م.بسيط = هل_بسيط(القيمة);
        
        // تحقق من الآثار الجانبية
        م.له_آثار_جانبية = هل_له_آثار_جانبية(القيمة);
        
        return م;
    }
    
private:
    /**
     * هل القيمة بسيطة؟
     */
    bool هل_بسيط(const std::string& قيمة) {
        // عدد صحيح
        if (كل_أرقام(قيمة)) return true;
        
        // عدد عشري
        bool نقطة = false;
        bool كل_رقمي = true;
        for (char c : قيمة) {
            if (c == '.' && !نقطة) { نقطة = true; continue; }
            if (!isdigit(c)) { كل_رقمي = false; break; }
        }
        if (كل_رقمي && نقطة) return true;
        
        // نص حرفي
        if (قيمة.length() >= 2 && قيمة[0] == '"' && قيمة.back() == '"') {
            return true;
        }
        
        // معرف بسيط (اسم متغير)
        if (هل_معرف(قيمة)) return true;
        
        return false;
    }
    
    /**
     * هل القيمة لها آثار جانبية؟
     */
    bool هل_له_آثار_جانبية(const std::string& قيمة) {
        // ++ أو --
        if (قيمة.find("++") != std::string::npos) return true;
        if (قيمة.find("--") != std::string::npos) return true;
        
        // استدعاء دالة (قد يكون له آثار)
        if (قيمة.find('(') != std::string::npos) return true;
        
        // إسناد
        if (قيمة.find('=') != std::string::npos && 
            قيمة.find("==") == std::string::npos &&
            قيمة.find("!=") == std::string::npos) {
            return true;
        }
        
        return false;
    }
    
    bool كل_أرقام(const std::string& نص) {
        for (char c : نص) {
            if (!isdigit(c)) return false;
        }
        return !نص.empty();
    }
    
    bool هل_معرف(const std::string& نص) {
        if (نص.empty()) return false;
        // تبسيط: أول حرف غير رقم، الباقي حروف أو أرقام
        return !isdigit(نص[0]);
    }
};

