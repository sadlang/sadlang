/**
 * نوع الإصلاح المقترح
 */
enum class نوع_إصلاح {
    تقسيم_نطاقات,      // قسِّم النطاقات المتداخلة
    إعادة_ترتيب,       // رتِّب الأنماط بترتيب مختلف
    إزالة_مكرر,        // أزل النمط المكرر
    إضافة_حارس,        // أضف شرط للتمييز
    تحويل_لبديل,       // حوِّل لنمط | بديل
    نقل_للأعلى,        // انقل النمط للأعلى
    حذف,              // احذف النمط (لا يمكن الوصول إليه)
};

// ═══════════════════════════════════════════════════════════════════════════════
