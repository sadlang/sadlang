/**
 * نطاق رقمي بسيط
 */
struct نطاق_رقمي {
    int64_t من;
    int64_t إلى;
    std::string الاسم;
    int السطر = 0;
    
    bool يتداخل_مع(const نطاق_رقمي& آخر) const {
        return من <= آخر.إلى && آخر.من <= إلى;
    }
};

