/**
 * مولد اقتراحات الإصلاح
 */
class مولد_اقتراحات_إصلاح {
public:
    /**
     * توليد اقتراحات لتداخل نطاقات
     */
    std::vector<اقتراح_إصلاح> اقترح_لتداخل(
        const نطاق_رقمي& الأول,
        const نطاق_رقمي& الثاني
    ) {
        std::vector<اقتراح_إصلاح> اقتراحات;
        
        // 1. تقسيم النطاقات
        اقتراحات.push_back(اقتراح_تقسيم(الأول, الثاني));
        
        // 2. إعادة ترتيب (إذا كان أحدهما محتوى)
        if (الأول.من <= الثاني.من && الأول.إلى >= الثاني.إلى) {
            اقتراحات.push_back(اقتراح_نقل_للأعلى(الثاني, الأول));
        } else if (الثاني.من <= الأول.من && الثاني.إلى >= الأول.إلى) {
            اقتراحات.push_back(اقتراح_نقل_للأعلى(الأول, الثاني));
        }
        
        // 3. إضافة حارس
        اقتراحات.push_back(اقتراح_حارس(الأول, الثاني));
        
        // ترتيب حسب الأولوية
        std::sort(اقتراحات.begin(), اقتراحات.end(),
            [](const اقتراح_إصلاح& أ, const اقتراح_إصلاح& ب) {
                return أ.الأولوية > ب.الأولوية;
            });
        
        return اقتراحات;
    }
    
    /**
     * توليد اقتراح لنمط مكرر
     */
    اقتراح_إصلاح اقترح_لتكرار(int سطر_أول, int سطر_ثاني) {
        اقتراح_إصلاح اقتراح;
        
        اقتراح.النوع = نوع_إصلاح::إزالة_مكرر;
        اقتراح.العنوان = "إزالة النمط المكرر";
        اقتراح.الشرح = "النمط موجود مرتين. أزل أحدهما.";
        اقتراح.الأولوية = 100;
        اقتراح.آمن = true;
        
        تغيير_كود تغيير;
        تغيير.السطر = سطر_ثاني;
        تغيير.النص_القديم = "(السطر بالكامل)";
        تغيير.النص_الجديد = "(حذف)";
        اقتراح.التغييرات.push_back(تغيير);
        
        return اقتراح;
    }
    
    /**
     * توليد اقتراح لنمط غير قابل للوصول
     */
    اقتراح_إصلاح اقترح_لغير_قابل_للوصول(
        const std::string& النمط,
        int السطر,
        int سطر_المُهمل
    ) {
        اقتراح_إصلاح اقتراح;
        
        اقتراح.النوع = نوع_إصلاح::نقل_للأعلى;
        اقتراح.العنوان = "نقل النمط قبل '_'";
        اقتراح.الشرح = "النمط '" + النمط + "' لن يُصل إليه لأن '_' يطابق كل شيء";
        اقتراح.الأولوية = 100;
        اقتراح.آمن = true;
        
        تغيير_كود تغيير1;
        تغيير1.السطر = السطر;
        تغيير1.النص_القديم = "(السطر بالكامل)";
        تغيير1.النص_الجديد = "(نقل إلى قبل سطر " + std::to_string(سطر_المُهمل) + ")";
        اقتراح.التغييرات.push_back(تغيير1);
        
        return اقتراح;
    }
    
private:
    /**
     * اقتراح تقسيم النطاقات
     */
    اقتراح_إصلاح اقتراح_تقسيم(const نطاق_رقمي& أ, const نطاق_رقمي& ب) {
        اقتراح_إصلاح اقتراح;
        
        اقتراح.النوع = نوع_إصلاح::تقسيم_نطاقات;
        اقتراح.العنوان = "تقسيم النطاقات المتداخلة";
        اقتراح.الأولوية = 90;
        اقتراح.آمن = false;  // قد يغير السلوك
        
        // حساب النطاقات الجديدة
        int64_t نقطة_الفصل = std::min(أ.إلى, ب.من);
        
        std::stringstream شرح;
        شرح << "قسِّم النطاقات عند " << نقطة_الفصل << ":\n";
        شرح << "  " << أ.الاسم << ": " << أ.من << ".." << (نقطة_الفصل - 1) << "\n";
        شرح << "  " << ب.الاسم << ": " << نقطة_الفصل << ".." << std::max(أ.إلى, ب.إلى);
        
        اقتراح.الشرح = شرح.str();
        
        // التغييرات
        تغيير_كود تغيير1;
        تغيير1.السطر = أ.السطر;
        تغيير1.النص_القديم = "حالة " + std::to_string(أ.من) + ".." + std::to_string(أ.إلى);
        تغيير1.النص_الجديد = "حالة " + std::to_string(أ.من) + ".." + std::to_string(نقطة_الفصل - 1);
        اقتراح.التغييرات.push_back(تغيير1);
        
        تغيير_كود تغيير2;
        تغيير2.السطر = ب.السطر;
        تغيير2.النص_القديم = "حالة " + std::to_string(ب.من) + ".." + std::to_string(ب.إلى);
        تغيير2.النص_الجديد = "حالة " + std::to_string(نقطة_الفصل) + ".." + std::to_string(std::max(أ.إلى, ب.إلى));
        اقتراح.التغييرات.push_back(تغيير2);
        
        return اقتراح;
    }
    
    /**
     * اقتراح نقل للأعلى
     */
    اقتراح_إصلاح اقتراح_نقل_للأعلى(const نطاق_رقمي& صغير, const نطاق_رقمي& كبير) {
        اقتراح_إصلاح اقتراح;
        
        اقتراح.النوع = نوع_إصلاح::نقل_للأعلى;
        اقتراح.العنوان = "نقل النمط الأخص للأعلى";
        اقتراح.الشرح = "انقل '" + صغير.الاسم + "' قبل '" + كبير.الاسم + "' ليُفحص أولاً";
        اقتراح.الأولوية = 80;
        اقتراح.آمن = true;
        
        تغيير_كود تغيير;
        تغيير.السطر = صغير.السطر;
        تغيير.النص_القديم = "(السطر بالكامل)";
        تغيير.النص_الجديد = "(نقل إلى قبل سطر " + std::to_string(كبير.السطر) + ")";
        اقتراح.التغييرات.push_back(تغيير);
        
        return اقتراح;
    }
    
    /**
     * اقتراح إضافة حارس
     */
    اقتراح_إصلاح اقتراح_حارس(const نطاق_رقمي& أ, const نطاق_رقمي& ب) {
        اقتراح_إصلاح اقتراح;
        
        اقتراح.النوع = نوع_إصلاح::إضافة_حارس;
        اقتراح.العنوان = "إضافة شرط تمييز";
        اقتراح.الأولوية = 50;
        اقتراح.آمن = false;
        
        std::stringstream شرح;
        شرح << "أضف شرطاً للتمييز بين الحالتين:\n";
        شرح << "  حالة " << أ.من << ".." << أ.إلى << " إذا شرط_خاص:\n";
        شرح << "  حالة " << ب.من << ".." << ب.إلى << ":";
        
        اقتراح.الشرح = شرح.str();
        
        تغيير_كود تغيير;
        تغيير.السطر = أ.السطر;
        تغيير.النص_القديم = "حالة " + std::to_string(أ.من) + ".." + std::to_string(أ.إلى) + ":";
        تغيير.النص_الجديد = "حالة " + std::to_string(أ.من) + ".." + std::to_string(أ.إلى) + " إذا شرط_خاص:";
        اقتراح.التغييرات.push_back(تغيير);
        
        return اقتراح;
    }
};

