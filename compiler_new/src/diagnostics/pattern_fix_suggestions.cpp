/**
 * مُطبِّق الإصلاحات على الكود
 */
class مطبق_إصلاحات {
public:
    /**
     * تطبيق اقتراح على كود مصدري
     */
    std::string طبِّق(const std::string& الكود, const اقتراح_إصلاح& اقتراح) {
        std::vector<std::string> الأسطر;
        std::stringstream ss(الكود);
        std::string سطر;
        
        while (std::getline(ss, سطر)) {
            الأسطر.push_back(سطر);
        }
        
        // طبِّق التغييرات من الأسفل للأعلى (لتجنب تغيير أرقام الأسطر)
        std::vector<تغيير_كود> تغييرات_مرتبة = اقتراح.التغييرات;
        std::sort(تغييرات_مرتبة.begin(), تغييرات_مرتبة.end(),
            [](const تغيير_كود& أ, const تغيير_كود& ب) {
                return أ.السطر > ب.السطر;
            });
        
        for (const auto& تغيير : تغييرات_مرتبة) {
            int i = تغيير.السطر - 1;  // تحويل لـ 0-based
            
            if (i >= 0 && i < static_cast<int>(الأسطر.size())) {
                if (تغيير.النص_الجديد == "(حذف)") {
                    الأسطر.erase(الأسطر.begin() + i);
                } else if (تغيير.النص_الجديد.find("(نقل إلى") == 0) {
                    // نقل السطر - تحتاج معالجة خاصة
                } else {
                    // استبدال بسيط
                    size_t pos = الأسطر[i].find(تغيير.النص_القديم);
                    if (pos != std::string::npos) {
                        الأسطر[i].replace(pos, تغيير.النص_القديم.length(), 
                                         تغيير.النص_الجديد);
                    }
                }
            }
        }
        
        // إعادة بناء الكود
        std::stringstream نتيجة;
        for (size_t i = 0; i < الأسطر.size(); i++) {
            نتيجة << الأسطر[i];
            if (i < الأسطر.size() - 1) {
                نتيجة << "\n";
            }
        }
        
        return نتيجة.str();
    }
};

