/**
 * تغيير واحد في الكود
 */
struct تغيير_كود {
    int السطر;
    int العمود_بداية;
    int العمود_نهاية;
    std::string النص_القديم;
    std::string النص_الجديد;
    
    /**
     * تحويل لنص مقروء
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "سطر " << السطر << ": ";
        ss << "\"" << النص_القديم << "\" → \"" << النص_الجديد << "\"";
        return ss.str();
    }
};

/**
 * اقتراح إصلاح كامل
 */
struct اقتراح_إصلاح {
    نوع_إصلاح النوع;
    std::string العنوان;
    std::string الشرح;
    std::vector<تغيير_كود> التغييرات;
    int الأولوية = 0;  // الأعلى = الأفضل
    
    /**
     * هل الإصلاح آمن (لا يغير السلوك)؟
     */
    bool آمن = true;
    
    /**
     * تحويل لنص مقروء
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        
        ss << "╔═══════════════════════════════════════╗\n";
        ss << "║ 💡 " << العنوان << "\n";
        ss << "╠═══════════════════════════════════════╣\n";
        ss << "║ " << الشرح << "\n";
        ss << "╠═══════════════════════════════════════╣\n";
        ss << "║ التغييرات:\n";
        
        for (const auto& تغيير : التغييرات) {
            ss << "║   • " << تغيير.إلى_نص() << "\n";
        }
        
        if (!آمن) {
            ss << "╠═══════════════════════════════════════╣\n";
            ss << "║ ⚠️ تحذير: هذا الإصلاح قد يغير السلوك\n";
        }
        
        ss << "╚═══════════════════════════════════════╝\n";
        
        return ss.str();
    }
};

