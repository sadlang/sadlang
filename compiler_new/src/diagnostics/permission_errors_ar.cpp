    /**
     * تهريب نص JSON
     */
    std::string escape_json(const std::string& نص) {
        std::string نتيجة;
        for (char c : نص) {
            switch (c) {
                case '"': نتيجة += "\\\""; break;
                case '\\': نتيجة += "\\\\"; break;
                case '\n': نتيجة += "\\n"; break;
                case '\r': نتيجة += "\\r"; break;
                case '\t': نتيجة += "\\t"; break;
                default: نتيجة += c;
            }
        }
        return نتيجة;
    }
