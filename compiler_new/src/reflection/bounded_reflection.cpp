/**
 * سجل كل الأنواع المُعرَّفة
 */
class سجل_أنواع {
public:
    /**
     * المثال الوحيد
     */
    static سجل_أنواع& المثال() {
        static سجل_أنواع مثال;
        return مثال;
    }
    
    /**
     * تسجيل نوع
     */
    void سجِّل(const معلومات_نوع& نوع) {
        m_الأنواع[نوع.الاسم_الكامل] = نوع;
        m_الأنواع_بالاسم_القصير[نوع.الاسم] = نوع.الاسم_الكامل;
    }
    
    /**
     * البحث عن نوع
     */
    std::optional<معلومات_نوع> ابحث(const std::string& اسم) const {
        // حاول الاسم الكامل أولاً
        auto it = m_الأنواع.find(اسم);
        if (it != m_الأنواع.end()) {
            return it->second;
        }
        
        // حاول الاسم القصير
        auto it2 = m_الأنواع_بالاسم_القصير.find(اسم);
        if (it2 != m_الأنواع_بالاسم_القصير.end()) {
            it = m_الأنواع.find(it2->second);
            if (it != m_الأنواع.end()) {
                return it->second;
            }
        }
        
        return std::nullopt;
    }
    
    /**
     * كل الأنواع المُسجَّلة
     */
    std::vector<std::string> كل_الأنواع() const {
        std::vector<std::string> قائمة;
        for (const auto& [اسم, _] : m_الأنواع) {
            قائمة.push_back(اسم);
        }
        return قائمة;
    }
    
private:
    سجل_أنواع() = default;
    
    std::unordered_map<std::string, معلومات_نوع> m_الأنواع;
    std::unordered_map<std::string, std::string> m_الأنواع_بالاسم_القصير;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              دالة نوع_من
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * الحصول على معلومات نوع كائن
 * 
 * مثال:
 *     دع ش = شخص("أحمد", 25)
 *     دع نوع = نوع_من(ش)
 *     اطبع(نوع.الاسم)  // → "شخص"
 */
template<typename T>
معلومات_نوع نوع_من() {
    auto نتيجة = سجل_أنواع::المثال().ابحث(typeid(T).name());
    if (نتيجة.has_value()) {
        return *نتيجة;
    }
    
    // نوع غير مُسجَّل - أنشئ معلومات أساسية
    معلومات_نوع أساسي;
    أساسي.الاسم = typeid(T).name();
    أساسي.الاسم_الكامل = أساسي.الاسم;
    أساسي.الحجم = sizeof(T);
    أساسي.المحاذاة = alignof(T);
    
    return أساسي;
}

