/**
 * مستوى رؤية الانعكاس
 */
enum class رؤية_انعكاس {
    مرئي,       // يُكشف للجميع
    مخفي,       // لا يُكشف أبداً
    مقيد,       // يُكشف لأدوار معينة
    افتراضي,    // حسب مستوى الوصول (عام = مرئي، خاص = مخفي)
};

/**
 * إعدادات الانعكاس لنوع
 */
struct إعدادات_انعكاس {
    رؤية_انعكاس حقول_عامة = رؤية_انعكاس::مرئي;
    رؤية_انعكاس حقول_خاصة = رؤية_انعكاس::مخفي;
    رؤية_انعكاس دوال_عامة = رؤية_انعكاس::مرئي;
    رؤية_انعكاس دوال_خاصة = رؤية_انعكاس::مخفي;
    
    std::vector<std::string> الأدوار_المسموحة;  // للمقيد
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              معلومات الحقل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات حقل واحد
 */
struct معلومات_حقل {
    std::string الاسم;
    std::string اسم_النوع;
    bool عام = true;
    رؤية_انعكاس الرؤية = رؤية_انعكاس::افتراضي;
    
    // الإزاحة في الذاكرة (للوصول)
    size_t الإزاحة = 0;
    size_t الحجم = 0;
    
    // دوال القراءة والكتابة
    std::function<std::any(const void*)> اقرأ;
    std::function<void(void*, const std::any&)> اكتب;
    
    /**
     * هل مرئي للسياق المُعطى؟
     */
    bool مرئي_لـ(const std::vector<std::string>& أدوار_المستخدم) const {
        switch (الرؤية) {
            case رؤية_انعكاس::مرئي:
                return true;
            case رؤية_انعكاس::مخفي:
                return false;
            case رؤية_انعكاس::مقيد:
                // تحقق من الأدوار
                for (const auto& دور : أدوار_المستخدم) {
                    for (const auto& مسموح : m_الأدوار_المسموحة) {
                        if (دور == مسموح) return true;
                    }
                }
                return false;
            case رؤية_انعكاس::افتراضي:
                return عام;
        }
        return false;
    }
    
    void أضف_دور(const std::string& دور) {
        m_الأدوار_المسموحة.push_back(دور);
    }
    
private:
    std::vector<std::string> m_الأدوار_المسموحة;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              معلومات الدالة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات دالة واحدة
 */
struct معلومات_دالة_انعكاس {
    std::string الاسم;
    std::string نوع_الإرجاع;
    std::vector<std::pair<std::string, std::string>> المعاملات;  // (اسم، نوع)
    bool عامة = true;
    رؤية_انعكاس الرؤية = رؤية_انعكاس::افتراضي;
    
    // استدعاء الدالة
    std::function<std::any(void*, const std::vector<std::any>&)> استدعِ;
    
    /**
     * هل مرئية للسياق المُعطى؟
     */
    bool مرئية_لـ(const std::vector<std::string>& أدوار) const {
        // مشابه للحقول
        switch (الرؤية) {
            case رؤية_انعكاس::مرئي: return true;
            case رؤية_انعكاس::مخفي: return false;
            case رؤية_انعكاس::افتراضي: return عامة;
            default: return false;
        }
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
