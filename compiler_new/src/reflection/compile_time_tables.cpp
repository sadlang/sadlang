#pragma once

#include <string>
#include <vector>
#include <unordered_map>
#include <sstream>
#include <functional>

namespace sad {
namespace مترجم {

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُدخل جدول الحقل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مُدخل حقل في جدول وقت الترجمة
 */
struct مدخل_حقل_جدول {
    const char* الاسم;
    const char* اسم_النوع;
    size_t الإزاحة;
    size_t الحجم;
    bool عام;
    uint8_t الرؤية;  // 0=مرئي, 1=مخفي, 2=مقيد, 3=افتراضي
};

/**
 * مُدخل دالة في جدول وقت الترجمة
 */
struct مدخل_دالة_جدول {
    const char* الاسم;
    const char* نوع_الإرجاع;
    const char* const* أسماء_المعاملات;
    const char* const* أنواع_المعاملات;
    size_t عدد_المعاملات;
    bool عامة;
    void* مؤشر_الدالة;
};

/**
 * جدول نوع كامل
 */
struct جدول_نوع {
    const char* الاسم;
    const char* الاسم_الكامل;
    size_t الحجم;
    size_t المحاذاة;
    uint8_t التصنيف;  // 0=بنية, 1=صنف, 2=سمة, 3=تعداد, 4=بدائي
    
    const مدخل_حقل_جدول* الحقول;
    size_t عدد_الحقول;
    
    const مدخل_دالة_جدول* الدوال;
    size_t عدد_الدوال;
    
    const char* const* السمات_المُنفَّذة;
    size_t عدد_السمات;
    
    const char* الأب;  // nullptr إذا لا يوجد
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُولِّد الجداول
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات الحقل للمولد
 */
struct حقل_للتوليد {
    std::string الاسم;
    std::string النوع;
    size_t الإزاحة;
    size_t الحجم;
    bool عام;
    int الرؤية;
};

/**
 * معلومات الدالة للمولد
 */
struct دالة_للتوليد {
    std::string الاسم;
    std::string نوع_الإرجاع;
    std::vector<std::pair<std::string, std::string>> المعاملات;
    bool عامة;
};

/**
 * معلومات النوع للمولد
 */
struct نوع_للتوليد {
    std::string الاسم;
    std::string الاسم_الكامل;
    size_t الحجم;
    size_t المحاذاة;
    int التصنيف;
    
    std::vector<حقل_للتوليد> الحقول;
    std::vector<دالة_للتوليد> الدوال;
    std::vector<std::string> السمات;
    std::string الأب;
};

/**
 * مُولِّد جداول الانعكاس
 * 
 * يُنتج كود C++ ثابت يُضمَّن في البرنامج
 */
class مولد_جداول_انعكاس {
public:
    /**
     * توليد جدول لنوع واحد
     */
    std::string ولِّد_جدول(const نوع_للتوليد& نوع) {
        std::stringstream كود;
        
        كود << "// جدول انعكاس مُولَّد تلقائياً لـ " << نوع.الاسم << "\n";
        كود << "// لا تُعدِّل هذا الملف يدوياً!\n\n";
        
        كود << "namespace sad { namespace انعكاس {\n\n";
        
        // جدول الحقول
        if (!نوع.الحقول.empty()) {
            كود << "static const مدخل_حقل_جدول __حقول_" << نوع.الاسم << "[] = {\n";
            
            for (const auto& حقل : نوع.الحقول) {
                كود << "    {\"" << حقل.الاسم << "\", \"" << حقل.النوع << "\", "
                    << حقل.الإزاحة << ", " << حقل.الحجم << ", "
                    << (حقل.عام ? "true" : "false") << ", "
                    << حقل.الرؤية << "},\n";
            }
            
            كود << "};\n\n";
        }
        
        // جدول الدوال
        if (!نوع.الدوال.empty()) {
            // أسماء المعاملات وأنواعها
            int دالة_رقم = 0;
            for (const auto& دالة : نوع.الدوال) {
                if (!دالة.المعاملات.empty()) {
                    كود << "static const char* __أسماء_" << نوع.الاسم << "_" 
                        << دالة_رقم << "[] = {";
                    for (size_t i = 0; i < دالة.المعاملات.size(); i++) {
                        if (i > 0) كود << ", ";
                        كود << "\"" << دالة.المعاملات[i].first << "\"";
                    }
                    كود << "};\n";
                    
                    كود << "static const char* __أنواع_" << نوع.الاسم << "_" 
                        << دالة_رقم << "[] = {";
                    for (size_t i = 0; i < دالة.المعاملات.size(); i++) {
                        if (i > 0) كود << ", ";
                        كود << "\"" << دالة.المعاملات[i].second << "\"";
                    }
                    كود << "};\n";
                }
                دالة_رقم++;
            }
            
            كود << "\nstatic const مدخل_دالة_جدول __دوال_" << نوع.الاسم << "[] = {\n";
            
            دالة_رقم = 0;
            for (const auto& دالة : نوع.الدوال) {
                كود << "    {\"" << دالة.الاسم << "\", \"" << دالة.نوع_الإرجاع << "\", ";
                
                if (دالة.المعاملات.empty()) {
                    كود << "nullptr, nullptr, 0, ";
                } else {
                    كود << "__أسماء_" << نوع.الاسم << "_" << دالة_رقم << ", "
                        << "__أنواع_" << نوع.الاسم << "_" << دالة_رقم << ", "
                        << دالة.المعاملات.size() << ", ";
                }
                
                كود << (دالة.عامة ? "true" : "false") << ", nullptr},\n";
                دالة_رقم++;
            }
            
            كود << "};\n\n";
        }
        
        // السمات
        if (!نوع.السمات.empty()) {
            كود << "static const char* __سمات_" << نوع.الاسم << "[] = {";
            for (size_t i = 0; i < نوع.السمات.size(); i++) {
                if (i > 0) كود << ", ";
                كود << "\"" << نوع.السمات[i] << "\"";
            }
            كود << "};\n\n";
        }
        
        // الجدول الرئيسي
        كود << "static const جدول_نوع __جدول_" << نوع.الاسم << " = {\n";
        كود << "    \"" << نوع.الاسم << "\",\n";
        كود << "    \"" << نوع.الاسم_الكامل << "\",\n";
        كود << "    " << نوع.الحجم << ",\n";
        كود << "    " << نوع.المحاذاة << ",\n";
        كود << "    " << نوع.التصنيف << ",\n";
        
        if (نوع.الحقول.empty()) {
            كود << "    nullptr, 0,\n";
        } else {
            كود << "    __حقول_" << نوع.الاسم << ", " << نوع.الحقول.size() << ",\n";
        }
        
        if (نوع.الدوال.empty()) {
            كود << "    nullptr, 0,\n";
        } else {
            كود << "    __دوال_" << نوع.الاسم << ", " << نوع.الدوال.size() << ",\n";
        }
        
        if (نوع.السمات.empty()) {
            كود << "    nullptr, 0,\n";
        } else {
            كود << "    __سمات_" << نوع.الاسم << ", " << نوع.السمات.size() << ",\n";
        }
        
        if (نوع.الأب.empty()) {
            كود << "    nullptr\n";
        } else {
            كود << "    \"" << نوع.الأب << "\"\n";
        }
        
        كود << "};\n\n";
        
        // دالة الوصول
        كود << "const جدول_نوع* احصل_جدول_" << نوع.الاسم << "() {\n";
        كود << "    return &__جدول_" << نوع.الاسم << ";\n";
        كود << "}\n\n";
        
        كود << "}} // namespace sad::انعكاس\n";
        
        return كود.str();
    }
    
    /**
     * توليد ملف تجميعي لكل الأنواع
     */
    std::string ولِّد_ملف_تجميعي(const std::vector<نوع_للتوليد>& الأنواع) {
        std::stringstream كود;
        
        كود << "// جداول انعكاس مُولَّدة تلقائياً\n";
        كود << "// لا تُعدِّل هذا الملف يدوياً!\n\n";
        
        كود << "#pragma once\n\n";
        كود << "#include \"reflection_tables.hpp\"\n\n";
        
        for (const auto& نوع : الأنواع) {
            كود << ولِّد_جدول(نوع);
            كود << "\n// ═══════════════════════════════════════════════════════════════\n\n";
        }
        
        // جدول البحث العام
        كود << "namespace sad { namespace انعكاس {\n\n";
        كود << "const جدول_نوع* ابحث_عن_جدول(const char* اسم) {\n";
        
        for (const auto& نوع : الأنواع) {
            كود << "    if (strcmp(اسم, \"" << نوع.الاسم << "\") == 0 || "
                << "strcmp(اسم, \"" << نوع.الاسم_الكامل << "\") == 0) {\n";
            كود << "        return احصل_جدول_" << نوع.الاسم << "();\n";
            كود << "    }\n";
        }
        
        كود << "    return nullptr;\n";
        كود << "}\n\n";
        كود << "}} // namespace sad::انعكاس\n";
        
        return كود.str();
    }
};

} // namespace مترجم
} // namespace sad
