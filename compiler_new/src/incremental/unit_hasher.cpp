/**
 * ذاكرة تخزين hashes للوحدات
 */
class ذاكرة_hash {
public:
    ذاكرة_hash(const std::string& مجلد_المشروع)
        : m_مسار_الذاكرة(مجلد_المشروع + "/.sad/hash_cache.bin") {}
    
    /**
     * حفظ hash وحدة
     */
    void احفظ(const معلومات_وحدة& وحدة) {
        m_الذاكرة[وحدة.المعرف] = وحدة;
    }
    
    /**
     * استرجاع hash وحدة
     */
    std::optional<معلومات_وحدة> استرجع(const std::string& معرف) const {
        auto it = m_الذاكرة.find(معرف);
        if (it != m_الذاكرة.end()) {
            return it->second;
        }
        return std::nullopt;
    }
    
    /**
     * هل تغيّرت الوحدة؟
     */
    bool تغيّرت(const std::string& معرف, uint64_t hash_جديد) const {
        auto قديم = استرجع(معرف);
        if (!قديم.has_value()) return true;  // جديدة
        return قديم->hash_الكامل != hash_جديد;
    }
    
    /**
     * حفظ الذاكرة لملف
     */
    void احفظ_للملف() {
        std::filesystem::create_directories(
            std::filesystem::path(m_مسار_الذاكرة).parent_path()
        );
        
        std::ofstream ملف(m_مسار_الذاكرة, std::ios::binary);
        if (!ملف) return;
        
        // عدد العناصر
        size_t عدد = m_الذاكرة.size();
        ملف.write(reinterpret_cast<char*>(&عدد), sizeof(عدد));
        
        // العناصر
        for (const auto& [معرف, وحدة] : m_الذاكرة) {
            // طول المعرف والمعرف
            size_t طول = معرف.length();
            ملف.write(reinterpret_cast<char*>(&طول), sizeof(طول));
            ملف.write(معرف.c_str(), طول);
            
            // الـ hashes
            ملف.write(reinterpret_cast<const char*>(&وحدة.hash_الكامل), sizeof(uint64_t));
            ملف.write(reinterpret_cast<const char*>(&وحدة.hash_التوقيع), sizeof(uint64_t));
            ملف.write(reinterpret_cast<const char*>(&وحدة.hash_الجسم), sizeof(uint64_t));
        }
    }
    
    /**
     * تحميل الذاكرة من ملف
     */
    void حمِّل_من_ملف() {
        std::ifstream ملف(m_مسار_الذاكرة, std::ios::binary);
        if (!ملف) return;
        
        m_الذاكرة.clear();
        
        size_t عدد;
        ملف.read(reinterpret_cast<char*>(&عدد), sizeof(عدد));
        
        for (size_t i = 0; i < عدد; i++) {
            size_t طول;
            ملف.read(reinterpret_cast<char*>(&طول), sizeof(طول));
            
            std::string معرف(طول, '\0');
            ملف.read(&معرف[0], طول);
            
            معلومات_وحدة وحدة;
            وحدة.المعرف = معرف;
            
            ملف.read(reinterpret_cast<char*>(&وحدة.hash_الكامل), sizeof(uint64_t));
            ملف.read(reinterpret_cast<char*>(&وحدة.hash_التوقيع), sizeof(uint64_t));
            ملف.read(reinterpret_cast<char*>(&وحدة.hash_الجسم), sizeof(uint64_t));
            
            m_الذاكرة[معرف] = وحدة;
        }
    }
    
    /**
     * مسح الذاكرة
     */
    void امسح() {
        m_الذاكرة.clear();
    }
    
private:
    std::string m_مسار_الذاكرة;
    std::unordered_map<std::string, معلومات_وحدة> m_الذاكرة;
};

