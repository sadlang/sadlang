/**
 * نوع الوحدة
 */
enum class نوع_وحدة {
    دالة,
    صنف,
    بنية,
    سمة,
    ثابت,
    استيراد,
};

/**
 * معلومات وحدة واحدة
 */
struct معلومات_وحدة {
    std::string المعرف;
    نوع_وحدة النوع;
    std::string الملف;
    int سطر_البداية = 0;
    int سطر_النهاية = 0;
    
    // Hashes
    uint64_t hash_التوقيع = 0;    // Hash للواجهة (الجزء العام)
    uint64_t hash_الجسم = 0;      // Hash للتنفيذ
    uint64_t hash_الكامل = 0;     // Hash للكل
    
    // التبعيات
    std::vector<std::string> يعتمد_على;
};

/**
 * حاسب hash للوحدات
 */
class حاسب_hash_وحدات {
public:
    /**
     * حساب hash لوحدة
     */
    معلومات_وحدة احسب_وحدة(
        const std::string& معرف,
        نوع_وحدة نوع,
        const std::string& الكود,
        const std::string& ملف,
        int بداية,
        int نهاية
    ) {
        معلومات_وحدة م;
        م.المعرف = معرف;
        م.النوع = نوع;
        م.الملف = ملف;
        م.سطر_البداية = بداية;
        م.سطر_النهاية = نهاية;
        
        حاسب_hash_كود حاسب;
        م.hash_الكامل = حاسب.احسب(الكود);
        
        // للتوقيع والجسم، نحتاج تحليل أعمق
        // هذا تبسيط - نستخدم الكامل
        م.hash_التوقيع = م.hash_الكامل;
        م.hash_الجسم = م.hash_الكامل;
        
        return م;
    }
    
    /**
     * مقارنة وحدتين
     */
    bool متطابقتان(const معلومات_وحدة& أ, const معلومات_وحدة& ب) const {
        return أ.hash_الكامل == ب.hash_الكامل;
    }
    
    /**
     * هل تغيّر التوقيع فقط؟
     */
    bool تغيّر_التوقيع(const معلومات_وحدة& قديم, const معلومات_وحدة& جديد) const {
        return قديم.hash_التوقيع != جديد.hash_التوقيع;
    }
    
    /**
     * هل تغيّر الجسم فقط؟
     */
    bool تغيّر_الجسم(const معلومات_وحدة& قديم, const معلومات_وحدة& جديد) const {
        return قديم.hash_التوقيع == جديد.hash_التوقيع &&
               قديم.hash_الجسم != جديد.hash_الجسم;
    }
};

