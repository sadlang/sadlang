/**
 * خوارزمية FNV-1a Hash (سريعة وجيدة للنصوص)
 * 
 * لماذا FNV-1a؟
 * - سريعة جداً (byte بـ byte)
 * - توزيع جيد (قليل من التصادمات)
 * - بسيطة التنفيذ
 */
class حاسب_hash_fnv {
public:
    /**
     * حساب hash لنص
     */
    static uint64_t احسب(const std::string& نص) {
        uint64_t hash = FNV_أساس;
        
        for (char c : نص) {
            hash ^= static_cast<uint64_t>(c);
            hash *= FNV_أولي;
        }
        
        return hash;
    }
    
    /**
     * حساب hash لبيانات ثنائية
     */
    static uint64_t احسب(const uint8_t* بيانات, size_t طول) {
        uint64_t hash = FNV_أساس;
        
        for (size_t i = 0; i < طول; i++) {
            hash ^= static_cast<uint64_t>(بيانات[i]);
            hash *= FNV_أولي;
        }
        
        return hash;
    }
    
    /**
     * دمج عدة hashes في واحد
     */
    static uint64_t ادمج(const std::vector<uint64_t>& قيم) {
        uint64_t نتيجة = FNV_أساس;
        
        for (uint64_t قيمة : قيم) {
            نتيجة ^= قيمة;
            نتيجة *= FNV_أولي;
        }
        
        return نتيجة;
    }
    
private:
    // ثوابت FNV-1a 64-bit
    static constexpr uint64_t FNV_أساس = 14695981039346656037ULL;
    static constexpr uint64_t FNV_أولي = 1099511628211ULL;
};

// ═══════════════════════════════════════════════════════════════════════════════
