/**
 * مُنسِّق الترجمة الموازية
 * 
 * يُدير ترتيب الترجمة حسب التبعيات
 */
class منسق_ترجمة_موازية {
public:
    using دالة_ترجمة = std::function<bool(وحدة_ترجمة&)>;
    
    منسق_ترجمة_موازية(size_t عدد_خيوط = 0)
        : m_التجمع(عدد_خيوط) {}
    
    /**
     * ترجمة مجموعة وحدات
     */
    نتيجة_ترجمة_موازية ترجِم(
        std::vector<وحدة_ترجمة>& الوحدات,
        دالة_ترجمة مُترجم
    ) {
        نتيجة_ترجمة_موازية نتيجة;
        auto بداية = std::chrono::steady_clock::now();
        
        // رتِّب الوحدات حسب التبعيات
        auto مرتبة = رتِّب_طوبولوجياً(الوحدات);
        
        // قسِّم إلى مستويات (كل مستوى يمكن ترجمته موازياً)
        auto مستويات = قسِّم_لمستويات(مرتبة);
        
        // ترجِم كل مستوى
        for (auto& مستوى : مستويات) {
            std::vector<std::future<bool>> المستقبلات;
            
            // أطلق كل وحدات المستوى
            for (auto* وحدة : مستوى) {
                auto مستقبل = m_التجمع.أضف([وحدة, &مُترجم]() {
                    auto بداية_وحدة = std::chrono::steady_clock::now();
                    bool نجح = مُترجم(*وحدة);
                    auto نهاية_وحدة = std::chrono::steady_clock::now();
                    
                    وحدة->نجحت = نجح;
                    وحدة->وقت_الترجمة = std::chrono::duration_cast<std::chrono::milliseconds>(
                        نهاية_وحدة - بداية_وحدة
                    );
                    
                    return نجح;
                });
                
                المستقبلات.push_back(std::move(مستقبل));
            }
            
            // انتظر كل الوحدات في المستوى
            for (size_t i = 0; i < المستقبلات.size(); i++) {
                bool نجح = المستقبلات[i].get();
                if (نجح) {
                    نتيجة.وحدات_ناجحة++;
                } else {
                    نتيجة.وحدات_فاشلة++;
                    نتيجة.أخطاء.push_back(مستوى[i]->رسالة_خطأ);
                }
            }
            
            // توقف إذا فشل شيء
            if (نتيجة.وحدات_فاشلة > 0) {
                break;
            }
        }
        
        auto نهاية = std::chrono::steady_clock::now();
        نتيجة.الوقت_الكلي = std::chrono::duration_cast<std::chrono::milliseconds>(
            نهاية - بداية
        );
        
        return نتيجة;
    }
    
    /**
     * عدد الخيوط المستخدمة
     */
    size_t عدد_الخيوط() const {
        return m_التجمع.عدد_الخيوط();
    }
    
private:
    تجمع_خيوط m_التجمع;
    
    /**
     * ترتيب طوبولوجي حسب التبعيات
     */
    std::vector<وحدة_ترجمة*> رتِّب_طوبولوجياً(std::vector<وحدة_ترجمة>& الوحدات) {
        std::vector<وحدة_ترجمة*> نتيجة;
        std::unordered_map<std::string, وحدة_ترجمة*> خريطة;
        std::unordered_map<std::string, int> درجة_الدخول;
        
        // بناء الخريطة وحساب درجات الدخول
        for (auto& وحدة : الوحدات) {
            خريطة[وحدة.المعرف] = &وحدة;
            درجة_الدخول[وحدة.المعرف] = 0;
        }
        
        for (auto& وحدة : الوحدات) {
            for (const auto& تبعية : وحدة.يعتمد_على) {
                if (خريطة.count(تبعية) > 0) {
                    درجة_الدخول[وحدة.المعرف]++;
                }
            }
        }
        
        // خوارزمية Kahn
        std::queue<std::string> صفر_تبعيات;
        for (const auto& [معرف, درجة] : درجة_الدخول) {
            if (درجة == 0) {
                صفر_تبعيات.push(معرف);
            }
        }
        
        while (!صفر_تبعيات.empty()) {
            std::string حالي = صفر_تبعيات.front();
            صفر_تبعيات.pop();
            نتيجة.push_back(خريطة[حالي]);
            
            // قلِّل درجة دخول المعتمدين
            for (auto& وحدة : الوحدات) {
                for (const auto& تبعية : وحدة.يعتمد_على) {
                    if (تبعية == حالي) {
                        درجة_الدخول[وحدة.المعرف]--;
                        if (درجة_الدخول[وحدة.المعرف] == 0) {
                            صفر_تبعيات.push(وحدة.المعرف);
                        }
                    }
                }
            }
        }
        
        return نتيجة;
    }
    
    /**
     * تقسيم لمستويات متوازية
     */
    std::vector<std::vector<وحدة_ترجمة*>> قسِّم_لمستويات(
        const std::vector<وحدة_ترجمة*>& مرتبة
    ) {
        std::vector<std::vector<وحدة_ترجمة*>> مستويات;
        std::unordered_set<std::string> مُترجمة;
        
        std::vector<وحدة_ترجمة*> متبقية(مرتبة.begin(), مرتبة.end());
        
        while (!متبقية.empty()) {
            std::vector<وحدة_ترجمة*> مستوى_حالي;
            std::vector<وحدة_ترجمة*> للمرة_القادمة;
            
            for (auto* وحدة : متبقية) {
                bool جاهزة = true;
                
                for (const auto& تبعية : وحدة->يعتمد_على) {
                    if (مُترجمة.count(تبعية) == 0) {
                        جاهزة = false;
                        break;
                    }
                }
                
                if (جاهزة) {
                    مستوى_حالي.push_back(وحدة);
                } else {
                    للمرة_القادمة.push_back(وحدة);
                }
            }
            
            if (مستوى_حالي.empty() && !للمرة_القادمة.empty()) {
                // دورة في التبعيات!
                throw std::runtime_error("دورة في التبعيات!");
            }
            
            for (auto* وحدة : مستوى_حالي) {
                مُترجمة.insert(وحدة->المعرف);
            }
            
            مستويات.push_back(std::move(مستوى_حالي));
            متبقية = std::move(للمرة_القادمة);
        }
        
        return مستويات;
    }
};

