/**
 * تجمع خيوط لإدارة المهام المتوازية
 * 
 * فكِّر فيه كفريق عمال:
 * - لديك عدد من العمال (الخيوط)
 * - تُعطيهم مهام
 * - يأخذ كل عامل مهمة وينفذها
 * - عندما ينتهي، يأخذ المهمة التالية
 */
class تجمع_خيوط {
public:
    /**
     * إنشاء تجمع بعدد معين من الخيوط
     * 
     * @param عدد_الخيوط عدد الخيوط (افتراضياً = عدد الأنوية)
     */
    explicit تجمع_خيوط(size_t عدد_الخيوط = 0) {
        if (عدد_الخيوط == 0) {
            عدد_الخيوط = std::thread::hardware_concurrency();
            if (عدد_الخيوط == 0) عدد_الخيوط = 4;  // احتياطي
        }
        
        m_يعمل = true;
        
        for (size_t i = 0; i < عدد_الخيوط; i++) {
            m_الخيوط.emplace_back([this] { حلقة_العامل(); });
        }
    }
    
    ~تجمع_خيوط() {
        {
            std::unique_lock<std::mutex> قفل(m_قفل);
            m_يعمل = false;
        }
        
        m_شرط.notify_all();
        
        for (auto& خيط : m_الخيوط) {
            if (خيط.joinable()) {
                خيط.join();
            }
        }
    }
    
    /**
     * إضافة مهمة للتنفيذ
     * 
     * مثال:
     *     auto نتيجة = تجمع.أضف([](){ return 42; });
     *     int قيمة = نتيجة.get();  // ينتظر ثم يُرجع 42
     */
    template<typename دالة, typename... معاملات>
    auto أضف(دالة&& د, معاملات&&... م) 
        -> std::future<typename std::invoke_result<دالة, معاملات...>::type>
    {
        using نوع_الإرجاع = typename std::invoke_result<دالة, معاملات...>::type;
        
        auto مهمة = std::make_shared<std::packaged_task<نوع_الإرجاع()>>(
            std::bind(std::forward<دالة>(د), std::forward<معاملات>(م)...)
        );
        
        std::future<نوع_الإرجاع> مستقبل = مهمة->get_future();
        
        {
            std::unique_lock<std::mutex> قفل(m_قفل);
            if (!m_يعمل) {
                throw std::runtime_error("التجمع متوقف");
            }
            m_المهام.emplace([مهمة]() { (*مهمة)(); });
        }
        
        m_شرط.notify_one();
        return مستقبل;
    }
    
    /**
     * عدد الخيوط
     */
    size_t عدد_الخيوط() const {
        return m_الخيوط.size();
    }
    
    /**
     * عدد المهام المنتظرة
     */
    size_t المهام_المنتظرة() const {
        std::unique_lock<std::mutex> قفل(m_قفل);
        return m_المهام.size();
    }
    
private:
    std::vector<std::thread> m_الخيوط;
    std::queue<std::function<void()>> m_المهام;
    mutable std::mutex m_قفل;
    std::condition_variable m_شرط;
    std::atomic<bool> m_يعمل{true};
    
    void حلقة_العامل() {
        while (true) {
            std::function<void()> مهمة;
            
            {
                std::unique_lock<std::mutex> قفل(m_قفل);
                m_شرط.wait(قفل, [this] {
                    return !m_يعمل || !m_المهام.empty();
                });
                
                if (!m_يعمل && m_المهام.empty()) {
                    return;
                }
                
                مهمة = std::move(m_المهام.front());
                m_المهام.pop();
            }
            
            مهمة();
        }
    }
};

