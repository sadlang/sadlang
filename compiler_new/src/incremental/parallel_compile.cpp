/**
 * مراقب تقدم الترجمة
 */
class مراقب_تقدم {
public:
    void ابدأ(int إجمالي) {
        m_إجمالي = إجمالي;
        m_حالي = 0;
        m_بداية = std::chrono::steady_clock::now();
    }
    
    void تقدَّم(const std::string& وحدة) {
        m_حالي++;
        اطبع_شريط(وحدة);
    }
    
    void انتهى() {
        auto نهاية = std::chrono::steady_clock::now();
        auto وقت = std::chrono::duration_cast<std::chrono::milliseconds>(
            نهاية - m_بداية
        );
        
        std::cout << "\n✅ انتهت الترجمة في " << وقت.count() << "ms\n";
    }
    
private:
    int m_إجمالي = 0;
    std::atomic<int> m_حالي{0};
    std::chrono::steady_clock::time_point m_بداية;
    std::mutex m_قفل_طباعة;
    
    void اطبع_شريط(const std::string& وحدة) {
        std::lock_guard<std::mutex> قفل(m_قفل_طباعة);
        
        int نسبة = (m_حالي * 100) / m_إجمالي;
        int أعمدة = (m_حالي * 40) / m_إجمالي;
        
        std::cout << "\r[";
        for (int i = 0; i < 40; i++) {
            if (i < أعمدة) std::cout << "█";
            else std::cout << "░";
        }
        std::cout << "] " << نسبة << "% - " << وحدة << "        ";
        std::cout.flush();
    }
};

