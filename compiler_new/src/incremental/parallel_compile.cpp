/**
 * وحدة ترجمة واحدة
 */
struct وحدة_ترجمة {
    std::string المعرف;
    std::string مسار_المصدر;
    std::string مسار_الخرج;
    
    // التبعيات (يجب ترجمتها أولاً)
    std::vector<std::string> يعتمد_على;
    
    // النتيجة
    bool نجحت = false;
    std::string رسالة_خطأ;
    std::chrono::milliseconds وقت_الترجمة{0};
};

/**
 * نتيجة ترجمة موازية
 */
struct نتيجة_ترجمة_موازية {
    int وحدات_ناجحة = 0;
    int وحدات_فاشلة = 0;
    std::chrono::milliseconds الوقت_الكلي{0};
    
    std::vector<std::string> أخطاء;
    
    bool نجحت() const { return وحدات_فاشلة == 0; }
};

