/**
 * توقيع دالة (للمقارنة)
 * 
 * التوقيع = اسم + أنواع المعاملات + نوع الإرجاع
 * 
 * إذا تغيّر التوقيع → يجب إعادة ترجمة المستدعين
 */
struct توقيع_دالة {
    std::string الاسم;
    std::vector<std::string> أنواع_المعاملات;
    std::string نوع_الإرجاع;
    bool ثابتة = false;        // const
    bool غير_متزامنة = false;  // async
    
    /**
     * تحويل لنص للمقارنة
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << الاسم << "(";
        for (size_t i = 0; i < أنواع_المعاملات.size(); i++) {
            if (i > 0) ss << ", ";
            ss << أنواع_المعاملات[i];
        }
        ss << ")";
        if (ثابتة) ss << " ثابتة";
        if (غير_متزامنة) ss << " منتظرة";
        ss << " -> " << نوع_الإرجاع;
        return ss.str();
    }
    
    /**
     * حساب Hash للتوقيع
     */
    size_t hash() const {
        std::hash<std::string> hasher;
        return hasher(إلى_نص());
    }
    
    bool operator==(const توقيع_دالة& أخرى) const {
        return إلى_نص() == أخرى.إلى_نص();
    }
    
    bool operator!=(const توقيع_دالة& أخرى) const {
        return !(*this == أخرى);
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
