/**
 * نوع التغيير
 */
enum class نوع_تغيير {
    لا_تغيير,        // لم يتغير شيء
    تغيير_توقيع,     // تغيّر التوقيع (خطير!)
    تغيير_جسم,       // تغيّر الجسم فقط
    تغيير_تعليق,     // تغيّر تعليق فقط (لا يؤثر)
    إضافة,           // دالة جديدة
    حذف,             // دالة مُحذوفة
};

/**
 * نتيجة تحليل التغييرات
 */
struct تحليل_تغييرات {
    نوع_تغيير النوع;
    std::string الدالة;
    
    // للتغييرات في التوقيع
    std::optional<توقيع_دالة> التوقيع_القديم;
    std::optional<توقيع_دالة> التوقيع_الجديد;
    
    std::string الوصف() const {
        switch (النوع) {
            case نوع_تغيير::لا_تغيير:
                return الدالة + ": لا تغيير";
            case نوع_تغيير::تغيير_توقيع:
                return الدالة + ": تغيّر التوقيع ⚠️";
            case نوع_تغيير::تغيير_جسم:
                return الدالة + ": تغيّر الجسم";
            case نوع_تغيير::تغيير_تعليق:
                return الدالة + ": تغيّر تعليق فقط";
            case نوع_تغيير::إضافة:
                return الدالة + ": دالة جديدة ➕";
            case نوع_تغيير::حذف:
                return الدالة + ": دالة محذوفة ➖";
        }
        return "";
    }
};

/**
 * رسم التبعيات الرئيسي
 */
class رسم_التبعيات {
public:
    /**
     * إضافة دالة للرسم
     */
    void أضف_دالة(const معلومات_دالة& م) {
        m_الدوال[م.المعرف] = م;
        
        // حدِّث الرسم العكسي (من يستدعي هذه الدالة)
        for (const auto& مُستدعاة : م.الاستدعاءات) {
            m_المستدعون[مُستدعاة].insert(م.المعرف);
        }
    }
    
    /**
     * إزالة دالة
     */
    void أزل_دالة(const std::string& معرف) {
        auto it = m_الدوال.find(معرف);
        if (it != m_الدوال.end()) {
            // أزل من الرسم العكسي
            for (const auto& مُستدعاة : it->second.الاستدعاءات) {
                m_المستدعون[مُستدعاة].erase(معرف);
            }
            m_الدوال.erase(it);
        }
    }
    
    /**
     * الحصول على الدوال التي تستدعي دالة معينة
     */
    std::unordered_set<std::string> من_يستدعي(const std::string& معرف) const {
        auto it = m_المستدعون.find(معرف);
        if (it != m_المستدعون.end()) {
            return it->second;
        }
        return {};
    }
    
    /**
     * الحصول على الدوال التي تستدعيها دالة معينة
     */
    std::unordered_set<std::string> ماذا_تستدعي(const std::string& معرف) const {
        auto it = m_الدوال.find(معرف);
        if (it != m_الدوال.end()) {
            return it->second.الاستدعاءات;
        }
        return {};
    }
    
    /**
     * حساب المتأثرين بتغيير دالة
     * 
     * إذا تغيّر التوقيع: نُرجع كل المستدعين (بشكل تكراري)
     * إذا تغيّر الجسم فقط: نُرجع الدالة نفسها فقط
     */
    std::unordered_set<std::string> المتأثرون_بتغيير(
        const std::string& معرف,
        نوع_تغيير نوع
    ) {
        std::unordered_set<std::string> نتيجة;
        
        if (نوع == نوع_تغيير::تغيير_تعليق || نوع == نوع_تغيير::لا_تغيير) {
            // لا أحد متأثر
            return نتيجة;
        }
        
        if (نوع == نوع_تغيير::تغيير_جسم) {
            // الدالة نفسها فقط
            نتيجة.insert(معرف);
            return نتيجة;
        }
        
        // تغيير توقيع أو حذف أو إضافة → كل المستدعين متأثرون
        std::vector<std::string> للزيارة = {معرف};
        
        while (!للزيارة.empty()) {
            std::string حالي = للزيارة.back();
            للزيارة.pop_back();
            
            if (نتيجة.count(حالي) > 0) continue;  // زُرناه
            نتيجة.insert(حالي);
            
            // أضف كل من يستدعي هذه الدالة
            for (const auto& مستدعي : من_يستدعي(حالي)) {
                للزيارة.push_back(مستدعي);
            }
        }
        
        return نتيجة;
    }
    
    /**
     * تحليل التغييرات بين نسختين
     */
    std::vector<تحليل_تغييرات> حلِّل_تغييرات(
        const std::unordered_map<std::string, معلومات_دالة>& القديم,
        const std::unordered_map<std::string, معلومات_دالة>& الجديد
    ) {
        std::vector<تحليل_تغييرات> نتيجة;
        
        // ابحث عن الدوال المُعدَّلة والمحذوفة
        for (const auto& [معرف, قديم] : القديم) {
            تحليل_تغييرات ت;
            ت.الدالة = معرف;
            
            auto it = الجديد.find(معرف);
            if (it == الجديد.end()) {
                // دالة محذوفة
                ت.النوع = نوع_تغيير::حذف;
                نتيجة.push_back(ت);
                continue;
            }
            
            const auto& جديد = it->second;
            
            // قارن التوقيع
            if (قديم.التوقيع != جديد.التوقيع) {
                ت.النوع = نوع_تغيير::تغيير_توقيع;
                ت.التوقيع_القديم = قديم.التوقيع;
                ت.التوقيع_الجديد = جديد.التوقيع;
            } else if (قديم.hash_الجسم != جديد.hash_الجسم) {
                ت.النوع = نوع_تغيير::تغيير_جسم;
            } else {
                ت.النوع = نوع_تغيير::لا_تغيير;
            }
            
            if (ت.النوع != نوع_تغيير::لا_تغيير) {
                نتيجة.push_back(ت);
            }
        }
        
        // ابحث عن الدوال الجديدة
        for (const auto& [معرف, جديد] : الجديد) {
            if (القديم.count(معرف) == 0) {
                تحليل_تغييرات ت;
                ت.الدالة = معرف;
                ت.النوع = نوع_تغيير::إضافة;
                نتيجة.push_back(ت);
            }
        }
        
        return نتيجة;
    }
    
    /**
     * طباعة الرسم (للتصحيح)
     */
    void اطبع() const {
        std::cout << "\n═══ رسم التبعيات ═══\n\n";
        
        for (const auto& [معرف, دالة] : m_الدوال) {
            std::cout << "دالة: " << معرف << "\n";
            std::cout << "  التوقيع: " << دالة.التوقيع.إلى_نص() << "\n";
            
            if (!دالة.الاستدعاءات.empty()) {
                std::cout << "  تستدعي:\n";
                for (const auto& س : دالة.الاستدعاءات) {
                    std::cout << "    → " << س << "\n";
                }
            }
            
            auto مستدعون = من_يستدعي(معرف);
            if (!مستدعون.empty()) {
                std::cout << "  يستدعيها:\n";
                for (const auto& م : مستدعون) {
                    std::cout << "    ← " << م << "\n";
                }
            }
            
            std::cout << "\n";
        }
    }
    
private:
    // الدوال مفهرسة بمعرفها
    std::unordered_map<std::string, معلومات_دالة> m_الدوال;
    
    // الرسم العكسي: دالة → من يستدعيها
    std::unordered_map<std::string, std::unordered_set<std::string>> m_المستدعون;
};

