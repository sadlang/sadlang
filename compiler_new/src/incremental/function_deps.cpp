/**
 * معلومات دالة واحدة
 */
struct معلومات_دالة {
    std::string المعرف;           // الاسم الفريد الكامل
    توقيع_دالة التوقيع;
    std::string الملف;
    int سطر_البداية = 0;
    int سطر_النهاية = 0;
    
    // Hash لمحتوى الجسم
    size_t hash_الجسم = 0;
    
    // الدوال التي تستدعيها هذه الدالة
    std::unordered_set<std::string> الاستدعاءات;
    
    // المتغيرات العامة التي تستخدمها
    std::unordered_set<std::string> المتغيرات_العامة;
    
    /**
     * هل الدالة "نقية"؟
     * الدالة النقية لا تقرأ/تكتب متغيرات عامة
     */
    bool نقية() const {
        return المتغيرات_العامة.empty();
    }
};

