#include <string>
#include <vector>
#include <map>
#include <iostream>
#include <fstream>
#include <sstream>
#include <regex>

namespace sad {
namespace compat {

/**
 * إصدار اللغة
 */
struct إصدار {
    int رئيسي = 1;
    int ثانوي = 0;
    int تصحيح = 0;
    
    std::string كنص() const {
        return std::to_string(رئيسي) + "." + 
               std::to_string(ثانوي) + "." + 
               std::to_string(تصحيح);
    }
    
    bool operator<(const إصدار& آخر) const {
        if (رئيسي != آخر.رئيسي) return رئيسي < آخر.رئيسي;
        if (ثانوي != آخر.ثانوي) return ثانوي < آخر.ثانوي;
        return تصحيح < آخر.تصحيح;
    }
    
    bool operator==(const إصدار& آخر) const {
        return رئيسي == آخر.رئيسي && 
               ثانوي == آخر.ثانوي && 
               تصحيح == آخر.تصحيح;
    }
};

/**
 * 📋 محلل إصدار اللغة
 */
class محلل_إصدار {
public:
    /**
     * قراءة الإصدار من ملف المشروع
     */
    إصدار اقرأ_من_ملف(const std::string& مسار) {
        إصدار نتيجة;
        
        std::ifstream ملف(مسار);
        if (!ملف.is_open()) {
            std::cerr << "⚠️ لا يمكن قراءة ملف المشروع، استخدام الإصدار الافتراضي\n";
            return نتيجة;
        }
        
        std::string سطر;
        while (std::getline(ملف, سطر)) {
            // البحث عن إصدار_اللغة = "X.Y.Z"
            std::regex نمط(R"(إصدار_اللغة\s*=\s*\"([^\"]+)\")");
            std::smatch تطابق;
            
            if (std::regex_search(سطر, تطابق, نمط)) {
                return حلل_نص(تطابق[1].str());
            }
            
            // البحث بالإنجليزية أيضاً
            std::regex نمط_en(R"(language_version\s*=\s*\"([^\"]+)\")");
            if (std::regex_search(سطر, تطابق, نمط_en)) {
                return حلل_نص(تطابق[1].str());
            }
        }
        
        return نتيجة;
    }
    
    /**
     * تحليل نص الإصدار
     */
    إصدار حلل_نص(const std::string& نص) {
        إصدار نتيجة;
        
        std::regex نمط(R"((\d+)(?:\.(\d+))?(?:\.(\d+))?)");
        std::smatch تطابق;
        
        if (std::regex_search(نص, تطابق, نمط)) {
            نتيجة.رئيسي = std::stoi(تطابق[1].str());
            if (تطابق[2].matched) نتيجة.ثانوي = std::stoi(تطابق[2].str());
            if (تطابق[3].matched) نتيجة.تصحيح = std::stoi(تطابق[3].str());
        }
        
        return نتيجة;
    }
    
    /**
     * التحقق من التوافق
     */
    struct نتيجة_توافق {
        bool متوافق;
        std::vector<std::string> تحذيرات;
        std::vector<std::string> أخطاء;
    };
    
    نتيجة_توافق تحقق_التوافق(const إصدار& كود, const إصدار& مترجم) {
        نتيجة_توافق نتيجة;
        نتيجة.متوافق = true;
        
        // الإصدار الرئيسي مختلف = غير متوافق
        if (كود.رئيسي != مترجم.رئيسي) {
            نتيجة.متوافق = false;
            نتيجة.أخطاء.push_back(
                "الإصدار الرئيسي مختلف: الكود يتطلب v" + كود.كنص() +
                " والمترجم v" + مترجم.كنص()
            );
        }
        
        // كود أحدث من المترجم
        if (مترجم < كود) {
            نتيجة.تحذيرات.push_back(
                "الكود مكتوب لإصدار أحدث (" + كود.كنص() + 
                ") - قد تكون هناك ميزات غير مدعومة"
            );
        }
        
        // كود أقدم بكثير
        if (كود.ثانوي + 5 < مترجم.ثانوي) {
            نتيجة.تحذيرات.push_back(
                "الكود قديم جداً - يُنصح بتحديثه باستخدام: ص ترقية"
            );
        }
        
        return نتيجة;
    }
    
    /**
     * عرض معلومات الإصدار
     */
    void اعرض_معلومات(const إصدار& إ) const {
        std::cout << "╔══════════════════════════════════════════════════════════════╗\n";
        std::cout << "║                    📋 إصدار اللغة                             ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════╣\n";
        std::cout << "║ الإصدار: v" << إ.كنص() << "\n";
        std::cout << "║ الرئيسي: " << إ.رئيسي << " (تغييرات جذرية)\n";
        std::cout << "║ الثانوي: " << إ.ثانوي << " (ميزات جديدة)\n";
        std::cout << "║ التصحيح: " << إ.تصحيح << " (إصلاحات)\n";
        std::cout << "╚══════════════════════════════════════════════════════════════╝\n";
    }
};

} // namespace compat
} // namespace sad

int main() {
    sad::compat::محلل_إصدار محلل;
    
    // اختبار التحليل
    auto إصدار = محلل.حلل_نص("2.1.5");
    محلل.اعرض_معلومات(إصدار);
    
    // اختبار التوافق
    sad::compat::إصدار كود{2, 0, 0};
    sad::compat::إصدار مترجم{2, 5, 0};
    
    auto نتيجة = محلل.تحقق_التوافق(كود, مترجم);
    
    std::cout << "\n📊 نتيجة التوافق:\n";
    std::cout << "   متوافق: " << (نتيجة.متوافق ? "✅ نعم" : "❌ لا") << "\n";
    
    for (const auto& ت : نتيجة.تحذيرات) {
        std::cout << "   ⚠️ " << ت << "\n";
    }
    
    return 0;
}
