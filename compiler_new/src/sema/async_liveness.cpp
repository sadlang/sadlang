/**
 * نوع التعبير
 */
enum class نوع_تعبير {
    متغير,            // مجرد اسم متغير
    استدعاء,          // استدعاء دالة
    انتظار,           // await
    تعيين,            // =
    إرجاع,           // return
    شرط,             // if
    حلقة,            // while/for
    أخرى
};

/**
 * تعبير في AST
 */
struct تعبير_ast {
    نوع_تعبير النوع;
    std::string القيمة;                     // للمتغيرات: اسم المتغير
    std::vector<std::shared_ptr<تعبير_ast>> الأبناء;
    int رقم_السطر = 0;
    
    // للتعيين
    std::string المتغير_المُعيَّن;
    
    // للاستدعاء
    std::string اسم_الدالة;
    std::vector<std::string> المتغيرات_المُستخدمة;  // المتغيرات المُستخدمة في هذا التعبير
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              نقطة انتظار
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * نقطة انتظار (await point)
 * 
 * كل "انتظار" في الدالة يُحدد نقطة قد تتوقف عندها.
 * نحتاج معرفة ما هي المتغيرات الحية عند كل نقطة.
 */
struct نقطة_انتظار {
    int المعرف;
    int رقم_السطر;
    
    // المتغيرات الحية قبل الانتظار
    std::unordered_set<std::string> المتغيرات_الحية_قبل;
    
    // المتغيرات الحية بعد الانتظار
    std::unordered_set<std::string> المتغيرات_الحية_بعد;
    
    // المتغيرات التي يمكن تحريرها عند هذه النقطة
    std::unordered_set<std::string> المتغيرات_للتحرير;
    
    // المتغير الناتج من الانتظار (إذا وجد)
    std::optional<std::string> المتغير_الناتج;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              معلومات المتغير
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات متغير
 */
struct معلومات_متغير {
    std::string الاسم;
    int سطر_التعريف;
    int آخر_استخدام;
    size_t الحجم_التقريبي;      // حجم الذاكرة
    bool مُستخدم_في_انتظار;    // هل يُستخدم عبر نقطة انتظار؟
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل الاستخدام
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * محلل استخدام المتغيرات
 * 
 * يجد كل المتغيرات المُستخدمة في تعبير
 */
class محلل_استخدام {
public:
    /**
     * استخراج المتغيرات المُستخدمة في تعبير
     */
    std::unordered_set<std::string> استخرج_المُستخدمة(
        const std::shared_ptr<تعبير_ast>& تعبير
    ) {
        std::unordered_set<std::string> نتيجة;
        استخرج_تكراري(تعبير, نتيجة);
        return نتيجة;
    }
    
    /**
     * استخراج المتغير المُعرَّف في تعبير
     */
    std::optional<std::string> استخرج_المُعرَّف(
        const std::shared_ptr<تعبير_ast>& تعبير
    ) {
        if (تعبير->النوع == نوع_تعبير::تعيين) {
            return تعبير->المتغير_المُعيَّن;
        }
        return std::nullopt;
    }

private:
    void استخرج_تكراري(
        const std::shared_ptr<تعبير_ast>& تعبير,
        std::unordered_set<std::string>& نتيجة
    ) {
        if (!تعبير) return;
        
        if (تعبير->النوع == نوع_تعبير::متغير) {
            نتيجة.insert(تعبير->القيمة);
        }
        
        for (const auto& ابن : تعبير->الأبناء) {
            استخرج_تكراري(ابن, نتيجة);
        }
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل Liveness
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * محلل Liveness للدوال غير المتزامنة
 * 
 * يحسب المتغيرات الحية عند كل نقطة انتظار
 * ويُحدد ما يمكن تحريره.
 */
class محلل_liveness {
public:
    /**
     * تحليل دالة غير متزامنة
     * 
     * @param التعبيرات قائمة التعبيرات في الدالة
     * @return قائمة نقاط الانتظار مع معلومات Liveness
     */
    std::vector<نقطة_انتظار> حلل(
        const std::vector<std::shared_ptr<تعبير_ast>>& التعبيرات
    ) {
        // الخطوة 1: اكتشاف نقاط الانتظار
        auto نقاط = اكتشف_نقاط_الانتظار(التعبيرات);
        
        // الخطوة 2: تحليل الاستخدامات (backward pass)
        std::unordered_set<std::string> حية_بعد;
        
        for (int i = التعبيرات.size() - 1; i >= 0; i--) {
            auto& تعبير = التعبيرات[i];
            
            // استخدامات هذا التعبير
            auto مُستخدمة = محلل_.استخرج_المُستخدمة(تعبير);
            
            // المتغير المُعرَّف (إن وجد)
            auto مُعرَّف = محلل_.استخرج_المُعرَّف(تعبير);
            
            // إذا كان هذا نقطة انتظار، سجِّل الحالة
            if (تعبير->النوع == نوع_تعبير::انتظار) {
                // ابحث عن النقطة المقابلة
                for (auto& نقطة : نقاط) {
                    if (نقطة.رقم_السطر == تعبير->رقم_السطر) {
                        نقطة.المتغيرات_الحية_بعد = حية_بعد;
                    }
                }
            }
            
            // تحديث المجموعة الحية
            // Liveness: live_before = (live_after - defined) ∪ used
            if (مُعرَّف) {
                حية_بعد.erase(*مُعرَّف);
            }
            حية_بعد.insert(مُستخدمة.begin(), مُستخدمة.end());
            
            // سجِّل الحالة قبل الانتظار
            if (تعبير->النوع == نوع_تعبير::انتظار) {
                for (auto& نقطة : نقاط) {
                    if (نقطة.رقم_السطر == تعبير->رقم_السطر) {
                        نقطة.المتغيرات_الحية_قبل = حية_بعد;
                    }
                }
            }
        }
        
        // الخطوة 3: حساب ما يمكن تحريره بين كل نقطتين
        حسب_التحرير(نقاط);
        
        return نقاط;
    }
    
    /**
     * توليد تقرير Liveness
     */
    std::string ولِّد_تقرير(const std::vector<نقطة_انتظار>& نقاط) {
        std::stringstream تقرير;
        
        تقرير << "تقرير تحليل Liveness\n";
        تقرير << "═══════════════════════\n\n";
        
        for (const auto& نقطة : نقاط) {
            تقرير << "نقطة انتظار #" << نقطة.المعرف 
                  << " (سطر " << نقطة.رقم_السطر << ")\n";
            
            تقرير << "  حية قبل: {";
            bool أول = true;
            for (const auto& م : نقطة.المتغيرات_الحية_قبل) {
                if (!أول) تقرير << ", ";
                تقرير << م;
                أول = false;
            }
            تقرير << "}\n";
            
            تقرير << "  حية بعد: {";
            أول = true;
            for (const auto& م : نقطة.المتغيرات_الحية_بعد) {
                if (!أول) تقرير << ", ";
                تقرير << م;
                أول = false;
            }
            تقرير << "}\n";
            
            if (!نقطة.المتغيرات_للتحرير.empty()) {
                تقرير << "  💾 للتحرير: {";
                أول = true;
                for (const auto& م : نقطة.المتغيرات_للتحرير) {
                    if (!أول) تقرير << ", ";
                    تقرير << م;
                    أول = false;
                }
                تقرير << "}\n";
            }
            
            تقرير << "\n";
        }
        
        return تقرير.str();
    }

private:
    /**
     * اكتشاف نقاط الانتظار
     */
    std::vector<نقطة_انتظار> اكتشف_نقاط_الانتظار(
        const std::vector<std::shared_ptr<تعبير_ast>>& التعبيرات
    ) {
        std::vector<نقطة_انتظار> نقاط;
        int معرف = 0;
        
        for (const auto& تعبير : التعبيرات) {
            if (تعبير->النوع == نوع_تعبير::انتظار) {
                نقطة_انتظار نقطة;
                نقطة.المعرف = معرف++;
                نقطة.رقم_السطر = تعبير->رقم_السطر;
                
                // إذا كان الانتظار جزءاً من تعيين
                // بيانات = انتظر جلب()
                if (auto أب = تعبير->الأبناء.empty() ? nullptr : تعبير->الأبناء[0]) {
                    نقطة.المتغير_الناتج = أب->المتغير_المُعيَّن;
                }
                
                نقاط.push_back(نقطة);
            }
        }
        
        return نقاط;
    }
    
    /**
     * حساب المتغيرات التي يمكن تحريرها
     */
    void حسب_التحرير(std::vector<نقطة_انتظار>& نقاط) {
        for (size_t i = 1; i < نقاط.size(); i++) {
            auto& نقطة_سابقة = نقاط[i - 1];
            auto& نقطة_حالية = نقاط[i];
            
            // المتغيرات التي كانت حية في السابقة لكن ميتة في الحالية
            for (const auto& م : نقطة_سابقة.المتغيرات_الحية_بعد) {
                if (نقطة_حالية.المتغيرات_الحية_قبل.find(م) == 
                    نقطة_حالية.المتغيرات_الحية_قبل.end()) {
                    نقطة_حالية.المتغيرات_للتحرير.insert(م);
                }
            }
        }
    }
    
    محلل_استخدام محلل_;
};

