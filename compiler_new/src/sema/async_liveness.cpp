/**
 * مُحسِّن حالة الآلة Async
 * 
 * يُنتج state machine أصغر بناءً على تحليل Liveness
 */
class محسن_حالة_async {
public:
    /**
     * معلومات الحالة المُحسَّنة
     */
    struct حالة_محسنة {
        int رقم_الحالة;
        std::vector<std::string> الحقول_المطلوبة;  // فقط المتغيرات الحية
        size_t الحجم_المُقدَّر;
    };
    
    /**
     * حساب الحالات المُحسَّنة
     */
    std::vector<حالة_محسنة> حسِّن(
        const std::vector<نقطة_انتظار>& نقاط,
        const std::unordered_map<std::string, size_t>& أحجام_المتغيرات
    ) {
        std::vector<حالة_محسنة> حالات;
        
        for (const auto& نقطة : نقاط) {
            حالة_محسنة حالة;
            حالة.رقم_الحالة = نقطة.المعرف;
            حالة.الحجم_المُقدَّر = 0;
            
            // فقط المتغيرات الحية تُخزَّن في الحالة
            for (const auto& م : نقطة.المتغيرات_الحية_بعد) {
                حالة.الحقول_المطلوبة.push_back(م);
                
                auto it = أحجام_المتغيرات.find(م);
                if (it != أحجام_المتغيرات.end()) {
                    حالة.الحجم_المُقدَّر += it->second;
                }
            }
            
            حالات.push_back(حالة);
        }
        
        return حالات;
    }
    
    /**
     * حساب التوفير في الذاكرة
     */
    size_t احسب_التوفير(
        const std::vector<نقطة_انتظار>& نقاط,
        const std::unordered_map<std::string, size_t>& أحجام_المتغيرات
    ) {
        size_t الحجم_الكامل = 0;
        size_t الحجم_المُحسَّن = 0;
        
        // الحجم الكامل = كل المتغيرات في كل حالة
        std::unordered_set<std::string> كل_المتغيرات;
        for (const auto& نقطة : نقاط) {
            كل_المتغيرات.insert(
                نقطة.المتغيرات_الحية_قبل.begin(),
                نقطة.المتغيرات_الحية_قبل.end()
            );
            كل_المتغيرات.insert(
                نقطة.المتغيرات_الحية_بعد.begin(),
                نقطة.المتغيرات_الحية_بعد.end()
            );
        }
        
        for (const auto& م : كل_المتغيرات) {
            auto it = أحجام_المتغيرات.find(م);
            if (it != أحجام_المتغيرات.end()) {
                الحجم_الكامل += it->second;
            }
        }
        
        // الحجم المُحسَّن = أكبر حالة
        for (const auto& نقطة : نقاط) {
            size_t حجم_حالة = 0;
            for (const auto& م : نقطة.المتغيرات_الحية_بعد) {
                auto it = أحجام_المتغيرات.find(م);
                if (it != أحجام_المتغيرات.end()) {
                    حجم_حالة += it->second;
                }
            }
            الحجم_المُحسَّن = std::max(الحجم_المُحسَّن, حجم_حالة);
        }
        
        return الحجم_الكامل > الحجم_المُحسَّن ? 
               الحجم_الكامل - الحجم_المُحسَّن : 0;
    }
};

