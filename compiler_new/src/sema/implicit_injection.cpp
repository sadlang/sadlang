/**
 * اكتشاف التبعيات الدائرية
 * 
 *     A → B → C → A  ← دورة!
 */
class كاشف_دورات {
public:
    كاشف_دورات(سجل_خدمات& سجل) : m_السجل(سجل) {}
    
    /**
     * هل توجد دورة؟
     */
    std::optional<std::vector<std::string>> ابحث_عن_دورة() {
        std::unordered_set<std::string> زائر;
        std::unordered_set<std::string> في_المسار;
        std::vector<std::string> المسار;
        
        for (const auto& خدمة : m_السجل.كل_الخدمات()) {
            if (زائر.count(خدمة) == 0) {
                auto دورة = dfs(خدمة, زائر, في_المسار, المسار);
                if (دورة.has_value()) {
                    return دورة;
                }
            }
        }
        
        return std::nullopt;
    }
    
private:
    سجل_خدمات& m_السجل;
    
    std::optional<std::vector<std::string>> dfs(
        const std::string& خدمة,
        std::unordered_set<std::string>& زائر,
        std::unordered_set<std::string>& في_المسار,
        std::vector<std::string>& المسار
    ) {
        زائر.insert(خدمة);
        في_المسار.insert(خدمة);
        المسار.push_back(خدمة);
        
        auto تسجيل = m_السجل.ابحث(خدمة);
        if (تسجيل.has_value()) {
            for (const auto& تبعية : تسجيل->التبعيات) {
                if (في_المسار.count(تبعية) > 0) {
                    // وجدنا دورة!
                    المسار.push_back(تبعية);
                    return المسار;
                }
                
                if (زائر.count(تبعية) == 0) {
                    auto دورة = dfs(تبعية, زائر, في_المسار, المسار);
                    if (دورة.has_value()) {
                        return دورة;
                    }
                }
            }
        }
        
        في_المسار.erase(خدمة);
        المسار.pop_back();
        return std::nullopt;
    }
};

