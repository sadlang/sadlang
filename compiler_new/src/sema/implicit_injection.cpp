/**
 * نطاق الخدمة
 */
enum class نطاق_خدمة {
    مفرد,       // Singleton: نسخة واحدة للتطبيق
    نطاقي,      // Scoped: نسخة واحدة لكل طلب/سياق
    عابر,       // Transient: نسخة جديدة لكل استخدام
};

/**
 * معلومات تسجيل خدمة
 */
struct تسجيل_خدمة {
    std::string اسم_السمة;           // السمة/الواجهة التي تُنفذها
    std::string اسم_التنفيذ;         // الصنف المُنفِّذ
    نطاق_خدمة النطاق;
    std::vector<std::string> التبعيات;  // خدمات تعتمد عليها
    
    // للتنفيذ الفعلي
    std::function<std::any()> المُنشئ;
};

/**
 * معلومات معامل ضمني
 */
struct معامل_ضمني {
    std::string الاسم;               // اسم المعامل في الدالة
    std::string اسم_النوع;           // نوع الواجهة المطلوبة
    bool اختياري = false;           // هل له قيمة افتراضية
};

// ═══════════════════════════════════════════════════════════════════════════════
