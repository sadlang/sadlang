/**
 * خطأ في الحقن
 */
struct خطأ_حقن {
    std::string الدالة;
    std::string المعامل;
    std::string السبب;
    
    std::string الرسالة() const {
        return "❌ خطأ حقن في " + الدالة + ":\n   المعامل '" + 
               المعامل + "': " + السبب;
    }
};

/**
 * نتيجة تحليل الحقن
 */
struct نتيجة_تحليل_حقن {
    bool نجح = true;
    std::vector<معامل_ضمني> المعاملات_الضمنية;
    std::vector<خطأ_حقن> الأخطاء;
};

/**
 * مُحلِّل الحقن الضمني
 * 
 * يُحلِّل توقيع الدالة ويُحدد ما يحتاج حقناً
 */
class محلل_حقن {
public:
    محلل_حقن(سجل_خدمات& سجل) : m_السجل(سجل) {}
    
    /**
     * تحليل دالة لاستخراج المعاملات الضمنية
     */
    نتيجة_تحليل_حقن حلِّل_دالة(
        const std::string& اسم_الدالة,
        const std::vector<std::pair<std::string, std::string>>& المعاملات  // (اسم, نوع)
    ) {
        نتيجة_تحليل_حقن نتيجة;
        
        for (const auto& [اسم, نوع] : المعاملات) {
            // هل المعامل مُعلَّم بـ "ضمني"؟
            if (نوع.find("ضمني") != std::string::npos) {
                معامل_ضمني م;
                م.الاسم = اسم;
                
                // استخرج النوع الفعلي
                م.اسم_النوع = استخرج_نوع(نوع);
                
                // تحقق من وجود خدمة مُسجَّلة
                if (!m_السجل.مُسجَّلة(م.اسم_النوع)) {
                    خطأ_حقن خ;
                    خ.الدالة = اسم_الدالة;
                    خ.المعامل = اسم;
                    خ.السبب = "لا توجد خدمة مُسجَّلة للنوع '" + م.اسم_النوع + "'";
                    نتيجة.الأخطاء.push_back(خ);
                    نتيجة.نجح = false;
                } else {
                    نتيجة.المعاملات_الضمنية.push_back(م);
                }
            }
        }
        
        return نتيجة;
    }
    
    /**
     * توليد كود الحقن لاستدعاء دالة
     */
    std::string ولِّد_كود_حقن(
        const std::string& اسم_الدالة,
        const std::vector<std::string>& المعاملات_الصريحة,
        const std::vector<معامل_ضمني>& المعاملات_الضمنية
    ) {
        std::stringstream كود;
        
        // أنشئ المعاملات الضمنية
        for (const auto& م : المعاملات_الضمنية) {
            auto خدمة = m_السجل.ابحث(م.اسم_النوع);
            if (خدمة.has_value()) {
                كود << "    دع __" << م.الاسم << " = ";
                
                switch (خدمة->النطاق) {
                    case نطاق_خدمة::مفرد:
                        كود << "حاوي_خدمات::المثال().احصل<" << م.اسم_النوع << ">();\n";
                        break;
                    case نطاق_خدمة::نطاقي:
                        كود << "سياق_حالي().احصل<" << م.اسم_النوع << ">();\n";
                        break;
                    case نطاق_خدمة::عابر:
                        كود << "أنشئ<" << خدمة->اسم_التنفيذ << ">();\n";
                        break;
                }
            }
        }
        
        // استدعِ الدالة
        كود << "    " << اسم_الدالة << "(";
        
        bool أول = true;
        for (const auto& م : المعاملات_الصريحة) {
            if (!أول) كود << ", ";
            كود << م;
            أول = false;
        }
        
        for (const auto& م : المعاملات_الضمنية) {
            if (!أول) كود << ", ";
            كود << "__" << م.الاسم;
            أول = false;
        }
        
        كود << ");\n";
        
        return كود.str();
    }
    
private:
    سجل_خدمات& m_السجل;
    
    /**
     * استخراج اسم النوع من تعريف "ضمني"
     */
    std::string استخرج_نوع(const std::string& تعريف) {
        // مثال: "ضمني قاعدة_بيانات" → "قاعدة_بيانات"
        size_t موضع = تعريف.find("ضمني");
        if (موضع != std::string::npos) {
            std::string بعد_ضمني = تعريف.substr(موضع + 8);  // طول "ضمني " بالـ UTF-8
            
            // قص المسافات
            size_t بداية = بعد_ضمني.find_first_not_of(" \t");
            size_t نهاية = بعد_ضمني.find_last_not_of(" \t");
            
            if (بداية != std::string::npos) {
                return بعد_ضمني.substr(بداية, نهاية - بداية + 1);
            }
        }
        return تعريف;
    }
};

