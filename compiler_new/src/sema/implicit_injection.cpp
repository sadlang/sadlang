/**
 * سجل الخدمات المُسجَّلة
 * 
 * يُبنى من التعليقات التوضيحية @خدمة
 */
class سجل_خدمات {
public:
    /**
     * تسجيل خدمة
     */
    void سجِّل(const تسجيل_خدمة& خدمة) {
        m_الخدمات[خدمة.اسم_السمة] = خدمة;
    }
    
    /**
     * هل الخدمة مُسجَّلة؟
     */
    bool مُسجَّلة(const std::string& اسم_السمة) const {
        return m_الخدمات.count(اسم_السمة) > 0;
    }
    
    /**
     * الحصول على تسجيل خدمة
     */
    std::optional<تسجيل_خدمة> ابحث(const std::string& اسم_السمة) const {
        auto it = m_الخدمات.find(اسم_السمة);
        if (it != m_الخدمات.end()) {
            return it->second;
        }
        return std::nullopt;
    }
    
    /**
     * قائمة كل الخدمات
     */
    std::vector<std::string> كل_الخدمات() const {
        std::vector<std::string> قائمة;
        for (const auto& [اسم, _] : m_الخدمات) {
            قائمة.push_back(اسم);
        }
        return قائمة;
    }
    
private:
    std::unordered_map<std::string, تسجيل_خدمة> m_الخدمات;
};

// ═══════════════════════════════════════════════════════════════════════════════
