/**
 * مُدقق الأذونات وقت الترجمة
 * 
 * للمبتدئ: هذه الفئة تفحص الكود وتتأكد أنه لا يتجاوز الأذونات
 * 
 * مثال:
 * ```cpp
 * مدقق_أذونات مدقق(بيان_الأذونات);
 * مدقق.افحص(شجرة_AST);
 * 
 * if (مدقق.يوجد_انتهاكات()) {
 *     for (const auto& انتهاك : مدقق.الانتهاكات()) {
 *         std::cerr << انتهاك.رسالة_خطأ();
 *     }
 * }
 * ```
 */
class مدقق_أذونات {
public:
    /**
     * إنشاء مدقق مع بيان أذونات
     */
    explicit مدقق_أذونات(const permissions::بيان_أذونات& بيان)
        : m_بيان(بيان)
        , m_قواعد(جدول_قواعد_فحص::الافتراضي()) {}
    
    /**
     * فحص استدعاء دالة
     */
    std::optional<انتهاك_إذن> افحص_استدعاء(
        const std::string& اسم_الدالة,
        const std::vector<std::string>& المعاملات,
        موقع_كود الموقع) {
        
        // البحث عن قاعدة
        const قاعدة_فحص_دالة* قاعدة = m_قواعد.ابحث(اسم_الدالة);
        if (!قاعدة) return std::nullopt;  // لا تحتاج فحص
        
        // استخراج الهدف
        std::string هدف;
        if (قاعدة->رقم_معامل_الهدف >= 0 && 
            قاعدة->رقم_معامل_الهدف < static_cast<int>(المعاملات.size())) {
            هدف = المعاملات[قاعدة->رقم_معامل_الهدف];
        }
        
        // فحص الإذن
        bool مسموح = m_بيان.مسموح(قاعدة->الفئة_المطلوبة, هدف, قاعدة->العملية);
        
        if (!مسموح) {
            انتهاك_إذن انتهاك;
            انتهاك.النوع = فئة_إلى_نوع_انتهاك(قاعدة->الفئة_المطلوبة);
            انتهاك.الموقع = الموقع;
            انتهاك.الوصف = قاعدة->وصف;
            انتهاك.الكود = بناء_نص_استدعاء(اسم_الدالة, المعاملات);
            انتهاك.الهدف = هدف;
            انتهاك.الحل_المقترح = اقترح_حل(قاعدة->الفئة_المطلوبة, هدف, قاعدة->العملية);
            
            m_انتهاكات.push_back(انتهاك);
            return انتهاك;
        }
        
        return std::nullopt;
    }
    
    /**
     * فحص FFI
     */
    std::optional<انتهاك_إذن> افحص_ffi(
        const std::string& اسم_الدالة,
        const std::string& المكتبة,
        موقع_كود الموقع) {
        
        // FFI يحتاج إذن خاص
        // يمكن إضافة فحص أكثر تعقيداً هنا
        
        return std::nullopt;  // مسموح مبدئياً (يُفحص بالجدار الناري)
    }
    
    /**
     * هل يوجد انتهاكات؟
     */
    bool يوجد_انتهاكات() const {
        return !m_انتهاكات.empty();
    }
    
    /**
     * عدد الانتهاكات
     */
    size_t عدد_الانتهاكات() const {
        return m_انتهاكات.size();
    }
    
    /**
     * الحصول على الانتهاكات
     */
    const std::vector<انتهاك_إذن>& الانتهاكات() const {
        return m_انتهاكات;
    }
    
    /**
     * مسح الانتهاكات
     */
    void امسح() {
        m_انتهاكات.clear();
    }
    
    /**
     * تقرير كامل
     */
    std::string تقرير() const {
        if (m_انتهاكات.empty()) {
            return "✅ لا توجد انتهاكات أذونات";
        }
        
        std::stringstream ss;
        ss << "❌ تم اكتشاف " << m_انتهاكات.size() << " انتهاك(ات) أذونات:\n\n";
        
        for (size_t i = 0; i < m_انتهاكات.size(); i++) {
            ss << "[" << (i + 1) << "] " << m_انتهاكات[i].رسالة_خطأ() << "\n";
        }
        
        return ss.str();
    }
    
private:
    const permissions::بيان_أذونات& m_بيان;
    جدول_قواعد_فحص m_قواعد;
    std::vector<انتهاك_إذن> m_انتهاكات;
    
    /**
     * تحويل فئة إذن إلى نوع انتهاك
     */
    نوع_انتهاك فئة_إلى_نوع_انتهاك(permissions::فئة_إذن فئة) {
        switch (فئة) {
            case permissions::فئة_إذن::ملفات: return نوع_انتهاك::ملف_غير_مسموح;
            case permissions::فئة_إذن::شبكة: return نوع_انتهاك::شبكة_غير_مسموحة;
            case permissions::فئة_إذن::نظام: return نوع_انتهاك::نظام_غير_مسموح;
            case permissions::فئة_إذن::كاميرا: return نوع_انتهاك::كاميرا_غير_مسموحة;
            case permissions::فئة_إذن::ميكروفون: return نوع_انتهاك::ميكروفون_غير_مسموح;
            case permissions::فئة_إذن::موقع: return نوع_انتهاك::موقع_غير_مسموح;
            case permissions::فئة_إذن::عملية: return نوع_انتهاك::عملية_غير_مسموحة;
            default: return نوع_انتهاك::نظام_غير_مسموح;
        }
    }
    
    /**
     * بناء نص استدعاء دالة
     */
    std::string بناء_نص_استدعاء(
        const std::string& اسم,
        const std::vector<std::string>& المعاملات) {
        
        std::stringstream ss;
        ss << اسم << "(";
        for (size_t i = 0; i < المعاملات.size(); i++) {
            if (i > 0) ss << ", ";
            ss << "\"" << المعاملات[i] << "\"";
        }
        ss << ")";
        return ss.str();
    }
    
    /**
     * اقتراح حل
     */
    std::string اقترح_حل(
        permissions::فئة_إذن فئة,
        const std::string& هدف,
        permissions::نوع_عملية عملية) {
        
        std::stringstream ss;
        ss << "أضف إلى ص.toml:\n";
        ss << "[أذونات]\n";
        
        std::string اسم_فئة;
        switch (فئة) {
            case permissions::فئة_إذن::ملفات: اسم_فئة = "ملفات"; break;
            case permissions::فئة_إذن::شبكة: اسم_فئة = "شبكة"; break;
            case permissions::فئة_إذن::نظام: اسم_فئة = "نظام"; break;
            case permissions::فئة_إذن::كاميرا: اسم_فئة = "كاميرا"; break;
            case permissions::فئة_إذن::ميكروفون: اسم_فئة = "ميكروفون"; break;
            case permissions::فئة_إذن::موقع: اسم_فئة = "موقع"; break;
            case permissions::فئة_إذن::عملية: اسم_فئة = "عملية"; break;
            default: اسم_فئة = "غير_معروف";
        }
        
        if (هدف.empty()) {
            ss << اسم_فئة << " = صحيح";
        } else {
            std::string عملية_نص;
            switch (عملية) {
                case permissions::نوع_عملية::قراءة: عملية_نص = "قراءة"; break;
                case permissions::نوع_عملية::كتابة: عملية_نص = "كتابة"; break;
                default: عملية_نص = "";
            }
            
            if (عملية_نص.empty()) {
                ss << اسم_فئة << " = [\"" << هدف << "\"]";
            } else {
                ss << اسم_فئة << " = [\"" << عملية_نص << ":" << هدف << "\"]";
            }
        }
        
        return ss.str();
    }
};

