/**
 * نوع انتهاك الإذن
 */
enum class نوع_انتهاك {
    ملف_غير_مسموح,       // محاولة الوصول لملف
    شبكة_غير_مسموحة,     // محاولة الاتصال بالشبكة
    نظام_غير_مسموح,      // محاولة تنفيذ أمر نظام
    كاميرا_غير_مسموحة,   // محاولة استخدام الكاميرا
    ميكروفون_غير_مسموح,  // محاولة استخدام الميكروفون
    موقع_غير_مسموح,      // محاولة الحصول على الموقع
    عملية_غير_مسموحة,    // محاولة إنشاء عملية فرعية
    ffi_غير_مسموح,       // محاولة استدعاء FFI بدون إذن
};

/**
 * تحويل نوع انتهاك إلى نص
 */
inline std::string نوع_انتهاك_إلى_نص(نوع_انتهاك نوع) {
    switch (نوع) {
        case نوع_انتهاك::ملف_غير_مسموح: return "وصول لملف غير مسموح";
        case نوع_انتهاك::شبكة_غير_مسموحة: return "اتصال بشبكة غير مسموح";
        case نوع_انتهاك::نظام_غير_مسموح: return "أمر نظام غير مسموح";
        case نوع_انتهاك::كاميرا_غير_مسموحة: return "استخدام كاميرا غير مسموح";
        case نوع_انتهاك::ميكروفون_غير_مسموح: return "استخدام ميكروفون غير مسموح";
        case نوع_انتهاك::موقع_غير_مسموح: return "الحصول على موقع غير مسموح";
        case نوع_انتهاك::عملية_غير_مسموحة: return "إنشاء عملية غير مسموح";
        case نوع_انتهاك::ffi_غير_مسموح: return "استدعاء FFI غير مسموح";
        default: return "انتهاك غير معروف";
    }
}

