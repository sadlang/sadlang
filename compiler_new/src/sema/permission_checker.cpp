/**
 * موقع في الكود المصدري
 */
struct موقع_كود {
    std::string الملف;
    int السطر = 0;
    int العمود = 0;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << الملف << ":" << السطر << ":" << العمود;
        return ss.str();
    }
};

/**
 * سجل انتهاك إذن
 */
struct انتهاك_إذن {
    نوع_انتهاك النوع;
    موقع_كود الموقع;
    std::string الوصف;
    std::string الكود;           // الكود المُنتهِك
    std::string الهدف;           // الملف/URL/الأمر المطلوب
    std::string الحل_المقترح;
    
    /**
     * رسالة الخطأ الكاملة
     */
    std::string رسالة_خطأ() const {
        std::stringstream ss;
        ss << "❌ خطأ أذونات [" << الموقع.إلى_نص() << "]\n"
           << "   " << نوع_انتهاك_إلى_نص(النوع) << "\n"
           << "   الكود: " << الكود << "\n"
           << "   الهدف: " << الهدف << "\n";
        
        if (!الحل_المقترح.empty()) {
            ss << "\n   💡 الحل: " << الحل_المقترح << "\n";
        }
        
        return ss.str();
    }
};

