/**
 * عقدة في رسم التبعيات
 */
struct عقدة_تبعية {
    std::string الاسم;
    std::vector<std::string> يعتمد_على;    // تبعيات مباشرة
    std::vector<std::string> يعتمد_عليه;   // من يعتمد عليّ
};

/**
 * رسم التبعيات
 */
class رسم_تبعيات {
public:
    /**
     * إضافة عقدة
     */
    void أضف(const std::string& اسم, const std::vector<std::string>& تبعيات) {
        عقدة_تبعية عقدة;
        عقدة.الاسم = اسم;
        عقدة.يعتمد_على = تبعيات;
        
        m_العقد[اسم] = عقدة;
        
        // حدِّث الرسم العكسي
        for (const auto& تبعية : تبعيات) {
            m_العقد[تبعية].يعتمد_عليه.push_back(اسم);
        }
    }
    
    /**
     * الحصول على تبعيات عقدة
     */
    std::vector<std::string> التبعيات(const std::string& اسم) const {
        auto it = m_العقد.find(اسم);
        if (it != m_العقد.end()) {
            return it->second.يعتمد_على;
        }
        return {};
    }
    
    /**
     * من يعتمد على هذه العقدة؟
     */
    std::vector<std::string> المعتمدون(const std::string& اسم) const {
        auto it = m_العقد.find(اسم);
        if (it != m_العقد.end()) {
            return it->second.يعتمد_عليه;
        }
        return {};
    }
    
    /**
     * كل العقد
     */
    std::vector<std::string> كل_العقد() const {
        std::vector<std::string> قائمة;
        for (const auto& [اسم, _] : m_العقد) {
            قائمة.push_back(اسم);
        }
        return قائمة;
    }
    
private:
    std::unordered_map<std::string, عقدة_تبعية> m_العقد;
};

