/**
 * نتيجة حل التبعيات
 */
struct نتيجة_حل {
    bool نجح = true;
    std::vector<std::string> الترتيب;      // الترتيب الصحيح للإنشاء
    std::optional<std::vector<std::string>> دورة;  // إذا وُجدت دورة
    std::vector<std::string> مفقودة;       // تبعيات غير موجودة
};

/**
 * حال التبعيات
 * 
 * يستخدم خوارزمية Kahn للترتيب الطوبولوجي
 */
class حال_تبعيات {
public:
    /**
     * حل التبعيات لخدمة معينة
     * 
     * يُرجع قائمة بالترتيب الصحيح لإنشاء الخدمات
     */
    نتيجة_حل حُل(const رسم_تبعيات& رسم, const std::string& هدف) {
        نتيجة_حل نتيجة;
        
        // اجمع كل التبعيات (مباشرة وغير مباشرة)
        std::unordered_set<std::string> كل_التبعيات;
        اجمع_التبعيات(رسم, هدف, كل_التبعيات);
        كل_التبعيات.insert(هدف);
        
        // أنشئ رسماً فرعياً
        std::unordered_map<std::string, int> درجة_الدخول;
        for (const auto& عقدة : كل_التبعيات) {
            درجة_الدخول[عقدة] = 0;
        }
        
        for (const auto& عقدة : كل_التبعيات) {
            for (const auto& تبعية : رسم.التبعيات(عقدة)) {
                if (كل_التبعيات.count(تبعية) > 0) {
                    درجة_الدخول[عقدة]++;
                } else {
                    // تبعية مفقودة
                    نتيجة.مفقودة.push_back(تبعية);
                }
            }
        }
        
        if (!نتيجة.مفقودة.empty()) {
            نتيجة.نجح = false;
            return نتيجة;
        }
        
        // خوارزمية Kahn
        std::queue<std::string> صفر_تبعيات;
        for (const auto& [عقدة, درجة] : درجة_الدخول) {
            if (درجة == 0) {
                صفر_تبعيات.push(عقدة);
            }
        }
        
        while (!صفر_تبعيات.empty()) {
            std::string حالي = صفر_تبعيات.front();
            صفر_تبعيات.pop();
            نتيجة.الترتيب.push_back(حالي);
            
            // قلِّل درجة دخول المعتمدين
            for (const auto& معتمد : رسم.المعتمدون(حالي)) {
                if (كل_التبعيات.count(معتمد) > 0) {
                    درجة_الدخول[معتمد]--;
                    if (درجة_الدخول[معتمد] == 0) {
                        صفر_تبعيات.push(معتمد);
                    }
                }
            }
        }
        
        // تحقق من وجود دورة
        if (نتيجة.الترتيب.size() != كل_التبعيات.size()) {
            نتيجة.نجح = false;
            نتيجة.دورة = ابحث_عن_دورة(رسم, كل_التبعيات);
        }
        
        return نتيجة;
    }
    
    /**
     * حل كل التبعيات في الرسم
     */
    نتيجة_حل حُل_الكل(const رسم_تبعيات& رسم) {
        نتيجة_حل نتيجة;
        
        std::unordered_map<std::string, int> درجة_الدخول;
        auto كل_العقد = رسم.كل_العقد();
        
        for (const auto& عقدة : كل_العقد) {
            درجة_الدخول[عقدة] = static_cast<int>(رسم.التبعيات(عقدة).size());
        }
        
        std::queue<std::string> صفر_تبعيات;
        for (const auto& [عقدة, درجة] : درجة_الدخول) {
            if (درجة == 0) {
                صفر_تبعيات.push(عقدة);
            }
        }
        
        while (!صفر_تبعيات.empty()) {
            std::string حالي = صفر_تبعيات.front();
            صفر_تبعيات.pop();
            نتيجة.الترتيب.push_back(حالي);
            
            for (const auto& معتمد : رسم.المعتمدون(حالي)) {
                درجة_الدخول[معتمد]--;
                if (درجة_الدخول[معتمد] == 0) {
                    صفر_تبعيات.push(معتمد);
                }
            }
        }
        
        if (نتيجة.الترتيب.size() != كل_العقد.size()) {
            نتيجة.نجح = false;
            std::unordered_set<std::string> مجموعة(كل_العقد.begin(), كل_العقد.end());
            نتيجة.دورة = ابحث_عن_دورة(رسم, مجموعة);
        }
        
        return نتيجة;
    }
    
private:
    /**
     * جمع كل التبعيات (تكرارياً)
     */
    void اجمع_التبعيات(
        const رسم_تبعيات& رسم,
        const std::string& عقدة,
        std::unordered_set<std::string>& النتيجة
    ) {
        for (const auto& تبعية : رسم.التبعيات(عقدة)) {
            if (النتيجة.count(تبعية) == 0) {
                النتيجة.insert(تبعية);
                اجمع_التبعيات(رسم, تبعية, النتيجة);
            }
        }
    }
    
    /**
     * البحث عن دورة
     */
    std::optional<std::vector<std::string>> ابحث_عن_دورة(
        const رسم_تبعيات& رسم,
        const std::unordered_set<std::string>& العقد
    ) {
        std::unordered_set<std::string> زائر;
        std::unordered_set<std::string> في_المسار;
        std::vector<std::string> المسار;
        
        for (const auto& عقدة : العقد) {
            if (زائر.count(عقدة) == 0) {
                auto دورة = dfs_دورة(رسم, عقدة, العقد, زائر, في_المسار, المسار);
                if (دورة.has_value()) {
                    return دورة;
                }
            }
        }
        
        return std::nullopt;
    }
    
    std::optional<std::vector<std::string>> dfs_دورة(
        const رسم_تبعيات& رسم,
        const std::string& عقدة,
        const std::unordered_set<std::string>& العقد,
        std::unordered_set<std::string>& زائر,
        std::unordered_set<std::string>& في_المسار,
        std::vector<std::string>& المسار
    ) {
        زائر.insert(عقدة);
        في_المسار.insert(عقدة);
        المسار.push_back(عقدة);
        
        for (const auto& تبعية : رسم.التبعيات(عقدة)) {
            if (العقد.count(تبعية) == 0) continue;
            
            if (في_المسار.count(تبعية) > 0) {
                المسار.push_back(تبعية);
                return المسار;
            }
            
            if (زائر.count(تبعية) == 0) {
                auto دورة = dfs_دورة(رسم, تبعية, العقد, زائر, في_المسار, المسار);
                if (دورة.has_value()) {
                    return دورة;
                }
            }
        }
        
        في_المسار.erase(عقدة);
        المسار.pop_back();
        return std::nullopt;
    }
};

