/**
 * مولد كود إنشاء الخدمات
 */
class مولد_كود_إنشاء {
public:
    /**
     * توليد كود إنشاء خدمة
     */
    std::string ولِّد(
        const std::string& اسم_الخدمة,
        const std::vector<std::string>& ترتيب_التبعيات
    ) {
        std::stringstream كود;
        
        كود << "// كود إنشاء " << اسم_الخدمة << " (مُولَّد تلقائياً)\n\n";
        
        // أنشئ كل تبعية بالترتيب
        for (const auto& تبعية : ترتيب_التبعيات) {
            كود << "// إنشاء " << تبعية << "\n";
            كود << "دع _" << تبعية << " = حاوي::أنشئ<" << تبعية << ">();\n";
        }
        
        كود << "\n// إرجاع الخدمة المطلوبة\n";
        كود << "أرجع _" << اسم_الخدمة << ";\n";
        
        return كود.str();
    }
};

