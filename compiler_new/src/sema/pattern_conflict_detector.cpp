/**
 * نوع التعارض
 */
enum class نوع_تعارض {
    تداخل_جزئي,      // الأنماط تتداخل جزئياً
    احتواء_كامل,     // نمط يحتوي آخر بالكامل
    تكرار,           // نفس النمط مكرر
    غير_قابل_للوصول, // نمط لن يُصل إليه أبداً
};

/**
 * معلومات التعارض
 */
struct تعارض_أنماط {
    نوع_تعارض النوع;
    
    // النمطان المتعارضان
    نمط النمط_الأول;
    نمط النمط_الثاني;
    
    // تفاصيل
    std::optional<نطاق_قيم<int64_t>> منطقة_التداخل;
    
    /**
     * رسالة التحذير
     */
    std::string الرسالة() const {
        std::stringstream ss;
        
        switch (النوع) {
            case نوع_تعارض::تداخل_جزئي:
                ss << "⚠️ تداخل الأنماط: ";
                ss << "'" << النمط_الأول.إلى_نص() << "' (سطر " << النمط_الأول.السطر << ")";
                ss << " و '" << النمط_الثاني.إلى_نص() << "' (سطر " << النمط_الثاني.السطر << ")";
                if (منطقة_التداخل.has_value()) {
                    ss << " يتداخلان في " << منطقة_التداخل->إلى_نص();
                }
                break;
                
            case نوع_تعارض::احتواء_كامل:
                ss << "⚠️ نمط محتوى: ";
                ss << "'" << النمط_الثاني.إلى_نص() << "' (سطر " << النمط_الثاني.السطر << ")";
                ss << " محتوى بالكامل في '" << النمط_الأول.إلى_نص() << "' (سطر " << النمط_الأول.السطر << ")";
                break;
                
            case نوع_تعارض::تكرار:
                ss << "⚠️ نمط مكرر: ";
                ss << "'" << النمط_الأول.إلى_نص() << "'";
                ss << " في سطر " << النمط_الأول.السطر << " و " << النمط_الثاني.السطر;
                break;
                
            case نوع_تعارض::غير_قابل_للوصول:
                ss << "⚠️ نمط لن يُصل إليه: ";
                ss << "'" << النمط_الثاني.إلى_نص() << "' (سطر " << النمط_الثاني.السطر << ")";
                ss << " بسبب '" << النمط_الأول.إلى_نص() << "' (سطر " << النمط_الأول.السطر << ")";
                break;
        }
        
        return ss.str();
    }
    
    /**
     * خطورة التعارض
     */
    enum class مستوى_خطورة { تحذير, خطأ };
    
    مستوى_خطورة الخطورة() const {
        switch (النوع) {
            case نوع_تعارض::تكرار:
            case نوع_تعارض::غير_قابل_للوصول:
                return مستوى_خطورة::خطأ;
            default:
                return مستوى_خطورة::تحذير;
        }
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              كاشف التعارضات
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * كاشف تعارض الأنماط
 */
class كاشف_تعارض_أنماط {
public:
    /**
     * فحص قائمة أنماط للتعارضات
     */
    std::vector<تعارض_أنماط> افحص(const std::vector<نمط>& الأنماط) {
        std::vector<تعارض_أنماط> التعارضات;
        
        // فحص كل زوج
        for (size_t i = 0; i < الأنماط.size(); i++) {
            for (size_t j = i + 1; j < الأنماط.size(); j++) {
                auto تعارض = افحص_زوج(الأنماط[i], الأنماط[j]);
                if (تعارض.has_value()) {
                    التعارضات.push_back(*تعارض);
                }
            }
        }
        
        // فحص الأنماط غير القابلة للوصول
        bool وجد_مُهمل = false;
        int سطر_مُهمل = 0;
        
        for (size_t i = 0; i < الأنماط.size(); i++) {
            if (الأنماط[i].النوع == نوع_نمط::مُهمل) {
                if (وجد_مُهمل) {
                    // تكرار _
                    تعارض_أنماط ت;
                    ت.النوع = نوع_تعارض::تكرار;
                    ت.النمط_الأول = الأنماط[i];
                    ت.النمط_الأول.السطر = سطر_مُهمل;
                    ت.النمط_الثاني = الأنماط[i];
                    التعارضات.push_back(ت);
                }
                
                وجد_مُهمل = true;
                سطر_مُهمل = الأنماط[i].السطر;
                
                // أي نمط بعد _ لا يمكن الوصول إليه
                for (size_t j = i + 1; j < الأنماط.size(); j++) {
                    تعارض_أنماط ت;
                    ت.النوع = نوع_تعارض::غير_قابل_للوصول;
                    ت.النمط_الأول = الأنماط[i];
                    ت.النمط_الثاني = الأنماط[j];
                    التعارضات.push_back(ت);
                }
                
                break;  // لا داعي للاستمرار
            }
        }
        
        return التعارضات;
    }
    
    /**
     * فحص زوج من الأنماط
     */
    std::optional<تعارض_أنماط> افحص_زوج(const نمط& أ, const نمط& ب) {
        // مُهمل مع أي شيء = تعارض
        if (أ.النوع == نوع_نمط::مُهمل || ب.النوع == نوع_نمط::مُهمل) {
            return std::nullopt;  // يُعالج منفصلاً
        }
        
        // قيمة مع قيمة
        if (أ.النوع == نوع_نمط::قيمة_محددة && ب.النوع == نوع_نمط::قيمة_محددة) {
            if (std::get<int64_t>(أ.البيانات) == std::get<int64_t>(ب.البيانات)) {
                تعارض_أنماط ت;
                ت.النوع = نوع_تعارض::تكرار;
                ت.النمط_الأول = أ;
                ت.النمط_الثاني = ب;
                return ت;
            }
            return std::nullopt;
        }
        
        // نطاق مع نطاق
        if (أ.النوع == نوع_نمط::نطاق && ب.النوع == نوع_نمط::نطاق) {
            const auto& نطاق_أ = std::get<نطاق_قيم<int64_t>>(أ.البيانات);
            const auto& نطاق_ب = std::get<نطاق_قيم<int64_t>>(ب.البيانات);
            
            if (نطاق_أ.يتداخل_مع(نطاق_ب)) {
                تعارض_أنماط ت;
                
                if (نطاق_أ.يحتوي(نطاق_ب)) {
                    ت.النوع = نوع_تعارض::احتواء_كامل;
                } else if (نطاق_ب.يحتوي(نطاق_أ)) {
                    ت.النوع = نوع_تعارض::احتواء_كامل;
                    // بدِّل الترتيب
                    ت.النمط_الأول = ب;
                    ت.النمط_الثاني = أ;
                    ت.منطقة_التداخل = نطاق_أ.التداخل(نطاق_ب);
                    return ت;
                } else {
                    ت.النوع = نوع_تعارض::تداخل_جزئي;
                }
                
                ت.النمط_الأول = أ;
                ت.النمط_الثاني = ب;
                ت.منطقة_التداخل = نطاق_أ.التداخل(نطاق_ب);
                return ت;
            }
            return std::nullopt;
        }
        
        // قيمة مع نطاق
        if ((أ.النوع == نوع_نمط::قيمة_محددة && ب.النوع == نوع_نمط::نطاق) ||
            (أ.النوع == نوع_نمط::نطاق && ب.النوع == نوع_نمط::قيمة_محددة)) {
            
            const نمط& نمط_قيمة = (أ.النوع == نوع_نمط::قيمة_محددة) ? أ : ب;
            const نمط& نمط_نطاق = (أ.النوع == نوع_نمط::نطاق) ? أ : ب;
            
            int64_t القيمة = std::get<int64_t>(نمط_قيمة.البيانات);
            const auto& النطاق = std::get<نطاق_قيم<int64_t>>(نمط_نطاق.البيانات);
            
            int64_t نهاية_فعلية = النطاق.شامل_النهاية ? النطاق.النهاية : النطاق.النهاية - 1;
            
            if (القيمة >= النطاق.البداية && القيمة <= نهاية_فعلية) {
                تعارض_أنماط ت;
                ت.النوع = نوع_تعارض::احتواء_كامل;
                ت.النمط_الأول = نمط_نطاق;
                ت.النمط_الثاني = نمط_قيمة;
                return ت;
            }
            return std::nullopt;
        }
        
        return std::nullopt;
    }
    
    /**
     * هل يوجد أي تعارض؟
     */
    bool يوجد_تعارضات(const std::vector<نمط>& الأنماط) {
        return !افحص(الأنماط).empty();
    }
    
    /**
     * عدد التعارضات
     */
    size_t عدد_التعارضات(const std::vector<نمط>& الأنماط) {
        return افحص(الأنماط).size();
    }
};

