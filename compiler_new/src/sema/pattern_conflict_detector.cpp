/**
 * نوع النمط
 */
enum class نوع_نمط {
    قيمة_محددة,     // حالة 5:
    نطاق,          // حالة 1..10:
    بديل,          // حالة 1 | 2 | 3:
    حارس,          // حالة n إذا n > 0:
    مُهمل,          // حالة _:
    بنية,          // حالة نقطة(س, ص):
    قائمة,         // حالة [أول, ..باقي]:
};

/**
 * نطاق قيم (Range)
 */
template<typename T>
struct نطاق_قيم {
    T البداية;
    T النهاية;
    bool شامل_النهاية = true;  // true: 1..=10, false: 1..10
    
    /**
     * هل يتداخل مع نطاق آخر؟
     */
    bool يتداخل_مع(const نطاق_قيم& آخر) const {
        T نهاية_فعلية = شامل_النهاية ? النهاية : النهاية - 1;
        T نهاية_آخر_فعلية = آخر.شامل_النهاية ? آخر.النهاية : آخر.النهاية - 1;
        
        return البداية <= نهاية_آخر_فعلية && آخر.البداية <= نهاية_فعلية;
    }
    
    /**
     * هل يحتوي على نطاق آخر؟
     */
    bool يحتوي(const نطاق_قيم& آخر) const {
        T نهاية_فعلية = شامل_النهاية ? النهاية : النهاية - 1;
        T نهاية_آخر_فعلية = آخر.شامل_النهاية ? آخر.النهاية : آخر.النهاية - 1;
        
        return البداية <= آخر.البداية && نهاية_فعلية >= نهاية_آخر_فعلية;
    }
    
    /**
     * الجزء المتداخل
     */
    std::optional<نطاق_قيم> التداخل(const نطاق_قيم& آخر) const {
        if (!يتداخل_مع(آخر)) {
            return std::nullopt;
        }
        
        نطاق_قيم تداخل;
        تداخل.البداية = std::max(البداية, آخر.البداية);
        
        T نهاية_فعلية = شامل_النهاية ? النهاية : النهاية - 1;
        T نهاية_آخر_فعلية = آخر.شامل_النهاية ? آخر.النهاية : آخر.النهاية - 1;
        
        تداخل.النهاية = std::min(نهاية_فعلية, نهاية_آخر_فعلية);
        تداخل.شامل_النهاية = true;
        
        return تداخل;
    }
    
    /**
     * تحويل إلى نص للعرض
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << البداية << ".." << (شامل_النهاية ? "=" : "") << النهاية;
        return ss.str();
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              النمط (Pattern)
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * نمط في Pattern Matching
 */
class نمط {
public:
    نوع_نمط النوع;
    
    // بيانات حسب النوع
    std::variant<
        int64_t,                          // قيمة محددة
        نطاق_قيم<int64_t>,                // نطاق
        std::vector<نمط>,                 // بديل أو بنية
        std::string                       // اسم متغير أو حارس
    > البيانات;
    
    // موقع في الكود
    std::string الملف;
    int السطر = 0;
    int العمود = 0;
    
    /**
     * إنشاء نمط قيمة محددة
     */
    static نمط قيمة(int64_t ق, int سطر = 0) {
        نمط ن;
        ن.النوع = نوع_نمط::قيمة_محددة;
        ن.البيانات = ق;
        ن.السطر = سطر;
        return ن;
    }
    
    /**
     * إنشاء نمط نطاق
     */
    static نمط نطاق(int64_t من, int64_t إلى, bool شامل = true, int سطر = 0) {
        نمط ن;
        ن.النوع = نوع_نمط::نطاق;
        ن.البيانات = نطاق_قيم<int64_t>{من, إلى, شامل};
        ن.السطر = سطر;
        return ن;
    }
    
    /**
     * إنشاء نمط مُهمل (_)
     */
    static نمط مُهمل(int سطر = 0) {
        نمط ن;
        ن.النوع = نوع_نمط::مُهمل;
        ن.السطر = سطر;
        return ن;
    }
    
    /**
     * تحويل إلى نص
     */
    std::string إلى_نص() const {
        switch (النوع) {
            case نوع_نمط::قيمة_محددة:
                return std::to_string(std::get<int64_t>(البيانات));
                
            case نوع_نمط::نطاق:
                return std::get<نطاق_قيم<int64_t>>(البيانات).إلى_نص();
                
            case نوع_نمط::مُهمل:
                return "_";
                
            case نوع_نمط::بديل: {
                std::string نتيجة;
                const auto& أنماط = std::get<std::vector<نمط>>(البيانات);
                for (size_t i = 0; i < أنماط.size(); i++) {
                    if (i > 0) نتيجة += " | ";
                    نتيجة += أنماط[i].إلى_نص();
                }
                return نتيجة;
            }
            
            default:
                return "?";
        }
    }
};

