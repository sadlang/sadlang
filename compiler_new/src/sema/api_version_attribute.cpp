/**
 * حالة الإهمال
 */
enum class حالة_إهمال {
    نشط,           // يعمل بشكل طبيعي
    مُهمَل,         // سيُزال في المستقبل
    منتهي_الصلاحية  // لم يعد يعمل
};

/**
 * سمة @api للواجهات
 */
struct سمة_api {
    // معلومات الإصدار
    رقم_إصدار الإصدار;
    std::string تاريخ_البداية;
    std::optional<std::string> تاريخ_الإهمال;
    std::optional<std::string> تاريخ_الإزالة;
    
    // معلومات الإهمال
    حالة_إهمال الحالة = حالة_إهمال::نشط;
    std::string رسالة_إهمال;
    std::string البديل;  // الدالة/الواجهة البديلة
    
    // توثيق التغييرات
    std::string وصف_التغيير;
    std::vector<std::string> الميزات_الجديدة;
    std::vector<std::string> التغييرات_الكسرية;
    
    // التوافق
    std::optional<نطاق_إصدار> نطاق_التوافق;
};

