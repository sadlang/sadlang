/**
 * محلل سمة @api
 */
class محلل_سمة_api {
public:
    /**
     * تحليل سمة @api من نص
     * 
     * أمثلة:
     * - @api(إصدار = "1.0")
     * - @api(إصدار = "2.0", بداية = "2024-01-01")
     * - @api(إصدار = "1.5", مُهمَل, بديل = "دالة_جديدة")
     */
    std::optional<سمة_api> حلل(const std::string& نص) {
        سمة_api سمة;
        
        // استخراج المعاملات
        std::regex نمط_معامل(R"((\w+)\s*=\s*\"([^\"]*)\")");
        std::sregex_iterator it(نص.begin(), نص.end(), نمط_معامل);
        std::sregex_iterator end;
        
        while (it != end) {
            std::string اسم = (*it)[1];
            std::string قيمة = (*it)[2];
            
            if (اسم == "إصدار" || اسم == "version") {
                auto إصدار = رقم_إصدار::حلل(قيمة);
                if (إصدار) {
                    سمة.الإصدار = *إصدار;
                }
            }
            else if (اسم == "بداية" || اسم == "since") {
                سمة.تاريخ_البداية = قيمة;
            }
            else if (اسم == "إهمال" || اسم == "deprecated") {
                سمة.تاريخ_الإهمال = قيمة;
                سمة.الحالة = حالة_إهمال::مُهمَل;
            }
            else if (اسم == "إزالة" || اسم == "removal") {
                سمة.تاريخ_الإزالة = قيمة;
            }
            else if (اسم == "بديل" || اسم == "replacement") {
                سمة.البديل = قيمة;
            }
            else if (اسم == "رسالة" || اسم == "message") {
                سمة.رسالة_إهمال = قيمة;
            }
            
            ++it;
        }
        
        // تحقق من وجود "مُهمَل" كعلم
        if (نص.find("مُهمَل") != std::string::npos ||
            نص.find("deprecated") != std::string::npos) {
            سمة.الحالة = حالة_إهمال::مُهمَل;
        }
        
        return سمة;
    }
};

