/**
 * مدير إصدارات API
 */
class مدير_إصدارات {
public:
    static مدير_إصدارات& المثيل() {
        static مدير_إصدارات مثيل;
        return مثيل;
    }
    
    /**
     * تسجيل واجهة جديدة
     */
    void سجل(const واجهة_مُسجَّلة& واجهة) {
        الواجهات_[واجهة.الاسم].push_back(واجهة);
    }
    
    /**
     * البحث عن واجهة بإصدار معين
     */
    std::optional<واجهة_مُسجَّلة> ابحث(
        const std::string& اسم,
        const رقم_إصدار& إصدار
    ) const {
        auto it = الواجهات_.find(اسم);
        if (it == الواجهات_.end()) {
            return std::nullopt;
        }
        
        // البحث عن أفضل تطابق
        const واجهة_مُسجَّلة* أفضل = nullptr;
        
        for (const auto& واجهة : it->second) {
            if (واجهة.السمة.الإصدار <= إصدار) {
                if (!أفضل || واجهة.السمة.الإصدار > أفضل->السمة.الإصدار) {
                    أفضل = &واجهة;
                }
            }
        }
        
        if (أفضل) {
            return *أفضل;
        }
        
        return std::nullopt;
    }
    
    /**
     * الحصول على أحدث إصدار
     */
    std::optional<واجهة_مُسجَّلة> أحدث_إصدار(const std::string& اسم) const {
        auto it = الواجهات_.find(اسم);
        if (it == الواجهات_.end() || it->second.empty()) {
            return std::nullopt;
        }
        
        const واجهة_مُسجَّلة* أحدث = &it->second[0];
        for (const auto& واجهة : it->second) {
            if (واجهة.السمة.الإصدار > أحدث->السمة.الإصدار) {
                أحدث = &واجهة;
            }
        }
        
        return *أحدث;
    }
    
    /**
     * قائمة جميع إصدارات واجهة
     */
    std::vector<رقم_إصدار> إصدارات_متوفرة(const std::string& اسم) const {
        std::vector<رقم_إصدار> إصدارات;
        
        auto it = الواجهات_.find(اسم);
        if (it != الواجهات_.end()) {
            for (const auto& واجهة : it->second) {
                إصدارات.push_back(واجهة.السمة.الإصدار);
            }
        }
        
        // ترتيب تصاعدي
        std::sort(إصدارات.begin(), إصدارات.end());
        
        return إصدارات;
    }
    
    /**
     * الواجهات المُهملة
     */
    std::vector<واجهة_مُسجَّلة> الواجهات_المُهملة() const {
        std::vector<واجهة_مُسجَّلة> مُهملة;
        
        for (const auto& [اسم, قائمة] : الواجهات_) {
            for (const auto& واجهة : قائمة) {
                if (واجهة.السمة.الحالة == حالة_إهمال::مُهمَل) {
                    مُهملة.push_back(واجهة);
                }
            }
        }
        
        return مُهملة;
    }
    
    /**
     * التحقق من التوافق
     */
    bool متوافق(
        const رقم_إصدار& من_إصدار,
        const رقم_إصدار& إلى_إصدار
    ) const {
        // التوافق الخلفي: إذا كان الـ major نفسه
        return من_إصدار.major == إلى_إصدار.major;
    }
    
private:
    مدير_إصدارات() = default;
    
    std::map<std::string, std::vector<واجهة_مُسجَّلة>> الواجهات_;
};

