/**
 * رقم الإصدار
 * 
 * يتكون من ثلاثة أجزاء: major.minor.patch
 * 
 *     مثال: 2.1.3
 *           │ │ └── patch (تصحيحات صغيرة)
 *           │ └──── minor (ميزات جديدة متوافقة)
 *           └────── major (تغييرات كسرية)
 */
struct رقم_إصدار {
    int major = 1;    // الإصدار الرئيسي
    int minor = 0;    // الإصدار الفرعي
    int patch = 0;    // التصحيحات
    
    // تحليل من نص
    static std::optional<رقم_إصدار> حلل(const std::string& نص) {
        رقم_إصدار إصدار;
        
        std::regex نمط(R"((\d+)(?:\.(\d+))?(?:\.(\d+))?)");
        std::smatch تطابق;
        
        if (!std::regex_match(نص, تطابق, نمط)) {
            return std::nullopt;
        }
        
        إصدار.major = std::stoi(تطابق[1]);
        if (تطابق[2].matched) {
            إصدار.minor = std::stoi(تطابق[2]);
        }
        if (تطابق[3].matched) {
            إصدار.patch = std::stoi(تطابق[3]);
        }
        
        return إصدار;
    }
    
    std::string إلى_نص() const {
        return std::to_string(major) + "." + 
               std::to_string(minor) + "." + 
               std::to_string(patch);
    }
    
    // مقارنات
    bool operator<(const رقم_إصدار& آخر) const {
        if (major != آخر.major) return major < آخر.major;
        if (minor != آخر.minor) return minor < آخر.minor;
        return patch < آخر.patch;
    }
    
    bool operator<=(const رقم_إصدار& آخر) const {
        return *this < آخر || *this == آخر;
    }
    
    bool operator>(const رقم_إصدار& آخر) const {
        return آخر < *this;
    }
    
    bool operator>=(const رقم_إصدار& آخر) const {
        return آخر <= *this;
    }
    
    bool operator==(const رقم_إصدار& آخر) const {
        return major == آخر.major && 
               minor == آخر.minor && 
               patch == آخر.patch;
    }
    
    bool operator!=(const رقم_إصدار& آخر) const {
        return !(*this == آخر);
    }
};

/**
 * نطاق الإصدارات
 */
struct نطاق_إصدار {
    std::optional<رقم_إصدار> الحد_الأدنى;
    std::optional<رقم_إصدار> الحد_الأعلى;
    bool يشمل_الأدنى = true;
    bool يشمل_الأعلى = true;
    
    bool يحتوي(const رقم_إصدار& إصدار) const {
        if (الحد_الأدنى) {
            if (يشمل_الأدنى) {
                if (إصدار < *الحد_الأدنى) return false;
            }
            else {
                if (إصدار <= *الحد_الأدنى) return false;
            }
        }
        
        if (الحد_الأعلى) {
            if (يشمل_الأعلى) {
                if (إصدار > *الحد_الأعلى) return false;
            }
            else {
                if (إصدار >= *الحد_الأعلى) return false;
            }
        }
        
        return true;
    }
};

