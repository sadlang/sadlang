/**
 * مولد توثيق الإصدارات
 */
class مولد_توثيق_إصدارات {
public:
    /**
     * توليد توثيق CHANGELOG
     */
    std::string ولّد_changelog(const std::string& اسم_واجهة) const {
        std::string توثيق;
        
        auto إصدارات = مدير_إصدارات::المثيل().إصدارات_متوفرة(اسم_واجهة);
        
        توثيق += "# سجل التغييرات - " + اسم_واجهة + "\n\n";
        
        // من الأحدث للأقدم
        for (auto it = إصدارات.rbegin(); it != إصدارات.rend(); ++it) {
            auto واجهة = مدير_إصدارات::المثيل().ابحث(اسم_واجهة, *it);
            if (!واجهة) continue;
            
            توثيق += "## الإصدار " + it->إلى_نص() + "\n\n";
            
            if (!واجهة->السمة.تاريخ_البداية.empty()) {
                توثيق += "**التاريخ:** " + واجهة->السمة.تاريخ_البداية + "\n\n";
            }
            
            if (واجهة->السمة.الحالة == حالة_إهمال::مُهمَل) {
                توثيق += "⚠️ **مُهمَل:** " + واجهة->السمة.رسالة_إهمال + "\n\n";
                if (!واجهة->السمة.البديل.empty()) {
                    توثيق += "استخدم بدلاً منه: `" + واجهة->السمة.البديل + "`\n\n";
                }
            }
            
            if (!واجهة->السمة.الميزات_الجديدة.empty()) {
                توثيق += "### الميزات الجديدة\n";
                for (const auto& ميزة : واجهة->السمة.الميزات_الجديدة) {
                    توثيق += "- " + ميزة + "\n";
                }
                توثيق += "\n";
            }
            
            if (!واجهة->السمة.التغييرات_الكسرية.empty()) {
                توثيق += "### ⚠️ تغييرات كسرية\n";
                for (const auto& تغيير : واجهة->السمة.التغييرات_الكسرية) {
                    توثيق += "- " + تغيير + "\n";
                }
                توثيق += "\n";
            }
        }
        
        return توثيق;
    }
    
    /**
     * توليد مصفوفة التوافق
     */
    std::string ولّد_مصفوفة_توافق(const std::string& اسم_واجهة) const {
        std::string توثيق;
        
        auto إصدارات = مدير_إصدارات::المثيل().إصدارات_متوفرة(اسم_واجهة);
        
        توثيق += "# مصفوفة التوافق - " + اسم_واجهة + "\n\n";
        توثيق += "| من \\ إلى |";
        
        for (const auto& إصدار : إصدارات) {
            توثيق += " " + إصدار.إلى_نص() + " |";
        }
        توثيق += "\n";
        
        توثيق += "|----------|";
        for (size_t i = 0; i < إصدارات.size(); i++) {
            توثيق += "------|";
        }
        توثيق += "\n";
        
        for (const auto& من : إصدارات) {
            توثيق += "| " + من.إلى_نص() + " |";
            for (const auto& إلى : إصدارات) {
                bool متوافق = مدير_إصدارات::المثيل().متوافق(من, إلى);
                توثيق += متوافق ? " ✅ |" : " ❌ |";
            }
            توثيق += "\n";
        }
        
        return توثيق;
    }
};

