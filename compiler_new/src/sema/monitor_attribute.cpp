/**
 * 📈 مُولِّد المقاييس
 */
class مولد_مقاييس {
public:
    /**
     * توليد كود تعريف المقاييس
     */
    static std::string ولد_تعريفات() {
        return R"(
// مقاييس المراقبة المُولَّدة تلقائياً
namespace __مراقبة__ {
    std::map<std::string, std::atomic<size_t>> __عداد_طلبات__;
    std::map<std::string, std::atomic<size_t>> __عداد_أخطاء__;
    std::map<std::string, std::atomic<size_t>> __طلبات_نشطة__;
    std::map<std::string, std::vector<double>> __أوقات_استجابة__;
    std::mutex __قفل_مقاييس__;
    
    void __سجل_مدة__(const std::string& اسم, double مدة) {
        std::lock_guard<std::mutex> قفل(__قفل_مقاييس__);
        __أوقات_استجابة__[اسم].push_back(مدة);
        // الاحتفاظ بآخر 1000 قياس فقط
        if (__أوقات_استجابة__[اسم].size() > 1000) {
            __أوقات_استجابة__[اسم].erase(__أوقات_استجابة__[اسم].begin());
        }
    }
    
    void __سجل__(const std::string& نوع, const std::string& رسالة) {
        // تسجيل للتصحيح
    }
    
    void __حذر__(const std::string& رسالة) {
        std::cerr << "⚠️  تحذير: " << رسالة << std::endl;
    }
    
    // تصدير المقاييس بتنسيق Prometheus
    std::string صدر_prometheus() {
        std::ostringstream نتيجة;
        
        for (const auto& [اسم, عدد] : __عداد_طلبات__) {
            نتيجة << "sad_requests_total{function=\"" << اسم << "\"} " << عدد << "\n";
        }
        
        for (const auto& [اسم, عدد] : __عداد_أخطاء__) {
            نتيجة << "sad_errors_total{function=\"" << اسم << "\"} " << عدد << "\n";
        }
        
        for (const auto& [اسم, عدد] : __طلبات_نشطة__) {
            نتيجة << "sad_active_requests{function=\"" << اسم << "\"} " << عدد << "\n";
        }
        
        return نتيجة.str();
    }
}
)";
    }
};

