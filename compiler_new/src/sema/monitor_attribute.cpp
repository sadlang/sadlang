/**
 * مستوى المراقبة
 */
enum class مستوى_مراقبة {
    أساسي,      // عدد الطلبات والأخطاء فقط
    عادي,       // + زمن الاستجابة
    تفصيلي,     // + كل المتغيرات
    تتبع        // + تتبع كامل
};

/**
 * إعدادات المراقب
 */
struct إعدادات_مراقب {
    مستوى_مراقبة المستوى = مستوى_مراقبة::عادي;
    std::set<std::string> تجاهل;
    double حد_التحذير_ms = 1000.0;
    double حد_الخطأ_ms = 5000.0;
    bool سجل_المعاملات = false;
    bool سجل_النتيجة = false;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل السمة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 📊 محلل سمة @مراقب
 */
class محلل_سمة_مراقب {
public:
    /**
     * تحليل السمة من AST
     */
    إعدادات_مراقب حلل(const std::map<std::string, std::string>& معاملات) {
        إعدادات_مراقب إعدادات;
        
        // مستوى المراقبة
        auto it_مستوى = معاملات.find("مستوى");
        if (it_مستوى != معاملات.end()) {
            if (it_مستوى->second == "أساسي") {
                إعدادات.المستوى = مستوى_مراقبة::أساسي;
            } else if (it_مستوى->second == "تفصيلي") {
                إعدادات.المستوى = مستوى_مراقبة::تفصيلي;
            } else if (it_مستوى->second == "تتبع") {
                إعدادات.المستوى = مستوى_مراقبة::تتبع;
            }
        }
        
        // حدود التحذير
        auto it_حد = معاملات.find("حد_تحذير");
        if (it_حد != معاملات.end()) {
            إعدادات.حد_التحذير_ms = std::stod(it_حد->second);
        }
        
        // تسجيل المعاملات
        auto it_معاملات = معاملات.find("سجل_المعاملات");
        if (it_معاملات != معاملات.end()) {
            إعدادات.سجل_المعاملات = (it_معاملات->second == "صحيح");
        }
        
        return إعدادات;
    }
    
    /**
     * توليد كود المراقبة
     */
    std::string ولد_كود_بداية(const std::string& اسم_الدالة,
                                const إعدادات_مراقب& إعدادات) {
        std::string كود;
        
        // بداية القياس
        كود += "    auto __وقت_البداية__ = std::chrono::high_resolution_clock::now();\n";
        كود += "    __عداد_طلبات__[\"" + اسم_الدالة + "\"]++;\n";
        كود += "    __طلبات_نشطة__[\"" + اسم_الدالة + "\"]++;\n";
        
        if (إعدادات.المستوى >= مستوى_مراقبة::تفصيلي) {
            كود += "    __سجل__(\"بدء\", \"" + اسم_الدالة + "\");\n";
        }
        
        return كود;
    }
    
    /**
     * توليد كود نهاية المراقبة
     */
    std::string ولد_كود_نهاية(const std::string& اسم_الدالة,
                               const إعدادات_مراقب& إعدادات) {
        std::string كود;
        
        // نهاية القياس
        كود += "    auto __وقت_النهاية__ = std::chrono::high_resolution_clock::now();\n";
        كود += "    __طلبات_نشطة__[\"" + اسم_الدالة + "\"]--;\n";
        كود += "    auto __المدة__ = std::chrono::duration<double, std::milli>(__وقت_النهاية__ - __وقت_البداية__).count();\n";
        كود += "    __سجل_مدة__(\"" + اسم_الدالة + "\", __المدة__);\n";
        
        // تحذير عند التجاوز
        كود += "    if (__المدة__ > " + std::to_string(إعدادات.حد_التحذير_ms) + ") {\n";
        كود += "        __حذر__(\"" + اسم_الدالة + " بطيئة: \" + std::to_string(__المدة__) + \"ms\");\n";
        كود += "    }\n";
        
        return كود;
    }
    
    /**
     * توليد كود معالجة الخطأ
     */
    std::string ولد_كود_خطأ(const std::string& اسم_الدالة) {
        std::string كود;
        
        كود += "    __عداد_أخطاء__[\"" + اسم_الدالة + "\"]++;\n";
        كود += "    __طلبات_نشطة__[\"" + اسم_الدالة + "\"]--;\n";
        
        return كود;
    }
};

