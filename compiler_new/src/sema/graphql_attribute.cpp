/**
 * مولد مخطط GraphQL
 * 
 * يحول البنيات المُعلَّمة إلى مخطط GraphQL
 */
class مولد_مخطط {
public:
    /**
     * توليد مخطط لنوع
     */
    std::string ولّد_نوع(const نوع_كائن_غراف& نوع) {
        std::string مخطط;
        
        // الوصف
        if (!نوع.الوصف.empty()) {
            مخطط += "\"\"\"" + نوع.الوصف + "\"\"\"\n";
        }
        
        // تعريف النوع
        mخطط += "type " + نوع.الاسم;
        
        // الواجهات
        if (!نوع.الواجهات.empty()) {
            مخطط += " implements ";
            for (size_t i = 0; i < نوع.الواجهات.size(); i++) {
                if (i > 0) مخطط += " & ";
                مخطط += نوع.الواجهات[i];
            }
        }
        
        مخطط += " {\n";
        
        // الحقول
        for (const auto& حقل : نوع.الحقول) {
            مخطط += ولّد_حقل(حقل);
        }
        
        مخطط += "}\n";
        
        return مخطط;
    }
    
    /**
     * توليد تعريف حقل
     */
    std::string ولّد_حقل(const حقل_غراف& حقل) {
        std::string تعريف = "  " + حقل.الاسم;
        
        // الوسائط
        if (!حقل.الوسائط.empty()) {
            تعريف += "(";
            for (size_t i = 0; i < حقل.الوسائط.size(); i++) {
                if (i > 0) تعريف += ", ";
                تعريف += حقل.الوسائط[i].first + ": " + حقل.الوسائط[i].second;
            }
            تعريف += ")";
        }
        
        // النوع
        تعريف += ": ";
        
        if (حقل.قائمة) {
            تعريف += "[" + حقل.اسم_النوع;
            if (حقل.عناصر_مطلوبة) تعريف += "!";
            تعريف += "]";
        } else {
            تعريف += حقل.اسم_النوع;
        }
        
        if (حقل.مطلوب) {
            تعريف += "!";
        }
        
        // الإهمال
        if (حقل.مُهمَل) {
            تعريف += " @deprecated";
            if (!حقل.سبب_الإهمال.empty()) {
                تعريف += "(reason: \"" + حقل.سبب_الإهمال + "\")";
            }
        }
        
        تعريف += "\n";
        
        return تعريف;
    }
    
    /**
     * توليد مخطط كامل
     */
    std::string ولّد_مخطط_كامل(const std::vector<نوع_كائن_غراف>& أنواع) {
        std::string مخطط;
        
        for (const auto& نوع : أنواع) {
            مخطط += ولّد_نوع(نوع) + "\n";
        }
        
        return مخطط;
    }
};

