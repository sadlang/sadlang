/**
 * نوع GraphQL
 */
enum class نوع_غراف {
    عددي,              // Int, Float, String, Boolean, ID
    كائن,              // Object type
    واجهة,             // Interface
    اتحاد,             // Union
    تعداد,             // Enum
    قائمة,             // List
    غير_فارغ           // Non-null (!)
};

/**
 * نوع عددي (Scalar)
 */
enum class عددي_غراف {
    عدد_صحيح,          // Int
    عدد_عشري,          // Float
    نص,                // String
    منطقي,             // Boolean
    معرف               // ID
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              تعريف الحقل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * استراتيجية التحميل
 */
enum class استراتيجية_حمل {
    فوري,              // تحميل مع الكائن الأب
    كسول,              // تحميل عند الطلب
    دفعة               // تجميع الطلبات (DataLoader)
};

/**
 * خيارات العلاقة
 */
struct خيارات_علاقة {
    استراتيجية_حمل الحمل = استراتيجية_حمل::كسول;
    std::string دالة_جلب;
    std::string مفتاح_أجنبي;
    bool حذف_متسلسل = false;
};

/**
 * تعريف حقل GraphQL
 */
struct حقل_غراف {
    std::string الاسم;
    std::string الاسم_عربي;
    
    // النوع
    نوع_غراف النوع = نوع_غراف::عددي;
    std::string اسم_النوع;
    bool مطلوب = false;
    bool قائمة = false;
    bool عناصر_مطلوبة = false;
    
    // الوصف
    std::string الوصف;
    bool مُهمَل = false;
    std::string سبب_الإهمال;
    
    // العلاقة
    bool علاقة = false;
    خيارات_علاقة الخيارات;
    
    // القيمة الافتراضية
    std::optional<std::string> قيمة_افتراضية;
    
    // الوسائط (للحقول الحاسوبية)
    std::vector<std::pair<std::string, std::string>> الوسائط;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              تعريف النوع
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * تعريف نوع GraphQL
 */
struct نوع_كائن_غراف {
    std::string الاسم;
    std::string الاسم_عربي;
    std::string الوصف;
    
    std::vector<حقل_غراف> الحقول;
    std::vector<std::string> الواجهات;
    
    // موقع في الكود المصدري
    std::string الملف;
    int السطر = 0;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل سمة @غراف
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * محلل سمة @غراف
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │                 محلل @غراف                             │
 *     │                                                        │
 *     │   المدخل:                                              │
 *     │   ────────                                             │
 *     │   @غراف                                                │
 *     │   بنية مستخدم:                                         │
 *     │       id: معرف!                                        │
 *     │       اسم: نص!                                         │
 *     │                                                        │
 *     │   المخرج:                                              │
 *     │   ────────                                             │
 *     │   type User {                                          │
 *     │       id: ID!                                          │
 *     │       name: String!                                    │
 *     │   }                                                    │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
class محلل_غراف {
public:
    /**
     * تحليل بنية مُعلَّمة بـ @غراف
     */
    std::optional<نوع_كائن_غراف> حلل_بنية(
        const std::string& اسم,
        const std::vector<std::pair<std::string, std::string>>& حقول,
        const std::map<std::string, std::string>& سمات
    ) {
        نوع_كائن_غراف نوع;
        نوع.الاسم = ترجم_اسم(اسم);
        نوع.الاسم_عربي = اسم;
        
        // الوصف من السمة
        if (سمات.count("وصف")) {
            نوع.الوصف = سمات.at("وصف");
        }
        
        // الواجهات
        if (سمات.count("ينفذ")) {
            // تحليل قائمة الواجهات
            نوع.الواجهات = قسّم(سمات.at("ينفذ"), ',');
        }
        
        // تحليل الحقول
        for (const auto& [اسم_حقل, نوع_حقل] : حقول) {
            auto حقل = حلل_حقل(اسم_حقل, نوع_حقل);
            if (حقل) {
                نوع.الحقول.push_back(*حقل);
            }
        }
        
        return نوع;
    }
    
    /**
     * تحليل حقل
     */
    std::optional<حقل_غراف> حلل_حقل(
        const std::string& اسم,
        const std::string& نوع_نصي
    ) {
        حقل_غراف حقل;
        حقل.الاسم = ترجم_اسم(اسم);
        حقل.الاسم_عربي = اسم;
        
        // تحليل النوع
        std::string نوع_مُحلَّل = نوع_نصي;
        
        // هل مطلوب (!)؟
        if (!نوع_مُحلَّل.empty() && نوع_مُحلَّل.back() == '!') {
            حقل.مطلوب = true;
            نوع_مُحلَّل.pop_back();
        }
        
        // هل قائمة ([])؟
        if (نوع_مُحلَّل.front() == '[' && نوع_مُحلَّل.back() == ']') {
            حقل.قائمة = true;
            نوع_مُحلَّل = نوع_مُحلَّل.substr(1, نوع_مُحلَّل.size() - 2);
            
            // هل العناصر مطلوبة؟
            if (!نوع_مُحلَّل.empty() && نوع_مُحلَّل.back() == '!') {
                حقل.عناصر_مطلوبة = true;
                نوع_مُحلَّل.pop_back();
            }
        }
        
        // تحديد النوع
        حقل.اسم_النوع = ترجم_نوع(نوع_مُحلَّل);
        حقل.النوع = صنّف_نوع(نوع_مُحلَّل);
        
        return حقل;
    }
    
    /**
     * تحليل سمة @علاقة
     */
    خيارات_علاقة حلل_علاقة(const std::map<std::string, std::string>& سمات) {
        خيارات_علاقة خيارات;
        
        if (سمات.count("حمل")) {
            auto قيمة = سمات.at("حمل");
            if (قيمة == "فوري") خيارات.الحمل = استراتيجية_حمل::فوري;
            else if (قيمة == "كسول") خيارات.الحمل = استراتيجية_حمل::كسول;
            else if (قيمة == "دفعة") خيارات.الحمل = استراتيجية_حمل::دفعة;
        }
        
        if (سمات.count("جلب")) {
            خيارات.دالة_جلب = سمات.at("جلب");
        }
        
        if (سمات.count("مفتاح")) {
            خيارات.مفتاح_أجنبي = سمات.at("مفتاح");
        }
        
        return خيارات;
    }
    
private:
    /**
     * ترجمة اسم عربي للإنجليزية
     */
    std::string ترجم_اسم(const std::string& اسم) {
        // قاموس الترجمة
        static std::map<std::string, std::string> قاموس = {
            {"مستخدم", "User"},
            {"مقال", "Article"},
            {"تعليق", "Comment"},
            {"اسم", "name"},
            {"عنوان", "title"},
            {"محتوى", "content"},
            {"تاريخ", "date"},
            {"مؤلف", "author"},
            {"مقالات", "articles"},
            {"تعليقات", "comments"},
            {"أصدقاء", "friends"}
        };
        
        if (قاموس.count(اسم)) {
            return قاموس[اسم];
        }
        
        // تحويل افتراضي
        return اسم;
    }
    
    /**
     * ترجمة نوع للإنجليزية
     */
    std::string ترجم_نوع(const std::string& نوع) {
        static std::map<std::string, std::string> أنواع = {
            {"معرف", "ID"},
            {"نص", "String"},
            {"عدد", "Int"},
            {"عدد_صحيح", "Int"},
            {"عدد_عشري", "Float"},
            {"منطقي", "Boolean"},
            {"تاريخ", "DateTime"}
        };
        
        if (أنواع.count(نوع)) {
            return أنواع[نوع];
        }
        
        return ترجم_اسم(نوع);
    }
    
    /**
     * تصنيف النوع
     */
    نوع_غراف صنّف_نوع(const std::string& نوع) {
        static std::set<std::string> أنواع_عددية = {
            "معرف", "نص", "عدد", "عدد_صحيح", "عدد_عشري", "منطقي", "تاريخ"
        };
        
        if (أنواع_عددية.count(نوع)) {
            return نوع_غراف::عددي;
        }
        
        return نوع_غراف::كائن;
    }
    
    /**
     * تقسيم نص
     */
    std::vector<std::string> قسّم(const std::string& نص, char فاصل) {
        std::vector<std::string> أجزاء;
        std::string جزء;
        
        for (char c : نص) {
            if (c == فاصل) {
                if (!جزء.empty()) {
                    أجزاء.push_back(جزء);
                    جزء.clear();
                }
            } else {
                جزء += c;
            }
        }
        
        if (!جزء.empty()) {
            أجزاء.push_back(جزء);
        }
        
        return أجزاء;
    }
};

