/**
 * مسجل أنواع GraphQL
 * 
 * يجمع كل الأنواع المُعلَّمة بـ @غراف
 */
class مسجل_غراف {
public:
    /**
     * الحصول على المثيل الوحيد
     */
    static مسجل_غراف& المثيل() {
        static مسجل_غراف مسجل;
        return مسجل;
    }
    
    /**
     * تسجيل نوع
     */
    void سجّل(const نوع_كائن_غراف& نوع) {
        الأنواع_[نوع.الاسم] = نوع;
    }
    
    /**
     * الحصول على نوع
     */
    std::optional<نوع_كائن_غراف> احصل(const std::string& اسم) const {
        if (الأنواع_.count(اسم)) {
            return الأنواع_.at(اسم);
        }
        return std::nullopt;
    }
    
    /**
     * كل الأنواع
     */
    std::vector<نوع_كائن_غراف> كل_الأنواع() const {
        std::vector<نوع_كائن_غراف> قائمة;
        for (const auto& [_, نوع] : الأنواع_) {
            قائمة.push_back(نوع);
        }
        return قائمة;
    }
    
    /**
     * توليد المخطط الكامل
     */
    std::string المخطط() const {
        مولد_مخطط مولد;
        return مولد.ولّد_مخطط_كامل(كل_الأنواع());
    }
    
private:
    مسجل_غراف() = default;
    
    std::map<std::string, نوع_كائن_غراف> الأنواع_;
};

