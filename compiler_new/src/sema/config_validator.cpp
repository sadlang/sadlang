/**
 * مستوى الخطأ
 */
enum class مستوى_خطأ {
    خطأ,              // يمنع الترجمة
    تحذير,            // ينصح بالتصحيح
    معلومة           // للتوضيح فقط
};

/**
 * خطأ تحقق من إعداد
 */
struct خطأ_إعداد {
    مستوى_خطأ المستوى;
    std::string المفتاح;
    std::string الرسالة;
    std::string القيمة_الفعلية;
    std::string القيمة_المتوقعة;
    
    // الموقع في الملف
    std::string الملف;
    int السطر = 0;
    int العمود = 0;
    
    /**
     * تنسيق الخطأ
     */
    std::string تنسيق() const {
        std::stringstream س;
        
        // الرمز
        switch (المستوى) {
            case مستوى_خطأ::خطأ: س << "❌ خطأ"; break;
            case مستوى_خطأ::تحذير: س << "⚠️ تحذير"; break;
            case مستوى_خطأ::معلومة: س << "ℹ️ معلومة"; break;
        }
        
        // الموقع
        if (!الملف.empty()) {
            س << " [" << الملف;
            if (السطر > 0) س << ":" << السطر;
            س << "]";
        }
        
        س << ": " << الرسالة << "\n";
        س << "       المفتاح: " << المفتاح << "\n";
        
        if (!القيمة_الفعلية.empty()) {
            س << "       القيمة: " << القيمة_الفعلية << "\n";
        }
        
        if (!القيمة_المتوقعة.empty()) {
            س << "       المتوقع: " << القيمة_المتوقعة << "\n";
        }
        
        return س.str();
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
