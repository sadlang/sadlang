/**
 * محقق الإعدادات
 * 
 * يتحقق من صحة الإعدادات حسب المخطط المُعرَّف
 */
class محقق_إعدادات {
public:
    /**
     * إضافة تعريف إعداد
     */
    void أضف_تعريف(const تعريف_إعداد& تعريف) {
        التعريفات_[تعريف.المفتاح] = تعريف;
    }
    
    /**
     * تحقق من قيمة إعداد
     */
    std::vector<خطأ_إعداد> تحقق_قيمة(
        const std::string& مفتاح,
        const std::string& قيمة,
        const std::string& ملف = "",
        int سطر = 0
    ) const {
        std::vector<خطأ_إعداد> أخطاء;
        
        // ابحث عن التعريف
        auto it = التعريفات_.find(مفتاح);
        if (it == التعريفات_.end()) {
            // إعداد غير معروف
            خطأ_إعداد خطأ;
            خطأ.المستوى = مستوى_خطأ::تحذير;
            خطأ.المفتاح = مفتاح;
            خطأ.الرسالة = "إعداد غير معروف";
            خطأ.القيمة_الفعلية = قيمة;
            خطأ.الملف = ملف;
            خطأ.السطر = سطر;
            أخطاء.push_back(خطأ);
            return أخطاء;
        }
        
        const auto& تعريف = it->second;
        
        // تحقق من نوع البيانات
        if (!تحقق_نوع(قيمة, تعريف.نوع_البيانات)) {
            خطأ_إعداد خطأ;
            خطأ.المستوى = مستوى_خطأ::خطأ;
            خطأ.المفتاح = مفتاح;
            خطأ.الرسالة = "نوع بيانات غير صحيح";
            خطأ.القيمة_الفعلية = قيمة;
            خطأ.القيمة_المتوقعة = تعريف.نوع_البيانات;
            خطأ.الملف = ملف;
            خطأ.السطر = سطر;
            أخطاء.push_back(خطأ);
        }
        
        // تحقق من القيود
        for (const auto& قيد : تعريف.القيود) {
            auto خطأ_قيد = تحقق_قيد(قيمة, قيد, مفتاح, ملف, سطر);
            if (خطأ_قيد) {
                أخطاء.push_back(*خطأ_قيد);
            }
        }
        
        return أخطاء;
    }
    
    /**
     * تحقق من ملف إعدادات كامل
     */
    std::vector<خطأ_إعداد> تحقق_ملف(
        const std::unordered_map<std::string, std::string>& إعدادات,
        const std::string& ملف = ""
    ) const {
        std::vector<خطأ_إعداد> أخطاء;
        
        // تحقق من كل إعداد موجود
        for (const auto& [مفتاح, قيمة] : إعدادات) {
            auto أخطاء_قيمة = تحقق_قيمة(مفتاح, قيمة, ملف);
            أخطاء.insert(أخطاء.end(), أخطاء_قيمة.begin(), أخطاء_قيمة.end());
        }
        
        // تحقق من الإعدادات الإلزامية
        for (const auto& [مفتاح, تعريف] : التعريفات_) {
            if (تعريف.إلزامي && إعدادات.find(مفتاح) == إعدادات.end()) {
                خطأ_إعداد خطأ;
                خطأ.المستوى = مستوى_خطأ::خطأ;
                خطأ.المفتاح = مفتاح;
                خطأ.الرسالة = "إعداد إلزامي مفقود";
                خطأ.القيمة_المتوقعة = تعريف.الوصف;
                خطأ.الملف = ملف;
                أخطاء.push_back(خطأ);
            }
        }
        
        return أخطاء;
    }
    
    /**
     * توليد توثيق للإعدادات
     */
    std::string ولِّد_توثيق() const {
        std::stringstream س;
        
        س << "# مرجع الإعدادات\n\n";
        
        // تجميع حسب القسم
        std::map<std::string, std::vector<const تعريف_إعداد*>> أقسام;
        
        for (const auto& [مفتاح, تعريف] : التعريفات_) {
            size_t نقطة = مفتاح.find('.');
            std::string قسم = نقطة != std::string::npos ? مفتاح.substr(0, نقطة) : "عام";
            أقسام[قسم].push_back(&تعريف);
        }
        
        for (const auto& [قسم, تعريفات] : أقسام) {
            س << "## [" << قسم << "]\n\n";
            
            for (const auto* تعريف : تعريفات) {
                س << "### `" << تعريف->المفتاح << "`\n\n";
                س << "- **النوع**: " << تعريف->نوع_البيانات << "\n";
                س << "- **إلزامي**: " << (تعريف->إلزامي ? "نعم" : "لا") << "\n";
                
                if (تعريف->القيمة_الافتراضية) {
                    س << "- **الافتراضي**: `" << *تعريف->القيمة_الافتراضية << "`\n";
                }
                
                س << "\n" << تعريف->الوصف << "\n\n";
                
                if (!تعريف->مثال.empty()) {
                    س << "**مثال**:\n```toml\n" << تعريف->مثال << "\n```\n\n";
                }
            }
        }
        
        return س.str();
    }

private:
    bool تحقق_نوع(const std::string& قيمة, const std::string& نوع) const {
        if (نوع == "عدد" || نوع == "int" || نوع == "عدد_صحيح") {
            try {
                std::stoll(قيمة);
                return true;
            } catch (...) {
                return false;
            }
        }
        
        if (نوع == "عشري" || نوع == "float" || نوع == "double") {
            try {
                std::stod(قيمة);
                return true;
            } catch (...) {
                return false;
            }
        }
        
        if (نوع == "منطقي" || نوع == "bool") {
            return قيمة == "true" || قيمة == "false" ||
                   قيمة == "صحيح" || قيمة == "خاطئ" ||
                   قيمة == "1" || قيمة == "0";
        }
        
        if (نوع == "نص" || نوع == "string") {
            return true;  // أي شيء يمكن أن يكون نصاً
        }
        
        return true;  // نوع غير معروف = نقبل أي شيء
    }
    
    std::optional<خطأ_إعداد> تحقق_قيد(
        const std::string& قيمة,
        const قيد_إعداد& قيد,
        const std::string& مفتاح,
        const std::string& ملف,
        int سطر
    ) const {
        switch (قيد.النوع) {
            case نوع_قيد::نطاق: {
                double رقم;
                try {
                    رقم = std::stod(قيمة);
                } catch (...) {
                    return std::nullopt;  // ليس رقماً، سيُكتشف في نوع البيانات
                }
                
                if (قيد.الحد_الأدنى && رقم < *قيد.الحد_الأدنى) {
                    خطأ_إعداد خطأ;
                    خطأ.المستوى = مستوى_خطأ::خطأ;
                    خطأ.المفتاح = مفتاح;
                    خطأ.الرسالة = "القيمة أقل من الحد الأدنى";
                    خطأ.القيمة_الفعلية = قيمة;
                    خطأ.القيمة_المتوقعة = ">= " + std::to_string(*قيد.الحد_الأدنى);
                    خطأ.الملف = ملف;
                    خطأ.السطر = سطر;
                    return خطأ;
                }
                
                if (قيد.الحد_الأقصى && رقم > *قيد.الحد_الأقصى) {
                    خطأ_إعداد خطأ;
                    خطأ.المستوى = مستوى_خطأ::خطأ;
                    خطأ.المفتاح = مفتاح;
                    خطأ.الرسالة = "القيمة أكبر من الحد الأقصى";
                    خطأ.القيمة_الفعلية = قيمة;
                    خطأ.القيمة_المتوقعة = "<= " + std::to_string(*قيد.الحد_الأقصى);
                    خطأ.الملف = ملف;
                    خطأ.السطر = سطر;
                    return خطأ;
                }
                break;
            }
            
            case نوع_قيد::قيم_محددة: {
                bool موجود = false;
                for (const auto& مسموح : قيد.القيم_المسموحة) {
                    if (قيمة == مسموح) {
                        موجود = true;
                        break;
                    }
                }
                
                if (!موجود) {
                    خطأ_إعداد خطأ;
                    خطأ.المستوى = مستوى_خطأ::خطأ;
                    خطأ.المفتاح = مفتاح;
                    خطأ.الرسالة = "قيمة غير مسموحة";
                    خطأ.القيمة_الفعلية = قيمة;
                    
                    std::string مسموحة;
                    for (size_t i = 0; i < قيد.القيم_المسموحة.size(); i++) {
                        if (i > 0) مسموحة += ", ";
                        مسموحة += "\"" + قيد.القيم_المسموحة[i] + "\"";
                    }
                    خطأ.القيمة_المتوقعة = "أحد: " + مسموحة;
                    خطأ.الملف = ملف;
                    خطأ.السطر = سطر;
                    return خطأ;
                }
                break;
            }
            
            case نوع_قيد::نمط: {
                try {
                    std::regex نمط(قيد.النمط_regex);
                    if (!std::regex_match(قيمة, نمط)) {
                        خطأ_إعداد خطأ;
                        خطأ.المستوى = مستوى_خطأ::خطأ;
                        خطأ.المفتاح = مفتاح;
                        خطأ.الرسالة = "القيمة لا تُطابق النمط المطلوب";
                        خطأ.القيمة_الفعلية = قيمة;
                        خطأ.القيمة_المتوقعة = قيد.الوصف;
                        خطأ.الملف = ملف;
                        خطأ.السطر = سطر;
                        return خطأ;
                    }
                } catch (...) {
                    // نمط غير صالح
                }
                break;
            }
            
            case نوع_قيد::طول: {
                size_t طول = قيمة.size();
                
                if (قيد.الحد_الأدنى_طول && طول < *قيد.الحد_الأدنى_طول) {
                    خطأ_إعداد خطأ;
                    خطأ.المستوى = مستوى_خطأ::خطأ;
                    خطأ.المفتاح = مفتاح;
                    خطأ.الرسالة = "النص أقصر من المطلوب";
                    خطأ.القيمة_الفعلية = std::to_string(طول) + " حرف";
                    خطأ.القيمة_المتوقعة = ">= " + std::to_string(*قيد.الحد_الأدنى_طول) + " حرف";
                    خطأ.الملف = ملف;
                    خطأ.السطر = سطر;
                    return خطأ;
                }
                
                if (قيد.الحد_الأقصى_طول && طول > *قيد.الحد_الأقصى_طول) {
                    خطأ_إعداد خطأ;
                    خطأ.المستوى = مستوى_خطأ::خطأ;
                    خطأ.المفتاح = مفتاح;
                    خطأ.الرسالة = "النص أطول من المسموح";
                    خطأ.القيمة_الفعلية = std::to_string(طول) + " حرف";
                    خطأ.القيمة_المتوقعة = "<= " + std::to_string(*قيد.الحد_الأقصى_طول) + " حرف";
                    خطأ.الملف = ملف;
                    خطأ.السطر = سطر;
                    return خطأ;
                }
                break;
            }
            
            default:
                break;
        }
        
        return std::nullopt;
    }
    
    std::unordered_map<std::string, تعريف_إعداد> التعريفات_;
};

