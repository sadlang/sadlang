/**
 * إنشاء مخطط إعدادات خادم ويب نموذجي
 */
inline محقق_إعدادات أنشئ_مخطط_خادم() {
    محقق_إعدادات محقق;
    
    // إعدادات الخادم
    تعريف_إعداد منفذ;
    منفذ.المفتاح = "server.port";
    منفذ.الوصف = "رقم المنفذ الذي يستمع عليه الخادم";
    منفذ.نوع_البيانات = "عدد";
    منفذ.إلزامي = false;
    منفذ.القيمة_الافتراضية = "8080";
    منفذ.مثال = "server.port = 3000";
    
    قيد_إعداد قيد_منفذ;
    قيد_منفذ.النوع = نوع_قيد::نطاق;
    قيد_منفذ.الحد_الأدنى = 1;
    قيد_منفذ.الحد_الأقصى = 65535;
    منفذ.القيود.push_back(قيد_منفذ);
    
    محقق.أضف_تعريف(منفذ);
    
    // إعداد المضيف
    تعريف_إعداد مضيف;
    مضيف.المفتاح = "server.host";
    مضيف.الوصف = "عنوان IP الذي يستمع عليه الخادم";
    مضيف.نوع_البيانات = "نص";
    مضيف.القيمة_الافتراضية = "127.0.0.1";
    محقق.أضف_تعريف(مضيف);
    
    // إعداد البيئة
    تعريف_إعداد بيئة;
    بيئة.المفتاح = "app.environment";
    بيئة.الوصف = "بيئة التشغيل";
    بيئة.نوع_البيانات = "نص";
    بيئة.القيمة_الافتراضية = "development";
    
    قيد_إعداد قيد_بيئة;
    قيد_بيئة.النوع = نوع_قيد::قيم_محددة;
    قيد_بيئة.القيم_المسموحة = {"development", "staging", "production"};
    بيئة.القيود.push_back(قيد_بيئة);
    
    محقق.أضف_تعريف(بيئة);
    
    return محقق;
}

