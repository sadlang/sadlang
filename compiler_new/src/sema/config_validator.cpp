/**
 * نوع القيد
 */
enum class نوع_قيد {
    نوع_بيانات,       // يجب أن يكون عدداً/نصاً/إلخ
    نطاق,             // بين قيمتين
    قيم_محددة,        // من قائمة محددة
    نمط,              // يُطابق regex
    طول,              // طول النص
    إلزامي,           // يجب أن يوجد
    مخصص             // تحقق مخصص
};

/**
 * قيد على إعداد
 */
struct قيد_إعداد {
    نوع_قيد النوع;
    std::string الوصف;
    
    // حسب النوع:
    std::string نوع_البيانات;                    // لـ نوع_بيانات
    std::optional<double> الحد_الأدنى;           // لـ نطاق
    std::optional<double> الحد_الأقصى;           // لـ نطاق
    std::vector<std::string> القيم_المسموحة;    // لـ قيم_محددة
    std::string النمط_regex;                     // لـ نمط
    std::optional<size_t> الحد_الأدنى_طول;       // لـ طول
    std::optional<size_t> الحد_الأقصى_طول;       // لـ طول
};

// ═══════════════════════════════════════════════════════════════════════════════
