/**
 * تعريف إعداد
 */
struct تعريف_إعداد {
    std::string المفتاح;
    std::string الوصف;
    std::string نوع_البيانات;      // "عدد"، "نص"، "منطقي"، "قائمة"
    
    bool إلزامي = false;
    std::optional<std::string> القيمة_الافتراضية;
    
    std::vector<قيد_إعداد> القيود;
    
    // للتوثيق
    std::string مثال;
    std::vector<std::string> ملاحظات;
};

// ═══════════════════════════════════════════════════════════════════════════════
