/**
 * فئة الدالة - تُغلِّف llvm::Function
 * 
 * للمبتدئ: الدالة في LLVM تحتوي:
 * - التوقيع: الاسم + المعطيات + نوع الإرجاع
 * - الكتل: الكود الفعلي (BasicBlocks)
 * - السمات: معلومات إضافية (inline, nounwind, etc.)
 */
class دالة {
public:
    /**
     * نوع الربط (Linkage)
     * يحدد كيف تُرى الدالة من خارج الوحدة
     */
    enum class ربط {
        خارجي,      // External - مرئية من كل مكان
        داخلي,      // Internal - فقط داخل الوحدة
        خاص,        // Private - فقط داخل الملف
        ضعيف,       // Weak - يمكن استبدالها
    };
    
    دالة() = default;
    
#ifdef SAD_USE_LLVM
    explicit دالة(llvm::Function* دالة_llvm) : m_دالة(دالة_llvm) {}
#endif
    
    // ───────────────────────────────────────────────────────────────────────
    // الاستعلامات
    // ───────────────────────────────────────────────────────────────────────
    
    bool صالحة() const;
    std::string اسم() const;
    نوع نوع_الإرجاع() const;
    size_t عدد_المعطيات() const;
    قيمة معطى(size_t الفهرس) const;
    std::vector<قيمة> المعطيات() const;
    
    // ───────────────────────────────────────────────────────────────────────
    // إدارة الكتل
    // ───────────────────────────────────────────────────────────────────────
    
    /// إنشاء كتلة أساسية جديدة
    كتلة_أساسية أنشئ_كتلة(const std::string& اسم = "");
    
    /// الحصول على كتلة الدخول
    كتلة_أساسية كتلة_الدخول() const;
    
    /// عدد الكتل
    size_t عدد_الكتل() const;
    
    // ───────────────────────────────────────────────────────────────────────
    // السمات
    // ───────────────────────────────────────────────────────────────────────
    
    /// إضافة سمة للدالة
    void أضف_سمة(const std::string& اسم_السمة);
    
    /// هل الدالة مُضمَّنة دائماً؟
    void عيِّن_مضمنة_دائماً();
    
    /// هل الدالة لا تُلقي استثناءات؟
    void عيِّن_بدون_استثناءات();
    
    // ───────────────────────────────────────────────────────────────────────
    // التحقق
    // ───────────────────────────────────────────────────────────────────────
    
    /// التحقق من صحة الدالة
    bool تحقق() const;
    
    /// تحويل إلى نص IR
    std::string إلى_ir() const;
    
#ifdef SAD_USE_LLVM
    llvm::Function* خام() const { return m_دالة; }
#endif

private:
#ifdef SAD_USE_LLVM
    llvm::Function* m_دالة = nullptr;
#endif
};

