/**
 * الكتلة الأساسية (Basic Block)
 * 
 * للمبتدئ: الكتلة الأساسية هي سلسلة من الأوامر التي:
 * - تُنفذ بالترتيب من الأول للأخير
 * - لا يوجد قفزات في المنتصف
 * - تنتهي بتعليمة "منهية" (terminator): قفزة أو رجوع
 * 
 * مثال:
 *     entry:                          ; ← اسم الكتلة
 *         %sum = add i32 %a, %b       ; تعليمة 1
 *         %result = mul i32 %sum, 2   ; تعليمة 2
 *         ret i32 %result             ; المُنهي
 */
class كتلة_أساسية {
public:
    كتلة_أساسية() = default;
    
#ifdef SAD_USE_LLVM
    explicit كتلة_أساسية(llvm::BasicBlock* كتلة_llvm) : m_كتلة(كتلة_llvm) {}
#endif
    
    /// هل الكتلة صالحة؟
    bool صالحة() const;
    
    /// الحصول على اسم الكتلة
    std::string اسم() const;
    
    /// هل الكتلة لها مُنهي؟
    bool لها_منهي() const;
    
    /// الحصول على الدالة الأم
    دالة الدالة_الأم() const;
    
#ifdef SAD_USE_LLVM
    llvm::BasicBlock* خام() const { return m_كتلة; }
#endif

private:
#ifdef SAD_USE_LLVM
    llvm::BasicBlock* m_كتلة = nullptr;
#endif
};

