/**
 * مُنشئ IR (IR Builder)
 * 
 * للمبتدئ: هذا هو "القلم" الذي نكتب به تعليمات LLVM.
 * - نُحدد أين نكتب (في أي كتلة)
 * - نُنشئ التعليمات واحدة تلو الأخرى
 * 
 * مثال:
 *     builder.عيِّن_موضع_الإدراج(entry_block)  // أين نكتب؟
 *     builder.أنشئ_جمع(a, b, "sum")            // نكتب: %sum = add a, b
 *     builder.أنشئ_رجوع(sum)                   // نكتب: ret %sum
 */
class مُنشئ_IR {
public:
    مُنشئ_IR() = default;
    
#ifdef SAD_USE_LLVM
    explicit مُنشئ_IR(llvm::LLVMContext& سياق);
#endif
    
    // ───────────────────────────────────────────────────────────────────────
    // موضع الإدراج
    // ───────────────────────────────────────────────────────────────────────
    
    /// تعيين موضع الإدراج إلى نهاية كتلة
    void عيِّن_موضع_الإدراج(كتلة_أساسية كتلة);
    
    /// الحصول على الكتلة الحالية
    كتلة_أساسية الكتلة_الحالية() const;
    
    // ───────────────────────────────────────────────────────────────────────
    // إنشاء الثوابت
    // ───────────────────────────────────────────────────────────────────────
    
    /// إنشاء ثابت عدد صحيح
    قيمة أنشئ_ثابت_صحيح(نوع النوع, int64_t القيمة);
    
    /// إنشاء ثابت عشري
    قيمة أنشئ_ثابت_عشري(نوع النوع, double القيمة);
    
    /// إنشاء ثابت نص
    قيمة أنشئ_ثابت_نص(const std::string& النص);
    
    /// إنشاء قيمة null
    قيمة أنشئ_null(نوع النوع);
    
    // ───────────────────────────────────────────────────────────────────────
    // العمليات الحسابية
    // ───────────────────────────────────────────────────────────────────────
    
    /// جمع (add)
    قيمة أنشئ_جمع(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// طرح (sub)
    قيمة أنشئ_طرح(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// ضرب (mul)
    قيمة أنشئ_ضرب(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// قسمة صحيحة بإشارة (sdiv)
    قيمة أنشئ_قسمة(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// قسمة بدون إشارة (udiv)
    قيمة أنشئ_قسمة_بدون_إشارة(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// باقي القسمة (srem)
    قيمة أنشئ_باقي(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// سالب (neg)
    قيمة أنشئ_سالب(قيمة القيمة, const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // العمليات العشرية
    // ───────────────────────────────────────────────────────────────────────
    
    /// جمع عشري (fadd)
    قيمة أنشئ_جمع_عشري(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// طرح عشري (fsub)
    قيمة أنشئ_طرح_عشري(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// ضرب عشري (fmul)
    قيمة أنشئ_ضرب_عشري(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// قسمة عشرية (fdiv)
    قيمة أنشئ_قسمة_عشري(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // العمليات المنطقية
    // ───────────────────────────────────────────────────────────────────────
    
    /// AND منطقي
    قيمة أنشئ_و(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// OR منطقي
    قيمة أنشئ_أو(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// XOR منطقي
    قيمة أنشئ_أو_حصري(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// NOT منطقي
    قيمة أنشئ_نفي(قيمة القيمة, const std::string& اسم = "");
    
    /// إزاحة يسار
    قيمة أنشئ_إزاحة_يسار(قيمة القيمة, قيمة المقدار, const std::string& اسم = "");
    
    /// إزاحة يمين (مع إشارة)
    قيمة أنشئ_إزاحة_يمين(قيمة القيمة, قيمة المقدار, const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // المقارنات
    // ───────────────────────────────────────────────────────────────────────
    
    /// مقارنة تساوي (==)
    قيمة أنشئ_مقارنة_تساوي(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// مقارنة عدم تساوي (!=)
    قيمة أنشئ_مقارنة_عدم_تساوي(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// مقارنة أقل (< للأعداد بإشارة)
    قيمة أنشئ_مقارنة_أقل(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// مقارنة أقل أو يساوي (<=)
    قيمة أنشئ_مقارنة_أقل_أو_يساوي(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// مقارنة أكبر (>)
    قيمة أنشئ_مقارنة_أكبر(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    /// مقارنة أكبر أو يساوي (>=)
    قيمة أنشئ_مقارنة_أكبر_أو_يساوي(قيمة يسار, قيمة يمين, const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // الذاكرة
    // ───────────────────────────────────────────────────────────────────────
    
    /// حجز متغير على المكدس (alloca)
    قيمة أنشئ_حجز(نوع النوع, const std::string& اسم = "");
    
    /// تحميل من الذاكرة (load)
    قيمة أنشئ_تحميل(نوع النوع, قيمة مؤشر, const std::string& اسم = "");
    
    /// تخزين في الذاكرة (store)
    void أنشئ_تخزين(قيمة القيمة, قيمة مؤشر);
    
    /// الحصول على عنوان عنصر (getelementptr)
    قيمة أنشئ_عنوان_عنصر(نوع النوع, قيمة مؤشر, 
                        const std::vector<قيمة>& فهارس,
                        const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // التحكم في التدفق
    // ───────────────────────────────────────────────────────────────────────
    
    /// قفزة غير مشروطة (br label)
    void أنشئ_قفزة(كتلة_أساسية الهدف);
    
    /// قفزة مشروطة (br i1 cond, label true, label false)
    void أنشئ_قفزة_مشروطة(قيمة شرط, كتلة_أساسية إذا_صحيح, كتلة_أساسية إذا_خطأ);
    
    /// رجوع من الدالة (ret)
    void أنشئ_رجوع(قيمة القيمة);
    
    /// رجوع بدون قيمة (ret void)
    void أنشئ_رجوع_فراغ();
    
    /// switch
    void أنشئ_تبديل(قيمة القيمة, كتلة_أساسية الافتراضي,
                   const std::vector<std::pair<قيمة, كتلة_أساسية>>& الحالات);
    
    // ───────────────────────────────────────────────────────────────────────
    // استدعاء الدوال
    // ───────────────────────────────────────────────────────────────────────
    
    /// استدعاء دالة (call)
    قيمة أنشئ_استدعاء(دالة الدالة, 
                      const std::vector<قيمة>& المعطيات,
                      const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // تحويل الأنواع
    // ───────────────────────────────────────────────────────────────────────
    
    /// تحويل عدد صحيح إلى عشري
    قيمة أنشئ_صحيح_إلى_عشري(قيمة القيمة, نوع النوع_الهدف, const std::string& اسم = "");
    
    /// تحويل عشري إلى صحيح
    قيمة أنشئ_عشري_إلى_صحيح(قيمة القيمة, نوع النوع_الهدف, const std::string& اسم = "");
    
    /// توسيع عدد صحيح (مع إشارة)
    قيمة أنشئ_توسيع(قيمة القيمة, نوع النوع_الهدف, const std::string& اسم = "");
    
    /// تقليص عدد صحيح
    قيمة أنشئ_تقليص(قيمة القيمة, نوع النوع_الهدف, const std::string& اسم = "");
    
    /// تحويل مؤشر
    قيمة أنشئ_تحويل_مؤشر(قيمة القيمة, نوع النوع_الهدف, const std::string& اسم = "");
    
    // ───────────────────────────────────────────────────────────────────────
    // PHI Nodes
    // ───────────────────────────────────────────────────────────────────────
    
    /// إنشاء phi node (للتحكم في التدفق)
    قيمة أنشئ_phi(نوع النوع, const std::string& اسم = "");
    
    /// إضافة قيمة واردة إلى phi
    void أضف_وارد_phi(قيمة phi, قيمة القيمة, كتلة_أساسية المصدر);
    
#ifdef SAD_USE_LLVM
    llvm::IRBuilder<>* خام() const { return m_builder.get(); }
#endif

private:
#ifdef SAD_USE_LLVM
    std::unique_ptr<llvm::IRBuilder<>> m_builder;
#endif
};

