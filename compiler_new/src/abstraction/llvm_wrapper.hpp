/**
 * الوحدة (Module) - أعلى مستوى في LLVM
 * 
 * للمبتدئ: الوحدة مثل "الملف" في LLVM:
 * - تحتوي كل الدوال
 * - تحتوي المتغيرات العامة
 * - تحتوي معلومات الهدف (أي معالج/نظام)
 */
class وحدة {
public:
    // ───────────────────────────────────────────────────────────────────────
    // المُنشئات
    // ───────────────────────────────────────────────────────────────────────
    
    وحدة() = default;
    
    /// إنشاء وحدة جديدة
    static std::unique_ptr<وحدة> أنشئ(const std::string& اسم);
    
    // ───────────────────────────────────────────────────────────────────────
    // إدارة الدوال
    // ───────────────────────────────────────────────────────────────────────
    
    /// إنشاء دالة جديدة
    دالة أنشئ_دالة(const std::string& اسم,
                   نوع نوع_الإرجاع,
                   const std::vector<نوع>& أنواع_المعطيات,
                   bool متغيرة_المعطيات = false,
                   دالة::ربط الربط = دالة::ربط::خارجي);
    
    /// الحصول على دالة بالاسم
    std::optional<دالة> احصل_على_دالة(const std::string& اسم) const;
    
    /// التصريح بدالة خارجية
    دالة صرِّح_دالة_خارجية(const std::string& اسم,
                           نوع نوع_الإرجاع,
                           const std::vector<نوع>& أنواع_المعطيات,
                           bool متغيرة_المعطيات = false);
    
    // ───────────────────────────────────────────────────────────────────────
    // المتغيرات العامة
    // ───────────────────────────────────────────────────────────────────────
    
    /// إنشاء متغير عام
    قيمة أنشئ_متغير_عام(const std::string& اسم,
                         نوع النوع,
                         قيمة القيمة_الابتدائية,
                         bool ثابت = false);
    
    // ───────────────────────────────────────────────────────────────────────
    // الأنواع
    // ───────────────────────────────────────────────────────────────────────
    
    /// إنشاء نوع أساسي
    نوع احصل_نوع_أساسي(نوع_أساسي النوع);
    
    /// إنشاء نوع مؤشر
    نوع نوع_مؤشر();
    
    /// الحصول على السياق
    void* السياق();
    
    // ───────────────────────────────────────────────────────────────────────
    // مُنشئ IR
    // ───────────────────────────────────────────────────────────────────────
    
    /// الحصول على مُنشئ IR
    مُنشئ_IR& المُنشئ();
    
    // ───────────────────────────────────────────────────────────────────────
    // التحقق والتحسين
    // ───────────────────────────────────────────────────────────────────────
    
    /// التحقق من صحة الوحدة
    bool تحقق() const;
    
    /// تطبيق التحسينات
    void حسِّن(مستوى_تحسين المستوى);
    
    // ───────────────────────────────────────────────────────────────────────
    // التصدير
    // ───────────────────────────────────────────────────────────────────────
    
    /// تصدير إلى نص IR
    std::string إلى_ir() const;
    
    /// تصدير إلى ملف IR (.ll)
    bool اكتب_ir(const std::string& مسار) const;
    
    /// تصدير إلى bitcode (.bc)
    bool اكتب_bitcode(const std::string& مسار) const;
    
    /// تصدير إلى ملف كائن (.o / .obj)
    bool اكتب_كائن(const std::string& مسار, منصة_هدف الهدف);
    
    // ───────────────────────────────────────────────────────────────────────
    // إعدادات الهدف
    // ───────────────────────────────────────────────────────────────────────
    
    /// تعيين Triple (مثال: x86_64-pc-windows-msvc)
    void عيِّن_triple(const std::string& triple);
    
    /// تعيين Data Layout
    void عيِّن_data_layout(const std::string& layout);
    
#ifdef SAD_USE_LLVM
    llvm::Module* خام() const { return m_module.get(); }
    llvm::LLVMContext& خام_السياق() const { return *m_context; }
#endif

private:
#ifdef SAD_USE_LLVM
    std::unique_ptr<llvm::LLVMContext> m_context;
    std::unique_ptr<llvm::Module> m_module;
    std::unique_ptr<مُنشئ_IR> m_builder;
#endif
};

