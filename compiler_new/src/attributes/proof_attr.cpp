/**
 * نتيجة تحليل السمة
 */
struct نتيجة_تحليل_سمة {
    bool نجح = false;
    سمة السمة;
    std::string رسالة_خطأ;
};

/**
 * محلل السمات
 */
class محلل_السمات {
private:
    std::unordered_map<std::string, نوع_السمة> الأنواع_المعروفة = {
        {"برهان", نوع_السمة::برهان},
        {"prove", نوع_السمة::برهان},
        {"تحقق", نوع_السمة::تحقق},
        {"verify", نوع_السمة::تحقق},
        {"موثوق", نوع_السمة::موثوق},
        {"unsafe", نوع_السمة::موثوق},
        {"نقي", نوع_السمة::نقي},
        {"pure", نوع_السمة::نقي},
        {"ثابت", نوع_السمة::ثابت},
        {"invariant", نوع_السمة::ثابت},
        {"متغير", نوع_السمة::متغير},
        {"variant", نوع_السمة::متغير},
        {"قبل", نوع_السمة::قبل},
        {"pre", نوع_السمة::قبل},
        {"بعد", نوع_السمة::بعد},
        {"post", نوع_السمة::بعد},
        {"افتراض", نوع_السمة::افتراض},
        {"assume", نوع_السمة::افتراض},
        {"مهلة", نوع_السمة::مهلة},
        {"timeout", نوع_السمة::مهلة},
        {"تخطي_برهان", نوع_السمة::تخطي},
        {"skip_proof", نوع_السمة::تخطي}
    };
    
public:
    /**
     * تحليل سمة من نص
     * مثال: "برهان" أو "مهلة(30)"
     */
    نتيجة_تحليل_سمة حلل(const std::string& نص, int السطر = 0, int العمود = 0) {
        نتيجة_تحليل_سمة نتيجة;
        
        size_t موضع = 0;
        
        // تخطي #[
        while (موضع < نص.size() && (نص[موضع] == '#' || نص[موضع] == '[' || نص[موضع] == ' ')) {
            موضع++;
        }
        
        // قراءة الاسم
        std::string الاسم;
        while (موضع < نص.size() && نص[موضع] != '(' && نص[موضع] != ']' && نص[موضع] != ' ') {
            الاسم += نص[موضع++];
        }
        
        // البحث عن النوع
        auto it = الأنواع_المعروفة.find(الاسم);
        if (it == الأنواع_المعروفة.end()) {
            نتيجة.نجح = false;
            نتيجة.رسالة_خطأ = "سمة غير معروفة: " + الاسم;
            return نتيجة;
        }
        
        نتيجة.السمة.النوع = it->second;
        نتيجة.السمة.الاسم_النصي = الاسم;
        نتيجة.السمة.السطر = السطر;
        نتيجة.السمة.العمود = العمود;
        
        // تخطي الفراغات
        while (موضع < نص.size() && نص[موضع] == ' ') موضع++;
        
        // قراءة المعاملات إن وجدت
        if (موضع < نص.size() && نص[موضع] == '(') {
            موضع++; // تخطي (
            
            while (موضع < نص.size() && نص[موضع] != ')') {
                // تخطي الفراغات
                while (موضع < نص.size() && نص[موضع] == ' ') موضع++;
                
                معامل_سمة معامل;
                
                // قراءة اسم المعامل أو قيمة مباشرة
                while (موضع < نص.size() && 
                       نص[موضع] != '=' && 
                       نص[موضع] != ',' && 
                       نص[موضع] != ')' &&
                       نص[موضع] != ' ') {
                    معامل.الاسم += نص[موضع++];
                }
                
                // تخطي الفراغات
                while (موضع < نص.size() && نص[موضع] == ' ') موضع++;
                
                // هل يوجد قيمة؟
                if (موضع < نص.size() && نص[موضع] == '=') {
                    موضع++; // تخطي =
                    while (موضع < نص.size() && نص[موضع] == ' ') موضع++;
                    
                    // قراءة القيمة
                    if (موضع < نص.size() && نص[موضع] == '"') {
                        موضع++; // تخطي "
                        while (موضع < نص.size() && نص[موضع] != '"') {
                            معامل.القيمة += نص[موضع++];
                        }
                        if (موضع < نص.size()) موضع++; // تخطي "
                    } else {
                        while (موضع < نص.size() && 
                               نص[موضع] != ',' && 
                               نص[موضع] != ')' &&
                               نص[موضع] != ' ') {
                            معامل.القيمة += نص[موضع++];
                        }
                    }
                    معامل.لديه_قيمة = true;
                } else {
                    // المعامل هو القيمة نفسها
                    معامل.القيمة = معامل.الاسم;
                    معامل.لديه_قيمة = true;
                }
                
                if (!معامل.الاسم.empty()) {
                    نتيجة.السمة.المعاملات.push_back(معامل);
                }
                
                // تخطي الفراغات والفاصلة
                while (موضع < نص.size() && (نص[موضع] == ' ' || نص[موضع] == ',')) {
                    موضع++;
                }
            }
        }
        
        نتيجة.نجح = true;
        return نتيجة;
    }
};

