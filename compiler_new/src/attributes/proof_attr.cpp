/**
 * معلومات البرهان
 */
struct معلومات_برهان {
    std::string اسم_الدالة;
    int مهلة_بالثواني = 30;
    bool تخطي = false;
    bool نقي = false;
    
    // الشروط المستخرجة
    std::vector<std::string> الشروط_المسبقة;
    std::vector<std::string> الشروط_اللاحقة;
    std::vector<std::string> الثوابت;
    std::vector<std::string> الافتراضات;
};

/**
 * معالج سمة البرهان
 */
class معالج_البرهان {
private:
    محلل_السمات المحلل;
    
public:
    /**
     * معالجة سمات دالة
     */
    معلومات_برهان عالج(const std::vector<سمة>& السمات,
                        const std::string& اسم_الدالة) {
        معلومات_برهان معلومات;
        معلومات.اسم_الدالة = اسم_الدالة;
        
        for (const auto& سمة : السمات) {
            switch (سمة.النوع) {
                case نوع_السمة::برهان:
                    // معالجة سمة البرهان
                    break;
                
                case نوع_السمة::مهلة:
                    if (!سمة.المعاملات.empty()) {
                        try {
                            معلومات.مهلة_بالثواني = std::stoi(سمة.المعاملات[0].القيمة);
                        } catch (...) {}
                    }
                    break;
                
                case نوع_السمة::تخطي:
                    معلومات.تخطي = true;
                    break;
                
                case نوع_السمة::نقي:
                    معلومات.نقي = true;
                    break;
                
                case نوع_السمة::قبل:
                    if (!سمة.المعاملات.empty()) {
                        معلومات.الشروط_المسبقة.push_back(سمة.المعاملات[0].القيمة);
                    }
                    break;
                
                case نوع_السمة::بعد:
                    if (!سمة.المعاملات.empty()) {
                        معلومات.الشروط_اللاحقة.push_back(سمة.المعاملات[0].القيمة);
                    }
                    break;
                
                case نوع_السمة::ثابت:
                    if (!سمة.المعاملات.empty()) {
                        معلومات.الثوابت.push_back(سمة.المعاملات[0].القيمة);
                    }
                    break;
                
                case نوع_السمة::افتراض:
                    if (!سمة.المعاملات.empty()) {
                        معلومات.الافتراضات.push_back(سمة.المعاملات[0].القيمة);
                    }
                    break;
                
                default:
                    break;
            }
        }
        
        return معلومات;
    }
    
    /**
     * هل الدالة تحتاج برهان؟
     */
    bool تحتاج_برهان(const std::vector<سمة>& السمات) {
        for (const auto& سمة : السمات) {
            if (سمة.النوع == نوع_السمة::برهان) {
                return true;
            }
        }
        return false;
    }
};

