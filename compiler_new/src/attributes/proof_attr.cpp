/**
 * مولّد كود التحقق
 */
class مولّد_كود_البرهان {
public:
    /**
     * توليد كود التحقق من الشروط المسبقة
     */
    std::string ولّد_فحص_مسبق(const معلومات_برهان& معلومات) {
        std::stringstream كود;
        
        for (const auto& شرط : معلومات.الشروط_المسبقة) {
            كود << "    // شرط مسبق\n";
            كود << "    if (!(" << شرط << ")) {\n";
            كود << "        throw std::runtime_error(\"فشل الشرط المسبق: " 
                 << شرط << "\");\n";
            كود << "    }\n";
        }
        
        return كود.str();
    }
    
    /**
     * توليد كود التحقق من الشروط اللاحقة
     */
    std::string ولّد_فحص_لاحق(const معلومات_برهان& معلومات,
                              const std::string& متغير_النتيجة = "النتيجة") {
        std::stringstream كود;
        
        for (const auto& شرط : معلومات.الشروط_اللاحقة) {
            // استبدال "النتيجة" بالمتغير الفعلي
            std::string شرط_معدّل = شرط;
            // TODO: استبدال حقيقي
            
            كود << "    // شرط لاحق\n";
            كود << "    if (!(" << شرط_معدّل << ")) {\n";
            كود << "        throw std::runtime_error(\"فشل الشرط اللاحق: " 
                 << شرط << "\");\n";
            كود << "    }\n";
        }
        
        return كود.str();
    }
    
    /**
     * توليد كود البرهان كاملاً
     */
    std::string ولّد_غلاف_برهان(const معلومات_برهان& معلومات,
                                 const std::string& توقيع_الدالة,
                                 const std::string& جسم_الدالة) {
        std::stringstream كود;
        
        كود << "// دالة مع برهان: " << معلومات.اسم_الدالة << "\n";
        كود << توقيع_الدالة << " {\n";
        
        // فحص الشروط المسبقة
        كود << ولّد_فحص_مسبق(معلومات);
        
        كود << "\n    // الجسم الأصلي\n";
        كود << جسم_الدالة;
        
        // فحص الشروط اللاحقة
        كود << "\n";
        كود << ولّد_فحص_لاحق(معلومات);
        
        كود << "}\n";
        
        return كود.str();
    }
};

