/**
 * نوع السمة
 */
enum class نوع_السمة {
    برهان,           // #[برهان] - إثبات صحة الدالة
    تحقق,            // #[تحقق] - تحقق وقت التشغيل فقط
    موثوق,           // #[موثوق] - الدالة موثوقة (unsafe)
    نقي,             // #[نقي] - الدالة بدون تأثيرات جانبية
    ثابت,            // #[ثابت] - ثابت الصنف
    متغير,           // #[متغير] - متغير تناقصي للحلقة
    قبل,             // #[قبل] - شرط مسبق
    بعد,             // #[بعد] - شرط لاحق
    افتراض,          // #[افتراض] - افتراض للمحقق
    مهلة,            // #[مهلة(ثواني)] - مهلة التحقق
    تخطي             // #[تخطي_برهان] - تخطي هذا البرهان
};

/**
 * معامل السمة
 */
struct معامل_سمة {
    std::string الاسم;
    std::string القيمة;
    bool لديه_قيمة = false;
};

/**
 * سمة كاملة
 */
struct سمة {
    نوع_السمة النوع;
    std::string الاسم_النصي;
    std::vector<معامل_سمة> المعاملات;
    int السطر = 0;
    int العمود = 0;
    
    /**
     * الحصول على قيمة معامل
     */
    std::optional<std::string> قيمة_المعامل(const std::string& اسم) const {
        for (const auto& م : المعاملات) {
            if (م.الاسم == اسم) {
                return م.القيمة;
            }
        }
        return std::nullopt;
    }
    
    /**
     * هل المعامل موجود؟
     */
    bool لديه_معامل(const std::string& اسم) const {
        for (const auto& م : المعاملات) {
            if (م.الاسم == اسم) return true;
        }
        return false;
    }
};

