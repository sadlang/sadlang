/**
 * محلل سمة #[ممثل]
 */
class محلل_سمة_ممثل {
public:
    /**
     * تحليل السمة
     */
    خيارات_ممثل حلل(const std::string& نص_السمة) {
        خيارات_ممثل خيارات;
        
        // تحليل المعاملات
        // #[ممثل(اسم = "خادم", قابل_للتوزيع = نعم, حد_الرسائل = 5000)]
        
        size_t بداية = نص_السمة.find('(');
        size_t نهاية = نص_السمة.rfind(')');
        
        if (بداية == std::string::npos) {
            // سمة بدون معاملات
            return خيارات;
        }
        
        std::string معاملات = نص_السمة.substr(بداية + 1, نهاية - بداية - 1);
        
        // تحليل كل معامل
        size_t موقع = 0;
        while (موقع < معاملات.length()) {
            // البحث عن =
            size_t يساوي = معاملات.find('=', موقع);
            if (يساوي == std::string::npos) break;
            
            std::string مفتاح = قص_مسافات(معاملات.substr(موقع, يساوي - موقع));
            
            // البحث عن نهاية القيمة
            size_t فاصلة = معاملات.find(',', يساوي);
            if (فاصلة == std::string::npos) فاصلة = معاملات.length();
            
            std::string قيمة = قص_مسافات(معاملات.substr(يساوي + 1, فاصلة - يساوي - 1));
            
            // إزالة علامات التنصيص
            if (قيمة.front() == '"' && قيمة.back() == '"') {
                قيمة = قيمة.substr(1, قيمة.length() - 2);
            }
            
            // تطبيق القيمة
            if (مفتاح == "اسم" || مفتاح == "name") {
                خيارات.اسم = قيمة;
            } else if (مفتاح == "قابل_للتوزيع" || مفتاح == "distributed") {
                خيارات.قابل_للتوزيع = (قيمة == "نعم" || قيمة == "true");
            } else if (مفتاح == "مستمر" || مفتاح == "persistent") {
                خيارات.مستمر = (قيمة == "نعم" || قيمة == "true");
            } else if (مفتاح == "حد_الرسائل" || مفتاح == "mailbox_limit") {
                خيارات.حد_الرسائل = std::stoi(قيمة);
            } else if (مفتاح == "أولوية" || مفتاح == "priority") {
                خيارات.أولوية = std::stoi(قيمة);
            } else if (مفتاح == "مشرف" || مفتاح == "supervisor") {
                خيارات.مشرف = قيمة;
            }
            
            موقع = فاصلة + 1;
        }
        
        return خيارات;
    }
    
private:
    std::string قص_مسافات(const std::string& نص) {
        size_t بداية = نص.find_first_not_of(" \t");
        size_t نهاية = نص.find_last_not_of(" \t");
        if (بداية == std::string::npos) return "";
        return نص.substr(بداية, نهاية - بداية + 1);
    }
};

