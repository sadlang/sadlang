/**
 * معلومات رسالة
 */
struct معلومات_رسالة {
    std::string اسم;
    std::vector<std::pair<std::string, std::string>> معاملات;  // اسم، نوع
    std::string نوع_إرجاع;
    bool متزامن = false;  // إذا كانت تنتظر الرد
};

/**
 * معلومات حالة
 */
struct معلومات_حالة {
    std::string اسم;
    std::string نوع;
    std::string قيمة_افتراضية;
};

/**
 * تعريف Actor محول
 */
struct تعريف_Actor {
    std::string اسم_الصنف;
    خيارات_ممثل خيارات;
    std::vector<معلومات_رسالة> رسائل;
    std::vector<معلومات_حالة> حالة;
};

/**
 * محول الصنف إلى Actor
 */
class محوّل_إلى_Actor {
private:
    تعريف_Actor تعريف_;
    
public:
    /**
     * بدء التحويل
     */
    void ابدأ(const std::string& اسم_الصنف, const خيارات_ممثل& خيارات) {
        تعريف_.اسم_الصنف = اسم_الصنف;
        تعريف_.خيارات = خيارات;
    }
    
    /**
     * إضافة رسالة
     */
    void أضف_رسالة(const معلومات_رسالة& رسالة) {
        تعريف_.رسائل.push_back(رسالة);
    }
    
    /**
     * إضافة متغير حالة
     */
    void أضف_حالة(const معلومات_حالة& حالة) {
        تعريف_.حالة.push_back(حالة);
    }
    
    /**
     * توليد كود Actor
     */
    std::string ولّد_كود() {
        std::string كود;
        
        // رأس الصنف المُولّد
        كود += "// كود Actor مُولّد تلقائياً\n";
        كود += "صنف " + تعريف_.اسم_الصنف + "_Actor\n";
        
        // الحالة
        for (const auto& ح : تعريف_.حالة) {
            كود += "    خاص متغير " + ح.اسم + ": " + ح.نوع + "\n";
        }
        
        // صندوق الرسائل
        كود += "    خاص متغير _صندوق: صندوق_رسائل\n";
        كود += "    خاص متغير _معرف: نص\n\n";
        
        // المُنشئ
        كود += "    عام دالة جديد() -> " + تعريف_.اسم_الصنف + "_Actor\n";
        كود += "        ذاتي._معرف = ولّد_معرف()\n";
        كود += "        ذاتي._صندوق = صندوق_رسائل.جديد()\n";
        كود += "    نهاية\n\n";
        
        // الرسائل
        for (const auto& ر : تعريف_.رسائل) {
            كود += ولّد_دالة_رسالة(ر);
        }
        
        // حلقة المعالجة
        كود += ولّد_حلقة_معالجة();
        
        كود += "نهاية\n";
        
        return كود;
    }
    
private:
    std::string ولّد_دالة_رسالة(const معلومات_رسالة& ر) {
        std::string كود;
        
        // دالة الإرسال
        كود += "    عام دالة " + ر.اسم + "(";
        for (size_t i = 0; i < ر.معاملات.size(); i++) {
            if (i > 0) كود += ", ";
            كود += ر.معاملات[i].first + ": " + ر.معاملات[i].second;
        }
        كود += ")";
        
        if (!ر.نوع_إرجاع.empty() && ر.نوع_إرجاع != "void") {
            كود += " -> " + ر.نوع_إرجاع;
        }
        كود += "\n";
        
        كود += "        // إرسال رسالة\n";
        كود += "        ذاتي._صندوق.أرسل(\"" + ر.اسم + "\"";
        for (const auto& م : ر.معاملات) {
            كود += ", " + م.first;
        }
        كود += ")\n";
        كود += "    نهاية\n\n";
        
        return كود;
    }
    
    std::string ولّد_حلقة_معالجة() {
        std::string كود;
        
        كود += "    خاص دالة _عالج_رسائل()\n";
        كود += "        بينما صحيح اعمل\n";
        كود += "            متغير رسالة = ذاتي._صندوق.استلم()\n";
        كود += "            طابق رسالة.اسم\n";
        
        for (const auto& ر : تعريف_.رسائل) {
            كود += "                حالة \"" + ر.اسم + "\" => ذاتي._" + ر.اسم + "_معالج(رسالة)\n";
        }
        
        كود += "            نهاية\n";
        كود += "        نهاية\n";
        كود += "    نهاية\n";
        
        return كود;
    }
};

