# اختبار تضارب الأسماء

دالة مصفوفة نطاق(رقم نهاية_نطاق = 10، رقم بداية = 0، رقم خطوة = 1)
    مصفوفة نتيجة = []
    رقم ع = بداية
    بينما (ع < نهاية_نطاق)
        أضف(نتيجة، ع)
        ع = ع + خطوة
    نهاية
    إرجاع نتيجة
نهاية

اطبع("=== اختبار 1 ===")
مصفوفة نطاق1 = نطاق()
اطبع("نطاق1:", نطاق1)

اطبع("\n=== اختبار 2 ===")
مصفوفة نطاق2 = نطاق(5)
اطبع("نطاق2:", نطاق2)
