# اختبار شامل للبنية الجديدة مع "نهاية"

# 1. اختبار if-else
دالة اختبار_if(عدد: صحيح)
    إذا (عدد > 10)
        اطبع("العدد أكبر من 10")
    وإلا
        اطبع("العدد أصغر أو يساوي 10")
    نهاية
نهاية

# 2. اختبار while
دالة اختبار_while()
    متغير عداد = 0
    بينما (عداد < 3)
        اطبع("عداد: ")
        اطبع(عداد)
        عداد = عداد + 1
    نهاية
نهاية

# 3. اختبار for
دالة اختبار_for()
    لكل (عنصر في [1, 2, 3])
        اطبع("عنصر: ")
        اطبع(عنصر)
    نهاية
نهاية

