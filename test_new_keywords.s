اطبع("=== المشغلات الحسابية (Arithmetic Operators) ===\n")

# الجمع (+)
رقم جمع = 10 + 5
اطبع("10 + 5 =", جمع, "\n")

# الطرح (-)
رقم طرح = 20 - 7
اطبع("20 - 7 =", طرح, "\n")

# الضرب (*)
رقم ضرب = 6 * 4
اطبع("6 × 4 =", ضرب, "\n")

# القسمة (/)
رقم قسمة = 15 / 3
اطبع("15 ÷ 3 =", قسمة, "\n")

# باقي القسمة (%)
رقم باقي = 17 % 5
اطبع("17 % 5 =", باقي, "\n")

# الأس (**)
رقم أس = 2 ** 8
اطبع("2^8 =", أس, "\n")

# السالب الأحادي (-)
رقم موجب = 42
رقم سالب = -موجب
اطبع("سالب 42 =", سالب, "\n")

اطبع("\n=== المشغلات الحسابية على أنواع مختلفة ===\n")

# عمليات على الأعداد العشرية
عشري ع1 = 10.5 + 5.3
عشري ع2 = 20.8 - 7.2
عشري ع3 = 3.5 * 2.0
عشري ع4 = 10.0 / 4.0

اطبع("10.5 + 5.3 =", ع1, "\n")
اطبع("20.8 - 7.2 =", ع2, "\n")
اطبع("3.5 × 2.0 =", ع3, "\n")
اطبع("10.0 ÷ 4.0 =", ع4, "\n")

# عمليات مختلطة (int + float)
عشري مختلط1 = 10 + 5.5
عشري مختلط2 = 20.5 - 5
اطبع("10 + 5.5 =", مختلط1, "\n")
اطبع("20.5 - 5 =", مختلط2, "\n")

اطبع("\n=== مشغلات المقارنة (Comparison Operators) ===\n")

# أكبر من (>)
منطقي أكبر = 10 > 5
اطبع("10 > 5 هو", أكبر, "\n")

# أصغر من (<)
منطقي أصغر = 3 < 7
اطبع("3 < 7 هو", أصغر, "\n")

# يساوي (==)
منطقي يساوي = 15 == 15
اطبع("15 == 15 هو", يساوي, "\n")

# لا يساوي (!=)
منطقي لا_يساوي = 8 != 9
اطبع("8 != 9 هو", لا_يساوي, "\n")

# أكبر من أو يساوي (>=)
منطقي أكبر_يساوي1 = 12 >= 10
منطقي أكبر_يساوي2 = 10 >= 10
اطبع("12 >= 10 هو", أكبر_يساوي1, "\n")
اطبع("10 >= 10 هو", أكبر_يساوي2, "\n")

# أصغر من أو يساوي (<=)
منطقي أصغر_يساوي1 = 6 <= 10
منطقي أصغر_يساوي2 = 10 <= 10
اطبع("6 <= 10 هو", أصغر_يساوي1, "\n")
اطبع("10 <= 10 هو", أصغر_يساوي2, "\n")

اطبع("\n=== مقارنات على أنواع مختلفة ===\n")

# مقارنة نصوص
منطقي نص1 = "أحمد" == "أحمد"
منطقي نص2 = "أحمد" != "محمد"
اطبع("'أحمد' == 'أحمد' هو", نص1, "\n")
اطبع("'أحمد' != 'محمد' هو", نص2, "\n")

# مقارنة منطقية
منطقي منطق1 = صحيح == صحيح
منطقي منطق2 = صحيح != خطأ
اطبع("صحيح == صحيح هو", منطق1, "\n")
اطبع("صحيح != خطأ هو", منطق2, "\n")

اطبع("\n=== المشغلات المنطقية (Logical Operators) ===\n")

# و (and)
منطقي و1 = صحيح و صحيح
منطقي و2 = صحيح و خطأ
منطقي و3 = خطأ و خطأ
اطبع("صحيح و صحيح =", و1, "\n")
اطبع("صحيح و خطأ =", و2, "\n")
اطبع("خطأ و خطأ =", و3, "\n")
