/**
 * واجهة مزود AI
 */
class مزود_AI {
public:
    virtual ~مزود_AI() = default;
    
    /**
     * اسم المزود
     */
    virtual std::string الاسم() const = 0;
    
    /**
     * هل المزود متاح؟
     */
    virtual bool متاح() const = 0;
    
    /**
     * تحليل الذعر
     */
    virtual نتيجة_تحليل_AI حلل(const معلومات_ذعر& معلومات) = 0;
};

/**
 * مزود AI محلي (يستخدم قواعد ثابتة)
 */
class مزود_AI_محلي : public مزود_AI {
public:
    std::string الاسم() const override { return "محلي"; }
    
    bool متاح() const override { return true; }
    
    نتيجة_تحليل_AI حلل(const معلومات_ذعر& معلومات) override {
        نتيجة_تحليل_AI نتيجة;
        نتيجة.نجح = true;
        نتيجة.مصدر_التحليل = "محلي";
        
        // تحليل بناءً على نوع الذعر
        حلل_حسب_النوع(معلومات, نتيجة);
        
        // تحليل إضافي من السياق
        حلل_من_السياق(معلومات, نتيجة);
        
        return نتيجة;
    }
    
private:
    void حلل_حسب_النوع(const معلومات_ذعر& معلومات, نتيجة_تحليل_AI& نتيجة);
    void حلل_من_السياق(const معلومات_ذعر& معلومات, نتيجة_تحليل_AI& نتيجة);
};

