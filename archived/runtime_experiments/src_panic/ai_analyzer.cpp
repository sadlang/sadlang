inline void مزود_AI_محلي::حلل_من_السياق(
    const معلومات_ذعر& معلومات,
    نتيجة_تحليل_AI& نتيجة) {
    
    // تحليل إضافي من المتغيرات
    for (const auto& [اسم, قيمة] : معلومات.المتغيرات) {
        // فحص قيم مشبوهة
        if (قيمة == "0" && معلومات.النوع == نوع_ذعر::قسمة_على_صفر) {
            نتيجة.الأسباب_المحتملة.push_back(
                "المتغير '" + اسم + "' قيمته صفر"
            );
        }
        
        // فحص فهارس كبيرة
        try {
            int رقم = std::stoi(قيمة);
            if (رقم > 10000 && معلومات.النوع == نوع_ذعر::فهرس_خارج_الحدود) {
                نتيجة.الأسباب_المحتملة.push_back(
                    "المتغير '" + اسم + "' = " + قيمة + " (قيمة كبيرة جداً)"
                );
            }
        } catch (...) {
            // ليس رقم
        }
    }
    
    // تحليل من آخر الأحداث
    for (const auto& حدث : معلومات.آخر_الأحداث) {
        if (حدث.النوع == نوع_حدث::كتابة_متغير) {
            // فحص آخر تعيينات قبل الخطأ
            auto it = حدث.بيانات_إضافية.find("قيمة");
            if (it != حدث.بيانات_إضافية.end()) {
                // يمكن إضافة تحليل أعمق هنا
            }
        }
    }
}

