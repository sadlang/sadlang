/**
 * مستوى الثقة في التحليل
 */
enum class مستوى_ثقة {
    منخفض,    // أقل من 50%
    متوسط,    // 50-75%
    عالي,     // 75-90%
    مؤكد,     // أكثر من 90%
};

/**
 * نتيجة تحليل AI
 */
struct نتيجة_تحليل_AI {
    bool نجح = false;
    مستوى_ثقة الثقة = مستوى_ثقة::منخفض;
    
    // التحليل
    std::string السبب_الجذري;
    std::string شرح_مفصل;
    std::vector<std::string> الأسباب_المحتملة;
    
    // الحل
    std::string الحل_الموصى;
    std::string كود_مقترح;
    std::vector<std::string> خطوات_الإصلاح;
    
    // موارد إضافية
    std::vector<std::string> روابط_مفيدة;
    std::vector<std::string> أمثلة_مشابهة;
    
    // معلومات التحليل
    std::string مصدر_التحليل;  // "local" أو "cloud"
    double وقت_التحليل_ms = 0;
    std::string رسالة_خطأ;
    
    /**
     * تقرير التحليل
     */
    std::string تقرير() const {
        std::stringstream ss;
        
        if (!نجح) {
            ss << "❌ فشل التحليل: " << رسالة_خطأ << "\n";
            return ss.str();
        }
        
        ss << "\n"
           << "╔══════════════════════════════════════════════════════════════════╗\n"
           << "║  🤖 تحليل الذكاء الاصطناعي                                        ║\n"
           << "╠══════════════════════════════════════════════════════════════════╣\n";
        
        // مستوى الثقة
        ss << "║  📊 مستوى الثقة: ";
        switch (الثقة) {
            case مستوى_ثقة::مؤكد: ss << "مؤكد ████████████"; break;
            case مستوى_ثقة::عالي: ss << "عالي █████████░░░"; break;
            case مستوى_ثقة::متوسط: ss << "متوسط ██████░░░░░░"; break;
            case مستوى_ثقة::منخفض: ss << "منخفض ███░░░░░░░░░"; break;
        }
        ss << "\n║\n";
        
        // السبب الجذري
        ss << "║  🎯 السبب الجذري:\n"
           << "║     " << السبب_الجذري << "\n║\n";
        
        // الشرح المفصل
        if (!شرح_مفصل.empty()) {
            ss << "║  📖 الشرح:\n";
            std::istringstream شرح_stream(شرح_مفصل);
            std::string سطر;
            while (std::getline(شرح_stream, سطر)) {
                ss << "║     " << سطر << "\n";
            }
            ss << "║\n";
        }
        
        // الحل
        ss << "║  💡 الحل الموصى:\n"
           << "║     " << الحل_الموصى << "\n║\n";
        
        // الكود المقترح
        if (!كود_مقترح.empty()) {
            ss << "║  📝 كود مقترح:\n"
               << "║     ┌────────────────────────────────────────┐\n";
            std::istringstream كود_stream(كود_مقترح);
            std::string سطر;
            while (std::getline(كود_stream, سطر)) {
                ss << "║     │ " << سطر << "\n";
            }
            ss << "║     └────────────────────────────────────────┘\n║\n";
        }
        
        // خطوات الإصلاح
        if (!خطوات_الإصلاح.empty()) {
            ss << "║  📋 خطوات الإصلاح:\n";
            for (size_t i = 0; i < خطوات_الإصلاح.size(); i++) {
                ss << "║     " << (i + 1) << ". " << خطوات_الإصلاح[i] << "\n";
            }
            ss << "║\n";
        }
        
        ss << "╚══════════════════════════════════════════════════════════════════╝\n";
        
        return ss.str();
    }
};

