            نتيجة.كود_مقترح = 
                "إذا قيمة != عدم\n"
                "    استخدم(قيمة)\n"
                "وإلا\n"
                "    // تعامل مع حالة عدم\n"
                "نهاية\n"
                "\n"
                "// أو استخدم عامل الأمان:\n"
                "قيمة?.دالة()";
            break;
            
        case نوع_ذعر::تجاوز_المكدس:
            نتيجة.الثقة = مستوى_ثقة::عالي;
            نتيجة.السبب_الجذري = "تكرار لا نهائي أو تداخل دوال عميق جداً";
            نتيجة.الحل_الموصى = "أضف حالة إيقاف للتكرار أو حوّله لحلقة";
