/**
 * مُحلل AI للذعر
 */
class مُحلل_ذعر_AI {
public:
    /**
     * إعدادات المُحلل
     */
    struct إعدادات {
        bool استخدم_محلي = true;
        bool استخدم_سحابي = false;
        std::string endpoint_سحابي;
        std::string api_key;
        int timeout_ms = 5000;
        bool غير_متزامن = false;
    };
    
    /**
     * الحصول على المُحلل العالمي
     */
    static مُحلل_ذعر_AI& المثال() {
        static مُحلل_ذعر_AI مثال;
        return مثال;
    }
    
    /**
     * تعيين الإعدادات
     */
    void عيِّن_الإعدادات(إعدادات إعدادات) {
        m_إعدادات = std::move(إعدادات);
        
        // إنشاء المزودين
        m_مزودين.clear();
        
        if (m_إعدادات.استخدم_محلي) {
            m_مزودين.push_back(std::make_unique<مزود_AI_محلي>());
        }
        
        if (m_إعدادات.استخدم_سحابي && !m_إعدادات.endpoint_سحابي.empty()) {
            m_مزودين.push_back(std::make_unique<مزود_AI_سحابي>(
                m_إعدادات.endpoint_سحابي,
                m_إعدادات.api_key
            ));
        }
    }
    
    /**
     * تحليل ذعر
     */
    نتيجة_تحليل_AI حلل(const معلومات_ذعر& معلومات) {
        auto بداية = std::chrono::steady_clock::now();
        
        // جرب كل مزود
        for (auto& مزود : m_مزودين) {
            if (!مزود->متاح()) continue;
            
            auto نتيجة = مزود->حلل(معلومات);
            
            if (نتيجة.نجح) {
                auto نهاية = std::chrono::steady_clock::now();
                نتيجة.وقت_التحليل_ms = 
                    std::chrono::duration<double, std::milli>(نهاية - بداية).count();
                return نتيجة;
            }
        }
        
        // فشل كل المزودين
        نتيجة_تحليل_AI نتيجة;
        نتيجة.نجح = false;
        نتيجة.رسالة_خطأ = "لا يوجد مزود AI متاح";
        return نتيجة;
    }
    
    /**
     * تحليل غير متزامن
     */
    std::future<نتيجة_تحليل_AI> حلل_غير_متزامن(const معلومات_ذعر& معلومات) {
        return std::async(std::launch::async, [this, معلومات]() {
            return حلل(معلومات);
        });
    }
    
private:
    مُحلل_ذعر_AI() {
        // إعداد افتراضي
        m_مزودين.push_back(std::make_unique<مزود_AI_محلي>());
    }
    
    إعدادات m_إعدادات;
    std::vector<std::unique_ptr<مزود_AI>> m_مزودين;
};

