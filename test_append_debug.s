# اختبار append مباشر لنرى هل المشكلة في المتغير أم الدالة

# اختبار 1: array عادي
اطبع("=== اختبار 1 ===")
مصفوفة م1 = []
اطبع("م1 قبل:", م1)
أضف(م1، 5)
اطبع("م1 بعد:", م1)

# اختبار 2: دالة بدون default
دالة مصفوفة ق1()
    مصفوفة ن = []
    اطبع("داخل ق1، ن =", ن)
    أضف(ن، 10)
    إرجاع ن
نهاية

اطبع("\n=== اختبار 2 ===")
مصفوفة ن1 = ق1()
اطبع("نتيجة ق1:", ن1)

# اختبار 3: دالة مع default واحد
دالة مصفوفة ق2(رقم س = 5)
    مصفوفة ن = []
    اطبع("داخل ق2، س =", س، "، ن =", ن)
    أضف(ن، س)
    إرجاع ن
نهاية

اطبع("\n=== اختبار 3 ===")
مصفوفة ن2 = ق2()
اطبع("نتيجة ق2:", ن2)

# اختبار 4: دالة مع 3 defaults (مثل نطاق)
دالة مصفوفة ق3(رقم أ = 1، رقم ب = 2، رقم ج = 3)
    مصفوفة ن = []
    اطبع("داخل ق3، أ =", أ، "، ب =", ب، "، ج =", ج)
    أضف(ن، أ)
    إرجاع ن
نهاية

اطبع("\n=== اختبار 4 ===")
مصفوفة ن3 = ق3()
اطبع("نتيجة ق3:", ن3)
