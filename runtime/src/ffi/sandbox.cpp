/**
 * مراقب موارد sandbox
 */
class مراقب_موارد {
public:
    مراقب_موارد(إعدادات_sandbox إعدادات)
        : m_إعدادات(std::move(إعدادات)) {}
    
    /**
     * بدء المراقبة
     */
    void ابدأ() {
        m_وقت_البدء = std::chrono::steady_clock::now();
        m_يعمل = true;
        
        // خيط مراقبة الوقت
        m_خيط_مراقبة = std::thread([this]() {
            while (m_يعمل) {
                std::this_thread::sleep_for(std::chrono::milliseconds(10));
                
                auto الآن = std::chrono::steady_clock::now();
                auto المدة = std::chrono::duration_cast<std::chrono::milliseconds>(
                    الآن - m_وقت_البدء
                );
                
                if (المدة > m_إعدادات.حد_الوقت) {
                    m_تجاوز_الوقت = true;
                    m_يعمل = false;
                    break;
                }
            }
        });
    }
    
    /**
     * إيقاف المراقبة
     */
    void أوقف() {
        m_يعمل = false;
        if (m_خيط_مراقبة.joinable()) {
            m_خيط_مراقبة.join();
        }
        m_وقت_النهاية = std::chrono::steady_clock::now();
    }
    
    /**
     * هل تجاوز الوقت؟
     */
    bool تجاوز_الوقت() const { return m_تجاوز_الوقت; }
    
    /**
     * المدة الفعلية
     */
    std::chrono::milliseconds المدة() const {
        auto نهاية = m_يعمل ? std::chrono::steady_clock::now() : m_وقت_النهاية;
        return std::chrono::duration_cast<std::chrono::milliseconds>(
            نهاية - m_وقت_البدء
        );
    }
    
    /**
     * تسجيل syscall
     */
    void سجِّل_syscall(const std::string& اسم) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_عدد_syscalls++;
        m_syscalls.push_back(اسم);
        
        // فحص إذا كانت محظورة
        if (m_إعدادات.المستوى >= مستوى_عزل::متوسط) {
            if (!m_إعدادات.syscalls_مسموحة.empty() &&
                m_إعدادات.syscalls_مسموحة.find(اسم) == m_إعدادات.syscalls_مسموحة.end()) {
                m_انتهاكات.push_back("syscall محظور: " + اسم);
            }
        }
    }
    
    /**
     * تسجيل وصول لملف
     */
    void سجِّل_وصول_ملف(const std::string& مسار, bool كتابة) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        if (كتابة && !m_إعدادات.ملفات.مسموح_الكتابة) {
            m_انتهاكات.push_back("محاولة كتابة لملف: " + مسار);
        } else if (!كتابة && !m_إعدادات.ملفات.مسموح_القراءة) {
            m_انتهاكات.push_back("محاولة قراءة من ملف: " + مسار);
        } else if (!m_إعدادات.ملفات.مسار_مسموح(مسار)) {
            m_انتهاكات.push_back("وصول لمسار غير مسموح: " + مسار);
        }
    }
    
    /**
     * تسجيل اتصال شبكة
     */
    void سجِّل_اتصال_شبكة(const std::string& مضيف, int منفذ) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        if (!m_إعدادات.شبكة.مسموح_المضيف(مضيف, منفذ)) {
            m_انتهاكات.push_back(
                "اتصال شبكة غير مسموح: " + مضيف + ":" + std::to_string(منفذ)
            );
        }
    }
    
    /**
     * تحديث استخدام الذاكرة
     */
    void حدِّث_ذاكرة(size_t حجم) {
        m_ذاكرة_حالية = حجم;
        if (حجم > m_ذاكرة_قصوى) m_ذاكرة_قصوى = حجم;
        
        if (حجم > m_إعدادات.حد_الذاكرة_بايت) {
            m_تجاوز_الذاكرة = true;
        }
    }
    
    /**
     * هل تجاوز الذاكرة؟
     */
    bool تجاوز_الذاكرة() const { return m_تجاوز_الذاكرة; }
    
    /**
     * الحصول على الانتهاكات
     */
    std::vector<std::string> الانتهاكات() const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        return m_انتهاكات;
    }
    
    /**
     * عدد syscalls
     */
    size_t عدد_syscalls() const { return m_عدد_syscalls; }
    
    /**
     * الذاكرة القصوى المستخدمة
     */
    size_t الذاكرة_قصوى() const { return m_ذاكرة_قصوى; }
    
private:
    إعدادات_sandbox m_إعدادات;
    
    std::chrono::steady_clock::time_point m_وقت_البدء;
    std::chrono::steady_clock::time_point m_وقت_النهاية;
    
    std::atomic<bool> m_يعمل{false};
    std::atomic<bool> m_تجاوز_الوقت{false};
    std::atomic<bool> m_تجاوز_الذاكرة{false};
    
    std::atomic<size_t> m_ذاكرة_حالية{0};
    std::atomic<size_t> m_ذاكرة_قصوى{0};
    std::atomic<size_t> m_عدد_syscalls{0};
    
    mutable std::mutex m_قفل;
    std::vector<std::string> m_syscalls;
    std::vector<std::string> m_انتهاكات;
    
    std::thread m_خيط_مراقبة;
};

