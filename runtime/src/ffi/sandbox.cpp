/**
 * أنواع القيود
 */
enum class نوع_قيد_sandbox {
    الذاكرة,           // حد أقصى للذاكرة
    الوقت,             // حد أقصى لوقت التنفيذ
    الملفات,           // قيود الوصول للملفات
    الشبكة,            // قيود الشبكة
    العمليات,          // قيود تشغيل عمليات
    الخيوط,            // قيود إنشاء خيوط
    syscalls,        // قيود syscalls
};

/**
 * مستوى عزل Sandbox
 */
enum class مستوى_عزل {
    أدنى,     // تتبع فقط، بدون منع
    متوسط,    // حظر syscalls خطيرة
    عالي,     // عزل كامل مع حدود صارمة
    أقصى,     // process isolation
};

/**
 * سياسة الملفات
 */
struct سياسة_ملفات {
    bool مسموح_القراءة = false;
    bool مسموح_الكتابة = false;
    bool مسموح_الإنشاء = false;
    std::vector<std::string> مسارات_مسموحة;
    std::vector<std::string> مسارات_ممنوعة;
    
    /**
     * التحقق من مسار
     */
    bool مسار_مسموح(const std::string& مسار) const {
        // فحص المسارات الممنوعة أولاً
        for (const auto& ممنوع : مسارات_ممنوعة) {
            if (مسار.find(ممنوع) == 0) return false;
        }
        
        // فحص المسارات المسموحة
        if (مسارات_مسموحة.empty()) return true;
        
        for (const auto& مسموح : مسارات_مسموحة) {
            if (مسار.find(مسموح) == 0) return true;
        }
        
        return false;
    }
};

/**
 * سياسة الشبكة
 */
struct سياسة_شبكة {
    bool مسموح = false;
    std::vector<std::string> مضيفات_مسموحة;
    std::vector<int> منافذ_مسموحة;
    size_t حد_الاتصالات = 0;
    
    bool مسموح_المضيف(const std::string& مضيف, int منفذ) const {
        if (!مسموح) return false;
        
        bool مضيف_مسموح = مضيفات_مسموحة.empty() ||
            std::find(مضيفات_مسموحة.begin(), مضيفات_مسموحة.end(), مضيف) != مضيفات_مسموحة.end();
            
        bool منفذ_مسموح = منافذ_مسموحة.empty() ||
            std::find(منافذ_مسموحة.begin(), منافذ_مسموحة.end(), منفذ) != منافذ_مسموحة.end();
            
        return مضيف_مسموح && منفذ_مسموح;
    }
};

/**
 * إعدادات Sandbox كاملة
 */
struct إعدادات_sandbox {
    مستوى_عزل المستوى = مستوى_عزل::متوسط;
    
    // حدود الموارد
    size_t حد_الذاكرة_بايت = 100 * 1024 * 1024;  // 100 MB
    std::chrono::milliseconds حد_الوقت{5000};     // 5 ثواني
    size_t حد_الخيوط = 1;
    size_t حد_العمليات = 0;  // لا عمليات فرعية
    
    // سياسات
    سياسة_ملفات ملفات;
    سياسة_شبكة شبكة;
    
    // syscalls مسموحة
    std::unordered_set<std::string> syscalls_مسموحة;
    
    // دوال رد الاتصال
    std::function<void(const std::string&)> عند_انتهاك;
    
    /**
     * إنشاء إعدادات صارمة
     */
    static إعدادات_sandbox صارمة() {
        إعدادات_sandbox إعدادات;
        إعدادات.المستوى = مستوى_عزل::عالي;
        إعدادات.حد_الذاكرة_بايت = 50 * 1024 * 1024;  // 50 MB
        إعدادات.حد_الوقت = std::chrono::milliseconds{2000};  // 2 ثانية
        إعدادات.حد_الخيوط = 1;
        إعدادات.حد_العمليات = 0;
        إعدادات.ملفات.مسموح_القراءة = false;
        إعدادات.ملفات.مسموح_الكتابة = false;
        إعدادات.شبكة.مسموح = false;
        return إعدادات;
    }
    
    /**
     * إنشاء إعدادات متساهلة
     */
    static إعدادات_sandbox متساهلة() {
        إعدادات_sandbox إعدادات;
        إعدادات.المستوى = مستوى_عزل::أدنى;
        إعدادات.حد_الذاكرة_بايت = 1024 * 1024 * 1024;  // 1 GB
        إعدادات.حد_الوقت = std::chrono::milliseconds{60000};  // دقيقة
        إعدادات.حد_الخيوط = 100;
        إعدادات.حد_العمليات = 10;
        إعدادات.ملفات.مسموح_القراءة = true;
        إعدادات.شبكة.مسموح = true;
        return إعدادات;
    }
};

