/**
 * =============================================================================
 * ملف: sandbox.cpp
 * الوصف: Sandbox اختياري لعزل كود FFI - @ffi(sandbox = صحيح)
 * المهمة: T1039 - Phase 93
 * =============================================================================
 * 
 * 📚 دليل المبتدئ لـ Sandbox (صندوق الرمل)
 * ═════════════════════════════════════════
 * 
 * ما هو Sandbox؟
 * ─────────────
 * 
 * Sandbox هو بيئة معزولة تشبه "صندوق رمل" للأطفال:
 * - الطفل يلعب داخل الصندوق
 * - الرمل لا يخرج للحديقة
 * - الحديقة محمية
 * 
 *     ┌─────────────────────────────────────────────────────────────┐
 *     │                      الحديقة (النظام)                       │
 *     │  ┌───────────────────────────────────────────────────────┐  │
 *     │  │               صندوق الرمل (Sandbox)                   │  │
 *     │  │                                                       │  │
 *     │  │   ┌─────────────────────────────────────────────────┐ │  │
 *     │  │   │         كود C الخارجي                           │ │  │
 *     │  │   │                                                 │ │  │
 *     │  │   │   يستطيع:                                       │ │  │
 *     │  │   │   ✅ استخدام الذاكرة المخصصة له                 │ │  │
 *     │  │   │   ✅ إرجاع نتائج                                 │ │  │
 *     │  │   │                                                 │ │  │
 *     │  │   │   لا يستطيع:                                    │ │  │
 *     │  │   │   ❌ الوصول لملفات النظام                       │ │  │
 *     │  │   │   ❌ الاتصال بالشبكة                             │ │  │
 *     │  │   │   ❌ تشغيل برامج                                 │ │  │
 *     │  │   │                                                 │ │  │
 *     │  │   └─────────────────────────────────────────────────┘ │  │
 *     │  │                                                       │  │
 *     │  └───────────────────────────────────────────────────────┘  │
 *     │                                                             │
 *     └─────────────────────────────────────────────────────────────┘
 * 
 * متى نستخدم Sandbox؟
 * ──────────────────
 * 
 * 1. عند استدعاء مكتبات C غير موثوقة
 * 2. عند معالجة بيانات من مصادر خارجية
 * 3. عند تشغيل كود من المستخدم
 * 
 * كيف نستخدمه في ص؟
 * ─────────────────
 * 
 *     @ffi(sandbox = صحيح)
 *     دالة خارجية معالج_صورة(بيانات: مؤشر<بايت>) -> نتيجة
 * 
 *     // الدالة تعمل في بيئة معزولة
 *     // حتى لو حاولت الوصول للملفات، ستُمنع
 * 
 * ما الذي يفعله Sandbox؟
 * ─────────────────────
 * 
 * 1. يُحدد الذاكرة المتاحة
 * 2. يحظر syscalls خطيرة
 * 3. يُحدد وقت التنفيذ
 * 4. يمنع الوصول للشبكة
 * 5. يراقب السلوك
 * 
 * =============================================================================
 */

