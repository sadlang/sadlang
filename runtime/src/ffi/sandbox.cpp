/**
 * مغلف لتنفيذ دالة FFI في sandbox
 * 
 * للمبتدئ: يُستخدم هذا مع @ffi(sandbox = صحيح)
 * 
 * مثال داخلي:
 * ```cpp
 * // عند استدعاء دالة FFI مع sandbox:
 * auto نتيجة = نفِّذ_في_sandbox<int>(
 *     "اسم_الدالة",
 *     إعدادات_sandbox::صارمة(),
 *     []() { return c_function(arg1, arg2); }
 * );
 * ```
 */
template<typename ReturnType, typename Func>
std::pair<نتيجة_sandbox, ReturnType> نفِّذ_في_sandbox(
    const std::string& اسم_الدالة,
    إعدادات_sandbox إعدادات,
    Func&& دالة) {
    
    صندوق_رمل_FFI sandbox(std::move(إعدادات));
    ReturnType قيمة{};
    
    auto نتيجة = sandbox.نفِّذ([&]() {
        قيمة = دالة();
    });
    
    return {نتيجة, قيمة};
}

/**
 * التحقق من أن دالة FFI تحتاج sandbox
 */
inline bool يحتاج_sandbox(const std::string& سمات_ffi) {
    return سمات_ffi.find("sandbox") != std::string::npos &&
           سمات_ffi.find("صحيح") != std::string::npos;
}

/**
 * استخراج مستوى العزل من السمات
 */
inline مستوى_عزل استخرج_مستوى_العزل(const std::string& سمات_ffi) {
    if (سمات_ffi.find("أقصى") != std::string::npos) return مستوى_عزل::أقصى;
    if (سمات_ffi.find("عالي") != std::string::npos) return مستوى_عزل::عالي;
    if (سمات_ffi.find("أدنى") != std::string::npos) return مستوى_عزل::أدنى;
    return مستوى_عزل::متوسط;  // الافتراضي
}

