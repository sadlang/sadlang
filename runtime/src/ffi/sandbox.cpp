/**
 * سبب إيقاف التنفيذ
 */
enum class سبب_إيقاف {
    نجاح,              // تم التنفيذ بنجاح
    تجاوز_الوقت,       // Timeout
    تجاوز_الذاكرة,      // OOM
    انتهاك_سياسة,      // Policy violation
    خطأ_تنفيذ,         // Runtime error
    إيقاف_يدوي,        // Manually stopped
};

/**
 * نتيجة تنفيذ في Sandbox
 */
struct نتيجة_sandbox {
    bool نجح = false;
    سبب_إيقاف السبب = سبب_إيقاف::نجاح;
    
    // النتيجة (إذا نجح)
    std::vector<uint8_t> القيمة_المُرجعة;
    
    // معلومات التنفيذ
    std::chrono::milliseconds مدة_التنفيذ{0};
    size_t ذاكرة_مستخدمة = 0;
    size_t عدد_syscalls = 0;
    
    // الأخطاء والتحذيرات
    std::string رسالة_خطأ;
    std::vector<std::string> تحذيرات;
    std::vector<std::string> انتهاكات;
    
    /**
     * تقرير نصي
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        
        if (نجح) {
            ss << "✅ تم التنفيذ بنجاح\n";
        } else {
            ss << "❌ فشل التنفيذ: ";
            switch (السبب) {
                case سبب_إيقاف::تجاوز_الوقت:
                    ss << "تجاوز الوقت المسموح\n";
                    break;
                case سبب_إيقاف::تجاوز_الذاكرة:
                    ss << "تجاوز الذاكرة المسموحة\n";
                    break;
                case سبب_إيقاف::انتهاك_سياسة:
                    ss << "انتهاك سياسة الأمان\n";
                    break;
                case سبب_إيقاف::خطأ_تنفيذ:
                    ss << "خطأ أثناء التنفيذ\n";
                    break;
                default:
                    ss << "سبب غير معروف\n";
            }
        }
        
        ss << "\nإحصائيات:\n"
           << "  المدة: " << مدة_التنفيذ.count() << " ms\n"
           << "  الذاكرة: " << (ذاكرة_مستخدمة / 1024) << " KB\n"
           << "  syscalls: " << عدد_syscalls << "\n";
        
        if (!انتهاكات.empty()) {
            ss << "\nانتهاكات:\n";
            for (const auto& انتهاك : انتهاكات) {
                ss << "  ⚠️ " << انتهاك << "\n";
            }
        }
        
        return ss.str();
    }
};

