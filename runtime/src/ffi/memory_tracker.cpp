/**
 * إحصائيات استخدام الذاكرة
 */
struct إحصائيات_ذاكرة {
    // عدادات التخصيص
    std::atomic<size_t> عدد_التخصيصات{0};
    std::atomic<size_t> عدد_التحريرات{0};
    std::atomic<size_t> عدد_التخصيصات_الحالية{0};
    
    // أحجام
    std::atomic<size_t> إجمالي_المخصص{0};
    std::atomic<size_t> إجمالي_المحرر{0};
    std::atomic<size_t> الحالي{0};
    std::atomic<size_t> الذروة{0};
    
    // الأخطاء
    std::atomic<size_t> محاولات_تحرير_مزدوج{0};
    std::atomic<size_t> تحريرات_عناوين_مجهولة{0};
    std::atomic<size_t> التسريبات_المكتشفة{0};
    
    /**
     * تحديث الذروة
     */
    void حدِّث_الذروة() {
        size_t حالي = الحالي.load();
        size_t ذروة_حالية = الذروة.load();
        while (حالي > ذروة_حالية) {
            if (الذروة.compare_exchange_weak(ذروة_حالية, حالي)) break;
        }
    }
    
    /**
     * تقرير نصي
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "╔════════════════════════════════════════════╗\n"
           << "║           إحصائيات الذاكرة                 ║\n"
           << "╠════════════════════════════════════════════╣\n"
           << "║ التخصيصات: " << عدد_التخصيصات << "                             ║\n"
           << "║ التحريرات: " << عدد_التحريرات << "                             ║\n"
           << "║ الحالي: " << عدد_التخصيصات_الحالية << " تخصيص                      ║\n"
           << "╠════════════════════════════════════════════╣\n"
           << "║ إجمالي مخصص: " << (إجمالي_المخصص / 1024) << " KB                   ║\n"
           << "║ إجمالي محرر: " << (إجمالي_المحرر / 1024) << " KB                   ║\n"
           << "║ الحالي: " << (الحالي / 1024) << " KB                           ║\n"
           << "║ الذروة: " << (الذروة / 1024) << " KB                           ║\n"
           << "╠════════════════════════════════════════════╣\n";
        
        if (محاولات_تحرير_مزدوج > 0 || تحريرات_عناوين_مجهولة > 0 || التسريبات_المكتشفة > 0) {
            ss << "║ ⚠️ أخطاء:                                  ║\n";
            if (محاولات_تحرير_مزدوج > 0)
                ss << "║   تحرير مزدوج: " << محاولات_تحرير_مزدوج << "                       ║\n";
            if (تحريرات_عناوين_مجهولة > 0)
                ss << "║   عناوين مجهولة: " << تحريرات_عناوين_مجهولة << "                     ║\n";
            if (التسريبات_المكتشفة > 0)
                ss << "║   تسريبات: " << التسريبات_المكتشفة << "                           ║\n";
        } else {
            ss << "║ ✅ لا أخطاء                                ║\n";
        }
        
        ss << "╚════════════════════════════════════════════╝";
        return ss.str();
    }
};

