/**
 * نوع عملية الذاكرة
 */
enum class نوع_عملية_ذاكرة {
    malloc,
    calloc,
    realloc,
    aligned_alloc,
    new_op,       // C++ new
    new_array,    // C++ new[]
    
    free_op,
    delete_op,    // C++ delete
    delete_array, // C++ delete[]
    
    مخصص,        // custom allocator
};

/**
 * معلومات موقع في الكود المصدري
 */
struct موقع_مصدري {
    std::string الملف;
    int السطر = 0;
    std::string الدالة;
    
    std::string إلى_نص() const {
        if (الملف.empty()) return "(غير معروف)";
        std::stringstream ss;
        ss << الملف;
        if (السطر > 0) ss << ":" << السطر;
        if (!الدالة.empty()) ss << " في " << الدالة << "()";
        return ss.str();
    }
};

/**
 * سجل تخصيص ذاكرة
 */
struct سجل_تخصيص {
    // معلومات التخصيص
    void* العنوان = nullptr;
    size_t الحجم = 0;
    size_t المحاذاة = 0;
    نوع_عملية_ذاكرة النوع;
    
    // معلومات المصدر
    موقع_مصدري موقع_التخصيص;
    std::chrono::steady_clock::time_point وقت_التخصيص;
    
    // معلومات التحرير (إذا تم)
    bool مُحرر = false;
    موقع_مصدري موقع_التحرير;
    std::chrono::steady_clock::time_point وقت_التحرير;
    
    // معلومات إضافية
    std::string تعليق;
    uint64_t معرف_الخيط = 0;
    
    /**
     * العمر منذ التخصيص (بالمللي ثانية)
     */
    double العمر_ms() const {
        auto النهاية = مُحرر ? وقت_التحرير : std::chrono::steady_clock::now();
        return std::chrono::duration<double, std::milli>(النهاية - وقت_التخصيص).count();
    }
    
    /**
     * تقرير نصي
     */
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "📍 " << العنوان << " (" << الحجم << " بايت)\n"
           << "   المصدر: " << موقع_التخصيص.إلى_نص() << "\n"
           << "   الحالة: " << (مُحرر ? "مُحرر ✓" : "مخصص ⚠️") << "\n"
           << "   العمر: " << العمر_ms() << " ms";
        return ss.str();
    }
};

