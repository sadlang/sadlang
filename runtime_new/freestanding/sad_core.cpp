#include "sad_core.h"

extern "C" {

// ═══════════════════════════════════════════════════════════════════════════════
//                           sad_memcpy — نسخ ذاكرة
// ═══════════════════════════════════════════════════════════════════════════════

void* sad_memcpy(void* وجهة, const void* مصدر, حجم عدد) {
    ع8* و = (ع8*)وجهة;
    const ع8* م = (const ع8*)مصدر;
    
    // مسار سريع: نسخ 8 بايت في كل مرة (64-bit)
    while (عدد >= sizeof(ع64)) {
        *(ع64*)و = *(const ع64*)م;
        و += sizeof(ع64);
        م += sizeof(ع64);
        عدد -= sizeof(ع64);
    }
    
    // نسخ البايتات المتبقية
    while (عدد > 0) {
        *و++ = *م++;
        عدد--;
    }
    
    return وجهة;
}

// ═══════════════════════════════════════════════════════════════════════════════
//                           sad_memset — ملء ذاكرة
// ═══════════════════════════════════════════════════════════════════════════════

void* sad_memset(void* وجهة, ع8 قيمة, حجم عدد) {
    ع8* و = (ع8*)وجهة;
    
    // بناء كلمة 64-bit مكررة
    ع64 كلمة = قيمة;
    كلمة |= كلمة << 8;
    كلمة |= كلمة << 16;
    كلمة |= كلمة << 32;
    
    // مسار سريع: ملء 8 بايت في كل مرة
    while (عدد >= sizeof(ع64)) {
        *(ع64*)و = كلمة;
        و += sizeof(ع64);
        عدد -= sizeof(ع64);
    }
    
    // ملء البايتات المتبقية
    while (عدد > 0) {
        *و++ = قيمة;
        عدد--;
    }
    
    return وجهة;
}

// ═══════════════════════════════════════════════════════════════════════════════
//                           sad_memcmp — مقارنة ذاكرة
// ═══════════════════════════════════════════════════════════════════════════════

ح32 sad_memcmp(const void* أ, const void* ب, حجم عدد) {
    const ع8* ا = (const ع8*)أ;
    const ع8* ب2 = (const ع8*)ب;
    
    // مسار سريع: مقارنة 8 بايت في كل مرة
    while (عدد >= sizeof(ع64)) {
        ع64 كأ = *(const ع64*)ا;
        ع64 كب = *(const ع64*)ب2;
        if (كأ != كب) {
            // اختلاف — مقارنة بايت بايت
            for (حجم ن = 0; ن < sizeof(ع64); ن++) {
                if (ا[ن] != ب2[ن]) {
                    return (ح32)ا[ن] - (ح32)ب2[ن];
                }
            }
        }
        ا += sizeof(ع64);
        ب2 += sizeof(ع64);
        عدد -= sizeof(ع64);
    }
    
    // مقارنة البايتات المتبقية
    while (عدد > 0) {
        if (*ا != *ب2) {
            return (ح32)*ا - (ح32)*ب2;
        }
        ا++;
        ب2++;
        عدد--;
    }
    
    return 0;
}

// ═══════════════════════════════════════════════════════════════════════════════
//                           sad_memmove — نقل مع تداخل
// ═══════════════════════════════════════════════════════════════════════════════

void* sad_memmove(void* وجهة, const void* مصدر, حجم عدد) {
    ع8* و = (ع8*)وجهة;
    const ع8* م = (const ع8*)مصدر;
    
    if (و == م || عدد == 0) {
        return وجهة;
    }
    
    if (و < م) {
        // الوجهة قبل المصدر — نسخ من الأمام
        return sad_memcpy(وجهة, مصدر, عدد);
    } else {
        // الوجهة بعد المصدر — نسخ من الخلف
        و += عدد;
        م += عدد;
        
        while (عدد > 0) {
            *(--و) = *(--م);
            عدد--;
        }
    }
    
    return وجهة;
}

// ═══════════════════════════════════════════════════════════════════════════════
//                           sad_memzero — تصفير ذاكرة
// ═══════════════════════════════════════════════════════════════════════════════

void sad_memzero(void* بداية, حجم عدد) {
    sad_memset(بداية, 0, عدد);
}

// ═══════════════════════════════════════════════════════════════════════════════
//                           دوال نصية بسيطة
// ═══════════════════════════════════════════════════════════════════════════════

حجم sad_strlen(const char* نص) {
    حجم طول = 0;
    while (نص[طول] != '\0') {
        طول++;
    }
    return طول;
}

حجم sad_strncpy(char* وجهة, const char* مصدر, حجم أقصى) {
    حجم ن = 0;
    while (ن < أقصى && مصدر[ن] != '\0') {
        وجهة[ن] = مصدر[ن];
        ن++;
    }
    // تصفير الباقي
    while (ن < أقصى) {
        وجهة[ن] = '\0';
        ن++;
    }
    return ن;
}

ح32 sad_strncmp(const char* أ, const char* ب, حجم أقصى) {
    for (حجم ن = 0; ن < أقصى; ن++) {
        if (أ[ن] != ب[ن]) {
            return (ح32)(ع8)أ[ن] - (ح32)(ع8)ب[ن];
        }
        if (أ[ن] == '\0') {
            return 0;
        }
    }
    return 0;
}

// ═══════════════════════════════════════════════════════════════════════════════
//              أسماء بديلة متوافقة مع C (يحتاجها المترجم ضمنياً)
// ═══════════════════════════════════════════════════════════════════════════════

// المترجم قد يُولِّد استدعاءات لهذه الدوال تلقائياً
// (مثلاً عند نسخ struct أو تصفير مصفوفة)

void* memcpy(void* dest, const void* src, حجم n) {
    return sad_memcpy(dest, src, n);
}

void* memset(void* dest, int val, حجم n) {
    return sad_memset(dest, (ع8)val, n);
}

int memcmp(const void* a, const void* b, حجم n) {
    return sad_memcmp(a, b, n);
}

void* memmove(void* dest, const void* src, حجم n) {
    return sad_memmove(dest, src, n);
}

} // extern "C"
