//
// حواجز إضافية قوية للتأكد من ترتيب عمليات MMIO على الأنظمة ذات ذاكرة مرنة
// (مثل ARM التي لها نموذج ذاكرة أكثر مرونة من x86).
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حاجز_mmio — حاجز ذاكرة كامل (DSB + ISB على ARM، MFENCE على x86)
 *
 * يضمن:
 *   1. اكتمال جميع عمليات MMIO السابقة
 *   2. عدم تحريك أي عملية MMIO لاحقة قبله
 *   3. مسح خط أنابيب التعليمات (ISB)
 *
 * يُستخدم بين عمليات تهيئة الجهاز الحرجة.
 */
#if defined(SAD_ARCH_AARCH64)
    #define حاجز_mmio() \
        __asm__ volatile ("dsb sy\n\t isb" ::: "memory")
#elif defined(SAD_ARCH_ARM)
    #define حاجز_mmio() \
        __asm__ volatile ("dsb\n\t isb" ::: "memory")
#elif defined(SAD_ARCH_X86_64) || defined(SAD_ARCH_X86)
    #define حاجز_mmio() \
        __asm__ volatile ("mfence" ::: "memory")
#elif defined(SAD_ARCH_RISCV)
    #define حاجز_mmio() \
        __asm__ volatile ("fence iorw,iorw" ::: "memory")
#else
    #define حاجز_mmio() __asm__ volatile ("" ::: "memory")
#endif

/**
 * حاجز_قراءة_mmio — حاجز قراءة فقط (ACQUIRE)
 *
 * يضمن اكتمال جميع قراءات MMIO السابقة قبل أي قراءة لاحقة.
 * أخف من حاجز_mmio الكامل.
 */
#if defined(SAD_ARCH_AARCH64)
    #define حاجز_قراءة_mmio() __asm__ volatile ("dsb ld" ::: "memory")
#else
    #define حاجز_قراءة_mmio() __asm__ volatile ("" ::: "memory")
#endif

/**
 * حاجز_كتابة_mmio — حاجز كتابة فقط (RELEASE)
 *
 * يضمن اكتمال جميع كتابات MMIO السابقة قبل أي كتابة لاحقة.
 */
#if defined(SAD_ARCH_AARCH64)
    #define حاجز_كتابة_mmio() __asm__ volatile ("dsb st" ::: "memory")
#else
    #define حاجز_كتابة_mmio() __asm__ volatile ("" ::: "memory")
#endif

