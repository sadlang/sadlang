/**
 * =============================================================================
 * ملف: sad_control_flow.h
 * الوصف: دعم تراكيب التحكم في بيئة Freestanding (بدون مكتبة قياسية)
 * المهمة: م-ج03 — دعم شامل لجمل التحكم في وضع Freestanding
 * =============================================================================
 *
 * هذا الملف يُوفّر دعمًا كاملًا لتراكيب التحكم في لغة ص عند التشغيل
 * بدون مكتبة قياسية، بما فيها:
 *
 *   ─────────────────────────────────────────────────────────
 *   | تركيب لغة ص   | تركيب مكافئ    | الدعم في Freestanding |
 *   ─────────────────────────────────────────────────────────
 *   | إذا            | if             | ✅ مدعوم كاملاً        |
 *   | وإلا           | else           | ✅ مدعوم كاملاً        |
 *   | وإلا_إذا       | else if        | ✅ مدعوم كاملاً        |
 *   | طالما          | while          | ✅ مدعوم كاملاً        |
 *   | لكل            | for            | ✅ مدعوم كاملاً        |
 *   | تطابق          | match/switch   | ✅ مدعوم كاملاً        |
 *   | أكمل           | continue       | ✅ مدعوم كاملاً        |
 *   | أوقف           | break          | ✅ مدعوم كاملاً        |
 *   | أرجع           | return         | ✅ مدعوم كاملاً        |
 *   | ذعر            | panic          | ✅ يستخدم sad_panic     |
 *   | تأكد           | assert         | ✅ يستخدم sad_assert    |
 *   ─────────────────────────────────────────────────────────
 *
 * الاستخدام الأساسي في كود النواة:
 * ─────────────────────────────────
 *   #include "sad_core.h"   // يُضمّن هذا الملف تلقائياً
 *
 *   // مثال: إذا/وإلا
 *   إذا (شرط) {
 *       // كود الشرط الصحيح
 *   } وإلا {
 *       // كود الشرط الخاطئ
 *   }
 *
 *   // مثال: طالما
 *   طالما (شرط) {
 *       // جسم الحلقة
 *   }
 *
 *   // مثال: لكل
 *   لكل (متغير ن = 0; ن < 10; ن++) {
 *       // جسم الحلقة
 *   }
 *
 * ملاحظة: جمل التحكم تعمل مباشرة عبر C/C++ في وضع freestanding
 * لأن المترجم يُولّد كود تحكم مباشر بدون أي اعتماد على المكتبة القياسية.
 * هذا الملف يُوفّر الماكروهات والأدوات المساعدة فقط.
 * =============================================================================
 */

#ifndef SAD_FREESTANDING_CONTROL_FLOW_H
#define SAD_FREESTANDING_CONTROL_FLOW_H

#include "sad_types.h"
#include "sad_panic.h"

// ═══════════════════════════════════════════════════════════════════════════════
//                    ماكروهات مساعدة لجمل التحكم بالعربية
//
// هذه الماكروهات تُتيح كتابة كود freestanding بمعرّفات عربية.
// المترجم الأصلي يُترجم جمل التحكم العربية مباشرة — هذه للملفات C/C++
// التي تُكتب يدوياً في مكتبة الوقت التشغيلي freestanding.
// ═══════════════════════════════════════════════════════════════════════════════

// ─── جملة الشرط ───────────────────────────────────────────────────────────────

/**
 * إذا — جملة if
 *
 * الاستخدام:
 *   إذا (شرط) {
 *       // الكود عند الصحة
 *   }
 *
 * تُوسَّع إلى: if (شرط) { ... }
 * تعمل كاملاً في بيئة freestanding — لا تعتمد على أي مكتبة.
 */
#define إذا if

/**
 * وإلا — جملة else
 *
 * الاستخدام:
 *   إذا (شرط) {
 *       // صحيح
 *   } وإلا {
 *       // خطأ
 *   }
 */
#define وإلا else

/**
 * وإلا_إذا — جملة else if (مركّبة)
 *
 * الاستخدام:
 *   إذا (شرط1) {
 *       // حالة 1
 *   } وإلا_إذا (شرط2) {
 *       // حالة 2
 *   } وإلا {
 *       // الافتراضي
 *   }
 */
#define وإلا_إذا else if

// ─── حلقات التكرار ────────────────────────────────────────────────────────────

/**
 * طالما — حلقة while
 *
 * الاستخدام:
 *   طالما (شرط) {
 *       // الكود المتكرر
 *   }
 *
 * مثال مفيد للنواة — انتظار جاهزية الجهاز:
 *   طالما (!(قراءة_منفذ(0x64) & 0x02)) { }  // انتظر حتى يفرغ البافر
 */
#define طالما while

/**
 * لكل — حلقة for
 *
 * الاستخدام:
 *   لكل (ع32 ن = 0; ن < عدد; ن++) {
 *       // الكود المتكرر
 *   }
 */
#define لكل for

/**
 * حلقة — loop (حلقة لانهائية) — مكافئ لـ while(true)
 *
 * الاستخدام:
 *   حلقة {
 *       // ينفَّذ إلى الأبد (أو حتى أوقف/أرجع)
 *   }
 *
 * يُستخدم في نقاط الدخول والمعالجات:
 *   #[نقطة_دخول]
 *   دالة _start() {
 *       حلقة {
 *           // حلقة النواة الرئيسية
 *       }
 *   }
 */
#define حلقة while(صحيح)

// ─── جمل التحكم في الحلقات والدوال ──────────────────────────────────────────

/**
 * أكمل — continue
 * ينتقل إلى التكرار التالي في الحلقة الحالية
 *
 * الاستخدام:
 *   لكل (ع32 ن = 0; ن < 100; ن++) {
 *       إذا (ن % 2 == 0) أكمل;  // تخطَّ الأزواج
 *       // معالجة الأفراد فقط
 *   }
 */
#define أكمل continue

/**
 * أوقف — break
 * يخرج من الحلقة الحالية
 *
 * الاستخدام:
 *   طالما (صحيح) {
 *       إذا (شرط_الخروج) أوقف;
 *   }
 */
#define أوقف break

/**
 * أرجع — return
 * يُرجع قيمة من الدالة
 *
 * الاستخدام:
 *   إذا (خطأ) أرجع فراغ;
 *   أرجع النتيجة;
 */
#define أرجع return

// ─── جملة switch/تطابق ────────────────────────────────────────────────────────

/**
 * تطابق — switch
 * يُطابق قيمة مع حالات
 *
 * الاستخدام:
 *   تطابق (رمز) {
 *       حالة 'أ': // معالجة أ
 *           أوقف;
 *       حالة 'ب': // معالجة ب
 *           أوقف;
 *       افتراضي:  // الحالة الافتراضية
 *           أوقف;
 *   }
 */
#define تطابق switch

/**
 * حالة — case (داخل switch)
 */
#define حالة case

/**
 * افتراضي — default (داخل switch)
 */
#define افتراضي default

// ═══════════════════════════════════════════════════════════════════════════════
//                    أدوات التأكيد والتحقق في Freestanding
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * تأكد — assert في بيئة freestanding
 *
 * يُطلق ذعراً إذا لم يكن الشرط صحيحاً.
 * مختلف عن assert() القياسي: لا يعتمد على stdio.
 *
 * الاستخدام:
 *   تأكد(مؤشر != فراغ);
 *   تأكد(حجم > 0);
 *
 * عند الفشل: يستدعي sad_panic بمعلومات الملف والسطر
 */
#define تأكد(شرط) \
    do { \
        إذا (!(شرط)) { \
            sad_panic("فشل التأكد: " #شرط, __FILE__, (ع32)__LINE__); \
        } \
    } while (0)

/**
 * تأكد_لن_يُنفَّذ — unreachable assertion
 *
 * يُعلم المترجم أن هذا المكان لا يجب أن يُنفَّذ.
 * إذا وصل التنفيذ هنا — ذعر فوري.
 *
 * الاستخدام:
 *   تطابق (نوع) {
 *       حالة 1: // ...
 *       حالة 2: // ...
 *       افتراضي: تأكد_لن_يُنفَّذ;
 *   }
 */
#define تأكد_لن_يُنفَّذ \
    sad_panic("وصل إلى كود مستحيل!", __FILE__, (ع32)__LINE__)

// ═══════════════════════════════════════════════════════════════════════════════
//                    ماكروهات تحسين التفريع للمترجم
//
// تُساعد المترجم على تحسين كود التفريع وفق الاحتمالية.
// مفيدة في مسارات المعالج الحرج (hot path) لتحسين الأداء.
// ═══════════════════════════════════════════════════════════════════════════════

#ifdef __GNUC__

/**
 * مرجَّح — الشرط يكون صحيحاً في الغالب (likely)
 * يُوجِّه المترجم لتحسين المسار الصحيح
 *
 * الاستخدام في المسار الحرج:
 *   إذا (مرجَّح(البافر != فراغ)) {
 *       // المسار الأسرع — يحدث 99% من الوقت
 *   }
 */
#define مرجَّح(شرط)    __builtin_expect(!!(شرط), 1)

/**
 * نادر — الشرط يكون صحيحاً نادراً (unlikely)
 * يُوجِّه المترجم للتحسين ضد هذا المسار
 *
 * الاستخدام لمعالجة الأخطاء:
 *   إذا (نادر(خطأ_حرج)) {
 *       ذعر("خطأ حرج!");
 *   }
 */
#define نادر(شرط)      __builtin_expect(!!(شرط), 0)

#else

// بدون GCC: لا تحسين تفريع — تعمل فقط كشروط عادية
#define مرجَّح(شرط)    (شرط)
#define نادر(شرط)      (شرط)

#endif

// ═══════════════════════════════════════════════════════════════════════════════
//                    أدوات التزامن المبسّطة (فعلياً للأنوية أحادية المعالج)
//
// في الأنوية الأولية أو الأنظمة المدمجة أحادية المعالج، نحتاج
// أحياناً لتعطيل المقاطعات أثناء الأقسام الحرجة.
// ═══════════════════════════════════════════════════════════════════════════════

#if defined(__i386__) || defined(__x86_64__) || defined(_M_IX86) || defined(_M_X64)

/**
 * قسم_حرج_بدء — تعطيل المقاطعات (x86/x86_64 فقط)
 *
 * الاستخدام:
 *   قسم_حرج_بدء;
 *       // كود بدون مقاطعات
 *   قسم_حرج_نهاية;
 */
#define قسم_حرج_بدء      __asm__ volatile("cli" ::: "memory")

/**
 * قسم_حرج_نهاية — تفعيل المقاطعات (x86/x86_64 فقط)
 */
#define قسم_حرج_نهاية    __asm__ volatile("sti" ::: "memory")

/**
 * حاجز_ذاكرة — يمنع إعادة ترتيب عمليات الذاكرة
 * مهم بعد تعيين سجلات الجهاز (MMIO)
 */
#define حاجز_ذاكرة       __asm__ volatile("" ::: "memory")

#elif defined(__aarch64__) || defined(_M_ARM64)

// ARM64 — إيقاف/تشغيل المقاطعات
#define قسم_حرج_بدء      __asm__ volatile("msr daifset, #2" ::: "memory")
#define قسم_حرج_نهاية    __asm__ volatile("msr daifclr, #2" ::: "memory")
#define حاجز_ذاكرة       __asm__ volatile("dmb ish" ::: "memory")

#else

// منصات أخرى — لا يوجد دعم أجهزة محدد
#define قسم_حرج_بدء      ((void)0)
#define قسم_حرج_نهاية    ((void)0)
#define حاجز_ذاكرة       ((void)0)

#endif

// ═══════════════════════════════════════════════════════════════════════════════
//                    ماكروهات الإرجاع اللانهائي
//
// بعض الدوال في النواة لا ترجع أبداً (نقطة الدخول، معالج الذعر).
// نُعلم المترجم بذلك لتحسين الكود.
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * لن_ترجع — نوع الإرجاع للدوال التي لا تعود
 *
 * الاستخدام:
 *   لن_ترجع دالة _start() {
 *       حلقة { }
 *   }
 */
#ifdef __cplusplus
#define لن_ترجع [[noreturn]] void
#elif defined(__GNUC__)
#define لن_ترجع __attribute__((noreturn)) void
#else
#define لن_ترجع void
#endif

// ═══════════════════════════════════════════════════════════════════════════════
//                    أدوات مساعدة للحلقات الشائعة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * لكل_ع32 — حلقة for من 0 إلى عدد-1 بنوع ع32
 *
 * الاستخدام:
 *   لكل_ع32 (ن, عدد_العناصر) {
 *       معالجة(مصفوفة[ن]);
 *   }
 *
 * تُوسَّع إلى: for (ع32 ن = 0; ن < عدد_العناصر; ن++) { ... }
 */
#define لكل_ع32(متغير, عدد) \
    لكل (ع32 متغير = 0; متغير < (ع32)(عدد); متغير++)

/**
 * لكل_حجم — حلقة for من 0 إلى عدد-1 بنوع حجم
 *
 * الاستخدام:
 *   لكل_حجم (ن, طول_المصفوفة) {
 *       // معالجة العنصر ن
 *   }
 */
#define لكل_حجم(متغير, عدد) \
    لكل (حجم متغير = 0; متغير < (حجم)(عدد); متغير++)

/**
 * انتظر_حتى — حلقة انتظار حتى يتحقق الشرط
 *
 * مُفيد لانتظار جهاز (polling):
 *   انتظر_حتى(قراءة_منفذ(0x64) & 0x01);  // انتظر حتى يُتاح الإدخال
 *
 * تحذير: لا تحتوي على timeout! استخدم طالما مع عداد للأنظمة الحرجة.
 */
#define انتظر_حتى(شرط) طالما (!(شرط)) { حاجز_ذاكرة; }

/**
 * انتظر_بينما — حلقة انتظار طالما الشرط محقق
 *
 * الاستخدام:
 *   انتظر_بينما(الجهاز_مشغول());  // انتظر حتى يفرغ الجهاز
 */
#define انتظر_بينما(شرط) طالما (شرط) { حاجز_ذاكرة; }

#endif /* SAD_FREESTANDING_CONTROL_FLOW_H */
