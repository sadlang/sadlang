// ═══════════════════════════════════════════════════════════════════════════════
//                              تخطيط الحقل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات حقل في الحالة
 */
struct حقل_حالة {
    std::string الاسم;
    std::string النوع;
    size_t الحجم;
    size_t المحاذاة;
    size_t الإزاحة;          // الإزاحة في التخطيط
    bool حي_في_كل_الحالات;  // هل مطلوب في كل الحالات؟
};

/**
 * تخطيط حالة واحدة
 */
struct تخطيط_حالة {
    int رقم_الحالة;
    std::vector<std::string> الحقول_الحية;
    size_t الحجم_الكلي;
    size_t المحاذاة;
    
    // خريطة الحقول إلى الإزاحات
    std::unordered_map<std::string, size_t> خريطة_الإزاحات;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              استراتيجية الضغط
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * استراتيجيات الضغط المختلفة
 */
enum class استراتيجية_ضغط {
    لا_ضغط,              // كل الحقول دائماً
    حالات_منفصلة,        // union من الحالات
    ضغط_تدريجي,         // حقول مشتركة + union
    ضغط_ديناميكي        // تخصيص حسب الحاجة
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل التخطيط
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * محلل تخطيط State Machine
 */
class محلل_تخطيط {
public:
    /**
     * تحليل الحقول المطلوبة لكل حالة
     * 
     * @param عدد_الحالات عدد نقاط الانتظار + 1
     * @param حقول_حية خريطة: رقم الحالة → الحقول الحية
     * @param معلومات_الحقول معلومات كل حقل
     */
    std::vector<تخطيط_حالة> حلل(
        int عدد_الحالات,
        const std::unordered_map<int, std::unordered_set<std::string>>& حقول_حية,
        const std::unordered_map<std::string, حقل_حالة>& معلومات_الحقول
    ) {
        std::vector<تخطيط_حالة> تخطيطات;
        
        for (int i = 0; i < عدد_الحالات; i++) {
            تخطيط_حالة تخطيط;
            تخطيط.رقم_الحالة = i;
            
            // الحقول الحية في هذه الحالة
            auto it = حقول_حية.find(i);
            if (it != حقول_حية.end()) {
                تخطيط.الحقول_الحية = std::vector<std::string>(
                    it->second.begin(), 
                    it->second.end()
                );
            }
            
            // حساب التخطيط
            size_t إزاحة_حالية = 0;
            size_t أقصى_محاذاة = 1;
            
            for (const auto& اسم : تخطيط.الحقول_الحية) {
                auto it_حقل = معلومات_الحقول.find(اسم);
                if (it_حقل == معلومات_الحقول.end()) continue;
                
                const auto& حقل = it_حقل->second;
                
                // محاذاة
                size_t محاذاة = حقل.المحاذاة > 0 ? حقل.المحاذاة : 1;
                if (إزاحة_حالية % محاذاة != 0) {
                    إزاحة_حالية += محاذاة - (إزاحة_حالية % محاذاة);
                }
                
                تخطيط.خريطة_الإزاحات[اسم] = إزاحة_حالية;
                إزاحة_حالية += حقل.الحجم;
                أقصى_محاذاة = std::max(أقصى_محاذاة, محاذاة);
            }
            
            // محاذاة نهائية
            if (إزاحة_حالية % أقصى_محاذاة != 0) {
                إزاحة_حالية += أقصى_محاذاة - (إزاحة_حالية % أقصى_محاذاة);
            }
            
            تخطيط.الحجم_الكلي = إزاحة_حالية;
            تخطيط.المحاذاة = أقصى_محاذاة;
            
            تخطيطات.push_back(تخطيط);
        }
        
        return تخطيطات;
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              ضاغط الحالة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * ضاغط State Machine
 * 
 * يُنتج تخطيطاً مُحسَّناً للذاكرة
 */
class ضاغط_حالة {
public:
    /**
     * نتيجة الضغط
     */
    struct نتيجة_ضغط {
        // الحقول المشتركة (موجودة في كل الحالات)
        std::vector<حقل_حالة> الحقول_المشتركة;
        
        // تخطيطات الجزء المتغير (union)
        std::vector<تخطيط_حالة> تخطيطات_المتغير;
        
        // الأحجام
        size_t حجم_المشترك;
        size_t حجم_المتغير_أقصى;
        size_t الحجم_الكلي;
        
        // التوفير
        size_t الحجم_بدون_ضغط;
        float نسبة_التوفير;
    };
    
    /**
     * ضغط State Machine
     */
    نتيجة_ضغط اضغط(
        const std::vector<تخطيط_حالة>& تخطيطات,
        const std::unordered_map<std::string, حقل_حالة>& معلومات_الحقول,
        استراتيجية_ضغط استراتيجية = استراتيجية_ضغط::ضغط_تدريجي
    ) {
        نتيجة_ضغط نتيجة;
        
        switch (استراتيجية) {
            case استراتيجية_ضغط::لا_ضغط:
                نتيجة = بدون_ضغط(تخطيطات, معلومات_الحقول);
                break;
            
            case استراتيجية_ضغط::حالات_منفصلة:
                نتيجة = union_حالات(تخطيطات, معلومات_الحقول);
                break;
            
            case استراتيجية_ضغط::ضغط_تدريجي:
            default:
                نتيجة = ضغط_تدريجي(تخطيطات, معلومات_الحقول);
                break;
        }
        
        // حساب التوفير
        نتيجة.نسبة_التوفير = نتيجة.الحجم_بدون_ضغط > 0 ?
            100.0f * (1.0f - float(نتيجة.الحجم_الكلي) / نتيجة.الحجم_بدون_ضغط) :
            0.0f;
        
        return نتيجة;
    }

private:
    /**
     * بدون ضغط - كل الحقول دائماً
     */
    نتيجة_ضغط بدون_ضغط(
        const std::vector<تخطيط_حالة>& تخطيطات,
        const std::unordered_map<std::string, حقل_حالة>& معلومات_الحقول
    ) {
        نتيجة_ضغط نتيجة;
        
        // كل الحقول مشتركة
        for (const auto& [اسم, حقل] : معلومات_الحقول) {
            نتيجة.الحقول_المشتركة.push_back(حقل);
        }
        
        // حساب الحجم
        نتيجة.حجم_المشترك = 0;
        for (const auto& حقل : نتيجة.الحقول_المشتركة) {
            نتيجة.حجم_المشترك += حقل.الحجم;
        }
        
        نتيجة.حجم_المتغير_أقصى = 0;
        نتيجة.الحجم_الكلي = نتيجة.حجم_المشترك;
        نتيجة.الحجم_بدون_ضغط = نتيجة.الحجم_الكلي;
        
        return نتيجة;
    }
    
    /**
     * Union من الحالات
     */
    نتيجة_ضغط union_حالات(
        const std::vector<تخطيط_حالة>& تخطيطات,
        const std::unordered_map<std::string, حقل_حالة>& معلومات_الحقول
    ) {
        نتيجة_ضغط نتيجة;
        
        // لا حقول مشتركة
        نتيجة.حجم_المشترك = sizeof(int);  // رقم الحالة فقط
        
        // أقصى حجم حالة
        نتيجة.حجم_المتغير_أقصى = 0;
        for (const auto& تخطيط : تخطيطات) {
            نتيجة.حجم_المتغير_أقصى = std::max(
                نتيجة.حجم_المتغير_أقصى,
                تخطيط.الحجم_الكلي
            );
            نتيجة.تخطيطات_المتغير.push_back(تخطيط);
        }
        
        نتيجة.الحجم_الكلي = نتيجة.حجم_المشترك + نتيجة.حجم_المتغير_أقصى;
        
        // حساب الحجم بدون ضغط
        نتيجة.الحجم_بدون_ضغط = 0;
        for (const auto& [_, حقل] : معلومات_الحقول) {
            نتيجة.الحجم_بدون_ضغط += حقل.الحجم;
        }
        
        return نتيجة;
    }
    
    /**
     * ضغط تدريجي - حقول مشتركة + union
     */
    نتيجة_ضغط ضغط_تدريجي(
        const std::vector<تخطيط_حالة>& تخطيطات,
        const std::unordered_map<std::string, حقل_حالة>& معلومات_الحقول
    ) {
        نتيجة_ضغط نتيجة;
        
        // اكتشاف الحقول المشتركة (موجودة في كل الحالات)
        std::unordered_set<std::string> مشتركة;
        
        if (!تخطيطات.empty()) {
            // ابدأ بحقول الحالة الأولى
            for (const auto& اسم : تخطيطات[0].الحقول_الحية) {
                مشتركة.insert(اسم);
            }
            
            // احتفظ فقط بالموجودة في كل الحالات
            for (size_t i = 1; i < تخطيطات.size(); i++) {
                std::unordered_set<std::string> حالية(
                    تخطيطات[i].الحقول_الحية.begin(),
                    تخطيطات[i].الحقول_الحية.end()
                );
                
                std::unordered_set<std::string> تقاطع;
                for (const auto& اسم : مشتركة) {
                    if (حالية.find(اسم) != حالية.end()) {
                        تقاطع.insert(اسم);
                    }
                }
                مشتركة = تقاطع;
            }
        }
        
        // بناء قائمة الحقول المشتركة
        نتيجة.حجم_المشترك = sizeof(int);  // رقم الحالة
        for (const auto& اسم : مشتركة) {
            auto it = معلومات_الحقول.find(اسم);
            if (it != معلومات_الحقول.end()) {
                نتيجة.الحقول_المشتركة.push_back(it->second);
                نتيجة.حجم_المشترك += it->second.الحجم;
            }
        }
        
        // بناء تخطيطات المتغير (الحقول غير المشتركة)
        نتيجة.حجم_المتغير_أقصى = 0;
        
        for (const auto& تخطيط : تخطيطات) {
            تخطيط_حالة تخطيط_متغير;
            تخطيط_متغير.رقم_الحالة = تخطيط.رقم_الحالة;
            
            size_t حجم = 0;
            for (const auto& اسم : تخطيط.الحقول_الحية) {
                if (مشتركة.find(اسم) == مشتركة.end()) {
                    تخطيط_متغير.الحقول_الحية.push_back(اسم);
                    
                    auto it = معلومات_الحقول.find(اسم);
                    if (it != معلومات_الحقول.end()) {
                        تخطيط_متغير.خريطة_الإزاحات[اسم] = حجم;
                        حجم += it->second.الحجم;
                    }
                }
            }
            
            تخطيط_متغير.الحجم_الكلي = حجم;
            نتيجة.تخطيطات_المتغير.push_back(تخطيط_متغير);
            نتيجة.حجم_المتغير_أقصى = std::max(نتيجة.حجم_المتغير_أقصى, حجم);
        }
        
        نتيجة.الحجم_الكلي = نتيجة.حجم_المشترك + نتيجة.حجم_المتغير_أقصى;
        
        // حساب الحجم بدون ضغط
        نتيجة.الحجم_بدون_ضغط = 0;
        for (const auto& [_, حقل] : معلومات_الحقول) {
            نتيجة.الحجم_بدون_ضغط += حقل.الحجم;
        }
        
        return نتيجة;
    }
};

