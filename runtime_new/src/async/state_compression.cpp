/**
 * مُولِّد كود State Machine المضغوط
 */
class مولد_كود_حالة {
public:
    /**
     * توليد تعريف البنية المضغوطة
     */
    std::string ولِّد_تعريف(
        const std::string& اسم_الدالة,
        const ضاغط_حالة::نتيجة_ضغط& ضغط
    ) {
        std::stringstream كود;
        
        كود << "// State Machine لـ " << اسم_الدالة << "\n";
        كود << "// الحجم: " << ضغط.الحجم_الكلي << " بايت ";
        كود << "(توفير " << ضغط.نسبة_التوفير << "%)\n\n";
        
        كود << "struct حالة_" << اسم_الدالة << " {\n";
        كود << "    int رقم_الحالة;\n";
        
        // الحقول المشتركة
        if (!ضغط.الحقول_المشتركة.empty()) {
            كود << "    \n    // الحقول المشتركة\n";
            for (const auto& حقل : ضغط.الحقول_المشتركة) {
                كود << "    " << حقل.النوع << " " << حقل.الاسم << ";\n";
            }
        }
        
        // Union للجزء المتغير
        if (ضغط.حجم_المتغير_أقصى > 0) {
            كود << "    \n    // الجزء المتغير (union)\n";
            كود << "    union {\n";
            
            for (const auto& تخطيط : ضغط.تخطيطات_المتغير) {
                if (!تخطيط.الحقول_الحية.empty()) {
                    كود << "        struct { // حالة " << تخطيط.رقم_الحالة << "\n";
                    for (const auto& اسم : تخطيط.الحقول_الحية) {
                        كود << "            // " << اسم << "\n";
                    }
                    كود << "        } حالة_" << تخطيط.رقم_الحالة << ";\n";
                }
            }
            
            كود << "        uint8_t _بيانات[" << ضغط.حجم_المتغير_أقصى << "];\n";
            كود << "    } متغير;\n";
        }
        
        كود << "};\n";
        
        return كود.str();
    }
};

