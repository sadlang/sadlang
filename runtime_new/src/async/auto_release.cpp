/**
 * نقطة إصدار متغير
 */
struct نقطة_إصدار {
    std::string اسم_المتغير;
    int رقم_نقطة_الانتظار;  // قبل أي نقطة انتظار نحرر
    size_t الحجم_المقدر;    // كم ذاكرة نوفر
    bool يحتاج_destructor;
};

/**
 * خطة الإصدار للدالة
 */
struct خطة_إصدار {
    std::string اسم_الدالة;
    
    // نقاط الإصدار مجمعة حسب نقطة الانتظار
    std::unordered_map<int, std::vector<نقطة_إصدار>> إصدارات_قبل_انتظار;
    
    // إحصائيات
    size_t الذاكرة_الموفرة_الكلية;
    int عدد_المتغيرات_المحررة;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل الإصدار
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * معلومات متغير للتحليل
 */
struct معلومات_متغير_إصدار {
    std::string الاسم;
    std::string النوع;
    size_t الحجم;
    int تعريف_في_سطر;
    int آخر_استخدام_سطر;
    bool يحتاج_destructor;
    
    // استخدام حسب نقاط الانتظار
    std::unordered_set<int> مستخدم_بعد_انتظار;  // أرقام نقاط الانتظار
};

/**
 * محلل إمكانية الإصدار المبكر
 */
class محلل_إصدار {
public:
    /**
     * إعداد نقاط الانتظار
     */
    void حدد_نقاط_الانتظار(const std::vector<int>& أسطر_الانتظار) {
        نقاط_الانتظار_ = أسطر_الانتظار;
    }
    
    /**
     * إضافة معلومات متغير
     */
    void أضف_متغير(const معلومات_متغير_إصدار& معلومات) {
        المتغيرات_[معلومات.الاسم] = معلومات;
    }
    
    /**
     * تحليل وإنتاج خطة الإصدار
     */
    خطة_إصدار حلل() {
        خطة_إصدار خطة;
        خطة.الذاكرة_الموفرة_الكلية = 0;
        خطة.عدد_المتغيرات_المحررة = 0;
        
        for (const auto& [اسم, معلومات] : المتغيرات_) {
            // اكتشف أول نقطة انتظار لا نحتاج فيها المتغير
            int نقطة_الإصدار = اكتشف_نقطة_إصدار(معلومات);
            
            if (نقطة_الإصدار >= 0) {
                نقطة_إصدار نقطة;
                نقطة.اسم_المتغير = اسم;
                نقطة.رقم_نقطة_الانتظار = نقطة_الإصدار;
                نقطة.الحجم_المقدر = معلومات.الحجم;
                نقطة.يحتاج_destructor = معلومات.يحتاج_destructor;
                
                خطة.إصدارات_قبل_انتظار[نقطة_الإصدار].push_back(نقطة);
                خطة.الذاكرة_الموفرة_الكلية += معلومات.الحجم;
                خطة.عدد_المتغيرات_المحررة++;
            }
        }
        
        return خطة;
    }

private:
    std::vector<int> نقاط_الانتظار_;
    std::unordered_map<std::string, معلومات_متغير_إصدار> المتغيرات_;
    
    /**
     * اكتشاف أقرب نقطة إصدار ممكنة
     */
    int اكتشف_نقطة_إصدار(const معلومات_متغير_إصدار& معلومات) {
        // إذا مستخدم بعد كل نقاط الانتظار، لا نستطيع تحريره مبكراً
        if (معلومات.مستخدم_بعد_انتظار.size() == نقاط_الانتظار_.size()) {
            return -1;  // لا إصدار مبكر
        }
        
        // ابحث عن أول نقطة انتظار لا يُستخدم بعدها
        for (size_t i = 0; i < نقاط_الانتظار_.size(); i++) {
            bool مستخدم_بعد_هذه = false;
            
            for (size_t j = i; j < نقاط_الانتظار_.size(); j++) {
                if (معلومات.مستخدم_بعد_انتظار.find(j) != 
                    معلومات.مستخدم_بعد_انتظار.end()) {
                    مستخدم_بعد_هذه = true;
                    break;
                }
            }
            
            if (!مستخدم_بعد_هذه) {
                return i;  // يمكن تحريره قبل هذه النقطة
            }
        }
        
        return -1;
    }
};

