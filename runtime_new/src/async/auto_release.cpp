/**
 * واجهة تحرير الذاكرة
 */
class واجهة_محرر {
public:
    virtual ~واجهة_محرر() = default;
    
    /**
     * تحرير متغير
     * @return true إذا تم التحرير بنجاح
     */
    virtual bool حرر(const std::string& اسم_المتغير) = 0;
    
    /**
     * استدعاء destructor قبل التحرير
     */
    virtual void استدعِ_destructor(const std::string& اسم_المتغير) = 0;
};

/**
 * مُحرر للحالة (State)
 */
class محرر_حالة : public واجهة_محرر {
public:
    /**
     * @param مؤشر_الحالة مؤشر لبنية الحالة
     * @param خريطة_الإزاحات إزاحة كل متغير في الحالة
     */
    محرر_حالة(
        void* مؤشر_الحالة,
        std::unordered_map<std::string, size_t> خريطة_الإزاحات
    ) : الحالة_(مؤشر_الحالة), الإزاحات_(خريطة_الإزاحات) {}
    
    bool حرر(const std::string& اسم_المتغير) override {
        auto it = الإزاحات_.find(اسم_المتغير);
        if (it == الإزاحات_.end()) {
            return false;
        }
        
        // في التنفيذ الحقيقي، نصفر الذاكرة أو نعلمها كمحررة
        // هنا نحتفظ فقط بالاسم للتتبع
        المحررة_.insert(اسم_المتغير);
        return true;
    }
    
    void استدعِ_destructor(const std::string& اسم_المتغير) override {
        auto it = الإزاحات_.find(اسم_المتغير);
        if (it == الإزاحات_.end()) return;
        
        // في التنفيذ الحقيقي، نستدعي الـ destructor
        // هذا يتطلب معرفة نوع المتغير
    }
    
    bool محرر(const std::string& اسم) const {
        return المحررة_.find(اسم) != المحررة_.end();
    }

private:
    void* الحالة_;
    std::unordered_map<std::string, size_t> الإزاحات_;
    std::unordered_set<std::string> المحررة_;
};

// ═══════════════════════════════════════════════════════════════════════════════
