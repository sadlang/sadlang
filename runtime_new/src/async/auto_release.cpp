/**
 * مولد كود الإصدار التلقائي
 */
class مولد_كود_إصدار {
public:
    /**
     * توليد كود C++ للإصدار التلقائي
     */
    std::string ولِّد_كود(const خطة_إصدار& خطة) {
        std::stringstream كود;
        
        كود << "// كود الإصدار التلقائي لـ " << خطة.اسم_الدالة << "\n";
        كود << "// يوفر " << خطة.الذاكرة_الموفرة_الكلية << " بايت\n\n";
        
        for (const auto& [رقم_نقطة, إصدارات] : خطة.إصدارات_قبل_انتظار) {
            كود << "// قبل نقطة الانتظار " << رقم_نقطة << "\n";
            كود << "inline void إصدار_قبل_" << رقم_نقطة << "(حالة_" 
                << خطة.اسم_الدالة << "& حالة) {\n";
            
            for (const auto& إصدار : إصدارات) {
                if (إصدار.يحتاج_destructor) {
                    كود << "    حالة." << إصدار.اسم_المتغير << ".~";
                    كود << "(); // استدعاء destructor\n";
                }
                كود << "    // تحرير " << إصدار.اسم_المتغير;
                كود << " (" << إصدار.الحجم_المقدر << " بايت)\n";
            }
            
            كود << "}\n\n";
        }
        
        return كود.str();
    }
    
    /**
     * توليد تقرير الإصدار
     */
    std::string ولِّد_تقرير(const خطة_إصدار& خطة) {
        std::stringstream تقرير;
        
        تقرير << "╔════════════════════════════════════════════════╗\n";
        تقرير << "║        تقرير الإصدار التلقائي للذاكرة          ║\n";
        تقرير << "╠════════════════════════════════════════════════╣\n";
        تقرير << "║ الدالة: " << خطة.اسم_الدالة << "\n";
        تقرير << "║ المتغيرات المحررة: " << خطة.عدد_المتغيرات_المحررة << "\n";
        تقرير << "║ الذاكرة الموفرة: " << خطة.الذاكرة_الموفرة_الكلية << " بايت\n";
        تقرير << "╠════════════════════════════════════════════════╣\n";
        
        for (const auto& [رقم_نقطة, إصدارات] : خطة.إصدارات_قبل_انتظار) {
            تقرير << "║ قبل انتظار #" << رقم_نقطة << ":\n";
            
            for (const auto& إصدار : إصدارات) {
                تقرير << "║   ├─ " << إصدار.اسم_المتغير;
                تقرير << " (" << إصدار.الحجم_المقدر << " بايت)";
                if (إصدار.يحتاج_destructor) {
                    تقرير << " [destructor]";
                }
                تقرير << "\n";
            }
        }
        
        تقرير << "╚════════════════════════════════════════════════╝\n";
        
        return تقرير.str();
    }
};

