// ═══════════════════════════════════════════════════════════════════════════════

/**
 * منفذ خطة الإصدار
 */
class منفذ_إصدار {
public:
    منفذ_إصدار(
        std::shared_ptr<واجهة_محرر> محرر,
        const خطة_إصدار& خطة
    ) : المحرر_(محرر), الخطة_(خطة), النقطة_الحالية_(0) {}
    
    /**
     * التقدم إلى نقطة انتظار معينة
     * يحرر كل المتغيرات المقررة للتحرير حتى هذه النقطة
     */
    void تقدم_إلى(int رقم_النقطة) {
        while (النقطة_الحالية_ <= رقم_النقطة) {
            نفِّذ_إصدارات_قبل(النقطة_الحالية_);
            النقطة_الحالية_++;
        }
    }
    
    /**
     * الإحصائيات
     */
    size_t الذاكرة_المحررة() const { return الذاكرة_المحررة_; }
    int عدد_التحريرات() const { return عدد_التحريرات_; }

private:
    std::shared_ptr<واجهة_محرر> المحرر_;
    خطة_إصدار الخطة_;
    int النقطة_الحالية_;
    size_t الذاكرة_المحررة_ = 0;
    int عدد_التحريرات_ = 0;
    
    void نفِّذ_إصدارات_قبل(int رقم_النقطة) {
        auto it = الخطة_.إصدارات_قبل_انتظار.find(رقم_النقطة);
        if (it == الخطة_.إصدارات_قبل_انتظار.end()) return;
        
        for (const auto& نقطة : it->second) {
            // استدعاء destructor إذا لزم
            if (نقطة.يحتاج_destructor) {
                المحرر_->استدعِ_destructor(نقطة.اسم_المتغير);
            }
            
            // تحرير الذاكرة
            if (المحرر_->حرر(نقطة.اسم_المتغير)) {
                الذاكرة_المحررة_ += نقطة.الحجم_المقدر;
                عدد_التحريرات_++;
            }
        }
    }
};

