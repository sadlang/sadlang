/**
 * أنواع الانتهاكات
 */
enum class نوع_انتهاك {
    وصول_غير_مصرح,        // محاولة وصول بدون إذن
    تجاوز_ذاكرة,           // استهلاك ذاكرة زائد
    تجاوز_وقت,             // تجاوز حد الوقت
    تجاوز_استدعاءات,      // استدعاءات كثيرة جداً
    وصول_ملف_محظور,       // ملف غير مسموح
    وصول_شبكة_محظور,      // شبكة غير مسموحة
    عملية_محظورة          // عملية نظام غير مسموحة
};

/**
 * سجل انتهاك
 */
struct انتهاك {
    نوع_انتهاك النوع;
    std::string الوصف;
    std::string المورد;          // ما حاول الوصول إليه
    std::chrono::system_clock::time_point الوقت;
    bool خطير;                   // هل يستدعي الإنهاء الفوري؟
};

