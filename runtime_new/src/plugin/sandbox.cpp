/**
 * قوالب صناديق رمل جاهزة
 */
class مصنع_صناديق {
public:
    /**
     * صندوق مُقيَّد جداً (للإضافات غير الموثوقة)
     */
    static صندوق_رمل مُقيَّد() {
        حدود_موارد حدود;
        حدود.حد_الذاكرة_بايت = 16 * 1024 * 1024;  // 16 MB
        حدود.حد_التنفيذ = std::chrono::milliseconds{5000};
        حدود.حد_الاستدعاءات_الكلي = 10000;
        
        return صندوق_رمل(حدود, {});
    }
    
    /**
     * صندوق متوسط (للإضافات الموثوقة نسبياً)
     */
    static صندوق_رمل متوسط() {
        حدود_موارد حدود;
        حدود.حد_الذاكرة_بايت = 128 * 1024 * 1024;  // 128 MB
        حدود.حد_التنفيذ = std::chrono::milliseconds{60000};
        
        std::vector<إذن_محدد> أذونات = {
            {نوع_إذن::اتصال_http}
        };
        
        return صندوق_رمل(حدود, أذونات);
    }
    
    /**
     * صندوق مُوسَّع (للإضافات الموثوقة تماماً)
     */
    static صندوق_رمل مُوسَّع() {
        حدود_موارد حدود;
        حدود.حد_الذاكرة_بايت = 512 * 1024 * 1024;  // 512 MB
        حدود.حد_التنفيذ = std::chrono::milliseconds{300000};  // 5 دقائق
        
        std::vector<إذن_محدد> أذونات = {
            {نوع_إذن::قراءة_ملفات},
            {نوع_إذن::كتابة_ملفات},
            {نوع_إذن::اتصال_http},
            {نوع_إذن::قراءة_بيئة}
        };
        
        return صندوق_رمل(حدود, أذونات);
    }
};

