/**
 * أنواع الأذونات
 * 
 * كل إذن يفتح قدرة معينة للإضافة
 */
enum class نوع_إذن {
    // نظام الملفات
    قراءة_ملفات,           // قراءة ملفات محددة
    كتابة_ملفات,           // كتابة لملفات محددة
    حذف_ملفات,             // حذف ملفات
    تصفح_مجلدات,           // رؤية قائمة الملفات
    
    // الشبكة
    اتصال_http,            // طلبات HTTP صادرة
    استماع_منفذ,           // فتح منفذ للاستماع
    اتصال_مقبس,            // مقابس خام
    
    // النظام
    قراءة_بيئة,            // قراءة متغيرات البيئة
    تنفيذ_أوامر,           // تنفيذ أوامر النظام
    
    // الموارد
    خيوط_متعددة,           // إنشاء خيوط
    ذاكرة_إضافية,          // تجاوز حد الذاكرة
    وقت_ممتد              // تجاوز حد الوقت
};

/**
 * إذن محدد مع تفاصيل
 */
struct إذن_محدد {
    نوع_إذن النوع;
    std::string التفاصيل;  // مثل: مسار ملف أو عنوان شبكة
    
    إذن_محدد(نوع_إذن نوع, std::string تفاصيل = "")
        : النوع(نوع), التفاصيل(std::move(تفاصيل)) {}
};

