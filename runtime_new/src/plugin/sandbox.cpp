/**
 * سياق تنفيذ معزول
 * 
 * يتتبع حالة التنفيذ والموارد المُستخدمة
 */
class سياق_عزل {
public:
    سياق_عزل(const حدود_موارد& حدود)
        : الحدود_(حدود)
        , الذاكرة_المُستخدمة_(0)
        , عدد_الاستدعاءات_(0)
        , عمق_المكدس_(0)
        , نشط_(true)
    {
        وقت_البدء_ = std::chrono::steady_clock::now();
    }
    
    /**
     * هل السياق لا يزال نشطاً؟
     */
    bool نشط() const { return نشط_; }
    
    /**
     * تخصيص ذاكرة
     * @return true إذا نجح، false إذا تجاوز الحد
     */
    bool خصص_ذاكرة(size_t حجم) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        if (الذاكرة_المُستخدمة_ + حجم > الحدود_.حد_الذاكرة_بايت) {
            سجِّل_انتهاك(نوع_انتهاك::تجاوز_ذاكرة, 
                        "محاولة تخصيص " + std::to_string(حجم) + " بايت");
            return false;
        }
        
        الذاكرة_المُستخدمة_ += حجم;
        return true;
    }
    
    /**
     * تحرير ذاكرة
     */
    void حرر_ذاكرة(size_t حجم) {
        std::lock_guard<std::mutex> قفل(القفل_);
        الذاكرة_المُستخدمة_ = حجم > الذاكرة_المُستخدمة_ ? 0 : الذاكرة_المُستخدمة_ - حجم;
    }
    
    /**
     * بدء استدعاء دالة
     */
    bool ادخل_استدعاء() {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        // تحقق من عمق المكدس
        if (عمق_المكدس_ >= الحدود_.حد_عمق_المكدس) {
            سجِّل_انتهاك(نوع_انتهاك::تجاوز_استدعاءات,
                        "تجاوز حد عمق المكدس: " + std::to_string(عمق_المكدس_));
            return false;
        }
        
        // تحقق من عدد الاستدعاءات الكلي
        if (عدد_الاستدعاءات_ >= الحدود_.حد_الاستدعاءات_الكلي) {
            سجِّل_انتهاك(نوع_انتهاك::تجاوز_استدعاءات,
                        "تجاوز حد الاستدعاءات: " + std::to_string(عدد_الاستدعاءات_));
            return false;
        }
        
        عمق_المكدس_++;
        عدد_الاستدعاءات_++;
        return true;
    }
    
    /**
     * إنهاء استدعاء دالة
     */
    void اخرج_استدعاء() {
        std::lock_guard<std::mutex> قفل(القفل_);
        if (عمق_المكدس_ > 0) عمق_المكدس_--;
    }
    
    /**
     * تحقق من حد الوقت
     */
    bool تحقق_الوقت() {
        auto الآن = std::chrono::steady_clock::now();
        auto المدة = std::chrono::duration_cast<std::chrono::milliseconds>(الآن - وقت_البدء_);
        
        if (المدة > الحدود_.حد_التنفيذ) {
            سجِّل_انتهاك(نوع_انتهاك::تجاوز_وقت, "تجاوز حد التنفيذ", true);
            نشط_ = false;
            return false;
        }
        
        return true;
    }
    
    /**
     * إحصائيات الاستخدام
     */
    size_t الذاكرة_المُستخدمة() const { return الذاكرة_المُستخدمة_; }
    size_t عدد_الاستدعاءات() const { return عدد_الاستدعاءات_; }
    size_t عمق_المكدس() const { return عمق_المكدس_; }
    
    /**
     * قائمة الانتهاكات
     */
    const std::vector<انتهاك>& الانتهاكات() const { return الانتهاكات_; }
    
    /**
     * إنهاء السياق
     */
    void أنهِ(const std::string& سبب = "") {
        نشط_ = false;
        if (!سبب.empty()) {
            سجِّل_انتهاك(نوع_انتهاك::عملية_محظورة, "إنهاء: " + سبب);
        }
    }

private:
    void سجِّل_انتهاك(نوع_انتهاك نوع, const std::string& وصف, bool خطير = false) {
        انتهاك ا;
        ا.النوع = نوع;
        ا.الوصف = وصف;
        ا.الوقت = std::chrono::system_clock::now();
        ا.خطير = خطير;
        الانتهاكات_.push_back(ا);
        
        if (خطير) {
            نشط_ = false;
        }
    }
    
    حدود_موارد الحدود_;
    std::atomic<size_t> الذاكرة_المُستخدمة_;
    std::atomic<size_t> عدد_الاستدعاءات_;
    std::atomic<size_t> عمق_المكدس_;
    std::atomic<bool> نشط_;
    std::chrono::steady_clock::time_point وقت_البدء_;
    std::vector<انتهاك> الانتهاكات_;
    std::mutex القفل_;
};

