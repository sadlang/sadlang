/**
 * حدود موارد الـ Sandbox
 * 
 * تمنع الإضافة من استهلاك موارد زائدة
 */
struct حدود_موارد {
    // الذاكرة
    size_t حد_الذاكرة_بايت = 64 * 1024 * 1024;     // 64 MB
    size_t حجم_المكدس_بايت = 1 * 1024 * 1024;      // 1 MB
    
    // الوقت
    std::chrono::milliseconds حد_التنفيذ{30000};   // 30 ثانية
    std::chrono::milliseconds حد_الاستدعاء{5000};  // 5 ثوانٍ لكل استدعاء
    
    // استدعاءات
    size_t حد_عمق_المكدس = 500;
    size_t حد_الاستدعاءات_الكلي = 100000;
    
    // ملفات
    size_t حد_الملفات_المفتوحة = 10;
    size_t حد_حجم_الملف_بايت = 10 * 1024 * 1024;   // 10 MB
    
    // شبكة
    size_t حد_الاتصالات = 5;
    size_t حد_البيانات_المرسلة = 1 * 1024 * 1024;  // 1 MB
};

