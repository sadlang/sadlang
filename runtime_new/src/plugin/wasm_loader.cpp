/**
 * بيانات وحدة WASM المُحمَّلة
 */
struct بيانات_وحدة {
    std::vector<uint8_t> البايتات;
    std::string الاسم;
    std::string المسار;
    size_t الحجم;
    
    // التوقيع للتحقق من السلامة
    std::string التوقيع_sha256;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              خيارات التحميل
