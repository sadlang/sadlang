/**
 * أنواع القيم التي يدعمها WASM
 * 
 * WASM يدعم أنواع محدودة:
 * - i32: عدد صحيح 32-bit
 * - i64: عدد صحيح 64-bit  
 * - f32: عدد عشري 32-bit
 * - f64: عدد عشري 64-bit
 * - externref: مرجع خارجي
 */
enum class نوع_wasm {
    عدد_32,      // i32
    عدد_64,      // i64
    عشري_32,    // f32
    عشري_64,    // f64
    مرجع_خارجي // externref
};

/**
 * قيمة WASM
 */
struct قيمة_wasm {
    نوع_wasm النوع;
    union {
        int32_t عدد_32;
        int64_t عدد_64;
        float عشري_32;
        double عشري_64;
        void* مرجع;
    } القيمة;
    
    // بناة مساعدة
    static قيمة_wasm من_عدد(int32_t x) {
        قيمة_wasm v;
        v.النوع = نوع_wasm::عدد_32;
        v.القيمة.عدد_32 = x;
        return v;
    }
    
    static قيمة_wasm من_عدد_كبير(int64_t x) {
        قيمة_wasm v;
        v.النوع = نوع_wasm::عدد_64;
        v.القيمة.عدد_64 = x;
        return v;
    }
    
    static قيمة_wasm من_عشري(double x) {
        قيمة_wasm v;
        v.النوع = نوع_wasm::عشري_64;
        v.القيمة.عشري_64 = x;
        return v;
    }
};

