/**
 * واصف دالة مُصدَّرة من WASM
 * 
 * كل دالة في الإضافة لها:
 * - اسم (للاستدعاء)
 * - أنواع المعاملات
 * - أنواع القيم المُرجَعة
 */
struct واصف_دالة_wasm {
    std::string الاسم;
    std::vector<نوع_wasm> المعاملات;
    std::vector<نوع_wasm> نتائج_الإرجاع;
};

