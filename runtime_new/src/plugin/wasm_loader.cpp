/**
 * دالة يُوفرها البرنامج الرئيسي للإضافة
 * 
 * "الاستيراد" = الإضافة تستخدم دالة من البرنامج الرئيسي
 * مثلاً: إضافة تريد طباعة رسالة، تستورد دالة "اطبع"
 */
using دالة_مستوردة = std::function<std::vector<قيمة_wasm>(
    const std::vector<قيمة_wasm>& معاملات
)>;

struct استيراد_دالة {
    std::string الوحدة;
    std::string الاسم;
    واصف_دالة_wasm الواصف;
    دالة_مستوردة التنفيذ;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              حالة التحميل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حالة تحميل الإضافة
 */
enum class حالة_تحميل {
    نجاح,
    ملف_غير_موجود,
    صيغة_غير_صالحة,
    توقيع_غير_صالح,
    نقص_استيرادات,
    تجاوز_حدود,
    خطأ_غير_معروف
};

/**
 * نتيجة التحميل
 */
struct نتيجة_تحميل {
    حالة_تحميل الحالة;
    std::string رسالة_خطأ;
    std::vector<واصف_دالة_wasm> الدوال_المُصدَّرة;
    
    bool نجح() const { return الحالة == حالة_تحميل::نجاح; }
};

