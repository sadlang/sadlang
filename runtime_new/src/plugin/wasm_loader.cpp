/**
 * مثيل إضافة WASM قيد التشغيل
 * 
 * كل "مثيل" هو نسخة مستقلة من الإضافة:
 * - ذاكرة منفصلة
 * - حالة منفصلة
 * - يمكن تشغيل عدة مثيلات من نفس الإضافة
 */
class مثيل_إضافة {
public:
    virtual ~مثيل_إضافة() = default;
    
    /**
     * استدعاء دالة مُصدَّرة
     * 
     * @param اسم اسم الدالة
     * @param معاملات قيم المعاملات
     * @return نتائج الدالة (أو خطأ)
     */
    virtual std::optional<std::vector<قيمة_wasm>> استدعِ(
        const std::string& اسم,
        const std::vector<قيمة_wasm>& معاملات
    ) = 0;
    
    /**
     * الحصول على قائمة الدوال المُصدَّرة
     */
    virtual std::vector<واصف_دالة_wasm> الدوال_المُصدَّرة() const = 0;
    
    /**
     * هل الدالة موجودة؟
     */
    virtual bool توجد_دالة(const std::string& اسم) const = 0;
    
    /**
     * إحصائيات الاستخدام
     */
    virtual size_t الذاكرة_المُستخدمة() const = 0;
    virtual size_t عدد_الاستدعاءات() const = 0;
};

