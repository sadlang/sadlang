/**
 * خيارات تحميل الإضافة
 */
struct خيارات_تحميل {
    // حدود الموارد
    size_t حد_الذاكرة = 256 * 1024 * 1024;  // 256 MB افتراضياً
    size_t حد_الوقت_ثانية = 60;             // دقيقة واحدة
    size_t حد_استدعاءات_المكدس = 1000;
    
    // الأمان
    bool السماح_بالملفات = false;
    bool السماح_بالشبكة = false;
    bool السماح_بالبيئة = false;
    
    // التحقق
    bool التحقق_من_التوقيع = true;
    std::vector<std::string> الموقعين_الموثوقين;
};

