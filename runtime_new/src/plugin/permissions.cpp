/**
 * مجموعة أذونات لإضافة
 */
class مجموعة_أذونات {
public:
    /**
     * إضافة قاعدة إذن
     */
    void أضف(const قاعدة_إذن& قاعدة) {
        القواعد_[قاعدة.معرف_الإذن].push_back(قاعدة);
    }
    
    /**
     * إزالة كل قواعد إذن
     */
    void أزل(const std::string& معرف) {
        القواعد_.erase(معرف);
    }
    
    /**
     * التحقق من إذن
     */
    bool مسموح(const std::string& معرف, const std::string& مورد = "") const {
        auto it = القواعد_.find(معرف);
        if (it == القواعد_.end()) {
            return false;
        }
        
        // تحقق من كل قاعدة
        for (const auto& قاعدة : it->second) {
            // تحقق من الانتهاء
            if (!قاعدة.دائم) {
                if (std::chrono::system_clock::now() > قاعدة.ينتهي_في) {
                    continue;
                }
            }
            
            if (قاعدة.يسمح(مورد)) {
                return true;
            }
        }
        
        return false;
    }
    
    /**
     * قائمة الأذونات الممنوحة
     */
    std::vector<std::string> الممنوحة() const {
        std::vector<std::string> نتائج;
        for (const auto& [معرف, _] : القواعد_) {
            نتائج.push_back(معرف);
        }
        return نتائج;
    }
    
    /**
     * دمج مع مجموعة أخرى
     */
    void ادمج(const مجموعة_أذونات& أخرى) {
        for (const auto& [معرف, قواعد] : أخرى.القواعد_) {
            for (const auto& قاعدة : قواعد) {
                أضف(قاعدة);
            }
        }
    }

private:
    std::unordered_map<std::string, std::vector<قاعدة_إذن>> القواعد_;
};

