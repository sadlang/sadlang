/**
 * نتيجة التحقق
 */
struct نتيجة_تحقق_إذن {
    bool مسموح;
    std::string السبب;
    مستوى_خطورة الخطورة;
};

/**
 * محقق الأذونات
 * 
 * يفحص الأذونات ويُسجل المحاولات
 */
class محقق_أذونات {
public:
    محقق_أذونات(مجموعة_أذونات& أذونات)
        : الأذونات_(أذونات) {}
    
    /**
     * تحقق من إذن
     */
    نتيجة_تحقق_إذن تحقق(
        const std::string& معرف,
        const std::string& مورد = ""
    ) {
        نتيجة_تحقق_إذن نتيجة;
        
        // ابحث عن تعريف الإذن
        auto* تعريف = سجل_أذونات::المثال().احصل(معرف);
        if (!تعريف) {
            نتيجة.مسموح = false;
            نتيجة.السبب = "إذن غير معروف: " + معرف;
            نتيجة.الخطورة = مستوى_خطورة::حرج;
            سجِّل_محاولة(معرف, مورد, false);
            return نتيجة;
        }
        
        // تحقق من الأذونات المُتطلَّبة
        for (const auto& مُتطلَّب : تعريف->يتطلب) {
            if (!الأذونات_.مسموح(مُتطلَّب)) {
                نتيجة.مسموح = false;
                نتيجة.السبب = "يتطلب إذن: " + مُتطلَّب;
                نتيجة.الخطورة = تعريف->الخطورة;
                سجِّل_محاولة(معرف, مورد, false);
                return نتيجة;
            }
        }
        
        // تحقق من الإذن نفسه
        if (!الأذونات_.مسموح(معرف, مورد)) {
            نتيجة.مسموح = false;
            نتيجة.السبب = "الإذن غير ممنوح";
            نتيجة.الخطورة = تعريف->الخطورة;
            سجِّل_محاولة(معرف, مورد, false);
            return نتيجة;
        }
        
        نتيجة.مسموح = true;
        نتيجة.الخطورة = تعريف->الخطورة;
        سجِّل_محاولة(معرف, مورد, true);
        return نتيجة;
    }
    
    /**
     * تحقق سريع (بدون تفاصيل)
     */
    bool مسموح_سريع(const std::string& معرف, const std::string& مورد = "") {
        return تحقق(معرف, مورد).مسموح;
    }
    
    /**
     * إحصائيات
     */
    size_t عدد_المحاولات() const { return عدد_المحاولات_; }
    size_t عدد_المرفوضات() const { return عدد_المرفوضات_; }

private:
    void سجِّل_محاولة(const std::string& معرف, const std::string& مورد, bool نجح) {
        عدد_المحاولات_++;
        if (!نجح) {
            عدد_المرفوضات_++;
        }
        // يمكن إضافة تسجيل مُفصَّل هنا
    }
    
    مجموعة_أذونات& الأذونات_;
    size_t عدد_المحاولات_ = 0;
    size_t عدد_المرفوضات_ = 0;
};

