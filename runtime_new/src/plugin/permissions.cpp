/**
 * فئات الأذونات
 * 
 * مجموعة عامة لتصنيف الأذونات
 */
enum class فئة_إذن {
    نظام_ملفات,      // كل ما يتعلق بالملفات
    شبكة,            // اتصالات الإنترنت
    نظام_تشغيل,      // أوامر النظام
    موارد,           // الذاكرة والوقت
    حساسة            // بيانات حساسة
};

/**
 * مستوى الخطورة
 */
enum class مستوى_خطورة {
    منخفض,           // لا ضرر محتمل
    متوسط,           // قد يُسبب مشاكل
    عالي,            // خطر أمني
    حرج              // خطر شديد
};

/**
 * تعريف إذن كامل
 */
struct تعريف_إذن {
    std::string المعرف;           // مثل: "fs.read"
    std::string الاسم_العربي;
    std::string الوصف;
    فئة_إذن الفئة;
    مستوى_خطورة الخطورة;
    std::vector<std::string> يتطلب;  // أذونات مُتطلَّبة
};

