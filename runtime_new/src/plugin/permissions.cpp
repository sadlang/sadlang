/**
 * سجل تعريفات الأذونات
 * 
 * يحتوي كل الأذونات المتاحة في النظام
 */
class سجل_أذونات {
public:
    static سجل_أذونات& المثال() {
        static سجل_أذونات instance;
        return instance;
    }
    
    /**
     * تسجيل إذن جديد
     */
    void سجِّل(const تعريف_إذن& تعريف) {
        التعريفات_[تعريف.المعرف] = تعريف;
    }
    
    /**
     * الحصول على تعريف إذن
     */
    const تعريف_إذن* احصل(const std::string& معرف) const {
        auto it = التعريفات_.find(معرف);
        return it != التعريفات_.end() ? &it->second : nullptr;
    }
    
    /**
     * كل الأذونات في فئة
     */
    std::vector<تعريف_إذن> في_فئة(فئة_إذن فئة) const {
        std::vector<تعريف_إذن> نتائج;
        for (const auto& [_, تعريف] : التعريفات_) {
            if (تعريف.الفئة == فئة) {
                نتائج.push_back(تعريف);
            }
        }
        return نتائج;
    }
    
    /**
     * تهيئة الأذونات الافتراضية
     */
    void هيِّئ_الافتراضية() {
        // أذونات الملفات
        سجِّل({"fs.read", "قراءة ملفات", "السماح بقراءة الملفات", 
               فئة_إذن::نظام_ملفات, مستوى_خطورة::منخفض, {}});
        سجِّل({"fs.write", "كتابة ملفات", "السماح بكتابة الملفات",
               فئة_إذن::نظام_ملفات, مستوى_خطورة::متوسط, {"fs.read"}});
        سجِّل({"fs.delete", "حذف ملفات", "السماح بحذف الملفات",
               فئة_إذن::نظام_ملفات, مستوى_خطورة::عالي, {"fs.write"}});
        سجِّل({"fs.list", "تصفح المجلدات", "السماح برؤية محتويات المجلدات",
               فئة_إذن::نظام_ملفات, مستوى_خطورة::منخفض, {}});
        
        // أذونات الشبكة
        سجِّل({"net.http", "اتصال HTTP", "السماح بطلبات HTTP/HTTPS",
               فئة_إذن::شبكة, مستوى_خطورة::متوسط, {}});
        سجِّل({"net.socket", "مقابس خام", "السماح باتصالات TCP/UDP مباشرة",
               فئة_إذن::شبكة, مستوى_خطورة::عالي, {}});
        سجِّل({"net.listen", "استماع منفذ", "السماح بفتح منفذ للاستماع",
               فئة_إذن::شبكة, مستوى_خطورة::عالي, {}});
        
        // أذونات النظام
        سجِّل({"sys.env", "متغيرات البيئة", "السماح بقراءة متغيرات البيئة",
               فئة_إذن::نظام_تشغيل, مستوى_خطورة::متوسط, {}});
        سجِّل({"sys.exec", "تنفيذ أوامر", "السماح بتنفيذ أوامر النظام",
               فئة_إذن::نظام_تشغيل, مستوى_خطورة::حرج, {}});
        
        // أذونات الموارد
        سجِّل({"res.threads", "خيوط متعددة", "السماح بإنشاء خيوط",
               فئة_إذن::موارد, مستوى_خطورة::متوسط, {}});
        سجِّل({"res.memory", "ذاكرة إضافية", "السماح بتجاوز حد الذاكرة",
               فئة_إذن::موارد, مستوى_خطورة::عالي, {}});
    }

private:
    سجل_أذونات() { هيِّئ_الافتراضية(); }
    std::unordered_map<std::string, تعريف_إذن> التعريفات_;
};

