/**
 * سياسة أذونات مُسماة
 * 
 * مجموعة من الأذونات بإعدادات محددة
 */
struct سياسة {
    std::string الاسم;
    std::string الوصف;
    مجموعة_أذونات الأذونات;
    مستوى_خطورة الحد_الأقصى;  // أقصى خطورة مسموحة
};

/**
 * مدير السياسات
 */
class مدير_سياسات {
public:
    static مدير_سياسات& المثال() {
        static مدير_سياسات instance;
        return instance;
    }
    
    /**
     * تسجيل سياسة
     */
    void سجِّل(const سياسة& س) {
        السياسات_[س.الاسم] = س;
    }
    
    /**
     * الحصول على سياسة
     */
    const سياسة* احصل(const std::string& اسم) const {
        auto it = السياسات_.find(اسم);
        return it != السياسات_.end() ? &it->second : nullptr;
    }
    
    /**
     * إنشاء السياسات الافتراضية
     */
    void هيِّئ_الافتراضية() {
        // سياسة مُقيَّدة
        سياسة مُقيَّدة;
        مُقيَّدة.الاسم = "مُقيَّد";
        مُقيَّدة.الوصف = "أذونات محدودة جداً للإضافات غير الموثوقة";
        مُقيَّدة.الحد_الأقصى = مستوى_خطورة::منخفض;
        سجِّل(مُقيَّدة);
        
        // سياسة عادية
        سياسة عادية;
        عادية.الاسم = "عادي";
        عادية.الوصف = "أذونات متوسطة للإضافات العادية";
        عادية.الحد_الأقصى = مستوى_خطورة::متوسط;
        
        قاعدة_إذن قراءة;
        قراءة.معرف_الإذن = "fs.read";
        عادية.الأذونات.أضف(قراءة);
        
        قاعدة_إذن http;
        http.معرف_الإذن = "net.http";
        عادية.الأذونات.أضف(http);
        
        سجِّل(عادية);
        
        // سياسة موثوقة
        سياسة موثوقة;
        موثوقة.الاسم = "موثوق";
        موثوقة.الوصف = "أذونات واسعة للإضافات الموثوقة";
        موثوقة.الحد_الأقصى = مستوى_خطورة::عالي;
        
        قاعدة_إذن كتابة;
        كتابة.معرف_الإذن = "fs.write";
        موثوقة.الأذونات.أضف(كتابة);
        
        موثوقة.الأذونات.ادمج(عادية.الأذونات);
        
        سجِّل(موثوقة);
    }

private:
    مدير_سياسات() { هيِّئ_الافتراضية(); }
    std::unordered_map<std::string, سياسة> السياسات_;
};

