/**
 * قاعدة إذن مع شروط
 * 
 * الإذن + شروط استخدامه
 * مثال: "قراءة ملفات في مجلد /data فقط"
 */
struct قاعدة_إذن {
    std::string معرف_الإذن;
    
    // قيود إضافية
    std::vector<std::string> المسارات_المسموحة;     // للملفات
    std::vector<std::string> النطاقات_المسموحة;    // للشبكة
    std::vector<int> المنافذ_المسموحة;              // للشبكة
    
    // حدود
    size_t حد_الحجم = 0;                            // 0 = لا حد
    int حد_العمليات_في_الدقيقة = 0;
    
    // الفترة الزمنية
    std::chrono::system_clock::time_point ينتهي_في;
    bool دائم = true;
    
    /**
     * هل القاعدة تسمح بالمورد؟
     */
    bool يسمح(const std::string& مورد) const {
        // إذا لا قيود، يسمح بكل شيء
        if (المسارات_المسموحة.empty()) {
            return true;
        }
        
        // تحقق من كل نمط
        for (const auto& نمط : المسارات_المسموحة) {
            if (يُطابق(مورد, نمط)) {
                return true;
            }
        }
        
        return false;
    }
    
private:
    bool يُطابق(const std::string& نص, const std::string& نمط) const {
        // نمط بسيط: * = أي شيء
        if (نمط == "*") return true;
        if (نمط.back() == '*') {
            return نص.substr(0, نمط.size() - 1) == نمط.substr(0, نمط.size() - 1);
        }
        return نص == نمط;
    }
};

