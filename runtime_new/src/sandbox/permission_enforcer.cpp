/**
 * سجل لتتبع العمليات الحساسة
 */
struct سجل_عملية {
    استثناء_إذن::نوع النوع;
    std::string العملية;
    std::string الهدف;
    bool مسموح;
    std::chrono::system_clock::time_point الوقت;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << (مسموح ? "✅" : "❌") << " ";
        ss << "[" << نوع_إلى_نص(النوع) << "] ";
        ss << العملية;
        if (!الهدف.empty()) ss << " → " << الهدف;
        return ss.str();
    }
    
    static std::string نوع_إلى_نص(استثناء_إذن::نوع نوع) {
        switch (نوع) {
            case استثناء_إذن::نوع::ملف: return "ملف";
            case استثناء_إذن::نوع::شبكة: return "شبكة";
            case استثناء_إذن::نوع::نظام: return "نظام";
            case استثناء_إذن::نوع::كاميرا: return "كاميرا";
            case استثناء_إذن::نوع::ميكروفون: return "ميكروفون";
            case استثناء_إذن::نوع::موقع: return "موقع";
            case استثناء_إذن::نوع::عملية: return "عملية";
            default: return "غير_محدد";
        }
    }
};

