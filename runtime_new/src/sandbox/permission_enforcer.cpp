/**
 * تحويل فئة إذن إلى نص (forward declaration)
 */
enum class فئة_إذن {
    ملفات,
    شبكة,
    نظام,
    كاميرا,
    ميكروفون,
    موقع,
    إشعارات,
    حافظة,
    بيئة,
    عملية,
};

enum class نوع_عملية {
    قراءة,
    كتابة,
    تنفيذ,
    إنشاء,
    حذف,
    الكل,
};

/**
 * مُنفِّذ الأذونات وقت التشغيل
 * 
 * للمبتدئ: هذه الفئة تُستخدم من runtime لفرض الأذونات
 * 
 * مثال:
 * ```cpp
 * // في بداية البرنامج
 * مُنفِّذ_أذونات::المثال().حمِّل_من_ملف("ص.toml");
 * 
 * // قبل كل عملية حساسة
 * مُنفِّذ_أذونات::المثال().تأكد_ملف("/path/to/file", نوع_عملية::قراءة);
 * ```
 */
class مُنفِّذ_أذونات {
public:
    /**
     * إعدادات المُنفِّذ
     */
    struct إعدادات {
        bool فعَّال = true;                      // هل الفحص مفعَّل؟
        bool سجِّل_المسموحات = false;           // سجِّل حتى العمليات المسموحة
        bool اسأل_عند_الرفض = false;           // اسأل المستخدم عند الرفض
        size_t حد_السجل = 1000;                // الحد الأقصى لسجل العمليات
        
        std::function<void(const سجل_عملية&)> معالج_انتهاك;
        std::function<bool(const std::string&)> مؤكد_المستخدم;
    };
    
    /**
     * الحصول على المُنفِّذ العالمي (Singleton)
     */
    static مُنفِّذ_أذونات& المثال() {
        static مُنفِّذ_أذونات مثال;
        return مثال;
    }
    
    /**
     * تعيين الإعدادات
     */
    void عيِّن_الإعدادات(إعدادات إعدادات) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_إعدادات = std::move(إعدادات);
    }
    
    /**
     * تعطيل الفحص (للتصحيح فقط!)
     */
    void عطِّل() {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_إعدادات.فعَّال = false;
    }
    
    /**
     * تفعيل الفحص
     */
    void فعِّل() {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_إعدادات.فعَّال = true;
    }
    
    // ═══════════════════════════════════════════════════════════════════════════
    //                              دوال التأكد
    // ═══════════════════════════════════════════════════════════════════════════
    
    /**
     * التأكد من إذن ملف
     * @throws استثناء_إذن إذا لم يكن مسموحاً
     */
    void تأكد_ملف(const std::string& مسار, نوع_عملية عملية) {
        تأكد(استثناء_إذن::نوع::ملف, عملية_إلى_نص(عملية), مسار,
             [&]() { return فحص_إذن_ملف(مسار, عملية); });
    }
    
    /**
     * التأكد من إذن شبكة
     */
    void تأكد_شبكة(const std::string& url) {
        تأكد(استثناء_إذن::نوع::شبكة, "اتصال", url,
             [&]() { return فحص_إذن_شبكة(url); });
    }
    
    /**
     * التأكد من إذن أمر نظام
     */
    void تأكد_نظام(const std::string& أمر) {
        تأكد(استثناء_إذن::نوع::نظام, "تنفيذ", أمر,
             [&]() { return فحص_إذن_نظام(أمر); });
    }
    
    /**
     * التأكد من إذن عملية
     */
    void تأكد_عملية(const std::string& برنامج) {
        تأكد(استثناء_إذن::نوع::عملية, "تشغيل", برنامج,
             [&]() { return فحص_إذن_عملية(برنامج); });
    }
    
    /**
     * التأكد من إذن كاميرا
     */
    void تأكد_كاميرا() {
        تأكد(استثناء_إذن::نوع::كاميرا, "فتح", "",
             [&]() { return فحص_إذن_كاميرا(); });
    }
    
    /**
     * التأكد من إذن ميكروفون
     */
    void تأكد_ميكروفون() {
        تأكد(استثناء_إذن::نوع::ميكروفون, "فتح", "",
             [&]() { return فحص_إذن_ميكروفون(); });
    }
    
    /**
     * التأكد من إذن موقع
     */
    void تأكد_موقع() {
        تأكد(استثناء_إذن::نوع::موقع, "قراءة", "",
             [&]() { return فحص_إذن_موقع(); });
    }
    
    // ═══════════════════════════════════════════════════════════════════════════
    //                              إدارة الأذونات
    // ═══════════════════════════════════════════════════════════════════════════
    
    /**
     * إضافة إذن ملف
     */
    void أضف_إذن_ملف(const std::string& نمط, نوع_عملية عملية) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_أنماط_ملفات[نمط].insert(عملية);
    }
    
    /**
     * إضافة إذن شبكة
     */
    void أضف_إذن_شبكة(const std::string& نمط) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_أنماط_شبكة.insert(نمط);
    }
    
    /**
     * تفعيل إذن بسيط
     */
    void فعِّل_إذن(فئة_إذن فئة) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_أذونات_بسيطة.insert(فئة);
    }
    
    /**
     * تعطيل إذن بسيط
     */
    void عطِّل_إذن(فئة_إذن فئة) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_أذونات_بسيطة.erase(فئة);
    }
    
    // ═══════════════════════════════════════════════════════════════════════════
    //                              السجل
    // ═══════════════════════════════════════════════════════════════════════════
    
    /**
     * الحصول على السجل
     */
    std::vector<سجل_عملية> السجل() const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        return m_سجل;
    }
    
    /**
     * مسح السجل
     */
    void امسح_السجل() {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_سجل.clear();
    }
    
    /**
     * إحصائيات السجل
     */
    struct إحصائيات {
        size_t عدد_المسموحات = 0;
        size_t عدد_الانتهاكات = 0;
    };
    
    إحصائيات الإحصائيات() const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        إحصائيات نتيجة;
        for (const auto& سجل : m_سجل) {
            if (سجل.مسموح) نتيجة.عدد_المسموحات++;
            else نتيجة.عدد_الانتهاكات++;
        }
        return نتيجة;
    }
    
private:
    مُنفِّذ_أذونات() = default;
    
    mutable std::mutex m_قفل;
    إعدادات m_إعدادات;
    
    // أنماط الأذونات
    std::unordered_map<std::string, std::unordered_set<نوع_عملية>> m_أنماط_ملفات;
    std::unordered_set<std::string> m_أنماط_شبكة;
    std::unordered_set<فئة_إذن> m_أذونات_بسيطة;
    
    // السجل
    std::vector<سجل_عملية> m_سجل;
    
    /**
     * الدالة الرئيسية للتأكد
     */
    void تأكد(
        استثناء_إذن::نوع نوع,
        const std::string& عملية,
        const std::string& هدف,
        std::function<bool()> فاحص) {
        
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        if (!m_إعدادات.فعَّال) return;
        
        bool مسموح = فاحص();
        
        // سجِّل العملية
        سجل_عملية سجل{نوع, عملية, هدف, مسموح, std::chrono::system_clock::now()};
        
        if (!مسموح || m_إعدادات.سجِّل_المسموحات) {
            if (m_سجل.size() >= m_إعدادات.حد_السجل) {
                m_سجل.erase(m_سجل.begin());  // إزالة الأقدم
            }
            m_سجل.push_back(سجل);
        }
        
        if (!مسموح) {
            // معالج مخصص
            if (m_إعدادات.معالج_انتهاك) {
                m_إعدادات.معالج_انتهاك(سجل);
            }
            
            // اسأل المستخدم؟
            if (m_إعدادات.اسأل_عند_الرفض && m_إعدادات.مؤكد_المستخدم) {
                std::string سؤال = "هل تسمح بـ " + عملية;
                if (!هدف.empty()) سؤال += " (" + هدف + ")";
                سؤال += "؟";
                
                if (m_إعدادات.مؤكد_المستخدم(سؤال)) {
                    return;  // سمح المستخدم
                }
            }
            
            // ارمِ استثناء
            throw استثناء_إذن(نوع, عملية, هدف);
        }
    }
    
    /**
     * تحويل عملية إلى نص
     */
    std::string عملية_إلى_نص(نوع_عملية عملية) const {
        switch (عملية) {
            case نوع_عملية::قراءة: return "قراءة";
            case نوع_عملية::كتابة: return "كتابة";
            case نوع_عملية::تنفيذ: return "تنفيذ";
            case نوع_عملية::إنشاء: return "إنشاء";
            case نوع_عملية::حذف: return "حذف";
            default: return "عملية";
        }
    }
    
    // ═══════════════════════════════════════════════════════════════════════════
    //                              دوال الفحص
    // ═══════════════════════════════════════════════════════════════════════════
    
    bool فحص_إذن_ملف(const std::string& مسار, نوع_عملية عملية) {
        // فحص كل نمط
        for (const auto& [نمط, عمليات] : m_أنماط_ملفات) {
            if (يطابق_نمط(مسار, نمط)) {
                if (عمليات.find(عملية) != عمليات.end() ||
                    عمليات.find(نوع_عملية::الكل) != عمليات.end()) {
                    return true;
                }
            }
        }
        
        // فحص إذن عام للملفات
        return m_أذونات_بسيطة.find(فئة_إذن::ملفات) != m_أذونات_بسيطة.end();
    }
    
    bool فحص_إذن_شبكة(const std::string& url) {
        for (const auto& نمط : m_أنماط_شبكة) {
            if (يطابق_نمط(url, نمط)) return true;
        }
        return m_أذونات_بسيطة.find(فئة_إذن::شبكة) != m_أذونات_بسيطة.end();
    }
    
    bool فحص_إذن_نظام(const std::string& أمر) {
        return m_أذونات_بسيطة.find(فئة_إذن::نظام) != m_أذونات_بسيطة.end();
    }
    
    bool فحص_إذن_عملية(const std::string& برنامج) {
        return m_أذونات_بسيطة.find(فئة_إذن::عملية) != m_أذونات_بسيطة.end();
    }
    
    bool فحص_إذن_كاميرا() {
        return m_أذونات_بسيطة.find(فئة_إذن::كاميرا) != m_أذونات_بسيطة.end();
    }
    
    bool فحص_إذن_ميكروفون() {
        return m_أذونات_بسيطة.find(فئة_إذن::ميكروفون) != m_أذونات_بسيطة.end();
    }
    
    bool فحص_إذن_موقع() {
        return m_أذونات_بسيطة.find(فئة_إذن::موقع) != m_أذونات_بسيطة.end();
    }
    
    /**
     * مطابقة نمط glob بسيط
     */
    bool يطابق_نمط(const std::string& نص, const std::string& نمط) {
        // تنفيذ بسيط - يمكن تحسينه
        if (نمط == "*") return true;
        
        size_t i = 0, j = 0;
        size_t نجمة = std::string::npos;
        size_t موقع_نص = 0;
        
        while (i < نص.size()) {
            if (j < نمط.size() && (نمط[j] == '?' || نمط[j] == نص[i])) {
                i++;
                j++;
            } else if (j < نمط.size() && نمط[j] == '*') {
                نجمة = j++;
                موقع_نص = i;
            } else if (نجمة != std::string::npos) {
                j = نجمة + 1;
                i = ++موقع_نص;
            } else {
                return false;
            }
        }
        
        while (j < نمط.size() && نمط[j] == '*') j++;
        
        return j == نمط.size();
    }
};

