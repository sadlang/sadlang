/**
 * استثناء يُرمى عند انتهاك إذن
 */
class استثناء_إذن : public std::runtime_error {
public:
    enum class نوع {
        ملف,
        شبكة,
        نظام,
        كاميرا,
        ميكروفون,
        موقع,
        عملية,
        غير_محدد,
    };
    
    استثناء_إذن(نوع النوع, const std::string& العملية, const std::string& الهدف)
        : std::runtime_error(بناء_رسالة(النوع, العملية, الهدف))
        , m_النوع(النوع)
        , m_العملية(العملية)
        , m_الهدف(الهدف) {}
    
    نوع احصل_النوع() const { return m_النوع; }
    const std::string& العملية() const { return m_العملية; }
    const std::string& الهدف() const { return m_الهدف; }
    
private:
    نوع m_النوع;
    std::string m_العملية;
    std::string m_الهدف;
    
    static std::string بناء_رسالة(نوع النوع, const std::string& العملية, const std::string& الهدف) {
        std::stringstream ss;
        ss << "❌ انتهاك إذن: ";
        
        switch (النوع) {
            case نوع::ملف: ss << "وصول لملف"; break;
            case نوع::شبكة: ss << "اتصال شبكة"; break;
            case نوع::نظام: ss << "أمر نظام"; break;
            case نوع::كاميرا: ss << "كاميرا"; break;
            case نوع::ميكروفون: ss << "ميكروفون"; break;
            case نوع::موقع: ss << "موقع"; break;
            case نوع::عملية: ss << "عملية"; break;
            default: ss << "غير محدد"; break;
        }
        
        ss << "\n   العملية: " << العملية;
        if (!الهدف.empty()) {
            ss << "\n   الهدف: " << الهدف;
        }
        
        return ss.str();
    }
};

