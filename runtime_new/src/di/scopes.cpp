/**
 * نوع النطاق
 */
enum class نوع_نطاق {
    مفرد,    // Singleton
    نطاقي,   // Scoped
    عابر,    // Transient
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مخزن الخدمات المفردة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مخزن الخدمات المفردة (Singletons)
 * 
 * Thread-safe باستخدام Double-Checked Locking
 */
class مخزن_مفردات {
public:
    /**
     * الحصول على المثال الوحيد
     */
    static مخزن_مفردات& المثال() {
        static مخزن_مفردات مثال;
        return مثال;
    }
    
    /**
     * الحصول على خدمة (أو إنشائها إذا لم تكن موجودة)
     */
    template<typename T>
    std::shared_ptr<T> احصل(std::function<std::shared_ptr<T>()> مُنشئ) {
        std::string مفتاح = typeid(T).name();
        
        // تحقق سريع بدون قفل
        {
            std::shared_lock قفل(m_قفل);
            auto it = m_الخدمات.find(مفتاح);
            if (it != m_الخدمات.end()) {
                return std::any_cast<std::shared_ptr<T>>(it->second);
            }
        }
        
        // إنشاء مع قفل
        std::unique_lock قفل(m_قفل);
        
        // تحقق مرة أخرى (ربما أنشأها خيط آخر)
        auto it = m_الخدمات.find(مفتاح);
        if (it != m_الخدمات.end()) {
            return std::any_cast<std::shared_ptr<T>>(it->second);
        }
        
        // أنشئ
        auto خدمة = مُنشئ();
        m_الخدمات[مفتاح] = خدمة;
        
        return خدمة;
    }
    
    /**
     * هل الخدمة موجودة؟
     */
    template<typename T>
    bool موجودة() const {
        std::shared_lock قفل(m_قفل);
        return m_الخدمات.count(typeid(T).name()) > 0;
    }
    
    /**
     * مسح كل الخدمات
     */
    void امسح() {
        std::unique_lock قفل(m_قفل);
        m_الخدمات.clear();
    }
    
private:
    مخزن_مفردات() = default;
    
    mutable std::shared_mutex m_قفل;
    std::unordered_map<std::string, std::any> m_الخدمات;
};

