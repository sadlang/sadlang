/**
 * الحصول على خدمة (اختصار)
 */
template<typename T>
std::shared_ptr<T> خدمة() {
    return مدير_نطاقات::المثال().احصل<T>(حارس_سياق::الحالي());
}

/**
 * تسجيل خدمة مفردة
 */
template<typename سمة, typename تنفيذ>
void سجِّل_مفرد() {
    مدير_نطاقات::المثال().سجِّل<سمة, تنفيذ>(نوع_نطاق::مفرد);
}

/**
 * تسجيل خدمة نطاقية
 */
template<typename سمة, typename تنفيذ>
void سجِّل_نطاقي() {
    مدير_نطاقات::المثال().سجِّل<سمة, تنفيذ>(نوع_نطاق::نطاقي);
}

/**
 * تسجيل خدمة عابرة
 */
template<typename سمة, typename تنفيذ>
void سجِّل_عابر() {
    مدير_نطاقات::المثال().سجِّل<سمة, تنفيذ>(نوع_نطاق::عابر);
}

