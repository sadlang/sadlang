/**
 * سياق للخدمات النطاقية
 * 
 * كل طلب/سياق له نسخته الخاصة
 */
class سياق_نطاقي {
public:
    سياق_نطاقي() = default;
    
    ~سياق_نطاقي() {
        // الخدمات تُحذف تلقائياً عند انتهاء السياق
        m_الخدمات.clear();
    }
    
    /**
     * الحصول على خدمة في هذا السياق
     */
    template<typename T>
    std::shared_ptr<T> احصل(std::function<std::shared_ptr<T>()> مُنشئ) {
        std::string مفتاح = typeid(T).name();
        
        auto it = m_الخدمات.find(مفتاح);
        if (it != m_الخدمات.end()) {
            return std::any_cast<std::shared_ptr<T>>(it->second);
        }
        
        auto خدمة = مُنشئ();
        m_الخدمات[مفتاح] = خدمة;
        
        return خدمة;
    }
    
    /**
     * هل الخدمة موجودة في هذا السياق؟
     */
    template<typename T>
    bool موجودة() const {
        return m_الخدمات.count(typeid(T).name()) > 0;
    }
    
private:
    std::unordered_map<std::string, std::any> m_الخدمات;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مدير النطاقات
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * تسجيل خدمة
 */
struct تسجيل_خدمة_وقت_تشغيل {
    std::string الاسم;
    نوع_نطاق النطاق;
    std::function<std::any()> المُنشئ;
};

/**
 * مدير النطاقات الرئيسي
 */
class مدير_نطاقات {
public:
    /**
     * المثال الوحيد
     */
    static مدير_نطاقات& المثال() {
        static مدير_نطاقات مثال;
        return مثال;
    }
    
    /**
     * تسجيل خدمة
     */
    template<typename سمة, typename تنفيذ>
    void سجِّل(نوع_نطاق نطاق) {
        تسجيل_خدمة_وقت_تشغيل تسجيل;
        تسجيل.الاسم = typeid(سمة).name();
        تسجيل.النطاق = نطاق;
        تسجيل.المُنشئ = []() -> std::any {
            return std::make_shared<تنفيذ>();
        };
        
        m_التسجيلات[تسجيل.الاسم] = تسجيل;
    }
    
    /**
     * الحصول على خدمة
     */
    template<typename T>
    std::shared_ptr<T> احصل(سياق_نطاقي* سياق = nullptr) {
        std::string مفتاح = typeid(T).name();
        
        auto it = m_التسجيلات.find(مفتاح);
        if (it == m_التسجيلات.end()) {
            throw std::runtime_error("خدمة غير مُسجَّلة: " + مفتاح);
        }
        
        auto& تسجيل = it->second;
        
        switch (تسجيل.النطاق) {
            case نوع_نطاق::مفرد:
                return مخزن_مفردات::المثال().احصل<T>([&تسجيل]() {
                    return std::any_cast<std::shared_ptr<T>>(تسجيل.المُنشئ());
                });
                
            case نوع_نطاق::نطاقي:
                if (سياق == nullptr) {
                    throw std::runtime_error("خدمة نطاقية تحتاج سياقاً");
                }
                return سياق->احصل<T>([&تسجيل]() {
                    return std::any_cast<std::shared_ptr<T>>(تسجيل.المُنشئ());
                });
                
            case نوع_نطاق::عابر:
                return std::any_cast<std::shared_ptr<T>>(تسجيل.المُنشئ());
        }
        
        return nullptr;
    }
    
private:
    مدير_نطاقات() = default;
    
    std::unordered_map<std::string, تسجيل_خدمة_وقت_تشغيل> m_التسجيلات;
};

