/**
 * حارس سياق نطاقي (RAII)
 * 
 * مثال:
 *     {
 *         حارس_سياق حارس;  // يُنشئ سياقاً
 *         
 *         // هنا الخدمات النطاقية تستخدم هذا السياق
 *         
 *     }  // هنا يُحذف السياق وكل خدماته
 */
class حارس_سياق {
public:
    حارس_سياق() {
        m_السياق_السابق = m_السياق_الحالي;
        m_السياق_الحالي = &m_سياقي;
    }
    
    ~حارس_سياق() {
        m_السياق_الحالي = m_السياق_السابق;
    }
    
    /**
     * السياق الحالي
     */
    static سياق_نطاقي* الحالي() {
        return m_السياق_الحالي;
    }
    
private:
    سياق_نطاقي m_سياقي;
    سياق_نطاقي* m_السياق_السابق;
    
    static thread_local سياق_نطاقي* m_السياق_الحالي;
};

// تهيئة المتغير الثابت
inline thread_local سياق_نطاقي* حارس_سياق::m_السياق_الحالي = nullptr;

// ═══════════════════════════════════════════════════════════════════════════════
