/**
 * معلومات دالة في الذاكرة
 */
struct معلومات_دالة_ذاكرة {
    std::string الاسم;
    void* العنوان;
    size_t الحجم;
    
    // البيانات الوصفية
    std::string التوقيع;
    std::string الملف_المصدري;
    int السطر;
    
    // تاريخ التحديث
    int رقم_النسخة = 1;
    std::chrono::system_clock::time_point وقت_التحميل;
};

/**
 * نسخة دالة (للتراجع)
 */
struct نسخة_دالة {
    int رقم_النسخة;
    std::vector<uint8_t> الكود;
    void* العنوان_الأصلي;
    std::chrono::system_clock::time_point وقت_الإنشاء;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              جدول الدوال
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * جدول الدوال القابلة للاستبدال
 * 
 * هذا الجدول يحتوي على مؤشرات غير مباشرة للدوال
 * بحيث نستطيع تغيير العنوان دون تغيير المستدعين
 */
class جدول_دوال {
public:
    /**
     * تسجيل دالة
     */
    void سجّل(const std::string& الاسم, void* العنوان) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        معلومات_دالة_ذاكرة معلومات;
        معلومات.الاسم = الاسم;
        معلومات.العنوان = العنوان;
        معلومات.وقت_التحميل = std::chrono::system_clock::now();
        
        الدوال_[الاسم] = معلومات;
    }
    
    /**
     * الحصول على عنوان دالة
     */
    void* احصل_عنوان(const std::string& الاسم) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        auto it = الدوال_.find(الاسم);
        return it != الدوال_.end() ? it->second.العنوان : nullptr;
    }
    
    /**
     * تحديث عنوان دالة
     */
    bool حدّث_عنوان(const std::string& الاسم, void* العنوان_الجديد) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        auto it = الدوال_.find(الاسم);
        if (it == الدوال_.end()) return false;
        
        // احفظ النسخة القديمة للتراجع
        نسخة_دالة نسخة;
        نسخة.رقم_النسخة = it->second.رقم_النسخة;
        نسخة.العنوان_الأصلي = it->second.العنوان;
        نسخة.وقت_الإنشاء = it->second.وقت_التحميل;
        تاريخ_النسخ_[الاسم].push_back(نسخة);
        
        // تحديث
        it->second.العنوان = العنوان_الجديد;
        it->second.رقم_النسخة++;
        it->second.وقت_التحميل = std::chrono::system_clock::now();
        
        return true;
    }
    
    /**
     * التراجع لنسخة سابقة
     */
    bool تراجع(const std::string& الاسم) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        auto it_تاريخ = تاريخ_النسخ_.find(الاسم);
        if (it_تاريخ == تاريخ_النسخ_.end() || it_تاريخ->second.empty()) {
            return false;
        }
        
        auto it_دالة = الدوال_.find(الاسم);
        if (it_دالة == الدوال_.end()) return false;
        
        // استرجع النسخة السابقة
        نسخة_دالة& نسخة = it_تاريخ->second.back();
        it_دالة->second.العنوان = نسخة.العنوان_الأصلي;
        it_دالة->second.رقم_النسخة = نسخة.رقم_النسخة;
        
        it_تاريخ->second.pop_back();
        return true;
    }
    
    /**
     * كل الدوال المسجلة
     */
    std::vector<std::string> كل_الأسماء() {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        std::vector<std::string> أسماء;
        for (const auto& [اسم, _] : الدوال_) {
            أسماء.push_back(اسم);
        }
        return أسماء;
    }

private:
    std::mutex القفل_;
    std::unordered_map<std::string, معلومات_دالة_ذاكرة> الدوال_;
    std::unordered_map<std::string, std::vector<نسخة_دالة>> تاريخ_النسخ_;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُستبدل الدوال
