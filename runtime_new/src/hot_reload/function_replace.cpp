/**
 * نتيجة الاستبدال
 */
struct نتيجة_استبدال {
    bool نجح;
    std::string خطأ;
    
    void* العنوان_القديم;
    void* العنوان_الجديد;
    
    double الزمن_ms;
};

/**
 * مُستبدل الدوال في الذاكرة
 */
class مستبدل_دوال {
public:
    /**
     * إنشاء مُستبدل
     */
    explicit مستبدل_دوال(std::shared_ptr<جدول_دوال> جدول)
        : الجدول_(جدول) {}
    
    /**
     * استبدال دالة بكود جديد
     */
    نتيجة_استبدال استبدل(
        const std::string& الاسم,
        const std::vector<uint8_t>& الكود_الجديد
    ) {
        نتيجة_استبدال نتيجة;
        auto بداية = std::chrono::high_resolution_clock::now();
        
        // 1. احصل على العنوان القديم
        نتيجة.العنوان_القديم = الجدول_->احصل_عنوان(الاسم);
        if (!نتيجة.العنوان_القديم) {
            نتيجة.نجح = false;
            نتيجة.خطأ = "الدالة غير موجودة: " + الاسم;
            return نتيجة;
        }
        
        // 2. خصص ذاكرة للكود الجديد
        void* ذاكرة_جديدة = خصص_ذاكرة_تنفيذية(الكود_الجديد.size());
        if (!ذاكرة_جديدة) {
            نتيجة.نجح = false;
            نتيجة.خطأ = "فشل تخصيص الذاكرة";
            return نتيجة;
        }
        
        // 3. انسخ الكود الجديد
        std::memcpy(ذاكرة_جديدة, الكود_الجديد.data(), الكود_الجديد.size());
        
        // 4. اجعل الذاكرة قابلة للتنفيذ
        if (!اجعل_قابلة_للتنفيذ(ذاكرة_جديدة, الكود_الجديد.size())) {
            نتيجة.نجح = false;
            نتيجة.خطأ = "فشل تغيير صلاحيات الذاكرة";
            حرر_ذاكرة(ذاكرة_جديدة, الكود_الجديد.size());
            return نتيجة;
        }
        
        // 5. حدّث الجدول (atomic)
        if (!الجدول_->حدّث_عنوان(الاسم, ذاكرة_جديدة)) {
            نتيجة.نجح = false;
            نتيجة.خطأ = "فشل تحديث الجدول";
            حرر_ذاكرة(ذاكرة_جديدة, الكود_الجديد.size());
            return نتيجة;
        }
        
        نتيجة.العنوان_الجديد = ذاكرة_جديدة;
        نتيجة.نجح = true;
        
        auto نهاية = std::chrono::high_resolution_clock::now();
        نتيجة.الزمن_ms = std::chrono::duration<double, std::milli>(
            نهاية - بداية
        ).count();
        
        return نتيجة;
    }
    
    /**
     * التراجع عن آخر استبدال
     */
    bool تراجع(const std::string& الاسم) {
        return الجدول_->تراجع(الاسم);
    }

private:
    std::shared_ptr<جدول_دوال> الجدول_;
    
    /**
     * تخصيص ذاكرة قابلة للتنفيذ
     */
    void* خصص_ذاكرة_تنفيذية(size_t الحجم) {
        // في Windows: VirtualAlloc
        // في Linux: mmap
#ifdef _WIN32
        return VirtualAlloc(nullptr, الحجم, 
            MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE);
#else
        return mmap(nullptr, الحجم, 
            PROT_READ | PROT_WRITE, 
            MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
#endif
    }
    
    /**
     * جعل الذاكرة قابلة للتنفيذ
     */
    bool اجعل_قابلة_للتنفيذ(void* عنوان, size_t الحجم) {
#ifdef _WIN32
        DWORD قديم;
        return VirtualProtect(عنوان, الحجم, PAGE_EXECUTE_READ, &قديم);
#else
        return mprotect(عنوان, الحجم, PROT_READ | PROT_EXEC) == 0;
#endif
    }
    
    /**
     * تحرير الذاكرة
     */
    void حرر_ذاكرة(void* عنوان, size_t الحجم) {
#ifdef _WIN32
        VirtualFree(عنوان, 0, MEM_RELEASE);
#else
        munmap(عنوان, الحجم);
#endif
    }
};

