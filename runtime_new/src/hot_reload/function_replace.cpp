/**
 * مدير Hot Reload الكامل
 */
class مدير_hot_reload {
public:
    using مستمع_تحديث = std::function<void(const std::string& دالة, bool نجح)>;
    
    /**
     * إنشاء المدير
     */
    مدير_hot_reload()
        : الجدول_(std::make_shared<جدول_دوال>()),
          المستبدل_(std::make_unique<مستبدل_دوال>(الجدول_)) {}
    
    /**
     * تسجيل دالة للمراقبة
     */
    void سجّل_دالة(const std::string& الاسم, void* العنوان) {
        الجدول_->سجّل(الاسم, العنوان);
    }
    
    /**
     * تحديث دالة
     */
    نتيجة_استبدال حدّث_دالة(
        const std::string& الاسم,
        const std::vector<uint8_t>& الكود_الجديد
    ) {
        auto نتيجة = المستبدل_->استبدل(الاسم, الكود_الجديد);
        
        // إبلاغ المستمعين
        for (auto& مستمع : المستمعون_) {
            مستمع(الاسم, نتيجة.نجح);
        }
        
        return نتيجة;
    }
    
    /**
     * التراجع عن تحديث
     */
    bool تراجع(const std::string& الاسم) {
        return المستبدل_->تراجع(الاسم);
    }
    
    /**
     * تسجيل مستمع
     */
    void عند_تحديث(مستمع_تحديث مستمع) {
        المستمعون_.push_back(مستمع);
    }
    
    /**
     * الحصول على جدول الدوال
     */
    std::shared_ptr<جدول_دوال> الجدول() {
        return الجدول_;
    }

private:
    std::shared_ptr<جدول_دوال> الجدول_;
    std::unique_ptr<مستبدل_دوال> المستبدل_;
    std::vector<مستمع_تحديث> المستمعون_;
};

