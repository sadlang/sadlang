/**
 * مستوى الخطأ
 */
enum class مستوى_خطأ_تحقق {
    تحذير,        // يُسجَّل فقط
    خطأ,          // يُرفَض المدخل
    حرج,          // يُوقَف البرنامج
};

/**
 * خطأ تحقق
 */
struct خطأ_تحقق {
    مستوى_خطأ_تحقق المستوى;
    std::string المعامل;
    std::string الرسالة;
    std::string القيمة_الفعلية;
    std::string القيمة_المتوقعة;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        
        switch (المستوى) {
            case مستوى_خطأ_تحقق::تحذير: ss << "⚠️ تحذير"; break;
            case مستوى_خطأ_تحقق::خطأ: ss << "❌ خطأ"; break;
            case مستوى_خطأ_تحقق::حرج: ss << "⛔ حرج"; break;
        }
        
        ss << " في المعامل '" << المعامل << "': " << الرسالة;
        
        if (!القيمة_الفعلية.empty()) {
            ss << "\n   القيمة الفعلية: " << القيمة_الفعلية;
        }
        if (!القيمة_المتوقعة.empty()) {
            ss << "\n   القيمة المتوقعة: " << القيمة_المتوقعة;
        }
        
        return ss.str();
    }
};

/**
 * نتيجة التحقق
 */
struct نتيجة_تحقق {
    bool ناجح = true;
    std::vector<خطأ_تحقق> الأخطاء;
    
    void أضف_خطأ(خطأ_تحقق خطأ) {
        if (خطأ.المستوى != مستوى_خطأ_تحقق::تحذير) {
            ناجح = false;
        }
        الأخطاء.push_back(std::move(خطأ));
    }
    
    /**
     * دمج نتيجتين
     */
    void ادمج(نتيجة_تحقق أخرى) {
        if (!أخرى.ناجح) ناجح = false;
        for (auto& خ : أخرى.الأخطاء) {
            الأخطاء.push_back(std::move(خ));
        }
    }
    
    /**
     * تقرير نصي
     */
    std::string تقرير() const {
        if (ناجح && الأخطاء.empty()) {
            return "✅ التحقق ناجح";
        }
        
        std::stringstream ss;
        ss << "📋 نتيجة التحقق: " << (ناجح ? "ناجح" : "فاشل") << "\n\n";
        
        for (const auto& خ : الأخطاء) {
            ss << خ.إلى_نص() << "\n\n";
        }
        
        return ss.str();
    }
};

