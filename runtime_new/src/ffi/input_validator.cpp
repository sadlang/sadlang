/**
 * قيود على قيمة رقمية
 */
template<typename T>
struct قيود_رقمية {
    std::optional<T> الحد_الأدنى;
    std::optional<T> الحد_الأقصى;
    std::optional<std::vector<T>> القيم_المسموحة;  // Whitelist
    std::optional<std::vector<T>> القيم_المرفوضة;  // Blacklist
    
    /**
     * التحقق من القيمة
     */
    bool تحقق(T قيمة) const {
        // تحقق من النطاق
        if (الحد_الأدنى && قيمة < *الحد_الأدنى) return false;
        if (الحد_الأقصى && قيمة > *الحد_الأقصى) return false;
        
        // تحقق من القائمة البيضاء
        if (القيم_المسموحة) {
            bool موجود = false;
            for (const auto& ق : *القيم_المسموحة) {
                if (ق == قيمة) {
                    موجود = true;
                    break;
                }
            }
            if (!موجود) return false;
        }
        
        // تحقق من القائمة السوداء
        if (القيم_المرفوضة) {
            for (const auto& ق : *القيم_المرفوضة) {
                if (ق == قيمة) return false;
            }
        }
        
        return true;
    }
    
    /**
     * رسالة الخطأ
     */
    std::string رسالة_خطأ(T قيمة) const {
        std::stringstream ss;
        ss << "القيمة " << قيمة << " غير صالحة";
        
        if (الحد_الأدنى && قيمة < *الحد_الأدنى) {
            ss << " (أقل من الحد الأدنى " << *الحد_الأدنى << ")";
        } else if (الحد_الأقصى && قيمة > *الحد_الأقصى) {
            ss << " (أكبر من الحد الأقصى " << *الحد_الأقصى << ")";
        }
        
        return ss.str();
    }
};

/**
 * قيود على نص
 */
struct قيود_نص {
    std::optional<size_t> الحد_الأدنى_للطول;
    std::optional<size_t> الحد_الأقصى_للطول;
    bool لا_يقبل_فارغ = false;
    bool لا_يقبل_null = true;
    bool يجب_UTF8 = false;
    std::optional<std::string> نمط_regex;
    std::optional<std::vector<char>> أحرف_مرفوضة;
    
    /**
     * التحقق من النص
     */
    bool تحقق(const char* نص, size_t طول_أقصى = 65536) const {
        // null check
        if (نص == nullptr) {
            return !لا_يقبل_null;
        }
        
        // حساب الطول
        size_t طول = 0;
        while (نص[طول] != '\0' && طول < طول_أقصى) طول++;
        
        // تحقق من الفراغ
        if (لا_يقبل_فارغ && طول == 0) return false;
        
        // تحقق من الطول
        if (الحد_الأدنى_للطول && طول < *الحد_الأدنى_للطول) return false;
        if (الحد_الأقصى_للطول && طول > *الحد_الأقصى_للطول) return false;
        
        // تحقق من الأحرف المرفوضة
        if (أحرف_مرفوضة) {
            for (size_t i = 0; i < طول; ++i) {
                for (char مرفوض : *أحرف_مرفوضة) {
                    if (نص[i] == مرفوض) return false;
                }
            }
        }
        
        return true;
    }
};

/**
 * قيود على مصفوفة
 */
struct قيود_مصفوفة {
    std::optional<size_t> الحد_الأدنى_للحجم;
    std::optional<size_t> الحد_الأقصى_للحجم;
    bool لا_يقبل_فارغة = false;
    bool لا_يقبل_null = true;
    
    bool تحقق(const void* ptr, size_t حجم) const {
        if (ptr == nullptr) return !لا_يقبل_null;
        if (لا_يقبل_فارغة && حجم == 0) return false;
        if (الحد_الأدنى_للحجم && حجم < *الحد_الأدنى_للحجم) return false;
        if (الحد_الأقصى_للحجم && حجم > *الحد_الأقصى_للحجم) return false;
        return true;
    }
};

/**
 * قيود على مؤشر
 */
struct قيود_مؤشر {
    bool لا_يقبل_null = true;
    std::optional<size_t> محاذاة;
    std::optional<std::pair<void*, void*>> نطاق_مسموح;  // [من, إلى]
    
    bool تحقق(const void* ptr) const {
        // null check
        if (ptr == nullptr) return !لا_يقبل_null;
        
        // تحقق من المحاذاة
        if (محاذاة) {
            size_t عنوان = reinterpret_cast<size_t>(ptr);
            if (عنوان % *محاذاة != 0) return false;
        }
        
        // تحقق من النطاق
        if (نطاق_مسموح) {
            if (ptr < نطاق_مسموح->first || ptr > نطاق_مسموح->second) {
                return false;
            }
        }
        
        return true;
    }
};

