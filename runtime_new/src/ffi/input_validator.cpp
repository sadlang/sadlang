/**
 * مُدقق المدخلات
 * 
 * للمبتدئ: هذه الفئة تتحقق من صحة المدخلات قبل إرسالها لدوال C.
 * 
 * مثال:
 * ```cpp
 * مدقق_مدخلات مدقق;
 * 
 * // تحقق من عمر
 * auto نتيجة = مدقق.تحقق_من_عدد(
 *     عمر, "العمر",
 *     قيود_رقمية<int>{.الحد_الأدنى = 0, .الحد_الأقصى = 150}
 * );
 * 
 * if (!نتيجة.ناجح) {
 *     // عالج الخطأ
 * }
 * ```
 */
class مدقق_مدخلات_FFI {
public:
    /**
     * تحقق من عدد صحيح
     */
    template<typename T>
    نتيجة_تحقق تحقق_من_عدد(
        T قيمة,
        const std::string& اسم_المعامل,
        const قيود_رقمية<T>& قيود) const {
        
        نتيجة_تحقق نتيجة;
        
        if (!قيود.تحقق(قيمة)) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = قيود.رسالة_خطأ(قيمة),
                .القيمة_الفعلية = std::to_string(قيمة),
                .القيمة_المتوقعة = نطاق_إلى_نص(قيود)
            });
        }
        
        return نتيجة;
    }
    
    /**
     * تحقق من نص
     */
    نتيجة_تحقق تحقق_من_نص(
        const char* نص,
        const std::string& اسم_المعامل,
        const قيود_نص& قيود) const {
        
        نتيجة_تحقق نتيجة;
        
        // تحقق من null
        if (نص == nullptr) {
            if (قيود.لا_يقبل_null) {
                نتيجة.أضف_خطأ({
                    .المستوى = مستوى_خطأ_تحقق::خطأ,
                    .المعامل = اسم_المعامل,
                    .الرسالة = "لا يمكن أن يكون null",
                    .القيمة_الفعلية = "null",
                    .القيمة_المتوقعة = "نص غير فارغ"
                });
            }
            return نتيجة;
        }
        
        // حساب الطول
        size_t طول = strlen(نص);
        
        // تحقق من الفراغ
        if (قيود.لا_يقبل_فارغ && طول == 0) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = "لا يمكن أن يكون فارغاً",
                .القيمة_الفعلية = "(فارغ)",
                .القيمة_المتوقعة = "نص غير فارغ"
            });
        }
        
        // تحقق من الطول
        if (قيود.الحد_الأدنى_للطول && طول < *قيود.الحد_الأدنى_للطول) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = "النص قصير جداً",
                .القيمة_الفعلية = "طول " + std::to_string(طول),
                .القيمة_المتوقعة = "طول >= " + std::to_string(*قيود.الحد_الأدنى_للطول)
            });
        }
        
        if (قيود.الحد_الأقصى_للطول && طول > *قيود.الحد_الأقصى_للطول) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = "النص طويل جداً",
                .القيمة_الفعلية = "طول " + std::to_string(طول),
                .القيمة_المتوقعة = "طول <= " + std::to_string(*قيود.الحد_الأقصى_للطول)
            });
        }
        
        // تحقق من الأحرف المرفوضة
        if (قيود.أحرف_مرفوضة) {
            for (size_t i = 0; i < طول; ++i) {
                for (char مرفوض : *قيود.أحرف_مرفوضة) {
                    if (نص[i] == مرفوض) {
                        نتيجة.أضف_خطأ({
                            .المستوى = مستوى_خطأ_تحقق::خطأ,
                            .المعامل = اسم_المعامل,
                            .الرسالة = "حرف غير مسموح في الموقع " + std::to_string(i),
                            .القيمة_الفعلية = std::string(1, نص[i]),
                            .القيمة_المتوقعة = "بدون الحرف '" + std::string(1, مرفوض) + "'"
                        });
                        break;
                    }
                }
            }
        }
        
        return نتيجة;
    }
    
    /**
     * تحقق من مؤشر
     */
    نتيجة_تحقق تحقق_من_مؤشر(
        const void* ptr,
        const std::string& اسم_المعامل,
        const قيود_مؤشر& قيود) const {
        
        نتيجة_تحقق نتيجة;
        
        // تحقق من null
        if (ptr == nullptr && قيود.لا_يقبل_null) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::حرج,
                .المعامل = اسم_المعامل,
                .الرسالة = "مؤشر null غير مسموح",
                .القيمة_الفعلية = "null",
                .القيمة_المتوقعة = "مؤشر صالح"
            });
            return نتيجة;
        }
        
        if (ptr == nullptr) return نتيجة;
        
        // تحقق من المحاذاة
        if (قيود.محاذاة) {
            size_t عنوان = reinterpret_cast<size_t>(ptr);
            if (عنوان % *قيود.محاذاة != 0) {
                نتيجة.أضف_خطأ({
                    .المستوى = مستوى_خطأ_تحقق::خطأ,
                    .المعامل = اسم_المعامل,
                    .الرسالة = "محاذاة غير صحيحة",
                    .القيمة_الفعلية = "محاذاة " + std::to_string(عنوان % *قيود.محاذاة),
                    .القيمة_المتوقعة = "محاذاة " + std::to_string(*قيود.محاذاة)
                });
            }
        }
        
        return نتيجة;
    }
    
    /**
     * تحقق من مصفوفة
     */
    نتيجة_تحقق تحقق_من_مصفوفة(
        const void* ptr,
        size_t حجم,
        const std::string& اسم_المعامل,
        const قيود_مصفوفة& قيود) const {
        
        نتيجة_تحقق نتيجة;
        
        // تحقق من null
        if (ptr == nullptr && قيود.لا_يقبل_null) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::حرج,
                .المعامل = اسم_المعامل,
                .الرسالة = "مصفوفة null غير مسموحة",
                .القيمة_الفعلية = "null",
                .القيمة_المتوقعة = "مصفوفة صالحة"
            });
            return نتيجة;
        }
        
        // تحقق من الحجم
        if (قيود.لا_يقبل_فارغة && حجم == 0) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = "مصفوفة فارغة غير مسموحة",
                .القيمة_الفعلية = "حجم 0",
                .القيمة_المتوقعة = "حجم > 0"
            });
        }
        
        if (قيود.الحد_الأدنى_للحجم && حجم < *قيود.الحد_الأدنى_للحجم) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = "المصفوفة صغيرة جداً",
                .القيمة_الفعلية = "حجم " + std::to_string(حجم),
                .القيمة_المتوقعة = "حجم >= " + std::to_string(*قيود.الحد_الأدنى_للحجم)
            });
        }
        
        if (قيود.الحد_الأقصى_للحجم && حجم > *قيود.الحد_الأقصى_للحجم) {
            نتيجة.أضف_خطأ({
                .المستوى = مستوى_خطأ_تحقق::خطأ,
                .المعامل = اسم_المعامل,
                .الرسالة = "المصفوفة كبيرة جداً",
                .القيمة_الفعلية = "حجم " + std::to_string(حجم),
                .القيمة_المتوقعة = "حجم <= " + std::to_string(*قيود.الحد_الأقصى_للحجم)
            });
        }
        
        return نتيجة;
    }
    
private:
    template<typename T>
    std::string نطاق_إلى_نص(const قيود_رقمية<T>& قيود) const {
        std::stringstream ss;
        
        if (قيود.الحد_الأدنى && قيود.الحد_الأقصى) {
            ss << "[" << *قيود.الحد_الأدنى << ", " << *قيود.الحد_الأقصى << "]";
        } else if (قيود.الحد_الأدنى) {
            ss << ">= " << *قيود.الحد_الأدنى;
        } else if (قيود.الحد_الأقصى) {
            ss << "<= " << *قيود.الحد_الأقصى;
        }
        
        return ss.str();
    }
};

