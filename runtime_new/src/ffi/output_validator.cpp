/**
 * نوع المخرج المتوقع
 */
enum class نوع_مخرج {
    مؤشر,              // void*, char*, etc.
    عدد_صحيح,          // int, long, etc.
    عدد_حقيقي,         // float, double
    منطقي,             // bool (0/1)
    كود_خطأ,           // -1 = خطأ, >= 0 = نجاح
    handle,            // موارد النظام (file descriptor, socket, etc.)
};

/**
 * قيمة الخطأ المعروفة
 */
template<typename T>
struct قيمة_خطأ {
    T القيمة;
    std::string المعنى;
};

/**
 * قيم الخطأ الشائعة
 */
namespace قيم_خطأ {
    // للمؤشرات
    constexpr void* NULL_PTR = nullptr;
    
    // لأكواد الإرجاع
    constexpr int خطأ_عام = -1;
    constexpr int EOF_VALUE = -1;
    
    // لـ sockets
    constexpr int INVALID_SOCKET = -1;
    
    // لـ file descriptors
    constexpr int INVALID_FD = -1;
    
    // لـ errno-based APIs
    constexpr int نجاح = 0;
}

