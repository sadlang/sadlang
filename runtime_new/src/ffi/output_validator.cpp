/**
 * حالة المخرج
 */
enum class حالة_مخرج {
    صالح,              // القيمة صالحة
    null,              // مؤشر null
    خطأ,               // كود خطأ
    غير_متوقع,         // قيمة غير متوقعة
    تجاوز_نطاق,        // خارج النطاق المتوقع
};

/**
 * نتيجة تحقق من مخرج
 */
struct نتيجة_تحقق_مخرج {
    حالة_مخرج الحالة;
    std::string الرسالة;
    std::string القيمة_الفعلية;
    std::optional<int> كود_الخطأ;         // errno or similar
    std::optional<std::string> وصف_الخطأ; // strerror or similar
    
    bool نجح() const {
        return الحالة == حالة_مخرج::صالح;
    }
    
    std::string إلى_نص() const {
        std::stringstream ss;
        
        switch (الحالة) {
            case حالة_مخرج::صالح:
                ss << "✅ مخرج صالح";
                break;
            case حالة_مخرج::null:
                ss << "⚠️ مؤشر null";
                break;
            case حالة_مخرج::خطأ:
                ss << "❌ خطأ";
                break;
            case حالة_مخرج::غير_متوقع:
                ss << "⚠️ قيمة غير متوقعة";
                break;
            case حالة_مخرج::تجاوز_نطاق:
                ss << "❌ تجاوز النطاق";
                break;
        }
        
        if (!الرسالة.empty()) {
            ss << ": " << الرسالة;
        }
        
        if (!القيمة_الفعلية.empty()) {
            ss << " (القيمة: " << القيمة_الفعلية << ")";
        }
        
        if (كود_الخطأ) {
            ss << " [errno=" << *كود_الخطأ;
            if (وصف_الخطأ) {
                ss << ": " << *وصف_الخطأ;
            }
            ss << "]";
        }
        
        return ss.str();
    }
};

