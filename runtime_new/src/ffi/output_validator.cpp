/**
 * قيود على مخرج مؤشر
 */
struct قيود_مخرج_مؤشر {
    bool يُسمح_null = false;              // هل null قيمة صالحة؟
    bool يتطلب_تحرير = false;             // هل يجب تحرير الذاكرة؟
    std::string دالة_التحرير;             // اسم دالة التحرير (free, fclose, etc.)
    
    // تحقق مخصص
    std::function<bool(void*)> تحقق_إضافي;
};

/**
 * قيود على مخرج رقمي
 */
template<typename T>
struct قيود_مخرج_رقمي {
    std::optional<T> قيمة_الخطأ;          // مثل -1
    std::optional<T> الحد_الأدنى_للنجاح;
    std::optional<T> الحد_الأقصى_للنجاح;
    std::vector<T> قيم_خطأ_إضافية;
    
    bool هي_خطأ(T قيمة) const {
        if (قيمة_الخطأ && قيمة == *قيمة_الخطأ) return true;
        
        for (const auto& ق : قيم_خطأ_إضافية) {
            if (قيمة == ق) return true;
        }
        
        if (الحد_الأدنى_للنجاح && قيمة < *الحد_الأدنى_للنجاح) return true;
        if (الحد_الأقصى_للنجاح && قيمة > *الحد_الأقصى_للنجاح) return true;
        
        return false;
    }
};

/**
 * قيود على كود خطأ
 */
struct قيود_كود_خطأ {
    int قيمة_النجاح = 0;                  // عادةً 0
    std::vector<int> قيم_نجاح_إضافية;
    bool الموجب_خطأ = false;              // بعض APIs: > 0 = خطأ
    bool السالب_خطأ = true;               // عادةً: < 0 = خطأ
    
    bool هو_نجاح(int قيمة) const {
        if (قيمة == قيمة_النجاح) return true;
        
        for (int ق : قيم_نجاح_إضافية) {
            if (قيمة == ق) return true;
        }
        
        if (السالب_خطأ && قيمة < 0) return false;
        if (الموجب_خطأ && قيمة > 0) return false;
        
        return true;
    }
};

