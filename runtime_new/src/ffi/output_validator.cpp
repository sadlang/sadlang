/**
 * ماكرو للتحقق من مخرج مؤشر
 */
#define SAD_FFI_CHECK_PTR(ptr, func_name) \
    do { \
        مدقق_مخرجات_FFI __مدقق; \
        auto __نتيجة = __مدقق.تحقق_من_مؤشر(ptr, func_name, {.يُسمح_null = false}); \
        if (!__نتيجة.نجح()) { \
            throw std::runtime_error(__نتيجة.إلى_نص()); \
        } \
    } while(0)

/**
 * ماكرو للتحقق من كود خطأ
 */
#define SAD_FFI_CHECK_ERR(code, func_name) \
    do { \
        مدقق_مخرجات_FFI __مدقق; \
        auto __نتيجة = __مدقق.تحقق_من_كود_خطأ(code, func_name); \
        if (!__نتيجة.نجح()) { \
            throw std::runtime_error(__نتيجة.إلى_نص()); \
        } \
    } while(0)

/**
 * ماكرو للتحقق من file descriptor
 */
#define SAD_FFI_CHECK_FD(fd, func_name) \
    do { \
