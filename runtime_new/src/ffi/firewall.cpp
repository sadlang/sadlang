/**
 * الجدار الناري لـ FFI
 * 
 * الفئة الرئيسية التي تجمع كل آليات الحماية.
 * 
 * مثال الاستخدام:
 * ```cpp
 * جدار_ناري_FFI جدار;
 * 
 * // تعريف دالة C
 * توقيع_دالة_FFI توقيع{
 *     .الاسم_C = "strlen",
 *     .الاسم_عربي = "طول_النص",
 *     .نوع_الإرجاع = نوع_FFI::طبيعي_64,
 *     .المعاملات = {
 *         {
 *             .الاسم = "str",
 *             .الاسم_عربي = "النص",
 *             .النوع = نوع_FFI::نص_C,
 *             .القيود = {.لا_يقبل_null = true}
 *         }
 *     }
 * };
 * 
 * // استدعاء مع حماية
 * جدار.استدعِ(توقيع, "مرحبا");
 * ```
 */
class جدار_ناري_FFI {
public:
    /**
     * إعدادات الجدار الناري
     */
    struct إعدادات {
        bool فعِّل_فحص_المدخلات = true;
        bool فعِّل_فحص_المخرجات = true;
        bool فعِّل_تتبع_الذاكرة = true;
        bool فعِّل_timeout = true;
        
        // سلوك عند الانتهاك
        bool رمي_استثناء = true;
        bool سجِّل_فقط = false;
        
        // معالجات
        std::function<void(const انتهاك_جدار_ناري&)> معالج_الانتهاكات;
    };
    
    /**
     * مُنشئ
     */
    جدار_ناري_FFI() = default;
    
    explicit جدار_ناري_FFI(إعدادات إعدادات)
        : m_إعدادات(std::move(إعدادات)) {}
    
    /**
     * تسجيل دالة FFI
     */
    void سجِّل_دالة(توقيع_دالة_FFI توقيع) {
        m_دوال[توقيع.الاسم_عربي] = std::move(توقيع);
    }
    
    /**
     * الحصول على توقيع دالة
     */
    const توقيع_دالة_FFI* احصل_على_توقيع(const std::string& اسم) const {
        auto it = m_دوال.find(اسم);
        if (it == m_دوال.end()) return nullptr;
        return &it->second;
    }
    
    /**
     * فحص المدخلات قبل الاستدعاء
     */
    مدقق_المدخلات::نتيجة افحص_قبل(
        const توقيع_دالة_FFI& توقيع,
        const std::vector<void*>& قيم_المعاملات) {
        
        if (!m_إعدادات.فعِّل_فحص_المدخلات) {
            return {};
        }
        
        مدقق_المدخلات::نتيجة نتيجة_كلية;
        نتيجة_كلية.صالح = true;
        
        for (size_t i = 0; i < توقيع.المعاملات.size() && 
                          i < قيم_المعاملات.size(); ++i) {
            
            const auto& معامل = توقيع.المعاملات[i];
            void* قيمة = قيم_المعاملات[i];
            
            // فحص حسب النوع
            مدقق_المدخلات::نتيجة نتيجة;
            
            switch (معامل.النوع) {
                case نوع_FFI::مؤشر:
                case نوع_FFI::نص_C:
                    نتيجة = m_مدقق_مدخلات.دقق_مؤشر(
                        قيمة, معامل, توقيع.الاسم_عربي);
                    break;
                default:
                    // أنواع أولية - نفترض صحتها
                    break;
            }
            
            if (!نتيجة.صالح) {
                نتيجة_كلية.صالح = false;
                for (auto& ان : نتيجة.الانتهاكات) {
                    نتيجة_كلية.الانتهاكات.push_back(std::move(ان));
                }
            }
        }
        
        // معالجة الانتهاكات
        for (const auto& ان : نتيجة_كلية.الانتهاكات) {
            عالج_انتهاك(ان);
        }
        
        return نتيجة_كلية;
    }
    
    /**
     * فحص المخرجات بعد الاستدعاء
     */
    مدقق_المدخلات::نتيجة افحص_بعد(
        const توقيع_دالة_FFI& توقيع,
        void* النتيجة) {
        
        if (!m_إعدادات.فعِّل_فحص_المخرجات) {
            return {};
        }
        
        auto نتيجة = m_مدقق_مخرجات.دقق_إرجاع(النتيجة, توقيع);
        
        for (const auto& ان : نتيجة.الانتهاكات) {
            عالج_انتهاك(ان);
        }
        
        return نتيجة;
    }
    
    /**
     * الحصول على متتبع الذاكرة
     */
    متتبع_الذاكرة& متتبع_ذاكرة() {
        return m_متتبع_ذاكرة;
    }
    
    /**
     * تقرير التسريبات
     */
    std::string تقرير_تسريبات() const {
        auto تسريبات = m_متتبع_ذاكرة.احصل_على_التسريبات();
        
        if (تسريبات.empty()) {
            return "✅ لا توجد تسريبات ذاكرة";
        }
        
        std::stringstream ss;
        ss << "⚠️ تم اكتشاف " << تسريبات.size() << " تسريب(ات) ذاكرة:\n\n";
        
        for (const auto& ت : تسريبات) {
            ss << "  📍 العنوان: " << ت.العنوان << "\n"
               << "     الحجم: " << ت.الحجم << " بايت\n"
               << "     المصدر: " << ت.الدالة << "\n"
               << "     العمر: " << ت.العمر_ms() << " ms\n\n";
        }
        
        return ss.str();
    }
    
private:
    إعدادات m_إعدادات;
    std::unordered_map<std::string, توقيع_دالة_FFI> m_دوال;
    مدقق_المدخلات m_مدقق_مدخلات;
    مدقق_المخرجات m_مدقق_مخرجات;
    متتبع_الذاكرة m_متتبع_ذاكرة;
    
    void عالج_انتهاك(const انتهاك_جدار_ناري& انتهاك) {
        // استدعاء المعالج المخصص
        if (m_إعدادات.معالج_الانتهاكات) {
            m_إعدادات.معالج_الانتهاكات(انتهاك);
        }
        
        // رمي استثناء إذا مطلوب
        if (m_إعدادات.رمي_استثناء && !m_إعدادات.سجِّل_فقط) {
            throw استثناء_FFI(انتهاك);
        }
    }
};

