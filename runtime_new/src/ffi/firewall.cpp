/**
 * مدقق مدخلات FFI
 * 
 * للمبتدئ: هذا المدقق يفحص كل معامل قبل إرساله لدالة C.
 */
class مدقق_المدخلات {
public:
    /**
     * نتيجة التدقيق
     */
    struct نتيجة {
        bool صالح = true;
        std::vector<انتهاك_جدار_ناري> الانتهاكات;
    };
    
    /**
     * تدقيق مؤشر
     */
    نتيجة دقق_مؤشر(
        void* ptr,
        const معامل_FFI& معامل,
        const std::string& دالة) const {
        
        نتيجة ن;
        
        if (معامل.القيود.لا_يقبل_null && ptr == nullptr) {
            ن.صالح = false;
            ن.الانتهاكات.push_back({نوع_انتهاك::مؤشر_null, دالة, معامل.الاسم_عربي, "المعامل لا يقبل قيمة null"});
        }
        
        return ن;
    }
    
    /**
     * تدقيق قيمة رقمية
     */
    نتيجة دقق_رقم(
        int64_t قيمة,
        const معامل_FFI& معامل,
        const std::string& دالة) const {
        
        نتيجة ن;
        
        if (!معامل.القيود.تحقق_من_قيمة(قيمة)) {
            ن.صالح = false;
            
            std::stringstream تفاصيل;
            تفاصيل << "القيمة: " << قيمة;
            if (معامل.القيود.الحد_الأدنى) {
                تفاصيل << ", الحد الأدنى: " << *معامل.القيود.الحد_الأدنى;
            }
            if (معامل.القيود.الحد_الأقصى) {
                تفاصيل << ", الحد الأقصى: " << *معامل.القيود.الحد_الأقصى;
            }
            
            ن.الانتهاكات.push_back({نوع_انتهاك::قيمة_خارج_النطاق, دالة, معامل.الاسم_عربي, تفاصيل.str()});
        }
        
        return ن;
    }
    
    /**
     * تدقيق نص C
     */
    نتيجة دقق_نص(
        const char* نص,
        size_t الحد_الأقصى,
        const معامل_FFI& معامل,
        const std::string& دالة) const {
        
        نتيجة ن;
        
        // تحقق من null
        if (معامل.القيود.لا_يقبل_null && نص == nullptr) {
            ن.صالح = false;
            ن.الانتهاكات.push_back({نوع_انتهاك::مؤشر_null, دالة, معامل.الاسم_عربي, "النص لا يمكن أن يكون null"});
            return ن;
        }
        
        if (نص == nullptr) return ن;
        
        // تحقق من انتهاء بـ null
        if (معامل.القيود.نص_منتهي_بـ_null) {
            bool منتهي = false;
            for (size_t i = 0; i < الحد_الأقصى; ++i) {
                if (نص[i] == '\0') {
                    منتهي = true;
                    break;
                }
            }
            
            if (!منتهي) {
                ن.صالح = false;
                ن.الانتهاكات.push_back({نوع_انتهاك::نص_غير_منتهي, دالة, معامل.الاسم_عربي, "النص يجب أن ينتهي بـ \\0"});
            }
        }
        
        // تحقق من الحجم
        if (نص != nullptr) {
            size_t طول = 0;
            while (نص[طول] != '\0' && طول < الحد_الأقصى) طول++;
            
            if (!معامل.القيود.تحقق_من_حجم(طول)) {
                ن.صالح = false;
                ن.الانتهاكات.push_back({نوع_انتهاك::حجم_خاطئ, دالة, معامل.الاسم_عربي, "طول النص: " + std::to_string(طول)});
            }
        }
        
        return ن;
    }
    
    /**
     * تدقيق محاذاة الذاكرة
     */
    نتيجة دقق_محاذاة(
        void* ptr,
        size_t المحاذاة,
        const معامل_FFI& معامل,
        const std::string& دالة) const {
        
        نتيجة ن;
        
        if (معامل.القيود.ذاكرة_محاذاة) {
            size_t العنوان = reinterpret_cast<size_t>(ptr);
            if (العنوان % المحاذاة != 0) {
                ن.صالح = false;
                ن.الانتهاكات.push_back({نوع_انتهاك::ذاكرة_غير_محاذاة, دالة, معامل.الاسم_عربي, "المحاذاة المطلوبة: " + std::to_string(المحاذاة)});
            }
        }
        
        return ن;
    }
};

