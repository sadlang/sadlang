/**
 * تخصيص ذاكرة مُتتبَّع
 */
struct تخصيص_ذاكرة {
    void* العنوان;
    size_t الحجم;
    std::string الدالة;              // الدالة التي خصصت
    std::chrono::steady_clock::time_point الوقت;
    bool مُحرر = false;
    
    double العمر_ms() const {
        auto الآن = std::chrono::steady_clock::now();
        return std::chrono::duration<double, std::milli>(الآن - الوقت).count();
    }
};

/**
 * متتبع ذاكرة FFI
 * 
 * للمبتدئ: هذا المتتبع يحفظ سجلاً لكل ذاكرة مخصصة من دوال C.
 * هذا يساعد في اكتشاف تسريبات الذاكرة.
 */
class متتبع_الذاكرة {
public:
    /**
     * تسجيل تخصيص جديد
     */
    void سجِّل_تخصيص(void* ptr, size_t حجم, const std::string& دالة) {
        if (ptr == nullptr) return;
        
        m_تخصيصات[ptr] = {ptr, حجم, دالة, std::chrono::steady_clock::now(), false};
        
        m_إجمالي_المخصص += حجم;
    }
    
    /**
     * تسجيل تحرير
     */
    انتهاك_جدار_ناري* سجِّل_تحرير(void* ptr) {
        if (ptr == nullptr) return nullptr;
        
        auto it = m_تخصيصات.find(ptr);
        
        if (it == m_تخصيصات.end()) {
            // تحرير ذاكرة غير مُتتبَّعة - ربما تحرير مزدوج أو ذاكرة خارجية
            static انتهاك_جدار_ناري انتهاك;
            انتهاك = {نوع_انتهاك::تحرير_مزدوج, "free/delete", "", "العنوان: " + عنوان_إلى_نص(ptr)};
            return &انتهاك;
        }
        
        if (it->second.مُحرر) {
            // تحرير مزدوج!
            static انتهاك_جدار_ناري انتهاك;
            انتهاك = {نوع_انتهاك::تحرير_مزدوج, it->second.الدالة, "", "الذاكرة سبق تحريرها"};
            return &انتهاك;
        }
        
        it->second.مُحرر = true;
        m_إجمالي_المحرر += it->second.الحجم;
        
        return nullptr;
    }
    
    /**
     * التحقق من تسريبات
     */
    std::vector<تخصيص_ذاكرة> احصل_على_التسريبات() const {
        std::vector<تخصيص_ذاكرة> تسريبات;
        
        for (const auto& [ptr, تخصيص] : m_تخصيصات) {
            if (!تخصيص.مُحرر) {
                تسريبات.push_back(تخصيص);
            }
        }
        
        return تسريبات;
    }
    
    /**
     * إحصائيات
     */
    struct إحصائيات {
        size_t عدد_التخصيصات;
        size_t عدد_التحريرات;
        size_t إجمالي_مخصص;
        size_t إجمالي_محرر;
        size_t الحالي;
        size_t عدد_التسريبات;
    };
    
    إحصائيات احصل_على_الإحصائيات() const {
        size_t تخصيصات = 0, تحريرات = 0;
        
        for (const auto& [ptr, ت] : m_تخصيصات) {
            تخصيصات++;
            if (ت.مُحرر) تحريرات++;
        }
        
        return {تخصيصات, تحريرات, m_إجمالي_المخصص, m_إجمالي_المحرر, m_إجمالي_المخصص - m_إجمالي_المحرر, تخصيصات - تحريرات};
    }
    
    /**
     * مسح كل السجلات
     */
    void امسح() {
        m_تخصيصات.clear();
        m_إجمالي_المخصص = 0;
        m_إجمالي_المحرر = 0;
    }
    
private:
    std::unordered_map<void*, تخصيص_ذاكرة> m_تخصيصات;
    size_t m_إجمالي_المخصص = 0;
    size_t m_إجمالي_المحرر = 0;
    
    static std::string عنوان_إلى_نص(void* ptr) {
        std::stringstream ss;
        ss << "0x" << std::hex << reinterpret_cast<uintptr_t>(ptr);
        return ss.str();
    }
};

