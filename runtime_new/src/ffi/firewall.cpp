/**
 * قيود على معامل FFI
 */
struct قيود_معامل {
    // قيود على القيمة
    std::optional<int64_t> الحد_الأدنى;
    std::optional<int64_t> الحد_الأقصى;
    
    // قيود على الحجم (للنصوص والمصفوفات)
    std::optional<size_t> الحجم_الأدنى;
    std::optional<size_t> الحجم_الأقصى;
    
    // قيود خاصة
    bool لا_يقبل_null = true;          // المؤشرات يجب ألا تكون null
    bool نص_منتهي_بـ_null = true;      // النصوص يجب أن تنتهي بـ \0
    bool ذاكرة_محاذاة = false;         // محاذاة الذاكرة مطلوبة
    size_t حجم_المحاذاة = 0;
    
    /**
     * التحقق من قيمة رقمية
     */
    bool تحقق_من_قيمة(int64_t قيمة) const {
        if (الحد_الأدنى && قيمة < *الحد_الأدنى) return false;
        if (الحد_الأقصى && قيمة > *الحد_الأقصى) return false;
        return true;
    }
    
    /**
     * التحقق من حجم
     */
    bool تحقق_من_حجم(size_t حجم) const {
        if (الحجم_الأدنى && حجم < *الحجم_الأدنى) return false;
        if (الحجم_الأقصى && حجم > *الحجم_الأقصى) return false;
        return true;
    }
};

