/**
 * أنواع البيانات المدعومة في FFI
 * 
 * للمبتدئ: هذه الأنواع يمكن نقلها بين لغة ص و C.
 */
enum class نوع_FFI {
    // أنواع أولية
    صحيح_8,        // int8_t
    صحيح_16,       // int16_t
    صحيح_32,       // int32_t
    صحيح_64,       // int64_t
    طبيعي_8,       // uint8_t
    طبيعي_16,      // uint16_t
    طبيعي_32,      // uint32_t
    طبيعي_64,      // uint64_t
    عشري_32,       // float
    عشري_64,       // double
    
    // أنواع مركبة
    مؤشر,          // void*
    نص_C,          // char*
    مصفوفة,        // T[]
    بنية,          // struct
    
    // أنواع خاصة
    فارغ,          // void
    غير_معروف,
};

/**
 * تحويل نوع FFI إلى اسم C
 */
inline std::string إلى_اسم_C(نوع_FFI نوع) {
    switch (نوع) {
        case نوع_FFI::صحيح_8: return "int8_t";
        case نوع_FFI::صحيح_16: return "int16_t";
        case نوع_FFI::صحيح_32: return "int32_t";
        case نوع_FFI::صحيح_64: return "int64_t";
        case نوع_FFI::طبيعي_8: return "uint8_t";
        case نوع_FFI::طبيعي_16: return "uint16_t";
        case نوع_FFI::طبيعي_32: return "uint32_t";
        case نوع_FFI::طبيعي_64: return "uint64_t";
        case نوع_FFI::عشري_32: return "float";
        case نوع_FFI::عشري_64: return "double";
        case نوع_FFI::مؤشر: return "void*";
        case نوع_FFI::نص_C: return "char*";
        case نوع_FFI::مصفوفة: return "array";
        case نوع_FFI::بنية: return "struct";
        case نوع_FFI::فارغ: return "void";
        case نوع_FFI::غير_معروف: return "unknown";
    }
    return "unknown";
}

/**
 * حجم النوع بالبايت
 */
inline size_t حجم_نوع(نوع_FFI نوع) {
    switch (نوع) {
        case نوع_FFI::صحيح_8:
        case نوع_FFI::طبيعي_8: return 1;
        case نوع_FFI::صحيح_16:
        case نوع_FFI::طبيعي_16: return 2;
        case نوع_FFI::صحيح_32:
        case نوع_FFI::طبيعي_32:
        case نوع_FFI::عشري_32: return 4;
        case نوع_FFI::صحيح_64:
        case نوع_FFI::طبيعي_64:
        case نوع_FFI::عشري_64:
        case نوع_FFI::مؤشر:
        case نوع_FFI::نص_C: return 8;  // 64-bit
        default: return 0;
    }
}

