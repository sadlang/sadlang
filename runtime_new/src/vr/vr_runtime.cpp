/**
 * كاميرا VR
 */
class كاميرا_VR {
private:
    مدير_جلسة_VR* الجلسة_;
    
public:
    explicit كاميرا_VR(مدير_جلسة_VR* جلسة) : الجلسة_(جلسة) {}
    
    متجه3 الموضع() const {
        return الجلسة_->الرأس().التحويل.الموضع;
    }
    
    متجه3 الاتجاه() const {
        return الجلسة_->الرأس().التحويل.الدوران.دوّر({0, 0, -1});
    }
    
    متجه3 اليمين() const {
        return الجلسة_->الرأس().التحويل.الدوران.دوّر({1, 0, 0});
    }
    
    متجه3 الأعلى() const {
        return الجلسة_->الرأس().التحويل.الدوران.دوّر({0, 1, 0});
    }
};

/**
 * شعاع التصويب (للتفاعل)
 */
struct شعاع {
    متجه3 الأصل;
    متجه3 الاتجاه;
    
    متجه3 نقطة(float مسافة) const {
        return الأصل + الاتجاه * مسافة;
    }
};

/**
 * نتيجة تصادم الشعاع
 */
struct نتيجة_شعاع {
    bool أصاب = false;
    متجه3 نقطة_التصادم;
    متجه3 العمودي;
    float المسافة = 0;
    void* الكائن = nullptr;
};

