/**
 * مدير التفاعل
 */
class مدير_تفاعل {
private:
    مدير_جلسة_VR* الجلسة_;
    
public:
    explicit مدير_تفاعل(مدير_جلسة_VR* جلسة) : الجلسة_(جلسة) {}
    
    // شعاع من اليد
    شعاع شعاع_اليد(يد ي) const {
        const auto& حالة = الجلسة_->اليد(ي);
        
        شعاع ش;
        ش.الأصل = حالة.التحويل.الموضع;
        ش.الاتجاه = حالة.التحويل.الدوران.دوّر({0, 0, -1});
        
        return ش;
    }
    
    // شعاع من النظر
    شعاع شعاع_النظر() const {
        const auto& رأس = الجلسة_->الرأس();
        
        شعاع ش;
        ش.الأصل = رأس.التحويل.الموضع;
        ش.الاتجاه = رأس.التحويل.الدوران.دوّر({0, 0, -1});
        
        return ش;
    }
    
    // هل تم الضغط على الزناد؟
    bool زناد_مضغوط(يد ي) const {
        return الجلسة_->اليد(ي).الزناد > 0.5f;
    }
    
    // هل تم القبض؟
    bool قبضة_مغلقة(يد ي) const {
        return الجلسة_->اليد(ي).القبضة > 0.5f;
    }
};

