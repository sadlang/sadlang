/**
 * متجه ثلاثي الأبعاد
 */
struct متجه3 {
    float س = 0.0f;
    float ص = 0.0f;
    float ع = 0.0f;
    
    متجه3() = default;
    متجه3(float _س, float _ص, float _ع) : س(_س), ص(_ص), ع(_ع) {}
    
    متجه3 operator+(const متجه3& أخر) const {
        return {س + أخر.س, ص + أخر.ص, ع + أخر.ع};
    }
    
    متجه3 operator-(const متجه3& أخر) const {
        return {س - أخر.س, ص - أخر.ص, ع - أخر.ع};
    }
    
    متجه3 operator*(float عامل) const {
        return {س * عامل, ص * عامل, ع * عامل};
    }
    
    float طول() const {
        return std::sqrt(س*س + ص*ص + ع*ع);
    }
    
    متجه3 طبيعي() const {
        float ط = طول();
        if (ط > 0.0001f) {
            return *this * (1.0f / ط);
        }
        return {0, 0, 0};
    }
    
    float ضرب_نقطي(const متجه3& أخر) const {
        return س * أخر.س + ص * أخر.ص + ع * أخر.ع;
    }
    
    متجه3 ضرب_تقاطعي(const متجه3& أخر) const {
        return {
            ص * أخر.ع - ع * أخر.ص,
            ع * أخر.س - س * أخر.ع,
            س * أخر.ص - ص * أخر.س
        };
    }
};

/**
 * رباعي للدوران
 */
struct رباعي {
    float س = 0.0f;
    float ص = 0.0f;
    float ع = 0.0f;
    float و = 1.0f;
    
    رباعي() = default;
    رباعي(float _س, float _ص, float _ع, float _و) 
        : س(_س), ص(_ص), ع(_ع), و(_و) {}
    
    static رباعي من_أويلر(float درجة_س, float درجة_ص, float درجة_ع) {
        float نصف_س = درجة_س * 0.5f;
        float نصف_ص = درجة_ص * 0.5f;
        float نصف_ع = درجة_ع * 0.5f;
        
        float جا_س = std::sin(نصف_س), جتا_س = std::cos(نصف_س);
        float جا_ص = std::sin(نصف_ص), جتا_ص = std::cos(نصف_ص);
        float جا_ع = std::sin(نصف_ع), جتا_ع = std::cos(نصف_ع);
        
        return {
            جا_س * جتا_ص * جتا_ع - جتا_س * جا_ص * جا_ع,
            جتا_س * جا_ص * جتا_ع + جا_س * جتا_ص * جا_ع,
            جتا_س * جتا_ص * جا_ع - جا_س * جا_ص * جتا_ع,
            جتا_س * جتا_ص * جتا_ع + جا_س * جا_ص * جا_ع
        };
    }
    
    رباعي operator*(const رباعي& أخر) const {
        return {
            و*أخر.س + س*أخر.و + ص*أخر.ع - ع*أخر.ص,
            و*أخر.ص - س*أخر.ع + ص*أخر.و + ع*أخر.س,
            و*أخر.ع + س*أخر.ص - ص*أخر.س + ع*أخر.و,
            و*أخر.و - س*أخر.س - ص*أخر.ص - ع*أخر.ع
        };
    }
    
    متجه3 دوّر(const متجه3& متجه) const {
        رباعي م = {متجه.س, متجه.ص, متجه.ع, 0};
        رباعي معكوس = {-س, -ص, -ع, و};
        رباعي نتيجة = *this * م * معكوس;
        return {نتيجة.س, نتيجة.ص, نتيجة.ع};
    }
};

/**
 * تحويل (موضع + دوران + مقياس)
 */
struct تحويل {
    متجه3 الموضع;
    رباعي الدوران;
    متجه3 المقياس = {1.0f, 1.0f, 1.0f};
    
    std::array<float, 16> إلى_مصفوفة() const {
        // تحويل إلى مصفوفة 4x4
        std::array<float, 16> م = {0};
        
        float س2 = الدوران.س * 2;
        float ص2 = الدوران.ص * 2;
        float ع2 = الدوران.ع * 2;
        
        float وس = الدوران.و * س2;
        float وص = الدوران.و * ص2;
        float وع = الدوران.و * ع2;
        float سس = الدوران.س * س2;
        float سص = الدوران.س * ص2;
        float سع = الدوران.س * ع2;
        float صص = الدوران.ص * ص2;
        float صع = الدوران.ص * ع2;
        float عع = الدوران.ع * ع2;
        
        م[0] = (1 - (صص + عع)) * المقياس.س;
        م[1] = (سص + وع) * المقياس.س;
        م[2] = (سع - وص) * المقياس.س;
        م[3] = 0;
        
        م[4] = (سص - وع) * المقياس.ص;
        م[5] = (1 - (سس + عع)) * المقياس.ص;
        م[6] = (صع + وس) * المقياس.ص;
        م[7] = 0;
        
        م[8] = (سع + وص) * المقياس.ع;
        م[9] = (صع - وس) * المقياس.ع;
        م[10] = (1 - (سس + صص)) * المقياس.ع;
        م[11] = 0;
        
        م[12] = الموضع.س;
        م[13] = الموضع.ص;
        م[14] = الموضع.ع;
        م[15] = 1;
        
        return م;
    }
};

