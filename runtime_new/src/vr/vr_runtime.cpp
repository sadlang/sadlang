extern "C" {

using namespace ص::واقع::افتراضي;

static مدير_جلسة_VR* الجلسة_العامة = nullptr;

int sad_vr_init() {
    if (!الجلسة_العامة) {
        الجلسة_العامة = new مدير_جلسة_VR();
    }
    return الجلسة_العامة->تهيئة() ? 1 : 0;
}

void sad_vr_shutdown() {
    if (الجلسة_العامة) {
        الجلسة_العامة->إيقاف();
        delete الجلسة_العامة;
        الجلسة_العامة = nullptr;
    }
}

int sad_vr_active() {
    return (الجلسة_العامة && الجلسة_العامة->نشط()) ? 1 : 0;
}

void sad_vr_update() {
    if (الجلسة_العامة) {
        الجلسة_العامة->تحديث_التتبع();
        الجلسة_العامة->تحديث_الإدخال();
    }
}

void sad_vr_get_head_position(float* x, float* y, float* z) {
    if (الجلسة_العامة) {
        auto موضع = الجلسة_العامة->الرأس().التحويل.الموضع;
        *x = موضع.س;
        *y = موضع.ص;
        *z = موضع.ع;
    }
}

void sad_vr_get_hand_position(int hand, float* x, float* y, float* z) {
    if (الجلسة_العامة) {
        auto موضع = الجلسة_العامة->اليد(hand == 0 ? يد::يسرى : يد::يمنى).التحويل.الموضع;
        *x = موضع.س;
        *y = موضع.ص;
        *z = موضع.ع;
    }
}

float sad_vr_get_trigger(int hand) {
    if (!الجلسة_العامة) return 0;
    return الجلسة_العامة->اليد(hand == 0 ? يد::يسرى : يد::يمنى).الزناد;
}

}  // extern "C"
