/**
 * مدير جلسة VR
 */
class مدير_جلسة_VR {
private:
    bool نشط_ = false;
    حالة_رأس الرأس_;
    حالة_يد اليد_اليسرى_ = {يد::يسرى};
    حالة_يد اليد_اليمنى_ = {يد::يمنى};
    حالة_عين العين_اليسرى_;
    حالة_عين العين_اليمنى_;
    معلومات_عرض العرض_;
    
    // دوال المعالجة
    std::function<void(float)> دالة_تحديث_;
    std::function<void(uint32_t)> دالة_رسم_;  // 0=يسرى، 1=يمنى
    
public:
    مدير_جلسة_VR() = default;
    
    // ============== التهيئة ==============
    
    bool تهيئة() {
        // في الواقع: اتصال بـ OpenXR
        نشط_ = true;
        
        // إعدادات افتراضية
        العرض_.العرض = 1920;
        العرض_.الارتفاع = 1080;
        العرض_.معدل_التحديث = 90.0f;
        
        return true;
    }
    
    void إيقاف() {
        نشط_ = false;
    }
    
    bool نشط() const { return نشط_; }
    
    // ============== التتبع ==============
    
    const حالة_رأس& الرأس() const { return الرأس_; }
    const حالة_يد& اليد(يد ي) const {
        return (ي == يد::يسرى) ? اليد_اليسرى_ : اليد_اليمنى_;
    }
    
    void تحديث_التتبع() {
        // في الواقع: قراءة من OpenXR
        
        // محاكاة حركة بسيطة
        static float زمن = 0;
        زمن += 0.016f;
        
        الرأس_.متتبع = true;
        الرأس_.التحويل.الموضع = {0, 1.6f, 0};  // ارتفاع الرأس
        الرأس_.التحويل.الدوران = رباعي::من_أويلر(0, std::sin(زمن) * 0.1f, 0);
        
        اليد_اليسرى_.متتبعة = true;
        اليد_اليسرى_.التحويل.الموضع = {-0.3f, 1.0f, -0.3f};
        
        اليد_اليمنى_.متتبعة = true;
        اليد_اليمنى_.التحويل.الموضع = {0.3f, 1.0f, -0.3f};
    }
    
    // ============== الإدخال ==============
    
    void تحديث_الإدخال() {
        // في الواقع: قراءة أزرار المتحكمات
    }
    
    // ============== العرض ==============
    
    const معلومات_عرض& العرض() const { return العرض_; }
    
    std::array<float, 16> مصفوفة_العرض(int عين) const {
        // حساب مصفوفة العرض للعين
        float إزاحة_عين = (عين == 0) ? -0.032f : 0.032f;  // IPD/2
        
        متجه3 موضع_عين = الرأس_.التحويل.الموضع;
        موضع_عين.س += إزاحة_عين;
        
        // مصفوفة نظر مبسطة
        std::array<float, 16> م = {0};
        م[0] = 1; م[5] = 1; م[10] = 1; م[15] = 1;
        م[12] = -موضع_عين.س;
        م[13] = -موضع_عين.ص;
        م[14] = -موضع_عين.ع;
        
        return م;
    }
    
    std::array<float, 16> مصفوفة_الإسقاط(int عين) const {
        const auto& عدسة = (عين == 0) ? العرض_.العين_اليسرى : العرض_.العين_اليمنى;
        
        float يسار = std::tan(عدسة.مجال_الرؤية_يسار * 3.14159f / 180.0f);
        float يمين = std::tan(عدسة.مجال_الرؤية_يمين * 3.14159f / 180.0f);
        float أعلى = std::tan(عدسة.مجال_الرؤية_أعلى * 3.14159f / 180.0f);
        float أسفل = std::tan(عدسة.مجال_الرؤية_أسفل * 3.14159f / 180.0f);
        
        float قريب = 0.1f;
        float بعيد = 1000.0f;
        
        std::array<float, 16> م = {0};
        
        م[0] = 2.0f / (يمين - يسار);
        م[5] = 2.0f / (أعلى - أسفل);
        م[8] = (يمين + يسار) / (يمين - يسار);
        م[9] = (أعلى + أسفل) / (أعلى - أسفل);
        م[10] = -(بعيد + قريب) / (بعيد - قريب);
        م[11] = -1.0f;
        م[14] = -(2.0f * بعيد * قريب) / (بعيد - قريب);
        
        return م;
    }
    
    // ============== الحلقة الرئيسية ==============
    
    void تعيين_دالة_التحديث(std::function<void(float)> دالة) {
        دالة_تحديث_ = دالة;
    }
    
    void تعيين_دالة_الرسم(std::function<void(uint32_t)> دالة) {
        دالة_رسم_ = دالة;
    }
    
    void إطار() {
        if (!نشط_) return;
        
        // تحديث التتبع
        تحديث_التتبع();
        تحديث_الإدخال();
        
        // استدعاء التحديث
        if (دالة_تحديث_) {
            دالة_تحديث_(1.0f / 90.0f);  // ~11ms
        }
        
        // رسم العينين
        if (دالة_رسم_) {
            دالة_رسم_(0);  // العين اليسرى
            دالة_رسم_(1);  // العين اليمنى
        }
    }
    
    void حلقة_رئيسية() {
        while (نشط_) {
            إطار();
        }
    }
};

