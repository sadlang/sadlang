// ============== معرّف الإيماءات ==============

class معرف_الإيماءات {
private:
    // عتبات التعرف
    float عتبة_الانثناء_ = 0.5f;
    float عتبة_التمدد_ = 0.3f;
    float عتبة_القرصة_ = 0.03f;  // متر
    
    // تاريخ الحركة
    std::vector<متجه3> تاريخ_الموضع_;
    static constexpr size_t حجم_التاريخ_ = 30;
    
public:
    // حساب انثناء إصبع (0 = ممدود، 1 = مثني)
    float حساب_انثناء_إصبع(const حالة_يد& يد, int إصبع) const {
        // الأصابع: 0=إبهام، 1=سبابة، 2=وسطى، 3=بنصر، 4=خنصر
        int قاعدة = 2 + إصبع * 5;  // بداية مفاصل الإصبع
        if (إصبع == 0) قاعدة = 2;  // الإبهام
        
        // حساب الزاوية بين المفاصل
        const auto& قريب = يد.المفاصل[قاعدة + 1].الموضع;
        const auto& وسط = يد.المفاصل[قاعدة + 2].الموضع;
        const auto& بعيد = يد.المفاصل[قاعدة + 3].الموضع;
        
        متجه3 v1 = (وسط - قريب).طبيعي();
        متجه3 v2 = (بعيد - وسط).طبيعي();
        
        float حاصل_نقطي = v1.نقطي(v2);
        float زاوية = std::acos(std::clamp(حاصل_نقطي, -1.0f, 1.0f));
        
        // تحويل لنسبة انثناء
        return زاوية / 3.14159f;
    }
    
    // التعرف على الإيماءة الحالية
    إيماءة التعرف(const حالة_يد& يد) {
        if (!يد.متتبعة) return إيماءة::غير_معروفة;
        
        // حساب انثناء كل إصبع
        float انثناء[5];
        for (int i = 0; i < 5; i++) {
            انثناء[i] = حساب_انثناء_إصبع(يد, i);
        }
        
        // فحص القبضة
        bool قبضة = true;
        for (int i = 1; i < 5; i++) {  // بدون الإبهام
            if (انثناء[i] < عتبة_الانثناء_) قبضة = false;
        }
        if (قبضة) return إيماءة::قبضة;
        
        // فحص الكف المفتوح
        bool كف_مفتوح = true;
        for (int i = 1; i < 5; i++) {
            if (انثناء[i] > عتبة_التمدد_) كف_مفتوح = false;
        }
        if (كف_مفتوح && انثناء[0] < عتبة_التمدد_) {
            return إيماءة::كف_مفتوح;
        }
        
        // فحص النقطة (سبابة فقط)
        if (انثناء[1] < عتبة_التمدد_ &&
            انثناء[2] > عتبة_الانثناء_ &&
            انثناء[3] > عتبة_الانثناء_ &&
            انثناء[4] > عتبة_الانثناء_) {
            return إيماءة::نقطة;
        }
        
        // فحص السلام
        if (انثناء[1] < عتبة_التمدد_ &&
            انثناء[2] < عتبة_التمدد_ &&
            انثناء[3] > عتبة_الانثناء_ &&
            انثناء[4] > عتبة_الانثناء_) {
            return إيماءة::سلام;
        }
        
        // فحص إيماءة روك
        if (انثناء[1] < عتبة_التمدد_ &&
            انثناء[2] > عتبة_الانثناء_ &&
            انثناء[3] > عتبة_الانثناء_ &&
            انثناء[4] < عتبة_التمدد_) {
            return إيماءة::روك;
        }
        
        // فحص القرصة (المسافة بين الإبهام والسبابة)
        const auto& إبهام = يد.مفصل(مفصل_يد::إبهام_طرف).الموضع;
        const auto& سبابة = يد.مفصل(مفصل_يد::سبابة_طرف).الموضع;
        float مسافة_قرصة = (إبهام - سبابة).طول();
        
        if (مسافة_قرصة < عتبة_القرصة_) {
            return إيماءة::قرصة;
        }
        
        // فحص موافق (OK)
        if (مسافة_قرصة < عتبة_القرصة_ * 2 &&
            انثناء[2] < عتبة_التمدد_ &&
            انثناء[3] < عتبة_التمدد_ &&
            انثناء[4] < عتبة_التمدد_) {
            return إيماءة::موافق;
        }
        
        // فحص إبهام لأعلى
        if (انثناء[0] < عتبة_التمدد_ &&
            انثناء[1] > عتبة_الانثناء_ &&
            انثناء[2] > عتبة_الانثناء_ &&
            انثناء[3] > عتبة_الانثناء_ &&
            انثناء[4] > عتبة_الانثناء_) {
            
            // فحص اتجاه الإبهام
            const auto& قاعدة = يد.مفصل(مفصل_يد::إبهام_سنعي).الموضع;
            const auto& طرف = يد.مفصل(مفصل_يد::إبهام_طرف).الموضع;
            متجه3 اتجاه = (طرف - قاعدة).طبيعي();
            
            if (اتجاه.y > 0.5f) return إيماءة::إبهام_لأعلى;
            if (اتجاه.y < -0.5f) return إيماءة::إبهام_لأسفل;
        }
        
        return إيماءة::غير_معروفة;
    }
    
    // التعرف على إيماءات الحركة
    إيماءة التعرف_على_الحركة(const حالة_يد& يد) {
        if (!يد.متتبعة) return إيماءة::غير_معروفة;
        
        // إضافة الموضع للتاريخ
        تاريخ_الموضع_.push_back(يد.مفصل(مفصل_يد::راحة).الموضع);
        if (تاريخ_الموضع_.size() > حجم_التاريخ_) {
            تاريخ_الموضع_.erase(تاريخ_الموضع_.begin());
        }
        
        if (تاريخ_الموضع_.size() < 10) return إيماءة::لا_حركة;
        
        // حساب الإزاحة الكلية
        متجه3 إزاحة = تاريخ_الموضع_.back() - تاريخ_الموضع_.front();
        float المسافة = إزاحة.طول();
        
        if (المسافة < 0.05f) return إيماءة::لا_حركة;
        
        // تحديد الاتجاه الرئيسي
        if (std::abs(إزاحة.x) > std::abs(إزاحة.y) &&
            std::abs(إزاحة.x) > std::abs(إزاحة.z)) {
            // حركة أفقية
            return إزاحة.x > 0 ? إيماءة::تمرير_يمين : إيماءة::تمرير_يسار;
        }
        
        if (std::abs(إزاحة.y) > std::abs(إزاحة.z)) {
            // حركة عمودية
            return إزاحة.y > 0 ? إيماءة::تمرير_أعلى : إيماءة::تمرير_أسفل;
        }
        
        return إيماءة::غير_معروفة;
    }
};

// ============== الإيماءات المخصصة ==============

struct تعريف_إيماءة_مخصصة {
    std::string الاسم;
    
    // حالة الأصابع المطلوبة (-1 = لا يهم، 0 = ممدود، 1 = مثني)
    std::array<int, 5> حالة_الأصابع = {-1, -1, -1, -1, -1};
    
    // مسافة القرصة المطلوبة (إذا > 0)
    float مسافة_قرصة_قصوى = -1;
    
    // اتجاه الراحة المطلوب (إذا != 0)
    متجه3 اتجاه_الراحة = {0, 0, 0};
    float عتبة_الاتجاه = 0.5f;
    
    // التحقق الديناميكي
    std::function<bool(const حالة_يد&)> فحص_مخصص;
};

class مدير_الإيماءات_المخصصة {
private:
    std::map<std::string, تعريف_إيماءة_مخصصة> الإيماءات_;
    معرف_الإيماءات معرف_;
    
public:
    void إضافة_إيماءة(const تعريف_إيماءة_مخصصة& تعريف) {
        الإيماءات_[تعريف.الاسم] = تعريف;
    }
    
    void إزالة_إيماءة(const std::string& اسم) {
        الإيماءات_.erase(اسم);
    }
    
    std::string التعرف(const حالة_يد& يد) {
        for (const auto& [اسم, تعريف] : الإيماءات_) {
            if (تطابق(يد, تعريف)) {
                return اسم;
            }
        }
        return "";
    }
    
private:
    bool تطابق(const حالة_يد& يد, const تعريف_إيماءة_مخصصة& تعريف) {
        // فحص حالة الأصابع
        for (int i = 0; i < 5; i++) {
            if (تعريف.حالة_الأصابع[i] != -1) {
                float انثناء = معرف_.حساب_انثناء_إصبع(يد, i);
                bool مثني = انثناء > 0.5f;
                
                if (تعريف.حالة_الأصابع[i] == 0 && مثني) return false;
                if (تعريف.حالة_الأصابع[i] == 1 && !مثني) return false;
            }
        }
        
        // فحص مسافة القرصة
        if (تعريف.مسافة_قرصة_قصوى > 0) {
            const auto& إبهام = يد.مفصل(مفصل_يد::إبهام_طرف).الموضع;
            const auto& سبابة = يد.مفصل(مفصل_يد::سبابة_طرف).الموضع;
            float مسافة = (إبهام - سبابة).طول();
            
            if (مسافة > تعريف.مسافة_قرصة_قصوى) return false;
        }
        
        // فحص الاتجاه
        float طول_اتجاه = تعريف.اتجاه_الراحة.طول();
        if (طول_اتجاه > 0.1f) {
            // حساب اتجاه الراحة
            const auto& رسغ = يد.مفصل(مفصل_يد::رسغ).الموضع;
            const auto& وسطى = يد.مفصل(مفصل_يد::وسطى_سنعي).الموضع;
            متجه3 اتجاه = (وسطى - رسغ).طبيعي();
            
            float تطابق = اتجاه.نقطي(تعريف.اتجاه_الراحة.طبيعي());
            if (تطابق < تعريف.عتبة_الاتجاه) return false;
        }
        
        // فحص مخصص
        if (تعريف.فحص_مخصص && !تعريف.فحص_مخصص(يد)) {
            return false;
        }
        
        return true;
    }
};

// ============== تتبع الهيكل العظمي ==============

class متتبع_الهيكل_العظمي {
private:
    // فلترة الموضع
    std::array<متجه3, 26> مواضع_مفلترة_;
    float عامل_التنعيم_ = 0.7f;
    
    // تنبؤ
    std::array<متجه3, 26> سرعات_;
    
public:
    حالة_يد تحديث(const std::array<معلومات_مفصل, 26>& بيانات_خام) {
        حالة_يد يد;
        
        for (size_t i = 0; i < 26; i++) {
            const auto& خام = بيانات_خام[i];
            
            if (خام.متتبع) {
                // فلترة الموضع (exponential smoothing)
                مواضع_مفلترة_[i].x = عامل_التنعيم_ * مواضع_مفلترة_[i].x + 
                                      (1 - عامل_التنعيم_) * خام.الموضع.x;
                مواضع_مفلترة_[i].y = عامل_التنعيم_ * مواضع_مفلترة_[i].y + 
                                      (1 - عامل_التنعيم_) * خام.الموضع.y;
                مواضع_مفلترة_[i].z = عامل_التنعيم_ * مواضع_مفلترة_[i].z + 
                                      (1 - عامل_التنعيم_) * خام.الموضع.z;
                
                يد.المفاصل[i].الموضع = مواضع_مفلترة_[i];
                يد.المفاصل[i].التوجه = خام.التوجه;
                يد.المفاصل[i].نصف_القطر = خام.نصف_القطر;
                يد.المفاصل[i].الثقة = خام.الثقة;
                يد.المفاصل[i].متتبع = true;
            } else {
                // تنبؤ بناءً على السرعة السابقة
                مواضع_مفلترة_[i].x += سرعات_[i].x;
                مواضع_مفلترة_[i].y += سرعات_[i].y;
                مواضع_مفلترة_[i].z += سرعات_[i].z;
                
                يد.المفاصل[i].الموضع = مواضع_مفلترة_[i];
                يد.المفاصل[i].متتبع = false;
            }
        }
        
        // حساب السرعات للإطار التالي
        // (يتم في الإطار التالي)
        
        يد.متتبعة = بيانات_خام[0].متتبع;
        
        return يد;
    }
    
    void تعيين_تنعيم(float عامل) {
        عامل_التنعيم_ = std::clamp(عامل, 0.0f, 1.0f);
    }
};

// ============== مدير تتبع الأيدي ==============

class مدير_تتبع_الأيدي {
private:
    حالة_يد اليد_اليمنى_;
    حالة_يد اليد_اليسرى_;
    
    متتبع_الهيكل_العظمي متتبع_يمين_;
    متتبع_الهيكل_العظمي متتبع_يسار_;
    
    معرف_الإيماءات معرف_;
    مدير_الإيماءات_المخصصة إيماءات_مخصصة_;
    
    // أحداث
    std::function<void(جانب_يد, إيماءة)> عند_إيماءة_;
    std::function<void(جانب_يد, const std::string&)> عند_إيماءة_مخصصة_;
    
public:
    // تحديث من بيانات التتبع
    void تحديث_يمين(const std::array<معلومات_مفصل, 26>& بيانات) {
        اليد_اليمنى_ = متتبع_يمين_.تحديث(بيانات);
        اليد_اليمنى_.الجانب = جانب_يد::يمنى;
        
        // التعرف على الإيماءات
        إيماءة إ = معرف_.التعرف(اليد_اليمنى_);
        if (إ != إيماءة::غير_معروفة && عند_إيماءة_) {
            عند_إيماءة_(جانب_يد::يمنى, إ);
        }
        
        // إيماءات مخصصة
        std::string مخصصة = إيماءات_مخصصة_.التعرف(اليد_اليمنى_);
        if (!مخصصة.empty() && عند_إيماءة_مخصصة_) {
            عند_إيماءة_مخصصة_(جانب_يد::يمنى, مخصصة);
        }
    }
    
    void تحديث_يسار(const std::array<معلومات_مفصل, 26>& بيانات) {
        اليد_اليسرى_ = متتبع_يسار_.تحديث(بيانات);
        اليد_اليسرى_.الجانب = جانب_يد::يسرى;
        
        // نفس المنطق للإيماءات
        إيماءة إ = معرف_.التعرف(اليد_اليسرى_);
        if (إ != إيماءة::غير_معروفة && عند_إيماءة_) {
            عند_إيماءة_(جانب_يد::يسرى, إ);
        }
        
        std::string مخصصة = إيماءات_مخصصة_.التعرف(اليد_اليسرى_);
        if (!مخصصة.empty() && عند_إيماءة_مخصصة_) {
            عند_إيماءة_مخصصة_(جانب_يد::يسرى, مخصصة);
        }
    }
    
    // الوصول للحالة
    const حالة_يد& يد_يمنى() const { return اليد_اليمنى_; }
    const حالة_يد& يد_يسرى() const { return اليد_اليسرى_; }
    
    // إضافة إيماءة مخصصة
    void إضافة_إيماءة_مخصصة(const تعريف_إيماءة_مخصصة& تعريف) {
        إيماءات_مخصصة_.إضافة_إيماءة(تعريف);
    }
    
    // أحداث
    void عند_إيماءة(std::function<void(جانب_يد, إيماءة)> معالج) {
        عند_إيماءة_ = معالج;
    }
    
    void عند_إيماءة_مخصصة(std::function<void(جانب_يد, const std::string&)> معالج) {
        عند_إيماءة_مخصصة_ = معالج;
    }
    
    // معلومات مفيدة
    bool قرصة_نشطة(جانب_يد جانب) const {
        const auto& يد = (جانب == جانب_يد::يمنى) ? اليد_اليمنى_ : اليد_اليسرى_;
        return يد.قوة_القرصة > 0.5f;
    }
    
    متجه3 موضع_راحة(جانب_يد جانب) const {
        const auto& يد = (جانب == جانب_يد::يمنى) ? اليد_اليمنى_ : اليد_اليسرى_;
        return يد.مفصل(مفصل_يد::راحة).الموضع;
    }
    
    متجه3 اتجاه_الإشارة(جانب_يد جانب) const {
        const auto& يد = (جانب == جانب_يد::يمنى) ? اليد_اليمنى_ : اليد_اليسرى_;
        return (يد.مفصل(مفصل_يد::سبابة_طرف).الموضع - 
                يد.مفصل(مفصل_يد::سبابة_سنعي).الموضع).طبيعي();
    }
};

