// ============== الأنواع الأساسية ==============

struct متجه3 {
    float x = 0, y = 0, z = 0;
    
    متجه3 operator-(const متجه3& أخر) const {
        return {x - أخر.x, y - أخر.y, z - أخر.z};
    }
    
    float طول() const {
        return std::sqrt(x*x + y*y + z*z);
    }
    
    متجه3 طبيعي() const {
        float ط = طول();
        if (ط < 0.0001f) return {0, 0, 0};
        return {x/ط, y/ط, z/ط};
    }
    
    float نقطي(const متجه3& أخر) const {
        return x*أخر.x + y*أخر.y + z*أخر.z;
    }
};

