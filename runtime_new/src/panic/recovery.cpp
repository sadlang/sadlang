/**
 * ماكرو لتنفيذ كود مع إمكانية التعافي
 */
#define SAD_RECOVERABLE(بديل, كود) \
    ([&]() { \
        try { \
            return كود; \
        } catch (...) { \
            return بديل; \
        } \
    })()

/**
 * ماكرو لتنفيذ كود مع إعادة محاولة
 */
#define SAD_RETRY(محاولات, انتظار_ms, كود) \
    ([&]() { \
        for (int _i = 0; _i < (محاولات); _i++) { \
            try { \
                return كود; \
            } catch (...) { \
                if (_i < (محاولات) - 1) { \
                    std::this_thread::sleep_for( \
                        std::chrono::milliseconds(انتظار_ms)); \
                } \
            } \
        } \
        throw; \
    })()

