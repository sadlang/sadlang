/**
 * نوع استراتيجية التعافي
 */
enum class نوع_استراتيجية {
    قيمة_بديلة,        // أرجع قيمة افتراضية
    إعادة_محاولة,       // أعد المحاولة n مرة
    تجاهل,             // تجاهل الخطأ واستمر
    تراجع,             // ارجع لآخر نقطة سليمة
    مخصص,              // استراتيجية مخصصة
};

/**
 * نتيجة محاولة التعافي
 */
enum class نتيجة_تعافي {
    نجح,               // تم التعافي بنجاح
    جزئي,              // تعافي جزئي (مع تحذير)
    فشل,               // فشل التعافي
};

/**
 * سجل محاولة تعافي
 */
struct سجل_تعافي {
    نوع_ذعر نوع_الذعر;
    نوع_استراتيجية الاستراتيجية;
    نتيجة_تعافي النتيجة;
    std::string الوصف;
    std::chrono::system_clock::time_point الوقت;
    int محاولة_رقم = 1;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "[" << استراتيجية_إلى_نص(الاستراتيجية) << "] ";
        switch (النتيجة) {
            case نتيجة_تعافي::نجح: ss << "✅ نجح"; break;
            case نتيجة_تعافي::جزئي: ss << "⚠️ جزئي"; break;
            case نتيجة_تعافي::فشل: ss << "❌ فشل"; break;
        }
        if (!الوصف.empty()) ss << ": " << الوصف;
        return ss.str();
    }
    
    static std::string استراتيجية_إلى_نص(نوع_استراتيجية استراتيجية) {
        switch (استراتيجية) {
            case نوع_استراتيجية::قيمة_بديلة: return "قيمة_بديلة";
            case نوع_استراتيجية::إعادة_محاولة: return "إعادة_محاولة";
            case نوع_استراتيجية::تجاهل: return "تجاهل";
            case نوع_استراتيجية::تراجع: return "تراجع";
            case نوع_استراتيجية::مخصص: return "مخصص";
            default: return "غير_معروف";
        }
    }
};

