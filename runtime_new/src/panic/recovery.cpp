/**
 * واجهة استراتيجية تعافي
 */
class استراتيجية_تعافي {
public:
    virtual ~استراتيجية_تعافي() = default;
    
    /**
     * نوع الاستراتيجية
     */
    virtual نوع_استراتيجية النوع() const = 0;
    
    /**
     * هل يمكن التعافي من هذا النوع من الذعر؟
     */
    virtual bool يمكن_التعافي(نوع_ذعر نوع) const = 0;
    
    /**
     * محاولة التعافي
     */
    virtual std::pair<نتيجة_تعافي, std::any> حاول(
        const معلومات_ذعر& معلومات,
        std::function<std::any()> العملية) = 0;
};

