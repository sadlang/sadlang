/**
 * استراتيجية إعادة المحاولة
 */
class استراتيجية_إعادة_محاولة : public استراتيجية_تعافي {
public:
    استراتيجية_إعادة_محاولة(
        int عدد_المحاولات = 3,
        std::chrono::milliseconds انتظار = std::chrono::milliseconds(100),
        bool انتظار_متزايد = true)
        : m_عدد_المحاولات(عدد_المحاولات)
        , m_الانتظار(انتظار)
        , m_انتظار_متزايد(انتظار_متزايد) {}
    
    نوع_استراتيجية النوع() const override {
        return نوع_استراتيجية::إعادة_محاولة;
    }
    
    bool يمكن_التعافي(نوع_ذعر نوع) const override {
        // إعادة المحاولة مفيدة للأخطاء المؤقتة
        switch (نوع) {
            case نوع_ذعر::خطأ_IO:
            case نوع_ذعر::خطأ_نظام:
            case نوع_ذعر::نفاد_الذاكرة:
                return true;
            default:
                return false;
        }
    }
    
    std::pair<نتيجة_تعافي, std::any> حاول(
        const معلومات_ذعر& معلومات,
        std::function<std::any()> العملية) override {
        
        for (int i = 0; i < m_عدد_المحاولات; i++) {
            try {
                // انتظر قبل إعادة المحاولة
                if (i > 0) {
                    auto انتظار = m_الانتظار;
                    if (m_انتظار_متزايد) {
                        انتظار *= (1 << i);  // exponential backoff
                    }
                    std::this_thread::sleep_for(انتظار);
                }
                
                // حاول
                auto نتيجة = العملية();
                return {نتيجة_تعافي::نجح, نتيجة};
                
            } catch (...) {
                // فشلت المحاولة، استمر
            }
        }
        
        return {نتيجة_تعافي::فشل, {}};
    }
    
private:
    int m_عدد_المحاولات;
    std::chrono::milliseconds m_الانتظار;
    bool m_انتظار_متزايد;
};

