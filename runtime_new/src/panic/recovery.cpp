/**
 * نقطة حفظ للتراجع
 */
struct نقطة_حفظ {
    std::string الاسم;
    std::unordered_map<std::string, std::any> الحالة;
    std::chrono::system_clock::time_point الوقت;
    
    نقطة_حفظ(const std::string& اسم = "")
        : الاسم(اسم)
        , الوقت(std::chrono::system_clock::now()) {}
};

/**
 * استراتيجية التراجع لنقطة سليمة
 */
class استراتيجية_تراجع : public استراتيجية_تعافي {
public:
    نوع_استراتيجية النوع() const override {
        return نوع_استراتيجية::تراجع;
    }
    
    bool يمكن_التعافي(نوع_ذعر نوع) const override {
        // يمكن التراجع إذا كانت هناك نقطة حفظ
        return !m_نقاط_الحفظ.empty();
    }
    
    std::pair<نتيجة_تعافي, std::any> حاول(
        const معلومات_ذعر& معلومات,
        std::function<std::any()> العملية) override {
        
        if (m_نقاط_الحفظ.empty()) {
            return {نتيجة_تعافي::فشل, {}};
        }
        
        // استرجع آخر نقطة حفظ
        نقطة_حفظ نقطة = m_نقاط_الحفظ.back();
        m_نقاط_الحفظ.pop_back();
        
        // استعادة الحالة (يحتاج تنفيذ مخصص)
        // restore_state(نقطة.الحالة);
        
        return {نتيجة_تعافي::نجح, نقطة.الحالة};
    }
    
    /**
     * إنشاء نقطة حفظ
     */
    void احفظ(const std::string& اسم = "") {
        m_نقاط_الحفظ.push_back(نقطة_حفظ(اسم));
    }
    
    /**
     * إضافة متغير للحالة
     */
    template<typename T>
    void احفظ_متغير(const std::string& اسم, const T& قيمة) {
        if (!m_نقاط_الحفظ.empty()) {
            m_نقاط_الحفظ.back().الحالة[اسم] = قيمة;
        }
    }
    
private:
    std::vector<نقطة_حفظ> m_نقاط_الحفظ;
};

