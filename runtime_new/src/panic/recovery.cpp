/**
 * مدير التعافي من الذعر
 */
class مدير_تعافي {
public:
    /**
     * الحصول على المدير العالمي
     */
    static مدير_تعافي& المثال() {
        static مدير_تعافي مثال;
        return مثال;
    }
    
    /**
     * تسجيل استراتيجية لنوع ذعر
     */
    void سجِّل_استراتيجية(
        نوع_ذعر نوع,
        std::shared_ptr<استراتيجية_تعافي> استراتيجية) {
        
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_استراتيجيات[نوع] = std::move(استراتيجية);
    }
    
    /**
     * محاولة التعافي
     */
    template<typename T>
    std::optional<T> حاول_التعافي(
        const معلومات_ذعر& معلومات,
        std::function<T()> العملية) {
        
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        // ابحث عن استراتيجية
        auto it = m_استراتيجيات.find(معلومات.النوع);
        if (it == m_استراتيجيات.end()) {
            return std::nullopt;
        }
        
        auto& استراتيجية = it->second;
        
        if (!استراتيجية->يمكن_التعافي(معلومات.النوع)) {
            return std::nullopt;
        }
        
        // حاول التعافي
        auto [نتيجة, قيمة] = استراتيجية->حاول(
            معلومات,
            [&العملية]() -> std::any { return العملية(); }
        );
        
        // سجِّل المحاولة
        سجل_تعافي سجل;
        سجل.نوع_الذعر = معلومات.النوع;
        سجل.الاستراتيجية = استراتيجية->النوع();
        سجل.النتيجة = نتيجة;
        سجل.الوقت = std::chrono::system_clock::now();
        m_سجل.push_back(سجل);
        
        if (نتيجة == نتيجة_تعافي::فشل) {
            return std::nullopt;
        }
        
        try {
            return std::any_cast<T>(قيمة);
        } catch (...) {
            return std::nullopt;
        }
    }
    
    /**
     * الحصول على سجل التعافي
     */
    std::vector<سجل_تعافي> السجل() const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        return m_سجل;
    }
    
    /**
     * تقرير التعافي
     */
    std::string تقرير() const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        if (m_سجل.empty()) {
            return "لا توجد محاولات تعافي";
        }
        
        std::stringstream ss;
        ss << "سجل التعافي (" << m_سجل.size() << " محاولة):\n";
        
        for (const auto& سجل : m_سجل) {
            ss << "  " << سجل.إلى_نص() << "\n";
        }
        
        return ss.str();
    }
    
private:
    مدير_تعافي() = default;
    
    mutable std::mutex m_قفل;
    std::unordered_map<نوع_ذعر, std::shared_ptr<استراتيجية_تعافي>> m_استراتيجيات;
    std::vector<سجل_تعافي> m_سجل;
};

