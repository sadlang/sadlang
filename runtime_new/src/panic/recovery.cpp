/**
 * استراتيجية إرجاع قيمة بديلة
 */
template<typename T>
class استراتيجية_قيمة_بديلة : public استراتيجية_تعافي {
public:
    استراتيجية_قيمة_بديلة(T قيمة)
        : m_البديل(std::move(قيمة)) {}
    
    نوع_استراتيجية النوع() const override {
        return نوع_استراتيجية::قيمة_بديلة;
    }
    
    bool يمكن_التعافي(نوع_ذعر نوع) const override {
        // يمكن التعافي من معظم الأخطاء
        return true;
    }
    
    std::pair<نتيجة_تعافي, std::any> حاول(
        const معلومات_ذعر& معلومات,
        std::function<std::any()> العملية) override {
        
        // أعد القيمة البديلة مباشرة
        return {نتيجة_تعافي::نجح, m_البديل};
    }
    
private:
    T m_البديل;
};

