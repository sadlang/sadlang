/**
 * نوع الذعر
 */
enum class نوع_ذعر {
    // أخطاء الذاكرة
    فهرس_خارج_الحدود,      // Index out of bounds
    مؤشر_فارغ,             // Null pointer dereference
    تجاوز_المكدس,          // Stack overflow
    نفاد_الذاكرة,          // Out of memory
    
    // أخطاء حسابية
    قسمة_على_صفر,          // Division by zero
    تجاوز_حسابي,           // Arithmetic overflow
    
    // أخطاء الأنواع
    تحويل_نوع_فاشل,        // Type cast failed
    نوع_غير_متوقع,         // Unexpected type
    
    // أخطاء التأكيدات
    تأكيد_فاشل,            // Assertion failed
    شرط_مسبق_فاشل,         // Precondition failed
    شرط_لاحق_فاشل,         // Postcondition failed
    
    // أخطاء النظام
    خطأ_نظام,              // System error
    خطأ_IO,                // I/O error
    
    // أخطاء المنطق
    حالة_مستحيلة,          // Unreachable code reached
    متغير_غير_مهيأ,        // Uninitialized variable
    
    // أخرى
    يدوي,                  // Manual panic (throw)
    غير_معروف,             // Unknown
};

/**
 * تحويل نوع ذعر إلى نص
 */
inline std::string نوع_ذعر_إلى_نص(نوع_ذعر نوع) {
    switch (نوع) {
        case نوع_ذعر::فهرس_خارج_الحدود: return "فهرس خارج الحدود";
        case نوع_ذعر::مؤشر_فارغ: return "مؤشر فارغ";
        case نوع_ذعر::تجاوز_المكدس: return "تجاوز المكدس";
        case نوع_ذعر::نفاد_الذاكرة: return "نفاد الذاكرة";
        case نوع_ذعر::قسمة_على_صفر: return "قسمة على صفر";
        case نوع_ذعر::تجاوز_حسابي: return "تجاوز حسابي";
        case نوع_ذعر::تحويل_نوع_فاشل: return "تحويل نوع فاشل";
        case نوع_ذعر::نوع_غير_متوقع: return "نوع غير متوقع";
        case نوع_ذعر::تأكيد_فاشل: return "تأكيد فاشل";
        case نوع_ذعر::شرط_مسبق_فاشل: return "شرط مسبق فاشل";
        case نوع_ذعر::شرط_لاحق_فاشل: return "شرط لاحق فاشل";
        case نوع_ذعر::خطأ_نظام: return "خطأ نظام";
        case نوع_ذعر::خطأ_IO: return "خطأ إدخال/إخراج";
        case نوع_ذعر::حالة_مستحيلة: return "حالة مستحيلة";
        case نوع_ذعر::متغير_غير_مهيأ: return "متغير غير مهيأ";
        case نوع_ذعر::يدوي: return "ذعر يدوي";
        default: return "غير معروف";
    }
}

