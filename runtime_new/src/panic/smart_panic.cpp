/**
 * معالج الذعر الذكي
 */
class معالج_ذعر {
public:
    /**
     * callback عند حدوث ذعر
     */
    using معالج = std::function<void(const معلومات_ذعر&)>;
    
    /**
     * الحصول على المعالج العالمي
     */
    static معالج_ذعر& المثال() {
        static معالج_ذعر مثال;
        return مثال;
    }
    
    /**
     * تسجيل معالج مخصص
     */
    void سجِّل_معالج(معالج م) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_معالجات.push_back(std::move(م));
    }
    
    /**
     * إطلاق ذعر
     */
    [[noreturn]] void أطلق(معلومات_ذعر معلومات) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        // جمع المعلومات
        معلومات.المكدس = تتبع_مكدس::المثال().الإطارات();
        معلومات.آخر_الأحداث = سجل_عمليات::المثال().آخر_أحداث(10);
        معلومات.وقت_الحدوث = std::chrono::system_clock::now();
        
        // تحليل السبب
        حلل_السبب(معلومات);
        
        // استدعاء المعالجات
        for (const auto& معالج : m_معالجات) {
            try {
                معالج(معلومات);
            } catch (...) {
                // تجاهل أخطاء المعالجات
            }
        }
        
        // طباعة التقرير
        std::cerr << معلومات.تقرير_كامل() << std::endl;
        
        // إنهاء البرنامج
        std::abort();
    }
    
    /**
     * ذعر بسيط
     */
    [[noreturn]] void أطلق(
        نوع_ذعر نوع,
        const std::string& رسالة,
        const std::string& ملف = "",
        int سطر = 0) {
        
        معلومات_ذعر معلومات;
        معلومات.النوع = نوع;
        معلومات.الرسالة = رسالة;
        معلومات.الملف = ملف;
        معلومات.السطر = سطر;
        
        أطلق(معلومات);
    }
    
private:
    معالج_ذعر() = default;
    
    std::mutex m_قفل;
    std::vector<معالج> m_معالجات;
    
    /**
     * تحليل السبب المحتمل
     */
    void حلل_السبب(معلومات_ذعر& معلومات) {
        switch (معلومات.النوع) {
            case نوع_ذعر::فهرس_خارج_الحدود:
                معلومات.السبب_المحتمل = 
                    "محاولة الوصول لفهرس في مصفوفة أكبر من حجمها.";
                معلومات.الحل_المقترح = 
                    "تحقق من الفهرس قبل الوصول:\n"
                    "     إذا فهرس < مصفوفة.طول\n"
                    "         عنصر = مصفوفة[فهرس]\n"
                    "     نهاية";
                break;
                
            case نوع_ذعر::مؤشر_فارغ:
                معلومات.السبب_المحتمل = 
                    "محاولة استخدام قيمة فارغة (عدم).";
                معلومات.الحل_المقترح = 
                    "تحقق من القيمة قبل الاستخدام:\n"
                    "     إذا قيمة != عدم\n"
                    "         استخدم(قيمة)\n"
                    "     نهاية";
                break;
                
            case نوع_ذعر::قسمة_على_صفر:
                معلومات.السبب_المحتمل = 
                    "محاولة قسمة عدد على صفر.";
                معلومات.الحل_المقترح = 
                    "تحقق من المقسوم عليه:\n"
                    "     إذا ب != 0\n"
                    "         ناتج = أ / ب\n"
                    "     وإلا\n"
                    "         أرجع خطأ\n"
                    "     نهاية";
                break;
                
            case نوع_ذعر::تجاوز_المكدس:
                معلومات.السبب_المحتمل = 
                    "استدعاءات متكررة عميقة جداً أو تكرار لا نهائي.";
                معلومات.الحل_المقترح = 
                    "1. تأكد من وجود حالة إيقاف للتكرار\n"
                    "     2. حوِّل التكرار لحلقة\n"
                    "     3. زِد حجم المكدس";
                break;
                
            case نوع_ذعر::نفاد_الذاكرة:
                معلومات.السبب_المحتمل = 
                    "البرنامج استهلك كل الذاكرة المتاحة.";
                معلومات.الحل_المقترح = 
                    "1. قلل حجم البيانات\n"
                    "     2. حرر الذاكرة غير المستخدمة\n"
                    "     3. استخدم معالجة دفعية";
                break;
                
            default:
                // لا تحليل إضافي
                break;
        }
    }
};

