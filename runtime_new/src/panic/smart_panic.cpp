/**
 * إطار في المكدس
 */
struct إطار_مكدس {
    std::string الدالة;
    std::string الملف;
    int السطر = 0;
    std::unordered_map<std::string, std::string> المتغيرات_المحلية;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << الدالة << "()";
        if (!الملف.empty()) {
            ss << " في " << الملف << ":" << السطر;
        }
        return ss.str();
    }
};

/**
 * تتبع المكدس
 */
class تتبع_مكدس {
public:
    /**
     * الحصول على التتبع العالمي (per-thread)
     */
    static تتبع_مكدس& المثال() {
        thread_local تتبع_مكدس مثال;
        return مثال;
    }
    
    /**
     * دخول دالة
     */
    void ادخل(
        const std::string& اسم_الدالة,
        const std::string& الملف,
        int السطر) {
        
        إطار_مكدس إطار;
        إطار.الدالة = اسم_الدالة;
        إطار.الملف = الملف;
        إطار.السطر = السطر;
        
        m_إطارات.push_back(إطار);
    }
    
    /**
     * خروج من دالة
     */
    void اخرج() {
        if (!m_إطارات.empty()) {
            m_إطارات.pop_back();
        }
    }
    
    /**
     * تحديث السطر الحالي
     */
    void حدِّث_السطر(int سطر) {
        if (!m_إطارات.empty()) {
            m_إطارات.back().السطر = سطر;
        }
    }
    
    /**
     * إضافة متغير محلي
     */
    void أضف_متغير(const std::string& اسم, const std::string& قيمة) {
        if (!m_إطارات.empty()) {
            m_إطارات.back().المتغيرات_المحلية[اسم] = قيمة;
        }
    }
    
    /**
     * الحصول على كل الإطارات
     */
    std::vector<إطار_مكدس> الإطارات() const {
        return m_إطارات;
    }
    
    /**
     * الإطار الحالي
     */
    const إطار_مكدس* الإطار_الحالي() const {
        if (m_إطارات.empty()) return nullptr;
        return &m_إطارات.back();
    }
    
    /**
     * العمق
     */
    size_t العمق() const {
        return m_إطارات.size();
    }
    
private:
    std::vector<إطار_مكدس> m_إطارات;
};

