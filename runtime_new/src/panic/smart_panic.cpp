/**
 * معلومات ذعر كاملة
 */
struct معلومات_ذعر {
    // نوع الذعر ورسالته
    نوع_ذعر النوع = نوع_ذعر::غير_معروف;
    std::string الرسالة;
    
    // الموقع
    std::string الملف;
    int السطر = 0;
    int العمود = 0;
    std::string الكود;  // السطر الذي حدث فيه الذعر
    
    // السياق
    std::vector<إطار_مكدس> المكدس;
    std::vector<حدث_سجل> آخر_الأحداث;
    std::unordered_map<std::string, std::string> المتغيرات;
    
    // التحليل
    std::string السبب_المحتمل;
    std::string الحل_المقترح;
    
    // الوقت
    std::chrono::system_clock::time_point وقت_الحدوث;
    
    /**
     * توليد تقرير كامل
     */
    std::string تقرير_كامل() const {
        std::stringstream ss;
        
        // الترويسة
        ss << "\n"
           << "╔══════════════════════════════════════════════════════════════════╗\n"
           << "║  💥 ذعر: " << نوع_ذعر_إلى_نص(النوع);
        
        // إضافة مسافات للمحاذاة
        size_t طول = نوع_ذعر_إلى_نص(النوع).length();
        for (size_t i = طول; i < 50; i++) ss << " ";
        ss << "║\n"
           << "╠══════════════════════════════════════════════════════════════════╣\n";
        
        // الرسالة
        ss << "║  📝 " << الرسالة << "\n";
        
        // الموقع
        ss << "║\n"
           << "║  📍 الموقع: " << الملف << ":" << السطر;
        if (العمود > 0) ss << ":" << العمود;
        ss << "\n";
        
        // الكود
        if (!الكود.empty()) {
            ss << "║  📄 الكود: " << الكود << "\n";
        }
        
        ss << "╠══════════════════════════════════════════════════════════════════╣\n";
        
        // المتغيرات
        if (!المتغيرات.empty()) {
            ss << "║  📊 قيم المتغيرات:\n";
            for (const auto& [اسم, قيمة] : المتغيرات) {
                ss << "║     " << اسم << " = " << قيمة << "\n";
            }
            ss << "║\n";
        }
        
        // Stack trace
        if (!المكدس.empty()) {
            ss << "║  📚 تتبع المكدس:\n";
            for (size_t i = 0; i < المكدس.size(); i++) {
                ss << "║     " << (المكدس.size() - i) << ". " 
                   << المكدس[i].إلى_نص() << "\n";
            }
            ss << "║\n";
        }
        
        // آخر الأحداث
        if (!آخر_الأحداث.empty()) {
            ss << "║  📜 آخر العمليات:\n";
            for (size_t i = 0; i < آخر_الأحداث.size(); i++) {
                ss << "║     " << (i + 1) << ". " 
                   << آخر_الأحداث[i].إلى_نص() << "\n";
            }
            ss << "║\n";
        }
        
        ss << "╠══════════════════════════════════════════════════════════════════╣\n";
        
        // التحليل
        if (!السبب_المحتمل.empty()) {
            ss << "║  💭 السبب المحتمل:\n"
               << "║     " << السبب_المحتمل << "\n║\n";
        }
        
        if (!الحل_المقترح.empty()) {
            ss << "║  🔧 الحل المقترح:\n"
               << "║     " << الحل_المقترح << "\n";
        }
        
        ss << "╚══════════════════════════════════════════════════════════════════╝\n";
        
        return ss.str();
    }
    
    /**
     * تقرير مختصر
     */
    std::string تقرير_مختصر() const {
        std::stringstream ss;
        ss << "💥 ذعر: " << نوع_ذعر_إلى_نص(النوع) << " @ " << الملف << ":" << السطر;
        if (!الرسالة.empty()) {
            ss << " - " << الرسالة;
        }
        return ss.str();
    }
};

