/**
 * نوع الحدث في السجل
 */
enum class نوع_حدث {
    استدعاء_دالة,      // Function call
    إرجاع_من_دالة,     // Function return
    قراءة_متغير,       // Variable read
    كتابة_متغير,       // Variable write
    وصول_مصفوفة,       // Array access
    تخصيص_ذاكرة,       // Memory allocation
    تحرير_ذاكرة,       // Memory deallocation
    فتح_ملف,           // File open
    إغلاق_ملف,         // File close
    اتصال_شبكة,        // Network connection
    تنفيذ_شرط,         // Condition evaluation
    بداية_حلقة,        // Loop start
    نهاية_حلقة,        // Loop end
    أخرى,              // Other
};

/**
 * حدث في سجل العمليات
 */
struct حدث_سجل {
    نوع_حدث النوع;
    std::string الوصف;
    std::string الملف;
    int السطر = 0;
    std::string الدالة;
    std::chrono::steady_clock::time_point الوقت;
    std::unordered_map<std::string, std::string> بيانات_إضافية;
    
    std::string إلى_نص() const {
        std::stringstream ss;
        ss << "[" << نوع_حدث_إلى_نص(النوع) << "] " << الوصف;
        if (!الملف.empty()) {
            ss << " @ " << الملف << ":" << السطر;
        }
        return ss.str();
    }
    
    static std::string نوع_حدث_إلى_نص(نوع_حدث نوع) {
        switch (نوع) {
            case نوع_حدث::استدعاء_دالة: return "استدعاء";
            case نوع_حدث::إرجاع_من_دالة: return "إرجاع";
            case نوع_حدث::قراءة_متغير: return "قراءة";
            case نوع_حدث::كتابة_متغير: return "كتابة";
            case نوع_حدث::وصول_مصفوفة: return "مصفوفة";
            case نوع_حدث::تخصيص_ذاكرة: return "تخصيص";
            case نوع_حدث::تحرير_ذاكرة: return "تحرير";
            case نوع_حدث::فتح_ملف: return "فتح";
            case نوع_حدث::إغلاق_ملف: return "إغلاق";
            case نوع_حدث::اتصال_شبكة: return "شبكة";
            case نوع_حدث::تنفيذ_شرط: return "شرط";
            case نوع_حدث::بداية_حلقة: return "حلقة↓";
            case نوع_حدث::نهاية_حلقة: return "حلقة↑";
            default: return "أخرى";
        }
    }
};

/**
 * سجل العمليات
 */
class سجل_عمليات {
public:
    /**
     * الحصول على السجل العالمي
     */
    static سجل_عمليات& المثال() {
        static سجل_عمليات مثال;
        return مثال;
    }
    
    /**
     * تسجيل حدث
     */
    void سجِّل(حدث_سجل حدث) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        حدث.الوقت = std::chrono::steady_clock::now();
        
        if (m_أحداث.size() >= m_الحد_الأقصى) {
            m_أحداث.pop_front();
        }
        
        m_أحداث.push_back(std::move(حدث));
    }
    
    /**
     * تسجيل استدعاء دالة
     */
    void سجِّل_استدعاء(
        const std::string& اسم_الدالة,
        const std::string& الملف,
        int السطر) {
        
        سجِّل({
            نوع_حدث::استدعاء_دالة,
            "استدعاء " + اسم_الدالة + "()",
            الملف, السطر, اسم_الدالة
        });
    }
    
    /**
     * تسجيل وصول لمصفوفة
     */
    void سجِّل_وصول_مصفوفة(
        const std::string& اسم_المصفوفة,
        size_t الفهرس,
        const std::string& الملف,
        int السطر) {
        
        حدث_سجل حدث;
        حدث.النوع = نوع_حدث::وصول_مصفوفة;
        حدث.الوصف = اسم_المصفوفة + "[" + std::to_string(الفهرس) + "]";
        حدث.الملف = الملف;
        حدث.السطر = السطر;
        حدث.بيانات_إضافية["فهرس"] = std::to_string(الفهرس);
        
        سجِّل(حدث);
    }
    
    /**
     * تسجيل كتابة متغير
     */
    void سجِّل_كتابة(
        const std::string& اسم_المتغير,
        const std::string& القيمة,
        const std::string& الملف,
        int السطر) {
        
        حدث_سجل حدث;
        حدث.النوع = نوع_حدث::كتابة_متغير;
        حدث.الوصف = اسم_المتغير + " = " + القيمة;
        حدث.الملف = الملف;
        حدث.السطر = السطر;
        حدث.بيانات_إضافية["متغير"] = اسم_المتغير;
        حدث.بيانات_إضافية["قيمة"] = القيمة;
        
        سجِّل(حدث);
    }
    
    /**
     * الحصول على آخر n حدث
     */
    std::vector<حدث_سجل> آخر_أحداث(size_t عدد = 10) const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        std::vector<حدث_سجل> نتيجة;
        
        size_t بداية = m_أحداث.size() > عدد ? m_أحداث.size() - عدد : 0;
        for (size_t i = بداية; i < m_أحداث.size(); i++) {
            نتيجة.push_back(m_أحداث[i]);
        }
        
        return نتيجة;
    }
    
    /**
     * مسح السجل
     */
    void امسح() {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_أحداث.clear();
    }
    
    /**
     * تعيين الحد الأقصى
     */
    void عيِّن_الحد(size_t حد) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_الحد_الأقصى = حد;
    }
    
private:
    سجل_عمليات() = default;
    
    mutable std::mutex m_قفل;
    std::deque<حدث_سجل> m_أحداث;
    size_t m_الحد_الأقصى = 100;
};

