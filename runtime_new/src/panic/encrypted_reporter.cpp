/**
 * مستوى الخصوصية
 */
enum class مستوى_خصوصية {
    كامل,        // أرسل كل شيء
    معتدل,       // أخفِ المعلومات الحساسة
    أدنى,        // معلومات أساسية فقط
    بدون_بيانات, // لا ترسل أي بيانات شخصية
};

/**
 * بيانات تقرير الذعر
 */
struct تقرير_ذعر {
    // معرف فريد
    std::string المعرف;
    
    // معلومات الذعر
    std::string نوع_الذعر;
    std::string الرسالة;
    std::string الملف;
    int السطر = 0;
    std::string الكود;
    
    // السياق
    std::vector<std::string> المكدس;
    std::vector<std::string> آخر_الأحداث;
    std::unordered_map<std::string, std::string> المتغيرات;
    
    // معلومات النظام
    std::string نظام_التشغيل;
    std::string إصدار_اللغة;
    std::string الهندسة;  // x86_64, ARM, etc.
    
    // الوقت
    std::string وقت_الحدوث;
    
    // البيانات المُخفاة
    bool تم_إخفاء_بيانات = false;
    std::vector<std::string> البيانات_المُخفاة;
    
    /**
     * تحويل إلى JSON
     */
    std::string إلى_JSON() const {
        std::stringstream ss;
        
        ss << "{\n";
        ss << "  \"id\": \"" << المعرف << "\",\n";
        ss << "  \"type\": \"" << نوع_الذعر << "\",\n";
        ss << "  \"message\": \"" << escape_json(الرسالة) << "\",\n";
        ss << "  \"file\": \"" << escape_json(الملف) << "\",\n";
        ss << "  \"line\": " << السطر << ",\n";
        ss << "  \"code\": \"" << escape_json(الكود) << "\",\n";
        
        // المكدس
        ss << "  \"stack\": [\n";
        for (size_t i = 0; i < المكدس.size(); i++) {
            ss << "    \"" << escape_json(المكدس[i]) << "\"";
            if (i < المكدس.size() - 1) ss << ",";
            ss << "\n";
        }
        ss << "  ],\n";
        
        // المتغيرات
        ss << "  \"variables\": {\n";
        size_t count = 0;
        for (const auto& [اسم, قيمة] : المتغيرات) {
            ss << "    \"" << escape_json(اسم) << "\": \"" << escape_json(قيمة) << "\"";
            if (++count < المتغيرات.size()) ss << ",";
            ss << "\n";
        }
        ss << "  },\n";
        
        // معلومات النظام
        ss << "  \"system\": {\n";
        ss << "    \"os\": \"" << نظام_التشغيل << "\",\n";
        ss << "    \"lang_version\": \"" << إصدار_اللغة << "\",\n";
        ss << "    \"arch\": \"" << الهندسة << "\"\n";
        ss << "  },\n";
        
        ss << "  \"timestamp\": \"" << وقت_الحدوث << "\",\n";
        ss << "  \"redacted\": " << (تم_إخفاء_بيانات ? "true" : "false") << "\n";
        ss << "}\n";
        
        return ss.str();
    }
    
private:
    static std::string escape_json(const std::string& نص) {
        std::string نتيجة;
        for (char c : نص) {
            switch (c) {
                case '"': نتيجة += "\\\""; break;
                case '\\': نتيجة += "\\\\"; break;
                case '\n': نتيجة += "\\n"; break;
                case '\r': نتيجة += "\\r"; break;
                case '\t': نتيجة += "\\t"; break;
                default: نتيجة += c;
            }
        }
        return نتيجة;
    }
};

