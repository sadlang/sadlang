/**
 * مُنقِّي البيانات الحساسة
 */
class مُنقِّي_بيانات {
public:
    /**
     * إضافة نمط للإخفاء
     */
    void أضف_نمط(const std::string& نمط, const std::string& بديل = "[مخفي]") {
        m_أنماط[نمط] = بديل;
    }
    
    /**
     * إخفاء البيانات الحساسة من نص
     */
    std::string نقِّ(const std::string& نص) const {
        std::string نتيجة = نص;
        
        // إخفاء أنماط معروفة
        for (const auto& [نمط, بديل] : m_أنماط) {
            size_t pos = 0;
            while ((pos = نتيجة.find(نمط, pos)) != std::string::npos) {
                نتيجة.replace(pos, نمط.length(), بديل);
                pos += بديل.length();
            }
        }
        
        // إخفاء أنماط شائعة
        نتيجة = أخفِ_كلمات_مرور(نتيجة);
        نتيجة = أخفِ_مسارات_منزل(نتيجة);
        نتيجة = أخفِ_بريد_إلكتروني(نتيجة);
        نتيجة = أخفِ_عناوين_IP(نتيجة);
        
        return نتيجة;
    }
    
    /**
     * الأنماط الافتراضية للإخفاء
     */
    static مُنقِّي_بيانات الافتراضي() {
        مُنقِّي_بيانات منقي;
        
        // كلمات حساسة
        منقي.أضف_نمط("password", "[كلمة_مرور]");
        منقي.أضف_نمط("secret", "[سر]");
        منقي.أضف_نمط("token", "[رمز]");
        منقي.أضف_نمط("api_key", "[مفتاح_API]");
        منقي.أضف_نمط("كلمة_مرور", "[مخفي]");
        منقي.أضف_نمط("رمز_سري", "[مخفي]");
        
        return منقي;
    }
    
private:
    std::unordered_map<std::string, std::string> m_أنماط;
    
    /**
     * إخفاء ما يشبه كلمات المرور
     */
    std::string أخفِ_كلمات_مرور(const std::string& نص) const {
        // بسيط: ابحث عن أنماط مثل password=... أو password: ...
        // في التنفيذ الحقيقي، استخدم regex
        return نص;
    }
    
    /**
     * إخفاء مسارات المنزل
     */
    std::string أخفِ_مسارات_منزل(const std::string& نص) const {
        std::string نتيجة = نص;
        
        // Windows
        size_t pos = 0;
        while ((pos = نتيجة.find("C:\\Users\\", pos)) != std::string::npos) {
            size_t end = نتيجة.find('\\', pos + 9);
            if (end != std::string::npos) {
                نتيجة.replace(pos, end - pos, "C:\\Users\\[مستخدم]");
            }
            pos += 15;
        }
        
        // Linux/Mac
        pos = 0;
        while ((pos = نتيجة.find("/home/", pos)) != std::string::npos) {
            size_t end = نتيجة.find('/', pos + 6);
            if (end != std::string::npos) {
                نتيجة.replace(pos, end - pos, "/home/[مستخدم]");
            }
            pos += 14;
        }
        
        return نتيجة;
    }
    
    /**
     * إخفاء عناوين البريد الإلكتروني
     */
    std::string أخفِ_بريد_إلكتروني(const std::string& نص) const {
        // تنفيذ بسيط - في الحقيقة استخدم regex
        return نص;
    }
    
    /**
     * إخفاء عناوين IP
     */
    std::string أخفِ_عناوين_IP(const std::string& نص) const {
        // تنفيذ بسيط - في الحقيقة استخدم regex
        return نص;
    }
};

