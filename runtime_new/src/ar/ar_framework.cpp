// ============== C API ==============

extern "C" {

using namespace ص::واقع::معزز;

static مدير_جلسة_AR* جلسة_AR_عامة = nullptr;

int sad_ar_init() {
    if (!جلسة_AR_عامة) {
        جلسة_AR_عامة = new مدير_جلسة_AR();
    }
    return جلسة_AR_عامة->تهيئة() ? 1 : 0;
}

void sad_ar_shutdown() {
    if (جلسة_AR_عامة) {
        جلسة_AR_عامة->إيقاف();
        delete جلسة_AR_عامة;
        جلسة_AR_عامة = nullptr;
    }
}

void sad_ar_update() {
    if (جلسة_AR_عامة) {
        جلسة_AR_عامة->تحديث();
    }
}

int sad_ar_get_plane_count() {
    if (!جلسة_AR_عامة) return 0;
    return static_cast<int>(جلسة_AR_عامة->الأسطح().size());
}

uint64_t sad_ar_create_anchor(float x, float y, float z) {
    if (!جلسة_AR_عامة) return 0;
    تحويل ت;
    ت.الموضع = {x, y, z};
    return جلسة_AR_عامة->إنشاء_مرساة(ت);
}

int sad_ar_hit_test(float ox, float oy, float oz, 
                    float dx, float dy, float dz,
                    float* hx, float* hy, float* hz) {
    if (!جلسة_AR_عامة) return 0;
    
    auto نتيجة = جلسة_AR_عامة->اختبار_شعاع({ox, oy, oz}, {dx, dy, dz});
    
    if (نتيجة.أصاب) {
        *hx = نتيجة.نقطة_التصادم.س;
        *hy = نتيجة.نقطة_التصادم.ص;
        *hz = نتيجة.نقطة_التصادم.ع;
        return 1;
    }
    
    return 0;
}

}  // extern "C"
