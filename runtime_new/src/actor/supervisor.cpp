extern "C" {

using namespace sad::runtime::actor;

// المشرف
void* sad_supervisor_create(const char* id) {
    return new مشرف(id);
}

void sad_supervisor_destroy(void* sup) {
    delete static_cast<مشرف*>(sup);
}

int sad_supervisor_start(void* sup) {
    return static_cast<مشرف*>(sup)->ابدأ() ? 1 : 0;
}

void sad_supervisor_stop(void* sup) {
    static_cast<مشرف*>(sup)->أوقف();
}

void sad_supervisor_handle_failure(void* sup, const char* child_id) {
    static_cast<مشرف*>(sup)->عالج_فشل(child_id);
}

int sad_supervisor_child_count(void* sup) {
    return static_cast<int>(static_cast<مشرف*>(sup)->عدد_الأبناء());
}

int sad_supervisor_restart_count(void* sup) {
    return static_cast<مشرف*>(sup)->إجمالي_إعادات_التشغيل();
}

// شجرة الإشراف
void* sad_supervision_tree_create() {
    return new بنّاء_شجرة_إشراف();
}

void sad_supervision_tree_destroy(void* tree) {
    delete static_cast<بنّاء_شجرة_إشراف*>(tree);
}

} // extern "C"
