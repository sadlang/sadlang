// ============== C API ==============

extern "C" {

using namespace ص::موزع;

static مدير_مراجع_موزعة* مدير_المراجع_العام = nullptr;
static جامع_قمامة_موزع* الجامع_العام = nullptr;

void sad_dist_gc_init(const char* معرف_عقدة) {
    if (!مدير_المراجع_العام) {
        مدير_المراجع_العام = new مدير_مراجع_موزعة(معرف_عقدة);
        الجامع_العام = new جامع_قمامة_موزع(*مدير_المراجع_العام);
    }
}

void sad_dist_gc_cleanup() {
    delete الجامع_العام;
    delete مدير_المراجع_العام;
    الجامع_العام = nullptr;
    مدير_المراجع_العام = nullptr;
}

uint64_t sad_dist_gc_create_object(size_t حجم) {
    if (!مدير_المراجع_العام) return 0;
    
    auto معرف = مدير_المراجع_العام->إنشاء_كائن(حجم);
    return معرف.المحلي;
}

void sad_dist_gc_add_local_ref(uint64_t معرف_محلي) {
    if (!مدير_المراجع_العام) return;
    
    معرف_كائن_موزع معرف;
    معرف.المحلي = معرف_محلي;
    
    مدير_المراجع_العام->إضافة_مرجع_محلي(معرف);
}

void sad_dist_gc_remove_local_ref(uint64_t معرف_محلي) {
    if (!مدير_المراجع_العام) return;
    
    معرف_كائن_موزع معرف;
    معرف.المحلي = معرف_محلي;
    
    مدير_المراجع_العام->إزالة_مرجع_محلي(معرف);
}

uint64_t sad_dist_gc_collect() {
    if (!الجامع_العام) return 0;
    return الجامع_العام->جمع();
}

size_t sad_dist_gc_object_count() {
    if (!مدير_المراجع_العام) return 0;
    return مدير_المراجع_العام->عدد_الكائنات();
}

}  // extern "C"
