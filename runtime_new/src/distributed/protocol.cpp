// ============== C API ==============

extern "C" {

using namespace ص::موزع;

// مدير العقد العام
static مدير_عقد* المدير_العام = nullptr;
static معالج_بروتوكول* المعالج_العام = nullptr;

void sad_distributed_init(const char* مضيف, int منفذ) {
    if (!المدير_العام) {
        المدير_العام = new مدير_عقد();
        المعالج_العام = new معالج_بروتوكول();
        
        عنوان_عقدة عنوان;
        عنوان.المضيف = مضيف;
        عنوان.المنفذ = منفذ;
        
        المدير_العام->تعيين_العقدة_المحلية(عنوان);
        المعالج_العام->تعيين_العنوان(عنوان);
    }
}

void sad_distributed_cleanup() {
    delete المدير_العام;
    delete المعالج_العام;
    المدير_العام = nullptr;
    المعالج_العام = nullptr;
}

int sad_distributed_add_node(const char* مضيف, int منفذ) {
    if (!المدير_العام) return 0;
    
    عنوان_عقدة عنوان;
    عنوان.المضيف = مضيف;
    عنوان.المنفذ = منفذ;
    
    return المدير_العام->إضافة_عقدة(عنوان) ? 1 : 0;
}

int sad_distributed_active_nodes() {
    if (!المدير_العام) return 0;
    return المدير_العام->عدد_العقد_النشطة();
}

}  // extern "C"
