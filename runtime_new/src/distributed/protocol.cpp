// ============== أنواع البروتوكول ==============

/**
 * نوع الرسالة
 */
enum class نوع_رسالة : uint8_t {
    // إدارة العقد
    انضمام = 0x01,
    مغادرة = 0x02,
    نبضة_قلب = 0x03,
    
    // الذاكرة
    قراءة = 0x10,
    كتابة = 0x11,
    حذف = 0x12,
    قفل = 0x13,
    فك_قفل = 0x14,
    
    // النسخ
    نسخ = 0x20,
    مزامنة = 0x21,
    تحقق = 0x22,
    
    // الاتساق
    تصويت = 0x30,
    التزام = 0x31,
    تراجع = 0x32,
    
    // الاستجابة
    نجاح = 0xF0,
    فشل = 0xF1,
    إعادة_توجيه = 0xF2
};

/**
 * مستوى الاتساق
 */
enum class مستوى_اتساق {
    ضعيف,          // Eventual consistency
    سببي,          // Causal consistency  
    متسلسل,        // Sequential consistency
    خطي,           // Linearizability
    قوي            // Strong consistency (Paxos/Raft)
};

/**
 * استراتيجية التوزيع
 */
enum class استراتيجية_توزيع {
    تجزئة,          // Hash-based
    نطاق,           // Range-based
    جغرافي,         // Geo-based
    موجه            // Directory-based
};

// ============== عنوان العقدة ==============

/**
 * عنوان عقدة في الشبكة
 */
struct عنوان_عقدة {
    std::string المضيف;
    uint16_t المنفذ = 0;
    std::string المنطقة;    // للتوزيع الجغرافي
    
    std::string إلى_نص() const {
        return المضيف + ":" + std::to_string(المنفذ);
    }
    
    bool operator==(const عنوان_عقدة& أخر) const {
        return المضيف == أخر.المضيف && المنفذ == أخر.المنفذ;
    }
    
    bool operator<(const عنوان_عقدة& أخر) const {
        if (المضيف != أخر.المضيف) return المضيف < أخر.المضيف;
        return المنفذ < أخر.المنفذ;
    }
};

// ============== معرف الكائن ==============

/**
 * معرف كائن موزع
 */
struct معرف_كائن {
    uint64_t الجزء_الأول = 0;   // UUID part 1
    uint64_t الجزء_الثاني = 0;  // UUID part 2
    
    static معرف_كائن توليد() {
        معرف_كائن م;
        // تبسيط - استخدام الوقت
        m.الجزء_الأول = static_cast<uint64_t>(time(nullptr));
        m.الجزء_الثاني = static_cast<uint64_t>(rand()) << 32 | rand();
        return م;
    }
    
    std::string إلى_نص() const {
        char buffer[40];
        snprintf(buffer, 40, "%016llx-%016llx", 
                 static_cast<unsigned long long>(الجزء_الأول),
                 static_cast<unsigned long long>(الجزء_الثاني));
        return buffer;
    }
    
    bool operator==(const معرف_كائن& أخر) const {
        return الجزء_الأول == أخر.الجزء_الأول && 
               الجزء_الثاني == أخر.الجزء_الثاني;
    }
    
    bool operator<(const معرف_كائن& أخر) const {
        if (الجزء_الأول != أخر.الجزء_الأول) 
            return الجزء_الأول < أخر.الجزء_الأول;
        return الجزء_الثاني < أخر.الجزء_الثاني;
    }
};

// ============== الرسالة ==============

/**
 * رسالة البروتوكول
 */
struct رسالة_بروتوكول {
    // الترويسة
    uint32_t الإصدار = 1;
    نوع_رسالة النوع;
    uint64_t معرف_الطلب = 0;
    
    // المصدر والوجهة
    عنوان_عقدة المصدر;
    عنوان_عقدة الوجهة;
    
    // البيانات
    معرف_كائن معرف_الكائن;
    std::vector<uint8_t> البيانات;
    
    // الاتساق
    مستوى_اتساق الاتساق = مستوى_اتساق::سببي;
    uint64_t الطابع_الزمني = 0;
    uint64_t الإصدار_المنطقي = 0;
    
    // TTL
    uint8_t عدد_القفزات = 10;
    
    // تسلسل
    std::vector<uint8_t> تسلسل() const {
        std::vector<uint8_t> نتيجة;
        
        // الإصدار (4 bytes)
        نتيجة.push_back(الإصدار >> 24);
        نتيجة.push_back(الإصدار >> 16);
        نتيجة.push_back(الإصدار >> 8);
        نتيجة.push_back(الإصدار);
        
        // النوع (1 byte)
        نتيجة.push_back(static_cast<uint8_t>(النوع));
        
        // معرف الطلب (8 bytes)
        for (int i = 7; i >= 0; i--) {
            نتيجة.push_back(معرف_الطلب >> (i * 8));
        }
        
        // طول البيانات (4 bytes)
        uint32_t طول = البيانات.size();
        نتيجة.push_back(طول >> 24);
        نتيجة.push_back(طول >> 16);
        نتيجة.push_back(طول >> 8);
        نتيجة.push_back(طول);
        
        // البيانات
        نتيجة.insert(نتيجة.end(), البيانات.begin(), البيانات.end());
        
        return نتيجة;
    }
};

// ============== حالة العقدة ==============

/**
 * حالة عقدة في الشبكة
 */
struct حالة_عقدة {
    عنوان_عقدة العنوان;
    
    bool نشطة = false;
    uint64_t آخر_نبضة = 0;
    
    // الإحصائيات
    uint64_t الذاكرة_المستخدمة = 0;
    uint64_t الذاكرة_الكلية = 0;
    uint32_t عدد_الكائنات = 0;
    
    // الأداء
    double زمن_الاستجابة = 0.0;  // بالمللي ثانية
    uint64_t الطلبات_المعالجة = 0;
};

// ============== معالج البروتوكول ==============

/**
 * معالج رسائل البروتوكول
 */
class معالج_بروتوكول {
public:
    using معالج_رسالة = std::function<رسالة_بروتوكول(const رسالة_بروتوكول&)>;
    
private:
    std::map<نوع_رسالة, معالج_رسالة> المعالجات_;
    عنوان_عقدة عنوان_محلي_;
    std::atomic<uint64_t> عداد_الطلبات_{0};
    
public:
    void تعيين_العنوان(const عنوان_عقدة& عنوان) {
        عنوان_محلي_ = عنوان;
    }
    
    void تسجيل_معالج(نوع_رسالة النوع, معالج_رسالة المعالج) {
        المعالجات_[النوع] = المعالج;
    }
    
    رسالة_بروتوكول معالجة(const رسالة_بروتوكول& رسالة) {
        auto it = المعالجات_.find(رسالة.النوع);
        
        if (it == المعالجات_.end()) {
            // لا يوجد معالج
            رسالة_بروتوكول استجابة;
            استجابة.النوع = نوع_رسالة::فشل;
            استجابة.معرف_الطلب = رسالة.معرف_الطلب;
            return استجابة;
        }
        
        return it->second(رسالة);
    }
    
    رسالة_بروتوكول إنشاء_طلب(نوع_رسالة النوع,
                               const عنوان_عقدة& الوجهة) {
        رسالة_بروتوكول رسالة;
        رسالة.النوع = النوع;
        رسالة.المصدر = عنوان_محلي_;
        رسالة.الوجهة = الوجهة;
        رسالة.معرف_الطلب = ++عداد_الطلبات_;
        رسالة.الطابع_الزمني = static_cast<uint64_t>(time(nullptr));
        
        return رسالة;
    }
    
    رسالة_بروتوكول إنشاء_استجابة(const رسالة_بروتوكول& الطلب,
                                   bool نجاح) {
        رسالة_بروتوكول رسالة;
        رسالة.النوع = نجاح ? نوع_رسالة::نجاح : نوع_رسالة::فشل;
        رسالة.المصدر = عنوان_محلي_;
        رسالة.الوجهة = الطلب.المصدر;
        رسالة.معرف_الطلب = الطلب.معرف_الطلب;
        رسالة.الطابع_الزمني = static_cast<uint64_t>(time(nullptr));
        
        return رسالة;
    }
};

// ============== إدارة العقد ==============

/**
 * مدير العقد في الشبكة
 */
class مدير_عقد {
private:
    std::map<عنوان_عقدة, حالة_عقدة> العقد_;
    عنوان_عقدة العقدة_المحلية_;
    std::mutex قفل_;
    
    // اكتشاف الأعطال
    uint64_t مهلة_نبضة_ = 10;  // ثواني
    
public:
    void تعيين_العقدة_المحلية(const عنوان_عقدة& عنوان) {
        العقدة_المحلية_ = عنوان;
    }
    
    bool إضافة_عقدة(const عنوان_عقدة& عنوان) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        if (العقد_.find(عنوان) != العقد_.end()) {
            return false;  // موجودة
        }
        
        حالة_عقدة حالة;
        حالة.العنوان = عنوان;
        حالة.نشطة = true;
        حالة.آخر_نبضة = static_cast<uint64_t>(time(nullptr));
        
        العقد_[عنوان] = حالة;
        return true;
    }
    
    bool إزالة_عقدة(const عنوان_عقدة& عنوان) {
        std::lock_guard<std::mutex> قفل(قفل_);
        return العقد_.erase(عنوان) > 0;
    }
    
    void تحديث_نبضة(const عنوان_عقدة& عنوان) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        auto it = العقد_.find(عنوان);
        if (it != العقد_.end()) {
            it->second.آخر_نبضة = static_cast<uint64_t>(time(nullptr));
            it->second.نشطة = true;
        }
    }
    
    std::vector<عنوان_عقدة> العقد_النشطة() const {
        std::vector<عنوان_عقدة> نتيجة;
        
        uint64_t الآن = static_cast<uint64_t>(time(nullptr));
        
        for (const auto& [عنوان, حالة] : العقد_) {
            if (حالة.نشطة && (الآن - حالة.آخر_نبضة) < مهلة_نبضة_) {
                نتيجة.push_back(عنوان);
            }
        }
        
        return نتيجة;
    }
    
    std::vector<عنوان_عقدة> اكتشاف_أعطال() {
        std::lock_guard<std::mutex> قفل(قفل_);
        std::vector<عنوان_عقدة> معطلة;
        
        uint64_t الآن = static_cast<uint64_t>(time(nullptr));
        
        for (auto& [عنوان, حالة] : العقد_) {
            if (حالة.نشطة && (الآن - حالة.آخر_نبضة) >= مهلة_نبضة_) {
                حالة.نشطة = false;
                معطلة.push_back(عنوان);
            }
        }
        
        return معطلة;
    }
    
    int عدد_العقد_النشطة() const {
        int عدد = 0;
        
        uint64_t الآن = static_cast<uint64_t>(time(nullptr));
        
        for (const auto& [_, حالة] : العقد_) {
            if (حالة.نشطة && (الآن - حالة.آخر_نبضة) < مهلة_نبضة_) {
                عدد++;
            }
        }
        
        return عدد;
    }
};

