// ============== أنواع الأعطال ==============

/**
 * نوع العطل
 */
enum class نوع_عطل {
    شبكة,            // Network failure
    عقدة,            // Node failure
    قرص,             // Disk failure
    ذاكرة,           // Memory failure
    مهلة,            // Timeout
    بيانات_تالفة,    // Data corruption
    عدم_اتساق        // Inconsistency
};

/**
 * شدة العطل
 */
enum class شدة_عطل {
    تحذير,           // Warning - recoverable
    خطأ,             // Error - needs attention
    حرج,             // Critical - immediate action
    كارثي            // Catastrophic - system down
};

/**
 * حالة التعافي
 */
enum class حالة_تعافي {
    لم_يبدأ,
    قيد_التنفيذ,
    ناجح,
    فاشل,
    مؤجل
};

/**
 * استراتيجية إعادة المحاولة
 */
enum class استراتيجية_إعادة {
    خطية,            // Linear backoff
    أسية,            // Exponential backoff
    فورية,           // Immediate retry
    عشوائية,         // Random jitter
    مخصصة            // Custom
};

// ============== هياكل البيانات ==============

/**
 * سجل العطل
 */
struct سجل_عطل {
    uint64_t المعرف = 0;
    نوع_عطل النوع;
    شدة_عطل الشدة;
    std::string المصدر;
    std::string الوصف;
    uint64_t الوقت = 0;
    حالة_تعافي حالة_التعافي = حالة_تعافي::لم_يبدأ;
    int محاولات_التعافي = 0;
};

/**
 * نقطة حفظ
 */
struct نقطة_حفظ {
    uint64_t المعرف = 0;
    std::string الاسم;
    uint64_t الوقت = 0;
    std::vector<uint8_t> البيانات;
    std::map<std::string, std::string> البيانات_الوصفية;
    bool صالحة = true;
};

/**
 * تكوين إعادة المحاولة
 */
struct تكوين_إعادة {
    استراتيجية_إعادة الاستراتيجية = استراتيجية_إعادة::أسية;
    int الحد_الأقصى = 5;
    uint64_t التأخير_الأساسي_مللي = 100;
    uint64_t الحد_الأقصى_للتأخير_مللي = 30000;
    double عامل_التضاعف = 2.0;
    double نسبة_الارتعاش = 0.1;  // Jitter
};

// ============== كاشف الأعطال ==============

/**
 * كاشف الأعطال
 */
class كاشف_أعطال {
private:
    std::vector<سجل_عطل> سجل_الأعطال_;
    std::atomic<uint64_t> عداد_الأعطال_{0};
    
    // عتبات الكشف
    std::map<نوع_عطل, int> عتبات_التحذير_;
    std::map<نوع_عطل, int> عدادات_الأعطال_;
    
    std::mutex قفل_;
    
    // معالجات الأحداث
    std::function<void(const سجل_عطل&)> معالج_عطل_;
    
public:
    كاشف_أعطال() {
        // عتبات افتراضية
        عتبات_التحذير_[نوع_عطل::شبكة] = 3;
        عتبات_التحذير_[نوع_عطل::عقدة] = 2;
        عتبات_التحذير_[نوع_عطل::مهلة] = 5;
    }
    
    // ============== التكوين ==============
    
    void تعيين_عتبة(نوع_عطل نوع, int عتبة) {
        std::lock_guard<std::mutex> قفل(قفل_);
        عتبات_التحذير_[نوع] = عتبة;
    }
    
    void تعيين_معالج(std::function<void(const سجل_عطل&)> معالج) {
        معالج_عطل_ = معالج;
    }
    
    // ============== تسجيل الأعطال ==============
    
    uint64_t تسجيل_عطل(نوع_عطل نوع, شدة_عطل شدة,
                        const std::string& مصدر,
                        const std::string& وصف) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        سجل_عطل سجل;
        سجل.المعرف = ++عداد_الأعطال_;
        سجل.النوع = نوع;
        سجل.الشدة = شدة;
        سجل.المصدر = مصدر;
        سجل.الوصف = وصف;
        سجل.الوقت = static_cast<uint64_t>(time(nullptr));
        
        سجل_الأعطال_.push_back(سجل);
        عدادات_الأعطال_[نوع]++;
        
        // فحص العتبة
        if (عدادات_الأعطال_[نوع] >= عتبات_التحذير_[نوع]) {
            if (معالج_عطل_) {
                معالج_عطل_(سجل);
            }
        }
        
        return سجل.المعرف;
    }
    
    // ============== الاستعلام ==============
    
    std::vector<سجل_عطل> الأعطال_الأخيرة(int عدد = 10) const {
        std::vector<سجل_عطل> نتيجة;
        
        size_t بداية = سجل_الأعطال_.size() > static_cast<size_t>(عدد)
            ? سجل_الأعطال_.size() - عدد
            : 0;
        
        for (size_t i = بداية; i < سجل_الأعطال_.size(); i++) {
            نتيجة.push_back(سجل_الأعطال_[i]);
        }
        
        return نتيجة;
    }
    
    int عدد_الأعطال(نوع_عطل نوع) const {
        auto it = عدادات_الأعطال_.find(نوع);
        return it != عدادات_الأعطال_.end() ? it->second : 0;
    }
    
    void إعادة_تعيين_العدادات() {
        std::lock_guard<std::mutex> قفل(قفل_);
        عدادات_الأعطال_.clear();
    }
};

// ============== مدير نقاط الحفظ ==============

/**
 * مدير نقاط الحفظ (Checkpoint Manager)
 */
class مدير_نقاط_حفظ {
private:
    std::vector<نقطة_حفظ> نقاط_الحفظ_;
    std::atomic<uint64_t> عداد_النقاط_{0};
    
    size_t الحد_الأقصى_للنقاط_ = 10;
    
    std::mutex قفل_;
    
public:
    void تعيين_الحد_الأقصى(size_t حد) { الحد_الأقصى_للنقاط_ = حد; }
    
    // ============== إنشاء نقاط الحفظ ==============
    
    uint64_t إنشاء_نقطة(const std::string& اسم,
                         const std::vector<uint8_t>& بيانات) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        نقطة_حفظ نقطة;
        نقطة.المعرف = ++عداد_النقاط_;
        نقطة.الاسم = اسم;
        نقطة.الوقت = static_cast<uint64_t>(time(nullptr));
        نقطة.البيانات = بيانات;
        نقطة.صالحة = true;
        
        نقاط_الحفظ_.push_back(نقطة);
        
        // تنظيف النقاط القديمة
        while (نقاط_الحفظ_.size() > الحد_الأقصى_للنقاط_) {
            نقاط_الحفظ_.erase(نقاط_الحفظ_.begin());
        }
        
        return نقطة.المعرف;
    }
    
    // ============== الاسترجاع ==============
    
    bool استرجاع(uint64_t معرف, std::vector<uint8_t>& بيانات) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        for (const auto& نقطة : نقاط_الحفظ_) {
            if (نقطة.المعرف == معرف && نقطة.صالحة) {
                بيانات = نقطة.البيانات;
                return true;
            }
        }
        
        return false;
    }
    
    bool استرجاع_آخر(std::vector<uint8_t>& بيانات) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        for (auto it = نقاط_الحفظ_.rbegin(); it != نقاط_الحفظ_.rend(); ++it) {
            if (it->صالحة) {
                بيانات = it->البيانات;
                return true;
            }
        }
        
        return false;
    }
    
    // ============== الإدارة ==============
    
    void إبطال(uint64_t معرف) {
        std::lock_guard<std::mutex> قفل(قفل_);
        
        for (auto& نقطة : نقاط_الحفظ_) {
            if (نقطة.المعرف == معرف) {
                نقطة.صالحة = false;
                break;
            }
        }
    }
    
    size_t عدد_النقاط_الصالحة() const {
        size_t عدد = 0;
        for (const auto& نقطة : نقاط_الحفظ_) {
            if (نقطة.صالحة) عدد++;
        }
        return عدد;
    }
};

// ============== مدير إعادة المحاولة ==============

/**
 * مدير إعادة المحاولة مع Backoff
 */
class مدير_إعادة_محاولة {
private:
    تكوين_إعادة التكوين_;
    std::random_device rd_;
    std::mt19937 مولد_;
    
public:
    مدير_إعادة_محاولة() : مولد_(rd_()) {}
    
    void تعيين_تكوين(const تكوين_إعادة& تكوين) {
        التكوين_ = تكوين;
    }
    
    // ============== حساب التأخير ==============
    
    uint64_t حساب_التأخير(int رقم_المحاولة) {
        uint64_t تأخير = 0;
        
        switch (التكوين_.الاستراتيجية) {
            case استراتيجية_إعادة::فورية:
                تأخير = 0;
                break;
                
            case استراتيجية_إعادة::خطية:
                تأخير = التكوين_.التأخير_الأساسي_مللي * رقم_المحاولة;
                break;
                
            case استراتيجية_إعادة::أسية:
                تأخير = static_cast<uint64_t>(
                    التكوين_.التأخير_الأساسي_مللي *
                    std::pow(التكوين_.عامل_التضاعف, رقم_المحاولة - 1)
                );
                break;
                
            case استراتيجية_إعادة::عشوائية:
                تأخير = حساب_تأخير_عشوائي(رقم_المحاولة);
                break;
                
            case استراتيجية_إعادة::مخصصة:
                تأخير = التكوين_.التأخير_الأساسي_مللي;
                break;
        }
        
        // إضافة الارتعاش
        تأخير = إضافة_ارتعاش(تأخير);
        
        // تطبيق الحد الأقصى
        return std::min(تأخير, التكوين_.الحد_الأقصى_للتأخير_مللي);
    }
    
    bool يمكن_الإعادة(int رقم_المحاولة) const {
        return رقم_المحاولة < التكوين_.الحد_الأقصى;
    }
    
    // ============== تنفيذ مع إعادة المحاولة ==============
    
    template<typename Func>
    bool نفذ_مع_إعادة(Func&& عملية, int& المحاولات) {
        المحاولات = 0;
        
        while (يمكن_الإعادة(المحاولات)) {
            المحاولات++;
            
            try {
                if (عملية()) {
                    return true;
                }
            } catch (...) {
                // استمر في الإعادة
            }
            
            if (يمكن_الإعادة(المحاولات)) {
                uint64_t تأخير = حساب_التأخير(المحاولات);
                // في الإنتاج: std::this_thread::sleep_for
                (void)تأخير;
            }
        }
        
        return false;
    }
    
private:
    uint64_t حساب_تأخير_عشوائي(int محاولة) {
        std::uniform_int_distribution<uint64_t> توزيع(
            التكوين_.التأخير_الأساسي_مللي,
            التكوين_.التأخير_الأساسي_مللي * محاولة * 2
        );
        return توزيع(مولد_);
    }
    
    uint64_t إضافة_ارتعاش(uint64_t تأخير) {
        if (التكوين_.نسبة_الارتعاش <= 0) return تأخير;
        
        double نطاق = تأخير * التكوين_.نسبة_الارتعاش;
        std::uniform_real_distribution<double> توزيع(-نطاق, نطاق);
        
        return static_cast<uint64_t>(تأخير + توزيع(مولد_));
    }
};

