// ============== C API ==============

extern "C" {

using namespace ص::موزع;

static مدير_تحمل_أعطال* مدير_الأعطال_العام = nullptr;

void sad_fault_init() {
    if (!مدير_الأعطال_العام) {
        مدير_الأعطال_العام = new مدير_تحمل_أعطال();
    }
}

void sad_fault_cleanup() {
    delete مدير_الأعطال_العام;
    مدير_الأعطال_العام = nullptr;
}

uint64_t sad_fault_report(int نوع, int شدة, const char* مصدر, const char* وصف) {
    if (!مدير_الأعطال_العام) return 0;
    
    return مدير_الأعطال_العام->الكاشف().تسجيل_عطل(
        static_cast<نوع_عطل>(نوع),
        static_cast<شدة_عطل>(شدة),
        مصدر,
        وصف
    );
}

uint64_t sad_checkpoint_create(const char* اسم, const void* بيانات, size_t حجم) {
    if (!مدير_الأعطال_العام) return 0;
    
    std::vector<uint8_t> v(
        static_cast<const uint8_t*>(بيانات),
        static_cast<const uint8_t*>(بيانات) + حجم
    );
    
    return مدير_الأعطال_العام->مدير_الحفظ().إنشاء_نقطة(اسم, v);
}

int sad_checkpoint_restore(uint64_t معرف, void* بيانات, size_t حجم_أقصى) {
    if (!مدير_الأعطال_العام) return 0;
    
    std::vector<uint8_t> v;
    if (!مدير_الأعطال_العام->مدير_الحفظ().استرجاع(معرف, v)) {
        return 0;
    }
    
    size_t للنسخ = std::min(v.size(), حجم_أقصى);
    memcpy(بيانات, v.data(), للنسخ);
    
    return static_cast<int>(للنسخ);
}

int sad_fault_recover() {
    if (!مدير_الأعطال_العام) return 0;
    return مدير_الأعطال_العام->بدء_التعافي() ? 1 : 0;
}

int sad_fault_is_recovering() {
    if (!مدير_الأعطال_العام) return 0;
    return مدير_الأعطال_العام->في_وضع_التعافي() ? 1 : 0;
}

}  // extern "C"
