/**
 * المدير الرئيسي للتحمل للأعطال
 */
class مدير_تحمل_أعطال {
private:
    كاشف_أعطال الكاشف_;
    مدير_نقاط_حفظ مدير_الحفظ_;
    مدير_إعادة_محاولة مدير_الإعادة_;
    
    std::atomic<bool> في_وضع_التعافي_{false};
    
    std::mutex قفل_;
    
public:
    // ============== الواجهات ==============
    
    كاشف_أعطال& الكاشف() { return الكاشف_; }
    مدير_نقاط_حفظ& مدير_الحفظ() { return مدير_الحفظ_; }
    مدير_إعادة_محاولة& مدير_الإعادة() { return مدير_الإعادة_; }
    
    // ============== التعافي ==============
    
    bool بدء_التعافي() {
        bool متوقع = false;
        if (!في_وضع_التعافي_.compare_exchange_strong(متوقع, true)) {
            return false;  // already recovering
        }
        
        // محاولة الاسترجاع من آخر نقطة حفظ
        std::vector<uint8_t> بيانات;
        if (مدير_الحفظ_.استرجاع_آخر(بيانات)) {
            // تطبيق البيانات المسترجعة
            // ...
        }
        
        في_وضع_التعافي_ = false;
        return true;
    }
    
    bool في_وضع_التعافي() const { return في_وضع_التعافي_; }
    
    // ============== نقطة حفظ تلقائية ==============
    
    uint64_t حفظ_حالة(const std::string& اسم,
                       const std::vector<uint8_t>& حالة) {
        return مدير_الحفظ_.إنشاء_نقطة(اسم, حالة);
    }
};

