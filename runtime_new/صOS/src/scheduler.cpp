/**
 * ==========================================================
 * ملف: scheduler.cpp
 * الوصف: مجدول المهام (Preemptive Scheduler)
 * المهمة: T316 - صOS-IoT
 * ==========================================================
 * 
 * 📚 شرح للمبتدئين:
 * ================
 * المجدول يقرر أي مهمة تعمل في أي وقت.
 * "Preemptive" يعني أن المجدول يمكنه إيقاف مهمة
 * في أي لحظة ليشغّل مهمة أخرى أكثر أهمية.
 * 
 * مثال من الحياة:
 * تخيل مدير مطعم يقرر أي طاهٍ يعمل على أي طلب.
 * الطلبات العاجلة تأخذ الأولوية!
 */

#include <cstdint>
#include <cstddef>
#include <atomic>

namespace صOS {

// ==========================================================
// 📌 خوارزميات الجدولة
// ==========================================================

/**
 * 📚 للمبتدئين:
 * هناك طرق مختلفة لتحديد أي مهمة تعمل:
 * - Round Robin: كل مهمة تأخذ دورها بالترتيب
 * - Priority: المهام المهمة تعمل أولاً
 * - EDF: المهام ذات الموعد النهائي الأقرب أولاً
 */

enum class خوارزمية_جدولة {
    دائري = 0,        // Round Robin
    أولوية = 1,       // Priority-based
    موعد_نهائي = 2,   // Earliest Deadline First (EDF)
    حصص_عادلة = 3     // Fair Share
};

// ==========================================================
// 📌 إعدادات المجدول
// ==========================================================

struct إعدادات_المجدول {
    خوارزمية_جدولة الخوارزمية;
    uint32_t الشريحة_الزمنية;  // Time slice بالميلي ثانية
    uint32_t دورة_الفحص;       // كل كم تكة نفحص
    bool تمكين_القفزة;         // السماح بتجاوز الدور للأولوية العالية
    
    إعدادات_المجدول() :
        الخوارزمية(خوارزمية_جدولة::أولوية),
        الشريحة_الزمنية(10),
        دورة_الفحص(1),
        تمكين_القفزة(true) {}
};

// ==========================================================
// 📌 إحصائيات المجدول
// ==========================================================

/**
 * 📚 للمبتدئين:
 * الإحصائيات تساعدنا فهم أداء النظام:
 * - كم مرة تبدّلنا بين المهام
 * - كم استهلكت كل مهمة من الوقت
 */

struct إحصائيات_المجدول {
    uint64_t عدد_التبديلات;      // إجمالي تبديلات السياق
    uint64_t وقت_الخمول;         // الوقت بدون مهام
    uint64_t وقت_التشغيل;        // إجمالي وقت التشغيل
    uint32_t أطول_تبديل;         // أطول وقت لتبديل السياق
    uint32_t متوسط_التبديل;      // متوسط وقت التبديل
    
    إحصائيات_المجدول() :
        عدد_التبديلات(0),
        وقت_الخمول(0),
        وقت_التشغيل(0),
        أطول_تبديل(0),
        متوسط_التبديل(0) {}
};

// ==========================================================
// 📌 عقدة قائمة المهام
// ==========================================================

// Forward declaration
struct كتلة_المهمة;

struct عقدة_مهمة {
    كتلة_المهمة* المهمة;
    عقدة_مهمة* التالي;
    عقدة_مهمة* السابق;
    
    // معلومات الجدولة
    uint32_t الشريحة_المتبقية;   // الوقت المتبقي في الدور الحالي
    uint32_t الموعد_النهائي;      // للـ EDF
    uint32_t الحصة;              // للـ Fair Share
    
    عقدة_مهمة() :
        المهمة(nullptr),
        التالي(nullptr),
        السابق(nullptr),
        الشريحة_المتبقية(0),
        الموعد_النهائي(0),
        الحصة(100) {}
};

// ==========================================================
// 📌 قائمة الأولوية
// ==========================================================

/**
 * 📚 للمبتدئين:
 * قائمة الأولوية تحفظ المهام مرتبة حسب أهميتها.
 * المهام المهمة جداً في المقدمة!
 */

class قائمة_الأولوية {
private:
    static constexpr int عدد_المستويات = 4;
    عقدة_مهمة* الرؤوس_[عدد_المستويات];
    uint32_t العداد_[عدد_المستويات];
    
public:
    قائمة_الأولوية() {
        for (int i = 0; i < عدد_المستويات; ++i) {
            الرؤوس_[i] = nullptr;
            العداد_[i] = 0;
        }
    }
    
    // إضافة عقدة
    void أضف(عقدة_مهمة* عقدة, int الأولوية) {
        if (الأولوية < 0 || الأولوية >= عدد_المستويات) {
            الأولوية = 1; // عادية
        }
        
        عقدة->التالي = الرؤوس_[الأولوية];
        عقدة->السابق = nullptr;
        
        if (الرؤوس_[الأولوية]) {
            الرؤوس_[الأولوية]->السابق = عقدة;
        }
        
        الرؤوس_[الأولوية] = عقدة;
        ++العداد_[الأولوية];
    }
    
    // إزالة عقدة
    void أزل(عقدة_مهمة* عقدة, int الأولوية) {
        if (الأولوية < 0 || الأولوية >= عدد_المستويات) return;
        
        if (عقدة->السابق) {
            عقدة->السابق->التالي = عقدة->التالي;
        } else {
            الرؤوس_[الأولوية] = عقدة->التالي;
        }
        
        if (عقدة->التالي) {
            عقدة->التالي->السابق = عقدة->السابق;
        }
        
        عقدة->التالي = nullptr;
        عقدة->السابق = nullptr;
        --العداد_[الأولوية];
    }
    
    // أحضر أعلى أولوية
    عقدة_مهمة* أحضر_الأعلى() {
        for (int i = عدد_المستويات - 1; i >= 0; --i) {
            if (الرؤوس_[i] != nullptr) {
                return الرؤوس_[i];
            }
        }
        return nullptr;
    }
    
    // أحضر التالي في المستوى
    عقدة_مهمة* أحضر_التالي(int الأولوية) {
        if (الأولوية < 0 || الأولوية >= عدد_المستويات) {
            return nullptr;
        }
        return الرؤوس_[الأولوية];
    }
    
    // انقل للنهاية (للـ Round Robin)
    void انقل_للنهاية(عقدة_مهمة* عقدة, int الأولوية) {
        أزل(عقدة, الأولوية);
        
        // أضف في النهاية
        if (الرؤوس_[الأولوية] == nullptr) {
            الرؤوس_[الأولوية] = عقدة;
            عقدة->التالي = nullptr;
            عقدة->السابق = nullptr;
        } else {
            عقدة_مهمة* حالي = الرؤوس_[الأولوية];
            while (حالي->التالي) {
                حالي = حالي->التالي;
            }
            حالي->التالي = عقدة;
            عقدة->السابق = حالي;
            عقدة->التالي = nullptr;
        }
        ++العداد_[الأولوية];
    }
    
    bool فارغة() const {
        for (int i = 0; i < عدد_المستويات; ++i) {
            if (العداد_[i] > 0) return false;
        }
        return true;
    }
    
    uint32_t العدد() const {
        uint32_t مجموع = 0;
        for (int i = 0; i < عدد_المستويات; ++i) {
            مجموع += العداد_[i];
        }
        return مجموع;
    }
};

// ==========================================================
// 📌 المجدول الرئيسي
// ==========================================================

class المجدول {
private:
    // الإعدادات والإحصائيات
    إعدادات_المجدول الإعدادات_;
    إحصائيات_المجدول الإحصائيات_;
    
    // قوائم المهام
    قائمة_الأولوية القائمة_الجاهزة_;
    
    // المهمة الحالية
    عقدة_مهمة* المهمة_الحالية_;
    عقدة_مهمة* مهمة_الخمول_;
    
    // العداد
    uint32_t التكة_الحالية_;
    
    // قفل للتعدد
    std::atomic_flag القفل_ = ATOMIC_FLAG_INIT;
    
    // Singleton
    static المجدول* النسخة_;
    
    المجدول() :
        المهمة_الحالية_(nullptr),
        مهمة_الخمول_(nullptr),
        التكة_الحالية_(0) {}

public:
    static المجدول& أحضر() {
        if (النسخة_ == nullptr) {
            static المجدول نسخة;
            النسخة_ = &نسخة;
        }
        return *النسخة_;
    }
    
    // =======================================================
    // 📌 التهيئة
    // =======================================================
    
    void هيّئ(const إعدادات_المجدول& إعدادات = إعدادات_المجدول()) {
        الإعدادات_ = إعدادات;
        الإحصائيات_ = إحصائيات_المجدول();
    }
    
    // تعيين مهمة الخمول
    void عيّن_مهمة_الخمول(عقدة_مهمة* مهمة) {
        مهمة_الخمول_ = مهمة;
    }
    
    // =======================================================
    // 📌 إدارة المهام
    // =======================================================
    
    void أضف_مهمة(عقدة_مهمة* عقدة, int الأولوية) {
        أقفل();
        عقدة->الشريحة_المتبقية = الإعدادات_.الشريحة_الزمنية;
        القائمة_الجاهزة_.أضف(عقدة, الأولوية);
        أفتح();
    }
    
    void أزل_مهمة(عقدة_مهمة* عقدة, int الأولوية) {
        أقفل();
        القائمة_الجاهزة_.أزل(عقدة, الأولوية);
        أفتح();
    }
    
    // =======================================================
    // 📌 الجدولة
    // =======================================================
    
    عقدة_مهمة* جدول() {
        ++الإحصائيات_.عدد_التبديلات;
        
        عقدة_مهمة* التالية = nullptr;
        
        switch (الإعدادات_.الخوارزمية) {
            case خوارزمية_جدولة::دائري:
                التالية = جدولة_دائرية();
                break;
                
            case خوارزمية_جدولة::أولوية:
                التالية = جدولة_أولوية();
                break;
                
            case خوارزمية_جدولة::موعد_نهائي:
                التالية = جدولة_موعد_نهائي();
                break;
                
            case خوارزمية_جدولة::حصص_عادلة:
                التالية = جدولة_حصص();
                break;
        }
        
        // إذا لم نجد مهمة، استخدم مهمة الخمول
        if (التالية == nullptr) {
            التالية = مهمة_الخمول_;
        }
        
        المهمة_الحالية_ = التالية;
        return التالية;
    }
    
    // =======================================================
    // 📌 خوارزميات الجدولة
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * Round Robin: كل مهمة تأخذ وقتاً متساوياً
     * مثل توزيع الحلوى بالتساوي على الأطفال
     */
    عقدة_مهمة* جدولة_دائرية() {
        أقفل();
        
        // إذا انتهى وقت المهمة الحالية
        if (المهمة_الحالية_ && المهمة_الحالية_->الشريحة_المتبقية == 0) {
            // أعد تعبئة الشريحة وانقلها للنهاية
            المهمة_الحالية_->الشريحة_المتبقية = الإعدادات_.الشريحة_الزمنية;
            // سيتم نقلها في tick
        }
        
        عقدة_مهمة* نتيجة = القائمة_الجاهزة_.أحضر_الأعلى();
        
        أفتح();
        return نتيجة;
    }
    
    /**
     * 📚 للمبتدئين:
     * Priority: المهمة الأهم تعمل أولاً
     * مثل سيارة الإسعاف لها الأولوية على الطريق
     */
    عقدة_مهمة* جدولة_أولوية() {
        أقفل();
        
        // ببساطة، اختر أعلى أولوية
        عقدة_مهمة* نتيجة = القائمة_الجاهزة_.أحضر_الأعلى();
        
        // إذا كانت المهمة الحالية بنفس الأولوية، استمر معها
        // (لتجنب التبديل المفرط)
        if (المهمة_الحالية_ && نتيجة &&
            !الإعدادات_.تمكين_القفزة) {
            // أبقِ على المهمة الحالية
            نتيجة = المهمة_الحالية_;
        }
        
        أفتح();
        return نتيجة;
    }
    
    /**
     * 📚 للمبتدئين:
     * EDF: المهمة التي موعدها أقرب تعمل أولاً
     * مثل إنهاء الواجب الذي موعده غداً قبل الذي بعد أسبوع
     */
    عقدة_مهمة* جدولة_موعد_نهائي() {
        أقفل();
        
        عقدة_مهمة* الأقرب = nullptr;
        uint32_t أقرب_موعد = UINT32_MAX;
        
        // البحث في كل المستويات
        for (int أولوية = 3; أولوية >= 0; --أولوية) {
            عقدة_مهمة* حالي = القائمة_الجاهزة_.أحضر_التالي(أولوية);
            while (حالي) {
                if (حالي->الموعد_النهائي < أقرب_موعد) {
                    أقرب_موعد = حالي->الموعد_النهائي;
                    الأقرب = حالي;
                }
                حالي = حالي->التالي;
            }
        }
        
        أفتح();
        return الأقرب;
    }
    
    /**
     * 📚 للمبتدئين:
     * Fair Share: كل مهمة تحصل على حصتها العادلة
     * مثل تقسيم الكعكة بنسب متفق عليها
     */
    عقدة_مهمة* جدولة_حصص() {
        أقفل();
        
        // احسب مجموع الحصص
        uint32_t مجموع_الحصص = 0;
        for (int أولوية = 0; أولوية <= 3; ++أولوية) {
            عقدة_مهمة* حالي = القائمة_الجاهزة_.أحضر_التالي(أولوية);
            while (حالي) {
                مجموع_الحصص += حالي->الحصة;
                حالي = حالي->التالي;
            }
        }
        
        if (مجموع_الحصص == 0) {
            أفتح();
            return nullptr;
        }
        
        // اختر عشوائياً (مبسط: استخدم التكة)
        uint32_t اختيار = التكة_الحالية_ % مجموع_الحصص;
        uint32_t تراكم = 0;
        
        for (int أولوية = 3; أولوية >= 0; --أولوية) {
            عقدة_مهمة* حالي = القائمة_الجاهزة_.أحضر_التالي(أولوية);
            while (حالي) {
                تراكم += حالي->الحصة;
                if (تراكم > اختيار) {
                    أفتح();
                    return حالي;
                }
                حالي = حالي->التالي;
            }
        }
        
        أفتح();
        return nullptr;
    }
    
    // =======================================================
    // 📌 معالج التكة
    // =======================================================
    
    void تكة() {
        ++التكة_الحالية_;
        ++الإحصائيات_.وقت_التشغيل;
        
        // تحديث الشريحة المتبقية
        if (المهمة_الحالية_) {
            if (المهمة_الحالية_->الشريحة_المتبقية > 0) {
                --المهمة_الحالية_->الشريحة_المتبقية;
            }
        } else {
            ++الإحصائيات_.وقت_الخمول;
        }
        
        // فحص الجدولة
        if (التكة_الحالية_ % الإعدادات_.دورة_الفحص == 0) {
            bool يحتاج_تبديل = false;
            
            // تبديل إذا انتهت الشريحة
            if (المهمة_الحالية_ && 
                المهمة_الحالية_->الشريحة_المتبقية == 0) {
                يحتاج_تبديل = true;
            }
            
            // تبديل إذا هناك مهمة أعلى أولوية
            if (الإعدادات_.تمكين_القفزة) {
                عقدة_مهمة* أعلى = القائمة_الجاهزة_.أحضر_الأعلى();
                // (يمكن إضافة منطق المقارنة هنا)
            }
            
            if (يحتاج_تبديل) {
                جدول();
            }
        }
    }
    
    // =======================================================
    // 📌 الاستعلامات
    // =======================================================
    
    عقدة_مهمة* أحضر_الحالية() const { return المهمة_الحالية_; }
    const إحصائيات_المجدول& أحضر_الإحصائيات() const { return الإحصائيات_; }
    const إعدادات_المجدول& أحضر_الإعدادات() const { return الإعدادات_; }
    
    void عيّن_الخوارزمية(خوارزمية_جدولة خ) {
        الإعدادات_.الخوارزمية = خ;
    }
    
    void عيّن_الشريحة(uint32_t ميلي_ثانية) {
        الإعدادات_.الشريحة_الزمنية = ميلي_ثانية;
    }

private:
    void أقفل() {
        while (القفل_.test_and_set(std::memory_order_acquire));
    }
    
    void أفتح() {
        القفل_.clear(std::memory_order_release);
    }
};

المجدول* المجدول::النسخة_ = nullptr;

} // namespace صOS

// ==========================================================
// 📌 C API
// ==========================================================

extern "C" {

// تهيئة المجدول
void sad_scheduler_init(void) {
    صOS::المجدول::أحضر().هيّئ();
}

// تعيين الخوارزمية
void sad_scheduler_set_algorithm(int algo) {
    صOS::المجدول::أحضر().عيّن_الخوارزمية(
        static_cast<صOS::خوارزمية_جدولة>(algo)
    );
}

// تعيين الشريحة الزمنية
void sad_scheduler_set_timeslice(uint32_t ms) {
    صOS::المجدول::أحضر().عيّن_الشريحة(ms);
}

// معالج التكة
void sad_scheduler_tick(void) {
    صOS::المجدول::أحضر().تكة();
}

// الجدولة
void* sad_scheduler_schedule(void) {
    return صOS::المجدول::أحضر().جدول();
}

// أحضر الإحصائيات
uint64_t sad_scheduler_get_context_switches(void) {
    return صOS::المجدول::أحضر().أحضر_الإحصائيات().عدد_التبديلات;
}

uint64_t sad_scheduler_get_idle_time(void) {
    return صOS::المجدول::أحضر().أحضر_الإحصائيات().وقت_الخمول;
}

} // extern "C"
