extern "C" {

// تسجيل جهاز
int sad_dev_register(void* device) {
    return static_cast<int>(
        صOS::مدير_الأجهزة::أحضر().سجّل_جهاز(
            static_cast<صOS::واصف_الجهاز*>(device)
        )
    );
}

// إلغاء تسجيل جهاز
int sad_dev_unregister(void* device) {
    return static_cast<int>(
        صOS::مدير_الأجهزة::أحضر().ألغِ_تسجيل_جهاز(
            static_cast<صOS::واصف_الجهاز*>(device)
        )
    );
}

// البحث بالاسم
void* sad_dev_find_by_name(const char* name) {
    return صOS::مدير_الأجهزة::أحضر().ابحث_بالاسم(name);
}

// البحث بالمعرّف
void* sad_dev_find_by_id(uint16_t id) {
    return صOS::مدير_الأجهزة::أحضر().ابحث_بالمعرّف(id);
}

// فتح جهاز
int sad_dev_open(void* device) {
    return static_cast<int>(
        صOS::مدير_الأجهزة::أحضر().افتح_جهاز(
            static_cast<صOS::واصف_الجهاز*>(device)
        )
    );
}

// إغلاق جهاز
int sad_dev_close(void* device) {
    return static_cast<int>(
        صOS::مدير_الأجهزة::أحضر().أغلق_جهاز(
            static_cast<صOS::واصف_الجهاز*>(device)
        )
    );
}

// قراءة من جهاز
int sad_dev_read(void* device, void* buffer, uint32_t size) {
    صOS::واصف_الجهاز* جهاز = static_cast<صOS::واصف_الجهاز*>(device);
    if (جهاز == nullptr || جهاز->العمليات == nullptr ||
        جهاز->العمليات->اقرأ == nullptr) {
        return -1;
    }
    return جهاز->العمليات->اقرأ(جهاز, buffer, size);
}

// كتابة لجهاز
int sad_dev_write(void* device, const void* data, uint32_t size) {
    صOS::واصف_الجهاز* جهاز = static_cast<صOS::واصف_الجهاز*>(device);
    if (جهاز == nullptr || جهاز->العمليات == nullptr ||
        جهاز->العمليات->اكتب == nullptr) {
        return -1;
    }
    return جهاز->العمليات->اكتب(جهاز, data, size);
}

// تحكم
int sad_dev_ioctl(void* device, uint32_t cmd, void* arg) {
    صOS::واصف_الجهاز* جهاز = static_cast<صOS::واصف_الجهاز*>(device);
    if (جهاز == nullptr || جهاز->العمليات == nullptr ||
        جهاز->العمليات->تحكّم == nullptr) {
        return -1;
    }
    return static_cast<int>(جهاز->العمليات->تحكّم(جهاز, cmd, arg));
}

// عدد الأجهزة
uint32_t sad_dev_count(void) {
    return صOS::مدير_الأجهزة::أحضر().أحضر_عدد_الأجهزة();
}

} // extern "C"
