/**
 * 📚 للمبتدئين:
 * الأجهزة لها أنواع مختلفة حسب طبيعة عملها.
 */

enum class نوع_الجهاز : uint8_t {
    حرفي = 0,       // Character device (byte by byte)
    كتلي = 1,       // Block device (sectors)
    شبكة = 2,       // Network device
    عرض = 3,        // Display device
    إدخال = 4,      // Input device (keyboard, touch)
    حساس = 5,       // Sensor
    موقت = 6,       // Timer
    تسلسلي = 7,     // Serial (UART, SPI, I2C)
    تخزين = 8,      // Storage
    أخرى = 255
};

// حالة الجهاز
enum class حالة_الجهاز : uint8_t {
    غير_موجود = 0,
    موجود = 1,
    مهيّأ = 2,
    مفتوح = 3,
    مشغول = 4,
    خطأ = 5
};

// ==========================================================
// 📌 رموز الخطأ
// ==========================================================

enum class رمز_خطأ : int {
    نجاح = 0,
    خطأ_عام = -1,
    غير_موجود = -2,
    مشغول = -3,
    لا_ذاكرة = -4,
    غير_مدعوم = -5,
    وسيط_خاطئ = -6,
    انتهى_الوقت = -7,
    لا_صلاحية = -8,
    مغلق = -9,
    ممتلئ = -10,
    فارغ = -11
};

// ==========================================================
// 📌 واجهة الجهاز
// ==========================================================

/**
 * 📚 للمبتدئين:
 * كل جهاز يجب أن يوفر هذه العمليات الأساسية.
 * هذه "واجهة" - عقد يلتزم به كل جهاز.
 */

struct عمليات_الجهاز;

struct واصف_الجهاز {
    const char* الاسم;
    نوع_الجهاز النوع;
    حالة_الجهاز الحالة;
    uint16_t المعرّف;
    uint16_t رقم_الإصدار;
    
    const عمليات_الجهاز* العمليات;
    void* البيانات_الخاصة;
    
    // إحصائيات
    uint32_t عدد_القراءات;
    uint32_t عدد_الكتابات;
    uint64_t بايتات_مقروءة;
    uint64_t بايتات_مكتوبة;
};

// نوع معالج المقاطعة للجهاز
using معالج_جهاز = void (*)(واصف_الجهاز* الجهاز, void* البيانات);

// ==========================================================
// 📌 عمليات الجهاز
// ==========================================================

/**
 * 📚 للمبتدئين:
 * هذه هي العمليات التي يمكن إجراؤها على أي جهاز.
 * كل جهاز يُنفّذ هذه العمليات بطريقته الخاصة.
 */

struct عمليات_الجهاز {
    // التهيئة والتنظيف
    رمز_خطأ (*هيّئ)(واصف_الجهاز* جهاز);
    رمز_خطأ (*نظّف)(واصف_الجهاز* جهاز);
    
    // الفتح والإغلاق
    رمز_خطأ (*افتح)(واصف_الجهاز* جهاز);
    رمز_خطأ (*أغلق)(واصف_الجهاز* جهاز);
    
    // القراءة والكتابة
    int (*اقرأ)(واصف_الجهاز* جهاز, void* المخزن, uint32_t الحجم);
    int (*اكتب)(واصف_الجهاز* جهاز, const void* البيانات, uint32_t الحجم);
    
    // التحكم
    رمز_خطأ (*تحكّم)(واصف_الجهاز* جهاز, uint32_t الأمر, void* الوسيط);
    
    // الموقع (للأجهزة الكتلية)
    رمز_خطأ (*انتقل)(واصف_الجهاز* جهاز, int64_t الموقع, int من_أين);
    
    // الاستطلاع
    رمز_خطأ (*استطلع)(واصف_الجهاز* جهاز, uint32_t* الأحداث, uint32_t المهلة);
};

