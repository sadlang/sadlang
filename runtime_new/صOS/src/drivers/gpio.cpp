#include <cstdint>
#include <cstddef>

namespace صOS {
namespace GPIO {

// ==========================================================
// 📌 ثوابت GPIO
// ==========================================================

constexpr int أقصى_عدد_أرجل = 40;  // ESP32 لديه ~40 GPIO

// ==========================================================
// 📌 اتجاه الرِجل
// ==========================================================

/**
 * 📚 للمبتدئين:
 * - إدخال: لقراءة إشارة (مثل زر)
 * - إخراج: لإرسال إشارة (مثل تشغيل LED)
 */

enum class اتجاه : uint8_t {
    إدخال = 0,      // Input
    إخراج = 1,      // Output
    ثنائي_الاتجاه = 2 // Bidirectional
};

// ==========================================================
// 📌 وضع السحب
// ==========================================================

/**
 * 📚 للمبتدئين:
 * عندما لا يكون هناك إشارة، ماذا تكون قيمة الرِجل؟
 * - سحب_علوي: القيمة الافتراضية 1 (عالية)
 * - سحب_سفلي: القيمة الافتراضية 0 (منخفضة)
 * - بدون: تطفو (غير محددة) - غير مستحسن
 */

enum class وضع_السحب : uint8_t {
    بدون = 0,       // No pull
    سحب_علوي = 1,   // Pull-up (default HIGH)
    سحب_سفلي = 2    // Pull-down (default LOW)
};

// ==========================================================
// 📌 وضع المقاطعة
// ==========================================================

/**
 * 📚 للمبتدئين:
 * المقاطعة تُخبرك فوراً عندما يتغير شيء.
 * بدلاً من فحص الزر كل لحظة، المقاطعة تنبّهك!
 */

enum class وضع_المقاطعة : uint8_t {
    معطّل = 0,      // لا مقاطعة
    حافة_صاعدة = 1, // عند التحول من 0 إلى 1
    حافة_هابطة = 2, // عند التحول من 1 إلى 0
    أي_حافة = 3,    // عند أي تغيير
    مستوى_عالي = 4, // طالما القيمة 1
    مستوى_منخفض = 5 // طالما القيمة 0
};

// ==========================================================
// 📌 إعدادات الرِجل
// ==========================================================

struct إعدادات_رِجل {
    uint8_t الرقم;
    اتجاه الاتجاه;
    وضع_السحب السحب;
    وضع_المقاطعة المقاطعة;
    bool مفتوح_الصرف;   // Open-drain mode
    
    إعدادات_رِجل() :
        الرقم(0),
        الاتجاه(اتجاه::إدخال),
        السحب(وضع_السحب::بدون),
        المقاطعة(وضع_المقاطعة::معطّل),
        مفتوح_الصرف(false) {}
};

// ==========================================================
// 📌 معالج المقاطعة
// ==========================================================

using معالج_مقاطعة_GPIO = void (*)(uint8_t رقم_الرِجل, void* البيانات);

// ==========================================================
// 📌 حالة الرِجل
// ==========================================================

struct حالة_رِجل {
    bool مُهيّأة;
    اتجاه الاتجاه;
    وضع_السحب السحب;
    bool القيمة;        // آخر قيمة معروفة
    
    // معالج المقاطعة
    معالج_مقاطعة_GPIO المعالج;
    void* بيانات_المعالج;
    وضع_المقاطعة وضع_المقاطعة_;
    
    // إحصائيات
    uint32_t عدد_المقاطعات;
    
    حالة_رِجل() :
        مُهيّأة(false),
        الاتجاه(اتجاه::إدخال),
        السحب(وضع_السحب::بدون),
        القيمة(false),
        المعالج(nullptr),
        بيانات_المعالج(nullptr),
        وضع_المقاطعة_(وضع_المقاطعة::معطّل),
        عدد_المقاطعات(0) {}
};

// ==========================================================
// 📌 مدير GPIO
// ==========================================================

class مدير_GPIO {
private:
    حالة_رِجل الأرجل_[أقصى_عدد_أرجل];
    bool مُهيّأ_;
    
    // Singleton
    static مدير_GPIO* النسخة_;
    
    مدير_GPIO() : مُهيّأ_(false) {}

public:
    static مدير_GPIO& أحضر() {
        if (النسخة_ == nullptr) {
            static مدير_GPIO نسخة;
            النسخة_ = &نسخة;
        }
        return *النسخة_;
    }
    
    // =======================================================
    // 📌 التهيئة
    // =======================================================
    
    bool هيّئ() {
        if (مُهيّأ_) return true;
        
        // إعادة ضبط كل الأرجل
        for (int i = 0; i < أقصى_عدد_أرجل; ++i) {
            الأرجل_[i] = حالة_رِجل();
        }
        
        // في التنفيذ الحقيقي:
        // gpio_install_isr_service(0);
        
        مُهيّأ_ = true;
        return true;
    }
    
    // =======================================================
    // 📌 تهيئة رِجل
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * قبل استخدام أي رِجل، يجب تهيئتها.
     * حدد: أي رِجل، إدخال أم إخراج، إعدادات السحب
     */
    
    bool هيّئ_رِجل(uint8_t الرقم, اتجاه الاتجاه, 
                  وضع_السحب السحب = وضع_السحب::بدون) {
        if (الرقم >= أقصى_عدد_أرجل) return false;
        if (!مُهيّأ_) هيّئ();
        
        حالة_رِجل& رِجل = الأرجل_[الرقم];
        
        // في التنفيذ الحقيقي:
        // gpio_config_t io_conf = {};
        // io_conf.pin_bit_mask = (1ULL << pin);
        // io_conf.mode = (direction == Direction::Output) ? 
        //                GPIO_MODE_OUTPUT : GPIO_MODE_INPUT;
        // io_conf.pull_up_en = (pull == PullMode::PullUp);
        // io_conf.pull_down_en = (pull == PullMode::PullDown);
        // gpio_config(&io_conf);
        
        رِجل.مُهيّأة = true;
        رِجل.الاتجاه = الاتجاه;
        رِجل.السحب = السحب;
        رِجل.القيمة = false;
        
        return true;
    }
    
    bool هيّئ_رِجل(const إعدادات_رِجل& الإعدادات) {
        bool نتيجة = هيّئ_رِجل(الإعدادات.الرقم, 
                              الإعدادات.الاتجاه, 
                              الإعدادات.السحب);
        
        if (نتيجة && الإعدادات.المقاطعة != وضع_المقاطعة::معطّل) {
            // تفعيل المقاطعة لاحقاً إذا تم تعيين معالج
            الأرجل_[الإعدادات.الرقم].وضع_المقاطعة_ = الإعدادات.المقاطعة;
        }
        
        return نتيجة;
    }
    
    // =======================================================
    // 📌 القراءة والكتابة
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * القراءة: معرفة هل الرِجل عالية (1) أم منخفضة (0)
     * الكتابة: تعيين الرِجل لقيمة معينة
     */
    
    bool اقرأ(uint8_t الرقم) {
        if (الرقم >= أقصى_عدد_أرجل) return false;
        if (!الأرجل_[الرقم].مُهيّأة) return false;
        
        // في التنفيذ الحقيقي:
        // return gpio_get_level(pin);
        
        return الأرجل_[الرقم].القيمة;
    }
    
    void اكتب(uint8_t الرقم, bool القيمة) {
        if (الرقم >= أقصى_عدد_أرجل) return;
        if (!الأرجل_[الرقم].مُهيّأة) return;
        if (الأرجل_[الرقم].الاتجاه != اتجاه::إخراج) return;
        
        // في التنفيذ الحقيقي:
        // gpio_set_level(pin, value);
        
        الأرجل_[الرقم].القيمة = القيمة;
    }
    
    // دوال مختصرة
    void عالي(uint8_t الرقم) { اكتب(الرقم, true); }
    void منخفض(uint8_t الرقم) { اكتب(الرقم, false); }
    void بدّل(uint8_t الرقم) { اكتب(الرقم, !اقرأ(الرقم)); }
    
    // =======================================================
    // 📌 المقاطعات
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * المقاطعة تنبّهك فوراً عند تغيّر حالة الرِجل.
     * مفيدة للأزرار والحساسات.
     */
    
    bool فعّل_المقاطعة(uint8_t الرقم, وضع_المقاطعة الوضع,
                      معالج_مقاطعة_GPIO المعالج, void* البيانات = nullptr) {
        if (الرقم >= أقصى_عدد_أرجل) return false;
        if (!الأرجل_[الرقم].مُهيّأة) return false;
        
        حالة_رِجل& رِجل = الأرجل_[الرقم];
        رِجل.وضع_المقاطعة_ = الوضع;
        رِجل.المعالج = المعالج;
        رِجل.بيانات_المعالج = البيانات;
        
        // في التنفيذ الحقيقي:
        // gpio_set_intr_type(pin, interrupt_mode);
        // gpio_isr_handler_add(pin, handler, data);
        
        return true;
    }
    
    void عطّل_المقاطعة(uint8_t الرقم) {
        if (الرقم >= أقصى_عدد_أرجل) return;
        
        حالة_رِجل& رِجل = الأرجل_[الرقم];
        رِجل.وضع_المقاطعة_ = وضع_المقاطعة::معطّل;
        رِجل.المعالج = nullptr;
        
        // gpio_isr_handler_remove(pin);
    }
    
    // محاكاة مقاطعة (للاختبار)
    void حاكِ_مقاطعة(uint8_t الرقم) {
        if (الرقم >= أقصى_عدد_أرجل) return;
        
        حالة_رِجل& رِجل = الأرجل_[الرقم];
        if (رِجل.المعالج) {
            ++رِجل.عدد_المقاطعات;
            رِجل.المعالج(الرقم, رِجل.بيانات_المعالج);
        }
    }
    
    // =======================================================
    // 📌 PWM (تعديل عرض النبضة)
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * PWM يُستخدم للتحكم في سطوع LED أو سرعة محرك.
     * بدلاً من تشغيل/إطفاء فقط، نتحكم في "نسبة التشغيل".
     */
    
    bool هيّئ_PWM(uint8_t الرقم, uint32_t التردد, uint8_t الدقة_بت = 8) {
        if (الرقم >= أقصى_عدد_أرجل) return false;
        
        // في التنفيذ الحقيقي (ESP32):
        // ledc_timer_config_t timer_conf = {
        //     .speed_mode = LEDC_LOW_SPEED_MODE,
        //     .duty_resolution = resolution_bits,
        //     .timer_num = LEDC_TIMER_0,
        //     .freq_hz = frequency,
        // };
        // ledc_timer_config(&timer_conf);
        
        return true;
    }
    
    void اكتب_PWM(uint8_t الرقم, uint16_t القيمة) {
        if (الرقم >= أقصى_عدد_أرجل) return;
        
        // في التنفيذ الحقيقي:
        // ledc_set_duty(LEDC_LOW_SPEED_MODE, channel, value);
        // ledc_update_duty(LEDC_LOW_SPEED_MODE, channel);
    }
    
    // =======================================================
    // 📌 الاستعلامات
    // =======================================================
    
    bool مُهيّأة(uint8_t الرقم) const {
        if (الرقم >= أقصى_عدد_أرجل) return false;
        return الأرجل_[الرقم].مُهيّأة;
    }
    
    اتجاه أحضر_الاتجاه(uint8_t الرقم) const {
        if (الرقم >= أقصى_عدد_أرجل) return اتجاه::إدخال;
        return الأرجل_[الرقم].الاتجاه;
    }
    
    uint32_t أحضر_عدد_المقاطعات(uint8_t الرقم) const {
        if (الرقم >= أقصى_عدد_أرجل) return 0;
        return الأرجل_[الرقم].عدد_المقاطعات;
    }
};

مدير_GPIO* مدير_GPIO::النسخة_ = nullptr;

} // namespace GPIO
} // namespace صOS

// ==========================================================
// 📌 C API
// ==========================================================

extern "C" {

// التهيئة
int sad_gpio_init(void) {
    return صOS::GPIO::مدير_GPIO::أحضر().هيّئ() ? 0 : -1;
}

// تهيئة رِجل
int sad_gpio_pin_init(uint8_t pin, uint8_t direction, uint8_t pull) {
    return صOS::GPIO::مدير_GPIO::أحضر().هيّئ_رِجل(
        pin,
        static_cast<صOS::GPIO::اتجاه>(direction),
        static_cast<صOS::GPIO::وضع_السحب>(pull)
    ) ? 0 : -1;
}

// القراءة والكتابة
int sad_gpio_read(uint8_t pin) {
    return صOS::GPIO::مدير_GPIO::أحضر().اقرأ(pin) ? 1 : 0;
}

void sad_gpio_write(uint8_t pin, int value) {
    صOS::GPIO::مدير_GPIO::أحضر().اكتب(pin, value != 0);
}

void sad_gpio_high(uint8_t pin) {
    صOS::GPIO::مدير_GPIO::أحضر().عالي(pin);
}

void sad_gpio_low(uint8_t pin) {
    صOS::GPIO::مدير_GPIO::أحضر().منخفض(pin);
}

void sad_gpio_toggle(uint8_t pin) {
    صOS::GPIO::مدير_GPIO::أحضر().بدّل(pin);
}

// PWM
int sad_gpio_pwm_init(uint8_t pin, uint32_t freq, uint8_t resolution) {
    return صOS::GPIO::مدير_GPIO::أحضر().هيّئ_PWM(pin, freq, resolution) ? 0 : -1;
}

void sad_gpio_pwm_write(uint8_t pin, uint16_t value) {
    صOS::GPIO::مدير_GPIO::أحضر().اكتب_PWM(pin, value);
}

} // extern "C"
