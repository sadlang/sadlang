// ==========================================================
// 📌 حالة النقل
// ==========================================================

enum class نتيجة_النقل : int {
    نجاح = 0,
    خطأ_عام = -1,
    لا_جواب = -2,      // NACK
    انتهى_الوقت = -3,
    مشغول = -4,
    وسيط_خاطئ = -5
};

// ==========================================================
// 📌 إعدادات I2C
// ==========================================================

struct إعدادات_I2C {
    uint8_t رقم_الناقل;      // 0 أو 1
    uint8_t رِجل_SDA;        // رِجل البيانات
    uint8_t رِجل_SCL;        // رِجل الساعة
    uint32_t السرعة;         // بالهرتز
    bool سحب_داخلي;         // تفعيل المقاومات الداخلية
    
    إعدادات_I2C() :
        رقم_الناقل(0),
        رِجل_SDA(21),
        رِجل_SCL(22),
        السرعة(السرعة_القياسية),
        سحب_داخلي(true) {}
};

