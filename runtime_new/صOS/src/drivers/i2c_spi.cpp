/**
 * 📚 للمبتدئين:
 * SPI له 4 أوضاع تحدد متى يتم قراءة/كتابة البيانات.
 * الوضع 0 هو الأكثر شيوعاً.
 */

enum class وضع_SPI : uint8_t {
    الوضع_0 = 0,  // CPOL=0, CPHA=0
    الوضع_1 = 1,  // CPOL=0, CPHA=1
    الوضع_2 = 2,  // CPOL=1, CPHA=0
    الوضع_3 = 3   // CPOL=1, CPHA=1
};

// ترتيب البتات
enum class ترتيب_البتات : uint8_t {
    MSB_أولاً = 0,  // البت الأكبر أولاً
    LSB_أولاً = 1   // البت الأصغر أولاً
};

// ==========================================================
// 📌 إعدادات SPI
// ==========================================================

struct إعدادات_SPI {
    uint8_t رقم_الناقل;
    uint8_t رِجل_MOSI;       // Master Out, Slave In
    uint8_t رِجل_MISO;       // Master In, Slave Out
    uint8_t رِجل_SCK;        // Serial Clock
    uint32_t السرعة;         // بالهرتز
    وضع_SPI الوضع;
    ترتيب_البتات الترتيب;
    
    إعدادات_SPI() :
        رقم_الناقل(1),       // HSPI
        رِجل_MOSI(23),
        رِجل_MISO(19),
        رِجل_SCK(18),
        السرعة(1000000),     // 1 MHz default
        الوضع(وضع_SPI::الوضع_0),
        الترتيب(ترتيب_البتات::MSB_أولاً) {}
};

// إعدادات الجهاز
struct إعدادات_جهاز_SPI {
    uint8_t رِجل_CS;          // Chip Select
    uint32_t السرعة;          // السرعة الخاصة بالجهاز
    وضع_SPI الوضع;
    uint8_t طول_الأمر_بت;     // طول الأمر بالبت (0-16)
    uint8_t طول_العنوان_بت;   // طول العنوان بالبت (0-64)
    
    إعدادات_جهاز_SPI() :
        رِجل_CS(5),
        السرعة(1000000),
        الوضع(وضع_SPI::الوضع_0),
        طول_الأمر_بت(0),
        طول_العنوان_بت(0) {}
};

