extern "C" {

// I2C
int sad_i2c_init(uint8_t bus, uint8_t sda, uint8_t scl, uint32_t speed) {
    صOS::I2C::إعدادات_I2C إعدادات;
    إعدادات.رقم_الناقل = bus;
    إعدادات.رِجل_SDA = sda;
    إعدادات.رِجل_SCL = scl;
    إعدادات.السرعة = speed;
    return static_cast<int>(
        صOS::I2C::مدير_I2C::أحضر().ناقل(bus).هيّئ(إعدادات)
    );
}

int sad_i2c_write(uint8_t bus, uint8_t addr, const uint8_t* data, uint32_t len) {
    return static_cast<int>(
        صOS::I2C::مدير_I2C::أحضر().ناقل(bus).اكتب(addr, data, len)
    );
}

int sad_i2c_read(uint8_t bus, uint8_t addr, uint8_t* buffer, uint32_t len) {
    return static_cast<int>(
        صOS::I2C::مدير_I2C::أحضر().ناقل(bus).اقرأ(addr, buffer, len)
    );
}

int sad_i2c_device_exists(uint8_t bus, uint8_t addr) {
    return صOS::I2C::مدير_I2C::أحضر().ناقل(bus).يوجد_جهاز(addr) ? 1 : 0;
}

// SPI
int sad_spi_init(uint8_t bus, uint8_t mosi, uint8_t miso, 
                 uint8_t sck, uint32_t speed) {
    صOS::SPI::إعدادات_SPI إعدادات;
    إعدادات.رقم_الناقل = bus;
    إعدادات.رِجل_MOSI = mosi;
    إعدادات.رِجل_MISO = miso;
    إعدادات.رِجل_SCK = sck;
    إعدادات.السرعة = speed;
    return صOS::SPI::مدير_SPI::أحضر().ناقل(bus).هيّئ(إعدادات) ? 0 : -1;
}

void* sad_spi_add_device(uint8_t bus, uint8_t cs, uint32_t speed) {
    صOS::SPI::إعدادات_جهاز_SPI إعدادات;
    إعدادات.رِجل_CS = cs;
    إعدادات.السرعة = speed;
    return صOS::SPI::مدير_SPI::أحضر().ناقل(bus).أضف_جهاز(إعدادات);
}

int sad_spi_transfer(void* device, const uint8_t* tx, uint8_t* rx, uint32_t len) {
    // نحتاج معرفة الناقل - للتبسيط نستخدم الناقل 1
    return صOS::SPI::مدير_SPI::أحضر().ناقل(1).انقل(
        device, tx, rx, len
    ) ? 0 : -1;
}

} // extern "C"
