/**
 * ==========================================================
 * ملف: interrupts.cpp
 * الوصف: معالجة المقاطعات
 * المهمة: T318 - صOS-IoT
 * ==========================================================
 * 
 * 📚 شرح للمبتدئين:
 * ================
 * المقاطعات (Interrupts) هي طريقة الأجهزة للتحدث مع المعالج.
 * تخيل جرس الباب: عندما يرن، توقف ما تفعله وتذهب للباب.
 * المعالج يفعل نفس الشيء عند حدوث مقاطعة.
 * 
 * أمثلة على المقاطعات:
 * - الضغط على زر
 * - وصول بيانات من الشبكة
 * - انتهاء عداد الوقت
 */

#include <cstdint>
#include <cstddef>

namespace صOS {

// ==========================================================
// 📌 ثوابت المقاطعات
// ==========================================================

constexpr int أقصى_عدد_مقاطعات = 256;
constexpr int عدد_مستويات_الأولوية = 16;

// ==========================================================
// 📌 أنواع المقاطعات
// ==========================================================

/**
 * 📚 للمبتدئين:
 * هناك أنواع مختلفة من المقاطعات:
 * - استثناءات: أخطاء (مثل القسمة على صفر)
 * - مقاطعات خارجية: من الأجهزة
 * - مقاطعات برمجية: من البرنامج نفسه
 */

enum class نوع_المقاطعة : uint8_t {
    استثناء = 0,        // Exception
    غير_قابل_للقناع = 1, // NMI - Non-Maskable Interrupt
    خارجي = 2,          // External (IRQ)
    برمجي = 3           // Software (SWI)
};

// مقاطعات النظام الأساسية (ARM Cortex-M)
enum مقاطعة_نظام : int {
    إعادة_ضبط = -15,     // Reset
    غير_قابل_للقناع_NMI = -14,
    خطأ_صعب = -13,       // Hard Fault
    خطأ_ذاكرة = -12,     // Memory Management Fault
    خطأ_باص = -11,       // Bus Fault
    خطأ_استخدام = -10,   // Usage Fault
    استدعاء_مشرف = -5,   // SVCall
    مراقب_تصحيح = -4,    // Debug Monitor
    معلق_SV = -2,        // PendSV
    تكة_النظام = -1      // SysTick
};

// ==========================================================
// 📌 سياق المقاطعة
// ==========================================================

/**
 * 📚 للمبتدئين:
 * عند حدوث مقاطعة، يجب حفظ حالة المعالج
 * حتى نتمكن من العودة لما كنا نفعله.
 */

struct سياق_المقاطعة {
    // السجلات المحفوظة تلقائياً (Hardware Saved)
    uint32_t r0, r1, r2, r3;
    uint32_t r12;
    uint32_t lr;    // Link Register
    uint32_t pc;    // Program Counter
    uint32_t xpsr;  // Status Register
    
    // السجلات المحفوظة يدوياً (Software Saved)
    uint32_t r4, r5, r6, r7;
    uint32_t r8, r9, r10, r11;
    
    // معلومات إضافية
    uint32_t رقم_المقاطعة;
    uint32_t رمز_الخطأ;
};

// ==========================================================
// 📌 واصف المقاطعة
// ==========================================================

/**
 * 📚 للمبتدئين:
 * لكل مقاطعة معلومات خاصة بها:
 * - المعالج: الدالة التي تُستدعى
 * - الأولوية: مدى أهميتها
 * - الحالة: مفعّلة أم لا
 */

// نوع معالج المقاطعة
using معالج_مقاطعة = void (*)(سياق_المقاطعة*);

struct واصف_مقاطعة {
    معالج_مقاطعة المعالج;
    نوع_المقاطعة النوع;
    uint8_t الأولوية;     // 0 = أعلى
    bool مفعّلة;
    bool معلّقة;          // في انتظار المعالجة
    const char* الاسم;
    
    // إحصائيات
    uint32_t عدد_الحدوث;
    uint64_t آخر_حدوث;    // بالتكات
    uint64_t إجمالي_الوقت; // الوقت داخل المعالج
    
    واصف_مقاطعة() :
        المعالج(nullptr),
        النوع(نوع_المقاطعة::خارجي),
        الأولوية(8),
        مفعّلة(false),
        معلّقة(false),
        الاسم("غير معروف"),
        عدد_الحدوث(0),
        آخر_حدوث(0),
        إجمالي_الوقت(0) {}
};

// ==========================================================
// 📌 متحكم المقاطعات (NVIC Abstraction)
// ==========================================================

/**
 * 📚 للمبتدئين:
 * NVIC = Nested Vectored Interrupt Controller
 * هو الجزء من المعالج الذي يدير المقاطعات.
 */

class متحكم_المقاطعات {
private:
    واصف_مقاطعة الواصفات_[أقصى_عدد_مقاطعات];
    
    // حالة المتحكم
    bool المقاطعات_معطّلة_;
    int عمق_التعطيل_;
    
    // المقاطعة الجارية
    int المقاطعة_الجارية_;
    
    // الإحصائيات
    uint64_t إجمالي_المقاطعات_;
    uint64_t التكة_الحالية_;
    
    // Singleton
    static متحكم_المقاطعات* النسخة_;
    
    متحكم_المقاطعات() :
        المقاطعات_معطّلة_(false),
        عمق_التعطيل_(0),
        المقاطعة_الجارية_(-1),
        إجمالي_المقاطعات_(0),
        التكة_الحالية_(0) {}

public:
    static متحكم_المقاطعات& أحضر() {
        if (النسخة_ == nullptr) {
            static متحكم_المقاطعات نسخة;
            النسخة_ = &نسخة;
        }
        return *النسخة_;
    }
    
    // =======================================================
    // 📌 التهيئة
    // =======================================================
    
    void هيّئ() {
        // تهيئة الاستثناءات الافتراضية
        سجّل_مقاطعة(
            static_cast<int>(خطأ_صعب),
            معالج_خطأ_صعب_افتراضي,
            "خطأ صعب",
            0  // أعلى أولوية
        );
        
        سجّل_مقاطعة(
            static_cast<int>(تكة_النظام),
            معالج_تكة_افتراضي,
            "تكة النظام",
            15
        );
    }
    
    // =======================================================
    // 📌 تسجيل المقاطعات
    // =======================================================
    
    bool سجّل_مقاطعة(
        int الرقم,
        معالج_مقاطعة المعالج,
        const char* الاسم = nullptr,
        uint8_t الأولوية = 8,
        نوع_المقاطعة النوع = نوع_المقاطعة::خارجي
    ) {
        int الفهرس = الرقم + 16; // الإزاحة للمقاطعات السالبة
        if (الفهرس < 0 || الفهرس >= أقصى_عدد_مقاطعات) {
            return false;
        }
        
        واصف_مقاطعة& واصف = الواصفات_[الفهرس];
        واصف.المعالج = المعالج;
        واصف.النوع = النوع;
        واصف.الأولوية = الأولوية;
        واصف.الاسم = الاسم ? الاسم : "بدون اسم";
        واصف.مفعّلة = true;
        
        return true;
    }
    
    bool ألغِ_تسجيل_مقاطعة(int الرقم) {
        int الفهرس = الرقم + 16;
        if (الفهرس < 0 || الفهرس >= أقصى_عدد_مقاطعات) {
            return false;
        }
        
        الواصفات_[الفهرس].المعالج = nullptr;
        الواصفات_[الفهرس].مفعّلة = false;
        
        return true;
    }
    
    // =======================================================
    // 📌 التحكم بالتفعيل
    // =======================================================
    
    void فعّل_مقاطعة(int الرقم) {
        int الفهرس = الرقم + 16;
        if (الفهرس >= 0 && الفهرس < أقصى_عدد_مقاطعات) {
            الواصفات_[الفهرس].مفعّلة = true;
        }
    }
    
    void عطّل_مقاطعة(int الرقم) {
        int الفهرس = الرقم + 16;
        if (الفهرس >= 0 && الفهرس < أقصى_عدد_مقاطعات) {
            الواصفات_[الفهرس].مفعّلة = false;
        }
    }
    
    void عيّن_الأولوية(int الرقم, uint8_t الأولوية) {
        int الفهرس = الرقم + 16;
        if (الفهرس >= 0 && الفهرس < أقصى_عدد_مقاطعات) {
            الواصفات_[الفهرس].الأولوية = الأولوية;
        }
    }
    
    // =======================================================
    // 📌 التحكم العام
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * أحياناً نحتاج لتعطيل كل المقاطعات مؤقتاً
     * (مثل القسم الحرج في الكود)
     */
    
    void عطّل_الكل() {
        ++عمق_التعطيل_;
        المقاطعات_معطّلة_ = true;
        // __disable_irq(); // ARM Cortex-M
    }
    
    void فعّل_الكل() {
        if (عمق_التعطيل_ > 0) {
            --عمق_التعطيل_;
        }
        if (عمق_التعطيل_ == 0) {
            المقاطعات_معطّلة_ = false;
            // __enable_irq(); // ARM Cortex-M
        }
    }
    
    bool معطّلة() const { return المقاطعات_معطّلة_; }
    
    // =======================================================
    // 📌 معالجة المقاطعات
    // =======================================================
    
    /**
     * 📚 للمبتدئين:
     * هذه الدالة تُستدعى عند حدوث أي مقاطعة.
     * تحدد أي مقاطعة حدثت وتستدعي المعالج المناسب.
     */
    
    void عالج_المقاطعة(int الرقم, سياق_المقاطعة* السياق) {
        if (المقاطعات_معطّلة_) {
            // علّق للمعالجة لاحقاً
            علّق_مقاطعة(الرقم);
            return;
        }
        
        int الفهرس = الرقم + 16;
        if (الفهرس < 0 || الفهرس >= أقصى_عدد_مقاطعات) {
            return;
        }
        
        واصف_مقاطعة& واصف = الواصفات_[الفهرس];
        
        if (!واصف.مفعّلة || واصف.المعالج == nullptr) {
            return;
        }
        
        // تحقق من التعشيش (nested interrupts)
        if (المقاطعة_الجارية_ >= 0) {
            // مقاطعة داخل مقاطعة - تحقق من الأولوية
            واصف_مقاطعة& الجاري = الواصفات_[المقاطعة_الجارية_ + 16];
            if (واصف.الأولوية >= الجاري.الأولوية) {
                // أولوية أقل، علّق
                علّق_مقاطعة(الرقم);
                return;
            }
        }
        
        // سجّل بدء المعالجة
        uint64_t بداية = التكة_الحالية_;
        int المقاطعة_السابقة = المقاطعة_الجارية_;
        المقاطعة_الجارية_ = الرقم;
        
        // استدعِ المعالج
        السياق->رقم_المقاطعة = الرقم;
        واصف.المعالج(السياق);
        
        // سجّل الانتهاء
        المقاطعة_الجارية_ = المقاطعة_السابقة;
        ++واصف.عدد_الحدوث;
        واصف.آخر_حدوث = التكة_الحالية_;
        واصف.إجمالي_الوقت += (التكة_الحالية_ - بداية);
        ++إجمالي_المقاطعات_;
        
        // عالج المقاطعات المعلّقة
        عالج_المعلّقة();
    }
    
    // =======================================================
    // 📌 المقاطعات المعلّقة
    // =======================================================
    
    void علّق_مقاطعة(int الرقم) {
        int الفهرس = الرقم + 16;
        if (الفهرس >= 0 && الفهرس < أقصى_عدد_مقاطعات) {
            الواصفات_[الفهرس].معلّقة = true;
        }
    }
    
    void عالج_المعلّقة() {
        if (المقاطعات_معطّلة_) return;
        
        // ابحث عن أعلى أولوية معلّقة
        int أفضل_فهرس = -1;
        uint8_t أفضل_أولوية = 255;
        
        for (int i = 0; i < أقصى_عدد_مقاطعات; ++i) {
            if (الواصفات_[i].معلّقة && 
                الواصفات_[i].مفعّلة &&
                الواصفات_[i].الأولوية < أفضل_أولوية) {
                أفضل_أولوية = الواصفات_[i].الأولوية;
                أفضل_فهرس = i;
            }
        }
        
        if (أفضل_فهرس >= 0) {
            الواصفات_[أفضل_فهرس].معلّقة = false;
            سياق_المقاطعة سياق = {};
            عالج_المقاطعة(أفضل_فهرس - 16, &سياق);
        }
    }
    
    // =======================================================
    // 📌 الاستعلامات
    // =======================================================
    
    uint64_t أحضر_إجمالي_المقاطعات() const { return إجمالي_المقاطعات_; }
    int أحضر_المقاطعة_الجارية() const { return المقاطعة_الجارية_; }
    
    const واصف_مقاطعة* أحضر_معلومات(int الرقم) const {
        int الفهرس = الرقم + 16;
        if (الفهرس >= 0 && الفهرس < أقصى_عدد_مقاطعات) {
            return &الواصفات_[الفهرس];
        }
        return nullptr;
    }
    
    void حدّث_التكة() { ++التكة_الحالية_; }

private:
    // معالجات افتراضية
    static void معالج_خطأ_صعب_افتراضي(سياق_المقاطعة* سياق) {
        // في نظام حقيقي: سجّل الخطأ وأعد التشغيل
        while (true) {} // حلقة لا نهائية
    }
    
    static void معالج_تكة_افتراضي(سياق_المقاطعة* سياق) {
        أحضر().حدّث_التكة();
        // استدعِ المجدول
    }
};

متحكم_المقاطعات* متحكم_المقاطعات::النسخة_ = nullptr;

// ==========================================================
// 📌 قسم حرج (Critical Section)
// ==========================================================

/**
 * 📚 للمبتدئين:
 * القسم الحرج هو جزء من الكود لا يجب أن تقاطعه مقاطعة.
 * مثل: تحديث متغير مشترك بين المهام
 */

class قسم_حرج {
public:
    قسم_حرج() {
        متحكم_المقاطعات::أحضر().عطّل_الكل();
    }
    
    ~قسم_حرج() {
        متحكم_المقاطعات::أحضر().فعّل_الكل();
    }
    
    // امنع النسخ
    قسم_حرج(const قسم_حرج&) = delete;
    قسم_حرج& operator=(const قسم_حرج&) = delete;
};

// ماكرو للاستخدام السهل
#define قسم_حرج_ابدأ() { صOS::قسم_حرج __cs;
#define قسم_حرج_انتهى() }

} // namespace صOS

// ==========================================================
// 📌 C API
// ==========================================================

extern "C" {

// التهيئة
void sad_irq_init(void) {
    صOS::متحكم_المقاطعات::أحضر().هيّئ();
}

// تسجيل مقاطعة
int sad_irq_register(int irq_num, void (*handler)(void*), 
                     const char* name, uint8_t priority) {
    return صOS::متحكم_المقاطعات::أحضر().سجّل_مقاطعة(
        irq_num,
        reinterpret_cast<صOS::معالج_مقاطعة>(handler),
        name,
        priority
    ) ? 0 : -1;
}

// إلغاء تسجيل مقاطعة
int sad_irq_unregister(int irq_num) {
    return صOS::متحكم_المقاطعات::أحضر().ألغِ_تسجيل_مقاطعة(irq_num) ? 0 : -1;
}

// تفعيل/تعطيل
void sad_irq_enable(int irq_num) {
    صOS::متحكم_المقاطعات::أحضر().فعّل_مقاطعة(irq_num);
}

void sad_irq_disable(int irq_num) {
    صOS::متحكم_المقاطعات::أحضر().عطّل_مقاطعة(irq_num);
}

// تفعيل/تعطيل الكل
void sad_irq_disable_all(void) {
    صOS::متحكم_المقاطعات::أحضر().عطّل_الكل();
}

void sad_irq_enable_all(void) {
    صOS::متحكم_المقاطعات::أحضر().فعّل_الكل();
}

// تعيين الأولوية
void sad_irq_set_priority(int irq_num, uint8_t priority) {
    صOS::متحكم_المقاطعات::أحضر().عيّن_الأولوية(irq_num, priority);
}

// الإحصائيات
uint64_t sad_irq_get_total(void) {
    return صOS::متحكم_المقاطعات::أحضر().أحضر_إجمالي_المقاطعات();
}

} // extern "C"
