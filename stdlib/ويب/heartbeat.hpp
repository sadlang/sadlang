/**
 * إعدادات نظام Heartbeat
 */
struct إعدادات_heartbeat {
    // الفاصل الزمني بين النبضات (30 ثانية افتراضياً)
    std::chrono::seconds فاصل_النبضات{30};
    
    // مهلة انتظار الرد (5 ثوان افتراضياً)
    std::chrono::seconds مهلة_الرد{5};
    
    // عدد النبضات المفقودة قبل إعلان الانقطاع (3 افتراضياً)
    int نبضات_مفقودة_مسموحة = 3;
    
    // هل نحسب متوسط زمن الاستجابة؟
    bool قياس_زمن_استجابة = true;
    
    // عدد العينات لحساب المتوسط
    int عدد_عينات_زمن = 10;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              قياس زمن الاستجابة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حاسب زمن الاستجابة
 * 
 * يحسب متوسط الوقت بين إرسال ping واستلام pong
 */
class حاسب_زمن_استجابة {
public:
    explicit حاسب_زمن_استجابة(int عدد_عينات = 10)
        : الحد_الأقصى_(عدد_عينات) {}
    
    /**
     * بدء القياس (عند إرسال ping)
     */
    void ابدأ() {
        وقت_البدء_ = std::chrono::steady_clock::now();
        في_انتظار_ = true;
    }
    
    /**
     * إنهاء القياس (عند استلام pong)
     */
    void انتهى() {
        if (!في_انتظار_) return;
        
        auto وقت_النهاية = std::chrono::steady_clock::now();
        auto الفرق = std::chrono::duration_cast<std::chrono::milliseconds>(
            وقت_النهاية - وقت_البدء_
        );
        
        أضف_عينة(الفرق);
        في_انتظار_ = false;
    }
    
    /**
     * متوسط زمن الاستجابة
     */
    std::chrono::milliseconds المتوسط() const {
        if (العينات_.empty()) {
            return std::chrono::milliseconds{0};
        }
        
        long long مجموع = 0;
        for (const auto& عينة : العينات_) {
            مجموع += عينة.count();
        }
        
        return std::chrono::milliseconds{مجموع / static_cast<long long>(العينات_.size())};
    }
    
    /**
     * أقل زمن
     */
    std::chrono::milliseconds الأقل() const {
        if (العينات_.empty()) {
            return std::chrono::milliseconds{0};
        }
        
        auto أصغر = العينات_.front();
        for (const auto& عينة : العينات_) {
            if (عينة < أصغر) أصغر = عينة;
        }
        return أصغر;
    }
    
    /**
     * أكبر زمن
     */
    std::chrono::milliseconds الأكبر() const {
        if (العينات_.empty()) {
            return std::chrono::milliseconds{0};
        }
        
        auto أكبر = العينات_.front();
        for (const auto& عينة : العينات_) {
            if (عينة > أكبر) أكبر = عينة;
        }
        return أكبر;
    }
    
    /**
     * هل في انتظار الرد؟
     */
    bool في_انتظار() const { return في_انتظار_; }
    
    /**
     * إعادة التعيين
     */
    void أعد_التعيين() {
        العينات_.clear();
        في_انتظار_ = false;
    }
    
private:
    void أضف_عينة(std::chrono::milliseconds عينة) {
        العينات_.push_back(عينة);
        
        // حافظ على الحد الأقصى
        while (العينات_.size() > الحد_الأقصى_) {
            العينات_.pop_front();
        }
    }
    
    size_t الحد_الأقصى_;
    std::deque<std::chrono::milliseconds> العينات_;
    std::chrono::steady_clock::time_point وقت_البدء_;
    bool في_انتظار_ = false;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مدير Heartbeat
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حالة الاتصال من منظور Heartbeat
 */
enum class حالة_heartbeat {
    نشط,               // الاتصال يعمل
    في_انتظار,          // في انتظار رد
    متأخر,             // الرد متأخر
    منقطع              // يُعتبر منقطعاً
};

/**
 * مدير Heartbeat
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │                   مدير Heartbeat                       │
 *     │                                                        │
 *     │   الحالة: نشط ✓                                        │
 *     │   زمن الاستجابة: 45ms                                  │
 *     │   النبضات المفقودة: 0                                  │
 *     │                                                        │
 *     │   ┌──────────────────────────────────────────────┐    │
 *     │   │ الإحصائيات:                                  │    │
 *     │   │                                              │    │
 *     │   │   النبضات المُرسَلة: 127                     │    │
 *     │   │   الردود المُستلَمة: 127                     │    │
 *     │   │   متوسط الزمن: 45ms                         │    │
 *     │   │   أقل زمن: 12ms                             │    │
 *     │   │   أكبر زمن: 234ms                           │    │
 *     │   │                                              │    │
 *     │   └──────────────────────────────────────────────┘    │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
class مدير_heartbeat {
public:
    // أنواع المعالجات
    using دالة_ping = std::function<void()>;
    using معالج_انقطاع = std::function<void()>;
    using معالج_استعادة = std::function<void()>;
    
    explicit مدير_heartbeat(
        const إعدادات_heartbeat& إعدادات = إعدادات_heartbeat{}
    ) : الإعدادات_(إعدادات),
        حاسب_الزمن_(إعدادات.عدد_عينات_زمن),
        الحالة_(حالة_heartbeat::نشط) {}
    
    ~مدير_heartbeat() {
        أوقف();
    }
    
    /**
     * تعيين دالة إرسال ping
     */
    void عند_إرسال_ping(دالة_ping دالة) {
        دالة_ping_ = دالة;
    }
    
    /**
     * معالج الانقطاع
     */
    void عند_انقطاع(معالج_انقطاع معالج) {
        معالج_انقطاع_ = معالج;
    }
    
    /**
     * معالج استعادة الاتصال
     */
    void عند_استعادة(معالج_استعادة معالج) {
        معالج_استعادة_ = معالج;
    }
    
    /**
     * بدء Heartbeat
     */
    void ابدأ() {
        يعمل_ = true;
        النبضات_المفقودة_ = 0;
        
        // خيط المراقبة
        خيط_المراقبة_ = std::make_unique<std::thread>([this]() {
            حلقة_المراقبة();
        });
    }
    
    /**
     * إيقاف Heartbeat
     */
    void أوقف() {
        يعمل_ = false;
        
        if (خيط_المراقبة_ && خيط_المراقبة_->joinable()) {
            خيط_المراقبة_->join();
        }
    }
    
    /**
     * استلام pong (الرد على ping)
     */
    void استلم_pong() {
        if (الإعدادات_.قياس_زمن_استجابة) {
            حاسب_الزمن_.انتهى();
        }
        
        النبضات_المفقودة_ = 0;
        
        // هل كنا منقطعين؟
        if (الحالة_ == حالة_heartbeat::منقطع) {
            الحالة_ = حالة_heartbeat::نشط;
            
            if (معالج_استعادة_) {
                معالج_استعادة_();
            }
        }
        else {
            الحالة_ = حالة_heartbeat::نشط;
        }
    }
    
    /**
     * الحالة الحالية
     */
    حالة_heartbeat الحالة() const {
        return الحالة_;
    }
    
    /**
     * زمن الاستجابة
     */
    std::chrono::milliseconds زمن_الاستجابة() const {
        return حاسب_الزمن_.المتوسط();
    }
    
    /**
     * الإحصائيات
     */
    struct إحصائيات {
        int نبضات_مُرسَلة = 0;
        int ردود_مُستلَمة = 0;
        int نبضات_مفقودة = 0;
        std::chrono::milliseconds متوسط_زمن{0};
        std::chrono::milliseconds أقل_زمن{0};
        std::chrono::milliseconds أكبر_زمن{0};
    };
    
    إحصائيات الإحصائيات() const {
        إحصائيات إحص;
        إحص.نبضات_مُرسَلة = نبضات_مُرسَلة_;
        إحص.ردود_مُستلَمة = ردود_مُستلَمة_;
        إحص.نبضات_مفقودة = النبضات_المفقودة_;
        إحص.متوسط_زمن = حاسب_الزمن_.المتوسط();
        إحص.أقل_زمن = حاسب_الزمن_.الأقل();
        إحص.أكبر_زمن = حاسب_الزمن_.الأكبر();
        return إحص;
    }
    
private:
    void حلقة_المراقبة() {
        while (يعمل_) {
            // أرسل ping
            أرسل_ping();
            
            // انتظر
            std::this_thread::sleep_for(الإعدادات_.مهلة_الرد);
            
            // تحقق من الرد
            if (حاسب_الزمن_.في_انتظار()) {
                // لم نستلم رداً!
                النبضات_المفقودة_++;
                
                if (النبضات_المفقودة_ >= الإعدادات_.نبضات_مفقودة_مسموحة) {
                    // انقطاع!
                    الحالة_ = حالة_heartbeat::منقطع;
                    
                    if (معالج_انقطاع_) {
                        معالج_انقطاع_();
                    }
                }
                else {
                    الحالة_ = حالة_heartbeat::متأخر;
                }
            }
            
            // انتظر الفاصل المتبقي
            auto انتظار_متبقي = الإعدادات_.فاصل_النبضات - الإعدادات_.مهلة_الرد;
            if (انتظار_متبقي.count() > 0) {
                std::this_thread::sleep_for(انتظار_متبقي);
            }
        }
    }
    
    void أرسل_ping() {
        if (الإعدادات_.قياس_زمن_استجابة) {
            حاسب_الزمن_.ابدأ();
        }
        
        نبضات_مُرسَلة_++;
        
        if (دالة_ping_) {
            دالة_ping_();
        }
        
        الحالة_ = حالة_heartbeat::في_انتظار;
    }
    
    إعدادات_heartbeat الإعدادات_;
    حاسب_زمن_استجابة حاسب_الزمن_;
    std::atomic<حالة_heartbeat> الحالة_;
    std::atomic<bool> يعمل_{false};
    std::atomic<int> النبضات_المفقودة_{0};
    
    int نبضات_مُرسَلة_ = 0;
    int ردود_مُستلَمة_ = 0;
    
    دالة_ping دالة_ping_;
    معالج_انقطاع معالج_انقطاع_;
    معالج_استعادة معالج_استعادة_;
    
    std::unique_ptr<std::thread> خيط_المراقبة_;
};

