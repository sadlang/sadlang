/**
 * سبب الانقطاع المُكتشَف
 */
enum class سبب_انقطاع {
    غير_معروف,
    مهلة_heartbeat,         // لم نستلم pong
    خطأ_شبكة,              // خطأ من الشبكة
    إغلاق_من_الخادم,       // الخادم أغلق الاتصال
    إغلاق_يدوي             // المستخدم أغلق
};

/**
 * كاشف انقطاع متقدم
 * 
 * يدمج عدة طرق لكشف الانقطاع
 */
class كاشف_انقطاع {
public:
    using معالج_انقطاع = std::function<void(سبب_انقطاع)>;
    
    كاشف_انقطاع() {
        // إعداد heartbeat
        الـheartbeat_.عند_انقطاع([this]() {
            أبلغ_عن_انقطاع(سبب_انقطاع::مهلة_heartbeat);
        });
    }
    
    /**
     * تعيين معالج الانقطاع
     */
    void عند_انقطاع(معالج_انقطاع معالج) {
        المعالج_ = معالج;
    }
    
    /**
     * بدء المراقبة
     */
    void ابدأ() {
        الـheartbeat_.ابدأ();
    }
    
    /**
     * إيقاف المراقبة
     */
    void أوقف() {
        الـheartbeat_.أوقف();
    }
    
    /**
     * الإبلاغ عن خطأ شبكة
     */
    void خطأ_شبكة() {
        أبلغ_عن_انقطاع(سبب_انقطاع::خطأ_شبكة);
    }
    
    /**
     * الإبلاغ عن إغلاق من الخادم
     */
    void إغلاق_خادم() {
        أبلغ_عن_انقطاع(سبب_انقطاع::إغلاق_من_الخادم);
    }
    
    /**
     * استلام pong
     */
    void استلم_pong() {
        الـheartbeat_.استلم_pong();
    }
    
    /**
     * الوصول لمدير heartbeat
     */
    مدير_heartbeat& الـheartbeat() { return الـheartbeat_; }
    
private:
    void أبلغ_عن_انقطاع(سبب_انقطاع السبب) {
        if (المعالج_) {
            المعالج_(السبب);
        }
    }
    
    مدير_heartbeat الـheartbeat_;
    معالج_انقطاع المعالج_;
};

