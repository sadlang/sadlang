/**
 * اشتراك سريع
 */
inline bool اشترك_في(const std::string& قناة, const مشترك& م) {
    return مدير_قنوات::المثيل().احصل_أو_أنشئ(قناة)->اشترك(م);
}

/**
 * إلغاء اشتراك سريع
 */
inline void الغِ_اشتراك_من(const std::string& قناة, const std::string& معرف) {
    مدير_قنوات::المثيل().احصل_أو_أنشئ(قناة)->الغِ_اشتراك(معرف);
}

/**
 * بث سريع
 */
inline void بث_في(const std::string& قناة, const std::string& حدث, const std::any& بيانات) {
    مدير_قنوات::المثيل().احصل_أو_أنشئ(قناة)->بث(حدث, بيانات);
}

