/**
 * نمط القناة (مع متغيرات)
 * 
 * مثال: "محادثة:{غرفة_id}" يطابق:
 * - "محادثة:1"
 * - "محادثة:غرفة_الألعاب"
 * - "محادثة:abc123"
 */
class نمط_قناة {
public:
    explicit نمط_قناة(const std::string& نمط) : النمط_(نمط) {
        حلل_النمط();
    }
    
    /**
     * هل هذا الاسم يطابق النمط؟
     */
    bool يطابق(const std::string& اسم_قناة) const {
        return std::regex_match(اسم_قناة, التعبير_النمطي_);
    }
    
    /**
     * استخراج المتغيرات من اسم القناة
     */
    std::map<std::string, std::string> استخرج_متغيرات(
        const std::string& اسم_قناة
    ) const {
        std::map<std::string, std::string> متغيرات;
        
        std::smatch مطابقات;
        if (std::regex_match(اسم_قناة, مطابقات, التعبير_النمطي_)) {
            for (size_t i = 0; i < أسماء_المتغيرات_.size(); i++) {
                if (i + 1 < مطابقات.size()) {
                    متغيرات[أسماء_المتغيرات_[i]] = مطابقات[i + 1].str();
                }
            }
        }
        
        return متغيرات;
    }
    
    const std::string& النمط() const { return النمط_; }
    
private:
    void حلل_النمط() {
        std::string نمط_regex;
        std::string حالي;
        bool في_متغير = false;
        
        for (char c : النمط_) {
            if (c == '{') {
                في_متغير = true;
                حالي.clear();
            }
            else if (c == '}') {
                في_متغير = false;
                أسماء_المتغيرات_.push_back(حالي);
                نمط_regex += "([^/:]+)";
            }
            else if (في_متغير) {
                حالي += c;
            }
            else {
                // هروب من الأحرف الخاصة
                if (c == '.' || c == '*' || c == '+' || c == '?') {
                    نمط_regex += '\\';
                }
                نمط_regex += c;
            }
        }
        
        التعبير_النمطي_ = std::regex("^" + نمط_regex + "$");
    }
    
    std::string النمط_;
    std::regex التعبير_النمطي_;
    std::vector<std::string> أسماء_المتغيرات_;
};

// ═══════════════════════════════════════════════════════════════════════════════
