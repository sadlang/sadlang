/**
 * مدير القنوات - ينظم كل القنوات
 * 
 *     ┌──────────────────────────────────────────────────────┐
 *     │                   مدير القنوات                       │
 *     │  ┌──────────────────────────────────────────────┐   │
 *     │  │ القنوات النشطة:                              │   │
 *     │  │                                              │   │
 *     │  │   "محادثة:غرفة_1" ─── 5 مشتركين             │   │
 *     │  │   "محادثة:غرفة_2" ─── 3 مشتركين             │   │
 *     │  │   "إشعارات:عامة" ─── 100 مشترك              │   │
 *     │  │   "لعبة:غرفة_5" ─── 2 لاعبين                │   │
 *     │  │                                              │   │
 *     │  └──────────────────────────────────────────────┘   │
 *     │                                                      │
 *     │  الأنماط المُسجَّلة:                                 │
 *     │   📝 "محادثة:{غرفة_id}" → صنف_محادثة                │
 *     │   📝 "إشعارات:{نوع}" → صنف_إشعارات                  │
 *     │   📝 "لعبة:{لعبة_id}" → صنف_لعبة                    │
 *     │                                                      │
 *     └──────────────────────────────────────────────────────┘
 */
class مدير_قنوات {
public:
    using مصنع_قناة = std::function<std::shared_ptr<قناة>(
        const std::string&, 
        const std::map<std::string, std::string>&
    )>;
    
    /**
     * الحصول على المثيل الوحيد
     */
    static مدير_قنوات& المثيل() {
        static مدير_قنوات مدير;
        return مدير;
    }
    
    /**
     * تسجيل نمط قناة
     */
    void سجّل_نمط(const std::string& نمط, مصنع_قناة مصنع) {
        std::lock_guard<std::mutex> قفل(القفل_);
        الأنماط_.emplace_back(نمط_قناة(نمط), مصنع);
    }
    
    /**
     * الحصول على قناة (أو إنشاؤها)
     */
    std::shared_ptr<قناة> احصل_أو_أنشئ(const std::string& اسم) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        // هل موجودة؟
        if (القنوات_.count(اسم)) {
            return القنوات_[اسم];
        }
        
        // ابحث عن نمط مطابق
        for (const auto& [نمط, مصنع] : الأنماط_) {
            if (نمط.يطابق(اسم)) {
                auto متغيرات = نمط.استخرج_متغيرات(اسم);
                auto قناة_جديدة = مصنع(اسم, متغيرات);
                القنوات_[اسم] = قناة_جديدة;
                return قناة_جديدة;
            }
        }
        
        // قناة عادية
        auto قناة_جديدة = std::make_shared<قناة>(اسم);
        القنوات_[اسم] = قناة_جديدة;
        return قناة_جديدة;
    }
    
    /**
     * حذف قناة فارغة
     */
    void احذف_إذا_فارغة(const std::string& اسم) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        if (القنوات_.count(اسم) && القنوات_[اسم]->عدد_المشتركين() == 0) {
            القنوات_.erase(اسم);
        }
    }
    
    /**
     * قائمة القنوات النشطة
     */
    std::vector<std::string> القنوات_النشطة() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        std::vector<std::string> أسماء;
        for (const auto& [اسم, _] : القنوات_) {
            أسماء.push_back(اسم);
        }
        return أسماء;
    }
    
    /**
     * إحصائيات
     */
    struct إحصائيات {
        size_t عدد_القنوات = 0;
        size_t إجمالي_المشتركين = 0;
    };
    
    إحصائيات الإحصائيات() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        إحصائيات إحص;
        إحص.عدد_القنوات = القنوات_.size();
        for (const auto& [_, قناة] : القنوات_) {
            إحص.إجمالي_المشتركين += قناة->عدد_المشتركين();
        }
        return إحص;
    }
    
private:
    مدير_قنوات() = default;
    
    mutable std::mutex القفل_;
    std::map<std::string, std::shared_ptr<قناة>> القنوات_;
    std::vector<std::pair<نمط_قناة, مصنع_قناة>> الأنماط_;
};

