/**
 * أولوية الرسالة
 */
enum class أولوية_رسالة {
    عادية,         // رسائل عادية
    عالية,          // رسائل مهمة
    حرجة           // رسائل حرجة (نظام)
};

/**
 * رسالة قناة
 * 
 * مثل ظرف البريد:
 * - الحدث: عنوان الرسالة (مثل "رسالة_جديدة")
 * - البيانات: محتوى الرسالة
 * - المرسل: من أرسلها
 */
struct رسالة_قناة {
    std::string الحدث;
    std::any البيانات;
    std::string المرسل;
    std::chrono::system_clock::time_point الوقت;
    أولوية_رسالة الأولوية = أولوية_رسالة::عادية;
    std::string معرف_رسالة;
};

