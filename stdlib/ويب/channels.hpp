/**
 * معلومات المشترك في القناة
 */
struct مشترك {
    std::string المعرف;
    std::string اسم_المستخدم;
    std::chrono::system_clock::time_point وقت_الاشتراك;
    std::map<std::string, std::string> بيانات_إضافية;
    
    // حالة الاتصال
    bool متصل = true;
    std::chrono::system_clock::time_point آخر_نشاط;
};

