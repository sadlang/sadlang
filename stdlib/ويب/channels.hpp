/**
 * القناة - مكان تجمع المشتركين للرسائل
 * 
 *     ┌─────────────────────────────────────────────┐
 *     │                القناة                       │
 *     │  ┌─────────────────────────────────────┐   │
 *     │  │ المشتركون:                          │   │
 *     │  │   👤 أحمد                           │   │
 *     │  │   👤 سارة                           │   │
 *     │  │   👤 محمد                           │   │
 *     │  └─────────────────────────────────────┘   │
 *     │                                             │
 *     │  المستمعون (Listeners):                    │
 *     │   📧 "رسالة" → معالج_الرسائل()             │
 *     │   🚪 "انضمام" → معالج_الانضمام()           │
 *     │   👋 "مغادرة" → معالج_المغادرة()           │
 *     │                                             │
 *     └─────────────────────────────────────────────┘
 */
class قناة {
public:
    using معالج_حدث = std::function<void(const رسالة_قناة&)>;
    using معالج_اشتراك = std::function<bool(const مشترك&)>;
    
    explicit قناة(const std::string& الاسم) : الاسم_(الاسم) {
        وقت_الإنشاء_ = std::chrono::system_clock::now();
    }
    
    /**
     * الاسم
     */
    const std::string& الاسم() const { return الاسم_; }
    
    /**
     * إضافة مشترك
     */
    bool اشترك(const مشترك& م) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        // تحقق من الصلاحيات
        if (معالج_قبول_اشتراك_ && !معالج_قبول_اشتراك_(م)) {
            return false;
        }
        
        المشتركون_[م.المعرف] = م;
        
        // إشعار الانضمام
        رسالة_قناة رسالة;
        رسالة.الحدث = "انضمام";
        رسالة.المرسل = م.المعرف;
        رسالة.الوقت = std::chrono::system_clock::now();
        
        بث_داخلي(رسالة);
        
        return true;
    }
    
    /**
     * إزالة مشترك
     */
    void الغِ_اشتراك(const std::string& معرف) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        if (المشتركون_.count(معرف)) {
            // إشعار المغادرة
            رسالة_قناة رسالة;
            رسالة.الحدث = "مغادرة";
            رسالة.المرسل = معرف;
            رسالة.الوقت = std::chrono::system_clock::now();
            
            بث_داخلي(رسالة);
            
            المشتركون_.erase(معرف);
        }
    }
    
    /**
     * هل المستخدم مشترك؟
     */
    bool مشترك(const std::string& معرف) const {
        std::lock_guard<std::mutex> قفل(القفل_);
        return المشتركون_.count(معرف) > 0;
    }
    
    /**
     * عدد المشتركين
     */
    size_t عدد_المشتركين() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        return المشتركون_.size();
    }
    
    /**
     * قائمة المشتركين
     */
    std::vector<مشترك> المشتركون() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        std::vector<مشترك> قائمة;
        for (const auto& [_, م] : المشتركون_) {
            قائمة.push_back(م);
        }
        return قائمة;
    }
    
    /**
     * تسجيل مستمع للحدث
     */
    void عند(const std::string& حدث, معالج_حدث معالج) {
        std::lock_guard<std::mutex> قفل(القفل_);
        المستمعون_[حدث].push_back(معالج);
    }
    
    /**
     * بث رسالة لكل المشتركين
     */
    void بث(const std::string& حدث, const std::any& بيانات) {
        رسالة_قناة رسالة;
        رسالة.الحدث = حدث;
        رسالة.البيانات = بيانات;
        رسالة.الوقت = std::chrono::system_clock::now();
        
        std::lock_guard<std::mutex> قفل(القفل_);
        بث_داخلي(رسالة);
    }
    
    /**
     * إرسال رسالة لمشترك معين
     */
    void أرسل_إلى(const std::string& معرف, const std::string& حدث, const std::any& بيانات) {
        رسالة_قناة رسالة;
        رسالة.الحدث = حدث;
        رسالة.البيانات = بيانات;
        رسالة.الوقت = std::chrono::system_clock::now();
        
        std::lock_guard<std::mutex> قفل(القفل_);
        if (المشتركون_.count(معرف) && معالج_إرسال_) {
            معالج_إرسال_(معرف, رسالة);
        }
    }
    
    /**
     * تعيين معالج قبول الاشتراك
     */
    void عند_طلب_اشتراك(معالج_اشتراك معالج) {
        معالج_قبول_اشتراك_ = معالج;
    }
    
    /**
     * تعيين معالج الإرسال
     */
    using معالج_إرسال = std::function<void(const std::string&, const رسالة_قناة&)>;
    void حدد_معالج_إرسال(معالج_إرسال معالج) {
        معالج_إرسال_ = معالج;
    }
    
private:
    void بث_داخلي(const رسالة_قناة& رسالة) {
        // استدعاء المستمعين
        if (المستمعون_.count(رسالة.الحدث)) {
            for (const auto& معالج : المستمعون_[رسالة.الحدث]) {
                معالج(رسالة);
            }
        }
        
        // إرسال للمشتركين
        if (معالج_إرسال_) {
            for (const auto& [معرف, _] : المشتركون_) {
                معالج_إرسال_(معرف, رسالة);
            }
        }
    }
    
    std::string الاسم_;
    std::chrono::system_clock::time_point وقت_الإنشاء_;
    
    mutable std::mutex القفل_;
    std::map<std::string, مشترك> المشتركون_;
    std::map<std::string, std::vector<معالج_حدث>> المستمعون_;
    
    معالج_اشتراك معالج_قبول_اشتراك_;
    معالج_إرسال معالج_إرسال_;
};

