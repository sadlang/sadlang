/**
 * خوارزمية الضغط
 */
enum class خوارزمية_ضغط {
    بدون,              // لا ضغط
    deflate,           // الأكثر شيوعاً
    gzip,              // مع headers
    lz4,               // سريع جداً
    zstd,              // نسبة ضغط عالية
    brotli             // الأفضل للنصوص
};

/**
 * مستوى الضغط
 */
enum class مستوى_ضغط {
    أسرع,              // ضغط سريع، نسبة منخفضة
    متوازن,            // توازن بين السرعة والحجم
    أقصى               // أفضل نسبة، أبطأ
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              نتيجة الضغط
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * نتيجة عملية الضغط
 */
struct نتيجة_ضغط {
    std::vector<uint8_t> البيانات;
    خوارزمية_ضغط الخوارزمية;
    size_t الحجم_الأصلي;
    size_t الحجم_المضغوط;
    bool نجح = false;
    std::string خطأ;
    
    /**
     * نسبة التوفير
     */
    double نسبة_التوفير() const {
        if (الحجم_الأصلي == 0) return 0;
        return 100.0 * (1.0 - (double)الحجم_المضغوط / الحجم_الأصلي);
    }
    
    /**
     * هل الضغط مفيد؟
     */
    bool مفيد() const {
        return نجح && الحجم_المضغوط < الحجم_الأصلي;
    }
};

/**
 * نتيجة فك الضغط
 */
struct نتيجة_فك_ضغط {
    std::vector<uint8_t> البيانات;
    size_t الحجم_الأصلي;
    bool نجح = false;
    std::string خطأ;
    
    /**
     * كنص
     */
    std::string كنص() const {
        return std::string(البيانات.begin(), البيانات.end());
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              ضاغط الرسائل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * ضاغط الرسائل
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │                  ضاغط الرسائل                          │
 *     │                                                        │
 *     │   الخوارزمية: deflate                                  │
 *     │   المستوى: متوازن                                      │
 *     │   الحد الأدنى: 100 بايت                                │
 *     │                                                        │
 *     │   الإحصائيات:                                          │
 *     │   ────────────                                         │
 *     │   رسائل مضغوطة: 1,234                                  │
 *     │   إجمالي أصلي: 2.5 MB                                  │
 *     │   إجمالي مضغوط: 0.8 MB                                 │
 *     │   متوسط التوفير: 68%                                   │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
class ضاغط_رسائل {
public:
    explicit ضاغط_رسائل(
        خوارزمية_ضغط خوارزمية = خوارزمية_ضغط::deflate,
        مستوى_ضغط مستوى = مستوى_ضغط::متوازن
    ) : الخوارزمية_(خوارزمية), المستوى_(مستوى) {}
    
    /**
     * ضغط رسالة
     */
    نتيجة_ضغط اضغط(const std::string& رسالة) {
        return اضغط(
            std::vector<uint8_t>(رسالة.begin(), رسالة.end())
        );
    }
    
    /**
     * ضغط بيانات
     */
    نتيجة_ضغط اضغط(const std::vector<uint8_t>& بيانات) {
        نتيجة_ضغط نتيجة;
        نتيجة.الحجم_الأصلي = بيانات.size();
        نتيجة.الخوارزمية = الخوارزمية_;
        
        // هل الرسالة صغيرة جداً؟
        if (بيانات.size() < الحد_الأدنى_للضغط_) {
            نتيجة.البيانات = بيانات;
            نتيجة.الحجم_المضغوط = بيانات.size();
            نتيجة.نجح = true;
            return نتيجة;
        }
        
        // اضغط حسب الخوارزمية
        switch (الخوارزمية_) {
            case خوارزمية_ضغط::بدون:
                نتيجة.البيانات = بيانات;
                نتيجة.الحجم_المضغوط = بيانات.size();
                نتيجة.نجح = true;
                break;
                
            case خوارزمية_ضغط::deflate:
                نتيجة = اضغط_deflate(بيانات);
                break;
                
            case خوارزمية_ضغط::lz4:
                نتيجة = اضغط_lz4(بيانات);
                break;
                
            case خوارزمية_ضغط::zstd:
                نتيجة = اضغط_zstd(بيانات);
                break;
                
            default:
                نتيجة = اضغط_deflate(بيانات);
                break;
        }
        
        // إحصائيات
        if (نتيجة.نجح) {
            إجمالي_أصلي_ += نتيجة.الحجم_الأصلي;
            إجمالي_مضغوط_ += نتيجة.الحجم_المضغوط;
            رسائل_مضغوطة_++;
        }
        
        return نتيجة;
    }
    
    /**
     * فك ضغط
     */
    نتيجة_فك_ضغط فك_الضغط(
        const std::vector<uint8_t>& بيانات,
        خوارزمية_ضغط خوارزمية
    ) {
        switch (خوارزمية) {
            case خوارزمية_ضغط::بدون:
                return {بيانات, بيانات.size(), true, ""};
                
            case خوارزمية_ضغط::deflate:
                return فك_ضغط_deflate(بيانات);
                
            case خوارزمية_ضغط::lz4:
                return فك_ضغط_lz4(بيانات);
                
            case خوارزمية_ضغط::zstd:
                return فك_ضغط_zstd(بيانات);
                
            default:
                return فك_ضغط_deflate(بيانات);
        }
    }
    
    /**
     * تعيين الحد الأدنى للضغط
     */
    void حدد_الحد_الأدنى(size_t حد) {
        الحد_الأدنى_للضغط_ = حد;
    }
    
    /**
     * الإحصائيات
     */
    struct إحصائيات {
        size_t رسائل_مضغوطة = 0;
        size_t إجمالي_أصلي = 0;
        size_t إجمالي_مضغوط = 0;
        
        double متوسط_التوفير() const {
            if (إجمالي_أصلي == 0) return 0;
            return 100.0 * (1.0 - (double)إجمالي_مضغوط / إجمالي_أصلي);
        }
    };
    
    إحصائيات الإحصائيات() const {
        return {رسائل_مضغوطة_, إجمالي_أصلي_, إجمالي_مضغوط_};
    }
    
private:
    // ═══════════════════════════════════════════════════════════════════
    // تنفيذ Deflate (مبسط - في الإنتاج استخدم zlib)
    // ═══════════════════════════════════════════════════════════════════
    
    نتيجة_ضغط اضغط_deflate(const std::vector<uint8_t>& بيانات) {
        نتيجة_ضغط نتيجة;
        نتيجة.الحجم_الأصلي = بيانات.size();
        نتيجة.الخوارزمية = خوارزمية_ضغط::deflate;
        
        // في الإنتاج: استخدم zlib
        // هنا نستخدم Run-Length Encoding مبسط للتوضيح
        
        std::vector<uint8_t> مضغوط;
        مضغوط.reserve(بيانات.size());
        
        size_t i = 0;
        while (i < بيانات.size()) {
            uint8_t الحرف = بيانات[i];
            size_t عدد = 1;
            
            // عد التكرارات
            while (i + عدد < بيانات.size() && 
                   بيانات[i + عدد] == الحرف && 
                   عدد < 255) {
                عدد++;
            }
            
            if (عدد >= 3) {
                // ضغط
                مضغوط.push_back(0xFF);  // علامة الضغط
                مضغوط.push_back(static_cast<uint8_t>(عدد));
                مضغوط.push_back(الحرف);
            }
            else {
                // بدون ضغط
                for (size_t j = 0; j < عدد; j++) {
                    if (الحرف == 0xFF) {
                        مضغوط.push_back(0xFF);
                        مضغوط.push_back(0x00);  // هروب
                    }
                    else {
                        مضغوط.push_back(الحرف);
                    }
                }
            }
            
            i += عدد;
        }
        
        نتيجة.البيانات = مضغوط;
        نتيجة.الحجم_المضغوط = مضغوط.size();
        نتيجة.نجح = true;
        
        return نتيجة;
    }
    
    نتيجة_فك_ضغط فك_ضغط_deflate(const std::vector<uint8_t>& بيانات) {
        نتيجة_فك_ضغط نتيجة;
        
        std::vector<uint8_t> مفكوك;
        mفكوك.reserve(بيانات.size() * 2);
        
        size_t i = 0;
        while (i < بيانات.size()) {
            if (بيانات[i] == 0xFF) {
                i++;
                if (i >= بيانات.size()) break;
                
                if (بيانات[i] == 0x00) {
                    // هروب - 0xFF حقيقي
                    مفكوك.push_back(0xFF);
                    i++;
                }
                else {
                    // ضغط
                    uint8_t عدد = بيانات[i++];
                    if (i >= بيانات.size()) break;
                    uint8_t الحرف = بيانات[i++];
                    
                    for (uint8_t j = 0; j < عدد; j++) {
                        مفكوك.push_back(الحرف);
                    }
                }
            }
            else {
                مفكوك.push_back(بيانات[i++]);
            }
        }
        
        نتيجة.البيانات = مفكوك;
        نتيجة.الحجم_الأصلي = مفكوك.size();
        نتيجة.نجح = true;
        
        return نتيجة;
    }
    
    // ═══════════════════════════════════════════════════════════════════
    // تنفيذ LZ4 (مبسط)
    // ═══════════════════════════════════════════════════════════════════
    
    نتيجة_ضغط اضغط_lz4(const std::vector<uint8_t>& بيانات) {
        // في الإنتاج: استخدم مكتبة LZ4
        return اضغط_deflate(بيانات);  // fallback
    }
    
    نتيجة_فك_ضغط فك_ضغط_lz4(const std::vector<uint8_t>& بيانات) {
        return فك_ضغط_deflate(بيانات);
    }
    
    // ═══════════════════════════════════════════════════════════════════
    // تنفيذ ZSTD (مبسط)
    // ═══════════════════════════════════════════════════════════════════
    
    نتيجة_ضغط اضغط_zstd(const std::vector<uint8_t>& بيانات) {
        // في الإنتاج: استخدم مكتبة ZSTD
        return اضغط_deflate(بيانات);  // fallback
    }
    
    نتيجة_فك_ضغط فك_ضغط_zstd(const std::vector<uint8_t>& بيانات) {
        return فك_ضغط_deflate(بيانات);
    }
    
    خوارزمية_ضغط الخوارزمية_;
    مستوى_ضغط المستوى_;
    size_t الحد_الأدنى_للضغط_ = 100;
    
    // إحصائيات
    size_t رسائل_مضغوطة_ = 0;
    size_t إجمالي_أصلي_ = 0;
    size_t إجمالي_مضغوط_ = 0;
};

