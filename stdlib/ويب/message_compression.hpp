/**
 * ضاغط ذكي يختار الخوارزمية تلقائياً
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │                   الضاغط الذكي                         │
 *     │                                                        │
 *     │   يختار الخوارزمية الأفضل حسب:                         │
 *     │   • نوع البيانات (نص، JSON، ثنائي)                    │
 *     │   • حجم البيانات                                       │
 *     │   • سرعة المطلوبة vs نسبة الضغط                       │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
class ضاغط_ذكي {
public:
    /**
     * ضغط ذكي
     */
    نتيجة_ضغط اضغط(const std::string& رسالة) {
        // اختر الخوارزمية
        auto خوارزمية = اختر_خوارزمية(رسالة);
        
        ضاغط_رسائل ضاغط(خوارزمية);
        return ضاغط.اضغط(رسالة);
    }
    
private:
    خوارزمية_ضغط اختر_خوارزمية(const std::string& رسالة) {
        // صغير جداً؟ لا تضغط
        if (رسالة.size() < 50) {
            return خوارزمية_ضغط::بدون;
        }
        
        // JSON?
        if (رسالة.front() == '{' || رسالة.front() == '[') {
            return خوارزمية_ضغط::zstd;  // الأفضل للـ JSON
        }
        
        // نص عربي?
        bool عربي = false;
        for (char c : رسالة) {
            if (static_cast<unsigned char>(c) > 127) {
                عربي = true;
                break;
            }
        }
        
        if (عربي) {
            return خوارزمية_ضغط::brotli;  // الأفضل للنصوص
        }
        
        // افتراضي
        return خوارزمية_ضغط::deflate;
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              رأس الرسالة المضغوطة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * رأس الرسالة المضغوطة
 * 
 * يُضاف في بداية الرسالة لمعرفة كيفية فكها
 */
struct رأس_ضغط {
    uint8_t السحر[2] = {0xC0, 0xDE};  // للتعرف
    uint8_t الخوارزمية;
    uint32_t الحجم_الأصلي;
    uint32_t checksum;
    
    /**
     * تسلسل الرأس
     */
    std::vector<uint8_t> سلسل() const {
        std::vector<uint8_t> بيانات;
        بيانات.push_back(السحر[0]);
        بيانات.push_back(السحر[1]);
        بيانات.push_back(الخوارزمية);
        
        // الحجم (little-endian)
        بيانات.push_back(الحجم_الأصلي & 0xFF);
        بيانات.push_back((الحجم_الأصلي >> 8) & 0xFF);
        بيانات.push_back((الحجم_الأصلي >> 16) & 0xFF);
        بيانات.push_back((الحجم_الأصلي >> 24) & 0xFF);
        
        // checksum
        بيانات.push_back(checksum & 0xFF);
        بيانات.push_back((checksum >> 8) & 0xFF);
        بيانات.push_back((checksum >> 16) & 0xFF);
        بيانات.push_back((checksum >> 24) & 0xFF);
        
        return بيانات;
    }
    
    /**
     * قراءة من بيانات
     */
    static std::optional<رأس_ضغط> من_بيانات(const std::vector<uint8_t>& بيانات) {
        if (بيانات.size() < 11) return std::nullopt;
        
        رأس_ضغط رأس;
        
        // تحقق من السحر
        if (بيانات[0] != 0xC0 || بيانات[1] != 0xDE) {
            return std::nullopt;
        }
        
        رأس.الخوارزمية = بيانات[2];
        رأس.الحجم_الأصلي = بيانات[3] | (بيانات[4] << 8) | 
                          (بيانات[5] << 16) | (بيانات[6] << 24);
        رأس.checksum = بيانات[7] | (بيانات[8] << 8) | 
                       (بيانات[9] << 16) | (بيانات[10] << 24);
        
        return رأس;
    }
    
    /**
     * حجم الرأس
     */
    static constexpr size_t الحجم = 11;
};

