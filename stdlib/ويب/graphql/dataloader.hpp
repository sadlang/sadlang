/**
 * مفتاح التحميل (يمكن أن يكون أي نوع)
 */
template<typename K>
struct مفتاح_تحميل {
    K القيمة;
    std::chrono::steady_clock::time_point وقت_الطلب;
    
    مفتاح_تحميل(const K& قيمة) 
        : القيمة(قيمة), وقت_الطلب(std::chrono::steady_clock::now()) {}
};

/**
 * نتيجة التحميل
 */
template<typename V>
struct نتيجة_تحميل {
    std::optional<V> القيمة;
    std::optional<std::string> خطأ;
    
    bool نجح() const { return القيمة.has_value() && !خطأ.has_value(); }
    bool فشل() const { return خطأ.has_value(); }
};

