/**
 * مصنع DataLoader
 * 
 * ينشئ DataLoader لكل نوع علاقة
 */
class مصنع_dataloader {
public:
    /**
     * تسجيل دالة تحميل لعلاقة
     */
    template<typename K, typename V>
    void سجّل(
        const std::string& اسم_العلاقة,
        typename DataLoader<K, V>::دالة_تحميل_دفعة دالة
    ) {
        الدوال_[اسم_العلاقة] = [دالة]() {
            return std::make_shared<DataLoader<K, V>>(دالة);
        };
    }
    
    /**
     * الحصول على DataLoader
     */
    template<typename K, typename V>
    std::shared_ptr<DataLoader<K, V>> احصل(const std::string& اسم_العلاقة) {
        if (!الدوال_.count(اسم_العلاقة)) {
            return nullptr;
        }
        
        // في الإنتاج: خزّن لكل طلب GraphQL
        auto مصنع = الدوال_[اسم_العلاقة];
        return std::static_pointer_cast<DataLoader<K, V>>(
            std::any_cast<std::shared_ptr<void>>(مصنع())
        );
    }
    
private:
    std::map<std::string, std::function<std::shared_ptr<void>()>> الدوال_;
};

