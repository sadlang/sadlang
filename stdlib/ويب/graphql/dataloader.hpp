/**
 * DataLoader - يجمع الطلبات ويُنفذها دفعة واحدة
 * 
 *     ┌────────────────────────────────────────────────────────┐
 *     │                   DataLoader                           │
 *     │                                                        │
 *     │   ┌──────────────────────────────────────────────┐    │
 *     │   │ طابور الطلبات:                               │    │
 *     │   │                                              │    │
 *     │   │   طلب(1) ───┐                               │    │
 *     │   │   طلب(2) ───┼───→ دفعة [1,2,3,4] ──→ استعلام│    │
 *     │   │   طلب(3) ───┤           واحد!              │    │
 *     │   │   طلب(4) ───┘                               │    │
 *     │   │                                              │    │
 *     │   └──────────────────────────────────────────────┘    │
 *     │                                                        │
 *     │   الذاكرة المؤقتة:                                     │
 *     │   ────────────────                                     │
 *     │   { 1: مقالات_1, 2: مقالات_2, ... }                   │
 *     │                                                        │
 *     └────────────────────────────────────────────────────────┘
 */
template<typename K, typename V>
class DataLoader {
public:
    /**
     * دالة التحميل بالدفعة
     * 
     * تأخذ قائمة مفاتيح → ترجع map من مفتاح إلى قيمة
     */
    using دالة_تحميل_دفعة = std::function<std::map<K, V>(const std::vector<K>&)>;
    
    /**
     * إعدادات DataLoader
     */
    struct إعدادات {
        // أقصى حجم للدفعة
        size_t أقصى_حجم_دفعة = 100;
        
        // المهلة الزمنية لتجميع الطلبات (ms)
        std::chrono::milliseconds مهلة_تجميع{10};
        
        // هل نستخدم الذاكرة المؤقتة؟
        bool تخزين_مؤقت = true;
        
        // أقصى حجم للذاكرة المؤقتة
        size_t أقصى_حجم_ذاكرة = 1000;
    };
    
    explicit DataLoader(دالة_تحميل_دفعة دالة, إعدادات إعدادات = إعدادات{})
        : دالة_التحميل_(دالة), الإعدادات_(إعدادات) {}
    
    /**
     * تحميل قيمة بمفتاح
     */
    std::future<نتيجة_تحميل<V>> حمّل(const K& مفتاح) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        // تحقق من الذاكرة المؤقتة
        if (الإعدادات_.تخزين_مؤقت && الذاكرة_.count(مفتاح)) {
            auto promise = std::make_shared<std::promise<نتيجة_تحميل<V>>>();
            promise->set_value({الذاكرة_[مفتاح], std::nullopt});
            return promise->get_future();
        }
        
        // أضف للطابور
        auto promise = std::make_shared<std::promise<نتيجة_تحميل<V>>>();
        طابور_الانتظار_[مفتاح].push_back(promise);
        مفاتيح_الطابور_.push_back(مفتاح);
        
        // هل نُنفذ الآن؟
        if (مفاتيح_الطابور_.size() >= الإعدادات_.أقصى_حجم_دفعة) {
            نفّذ_الدفعة();
        }
        else if (!مؤقت_نشط_) {
            // ابدأ المؤقت
            مؤقت_نشط_ = true;
            // في الإنتاج: استخدم event loop بدلاً من thread
        }
        
        return promise->get_future();
    }
    
    /**
     * تحميل قائمة
     */
    std::future<std::map<K, نتيجة_تحميل<V>>> حمّل_قائمة(const std::vector<K>& مفاتيح) {
        auto promise = std::make_shared<std::promise<std::map<K, نتيجة_تحميل<V>>>>();
        
        std::map<K, نتيجة_تحميل<V>> نتائج;
        std::vector<std::future<نتيجة_تحميل<V>>> مستقبلات;
        
        for (const auto& مفتاح : مفاتيح) {
            mستقبلات.push_back(حمّل(مفتاح));
        }
        
        // في الإنتاج: استخدم async أفضل
        for (size_t i = 0; i < مفاتيح.size(); i++) {
            نتائج[مفاتيح[i]] = مستقبلات[i].get();
        }
        
        promise->set_value(نتائج);
        return promise->get_future();
    }
    
    /**
     * تنفيذ الدفعة يدوياً
     */
    void نفّذ() {
        std::lock_guard<std::mutex> قفل(القفل_);
        نفّذ_الدفعة();
    }
    
    /**
     * مسح الذاكرة المؤقتة
     */
    void امسح_الذاكرة() {
        std::lock_guard<std::mutex> قفل(القفل_);
        الذاكرة_.clear();
    }
    
    /**
     * مسح مفتاح من الذاكرة
     */
    void امسح(const K& مفتاح) {
        std::lock_guard<std::mutex> قفل(القفل_);
        الذاكرة_.erase(مفتاح);
    }
    
    /**
     * إضافة للذاكرة المؤقتة يدوياً
     */
    void خزّن(const K& مفتاح, const V& قيمة) {
        std::lock_guard<std::mutex> قفل(القفل_);
        أضف_للذاكرة(مفتاح, قيمة);
    }
    
    /**
     * الإحصائيات
     */
    struct إحصائيات {
        size_t إجمالي_الطلبات = 0;
        size_t طلبات_من_الذاكرة = 0;
        size_t عدد_الدفعات = 0;
        size_t متوسط_حجم_دفعة = 0;
    };
    
    إحصائيات الإحصائيات() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        return إحصائيات_;
    }
    
private:
    void نفّذ_الدفعة() {
        if (مفاتيح_الطابور_.empty()) {
            مؤقت_نشط_ = false;
            return;
        }
        
        // انسخ واخلِ الطابور
        auto مفاتيح = std::move(مفاتيح_الطابور_);
        auto طابور = std::move(طابور_الانتظار_);
        مفاتيح_الطابور_.clear();
        طابور_الانتظار_.clear();
        مؤقت_نشط_ = false;
        
        // أزل التكرارات
        std::vector<K> مفاتيح_فريدة;
        std::set<K> تمت_رؤيتها;
        for (const auto& م : مفاتيح) {
            if (!تمت_رؤيتها.count(م)) {
                تمت_رؤيتها.insert(م);
                مفاتيح_فريدة.push_back(م);
            }
        }
        
        // نفّذ الدفعة
        إحصائيات_.عدد_الدفعات++;
        إحصائيات_.إجمالي_الطلبات += مفاتيح.size();
        
        std::map<K, V> نتائج;
        try {
            نتائج = دالة_التحميل_(مفاتيح_فريدة);
        }
        catch (const std::exception& e) {
            // أبلغ عن الخطأ لكل طلب
            for (auto& [مفتاح, قائمة] : طابور) {
                for (auto& promise : قائمة) {
                    promise->set_value({std::nullopt, e.what()});
                }
            }
            return;
        }
        
        // وزع النتائج
        for (auto& [مفتاح, قائمة] : طابور) {
            نتيجة_تحميل<V> نتيجة;
            
            if (نتائج.count(مفتاح)) {
                نتيجة.القيمة = نتائج[مفتاح];
                
                // خزّن
                if (الإعدادات_.تخزين_مؤقت) {
                    أضف_للذاكرة(مفتاح, نتائج[مفتاح]);
                }
            }
            else {
                نتيجة.خطأ = "لم يُوجد";
            }
            
            for (auto& promise : قائمة) {
                promise->set_value(نتيجة);
            }
        }
    }
    
    void أضف_للذاكرة(const K& مفتاح, const V& قيمة) {
        // تحقق من الحجم
        if (الذاكرة_.size() >= الإعدادات_.أقصى_حجم_ذاكرة) {
            // احذف أول عنصر (بسيط - في الإنتاج استخدم LRU)
            الذاكرة_.erase(الذاكرة_.begin());
        }
        
        الذاكرة_[مفتاح] = قيمة;
    }
    
    دالة_تحميل_دفعة دالة_التحميل_;
    إعدادات الإعدادات_;
    
    mutable std::mutex القفل_;
    
    std::vector<K> مفاتيح_الطابور_;
    std::map<K, std::vector<std::shared_ptr<std::promise<نتيجة_تحميل<V>>>>> طابور_الانتظار_;
    
    std::map<K, V> الذاكرة_;
    bool مؤقت_نشط_ = false;
    
    إحصائيات إحصائيات_;
};

