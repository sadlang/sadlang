/**
 * سياق DataLoader لطلب GraphQL
 * 
 * كل طلب GraphQL يحصل على سياق خاص به
 */
class سياق_dataloader {
public:
    /**
     * الحصول على DataLoader لعلاقة
     */
    template<typename K, typename V>
    std::shared_ptr<DataLoader<K, V>> احصل_أو_أنشئ(
        const std::string& اسم,
        typename DataLoader<K, V>::دالة_تحميل_دفعة دالة
    ) {
        if (!المحملات_.count(اسم)) {
            المحملات_[اسم] = std::make_shared<DataLoader<K, V>>(دالة);
        }
        
        return std::static_pointer_cast<DataLoader<K, V>>(المحملات_[اسم]);
    }
    
    /**
     * تنفيذ كل الدفعات
     */
    void نفّذ_الكل() {
        // في الإنتاج: نفّذ بالترتيب الصحيح
    }
    
    /**
     * مسح كل الذاكرة المؤقتة
     */
    void امسح_الكل() {
        المحملات_.clear();
    }
    
private:
    std::map<std::string, std::shared_ptr<void>> المحملات_;
};

