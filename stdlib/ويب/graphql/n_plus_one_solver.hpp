/**
 * مُحسِّن استعلام GraphQL
 * 
 * يُحسِّن الاستعلام قبل التنفيذ
 */
class مُحسِّن_استعلام {
public:
    explicit مُحسِّن_استعلام(حالّ_n_plus_one& حالّ) : الحالّ_(حالّ) {}
    
    /**
     * تحسين استعلام
     */
    std::string حسِّن(const std::string& استعلام) {
        // احصل على خطط الحل
        auto خطط = الحالّ_.حلل_وخطط(استعلام);
        
        // في الإنتاج: أعد كتابة الاستعلام
        // هنا نرجع الأصلي
        
        return استعلام;
    }
    
    /**
     * تقرير التحسين
     */
    std::string تقرير(const std::string& استعلام) {
        auto خطط = الحالّ_.حلل_وخطط(استعلام);
        
        std::string تقرير;
        تقرير += "╔════════════════════════════════════════╗\n";
        تقرير += "║         تقرير تحسين N+1               ║\n";
        تقرير += "╠════════════════════════════════════════╣\n";
        
        if (خطط.empty()) {
            تقرير += "║ لا توجد أنماط N+1 مُكتشَفة ✓          ║\n";
        }
        else {
            for (const auto& خطة : خطط) {
                تقرير += "║ العلاقة: " + خطة.العلاقة + "\n";
                تقرير += "║   الاستراتيجية: ";
                
                switch (خطة.الاستراتيجية) {
                    case استراتيجية_حل::دفعة:
                        تقرير += "دفعة (DataLoader)";
                        break;
                    case استراتيجية_حل::join:
                        تقرير += "SQL JOIN";
                        break;
                    case استراتيجية_حل::تحميل_مسبق:
                        تقرير += "تحميل مسبق";
                        break;
                }
                تقرير += "\n";
                
                تقرير += "║   التحسين المتوقع: " + 
                         std::to_string((int)خطة.التحسين_المتوقع) + "%\n";
                تقرير += "║\n";
            }
        }
        
        تقرير += "╚════════════════════════════════════════╝\n";
        
        return تقرير;
    }
    
private:
    حالّ_n_plus_one& الحالّ_;
};

