/**
 * نوع العلاقة
 */
enum class نوع_علاقة {
    واحد_لواحد,        // User → Profile
    واحد_لكثير,        // User → Articles
    كثير_لكثير         // Article → Tags
};

/**
 * تعريف علاقة
 */
struct تعريف_علاقة {
    std::string الاسم;
    std::string النوع_المصدر;
    std::string النوع_الهدف;
    std::string الحقل_المصدر;  // مثلاً id
    std::string الحقل_الهدف;   // مثلاً author_id
    نوع_علاقة النوع;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              تتبع الاستعلام
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * طلب علاقة مُكتشَف
 */
struct طلب_علاقة {
    std::string العلاقة;
    std::vector<std::any> المفاتيح;
    std::chrono::steady_clock::time_point الوقت;
};

/**
 * متتبع الاستعلامات
 * 
 * يتتبع استعلامات العلاقات لاكتشاف N+1
 */
class متتبع_استعلامات {
public:
    /**
     * تسجيل طلب علاقة
     */
    void سجّل(const طلب_علاقة& طلب) {
        الطلبات_[طلب.العلاقة].push_back(طلب);
        
        // تحقق من نمط N+1
        if (الطلبات_[طلب.العلاقة].size() > حد_اكتشاف_) {
            أنماط_n_plus_one_.insert(طلب.العلاقة);
        }
    }
    
    /**
     * هل هذه علاقة N+1؟
     */
    bool علاقة_n_plus_one(const std::string& علاقة) const {
        return أنماط_n_plus_one_.count(علاقة) > 0;
    }
    
    /**
     * العلاقات المُكتشَفة كـ N+1
     */
    std::set<std::string> أنماط_n_plus_one() const {
        return أنماط_n_plus_one_;
    }
    
    /**
     * إحصائيات
     */
    struct إحصائيات {
        size_t إجمالي_طلبات = 0;
        size_t علاقات_n_plus_one = 0;
        std::map<std::string, size_t> طلبات_لكل_علاقة;
    };
    
    إحصائيات الإحصائيات() const {
        إحصائيات إحص;
        إحص.علاقات_n_plus_one = أنماط_n_plus_one_.size();
        
        for (const auto& [علاقة, طلبات] : الطلبات_) {
            إحص.إجمالي_طلبات += طلبات.size();
            إحص.طلبات_لكل_علاقة[علاقة] = طلبات.size();
        }
        
        return إحص;
    }
    
    /**
     * مسح التتبع
     */
    void امسح() {
        الطلبات_.clear();
        أنماط_n_plus_one_.clear();
    }
    
    /**
     * تعيين حد الاكتشاف
     */
    void حدد_حد_اكتشاف(size_t حد) {
        حد_اكتشاف_ = حد;
    }
    
private:
    std::map<std::string, std::vector<طلب_علاقة>> الطلبات_;
    std::set<std::string> أنماط_n_plus_one_;
    size_t حد_اكتشاف_ = 3;  // 3 طلبات = N+1 محتمل
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل الاستعلام
