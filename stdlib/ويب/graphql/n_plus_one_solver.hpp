/**
 * عقدة استعلام GraphQL
 */
struct عقدة_استعلام {
    std::string الاسم;
    std::string النوع;
    bool قائمة = false;
    std::vector<std::shared_ptr<عقدة_استعلام>> الأبناء;
    std::map<std::string, std::string> الوسائط;
};

/**
 * محلل الاستعلام
 * 
 * يحلل استعلام GraphQL لاكتشاف العلاقات
 */
class محلل_استعلام {
public:
    /**
     * تحليل استعلام
     */
    std::shared_ptr<عقدة_استعلام> حلل(const std::string& استعلام) {
        // في الإنتاج: استخدم parser حقيقي
        // هنا نستخدم تحليل مبسط
        
        auto جذر = std::make_shared<عقدة_استعلام>();
        جذر->الاسم = "Query";
        
        // تحليل مبسط...
        
        return جذر;
    }
    
    /**
     * استخراج العلاقات من الاستعلام
     */
    std::vector<std::string> استخرج_علاقات(
        const std::shared_ptr<عقدة_استعلام>& عقدة,
        const std::map<std::string, تعريف_علاقة>& العلاقات
    ) {
        std::vector<std::string> مُكتشَفة;
        
        استخرج_علاقات_متكرر(عقدة, العلاقات, مُكتشَفة);
        
        return مُكتشَفة;
    }
    
private:
    void استخرج_علاقات_متكرر(
        const std::shared_ptr<عقدة_استعلام>& عقدة,
        const std::map<std::string, تعريف_علاقة>& العلاقات,
        std::vector<std::string>& مُكتشَفة
    ) {
        if (!عقدة) return;
        
        if (العلاقات.count(عقدة->الاسم)) {
            مُكتشَفة.push_back(عقدة->الاسم);
        }
        
        for (const auto& ابن : عقدة->الأبناء) {
            استخرج_علاقات_متكرر(ابن, العلاقات, مُكتشَفة);
        }
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              حالّ N+1
