/**
 * مُحوِّل بيانات JSON بسيط
 * 
 * تخزن البيانات كقاموس نص → نص للتبسيط
 */
class مُحوِّل_json {
public:
    using بيانات = std::map<std::string, std::string>;
    
    /**
     * تطبيق قواعد التحويل
     */
    بيانات حوِّل(
        const بيانات& الأصل,
        const std::vector<قاعدة_تحويل>& القواعد
    ) const {
        بيانات نتيجة = الأصل;
        
        for (const auto& قاعدة : القواعد) {
            switch (قاعدة.النوع) {
                case نوع_تحويل::إعادة_تسمية:
                    نتيجة = أعد_تسمية(نتيجة, قاعدة);
                    break;
                    
                case نوع_تحويل::تقسيم:
                    نتيجة = قسِّم(نتيجة, قاعدة);
                    break;
                    
                case نوع_تحويل::دمج:
                    نتيجة = ادمج(نتيجة, قاعدة);
                    break;
                    
                case نوع_تحويل::إضافة_افتراضي:
                    نتيجة = أضف_افتراضي(نتيجة, قاعدة);
                    break;
                    
                case نوع_تحويل::حذف:
                    نتيجة = احذف(نتيجة, قاعدة);
                    break;
                    
                case نوع_تحويل::مخصص:
                    if (قاعدة.دالة_تحويل) {
                        // تطبيق على الحقل المحدد
                        if (نتيجة.count(قاعدة.الاسم_القديم)) {
                            نتيجة[قاعدة.الاسم_القديم] = 
                                قاعدة.دالة_تحويل(نتيجة[قاعدة.الاسم_القديم]);
                        }
                    }
                    break;
                    
                default:
                    break;
            }
        }
        
        return نتيجة;
    }
    
private:
    بيانات أعد_تسمية(const بيانات& أصل, const قاعدة_تحويل& قاعدة) const {
        بيانات نتيجة = أصل;
        
        auto it = نتيجة.find(قاعدة.الاسم_القديم);
        if (it != نتيجة.end()) {
            نتيجة[قاعدة.الاسم_الجديد] = it->second;
            نتيجة.erase(it);
        }
        
        return نتيجة;
    }
    
    بيانات قسِّم(const بيانات& أصل, const قاعدة_تحويل& قاعدة) const {
        بيانات نتيجة = أصل;
        
        auto it = نتيجة.find(قاعدة.الاسم_القديم);
        if (it != نتيجة.end()) {
            // تقسيم بسيط على المسافة
            std::string قيمة = it->second;
            size_t فاصل = قيمة.find(' ');
            
            if (قاعدة.الحقول_الناتجة.size() >= 2) {
                if (فاصل != std::string::npos) {
                    نتيجة[قاعدة.الحقول_الناتجة[0]] = قيمة.substr(0, فاصل);
                    نتيجة[قاعدة.الحقول_الناتجة[1]] = قيمة.substr(فاصل + 1);
                }
                else {
                    نتيجة[قاعدة.الحقول_الناتجة[0]] = قيمة;
                    نتيجة[قاعدة.الحقول_الناتجة[1]] = "";
                }
            }
            
            نتيجة.erase(it);
        }
        
        return نتيجة;
    }
    
    بيانات ادمج(const بيانات& أصل, const قاعدة_تحويل& قاعدة) const {
        بيانات نتيجة = أصل;
        
        std::string مدمج;
        for (const auto& حقل : قاعدة.الحقول_المدمجة) {
            auto it = نتيجة.find(حقل);
            if (it != نتيجة.end()) {
                if (!مدمج.empty()) مدمج += " ";
                مدمج += it->second;
                نتيجة.erase(it);
            }
        }
        
        نتيجة[قاعدة.الاسم_الجديد] = مدمج;
        
        return نتيجة;
    }
    
    بيانات أضف_افتراضي(const بيانات& أصل, const قاعدة_تحويل& قاعدة) const {
        بيانات نتيجة = أصل;
        
        if (نتيجة.find(قاعدة.الاسم_الجديد) == نتيجة.end()) {
            نتيجة[قاعدة.الاسم_الجديد] = قاعدة.القيمة_الافتراضية;
        }
        
        return نتيجة;
    }
    
    بيانات احذف(const بيانات& أصل, const قاعدة_تحويل& قاعدة) const {
        بيانات نتيجة = أصل;
        نتيجة.erase(قاعدة.الاسم_القديم);
        return نتيجة;
    }
};

