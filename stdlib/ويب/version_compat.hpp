/**
 * DSL لتسجيل التوافق بسهولة
 */
class مُسجِّل_توافق {
public:
    مُسجِّل_توافق(const إصدار& من, const إصدار& إلى)
        : من_(من), إلى_(إلى) {}
    
    /**
     * إعادة تسمية حقل
     */
    مُسجِّل_توافق& أعد_تسمية(
        const std::string& قديم,
        const std::string& جديد
    ) {
        قاعدة_تحويل قاعدة;
        قاعدة.النوع = نوع_تحويل::إعادة_تسمية;
        قاعدة.الاسم_القديم = قديم;
        قاعدة.الاسم_الجديد = جديد;
        القواعد_.push_back(قاعدة);
        return *this;
    }
    
    /**
     * تقسيم حقل
     */
    مُسجِّل_توافق& قسِّم(
        const std::string& أصل,
        std::vector<std::string> ناتج
    ) {
        قاعدة_تحويل قاعدة;
        قاعدة.النوع = نوع_تحويل::تقسيم;
        قاعدة.الاسم_القديم = أصل;
        قاعدة.الحقول_الناتجة = std::move(ناتج);
        القواعد_.push_back(قاعدة);
        return *this;
    }
    
    /**
     * دمج حقول
     */
    مُسجِّل_توافق& ادمج(
        std::vector<std::string> حقول,
        const std::string& ناتج
    ) {
        قاعدة_تحويل قاعدة;
        قاعدة.النوع = نوع_تحويل::دمج;
        قاعدة.الحقول_المدمجة = std::move(حقول);
        قاعدة.الاسم_الجديد = ناتج;
        القواعد_.push_back(قاعدة);
        return *this;
    }
    
    /**
     * إضافة قيمة افتراضية
     */
    مُسجِّل_توافق& أضف_افتراضي(
        const std::string& حقل,
        const std::string& قيمة
    ) {
        قاعدة_تحويل قاعدة;
        قاعدة.النوع = نوع_تحويل::إضافة_افتراضي;
        قاعدة.الاسم_الجديد = حقل;
        قاعدة.القيمة_الافتراضية = قيمة;
        القواعد_.push_back(قاعدة);
        return *this;
    }
    
    /**
     * حذف حقل
     */
    مُسجِّل_توافق& احذف(const std::string& حقل) {
        قاعدة_تحويل قاعدة;
        قاعدة.النوع = نوع_تحويل::حذف;
        قاعدة.الاسم_القديم = حقل;
        القواعد_.push_back(قاعدة);
        return *this;
    }
    
    /**
     * تسجيل التوافق
     */
    void سجّل() {
        مدير_توافق::المثيل().سجل_تحويل(من_, إلى_, القواعد_);
    }
    
private:
    إصدار من_;
    إصدار إلى_;
    std::vector<قاعدة_تحويل> القواعد_;
};

/**
 * دالة مساعدة لإنشاء مسجل
 */
inline مُسجِّل_توافق توافق_من(const إصدار& من, const إصدار& إلى) {
    return مُسجِّل_توافق(من, إلى);
}

