/**
 * نوع التحويل
 */
enum class نوع_تحويل {
    إعادة_تسمية,      // تغيير اسم الحقل
    تحويل_نوع,        // تحويل نوع البيانات
    تقسيم,           // تقسيم حقل لعدة حقول
    دمج,             // دمج عدة حقول في حقل واحد
    إضافة_افتراضي,   // إضافة قيمة افتراضية
    حذف,             // حذف حقل
    مخصص             // تحويل مخصص
};

/**
 * قاعدة تحويل حقل
 */
struct قاعدة_تحويل {
    نوع_تحويل النوع;
    
    // للإعادة تسمية
    std::string الاسم_القديم;
    std::string الاسم_الجديد;
    
    // للتقسيم
    std::vector<std::string> الحقول_الناتجة;
    
    // للدمج
    std::vector<std::string> الحقول_المدمجة;
    
    // للقيمة الافتراضية
    std::string القيمة_الافتراضية;
    
    // للتحويل المخصص
    std::function<std::string(const std::string&)> دالة_تحويل;
};

