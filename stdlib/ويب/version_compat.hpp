/**
 * رقم الإصدار (نسخة بسيطة للاستخدام في طبقة التوافق)
 */
struct إصدار {
    int major = 1;
    int minor = 0;
    int patch = 0;
    
    std::string إلى_نص() const {
        return std::to_string(major) + "." + 
               std::to_string(minor) + "." + 
               std::to_string(patch);
    }
    
    static إصدار من_نص(const std::string& نص) {
        إصدار v;
        sscanf(نص.c_str(), "%d.%d.%d", &v.major, &v.minor, &v.patch);
        return v;
    }
    
    bool operator==(const إصدار& آخر) const {
        return major == آخر.major && minor == آخر.minor && patch == آخر.patch;
    }
    
    bool operator<(const إصدار& آخر) const {
        if (major != آخر.major) return major < آخر.major;
        if (minor != آخر.minor) return minor < آخر.minor;
        return patch < آخر.patch;
    }
    
    bool operator>(const إصدار& آخر) const { return آخر < *this; }
    bool operator<=(const إصدار& آخر) const { return !(آخر < *this); }
    bool operator>=(const إصدار& آخر) const { return !(*this < آخر); }
};

