/**
 * تعريف مسار تحويل
 */
struct مسار_تحويل {
    إصدار من;
    إصدار إلى;
    std::vector<قاعدة_تحويل> القواعد;
};

/**
 * مدير طبقة التوافق
 * 
 * يدير التحويلات بين جميع الإصدارات
 */
class مدير_توافق {
public:
    static مدير_توافق& المثيل() {
        static مدير_توافق مثيل;
        return مثيل;
    }
    
    /**
     * تسجيل مسار تحويل
     */
    void سجل_تحويل(const مسار_تحويل& مسار) {
        المسارات_.push_back(مسار);
    }
    
    /**
     * تسجيل تحويل بسيط
     */
    void سجل_تحويل(
        const إصدار& من,
        const إصدار& إلى,
        std::vector<قاعدة_تحويل> قواعد
    ) {
        مسار_تحويل مسار;
        مسار.من = من;
        مسار.إلى = إلى;
        مسار.القواعد = std::move(قواعد);
        المسارات_.push_back(مسار);
    }
    
    /**
     * تحويل البيانات من إصدار لآخر
     */
    مُحوِّل_json::بيانات حوِّل(
        const مُحوِّل_json::بيانات& بيانات,
        const إصدار& من,
        const إصدار& إلى
    ) const {
        if (من == إلى) {
            return بيانات;
        }
        
        // البحث عن مسار التحويل
        auto مسار = ابحث_مسار(من, إلى);
        if (مسار.empty()) {
            // لا يوجد مسار - إرجاع البيانات كما هي
            return بيانات;
        }
        
        // تطبيق التحويلات المتتالية
        مُحوِّل_json محول;
        auto نتيجة = بيانات;
        
        for (const auto& خطوة : مسار) {
            نتيجة = محول.حوِّل(نتيجة, خطوة.القواعد);
        }
        
        return نتيجة;
    }
    
    /**
     * التحقق من إمكانية التحويل
     */
    bool يمكن_تحويل(const إصدار& من, const إصدار& إلى) const {
        if (من == إلى) return true;
        return !ابحث_مسار(من, إلى).empty();
    }
    
    /**
     * الحصول على جميع الإصدارات المدعومة
     */
    std::vector<إصدار> الإصدارات_المدعومة() const {
        std::vector<إصدار> إصدارات;
        
        for (const auto& مسار : المسارات_) {
            // إضافة إذا غير موجود
            bool موجود_من = false;
            bool موجود_إلى = false;
            
            for (const auto& إصدار : إصدارات) {
                if (إصدار == مسار.من) موجود_من = true;
                if (إصدار == مسار.إلى) موجود_إلى = true;
            }
            
            if (!موجود_من) إصدارات.push_back(مسار.من);
            if (!موجود_إلى) إصدارات.push_back(مسار.إلى);
        }
        
        // ترتيب
        std::sort(إصدارات.begin(), إصدارات.end());
        
        return إصدارات;
    }
    
private:
    مدير_توافق() = default;
    
    /**
     * البحث عن مسار تحويل (BFS)
     */
    std::vector<مسار_تحويل> ابحث_مسار(
        const إصدار& من,
        const إصدار& إلى
    ) const {
        // تحويل مباشر
        for (const auto& مسار : المسارات_) {
            if (مسار.من == من && مسار.إلى == إلى) {
                return {مسار};
            }
        }
        
        // BFS للبحث عن مسار غير مباشر
        std::vector<إصدار> زيارة;
        std::vector<std::pair<إصدار, std::vector<مسار_تحويل>>> طابور;
        طابور.push_back({من, {}});
        
        while (!طابور.empty()) {
            auto [حالي, مسار_حالي] = طابور.front();
            طابور.erase(طابور.begin());
            
            // تم الوصول
            if (حالي == إلى) {
                return مسار_حالي;
            }
            
            // تحقق من الزيارة
            bool تم_زيارة = false;
            for (const auto& z : زيارة) {
                if (z == حالي) {
                    تم_زيارة = true;
                    break;
                }
            }
            if (تم_زيارة) continue;
            زيارة.push_back(حالي);
            
            // البحث عن التحويلات المتاحة
            for (const auto& مسار : المسارات_) {
                if (مسار.من == حالي) {
                    auto مسار_جديد = مسار_حالي;
                    مسار_جديد.push_back(مسار);
                    طابور.push_back({مسار.إلى, مسار_جديد});
                }
            }
        }
        
        return {};  // لا يوجد مسار
    }
    
    std::vector<مسار_تحويل> المسارات_;
};

