/**
 * مستوى الحمل على الخادم
 */
enum class مستوى_حمل {
    خفيف,      // < 30%
    عادي,      // 30-70%
    عالي,      // 70-90%
    حرج,       // > 90%
};

/**
 * نتيجة فحص المعدل
 */
enum class نتيجة_معدل {
    مسموح,         // OK, استمر
    محدود,         // أبطئ قليلاً
    مرفوض,         // توقف وانتظر
    محظور,         // محظور مؤقتاً
    يتطلب_تحقق,    // أثبت أنك إنسان
};

/**
 * معلومات العميل
 */
struct معلومات_عميل {
    std::string المعرف;           // IP أو User ID
    int الطلبات_المتبقية = 0;   // في النافذة الحالية
    std::chrono::seconds إعادة_الضبط;
    نتيجة_معدل النتيجة = نتيجة_معدل::مسموح;
    
    // إحصائيات تاريخية
    int إجمالي_الطلبات = 0;
    int الرفض = 0;
    int التحذيرات = 0;
};

