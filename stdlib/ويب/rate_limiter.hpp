/**
 * نافذة زمنية منزلقة (Sliding Window)
 * 
 * تخيل نافذة تتحرك مع الوقت:
 * 
 *     الوقت: ──────────────────────────────────────→
 *            │●●●●●│        │                       
 *                  │●●●│    │                       
 *                       │●●●●●●│                    
 *            ←─ دقيقة ─→                            
 *                                                  
 *     ● = طلب
 *     نحسب الطلبات داخل النافذة فقط
 */
class نافذة_منزلقة {
public:
    explicit نافذة_منزلقة(std::chrono::seconds حجم_النافذة = std::chrono::seconds(60))
        : m_حجم_النافذة(حجم_النافذة) {}
    
    /**
     * إضافة طلب جديد
     */
    void أضف_طلب() {
        auto الآن = std::chrono::steady_clock::now();
        m_الطلبات.push_back(الآن);
        نظِّف();
    }
    
    /**
     * عدد الطلبات في النافذة الحالية
     */
    int العدد() const {
        // نظِّف أولاً ثم عُد
        نظِّف_const();
        return static_cast<int>(m_الطلبات.size());
    }
    
    /**
     * الوقت حتى تفرغ النافذة
     */
    std::chrono::seconds الوقت_المتبقي() const {
        if (m_الطلبات.empty()) {
            return std::chrono::seconds(0);
        }
        
        auto الآن = std::chrono::steady_clock::now();
        auto أقدم = m_الطلبات.front();
        auto مضى = std::chrono::duration_cast<std::chrono::seconds>(الآن - أقدم);
        
        if (مضى >= m_حجم_النافذة) {
            return std::chrono::seconds(0);
        }
        
        return m_حجم_النافذة - مضى;
    }
    
private:
    std::chrono::seconds m_حجم_النافذة;
    mutable std::vector<std::chrono::steady_clock::time_point> m_الطلبات;
    
    void نظِّف() {
        auto الآن = std::chrono::steady_clock::now();
        while (!m_الطلبات.empty()) {
            auto عمر = std::chrono::duration_cast<std::chrono::seconds>(
                الآن - m_الطلبات.front());
            if (عمر >= m_حجم_النافذة) {
                m_الطلبات.erase(m_الطلبات.begin());
            } else {
                break;
            }
        }
    }
    
    void نظِّف_const() const {
        auto الآن = std::chrono::steady_clock::now();
        while (!m_الطلبات.empty()) {
            auto عمر = std::chrono::duration_cast<std::chrono::seconds>(
                الآن - m_الطلبات.front());
            if (عمر >= m_حجم_النافذة) {
                m_الطلبات.erase(m_الطلبات.begin());
            } else {
                break;
            }
        }
    }
};

