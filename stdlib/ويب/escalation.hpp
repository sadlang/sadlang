/**
 * مرحلة التصعيد
 */
enum class مرحلة_تصعيد {
    عادي,        // لا مشاكل
    تحذير,       // تحذير ودي
    إبطاء,       // تأخير مصطنع
    حظر_قصير,    // حظر 15 دقيقة
    حظر_طويل,    // حظر 24 ساعة
    حظر_دائم,    // حظر دائم (يتطلب تدخل يدوي)
};

/**
 * سبب التصعيد
 */
enum class سبب_تصعيد {
    تجاوز_المعدل,     // طلبات كثيرة جداً
    طلبات_مشبوهة,     // أنماط طلبات غريبة
    محاولة_اختراق,    // كشف هجوم
    سلوك_غير_طبيعي,   // مثل طلب نفس الصفحة 1000 مرة
    شكوى_مستخدم,      // أبلغ عنه مستخدم آخر
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              سجل العميل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حدث في سجل العميل
 */
struct حدث_تصعيد {
    std::chrono::steady_clock::time_point الوقت;
    سبب_تصعيد السبب;
    std::string التفاصيل;
};

/**
 * سجل العميل للتصعيد
 */
struct سجل_عميل {
    std::string المعرف;
    مرحلة_تصعيد المرحلة = مرحلة_تصعيد::عادي;
    
    // عدادات
    int التحذيرات = 0;
    int مرات_الإبطاء = 0;
    int مرات_الحظر = 0;
    
    // توقيتات
    std::chrono::steady_clock::time_point آخر_تصعيد;
    std::chrono::steady_clock::time_point نهاية_الحظر;
    
    // سجل الأحداث
    std::vector<حدث_تصعيد> الأحداث;
    
    // التأخير الحالي (للإبطاء)
    std::chrono::milliseconds التأخير{0};
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              إعدادات التصعيد
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * إعدادات التصعيد
 */
struct إعدادات_تصعيد {
    // عتبات الانتقال
    int تحذيرات_للإبطاء = 3;          // 3 تحذيرات → إبطاء
    int إبطاء_للحظر_قصير = 5;         // 5 مرات إبطاء → حظر قصير
    int حظر_قصير_للطويل = 3;          // 3 حظرات قصيرة → حظر طويل
    int حظر_طويل_للدائم = 5;          // 5 حظرات طويلة → حظر دائم
    
    // فترات الحظر
    std::chrono::minutes حظر_قصير{15};
    std::chrono::hours حظر_طويل{24};
    
    // الإبطاء
    std::chrono::milliseconds تأخير_ابتدائي{200};
    std::chrono::milliseconds تأخير_أقصى{5000};
    double معامل_تزايد_التأخير = 1.5;
    
    // إعادة الضبط
    std::chrono::hours وقت_تهدئة{1};     // إذا لم يخالف لمدة ساعة، نقلل المرحلة
    bool إعادة_ضبط_تلقائي = true;
    
    // الإشعارات
    std::function<void(const std::string&, مرحلة_تصعيد, const std::string&)> عند_التصعيد;
};

// ═══════════════════════════════════════════════════════════════════════════════
