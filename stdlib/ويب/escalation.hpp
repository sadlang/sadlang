/**
 * Middleware للتصعيد التدريجي
 */
template<typename طلب, typename استجابة>
class middleware_تصعيد {
public:
    using معالج = std::function<استجابة(const طلب&)>;
    using مستخرج_معرف = std::function<std::string(const طلب&)>;
    using منشئ_رفض = std::function<استجابة(const نتيجة_تصعيد&)>;
    
    middleware_تصعيد(
        مستخرج_معرف استخراج,
        منشئ_رفض رفض
    ) : m_استخراج(std::move(استخراج)),
        m_رفض(std::move(رفض)) {}
    
    /**
     * تغليف معالج
     */
    معالج غلِّف(معالج التالي) {
        return [this, التالي](const طلب& req) -> استجابة {
            auto معرف = m_استخراج(req);
            auto نتيجة = مدير_تصعيد::المثال().افحص(معرف);
            
            if (!نتيجة.مسموح) {
                return m_رفض(نتيجة);
            }
            
            // تطبيق التأخير إذا وجد
            if (نتيجة.التأخير.has_value()) {
                std::this_thread::sleep_for(*نتيجة.التأخير);
            }
            
            return التالي(req);
        };
    }
    
private:
    مستخرج_معرف m_استخراج;
    منشئ_رفض m_رفض;
};

