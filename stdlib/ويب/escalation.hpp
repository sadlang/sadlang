// ═══════════════════════════════════════════════════════════════════════════════

/**
 * نتيجة فحص التصعيد
 */
struct نتيجة_تصعيد {
    bool مسموح;                              // هل يمكن المتابعة؟
    مرحلة_تصعيد المرحلة;                     // المرحلة الحالية
    std::optional<std::chrono::milliseconds> التأخير;  // تأخير مطلوب
    std::optional<std::string> رسالة;        // رسالة للمستخدم
    std::optional<std::chrono::seconds> الوقت_المتبقي;  // للحظر
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مدير التصعيد
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مدير التصعيد التدريجي
 */
class مدير_تصعيد {
public:
    /**
     * الحصول على المدير العالمي
     */
    static مدير_تصعيد& المثال() {
        static مدير_تصعيد مثال;
        return مثال;
    }
    
    /**
     * تعيين الإعدادات
     */
    void عيِّن_الإعدادات(إعدادات_تصعيد إعدادات) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_إعدادات = std::move(إعدادات);
    }
    
    /**
     * تسجيل مخالفة
     * 
     * مثال:
     *     مدير_تصعيد::المثال().سجِّل_مخالفة(
     *         "192.168.1.1",
     *         سبب_تصعيد::تجاوز_المعدل,
     *         "تجاوز 100 طلب/دقيقة"
     *     );
     */
    نتيجة_تصعيد سجِّل_مخالفة(
        const std::string& معرف_العميل,
        سبب_تصعيد السبب,
        const std::string& تفاصيل = ""
    ) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        auto& عميل = احصل_أو_أنشئ(معرف_العميل);
        
        // سجّل الحدث
        عميل.الأحداث.push_back({
            std::chrono::steady_clock::now(),
            السبب,
            تفاصيل
        });
        
        // صعِّد المرحلة
        return صعِّد(عميل, السبب);
    }
    
    /**
     * فحص حالة العميل
     */
    نتيجة_تصعيد افحص(const std::string& معرف_العميل) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        auto it = m_العملاء.find(معرف_العميل);
        if (it == m_العملاء.end()) {
            // عميل جديد - لا مشاكل
            return {true, مرحلة_تصعيد::عادي, {}, {}, {}};
        }
        
        auto& عميل = it->second;
        
        // تحقق من التهدئة التلقائية
        if (m_إعدادات.إعادة_ضبط_تلقائي) {
            تحقق_التهدئة(عميل);
        }
        
        return احصل_على_النتيجة(عميل);
    }
    
    /**
     * إعادة ضبط عميل
     */
    void أعد_ضبط(const std::string& معرف_العميل) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        m_العملاء.erase(معرف_العميل);
    }
    
    /**
     * تخفيض مرحلة يدوياً
     */
    void خفِّض_المرحلة(const std::string& معرف_العميل) {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        auto it = m_العملاء.find(معرف_العميل);
        if (it == m_العملاء.end()) return;
        
        auto& عميل = it->second;
        
        switch (عميل.المرحلة) {
            case مرحلة_تصعيد::حظر_دائم:
                عميل.المرحلة = مرحلة_تصعيد::حظر_طويل;
                break;
            case مرحلة_تصعيد::حظر_طويل:
                عميل.المرحلة = مرحلة_تصعيد::حظر_قصير;
                break;
            case مرحلة_تصعيد::حظر_قصير:
                عميل.المرحلة = مرحلة_تصعيد::إبطاء;
                break;
            case مرحلة_تصعيد::إبطاء:
                عميل.المرحلة = مرحلة_تصعيد::تحذير;
                عميل.التأخير = std::chrono::milliseconds(0);
                break;
            case مرحلة_تصعيد::تحذير:
                عميل.المرحلة = مرحلة_تصعيد::عادي;
                break;
            default:
                break;
        }
    }
    
    /**
     * الحصول على سجل العميل
     */
    std::optional<سجل_عميل> احصل_على_السجل(const std::string& معرف_العميل) const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        auto it = m_العملاء.find(معرف_العميل);
        if (it == m_العملاء.end()) {
            return std::nullopt;
        }
        
        return it->second;
    }
    
    /**
     * قائمة المحظورين
     */
    std::vector<std::string> المحظورين() const {
        std::lock_guard<std::mutex> قفل(m_قفل);
        
        std::vector<std::string> قائمة;
        
        for (const auto& [معرف, عميل] : m_العملاء) {
            if (عميل.المرحلة >= مرحلة_تصعيد::حظر_قصير) {
                قائمة.push_back(معرف);
            }
        }
        
        return قائمة;
    }
    
private:
    مدير_تصعيد() = default;
    
    إعدادات_تصعيد m_إعدادات;
    std::unordered_map<std::string, سجل_عميل> m_العملاء;
    mutable std::mutex m_قفل;
    
    /**
     * الحصول على أو إنشاء سجل عميل
     */
    سجل_عميل& احصل_أو_أنشئ(const std::string& معرف) {
        auto it = m_العملاء.find(معرف);
        if (it == m_العملاء.end()) {
            m_العملاء[معرف] = سجل_عميل{معرف};
        }
        return m_العملاء[معرف];
    }
    
    /**
     * تصعيد المرحلة
     */
    نتيجة_تصعيد صعِّد(سجل_عميل& عميل, سبب_تصعيد السبب) {
        عميل.آخر_تصعيد = std::chrono::steady_clock::now();
        
        switch (عميل.المرحلة) {
            case مرحلة_تصعيد::عادي:
                // أول مخالفة - تحذير
                عميل.المرحلة = مرحلة_تصعيد::تحذير;
                عميل.التحذيرات = 1;
                أبلغ(عميل.المعرف, مرحلة_تصعيد::تحذير, "تحذير أول");
                break;
                
            case مرحلة_تصعيد::تحذير:
                عميل.التحذيرات++;
                if (عميل.التحذيرات >= m_إعدادات.تحذيرات_للإبطاء) {
                    // انتقل للإبطاء
                    عميل.المرحلة = مرحلة_تصعيد::إبطاء;
                    عميل.التأخير = m_إعدادات.تأخير_ابتدائي;
                    أبلغ(عميل.المعرف, مرحلة_تصعيد::إبطاء, "بدء الإبطاء");
                }
                break;
                
            case مرحلة_تصعيد::إبطاء:
                عميل.مرات_الإبطاء++;
                // زد التأخير
                عميل.التأخير = std::chrono::milliseconds(static_cast<int>(
                    عميل.التأخير.count() * m_إعدادات.معامل_تزايد_التأخير
                ));
                if (عميل.التأخير > m_إعدادات.تأخير_أقصى) {
                    عميل.التأخير = m_إعدادات.تأخير_أقصى;
                }
                
                if (عميل.مرات_الإبطاء >= m_إعدادات.إبطاء_للحظر_قصير) {
                    // انتقل للحظر القصير
                    عميل.المرحلة = مرحلة_تصعيد::حظر_قصير;
                    عميل.نهاية_الحظر = std::chrono::steady_clock::now() 
                        + m_إعدادات.حظر_قصير;
                    عميل.مرات_الحظر++;
                    أبلغ(عميل.المعرف, مرحلة_تصعيد::حظر_قصير, "حظر 15 دقيقة");
                }
                break;
                
            case مرحلة_تصعيد::حظر_قصير:
                // محاولة أثناء الحظر - تمدد أو صعِّد
                if (عميل.مرات_الحظر >= m_إعدادات.حظر_قصير_للطويل) {
                    عميل.المرحلة = مرحلة_تصعيد::حظر_طويل;
                    عميل.نهاية_الحظر = std::chrono::steady_clock::now() 
                        + m_إعدادات.حظر_طويل;
                    أبلغ(عميل.المعرف, مرحلة_تصعيد::حظر_طويل, "حظر 24 ساعة");
                } else {
                    // تمدد الحظر
                    عميل.نهاية_الحظر = std::chrono::steady_clock::now() 
                        + m_إعدادات.حظر_قصير;
                    عميل.مرات_الحظر++;
                }
                break;
                
            case مرحلة_تصعيد::حظر_طويل:
                if (عميل.مرات_الحظر >= m_إعدادات.حظر_طويل_للدائم) {
                    عميل.المرحلة = مرحلة_تصعيد::حظر_دائم;
                    أبلغ(عميل.المعرف, مرحلة_تصعيد::حظر_دائم, "حظر دائم");
                } else {
                    عميل.نهاية_الحظر = std::chrono::steady_clock::now() 
                        + m_إعدادات.حظر_طويل;
                    عميل.مرات_الحظر++;
                }
                break;
                
            case مرحلة_تصعيد::حظر_دائم:
                // لا شيء - محظور دائماً
                break;
        }
        
        return احصل_على_النتيجة(عميل);
    }
    
    /**
     * الحصول على نتيجة من سجل العميل
     */
    نتيجة_تصعيد احصل_على_النتيجة(const سجل_عميل& عميل) const {
        نتيجة_تصعيد نتيجة;
        نتيجة.المرحلة = عميل.المرحلة;
        
        switch (عميل.المرحلة) {
            case مرحلة_تصعيد::عادي:
                نتيجة.مسموح = true;
                break;
                
            case مرحلة_تصعيد::تحذير:
                نتيجة.مسموح = true;
                نتيجة.رسالة = "⚠️ تحذير: لقد أرسلت طلبات كثيرة. يرجى الإبطاء.";
                break;
                
            case مرحلة_تصعيد::إبطاء:
                نتيجة.مسموح = true;
                نتيجة.التأخير = عميل.التأخير;
                نتيجة.رسالة = "🐌 طلباتك تُعالج ببطء بسبب الاستخدام المفرط.";
                break;
                
            case مرحلة_تصعيد::حظر_قصير:
            case مرحلة_تصعيد::حظر_طويل: {
                auto الآن = std::chrono::steady_clock::now();
                if (الآن >= عميل.نهاية_الحظر) {
                    // انتهى الحظر
                    نتيجة.مسموح = true;
                    نتيجة.المرحلة = مرحلة_تصعيد::تحذير;
                } else {
                    نتيجة.مسموح = false;
                    auto متبقي = std::chrono::duration_cast<std::chrono::seconds>(
                        عميل.نهاية_الحظر - الآن);
                    نتيجة.الوقت_المتبقي = متبقي;
                    نتيجة.رسالة = "⛔ تم حظرك مؤقتاً. حاول بعد " 
                        + std::to_string(متبقي.count() / 60) + " دقيقة.";
                }
                break;
            }
                
            case مرحلة_تصعيد::حظر_دائم:
                نتيجة.مسموح = false;
                نتيجة.رسالة = "🚫 تم حظرك. يرجى التواصل مع الدعم.";
                break;
        }
        
        return نتيجة;
    }
    
    /**
     * تحقق من التهدئة التلقائية
     */
    void تحقق_التهدئة(سجل_عميل& عميل) {
        if (عميل.المرحلة == مرحلة_تصعيد::عادي ||
            عميل.المرحلة == مرحلة_تصعيد::حظر_دائم) {
            return;
        }
        
        auto الآن = std::chrono::steady_clock::now();
        auto مضى = std::chrono::duration_cast<std::chrono::hours>(
            الآن - عميل.آخر_تصعيد);
        
        if (مضى >= m_إعدادات.وقت_تهدئة) {
            // خفِّض المرحلة
            switch (عميل.المرحلة) {
                case مرحلة_تصعيد::تحذير:
                    عميل.المرحلة = مرحلة_تصعيد::عادي;
                    عميل.التحذيرات = 0;
                    break;
                case مرحلة_تصعيد::إبطاء:
                    عميل.المرحلة = مرحلة_تصعيد::تحذير;
                    عميل.التأخير = std::chrono::milliseconds(0);
                    break;
                case مرحلة_تصعيد::حظر_قصير:
                case مرحلة_تصعيد::حظر_طويل:
                    // تحقق من انتهاء الحظر
                    if (الآن >= عميل.نهاية_الحظر) {
                        عميل.المرحلة = مرحلة_تصعيد::تحذير;
                    }
                    break;
                default:
                    break;
            }
            
            عميل.آخر_تصعيد = الآن;
        }
    }
    
    /**
     * إبلاغ عن تصعيد
     */
    void أبلغ(const std::string& معرف, مرحلة_تصعيد المرحلة, const std::string& تفاصيل) {
        if (m_إعدادات.عند_التصعيد) {
            m_إعدادات.عند_التصعيد(معرف, المرحلة, تفاصيل);
        }
    }
};

