    دالة منشئ(نص ن)
        نص_زر = ن
        لون_خلفية = لون.أساسي()
        لون_نص = لون.أبيض()
        مفعّل = صحيح
        نصف_قطر_زاوية = 8.0
        حشوة_زر = حشوة.متماثل(16، 8)
        إجراء = فراغ
    نهاية
    
    دالة لون_خلفية(لون ل) زر
        لون_خلفية = ل
        ارجع ذات
    نهاية
    
    دالة لون_نص(لون ل) زر
        لون_نص = ل
        ارجع ذات
    نهاية
    
    دالة معطّل(منطقي قيمة = صحيح) زر
        مفعّل = !قيمة
        ارجع ذات
    نهاية
    
    دالة عند_نقر(دالة<فراغ> د) زر
        إجراء = د
        ارجع ذات
    نهاية
    
    دالة اضغط()
        إذا (مفعّل)
            إذا (إجراء != فراغ)
                إجراء()
            نهاية
        نهاية
    نهاية
