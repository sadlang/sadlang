        وإلا_إذا (د >= 22.5 && د < 67.5)
            ارجع "شمال شرق"
        وإلا_إذا (د >= 67.5 && د < 112.5)
            ارجع "شرق"
        وإلا_إذا (د >= 112.5 && د < 157.5)
            ارجع "جنوب شرق"
        وإلا_إذا (د >= 157.5 && د < 202.5)
            ارجع "جنوب"
        وإلا_إذا (د >= 202.5 && د < 247.5)
            ارجع "جنوب غرب"
        وإلا_إذا (د >= 247.5 && د < 292.5)
            ارجع "غرب"
        وإلا
            ارجع "شمال غرب"
        نهاية
    نهاية
    
    # تعيين معالج التحديث
    دالة عند_تحديث(دالة<فراغ، عشري> معالج) بوصلة
        عند_تحديث_معالج = معالج
