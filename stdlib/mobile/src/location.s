# صنف إحداثيات - يمثل نقطة جغرافية
صنف إحداثيات
    عشري خط_عرض    # -90 إلى +90
    عشري خط_طول    # -180 إلى +180
    
    دالة منشئ(عشري عرض = 0، عشري طول = 0)
        خط_عرض = عرض
        خط_طول = طول
    نهاية
    
    # التحقق من صحة الإحداثيات
    دالة صالح() منطقي
        ارجع خط_عرض >= -90 && خط_عرض <= 90 &&
               خط_طول >= -180 && خط_طول <= 180
    نهاية
    
    # حساب المسافة إلى نقطة أخرى (بالأمتار)
    دالة مسافة_إلى(إحداثيات أخرى) عشري
        # صيغة Haversine
        عشري نق_أرض = 6371000  # نصف قطر الأرض بالأمتار
        
        عشري فرق_عرض = (أخرى.خط_عرض - خط_عرض) * 3.14159 / 180
        عشري فرق_طول = (أخرى.خط_طول - خط_طول) * 3.14159 / 180
        
        عشري عرض1 = خط_عرض * 3.14159 / 180
        عشري عرض2 = أخرى.خط_عرض * 3.14159 / 180
        
        عشري أ = جيب(فرق_عرض / 2) ** 2 +
                  جتا(عرض1) * جتا(عرض2) * جيب(فرق_طول / 2) ** 2
        عشري ج = 2 * جتا_عكسي(جذر(أ))
        
        ارجع نق_أرض * ج
    نهاية
    
    # حساب الاتجاه إلى نقطة أخرى (بالدرجات)
    دالة اتجاه_إلى(إحداثيات أخرى) عشري
        عشري فرق_طول = (أخرى.خط_طول - خط_طول) * 3.14159 / 180
        عشري عرض1 = خط_عرض * 3.14159 / 180
        عشري عرض2 = أخرى.خط_عرض * 3.14159 / 180
        
        عشري س = جيب(فرق_طول) * جتا(عرض2)
        عشري ص = جتا(عرض1) * جيب(عرض2) -
                  جيب(عرض1) * جتا(عرض2) * جتا(فرق_طول)
        
        عشري اتجاه = ظل_عكسي(س، ص) * 180 / 3.14159
        ارجع (اتجاه + 360) % 360
    نهاية
    
    # تحويل إلى نص
    دالة إلى_نص() نص
        ارجع ن"{خط_عرض}، {خط_طول}"
    نهاية
    
    # إحداثيات مدن عربية شهيرة
    ثابتة دالة الرياض() إحداثيات
        ارجع إحداثيات(24.7136، 46.6753)
    نهاية
    
    ثابتة دالة دبي() إحداثيات
        ارجع إحداثيات(25.2048، 55.2708)
    نهاية
    
    ثابتة دالة القاهرة() إحداثيات
        ارجع إحداثيات(30.0444، 31.2357)
    نهاية
    
    ثابتة دالة مكة() إحداثيات
        ارجع إحداثيات(21.3891، 39.8579)
    نهاية
    
    ثابتة دالة المدينة() إحداثيات
        ارجع إحداثيات(24.5247، 39.5692)
    نهاية
نهاية

