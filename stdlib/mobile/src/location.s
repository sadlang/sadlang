صنف بوصلة
    منطقي جاري
    عشري آخر_اتجاه
    دالة<فراغ، عشري> عند_تحديث_معالج
    
    دالة منشئ()
        جاري = خطأ
        آخر_اتجاه = 0
    نهاية
    
    # التحقق من توفر البوصلة
    ثابتة مزامن دالة متاحة() منطقي
        # التنفيذ الفعلي في المنصة
        ارجع صحيح
    نهاية
    
    # بدء قراءة الاتجاه
    مزامن دالة ابدأ() نتيجة<فراغ، خطأ_موقع>
        إذا (جاري)
            ارجع نتيجة.نجاح(فراغ)
        نهاية
        
        منطقي متوفرة = انتظر بوصلة.متاحة()
        إذا (!متوفرة)
            ارجع نتيجة.فشل(خطأ_موقع.غير_متاح)
        نهاية
        
        # بدء القراءة - التنفيذ الفعلي في المنصة
        جاري = صحيح
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # إيقاف قراءة الاتجاه
    دالة أوقف()
        إذا (جاري)
            # التنفيذ الفعلي في المنصة
            جاري = خطأ
        نهاية
    نهاية
    
    # الاتجاه الحالي
    دالة الاتجاه() عشري
        ارجع آخر_اتجاه
    نهاية
    
    # الاتجاه كنص (شمال، جنوب، إلخ)
    دالة الاتجاه_كنص() نص
        عشري د = آخر_اتجاه
        
        إذا (د >= 337.5 || د < 22.5)
