# صنف خدمة_موقع - الواجهة الرئيسية لخدمات الموقع
#
# مثال:
#     خدمة_موقع خ = خدمة_موقع()
#     
#     # الحصول على الموقع الحالي
#     نتيجة<موقع، خطأ_موقع> نت = انتظر خ.الموقع_الحالي()
#     إذا (نت.ناجح())
#         موقع م = نت.قيمة()
#         اطبع(ن"الموقع: {م.خط_عرض()}، {م.خط_طول()}")
#     نهاية
#     
#     # تتبع الموقع
#     خ.عند_تحديث(دالة(موقع م)
#         اطبع(ن"موقع جديد: {م.إلى_نص()}")
#     نهاية)
#     انتظر خ.ابدأ_تتبع()
#
صنف خدمة_موقع
    إعدادات_موقع إعدادات
    منطقي جاري_التتبع
    موقع آخر_موقع
    دالة<فراغ، موقع> عند_تحديث_معالج
    دالة<فراغ، خطأ_موقع> عند_خطأ_معالج
    
    دالة منشئ()
        إعدادات = إعدادات_موقع.افتراضي()
        جاري_التتبع = خطأ
        آخر_موقع = موقع()
    نهاية
    
    # =========================================
    #           دوال ثابتة
    # =========================================
    
    # التحقق من توفر خدمات الموقع
    ثابتة مزامن دالة متاحة() منطقي
        # التنفيذ الفعلي في المنصة
        ارجع صحيح
    نهاية
    
    # التحقق من حالة الإذن
    ثابتة مزامن دالة حالة_الإذن() حالة_إذن_موقع
        # التنفيذ الفعلي في المنصة
        ارجع حالة_إذن_موقع.غير_محدد
    نهاية
    
    # طلب إذن الوصول للموقع
    ثابتة مزامن دالة طلب_إذن(منطقي دائماً = خطأ) نتيجة<حالة_إذن_موقع، خطأ_موقع>
        # التنفيذ الفعلي في المنصة
        إذا (دائماً)
            ارجع نتيجة.نجاح(حالة_إذن_موقع.دائماً)
        وإلا
            ارجع نتيجة.نجاح(حالة_إذن_موقع.أثناء_استخدام)
        نهاية
    نهاية
    
    # فتح إعدادات الموقع
    ثابتة مزامن دالة فتح_الإعدادات()
        # التنفيذ الفعلي في المنصة
    نهاية
    
    # =========================================
    #           الموقع الحالي
    # =========================================
    
    # الحصول على الموقع الحالي
    مزامن دالة الموقع_الحالي() نتيجة<موقع، خطأ_موقع>
        ارجع انتظر الموقع_الحالي_بإعدادات(إعدادات)
    نهاية
    
    # الحصول على الموقع الحالي بإعدادات مخصصة
    مزامن دالة الموقع_الحالي_بإعدادات(إعدادات_موقع إع) نتيجة<موقع، خطأ_موقع>
        # التحقق من الإذن
        حالة_إذن_موقع حالة = انتظر خدمة_موقع.حالة_الإذن()
        
        إذا (حالة == حالة_إذن_موقع.مرفوض || حالة == حالة_إذن_موقع.مقيد)
            ارجع نتيجة.فشل(خطأ_موقع.لا_يوجد_إذن)
        نهاية
        
        إذا (حالة == حالة_إذن_موقع.غير_محدد)
            نتيجة<حالة_إذن_موقع، خطأ_موقع> نت_إذن = انتظر خدمة_موقع.طلب_إذن()
            إذا (نت_إذن.فاشل())
                ارجع نتيجة.فشل(نت_إذن.خطأ())
            نهاية
        نهاية
        
        # الحصول على الموقع - التنفيذ الفعلي في المنصة
        موقع م = موقع()
        # ... تعبئة بيانات الموقع ...
        
        آخر_موقع = م
        ارجع نتيجة.نجاح(م)
    نهاية
    
    # الحصول على آخر موقع معروف (بدون انتظار)
    دالة آخر_موقع_معروف() اختياري<موقع>
        إذا (آخر_موقع.صالح())
            ارجع اختياري.بعض(آخر_موقع)
        نهاية
        ارجع اختياري.لاشيء()
    نهاية
    
    # =========================================
    #           التتبع
    # =========================================
    
    # بدء تتبع الموقع
    مزامن دالة ابدأ_تتبع() نتيجة<فراغ، خطأ_موقع>
        ارجع انتظر ابدأ_تتبع_بإعدادات(إعدادات)
    نهاية
    
    # بدء تتبع الموقع بإعدادات مخصصة
    مزامن دالة ابدأ_تتبع_بإعدادات(إعدادات_موقع إع) نتيجة<فراغ، خطأ_موقع>
        إذا (جاري_التتبع)
            ارجع نتيجة.نجاح(فراغ)
        نهاية
        
        # التحقق من الإذن
        حالة_إذن_موقع حالة = انتظر خدمة_موقع.حالة_الإذن()
        
        إذا (إع.الخلفية && حالة != حالة_إذن_موقع.دائماً)
            # نحتاج إذن الخلفية
            نتيجة<حالة_إذن_موقع، خطأ_موقع> نت = انتظر خدمة_موقع.طلب_إذن(صحيح)
            إذا (نت.فاشل() || نت.قيمة() != حالة_إذن_موقع.دائماً)
                ارجع نتيجة.فشل(خطأ_موقع.لا_يوجد_إذن)
            نهاية
        نهاية
        
        # بدء التتبع - التنفيذ الفعلي في المنصة
        جاري_التتبع = صحيح
        إعدادات = إع
        
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # إيقاف تتبع الموقع
    دالة أوقف_تتبع()
        إذا (جاري_التتبع)
            # إيقاف التتبع - التنفيذ الفعلي في المنصة
            جاري_التتبع = خطأ
        نهاية
    نهاية
    
    # =========================================
    #           معالجات الأحداث
    # =========================================
    
    # تعيين معالج تحديث الموقع
    دالة عند_تحديث(دالة<فراغ، موقع> معالج) خدمة_موقع
        عند_تحديث_معالج = معالج
        ارجع ذات
    نهاية
    
    # تعيين معالج الخطأ
