# صنف موقع - يمثل موقع جغرافي كامل
صنف موقع
    إحداثيات إحداثيات_موقع
    عشري ارتفاع           # الارتفاع عن سطح البحر (متر)
    عشري دقة_أفقية        # دقة الموقع الأفقي (متر)
    عشري دقة_ارتفاع       # دقة الارتفاع (متر)
    عشري سرعة             # السرعة (متر/ثانية)
    عشري اتجاه            # الاتجاه (درجات، 0-360)
