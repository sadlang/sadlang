# صنف متجه ثلاثي الأبعاد
صنف متجه3
    عشري س    # المحور X
    عشري ص    # المحور Y
    عشري ع    # المحور Z
    
    دالة منشئ(عشري س_ق = 0، عشري ص_ق = 0، عشري ع_ق = 0)
        س = س_ق
        ص = ص_ق
        ع = ع_ق
    نهاية
    
    # الطول (المقدار)
    دالة طول() عشري
        ارجع جذر(س * س + ص * ص + ع * ع)
    نهاية
    
    # التطبيع (جعل الطول = 1)
    دالة تطبيع() متجه3
        عشري ط = طول()
        إذا (ط == 0)
            ارجع متجه3(0، 0، 0)
        نهاية
        ارجع متجه3(س / ط، ص / ط، ع / ط)
    نهاية
    
    # الجمع
    دالة جمع(متجه3 آخر) متجه3
        ارجع متجه3(س + آخر.س، ص + آخر.ص، ع + آخر.ع)
    نهاية
    
    # الطرح
    دالة طرح(متجه3 آخر) متجه3
        ارجع متجه3(س - آخر.س، ص - آخر.ص، ع - آخر.ع)
    نهاية
    
    # الضرب بعدد
    دالة ضرب(عشري ك) متجه3
        ارجع متجه3(س * ك، ص * ك، ع * ك)
    نهاية
    
    # حاصل الضرب النقطي
    دالة ضرب_نقطي(متجه3 آخر) عشري
        ارجع س * آخر.س + ص * آخر.ص + ع * آخر.ع
    نهاية
    
    # حاصل الضرب الاتجاهي
    دالة ضرب_اتجاهي(متجه3 آخر) متجه3
        ارجع متجه3(
            ص * آخر.ع - ع * آخر.ص،
            ع * آخر.س - س * آخر.ع،
            س * آخر.ص - ص * آخر.س
        )
    نهاية
    
    # الزاوية بين متجهين (بالراديان)
    دالة زاوية(متجه3 آخر) عشري
        عشري حاصل = ضرب_نقطي(آخر)
        عشري أطوال = طول() * آخر.طول()
        
        إذا (أطوال == 0)
            ارجع 0
        نهاية
        
        ارجع جتا_عكسي(حاصل / أطوال)
    نهاية
    
    # تحويل إلى نص
    دالة إلى_نص() نص
        ارجع ن"({س.تقريب(3)}، {ص.تقريب(3)}، {ع.تقريب(3)})"
    نهاية
    
    # متجه الصفر
    ثابتة دالة صفر() متجه3
        ارجع متجه3(0، 0، 0)
    نهاية
    
    # متجهات الوحدة
    ثابتة دالة وحدة_س() متجه3
        ارجع متجه3(1، 0، 0)
    نهاية
    
    ثابتة دالة وحدة_ص() متجه3
        ارجع متجه3(0، 1، 0)
    نهاية
    
    ثابتة دالة وحدة_ع() متجه3
        ارجع متجه3(0، 0، 1)
    نهاية
نهاية

