دالة اسم_مستشعر(نوع_مستشعر نوع) نص
    إذا (نوع == نوع_مستشعر.تسارع)
        ارجع "مقياس التسارع"
    وإلا_إذا (نوع == نوع_مستشعر.جيروسكوب)
        ارجع "الجيروسكوب"
    وإلا_إذا (نوع == نوع_مستشعر.مغناطيسية)
        ارجع "مقياس المغناطيسية"
    وإلا_إذا (نوع == نوع_مستشعر.ضغط)
        ارجع "مقياس الضغط"
    وإلا_إذا (نوع == نوع_مستشعر.إضاءة)
        ارجع "مقياس الإضاءة"
    وإلا_إذا (نوع == نوع_مستشعر.قرب)
        ارجع "مستشعر القرب"
    وإلا_إذا (نوع == نوع_مستشعر.توجه)
        ارجع "مستشعر التوجه"
    وإلا_إذا (نوع == نوع_مستشعر.خطوات)
        ارجع "عداد الخطوات"
    وإلا_إذا (نوع == نوع_مستشعر.نبض)
        ارجع "مقياس النبض"
    وإلا_إذا (نوع == نوع_مستشعر.حرارة)
        ارجع "مقياس الحرارة"
    وإلا_إذا (نوع == نوع_مستشعر.رطوبة)
        ارجع "مقياس الرطوبة"
    وإلا
        ارجع "مستشعر غير معروف"
