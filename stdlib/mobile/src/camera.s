# صنف كاميرا - الواجهة الرئيسية للتحكم بالكاميرا
#
# مثال:
#     نتيجة<كاميرا، خطأ_كاميرا> نت = انتظر كاميرا.جديد()
#     إذا (نت.ناجح())
#         كاميرا ك = نت.قيمة()
#         انتظر ك.ابدأ_معاينة()
#         صورة_ملتقطة ص = انتظر ك.التقط()
#     نهاية
#
صنف كاميرا
    نص معرف
    نوع_كاميرا نوع
    حالة_كاميرا حالة
    إعدادات_صورة إعدادات_ص
    إعدادات_فيديو إعدادات_ف
    عشري تكبير
    
    دالة منشئ()
        معرف = ""
        نوع = نوع_كاميرا.خلفية
        حالة = حالة_كاميرا.غير_مهيأة
        إعدادات_ص = إعدادات_صورة.افتراضي()
        إعدادات_ف = إعدادات_فيديو.افتراضي()
        تكبير = 1.0
    نهاية
    
    # =========================================
    #           دوال ثابتة
    # =========================================
    
    # التحقق من توفر الكاميرا
    ثابتة مزامن دالة متاحة() منطقي
        # التنفيذ الفعلي في المنصة
        ارجع صحيح
    نهاية
    
    # طلب إذن الوصول للكاميرا
    ثابتة مزامن دالة طلب_إذن() نتيجة<منطقي، خطأ_كاميرا>
        # التنفيذ الفعلي في المنصة
        ارجع نتيجة.نجاح(صحيح)
    نهاية
    
    # الحصول على قائمة الكاميرات المتاحة
    ثابتة مزامن دالة الكاميرات_المتاحة() نتيجة<مصفوفة<معلومات_كاميرا>، خطأ_كاميرا>
        # التنفيذ الفعلي في المنصة
        ارجع نتيجة.نجاح([])
    نهاية
    
    # إنشاء كاميرا جديدة
    ثابتة مزامن دالة جديد(نوع_كاميرا ن = نوع_كاميرا.خلفية) نتيجة<كاميرا، خطأ_كاميرا>
        # التحقق من الإذن
        نتيجة<منطقي، خطأ_كاميرا> إذن = انتظر كاميرا.طلب_إذن()
        
        إذا (إذن.فاشل())
            ارجع نتيجة.فشل(إذن.خطأ())
        نهاية
        
        إذا (!إذن.قيمة())
            ارجع نتيجة.فشل(خطأ_كاميرا.لا_يوجد_إذن)
        نهاية
        
        # إنشاء الكاميرا
        كاميرا ك = كاميرا()
        ك.نوع = ن
        
        ارجع نتيجة.نجاح(ك)
    نهاية
    
    # =========================================
    #           التهيئة والإغلاق
    # =========================================
    
    # تهيئة الكاميرا
    مزامن دالة هيئ() نتيجة<فراغ، خطأ_كاميرا>
        # التنفيذ الفعلي في المنصة
        حالة = حالة_كاميرا.جاهزة
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # إغلاق الكاميرا وتحرير الموارد
    مزامن دالة أغلق() نتيجة<فراغ، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.تسجيل)
            انتظر أوقف_تسجيل()
        نهاية
        
        إذا (حالة == حالة_كاميرا.معاينة)
            انتظر أوقف_معاينة()
        نهاية
        
        # التنفيذ الفعلي في المنصة
        حالة = حالة_كاميرا.غير_مهيأة
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # =========================================
    #           المعاينة
    # =========================================
    
    # بدء المعاينة
    مزامن دالة ابدأ_معاينة() نتيجة<فراغ، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.غير_مهيأة)
            ارجع نتيجة.فشل(خطأ_كاميرا.فشل_تهيئة)
        نهاية
        
        # التنفيذ الفعلي في المنصة
        حالة = حالة_كاميرا.معاينة
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # إيقاف المعاينة
    مزامن دالة أوقف_معاينة() نتيجة<فراغ، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.معاينة)
            # التنفيذ الفعلي في المنصة
            حالة = حالة_كاميرا.جاهزة
        نهاية
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # =========================================
    #           التقاط الصور
    # =========================================
    
    # التقاط صورة
    مزامن دالة التقط() نتيجة<صورة_ملتقطة، خطأ_كاميرا>
        ارجع انتظر التقط_بإعدادات(إعدادات_ص)
    نهاية
    
    # التقاط صورة بإعدادات مخصصة
    مزامن دالة التقط_بإعدادات(إعدادات_صورة إع) نتيجة<صورة_ملتقطة، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.تسجيل)
            ارجع نتيجة.فشل(خطأ_كاميرا.قيد_الاستخدام)
        نهاية
        
        حالة_كاميرا حالة_سابقة = حالة
        حالة = حالة_كاميرا.التقاط
        
        # التنفيذ الفعلي في المنصة
        صورة_ملتقطة صورة = صورة_ملتقطة()
        صورة.عرض = إع.دقة_صورة.عرض
        صورة.ارتفاع = إع.دقة_صورة.ارتفاع
        صورة.تنسيق = إع.تنسيق
        
        حالة = حالة_سابقة
        ارجع نتيجة.نجاح(صورة)
    نهاية
    
    # =========================================
    #           تسجيل الفيديو
    # =========================================
    
    # بدء تسجيل فيديو
    مزامن دالة ابدأ_تسجيل() نتيجة<فراغ، خطأ_كاميرا>
        ارجع انتظر ابدأ_تسجيل_بإعدادات(إعدادات_ف)
    نهاية
    
    # بدء تسجيل فيديو بإعدادات مخصصة
    مزامن دالة ابدأ_تسجيل_بإعدادات(إعدادات_فيديو إع) نتيجة<فراغ، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.تسجيل)
            ارجع نتيجة.فشل(خطأ_كاميرا.قيد_الاستخدام)
        نهاية
        
        # التنفيذ الفعلي في المنصة
        حالة = حالة_كاميرا.تسجيل
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # إيقاف تسجيل الفيديو مؤقتاً
    مزامن دالة أوقف_تسجيل_مؤقتاً() نتيجة<فراغ، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.تسجيل)
            # التنفيذ الفعلي في المنصة
            حالة = حالة_كاميرا.متوقفة
        نهاية
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # استئناف تسجيل الفيديو
    مزامن دالة استأنف_تسجيل() نتيجة<فراغ، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.متوقفة)
            # التنفيذ الفعلي في المنصة
            حالة = حالة_كاميرا.تسجيل
        نهاية
        ارجع نتيجة.نجاح(فراغ)
    نهاية
    
    # إيقاف تسجيل الفيديو
    مزامن دالة أوقف_تسجيل() نتيجة<فيديو_مسجل، خطأ_كاميرا>
        إذا (حالة == حالة_كاميرا.تسجيل || حالة == حالة_كاميرا.متوقفة)
