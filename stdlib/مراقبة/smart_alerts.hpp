/**
 * طباعة التنبيه
 */
inline void معالج_طباعة(const تنبيه& ت) {
    std::string رمز;
    switch (ت.المستوى) {
        case مستوى_تنبيه::معلومة: رمز = "ℹ️"; break;
        case مستوى_تنبيه::تحذير: رمز = "⚠️"; break;
        case مستوى_تنبيه::خطأ: رمز = "❌"; break;
        case مستوى_تنبيه::حرج: رمز = "🚨"; break;
    }
    
    std::cout << رمز << " [" << ت.المقياس << "] " << ت.الرسالة << std::endl;
    std::cout << "   القيمة: " << ت.القيمة_الحالية 
              << " (المتوقع: " << ت.القيمة_المتوقعة << ")" << std::endl;
}

