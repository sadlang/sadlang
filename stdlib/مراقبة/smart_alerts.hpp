/**
 * مستوى خطورة التنبيه
 */
enum class مستوى_تنبيه {
    معلومة,
    تحذير,
    خطأ,
    حرج
};

/**
 * تنبيه
 */
struct تنبيه {
    std::string المعرف;
    std::string المقياس;
    مستوى_تنبيه المستوى;
    std::string الرسالة;
    double القيمة_الحالية;
    double القيمة_المتوقعة;
    double الانحراف;
    std::chrono::system_clock::time_point الوقت;
    std::map<std::string, std::string> السياق;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              محلل الأنماط
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 📊 محلل الأنماط الزمنية
 */
class محلل_أنماط {
public:
    /**
     * إضافة قياس
     */
    void سجل(const std::string& مقياس, double قيمة) {
        auto الآن = std::chrono::system_clock::now();
        البيانات_[مقياس].push_back({الآن, قيمة});
        
        // الاحتفاظ ببيانات 7 أيام
        const auto حد = الآن - std::chrono::hours(7 * 24);
        auto& قائمة = البيانات_[مقياس];
        قائمة.erase(
            std::remove_if(قائمة.begin(), قائمة.end(),
                [حد](const auto& نقطة) { return نقطة.first < حد; }),
            قائمة.end()
        );
    }
    
    /**
     * الحصول على القيمة المتوقعة
     */
    double القيمة_المتوقعة(const std::string& مقياس) const {
        auto it = البيانات_.find(مقياس);
        if (it == البيانات_.end() || it->second.empty()) {
            return 0;
        }
        
        auto الآن = std::chrono::system_clock::now();
        auto وقت = std::chrono::system_clock::to_time_t(الآن);
        struct tm* زمن = std::localtime(&وقت);
        int الساعة = زمن->tm_hour;
        int اليوم = زمن->tm_wday;
        
        // حساب المتوسط لنفس الساعة في نفس اليوم
        double مجموع = 0;
        int عدد = 0;
        
        for (const auto& [وقت_نقطة, قيمة] : it->second) {
            auto وقت_t = std::chrono::system_clock::to_time_t(وقت_نقطة);
            struct tm* زمن_نقطة = std::localtime(&وقت_t);
            
            if (زمن_نقطة->tm_hour == الساعة && زمن_نقطة->tm_wday == اليوم) {
                مجموع += قيمة;
                عدد++;
            }
        }
        
        if (عدد > 0) {
            return مجموع / عدد;
        }
        
        // إذا لم تتوفر بيانات، استخدم المتوسط العام
        مجموع = 0;
        for (const auto& [_, قيمة] : it->second) {
            مجموع += قيمة;
        }
        return مجموع / it->second.size();
    }
    
    /**
     * الانحراف المعياري
     */
    double الانحراف_المعياري(const std::string& مقياس) const {
        auto it = البيانات_.find(مقياس);
        if (it == البيانات_.end() || it->second.size() < 2) {
            return 0;
        }
        
        double المتوسط = القيمة_المتوقعة(مقياس);
        double مجموع_المربعات = 0;
        
        for (const auto& [_, قيمة] : it->second) {
            مجموع_المربعات += (قيمة - المتوسط) * (قيمة - المتوسط);
        }
        
        return std::sqrt(مجموع_المربعات / it->second.size());
    }
    
private:
    std::map<std::string, std::vector<std::pair<std::chrono::system_clock::time_point, double>>> البيانات_;
};

