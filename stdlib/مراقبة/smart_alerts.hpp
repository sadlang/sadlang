/**
 * 🔔 نظام التنبيهات الذكية
 */
class نظام_تنبيهات {
public:
    using معالج_تنبيه = std::function<void(const تنبيه&)>;
    
    /**
     * إضافة معالج تنبيه
     */
    void أضف_معالج(معالج_تنبيه معالج) {
        المعالجات_.push_back(معالج);
    }
    
    /**
     * تسجيل قيمة وفحص التنبيه
     */
    void سجل_وافحص(const std::string& مقياس, double قيمة) {
        محلل_.سجل(مقياس, قيمة);
        
        double المتوقع = محلل_.القيمة_المتوقعة(مقياس);
        double الانحراف = محلل_.الانحراف_المعياري(مقياس);
        
        // فحص إذا كانت القيمة خارج النطاق الطبيعي
        double الفرق = std::abs(قيمة - المتوقع);
        
        // تنبيه إذا الانحراف أكثر من 2 انحرافات معيارية
        if (الانحراف > 0 && الفرق > 2 * الانحراف) {
            تنبيه ت;
            ت.المعرف = "alert-" + مقياس + "-" + std::to_string(std::time(nullptr));
            ت.المقياس = مقياس;
            ت.القيمة_الحالية = قيمة;
            ت.القيمة_المتوقعة = المتوقع;
            ت.الانحراف = الفرق / الانحراف;
            ت.الوقت = std::chrono::system_clock::now();
            
            // تحديد المستوى
            if (ت.الانحراف > 4) {
                ت.المستوى = مستوى_تنبيه::حرج;
                ت.الرسالة = "قيمة حرجة في " + مقياس;
            } else if (ت.الانحراف > 3) {
                ت.المستوى = مستوى_تنبيه::خطأ;
                ت.الرسالة = "قيمة غير طبيعية في " + مقياس;
            } else {
                ت.المستوى = مستوى_تنبيه::تحذير;
                ت.الرسالة = "قيمة خارج النطاق في " + مقياس;
            }
            
            // فحص التجميع (لا تكرار نفس التنبيه)
            if (يجب_إرسال(ت)) {
                أرسل_تنبيه(ت);
            }
        }
    }
    
    /**
     * تعيين حد ثابت
     */
    void عين_حد(const std::string& مقياس, double حد_تحذير, double حد_خطأ) {
        الحدود_[مقياس] = {حد_تحذير, حد_خطأ};
    }
    
private:
    محلل_أنماط محلل_;
    std::vector<معالج_تنبيه> المعالجات_;
    std::map<std::string, std::pair<double, double>> الحدود_;
    std::map<std::string, std::chrono::system_clock::time_point> آخر_تنبيه_;
    
    /**
     * هل يجب إرسال التنبيه؟
     */
    bool يجب_إرسال(const تنبيه& ت) {
        auto it = آخر_تنبيه_.find(ت.المقياس);
        if (it == آخر_تنبيه_.end()) {
            return true;
        }
        
        // لا تكرار نفس التنبيه خلال 5 دقائق
        auto فترة = std::chrono::minutes(5);
        if (ت.المستوى == مستوى_تنبيه::حرج) {
            فترة = std::chrono::minutes(1);
        }
        
        return (ت.الوقت - it->second) > فترة;
    }
    
    /**
     * إرسال التنبيه
     */
    void أرسل_تنبيه(const تنبيه& ت) {
        آخر_تنبيه_[ت.المقياس] = ت.الوقت;
        
        for (const auto& معالج : المعالجات_) {
            معالج(ت);
        }
    }
};

