/**
 * نقطة بيانات للتعلم
 */
struct نقطة_بيانات {
    double القيمة;
    int الساعة;         // 0-23
    int اليوم;          // 0-6 (الأحد = 0)
    std::chrono::system_clock::time_point الوقت;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              الحد التكيفي
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 📈 حد تكيفي
 */
class حد_تكيفي {
public:
    /**
     * إنشاء حد تكيفي
     */
    حد_تكيفي(double حد_أساسي = 100.0, double معامل_انحراف = 2.0)
        : الحد_الأساسي_(حد_أساسي)
        , معامل_الانحراف_(معامل_انحراف) {}
    
    /**
     * تسجيل قيمة
     */
    void سجل(double قيمة) {
        auto الآن = std::chrono::system_clock::now();
        auto وقت = std::chrono::system_clock::to_time_t(الآن);
        struct tm* زمن = std::localtime(&وقت);
        
        نقطة_بيانات نقطة;
        نقطة.القيمة = قيمة;
        نقطة.الساعة = زمن->tm_hour;
        نقطة.اليوم = زمن->tm_wday;
        نقطة.الوقت = الآن;
        
        البيانات_.push_back(نقطة);
        
        // الاحتفاظ ببيانات 14 يوم
        const auto حد = الآن - std::chrono::hours(14 * 24);
        البيانات_.erase(
            std::remove_if(البيانات_.begin(), البيانات_.end(),
                [حد](const نقطة_بيانات& ن) { return ن.الوقت < حد; }),
            البيانات_.end()
        );
        
        // إعادة حساب الحدود
        أعد_حساب_الحدود();
    }
    
    /**
     * الحصول على الحد الحالي
     */
    double الحد_الحالي() const {
        auto الآن = std::chrono::system_clock::now();
        auto وقت = std::chrono::system_clock::to_time_t(الآن);
        struct tm* زمن = std::localtime(&وقت);
        int الساعة = زمن->tm_hour;
        int اليوم = زمن->tm_wday;
        
        auto it = الحدود_.find({الساعة, اليوم});
        if (it != الحدود_.end()) {
            return it->second;
        }
        
        return الحد_الأساسي_;
    }
    
    /**
     * هل القيمة تتجاوز الحد؟
     */
    bool تجاوز(double قيمة) const {
        return قيمة > الحد_الحالي();
    }
    
    /**
     * نسبة التجاوز
     */
    double نسبة_التجاوز(double قيمة) const {
        double الحد = الحد_الحالي();
        if (الحد <= 0) return 0;
        return (قيمة - الحد) / الحد * 100;
    }
    
    /**
     * الحصول على جميع الحدود
     */
    std::map<std::pair<int, int>, double> جميع_الحدود() const {
        return الحدود_;
    }
    
private:
    double الحد_الأساسي_;
    double معامل_الانحراف_;
    std::vector<نقطة_بيانات> البيانات_;
    std::map<std::pair<int, int>, double> الحدود_;  // {ساعة، يوم} -> حد
    
    /**
     * إعادة حساب الحدود
     */
    void أعد_حساب_الحدود() {
        // تجميع البيانات حسب الساعة واليوم
        std::map<std::pair<int, int>, std::vector<double>> مجموعات;
        
        for (const auto& نقطة : البيانات_) {
            مجموعات[{نقطة.الساعة, نقطة.اليوم}].push_back(نقطة.القيمة);
        }
        
        // حساب الحد لكل مجموعة
        for (const auto& [مفتاح, قيم] : مجموعات) {
            if (قيم.size() < 3) {
                الحدود_[مفتاح] = الحد_الأساسي_;
                continue;
            }
            
            // المتوسط
            double مجموع = 0;
            for (double ق : قيم) مجموع += ق;
            double متوسط = مجموع / قيم.size();
            
            // الانحراف المعياري
            double مجموع_مربعات = 0;
            for (double ق : قيم) {
                مجموع_مربعات += (ق - متوسط) * (ق - متوسط);
            }
            double انحراف = std::sqrt(مجموع_مربعات / قيم.size());
            
            // الحد = المتوسط + معامل × الانحراف
            الحدود_[مفتاح] = متوسط + معامل_الانحراف_ * انحراف;
        }
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مدير الحدود
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 📊 مدير الحدود التكيفية
 */
class مدير_حدود {
public:
    /**
     * إضافة حد لمقياس
     */
    void أضف_حد(const std::string& مقياس, double حد_أساسي = 100.0) {
        الحدود_[مقياس] = حد_تكيفي(حد_أساسي);
    }
    
    /**
     * تسجيل قيمة
     */
    void سجل(const std::string& مقياس, double قيمة) {
        auto it = الحدود_.find(مقياس);
        if (it == الحدود_.end()) {
            أضف_حد(مقياس);
            it = الحدود_.find(مقياس);
        }
        
        it->second.سجل(قيمة);
    }
    
    /**
     * فحص التجاوز
     */
    bool تجاوز(const std::string& مقياس, double قيمة) const {
        auto it = الحدود_.find(مقياس);
        if (it == الحدود_.end()) {
            return false;
        }
        return it->second.تجاوز(قيمة);
    }
    
    /**
     * الحصول على الحد الحالي
     */
    double الحد(const std::string& مقياس) const {
        auto it = الحدود_.find(مقياس);
        if (it == الحدود_.end()) {
            return 0;
        }
        return it->second.الحد_الحالي();
    }
    
    /**
     * تقرير الحدود
     */
    std::string تقرير() const {
        std::string نتيجة;
        نتيجة += "╔════════════════════════════════════════════════╗\n";
        نتيجة += "║            📊 الحدود التكيفية الحالية          ║\n";
        نتيجة += "╠════════════════════════════════════════════════╣\n";
        
        for (const auto& [مقياس, حد] : الحدود_) {
            نتيجة += "║ " + مقياس + ": " + 
                      std::to_string(static_cast<int>(حد.الحد_الحالي())) + "\n";
        }
        
        نتيجة += "╚════════════════════════════════════════════════╝\n";
        return نتيجة;
    }
    
private:
    std::map<std::string, حد_تكيفي> الحدود_;
};

