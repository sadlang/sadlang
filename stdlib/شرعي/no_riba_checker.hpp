/**
 * نوع الربا المكتشف
 */
enum class نوع_ربا {
    ربا_القرض,      // قرض بفائدة
    ربا_النسيئة,    // تأخير مقابل زيادة
    ربا_الفضل,      // تفاضل في أموال الربا
    عائد_مضمون,     // عائد على رأس المال مضمون
    فائدة_متغيرة    // حتى الفائدة المتغيرة على القرض = ربا
};

/**
 * مستوى خطورة الربا
 */
enum class خطورة_ربا {
    صريح,      // ربا واضح لا شبهة فيه
    محتمل,     // يُحتمل أنه ربا
    مُشتبه     // يحتاج مراجعة فقهية
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              نتيجة فحص الربا
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * تفصيل مشكلة ربا
 */
struct مشكلة_ربا {
    نوع_ربا النوع;
    خطورة_ربا الخطورة;
    std::string الموقع;           // أين وُجدت المشكلة
    std::string الوصف;            // شرح المشكلة
    std::string الدليل;           // النص الذي يدل على الربا
    std::string البديل_المقترح;   // البديل الشرعي
};

/**
 * نتيجة فحص الربا
 */
struct نتيجة_فحص_ربا {
    bool يحتوي_ربا = false;
    std::vector<مشكلة_ربا> المشاكل;
    std::string ملخص;
    
    // إحصائيات
    int صريح = 0;
    int محتمل = 0;
    int مُشتبه = 0;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              فاحص الربا
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * فاحص الربا في الكود والمعاملات
 */
class فاحص_ربا {
public:
    /**
     * فحص نص الكود بحثاً عن أنماط الربا
     */
    نتيجة_فحص_ربا افحص_كود(const std::string& كود) const {
        نتيجة_فحص_ربا نتيجة;
        
        // البحث عن أنماط الفائدة الثابتة
        افحص_فائدة_ثابتة(كود, نتيجة);
        
        // البحث عن أنماط القرض بفائدة
        افحص_قرض_بفائدة(كود, نتيجة);
        
        // البحث عن العائد المضمون
        افحص_عائد_مضمون(كود, نتيجة);
        
        // البحث عن تأخير مقابل زيادة
        افحص_تأخير_بزيادة(كود, نتيجة);
        
        // تحديث الإحصائيات
        for (const auto& مشكلة : نتيجة.المشاكل) {
            switch (مشكلة.الخطورة) {
                case خطورة_ربا::صريح: نتيجة.صريح++; break;
                case خطورة_ربا::محتمل: نتيجة.محتمل++; break;
                case خطورة_ربا::مُشتبه: نتيجة.مُشتبه++; break;
            }
        }
        
        نتيجة.يحتوي_ربا = !نتيجة.المشاكل.empty();
        
        if (نتيجة.يحتوي_ربا) {
            نتيجة.ملخص = "⚠️ تم اكتشاف " + std::to_string(نتيجة.المشاكل.size()) + 
                         " مشكلة محتملة تتعلق بالربا";
        }
        else {
            نتيجة.ملخص = "✅ لم يُعثر على أنماط ربا في الكود";
        }
        
        return نتيجة;
    }
    
    /**
     * فحص معاملة مالية
     */
    نتيجة_فحص_ربا افحص_معاملة(
        double المبلغ_الأصلي,
        double المبلغ_النهائي,
        const std::string& نوع_المعاملة,
        int المدة_بالأشهر = 0
    ) const {
        نتيجة_فحص_ربا نتيجة;
        
        // حساب الفرق
        double الفرق = المبلغ_النهائي - المبلغ_الأصلي;
        double النسبة = (الفرق / المبلغ_الأصلي) * 100;
        
        // إذا كان قرضاً وهناك زيادة
        if (نوع_المعاملة == "قرض" || نوع_المعاملة == "loan") {
            if (الفرق > 0) {
                مشكلة_ربا مشكلة;
                مشكلة.النوع = نوع_ربا::ربا_القرض;
                مشكلة.الخطورة = خطورة_ربا::صريح;
                مشكلة.الوصف = "قرض بفائدة " + std::to_string(النسبة) + "%";
                مشكلة.الدليل = "كل قرض جر نفعاً فهو ربا";
                مشكلة.البديل_المقترح = "استخدم المشاركة أو المضاربة بدلاً من القرض بفائدة";
                نتيجة.المشاكل.push_back(مشكلة);
                نتيجة.صريح++;
            }
        }
        
        // إذا كان استثماراً بعائد مضمون
        if (نوع_المعاملة == "استثمار_مضمون" || نوع_المعاملة == "guaranteed") {
            مشكلة_ربا مشكلة;
            مشكلة.النوع = نوع_ربا::عائد_مضمون;
            مشكلة.الخطورة = خطورة_ربا::صريح;
            مشكلة.الوصف = "عائد مضمون على رأس المال";
            مشكلة.الدليل = "الغنم بالغرم - لا يجوز ضمان رأس المال والربح معاً";
            مشكلة.البديل_المقترح = "استخدم المشاركة في الربح والخسارة";
            نتيجة.المشاكل.push_back(مشكلة);
            نتيجة.صريح++;
        }
        
        نتيجة.يحتوي_ربا = !نتيجة.المشاكل.empty();
        
        if (نتيجة.يحتوي_ربا) {
            نتيجة.ملخص = "❌ المعاملة تحتوي على ربا";
        }
        else {
            نتيجة.ملخص = "✅ المعاملة خالية من الربا";
        }
        
        return نتيجة;
    }
    
private:
    void افحص_فائدة_ثابتة(const std::string& كود, نتيجة_فحص_ربا& نتيجة) const {
        // أنماط الفائدة الثابتة
        std::vector<std::regex> أنماط = {
            std::regex(R"(فائدة\s*[=:]\s*(\d+\.?\d*)\s*%)", std::regex::icase),
            std::regex(R"(interest\s*[=:]\s*(\d+\.?\d*)\s*%)", std::regex::icase),
            std::regex(R"(rate\s*[=:]\s*(\d+\.?\d*)\s*%)", std::regex::icase),
            std::regex(R"(نسبة_فائدة|interest_rate)", std::regex::icase),
            std::regex(R"(عائد_ثابت|fixed_return)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            std::smatch تطابق;
            std::string نص = كود;
            
            while (std::regex_search(نص, تطابق, نمط)) {
                مشكلة_ربا مشكلة;
                مشكلة.النوع = نوع_ربا::عائد_مضمون;
                مشكلة.الخطورة = خطورة_ربا::صريح;
                مشكلة.الدليل = تطابق[0];
                مشكلة.الوصف = "استخدام فائدة ثابتة";
                مشكلة.البديل_المقترح = "استبدل بنسبة مشاركة في الربح";
                نتيجة.المشاكل.push_back(مشكلة);
                
                نص = تطابق.suffix();
            }
        }
    }
    
    void افحص_قرض_بفائدة(const std::string& كود, نتيجة_فحص_ربا& نتيجة) const {
        std::vector<std::regex> أنماط = {
            std::regex(R"(قرض.*فائدة|فائدة.*قرض)", std::regex::icase),
            std::regex(R"(loan.*interest|interest.*loan)", std::regex::icase),
            std::regex(R"(اقترض.*بـ?\s*\d+\s*%)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            std::smatch تطابق;
            if (std::regex_search(كود, تطابق, نمط)) {
                مشكلة_ربا مشكلة;
                مشكلة.النوع = نوع_ربا::ربا_القرض;
                مشكلة.الخطورة = خطورة_ربا::صريح;
                مشكلة.الدليل = تطابق[0];
                مشكلة.الوصف = "قرض بفائدة";
                مشكلة.البديل_المقترح = "استخدم المرابحة أو المضاربة";
                نتيجة.المشاكل.push_back(مشكلة);
            }
        }
    }
    
    void افحص_عائد_مضمون(const std::string& كود, نتيجة_فحص_ربا& نتيجة) const {
        std::vector<std::regex> أنماط = {
            std::regex(R"(عائد_مضمون|guaranteed_return)", std::regex::icase),
            std::regex(R"(ربح_مضمون|guaranteed_profit)", std::regex::icase),
            std::regex(R"(ضمان.*رأس.*المال|capital_guarantee)", std::regex::icase),
            std::regex(R"(fixed_income|دخل_ثابت)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            std::smatch تطابق;
            if (std::regex_search(كود, تطابق, نمط)) {
                مشكلة_ربا مشكلة;
                مشكلة.النوع = نوع_ربا::عائد_مضمون;
                مشكلة.الخطورة = خطورة_ربا::صريح;
                مشكلة.الدليل = تطابق[0];
                مشكلة.الوصف = "عائد أو ربح مضمون";
                مشكلة.البديل_المقترح = "استخدم نسبة مشاركة غير مضمونة";
                نتيجة.المشاكل.push_back(مشكلة);
            }
        }
    }
    
    void افحص_تأخير_بزيادة(const std::string& كود, نتيجة_فحص_ربا& نتيجة) const {
        std::vector<std::regex> أنماط = {
            std::regex(R"(تأخير.*زيادة|زيادة.*تأخير)", std::regex::icase),
            std::regex(R"(late_fee|رسوم_تأخير)", std::regex::icase),
            std::regex(R"(penalty.*interest|فائدة.*غرامة)", std::regex::icase),
        };
        
        for (const auto& نمط : أنماط) {
            std::smatch تطابق;
            if (std::regex_search(كود, تطابق, نمط)) {
                مشكلة_ربا مشكلة;
                مشكلة.النوع = نوع_ربا::ربا_النسيئة;
                مشكلة.الخطورة = خطورة_ربا::محتمل;
                مشكلة.الدليل = تطابق[0];
                مشكلة.الوصف = "زيادة مقابل التأخير";
                مشكلة.البديل_المقترح = "استخدم التعويض عن الضرر الفعلي فقط";
                نتيجة.المشاكل.push_back(مشكلة);
            }
        }
    }
};

