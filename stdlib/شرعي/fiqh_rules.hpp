/**
 * نتيجة التدقيق الشرعي
 */
struct نتيجة_تدقيق {
    حكم_شرعي الحكم;
    يقين اليقين;
    std::string الشرح;
    std::vector<std::string> القواعد_المطبقة;
    std::vector<std::string> التوصيات;
};

/**
 * المُدقق الشرعي الأساسي
 */
class مُدقق_شرعي {
public:
    /**
     * تدقيق معاملة مالية
     */
    نتيجة_تدقيق دقق_معاملة(
        const std::string& الوصف,
        const std::map<std::string, std::string>& التفاصيل
    ) const {
        نتيجة_تدقيق نتيجة;
        نتيجة.الحكم = حكم_شرعي::مباح;
        نتيجة.اليقين = يقين::راجح;
        
        // البحث عن كلمات مفتاحية مشبوهة
        std::set<std::string> كلمات_ربا = {
            "فائدة", "interest", "ثابت", "مضمون", "نسبة"
        };
        
        std::set<std::string> كلمات_غرر = {
            "مجهول", "غير محدد", "تقريباً", "حوالي"
        };
        
        std::set<std::string> كلمات_ميسر = {
            "يانصيب", "سحب", "حظ", "مراهنة", "قمار"
        };
        
        // فحص الوصف والتفاصيل
        std::string النص_الكامل = الوصف;
        for (const auto& [مفتاح, قيمة] : التفاصيل) {
            النص_الكامل += " " + مفتاح + " " + قيمة;
        }
        
        // تحويل للحروف الصغيرة للمقارنة
        std::string نص_مقارنة = النص_الكامل;
        
        // فحص الربا
        for (const auto& كلمة : كلمات_ربا) {
            if (نص_مقارنة.find(كلمة) != std::string::npos) {
                نتيجة.الحكم = حكم_شرعي::حرام;
                نتيجة.اليقين = يقين::قطعي;
                نتيجة.الشرح = "يُشتبه وجود ربا في المعاملة";
                نتيجة.القواعد_المطبقة.push_back("ربا_001");
                نتيجة.القواعد_المطبقة.push_back("ربا_002");
                نتيجة.التوصيات.push_back("استبدل الفائدة الثابتة بالمشاركة في الربح والخسارة");
                return نتيجة;
            }
        }
        
        // فحص الميسر
        for (const auto& كلمة : كلمات_ميسر) {
            if (نص_مقارنة.find(كلمة) != std::string::npos) {
                نتيجة.الحكم = حكم_شرعي::حرام;
                نتيجة.اليقين = يقين::قطعي;
                نتيجة.الشرح = "يُشتبه وجود ميسر (قمار) في المعاملة";
                نتيجة.القواعد_المطبقة.push_back("ميسر_001");
                نتيجة.التوصيات.push_back("أزل عنصر الحظ والمصادفة من المعاملة");
                return نتيجة;
            }
        }
        
        // فحص الغرر
        for (const auto& كلمة : كلمات_غرر) {
            if (نص_مقارنة.find(كلمة) != std::string::npos) {
                نتيجة.الحكم = حكم_شرعي::مكروه;
                نتيجة.اليقين = يقين::راجح;
                نتيجة.الشرح = "يُشتبه وجود غرر في المعاملة";
                نتيجة.القواعد_المطبقة.push_back("غرر_001");
                نتيجة.التوصيات.push_back("وضّح جميع تفاصيل المعاملة");
            }
        }
        
        if (نتيجة.الحكم == حكم_شرعي::مباح) {
            نتيجة.الشرح = "لم يُعثر على ما يُشكل على المعاملة";
            نتيجة.القواعد_المطبقة.push_back("بيع_001");
        }
        
        return نتيجة;
    }
};

