/**
 * معلومات النوع الكاملة
 * 
 * هذا هو الكائن الرئيسي الذي تحصل عليه من نوع_من()
 * 
 *     ┌──────────────────────────────────────────────────────────────┐
 *     │                                                              │
 *     │   معلومات_نوع                                                │
 *     │   ├── الاسم()              "شخص"                             │
 *     │   ├── الاسم_الكامل()       "تطبيق::نماذج::شخص"               │
 *     │   ├── الحجم()              32 بايت                           │
 *     │   ├── التصنيف()            بنية                              │
 *     │   ├── الحقول()             [اسم, عمر]                        │
 *     │   ├── الدوال()             [قدِّم, احسب_عمر]                  │
 *     │   ├── السمات()             [قابل_للطباعة]                    │
 *     │   └── الأب()               كائن (أو لا شيء)                  │
 *     │                                                              │
 *     └──────────────────────────────────────────────────────────────┘
 */
class معلومات_نوع {
public:
    معلومات_نوع() = default;
    
    /**
     * اسم النوع القصير
     * مثال: "شخص"
     */
    const std::string& الاسم() const { return الاسم_; }
    void عيِّن_الاسم(std::string اسم) { الاسم_ = std::move(اسم); }
    
    /**
     * الاسم الكامل مع المسار
     * مثال: "تطبيق::نماذج::شخص"
     */
    const std::string& الاسم_الكامل() const { return الاسم_الكامل_; }
    void عيِّن_الاسم_الكامل(std::string اسم) { الاسم_الكامل_ = std::move(اسم); }
    
    /**
     * حجم النوع بالبايت
     * مفيد لمعرفة كم ذاكرة يستهلك الكائن
     */
    size_t الحجم() const { return الحجم_; }
    void عيِّن_الحجم(size_t حجم) { الحجم_ = حجم; }
    
    /**
     * محاذاة النوع بالبايت
     */
    size_t المحاذاة() const { return المحاذاة_; }
    void عيِّن_المحاذاة(size_t محاذاة) { المحاذاة_ = محاذاة; }
    
    /**
     * تصنيف النوع (بنية، صنف، سمة، إلخ)
     */
    تصنيف_نوع التصنيف() const { return التصنيف_; }
    void عيِّن_التصنيف(تصنيف_نوع تصنيف) { التصنيف_ = تصنيف; }
    
    /**
     * هل هذا بنية؟
     */
    bool بنية() const { return التصنيف_ == تصنيف_نوع::بنية; }
    
    /**
     * هل هذا صنف؟
     */
    bool صنف() const { return التصنيف_ == تصنيف_نوع::صنف; }
    
    /**
     * هل هذا سمة/واجهة؟
     */
    bool سمة() const { return التصنيف_ == تصنيف_نوع::سمة; }
    
    /**
     * هل هذا تعداد؟
     */
    bool تعداد() const { return التصنيف_ == تصنيف_نوع::تعداد; }
    
    /**
     * هل هذا نوع بدائي (عدد، نص، إلخ)؟
     */
    bool بدائي() const { return التصنيف_ == تصنيف_نوع::بدائي; }
    
    /**
     * قائمة حقول النوع
     */
    const قائمة_انعكاس<معلومات_حقل>& الحقول() const { return الحقول_; }
    void أضف_حقل(معلومات_حقل حقل) { 
        std::vector<معلومات_حقل> قائمة;
        for (const auto& ح : الحقول_) قائمة.push_back(ح);
        قائمة.push_back(std::move(حقل));
        الحقول_ = قائمة_انعكاس<معلومات_حقل>(std::move(قائمة));
    }
    
    /**
     * قائمة دوال النوع
     */
    const قائمة_انعكاس<معلومات_دالة>& الدوال() const { return الدوال_; }
    void أضف_دالة(معلومات_دالة دالة) { 
        std::vector<معلومات_دالة> قائمة;
        for (const auto& د : الدوال_) قائمة.push_back(د);
        قائمة.push_back(std::move(دالة));
        الدوال_ = قائمة_انعكاس<معلومات_دالة>(std::move(قائمة));
    }
    
    /**
     * السمات المُنفَّذة
     */
    const std::vector<std::string>& السمات_المُنفَّذة() const { return السمات_; }
    void أضف_سمة(std::string سمة) { السمات_.push_back(std::move(سمة)); }
    
    /**
     * هل النوع يُنفِّذ سمة معينة؟
     */
    bool يُنفِّذ(const std::string& سمة) const {
        for (const auto& س : السمات_) {
            if (س == سمة) return true;
        }
        return false;
    }
    
    /**
     * اسم النوع الأب (للوراثة)
     */
    const std::optional<std::string>& الأب() const { return الأب_; }
    void عيِّن_الأب(std::string أب) { الأب_ = std::move(أب); }
    
    /**
     * هل النوع يرث من نوع آخر؟
     */
    bool له_أب() const { return الأب_.has_value(); }
    
    /**
     * البحث عن حقل بالاسم
     */
    std::optional<معلومات_حقل> احصل_حقل(const std::string& اسم) const {
        return الحقول_.ابحث(اسم);
    }
    
    /**
     * البحث عن دالة بالاسم
     */
    std::optional<معلومات_دالة> احصل_دالة(const std::string& اسم) const {
        return الدوال_.ابحث(اسم);
    }
    
    /**
     * تمثيل نصي
     */
    std::string إلى_نص() const {
        std::string نتيجة = "نوع: " + الاسم_ + "\n";
        نتيجة += "  الحجم: " + std::to_string(الحجم_) + " بايت\n";
        نتيجة += "  الحقول (" + std::to_string(الحقول_.العدد()) + "):\n";
        
        for (const auto& حقل : الحقول_) {
            نتيجة += "    - " + حقل.الاسم() + ": " + حقل.اسم_النوع() + "\n";
        }
        
        نتيجة += "  الدوال (" + std::to_string(الدوال_.العدد()) + "):\n";
        
        for (const auto& دالة : الدوال_) {
            نتيجة += "    - " + دالة.الاسم() + "(): " + دالة.نوع_الإرجاع() + "\n";
        }
        
        return نتيجة;
    }

private:
    std::string الاسم_;
    std::string الاسم_الكامل_;
    size_t الحجم_ = 0;
    size_t المحاذاة_ = 1;
    تصنيف_نوع التصنيف_ = تصنيف_نوع::مجهول;
    
    قائمة_انعكاس<معلومات_حقل> الحقول_;
    قائمة_انعكاس<معلومات_دالة> الدوال_;
    std::vector<std::string> السمات_;
    std::optional<std::string> الأب_;
};

