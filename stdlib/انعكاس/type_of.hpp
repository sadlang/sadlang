/**
 * أنواع التصنيفات
 */
enum class تصنيف_نوع {
    بنية = 0,    // struct
    صنف = 1,     // class
    سمة = 2,     // trait/interface
    تعداد = 3,   // enum
    بدائي = 4,   // int, float, etc.
    مجهول = 5
};

// ═══════════════════════════════════════════════════════════════════════════════
