/**
 * معلومات حقل واحد في بنية/صنف
 * 
 * الحقل = متغير داخل البنية
 * مثل: "اسم" أو "عمر" في بنية "شخص"
 */
class معلومات_حقل {
public:
    معلومات_حقل() = default;
    
    معلومات_حقل(
        std::string اسم,
        std::string نوع,
        size_t إزاحة,
        size_t حجم,
        bool عام
    ) : الاسم_(اسم), النوع_(نوع), الإزاحة_(إزاحة), الحجم_(حجم), عام_(عام) {}
    
    /**
     * اسم الحقل
     * مثال: "اسم" في بنية شخص
     */
    const std::string& الاسم() const { return الاسم_; }
    
    /**
     * اسم نوع الحقل
     * مثال: "نص" أو "عدد"
     */
    const std::string& اسم_النوع() const { return النوع_; }
    
    /**
     * الإزاحة من بداية البنية (بالبايت)
     * مفيد للوصول المباشر للذاكرة
     */
    size_t الإزاحة() const { return الإزاحة_; }
    
    /**
     * حجم الحقل بالبايت
     */
    size_t الحجم() const { return الحجم_; }
    
    /**
     * هل الحقل عام (يمكن الوصول إليه من أي مكان)؟
     */
    bool عام() const { return عام_; }
    
    /**
     * احصل على قيمة الحقل من كائن
     * @param كائن مؤشر للكائن
     * @return مؤشر لقيمة الحقل
     */
    template<typename T>
    const T* احصل(const void* كائن) const {
        return reinterpret_cast<const T*>(
            static_cast<const char*>(كائن) + الإزاحة_
        );
    }
    
    /**
     * عيِّن قيمة الحقل في كائن
     * @param كائن مؤشر للكائن
     * @param قيمة القيمة الجديدة
     */
    template<typename T>
    void عيِّن(void* كائن, const T& قيمة) const {
        *reinterpret_cast<T*>(
            static_cast<char*>(كائن) + الإزاحة_
        ) = قيمة;
    }

private:
    std::string الاسم_;
    std::string النوع_;
    size_t الإزاحة_ = 0;
    size_t الحجم_ = 0;
    bool عام_ = true;
};

