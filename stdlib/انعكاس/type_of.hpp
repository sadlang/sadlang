/**
 * قائمة قابلة للتكرار
 * 
 * يمكنك استخدامها في حلقات:
 *     لكل حقل في معلومات.الحقول():
 *         اطبع(حقل.الاسم())
 *     نهاية
 */
template<typename T>
class قائمة_انعكاس {
public:
    قائمة_انعكاس() = default;
    
    قائمة_انعكاس(std::vector<T> عناصر) : العناصر_(std::move(عناصر)) {}
    
    /**
     * عدد العناصر
     */
    size_t العدد() const { return العناصر_.size(); }
    
    /**
     * هل القائمة فارغة؟
     */
    bool فارغة() const { return العناصر_.empty(); }
    
    /**
     * الوصول بالفهرس
     */
    const T& operator[](size_t فهرس) const { return العناصر_[فهرس]; }
    
    /**
     * البحث بالاسم
     */
    std::optional<T> ابحث(const std::string& اسم) const {
        for (const auto& عنصر : العناصر_) {
            if (عنصر.الاسم() == اسم) {
                return عنصر;
            }
        }
        return std::nullopt;
    }
    
    /**
     * تصفية العناصر
     */
    قائمة_انعكاس<T> صفِّ(std::function<bool(const T&)> شرط) const {
        std::vector<T> نتائج;
        for (const auto& عنصر : العناصر_) {
            if (شرط(عنصر)) {
                نتائج.push_back(عنصر);
            }
        }
        return قائمة_انعكاس<T>(std::move(نتائج));
    }
    
    /**
     * الحقول العامة فقط
     */
    قائمة_انعكاس<T> العامة_فقط() const {
        return صفِّ([](const T& ع) { return ع.عام(); });
    }
    
    // دعم range-based for loop
    auto begin() const { return العناصر_.begin(); }
    auto end() const { return العناصر_.end(); }

private:
    std::vector<T> العناصر_;
};

