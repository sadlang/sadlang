/**
 * معلومات معامل دالة
 */
struct معامل_دالة {
    std::string الاسم;
    std::string النوع;
};

/**
 * معلومات دالة/طريقة
 * 
 * الدالة = إجراء يمكن تنفيذه
 * مثل: "قدِّم()" في بنية "شخص"
 */
class معلومات_دالة {
public:
    معلومات_دالة() = default;
    
    معلومات_دالة(
        std::string اسم,
        std::string نوع_إرجاع,
        std::vector<معامل_دالة> معاملات,
        bool عامة
    ) : الاسم_(اسم), نوع_الإرجاع_(نوع_إرجاع), 
        المعاملات_(معاملات), عامة_(عامة) {}
    
    /**
     * اسم الدالة
     * مثال: "قدِّم" أو "احسب"
     */
    const std::string& الاسم() const { return الاسم_; }
    
    /**
     * نوع القيمة المُرجَعة
     * مثال: "عدد" أو "فراغ" (إذا لا تُرجع شيئاً)
     */
    const std::string& نوع_الإرجاع() const { return نوع_الإرجاع_; }
    
    /**
     * قائمة المعاملات (المدخلات)
     */
    const std::vector<معامل_دالة>& المعاملات() const { return المعاملات_; }
    
    /**
     * عدد المعاملات
     */
    size_t عدد_المعاملات() const { return المعاملات_.size(); }
    
    /**
     * هل الدالة عامة؟
     */
    bool عامة() const { return عامة_; }

private:
    std::string الاسم_;
    std::string نوع_الإرجاع_;
    std::vector<معامل_دالة> المعاملات_;
    bool عامة_ = true;
};

