/**
 * سجل الأنواع - مخزن مركزي لكل معلومات الأنواع
 * 
 * كل الأنواع في البرنامج مُسجَّلة هنا.
 * نوع_من() يبحث في هذا السجل.
 */
class سجل_الأنواع {
public:
    /**
     * الحصول على المثال الوحيد (Singleton)
     */
    static سجل_الأنواع& المثال() {
        static سجل_الأنواع instance;
        return instance;
    }
    
    /**
     * تسجيل نوع جديد
     */
    void سجِّل(const معلومات_نوع& نوع) {
        الأنواع_[نوع.الاسم()] = نوع;
        if (نوع.الاسم() != نوع.الاسم_الكامل()) {
            الأسماء_الكاملة_[نوع.الاسم_الكامل()] = نوع.الاسم();
        }
    }
    
    /**
     * البحث عن نوع بالاسم
     */
    std::optional<معلومات_نوع> ابحث(const std::string& اسم) const {
        auto it = الأنواع_.find(اسم);
        if (it != الأنواع_.end()) {
            return it->second;
        }
        
        // جرب الاسم الكامل
        auto it2 = الأسماء_الكاملة_.find(اسم);
        if (it2 != الأسماء_الكاملة_.end()) {
            return ابحث(it2->second);
        }
        
        return std::nullopt;
    }
    
    /**
     * هل النوع مُسجَّل؟
     */
    bool مُسجَّل(const std::string& اسم) const {
        return ابحث(اسم).has_value();
    }
    
    /**
     * قائمة كل الأنواع المُسجَّلة
     */
    std::vector<std::string> كل_الأنواع() const {
        std::vector<std::string> أسماء;
        for (const auto& [اسم, _] : الأنواع_) {
            أسماء.push_back(اسم);
        }
        return أسماء;
    }
    
    /**
     * عدد الأنواع المُسجَّلة
     */
    size_t عدد_الأنواع() const {
        return الأنواع_.size();
    }

private:
    سجل_الأنواع() = default;
    
    std::unordered_map<std::string, معلومات_نوع> الأنواع_;
    std::unordered_map<std::string, std::string> الأسماء_الكاملة_;
};

// ═══════════════════════════════════════════════════════════════════════════════
