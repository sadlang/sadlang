/**
 * دالة نوع_من() - الواجهة الرئيسية للانعكاس
 * 
 * استخدام:
 *     متغير معلومات = نوع_من("شخص")
 *     اطبع(معلومات.الاسم())
 */
inline std::optional<معلومات_نوع> نوع_من(const std::string& اسم) {
    return سجل_الأنواع::المثال().ابحث(اسم);
}

/**
 * دالة مساعدة للحصول على نوع من كائن
 */
template<typename T>
معلومات_نوع نوع_من_كائن(const T& كائن) {
    // في التنفيذ الكامل، هذا يستخدم RTTI أو جداول وقت الترجمة
    معلومات_نوع معلومات;
    معلومات.عيِّن_الاسم(typeid(T).name());
    معلومات.عيِّن_الحجم(sizeof(T));
    معلومات.عيِّن_المحاذاة(alignof(T));
    return معلومات;
}

