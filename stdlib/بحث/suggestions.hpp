/**
 * اقتراح بحث
 */
struct اقتراح_بحث {
    std::string النص;
    std::string السبب;           // لماذا هذا الاقتراح؟
    double درجة_الملاءمة;
    size_t عدد_النتائج_المتوقعة;
    
    // للعرض
    std::string نص_معروض() const {
        return "هل تقصد: \"" + النص + "\"؟";
    }
};

/**
 * نتيجة الاقتراحات
 */
struct نتيجة_اقتراحات {
    std::string الاستعلام_الأصلي;
    bool وُجدت_نتائج;
    std::vector<اقتراح_بحث> الاقتراحات;
    std::string الاقتراح_الرئيسي;  // أفضل اقتراح
};

// ═══════════════════════════════════════════════════════════════════════════════
