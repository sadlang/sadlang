/**
 * 💡 مُقترح البحث
 * 
 * يُقدم اقتراحات ذكية عندما لا تُوجد نتائج
 */
class مُقترح_بحث {
public:
    /**
     * إنشاء المُقترح
     */
    مُقترح_بحث() {
        حمّل_قاعدة_بيانات_افتراضية();
    }
    
    /**
     * إضافة كلمة للقاموس مع تكرارها
     */
    void سجّل_كلمة(const std::string& كلمة, size_t تكرار = 1) {
        تكرارات_الكلمات_[كلمة] += تكرار;
        القاموس_.insert(كلمة);
    }
    
    /**
     * إضافة مرادف
     */
    void أضف_مرادف(const std::string& كلمة, const std::string& مرادف) {
        المرادفات_[كلمة].push_back(مرادف);
        المرادفات_[مرادف].push_back(كلمة);
    }
    
    /**
     * توليد اقتراحات
     */
    نتيجة_اقتراحات اقترح(const std::string& استعلام, bool لا_نتائج = true) const {
        نتيجة_اقتراحات نتيجة;
        نتيجة.الاستعلام_الأصلي = استعلام;
        نتيجة.وُجدت_نتائج = !لا_نتائج;
        
        // 1. تصحيح الإملاء
        auto تصحيحات = اقتراحات_إملائية(استعلام);
        for (auto& اقتراح : تصحيحات) {
            نتيجة.الاقتراحات.push_back(اقتراح);
        }
        
        // 2. كلمات بنفس الجذر
        auto جذرية = اقتراحات_جذرية(استعلام);
        for (auto& اقتراح : جذرية) {
            نتيجة.الاقتراحات.push_back(اقتراح);
        }
        
        // 3. مرادفات
        auto مرادفات = اقتراحات_مرادفات(استعلام);
        for (auto& اقتراح : مرادفات) {
            نتيجة.الاقتراحات.push_back(اقتراح);
        }
        
        // 4. توسيعات
        auto توسيعات = اقتراحات_توسيع(استعلام);
        for (auto& اقتراح : توسيعات) {
            نتيجة.الاقتراحات.push_back(اقتراح);
        }
        
        // إزالة التكرارات
        أزل_التكرارات(نتيجة.الاقتراحات);
        
        // ترتيب حسب الملاءمة
        std::sort(نتيجة.الاقتراحات.begin(), نتيجة.الاقتراحات.end(),
            [](const اقتراح_بحث& أ, const اقتراح_بحث& ب) {
                return أ.درجة_الملاءمة > ب.درجة_الملاءمة;
            });
        
        // تحديد الاقتراح الرئيسي
        if (!نتيجة.الاقتراحات.empty()) {
            نتيجة.الاقتراح_الرئيسي = نتيجة.الاقتراحات[0].النص;
        }
        
        // الاحتفاظ بأفضل 5
        if (نتيجة.الاقتراحات.size() > 5) {
            نتيجة.الاقتراحات.resize(5);
        }
        
        return نتيجة;
    }
    
    /**
     * إكمال تلقائي
     */
    std::vector<std::string> أكمل(const std::string& بادئة, int الحد = 10) const {
        std::vector<std::pair<std::string, size_t>> مرشحون;
        
        for (const auto& كلمة : القاموس_) {
            if (كلمة.find(بادئة) == 0) {
                size_t تكرار = 1;
                auto it = تكرارات_الكلمات_.find(كلمة);
                if (it != تكرارات_الكلمات_.end()) {
                    تكرار = it->second;
                }
                مرشحون.push_back({كلمة, تكرار});
            }
        }
        
        // ترتيب حسب التكرار
        std::sort(مرشحون.begin(), مرشحون.end(),
            [](const auto& أ, const auto& ب) {
                return أ.second > ب.second;
            });
        
        std::vector<std::string> نتائج;
        for (size_t i = 0; i < std::min(مرشحون.size(), static_cast<size_t>(الحد)); i++) {
            نتائج.push_back(مرشحون[i].first);
        }
        
        return نتائج;
    }
    
private:
    std::set<std::string> القاموس_;
    std::map<std::string, size_t> تكرارات_الكلمات_;
    std::map<std::string, std::vector<std::string>> المرادفات_;
    
    /**
     * تحميل قاعدة بيانات افتراضية
     */
    void حمّل_قاعدة_بيانات_افتراضية() {
        // كلمات شائعة
        std::vector<std::pair<std::string, size_t>> كلمات = {
            {"برمجة", 1000}, {"مبرمج", 800}, {"البرمجة", 900},
            {"كتاب", 500}, {"كتب", 400}, {"مكتبة", 300},
            {"علم", 600}, {"عالم", 400}, {"علوم", 350},
            {"حاسوب", 700}, {"حاسب", 600}, {"حوسبة", 500},
            {"تقنية", 800}, {"تقني", 600}, {"تكنولوجيا", 700}
        };
        
        for (const auto& [كلمة, تكرار] : كلمات) {
            سجّل_كلمة(كلمة, تكرار);
        }
        
        // مرادفات
        أضف_مرادف("حاسوب", "كمبيوتر");
        أضف_مرادف("برمجة", "كودنج");
        أضف_مرادف("تقنية", "تكنولوجيا");
    }
    
    /**
     * اقتراحات إملائية
     */
    std::vector<اقتراح_بحث> اقتراحات_إملائية(const std::string& استعلام) const {
        std::vector<اقتراح_بحث> اقتراحات;
        
        for (const auto& كلمة : القاموس_) {
            int المسافة = مسافة_ليفنشتاين(استعلام, كلمة);
            
            if (المسافة > 0 && المسافة <= 2) {
                اقتراح_بحث اقتراح;
                اقتراح.النص = كلمة;
                اقتراح.السبب = "تصحيح إملائي";
                اقتراح.درجة_الملاءمة = 1.0 - (المسافة * 0.3);
                
                auto it = تكرارات_الكلمات_.find(كلمة);
                if (it != تكرارات_الكلمات_.end()) {
                    اقتراح.عدد_النتائج_المتوقعة = it->second;
                    // زيادة الدرجة للكلمات الشائعة
                    اقتراح.درجة_الملاءمة += std::min(0.2, it->second / 5000.0);
                }
                
                اقتراحات.push_back(اقتراح);
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * اقتراحات من نفس الجذر
     */
    std::vector<اقتراح_بحث> اقتراحات_جذرية(const std::string& استعلام) const {
        std::vector<اقتراح_بحث> اقتراحات;
        
        // البحث عن كلمات تحتوي الاستعلام كجزء
        for (const auto& كلمة : القاموس_) {
            if (كلمة != استعلام && 
                (كلمة.find(استعلام) != std::string::npos ||
                 استعلام.find(كلمة) != std::string::npos)) {
                
                اقتراح_بحث اقتراح;
                اقتراح.النص = كلمة;
                اقتراح.السبب = "كلمة ذات صلة";
                اقتراح.درجة_الملاءمة = 0.7;
                اقتراحات.push_back(اقتراح);
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * اقتراحات من المرادفات
     */
    std::vector<اقتراح_بحث> اقتراحات_مرادفات(const std::string& استعلام) const {
        std::vector<اقتراح_بحث> اقتراحات;
        
        auto it = المرادفات_.find(استعلام);
        if (it != المرادفات_.end()) {
            for (const auto& مرادف : it->second) {
                اقتراح_بحث اقتراح;
                اقتراح.النص = مرادف;
                اقتراح.السبب = "مرادف";
                اقتراح.درجة_الملاءمة = 0.85;
                اقتراحات.push_back(اقتراح);
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * اقتراحات توسيع
     */
    std::vector<اقتراح_بحث> اقتراحات_توسيع(const std::string& استعلام) const {
        std::vector<اقتراح_بحث> اقتراحات;
        
        // إضافة "ال" التعريف
        if (استعلام.find("ال") != 0) {
            std::string مع_ال = "ال" + استعلام;
            if (القاموس_.count(مع_ال) > 0) {
                اقتراح_بحث اقتراح;
                اقتراح.النص = مع_ال;
                اقتراح.السبب = "مع أل التعريف";
                اقتراح.درجة_الملاءمة = 0.9;
                اقتراحات.push_back(اقتراح);
            }
        }
        
        // إزالة "ال" التعريف
        if (استعلام.find("ال") == 0 && استعلام.length() > 4) {
            std::string بدون_ال = استعلام.substr(4);  // 4 bytes لـ "ال" في UTF-8
            if (القاموس_.count(بدون_ال) > 0) {
                اقتراح_بحث اقتراح;
                اقتراح.النص = بدون_ال;
                اقتراح.السبب = "بدون أل التعريف";
                اقتراح.درجة_الملاءمة = 0.88;
                اقتراحات.push_back(اقتراح);
            }
        }
        
        return اقتراحات;
    }
    
    /**
     * مسافة ليفنشتاين
     */
    int مسافة_ليفنشتاين(const std::string& أ, const std::string& ب) const {
        size_t م = أ.length();
        size_t ن = ب.length();
        
        std::vector<std::vector<int>> د(م + 1, std::vector<int>(ن + 1));
        
        for (size_t i = 0; i <= م; i++) د[i][0] = i;
        for (size_t j = 0; j <= ن; j++) د[0][j] = j;
        
        for (size_t i = 1; i <= م; i++) {
            for (size_t j = 1; j <= ن; j++) {
                int تكلفة = (أ[i - 1] == ب[j - 1]) ? 0 : 1;
                د[i][j] = std::min({
                    د[i - 1][j] + 1,
                    د[i][j - 1] + 1,
                    د[i - 1][j - 1] + تكلفة
                });
            }
        }
        
        return د[م][ن];
    }
    
    /**
     * إزالة التكرارات
     */
    void أزل_التكرارات(std::vector<اقتراح_بحث>& اقتراحات) const {
        std::set<std::string> مُشاهَد;
        auto it = std::remove_if(اقتراحات.begin(), اقتراحات.end(),
            [&مُشاهَد](const اقتراح_بحث& اقتراح) {
                if (مُشاهَد.count(اقتراح.النص) > 0) {
                    return true;
                }
                مُشاهَد.insert(اقتراح.النص);
                return false;
            });
        اقتراحات.erase(it, اقتراحات.end());
    }
};

