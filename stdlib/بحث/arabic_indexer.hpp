/**
 * موقع كلمة في وثيقة
 */
struct موقع_كلمة {
    std::string معرف_الوثيقة;
    size_t رقم_الفقرة;
    size_t موقع_البداية;
    size_t موقع_النهاية;
    std::string الكلمة_الأصلية;
    std::string الجذر;
};

/**
 * نتيجة بحث
 */
struct نتيجة_بحث {
    std::string معرف_الوثيقة;
    std::string عنوان_الوثيقة;
    std::vector<موقع_كلمة> المواقع;
    double درجة_الملاءمة = 0;
    std::string مقتطف;              // جزء من النص حول النتيجة
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مستخرج الجذور
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * مستخرج الجذور العربية
 */
class مستخرج_جذور {
public:
    /**
     * استخراج الجذر من كلمة عربية
     */
    std::string استخرج(const std::string& كلمة) const {
        std::string نظيفة = أزل_الزوائد(كلمة);
        
        // محاولة استخراج الجذر الثلاثي
        if (نظيفة.length() >= 6) {  // 3 أحرف عربية = 6 bytes في UTF-8
            return استخرج_ثلاثي(نظيفة);
        }
        
        return نظيفة;
    }
    
    /**
     * هل الكلمتان من نفس الجذر؟
     */
    bool نفس_الجذر(const std::string& أ, const std::string& ب) const {
        return استخرج(أ) == استخرج(ب);
    }
    
private:
    // السوابق الشائعة
    std::vector<std::string> السوابق_ = {
        "ال", "و", "ب", "ك", "ل", "ف",
        "است", "ان", "يت", "مت", "مس", "من"
    };
    
    // اللواحق الشائعة
    std::vector<std::string> اللواحق_ = {
        "ة", "ات", "ون", "ين", "ان", "تين",
        "وا", "ها", "هم", "هن", "كم", "نا"
    };
    
    /**
     * إزالة الزوائد
     */
    std::string أزل_الزوائد(const std::string& كلمة) const {
        std::string نتيجة = كلمة;
        
        // إزالة السوابق
        for (const auto& سابقة : السوابق_) {
            if (نتيجة.find(سابقة) == 0 && نتيجة.length() > سابقة.length() + 6) {
                نتيجة = نتيجة.substr(سابقة.length());
                break;
            }
        }
        
        // إزالة اللواحق
        for (const auto& لاحقة : اللواحق_) {
            size_t موقع = نتيجة.length() - لاحقة.length();
            if (نتيجة.length() > لاحقة.length() + 6 && 
                نتيجة.substr(موقع) == لاحقة) {
                نتيجة = نتيجة.substr(0, موقع);
                break;
            }
        }
        
        return نتيجة;
    }
    
    /**
     * استخراج الجذر الثلاثي
     */
    std::string استخرج_ثلاثي(const std::string& كلمة) const {
        // خوارزمية مبسطة - في الإنتاج تُستخدم خوارزميات أكثر تطوراً
        // مثل ISRI Stemmer أو Light Stemmer
        
        // إذا كانت الكلمة 3 أحرف، هي الجذر
        if (كلمة.length() == 6) {  // 3 أحرف UTF-8
            return كلمة;
        }
        
        // محاولة الحصول على 3 أحرف أساسية
        // (هذا تبسيط - الواقع أعقد)
        return كلمة;
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
