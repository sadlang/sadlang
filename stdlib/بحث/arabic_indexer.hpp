/**
 * وثيقة للفهرسة
 */
struct وثيقة {
    std::string المعرف;
    std::string العنوان;
    std::string المحتوى;
    std::map<std::string, std::string> البيانات_الوصفية;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              الفهرس العربي
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🔍 الفهرس العربي
 * 
 * فهرسة النصوص العربية بالجذور
 */
class فهرس_عربي {
public:
    /**
     * إضافة وثيقة للفهرس
     */
    void أضف(const وثيقة& و) {
        الوثائق_[و.المعرف] = و;
        
        // تقسيم المحتوى إلى كلمات
        auto الكلمات = قسّم_إلى_كلمات(و.المحتوى);
        
        size_t الموقع = 0;
        for (const auto& كلمة : الكلمات) {
            // استخراج الجذر
            std::string الجذر = المستخرج_.استخرج(كلمة);
            
            // إنشاء موقع
            موقع_كلمة موقع;
            موقع.معرف_الوثيقة = و.المعرف;
            موقع.موقع_البداية = الموقع;
            موقع.الكلمة_الأصلية = كلمة;
            موقع.الجذر = الجذر;
            
            // إضافة للفهرس
            فهرس_الجذور_[الجذر].push_back(موقع);
            
            الموقع++;
        }
    }
    
    /**
     * البحث في الفهرس
     */
    std::vector<نتيجة_بحث> ابحث(const std::string& استعلام, int الحد_الأقصى = 10) const {
        std::vector<نتيجة_بحث> النتائج;
        
        // استخراج جذور الاستعلام
        auto كلمات_الاستعلام = قسّم_إلى_كلمات(استعلام);
        std::vector<std::string> جذور_الاستعلام;
        
        for (const auto& كلمة : كلمات_الاستعلام) {
            جذور_الاستعلام.push_back(المستخرج_.استخرج(كلمة));
        }
        
        // البحث عن كل جذر
        std::map<std::string, std::vector<موقع_كلمة>> نتائج_الوثائق;
        
        for (const auto& جذر : جذور_الاستعلام) {
            auto it = فهرس_الجذور_.find(جذر);
            if (it != فهرس_الجذور_.end()) {
                for (const auto& موقع : it->second) {
                    نتائج_الوثائق[موقع.معرف_الوثيقة].push_back(موقع);
                }
            }
        }
        
        // ترتيب النتائج حسب الملاءمة
        for (const auto& [معرف, مواقع] : نتائج_الوثائق) {
            نتيجة_بحث نتيجة;
            نتيجة.معرف_الوثيقة = معرف;
            
            auto it = الوثائق_.find(معرف);
            if (it != الوثائق_.end()) {
                نتيجة.عنوان_الوثيقة = it->second.العنوان;
            }
            
            نتيجة.المواقع = مواقع;
            نتيجة.درجة_الملاءمة = مواقع.size();  // بسيط: عدد التطابقات
            
            // إنشاء مقتطف
            if (!مواقع.empty() && it != الوثائق_.end()) {
                نتيجة.مقتطف = أنشئ_مقتطف(it->second.المحتوى, مواقع[0]);
            }
            
            النتائج.push_back(نتيجة);
        }
        
        // ترتيب حسب الدرجة
        std::sort(النتائج.begin(), النتائج.end(),
            [](const نتيجة_بحث& أ, const نتيجة_بحث& ب) {
                return أ.درجة_الملاءمة > ب.درجة_الملاءمة;
            });
        
        // تحديد العدد
        if (النتائج.size() > static_cast<size_t>(الحد_الأقصى)) {
            النتائج.resize(الحد_الأقصى);
        }
        
        return النتائج;
    }
    
    /**
     * عدد الوثائق
     */
    size_t عدد_الوثائق() const {
        return الوثائق_.size();
    }
    
    /**
     * عدد الجذور المفهرسة
     */
    size_t عدد_الجذور() const {
        return فهرس_الجذور_.size();
    }
    
private:
    مستخرج_جذور المستخرج_;
    std::map<std::string, وثيقة> الوثائق_;
    std::map<std::string, std::vector<موقع_كلمة>> فهرس_الجذور_;
    
    /**
     * تقسيم النص إلى كلمات
     */
    std::vector<std::string> قسّم_إلى_كلمات(const std::string& نص) const {
        std::vector<std::string> كلمات;
        std::string كلمة_حالية;
        
        for (size_t i = 0; i < نص.length(); ) {
            unsigned char c = نص[i];
            
            // فراغ أو علامة ترقيم
            if (c == ' ' || c == '\n' || c == '\t' || 
                c == '.' || c == ',' || c == '!' || c == '?') {
                if (!كلمة_حالية.empty()) {
                    كلمات.push_back(كلمة_حالية);
                    كلمة_حالية.clear();
                }
                i++;
            }
            // UTF-8 حرف عربي
            else if ((c & 0xE0) == 0xC0) {
                كلمة_حالية += نص[i];
                كلمة_حالية += نص[i + 1];
                i += 2;
            }
            else if ((c & 0xF0) == 0xE0) {
                كلمة_حالية += نص[i];
                كلمة_حالية += نص[i + 1];
                كلمة_حالية += نص[i + 2];
                i += 3;
            }
            else {
                كلمة_حالية += نص[i];
                i++;
            }
        }
        
        if (!كلمة_حالية.empty()) {
            كلمات.push_back(كلمة_حالية);
        }
        
        return كلمات;
    }
    
    /**
     * إنشاء مقتطف حول الكلمة
     */
    std::string أنشئ_مقتطف(const std::string& محتوى, const موقع_كلمة& موقع, 
                          size_t طول = 100) const {
        // مقتطف بسيط - في الإنتاج يكون أكثر تطوراً
        size_t البداية = 0;
        size_t النهاية = std::min(محتوى.length(), طول);
        
        return محتوى.substr(البداية, النهاية) + "...";
    }
};

