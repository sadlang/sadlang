/**
 * اقتراح تصحيح
 */
struct اقتراح_تصحيح {
    std::string الكلمة_الصحيحة;
    double درجة_الثقة;        // 0.0 - 1.0
    std::string نوع_الخطأ;    // همزة، تاء مربوطة، طباعة...
};

/**
 * نتيجة فحص الإملاء
 */
struct نتيجة_فحص {
    std::string الكلمة_الأصلية;
    bool صحيحة;
    std::vector<اقتراح_تصحيح> الاقتراحات;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مصحح الإملاء
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * ✏️ مصحح الإملاء العربي
 */
class مصحح_إملاء {
public:
    /**
     * إنشاء المصحح
     */
    مصحح_إملاء() {
        // تحميل قاموس أساسي
        حمّل_قاموس_افتراضي();
    }
    
    /**
     * إضافة كلمة للقاموس
     */
    void أضف_كلمة(const std::string& كلمة) {
        القاموس_.insert(كلمة);
    }
    
    /**
     * إضافة كلمات متعددة
     */
    void أضف_كلمات(const std::vector<std::string>& كلمات) {
        for (const auto& كلمة : كلمات) {
            القاموس_.insert(كلمة);
        }
    }
    
    /**
     * فحص كلمة واحدة
     */
    نتيجة_فحص افحص_كلمة(const std::string& كلمة) const {
        نتيجة_فحص نتيجة;
        نتيجة.الكلمة_الأصلية = كلمة;
        
        // التحقق من وجود الكلمة في القاموس
        if (القاموس_.count(كلمة) > 0) {
            نتيجة.صحيحة = true;
            return نتيجة;
        }
        
        نتيجة.صحيحة = false;
        
        // البحث عن اقتراحات
        نتيجة.الاقتراحات = اقترح_تصحيحات(كلمة);
        
        return نتيجة;
    }
    
    /**
     * فحص نص كامل
     */
    std::vector<نتيجة_فحص> افحص_نص(const std::string& نص) const {
        std::vector<نتيجة_فحص> النتائج;
        
        auto الكلمات = قسّم_إلى_كلمات(نص);
        
        for (const auto& كلمة : الكلمات) {
            النتائج.push_back(افحص_كلمة(كلمة));
        }
        
        return النتائج;
    }
    
    /**
     * تصحيح نص تلقائياً
     */
    std::string صحح_نص(const std::string& نص) const {
        std::string نتيجة;
        
        auto الكلمات = قسّم_إلى_كلمات(نص);
        
        for (size_t i = 0; i < الكلمات.size(); i++) {
            auto فحص = افحص_كلمة(الكلمات[i]);
            
            if (فحص.صحيحة) {
                نتيجة += الكلمات[i];
            }
            else if (!فحص.الاقتراحات.empty() && 
                     فحص.الاقتراحات[0].درجة_الثقة > 0.8) {
                // تصحيح تلقائي إذا كانت الثقة عالية
                نتيجة += فحص.الاقتراحات[0].الكلمة_الصحيحة;
            }
            else {
                نتيجة += الكلمات[i];  // اترك الكلمة كما هي
            }
            
            if (i < الكلمات.size() - 1) {
                نتيجة += " ";
            }
        }
        
        return نتيجة;
    }
    
    /**
     * حجم القاموس
     */
    size_t حجم_القاموس() const {
        return القاموس_.size();
    }
    
private:
    std::set<std::string> القاموس_;
    
    // قواعد الهمزات
    std::map<std::string, std::string> قواعد_الهمزات_ = {
        {"انا", "أنا"},
        {"انت", "أنت"},
        {"انتم", "أنتم"},
        {"اكل", "أكل"},
        {"امر", "أمر"},
        {"اخذ", "أخذ"},
        {"اعطى", "أعطى"},
        {"اذا", "إذا"},
        {"الى", "إلى"},
        {"ان", "إن"},
        {"انما", "إنما"}
    };
    
    /**
     * تحميل قاموس افتراضي
     */
    void حمّل_قاموس_افتراضي() {
        // كلمات شائعة في العربية
        std::vector<std::string> كلمات_أساسية = {
            "أنا", "أنت", "هو", "هي", "نحن", "هم",
            "في", "من", "إلى", "على", "عن", "مع",
            "هذا", "هذه", "ذلك", "تلك", "هؤلاء",
            "كان", "كانت", "يكون", "تكون",
            "الذي", "التي", "الذين", "اللذان",
            "قال", "قالت", "يقول", "تقول",
            "كتاب", "كتب", "كاتب", "مكتبة",
            "علم", "عالم", "معلم", "تعليم",
            "عمل", "عامل", "عملية", "معمل",
            "كلمة", "كلام", "متكلم", "تكلم"
        };
        
        أضف_كلمات(كلمات_أساسية);
    }
    
    /**
     * اقتراح تصحيحات
     */
    std::vector<اقتراح_تصحيح> اقترح_تصحيحات(const std::string& كلمة) const {
        std::vector<اقتراح_تصحيح> اقتراحات;
        
        // 1. التحقق من قواعد الهمزات
        auto it = قواعد_الهمزات_.find(كلمة);
        if (it != قواعد_الهمزات_.end()) {
            اقتراح_تصحيح اقتراح;
            اقتراح.الكلمة_الصحيحة = it->second;
            اقتراح.درجة_الثقة = 0.95;
            اقتراح.نوع_الخطأ = "همزة";
            اقتراحات.push_back(اقتراح);
        }
        
        // 2. البحث عن كلمات قريبة
        for (const auto& كلمة_قاموس : القاموس_) {
            int المسافة = مسافة_ليفنشتاين(كلمة, كلمة_قاموس);
            
            if (المسافة > 0 && المسافة <= 2) {
                اقتراح_تصحيح اقتراح;
                اقتراح.الكلمة_الصحيحة = كلمة_قاموس;
                اقتراح.درجة_الثقة = 1.0 - (المسافة * 0.3);
                اقتراح.نوع_الخطأ = "طباعة";
                اقتراحات.push_back(اقتراح);
            }
        }
        
        // ترتيب حسب درجة الثقة
        std::sort(اقتراحات.begin(), اقتراحات.end(),
            [](const اقتراح_تصحيح& أ, const اقتراح_تصحيح& ب) {
                return أ.درجة_الثقة > ب.درجة_الثقة;
            });
        
        // الاحتفاظ بأفضل 5 اقتراحات
        if (اقتراحات.size() > 5) {
            اقتراحات.resize(5);
        }
        
        return اقتراحات;
    }
    
    /**
     * مسافة ليفنشتاين (عدد التعديلات لتحويل كلمة لأخرى)
     */
    int مسافة_ليفنشتاين(const std::string& أ, const std::string& ب) const {
        size_t م = أ.length();
        size_t ن = ب.length();
        
        std::vector<std::vector<int>> د(م + 1, std::vector<int>(ن + 1));
        
        for (size_t i = 0; i <= م; i++) د[i][0] = i;
        for (size_t j = 0; j <= ن; j++) د[0][j] = j;
        
        for (size_t i = 1; i <= م; i++) {
            for (size_t j = 1; j <= ن; j++) {
                int تكلفة = (أ[i - 1] == ب[j - 1]) ? 0 : 1;
                د[i][j] = std::min({
                    د[i - 1][j] + 1,        // حذف
                    د[i][j - 1] + 1,        // إضافة
                    د[i - 1][j - 1] + تكلفة // استبدال
                });
            }
        }
        
        return د[م][ن];
    }
    
    /**
     * تقسيم النص إلى كلمات
     */
    std::vector<std::string> قسّم_إلى_كلمات(const std::string& نص) const {
        std::vector<std::string> كلمات;
        std::string كلمة_حالية;
        
        for (char c : نص) {
            if (c == ' ' || c == '\n' || c == '\t' || 
                c == '.' || c == ',' || c == '!' || c == '?') {
                if (!كلمة_حالية.empty()) {
                    كلمات.push_back(كلمة_حالية);
                    كلمة_حالية.clear();
                }
            }
            else {
                كلمة_حالية += c;
            }
        }
        
        if (!كلمة_حالية.empty()) {
            كلمات.push_back(كلمة_حالية);
        }
        
        return كلمات;
    }
};

