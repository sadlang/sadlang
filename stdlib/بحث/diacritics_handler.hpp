/**
 * رموز التشكيل العربي
 */
namespace تشكيل {
    // الحركات الأساسية
    constexpr char32_t الفتحة = 0x064E;      // ◌َ
    constexpr char32_t الضمة = 0x064F;       // ◌ُ
    constexpr char32_t الكسرة = 0x0650;      // ◌ِ
    constexpr char32_t السكون = 0x0652;      // ◌ْ
    constexpr char32_t الشدة = 0x0651;       // ◌ّ
    
    // التنوين
    constexpr char32_t تنوين_فتح = 0x064B;   // ◌ً
    constexpr char32_t تنوين_ضم = 0x064C;    // ◌ٌ
    constexpr char32_t تنوين_كسر = 0x064D;   // ◌ٍ
    
    // علامات أخرى
    constexpr char32_t المد = 0x0653;        // ◌ٓ
    constexpr char32_t الهمزة_فوق = 0x0654;   // ◌ٔ
    constexpr char32_t الهمزة_تحت = 0x0655;   // ◌ٕ
    
    // نطاق التشكيل
    constexpr char32_t بداية_النطاق = 0x064B;
    constexpr char32_t نهاية_النطاق = 0x065F;
}

// ═══════════════════════════════════════════════════════════════════════════════
//                              معالج التشكيل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🔤 معالج التشكيل
 * 
 * إزالة التشكيل والمقارنة بتجاهله
 */
class معالج_التشكيل {
public:
    /**
     * إزالة التشكيل من نص
     */
    std::string أزل_التشكيل(const std::string& نص) const {
        std::string نتيجة;
        نتيجة.reserve(نص.length());
        
        size_t i = 0;
        while (i < نص.length()) {
            unsigned char c = نص[i];
            
            // UTF-8 متعدد البايت
            if ((c & 0x80) == 0) {
                // ASCII byte واحد
                نتيجة += c;
                i++;
            }
            else if ((c & 0xE0) == 0xC0) {
                // 2 bytes
                if (i + 1 < نص.length()) {
                    char32_t رمز = ((c & 0x1F) << 6) | (نص[i + 1] & 0x3F);
                    if (!هو_تشكيل(رمز)) {
                        نتيجة += نص[i];
                        نتيجة += نص[i + 1];
                    }
                }
                i += 2;
            }
            else if ((c & 0xF0) == 0xE0) {
                // 3 bytes
                if (i + 2 < نص.length()) {
                    char32_t رمز = ((c & 0x0F) << 12) | 
                                  ((نص[i + 1] & 0x3F) << 6) | 
                                  (نص[i + 2] & 0x3F);
                    if (!هو_تشكيل(رمز)) {
                        نتيجة += نص[i];
                        نتيجة += نص[i + 1];
                        نتيجة += نص[i + 2];
                    }
                }
                i += 3;
            }
            else if ((c & 0xF8) == 0xF0) {
                // 4 bytes
                if (i + 3 < نص.length()) {
                    نتيجة += نص[i];
                    نتيجة += نص[i + 1];
                    نتيجة += نص[i + 2];
                    نتيجة += نص[i + 3];
                }
                i += 4;
            }
            else {
                i++;
            }
        }
        
        return نتيجة;
    }
    
    /**
     * هل الرمز تشكيل؟
     */
    bool هو_تشكيل(char32_t رمز) const {
        return رمز >= تشكيل::بداية_النطاق && رمز <= تشكيل::نهاية_النطاق;
    }
    
    /**
     * مقارنة بتجاهل التشكيل
     */
    bool تساوي_بدون_تشكيل(const std::string& أ, const std::string& ب) const {
        return أزل_التشكيل(أ) == أزل_التشكيل(ب);
    }
    
    /**
     * البحث بتجاهل التشكيل
     */
    size_t ابحث_بدون_تشكيل(const std::string& نص, const std::string& استعلام) const {
        std::string نص_نظيف = أزل_التشكيل(نص);
        std::string استعلام_نظيف = أزل_التشكيل(استعلام);
        
        return نص_نظيف.find(استعلام_نظيف);
    }
    
    /**
     * استخراج التشكيل من كلمة
     */
    std::vector<char32_t> استخرج_التشكيل(const std::string& كلمة) const {
        std::vector<char32_t> تشكيل;
        
        size_t i = 0;
        while (i < كلمة.length()) {
            unsigned char c = كلمة[i];
            
            if ((c & 0xE0) == 0xC0 && i + 1 < كلمة.length()) {
                char32_t رمز = ((c & 0x1F) << 6) | (كلمة[i + 1] & 0x3F);
                if (هو_تشكيل(رمز)) {
                    تشكيل.push_back(رمز);
                }
                i += 2;
            }
            else if ((c & 0x80) == 0) {
                i++;
            }
            else if ((c & 0xF0) == 0xE0) {
                i += 3;
            }
            else if ((c & 0xF8) == 0xF0) {
                i += 4;
            }
            else {
                i++;
            }
        }
        
        return تشكيل;
    }
    
    /**
     * إضافة تشكيل لكلمة (تشكيل تلقائي بسيط)
     */
    std::string شكّل_كلمة(const std::string& كلمة) const {
        // تشكيل تلقائي يحتاج قاموس أو AI
        // هذا مثال مبسط جداً
        return كلمة;  // لا تغيير
    }
    
    /**
     * اسم الحركة
     */
    std::string اسم_الحركة(char32_t رمز) const {
        switch (رمز) {
            case تشكيل::الفتحة: return "فَتحة";
            case تشكيل::الضمة: return "ضَمة";
            case تشكيل::الكسرة: return "كَسرة";
            case تشكيل::السكون: return "سُكون";
            case تشكيل::الشدة: return "شَدة";
            case تشكيل::تنوين_فتح: return "تنوين فتح";
            case تشكيل::تنوين_ضم: return "تنوين ضم";
            case تشكيل::تنوين_كسر: return "تنوين كسر";
            default: return "غير معروف";
        }
    }
};

