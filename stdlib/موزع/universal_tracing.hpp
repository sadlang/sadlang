/**
 * نقطة في مسار التتبع
 */
struct نقطة_مسار {
    std::string الخدمة;
    std::string العملية;
    std::chrono::system_clock::time_point البداية;
    std::chrono::system_clock::time_point النهاية;
    std::map<std::string, std::string> البيانات;
    std::string الحالة;          // نجاح، فشل، خطأ
    std::string رسالة_الخطأ;
    
    /**
     * المدة بالمللي ثانية
     */
    double المدة_ms() const {
        auto فرق = النهاية - البداية;
        return std::chrono::duration<double, std::milli>(فرق).count();
    }
};

/**
 * البصمة الكونية
 */
struct بصمة_كونية {
    std::string المعرف;
    std::string معرف_الأب;       // للتتبع المتداخل
    std::chrono::system_clock::time_point وقت_الإنشاء;
    std::vector<نقطة_مسار> المسار;
    std::map<std::string, std::string> السياق;
    std::string مصدر_الطلب;      // IP، المستخدم، الخدمة
    
    /**
     * الحصول على المدة الإجمالية
     */
    double المدة_الإجمالية_ms() const {
        double المجموع = 0;
        for (const auto& نقطة : المسار) {
            المجموع += نقطة.المدة_ms();
        }
        return المجموع;
    }
    
    /**
     * أبطأ نقطة
     */
    const نقطة_مسار* أبطأ_نقطة() const {
        if (المسار.empty()) return nullptr;
        
        const نقطة_مسار* أبطأ = &المسار[0];
        for (const auto& نقطة : المسار) {
            if (نقطة.المدة_ms() > أبطأ->المدة_ms()) {
                أبطأ = &نقطة;
            }
        }
        return أبطأ;
    }
    
    /**
     * هل فشل الطلب؟
     */
    bool فاشل() const {
        for (const auto& نقطة : المسار) {
            if (نقطة.الحالة == "فشل" || نقطة.الحالة == "خطأ") {
                return true;
            }
        }
        return false;
    }
};

