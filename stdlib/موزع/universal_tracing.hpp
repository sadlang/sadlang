/**
 * 🌐 المُتتبع الكوني
 */
class متتبع_كوني {
public:
    /**
     * الحصول على المثيل
     */
    static متتبع_كوني& المثيل() {
        static متتبع_كوني مثيل;
        return مثيل;
    }
    
    /**
     * إنشاء بصمة جديدة
     */
    بصمة_كونية* أنشئ_بصمة(const std::string& مصدر = "") {
        بصمة_كونية بصمة;
        بصمة.المعرف = ولد_معرف();
        بصمة.وقت_الإنشاء = std::chrono::system_clock::now();
        بصمة.مصدر_الطلب = مصدر;
        
        البصمات_[بصمة.المعرف] = بصمة;
        return &البصمات_[بصمة.المعرف];
    }
    
    /**
     * الحصول على البصمة الحالية
     */
    بصمة_كونية* البصمة_الحالية() {
        if (معرف_البصمة_الحالية_.empty()) {
            return nullptr;
        }
        auto it = البصمات_.find(معرف_البصمة_الحالية_);
        return it != البصمات_.end() ? &it->second : nullptr;
    }
    
    /**
     * تعيين البصمة الحالية
     */
    void عين_البصمة_الحالية(const std::string& معرف) {
        معرف_البصمة_الحالية_ = معرف;
    }
    
    /**
     * بدء نقطة جديدة
     */
    void ابدأ_نقطة(const std::string& خدمة, const std::string& عملية) {
        auto* بصمة = البصمة_الحالية();
        if (!بصمة) return;
        
        نقطة_مسار نقطة;
        نقطة.الخدمة = خدمة;
        نقطة.العملية = عملية;
        نقطة.البداية = std::chrono::system_clock::now();
        نقطة.الحالة = "جاري";
        
        بصمة->المسار.push_back(نقطة);
    }
    
    /**
     * إنهاء النقطة الحالية
     */
    void أنهِ_نقطة(const std::string& حالة = "نجاح", 
                    const std::string& رسالة = "") {
        auto* بصمة = البصمة_الحالية();
        if (!بصمة || بصمة->المسار.empty()) return;
        
        auto& نقطة = بصمة->المسار.back();
        نقطة.النهاية = std::chrono::system_clock::now();
        نقطة.الحالة = حالة;
        نقطة.رسالة_الخطأ = رسالة;
    }
    
    /**
     * إضافة بيانات للنقطة
     */
    void أضف_بيانات(const std::string& مفتاح, const std::string& قيمة) {
        auto* بصمة = البصمة_الحالية();
        if (!بصمة || بصمة->المسار.empty()) return;
        
        بصمة->المسار.back().البيانات[مفتاح] = قيمة;
    }
    
    /**
     * الحصول على بصمة بالمعرف
     */
    const بصمة_كونية* اجلب(const std::string& معرف) const {
        auto it = البصمات_.find(معرف);
        return it != البصمات_.end() ? &it->second : nullptr;
    }
    
    /**
     * تصدير للتحليل
     */
    std::string صدر_json(const بصمة_كونية& بصمة) const {
        std::ostringstream json;
        json << "{\n";
        json << "  \"معرف\": \"" << بصمة.المعرف << "\",\n";
        json << "  \"مدة_إجمالية_ms\": " << بصمة.المدة_الإجمالية_ms() << ",\n";
        json << "  \"فاشل\": " << (بصمة.فاشل() ? "true" : "false") << ",\n";
        json << "  \"نقاط\": [\n";
        
        for (size_t i = 0; i < بصمة.المسار.size(); i++) {
            const auto& نقطة = بصمة.المسار[i];
            json << "    {\n";
            json << "      \"خدمة\": \"" << نقطة.الخدمة << "\",\n";
            json << "      \"عملية\": \"" << نقطة.العملية << "\",\n";
            json << "      \"مدة_ms\": " << نقطة.المدة_ms() << ",\n";
            json << "      \"حالة\": \"" << نقطة.الحالة << "\"\n";
            json << "    }";
            if (i < بصمة.المسار.size() - 1) json << ",";
            json << "\n";
        }
        
        json << "  ]\n";
        json << "}";
        
        return json.str();
    }
    
private:
    متتبع_كوني() = default;
    
    std::map<std::string, بصمة_كونية> البصمات_;
    std::string معرف_البصمة_الحالية_;
    
    /**
     * توليد معرف فريد
     */
    std::string ولد_معرف() {
        auto الآن = std::chrono::system_clock::now();
        auto زمن = std::chrono::system_clock::to_time_t(الآن);
        
        std::random_device rd;
        std::mt19937 gen(rd());
        std::uniform_int_distribution<> dis(0, 15);
        
        std::ostringstream ss;
        ss << "trace-" << std::put_time(std::localtime(&زمن), "%Y%m%d-%H%M%S") << "-";
        
        for (int i = 0; i < 8; i++) {
            ss << std::hex << dis(gen);
        }
        
        return ss.str();
    }
};

