/**
 * 📍 نطاق التتبع (RAII)
 */
class نطاق_تتبع {
public:
    نطاق_تتبع(const std::string& خدمة, const std::string& عملية) {
        متتبع_كوني::المثيل().ابدأ_نقطة(خدمة, عملية);
    }
    
    ~نطاق_تتبع() {
        متتبع_كوني::المثيل().أنهِ_نقطة("نجاح");
    }
    
    void فشل(const std::string& رسالة = "") {
        متتبع_كوني::المثيل().أنهِ_نقطة("فشل", رسالة);
    }
};

