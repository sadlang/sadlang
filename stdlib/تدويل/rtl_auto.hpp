/**
 * اتجاه النص
 */
enum class اتجاه_نص {
    من_اليمين,      // RTL - Right to Left
    من_اليسار,      // LTR - Left to Right
    تلقائي,         // Auto detect
    ثنائي_الاتجاه   // Bidirectional
};

/**
 * نتيجة تحليل الاتجاه
 */
struct تحليل_اتجاه {
    اتجاه_نص الاتجاه_الرئيسي;
    float نسبة_RTL;
    float نسبة_LTR;
    bool ثنائي;
    std::string الاتجاه_كنص;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              كاشف الاتجاه
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 🔄 كاشف الاتجاه التلقائي
 */
class كاشف_اتجاه {
public:
    /**
     * كشف اتجاه نص
     */
    تحليل_اتجاه اكشف(const std::string& نص) const {
        تحليل_اتجاه نتيجة;
        
        size_t عدد_rtl = 0;
        size_t عدد_ltr = 0;
        
        // تحليل الأحرف
        for (size_t i = 0; i < نص.length(); ) {
            unsigned char ب = static_cast<unsigned char>(نص[i]);
            
            // UTF-8 متعدد البايت
            if (ب >= 0xD8 && ب <= 0xDB) {
                // نطاق العربية/العبرية/الفارسية
                عدد_rtl++;
                i += 2;
            } else if (ب >= 0xE0 && ب < 0xF0) {
                // 3 بايت - قد يكون عربي أو آخر
                if (i + 2 < نص.length()) {
                    unsigned char ب2 = static_cast<unsigned char>(نص[i + 1]);
                    if (ب == 0xD9 || ب == 0xDA || ب == 0xDB ||
                        (ب == 0xD8 && ب2 >= 0xA0)) {
                        عدد_rtl++;
                    } else {
                        عدد_ltr++;
                    }
                }
                i += 3;
            } else if (ب >= 0x41 && ب <= 0x7A) {
                // أحرف إنجليزية
                عدد_ltr++;
                i++;
            } else if (ب >= 0xD9 || ب >= 0xDA) {
                // عربي
                عدد_rtl++;
                i += 2;
            } else {
                i++;
            }
        }
        
        size_t المجموع = عدد_rtl + عدد_ltr;
        if (المجموع == 0) {
            نتيجة.الاتجاه_الرئيسي = اتجاه_نص::من_اليسار;
            نتيجة.نسبة_RTL = 0;
            نتيجة.نسبة_LTR = 0;
            نتيجة.ثنائي = false;
            نتيجة.الاتجاه_كنص = "ltr";
            return نتيجة;
        }
        
        نتيجة.نسبة_RTL = static_cast<float>(عدد_rtl) / المجموع;
        نتيجة.نسبة_LTR = static_cast<float>(عدد_ltr) / المجموع;
        
        // تحديد الاتجاه الرئيسي
        if (نتيجة.نسبة_RTL > 0.8) {
            نتيجة.الاتجاه_الرئيسي = اتجاه_نص::من_اليمين;
            نتيجة.الاتجاه_كنص = "rtl";
        } else if (نتيجة.نسبة_LTR > 0.8) {
            نتيجة.الاتجاه_الرئيسي = اتجاه_نص::من_اليسار;
            نتيجة.الاتجاه_كنص = "ltr";
        } else {
            نتيجة.الاتجاه_الرئيسي = اتجاه_نص::ثنائي_الاتجاه;
            نتيجة.الاتجاه_كنص = نتيجة.نسبة_RTL > نتيجة.نسبة_LTR ? "rtl" : "ltr";
        }
        
        نتيجة.ثنائي = (عدد_rtl > 0 && عدد_ltr > 0);
        
        return نتيجة;
    }
    
    /**
     * هل النص عربي؟
     */
    bool هل_عربي(const std::string& نص) const {
        auto تحليل = اكشف(نص);
        return تحليل.نسبة_RTL > 0.5;
    }
    
    /**
     * هل اللغة RTL؟
     */
    bool هل_لغة_rtl(const std::string& كود_لغة) const {
        static const std::set<std::string> لغات_rtl = {
            "ar", "he", "fa", "ur", "ps", "sd", "yi"
        };
        return لغات_rtl.count(كود_لغة) > 0;
    }
};

