/**
 * كشف الاتجاه تلقائياً
 */
inline اتجاه_نص اتجاه(const std::string& نص) {
    كاشف_اتجاه كاشف;
    return كاشف.اكشف(نص).الاتجاه_الرئيسي;
}

/**
 * هل النص RTL؟
 */
inline bool هل_rtl(const std::string& نص) {
    return اتجاه(نص) == اتجاه_نص::من_اليمين;
}

/**
 * تغليف HTML مع الاتجاه الصحيح
 */
inline std::string غلف_html(const std::string& نص) {
    منسق_rtl منسق;
    return منسق.نسق_html(نص);
}

