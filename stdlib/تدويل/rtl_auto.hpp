/**
 * 📐 مُنسق RTL للواجهات
 */
class منسق_rtl {
public:
    /**
     * إنشاء المنسق
     */
    منسق_rtl() : الاتجاه_الافتراضي_(اتجاه_نص::تلقائي) {}
    
    /**
     * تعيين الاتجاه الافتراضي
     */
    void عيّن_الاتجاه(اتجاه_نص اتجاه) {
        الاتجاه_الافتراضي_ = اتجاه;
    }
    
    /**
     * تنسيق HTML مع الاتجاه
     */
    std::string نسق_html(const std::string& نص, bool اكتشف_تلقائي = true) const {
        std::string اتجاه = "ltr";
        
        if (اكتشف_تلقائي) {
            كاشف_اتجاه كاشف;
            auto تحليل = كاشف.اكشف(نص);
            اتجاه = تحليل.الاتجاه_كنص;
        } else if (الاتجاه_الافتراضي_ == اتجاه_نص::من_اليمين) {
            اتجاه = "rtl";
        }
        
        return "<div dir=\"" + اتجاه + "\">" + نص + "</div>";
    }
    
    /**
     * تنسيق CSS للاتجاه
     */
    std::string ولد_css(اتجاه_نص اتجاه) const {
        std::string css;
        
        if (اتجاه == اتجاه_نص::من_اليمين) {
            css += "direction: rtl;\n";
            css += "text-align: right;\n";
            css += "unicode-bidi: bidi-override;\n";
        } else {
            css += "direction: ltr;\n";
            css += "text-align: left;\n";
        }
        
        return css;
    }
    
    /**
     * عكس محاذاة واجهة المستخدم
     */
    std::map<std::string, std::string> اعكس_المحاذاة(
        const std::map<std::string, std::string>& أنماط) const {
        
        std::map<std::string, std::string> نتيجة = أنماط;
        
        // عكس left/right
        auto عكس_قيمة = [](const std::string& قيمة) {
            if (قيمة == "left") return std::string("right");
            if (قيمة == "right") return std::string("left");
            return قيمة;
        };
        
        // الخصائص التي تحتاج عكس
        std::vector<std::string> خصائص_للعكس = {
            "text-align", "float", "clear"
        };
        
        for (const auto& خاصية : خصائص_للعكس) {
            auto it = نتيجة.find(خاصية);
            if (it != نتيجة.end()) {
                it->second = عكس_قيمة(it->second);
            }
        }
        
        // عكس margin/padding
        auto عكس_أربعة = [](const std::string& قيمة) {
            // margin: top right bottom left → top left bottom right
            std::vector<std::string> أجزاء;
            std::string جزء;
            for (char c : قيمة) {
                if (c == ' ') {
                    if (!جزء.empty()) أجزاء.push_back(جزء);
                    جزء.clear();
                } else {
                    جزء += c;
                }
            }
            if (!جزء.empty()) أجزاء.push_back(جزء);
            
            if (أجزاء.size() == 4) {
                return أجزاء[0] + " " + أجزاء[3] + " " + أجزاء[2] + " " + أجزاء[1];
            }
            return قيمة;
        };
        
        for (const auto& خاصية : {"margin", "padding"}) {
            auto it = نتيجة.find(خاصية);
            if (it != نتيجة.end()) {
                it->second = عكس_أربعة(it->second);
            }
        }
        
        // تحويل margin-left → margin-right والعكس
        auto it_left = نتيجة.find("margin-left");
        auto it_right = نتيجة.find("margin-right");
        if (it_left != نتيجة.end() && it_right == نتيجة.end()) {
            نتيجة["margin-right"] = it_left->second;
            نتيجة.erase(it_left);
        } else if (it_right != نتيجة.end() && it_left == نتيجة.end()) {
            نتيجة["margin-left"] = it_right->second;
            نتيجة.erase(it_right);
        } else if (it_left != نتيجة.end() && it_right != نتيجة.end()) {
            std::swap(it_left->second, it_right->second);
        }
        
        return نتيجة;
    }
    
    /**
     * إضافة علامات Unicode للاتجاه
     */
    std::string أضف_علامات_unicode(const std::string& نص, اتجاه_نص اتجاه) const {
        // RLM = Right-to-Left Mark (U+200F)
        // LRM = Left-to-Right Mark (U+200E)
        // RLE = Right-to-Left Embedding (U+202B)
        // LRE = Left-to-Right Embedding (U+202A)
        // PDF = Pop Directional Formatting (U+202C)
        
        std::string نتيجة;
        
        if (اتجاه == اتجاه_نص::من_اليمين) {
            نتيجة = "\u202B" + نص + "\u202C";  // RLE...PDF
        } else if (اتجاه == اتجاه_نص::من_اليسار) {
            نتيجة = "\u202A" + نص + "\u202C";  // LRE...PDF
        } else {
            نتيجة = نص;
        }
        
        return نتيجة;
    }
    
private:
    اتجاه_نص الاتجاه_الافتراضي_;
};

