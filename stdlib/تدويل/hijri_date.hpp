/**
 * 🔄 محوّل التواريخ
 * 
 * تحويل بين الهجري والميلادي
 */
class محوّل_تاريخ {
public:
    /**
     * تحويل ميلادي إلى هجري
     * 
     * خوارزمية تقريبية
     */
    static تاريخ_هجري إلى_هجري(const تاريخ_ميلادي& م) {
        // حساب Julian Day Number
        int jd = جوليان_من_ميلادي(م.السنة, م.الشهر, م.اليوم);
        
        // تحويل إلى هجري
        return هجري_من_جوليان(jd);
    }
    
    /**
     * تحويل هجري إلى ميلادي
     */
    static تاريخ_ميلادي إلى_ميلادي(const تاريخ_هجري& ه) {
        // حساب Julian Day Number
        int jd = جوليان_من_هجري(ه.السنة, ه.الشهر, ه.اليوم);
        
        // تحويل إلى ميلادي
        return ميلادي_من_جوليان(jd);
    }
    
    /**
     * الحصول على التاريخ الهجري اليوم
     */
    static تاريخ_هجري اليوم_هجري() {
        time_t الآن = time(nullptr);
        struct tm* زمن = localtime(&الآن);
        
        تاريخ_ميلادي م;
        م.السنة = زمن->tm_year + 1900;
        م.الشهر = زمن->tm_mon + 1;
        م.اليوم = زمن->tm_mday;
        
        return إلى_هجري(م);
    }
    
    /**
     * هل السنة الهجرية كبيسة؟
     */
    static bool سنة_هجرية_كبيسة(int سنة) {
        // دورة 30 سنة، السنوات: 2, 5, 7, 10, 13, 16, 18, 21, 24, 26, 29
        int موقع = سنة % 30;
        return موقع == 2 || موقع == 5 || موقع == 7 || موقع == 10 ||
               موقع == 13 || موقع == 16 || موقع == 18 || موقع == 21 ||
               موقع == 24 || موقع == 26 || موقع == 29;
    }
    
    /**
     * عدد أيام الشهر الهجري
     */
    static int أيام_الشهر(int شهر, int سنة) {
        // الأشهر الفردية: 30 يوم، الزوجية: 29 يوم
        // ذو الحجة في السنة الكبيسة: 30 يوم
        if (شهر % 2 == 1) {
            return 30;
        } else if (شهر == 12 && سنة_هجرية_كبيسة(سنة)) {
            return 30;
        }
        return 29;
    }
    
private:
    /**
     * حساب Julian Day من تاريخ ميلادي
     */
    static int جوليان_من_ميلادي(int س, int ش, int ي) {
        if (ش <= 2) {
            س -= 1;
            ش += 12;
        }
        
        int أ = س / 100;
        int ب = 2 - أ + أ / 4;
        
        return static_cast<int>(365.25 * (س + 4716)) +
               static_cast<int>(30.6001 * (ش + 1)) + ي + ب - 1524;
    }
    
    /**
     * حساب Julian Day من تاريخ هجري
     */
    static int جوليان_من_هجري(int س, int ش, int ي) {
        return static_cast<int>((11 * س + 3) / 30) +
               354 * س + 30 * ش -
               static_cast<int>((ش - 1) / 2) + ي + 1948440 - 385;
    }
    
    /**
     * تحويل Julian Day إلى هجري
     */
    static تاريخ_هجري هجري_من_جوليان(int jd) {
        int l = jd - 1948440 + 10632;
        int n = static_cast<int>((l - 1) / 10631);
        l = l - 10631 * n + 354;
        
        int j = static_cast<int>((10985 - l) / 5316) *
                static_cast<int>((50 * l) / 17719) +
                static_cast<int>(l / 5670) *
                static_cast<int>((43 * l) / 15238);
        
        l = l - static_cast<int>((30 - j) / 15) *
                static_cast<int>((17719 * j) / 50) -
                static_cast<int>(j / 16) *
                static_cast<int>((15238 * j) / 43) + 29;
        
        تاريخ_هجري ه;
        ه.الشهر = static_cast<int>((24 * l) / 709);
        ه.اليوم = l - static_cast<int>((709 * ه.الشهر) / 24);
        ه.السنة = 30 * n + j - 30;
        
        return ه;
    }
    
    /**
     * تحويل Julian Day إلى ميلادي
     */
    static تاريخ_ميلادي ميلادي_من_جوليان(int jd) {
        int l = jd + 68569;
        int n = static_cast<int>((4 * l) / 146097);
        l = l - static_cast<int>((146097 * n + 3) / 4);
        int i = static_cast<int>((4000 * (l + 1)) / 1461001);
        l = l - static_cast<int>((1461 * i) / 4) + 31;
        int j = static_cast<int>((80 * l) / 2447);
        
        تاريخ_ميلادي م;
        م.اليوم = l - static_cast<int>((2447 * j) / 80);
        l = static_cast<int>(j / 11);
        م.الشهر = j + 2 - 12 * l;
        م.السنة = 100 * (n - 49) + i + l;
        
        return م;
    }
};

