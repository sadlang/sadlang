/**
 * 📅 مُنسق التاريخ الهجري
 */
class منسق_تاريخ_هجري {
public:
    /**
     * تنسيقات مختلفة
     */
    enum تنسيق {
        قصير,      // 5/9/1445
        متوسط,     // 5 رمضان 1445
        طويل,      // الجمعة 5 رمضان 1445
        كامل       // الجمعة، الخامس من رمضان لعام 1445 هـ
    };
    
    /**
     * تنسيق التاريخ
     */
    static std::string نسق(const تاريخ_هجري& ت, تنسيق نوع = متوسط) {
        switch (نوع) {
            case قصير:
                return std::to_string(ت.اليوم) + "/" +
                       std::to_string(ت.الشهر) + "/" +
                       std::to_string(ت.السنة);
                       
            case متوسط:
                return ت.نص();
                
            case طويل: {
                // حساب يوم الأسبوع (تقريبي)
                int يوم = (محوّل_تاريخ::إلى_ميلادي(ت).اليوم + 1) % 7;
                return أيام_الأسبوع[يوم] + " " + ت.نص();
            }
                
            case كامل: {
                int يوم = (محوّل_تاريخ::إلى_ميلادي(ت).اليوم + 1) % 7;
                return أيام_الأسبوع[يوم] + "، " +
                       ترتيب_يوم(ت.اليوم) + " من " +
                       ت.اسم_الشهر() + " لعام " +
                       std::to_string(ت.السنة) + " هـ";
            }
        }
        
        return ت.نص();
    }
    
    /**
     * الفرق بين تاريخين بالأيام
     */
    static int الفرق_بالأيام(const تاريخ_هجري& من, const تاريخ_هجري& إلى) {
        auto م1 = محوّل_تاريخ::إلى_ميلادي(من);
        auto م2 = محوّل_تاريخ::إلى_ميلادي(إلى);
        
        // حساب بسيط (تقريبي)
        int أيام1 = م1.السنة * 365 + م1.الشهر * 30 + م1.اليوم;
        int أيام2 = م2.السنة * 365 + م2.الشهر * 30 + م2.اليوم;
        
        return أيام2 - أيام1;
    }
    
private:
    /**
     * ترتيب اليوم (الأول، الثاني، ...)
     */
    static std::string ترتيب_يوم(int يوم) {
        static const std::vector<std::string> ترتيبات = {
            "", "الأول", "الثاني", "الثالث", "الرابع", "الخامس",
            "السادس", "السابع", "الثامن", "التاسع", "العاشر",
            "الحادي عشر", "الثاني عشر", "الثالث عشر", "الرابع عشر", "الخامس عشر",
            "السادس عشر", "السابع عشر", "الثامن عشر", "التاسع عشر", "العشرون",
            "الحادي والعشرون", "الثاني والعشرون", "الثالث والعشرون",
            "الرابع والعشرون", "الخامس والعشرون", "السادس والعشرون",
            "السابع والعشرون", "الثامن والعشرون", "التاسع والعشرون", "الثلاثون"
        };
        
        if (يوم >= 1 && يوم <= 30) {
            return ترتيبات[يوم];
        }
        return std::to_string(يوم);
    }
};

