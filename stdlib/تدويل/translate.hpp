/**
 * 🔤 ت() - دالة الترجمة المختصرة
 */
inline std::string ت(const std::string& مفتاح) {
    return مُترجم::المثيل().ترجم(مفتاح);
}

/**
 * ت() مع متغيرات
 */
inline std::string ت(const std::string& مفتاح, 
                     const std::map<std::string, std::string>& متغيرات) {
    return مُترجم::المثيل().ترجم(مفتاح, متغيرات);
}

/**
 * ت() مع عدد (للجمع)
 */
inline std::string ت_عدد(const std::string& مفتاح, int عدد) {
    return مُترجم::المثيل().ترجم_عدد(مفتاح, عدد);
}

/**
 * ت() مع عدد ومتغيرات
 */
inline std::string ت_عدد(const std::string& مفتاح, int عدد,
                          const std::map<std::string, std::string>& متغيرات) {
    std::string نتيجة = مُترجم::المثيل().ترجم_عدد(مفتاح, عدد);
    
    for (const auto& [اسم, قيمة] : متغيرات) {
        std::string علامة = "{" + اسم + "}";
        size_t موضع = نتيجة.find(علامة);
        while (موضع != std::string::npos) {
            نتيجة.replace(موضع, علامة.length(), قيمة);
            موضع = نتيجة.find(علامة);
        }
    }
    
    return نتيجة;
}

