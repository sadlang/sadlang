    عودة دالة(سياق)
        رقم دور_حالي = دالة_اقرأ_دور()
        
        لكل دور في أدوار_مطلوبة
            إذا (دور == دور_حالي)
                عودة صحيح
            نهاية
        نهاية
        
        انتقل(سياق["موجه"]، مسار_تحويل)
        عودة خطأ
    نهاية
