دالة تعامل_مع_مسار(موجه)
    # معالجة المسار الحالي
    رقم مسار = اقرأ_مسار_حالي(موجه)
    رقم استعلام = اقرأ_معاملات_استعلام()
    
    # البحث عن مسار مطابق
    لكل معلومات_مسار في موجه["مسارات"]
        رقم معاملات = طابق_مسار(معلومات_مسار، مسار)
        
        إذا (معاملات != عدم)
            # إنشاء سياق
            رقم سياق = {
                "مسار": مسار،
                "معاملات": معاملات،
                "استعلام": استعلام،
                "موجه": موجه
            }
            
            # تنفيذ قبل التنقل
            رقم متابعة = نفّذ_قبل_تنقل(موجه، سياق)
            إذا (!متابعة)
                عودة
            نهاية
            
            # تنفيذ الحراس
            متابعة = نفّذ_حراس(معلومات_مسار، سياق)
            إذا (!متابعة)
                عودة
            نهاية
            
            # تنفيذ الوسيط
            نفّذ_وسيط(موجه، سياق)
            نفّذ_وسيط_مسار(معلومات_مسار، سياق)
            
            # تحديث الحالة
            موجه["السابق"] = موجه["الحالي"]
            موجه["الحالي"] = سياق
            
            # تنفيذ المعالج
            معلومات_مسار["معالج"](سياق)
            
            # تنفيذ بعد التنقل
            نفّذ_بعد_تنقل(موجه، سياق)
            
            عودة
        نهاية
    نهاية
    
    # معالجة 404
    إذا (موجه["مسار_٤٠٤"] != عدم)
        موجه["مسار_٤٠٤"]({
            "مسار": مسار،
            "استعلام": استعلام
        })
    نهاية
نهاية

دالة اقرأ_مسار_حالي(موجه)
    # قراءة المسار الحالي
    إذا (موجه["وضع"] == "hash")
        رقم هاش = __sad_window_location_hash()
        إذا (__sad_string_starts_with(هاش، "#"))
            عودة __sad_string_slice(هاش، 1)
        وإلا
            عودة "/"
        نهاية
    وإلا
        عودة __sad_window_location_pathname()
    نهاية
نهاية

دالة اقرأ_معاملات_استعلام()
    # قراءة معاملات الاستعلام
    رقم بحث = __sad_window_location_search()
    رقم معاملات = {}
    
    إذا (__sad_string_length(بحث) > 1)
        رقم نص = __sad_string_slice(بحث، 1)
        رقم أزواج = __sad_string_split(نص، "&")
        
        لكل زوج في أزواج
            رقم أجزاء = __sad_string_split(زوج، "=")
            إذا (__sad_array_length(أجزاء) >= 2)
                رقم مفتاح = __sad_decode_uri_component(أجزاء[0])
                رقم قيمة = __sad_decode_uri_component(أجزاء[1])
                معاملات[مفتاح] = قيمة
            نهاية
        نهاية
    نهاية
    
    عودة معاملات
نهاية

