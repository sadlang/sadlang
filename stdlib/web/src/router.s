دالة حوّل_نمط_إلى_regex(نمط)
    # تحويل نمط المسار إلى regex
    # مثال: "/مستخدم/:معرف" -> "^/مستخدم/([^/]+)$"
    رقم regex_نص = نمط
    
    # استبدال المعاملات :اسم
    regex_نص = __sad_string_replace_all(regex_نص، ":([^/]+)"، "([^/]+)")
    
    # استبدال * للمطابقة العامة
    regex_نص = __sad_string_replace_all(regex_نص، "*"، ".*")
    
    # إضافة بداية ونهاية
    regex_نص = "^" + regex_نص + "$"
    
    عودة __sad_regex_new(regex_نص)
نهاية

دالة استخرج_أسماء_معاملات(نمط)
    # استخراج أسماء المعاملات من النمط
    رقم أسماء = []
    رقم regex = __sad_regex_new(":([^/]+)")
    رقم مطابقات = __sad_regex_match_all(regex، نمط)
    
    لكل مطابقة في مطابقات
        __sad_array_push(أسماء، مطابقة[1])
    نهاية
    
    عودة أسماء
نهاية

دالة طابق_مسار(معلومات_مسار، مسار)
    # مطابقة مسار مع نمط
    رقم مطابقة = __sad_regex_exec(معلومات_مسار["regex"]، مسار)
    
    إذا (مطابقة == عدم)
        عودة عدم
    نهاية
    
    رقم معاملات = {}
    رقم أسماء = معلومات_مسار["معاملات"]
    رقم ط = 0
    
    طالما (ط < __sad_array_length(أسماء))
        معاملات[أسماء[ط]] = مطابقة[ط + 1]
        ط = ط + 1
    نهاية
    
    عودة معاملات
نهاية

