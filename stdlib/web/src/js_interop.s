دالة كائن_من(مفاتيح، قيم)
    # إنشاء كائن من مصفوفتي مفاتيح وقيم
    رقم كائن = كائن_جديد()
    رقم ط = 0
    
    بينما (ط < طول(مفاتيح))
        كائن_عيّن(كائن، مفاتيح[ط]، قيم[ط])
        ط = ط + 1
    نهاية
    
    عودة كائن
