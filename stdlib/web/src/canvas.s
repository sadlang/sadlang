دالة ارسم_مضلع(سياق، مركز_س، مركز_ص، نصف_قطر، عدد_أضلاع)
    # رسم مضلع منتظم
    رقم باي = 3.14159265359
    رقم زاوية = باي * 2 / عدد_أضلاع
    
    ابدأ_مسار(سياق)
    
    رقم ط = 0
    طالما (ط < عدد_أضلاع)
        رقم س = مركز_س + نصف_قطر * __sad_math_cos(ط * زاوية - باي / 2)
        رقم ص = مركز_ص + نصف_قطر * __sad_math_sin(ط * زاوية - باي / 2)
        
        إذا (ط == 0)
            انتقل_إلى(سياق، س، ص)
        وإلا
            ارسم_خط_إلى(سياق، س، ص)
        نهاية
        
        ط = ط + 1
    نهاية
    
    أغلق_مسار(سياق)
نهاية

دالة ارسم_نجمة(سياق، مركز_س، مركز_ص، نصف_قطر_خارجي، نصف_قطر_داخلي، عدد_رؤوس)
    # رسم نجمة
    رقم باي = 3.14159265359
    رقم زاوية = باي / عدد_رؤوس
    
    ابدأ_مسار(سياق)
    
    رقم ط = 0
    طالما (ط < عدد_رؤوس * 2)
        رقم نصف_قطر = 0
        إذا (ط % 2 == 0)
            نصف_قطر = نصف_قطر_خارجي
        وإلا
            نصف_قطر = نصف_قطر_داخلي
        نهاية
        
        رقم س = مركز_س + نصف_قطر * __sad_math_cos(ط * زاوية - باي / 2)
        رقم ص = مركز_ص + نصف_قطر * __sad_math_sin(ط * زاوية - باي / 2)
        
        إذا (ط == 0)
