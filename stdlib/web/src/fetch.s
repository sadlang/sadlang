# ============================================================================
# المهلة الزمنية
# ============================================================================

دالة جلب_بمهلة(رابط، خيارات، مهلة_مللي)
    # جلب مع مهلة زمنية
    رقم متحكم = أنشئ_متحكم_إلغاء()
    رقم إشارة = إشارة_إلغاء(متحكم)
    
    إذا (خيارات == عدم)
        خيارات = أنشئ_خيارات()
    نهاية
    عيّن_إشارة_إلغاء(خيارات، إشارة)
    
    # إعداد المهلة
    رقم معرف_مهلة = __sad_set_timeout(دالة()
        ألغِ_طلب(متحكم)
    نهاية، مهلة_مللي)
    
    # تنفيذ الطلب
    رقم وعد = جلب_بخيارات(رابط، خيارات)
    
    # إلغاء المهلة عند الانتهاء
    عودة __sad_promise_finally(وعد، دالة()
        __sad_clear_timeout(معرف_مهلة)
    نهاية)
نهاية

