/**
 * نوع التغيير
 */
enum class نوع_تغيير {
    إنشاء,          // ملف جديد
    تعديل,          // تعديل محتوى
    حذف,            // حذف الملف
    إعادة_تسمية    // تغيير الاسم
};

/**
 * حدث تغيير
 */
struct حدث_تغيير {
    نوع_تغيير النوع;
    std::string المسار;
    std::chrono::system_clock::time_point الوقت;
};

/**
 * نتيجة إعادة التحميل
 */
struct نتيجة_تحميل {
    bool نجح;
    std::string رسالة;
    std::vector<std::string> المفاتيح_المتغيرة;
};

// ═══════════════════════════════════════════════════════════════════════════════
