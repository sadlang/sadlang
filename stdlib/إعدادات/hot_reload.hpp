/**
 * مراقب الملفات
 * 
 * يراقب ملفاً أو مجلداً ويُخبرنا عند التغيير
 */
class مراقب_ملفات {
public:
    مراقب_ملفات() : يعمل_(false) {}
    
    ~مراقب_ملفات() {
        أوقف();
    }
    
    /**
     * إضافة مسار للمراقبة
     */
    void راقب(const std::string& مسار) {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        if (std::filesystem::exists(مسار)) {
            معلومات_ملف معلومات;
            معلومات.المسار = مسار;
            معلومات.آخر_تعديل = std::filesystem::last_write_time(مسار);
            الملفات_[مسار] = معلومات;
        }
    }
    
    /**
     * إزالة مسار من المراقبة
     */
    void أوقف_مراقبة(const std::string& مسار) {
        std::lock_guard<std::mutex> قفل(القفل_);
        الملفات_.erase(مسار);
    }
    
    /**
     * إضافة مستمع
     */
    void عند_تغيير(مستمع_تغييرات مستمع) {
        المستمعون_.push_back(مستمع);
    }
    
    /**
     * بدء المراقبة في خيط منفصل
     */
    void ابدأ(std::chrono::milliseconds فاصل = std::chrono::milliseconds{1000}) {
        if (يعمل_) return;
        
        يعمل_ = true;
        خيط_المراقبة_ = std::thread([this, فاصل]() {
            while (يعمل_) {
                تحقق_من_التغييرات();
                std::this_thread::sleep_for(فاصل);
            }
        });
    }
    
    /**
     * إيقاف المراقبة
     */
    void أوقف() {
        يعمل_ = false;
        if (خيط_المراقبة_.joinable()) {
            خيط_المراقبة_.join();
        }
    }
    
    /**
     * هل يعمل؟
     */
    bool يعمل() const { return يعمل_; }
    
    /**
     * تحقق يدوي من التغييرات
     */
    std::vector<حدث_تغيير> تحقق_الآن() {
        return تحقق_من_التغييرات();
    }

private:
    struct معلومات_ملف {
        std::string المسار;
        std::filesystem::file_time_type آخر_تعديل;
    };
    
    std::vector<حدث_تغيير> تحقق_من_التغييرات() {
        std::lock_guard<std::mutex> قفل(القفل_);
        std::vector<حدث_تغيير> تغييرات;
        
        for (auto& [مسار, معلومات] : الملفات_) {
            if (!std::filesystem::exists(مسار)) {
                // الملف حُذف
                حدث_تغيير حدث;
                حدث.النوع = نوع_تغيير::حذف;
                حدث.المسار = مسار;
                حدث.الوقت = std::chrono::system_clock::now();
                تغييرات.push_back(حدث);
                أبلغ_المستمعين(حدث);
                continue;
            }
            
            auto وقت_حالي = std::filesystem::last_write_time(مسار);
            
            if (وقت_حالي != معلومات.آخر_تعديل) {
                معلومات.آخر_تعديل = وقت_حالي;
                
                حدث_تغيير حدث;
                حدث.النوع = نوع_تغيير::تعديل;
                حدث.المسار = مسار;
                حدث.الوقت = std::chrono::system_clock::now();
                تغييرات.push_back(حدث);
                أبلغ_المستمعين(حدث);
            }
        }
        
        return تغييرات;
    }
    
    void أبلغ_المستمعين(const حدث_تغيير& حدث) {
        for (const auto& مستمع : المستمعون_) {
            try {
                مستمع(حدث);
            } catch (...) {
                // تجاهل أخطاء المستمعين
            }
        }
    }
    
    std::unordered_map<std::string, معلومات_ملف> الملفات_;
    std::vector<مستمع_تغييرات> المستمعون_;
    std::thread خيط_المراقبة_;
    std::atomic<bool> يعمل_;
    std::mutex القفل_;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              إعدادات قابلة لإعادة التحميل
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * إعدادات قابلة لإعادة التحميل
 * 
 * تدعم:
 * - مراقبة الملف للتغييرات
 * - إعادة التحميل التلقائية
 * - إخطار المستمعين بالتغييرات
 */
class إعدادات_ديناميكية {
public:
    إعدادات_ديناميكية(const std::string& مسار_ملف)
        : مسار_الملف_(مسار_ملف)
    {
        // تحميل أولي
        حمِّل();
        
        // ربط المراقب
        المراقب_.راقب(مسار_ملف);
        المراقب_.عند_تغيير([this](const حدث_تغيير& حدث) {
            if (حدث.النوع == نوع_تغيير::تعديل) {
                أعد_التحميل();
            }
        });
    }
    
    /**
     * بدء المراقبة التلقائية
     */
    void ابدأ_المراقبة(std::chrono::milliseconds فاصل = std::chrono::milliseconds{1000}) {
        المراقب_.ابدأ(فاصل);
    }
    
    /**
     * إيقاف المراقبة
     */
    void أوقف_المراقبة() {
        المراقب_.أوقف();
    }
    
    /**
     * إعادة التحميل يدوياً
     */
    نتيجة_تحميل أعد_التحميل() {
        نتيجة_تحميل نتيجة;
        
        try {
            // حفظ القيم القديمة للمقارنة
            auto قديمة = القيم_;
            
            // إعادة التحميل
            if (!حمِّل()) {
                نتيجة.نجح = false;
                نتيجة.رسالة = "فشل قراءة الملف";
                return نتيجة;
            }
            
            // اكتشاف التغييرات
            for (const auto& [مفتاح, قيمة] : القيم_) {
                auto it = قديمة.find(مفتاح);
                if (it == قديمة.end() || it->second != قيمة) {
                    نتيجة.المفاتيح_المتغيرة.push_back(مفتاح);
                    أبلغ_مستمعي_الإعدادات(مفتاح, قيمة);
                }
            }
            
            نتيجة.نجح = true;
            نتيجة.رسالة = "تم التحميل بنجاح";
            
        } catch (const std::exception& e) {
            نتيجة.نجح = false;
            نتيجة.رسالة = e.what();
        }
        
        return نتيجة;
    }
    
    /**
     * قراءة قيمة
     */
    std::string احصل(const std::string& مفتاح, const std::string& افتراضي = "") const {
        std::lock_guard<std::mutex> قفل(القفل_);
        auto it = القيم_.find(مفتاح);
        return it != القيم_.end() ? it->second : افتراضي;
    }
    
    /**
     * قراءة عدد
     */
    int64_t احصل_عدد(const std::string& مفتاح, int64_t افتراضي = 0) const {
        auto قيمة = احصل(مفتاح);
        if (قيمة.empty()) return افتراضي;
        try {
            return std::stoll(قيمة);
        } catch (...) {
            return افتراضي;
        }
    }
    
    /**
     * قراءة منطقي
     */
    bool احصل_منطقي(const std::string& مفتاح, bool افتراضي = false) const {
        auto قيمة = احصل(مفتاح);
        if (قيمة.empty()) return افتراضي;
        return قيمة == "true" || قيمة == "صحيح" || قيمة == "1";
    }
    
    /**
     * الاستماع لتغيير إعداد معين
     */
    void عند_تغيير(const std::string& مفتاح, مستمع_إعدادات مستمع) {
        مستمعو_الإعدادات_[مفتاح].push_back(مستمع);
    }
    
    /**
     * الاستماع لأي تغيير
     */
    void عند_أي_تغيير(مستمع_إعدادات مستمع) {
        مستمعون_عامون_.push_back(مستمع);
    }
    
    /**
     * كل المفاتيح
     */
    std::vector<std::string> المفاتيح() const {
        std::lock_guard<std::mutex> قفل(القفل_);
        std::vector<std::string> نتائج;
        for (const auto& [مفتاح, _] : القيم_) {
            نتائج.push_back(مفتاح);
        }
        return نتائج;
    }

private:
    bool حمِّل() {
        std::lock_guard<std::mutex> قفل(القفل_);
        
        std::ifstream ملف(مسار_الملف_);
        if (!ملف.is_open()) {
            return false;
        }
        
        القيم_.clear();
        std::string سطر;
        std::string قسم;
        
        while (std::getline(ملف, سطر)) {
            // تجاهل التعليقات والأسطر الفارغة
            if (سطر.empty() || سطر[0] == '#') continue;
            
            // اكتشاف القسم
            if (سطر[0] == '[') {
                size_t نهاية = سطر.find(']');
                if (نهاية != std::string::npos) {
                    قسم = سطر.substr(1, نهاية - 1);
                }
                continue;
            }
            
            // تحليل القيمة
            size_t يساوي = سطر.find('=');
            if (يساوي == std::string::npos) continue;
            
            std::string مفتاح = قص(سطر.substr(0, يساوي));
            std::string قيمة = قص(سطر.substr(يساوي + 1));
            
            // إزالة علامات الاقتباس
            if (قيمة.size() >= 2 && قيمة.front() == '"' && قيمة.back() == '"') {
                قيمة = قيمة.substr(1, قيمة.size() - 2);
            }
            
            // بناء المفتاح الكامل
            std::string مفتاح_كامل = قسم.empty() ? مفتاح : قسم + "." + مفتاح;
            القيم_[مفتاح_كامل] = قيمة;
        }
        
        return true;
    }
    
    void أبلغ_مستمعي_الإعدادات(const std::string& مفتاح, const std::string& قيمة) {
        // مستمعون محددون
        auto it = مستمعو_الإعدادات_.find(مفتاح);
        if (it != مستمعو_الإعدادات_.end()) {
            for (const auto& مستمع : it->second) {
                try {
                    مستمع(مفتاح, قيمة);
                } catch (...) {}
            }
        }
        
        // مستمعون عامون
        for (const auto& مستمع : مستمعون_عامون_) {
            try {
                مستمع(مفتاح, قيمة);
            } catch (...) {}
        }
    }
    
    std::string قص(const std::string& نص) {
        size_t بداية = نص.find_first_not_of(" \t");
        size_t نهاية = نص.find_last_not_of(" \t");
        if (بداية == std::string::npos) return "";
        return نص.substr(بداية, نهاية - بداية + 1);
    }
    
    std::string مسار_الملف_;
    std::unordered_map<std::string, std::string> القيم_;
    مراقب_ملفات المراقب_;
    
    std::unordered_map<std::string, std::vector<مستمع_إعدادات>> مستمعو_الإعدادات_;
    std::vector<مستمع_إعدادات> مستمعون_عامون_;
    
    mutable std::mutex القفل_;
};

