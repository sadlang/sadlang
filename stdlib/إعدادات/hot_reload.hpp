// ═══════════════════════════════════════════════════════════════════════════════

/**
 * واجهة الاستماع للتغييرات
 */
using مستمع_تغييرات = std::function<void(const حدث_تغيير&)>;

/**
 * واجهة الاستماع للإعدادات
 */
using مستمع_إعدادات = std::function<void(const std::string& مفتاح, const std::string& قيمة_جديدة)>;

// ═══════════════════════════════════════════════════════════════════════════════
//                              مراقب الملفات
