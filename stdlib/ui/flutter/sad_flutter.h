// ═══════════════════════════════════════════════════════════════════════════════
//  Quick Reference - Arabic API
// ═══════════════════════════════════════════════════════════════════════════════
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  المكونات الأساسية                                              │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  نص(محتوى)           - عرض نص                                  │
//  │  نص_كبير(محتوى)       - عنوان كبير                              │
//  │  نص_صغير(محتوى)       - نص صغير                                 │
//  │  حاوية(طفل, ...)     - صندوق مع تزيين                          │
//  │  صندوق(طفل, خلفية)    - صندوق بلون                              │
//  │  بطاقة(طفل)          - بطاقة مع ظل                              │
//  │  ايقونة(رمز)         - عرض أيقونة                               │
//  └─────────────────────────────────────────────────────────────────┘
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  الأزرار                                                        │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  زر(عنوان, دالة)      - زر مرتفع                                │
//  │  زر_نصي(عنوان, دالة)   - زر بدون خلفية                          │
//  │  زر_ايقونة(رمز, دالة)  - زر بأيقونة                             │
//  └─────────────────────────────────────────────────────────────────┘
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  التخطيط                                                        │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  عمود({...})         - ترتيب عمودي                              │
//  │  صف({...})           - ترتيب أفقي                               │
//  │  تكديس({...})        - طبقات فوق بعضها                          │
//  │  توسيط(طفل)          - توسيط المحتوى                            │
//  │  حشو(مقدار, طفل)      - إضافة حشو                               │
//  │  توسيع(طفل)          - ملء المساحة المتاحة                       │
//  │  التفاف({...})       - التفاف العناصر                           │
//  └─────────────────────────────────────────────────────────────────┘
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  الإدخال                                                        │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  حقل_ادخال(...)      - حقل نص                                   │
//  │  اختيار(قيمة, دالة)   - مربع اختيار                             │
//  │  تبديل(قيمة, دالة)    - مفتاح تبديل                              │
//  │  منزلق(قيمة, دالة)    - شريط قيمة                               │
//  └─────────────────────────────────────────────────────────────────┘
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  التطبيق                                                        │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  شغل(تطبيق)          - تشغيل التطبيق                            │
//  │  تطبيق(...)          - MaterialApp                             │
//  │  هيكل(...)           - Scaffold                                │
//  │  شريط_تطبيق(...)      - AppBar                                  │
//  │  زر_عائم(...)         - FloatingActionButton                   │
//  └─────────────────────────────────────────────────────────────────┘
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  الألوان (الوان::)                                              │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  اسود(), ابيض(), احمر(), اخضر(), ازرق()                        │
//  │  اصفر(), برتقالي(), بنفسجي(), رمادي(), شفاف()                   │
//  │  مخصص(ر, خ, ز, ش), من_هكس(قيمة)                                 │
//  └─────────────────────────────────────────────────────────────────┘
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │  الرموز (رموز::)                                                │
//  ├─────────────────────────────────────────────────────────────────┤
//  │  اضافة, حذف, تعديل, مسح, حفظ, اغلاق, قائمة                      │
//  │  رئيسية, اعدادات, بحث, شخص, نجمة, مفضل                          │
//  │  صح, الغاء, رجوع, تقدم, المزيد                                  │
//  └─────────────────────────────────────────────────────────────────┘
//
