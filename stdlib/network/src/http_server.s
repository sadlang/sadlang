        إذا (مسار_مسجل["نمط"] == مسار)
            __sad_array_push(مسار_مسجل["وسيط"]، وسيط)
        نهاية
    نهاية
}

# وسيط شائع
دالة وسيط_json() {
    # وسيط تحليل JSON
    عودة دالة(طلب، رد، التالي) {
        رقم نوع_محتوى = __sad_http_request_header(طلب، "Content-Type")
        إذا (__sad_string_includes(نوع_محتوى، "application/json"))
            رقم جسم = __sad_http_request_body(طلب)
            طلب["json"] = __sad_json_parse(جسم)
        نهاية
        التالي()
    }
}

دالة وسيط_نموذج() {
    # وسيط تحليل النماذج
    عودة دالة(طلب، رد، التالي) {
        رقم نوع_محتوى = __sad_http_request_header(طلب، "Content-Type")
        إذا (__sad_string_includes(نوع_محتوى، "application/x-www-form-urlencoded"))
            رقم جسم = __sad_http_request_body(طلب)
            طلب["نموذج"] = حلّل_نموذج(جسم)
        نهاية
        التالي()
    }
}

دالة وسيط_cors(أصول) {
    # وسيط CORS
    عودة دالة(طلب، رد، التالي) {
        __sad_http_response_set_header(رد، "Access-Control-Allow-Origin"، أصول)
        __sad_http_response_set_header(رد، "Access-Control-Allow-Methods"، "GET, POST, PUT, DELETE, PATCH, OPTIONS")
        __sad_http_response_set_header(رد، "Access-Control-Allow-Headers"، "Content-Type, Authorization")
        
        إذا (__sad_http_request_method(طلب) == "OPTIONS")
            __sad_http_response_set_status(رد، 204)
            عودة
        نهاية
        
        التالي()
    }
}

دالة وسيط_سجل() {
    # وسيط التسجيل
    عودة دالة(طلب، رد، التالي) {
        رقم بداية = __sad_time_now()
        رقم طريقة = __sad_http_request_method(طلب)
        رقم مسار = __sad_http_request_path(طلب)
        
        التالي()
        
        رقم مدة = __sad_time_now() - بداية
        __sad_console_log("[" + طريقة + "] " + مسار + " - " + مدة + "ms")
    }
}

دالة وسيط_مصادقة(دالة_تحقق) {
    # وسيط المصادقة
    عودة دالة(طلب، رد، التالي) {
        رقم رمز = __sad_http_request_header(طلب، "Authorization")
        
        إذا (رمز == عدم)
            أرسل_خطأ(رد، 401، "غير مصرح")
            عودة
        نهاية
        
        إذا (__sad_string_starts_with(رمز، "Bearer "))
            رمز = __sad_string_slice(رمز، 7)
        نهاية
        
        رقم مستخدم = دالة_تحقق(رمز)
        إذا (مستخدم == عدم)
            أرسل_خطأ(رد، 401، "رمز غير صالح")
            عودة
        نهاية
        
        طلب["مستخدم"] = مستخدم
        التالي()
    }
}

دالة وسيط_حد_طلبات(الحد، نافذة_مللي) {
    # وسيط تحديد معدل الطلبات
    رقم طلبات = {}
    
    عودة دالة(طلب، رد، التالي) {
        رقم عنوان = __sad_http_request_ip(طلب)
        رقم الآن = __sad_time_now()
        
        إذا (طلبات[عنوان] == عدم)
            طلبات[عنوان] = {"عدد": 0، "بداية": الآن}
        نهاية
        
        رقم بيانات = طلبات[عنوان]
        
        # إعادة تعيين النافذة
        إذا (الآن - بيانات["بداية"] > نافذة_مللي)
            بيانات["عدد"] = 0
            بيانات["بداية"] = الآن
        نهاية
        
        بيانات["عدد"] = بيانات["عدد"] + 1
        
        إذا (بيانات["عدد"] > الحد)
            __sad_http_response_set_header(رد، "Retry-After"، (نافذة_مللي / 1000))
            أرسل_خطأ(رد، 429، "عدد الطلبات كبير جداً")
            عودة
        نهاية
        
        التالي()
    }
}

