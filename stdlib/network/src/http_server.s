دالة عالج_طلب(خادم، طلب، رد) {
    # معالجة طلب وارد
    رقم طريقة = __sad_http_request_method(طلب)
    رقم مسار = __sad_http_request_path(طلب)
    
    # البحث عن مسار مطابق
    لكل مسار_مسجل في خادم["مسارات"]
        إذا (طابق(مسار_مسجل، طريقة، مسار))
            # تنفيذ الوسيط العام
            نفّذ_وسيط_سلسلة(خادم["وسيط_عام"]، طلب، رد، دالة() {
                # تنفيذ وسيط المسار
                نفّذ_وسيط_سلسلة(مسار_مسجل["وسيط"]، طلب، رد، دالة() {
                    # استخراج المعاملات
                    طلب["معاملات"] = استخرج_معاملات(مسار_مسجل["نمط"]، مسار)
                    # تنفيذ المعالج
                    مسار_مسجل["معالج"](طلب، رد)
                })
            })
            عودة
        نهاية
    نهاية
    
    # 404 إذا لم يوجد مسار
    أرسل_خطأ(رد، 404، "المسار غير موجود")
}

دالة طابق(مسار_مسجل، طريقة، مسار) {
    # مطابقة المسار
    إذا (مسار_مسجل["طريقة"] != "*" && مسار_مسجل["طريقة"] != طريقة)
        عودة خطأ
    نهاية
    
    # تحويل النمط إلى regex
    رقم نمط = مسار_مسجل["نمط"]
    رقم regex = __sad_string_replace_all(نمط، ":([^/]+)"، "([^/]+)")
    regex = "^" + regex + "$"
    
    عودة __sad_regex_test(__sad_regex_new(regex)، مسار)
}

دالة استخرج_معاملات(نمط، مسار) {
    # استخراج المعاملات من المسار
    رقم معاملات = {}
    
    رقم أسماء_regex = __sad_regex_new(":([^/]+)")
    رقم أسماء = __sad_regex_match_all(أسماء_regex، نمط)
    
    رقم قيم_regex = __sad_string_replace_all(نمط، ":([^/]+)"، "([^/]+)")
    قيم_regex = "^" + قيم_regex + "$"
    رقم مطابقة = __sad_regex_exec(__sad_regex_new(قيم_regex)، مسار)
    
    رقم ط = 0
    طالما (ط < __sad_array_length(أسماء))
        معاملات[أسماء[ط][1]] = مطابقة[ط + 1]
        ط = ط + 1
    نهاية
    
    عودة معاملات
}

دالة نفّذ_وسيط_سلسلة(وسيط_قائمة، طلب، رد، نهائي) {
    # تنفيذ سلسلة الوسيط
    رقم فهرس = 0
    
    دالة التالي() {
        إذا (فهرس < __sad_array_length(وسيط_قائمة))
            رقم وسيط = وسيط_قائمة[فهرس]
            فهرس = فهرس + 1
            وسيط(طلب، رد، التالي)
        وإلا
            نهائي()
        نهاية
    }
    
    التالي()
}

