دالة خدمة_ملفات_ثابتة(خادم، مسار_ويب، مجلد) {
    # تقديم ملفات ثابتة
    خادم["ملفات_ثابتة"] = {
        "مسار": مسار_ويب،
        "مجلد": مجلد
    }
    
    احصل_على(خادم، مسار_ويب + "/*"، دالة(طلب، رد) {
        رقم مسار_طلب = __sad_http_request_path(طلب)
        رقم مسار_نسبي = __sad_string_slice(مسار_طلب، __sad_string_length(مسار_ويب))
        رقم مسار_ملف = مجلد + مسار_نسبي
        
        إذا (__sad_file_exists(مسار_ملف))
            أرسل_ملف(رد، مسار_ملف)
        وإلا
            أرسل_خطأ(رد، 404، "الملف غير موجود")
        نهاية
    })
}

دالة اكتشف_نوع_محتوى(مسار) {
    # اكتشاف نوع MIME
    رقم امتداد = __sad_path_extension(مسار)
    
    إذا (امتداد == ".html")
        عودة "text/html"
    وإلا_إذا (امتداد == ".css")
        عودة "text/css"
    وإلا_إذا (امتداد == ".js")
        عودة "application/javascript"
    وإلا_إذا (امتداد == ".json")
        عودة "application/json"
    وإلا_إذا (امتداد == ".png")
        عودة "image/png"
    وإلا_إذا (امتداد == ".jpg" || امتداد == ".jpeg")
        عودة "image/jpeg"
    وإلا_إذا (امتداد == ".gif")
        عودة "image/gif"
    وإلا_إذا (امتداد == ".svg")
        عودة "image/svg+xml"
    وإلا_إذا (امتداد == ".woff")
        عودة "font/woff"
    وإلا_إذا (امتداد == ".woff2")
        عودة "font/woff2"
    وإلا
        عودة "application/octet-stream"
    نهاية
}

