# ==========================================
# تسجيل المسارات
# ==========================================

دالة سجّل_مسار(خادم، طريقة، مسار، معالج) {
    # تسجيل مسار عام
    __sad_array_push(خادم["مسارات"]، {
        "طريقة": طريقة،
        "نمط": مسار،
        "معالج": معالج،
        "وسيط": []
    })
}

دالة احصل_على(خادم، مسار، معالج) {
    # تسجيل مسار GET
    سجّل_مسار(خادم، "GET"، مسار، معالج)
}

دالة أرسل_إلى(خادم، مسار، معالج) {
    # تسجيل مسار POST
    سجّل_مسار(خادم، "POST"، مسار، معالج)
}

دالة حدّث_في(خادم، مسار، معالج) {
    # تسجيل مسار PUT
    سجّل_مسار(خادم، "PUT"، مسار، معالج)
}

دالة حدّث_جزئي_في(خادم، مسار، معالج) {
    # تسجيل مسار PATCH
    سجّل_مسار(خادم، "PATCH"، مسار، معالج)
}

دالة احذف_من(خادم، مسار، معالج) {
    # تسجيل مسار DELETE
    سجّل_مسار(خادم، "DELETE"، مسار، معالج)
}

دالة جميع_الطرق(خادم، مسار، معالج) {
    # تسجيل مسار لجميع الطرق
    سجّل_مسار(خادم، "*"، مسار، معالج)
}

