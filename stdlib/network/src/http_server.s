    رقم محتوى = __sad_file_read(مسار_ملف)
    رقم نوع = اكتشف_نوع_محتوى(مسار_ملف)
    
    __sad_http_response_set_status(رد، 200)
    __sad_http_response_set_header(رد، "Content-Type"، نوع)
    __sad_http_response_set_body(رد، محتوى)
}

