    عودة {
        "منفذ": منفذ،
        "مسارات": [],
        "وسيط_عام": [],
        "وسيط_خطأ": عدم،
        "ملفات_ثابتة": عدم،
        "قوالب": {},
        "إعدادات": {
            "cors": خطأ،
            "cors_أصول": "*"،
