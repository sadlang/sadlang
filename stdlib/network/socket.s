    # صنف مقبس TCP - TCP Socket Class
    # =======================================
    
    صنف مقبس_tcp 
        خاص متغير _مؤشر: مؤشر
        
        # المُنشئ
        دالة انشئ() 
            خارجي دالة _tcp_انشئ() -> مؤشر
            هذا._مؤشر = _tcp_انشئ()
            
            اذا (هذا._مؤشر == عدم) 
                رمي خطأ("فشل إنشاء مقبس TCP: " + _شبكة_رسالة_خطأ())
            نهاية
        نهاية
        
        # المُدمر
        دالة ~انشئ() 
            خارجي دالة _tcp_احذف(مؤشر: مؤشر)
            اذا (هذا._مؤشر != عدم) 
                _tcp_احذف(هذا._مؤشر)
            نهاية
        نهاية
        
        # ربط المقبس بمنفذ
        دالة اربط(منفذ: رقم) -> منطقي 
            خارجي دالة _tcp_اربط(مؤشر: مؤشر، منفذ: رقم) -> منطقي
            متغير نتيجة = _tcp_اربط(هذا._مؤشر، منفذ)
            
            اذا (!نتيجة) 
                رمي خطأ("فشل ربط المقبس: " + _شبكة_رسالة_خطأ())
            نهاية
            
            ارجع نتيجة
        نهاية
        
        # الاستماع للاتصالات
        دالة استمع(عدد_انتظار: رقم = 10) -> منطقي 
            خارجي دالة _tcp_استمع(مؤشر: مؤشر، عدد: رقم) -> منطقي
            متغير نتيجة = _tcp_استمع(هذا._مؤشر، عدد_انتظار)
            
            اذا (!نتيجة) 
                رمي خطأ("فشل الاستماع: " + _شبكة_رسالة_خطأ())
            نهاية
            
            ارجع نتيجة
        نهاية
        
        # قبول اتصال جديد
        دالة اقبل() -> مقبس_tcp 
            خارجي دالة _tcp_اقبل(مؤشر: مؤشر) -> مؤشر
            متغير عميل_مؤشر = _tcp_اقبل(هذا._مؤشر)
            
            اذا (عميل_مؤشر == عدم) 
                رمي خطأ("فشل قبول الاتصال: " + _شبكة_رسالة_خطأ())
            نهاية
            
            متغير عميل = مقبس_tcp_من_مؤشر(عميل_مؤشر)
            ارجع عميل
        نهاية
        
        # الاتصال بخادم
        دالة اتصل(عنوان: نص، منفذ: رقم) -> منطقي 
            خارجي دالة _tcp_اتصل(مؤشر: مؤشر، عنوان: نص، منفذ: رقم) -> منطقي
            متغير نتيجة = _tcp_اتصل(هذا._مؤشر، عنوان، منفذ)
            
            اذا (!نتيجة) 
                رمي خطأ("فشل الاتصال بـ " + عنوان + ":" + منفذ + " - " + _شبكة_رسالة_خطأ())
            نهاية
            
            ارجع نتيجة
        نهاية
        
        # إرسال بيانات
        دالة ارسل(بيانات: نص) -> رقم 
            خارجي دالة _tcp_ارسل(مؤشر: مؤشر، بيانات: نص، حجم: رقم) -> رقم
            متغير مرسل = _tcp_ارسل(هذا._مؤشر، بيانات، طول(بيانات))
            
            اذا (مرسل < 0) 
                رمي خطأ("فشل الإرسال: " + _شبكة_رسالة_خطأ())
            نهاية
            
            ارجع مرسل
        نهاية
        
        # إرسال جميع البيانات
        دالة ارسل_الكل(بيانات: نص) -> منطقي 
            خارجي دالة _tcp_ارسل_الكل(مؤشر: مؤشر، بيانات: نص، حجم: رقم) -> منطقي
            متغير نتيجة = _tcp_ارسل_الكل(هذا._مؤشر، بيانات، طول(بيانات))
            
            اذا (!نتيجة) 
                رمي خطأ("فشل إرسال جميع البيانات: " + _شبكة_رسالة_خطأ())
            نهاية
            
            ارجع نتيجة
        نهاية
        
        # استقبال بيانات
        دالة استقبل(حجم: رقم = 4096) -> نص 
            خارجي دالة _tcp_استقبل(مؤشر: مؤشر، buffer: نص، حجم: رقم) -> رقم
            
            متغير buffer = انشئ_buffer(حجم)
            متغير مستقبل = _tcp_استقبل(هذا._مؤشر، buffer، حجم)
            
            اذا (مستقبل < 0) 
                رمي خطأ("فشل الاستقبال: " + _شبكة_رسالة_خطأ())
            نهاية
            
            اذا (مستقبل == 0) 
                ارجع "" # Connection closed
            نهاية
            
            ارجع قص_buffer(buffer، مستقبل)
        نهاية
        
        # هل متصل؟
        دالة هل_متصل() -> منطقي 
            خارجي دالة _tcp_هل_متصل(مؤشر: مؤشر) -> منطقي
            ارجع _tcp_هل_متصل(هذا._مؤشر)
        نهاية
        
        # إغلاق المقبس
        دالة اغلق() 
            خارجي دالة _tcp_اغلق(مؤشر: مؤشر)
            _tcp_اغلق(هذا._مؤشر)
        نهاية
        
        # تعيين مهلة الاستقبال (بالملي ثانية)
        دالة عين_مهلة_استقبال(مهلة: رقم) 
            خارجي دالة _tcp_عين_مهلة_استقبال(مؤشر: مؤشر، مهلة: رقم)
            _tcp_عين_مهلة_استقبال(هذا._مؤشر، مهلة)
        نهاية
        
        # تعيين مهلة الإرسال (بالملي ثانية)
        دالة عين_مهلة_ارسال(مهلة: رقم) 
            خارجي دالة _tcp_عين_مهلة_ارسال(مؤشر: مؤشر، مهلة: رقم)
            _tcp_عين_مهلة_ارسال(هذا._مؤشر، مهلة)
        نهاية
        
        # الحصول على عنوان الطرف الآخر
        دالة احصل_على_عنوان_الطرف_الآخر() -> عنوان 
            خارجي دالة _tcp_احصل_على_عنوان_الطرف_الآخر(مؤشر: مؤشر) -> مؤشر
            متغير عنوان_مؤشر = _tcp_احصل_على_عنوان_الطرف_الآخر(هذا._مؤشر)
            
            اذا (عنوان_مؤشر == عدم) 
                رمي خطأ("فشل الحصول على عنوان الطرف الآخر")
            نهاية
            
            ارجع عنوان_من_مؤشر(عنوان_مؤشر)
        نهاية
    نهاية
    
