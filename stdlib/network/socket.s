        # استقبال بيانات من عنوان
        دالة استقبل_من(حجم: رقم = 4096) -> بيانات: نص، عنوان: نص، منفذ: رقمنهاية 
            خارجي دالة _udp_استقبل_من(مؤشر: مؤشر، buffer: نص، حجم: رقم،
                                            عنوان_من: نص، منفذ_من: مؤشر) -> رقم
            
            متغير buffer = انشئ_buffer(حجم)
            متغير عنوان_من = انشئ_buffer(46) # IPv6 max length
            متغير منفذ_من = 0
            
            متغير مستقبل = _udp_استقبل_من(هذا._مؤشر، buffer، حجم، 
                                              عنوان_من، &منفذ_من)
            
            اذا (مستقبل < 0) 
                رمي خطأ("فشل الاستقبال: " + _شبكة_رسالة_خطأ())
            نهاية
            
            ارجع 
                بيانات: قص_buffer(buffer، مستقبل)،
                عنوان: نظف_نص(عنوان_من)،
                منفذ: منفذ_من
            نهاية
        نهاية
        
