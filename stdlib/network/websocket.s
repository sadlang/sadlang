// بسم الله الرحمن الرحيم
// websocket.s - واجهة WebSocket للغة ص
// WebSocket Interface for Sad Language

/**
 * @module شبكة.websocket
 * @brief واجهة WebSocket للاتصال في الوقت الفعلي
 * 
 * هذه الوحدة توفر دعماً كاملاً لبروتوكول WebSocket
 * للاتصالات ثنائية الاتجاه في الوقت الفعلي.
 * 
 * @example
 * استورد شبكة.websocket
 * 
 * دالة main() {
 *     متغير عميل = websocket.عميل_جديد()
 *     
 *     عميل.عند_فتح(() => {
 *         اطبع("متصل!")
 *         عميل.ارسل("مرحباً")
 *     })
 *     
 *     عميل.عند_رسالة((رسالة) => {
 *         اطبع("استلم: " + رسالة)
 *     })
 *     
 *     عميل.اتصل("ws://localhost:8080")
 * }
 */

// ============================================================================
// التعدادات / Enumerations
// ============================================================================

/**
 * @enum نوع_الرسالة
 * @brief نوع رسالة WebSocket
 */
تعداد نوع_الرسالة {
    نص = 0,      // رسالة نصية
    ثنائي = 1,   // رسالة ثنائية
    نبض = 2,     // ping
    استجابة = 3, // pong
    اغلاق = 4    // close
}

/**
 * @enum حالة_الاتصال
 * @brief حالة اتصال WebSocket
 */
تعداد حالة_الاتصال {
    جاري_الاتصال = 0, // connecting
    مفتوح = 1,        // open
    جاري_الاغلاق = 2, // closing
    مغلق = 3          // closed
}

/**
 * @enum رمز_الاغلاق
 * @brief رموز إغلاق WebSocket (RFC 6455)
 */
تعداد رمز_الاغلاق {
    عادي = 1000,              // إغلاق عادي
    مغادرة = 1001,            // المضيف يغادر
    خطأ_بروتوكول = 1002,     // خطأ في البروتوكول
    بيانات_غير_مدعومة = 1003, // بيانات غير مدعومة
    لا_حالة = 1005,           // لم تُستلم حالة
    اغلاق_غير_طبيعي = 1006,  // إغلاق غير طبيعي
    بيانات_غير_صالحة = 1007, // بيانات غير صالحة UTF-8
    انتهاك_سياسة = 1008,     // انتهاك السياسة
    رسالة_كبيرة = 1009,      // الرسالة كبيرة جداً
    امتداد_ناقص = 1010,      // امتداد مطلوب
    خطأ_داخلي = 1011,        // خطأ داخلي في الخادم
    فشل_tls = 1015           // فشل TLS
}

// ============================================================================
// صنف رسالة WebSocket / WebSocket Message Class
// ============================================================================

/**
 * @class رسالة
 * @brief رسالة WebSocket
 */
صنف رسالة {
    خاص:
        متغير _نوع: نوع_الرسالة
        متغير _بيانات: مصفوفة<بايت>
    
    عام:
        /**
         * @brief إنشاء رسالة نصية
         */
        دالة ثابتة نصية(نص: نص) -> رسالة {
            متغير رسالة = رسالة()
            رسالة._نوع = نوع_الرسالة.نص
            رسالة._بيانات = نص.الى_بايتات()
            ارجع رسالة
        }
        
        /**
         * @brief إنشاء رسالة ثنائية
         */
        دالة ثابتة ثنائية(بيانات: مصفوفة<بايت>) -> رسالة {
            متغير رسالة = رسالة()
            رسالة._نوع = نوع_الرسالة.ثنائي
            رسالة._بيانات = بيانات
            ارجع رسالة
        }
        
        /**
         * @brief الحصول على النوع
         */
        دالة النوع() -> نوع_الرسالة {
            ارجع _نوع
        }
        
        /**
         * @brief الحصول على البيانات كنص
         */
        دالة كنص() -> نص {
            ارجع نص.من_بايتات(_بيانات)
        }
        
        /**
         * @brief الحصول على البيانات الخام
         */
        دالة بيانات() -> مصفوفة<بايت> {
            ارجع _بيانات
        }
        
        /**
         * @brief هل الرسالة نصية
         */
        دالة هل_نصية() -> منطقي {
            ارجع _نوع == نوع_الرسالة.نص
        }
        
        /**
         * @brief هل الرسالة ثنائية
         */
        دالة هل_ثنائية() -> منطقي {
            ارجع _نوع == نوع_الرسالة.ثنائي
        }
}

// ============================================================================
// صنف عميل WebSocket / WebSocket Client Class
// ============================================================================

/**
 * @class عميل
 * @brief عميل WebSocket للاتصال بخوادم WebSocket
 * 
 * @example
 * متغير عميل = websocket.عميل_جديد()
 * عميل.عند_رسالة((رسالة) => اطبع(رسالة.كنص()))
 * عميل.اتصل("ws://localhost:8080")
 * عميل.ارسل("مرحباً!")
 */
صنف عميل {
    خاص:
        متغير _مقبض: رقم  // Native handle
        متغير _url: نص
        متغير _حالة: حالة_الاتصال
        متغير _على_فتح: دالة()
        متغير _على_اغلاق: دالة(رقم, نص)
        متغير _على_رسالة: دالة(رسالة)
        متغير _على_خطأ: دالة(نص)
    
    عام:
        /**
         * @brief المُنشئ
         */
        دالة انشئ() {
            _مقبض = __websocket_client_create()
            _حالة = حالة_الاتصال.مغلق
        }
        
        /**
         * @brief المُدمر
         */
        دالة دمر() {
            اذا (_حالة != حالة_الاتصال.مغلق) {
                اغلق()
            }
            __websocket_client_destroy(_مقبض)
        }
        
        // ============ دوال الاتصال ============
        
        /**
         * @brief الاتصال بخادم WebSocket
         * @param url رابط الخادم (ws:// أو wss://)
         * @return صحيح إذا نجح الاتصال
         */
        دالة اتصل(url: نص) -> منطقي {
            _url = url
            _حالة = حالة_الاتصال.جاري_الاتصال
            
            متغير نتيجة = __websocket_client_connect(_مقبض, url)
            
            اذا (نتيجة) {
                _حالة = حالة_الاتصال.مفتوح
                اذا (_على_فتح != فارغ) {
                    _على_فتح()
                }
            } والا {
                _حالة = حالة_الاتصال.مغلق
            }
            
            ارجع نتيجة
        }
        
        /**
         * @brief إغلاق الاتصال
         */
        دالة اغلق(رمز: رمز_الاغلاق = رمز_الاغلاق.عادي, سبب: نص = "") {
            اذا (_حالة == حالة_الاتصال.مغلق) {
                ارجع
            }
            
            _حالة = حالة_الاتصال.جاري_الاغلاق
            __websocket_client_close(_مقبض, رمز, سبب)
            _حالة = حالة_الاتصال.مغلق
            
            اذا (_على_اغلاق != فارغ) {
                _على_اغلاق(رمز, سبب)
            }
        }
        
        /**
         * @brief التحقق من الاتصال
         */
        دالة متصل() -> منطقي {
            ارجع _حالة == حالة_الاتصال.مفتوح
        }
        
        /**
         * @brief الحصول على حالة الاتصال
         */
        دالة الحالة() -> حالة_الاتصال {
            ارجع _حالة
        }
        
        // ============ دوال الإرسال ============
        
        /**
         * @brief إرسال رسالة نصية
         * @param رسالة النص المراد إرساله
         * @return صحيح إذا نجح الإرسال
         */
        دالة ارسل(رسالة: نص) -> منطقي {
            اذا (!متصل()) {
                ارجع خطأ
            }
            ارجع __websocket_client_send_text(_مقبض, رسالة)
        }
        
        /**
         * @brief إرسال بيانات ثنائية
         * @param بيانات البيانات الثنائية
         * @return صحيح إذا نجح الإرسال
         */
        دالة ارسل_ثنائي(بيانات: مصفوفة<بايت>) -> منطقي {
            اذا (!متصل()) {
                ارجع خطأ
            }
            ارجع __websocket_client_send_binary(_مقبض, بيانات)
        }
        
        /**
         * @brief إرسال نبض (ping)
         */
        دالة نبض(بيانات: مصفوفة<بايت> = []) -> منطقي {
            اذا (!متصل()) {
                ارجع خطأ
            }
            ارجع __websocket_client_ping(_مقبض, بيانات)
        }
        
        // ============ دوال الاستقبال ============
        
        /**
         * @brief استقبال رسالة (يحظر حتى وصول رسالة)
         */
        دالة استقبل() -> رسالة {
            ارجع __websocket_client_receive(_مقبض)
        }
        
        /**
         * @brief استقبال رسالة مع مهلة
         * @param مهلة المهلة بالميلي ثانية
         */
        دالة استقبل_بمهلة(مهلة: رقم) -> رسالة? {
            ارجع __websocket_client_receive_timeout(_مقبض, مهلة)
        }
        
        /**
         * @brief التحقق من وجود رسائل
         */
        دالة يوجد_رسالة() -> منطقي {
            ارجع __websocket_client_has_message(_مقبض)
        }
        
        /**
         * @brief معالجة الرسائل الواردة
         */
        دالة استطلع() {
            __websocket_client_poll(_مقبض)
        }
        
        // ============ دوال الاستجابة ============
        
        /**
         * @brief تعيين دالة عند فتح الاتصال
         */
        دالة عند_فتح(دالة_استجابة: دالة()) {
            _على_فتح = دالة_استجابة
            __websocket_client_on_open(_مقبض, دالة_استجابة)
        }
        
        /**
         * @brief تعيين دالة عند إغلاق الاتصال
         */
        دالة عند_اغلاق(دالة_استجابة: دالة(رقم, نص)) {
            _على_اغلاق = دالة_استجابة
            __websocket_client_on_close(_مقبض, دالة_استجابة)
        }
        
        /**
         * @brief تعيين دالة عند استلام رسالة
         */
        دالة عند_رسالة(دالة_استجابة: دالة(رسالة)) {
            _على_رسالة = دالة_استجابة
            __websocket_client_on_message(_مقبض, دالة_استجابة)
        }
        
        /**
         * @brief تعيين دالة عند حدوث خطأ
         */
        دالة عند_خطأ(دالة_استجابة: دالة(نص)) {
            _على_خطأ = دالة_استجابة
            __websocket_client_on_error(_مقبض, دالة_استجابة)
        }
        
        // ============ الإعدادات ============
        
        /**
         * @brief تعيين مهلة الاستقبال
         */
        دالة عين_مهلة_استقبال(مهلة: رقم) {
            __websocket_client_set_receive_timeout(_مقبض, مهلة)
        }
        
        /**
         * @brief تعيين مهلة الإرسال
         */
        دالة عين_مهلة_ارسال(مهلة: رقم) {
            __websocket_client_set_send_timeout(_مقبض, مهلة)
        }
        
        /**
         * @brief تفعيل إعادة الاتصال التلقائي
         */
        دالة عين_اعادة_اتصال(تفعيل: منطقي, محاولات: رقم = 5, تأخير: رقم = 1000) {
            __websocket_client_set_auto_reconnect(_مقبض, تفعيل, محاولات, تأخير)
        }
        
        /**
         * @brief تعيين فترة النبض
         */
        دالة عين_فترة_نبض(فترة: رقم) {
            __websocket_client_set_ping_interval(_مقبض, فترة)
        }
        
        // ============ المعلومات ============
        
        /**
         * @brief الحصول على عنوان الخادم
         */
        دالة عنوان_الخادم() -> نص {
            ارجع __websocket_client_get_remote_address(_مقبض)
        }
        
        /**
         * @brief الحصول على URL
         */
        دالة الرابط() -> نص {
            ارجع _url
        }
        
        /**
         * @brief الحصول على آخر خطأ
         */
        دالة اخر_خطأ() -> نص {
            ارجع __websocket_client_get_last_error(_مقبض)
        }
}

// ============================================================================
// صنف اتصال WebSocket (للخادم) / WebSocket Connection Class
// ============================================================================

/**
 * @class اتصال
 * @brief اتصال عميل بالخادم
 */
صنف اتصال {
    خاص:
        متغير _مقبض: رقم
        متغير _معرف: رقم
    
    عام:
        /**
         * @brief الحصول على معرف الاتصال
         */
        دالة المعرف() -> رقم {
            ارجع _معرف
        }
        
        /**
         * @brief إرسال رسالة نصية
         */
        دالة ارسل(رسالة: نص) -> منطقي {
            ارجع __websocket_connection_send(_مقبض, رسالة)
        }
        
        /**
         * @brief إرسال بيانات ثنائية
         */
        دالة ارسل_ثنائي(بيانات: مصفوفة<بايت>) -> منطقي {
            ارجع __websocket_connection_send_binary(_مقبض, بيانات)
        }
        
        /**
         * @brief إرسال نبض
         */
        دالة نبض() -> منطقي {
            ارجع __websocket_connection_ping(_مقبض)
        }
        
        /**
         * @brief إغلاق الاتصال
         */
        دالة اغلق(رمز: رمز_الاغلاق = رمز_الاغلاق.عادي, سبب: نص = "") {
            __websocket_connection_close(_مقبض, رمز, سبب)
        }
        
        /**
         * @brief التحقق من الاتصال
         */
        دالة متصل() -> منطقي {
            ارجع __websocket_connection_is_connected(_مقبض)
        }
        
        /**
         * @brief الحصول على عنوان العميل
         */
        دالة العنوان() -> نص {
            ارجع __websocket_connection_get_address(_مقبض)
        }
        
        /**
         * @brief الحصول على منفذ العميل
         */
        دالة المنفذ() -> رقم {
            ارجع __websocket_connection_get_port(_مقبض)
        }
        
        // ============ إدارة الغرف ============
        
        /**
         * @brief الانضمام لغرفة
         */
        دالة انضم(غرفة: نص) {
            __websocket_connection_join_room(_مقبض, غرفة)
        }
        
        /**
         * @brief مغادرة غرفة
         */
        دالة غادر(غرفة: نص) {
            __websocket_connection_leave_room(_مقبض, غرفة)
        }
        
        /**
         * @brief التحقق من الوجود في غرفة
         */
        دالة في_غرفة(غرفة: نص) -> منطقي {
            ارجع __websocket_connection_is_in_room(_مقبض, غرفة)
        }
        
        /**
         * @brief الحصول على الغرف
         */
        دالة الغرف() -> مصفوفة<نص> {
            ارجع __websocket_connection_get_rooms(_مقبض)
        }
}

