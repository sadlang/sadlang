/**
 * @class خادم
 * @brief خادم WebSocket لقبول اتصالات متعددة
 * 
 * @example
 * متغير خادم = websocket.خادم_جديد()
 * 
 * خادم.عند_اتصال((عميل) => {
 *     اطبع("عميل جديد: " + عميل.المعرف())
 *     عميل.ارسل("مرحباً!")
 * })
 * 
 * خادم.عند_رسالة((عميل, رسالة) => {
 *     خادم.بث(رسالة.كنص())  // بث للجميع
 * })
 * 
 * خادم.ابدأ(8080)
 */
صنف خادم {
    خاص:
        متغير _مقبض: رقم
        متغير _منفذ: رقم
        متغير _على_اتصال: دالة(اتصال)
        متغير _على_قطع: دالة(اتصال, رقم, نص)
        متغير _على_رسالة: دالة(اتصال, رسالة)
        متغير _على_خطأ: دالة(اتصال, نص)
    
    عام:
        /**
         * @brief المُنشئ
         */
        دالة انشئ() {
            _مقبض = __websocket_server_create()
            _منفذ = 0
        }
        
        /**
         * @brief المُدمر
         */
        دالة دمر() {
            اذا (يعمل()) {
                اوقف()
            }
            __websocket_server_destroy(_مقبض)
        }
        
        // ============ التحكم بالخادم ============
        
        /**
         * @brief بدء الخادم
         * @param منفذ رقم المنفذ
         * @param عنوان العنوان (افتراضي: 0.0.0.0)
         */
        دالة ابدأ(منفذ: رقم, عنوان: نص = "0.0.0.0") -> منطقي {
            _منفذ = منفذ
            ارجع __websocket_server_start(_مقبض, منفذ, عنوان)
        }
        
        /**
         * @brief إيقاف الخادم
         */
        دالة اوقف() {
            __websocket_server_stop(_مقبض)
        }
        
        /**
         * @brief التحقق من التشغيل
         */
        دالة يعمل() -> منطقي {
            ارجع __websocket_server_is_running(_مقبض)
        }
        
        /**
         * @brief الحصول على المنفذ
         */
        دالة المنفذ() -> رقم {
            ارجع _منفذ
        }
        
        // ============ إدارة العملاء ============
        
        /**
         * @brief الحصول على عدد الاتصالات
         */
        دالة عدد_الاتصالات() -> رقم {
            ارجع __websocket_server_connection_count(_مقبض)
        }
        
        /**
         * @brief الحصول على جميع الاتصالات
         */
        دالة الاتصالات() -> مصفوفة<اتصال> {
            ارجع __websocket_server_get_connections(_مقبض)
        }
        
        /**
         * @brief الحصول على اتصال بالمعرف
         */
        دالة اتصال(معرف: رقم) -> اتصال? {
            ارجع __websocket_server_get_connection(_مقبض, معرف)
        }
        
        /**
         * @brief إغلاق اتصال
         */
        دالة اغلق_اتصال(معرف: رقم, رمز: رمز_الاغلاق = رمز_الاغلاق.عادي, سبب: نص = "") {
            __websocket_server_close_connection(_مقبض, معرف, رمز, سبب)
        }
        
        /**
         * @brief إغلاق جميع الاتصالات
         */
        دالة اغلق_الجميع(رمز: رمز_الاغلاق = رمز_الاغلاق.مغادرة, سبب: نص = "الخادم يتوقف") {
            __websocket_server_close_all(_مقبض, رمز, سبب)
        }
        
        // ============ البث ============
        
        /**
         * @brief بث رسالة نصية للجميع
         */
        دالة بث(رسالة: نص) {
            __websocket_server_broadcast(_مقبض, رسالة)
        }
        
        /**
         * @brief بث بيانات ثنائية للجميع
         */
        دالة بث_ثنائي(بيانات: مصفوفة<بايت>) {
            __websocket_server_broadcast_binary(_مقبض, بيانات)
        }
        
        /**
         * @brief بث لغرفة محددة
         */
        دالة بث_لغرفة(غرفة: نص, رسالة: نص) {
            __websocket_server_broadcast_to_room(_مقبض, غرفة, رسالة)
        }
        
        /**
         * @brief بث ثنائي لغرفة محددة
         */
        دالة بث_ثنائي_لغرفة(غرفة: نص, بيانات: مصفوفة<بايت>) {
            __websocket_server_broadcast_binary_to_room(_مقبض, غرفة, بيانات)
        }
        
        /**
         * @brief بث باستثناء اتصال
         */
        دالة بث_ما_عدا(رسالة: نص, استثناء: رقم) {
            __websocket_server_broadcast_except(_مقبض, رسالة, استثناء)
        }
        
        // ============ إدارة الغرف ============
        
        /**
         * @brief الحصول على قائمة الغرف
         */
        دالة الغرف() -> مصفوفة<نص> {
            ارجع __websocket_server_get_rooms(_مقبض)
        }
        
        /**
         * @brief الحصول على اتصالات غرفة
         */
        دالة اتصالات_الغرفة(غرفة: نص) -> مصفوفة<اتصال> {
            ارجع __websocket_server_get_room_connections(_مقبض, غرفة)
        }
        
        /**
         * @brief الحصول على حجم الغرفة
         */
        دالة حجم_الغرفة(غرفة: نص) -> رقم {
            ارجع __websocket_server_get_room_size(_مقبض, غرفة)
        }
        
        // ============ دوال الاستجابة ============
        
        /**
         * @brief تعيين دالة عند اتصال عميل جديد
         */
        دالة عند_اتصال(دالة_استجابة: دالة(اتصال)) {
            _على_اتصال = دالة_استجابة
            __websocket_server_on_connection(_مقبض, دالة_استجابة)
        }
        
        /**
         * @brief تعيين دالة عند قطع اتصال عميل
         */
        دالة عند_قطع(دالة_استجابة: دالة(اتصال, رقم, نص)) {
            _على_قطع = دالة_استجابة
            __websocket_server_on_disconnect(_مقبض, دالة_استجابة)
        }
        
        /**
         * @brief تعيين دالة عند استلام رسالة
         */
        دالة عند_رسالة(دالة_استجابة: دالة(اتصال, رسالة)) {
            _على_رسالة = دالة_استجابة
            __websocket_server_on_message(_مقبض, دالة_استجابة)
        }
        
        /**
         * @brief تعيين دالة عند حدوث خطأ
         */
        دالة عند_خطأ(دالة_استجابة: دالة(اتصال, نص)) {
            _على_خطأ = دالة_استجابة
            __websocket_server_on_error(_مقبض, دالة_استجابة)
        }
        
        // ============ الإعدادات ============
        
        /**
         * @brief تعيين أقصى عدد اتصالات
         */
        دالة عين_اقصى_اتصالات(عدد: رقم) {
            __websocket_server_set_max_connections(_مقبض, عدد)
        }
        
        /**
         * @brief تعيين فترة النبض
         */
        دالة عين_فترة_نبض(فترة: رقم) {
            __websocket_server_set_ping_interval(_مقبض, فترة)
        }
        
        /**
         * @brief تعيين مهلة الاتصال
         */
        دالة عين_مهلة_اتصال(مهلة: رقم) {
            __websocket_server_set_connection_timeout(_مقبض, مهلة)
        }
}

