/**
 * @brief اتصال سريع بخادم WebSocket
 * @param url رابط الخادم
 * @param على_رسالة دالة معالجة الرسائل
 */
دالة اتصل(url: نص, على_رسالة: دالة(رسالة)) -> عميل {
    متغير عميل = عميل_جديد()
    عميل.عند_رسالة(على_رسالة)
    عميل.اتصل(url)
    ارجع عميل
}

