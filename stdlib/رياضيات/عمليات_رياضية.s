# الجذر التربيعي (تقريبي)
دالة عشري جذر_تربيعي(العدد: عشري)
    إذا (العدد < 0.0)
        إرجاع 0.0
    نهاية
    إذا (العدد == 0.0)
        إرجاع 0.0
    نهاية
    عشري تخمين = العدد / 2.0
    عشري السابق = 0.0
    بينما (قيمة_مطلقة_عشري(تخمين - السابق) > 0.00001)
        السابق = تخمين
        تخمين = (تخمين + العدد / تخمين) / 2.0
    نهاية
    إرجاع تخمين
نهاية

