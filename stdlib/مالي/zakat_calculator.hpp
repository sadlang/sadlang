/**
 * أسعار المعادن الثمينة
 */
struct أسعار_المعادن {
    double سعر_جرام_الذهب = 250.0;   // ريال/جرام (تقريبي)
    double سعر_جرام_الفضة = 3.5;     // ريال/جرام (تقريبي)
    std::string تاريخ_التحديث;
};

/**
 * إعدادات الحاسبة
 */
struct إعدادات_زكاة {
    // النصاب
    double نصاب_الذهب_جرام = 85.0;   // 85 جرام ذهب
    double نصاب_الفضة_جرام = 595.0;  // 595 جرام فضة
    
    // نسب الزكاة
    double نسبة_زكاة_المال = 2.5;    // 2.5%
    double نسبة_زكاة_الذهب = 2.5;    // 2.5%
    double نسبة_زكاة_الأسهم = 2.5;   // 2.5%
    double نسبة_زكاة_التجارة = 2.5;  // 2.5%
    double نسبة_زكاة_الزروع_سقي = 5.0;      // 5% إذا سُقيت بآلة
    double نسبة_زكاة_الزروع_مطر = 10.0;     // 10% إذا سُقيت بالمطر
    
    // أسعار المعادن
    أسعار_المعادن الأسعار;
    
    // استخدام نصاب الذهب أو الفضة
    bool استخدم_نصاب_الذهب = true;  // الأحوط للفقير
};

// ═══════════════════════════════════════════════════════════════════════════════
