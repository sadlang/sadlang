/**
 * تفصيل زكاة أصل واحد
 */
struct تفصيل_زكاة {
    نوع_أصل_زكاة النوع;
    std::string الوصف;
    double القيمة;
    double النسبة;       // نسبة الزكاة (2.5%, 5%, 10%, ...)
    double مبلغ_الزكاة;
    std::string ملاحظات;
};

/**
 * نتيجة حساب الزكاة الإجمالية
 */
struct نتيجة_زكاة {
    // هل تجب الزكاة؟
    bool تجب_الزكاة;
    std::string السبب;
    
    // المجاميع
    double إجمالي_الأصول;
    double النصاب;
    double إجمالي_الزكاة;
    
    // التفاصيل
    std::vector<تفصيل_زكاة> التفاصيل;
    
    // الخصومات
    double الديون_المستحقة = 0;    // ديون عليك
    double النفقات_الأساسية = 0;   // نفقات ضرورية
    
    // المبلغ الصافي
    double المبلغ_الصافي_للزكاة;
    
    // تاريخ الحساب
    std::string تاريخ_الحساب;
};

