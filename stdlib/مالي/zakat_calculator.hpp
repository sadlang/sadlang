/**
 * نوع الأصل الخاضع للزكاة
 */
enum class نوع_أصل_زكاة {
    نقد,           // نقود سائلة
    ذهب,           // ذهب (مجوهرات للتجارة أو ادخار)
    فضة,           // فضة
    أسهم,          // أسهم شركات
    عقارات_تجارة,  // عقارات للتجارة (لا للسكن)
    بضائع,         // بضائع تجارية
    ديون_مرجوة,    // ديون يُتوقع سدادها
    زروع,          // محاصيل زراعية
    أنعام          // إبل، بقر، غنم
};

/**
 * أصل خاضع للزكاة
 */
struct أصل_زكاة {
    نوع_أصل_زكاة النوع;
    std::string الوصف;
    double القيمة;              // بالريال السعودي
    double الكمية = 0;          // للذهب (جرام) أو الأنعام (عدد)
    bool مر_عليه_الحول = true; // هل مر عليه سنة؟
    std::string تاريخ_الملكية;
};

// ═══════════════════════════════════════════════════════════════════════════════
