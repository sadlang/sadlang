/**
 * 💰 حاسبة الزكاة
 * 
 * حساب زكاة المال والأصول المختلفة
 */
class حاسبة_زكاة {
public:
    /**
     * إنشاء الحاسبة
     */
    explicit حاسبة_زكاة(const إعدادات_زكاة& إعدادات = إعدادات_زكاة())
        : الإعدادات_(إعدادات) {}
    
    /**
     * تحديث أسعار المعادن
     */
    void حدّث_الأسعار(double سعر_الذهب, double سعر_الفضة) {
        الإعدادات_.الأسعار.سعر_جرام_الذهب = سعر_الذهب;
        الإعدادات_.الأسعار.سعر_جرام_الفضة = سعر_الفضة;
        
        auto الآن = std::chrono::system_clock::now();
        auto وقت = std::chrono::system_clock::to_time_t(الآن);
        std::ostringstream تاريخ;
        تاريخ << std::put_time(std::localtime(&وقت), "%Y-%m-%d");
        الإعدادات_.الأسعار.تاريخ_التحديث = تاريخ.str();
    }
    
    /**
     * حساب النصاب بالريال
     */
    double النصاب_بالريال() const {
        if (الإعدادات_.استخدم_نصاب_الذهب) {
            return الإعدادات_.نصاب_الذهب_جرام * الإعدادات_.الأسعار.سعر_جرام_الذهب;
        }
        return الإعدادات_.نصاب_الفضة_جرام * الإعدادات_.الأسعار.سعر_جرام_الفضة;
    }
    
    /**
     * حساب زكاة مبلغ نقدي
     */
    double زكاة_مبلغ(double المبلغ) const {
        if (المبلغ < النصاب_بالريال()) {
            return 0;
        }
        return المبلغ * (الإعدادات_.نسبة_زكاة_المال / 100.0);
    }
    
    /**
     * حساب زكاة الذهب
     */
    double زكاة_ذهب(double الكمية_جرام) const {
        if (الكمية_جرام < الإعدادات_.نصاب_الذهب_جرام) {
            return 0;
        }
        double القيمة = الكمية_جرام * الإعدادات_.الأسعار.سعر_جرام_الذهب;
        return القيمة * (الإعدادات_.نسبة_زكاة_الذهب / 100.0);
    }
    
    /**
     * حساب زكاة شاملة لجميع الأصول
     */
    نتيجة_زكاة احسب(const std::vector<أصل_زكاة>& الأصول, 
                    double الديون = 0,
                    double النفقات = 0) const {
        نتيجة_زكاة نتيجة;
        
        // تاريخ الحساب
        auto الآن = std::chrono::system_clock::now();
        auto وقت = std::chrono::system_clock::to_time_t(الآن);
        std::ostringstream تاريخ;
        تاريخ << std::put_time(std::localtime(&وقت), "%Y-%m-%d %H:%M:%S");
        نتيجة.تاريخ_الحساب = تاريخ.str();
        
        // النصاب
        نتيجة.النصاب = النصاب_بالريال();
        
        // حساب كل أصل
        نتيجة.إجمالي_الأصول = 0;
        نتيجة.إجمالي_الزكاة = 0;
        
        for (const auto& أصل : الأصول) {
            تفصيل_زكاة تفصيل;
            تفصيل.النوع = أصل.النوع;
            تفصيل.الوصف = أصل.الوصف;
            تفصيل.القيمة = أصل.القيمة;
            
            // حساب الزكاة حسب النوع
            switch (أصل.النوع) {
                case نوع_أصل_زكاة::نقد:
                case نوع_أصل_زكاة::أسهم:
                case نوع_أصل_زكاة::عقارات_تجارة:
                case نوع_أصل_زكاة::بضائع:
                case نوع_أصل_زكاة::ديون_مرجوة:
                    تفصيل.النسبة = الإعدادات_.نسبة_زكاة_المال;
                    تفصيل.مبلغ_الزكاة = أصل.القيمة * (تفصيل.النسبة / 100.0);
                    break;
                    
                case نوع_أصل_زكاة::ذهب:
                    تفصيل.النسبة = الإعدادات_.نسبة_زكاة_الذهب;
                    if (أصل.الكمية < الإعدادات_.نصاب_الذهب_جرام) {
                        تفصيل.مبلغ_الزكاة = 0;
                        تفصيل.ملاحظات = "لم يبلغ النصاب (85 جرام)";
                    }
                    else {
                        تفصيل.مبلغ_الزكاة = أصل.القيمة * (تفصيل.النسبة / 100.0);
                    }
                    break;
                    
                case نوع_أصل_زكاة::فضة:
                    تفصيل.النسبة = الإعدادات_.نسبة_زكاة_الذهب;
                    if (أصل.الكمية < الإعدادات_.نصاب_الفضة_جرام) {
                        تفصيل.مبلغ_الزكاة = 0;
                        تفصيل.ملاحظات = "لم يبلغ النصاب (595 جرام)";
                    }
                    else {
                        تفصيل.مبلغ_الزكاة = أصل.القيمة * (تفصيل.النسبة / 100.0);
                    }
                    break;
                    
                case نوع_أصل_زكاة::زروع:
                    // افتراض السقي بآلة
                    تفصيل.النسبة = الإعدادات_.نسبة_زكاة_الزروع_سقي;
                    تفصيل.مبلغ_الزكاة = أصل.القيمة * (تفصيل.النسبة / 100.0);
                    تفصيل.ملاحظات = "5% للسقي بآلة، 10% للمطر";
                    break;
                    
                case نوع_أصل_زكاة::أنعام:
                    // زكاة الأنعام لها جدول خاص
                    تفصيل.النسبة = 0;
                    تفصيل.مبلغ_الزكاة = 0;
                    تفصيل.ملاحظات = "زكاة الأنعام لها جدول خاص، راجع فقيهاً";
                    break;
            }
            
            if (!أصل.مر_عليه_الحول) {
                تفصيل.مبلغ_الزكاة = 0;
                تفصيل.ملاحظات = "لم يمر عليه الحول";
            }
            
            نتيجة.إجمالي_الأصول += أصل.القيمة;
            نتيجة.إجمالي_الزكاة += تفصيل.مبلغ_الزكاة;
            نتيجة.التفاصيل.push_back(تفصيل);
        }
        
        // الخصومات
        نتيجة.الديون_المستحقة = الديون;
        نتيجة.النفقات_الأساسية = النفقات;
        
        // المبلغ الصافي
        double المبلغ_بعد_الخصم = نتيجة.إجمالي_الأصول - الديون - النفقات;
        
        // هل تجب الزكاة؟
        if (المبلغ_بعد_الخصم >= نتيجة.النصاب) {
            نتيجة.تجب_الزكاة = true;
            نتيجة.السبب = "بلغ النصاب (" + std::to_string(نتيجة.النصاب) + " ريال)";
            نتيجة.المبلغ_الصافي_للزكاة = نتيجة.إجمالي_الزكاة;
        }
        else {
            نتيجة.تجب_الزكاة = false;
            نتيجة.السبب = "لم يبلغ النصاب";
            نتيجة.المبلغ_الصافي_للزكاة = 0;
        }
        
        return نتيجة;
    }
    
    /**
     * طباعة تقرير الزكاة
     */
    std::string تقرير_زكاة(const نتيجة_زكاة& نتيجة) const {
        std::ostringstream ss;
        
        ss << "╔══════════════════════════════════════════════════════════╗\n";
        ss << "║           تقرير حساب الزكاة                              ║\n";
        ss << "║           " << نتيجة.تاريخ_الحساب << "                    ║\n";
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        ss << "║                                                          ║\n";
        ss << "║  النصاب: " << std::fixed << std::setprecision(2) 
           << نتيجة.النصاب << " ريال\n";
        ss << "║                                                          ║\n";
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        ss << "║  الأصول:                                                 ║\n";
        ss << "║  ─────────                                               ║\n";
        
        for (const auto& ت : نتيجة.التفاصيل) {
            ss << "║  • " << ت.الوصف << ": " << ت.القيمة << " ريال";
            if (ت.مبلغ_الزكاة > 0) {
                ss << " → زكاة: " << ت.مبلغ_الزكاة << " ريال";
            }
            ss << "\n";
            if (!ت.ملاحظات.empty()) {
                ss << "║    (" << ت.ملاحظات << ")\n";
            }
        }
        
        ss << "║                                                          ║\n";
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        ss << "║  إجمالي الأصول:      " << نتيجة.إجمالي_الأصول << " ريال\n";
        
        if (نتيجة.الديون_المستحقة > 0) {
            ss << "║  - الديون:           " << نتيجة.الديون_المستحقة << " ريال\n";
        }
        
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        
        if (نتيجة.تجب_الزكاة) {
            ss << "║  ✅ تجب الزكاة                                          ║\n";
            ss << "║  💰 مبلغ الزكاة: " << نتيجة.المبلغ_الصافي_للزكاة << " ريال\n";
        }
        else {
            ss << "║  ❌ لا تجب الزكاة                                        ║\n";
            ss << "║  السبب: " << نتيجة.السبب << "\n";
        }
        
        ss << "║                                                          ║\n";
        ss << "╚══════════════════════════════════════════════════════════╝\n";
        ss << "\n⚠️ هذا الحساب تقريبي. يُنصح بمراجعة فقيه للتأكد.\n";
        
        return ss.str();
    }
    
private:
    إعدادات_زكاة الإعدادات_;
};

