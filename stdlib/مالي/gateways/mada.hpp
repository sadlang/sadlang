/**
 * إعدادات بوابة مدى
 */
struct إعدادات_مدى {
    // بيانات التاجر
    std::string معرف_التاجر;
    std::string مفتاح_api;
    std::string سر_api;
    
    // بيانات المحطة
    std::string معرف_المحطة;
    
    // البيئة
    bool بيئة_اختبار = true;
    
    // روابط
    std::string رابط_api() const {
        if (بيئة_اختبار) {
            return "https://test.mada.com.sa/api/v1";
        }
        return "https://api.mada.com.sa/v1";
    }
    
    // الرسوم (نسبة مئوية)
    double نسبة_الرسوم = 1.5;  // 1.5% للمعاملات المحلية
    double الحد_الأدنى_للرسوم = 0.5;  // 0.5 ريال
};

// ═══════════════════════════════════════════════════════════════════════════════
