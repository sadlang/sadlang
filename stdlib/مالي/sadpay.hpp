/**
 * إعدادات صَدفع
 */
struct إعدادات_صدفع {
    // بيانات التاجر
    std::string معرف_التاجر;
    std::string اسم_التاجر;
    std::string سر_api;
    
    // البيئة
    bool بيئة_اختبار = true;
    
    // خيارات الفحص
    bool فحص_شرعي_تلقائي = true;
    bool رفض_غير_الحلال = true;
    
    // إعدادات البوابات
    std::map<بوابة_دفع, std::map<std::string, std::string>> إعدادات_البوابات;
};

/**
 * 💰 نظام صَدفع
 * 
 * نظام الدفع الإسلامي الموحد
 */
class صَدفع {
public:
    /**
     * إنشاء نظام صدفع
     */
    explicit صَدفع(const إعدادات_صدفع& إعدادات)
        : الإعدادات_(إعدادات) {
        // تهيئة البوابات
        هيئ_البوابات();
    }
    
    /**
     * إنشاء معاملة دفع جديدة
     */
    نتيجة_معاملة أنشئ(const طلب_دفع& طلب) {
        نتيجة_معاملة نتيجة;
        
        // 1. الفحص الشرعي (إذا كان مُفعّلاً)
        if (الإعدادات_.فحص_شرعي_تلقائي || طلب.فحص_شرعي) {
            auto فحص = افحص_شرعياً(طلب);
            if (!فحص.متوافق && الإعدادات_.رفض_غير_الحلال) {
                نتيجة.الحالة = حالة_معاملة::مرفوضة;
                نتيجة.متوافق_شرعياً = false;
                نتيجة.ملاحظات_شرعية = فحص.ملاحظات;
                نتيجة.رسالة_الخطأ = "المعاملة غير متوافقة مع الشريعة الإسلامية";
                return نتيجة;
            }
            نتيجة.متوافق_شرعياً = فحص.متوافق;
            نتيجة.ملاحظات_شرعية = فحص.ملاحظات;
        }
        
        // 2. اختيار البوابة المناسبة
        auto بوابة = اختر_بوابة(طلب);
        if (!بوابة) {
            نتيجة.الحالة = حالة_معاملة::مرفوضة;
            نتيجة.رسالة_الخطأ = "لا توجد بوابة دفع متاحة";
            return نتيجة;
        }
        
        // 3. إنشاء جلسة الدفع
        نتيجة = بوابة->أنشئ_جلسة(طلب);
        
        // 4. تسجيل المعاملة
        سجل_معاملة(نتيجة);
        
        return نتيجة;
    }
    
    /**
     * التحقق من حالة معاملة
     */
    نتيجة_معاملة تحقق(const std::string& معرف) {
        // البحث عن المعاملة في السجلات
        auto it = المعاملات_.find(معرف);
        if (it == المعاملات_.end()) {
            نتيجة_معاملة نتيجة;
            نتيجة.الحالة = حالة_معاملة::مرفوضة;
            نتيجة.رسالة_الخطأ = "معاملة غير موجودة";
            return نتيجة;
        }
        
        return it->second;
    }
    
    /**
     * استرجاع معاملة (Refund)
     */
    نتيجة_معاملة استرجع(const std::string& معرف, double المبلغ = 0) {
        auto معاملة = تحقق(معرف);
        
        if (معاملة.الحالة != حالة_معاملة::ناجحة) {
            نتيجة_معاملة نتيجة;
            نتيجة.الحالة = حالة_معاملة::مرفوضة;
            نتيجة.رسالة_الخطأ = "لا يمكن استرجاع معاملة غير ناجحة";
            return نتيجة;
        }
        
        // استرجاع من البوابة الأصلية
        // (يتم التنفيذ في البوابات المحددة)
        
        معاملة.الحالة = حالة_معاملة::مُسترجعة;
        المعاملات_[معرف] = معاملة;
        
        return معاملة;
    }
    
    /**
     * الحصول على قائمة المعاملات
     */
    std::vector<نتيجة_معاملة> المعاملات() const {
        std::vector<نتيجة_معاملة> قائمة;
        for (const auto& [_, م] : المعاملات_) {
            قائمة.push_back(م);
        }
        return قائمة;
    }
    
private:
    إعدادات_صدفع الإعدادات_;
    std::map<بوابة_دفع, std::unique_ptr<واجهة_بوابة>> البوابات_;
    std::map<std::string, نتيجة_معاملة> المعاملات_;
    
    /**
     * نتيجة الفحص الشرعي
     */
    struct نتيجة_فحص_شرعي {
        bool متوافق;
        std::vector<std::string> ملاحظات;
    };
    
    /**
     * تهيئة البوابات
     */
    void هيئ_البوابات() {
        // يتم تهيئة كل بوابة حسب إعداداتها
        // (التنفيذ في الملفات المنفصلة لكل بوابة)
    }
    
    /**
     * الفحص الشرعي
     */
    نتيجة_فحص_شرعي افحص_شرعياً(const طلب_دفع& طلب) {
        نتيجة_فحص_شرعي نتيجة;
        نتيجة.متوافق = true;
        
        // فحص كل عنصر
        for (const auto& عنصر : طلب.العناصر) {
            if (!عنصر.حلال) {
                نتيجة.متوافق = false;
                نتيجة.ملاحظات.push_back("العنصر '" + عنصر.الاسم + "' غير حلال");
            }
        }
        
        // فحص الوصف بحثاً عن كلمات مشبوهة
        std::vector<std::string> كلمات_محظورة = {
            "فائدة", "ربا", "قمار", "يانصيب", "خمر", "كحول"
        };
        
        for (const auto& كلمة : كلمات_محظورة) {
            if (طلب.الوصف.find(كلمة) != std::string::npos) {
                نتيجة.متوافق = false;
                نتيجة.ملاحظات.push_back("الوصف يحتوي على كلمة مشبوهة: " + كلمة);
            }
        }
        
        if (نتيجة.متوافق) {
            نتيجة.ملاحظات.push_back("✅ المعاملة متوافقة مع الشريعة الإسلامية");
        }
        
        return نتيجة;
    }
    
    /**
     * اختيار البوابة المناسبة
     */
    واجهة_بوابة* اختر_بوابة(const طلب_دفع& طلب) {
        // محاولة إيجاد بوابة متاحة
        for (auto بوابة : طلب.البوابات_المسموحة) {
            auto it = البوابات_.find(بوابة);
            if (it != البوابات_.end() && it->second->متاحة()) {
                return it->second.get();
            }
        }
        
        // إذا لم تُحدد بوابات، جرب أي بوابة متاحة
        if (طلب.البوابات_المسموحة.empty()) {
            for (auto& [_, بوابة] : البوابات_) {
                if (بوابة->متاحة()) {
                    return بوابة.get();
                }
            }
        }
        
        return nullptr;
    }
    
    /**
     * تسجيل المعاملة
     */
    void سجل_معاملة(const نتيجة_معاملة& معاملة) {
        if (!معاملة.معرف_المعاملة.empty()) {
            المعاملات_[معاملة.معرف_المعاملة] = معاملة;
        }
    }
};

