/**
 * حالة المعاملة
 */
enum class حالة_معاملة {
    معلقة,         // في انتظار الدفع
    قيد_المعالجة,  // يُعالج الدفع
    ناجحة,         // تمت بنجاح
    مرفوضة,        // رُفضت من البوابة
    مُلغاة,        // ألغاها المستخدم
    مُسترجعة       // تم استرجاع المبلغ
};

/**
 * نص الحالة بالعربي
 */
inline std::string نص_الحالة(حالة_معاملة ح) {
    switch (ح) {
        case حالة_معاملة::معلقة: return "⏳ معلقة";
        case حالة_معاملة::قيد_المعالجة: return "⚙️ قيد المعالجة";
        case حالة_معاملة::ناجحة: return "✅ ناجحة";
        case حالة_معاملة::مرفوضة: return "❌ مرفوضة";
        case حالة_معاملة::مُلغاة: return "🚫 مُلغاة";
        case حالة_معاملة::مُسترجعة: return "↩️ مُسترجعة";
    }
    return "❓ غير معروفة";
}

