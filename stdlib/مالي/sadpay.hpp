enum class عملة {
    SAR,    // ريال سعودي
    AED,    // درهم إماراتي
    KWD,    // دينار كويتي
    QAR,    // ريال قطري
    BHD,    // دينار بحريني
    OMR,    // ريال عماني
    EGP,    // جنيه مصري
    USD,    // دولار أمريكي
    EUR,    // يورو
    GBP     // جنيه إسترليني
};

/**
 * تحويل العملة لنص
 */
