/**
 * إعدادات المرابحة
 */
struct إعدادات_مرابحة {
    // نسب الربح حسب النوع
    std::map<نوع_مرابحة, double> نسب_الربح = {
        { نوع_مرابحة::سلع_استهلاكية, 15.0 },  // 15%
        { نوع_مرابحة::سيارات, 12.0 },          // 12%
        { نوع_مرابحة::عقارات, 8.0 },           // 8%
        { نوع_مرابحة::معدات, 10.0 },           // 10%
        { نوع_مرابحة::تعليم, 5.0 }             // 5%
    };
    
    // الحدود
    double نسبة_الدفعة_الأولى_الدنيا = 10.0;   // 10% كحد أدنى
    int الحد_الأقصى_للأشهر = 60;              // 5 سنوات
    double نسبة_القسط_من_الدخل = 33.0;        // القسط لا يتجاوز 33% من الدخل
};

/**
 * 💰 حاسبة المرابحة
 * 
 * حساب تفاصيل عقد المرابحة الشرعي
 */
class حاسبة_مرابحة {
public:
    /**
     * إنشاء الحاسبة
     */
    explicit حاسبة_مرابحة(const إعدادات_مرابحة& إعدادات = إعدادات_مرابحة())
        : الإعدادات_(إعدادات) {}
    
    /**
     * حساب تفاصيل المرابحة
     */
    عقد_مرابحة احسب(const طلب_مرابحة& طلب) const {
        عقد_مرابحة عقد;
        
        // معلومات السلعة
        عقد.اسم_السلعة = طلب.اسم_السلعة;
        عقد.وصف_السلعة = طلب.وصف_السلعة;
        عقد.النوع = طلب.النوع;
        
        // الحسابات المالية
        عقد.تكلفة_الشراء = طلب.سعر_السلعة;
        عقد.نسبة_الربح = الإعدادات_.نسب_الربح.at(طلب.النوع);
        عقد.مبلغ_الربح = عقد.تكلفة_الشراء * (عقد.نسبة_الربح / 100.0);
        عقد.السعر_النهائي = عقد.تكلفة_الشراء + عقد.مبلغ_الربح;
        
        // التقسيط
        عقد.الدفعة_الأولى = طلب.الدفعة_الأولى;
        عقد.المبلغ_المُقسَّط = عقد.السعر_النهائي - عقد.الدفعة_الأولى;
        عقد.عدد_الأقساط = طلب.عدد_الأشهر;
        عقد.قيمة_القسط = عقد.المبلغ_المُقسَّط / عقد.عدد_الأقساط;
        
        // معلومات العميل
        عقد.العميل = طلب.العميل;
        
        // توليد جدول الأقساط
        عقد.جدول_الأقساط = ولّد_جدول_أقساط(عقد);
        
        return عقد;
    }
    
    /**
     * التحقق من أهلية العميل
     */
    struct نتيجة_أهلية {
        bool مؤهل;
        double الحد_الأقصى_للتمويل;
        std::vector<std::string> الملاحظات;
    };
    
    نتيجة_أهلية تحقق_الأهلية(const طلب_مرابحة& طلب) const {
        نتيجة_أهلية نتيجة;
        نتيجة.مؤهل = true;
        
        // حساب الدخل المتاح للأقساط
        double الدخل_المتاح = طلب.الدخل_الشهري - طلب.الالتزامات_الشهرية;
        double الحد_الأقصى_للقسط = طلب.الدخل_الشهري * (الإعدادات_.نسبة_القسط_من_الدخل / 100.0);
        
        // حساب القسط المتوقع
        double السعر_النهائي = طلب.سعر_السلعة * (1 + الإعدادات_.نسب_الربح.at(طلب.النوع) / 100.0);
        double المبلغ_المُقسَّط = السعر_النهائي - طلب.الدفعة_الأولى;
        double القسط_المتوقع = المبلغ_المُقسَّط / طلب.عدد_الأشهر;
        
        // التحقق من القسط
        if (القسط_المتوقع > الحد_الأقصى_للقسط) {
            نتيجة.مؤهل = false;
            نتيجة.الملاحظات.push_back(
                "القسط (" + std::to_string(القسط_المتوقع) + " ريال) يتجاوز " +
                std::to_string(الإعدادات_.نسبة_القسط_من_الدخل) + "% من الدخل"
            );
        }
        
        // التحقق من الدفعة الأولى
        double نسبة_الدفعة = (طلب.الدفعة_الأولى / طلب.سعر_السلعة) * 100;
        if (نسبة_الدفعة < الإعدادات_.نسبة_الدفعة_الأولى_الدنيا) {
            نتيجة.الملاحظات.push_back(
                "الدفعة الأولى يجب ألا تقل عن " + 
                std::to_string(الإعدادات_.نسبة_الدفعة_الأولى_الدنيا) + "%"
            );
        }
        
        // حساب الحد الأقصى للتمويل
        نتيجة.الحد_الأقصى_للتمويل = الحد_الأقصى_للقسط * طلب.عدد_الأشهر;
        
        return نتيجة;
    }
    
    /**
     * طباعة ملخص العقد
     */
    std::string ملخص_العقد(const عقد_مرابحة& عقد) const {
        std::ostringstream ss;
        
        ss << "╔══════════════════════════════════════════════════════════╗\n";
        ss << "║           عقد مرابحة - تمويل إسلامي                      ║\n";
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        ss << "║                                                          ║\n";
        ss << "║  السلعة: " << عقد.اسم_السلعة << "\n";
        ss << "║                                                          ║\n";
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        ss << "║  التفاصيل المالية (شفافية كاملة):                        ║\n";
        ss << "║  ─────────────────────────────────                       ║\n";
        ss << "║  تكلفة الشراء:     " << std::fixed << std::setprecision(2) 
           << عقد.تكلفة_الشراء << " ريال\n";
        ss << "║  نسبة الربح:       " << عقد.نسبة_الربح << "%\n";
        ss << "║  مبلغ الربح:       " << عقد.مبلغ_الربح << " ريال\n";
        ss << "║  ─────────────────────────────────                       ║\n";
        ss << "║  السعر النهائي:    " << عقد.السعر_النهائي << " ريال\n";
        ss << "╠══════════════════════════════════════════════════════════╣\n";
        ss << "║  التقسيط:                                                ║\n";
        ss << "║  ─────────                                               ║\n";
        ss << "║  الدفعة الأولى:    " << عقد.الدفعة_الأولى << " ريال\n";
        ss << "║  المبلغ المُقسَّط:  " << عقد.المبلغ_المُقسَّط << " ريال\n";
        ss << "║  عدد الأقساط:      " << عقد.عدد_الأقساط << " شهر\n";
        ss << "║  قيمة القسط:       " << عقد.قيمة_القسط << " ريال/شهر\n";
        ss << "╚══════════════════════════════════════════════════════════╝\n";
        
        return ss.str();
    }
    
private:
    إعدادات_مرابحة الإعدادات_;
    
    /**
     * توليد جدول الأقساط
     */
    std::vector<قسط> ولّد_جدول_أقساط(const عقد_مرابحة& عقد) const {
        std::vector<قسط> جدول;
        
        auto الآن = std::chrono::system_clock::now();
        
        for (int i = 1; i <= عقد.عدد_الأقساط; i++) {
            قسط ق;
            ق.الرقم = i;
            ق.المبلغ = عقد.قيمة_القسط;
            
            // حساب تاريخ الاستحقاق (شهر من الآن + i أشهر)
            auto استحقاق = الآن + std::chrono::hours(24 * 30 * i);
            auto وقت = std::chrono::system_clock::to_time_t(استحقاق);
            std::ostringstream تاريخ;
            تاريخ << std::put_time(std::localtime(&وقت), "%Y-%m-%d");
            ق.تاريخ_الاستحقاق = تاريخ.str();
            
            جدول.push_back(ق);
        }
        
        return جدول;
    }
};

