/**
 * نوع المرابحة
 */
enum class نوع_مرابحة {
    سلع_استهلاكية,   // أجهزة، أثاث، إلكترونيات
    سيارات,          // تمويل السيارات
    عقارات,          // تمويل العقارات
    معدات,           // معدات العمل
    تعليم            // تمويل التعليم
};

/**
 * حالة عقد المرابحة
 */
enum class حالة_مرابحة {
    قيد_الدراسة,    // الطلب قيد المراجعة
    معتمد,          // تم الاعتماد
    نشط,            // جاري السداد
    مُعلَّق,        // متأخر في السداد
    مُكتمل,         // تم السداد بالكامل
    مُلغى           // تم إلغاء العقد
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              تفاصيل القسط
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * قسط شهري
 */
struct قسط {
    int الرقم;                        // رقم القسط (1, 2, 3, ...)
    double المبلغ;                    // مبلغ القسط
    std::string تاريخ_الاستحقاق;     // تاريخ الاستحقاق
    bool مدفوع = false;              // هل تم دفعه؟
    std::string تاريخ_الدفع;         // تاريخ الدفع الفعلي
    std::string معرف_المعاملة;       // معرف معاملة الدفع
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              عقد المرابحة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * عقد مرابحة
 */
struct عقد_مرابحة {
    // معلومات العقد
    std::string رقم_العقد;
    نوع_مرابحة النوع;
    حالة_مرابحة الحالة = حالة_مرابحة::قيد_الدراسة;
    
    // معلومات السلعة
    std::string اسم_السلعة;
    std::string وصف_السلعة;
    std::string المورد;              // من أين اشترى البنك السلعة
    
    // معلومات مالية (شفافية كاملة)
    double تكلفة_الشراء;            // كم دفع البنك للسلعة
    double نسبة_الربح;              // نسبة ربح البنك
    double مبلغ_الربح;              // قيمة الربح
    double السعر_النهائي;           // التكلفة + الربح
    
    // معلومات التقسيط
    double الدفعة_الأولى = 0;       // إن وُجدت
    double المبلغ_المُقسَّط;         // السعر النهائي - الدفعة الأولى
    int عدد_الأقساط;
    double قيمة_القسط;
    
    // الأقساط
    std::vector<قسط> جدول_الأقساط;
    
    // معلومات العميل
    معلومات_عميل العميل;
    
    // التواريخ
    std::string تاريخ_العقد;
    std::string تاريخ_أول_قسط;
    std::string تاريخ_آخر_قسط;
    
    // حساب المتبقي
    double المبلغ_المدفوع() const {
        double مجموع = الدفعة_الأولى;
        for (const auto& ق : جدول_الأقساط) {
            if (ق.مدفوع) مجموع += ق.المبلغ;
        }
        return مجموع;
    }
    
    double المبلغ_المتبقي() const {
        return السعر_النهائي - المبلغ_المدفوع();
    }
    
    int الأقساط_المدفوعة() const {
        int عدد = 0;
        for (const auto& ق : جدول_الأقساط) {
            if (ق.مدفوع) عدد++;
        }
        return عدد;
    }
    
    int الأقساط_المتبقية() const {
        return عدد_الأقساط - الأقساط_المدفوعة();
    }
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              طلب مرابحة
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * طلب تمويل بالمرابحة
 */
struct طلب_مرابحة {
    // معلومات السلعة
    std::string اسم_السلعة;
    std::string وصف_السلعة;
    نوع_مرابحة النوع;
    double سعر_السلعة;           // السعر في السوق
    
    // معلومات التقسيط المطلوبة
    double الدفعة_الأولى = 0;    // اختياري
    int عدد_الأشهر;              // مدة التقسيط
    
    // معلومات العميل
    معلومات_عميل العميل;
    double الدخل_الشهري;
    double الالتزامات_الشهرية;   // أقساط أخرى
};

// ═══════════════════════════════════════════════════════════════════════════════
