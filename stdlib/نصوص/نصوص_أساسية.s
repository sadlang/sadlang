الحزمة نصوص

# احصل على طول النص
دالة عدد_صحيح طول(النص: نص)
    إرجاع النص.الحجم()
نهاية

# تحقق من أن النص فارغ
دالة منطق هل_فارغ(النص: نص)
    إرجاع النص.الحجم() == 0
نهاية

# احصل على أول حرف
دالة نص أول_حرف(النص: نص)
    إذا (هل_فارغ(النص))
        إرجاع ""
    نهاية
    إرجاع النص[0:1]
نهاية

# احصل على آخر حرف
دالة نص آخر_حرف(النص: نص)
    إذا (هل_فارغ(النص))
        إرجاع ""
    نهاية
    عدد_صحيح الطول = طول(النص)
    إرجاع النص[الطول - 1:الطول]
نهاية

# احصل على الحرف في موضع محدد
دالة نص احصل_على_حرف(النص: نص؛ الموضع: عدد_صحيح)
    إذا (الموضع < 0 || الموضع >= طول(النص))
        إرجاع ""
    نهاية
    إرجاع النص[الموضع:الموضع + 1]
نهاية

# احصل على جزء من النص
دالة نص احصل_على_جزء(النص: نص؛ البداية: عدد_صحيح؛ النهاية: عدد_صحيح)
    إذا (البداية < 0 || النهاية > طول(النص) || البداية >= النهاية)
        إرجاع ""
    نهاية
    إرجاع النص[البداية:النهاية]
نهاية

# ابحث عن موضع نص
دالة عدد_صحيح ابحث_عن(النص: نص؛ المبحوث: نص)
    إذا (هل_فارغ(المبحوث))
        إرجاع -1
    نهاية
    
    عدد_صحيح طول_النص = طول(النص)
    عدد_صحيح طول_المبحوث = طول(المبحوث)
    
    لكل الموضع في [0:طول_النص]
        إذا (النص[الموضع:الموضع + طول_المبحوث] == المبحوث)
            إرجاع الموضع
        نهاية
    نهاية
    
    إرجاع -1
نهاية

# تحقق من وجود نص داخل نص
دالة منطق يحتوي(النص: نص؛ المبحوث: نص)
    إرجاع ابحث_عن(النص؛ المبحوث) >= 0
نهاية

# استبدل كل ظهور نص بآخر
دالة نص استبدل(النص: نص؛ البحث: نص؛ الاستبدال: نص)
    إذا (هل_فارغ(البحث))
        إرجاع النص
    نهاية
    
    نص النتيجة = ""
    عدد_صحيح موضع_آخر = 0
    عدد_صحيح موضع = ابحث_عن(النص؛ البحث)
    
    بينما (موضع >= 0)
        النتيجة = النتيجة + احصل_على_جزء(النص؛ موضع_آخر؛ موضع) + الاستبدال
        موضع_آخر = موضع + طول(البحث)
        موضع = ابحث_عن(النص[موضع_آخر:]؛ البحث)
        إذا (موضع >= 0)
            موضع = موضع + موضع_آخر
        نهاية
    نهاية
    
    النتيجة = النتيجة + النص[موضع_آخر:]
    إرجاع النتيجة
نهاية

# حول النص إلى أحرف كبيرة
دالة نص تحويل_كبير(النص: نص)
    إرجاع النص.تحويل_كبير()
نهاية

# حول النص إلى أحرف صغيرة
دالة نص تحويل_صغير(النص: نص)
    إرجاع النص.تحويل_صغير()
نهاية

# عكس ترتيب النص
دالة نص عكس(النص: نص)
    نص النتيجة = ""
    عدد_صحيح الطول = طول(النص)
    لكل الموضع في [الطول - 1:-1:0]
        النتيجة = النتيجة + احصل_على_حرف(النص؛ الموضع)
    نهاية
    إرجاع النتيجة
نهاية

# تحقق من أن نصين متساويان
دالة منطق متساوي(النص1: نص؛ النص2: نص)
    إرجاع النص1 == النص2
نهاية

# تحقق من المساواة بدون حساسية لحالة الأحرف
دالة منطق متساوي_بدون_حساسية(النص1: نص؛ النص2: نص)
    إرجاع تحويل_صغير(النص1) == تحويل_صغير(النص2)
نهاية

# تحقق من أن النص يبدأ بـ
دالة منطق يبدأ_بـ(النص: نص؛ البادئة: نص)
    إذا (طول(البادئة) > طول(النص))
        إرجاع خطأ
    نهاية
    إرجاع احصل_على_جزء(النص؛ 0؛ طول(البادئة)) == البادئة
نهاية

# تحقق من أن النص ينتهي بـ
دالة منطق ينتهي_بـ(النص: نص؛ اللاحقة: نص)
    إذا (طول(اللاحقة) > طول(النص))
        إرجاع خطأ
    نهاية
    عدد_صحيح الطول = طول(النص)
    عدد_صحيح طول_اللاحقة = طول(اللاحقة)
    إرجاع احصل_على_جزء(النص؛ الطول - طول_اللاحقة؛ الطول) == اللاحقة
نهاية

# احصل على أول ن من الأحرف
دالة نص أول_أحرف(النص: نص؛ العدد: عدد_صحيح)
    إذا (العدد <= 0)
        إرجاع ""
    نهاية
    إذا (العدد >= طول(النص))
        إرجاع النص
    نهاية
    إرجاع احصل_على_جزء(النص؛ 0؛ العدد)
نهاية

# احصل على آخر ن من الأحرف
دالة نص آخر_أحرف(النص: نص؛ العدد: عدد_صحيح)
    إذا (العدد <= 0)
        إرجاع ""
    نهاية
    عدد_صحيح الطول = طول(النص)
    إذا (العدد >= الطول)
        إرجاع النص
    نهاية
    إرجاع احصل_على_جزء(النص؛ الطول - العدد؛ الطول)
نهاية
