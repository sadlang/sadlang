/**
 * نص عربي مضغوط
 * 
 * يخزن النص العربي بكفاءة عالية
 */
class نص_عربي_مضغوط {
public:
    نص_عربي_مضغوط() = default;
    
    /**
     * إنشاء من نص UTF-8
     */
    static نص_عربي_مضغوط من_utf8(const std::string& نص) {
        نص_عربي_مضغوط نتيجة;
        نتيجة.رمِّز(نص);
        return نتيجة;
    }
    
    /**
     * تحويل إلى UTF-8
     */
    std::string إلى_utf8() const {
        std::string نتيجة;
        
        for (const auto& حرف : الحروف_) {
            // تحويل الحرف إلى Unicode ثم UTF-8
            uint32_t رمز = مُحوِّل_حروف::المثيل().إلى_unicode(
                حرف.الحرف(), حرف.الشكل()
            );
            نتيجة += رمز_إلى_utf8(رمز);
            
            // إضافة التشكيل
            if (حرف.التشكيل() != تشكيل::بدون) {
                رمز = تشكيل_إلى_unicode(حرف.التشكيل());
                نتيجة += رمز_إلى_utf8(رمز);
            }
        }
        
        return نتيجة;
    }
    
    /**
     * عدد الحروف
     */
    size_t الطول() const { return الحروف_.size(); }
    
    /**
     * الحصول على حرف
     */
    const حرف_مُرمَّز& operator[](size_t فهرس) const {
        return الحروف_[فهرس];
    }
    
    /**
     * إضافة حرف
     */
    void أضف(const حرف_مُرمَّز& حرف) {
        الحروف_.push_back(حرف);
    }
    
    /**
     * حجم الذاكرة بالبايت
     */
    size_t حجم_الذاكرة() const {
        // 2 بايت لكل حرف (نستخدم uint16_t)
        return الحروف_.size() * sizeof(حرف_مُرمَّز);
    }
    
    /**
     * الحجم المقدر لو كان UTF-8
     */
    size_t حجم_utf8_المقدر() const {
        // متوسط 3 بايت لكل حرف عربي في UTF-8
        return الحروف_.size() * 3;
    }
    
    /**
     * نسبة التوفير
     */
    double نسبة_التوفير() const {
        if (حجم_utf8_المقدر() == 0) return 0;
        return 1.0 - (static_cast<double>(حجم_الذاكرة()) / حجم_utf8_المقدر());
    }
    
private:
    void رمِّز(const std::string& نص) {
        size_t i = 0;
        حرف_مُرمَّز حرف_حالي;
        bool حرف_انتظار = false;
        
        while (i < نص.size()) {
            uint32_t رمز = اقرأ_رمز_utf8(نص, i);
            
            // هل هذا تشكيل؟
            auto علامة = مُحوِّل_حروف::المثيل().تشكيل_من_unicode(رمز);
            if (علامة && حرف_انتظار) {
                حرف_حالي.عيّن_التشكيل(*علامة);
                الحروف_.push_back(حرف_حالي);
                حرف_انتظار = false;
                continue;
            }
            
            // احفظ الحرف السابق إن وُجد
            if (حرف_انتظار) {
                الحروف_.push_back(حرف_حالي);
            }
            
            // هل هذا حرف عربي؟
            auto حرف = مُحوِّل_حروف::المثيل().من_unicode(رمز);
            if (حرف) {
                حرف_حالي = حرف_مُرمَّز(*حرف);
                حرف_انتظار = true;
            }
            else {
                حرف_انتظار = false;
            }
        }
        
        // الحرف الأخير
        if (حرف_انتظار) {
            الحروف_.push_back(حرف_حالي);
        }
        
        // تحديد أشكال الحروف
        حدد_الأشكال();
    }
    
    void حدد_الأشكال() {
        for (size_t i = 0; i < الحروف_.size(); i++) {
            bool يتصل_قبل = (i > 0) && يمكن_وصله(الحروف_[i-1].الحرف());
            bool يتصل_بعد = (i < الحروف_.size() - 1) && 
                            يمكن_وصله(الحروف_[i].الحرف());
            
            شكل_حرف شكل;
            if (!يتصل_قبل && !يتصل_بعد) {
                شكل = شكل_حرف::منفصل;
            }
            else if (!يتصل_قبل && يتصل_بعد) {
                شكل = شكل_حرف::أول;
            }
            else if (يتصل_قبل && يتصل_بعد) {
                شكل = شكل_حرف::وسط;
            }
            else {
                شكل = شكل_حرف::آخر;
            }
            
            الحروف_[i].عيّن_الشكل(شكل);
        }
    }
    
    bool يمكن_وصله(حرف_عربي حرف) const {
        // الحروف التي لا تتصل بما بعدها
        return حرف != حرف_عربي::ألف &&
               حرف != حرف_عربي::دال &&
               حرف != حرف_عربي::ذال &&
               حرف != حرف_عربي::راء &&
               حرف != حرف_عربي::زاي &&
               حرف != حرف_عربي::واو;
    }
    
    uint32_t اقرأ_رمز_utf8(const std::string& نص, size_t& موقع) const {
        unsigned char أول = نص[موقع++];
        
        if ((أول & 0x80) == 0) {
            return أول;
        }
        else if ((أول & 0xE0) == 0xC0) {
            uint32_t رمز = (أول & 0x1F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else if ((أول & 0xF0) == 0xE0) {
            uint32_t رمز = (أول & 0x0F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
        else {
            uint32_t رمز = (أول & 0x07) << 18;
            رمز |= (نص[موقع++] & 0x3F) << 12;
            رمز |= (نص[موقع++] & 0x3F) << 6;
            رمز |= (نص[موقع++] & 0x3F);
            return رمز;
        }
    }
    
    std::string رمز_إلى_utf8(uint32_t رمز) const {
        std::string نتيجة;
        
        if (رمز < 0x80) {
            نتيجة += static_cast<char>(رمز);
        }
        else if (رمز < 0x800) {
            نتيجة += static_cast<char>(0xC0 | (رمز >> 6));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        else if (رمز < 0x10000) {
            نتيجة += static_cast<char>(0xE0 | (رمز >> 12));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 6) & 0x3F));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        else {
            نتيجة += static_cast<char>(0xF0 | (رمز >> 18));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 12) & 0x3F));
            نتيجة += static_cast<char>(0x80 | ((رمز >> 6) & 0x3F));
            نتيجة += static_cast<char>(0x80 | (رمز & 0x3F));
        }
        
        return نتيجة;
    }
    
    uint32_t تشكيل_إلى_unicode(تشكيل علامة) const {
        switch (علامة) {
            case تشكيل::فتحة: return 0x064E;
            case تشكيل::ضمة: return 0x064F;
            case تشكيل::كسرة: return 0x0650;
            case تشكيل::سكون: return 0x0652;
            case تشكيل::شدة: return 0x0651;
            case تشكيل::فتحتين: return 0x064B;
            case تشكيل::ضمتين: return 0x064C;
            default: return 0;
        }
    }
    
    std::vector<حرف_مُرمَّز> الحروف_;
};

