/**
 * الحروف العربية الأساسية (28 حرف)
 */
enum class حرف_عربي : uint8_t {
    ألف = 0,    // ا
    باء = 1,    // ب
    تاء = 2,    // ت
    ثاء = 3,    // ث
    جيم = 4,    // ج
    حاء = 5,    // ح
    خاء = 6,    // خ
    دال = 7,    // د
    ذال = 8,    // ذ
    راء = 9,    // ر
    زاي = 10,   // ز
    سين = 11,   // س
    شين = 12,   // ش
    صاد = 13,   // ص
    ضاد = 14,   // ض
    طاء = 15,   // ط
    ظاء = 16,   // ظ
    عين = 17,   // ع
    غين = 18,   // غ
    فاء = 19,   // ف
    قاف = 20,   // ق
    كاف = 21,   // ك
    لام = 22,   // ل
    ميم = 23,   // م
    نون = 24,   // ن
    هاء = 25,   // ه
    واو = 26,   // و
    ياء = 27,   // ي
    
    همزة = 28,     // ء
    ألف_مقصورة = 29, // ى
    تاء_مربوطة = 30, // ة
    لا_حرف = 31     // للرموز الأخرى
};

/**
 * علامات التشكيل
 */
enum class تشكيل : uint8_t {
    بدون = 0,      // بدون تشكيل
    فتحة = 1,      // ـَ
    ضمة = 2,       // ـُ
    كسرة = 3,      // ـِ
    سكون = 4,      // ـْ
    شدة = 5,       // ـّ
    فتحتين = 6,    // ـً (تنوين)
    ضمتين = 7      // ـٌ (تنوين)
};

/**
 * شكل الحرف حسب موقعه في الكلمة
 */
enum class شكل_حرف : uint8_t {
    منفصل = 0,   // الحرف منفصل
    أول = 1,     // في بداية الكلمة
    وسط = 2,     // في وسط الكلمة
    آخر = 3      // في نهاية الكلمة
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              الحرف المُرمَّز
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * حرف عربي مُرمَّز في 10 بت
 * 
 * البنية:
 * - بت 0-4: الحرف (5 بت)
 * - بت 5-7: التشكيل (3 بت)
 * - بت 8-9: الشكل (2 بت)
 */
class حرف_مُرمَّز {
public:
    حرف_مُرمَّز() : القيمة_(0) {}
    
    حرف_مُرمَّز(حرف_عربي حرف, تشكيل علامة = تشكيل::بدون, 
               شكل_حرف شكل = شكل_حرف::منفصل) {
        القيمة_ = static_cast<uint16_t>(حرف) |
                  (static_cast<uint16_t>(علامة) << 5) |
                  (static_cast<uint16_t>(شكل) << 8);
    }
    
    // الوصول للمكونات
    حرف_عربي الحرف() const {
        return static_cast<حرف_عربي>(القيمة_ & 0x1F);
    }
    
    تشكيل التشكيل() const {
        return static_cast<تشكيل>((القيمة_ >> 5) & 0x07);
    }
    
    شكل_حرف الشكل() const {
        return static_cast<شكل_حرف>((القيمة_ >> 8) & 0x03);
    }
    
    // القيمة الخام
    uint16_t القيمة() const { return القيمة_; }
    
    // تعيين المكونات
    void عيّن_الحرف(حرف_عربي حرف) {
        القيمة_ = (القيمة_ & ~0x1F) | static_cast<uint16_t>(حرف);
    }
    
    void عيّن_التشكيل(تشكيل علامة) {
        القيمة_ = (القيمة_ & ~0xE0) | (static_cast<uint16_t>(علامة) << 5);
    }
    
    void عيّن_الشكل(شكل_حرف شكل) {
        القيمة_ = (القيمة_ & ~0x300) | (static_cast<uint16_t>(شكل) << 8);
    }
    
private:
    uint16_t القيمة_;  // نستخدم 16 بت للتخزين، لكن 10 بت فقط فعّالة
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              مُحوِّل Unicode ↔ مُرمَّز
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * جدول تحويل Unicode إلى حرف عربي
 */
class مُحوِّل_حروف {
public:
    static مُحوِّل_حروف& المثيل() {
        static مُحوِّل_حروف مثيل;
        return مثيل;
    }
    
    /**
     * تحويل Unicode إلى حرف عربي
     */
    std::optional<حرف_عربي> من_unicode(uint32_t رمز) const {
        // الحروف العربية الأساسية: U+0627 - U+064A
        if (رمز >= 0x0627 && رمز <= 0x064A) {
            static const حرف_عربي جدول[] = {
                حرف_عربي::ألف,    // 0627
                حرف_عربي::لا_حرف, // 0628 - باء مع همزة
                حرف_عربي::لا_حرف, // 0629 - تاء مربوطة
                حرف_عربي::لا_حرف, // 062A
                // ... سيتم إكمال الجدول
            };
            
            // تبسيط: إرجاع الحرف مباشرة
            uint32_t فهرس = رمز - 0x0627;
            if (فهرس < 28) {
                return static_cast<حرف_عربي>(فهرس);
            }
        }
        
        // الهمزة
        if (رمز == 0x0621) return حرف_عربي::همزة;
        
        // ألف مقصورة
        if (رمز == 0x0649) return حرف_عربي::ألف_مقصورة;
        
        // تاء مربوطة
        if (رمز == 0x0629) return حرف_عربي::تاء_مربوطة;
        
        return std::nullopt;
    }
    
    /**
     * تحويل حرف عربي إلى Unicode
     */
    uint32_t إلى_unicode(حرف_عربي حرف, شكل_حرف شكل = شكل_حرف::منفصل) const {
        // جدول أشكال الحروف
        static const uint32_t أشكال[28][4] = {
            // منفصل، أول، وسط، آخر
            {0x0627, 0x0627, 0x0627, 0x0627}, // ألف
            {0x0628, 0xFE91, 0xFE92, 0xFE90}, // باء
            {0x062A, 0xFE97, 0xFE98, 0xFE96}, // تاء
            // ... سيتم إكمال الجدول
        };
        
        int ف = static_cast<int>(حرف);
        int ش = static_cast<int>(شكل);
        
        if (ف < 28 && ش < 4) {
            return أشكال[ف][ش];
        }
        
        return 0x0627;  // افتراضي: ألف
    }
    
    /**
     * تحويل Unicode تشكيل إلى تعداد
     */
    std::optional<تشكيل> تشكيل_من_unicode(uint32_t رمز) const {
        switch (رمز) {
            case 0x064E: return تشكيل::فتحة;
            case 0x064F: return تشكيل::ضمة;
            case 0x0650: return تشكيل::كسرة;
            case 0x0652: return تشكيل::سكون;
            case 0x0651: return تشكيل::شدة;
            case 0x064B: return تشكيل::فتحتين;
            case 0x064C: return تشكيل::ضمتين;
            default: return std::nullopt;
        }
    }
    
private:
    مُحوِّل_حروف() = default;
};

