/**
 * صلاحية واحدة
 */
using صلاحية = std::string;

/**
 * مجموعة صلاحيات
 */
using مجموعة_صلاحيات = std::unordered_set<صلاحية>;

/**
 * صفات (Attributes)
 */
using صفات = std::unordered_map<std::string, std::string>;

/**
 * نتيجة التحقق من الصلاحية
 */
struct نتيجة_صلاحية {
    bool مسموح = false;
    std::string السبب;
    std::optional<std::string> الصلاحية_المفقودة;
};

// ═══════════════════════════════════════════════════════════════════════════════
//                              الدور (Role)
