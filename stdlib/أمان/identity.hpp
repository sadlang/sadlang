/**
 * باني السياسات
 * 
 * مثال:
 *     باني_سياسة("سياسة_المبيعات", "قراءة_عملاء")
 *         .إذا_صفة_مستخدم("القسم", "مبيعات")
 *         .وخلال_ساعات(9, 17)
 *         .سجِّل();
 */
class باني_سياسة {
public:
    باني_سياسة(const std::string& اسم, const صلاحية& ص)
        : m_سياسة(std::make_shared<سياسة>(اسم, ص)) {}
    
    باني_سياسة& إذا_صفة_مستخدم(const std::string& مفتاح, const std::string& قيمة) {
        m_سياسة->أضف_شرط(std::make_shared<شرط_صفة_مستخدم>(مفتاح, قيمة));
        return *this;
    }
    
    باني_سياسة& وخلال_ساعات(int من, int إلى) {
        m_سياسة->أضف_شرط(std::make_shared<شرط_وقت>(من, إلى));
        return *this;
    }
    
    std::shared_ptr<سياسة> ابنِ() {
        return m_سياسة;
    }
    
    void سجِّل() {
        مدير_هوية::المثال().سجِّل_سياسة(m_سياسة);
    }
    
private:
    std::shared_ptr<سياسة> m_سياسة;
};

