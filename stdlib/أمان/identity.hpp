/**
 * باني الأدوار (Fluent API)
 * 
 * مثال:
 *     auto دور_مشرف = باني_دور("مشرف")
 *         .يرث("مستخدم")
 *         .له("قراءة_الكل")
 *         .له("حذف")
 *         .ابنِ();
 */
class باني_دور {
public:
    explicit باني_دور(const std::string& اسم) : m_دور(اسم) {}
    
    باني_دور& له(const صلاحية& ص) {
        m_دور.أضف_صلاحية(ص);
        return *this;
    }
    
    باني_دور& يرث(const std::string& اسم_دور) {
        auto دور_أب = مدير_هوية::المثال().احصل_على_دور(اسم_دور);
        if (دور_أب.has_value()) {
            m_دور.يرث_من(*دور_أب);
        }
        return *this;
    }
    
    دور ابنِ() {
        return m_دور;
    }
    
    void سجِّل() {
        مدير_هوية::المثال().سجِّل_دور(m_دور);
    }
    
private:
    دور m_دور;
};

