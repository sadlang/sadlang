/**
 * هوية المستخدم
 */
class هوية {
public:
    /**
     * إنشاء هوية
     */
    هوية(const std::string& المعرف, const std::string& الاسم)
        : m_المعرف(المعرف), m_الاسم(الاسم), m_مُصادق(false) {}
    
    // الوصول للبيانات
    const std::string& المعرف() const { return m_المعرف; }
    const std::string& الاسم() const { return m_الاسم; }
    bool مُصادق() const { return m_مُصادق; }
    
    /**
     * تعيين حالة المصادقة
     */
    void عيِّن_مُصادق(bool قيمة) { m_مُصادق = قيمة; }
    
    /**
     * إضافة دور
     */
    void أضف_دور(const std::string& اسم_الدور) {
        m_الأدوار.insert(اسم_الدور);
    }
    
    /**
     * إزالة دور
     */
    void أزل_دور(const std::string& اسم_الدور) {
        m_الأدوار.erase(اسم_الدور);
    }
    
    /**
     * هل لديه دور؟
     */
    bool لديه_دور(const std::string& اسم_الدور) const {
        return m_الأدوار.count(اسم_الدور) > 0;
    }
    
    /**
     * كل الأدوار
     */
    const std::unordered_set<std::string>& الأدوار() const {
        return m_الأدوار;
    }
    
    /**
     * إضافة صفة
     */
    void عيِّن_صفة(const std::string& مفتاح, const std::string& قيمة) {
        m_صفات[مفتاح] = قيمة;
    }
    
    /**
     * الحصول على صفة
     */
    std::optional<std::string> صفة(const std::string& مفتاح) const {
        auto it = m_صفات.find(مفتاح);
        if (it != m_صفات.end()) {
            return it->second;
        }
        return std::nullopt;
    }
    
    /**
     * كل الصفات
     */
    const صفات& كل_الصفات() const {
        return m_صفات;
    }
    
private:
    std::string m_المعرف;
    std::string m_الاسم;
    bool m_مُصادق;
    std::unordered_set<std::string> m_الأدوار;
    صفات m_صفات;
};

