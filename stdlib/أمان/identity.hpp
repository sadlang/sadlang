/**
 * شرط في السياسة
 */
class شرط_سياسة {
public:
    virtual ~شرط_سياسة() = default;
    virtual bool تحقق(const هوية& مستخدم, const صفات& مورد, const صفات& سياق) const = 0;
    virtual std::string الوصف() const = 0;
};

/**
 * شرط صفة المستخدم
 */
class شرط_صفة_مستخدم : public شرط_سياسة {
public:
    شرط_صفة_مستخدم(const std::string& مفتاح, const std::string& قيمة)
        : m_مفتاح(مفتاح), m_قيمة(قيمة) {}
    
    bool تحقق(const هوية& مستخدم, const صفات&, const صفات&) const override {
        auto صفة = مستخدم.صفة(m_مفتاح);
        return صفة.has_value() && *صفة == m_قيمة;
    }
    
    std::string الوصف() const override {
        return "المستخدم." + m_مفتاح + " == \"" + m_قيمة + "\"";
    }
    
private:
    std::string m_مفتاح;
    std::string m_قيمة;
};

/**
 * شرط الوقت
 */
class شرط_وقت : public شرط_سياسة {
public:
    شرط_وقت(int ساعة_بداية, int ساعة_نهاية)
        : m_بداية(ساعة_بداية), m_نهاية(ساعة_نهاية) {}
    
    bool تحقق(const هوية&, const صفات&, const صفات& سياق) const override {
        auto it = سياق.find("ساعة");
        if (it == سياق.end()) return true;  // لا معلومات عن الوقت
        
        int ساعة = std::stoi(it->second);
        return ساعة >= m_بداية && ساعة < m_نهاية;
    }
    
    std::string الوصف() const override {
        return "الوقت بين " + std::to_string(m_بداية) + " و " + std::to_string(m_نهاية);
    }
    
private:
    int m_بداية;
    int m_نهاية;
};

/**
 * شرط مركب (AND)
 */
class شرط_و : public شرط_سياسة {
public:
    void أضف(std::shared_ptr<شرط_سياسة> شرط) {
        m_الشروط.push_back(std::move(شرط));
    }
    
    bool تحقق(const هوية& مستخدم, const صفات& مورد, const صفات& سياق) const override {
        for (const auto& شرط : m_الشروط) {
            if (!شرط->تحقق(مستخدم, مورد, سياق)) {
                return false;
            }
        }
        return true;
    }
    
    std::string الوصف() const override {
        std::string نص = "(";
        for (size_t i = 0; i < m_الشروط.size(); i++) {
            نص += m_الشروط[i]->الوصف();
            if (i < m_الشروط.size() - 1) نص += " و ";
        }
        نص += ")";
        return نص;
    }
    
private:
    std::vector<std::shared_ptr<شرط_سياسة>> m_الشروط;
};

/**
 * سياسة ABAC كاملة
 */
class سياسة {
public:
    سياسة(const std::string& الاسم, const صلاحية& الصلاحية_المطلوبة)
        : m_الاسم(الاسم), m_الصلاحية(الصلاحية_المطلوبة) {}
    
    /**
     * إضافة شرط
     */
    void أضف_شرط(std::shared_ptr<شرط_سياسة> شرط) {
        m_الشروط.push_back(std::move(شرط));
    }
    
    /**
     * تقييم السياسة
     */
    نتيجة_صلاحية قيِّم(const هوية& مستخدم, const صفات& مورد, const صفات& سياق) const {
        for (const auto& شرط : m_الشروط) {
            if (!شرط->تحقق(مستخدم, مورد, سياق)) {
                return {false, "فشل الشرط: " + شرط->الوصف(), m_الصلاحية};
            }
        }
        return {true, "كل الشروط مستوفاة", {}};
    }
    
    const std::string& الاسم() const { return m_الاسم; }
    const صلاحية& الصلاحية_المطلوبة() const { return m_الصلاحية; }
    
private:
    std::string m_الاسم;
    صلاحية m_الصلاحية;
    std::vector<std::shared_ptr<شرط_سياسة>> m_الشروط;
};

