//
// الصلوات المحسوبة:
//   🌅 الفجر — قبل شروق الشمس (زاوية تحت الأفق حسب طريقة الحساب)
//   🌄 الشروق — لحظة طلوع الشمس فوق الأفق
//   ☀️ الظهر — عندما تكون الشمس في أعلى نقطة (منتصف النهار الشرعي)
//   🌤️ العصر — عندما يصبح ظل الشيء مثله أو مثليه (حسب المذهب)
//   🌅 المغرب — لحظة غروب الشمس تحت الأفق
//   🌙 العشاء — بعد اختفاء الشفق الأحمر
//
// طرق الحساب المدعومة:
//   - أم القرى (المملكة العربية السعودية)
//   - رابطة العالم الإسلامي
//   - الجمعية الإسلامية لأمريكا الشمالية (ISNA)
//   - الهيئة المصرية العامة للمساحة
//   - جامعة العلوم الإسلامية بكراتشي
//
// طرق حساب العصر:
//   - المذهب الشافعي/المالكي/الحنبلي: ظل الشيء = مثله
//   - المذهب الحنفي: ظل الشيء = مثليه
// ═══════════════════════════════════════════════════════════════════════════════
#pragma once

#include <string>
#include <vector>

namespace sad { namespace prayer {

// ═══════════════════════════════════════════════════════════════════
// طرق الحساب — كل طريقة تحدد زوايا الفجر والعشاء
// ═══════════════════════════════════════════════════════════════════

// طريقة حساب أوقات الصلاة
enum class CalcMethod {
    UmmAlQura,      // أم القرى — السعودية (الفجر: 18.5°، العشاء: 90 دقيقة بعد المغرب)
    MWL,            // رابطة العالم الإسلامي (الفجر: 18°، العشاء: 17°)
    ISNA,           // ❤ أمريكا الشمالية (الفجر: 15°، العشاء: 15°)
    Egypt,          // الهيئة المصرية (الفجر: 19.5°، العشاء: 17.5°)
    Karachi         // جامعة كراتشي (الفجر: 18°، العشاء: 18°)
};

// طريقة حساب العصر
enum class AsrMethod {
    Shafii,     // الشافعي — ظل الشيء = مثله (عامل = 1)
    Hanafi      // الحنفي — ظل الشيء = مثليه (عامل = 2)
};

// ═══════════════════════════════════════════════════════════════════
// هياكل البيانات
// ═══════════════════════════════════════════════════════════════════

// أوقات الصلوات الخمس + الشروق (بتنسيق ساعة:دقيقة)
struct PrayerTimes {
    double fajr = 0;        // الفجر — ساعات عشرية (مثلاً 4.75 = 4:45)
    double sunrise = 0;     // الشروق
    double dhuhr = 0;       // الظهر
    double asr = 0;         // العصر
    double maghrib = 0;     // المغرب
    double isha = 0;        // العشاء
};

// ═══════════════════════════════════════════════════════════════════
// واجهة برمجة التطبيقات — API
// ═══════════════════════════════════════════════════════════════════

// ─── حساب أوقات الصلاة ───

// حساب أوقات الصلاة لتاريخ وموقع محدد
// خط_العرض: بالدرجات (موجب = شمال، سالب = جنوب)
// خط_الطول: بالدرجات (موجب = شرق، سالب = غرب)
// المنطقة_الزمنية: الفرق عن غرينتش بالساعات (مثلاً: الرياض = +3)
PrayerTimes calculate(int year, int month, int day,
                      double latitude, double longitude, double timezone,
                      int method = 0, int asrMethod = 0);

// ─── تنسيق الوقت ───

// تحويل ساعات عشرية إلى نص "HH:MM"
std::string formatTime(double decimalHours);

// تحويل إلى تنسيق 12 ساعة "HH:MM ص/م"
std::string formatTime12(double decimalHours);

// ─── استعلامات مساعدة ───

// الحصول على وقت صلاة محددة (0=فجر، 1=شروق، 2=ظهر، 3=عصر، 4=مغرب، 5=عشاء)
double getPrayerTime(int prayerIndex, int year, int month, int day,
                     double lat, double lon, double tz, int method = 0, int asrMethod = 0);

// الحصول على اسم الصلاة بالعربية
std::string getPrayerName(int index);

// الحصول على اسم طريقة الحساب
std::string getMethodName(int method);

// الحصول على جميع الأوقات كنص منسق
std::string getAllTimesFormatted(int year, int month, int day,
                                double lat, double lon, double tz,
                                int method = 0, int asrMethod = 0);

}} // namespace sad::prayer
