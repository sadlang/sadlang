// نظام اتجاه القبلة — لغة ص
// Qibla Direction System — SAD Language
// ═══════════════════════════════════════════════════════════════════════════════
//
// حساب اتجاه القبلة من أي نقطة على الأرض — نحو الكعبة المشرفة في مكة المكرمة
// لا يوجد نظير لهذا في Flutter أو أي إطار عمل آخر!
//
// يستخدم صيغة Great Circle لحساب الاتجاه الأولي (Initial Bearing)
// من إحداثيات المستخدم إلى إحداثيات الكعبة:
//   خط عرض الكعبة: 21.4225° شمالاً
//   خط طول الكعبة: 39.8262° شرقاً
//
// الميزات:
//   🕋 حساب زاوية القبلة بالدرجات (0° = شمال، 90° = شرق)
//   📏 حساب المسافة إلى مكة بالكيلومترات
//   🧭 رسم بوصلة رسومية مع سهم القبلة
//   📍 الاتجاه بالنص (شمال شرق، جنوب غرب، ...)
// ═══════════════════════════════════════════════════════════════════════════════
#pragma once

#include <string>
#include <cstdint>

namespace sad { namespace qibla {

// ═══════════════════════════════════════════════════════════════════
// واجهة برمجة التطبيقات — API
// ═══════════════════════════════════════════════════════════════════

// ─── الحساب ───

// حساب زاوية القبلة من موقع المستخدم
// الزاوية: 0° = شمال، 90° = شرق، 180° = جنوب، 270° = غرب
// خط_العرض بالدرجات (موجب = شمال)
// خط_الطول بالدرجات (موجب = شرق)
double calculateAngle(double latitude, double longitude);

// حساب المسافة إلى الكعبة المشرفة بالكيلومترات
// يستخدم صيغة Haversine المعتمدة على نصف قطر الأرض
double calculateDistance(double latitude, double longitude);

// الحصول على اتجاه القبلة كنص عربي
// مثال: "شمال شرق"، "جنوب غرب"، "شرق"
std::string getDirectionText(double latitude, double longitude);

// الحصول على معلومات كاملة كنص منسق
std::string getQiblaInfo(double latitude, double longitude);

// ─── الرسم ───

// رسم بوصلة القبلة على الشاشة
// المرسم: مؤشر SDL_Renderer
// مركز_س، مركز_ص: مركز البوصلة على الشاشة
// نصف_القطر: حجم البوصلة
// زاوية_الجهاز: اتجاه الجهاز الحالي (للبوصلة الإلكترونية، 0 = مواجه الشمال)
void drawCompass(void* renderer, int cx, int cy, int radius,
                 double qiblaAngle, double deviceHeading = 0);

// رسم بوصلة القبلة باستخدام إحداثيات مباشرة
void drawQiblaCompass(void* renderer, int cx, int cy, int radius,
                      double latitude, double longitude, double deviceHeading = 0);

}} // namespace sad::qibla
