// إنشاء مجموعة أذكار مخصصة فارغة
// يمكن إضافة أذكار إليها لاحقاً باستخدام addDhikrToCollection
// يُرجع معرّف المجموعة (وهو نفسه معرّف الجلسة)
int createCustomCollection(const std::string& name) {
    int id = g_nextSessionId++;
    Session session;
    session.collection = DhikrCollection::Custom;
    session.currentIndex = 0;
    session.name = name;
    // المجموعة تبدأ بقائمة أذكار فارغة
    g_sessions[id] = session;
    return id;
}

// إضافة ذكر جديد إلى مجموعة مخصصة
// يمكن تحديد النص والعدد المطلوب والمرجع والثواب
void addDhikrToCollection(int collectionId, const std::string& text,
                           int targetCount, const std::string& reference,
                           const std::string& reward) {
    auto it = g_sessions.find(collectionId);
    if (it == g_sessions.end()) return;

    // التحقق من أن المجموعة من نوع مخصص
    if (it->second.collection != DhikrCollection::Custom) return;

    Dhikr dhikr;
    dhikr.text = text;
    dhikr.targetCount = (targetCount > 0) ? targetCount : 1;
    dhikr.currentCount = 0;
    dhikr.reference = reference;
    dhikr.reward = reward;

    it->second.adhkar.push_back(dhikr);
}

