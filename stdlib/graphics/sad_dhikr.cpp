// تنفيذ واجهة العدادات — Counter API Implementation
// ═══════════════════════════════════════════════════════════════════

// إنشاء عداد تسبيح جديد بالاسم والهدف المحدد
// يُرجع معرّف العداد الفريد لاستخدامه لاحقاً
int createCounter(const std::string& name, int target) {
    int id = g_nextCounterId++;
    Counter counter;
    counter.name = name;
    counter.target = (target > 0) ? target : 33;  // الافتراضي ٣٣
    counter.current = 0;
    g_counters[id] = counter;
    return id;
}

// زيادة قيمة العداد بمقدار واحد
// يُحدّث الإحصائيات العامة تلقائياً
// يُرجع القيمة الجديدة للعداد، أو -١ إذا كان المعرّف غير صالح
int increment(int counterId) {
    auto it = g_counters.find(counterId);
    if (it == g_counters.end()) return -1;  // معرّف غير صالح

    it->second.current++;

    // تحديث الإحصائيات العامة عند كل تسبيحة
    g_totalToday++;
    g_totalAllTime++;

    return it->second.current;
}

// إعادة تعيين العداد إلى الصفر
// مفيد عند الرغبة في البدء من جديد
void resetCounter(int counterId) {
    auto it = g_counters.find(counterId);
    if (it != g_counters.end()) {
        it->second.current = 0;
    }
}

// الحصول على القيمة الحالية للعداد
// يُرجع ٠ إذا كان المعرّف غير صالح
int getCount(int counterId) {
    auto it = g_counters.find(counterId);
    if (it == g_counters.end()) return 0;
    return it->second.current;
}

// الحصول على الهدف المحدد للعداد
// يُرجع ٠ إذا كان المعرّف غير صالح
int getTarget(int counterId) {
    auto it = g_counters.find(counterId);
    if (it == g_counters.end()) return 0;
    return it->second.target;
}

// التحقق مما إذا وصل العداد لهدفه
// يُرجع صحيح إذا كانت القيمة الحالية تساوي أو تتجاوز الهدف
bool isTargetReached(int counterId) {
    auto it = g_counters.find(counterId);
    if (it == g_counters.end()) return false;
    return it->second.current >= it->second.target;
}

// ═══════════════════════════════════════════════════════════════════
// تنفيذ واجهة مجموعات الأذكار — Collection API Implementation
// ═══════════════════════════════════════════════════════════════════

// تحميل مجموعة أذكار مدمجة وإنشاء جلسة جديدة
// يُرجع معرّف الجلسة لاستخدامه مع باقي دوال المجموعة
int loadCollection(DhikrCollection collection) {
    int id = g_nextSessionId++;
    Session session;
    session.collection = collection;
    session.currentIndex = 0;

    // تحميل الأذكار حسب نوع المجموعة
    switch (collection) {
        case DhikrCollection::Morning:
            session.adhkar = loadMorningAdhkar();
            session.name = "أذكار الصباح";
            break;
        case DhikrCollection::Evening:
            session.adhkar = loadEveningAdhkar();
            session.name = "أذكار المساء";
            break;
        case DhikrCollection::AfterPrayer:
            session.adhkar = loadAfterPrayerAdhkar();
            session.name = "أذكار بعد الصلاة";
            break;
        case DhikrCollection::BeforeSleep:
            session.adhkar = loadBeforeSleepAdhkar();
            session.name = "أذكار النوم";
            break;
        case DhikrCollection::Custom:
            // المجموعة المخصصة تبدأ فارغة
            session.name = "مجموعة مخصصة";
            break;
    }

    g_sessions[id] = session;
    return id;
}

// الحصول على الذكر الحالي في الجلسة
// يُرجع هيكل ذكر فارغ إذا كان المعرّف غير صالح أو المجموعة فارغة
Dhikr getCurrentDhikr(int sessionId) {
    auto it = g_sessions.find(sessionId);
    if (it == g_sessions.end()) return {"", "", 0, 0, ""};

    const Session& session = it->second;
    if (session.adhkar.empty()) return {"", "", 0, 0, ""};
    if (session.currentIndex < 0 || session.currentIndex >= (int)session.adhkar.size()) {
        return {"", "", 0, 0, ""};
    }

    return session.adhkar[session.currentIndex];
}

// تسبيح — زيادة عدد الذكر الحالي بواحد
// عند اكتمال العدد المطلوب للذكر الحالي ينتقل تلقائياً للذكر التالي
// يُرجع صحيح إذا تمت العملية بنجاح، خطأ إذا اكتملت المجموعة كلها
bool count(int sessionId) {
    auto it = g_sessions.find(sessionId);
    if (it == g_sessions.end()) return false;

    Session& session = it->second;
    if (session.adhkar.empty()) return false;
    if (session.currentIndex >= (int)session.adhkar.size()) return false;

    Dhikr& current = session.adhkar[session.currentIndex];

    // زيادة عدد الذكر الحالي
    current.currentCount++;

    // تحديث الإحصائيات العامة
    g_totalToday++;
    g_totalAllTime++;

    // التحقق من اكتمال الذكر الحالي والانتقال للتالي
    if (current.currentCount >= current.targetCount) {
        // الانتقال للذكر التالي إذا وُجد
        if (session.currentIndex + 1 < (int)session.adhkar.size()) {
            session.currentIndex++;
        } else {
            // اكتملت المجموعة بالكامل — تحديث إحصائيات الجلسات
            g_sessionsToday++;
            g_currentStreak++;
            if (g_currentStreak > g_longestStreak) {
                g_longestStreak = g_currentStreak;
            }
            return false;  // لا يوجد المزيد من الأذكار
        }
    }

    return true;
}

// الانتقال يدوياً للذكر التالي في المجموعة
// يُرجع صحيح إذا تم الانتقال بنجاح، خطأ إذا كنا في آخر ذكر
bool nextDhikr(int sessionId) {
    auto it = g_sessions.find(sessionId);
    if (it == g_sessions.end()) return false;

    Session& session = it->second;
    if (session.currentIndex + 1 < (int)session.adhkar.size()) {
        session.currentIndex++;
        return true;
    }
    return false;  // لا يوجد ذكر تالٍ
}

// الانتقال يدوياً للذكر السابق في المجموعة
// يُرجع صحيح إذا تم الانتقال بنجاح، خطأ إذا كنا في أول ذكر
bool prevDhikr(int sessionId) {
    auto it = g_sessions.find(sessionId);
    if (it == g_sessions.end()) return false;

    Session& session = it->second;
    if (session.currentIndex > 0) {
        session.currentIndex--;
        return true;
    }
    return false;  // لا يوجد ذكر سابق
}

// الحصول على معلومات الجلسة كاملة
// يحسب عدد الأذكار المكتملة وإجمالي التسبيحات وحالة الاكتمال
DhikrSession getSessionInfo(int sessionId) {
    DhikrSession info;
    info.sessionId = sessionId;
    info.collection = DhikrCollection::Custom;
    info.totalCount = 0;
    info.completedDhikrs = 0;
    info.totalDhikrs = 0;
    info.isComplete = false;

    auto it = g_sessions.find(sessionId);
    if (it == g_sessions.end()) return info;

    const Session& session = it->second;
    info.collection = session.collection;
    info.totalDhikrs = (int)session.adhkar.size();

    // حساب إجمالي التسبيحات وعدد الأذكار المكتملة
    int completed = 0;
    int total = 0;
    for (const auto& dhikr : session.adhkar) {
        total += dhikr.currentCount;
        if (dhikr.currentCount >= dhikr.targetCount) {
            completed++;
        }
    }

    info.totalCount = total;
    info.completedDhikrs = completed;
    info.isComplete = (completed == info.totalDhikrs && info.totalDhikrs > 0);

    return info;
}

// التحقق مما إذا اكتملت جميع أذكار المجموعة
// يُرجع صحيح فقط إذا وصل كل ذكر لعدده المطلوب
bool isCollectionComplete(int sessionId) {
    auto it = g_sessions.find(sessionId);
    if (it == g_sessions.end()) return false;

    const Session& session = it->second;
    if (session.adhkar.empty()) return false;

    // التحقق من اكتمال كل ذكر على حدة
    for (const auto& dhikr : session.adhkar) {
        if (dhikr.currentCount < dhikr.targetCount) {
            return false;  // يوجد ذكر لم يكتمل بعد
        }
    }
    return true;  // اكتملت جميع الأذكار — ما شاء الله
}

