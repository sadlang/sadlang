/**
 * نتيجة اختبار واحد
 */
struct نتيجة_اختبار {
    std::string الاسم;
    bool نجح;
    std::string رسالة_الخطأ;
    double الوقت_ms;
};

/**
 * مجموعة اختبارات
 */
class مجموعة_اختبارات {
public:
    explicit مجموعة_اختبارات(const std::string& اسم)
        : m_الاسم(اسم) {}
    
    /**
     * إضافة اختبار
     */
    void أضف(const std::string& اسم, std::function<void()> دالة) {
        m_اختبارات.push_back({اسم, std::move(دالة)});
    }
    
    /**
     * تشغيل كل الاختبارات
     */
    std::vector<نتيجة_اختبار> شغِّل() {
        std::vector<نتيجة_اختبار> نتائج;
        
        std::cout << "\n═══════════════════════════════════════════\n";
        std::cout << "🧪 " << m_الاسم << "\n";
        std::cout << "═══════════════════════════════════════════\n\n";
        
        for (const auto& [اسم, دالة] : m_اختبارات) {
            نتيجة_اختبار نتيجة;
            نتيجة.الاسم = اسم;
            
            auto بداية = std::chrono::high_resolution_clock::now();
            
            try {
                دالة();
                نتيجة.نجح = true;
                std::cout << "  ✅ " << اسم << "\n";
            } catch (const std::exception& e) {
                نتيجة.نجح = false;
                نتيجة.رسالة_الخطأ = e.what();
                std::cout << "  ❌ " << اسم << "\n";
                std::cout << "     └─ " << e.what() << "\n";
            }
            
            auto نهاية = std::chrono::high_resolution_clock::now();
            نتيجة.الوقت_ms = std::chrono::duration<double, std::milli>(
                نهاية - بداية).count();
            
            نتائج.push_back(نتيجة);
        }
        
        // ملخص
        size_t نجاح = 0, فشل = 0;
        for (const auto& ن : نتائج) {
            if (ن.نجح) نجاح++;
            else فشل++;
        }
        
        std::cout << "\n───────────────────────────────────────────\n";
        std::cout << "📊 " << نجاح << "/" << نتائج.size() << " نجح";
        if (فشل > 0) {
            std::cout << " ⚠️ " << فشل << " فشل";
        }
        std::cout << "\n\n";
        
        return نتائج;
    }
    
private:
    std::string m_الاسم;
    std::vector<std::pair<std::string, std::function<void()>>> m_اختبارات;
};

/**
 * ماكرو للتأكيد
 */
#define تأكد(شرط, رسالة) \
    if (!(شرط)) { \
        throw std::runtime_error(std::string(رسالة) + \
            " (في سطر " + std::to_string(__LINE__) + ")"); \
    }

#define تأكد_مساواة(فعلي, متوقع, رسالة) \
    if ((فعلي) != (متوقع)) { \
        std::stringstream ss; \
        ss << رسالة << " - متوقع: " << (متوقع) << ", فعلي: " << (فعلي); \
        throw std::runtime_error(ss.str()); \
    }

