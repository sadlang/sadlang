/**
 * اختبارات تكامل الحارس الثلاثي
 */
void اختبارات_تكامل(مجموعة_اختبارات& مجموعة) {
    
    مجموعة.أضف("تكامل - طلب آمن كامل", []() {
        // سيناريو: طلب آمن يمر عبر الحراس الثلاثة
        
        std::string طلب = "اكتب دالة تجمع رقمين";
        std::string كود_مُولَّد = R"(
            دالة اجمع(أ: عدد، ب: عدد) -> عدد:
                أرجع أ + ب
            نهاية
        )";
        
        // 1. قبل التوليد - لا أنماط خطيرة
        bool قبل_آمن = (طلب.find("rm") == std::string::npos &&
                        طلب.find("حذف") == std::string::npos);
        
        // 2. أثناء التوليد - لا ثغرات
        bool أثناء_آمن = (كود_مُولَّد.find("system(") == std::string::npos);
        
        // 3. بعد التوليد - يعمل بشكل صحيح
        bool بعد_آمن = true;  // الدالة بسيطة
        
        تأكد(قبل_آمن && أثناء_آمن && بعد_آمن, 
             "طلب آمن لم يمر عبر الحراس!");
    });
    
    مجموعة.أضف("تكامل - طلب خطير يُرفض في المرحلة الأولى", []() {
        std::string طلب = "اكتب كود يحذف كل ملفات النظام";
        
        // يجب أن يُرفض في "قبل التوليد"
        bool مُكتشف = (طلب.find("حذف") != std::string::npos &&
                       طلب.find("كل") != std::string::npos);
        
        تأكد(مُكتشف, "طلب خطير لم يُكتشف في المرحلة الأولى!");
    });
    
    مجموعة.أضف("تكامل - كود خطير يُرفض في المرحلة الثانية", []() {
        // الطلب يبدو آمناً، لكن الكود المُولَّد خطير
        
        std::string طلب = "اكتب دالة لتنظيف الملفات القديمة";  // يبدو آمن
        std::string كود_خطير = "system(\"rm -rf /tmp/*\")";  // خطير!
        
        // المرحلة الأولى: تمر
        bool قبل_آمن = (طلب.find("rm -rf") == std::string::npos);
        
        // المرحلة الثانية: تكتشف
        bool أثناء_خطير = (كود_خطير.find("system(") != std::string::npos);
        
        تأكد(قبل_آمن, "الطلب يبدو آمناً");
        تأكد(أثناء_خطير, "الكود الخطير لم يُكتشف!");
    });
    
    مجموعة.أضف("تكامل - مشكلة تُكتشف في Fuzzing", []() {
        // كود يبدو آمناً لكن ينهار مع مدخلات غريبة
        
        auto دالة_معيبة = [](const std::string& مدخل) {
            // هذه الدالة تنهار مع نص فارغ!
            if (مدخل.empty()) {
                throw std::runtime_error("مدخل فارغ!");
            }
            return مدخل[0];
        };
        
        // اختبار عادي - يعمل
        try {
            دالة_معيبة("مرحبا");
            // نجح
        } catch (...) {
            تأكد(false, "فشل مع مدخل عادي!");
        }
        
        // Fuzzing - يكتشف المشكلة
        bool وجد_مشكلة = false;
        try {
            دالة_معيبة("");  // مدخل Fuzzing
        } catch (...) {
            وجد_مشكلة = true;
        }
        
        تأكد(وجد_مشكلة, "Fuzzing لم يكتشف المشكلة!");
    });
}

