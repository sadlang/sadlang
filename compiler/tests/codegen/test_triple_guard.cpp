/**
 * اختبارات مولد مدخلات Fuzzing
 */
void اختبارات_Fuzzing(مجموعة_اختبارات& مجموعة) {
    
    مجموعة.أضف("Fuzzing - توليد نص فارغ", []() {
        std::string مدخل = "";  // نص فارغ
        تأكد_مساواة(مدخل.length(), 0u, "النص ليس فارغاً!");
    });
    
    مجموعة.أضف("Fuzzing - توليد نص طويل", []() {
        std::string مدخل(1000000, 'A');  // مليون حرف
        تأكد(مدخل.length() >= 1000000, "النص ليس طويلاً كفاية!");
    });
    
    مجموعة.أضف("Fuzzing - توليد SQL Injection", []() {
        std::string مدخل = "' OR '1'='1";
        تأكد(مدخل.find("OR") != std::string::npos, "لم يتم توليد SQL Injection!");
    });
    
    مجموعة.أضف("Fuzzing - اختبار دالة بسيطة", []() {
        // دالة تجمع رقمين
        auto دالة_جمع = [](int أ, int ب) { return أ + ب; };
        
        // اختبار عادي
        تأكد_مساواة(دالة_جمع(2, 3), 5, "2+3 يجب أن يساوي 5");
        
        // اختبار حدي
        // تأكد_مساواة(دالة_جمع(INT_MAX, 1), ???, "تجاوز!");
        // هذا سيكشف مشكلة integer overflow
    });
    
    مجموعة.أضف("Fuzzing - اختبار دالة نصية", []() {
        // دالة تعكس نص
        auto اعكس = [](const std::string& نص) {
            return std::string(نص.rbegin(), نص.rend());
        };
        
        // اختبار عادي
        تأكد_مساواة(اعكس("مرحبا"), "ابحرم", "العكس غير صحيح!");
        
        // اختبار نص فارغ
        تأكد_مساواة(اعكس(""), "", "عكس الفارغ يجب أن يكون فارغاً!");
    });
}

