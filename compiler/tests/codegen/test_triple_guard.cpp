/**
 * اختبارات قواعد الفحص
 */
void اختبارات_قواعد_الفحص(مجموعة_اختبارات& مجموعة) {
    
    مجموعة.أضف("SQL Injection - اكتشاف استعلام غير آمن", []() {
        std::string كود = "query = \"SELECT * FROM users WHERE id = \" + user_input";
        
        bool خطير = (كود.find("SELECT") != std::string::npos &&
                     كود.find("+") != std::string::npos);
        
        تأكد(خطير, "لم يتم اكتشاف SQL Injection!");
    });
    
    مجموعة.أضف("SQL Injection - استعلام آمن", []() {
        std::string كود = "query = \"SELECT * FROM users WHERE id = ?\"";
        
        // استخدام ? للمعاملات آمن
        bool آمن = (كود.find("?") != std::string::npos &&
                    كود.find("+") == std::string::npos);
        
        تأكد(آمن, "استعلام آمن تم اعتباره خطيراً!");
    });
    
    مجموعة.أضف("Command Injection - اكتشاف system()", []() {
        std::string كود = "system(user_command)";
        
        bool خطير = (كود.find("system(") != std::string::npos);
        تأكد(خطير, "لم يتم اكتشاف Command Injection!");
    });
    
    مجموعة.أضف("Buffer Overflow - اكتشاف strcpy", []() {
        std::string كود = "strcpy(buffer, input)";
        
        bool خطير = (كود.find("strcpy") != std::string::npos);
        تأكد(خطير, "لم يتم اكتشاف Buffer Overflow المحتمل!");
    });
    
    مجموعة.أضف("Hardcoded Secret - اكتشاف كلمة سر", []() {
        std::string كود = "password = \"admin123\"";
        
        bool خطير = (كود.find("password") != std::string::npos &&
                     كود.find("=") != std::string::npos &&
                     كود.find("\"") != std::string::npos);
        
        تأكد(خطير, "لم يتم اكتشاف كلمة السر المكشوفة!");
    });
    
    مجموعة.أضف("Path Traversal - اكتشاف ../", []() {
        std::string كود = "open(\"../../../etc/passwd\")";
        
        bool خطير = (كود.find("../") != std::string::npos);
        تأكد(خطير, "لم يتم اكتشاف Path Traversal!");
    });
}

