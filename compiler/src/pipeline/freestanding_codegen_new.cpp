/**
 * ابدأ_وحدة — إعداد وحدة ترجمة جديدة
 *
 * يهيئ الحالة الداخلية ويتحقق من صلاحية الإعدادات.
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_وحدة(const std::string& اسم) {
    // حفظ اسم الوحدة للتشخيص
    اسم_الوحدة_ = اسم;

    // تصفير العدّادات لكل وحدة جديدة
    عدّاد_الإذا_   = 0;
    عدّاد_الطالما_ = 0;
    عدّاد_اللكل_   = 0;
    عدّاد_الحلقة_  = 0;
    عدّاد_التطابق_ = 0;

    // تصفير متتبعات الاكتمال
    وُجدت_نقطة_دخول_ = false;
    وُجد_معالج_ذعر_   = false;

    // مسح قوائم الرسائل
    تحذيرات_.clear();
    أخطاء_.clear();

    // مسح مكدسات السياق
    while (!مكدس_الحلقات_.empty()) مكدس_الحلقات_.pop();
    while (!مكدس_الشروط_.empty())  مكدس_الشروط_.pop();

    return نتيجة_توليد::نجاح_();
}

/**
 * أنهِ_وحدة — التحقق من اكتمال الوحدة
 *
 * يتحقق من وجود المتطلبات اللازمة لوحدة freestanding صحيحة.
 */
نتيجة_توليد FreestandingCodeGen::أنهِ_وحدة() {
    // --- التحقق من نقطة الدخول ---
    if (إعداد_.noMainEnabled && !وُجدت_نقطة_دخول_) {
        // no_main مفعّل → يجب وجود #[نقطة_دخول]
        return نتيجة_توليد::خطأ_(
            FreestandingError::نقطة_دخول_مفقودة,
            "خطأ: لم يُعثر على دالة #[نقطة_دخول] في الوحدة '"
                + اسم_الوحدة_ + "'.\n"
                "الحل: أضف #[نقطة_دخول] قبل دالة نقطة البدء:\n"
                "    #[نقطة_دخول]\n"
                "    دالة _start() -> ! { حلقة {} }",
            "Error: No #[entry_point] function found in unit '" + اسم_الوحدة_ + "'.\n"
                "Fix: Add #[entry_point] before your startup function:\n"
                "    #[entry_point] fn _start() -> ! { loop {} }",
            اسم_الوحدة_
        );
    }

    // --- التحقق من معالج الذعر ---
    if (إعداد_.noStdEnabled && !وُجد_معالج_ذعر_) {
        // تحذير (ليس خطأ) — المعالج الافتراضي sad_panic موجود
        أضف_تحذير_(
            "تحذير: لم يُعرّف #[معالج_ذعر] مخصص. "
            "سيُستخدم المعالج الافتراضي (حلقة لانهائية + hlt).\n"
            "للتخصيص:\n"
            "    #[معالج_ذعر]\n"
            "    دالة عند_الذعر(معلومات: &معلومات_ذعر) -> ! {\n"
            "        // معالجتك الخاصة\n"
            "    }"
        );
    }

    // --- التحقق من أن المكدسات فارغة (لا وجد تقسيم غير مغلق) ---
    if (!مكدس_الحلقات_.empty()) {
        أضف_تحذير_("تحذير: توجد " +
            std::to_string(مكدس_الحلقات_.size()) +
            " حلقة(حلقات) لم تُغلق. قد تكون هناك مشكلة في الكود.");
    }

    if (!مكدس_الشروط_.empty()) {
        أضف_تحذير_("تحذير: توجد " +
            std::to_string(مكدس_الشروط_.size()) +
            " جملة إذا لم تُغلق.");
    }

    return نتيجة_توليد::نجاح_();
}

