/**
 * ابدأ_إذا — توليد بداية جملة if
 *
 * يُنشئ سياق الشرط ويضعه في مكدس الشروط.
 * الكتل المُنشأة (بالأسماء):
 *   - if.N.then  → جسم الشرط الصحيح
 *   - if.N.else  → جسم الشرط الخاطئ (إذا وجد وإلا)
 *   - if.N.end   → ما بعد جملة الشرط (دمج المسارين)
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_إذا(const std::string& تسمية_شرط) {
    // توليد معرّف فريد لهذه الجملة
    int رقم = ++عدّاد_الإذا_;

    // بناء أسماء الكتل (تستخدم في LLVM IR)
    سياق_شرط سياق;
    سياق.تسمية_صحيح = ولِّد_تسمية_("إذا." + تسمية_شرط + ".صحيح", رقم);
    سياق.تسمية_خطأ  = ولِّد_تسمية_("إذا." + تسمية_شرط + ".خطأ",  رقم);
    سياق.تسمية_دمج  = ولِّد_تسمية_("إذا." + تسمية_شرط + ".نهاية", رقم);
    سياق.له_وإلا    = false;

    // حفظ السياق في المكدس
    مكدس_الشروط_.push(سياق);

    return نتيجة_توليد::نجاح_();
}

/**
 * ابدأ_وإلا — الانتقال لفرع وإلا
 *
 * يُغلق فرع صحيح (إن لم يكن مغلقاً) ويفتح فرع خطأ.
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_وإلا() {
    // التحقق من وجود إذا نشط
    if (مكدس_الشروط_.empty()) {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'وإلا' بدون 'إذا' سابق",
            "Error: 'else' without preceding 'if'",
            اسم_الوحدة_
        );
    }

    // تعيين وجود وإلا
    مكدس_الشروط_.top().له_وإلا = true;

    return نتيجة_توليد::نجاح_();
}

/**
 * ابدأ_وإلا_إذا — الانتقال لفرع وإلا_إذا
 *
 * يُغلق الفرع السابق ويُنشئ فرعاً شرطياً جديداً.
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_وإلا_إذا(const std::string& تسمية_شرط) {
    // التحقق من وجود إذا نشط
    if (مكدس_الشروط_.empty()) {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'وإلا_إذا' بدون 'إذا' سابق",
            "Error: 'else if' without preceding 'if'",
            اسم_الوحدة_
        );
    }

    // تحديث التسمات للشرط الجديد
    int رقم = ++عدّاد_الإذا_;
    auto& سياق = مكدس_الشروط_.top();
    سياق.تسمية_صحيح = ولِّد_تسمية_("وإلا_إذا." + تسمية_شرط + ".صحيح", رقم);
    سياق.تسمية_خطأ  = ولِّد_تسمية_("وإلا_إذا." + تسمية_شرط + ".خطأ",  رقم);
    سياق.له_وإلا     = false;

    return نتيجة_توليد::نجاح_();
}

/**
 * أنهِ_إذا — إغلاق جملة الشرط
 *
 * يُخرج السياق من المكدس ويُنتج كتلة الدمج.
 */
نتيجة_توليد FreestandingCodeGen::أنهِ_إذا() {
    if (مكدس_الشروط_.empty()) {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'أنهِ_إذا' بدون 'إذا' مفتوح",
            "Error: end_if without open if statement",
            اسم_الوحدة_
        );
    }

    // إزالة من المكدس — الجملة مكتملة
    مكدس_الشروط_.pop();

    return نتيجة_توليد::نجاح_();
}

