/**
 * ابدأ_حلقة — بدء حلقة لانهائية
 *
 * الكتل المُنشأة:
 *   - حلقة.N.جسم   → جسم الحلقة (يُعاد تنفيذه مراراً)
 *   - حلقة.N.نهاية → ما بعد الحلقة (يصل إليه فقط بـ أوقف)
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_حلقة(const std::string& تسمية) {
    int رقم = ++عدّاد_الحلقة_;

    سياق_حلقة سياق;
    سياق.نوع_الحلقة    = سياق_حلقة::النوع::حلقة_ن;
    سياق.تسمية_البداية = ولِّد_تسمية_("حلقة." + تسمية + ".جسم",    رقم);
    سياق.تسمية_الجسم   = سياق.تسمية_البداية;
    سياق.تسمية_التحديث = سياق.تسمية_البداية; // في حلقة: التحديث = البداية
    سياق.تسمية_النهاية = ولِّد_تسمية_("حلقة." + تسمية + ".نهاية",  رقم);
    سياق.له_تسمية = false;

    مكدس_الحلقات_.push(سياق);

    return نتيجة_توليد::نجاح_();
}

