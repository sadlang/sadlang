/**
 * تحقق_من_النوع — التحقق من توافق النوع مع freestanding
 */
نتيجة_توليد FreestandingCodeGen::تحقق_من_النوع(const std::string& اسم_النوع) {
    // فحص الأنواع المحظورة صراحةً
    for (const auto& محظور : أنواع_محظورة_) {
        if (اسم_النوع.find(محظور) != std::string::npos) {
            return نتيجة_توليد::خطأ_(
                FreestandingError::نوع_غير_مدعوم,
                "خطأ: النوع '" + اسم_النوع + "' غير مدعوم في وضع بلا_مكتبة_قياسية.\n"
                "السبب: يعتمد على المكتبة القياسية.\n"
                "الحل: استخدم أنواع فريستاندنج:\n"
                "  ع8..ع64، ح8..ح64، حجم، منطق، عرض_نص، بار_نص",
                "Error: Type '" + اسم_النوع + "' not supported in no_std mode.\n"
                "It depends on the standard library.\n"
                "Use: u8..u64, i8..i64, usize, bool, str_view, text_buffer",
                اسم_الوحدة_
            );
        }
    }

    return نتيجة_توليد::نجاح_();
}

/**
 * تحقق_من_الرمز — التحقق من أن الرمز ليس من المكتبة القياسية
 */
نتيجة_توليد FreestandingCodeGen::تحقق_من_الرمز(const std::string& الرمز) {
    // --- فحص بوادئ المكتبة القياسية ---
    for (const auto& بادئة : رموز_مكتبة_قياسية_) {
        if (الرمز.find(بادئة) != std::string::npos) {
            return نتيجة_توليد::خطأ_(
                FreestandingError::رمز_مكتبة_قياسية,
                "خطأ: الرمز '" + الرمز + "' من المكتبة القياسية.\n"
                "في وضع #![بلا_مكتبة_قياسية] هذا غير مسموح.\n"
                "الحل: استخدم بدائل sad_core.h",
                "Error: Symbol '" + الرمز + "' is from the standard library.\n"
                "Not allowed in #![no_std] mode.",
                اسم_الوحدة_
            );
        }
    }

    // --- فحص الرموز المحظورة ---
    for (const auto& محظور : رموز_محظورة_) {
        if (الرمز == محظور) {
            return نتيجة_توليد::خطأ_(
                FreestandingError::رمز_مكتبة_قياسية,
                "خطأ: الدالة '" + الرمز + "' محظورة في وضع فريستاندنج.\n"
                "بدائل متاحة في sad_core.h:\n"
                "  malloc \u2192 sad_alloc()  |  memcpy \u2192 sad_memcpy()\n"
                "  printf \u2192 بار_نص + طباعة_تسلسلي()\n"
                "  assert \u2192 تأكد()       |  exit \u2192 ذعر()",
                "Error: Function '" + الرمز + "' is banned in freestanding mode.\n"
                "Alternatives available in sad_core.h",
                اسم_الوحدة_
            );
        }
    }

    return نتيجة_توليد::نجاح_();
}

