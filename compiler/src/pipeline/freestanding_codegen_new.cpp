/**
 * افحص_توافق_freestanding — فحص سريع للكود المصدري
 *
 * يبحث عن أنماط محظورة ويُعيد قائمة المشكلات.
 */
std::vector<std::string> افحص_توافق_freestanding(const std::string& المصدر) {
    std::vector<std::string> مشكلات;

    // --- البحث عن includes من المكتبة القياسية ---
    const std::vector<std::string> مكتبات_محظورة = {
        "#include <stdio.h>",      "#include <stdlib.h>",
        "#include <string.h>",     "#include <iostream>",
        "#include <string>",       "#include <vector>",
    };

    for (const auto& مكتبة : مكتبات_محظورة) {
        if (المصدر.find(مكتبة) != std::string::npos) {
            مشكلات.push_back(
                "استخدام محظور: '" + مكتبة + "' غير مسموح في وضع freestanding.\n"
                "الحل: أضف #include \"sad_core.h\" بدلاً منه."
            );
        }
    }

    // --- البحث عن استخدام printf/cout ---
    if (المصدر.find("printf") != std::string::npos) {
        مشكلات.push_back(
            "استخدام printf() محظور في freestanding.\n"
            "الحل: استخدم بار_نص + طباعة_تسلسلي() المخصصة."
        );
    }

    if (المصدر.find("std::cout") != std::string::npos) {
        مشكلات.push_back(
            "استخدام std::cout محظور في freestanding.\n"
            "الحل: استخدم قناة إخراج مخصصة للنواة."
        );
    }

    // --- البحث عن new/delete ---
    if (المصدر.find("new ") != std::string::npos ||
        المصدر.find("new\t") != std::string::npos) {
        مشكلات.push_back(
            "استخدام new محظور في freestanding (يتطلب runtime C++).\n"
            "الحل: استخدم مخصّص freestanding: sad_alloc() بعد تسجيل مخصّص."
        );
    }

    return مشكلات;
}

