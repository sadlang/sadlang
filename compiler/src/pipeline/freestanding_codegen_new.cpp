/**
 * ابدأ_طالما — بدء حلقة while
 *
 * الكتل المُنشأة:
 *   - while.N.شرط  → كتلة التحقق من الشرط
 *   - while.N.جسم  → جسم الحلقة
 *   - while.N.نهاية → ما بعد الحلقة
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_طالما(const std::string& تسمية) {
    int رقم = ++عدّاد_الطالما_;

    // بناء سياق الحلقة
    سياق_حلقة سياق;
    سياق.نوع_الحلقة  = سياق_حلقة::النوع::طالما_ن;
    سياق.تسمية_البداية = ولِّد_تسمية_("طالما." + تسمية + ".شرط",   رقم);
    سياق.تسمية_الجسم  = ولِّد_تسمية_("طالما." + تسمية + ".جسم",    رقم);
    سياق.تسمية_النهاية = ولِّد_تسمية_("طالما." + تسمية + ".نهاية",  رقم);
    سياق.تسمية_التحديث = سياق.تسمية_البداية; // في طالما: التحديث = الشرط
    سياق.له_تسمية = false;

    مكدس_الحلقات_.push(سياق);

    return نتيجة_توليد::نجاح_();
}

/**
 * أنهِ_طالما — إغلاق حلقة while
 */
نتيجة_توليد FreestandingCodeGen::أنهِ_طالما() {
    if (مكدس_الحلقات_.empty() ||
        مكدس_الحلقات_.top().نوع_الحلقة != سياق_حلقة::النوع::طالما_ن)
    {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'أنهِ_طالما' بدون 'ابدأ_طالما' مفتوح",
            "Error: end_while without open while loop",
            اسم_الوحدة_
        );
    }

    مكدس_الحلقات_.pop();
    return نتيجة_توليد::نجاح_();
}

