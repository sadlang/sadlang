/**
 * منشئ FreestandingCodeGen
 *
 * يهيئ المولّد بالإعدادات المعطاة ويعدّ الحالة الداخلية.
 */
FreestandingCodeGen::FreestandingCodeGen(
    const pipeline::NoStdConfig& إعداد_بلا_مكتبة)
    : إعداد_(إعداد_بلا_مكتبة)
    , عدّاد_الإذا_(0)
    , عدّاد_الطالما_(0)
    , عدّاد_اللكل_(0)
    , عدّاد_الحلقة_(0)
    , عدّاد_التطابق_(0)
    , وُجدت_نقطة_دخول_(false)
    , وُجد_معالج_ذعر_(false)
{
    // التحقق من صحة الإعدادات عند الإنشاء
    if (!إعداد_.noStdEnabled) {
        أضف_تحذير_(
            "تحذير: FreestandingCodeGen مستخدم لكن no_std غير مفعّل. "
            "أضف #![بلا_مكتبة_قياسية] في أعلى الملف.");
    }
}

FreestandingCodeGen::~FreestandingCodeGen() {
    // لا توجد موارد ديناميكية تحتاج تحريراً
}

