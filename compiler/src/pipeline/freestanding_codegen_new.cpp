/**
 * ولِّد_أوقف — توليد جملة break
 *
 * ينتقل إلى كتلة النهاية للحلقة الحالية.
 * يدعم الحلقات المتداخلة بشكل صحيح (ينتقل لأقرب حلقة فقط).
 */
نتيجة_توليد FreestandingCodeGen::ولِّد_أوقف() {
    // التحقق من وجود حلقة نشطة
    if (مكدس_الحلقات_.empty()) {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'أوقف' خارج حلقة — لا توجد حلقة نشطة للخروج منها.\n"
            "الحل: استخدم 'أوقف' فقط داخل طالما/لكل/حلقة.",
            "Error: 'break' outside loop \u2014 no active loop to exit from.\n"
            "Fix: Use 'break' only inside while/for/loop.",
            اسم_الوحدة_
        );
    }

    // الوجهة: كتلة نهاية الحلقة الحالية (الأعلى في المكدس)
    // التوليد الفعلي يتم في LLVMControlFlow
    return نتيجة_توليد::نجاح_();
}

/**
 * ولِّد_أكمل — توليد جملة continue
 *
 * ينتقل إلى:
 *   - كتلة التحديث في حلقة لكل (لتنفيذ الخطوة ثم التحقق من الشرط)
 *   - كتلة البداية في حلقة طالما/حلقة (للتحقق من الشرط مباشرة)
 */
نتيجة_توليد FreestandingCodeGen::ولِّد_أكمل() {
    // التحقق من وجود حلقة نشطة
    if (مكدس_الحلقات_.empty()) {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'أكمل' خارج حلقة — لا توجد حلقة نشطة للانتقال لتكرارها.\n"
            "الحل: استخدم 'أكمل' فقط داخل طالما/لكل/حلقة.",
            "Error: 'continue' outside loop \u2014 no active loop to continue.\n"
            "Fix: Use 'continue' only inside while/for/loop.",
            اسم_الوحدة_
        );
    }

    // الوجهة: كتلة التحديث للحلقة الحالية
    // (في حلقة لكل → التحديث → الشرط)
    // (طالما/حلقة → البداية/الشرط مباشرة)
    return نتيجة_توليد::نجاح_();
}

