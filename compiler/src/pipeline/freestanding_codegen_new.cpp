/**
 * ابدأ_لكل — بدء حلقة for
 *
 * الكتل المُنشأة:
 *   - for.N.شرط    → كتلة التحقق من شرط الاستمرار
 *   - for.N.جسم    → جسم الحلقة
 *   - for.N.تحديث  → كتلة تحديث المتغير (تُنفَّذ بعد كل تكرار)
 *   - for.N.نهاية  → ما بعد الحلقة
 *
 * ترتيب التنفيذ في حلقة for:
 *   1. التهيئة (مرة واحدة قبل البدء)
 *   2. شرط → إذا صحيح: انتقل للجسم، إلا: انتقل للنهاية
 *   3. جسم الحلقة
 *   4. تحديث المتغير
 *   5. عُد للخطوة 2
 */
نتيجة_توليد FreestandingCodeGen::ابدأ_لكل(const std::string& تسمية_متغير) {
    int رقم = ++عدّاد_اللكل_;

    سياق_حلقة سياق;
    سياق.نوع_الحلقة  = سياق_حلقة::النوع::لكل_ن;
    سياق.تسمية_البداية = ولِّد_تسمية_("لكل." + تسمية_متغير + ".شرط",    رقم);
    سياق.تسمية_الجسم  = ولِّد_تسمية_("لكل." + تسمية_متغير + ".جسم",     رقم);
    سياق.تسمية_التحديث = ولِّد_تسمية_("لكل." + تسمية_متغير + ".تحديث",  رقم);
    سياق.تسمية_النهاية = ولِّد_تسمية_("لكل." + تسمية_متغير + ".نهاية",  رقم);
    سياق.له_تسمية = false;

    مكدس_الحلقات_.push(سياق);

    return نتيجة_توليد::نجاح_();
}

/**
 * أنهِ_لكل — إغلاق حلقة for
 */
نتيجة_توليد FreestandingCodeGen::أنهِ_لكل() {
    if (مكدس_الحلقات_.empty() ||
        مكدس_الحلقات_.top().نوع_الحلقة != سياق_حلقة::النوع::لكل_ن)
    {
        return نتيجة_توليد::خطأ_(
            FreestandingError::توقف_خارج_حلقة,
            "خطأ: 'أنهِ_لكل' بدون 'ابدأ_لكل' مفتوح",
            "Error: end_for without open for loop",
            اسم_الوحدة_
        );
    }

    مكدس_الحلقات_.pop();
    return نتيجة_توليد::نجاح_();
}

