/**
 * أنشئ_تقرير_freestanding — تقرير توافق مفصّل
 */
std::string أنشئ_تقرير_freestanding(
    const std::string& المصدر,
    const std::string& اسم_الملف)
{
    std::ostringstream تقرير;
    تقرير << "══════════════════════════════════════════════════\n";
    تقرير << "   تقرير توافق Freestanding — لغة ص\n";
    تقرير << "   الملف: " << اسم_الملف << "\n";
    تقرير << "══════════════════════════════════════════════════\n\n";

    // --- فحص السمات المطلوبة ---
    bool له_بلا_مكتبة = المصدر.find("#![بلا_مكتبة_قياسية]") != std::string::npos
                       || المصدر.find("#![no_std]")            != std::string::npos;
    bool له_بلا_رئيسة = المصدر.find("#![بلا_رئيسية]") != std::string::npos
                        || المصدر.find("#![no_main]")      != std::string::npos;
    bool له_نقطة_دخول = المصدر.find("#[نقطة_دخول]") != std::string::npos
                       || المصدر.find("#[entry_point]") != std::string::npos;

    تقرير << "◆ السمات المطلوبة:\n";
    تقرير << "  " << (له_بلا_مكتبة ? "✓" : "✗")
           << " #![بلا_مكتبة_قياسية] / #![no_std]\n";
    تقرير << "  " << (له_بلا_رئيسة ? "✓" : "○")
           << " #![بلا_رئيسية] / #![no_main]  (اختياري)\n";
    تقرير << "  " << (له_نقطة_دخول ? "✓" : "○")
           << " #[نقطة_دخول] / #[entry_point]"
           << (له_بلا_رئيسة && !له_نقطة_دخول ? "  ⚠ مطلوب!" : "") << "\n\n";

    // --- فحص التوافق ---
    auto مشكلات = افحص_توافق_freestanding(المصدر);

    if (مشكلات.empty()) {
        تقرير << "◆ النتيجة: ✓ الكود متوافق مع وضع freestanding\n";
    } else {
        تقرير << "◆ المشكلات (" << مشكلات.size() << "):\n";
        for (size_t ن = 0; ن < مشكلات.size(); ++ن) {
            تقرير << "  " << (ن + 1) << ". " << مشكلات[ن] << "\n";
        }
    }

    تقرير << "\n══════════════════════════════════════════════════\n";
    return تقرير.str();
}

