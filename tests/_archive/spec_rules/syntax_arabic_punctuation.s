# Test 1: Arabic comma in function calls
دالة جمع_ثلاثة(رقم أ، رقم ب، رقم ج) -> رقم
    إرجاع أ + ب + ج
نهاية

# استخدام الفاصلة العربية / Using Arabic comma
رقم نتيجة1 = جمع_ثلاثة(10، 20، 30)
اطبع(ن"النتيجة 1 (فاصلة عربية): {نتيجة1}")  # Expected: 60

# استخدام الفاصلة الإنجليزية / Using English comma
رقم نتيجة2 = جمع_ثلاثة(5, 10, 15)
اطبع(ن"النتيجة 2 (فاصلة إنجليزية): {نتيجة2}")  # Expected: 30

# Test 2: Mixed commas (both should work)
دالة أربعة_معاملات(رقم أ، رقم ب، رقم ج، رقم د) -> رقم
    إرجاع أ * ب + ج * د
نهاية

رقم نتيجة3 = أربعة_معاملات(2، 3, 4، 5)  # Mixed commas
اطبع(ن"النتيجة 3 (مختلط): {نتيجة3}")  # Expected: 2*3 + 4*5 = 26

