# Test 9: Function with many parameters (Arabic comma)
دالة حساب_معقد(رقم أ، رقم ب، رقم ج، رقم د، رقم هـ) -> رقم
    إرجاع (أ + ب) * (ج - د) + هـ
نهاية

رقم نتيجة_معقدة = حساب_معقد(5، 3، 10، 2، 7)
اطبع(ن"\nنتيجة معقدة: {نتيجة_معقدة}")  # (5+3)*(10-2)+7 = 8*8+7 = 71

