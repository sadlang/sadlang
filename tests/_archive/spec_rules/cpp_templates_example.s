// اختبار 10: تطبيق عملي - قاموس عام / Test 10: Practical - Generic dict
// ============================================================
صنف <K، V> قاموس_عام
    مصفوفة مفاتيح
    مصفوفة قيم
    
    باني()
        هذا.مفاتيح = []
        هذا.قيم = []
    نهاية
    
    دالة ضع(K مفتاح، V قيمة)
        // البحث عن المفتاح / Search for key
        لكل ع في نطاق(طول(هذا.مفاتيح))
            إذا هذا.مفاتيح[ع] == مفتاح
                هذا.قيم[ع] = قيمة
                إرجاع
            نهاية
        نهاية
        
        // إضافة جديد / Add new
        هذا.مفاتيح.أضف(مفتاح)
        هذا.قيم.أضف(قيمة)
    نهاية
    
    دالة V احصل(K مفتاح)
        لكل ع في نطاق(طول(هذا.مفاتيح))
            إذا هذا.مفاتيح[ع] == مفتاح
                إرجاع هذا.قيم[ع]
            نهاية
        نهاية
        إرجاع لاغ
    نهاية
نهاية

قاموس_عام<نص، رقم> أعمار = قاموس_عام<نص، رقم>()
