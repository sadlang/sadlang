#!/usr/bin/env bash
# ============================================================================
# (SEM045 / RFC عقد الغياب — المرحلة أ) الفراغ لا يعبر إلى خانة مصنّفة
#
# (AR) المُشغّل القياسيّ يقارن stdout بلا أعلام، فلا يغطّي اختلاف السلوك حسب
#      محور الصرامة (D6). هذا السكربت يقيس أشكال العبور الستة في **المفسّر**:
#        ش١: غياب خريطة_احصل ⇒ خانة «نص»
#        ش٢: غياب خريطة_احصل ⇒ خانة اختيارية «نص عدمي» (لا باب خلفيًّا)
#        ش٣: ناتج دالة لم تُرجِع في فرعها ⇒ خانة «نص» (الحارس يحكم القيمة لا المصدر)
#        ش٥: إعادة إسناد فراغ لخانة «نص» قائمة (نصّ الـRFC يشملها)
#        ش٦: الإسناد داخل جسم دالة — الإيقاف موضعيّ لا مؤجَّل لنهاية البرنامج
#        ش٤: البديل الثالث لخريطة_احصل يلغي الفراغ ⇒ لا تشخيص أصلًا
#      وعلى أربع درجات: بلا أعلام (الافتراضيّ = تعلم) · --تعلم تحذير+خروج0 ·
#      --جامع صمت+خروج0 · --إنتاج وسم [خطأ نوع SEM045]+خروج≠0+لا تنفيذ لما بعده.
#
# (EN) Measures SEM045 (Void must not cross into typed slots) across the D6
#      strictness axis in the interpreter, including the no-flag default (Warn)
#      and mid-function fatal stop. Compiler-side enforcement is stage أ٢ of
#      the absence-contract RFC (sadlang/rfcs#58) — a declared follow-up wave.
#
# الاستعمال:  bash tests/behavior/null_safety/ns07_void_crossing_check.sh
#
# ⚠️ **دَينٌ مُقيَّدٌ — هذا السكربتُ لا يُنادَى من أيِّ بوّابةٍ ولا سيرِ عمل.**
#
#      **ثمانيةُ نداءاتٍ للمفسّرِ وصفرٌ للمترجم** — سكربتٌ أحاديُّ المحرّكِ بالكامل. قِيس ٢٠٢٦-٠٩-٠٤: ٤٩ توكيدًا، ١٦ نجح و٣٣ أخفق، وكلُّها لغيابِ المفسّر. ⇒ مصفوفةُ SEM045 (عبورُ الفراغِ) لأوضاعِ «افتراضي/تعلم/جامع/إنتاج» **غيرُ مقيسةٍ اليومَ بشيء**. وهذه خسارةُ تغطيةٍ حقيقيّةٌ لا تُسَدُّ بتحريرِ هذا الملفّ: تحتاجُ نقلَ التوكيداتِ إلى المترجمِ وإثباتَ ما يقابلُها فيه.
#
#      وسببُ التقييدِ أنّ «متجاهَل» يجبُ أن يبقى قرارًا لا نسيانًا: حارسٌ
#      لا يُنادَى ليس حارسًا، وسكوتُه يُقرأُ خضرةً وهو صمتٌ. والوصلُ
#      يحتاجُ فصلَ نصفِ المفسّرِ أوّلًا — وذاك عملٌ مقصودٌ لا يُقحَمُ في
#      رقعةِ تنظيف. والنظيرُ الموصولُ: `ns03` (بوّابةٌ في `ci.yml`).
# (EN) TRACKED DEBT — no gate or workflow invokes this script. "Ignored"
#      must stay a decision, never an oversight: a guard nobody calls is
#      not a guard, and its silence reads as green while it is only
#      silence. Wiring it up requires splitting the interpreter half out
#      first, which is deliberate work, not a cleanup patch. The wired
#      sibling is ns03 (a gate in ci.yml).
# ============================================================================
set -u
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
RUN="$ROOT/build/bin/Debug/sad-run.exe"
[ -x "$RUN" ] || RUN="$ROOT/dist/Debug/sad-run.exe"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

pass=0; fail=0
check() { # وصف ، شرط(0=نجاح)
  if [ "$2" -eq 0 ]; then echo "  ✅ $1"; pass=$((pass+1));
  else echo "  ❌ $1"; fail=$((fail+1)); fi
}

S1="$TMP/shape1.ص"
cat > "$S1" <<'SAD'
استورد خرائط
متغير سجل = خريطة()
متغير غائب = خريطة_احصل(سجل، "لا_وجود_له")
متغير نص اسم = غائب
اطبع_سطر("بعد_الإسناد")
SAD

S2="$TMP/shape2.ص"
cat > "$S2" <<'SAD'
استورد خرائط
متغير سجل = خريطة()
نص عدمي اسم = خريطة_احصل(سجل، "لا_وجود_له")
اطبع_سطر("بعد_الإسناد")
SAD

S3="$TMP/shape3.ص"
cat > "$S3" <<'SAD'
دالة نص ربما_ترجع(رقم شرط)
    إذا (شرط > 0)
        ارجع "قيمة"
    نهاية
نهاية
متغير نص ناتج = ربما_ترجع(0)
اطبع_سطر("بعد_الإسناد")
SAD

S4="$TMP/shape4.ص"
cat > "$S4" <<'SAD'
استورد خرائط
متغير سجل = خريطة()
متغير نص اسم = خريطة_احصل(سجل، "لا_وجود_له"، "بديل")
اطبع_سطر("النتيجة:" + اسم)
SAD

S5="$TMP/shape5.ص"
cat > "$S5" <<'SAD'
استورد خرائط
متغير سجل = خريطة()
متغير نص اسم = "قيمة_أولى"
اسم = خريطة_احصل(سجل، "لا_وجود_له")
اطبع_سطر("بعد_الإسناد")
SAD

S6="$TMP/shape6.ص"
cat > "$S6" <<'SAD'
استورد خرائط
دالة رئيسية()
    متغير سجل = خريطة()
    متغير نص اسم = خريطة_احصل(سجل، "لا_وجود_له")
    اطبع_سطر("بعد_الإسناد")
نهاية
SAD
# (AR) «رئيسية» تُستدعى تلقائيًّا — استدعاؤها صراحةً مع كود مستوى أعلى يصطدم بـSEM018.

run_shape() { # اسم الشكل ، ملف
  local name="$1" src="$2"
  local err rc out g p
  echo "== $name =="
  # بلا أعلام: الافتراضي = تعلم (تحذير + خروج 0) — يكشف تشديدًا صامتًا للافتراضي
  err=$("$RUN" "$src" 2>&1 1>/dev/null); rc=$?
  echo "$err" | grep -q "تحذير نوع SEM045"; check "افتراضي: تحذير SEM045 (لا خطأ)" $?
  check "افتراضي: الخروج 0 (يكمل)" $([ $rc -eq 0 ] && echo 0 || echo 1)
  # --تعلم: تحذير SEM045 على stderr + خروج 0 (يكمل)
  err=$("$RUN" --تعلم "$src" 2>&1 1>/dev/null); rc=$?
  echo "$err" | grep -q "تحذير نوع SEM045"; check "تعلم: تحذير SEM045 يظهر" $?
  check "تعلم: الخروج 0 (يكمل)" $([ $rc -eq 0 ] && echo 0 || echo 1)
  # --جامع: صمت + خروج 0 (انهيار عرضيّ لا يُقبل أخضر)
  err=$("$RUN" --جامع "$src" 2>&1 1>/dev/null); rc=$?
  echo "$err" | grep -q "SEM045"; g=$?
  check "جامع: لا تشخيص SEM045" $([ $g -ne 0 ] && echo 0 || echo 1)
  check "جامع: الخروج 0" $([ $rc -eq 0 ] && echo 0 || echo 1)
  # --إنتاج: وسم الخطأ + خروج ≠ 0 + السطر التالي لا يُطبع
  err=$("$RUN" --إنتاج "$src" 2>&1 1>/dev/null); rc=$?
  echo "$err" | grep -q "خطأ نوع SEM045"; check "إنتاج: الوسم [خطأ نوع SEM045] يظهر" $?
  check "إنتاج: خروج ≠ 0 (يوقف)" $([ $rc -ne 0 ] && echo 0 || echo 1)
  out=$("$RUN" --إنتاج "$src" 2>/dev/null)
  echo "$out" | grep -q "بعد_الإسناد"; p=$?
  check "إنتاج: ما بعد الإسناد لا يُنفَّذ" $([ $p -ne 0 ] && echo 0 || echo 1)
}

run_shape "ش١: غياب الجلب ⇒ خانة نص" "$S1"
run_shape "ش٢: غياب الجلب ⇒ خانة نص عدمي (لا باب خلفيًّا)" "$S2"
run_shape "ش٣: دالة لم ترجع في فرعها ⇒ خانة نص" "$S3"
run_shape "ش٥: إعادة إسناد فراغ لخانة نص قائمة" "$S5"
run_shape "ش٦: الإسناد داخل دالة — الإيقاف موضعيّ" "$S6"

echo "== ش٤: البديل الثالث يلغي الفراغ =="
err=$("$RUN" --تعلم "$S4" 2>&1 1>/dev/null); rc=$?
echo "$err" | grep -q "SEM045"; g=$?
check "تعلم: لا تشخيص SEM045 مع البديل" $([ $g -ne 0 ] && echo 0 || echo 1)
check "تعلم: الخروج 0" $([ $rc -eq 0 ] && echo 0 || echo 1)
out=$("$RUN" --إنتاج "$S4" 2>/dev/null); rc=$?
check "إنتاج: الخروج 0 (لا فراغ أصلًا)" $([ $rc -eq 0 ] && echo 0 || echo 1)
echo "$out" | grep -q "النتيجة:بديل"; check "القيمة هي البديل" $?

echo "── النتيجة: نجح=$pass فشل=$fail ──"
[ "$fail" -eq 0 ]
