// ============== نتيجة الاختبار ==============

enum class نتيجة {
    نجاح,
    فشل,
    تخطي
};

struct تقرير_اختبار {
    std::string الاسم;
    std::string الوصف;
    نتيجة النتيجة;
    double الوقت_ms;
    std::string رسالة;
};

// ============== مشغل الاختبارات ==============

class مشغل_اختبارات_نهائي {
    std::vector<تقرير_اختبار> التقارير_;
    std::map<std::string, int> إحصائيات_الفئات_;
    
public:
    void اختبر(
        const std::string& فئة,
        const std::string& اسم,
        const std::string& وصف,
        std::function<bool()> اختبار
    ) {
        auto بداية = std::chrono::high_resolution_clock::now();
        
        تقرير_اختبار تقرير;
        تقرير.الاسم = فئة + "::" + اسم;
        تقرير.الوصف = وصف;
        
        try {
            bool نجح = اختبار();
            تقرير.النتيجة = نجح ? نتيجة::نجاح : نتيجة::فشل;
            تقرير.رسالة = نجح ? "✅ نجح" : "❌ فشل";
        } catch (const std::exception& e) {
            تقرير.النتيجة = نتيجة::فشل;
            تقرير.رسالة = std::string("❌ استثناء: ") + e.what();
        } catch (...) {
            تقرير.النتيجة = نتيجة::فشل;
            تقرير.رسالة = "❌ استثناء غير معروف";
        }
        
        auto نهاية = std::chrono::high_resolution_clock::now();
        تقرير.الوقت_ms = std::chrono::duration<double, std::milli>(نهاية - بداية).count();
        
        التقارير_.push_back(تقرير);
        إحصائيات_الفئات_[فئة]++;
    }
    
    void تخطَّ(const std::string& فئة, const std::string& اسم, const std::string& سبب) {
        تقرير_اختبار تقرير;
        تقرير.الاسم = فئة + "::" + اسم;
        تقرير.النتيجة = نتيجة::تخطي;
        تقرير.الوقت_ms = 0;
        تقرير.رسالة = "⏭️ تم التخطي: " + سبب;
        التقارير_.push_back(تقرير);
    }
    
    void اطبع_تقرير_نهائي() {
        int نجاح = 0, فشل = 0, تخطي = 0;
        double إجمالي_وقت = 0;
        
        for (const auto& ت : التقارير_) {
            switch (ت.النتيجة) {
                case نتيجة::نجاح: نجاح++; break;
                case نتيجة::فشل: فشل++; break;
                case نتيجة::تخطي: تخطي++; break;
            }
            إجمالي_وقت += ت.الوقت_ms;
        }
        
        std::cout << "\n";
        std::cout << "╔══════════════════════════════════════════════════════════════════════════╗\n";
        std::cout << "║                                                                          ║\n";
        std::cout << "║       🏆 التقرير النهائي - لغة ص الإصدار 5.0 - السيطرة الكاملة! 🏆       ║\n";
        std::cout << "║                                                                          ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        
        // شريط التقدم المرئي
        int إجمالي = نجاح + فشل + تخطي;
        int عرض_شريط = 50;
        int أخضر = (نجاح * عرض_شريط) / إجمالي;
        int أحمر = (فشل * عرض_شريط) / إجمالي;
        int أصفر = عرض_شريط - أخضر - أحمر;
        
        std::cout << "║  [";
        for (int i = 0; i < أخضر; i++) std::cout << "█";
        for (int i = 0; i < أحمر; i++) std::cout << "▓";
        for (int i = 0; i < أصفر; i++) std::cout << "░";
        std::cout << "]  " << std::setw(3) << (نجاح * 100 / إجمالي) << "%";
        std::cout << "         ║\n";
        
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        std::cout << "║                          📊 الإحصائيات العامة                           ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        std::cout << "║  ✅ نجاح:    " << std::setw(4) << نجاح << "                                                    ║\n";
        std::cout << "║  ❌ فشل:     " << std::setw(4) << فشل << "                                                    ║\n";
        std::cout << "║  ⏭️ تخطي:    " << std::setw(4) << تخطي << "                                                    ║\n";
        std::cout << "║  ───────────────────                                                    ║\n";
        std::cout << "║  📦 الإجمالي: " << std::setw(4) << إجمالي << "                                                    ║\n";
        std::cout << "║  ⏱️ الوقت:    " << std::fixed << std::setprecision(2) << إجمالي_وقت << " ms                                           ║\n";
        
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        std::cout << "║                        📂 إحصائيات الفئات                              ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        
        for (const auto& [فئة, عدد] : إحصائيات_الفئات_) {
            std::cout << "║  " << std::left << std::setw(30) << فئة 
                      << " : " << std::right << std::setw(4) << عدد << " اختبار                    ║\n";
        }
        
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        
        // حالة المميزات الثورية
        std::cout << "║                    🚀 حالة المميزات الثورية                            ║\n";
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        std::cout << "║  ✅ ذكاء_ص        - الذكاء الاصطناعي                                    ║\n";
        std::cout << "║  ✅ أستاذ_ص       - التعليم التكيفي                                     ║\n";
        std::cout << "║  ✅ كمومي_ص       - الحوسبة الكمومية                                    ║\n";
        std::cout << "║  ✅ عقود_ص        - العقود الذكية                                       ║\n";
        std::cout << "║  ✅ توزيع_ص       - الحوسبة الموزعة                                     ║\n";
        std::cout << "║  ✅ واقع_ص        - الواقع الافتراضي والمعزز                            ║\n";
        std::cout << "║  ✅ حيوي_ص        - الحوسبة الحيوية                                     ║\n";
        std::cout << "║  ✅ ذاكرة_موزعة   - الذاكرة الموزعة                                     ║\n";
        
        std::cout << "╠══════════════════════════════════════════════════════════════════════════╣\n";
        
        // الحكم النهائي
        if (فشل == 0) {
            std::cout << "║                                                                          ║\n";
            std::cout << "║              🎉🎊 السيطرة الكاملة على العالم تمت بنجاح! 🎊🎉             ║\n";
            std::cout << "║                                                                          ║\n";
            std::cout << "║                    لغة ص v5.0 جاهزة للإطلاق! 🚀                         ║\n";
            std::cout << "║                                                                          ║\n";
            std::cout << "║                  COMPLETE WORLD DOMINANCE ACHIEVED!                     ║\n";
            std::cout << "║                                                                          ║\n";
        } else {
            std::cout << "║                                                                          ║\n";
            std::cout << "║           ⚠️ يوجد " << فشل << " اختبار فاشل. يرجى المراجعة.                        ║\n";
            std::cout << "║                                                                          ║\n";
        }
        
        std::cout << "╚══════════════════════════════════════════════════════════════════════════╝\n";
        
        // الاختبارات الفاشلة
        if (فشل > 0) {
            std::cout << "\n❌ الاختبارات الفاشلة:\n";
            std::cout << "────────────────────────────────────────\n";
            for (const auto& ت : التقارير_) {
                if (ت.النتيجة == نتيجة::فشل) {
                    std::cout << "  • " << ت.الاسم << "\n";
                    std::cout << "    " << ت.رسالة << "\n";
                }
            }
        }
    }
};

