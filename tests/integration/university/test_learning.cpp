// نظام تحفيز بسيط
class نظام_تحفيز_بسيط {
private:
    std::map<std::string, int> النقاط_;
    std::map<std::string, int> العملات_;
    std::map<std::string, std::vector<std::string>> الإنجازات_;
    
public:
    void إضافة_نقاط(const std::string& طالب, int نقاط) {
        النقاط_[طالب] += نقاط;
    }
    
    void إضافة_عملات(const std::string& طالب, int عملات) {
        العملات_[طالب] += عملات;
    }
    
    void فتح_إنجاز(const std::string& طالب, const std::string& إنجاز) {
        الإنجازات_[طالب].push_back(إنجاز);
    }
    
    int عدد_الإنجازات(const std::string& طالب) {
        return الإنجازات_.find(طالب) != الإنجازات_.end() ? 
               الإنجازات_[طالب].size() : 0;
    }
    
    bool يملك_إنجاز(const std::string& طالب, const std::string& إنجاز) {
        if (الإنجازات_.find(طالب) == الإنجازات_.end()) return false;
        for (const auto& إ : الإنجازات_[طالب]) {
            if (إ == إنجاز) return true;
        }
        return false;
    }
    
    int العملات(const std::string& طالب) {
        return العملات_.find(طالب) != العملات_.end() ? العملات_[طالب] : 0;
    }
    
    bool شراء(const std::string& طالب, int السعر) {
        if (العملات_[طالب] >= السعر) {
            العملات_[طالب] -= السعر;
            return true;
        }
        return false;
    }
};

