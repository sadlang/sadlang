#define اختبار(اسم) \
    void اسم(); \
    static bool _مسجل_##اسم = (مسجل_اختبارات::المثيل().تسجيل(#اسم, اسم), true); \
    void اسم()

#define تحقق(شرط) \
    if (!(شرط)) { \
        throw std::runtime_error("فشل التحقق: " #شرط); \
    }

#define تحقق_متساوي(أ, ب) \
    if ((أ) != (ب)) { \
        throw std::runtime_error("فشل التحقق: " #أ " != " #ب); \
    }

#define تحقق_أكبر(أ, ب) \
    if (!((أ) > (ب))) { \
        throw std::runtime_error("فشل التحقق: " #أ " ليس أكبر من " #ب); \
    }

#define تحقق_قريب(أ, ب, دقة) \
    if (std::abs((أ) - (ب)) > (دقة)) { \
        throw std::runtime_error("فشل التحقق: القيم ليست قريبة"); \
    }

