/**
 * اختبارات صياغة العقود
 */
class اختبارات_الصياغة {
public:
    /**
     * اختبار تعريف العقد
     */
    static bool اختبار_تعريف_عقد() {
        std::cout << "   📝 اختبار تعريف العقد... ";
        
        // عقد بسيط
        std::string كود = R"(
            #[عقد_ذكي]
            عقد محفظة
                متغير_تخزين رصيد: عدد256
                
                #[قابل_للدفع]
                دالة إيداع()
                    ذاتي.رصيد += رسالة.قيمة
                نهاية
                
                #[عرض_فقط]
                دالة احصل_رصيد() -> عدد256
                    ارجع ذاتي.رصيد
                نهاية
            نهاية
        )";
        
        // التحقق من وجود العناصر الأساسية
        bool يحتوي_عقد = كود.find("عقد_ذكي") != std::string::npos;
        bool يحتوي_تخزين = كود.find("متغير_تخزين") != std::string::npos;
        bool يحتوي_دالة = كود.find("دالة") != std::string::npos;
        
        bool نجح = يحتوي_عقد && يحتوي_تخزين && يحتوي_دالة;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار الأحداث
     */
    static bool اختبار_الأحداث() {
        std::cout << "   📝 اختبار الأحداث... ";
        
        std::string كود = R"(
            #[عقد_ذكي]
            عقد رمز
                حدث نقل(من: عنوان, إلى: عنوان, قيمة: عدد256)
                
                دالة _نقل(من: عنوان, إلى: عنوان, قيمة: عدد256)
                    // النقل
                    أطلق نقل(من، إلى، قيمة)
                نهاية
            نهاية
        )";
        
        bool نجح = كود.find("حدث") != std::string::npos &&
                   كود.find("أطلق") != std::string::npos;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار المعدّلات
     */
    static bool اختبار_المعدّلات() {
        std::cout << "   📝 اختبار المعدّلات... ";
        
        std::string كود = R"(
            #[عقد_ذكي]
            عقد مُدار
                متغير_تخزين مالك: عنوان
                
                معدّل المالك_فقط()
                    يجب رسالة.مرسل == ذاتي.مالك، "غير مصرح"
                    _
                نهاية
                
                #[المالك_فقط]
                دالة سحب()
                    // السحب
                نهاية
            نهاية
        )";
        
        bool نجح = كود.find("معدّل") != std::string::npos &&
                   كود.find("يجب") != std::string::npos;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * تشغيل جميع اختبارات الصياغة
     */
    static int شغّل_الكل() {
        std::cout << "\n📋 اختبارات الصياغة:\n";
        int فشل = 0;
        
        if (!اختبار_تعريف_عقد()) فشل++;
        if (!اختبار_الأحداث()) فشل++;
        if (!اختبار_المعدّلات()) فشل++;
        
        return فشل;
    }
};

