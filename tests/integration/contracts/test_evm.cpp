/**
 * اختبارات توليد EVM bytecode
 */
class اختبارات_EVM {
public:
    /**
     * اختبار PUSH
     */
    static bool اختبار_push() {
        std::cout << "   📝 اختبار PUSH opcodes... ";
        
        // PUSH1 = 0x60, PUSH32 = 0x7F
        uint8_t push1 = 0x60;
        uint8_t push32 = 0x7F;
        
        bool نجح = push1 == 0x60 && push32 == 0x7F;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار العمليات الحسابية
     */
    static bool اختبار_حسابية() {
        std::cout << "   📝 اختبار العمليات الحسابية... ";
        
        // ADD=0x01, SUB=0x03, MUL=0x02, DIV=0x04
        uint8_t add = 0x01;
        uint8_t sub = 0x03;
        uint8_t mul = 0x02;
        uint8_t div = 0x04;
        
        bool نجح = add == 0x01 && sub == 0x03 && mul == 0x02 && div == 0x04;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار التخزين
     */
    static bool اختبار_تخزين() {
        std::cout << "   📝 اختبار SLOAD/SSTORE... ";
        
        // SLOAD=0x54, SSTORE=0x55
        uint8_t sload = 0x54;
        uint8_t sstore = 0x55;
        
        bool نجح = sload == 0x54 && sstore == 0x55;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار الذاكرة
     */
    static bool اختبار_ذاكرة() {
        std::cout << "   📝 اختبار MLOAD/MSTORE... ";
        
        // MLOAD=0x51, MSTORE=0x52
        uint8_t mload = 0x51;
        uint8_t mstore = 0x52;
        
        bool نجح = mload == 0x51 && mstore == 0x52;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار القفزات
     */
    static bool اختبار_قفزات() {
        std::cout << "   📝 اختبار JUMP/JUMPI... ";
        
        // JUMP=0x56, JUMPI=0x57, JUMPDEST=0x5B
        uint8_t jump = 0x56;
        uint8_t jumpi = 0x57;
        uint8_t jumpdest = 0x5B;
        
        bool نجح = jump == 0x56 && jumpi == 0x57 && jumpdest == 0x5B;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار الاستدعاءات
     */
    static bool اختبار_استدعاءات() {
        std::cout << "   📝 اختبار CALL opcodes... ";
        
        // CALL=0xF1, STATICCALL=0xFA, DELEGATECALL=0xF4
        uint8_t call = 0xF1;
        uint8_t staticcall = 0xFA;
        uint8_t delegatecall = 0xF4;
        
        bool نجح = call == 0xF1 && staticcall == 0xFA && delegatecall == 0xF4;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * تشغيل جميع اختبارات EVM
     */
    static int شغّل_الكل() {
        std::cout << "\n⚙️ اختبارات EVM:\n";
        int فشل = 0;
        
        if (!اختبار_push()) فشل++;
        if (!اختبار_حسابية()) فشل++;
        if (!اختبار_تخزين()) فشل++;
        if (!اختبار_ذاكرة()) فشل++;
        if (!اختبار_قفزات()) فشل++;
        if (!اختبار_استدعاءات()) فشل++;
        
        return فشل;
    }
};

