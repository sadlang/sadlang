/**
 * اختبارات ترميز ABI
 */
class اختبارات_ABI {
public:
    /**
     * اختبار ترميز uint256
     */
    static bool اختبار_ترميز_uint256() {
        std::cout << "   📝 اختبار ترميز uint256... ";
        
        // القيمة 100 بصيغة 32 بايت
        std::string متوقع = std::string(62, '0') + "64";  // 0x64 = 100
        
        bool نجح = متوقع.length() == 64;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار ترميز address
     */
    static bool اختبار_ترميز_address() {
        std::cout << "   📝 اختبار ترميز address... ";
        
        // العنوان بصيغة 32 بايت (20 بايت + 12 صفر)
        std::string عنوان = "0x1234567890123456789012345678901234567890";
        
        bool نجح = عنوان.length() == 42;  // 0x + 40 حرف
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار ترميز string
     */
    static bool اختبار_ترميز_string() {
        std::cout << "   📝 اختبار ترميز string... ";
        
        std::string نص = "Hello, World!";
        // الطول + البيانات المحشوة
        
        bool نجح = نص.length() == 13;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * اختبار function selector
     */
    static bool اختبار_selector() {
        std::cout << "   📝 اختبار function selector... ";
        
        // keccak256("transfer(address,uint256)")[:4]
        std::string selector = "a9059cbb";  // transfer selector
        
        bool نجح = selector.length() == 8;
        std::cout << (نجح ? "✅" : "❌") << "\n";
        return نجح;
    }
    
    /**
     * تشغيل جميع اختبارات ABI
     */
    static int شغّل_الكل() {
        std::cout << "\n📋 اختبارات ABI:\n";
        int فشل = 0;
        
        if (!اختبار_ترميز_uint256()) فشل++;
        if (!اختبار_ترميز_address()) فشل++;
        if (!اختبار_ترميز_string()) فشل++;
        if (!اختبار_selector()) فشل++;
        
        return فشل;
    }
};

