# اختبار 5: صنف حساب بنكي / Test 5: Bank account class
# ============================================================
صنف حساب_بنكي
    نص رقم_حساب
    نص مالك
    رقم رصيد
    
    باني(نص رقم_حساب، نص مالك، رقم رصيد_أولي = 0)
        هذا.رقم_حساب = رقم_حساب
        هذا.مالك = مالك
        هذا.رصيد = رصيد_أولي
    نهاية
    
    دالة إيداع(رقم مبلغ)
        إذا مبلغ > 0
            هذا.رصيد = هذا.رصيد + مبلغ
            اطبع(ن"تم إيداع {مبلغ} ريال")
        نهاية
    نهاية
    
    دالة سحب(رقم مبلغ)
        إذا مبلغ > 0 && مبلغ <= هذا.رصيد
            هذا.رصيد = هذا.رصيد - مبلغ
            اطبع(ن"تم سحب {مبلغ} ريال")
        وإلا
            اطبع("رصيد غير كافٍ")
        نهاية
    نهاية
    
    دالة رقم احصل_رصيد()
        إرجاع هذا.رصيد
    نهاية
نهاية

حساب_بنكي ح = حساب_بنكي("12345"، "أحمد"، 1000)
تأكد(ح.احصل_رصيد() == 1000)

ح.إيداع(500)
تأكد(ح.احصل_رصيد() == 1500)

ح.سحب(300)
تأكد(ح.احصل_رصيد() == 1200)

اطبع("✓ اختبار 5: الحساب البنكي نجح")

