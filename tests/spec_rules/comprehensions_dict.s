# اختبار تضمينات القواميس / Test dict comprehensions
# Testing optional parentheses in if clause

# ========================================
# اختبار أساسي / Basic test
# ========================================
مصفوفة أعداد = [1، 2، 3، 4، 5]
قاموس مربعات = {ع: ع * ع لكل ع في أعداد}
اطبع(مربعات)
# Expected: {1: 1، 2: 4، 3: 9، 4: 16، 5: 25}

# ========================================
# شرط بدون أقواس / Condition without parentheses
# ========================================
قاموس زوجية = {ع: ع * 2 لكل ع في [1، 2، 3، 4، 5، 6] إذا ع % 2 == 0}
اطبع(زوجية)
# Expected: {2: 4، 4: 8، 6: 12}

# ========================================
# شرط بأقواس / Condition with parentheses
# ========================================
قاموس كبيرة = {ع: ع * ع لكل ع في [1، 2، 3، 4، 5، 6] إذا (ع > 3)}
اطبع(كبيرة)
# Expected: {4: 16، 5: 25، 6: 36}

# ========================================
# شرط معقد مع أقواس / Complex condition with parentheses
# ========================================
قاموس نطاق = {ع: ع + 10 لكل ع في أعداد إذا (ع >= 2 && ع <= 4)}
اطبع(نطاق)
# Expected: {2: 12، 3: 13، 4: 14}

# ========================================
# من قائمة نصوص / From string list
# ========================================
مصفوفة أسماء = ["أحمد"، "فاطمة"، "محمد"، "عائشة"]
قاموس أطوال = {اسم: اسم.طول() لكل اسم في أسماء}
اطبع(أطوال)
# Expected: {"أحمد": 4، "فاطمة": 5، "محمد": 4، "عائشة": 5}

# ========================================
# مع شرط على الأسماء / With condition on names
# ========================================
قاموس أسماء_طويلة = {اسم: اسم.طول() لكل اسم في أسماء إذا (اسم.طول() > 4)}
اطبع(أسماء_طويلة)
# Expected: {"فاطمة": 5، "عائشة": 5}

# ========================================
# تحويل النوع / Type conversion
# ========================================
قاموس نص_لعدد = {نص(ع): ع * ع لكل ع في [1، 2، 3] إذا ع > 1}
اطبع(نص_لعدد)
# Expected: {"2": 4، "3": 9}

# ========================================
# عكس قاموس / Reverse dictionary
# ========================================
قاموس أصلي = {"أ": 1، "ب": 2، "ج": 3}
# Note: This requires .items() method support
# قاموس معكوس = {قيمة: مفتاح لكل مفتاح، قيمة في أصلي.عناصر()}

# ========================================
# قاموس من نطاق / Dictionary from range
# ========================================
قاموس مكعبات = {ع: ع * ع * ع لكل ع في [1، 2، 3، 4، 5] إذا (ع <= 3)}
اطبع(مكعبات)
# Expected: {1: 1، 2: 8، 3: 27}

# ========================================
# مفاتيح مركبة / Compound keys
# ========================================
قاموس مركب = {ن"عدد_{ع}": ع * 10 لكل ع في [1، 2، 3]}
اطبع(مركب)
# Expected: {"عدد_1": 10، "عدد_2": 20، "عدد_3": 30}

اطبع("جميع اختبارات القواميس اكتملت!")
# Expected: "جميع اختبارات القواميس اكتملت!"
