// ============================================================
// اختبار 8: أعداد في قواميس / Test 8: Integers in dicts
// ============================================================
قاموس بيانات = {
    "عمر": 25،
    "سنة": 2025،
    "عدد": 100
}

تأكد(بيانات["عمر"] == 25)
تأكد(بيانات["سنة"] == 2025)
تأكد(بيانات["عدد"] == 100)

اطبع("✓ اختبار 8: الأعداد في القواميس نجحت")

// ============================================================
// اختبار 9: تحويل الأنواع / Test 9: Type conversion
// ============================================================
نص نص_رقم = "42"
