ع = ع * 4    // ع الآن = 24
تأكد(ع == 24)

ع = ع / 3    // ع الآن = 8
تأكد(ع == 8)

اطبع("✓ اختبار 5: العمليات المركبة نجحت")

// ============================================================
// اختبار 6: القيمة المطلقة / Test 6: Absolute value
