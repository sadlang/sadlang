// ══════════════════════════════════════════════════════════════════════════════
//  سيناريو ⑥ — مدمجة من مصدر الحقيقة لا تُحذَّر كاذبًا كـ«غير معرّف»
// ══════════════════════════════════════════════════════════════════════════════
//
// قبل توحيد المصدر كان كاشف «غير معرّف» يعرف 21 اسمًا مهرَّدًا فقط، فيحذّر كاذبًا
// عن ~99٪ من المدمجات. الآن يستشير سجلّ مصدر الحقيقة (isKnownBuiltin، 1073).
// «قناة» مدمجة (تزامن، بلا استيراد) لم تكن في القائمة المهرَّدة القديمة.
TEST(LspBehavior, مدمجة_من_المصدر_لا_تُحذَّر_غير_معرّفة) {
    Editor ed;
    DocumentUri uri = "file:///مدمجة.ص";
    ed.open(uri,
            u8"دالة جرّب()\n"
            u8"    متغير ق = قناة(5)\n"
            u8"    أرجع ق\n"
            u8"نهاية\n");

    // لا يجوز وجود تحذير «المعرّف غير معرّف» (ص-ت١٠٣) عن «قناة».
    for (const auto& d : ed.diags) {
        if (d.code == u8"ص-ت١٠٣")
            ASSERT_TRUE(d.message.find(u8"قناة") == std::string::npos);
    }
}

// ══════════════════════════════════════════════════════════════════════════════
//  سيناريو ⑦ — مدمجات من عائلات الكتالوج المتنوّعة لا تُحذَّر كاذبًا
// ══════════════════════════════════════════════════════════════════════════════
//
// يعمّم سيناريو ⑥ على عائلات مصدر الحقيقة: نصوص (استبدل)، مصفوفات (رتب)،
// رياضيات (جذر)، ملفّات (اقرأ_ملف). أيّ تهريد مستقبليّ ينقص عائلةً كاملة
// سيسقط هنا فورًا بتحذير «غير معرّف» (ص-ت١٠٣) كاذب.
TEST(LspBehavior, مدمجات_عائلات_متنوعة_لا_تُحذَّر_غير_معرّفة) {
    Editor ed;
    DocumentUri uri = "file:///عائلات.ص";
    ed.open(uri,
            u8"دالة جرّب_العائلات()\n"
            u8"    متغير ن = استبدل(\"سلام\"، \"س\"، \"ص\")\n" // نصوص
            u8"    متغير م = رتب([3، 1، 2])\n"                 // مصفوفات
            u8"    متغير ج = جذر(16)\n"                        // رياضيات
            u8"    متغير ق = اقرأ_ملف(\"ملف.نص\")\n"           // ملفّات
            u8"    أرجع ج\n"
            u8"نهاية\n");

    const char* family_builtins[] = {
        u8"استبدل", u8"رتب", u8"جذر", u8"اقرأ_ملف"};
    for (const auto& d : ed.diags) {
        if (d.code != u8"ص-ت١٠٣") continue;
        for (const char* name : family_builtins)
            ASSERT_TRUE(d.message.find(name) == std::string::npos);
    }
}

// ══════════════════════════════════════════════════════════════════════════════
//  سيناريو ⑧ — كتل من مصدر الحقيقة لا تُحذَّر «نهاية زائدة» كاذبًا
// ══════════════════════════════════════════════════════════════════════════════
//
// كان فحص توازن الكتل يعرف 9 كلمات فتح مهرَّدة (من 24 بدور block_opener في
// المعجم): كتلة «سمة … نهاية» أو «اختبر … نهاية» كانت تُحسب «نهاية» بلا فاتح
// ⇒ تحذير ص-ن٢٠٢ كاذب. بعد الاشتقاق من sot_vocab يجب أن يتوازن العدّ.
TEST(LspBehavior, كتل_سمة_واختبر_لا_تُحذَّر_نهاية_زائدة) {
    Editor ed;
    DocumentUri uri = "file:///كتل.ص";
    ed.open(uri,
            u8"سمة قابل_للعرض\n"
            u8"نهاية\n"
            u8"\n"
            u8"اختبر(\"توازن الكتل\")\n"
            u8"    اطبع(\"تمام\")\n"
            u8"نهاية\n");

    // لا «نهاية زائدة» (ص-ن٢٠٢) ولا «كتلة بلا نهاية» (ص-ن٢٠١) على كود متوازن.
    ASSERT_FALSE(ed.has_code(u8"ص-ن٢٠٢"));
    ASSERT_FALSE(ed.has_code(u8"ص-ن٢٠١"));
}

namespace {
/// (AR) عتاد مساعد: يفتح المصدر ويؤكّد خلوّ التشخيصات من كواذب توازن الكتل.
/// (EN) Helper: open source and assert no false block-balance diagnostics.
bool balance_clean(const std::string& src) {
    Editor ed;
    ed.open("file:///توازن.ص", src);
    return !ed.has_code(u8"ص-ن٢٠١") && !ed.has_code(u8"ص-ن٢٠٢");
}
} // namespace

// ══════════════════════════════════════════════════════════════════════════════
//  سيناريو ⑨ — القالب غلافٌ لا يستهلك «نهاية» خاصّة به
// ══════════════════════════════════════════════════════════════════════════════
//
// TemplateDecl = 'قالب' TemplateParams (FunctionDecl|ClassDecl) — «نهاية» يملكها
// التصريح الملفوف. عدُّ «قالب» فاتحًا مستقلًّا كان يُنتج ص-ن٢٠١ كاذبًا على النمط
// الحقيقيّ في مصفوفة القواعد (gr.adv.template_args: «قالب <نوع ت>» بسطر مستقلّ).
TEST(LspBehavior, قالب_غلاف_لا_يُحدث_توازنًا_كاذبًا) {
    // قالب بسطر مستقلّ + دالة متعدّدة الأسطر
    ASSERT_TRUE(balance_clean(
        u8"قالب <نوع ت>\nدالة هوية(ت س)\n    ارجع س\nنهاية\n"));
    // قالب والدالة على السطر نفسه
    ASSERT_TRUE(balance_clean(
        u8"قالب <نوع ت> دالة هوية(ت س)\n    ارجع س\nنهاية\n"));
    // النمط الحرفيّ من مصفوفة القواعد: دالة سطر واحد بنهاية مضمّنة
    ASSERT_TRUE(balance_clean(
        u8"قالب <نوع ت>\nدالة هوية(ت س) ارجع س نهاية\nاطبع_سطر(هوية<رقم>(7))\n"));
}

// ══════════════════════════════════════════════════════════════════════════════
//  سيناريو ⑩ — صيغ السطر الواحد: «نهاية» المضمّنة تُغلق فاتح سطرها
// ══════════════════════════════════════════════════════════════════════════════
TEST(LspBehavior, نهاية_مضمّنة_تُغلق_فاتح_السطر_نفسه) {
    // دالة سطر واحد
    ASSERT_TRUE(balance_clean(u8"دالة هوية(س) ارجع س نهاية\n"));
    // «نهاية» داخل سلسلة أو كبادئة اسم لا تُحتسب
    ASSERT_TRUE(balance_clean(
        u8"دالة س()\n    اطبع(\"نهاية\")\n    متغير نهاية_الأمر = 1\nنهاية\n"));
}

// ══════════════════════════════════════════════════════════════════════════════
//  سيناريو ⑪ — لامدا: كتلة وسط السطر تفتح «نهاية»، وصيغة السهم التعبيريّة لا
// ══════════════════════════════════════════════════════════════════════════════
TEST(LspBehavior, لامدا_كتلة_وسهم_بلا_كواذب_توازن) {
    // لامدا كتليّة مسندة وسط السطر — «نهاية»ها كانت تُحسب زائدة (ن٢٠٢ كاذب)
    ASSERT_TRUE(balance_clean(
        u8"دالة س()\n    متغير د = لامدا(م)\n        ارجع م\n    نهاية\nنهاية\n"));
    // صيغة السهم التعبيريّة بلا كتلة أصلًا
    ASSERT_TRUE(balance_clean(u8"متغير د = لامدا(س) => س\n"));
}

// ══════════════════════════════════════════════════════════════════════════════
