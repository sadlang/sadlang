/// يبني بايت كود لدالة تُرجع مجموع معاملين (أ + ب)
/// Builds bytecode for a function returning sum of two args (a + b)
static وحدة_بايت_كود ابنِ_دالة_جمع() {
    وحدة_بايت_كود كود("جمع");
    // تحميل المعامل الأول (المحلي 0)
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 0, 1);
    // تحميل المعامل الثاني (المحلي 1)
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 1, 1);
    // جمع
    كود.اكتب(عملية_جمع, 1);
    // إرجاع القيمة
    كود.اكتب(عملية_عودة_بقيمة, 1);
    return كود;
}

/// يبني بايت كود لدالة تُرجع ثابت (42)
/// Builds bytecode for function returning constant 42
static وحدة_بايت_كود ابنِ_دالة_ثابت() {
    وحدة_بايت_كود كود("ثابت");
    auto فهرس = كود.أضف_ثابت(قيمة::صحيح(42));
    كود.اكتب_عملية_ومعامل16(عملية_ثابت, فهرس, 1);
    كود.اكتب(عملية_عودة_بقيمة, 1);
    return كود;
}

/// يبني بايت كود لدالة حسابية: (أ * ب) - (أ / ب)
/// Builds bytecode for: (a * b) - (a / b)
static وحدة_بايت_كود ابنِ_دالة_حسابية() {
    وحدة_بايت_كود كود("حساب");
    // أ * ب
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 0, 1);
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 1, 1);
    كود.اكتب(عملية_ضرب, 1);
    // أ / ب
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 0, 1);
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 1, 1);
    كود.اكتب(عملية_قسمة, 1);
    // طرح
    كود.اكتب(عملية_طرح, 1);
    كود.اكتب(عملية_عودة_بقيمة, 1);
    return كود;
}

