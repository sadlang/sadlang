/// يبني بايت كود لدالة بمتغير محلي: محلي = أ + 10; ارجع محلي
/// Builds bytecode for: local = a + 10; return local
static وحدة_بايت_كود ابنِ_دالة_متغير_محلي() {
    وحدة_بايت_كود كود("متغير_محلي");
    // تحميل المعامل أ
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 0, 1);
    // ثابت 10
    auto فهرس = كود.أضف_ثابت(قيمة::صحيح(10));
    كود.اكتب_عملية_ومعامل16(عملية_ثابت, فهرس, 1);
    // جمع
    كود.اكتب(عملية_جمع, 1);
    // تخزين في محلي 2
    كود.اكتب_عملية_ومعامل8(عملية_تخزين_محلي, 2, 1);
    // تحميل المحلي 2 وإرجاعه
    كود.اكتب_عملية_ومعامل8(عملية_تحميل_محلي, 2, 1);
    كود.اكتب(عملية_عودة_بقيمة, 1);
    return كود;
}

