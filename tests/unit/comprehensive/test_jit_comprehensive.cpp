        محرك_JIT jit(إعدادات);
        jit.هيّئ();
        jit.سجّل_دالة("دالة", ابنِ_دالة_جمع(), 2);

        // الاستدعاء 1: false
        SAD_ASSERT_FALSE(jit.سجّل_استدعاء("دالة"));
        // الاستدعاء 2: true (وصل العتبة)
        SAD_ASSERT_TRUE(jit.سجّل_استدعاء("دالة"));

        // ترجمة الدالة عند O1 — قد تنجح أو لا (حسب LLVM)
