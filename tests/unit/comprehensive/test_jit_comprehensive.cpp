    SAD_GROUP("JIT — أمان الخيوط");

    SAD_TEST("JIT_THREAD_01: تسجيل استدعاءات من خيوط متعددة", {
        إعدادات_JIT إعدادات;
        إعدادات.عتبة_الترجمة = 100;
        إعدادات.التحسين_التكيفي = false;
        محرك_JIT jit(إعدادات);
        jit.هيّئ();
        jit.سجّل_دالة("دالة", ابنِ_دالة_جمع(), 2);

        std::atomic<int> عدد_العتبات{0};
        auto مهمة = [&]() {
            for (int i = 0; i < 200; ++i) {
                if (jit.سجّل_استدعاء("دالة")) {
                    عدد_العتبات++;
                }
            }
        };

        std::thread خيط1(مهمة);
        std::thread خيط2(مهمة);
        std::thread خيط3(مهمة);
        خيط1.join();
        خيط2.join();
        خيط3.join();

        // يجب أن تصل العتبة مرة واحدة أو أكثر (race conditions ممكنة)
        // لكن لا يجب أن يكون هناك crash
        SAD_ASSERT_GE(عدد_العتبات.load(), 1);
    });

    SAD_TEST("JIT_THREAD_02: تنفيذ متزامن آمن", {
        محرك_JIT jit;
        jit.هيّئ();
        jit.سجّل_دالة("أ", ابنِ_دالة_جمع(), 2);
        jit.سجّل_دالة("ب", ابنِ_دالة_ثابت(), 0);

        auto مهمة_أ = [&]() {
            for (int i = 0; i < 100; ++i) {
                jit.نفّذ("أ", {i, i + 1});
            }
        };
        auto مهمة_ب = [&]() {
            for (int i = 0; i < 100; ++i) {
                jit.نفّذ("ب", {});
            }
        };

        std::thread خيط1(مهمة_أ);
        std::thread خيط2(مهمة_ب);
        خيط1.join();
        خيط2.join();

        // مجموع الاستدعاءات = 200
        SAD_ASSERT_EQ(jit.الإحصائيات().عدد_الاستدعاءات_المفسرة, 200u);
    });

    SAD_TEST("JIT_THREAD_03: تسجيل وتنفيذ متزامن", {
        محرك_JIT jit;
        jit.هيّئ();
        jit.سجّل_دالة("مشتركة", ابنِ_دالة_جمع(), 2);

        auto مهمة_تنفيذ = [&]() {
            for (int i = 0; i < 50; ++i) {
                jit.نفّذ("مشتركة", {i, i});
            }
        };

        auto مهمة_إحصائيات = [&]() {
            for (int i = 0; i < 50; ++i) {
                // قراءة الإحصائيات أثناء التنفيذ
                auto إحص = jit.الإحصائيات();
                (void)إحص.نسبة_التسريع();
            }
        };

        std::thread خيط1(مهمة_تنفيذ);
        std::thread خيط2(مهمة_إحصائيات);
        خيط1.join();
        خيط2.join();

        SAD_ASSERT_TRUE(true); // لا crash = نجاح
    });

