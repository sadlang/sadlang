private:
    void اختبر_النصيحة_السياقية() {
        std::cout << "  🔍 اختبار النصيحة السياقية... ";
        
        // كود مع TODO
        std::string كود = "// TODO: أكمل هذا لاحقاً";
        
        std::string نصيحة;
        if (كود.find("TODO") != std::string::npos) {
            نصيحة = "لديك مهام معلقة";
        }
        
        assert(!نصيحة.empty());
        
        std::cout << "✅\n";
    }
    
    void اختبر_تصنيف_النصائح() {
        std::cout << "  🔍 اختبار تصنيف النصائح... ";
        
        enum class فئة { جودة, أداء, أمان };
        
        std::vector<std::pair<std::string, فئة>> نصائح = {
            {"أضف تعليقات", فئة::جودة},
            {"تجنب الحلقات المتداخلة", فئة::أداء},
            {"تحقق من المدخلات", فئة::أمان}
        };
        
        // تصفية حسب الفئة
        int عدد_الجودة = 0;
        for (const auto& [نص, ف] : نصائح) {
            if (ف == فئة::جودة) عدد_الجودة++;
        }
        
        assert(عدد_الجودة == 1);
        
        std::cout << "✅\n";
    }
