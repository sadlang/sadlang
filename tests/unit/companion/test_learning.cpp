/**
 * اختبارات محلل الأسلوب
 */
class اختبارات_محلل_الأسلوب {
public:
    void شغّل() {
        std::cout << "═══════════════════════════════════════════════════\n";
        std::cout << "🧪 اختبارات محلل الأسلوب\n";
        std::cout << "═══════════════════════════════════════════════════\n\n";
        
        اختبر_كشف_لغة_التسمية();
        اختبر_كشف_نمط_الإزاحة();
        اختبر_حساب_نسبة_التعليقات();
        
        std::cout << "✅ جميع اختبارات محلل الأسلوب نجحت\n\n";
    }
    
private:
    void اختبر_كشف_لغة_التسمية() {
        std::cout << "  🔍 اختبار كشف لغة التسمية... ";
        
        // كود عربي
        std::string كود_عربي = R"(
دالة احسب_المجموع(أرقام: قائمة<صحيح>) -> صحيح
    متغير المجموع = 0
    لكل رقم من أرقام افعل
        المجموع = المجموع + رقم
    نهاية
    أرجع المجموع
نهاية
)";
        
        // التحقق: يجب اكتشاف أن التسمية عربية
        bool وجد_عربي = (كود_عربي.find("احسب") != std::string::npos);
        assert(وجد_عربي);
        
        std::cout << "✅\n";
    }
    
    void اختبر_كشف_نمط_الإزاحة() {
        std::cout << "  🔍 اختبار كشف نمط الإزاحة... ";
        
        // كود بإزاحة 4 مسافات
        std::string كود = "دالة\n    محتوى\nنهاية";
        
        // كشف الإزاحة
        size_t موقع_السطر = كود.find('\n');
        if (موقع_السطر != std::string::npos) {
            int مسافات = 0;
            for (size_t i = موقع_السطر + 1; i < كود.length(); i++) {
                if (كود[i] == ' ') مسافات++;
                else break;
            }
            assert(مسافات == 4);
        }
        
        std::cout << "✅\n";
    }
    
    void اختبر_حساب_نسبة_التعليقات() {
        std::cout << "  🔍 اختبار حساب نسبة التعليقات... ";
        
        std::string كود = R"(
// هذا تعليق
دالة اختبار()
    // تعليق آخر
    اطبع("مرحبا")
نهاية
)";
        
        // حساب التعليقات
        int سطور = 0;
        int تعليقات = 0;
        bool في_سطر = false;
        bool في_تعليق = false;
        
        for (size_t i = 0; i < كود.length(); i++) {
            if (كود[i] == '\n') {
                if (في_سطر) سطور++;
                if (في_تعليق) تعليقات++;
                في_سطر = false;
                في_تعليق = false;
            } else if (كود[i] != ' ' && كود[i] != '\t') {
                في_سطر = true;
                if (i + 1 < كود.length() && كود[i] == '/' && كود[i+1] == '/') {
                    في_تعليق = true;
                }
            }
        }
        
        assert(تعليقات >= 2);
        
        std::cout << "✅\n";
    }
};

/**
 * اختبارات النموذج المحلي
 */
class اختبارات_النموذج_المحلي {
public:
    void شغّل() {
        std::cout << "═══════════════════════════════════════════════════\n";
        std::cout << "🧪 اختبارات النموذج المحلي\n";
        std::cout << "═══════════════════════════════════════════════════\n\n";
        
        اختبر_تخزين_الأنماط();
        اختبر_توليد_الاقتراحات();
        اختبر_التعلم_التكيفي();
        
        std::cout << "✅ جميع اختبارات النموذج المحلي نجحت\n\n";
    }
    
private:
    void اختبر_تخزين_الأنماط() {
        std::cout << "  🔍 اختبار تخزين الأنماط... ";
        
        // محاكاة تخزين نمط
        std::map<std::string, int> أنماط;
        أنماط["إذا_ثم_نهاية"] = 5;
        أنماط["لكل_من_افعل"] = 3;
        
        assert(أنماط.size() == 2);
        assert(أنماط["إذا_ثم_نهاية"] == 5);
        
        std::cout << "✅\n";
    }
    
    void اختبر_توليد_الاقتراحات() {
        std::cout << "  🔍 اختبار توليد الاقتراحات... ";
        
        // محاكاة اقتراح بناءً على السياق
        std::string سياق = "إذا عدد > 0";
        std::string اقتراح;
        
        if (سياق.find("إذا") != std::string::npos) {
            اقتراح = " ثم\n    \nنهاية";
        }
        
        assert(!اقتراح.empty());
        assert(اقتراح.find("نهاية") != std::string::npos);
        
        std::cout << "✅\n";
    }
    
    void اختبر_التعلم_التكيفي() {
        std::cout << "  🔍 اختبار التعلم التكيفي... ";
        
        // محاكاة التعلم من القبول/الرفض
        struct تفضيل {
            int مقبول = 0;
            int مرفوض = 0;
        };
        
        std::map<std::string, تفضيل> تفضيلات;
        
        // المستخدم قبل 3 اقتراحات ورفض 1
        تفضيلات["اقتراح_الدالة"].مقبول = 3;
        تفضيلات["اقتراح_الدالة"].مرفوض = 1;
        
        // حساب معدل القبول
        double معدل = (double)تفضيلات["اقتراح_الدالة"].مقبول / 
                      (تفضيلات["اقتراح_الدالة"].مقبول + تفضيلات["اقتراح_الدالة"].مرفوض);
        
        assert(معدل > 0.5);  // 75%
        
        std::cout << "✅\n";
    }
};

