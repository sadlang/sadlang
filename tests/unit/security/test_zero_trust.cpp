/**
 * تنفيذ جميع اختبارات الأمان
 */
class منفذ_اختبارات_الأمان {
public:
    تقرير_الاختبارات نفّذ_الكل() {
        تقرير_الاختبارات تقرير_كامل;
        
        std::cout << "\n";
        std::cout << "╔═══════════════════════════════════════════════════════════════╗\n";
        std::cout << "║         🔒 اختبارات نظام الأمان Zero Trust                    ║\n";
        std::cout << "╚═══════════════════════════════════════════════════════════════╝\n";
        
        // تنفيذ كل مجموعة
        std::vector<std::unique_ptr<مجموعة_اختبارات>> مجموعات;
        مجموعات.push_back(std::make_unique<اختبارات_التوقيع>());
        مجموعات.push_back(std::make_unique<اختبارات_التلوث>());
        مجموعات.push_back(std::make_unique<اختبارات_Sandbox>());
        مجموعات.push_back(std::make_unique<اختبارات_SQL>());
        مجموعات.push_back(std::make_unique<اختبارات_XSS>());
        مجموعات.push_back(std::make_unique<اختبارات_التبعيات>());
        مجموعات.push_back(std::make_unique<اختبارات_التقارير>());
        
        for (auto& مجموعة : مجموعات) {
            auto تقرير = مجموعة->نفّذ();
            تقرير_كامل.إجمالي += تقرير.إجمالي;
            تقرير_كامل.ناجح += تقرير.ناجح;
            تقرير_كامل.فاشل += تقرير.فاشل;
            for (const auto& نتيجة : تقرير.نتائج) {
                تقرير_كامل.نتائج.push_back(نتيجة);
            }
        }
        
        // الملخص النهائي
        std::cout << "\n";
        std::cout << "═══════════════════════════════════════════════════════════════\n";
        std::cout << "📊 ملخص الاختبارات\n";
        std::cout << "═══════════════════════════════════════════════════════════════\n";
        std::cout << "  إجمالي الاختبارات: " << تقرير_كامل.إجمالي << "\n";
        std::cout << "  ✅ ناجح: " << تقرير_كامل.ناجح << "\n";
        std::cout << "  ❌ فاشل: " << تقرير_كامل.فاشل << "\n";
        std::cout << "  📈 نسبة النجاح: " << تقرير_كامل.نسبة_النجاح() << "%\n";
        std::cout << "═══════════════════════════════════════════════════════════════\n";
        
        if (تقرير_كامل.فاشل == 0) {
            std::cout << "✅ جميع الاختبارات نجحت!\n";
        } else {
            std::cout << "⚠️ بعض الاختبارات فشلت\n";
        }
        
        return تقرير_كامل;
    }
};

