/**
 * نتيجة اختبار
 */
struct نتيجة_اختبار {
    std::string اسم;
    bool نجاح;
    std::string رسالة;
    double مدة_ms;
};

/**
 * تقرير الاختبارات
 */
struct تقرير_الاختبارات {
    int إجمالي = 0;
    int ناجح = 0;
    int فاشل = 0;
    std::vector<نتيجة_اختبار> نتائج;
    
    void أضف(const نتيجة_اختبار& نتيجة) {
        نتائج.push_back(نتيجة);
        إجمالي++;
        if (نتيجة.نجاح) ناجح++;
        else فاشل++;
    }
    
    double نسبة_النجاح() const {
        return إجمالي > 0 ? (ناجح * 100.0 / إجمالي) : 0;
    }
};

/**
 * مجموعة اختبارات
 */
class مجموعة_اختبارات {
protected:
    std::string اسم_;
    std::vector<std::pair<std::string, std::function<bool()>>> اختبارات_;
    
public:
    explicit مجموعة_اختبارات(const std::string& اسم) : اسم_(اسم) {}
    virtual ~مجموعة_اختبارات() = default;
    
    void أضف_اختبار(const std::string& اسم, std::function<bool()> اختبار) {
        اختبارات_.emplace_back(اسم, اختبار);
    }
    
    تقرير_الاختبارات نفّذ() {
        تقرير_الاختبارات تقرير;
        
        std::cout << "\n═══════════════════════════════════════════════════\n";
        std::cout << "🧪 " << اسم_ << "\n";
        std::cout << "═══════════════════════════════════════════════════\n\n";
        
        for (const auto& [اسم, اختبار] : اختبارات_) {
            نتيجة_اختبار نتيجة;
            نتيجة.اسم = اسم;
            
            try {
                نتيجة.نجاح = اختبار();
                نتيجة.رسالة = نتيجة.نجاح ? "نجح" : "فشل";
            } catch (const std::exception& e) {
                نتيجة.نجاح = false;
                نتيجة.رسالة = e.what();
            }
            
            std::cout << (نتيجة.نجاح ? "  ✅ " : "  ❌ ") << اسم;
            if (!نتيجة.نجاح) {
                std::cout << " - " << نتيجة.رسالة;
            }
            std::cout << "\n";
            
            تقرير.أضف(نتيجة);
        }
        
        return تقرير;
    }
};

