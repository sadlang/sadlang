// ============== محاكاة محاذاة التسلسلات ==============

struct نتيجة_محاذاة_محاكاة {
    std::string المحاذاة١;
    std::string المحاذاة٢;
    int النقاط;
    double الهوية;
    int الفجوات;
};

class محاذاة_عالمية_محاكاة {
public:
    static نتيجة_محاذاة_محاكاة محاذاة(const std::string& s1, const std::string& s2) {
        int m = s1.size();
        int n = s2.size();
        
        // مصفوفة النقاط
        std::vector<std::vector<int>> dp(m + 1, std::vector<int>(n + 1, 0));
        
        int match = 2, mismatch = -1, gap = -2;
        
        // تهيئة
        for (int i = 0; i <= m; ++i) dp[i][0] = i * gap;
        for (int j = 0; j <= n; ++j) dp[0][j] = j * gap;
        
        // ملء المصفوفة
        for (int i = 1; i <= m; ++i) {
            for (int j = 1; j <= n; ++j) {
                int diag = dp[i-1][j-1] + (s1[i-1] == s2[j-1] ? match : mismatch);
                int up = dp[i-1][j] + gap;
                int left = dp[i][j-1] + gap;
                dp[i][j] = std::max({diag, up, left});
            }
        }
        
        // التتبع الخلفي
        نتيجة_محاذاة_محاكاة نتيجة;
        نتيجة.النقاط = dp[m][n];
        
        int i = m, j = n;
        while (i > 0 || j > 0) {
            if (i > 0 && j > 0 && dp[i][j] == dp[i-1][j-1] + (s1[i-1] == s2[j-1] ? match : mismatch)) {
                نتيجة.المحاذاة١ = s1[i-1] + نتيجة.المحاذاة١;
                نتيجة.المحاذاة٢ = s2[j-1] + نتيجة.المحاذاة٢;
                --i; --j;
            } else if (i > 0 && dp[i][j] == dp[i-1][j] + gap) {
                نتيجة.المحاذاة١ = s1[i-1] + نتيجة.المحاذاة١;
                نتيجة.المحاذاة٢ = '-' + نتيجة.المحاذاة٢;
                --i;
                ++نتيجة.الفجوات;
            } else {
                نتيجة.المحاذاة١ = '-' + نتيجة.المحاذاة١;
                نتيجة.المحاذاة٢ = s2[j-1] + نتيجة.المحاذاة٢;
                --j;
                ++نتيجة.الفجوات;
            }
        }
        
        // حساب الهوية
        int matches = 0;
        for (size_t k = 0; k < نتيجة.المحاذاة١.size(); ++k) {
            if (نتيجة.المحاذاة١[k] == نتيجة.المحاذاة٢[k] && نتيجة.المحاذاة١[k] != '-') {
                ++matches;
            }
        }
        نتيجة.الهوية = 100.0 * matches / نتيجة.المحاذاة١.size();
        
        return نتيجة;
    }
};

// ============== محاكاة طاقة البروتين ==============

struct متجه٣_محاكاة {
    double x, y, z;
    
    متجه٣_محاكاة(double _x = 0, double _y = 0, double _z = 0) : x(_x), y(_y), z(_z) {}
    
    double طول() const { return std::sqrt(x*x + y*y + z*z); }
    
    متجه٣_محاكاة operator-(const متجه٣_محاكاة& أخر) const {
        return متجه٣_محاكاة(x - أخر.x, y - أخر.y, z - أخر.z);
    }
};

class حاسب_طاقة_محاكاة {
public:
    // طاقة الرابطة التساهمية
    static double طاقة_رابطة(double مسافة, double طول_توازن, double ثابت_قوة) {
        double انحراف = مسافة - طول_توازن;
        return 0.5 * ثابت_قوة * انحراف * انحراف;
    }
    
    // طاقة Lennard-Jones
    static double طاقة_LJ(double مسافة, double epsilon, double sigma) {
        if (مسافة < 0.1) return 1e10;  // تجنب القسمة على صفر
        double s_r = sigma / مسافة;
        double s_r6 = std::pow(s_r, 6);
        return 4.0 * epsilon * (s_r6 * s_r6 - s_r6);
    }
    
    // طاقة كولوم
    static double طاقة_كولوم(double مسافة, double شحنة١, double شحنة٢) {
        if (مسافة < 0.1) return 1e10;
        return 332.0636 * شحنة١ * شحنة٢ / مسافة;
    }
};

// ============== محاكاة التعبير الجيني ==============

class مطبع_TPM_محاكاة {
public:
    static std::vector<double> حساب_TPM(
        const std::vector<int>& قراءات,
        const std::vector<int>& أطوال_الجينات
    ) {
        std::vector<double> tpm;
        if (قراءات.size() != أطوال_الجينات.size()) return tpm;
        
        // الخطوة 1: حساب RPK
        std::vector<double> rpk;
        double مجموع_rpk = 0;
        
        for (size_t i = 0; i < قراءات.size(); ++i) {
            double طول_بالكيلو = أطوال_الجينات[i] / 1000.0;
            double r = (طول_بالكيلو > 0) ? قراءات[i] / طول_بالكيلو : 0;
            rpk.push_back(r);
            مجموع_rpk += r;
        }
        
        // الخطوة 2: التطبيع لمليون
        double معامل = (مجموع_rpk > 0) ? 1000000.0 / مجموع_rpk : 0;
        
        for (double r : rpk) {
            tpm.push_back(r * معامل);
        }
        
        return tpm;
    }
};

