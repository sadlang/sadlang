class مشغل_الاختبارات {
    struct اختبار {
        std::string الاسم;
        std::function<bool()> الدالة;
        std::string الفئة;
    };
    
    std::vector<اختبار> الاختبارات_;
    int نجح_ = 0;
    int فشل_ = 0;
    
public:
    void إضافة(const std::string& اسم, const std::string& فئة, std::function<bool()> دالة) {
        الاختبارات_.push_back({اسم, دالة, فئة});
    }
    
    void تشغيل() {
        std::cout << "\n╔══════════════════════════════════════════════════════════════════╗" << std::endl;
        std::cout << "║              اختبارات وحدة الحوسبة الحيوية (ص حيوي)              ║" << std::endl;
        std::cout << "╚══════════════════════════════════════════════════════════════════╝\n" << std::endl;
        
        std::string فئة_حالية;
        
        for (const auto& اختبار : الاختبارات_) {
            if (اختبار.الفئة != فئة_حالية) {
                فئة_حالية = اختبار.الفئة;
                std::cout << "\n▶ " << فئة_حالية << "\n" << std::string(50, '-') << std::endl;
            }
            
            std::cout << "  ◦ " << اختبار.الاسم << "... ";
            std::cout.flush();
            
            try {
                if (اختبار.الدالة()) {
                    std::cout << "\033[32m✓ نجح\033[0m" << std::endl;
                    ++نجح_;
                } else {
                    std::cout << "\033[31m✗ فشل\033[0m" << std::endl;
                    ++فشل_;
                }
            } catch (const std::exception& e) {
                std::cout << "\033[31m✗ استثناء: " << e.what() << "\033[0m" << std::endl;
                ++فشل_;
            }
        }
        
        // ملخص
        std::cout << "\n" << std::string(60, '=') << std::endl;
        std::cout << "النتيجة: ";
        if (فشل_ == 0) {
            std::cout << "\033[32m✓ جميع الاختبارات نجحت!\033[0m";
        } else {
            std::cout << "\033[31m✗ " << فشل_ << " اختبار فشل\033[0m";
        }
        std::cout << " (" << نجح_ << "/" << (نجح_ + فشل_) << ")" << std::endl;
    }
    
    int الفاشلة() const { return فشل_; }
};

