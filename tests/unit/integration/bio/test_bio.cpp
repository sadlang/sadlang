enum class قاعدة_DNA { A, T, G, C, N };
enum class قاعدة_RNA { A, U, G, C, N };

class تسلسل_DNA_محاكاة {
    std::string البيانات_;
    
public:
    تسلسل_DNA_محاكاة(const std::string& تسلسل = "") : البيانات_(تسلسل) {}
    
    size_t طول() const { return البيانات_.size(); }
    
    char في(size_t فهرس) const {
        return فهرس < البيانات_.size() ? البيانات_[فهرس] : 'N';
    }
    
    std::string مكمل() const {
        std::string نتيجة;
        for (char c : البيانات_) {
            switch (c) {
                case 'A': نتيجة += 'T'; break;
                case 'T': نتيجة += 'A'; break;
                case 'G': نتيجة += 'C'; break;
                case 'C': نتيجة += 'G'; break;
                default: نتيجة += 'N';
            }
        }
        return نتيجة;
    }
    
    std::string مكمل_عكسي() const {
        std::string مكمل_عادي = مكمل();
        return std::string(مكمل_عادي.rbegin(), مكمل_عادي.rend());
    }
    
    std::string نسخ() const {
        std::string rna;
        for (char c : البيانات_) {
            rna += (c == 'T') ? 'U' : c;
        }
        return rna;
    }
    
    double محتوى_GC() const {
        if (البيانات_.empty()) return 0.0;
        int gc = 0;
        for (char c : البيانات_) {
            if (c == 'G' || c == 'C') ++gc;
        }
        return 100.0 * gc / البيانات_.size();
    }
    
    int بحث(const std::string& نمط) const {
        size_t pos = البيانات_.find(نمط);
        return pos != std::string::npos ? (int)pos : -1;
    }
    
    const std::string& كنص() const { return البيانات_; }
};

