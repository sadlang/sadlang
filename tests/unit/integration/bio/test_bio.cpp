bool اختبار_طاقة_LJ() {
    // عند sigma، الطاقة قريبة من الصفر
    double طاقة = حاسب_طاقة_محاكاة::طاقة_LJ(3.4, 0.1, 3.4);
    تحقق_قريب(طاقة, 0.0, 0.01);
    
    // عند 2^(1/6) * sigma، الطاقة = -epsilon (الحد الأدنى)
    double r_min = std::pow(2.0, 1.0/6.0) * 3.4;
    طاقة = حاسب_طاقة_محاكاة::طاقة_LJ(r_min, 0.1, 3.4);
    تحقق_قريب(طاقة, -0.1, 0.01);
    return true;
}

