// ============== نوع السؤال ==============

enum class نوع_سؤال {
    اختيار_واحد,
    اختيار_متعدد,
    صح_خطأ,
    كتابة_كود
};

// ============== السؤال ==============

struct سؤال {
    std::string معرف;
    نوع_سؤال النوع;
    std::string نص;
    std::vector<std::string> الخيارات;
    int الإجابة_الصحيحة;  // فهرس
    int النقاط = 1;
};

// ============== الامتحان ==============

class امتحان_بسيط {
private:
    std::string معرف_;
    std::vector<سؤال> الأسئلة_;
    int الوقت_الكلي_ = 3600;
    double نسبة_النجاح_ = 70.0;
    
public:
    امتحان_بسيط(const std::string& معرف) : معرف_(معرف) {}
    
    void إضافة_سؤال(const سؤال& س) {
        الأسئلة_.push_back(س);
    }
    
    int عدد_الأسئلة() const { return الأسئلة_.size(); }
    
    int مجموع_النقاط() const {
        int مجموع = 0;
        for (const auto& س : الأسئلة_) {
            مجموع += س.النقاط;
        }
        return مجموع;
    }
    
    double تصحيح(const std::vector<int>& الإجابات) const {
        if (الإجابات.size() != الأسئلة_.size()) return 0;
        
        int صحيحة = 0;
        int كلي = 0;
        
        for (size_t i = 0; i < الأسئلة_.size(); ++i) {
            كلي += الأسئلة_[i].النقاط;
            if (الإجابات[i] == الأسئلة_[i].الإجابة_الصحيحة) {
                صحيحة += الأسئلة_[i].النقاط;
            }
        }
        
        return كلي > 0 ? (100.0 * صحيحة / كلي) : 0;
    }
    
    bool نجح(double النسبة) const {
        return النسبة >= نسبة_النجاح_;
    }
};

// ============== محرك التقييم ==============

class محرك_تقييم_بسيط {
private:
    std::map<std::string, double> المهارات_;
    
public:
    void تسجيل_نتيجة(const std::string& مهارة, bool صحيح, double صعوبة) {
        double& مستوى = المهارات_[مهارة];
        
        if (صحيح) {
            مستوى += صعوبة * 0.1;
        } else {
            مستوى -= (100 - صعوبة) * 0.08;
        }
        
        // تحديد الحدود
        if (مستوى < 0) مستوى = 0;
        if (مستوى > 100) مستوى = 100;
    }
    
    double مستوى_مهارة(const std::string& مهارة) const {
        auto it = المهارات_.find(مهارة);
        return it != المهارات_.end() ? it->second : 50.0;
    }
    
    double المستوى_العام() const {
        if (المهارات_.empty()) return 50.0;
        
        double مجموع = 0;
        for (const auto& [_, م] : المهارات_) {
            مجموع += م;
        }
        return مجموع / المهارات_.size();
    }
};

// ============== الشارات ==============

struct شارة {
    std::string معرف;
    std::string اسم;
    std::string وصف;
    bool نشطة = true;
};

class نظام_شارات_بسيط {
private:
    std::map<std::string, شارة> التعريفات_;
    std::map<std::string, std::vector<std::string>> شارات_المستخدمين_;
    int عداد_ = 0;
    
public:
    std::string إضافة_تعريف(شارة& ش) {
        ش.معرف = "badge_" + std::to_string(++عداد_);
        التعريفات_[ش.معرف] = ش;
        return ش.معرف;
    }
    
    std::string منح_شارة(const std::string& معرف_تعريف,
                         const std::string& معرف_مستخدم) {
        if (التعريفات_.find(معرف_تعريف) == التعريفات_.end()) {
            return "";
        }
        
        شارات_المستخدمين_[معرف_مستخدم].push_back(معرف_تعريف);
        return "grant_" + std::to_string(++عداد_);
    }
    
    int عدد_شارات(const std::string& معرف_مستخدم) const {
        auto it = شارات_المستخدمين_.find(معرف_مستخدم);
        return it != شارات_المستخدمين_.end() ? it->second.size() : 0;
    }
    
    bool لديه_شارة(const std::string& معرف_مستخدم,
                   const std::string& معرف_تعريف) const {
        auto it = شارات_المستخدمين_.find(معرف_مستخدم);
        if (it == شارات_المستخدمين_.end()) return false;
        
        for (const auto& ش : it->second) {
            if (ش == معرف_تعريف) return true;
        }
        return false;
    }
};

// ============== التحقق ==============

struct نتيجة_تحقق {
    bool صالح = false;
    std::string رسالة;
};

class نظام_تحقق_بسيط {
private:
    std::map<std::string, bool> الشهادات_;
    
public:
    void تسجيل_شهادة(const std::string& معرف) {
        الشهادات_[معرف] = true;
    }
    
    void إلغاء_شهادة(const std::string& معرف) {
        الشهادات_[معرف] = false;
    }
    
    نتيجة_تحقق تحقق(const std::string& معرف) {
        نتيجة_تحقق نتيجة;
        
        auto it = الشهادات_.find(معرف);
        if (it == الشهادات_.end()) {
            نتيجة.صالح = false;
            نتيجة.رسالة = "الشهادة غير موجودة";
        } else if (!it->second) {
            نتيجة.صالح = false;
            نتيجة.رسالة = "الشهادة ملغاة";
        } else {
            نتيجة.صالح = true;
            نتيجة.رسالة = "الشهادة صالحة";
        }
        
        return نتيجة;
    }
};

