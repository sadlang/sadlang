اختبار(تقييم_متوسط) {
    خدمة_سوق_اختبار سوق;
    
    حزمة_اختبار حزمة;
    حزمة.اسم = "اختبار";
    auto معرف_حزمة = سوق.تسجيل_حزمة(حزمة);
    
    // إضافة تقييمات متعددة
    for (int i = 0; i < 5; ++i) {
        تقييم_اختبار تقييم;
        تقييم.معرف_حزمة = معرف_حزمة;
        تقييم.معرف_مستخدم = "user" + std::to_string(i);
        تقييم.نجوم = (i % 2 == 0) ? 5 : 4;  // 5, 4, 5, 4, 5
        سوق.إضافة_تقييم(تقييم);
    }
    
    // المتوسط = (5+4+5+4+5)/5 = 4.6
    تحقق_قريب(سوق.متوسط_تقييم(معرف_حزمة), 4.6, 0.01);
}

