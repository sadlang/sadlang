#define تحقق(شرط) \
    do { \
        if (!(شرط)) { \
            throw std::runtime_error("فشل التحقق: " #شرط); \
        } \
    } while(0)

#define تحقق_متساوي(متوقع, فعلي) \
    do { \
        if ((متوقع) != (فعلي)) { \
            throw std::runtime_error("فشل التحقق: القيم غير متساوية"); \
        } \
    } while(0)

#define تحقق_قريب(متوقع, فعلي, دقة) \
    do { \
        if (std::abs((متوقع) - (فعلي)) > (دقة)) { \
            throw std::runtime_error("فشل التحقق: القيم غير قريبة"); \
        } \
    } while(0)

