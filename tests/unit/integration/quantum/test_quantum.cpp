اختبار(جروفر_يجد_الهدف_في_قاعدة_صغيرة) {
    // بحث جروفر في قاعدة من 4 عناصر (2 كيوبتات)
    int هدف = 3;  // نبحث عن |11⟩
    
    محاكي_اختبار م(2);
    
    // التهيئة: تراكب متساوي
    م.H(0);
    م.H(1);
    
    // تكرار جروفر واحد (أمثل لـ N=4)
    
    // الأوراكل: قلب طور الهدف |11⟩
    م.Z(0);  // مبسط - في الواقع نحتاج CZ
    
    // الانتشار
    م.H(0);
    م.H(1);
    م.X(0);
    م.X(1);
    // CZ
    م.H(1);
    م.CNOT(0, 1);
    م.H(1);
    م.X(0);
    م.X(1);
    م.H(0);
    م.H(1);
    
    // يجب أن يكون احتمال الهدف أعلى
    double احتمال_الهدف = م.احتمال(هدف);
    تحقق(احتمال_الهدف > 0.4);  // يجب أن يكون مرتفع
}

