void تسجيل_اختبار(const std::string& اسم, دالة_اختبار دالة) {
    سجل_اختبارات::المثيل().الاختبارات.push_back({اسم, دالة});
}

// ============== محاكي اختبار ==============

using عدد_مركب = std::complex<double>;

class محاكي_اختبار {
private:
    std::vector<عدد_مركب> الحالة_;
    size_t الكيوبتات_;
    std::mt19937 مولد_;
    
public:
    محاكي_اختبار(size_t كيوبتات) 
        : الكيوبتات_(كيوبتات), مولد_(42) {
        
        size_t حجم = 1ULL << كيوبتات;
        الحالة_.resize(حجم, عدد_مركب(0, 0));
        الحالة_[0] = عدد_مركب(1, 0);
    }
    
    void X(size_t هدف) {
        size_t قناع = 1ULL << هدف;
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) == 0) {
                std::swap(الحالة_[i], الحالة_[i | قناع]);
            }
        }
    }
    
    void H(size_t هدف) {
        double ج = 1.0 / std::sqrt(2.0);
        size_t قناع = 1ULL << هدف;
        
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) == 0) {
                size_t j = i | قناع;
                عدد_مركب أ = الحالة_[i];
                عدد_مركب ب = الحالة_[j];
                
                الحالة_[i] = ج * (أ + ب);
                الحالة_[j] = ج * (أ - ب);
            }
        }
    }
    
    void CNOT(size_t متحكم, size_t هدف) {
        size_t قناع_متحكم = 1ULL << متحكم;
        size_t قناع_هدف = 1ULL << هدف;
        
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع_متحكم) != 0 && (i & قناع_هدف) == 0) {
                std::swap(الحالة_[i], الحالة_[i | قناع_هدف]);
            }
        }
    }
    
    void Z(size_t هدف) {
        size_t قناع = 1ULL << هدف;
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) != 0) {
                الحالة_[i] = -الحالة_[i];
            }
        }
    }
    
    void S(size_t هدف) {
        size_t قناع = 1ULL << هدف;
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) != 0) {
                الحالة_[i] *= عدد_مركب(0, 1);
            }
        }
    }
    
    void T(size_t هدف) {
        double ج = 1.0 / std::sqrt(2.0);
        size_t قناع = 1ULL << هدف;
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) != 0) {
                الحالة_[i] *= عدد_مركب(ج, ج);
            }
        }
    }
    
    void Rz(size_t هدف, double زاوية) {
        double نصف = زاوية / 2.0;
        عدد_مركب e_pos(std::cos(نصف), std::sin(نصف));
        عدد_مركب e_neg(std::cos(نصف), -std::sin(نصف));
        
        size_t قناع = 1ULL << هدف;
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) != 0) {
                الحالة_[i] *= e_pos;
            } else {
                الحالة_[i] *= e_neg;
            }
        }
    }
    
    double احتمال(size_t حالة) const {
        return std::norm(الحالة_[حالة]);
    }
    
    double احتمال_كيوبت_واحد(size_t كيوبت) const {
        size_t قناع = 1ULL << كيوبت;
        double مجموع = 0.0;
        
        for (size_t i = 0; i < الحالة_.size(); i++) {
            if ((i & قناع) != 0) {
                مجموع += std::norm(الحالة_[i]);
            }
        }
        
        return مجموع;
    }
    
    int قياس(size_t كيوبت) {
        double احتمال_واحد = احتمال_كيوبت_واحد(كيوبت);
        std::uniform_real_distribution<double> توزيع(0.0, 1.0);
        
        int نتيجة = (توزيع(مولد_) < احتمال_واحد) ? 1 : 0;
        
        // انهيار
        size_t قناع = 1ULL << كيوبت;
        double عامل = 0.0;
        
        for (size_t i = 0; i < الحالة_.size(); i++) {
            bool قيمة = (i & قناع) != 0;
            if ((نتيجة == 1) != قيمة) {
                الحالة_[i] = عدد_مركب(0, 0);
            } else {
                عامل += std::norm(الحالة_[i]);
            }
        }
        
        عامل = std::sqrt(عامل);
        if (عامل > 1e-10) {
            for (auto& سعة : الحالة_) {
                سعة /= عامل;
            }
        }
        
        return نتيجة;
    }
    
    std::map<std::string, int> تشغيل_مرات(size_t عدد) {
        std::map<std::string, int> نتائج;
        auto حالة_أصلية = الحالة_;
        
        for (size_t t = 0; t < عدد; t++) {
            الحالة_ = حالة_أصلية;
            
            std::string مفتاح;
            for (size_t q = 0; q < الكيوبتات_; q++) {
                mفتاح = (قياس(q) == 1 ? '1' : '0') + مفتاح;
            }
            
            نتائج[مفتاح]++;
        }
        
        return نتائج;
    }
    
    void إعادة_تعيين() {
        std::fill(الحالة_.begin(), الحالة_.end(), عدد_مركب(0, 0));
        الحالة_[0] = عدد_مركب(1, 0);
    }
};

// ============== اختبارات البوابات الأساسية ==============

اختبار(بوابة_X_تقلب_الكيوبت) {
    محاكي_اختبار م(1);
    
    // |0⟩ → |1⟩
    م.X(0);
    تحقق_قريب(1.0, م.احتمال(1), 1e-10);
    
    // |1⟩ → |0⟩
    م.X(0);
    تحقق_قريب(1.0, م.احتمال(0), 1e-10);
}

اختبار(بوابة_H_تنشئ_تراكب) {
    محاكي_اختبار م(1);
    
    // |0⟩ → |+⟩ = (|0⟩ + |1⟩)/√2
    م.H(0);
    
    تحقق_قريب(0.5, م.احتمال(0), 1e-10);
    تحقق_قريب(0.5, م.احتمال(1), 1e-10);
}

اختبار(بوابة_H_مزدوجة_تعيد_الحالة) {
    محاكي_اختبار م(1);
    
    م.H(0);
    م.H(0);
    
    // H² = I
    تحقق_قريب(1.0, م.احتمال(0), 1e-10);
}

اختبار(بوابة_Z_تقلب_الطور) {
    محاكي_اختبار م(1);
    
    // Z|0⟩ = |0⟩
    م.Z(0);
    تحقق_قريب(1.0, م.احتمال(0), 1e-10);
    
    // Z|1⟩ = -|1⟩ (الاحتمال لا يتغير)
    م.X(0);
    م.Z(0);
    تحقق_قريب(1.0, م.احتمال(1), 1e-10);
}

