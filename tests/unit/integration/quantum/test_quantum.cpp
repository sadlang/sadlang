اختبار(قياس_بيل_متشابك) {
    // في حالة بيل، قياس كيوبت واحد يحدد الآخر
    int تطابقات = 0;
    int محاولات = 100;
    
    for (int i = 0; i < محاولات; i++) {
        محاكي_اختبار م(2);
        م.H(0);
        م.CNOT(0, 1);
        
        int ن1 = م.قياس(0);
        int ن2 = م.قياس(1);
        
        if (ن1 == ن2) تطابقات++;
    }
    
    // يجب أن تتطابق دائماً (أو تقريباً)
    تحقق(تطابقات > 95);
}

