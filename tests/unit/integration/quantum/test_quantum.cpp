اختبار(QFT_على_كيوبت_واحد) {
    // QFT على كيوبت واحد = H
    محاكي_اختبار م(1);
    م.H(0);  // هذا هو QFT لكيوبت واحد
    
    تحقق_قريب(0.5, م.احتمال(0), 1e-10);
    تحقق_قريب(0.5, م.احتمال(1), 1e-10);
}

اختبار(QFT_على_كيوبتين) {
    محاكي_اختبار م(2);
    
    // QFT على |00⟩ يعطي تراكب متساوي
    م.H(0);
    م.Rz(0, M_PI / 2);  // بوابة طور متحكم بها (مبسطة)
    م.H(1);
    
    // كل الحالات يجب أن يكون لها احتمال متساوي تقريباً
    double مجموع = م.احتمال(0) + م.احتمال(1) + م.احتمال(2) + م.احتمال(3);
    تحقق_قريب(1.0, مجموع, 1e-10);
}

