// ============== محاكاة نظام الترخيص ==============

class نظام_ترخيص_بسيط {
    std::map<std::string, int> التراخيص_;
    std::map<std::string, std::vector<std::string>> المستخدمون_;
    
public:
    std::string إنشاء_ترخيص(const std::string& المؤسسة, int المقاعد) {
        std::string معرف = "LIC-" + std::to_string(التراخيص_.size() + 1);
        التراخيص_[معرف] = المقاعد;
        return معرف;
    }
    
    bool إضافة_مستخدم(const std::string& معرف_ترخيص, const std::string& المستخدم) {
        auto it = التراخيص_.find(معرف_ترخيص);
        if (it == التراخيص_.end()) return false;
        
        auto& مستخدمون = المستخدمون_[معرف_ترخيص];
        if (مستخدمون.size() >= static_cast<size_t>(it->second)) {
            return false;  // تجاوز المقاعد
        }
        
        مستخدمون.push_back(المستخدم);
        return true;
    }
    
    int عدد_المستخدمين(const std::string& معرف_ترخيص) const {
        auto it = المستخدمون_.find(معرف_ترخيص);
        return it != المستخدمون_.end() ? it->second.size() : 0;
    }
    
    int الحد_الأقصى(const std::string& معرف_ترخيص) const {
        auto it = التراخيص_.find(معرف_ترخيص);
        return it != التراخيص_.end() ? it->second : 0;
    }
};

// ============== محاكاة نظام الدعم ==============

class نظام_دعم_بسيط {
    struct تذكرة {
        std::string معرف;
        std::string العنوان;
        int الأولوية;  // 1=حرج، 4=منخفض
        bool مغلقة = false;
    };
    
    std::vector<تذكرة> التذاكر_;
    
public:
    std::string إنشاء_تذكرة(const std::string& العنوان, int الأولوية) {
        تذكرة ت;
        ت.معرف = "TKT-" + std::to_string(التذاكر_.size() + 1);
        ت.العنوان = العنوان;
        ت.الأولوية = الأولوية;
        التذاكر_.push_back(ت);
        return ت.معرف;
    }
    
    bool إغلاق_تذكرة(const std::string& معرف) {
        for (auto& ت : التذاكر_) {
            if (ت.معرف == معرف) {
                ت.مغلقة = true;
                return true;
            }
        }
        return false;
    }
    
    int تذاكر_مفتوحة() const {
        int عدد = 0;
        for (const auto& ت : التذاكر_) {
            if (!ت.مغلقة) عدد++;
        }
        return عدد;
    }
};

// ============== محاكاة نظام SLA ==============

class نظام_SLA_بسيط {
    struct مقياس {
        std::string الاسم;
        double الهدف;
        double الفعلي;
    };
    
    std::vector<مقياس> المقاييس_;
    
public:
    void إضافة_مقياس(const std::string& الاسم, double الهدف) {
        المقاييس_.push_back({الاسم, الهدف, الهدف});
    }
    
    void تسجيل_قيمة(const std::string& الاسم, double القيمة) {
        for (auto& م : المقاييس_) {
            if (م.الاسم == الاسم) {
                م.الفعلي = القيمة;
                break;
            }
        }
    }
    
    bool ممتثل(const std::string& الاسم) const {
        for (const auto& م : المقاييس_) {
            if (م.الاسم == الاسم) {
                return م.الفعلي >= م.الهدف;
            }
        }
        return false;
    }
    
    double نسبة_الالتزام() const {
        if (المقاييس_.empty()) return 100.0;
        
        int ممتثل = 0;
        for (const auto& م : المقاييس_) {
            if (م.الفعلي >= م.الهدف) ممتثل++;
        }
        
        return (ممتثل * 100.0) / المقاييس_.size();
    }
};

// ============== محاكاة نظام الامتثال ==============

class نظام_امتثال_بسيط {
    struct ضابط {
        std::string الكود;
        std::string العنوان;
        int الحالة;  // 0=غير ممتثل، 1=جزئي، 2=ممتثل
    };
    
    std::vector<ضابط> الضوابط_;
    
public:
    void إضافة_ضابط(const std::string& الكود, const std::string& العنوان) {
        الضوابط_.push_back({الكود, العنوان, 0});
    }
    
    void تحديث_حالة(const std::string& الكود, int الحالة) {
        for (auto& ض : الضوابط_) {
            if (ض.الكود == الكود) {
                ض.الحالة = الحالة;
                break;
            }
        }
    }
    
    double نسبة_الامتثال() const {
        if (الضوابط_.empty()) return 0.0;
        
        double مجموع = 0.0;
        for (const auto& ض : الضوابط_) {
            mجموع += ض.الحالة * 50.0;  // 0=0%, 1=50%, 2=100%
        }
        
        return مجموع / الضوابط_.size();
    }
    
    int عدد_الضوابط() const { return الضوابط_.size(); }
};

// ============== محاكاة نظام التحليلات ==============

class نظام_تحليلات_بسيط {
    std::map<std::string, std::vector<double>> البيانات_;
    
public:
    void تسجيل(const std::string& المقياس, double القيمة) {
        البيانات_[المقياس].push_back(القيمة);
    }
    
    double المتوسط(const std::string& المقياس) const {
        auto it = البيانات_.find(المقياس);
        if (it == البيانات_.end() || it->second.empty()) return 0.0;
        
        double مجموع = 0.0;
        for (double ق : it->second) {
            مجموع += ق;
        }
        
        return مجموع / it->second.size();
    }
    
    double الحد_الأقصى(const std::string& المقياس) const {
        auto it = البيانات_.find(المقياس);
        if (it == البيانات_.end() || it->second.empty()) return 0.0;
        
        double أقصى = it->second[0];
        for (double ق : it->second) {
            if (ق > أقصى) أقصى = ق;
        }
        
        return أقصى;
    }
};

