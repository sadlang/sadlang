// ============== تشغيل الاختبارات ==============

class مشغل_اختبارات {
    std::vector<std::pair<std::string, std::function<void()>>> الاختبارات_;
    
public:
    void إضافة(const std::string& الاسم, std::function<void()> الاختبار) {
        الاختبارات_.push_back({الاسم, الاختبار});
    }
    
    int تشغيل() {
        int نجاح = 0;
        int فشل = 0;
        
        std::cout << "\n=== اختبارات نظام المؤسسات ===\n\n";
        
        for (const auto& [الاسم, الاختبار] : الاختبارات_) {
            std::cout << "  اختبار: " << الاسم << " ... ";
            
            try {
                الاختبار();
                std::cout << "✓ نجح\n";
                نجاح++;
            } catch (const std::exception& e) {
                std::cout << "✗ فشل: " << e.what() << "\n";
                فشل++;
            }
        }
        
        std::cout << "\n=== النتائج ===\n";
        std::cout << "  نجح: " << نجاح << "\n";
        std::cout << "  فشل: " << فشل << "\n";
        std::cout << "  المجموع: " << (نجاح + فشل) << "\n\n";
        
        return فشل > 0 ? 1 : 0;
    }
};

