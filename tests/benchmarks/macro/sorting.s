# الترتيب بالاختيار - O(n²)
دالة ترتيب_بالاختيار(مصفوفة م)
    رقم ن = طول(م)
    لكل ي في مدى(0، ن - 1)
        رقم أصغر_موقع = ي
        
        لكل ج في مدى(ي + 1، ن)
            إذا (م[ج] < م[أصغر_موقع])
                أصغر_موقع = ج
            نهاية
        نهاية
        
        إذا (أصغر_موقع != ي)
            رقم مؤقت = م[ي]
            م[ي] = م[أصغر_موقع]
            م[أصغر_موقع] = مؤقت
        نهاية
    نهاية
