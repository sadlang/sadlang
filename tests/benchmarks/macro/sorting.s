    لكل _ في مدى(0، عدد_الجولات)
        مصفوفة نسخة = انسخ_مصفوفة(بيانات_أصلية)
        
        متغير بداية = وقت.الآن_نانو()
        خوارزمية(نسخة)
        متغير نهاية = وقت.الآن_نانو()
        
        أوقات.أضف(نهاية - بداية)
    نهاية
    
    # احسب المتوسط
    رقم مجموع = 0
    لكل و في أوقات
        مجموع = مجموع + و
    نهاية
    
    ارجع {
        "الاسم": الاسم،
        "الحجم": طول(بيانات_أصلية)،
        "الجولات": عدد_الجولات،
        "متوسط_الوقت_مللي": (مجموع / عدد_الجولات) / 1000000.0
    }
