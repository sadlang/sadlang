دالة قسّم_للترتيب(مصفوفة م، رقم بداية، رقم نهاية) -> رقم
    رقم محور = م[نهاية]
    رقم ي = بداية - 1
    
    لكل ج في مدى(بداية، نهاية)
        إذا (م[ج] <= محور)
            ي = ي + 1
            رقم مؤقت = م[ي]
            م[ي] = م[ج]
            م[ج] = مؤقت
        نهاية
    نهاية
    
    رقم مؤقت = م[ي + 1]
    م[ي + 1] = م[نهاية]
    م[نهاية] = مؤقت
    
    ارجع ي + 1
