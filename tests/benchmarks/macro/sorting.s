# الترتيب السريع - O(n log n)
دالة ترتيب_سريع(مصفوفة م، رقم بداية، رقم نهاية)
    إذا (بداية < نهاية)
        رقم محور = قسّم_للترتيب(م، بداية، نهاية)
        ترتيب_سريع(م، بداية، محور - 1)
        ترتيب_سريع(م، محور + 1، نهاية)
    نهاية
