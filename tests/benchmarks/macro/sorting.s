# الترتيب بالإدراج - O(n²)
دالة ترتيب_بالإدراج(مصفوفة م)
    لكل ي في مدى(1، طول(م))
        رقم مفتاح = م[ي]
        رقم ج = ي - 1
        
        بينما (ج >= 0 && م[ج] > مفتاح)
            م[ج + 1] = م[ج]
            ج = ج - 1
        نهاية
        
        م[ج + 1] = مفتاح
    نهاية
