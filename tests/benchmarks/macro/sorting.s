دالة ادمج(مصفوفة م، رقم بداية، رقم منتصف، رقم نهاية)
    مصفوفة يسار = []
    مصفوفة يمين = []
    
    لكل ي في مدى(بداية، منتصف + 1)
        يسار.أضف(م[ي])
    نهاية
    
    لكل ي في مدى(منتصف + 1، نهاية + 1)
        يمين.أضف(م[ي])
    نهاية
    
    رقم ي = 0
    رقم ج = 0
    رقم ك = بداية
    
    بينما (ي < طول(يسار) && ج < طول(يمين))
        إذا (يسار[ي] <= يمين[ج])
            م[ك] = يسار[ي]
            ي = ي + 1
        وإلا
            م[ك] = يمين[ج]
            ج = ج + 1
        نهاية
        ك = ك + 1
    نهاية
    
    بينما (ي < طول(يسار))
        م[ك] = يسار[ي]
        ي = ي + 1
        ك = ك + 1
    نهاية
    
    بينما (ج < طول(يمين))
        م[ك] = يمين[ج]
        ج = ج + 1
        ك = ك + 1
    نهاية
