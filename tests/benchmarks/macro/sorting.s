# الترتيب الفقاعي - O(n²)
دالة ترتيب_فقاعي(مصفوفة م)
    رقم ن = طول(م)
    لكل ي في مدى(0، ن - 1)
        لكل ج في مدى(0، ن - ي - 1)
            إذا (م[ج] > م[ج + 1])
                رقم مؤقت = م[ج]
                م[ج] = م[ج + 1]
                م[ج + 1] = مؤقت
            نهاية
        نهاية
    نهاية
