# الترتيب بالدمج - O(n log n)
دالة ترتيب_بالدمج(مصفوفة م، رقم بداية، رقم نهاية)
    إذا (بداية < نهاية)
        رقم منتصف = (بداية + نهاية) / 2
        ترتيب_بالدمج(م، بداية، منتصف)
        ترتيب_بالدمج(م، منتصف + 1، نهاية)
        ادمج(م، بداية، منتصف، نهاية)
