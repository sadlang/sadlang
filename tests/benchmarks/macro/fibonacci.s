# ═══════════════════════════════════════════════════════
# تنفيذ تكراري بسيط - O(2^n)
# ═══════════════════════════════════════════════════════

دالة فيب_تكراري(رقم ن) -> رقم
    إذا (ن <= 1)
        ارجع ن
    نهاية
    ارجع فيب_تكراري(ن - 1) + فيب_تكراري(ن - 2)
نهاية

# ═══════════════════════════════════════════════════════
# تنفيذ تكراري مع الذاكرة (Memoization) - O(n)
# ═══════════════════════════════════════════════════════

قاموس ذاكرة_فيب = {}

دالة فيب_محسن(رقم ن) -> رقم
    إذا (ن <= 1)
        ارجع ن
    نهاية
    
    إذا (ذاكرة_فيب.يحتوي_على_مفتاح(ن))
        ارجع ذاكرة_فيب[ن]
    نهاية
    
    رقم نتيجة = فيب_محسن(ن - 1) + فيب_محسن(ن - 2)
    ذاكرة_فيب[ن] = نتيجة
    ارجع نتيجة
نهاية

# ═══════════════════════════════════════════════════════
# تنفيذ تكراري (Loop) - O(n)
# ═══════════════════════════════════════════════════════

دالة فيب_حلقة(رقم ن) -> رقم
    إذا (ن <= 1)
        ارجع ن
    نهاية
    
    رقم أ = 0
    رقم ب = 1
    
    لكل _ في مدى(2، ن + 1)
        رقم مؤقت = أ + ب
        أ = ب
        ب = مؤقت
    نهاية
    
    ارجع ب
نهاية

# ═══════════════════════════════════════════════════════
# تنفيذ بالمصفوفات (Matrix) - O(log n)
# ═══════════════════════════════════════════════════════

دالة اضرب_مصفوفات(مصفوفة أ، مصفوفة ب) -> مصفوفة
    ارجع [
        [أ[0][0] * ب[0][0] + أ[0][1] * ب[1][0]، أ[0][0] * ب[0][1] + أ[0][1] * ب[1][1]]،
        [أ[1][0] * ب[0][0] + أ[1][1] * ب[1][0]، أ[1][0] * ب[0][1] + أ[1][1] * ب[1][1]]
    ]
نهاية

دالة قوة_مصفوفة(مصفوفة م، رقم ن) -> مصفوفة
    إذا (ن == 1)
        ارجع م
    نهاية
    
    إذا (ن % 2 == 0)
        متغير نصف = قوة_مصفوفة(م، ن / 2)
        ارجع اضرب_مصفوفات(نصف، نصف)
    وإلا
        ارجع اضرب_مصفوفات(م، قوة_مصفوفة(م، ن - 1))
    نهاية
نهاية

دالة فيب_مصفوفة(رقم ن) -> رقم
    إذا (ن <= 1)
        ارجع ن
    نهاية
    
    مصفوفة أساس = [[1، 1]، [1، 0]]
    متغير نتيجة = قوة_مصفوفة(أساس، ن - 1)
    ارجع نتيجة[0][0]
نهاية

