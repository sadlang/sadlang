دالة اختبر_خوارزمية(نص الاسم، دالة خوارزمية، رقم ن) -> قاموس
    # التسخين
    لكل _ في مدى(0، 3)
        خوارزمية(ن / 2)
    نهاية
    
    # القياس
    متغير بداية = وقت.الآن_نانو()
    رقم نتيجة = خوارزمية(ن)
    متغير نهاية = وقت.الآن_نانو()
    
    ارجع {
        "الاسم": الاسم،
        "ن": ن،
        "النتيجة": نتيجة،
        "الوقت_مللي": (نهاية - بداية) / 1000000.0
    }
نهاية

