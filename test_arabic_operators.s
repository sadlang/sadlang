# اختبار العوامل المنطقية العربية

اطبع("=== اختبار العوامل العربية ===\n")

# اختبار "و"
منطقي نتيجة1 = صحيح و صحيح
منطقي نتيجة2 = صحيح و خطأ
اطبع("صحيح و صحيح =", نتيجة1, "\n")
اطبع("صحيح و خطأ =", نتيجة2, "\n")

# اختبار "أو"
منطقي نتيجة3 = صحيح أو خطأ
منطقي نتيجة4 = خطأ أو خطأ
اطبع("صحيح أو خطأ =", نتيجة3, "\n")
اطبع("خطأ أو خطأ =", نتيجة4, "\n")

# اختبار "ليس"
منطقي نتيجة5 = ليس صحيح
منطقي نتيجة6 = ليس خطأ
اطبع("ليس صحيح =", نتيجة5, "\n")
اطبع("ليس خطأ =", نتيجة6, "\n")

# تعبير معقد
منطقي معقد = (صحيح و خطأ) أو (ليس خطأ)
اطبع("(صحيح و خطأ) أو (ليس خطأ) =", معقد, "\n")

اطبع("\n✅ جميع العوامل العربية تعمل بنجاح!\n")
